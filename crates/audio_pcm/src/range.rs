//! 標本の範囲の型。

use crate::position::{動画上の標本位置, 標本数};

/// 標本の範囲とは、動画上の標本位置の開始から終了の手前までのことである。溜めた音と流れてくる音が持つ標本の範囲に使う。
/// 不変条件: 開始は終了より後ろにない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 標本の範囲 {
    開始: 動画上の標本位置,
    終了: 動画上の標本位置,
}

impl 標本の範囲 {
    /// 開始と終了から作成する。開始が終了より後ろなら作らない。
    pub fn 作成する(
        開始: 動画上の標本位置, 終了: 動画上の標本位置
    ) -> Option<Self> {
        (開始 <= 終了).then_some(Self { 開始, 終了 })
    }

    /// 開始から指定の長さの範囲を作る。
    pub fn 開始と長さから作る(
        開始: 動画上の標本位置, 長さ: 標本数
    ) -> Self {
        Self {
            開始,
            終了: 開始.進める(長さ),
        }
    }

    /// 開始の位置。
    pub fn 開始(&self) -> 動画上の標本位置 {
        self.開始
    }

    /// 終了の位置(範囲に含まない)。
    pub fn 終了(&self) -> 動画上の標本位置 {
        self.終了
    }

    /// 範囲の標本数。
    pub fn 長さ(&self) -> 標本数 {
        self.終了.起点からの標本数(self.開始)
    }
}
