//! サンプリング周波数の型と、時刻と標本位置の対応。

use clip_domain::{
    動画上の区間, 動画上の秒, 境目を許容して切り捨てた整数, 小数を四捨五入した整数, 時刻,
    時間の長さ,
};

use crate::difference::標本の差;
use crate::fractional::小数の標本位置;
use crate::fractional_range::小数の標本の範囲;
use crate::position::{動画上の標本位置, 標本数};

/// サンプリング周波数とは、1秒あたりの標本の数のことである。出力装置が決め、FFmpeg はこの周波数へ変換して音を出す。
/// 不変条件: 1以上である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct サンプリング周波数(u32);

impl サンプリング周波数 {
    /// 1秒あたりの標本の数から作成する。0なら作らない。
    pub fn 作成する(毎秒の標本数: u32) -> Option<Self> {
        (毎秒の標本数 > 0).then_some(Self(毎秒の標本数))
    }

    /// 1秒あたりの標本の数。FFmpeg の引数と表示へ渡す境界で使う。
    pub fn 毎秒の標本数(self) -> u32 {
        self.0
    }

    /// その時刻に鳴っている標本の位置を求める。
    pub fn 時刻を含む標本位置(self, 位置: 動画上の秒) -> 動画上の標本位置 {
        let 標本単位 = 位置.秒数() * f64::from(self.0);
        動画上の標本位置::作成する(境目を許容して切り捨てた整数(標本単位))
    }

    /// 動画上の区間を、端数を丸めない小数の標本の範囲へ換算する。
    pub fn 区間の範囲(self, 区間: &動画上の区間) -> 小数の標本の範囲 {
        小数の標本の範囲::収めて作る(
            self.時刻の小数の位置(区間.開始()),
            self.時刻の小数の位置(区間.終了()),
        )
    }

    /// その時刻を、標本の間も指せる位置として求める。
    pub fn 時刻の小数の位置(self, 位置: 動画上の秒) -> 小数の標本位置 {
        小数の標本位置::収めて作る(位置.秒数() * f64::from(self.0))
    }

    /// 長さを標本数へ換算する(四捨五入)。
    pub fn 長さの標本数(self, 長さ: 時間の長さ) -> 標本数 {
        標本数::作成する(小数を四捨五入した整数(
            長さ.秒数() * f64::from(self.0),
        ))
    }

    /// 秒数を、端数のある標本数へ換算する。実時間の経過から読み位置の進みを求めるときに使う。
    pub fn 秒数の小数の標本数(self, 秒数: f64) -> 標本の差 {
        標本の差::収めて作る(秒数 * f64::from(self.0))
    }

    /// 標本数を長さへ換算する。
    pub fn 標本数の長さ(self, 数: 標本数) -> 時間の長さ {
        時間の長さ::作成する(数.小数の値() / f64::from(self.0)).unwrap_or(時間の長さ::ゼロ)
    }

    /// その標本が鳴り始める動画上の時刻を求める。
    pub fn 標本位置の時刻(self, 位置: 動画上の標本位置) -> 動画上の秒 {
        時刻::作成する(位置.小数の値() / f64::from(self.0)).unwrap_or(時刻::先頭)
    }
}
