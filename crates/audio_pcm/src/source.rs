//! 音の出どころ。音声のスレッドが標本を読む入れ物の区別である。

use std::sync::Arc;

use crate::flowing::流れてくる音;
use crate::position::動画上の標本位置;
use crate::stereo::ステレオの標本;
use crate::stored::溜めた音;

/// 音の出どころとは、音声のスレッドが標本を読む入れ物が、溜めた音か流れてくる音かの区別のことである。
/// 複製は参照の数を増やすだけで、メモリを確保しない。
#[derive(Debug, Clone)]
pub enum 音の出どころ {
    /// 区間を読み切って溜めた音。
    溜めた音(Arc<溜めた音>),
    /// 流し読みが書き足している音。
    流れてくる音(Arc<流れてくる音>),
}

impl 音の出どころ {
    /// その位置の標本。入れ物がその位置を持っていなければ無い。
    pub fn 標本(&self, 位置: 動画上の標本位置) -> Option<ステレオの標本> {
        match self {
            Self::溜めた音(音) => 音.標本(位置),
            Self::流れてくる音(音) => 音.標本(位置),
        }
    }

    /// 鳴らしている位置を知らせる。流れてくる音の書き手は、これを見て古い標本の場所へ上書きする。
    pub fn 鳴らしている位置を知らせる(&self, 位置: 動画上の標本位置) {
        if let Self::流れてくる音(音) = self {
            音.鳴らしている位置を知らせる(位置);
        }
    }

    /// 同じ入れ物を指しているか。
    pub fn 同じ入れ物か(&self, 他方: &Self) -> bool {
        match (self, 他方) {
            (Self::溜めた音(左), Self::溜めた音(右)) => Arc::ptr_eq(左, 右),
            (Self::流れてくる音(左), Self::流れてくる音(右)) => Arc::ptr_eq(左, 右),
            _ => false,
        }
    }
}
