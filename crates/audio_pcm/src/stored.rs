//! 溜めた音。区間の音を読み切った不変の入れ物である。

use crate::position::{動画上の標本位置, 標本数};
use crate::range::標本の範囲;
use crate::stereo::{ステレオの標本, 左右の値};

/// 溜めた音とは、動画上の標本位置の先頭から続く、読み切った左右の値の並びのことである。作った後は変えない。
/// 音の倉庫が作って `Arc` で持ち、音声のスレッドへ参照を渡す。
#[derive(Debug, Clone, PartialEq)]
pub struct 溜めた音 {
    先頭: 動画上の標本位置,
    値の並び: Box<[左右の値]>,
}

impl 溜めた音 {
    /// 先頭の位置と、そこから続く左右の値の並びから作成する。
    pub fn 作成する(先頭: 動画上の標本位置, 値の並び: Vec<左右の値>) -> Self {
        Self {
            先頭,
            値の並び: 値の並び.into_boxed_slice(),
        }
    }

    /// 最初の標本の位置。
    pub fn 先頭(&self) -> 動画上の標本位置 {
        self.先頭
    }

    /// 溜めた標本の数。
    pub fn 標本数(&self) -> 標本数 {
        標本数::並びの長さから作る(self.値の並び.len())
    }

    /// 溜めた標本が占める範囲。
    pub fn 範囲(&self) -> 標本の範囲 {
        標本の範囲::開始と長さから作る(self.先頭, self.標本数())
    }

    /// その位置の標本。溜めた範囲の外なら無い。
    pub fn 標本(&self, 位置: 動画上の標本位置) -> Option<ステレオの標本> {
        if 位置 < self.先頭 {
            return None;
        }
        let 添字 = 位置.起点からの標本数(self.先頭).並びの長さ();
        self.値の並び
            .get(添字)
            .copied()
            .map(ステレオの標本::左右の値から作る)
    }
}
