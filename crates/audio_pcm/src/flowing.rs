//! 流れてくる音。流し読みの裏のスレッドが書き足し、音声のスレッドが読む、錠付きの音の窓である。

use std::sync::{Condvar, Mutex, MutexGuard, PoisonError};

use crate::flowing_ring::音の窓;
use crate::position::{動画上の標本位置, 標本数};
use crate::range::標本の範囲;
use crate::stereo::{ステレオの標本, 左右の値};

/// 書き足した結果とは、書き手が渡した値をすべて書き足せたか、途中で入れ物が閉じられたかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 書き足した結果 {
    /// すべて書き足した。
    書き足した,
    /// 入れ物が閉じられた。書き手は読むのをやめる。
    閉じられた,
}

/// 窓の状態とは、音の窓と、入れ物が閉じられたかの組のことである。
struct 窓の状態 {
    窓: 音の窓,
    閉じたか: bool,
}

/// 流れてくる音とは、流し読みの裏のスレッドが開始の位置から順に書き足し、音声のスレッドが位置を指して読む入れ物のことである。
/// 容量が埋まると書き手は、読み手が鳴らしている位置を進めるか入れ物が閉じられるまで待つ。
/// 錠は1標本の読み書きと、1回の書き足しの間だけ持つ。読み手が書き手を待つことはない。
pub struct 流れてくる音 {
    状態: Mutex<窓の状態>,
    空きができた: Condvar,
}

impl 流れてくる音 {
    /// 開始の位置から書き始める空の入れ物を作る。容量と、鳴らしている位置より前に残す長さを受け取る。
    pub fn 作成する(
        開始: 動画上の標本位置, 容量: 標本数, 残す長さ: 標本数
    ) -> Self {
        Self {
            状態: Mutex::new(窓の状態 {
                窓: 音の窓::作成する(開始, 容量, 残す長さ),
                閉じたか: false,
            }),
            空きができた: Condvar::new(),
        }
    }

    /// 値の並びを順に書き足す。容量が埋まっている間は、空きができるか閉じられるまで待つ。書き手のスレッドから呼ぶ。
    pub fn 書き足す(&self, 値の並び: &[左右の値]) -> 書き足した結果 {
        let mut 残り = 値の並び;
        let mut 状態 = self.錠を取る();
        while !残り.is_empty() {
            if 状態.閉じたか {
                return 書き足した結果::閉じられた;
            }
            let 書いた数 = 状態.窓.書き込む(残り);
            残り = &残り[書いた数..];
            if 書いた数 == 0 {
                状態 = self
                    .空きができた
                    .wait(状態)
                    .unwrap_or_else(PoisonError::into_inner);
            }
        }
        書き足した結果::書き足した
    }

    /// 入れ物を閉じ、待っている書き手を起こす。書き手はそれ以上書き足さない。
    pub fn 閉じる(&self) {
        self.錠を取る().閉じたか = true;
        self.空きができた.notify_all();
    }

    /// その位置の標本。まだ届いていないか、上書きされた後なら無い。
    pub fn 標本(&self, 位置: 動画上の標本位置) -> Option<ステレオの標本> {
        self.錠を取る().窓.標本(位置)
    }

    /// 読み手が鳴らしている位置を知らせ、空きを待っている書き手を起こす。
    pub fn 鳴らしている位置を知らせる(&self, 位置: 動画上の標本位置) {
        self.錠を取る().窓.鳴らしている位置を覚える(位置);
        self.空きができた.notify_one();
    }

    /// 入れ物が今持っている標本の範囲。
    pub fn 範囲(&self) -> 標本の範囲 {
        self.錠を取る().窓.範囲()
    }

    /// 錠を取る。錠を持ったスレッドがパニックしても、窓の不変条件は1回の書き込みの途中でしか崩れないため、中身をそのまま使う。
    fn 錠を取る(&self) -> MutexGuard<'_, 窓の状態> {
        self.状態.lock().unwrap_or_else(PoisonError::into_inner)
    }
}

impl std::fmt::Debug for 流れてくる音 {
    fn fmt(&self, 書き先: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(書き先, "流れてくる音({:?})", self.範囲())
    }
}
