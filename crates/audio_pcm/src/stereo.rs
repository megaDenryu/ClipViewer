//! 左右の標本の型と、重ね合わせの計算。

/// 左右の値とは、FFmpeg が出した f32le の1つの時点の [左, 右] の値のことである。溜めるときの形であり、計算には使わない。
pub type 左右の値 = [f32; 2];

/// 左右の値1つが占めるバイト数。FFmpeg が f32le・2ch で出す1標本の長さと、溜めた音のメモリの見積もりに使う。
pub const 左右の値のバイト数: usize = size_of::<左右の値>();

/// ステレオの標本とは、ある1つの時点の左の音の値と右の音の値の組のことである。値はおおよそ -1 から 1 の間にある。
/// 計算の途中の丸めを避けるため倍精度で持つ。溜めるときは単精度の `左右の値` で持つ。
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct ステレオの標本 {
    /// 左の音の値。
    pub 左: f64,
    /// 右の音の値。
    pub 右: f64,
}

impl ステレオの標本 {
    /// 無音(左右とも0)。
    pub const 無音: Self = Self { 左: 0.0, 右: 0.0 };

    /// 溜めた左右の値から作る。
    pub fn 左右の値から作る(値: 左右の値) -> Self {
        Self {
            左: f64::from(値[0]),
            右: f64::from(値[1]),
        }
    }

    /// 左右を同じ倍率で掛けた標本を求める。音量や重ね合わせの重みに使う。
    pub fn 倍にする(self, 倍率: f64) -> Self {
        Self {
            左: self.左 * 倍率,
            右: self.右 * 倍率,
        }
    }

    /// 2つの標本を足し合わせる。
    pub fn 足す(self, 他方: Self) -> Self {
        Self {
            左: self.左 + 他方.左,
            右: self.右 + 他方.右,
        }
    }

    /// 左右の値をそれぞれ −1 以上 1 以下へ収めた標本を求める。範囲の外の値は近い方の端にする。
    /// 行の音を足し合わせた標本は1を超えうるため、装置へ渡す前にこれで収める。値が NaN ならそのまま NaN を返す。
    pub fn 負の1から1へ収める(self) -> Self {
        Self {
            左: self.左.clamp(-1.0, 1.0),
            右: self.右.clamp(-1.0, 1.0),
        }
    }

    /// 自分から他方へ、重み(0で自分、1で他方)の分だけ寄せた標本を求める。
    pub fn 他方へ寄せる(self, 他方: Self, 重み: f64) -> Self {
        self.倍にする(1.0 - 重み).足す(他方.倍にする(重み))
    }
}
