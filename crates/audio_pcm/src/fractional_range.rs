//! 小数の標本の範囲の型。区間の開始と終了を、秒から換算した端数のある標本位置で持つ。

use crate::difference::標本の差;
use crate::fractional::小数の標本位置;

/// 小数の標本の範囲とは、区間の開始から終了の手前までを、端数のある標本位置で表したもののことである。
/// 端数を丸めずに持つのは、音が区間を1周する長さを映像の1周(秒)と一致させ、繰り返すたびにずれが溜まらないようにするためである。
/// 不変条件: 開始は終了より後ろにない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 小数の標本の範囲 {
    開始: 小数の標本位置,
    終了: 小数の標本位置,
}

impl 小数の標本の範囲 {
    /// 開始と終了から作成する。開始が終了より後ろなら、終了を開始に合わせる。
    pub fn 収めて作る(開始: 小数の標本位置, 終了: 小数の標本位置) -> Self {
        let 終了 = if 終了 < 開始 { 開始 } else { 終了 };
        Self { 開始, 終了 }
    }

    /// 開始の位置。
    pub fn 開始(&self) -> 小数の標本位置 {
        self.開始
    }

    /// 終了の位置(範囲に含まない)。
    pub fn 終了(&self) -> 小数の標本位置 {
        self.終了
    }

    /// 範囲の長さ。
    pub fn 長さ(&self) -> 標本の差 {
        self.終了.他方からの差(self.開始)
    }

    /// 位置から終了までの残り。位置が終了より後ろなら負である。
    pub fn 終了までの残り(&self, 位置: 小数の標本位置) -> 標本の差 {
        self.終了.他方からの差(位置)
    }

    /// 開始から位置までの進み。位置が開始より前なら負である。
    pub fn 開始からの進み(&self, 位置: 小数の標本位置) -> 標本の差 {
        位置.他方からの差(self.開始)
    }
}
