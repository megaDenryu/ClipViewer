//! 標本と標本の間も指せる位置の型。

use clip_domain::{再生速度, 小数を切り捨てた整数};

use crate::difference::標本の差;
use crate::position::動画上の標本位置;

/// 小数の標本位置とは、標本と標本の間も指せる動画上の位置のことである。速度を変えて読むときの読み位置に使う。
/// 不変条件: 0以上の有限の数である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd, Default)]
#[repr(transparent)]
pub struct 小数の標本位置(f64);

impl 小数の標本位置 {
    /// 小数から作成する。負と非数と無限大は0に収める。
    pub fn 収めて作る(値: f64) -> Self {
        if !値.is_finite() {
            return Self(0.0);
        }
        Self(値.max(0.0))
    }

    /// 標本位置から作る。
    pub fn 標本位置から作る(位置: 動画上の標本位置) -> Self {
        Self(位置.小数の値())
    }

    /// 値を返す。
    pub fn 値(self) -> f64 {
        self.0
    }

    /// 指定の差だけずらした位置を求める。差が負なら前へ戻し、先頭より前には戻らない。
    pub fn ずらす(self, 差: 標本の差) -> Self {
        Self::収めて作る(self.0 + 差.値())
    }

    /// 1標本を鳴らす間に、速度の分だけ進めた位置を求める。
    pub fn 速度の分だけ進める(self, 速度: 再生速度) -> Self {
        Self::収めて作る(self.0 + 速度.倍率())
    }

    /// 他方からこの位置までの差。この位置が他方より前なら負である。
    pub fn 他方からの差(self, 他方: Self) -> 標本の差 {
        標本の差::収めて作る(self.0 - 他方.0)
    }

    /// 端数を切り捨てた位置。
    pub fn 切り捨てた位置(self) -> 動画上の標本位置 {
        動画上の標本位置::作成する(小数を切り捨てた整数(self.0))
    }

    /// 切り捨てた位置からの端数(0以上1未満)。線形補間の重みに使う。
    pub fn 端数(self) -> f64 {
        self.0 - self.切り捨てた位置().小数の値()
    }
}
