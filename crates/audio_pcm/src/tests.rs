//! 音の値の型と溜めた音の試験。

#![allow(clippy::expect_used)]

use clip_domain::{時刻, 時間の長さ};

use crate::{
    サンプリング周波数, ステレオの標本, 動画上の標本位置, 小数の標本位置, 標本の差, 標本数,
    溜めた音, 音量,
};

fn 周波数() -> サンプリング周波数 {
    サンプリング周波数::作成する(48_000).expect("周波数を作れない")
}

#[test]
fn 時刻と標本位置は周波数で対応する() {
    let 一秒半 = 時刻::作成する(1.5).expect("時刻");
    assert_eq!(周波数().時刻を含む標本位置(一秒半).値(), 72_000);
    let 長さ = 時間の長さ::作成する(0.01).expect("長さ");
    assert_eq!(周波数().長さの標本数(長さ).値(), 480);
    let 位置 = 動画上の標本位置::作成する(24_000);
    assert!((周波数().標本位置の時刻(位置).秒数() - 0.5).abs() < 1e-12);
    assert!(サンプリング周波数::作成する(0).is_none());
}

#[test]
fn 境目ちょうどの時刻は1つ前の標本へ落ちない() {
    let 時刻 = 時刻::作成する(0.1).expect("時刻");
    assert_eq!(周波数().時刻を含む標本位置(時刻).値(), 4_800);
}

#[test]
fn 小数の標本位置は切り捨てた位置と端数に分かれる() {
    let 位置 = 小数の標本位置::収めて作る(10.25);
    assert_eq!(位置.切り捨てた位置().値(), 10);
    assert!((位置.端数() - 0.25).abs() < 1e-12);
    assert_eq!(小数の標本位置::収めて作る(-3.0).値(), 0.0);
    assert_eq!(小数の標本位置::収めて作る(f64::NAN).値(), 0.0);
    assert_eq!(位置.ずらす(標本の差::収めて作る(-20.0)).値(), 0.0);
}

#[test]
fn 溜めた音は先頭からの範囲だけ標本を返す() {
    let 先頭 = 動画上の標本位置::作成する(100);
    let 音 = 溜めた音::作成する(先頭, vec![[0.1, -0.1], [0.2, -0.2], [0.3, -0.3]]);
    assert_eq!(音.標本数(), 標本数::作成する(3));
    assert_eq!(音.範囲().終了().値(), 103);
    assert!(音.標本(動画上の標本位置::作成する(99)).is_none());
    assert!(音.標本(動画上の標本位置::作成する(103)).is_none());
    let 真ん中 = 音.標本(動画上の標本位置::作成する(101)).expect("標本");
    assert!((真ん中.左 - 0.2).abs() < 1e-6);
    assert!((真ん中.右 + 0.2).abs() < 1e-6);
}

#[test]
fn 標本を寄せる重みは両端で自分と他方になる() {
    let 自分 = ステレオの標本 { 左: 1.0, 右: 0.0 };
    let 他方 = ステレオの標本 { 左: 0.0, 右: 1.0 };
    assert_eq!(自分.他方へ寄せる(他方, 0.0), 自分);
    assert_eq!(自分.他方へ寄せる(他方, 1.0), 他方);
    assert!((自分.他方へ寄せる(他方, 0.5).左 - 0.5).abs() < 1e-12);
}

#[test]
fn 音量は0から1へ収める() {
    assert_eq!(音量::範囲へ収めて作る(-1.0).値(), 0.0);
    assert_eq!(音量::範囲へ収めて作る(2.0).値(), 1.0);
    assert_eq!(音量::範囲へ収めて作る(f64::NAN).値(), 0.0);
    assert_eq!(音量::既定.値(), 0.5);
}
