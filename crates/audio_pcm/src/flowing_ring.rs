//! 音の輪。流れてくる音の中身であり、決まった容量の輪の上に、動画上の連続した範囲の標本を持つ。
//! 同期(錠と待ち合わせ)は持たない純粋なデータ構造で、`流れてくる音` が錠の中で操作する。

use crate::position::{動画上の標本位置, 標本数};
use crate::range::標本の範囲;
use crate::stereo::{ステレオの標本, 左右の値};

/// 音の輪とは、決まった容量の輪の上に、動画上の最も古い位置から書いた先の手前までの標本を持つもののことである。
/// 書き手は、鳴らしている位置より残す長さだけ前の位置までの古い標本の場所へ上書きしてよい。
/// 不変条件: 最も古い位置 <= 書いた先、かつ 書いた先 - 最も古い位置 <= 容量。
pub(crate) struct 音の輪 {
    値の並び: Vec<左右の値>,
    最も古い位置: 動画上の標本位置,
    書いた先: 動画上の標本位置,
    鳴らしている位置: 動画上の標本位置,
    残す長さ: 標本数,
}

impl 音の輪 {
    /// 開始の位置から書き始める空の輪を作る。容量は1以上に収める。確保はここで1回だけ行う。
    pub(crate) fn 作成する(
        開始: 動画上の標本位置, 容量: 標本数, 残す長さ: 標本数
    ) -> Self {
        let 容量 = 容量.並びの長さ().max(1);
        Self {
            値の並び: vec![[0.0, 0.0]; 容量],
            最も古い位置: 開始,
            書いた先: 開始,
            鳴らしている位置: 開始,
            残す長さ,
        }
    }

    /// 今書き込める標本の数。
    pub(crate) fn 書き込める数(&self) -> usize {
        let 捨ててよい境 = self.鳴らしている位置.戻す(self.残す長さ);
        let 残す始まり = self.最も古い位置.max(捨ててよい境);
        let 使っている数 = self.書いた先.起点からの標本数(残す始まり).並びの長さ();
        self.値の並び.len().saturating_sub(使っている数)
    }

    /// 並びの先頭から、書き込める数までを書き込む。書き込んだ数を返す。
    pub(crate) fn 書き込む(&mut self, 値: &[左右の値]) -> usize {
        let 書く数 = 値.len().min(self.書き込める数());
        for 一つ in &値[..書く数] {
            let 添字 = self.添字(self.書いた先);
            self.値の並び[添字] = *一つ;
            self.書いた先 = self.書いた先.進める(標本数::作成する(1));
        }
        let 容量 = 標本数::並びの長さから作る(self.値の並び.len());
        self.最も古い位置 = self.最も古い位置.max(self.書いた先.戻す(容量));
        書く数
    }

    /// その位置の標本。輪の範囲の外なら無い。
    pub(crate) fn 標本(&self, 位置: 動画上の標本位置) -> Option<ステレオの標本> {
        if 位置 < self.最も古い位置 || 位置 >= self.書いた先 {
            return None;
        }
        let 値 = self.値の並び[self.添字(位置)];
        Some(ステレオの標本::左右の値から作る(値))
    }

    /// 鳴らしている位置を覚える。書き手はこの位置より残す長さだけ前までの標本を上書きしてよくなる。
    pub(crate) fn 鳴らしている位置を覚える(
        &mut self, 位置: 動画上の標本位置
    ) {
        self.鳴らしている位置 = 位置;
    }

    /// 輪が持っている標本の範囲。
    pub(crate) fn 範囲(&self) -> 標本の範囲 {
        let 長さ = self.書いた先.起点からの標本数(self.最も古い位置);
        標本の範囲::開始と長さから作る(self.最も古い位置, 長さ)
    }

    fn 添字(&self, 位置: 動画上の標本位置) -> usize {
        let 番号 = usize::try_from(位置.値()).unwrap_or(usize::MAX);
        番号 % self.値の並び.len()
    }
}
