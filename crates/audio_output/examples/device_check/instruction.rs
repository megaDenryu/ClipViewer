//! 確認で鳴らす指示。1秒の無音を溜めた区間を音量0で再生し、装置へ音を出さずに再生の経路(溜めた音の読み出し)を通す。

use std::sync::Arc;
use std::time::Instant;

use audio_output::{
    再生の指示, 再生の様子, 範囲の外の行の番号, 終わりで続く音, 行ごとの再生の指示, 音の区間,
};
use audio_pcm::{
    サンプリング周波数, 動画上の標本位置, 小数の標本の範囲, 小数の標本位置, 溜めた音, 音の出どころ,
    音量,
};
use clip_domain::行の番号;

/// 1秒の無音を溜めた区間を、音量0で再生している指示。1本目の流れに渡す。
pub(crate) fn 無音の区間を鳴らす指示(
    周波数: サンプリング周波数
) -> 再生の指示 {
    let 一秒 = 周波数.毎秒の標本数();
    let 先頭 = 動画上の標本位置::先頭;
    let 音 = 溜めた音::作成する(先頭, vec![[0.0, 0.0]; usize::try_from(一秒).unwrap_or(0)]);
    let 範囲 = 小数の標本の範囲::収めて作る(
        小数の標本位置::標本位置から作る(先頭),
        小数の標本位置::標本位置から作る(先頭.進める(音.標本数())),
    );
    let mut 指示 = 再生の指示::黙る(Instant::now());
    指示.様子 = 再生の様子::再生している;
    指示.音量 = 音量::無音;
    指示.区間 = Some(音の区間 {
        範囲,
        出どころ: Some(音の出どころ::溜めた音(Arc::new(音))),
    });
    指示.行き先 = 終わりで続く音::開始へ戻る;
    指示
}

/// 0番の行と最後の行で無音の区間を音量0で鳴らし、ほかの行は黙る指示。2本目の流れに渡し、行を混ぜる経路を通す。
pub(crate) fn 行で無音の区間を鳴らす指示(
    周波数: サンプリング周波数,
) -> Result<行ごとの再生の指示, 範囲の外の行の番号> {
    let mut 指示 = 行ごとの再生の指示::黙る(Instant::now());
    for 番号 in [0, clip_domain::同時に重ねられる行の数 - 1] {
        指示.行の指示を置き換える(
            行の番号::番号から作成する(番号),
            無音の区間を鳴らす指示(周波数),
        )?;
    }
    Ok(指示)
}
