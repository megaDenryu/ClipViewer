//! 確認で鳴らす指示。耳に聞こえる音を出さずに、再生の経路(溜めた音の読み出し)と行を混ぜる経路を通す。

use std::sync::Arc;
use std::time::Instant;

use audio_output::{
    再生の指示, 再生の様子, 範囲の外の行の番号, 終わりで続く音, 行ごとの再生の指示, 音の区間,
};
use audio_pcm::{
    サンプリング周波数, 動画上の標本位置, 小数の標本の範囲, 小数の標本位置, 左右の値, 溜めた音,
    音の出どころ, 音量,
};
use clip_domain::{同時に重ねられる行の数, 行の番号};

/// 1秒の無音を溜めた区間を、音量0で再生している指示。スタックの音の出力に渡す。
pub(crate) fn 無音の区間を鳴らす指示(
    周波数: サンプリング周波数
) -> 再生の指示 {
    let 一秒 = usize::try_from(周波数.毎秒の標本数()).unwrap_or(0);
    let 指示 =
        溜めた音を鳴らす指示(&溜めた音を作る(vec![[0.0, 0.0]; 一秒]), Instant::now());
    再生の指示 {
        音量: 音量::無音,
        ..指示
    }
}

/// すべての行で、振幅0.5の三角の波を音量1で鳴らし、奇数番の行は符号を反転した波にする指示。行の音の出力に渡す。
/// 行の音を混ぜる係は行の番号の順に足すため、偶数番の行と次の奇数番の行が標本ごとにちょうど打ち消し合い、
/// 混ぜた標本はすべて0になる(符号を反転した値の読み出しと掛け算は、丸めも符号だけが反転する)。
/// 8行の再生器が音量0でない標本を作る負荷をかけながら、装置からは音が出ない。
pub(crate) fn 行で打ち消し合う波を鳴らす指示(
    周波数: サンプリング周波数,
) -> Result<行ごとの再生の指示, 範囲の外の行の番号> {
    let 一秒 = 周波数.毎秒の標本数();
    let 正の波 = 溜めた音を作る(三角の波(一秒, 1.0));
    let 負の波 = 溜めた音を作る(三角の波(一秒, -1.0));
    let 今 = Instant::now();
    let mut 指示 = 行ごとの再生の指示::黙る(今);
    for 番号 in 0..同時に重ねられる行の数 {
        let 音 = if 番号 % 2 == 0 {
            &正の波
        } else {
            &負の波
        };
        指示.行の指示を置き換える(
            行の番号::番号から作成する(番号),
            溜めた音を鳴らす指示(音, 今),
        )?;
    }
    Ok(指示)
}

/// 周期200標本・振幅0.5の三角の波を、標本の数だけ並べたもの。右は左の符号を反転した値にする。
fn 三角の波(標本の数: u32, 符号: f32) -> Vec<左右の値> {
    (0..標本の数)
        .map(|番号| {
            let 山からの距離 = u16::try_from(番号 % 200).unwrap_or(0).abs_diff(100);
            let 値 = 符号 * f32::from(山からの距離) / 200.0;
            [値, -値]
        })
        .collect()
}

fn 溜めた音を作る(値の並び: Vec<左右の値>) -> Arc<溜めた音> {
    Arc::new(溜めた音::作成する(動画上の標本位置::先頭, 値の並び))
}

/// 溜めた音の全体を区間にし、今に先頭を指示した、音量1で繰り返し再生している指示。打ち消し合う行は同じ今で作り、読み位置を揃える。
fn 溜めた音を鳴らす指示(音: &Arc<溜めた音>, 今: Instant) -> 再生の指示 {
    let 先頭 = 動画上の標本位置::先頭;
    let mut 指示 = 再生の指示::黙る(今);
    指示.様子 = 再生の様子::再生している;
    指示.音量 = 音量::範囲へ収めて作る(1.0);
    指示.区間 = Some(音の区間 {
        範囲: 小数の標本の範囲::収めて作る(
            小数の標本位置::標本位置から作る(先頭),
            小数の標本位置::標本位置から作る(先頭.進める(音.標本数())),
        ),
        出どころ: Some(音の出どころ::溜めた音(Arc::clone(音))),
    });
    指示.行き先 = 終わりで続く音::開始へ戻る;
    指示
}
