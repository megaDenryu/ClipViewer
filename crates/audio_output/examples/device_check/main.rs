//! 音声出力装置の確認。既定の出力装置にスタックの音の出力(1本目の流れ)を開いて音量0で鳴らし、続けて同じ装置に
//! 行の音の出力(2本目の流れ)を開いて、8行で打ち消し合う波(混ぜると0になる)を鳴らす。確かめることは次のとおりである。
//! - 2本とも開けて、装置が2本とも音を求めること(2本目を開けない環境は、重ね合わせの音の設計が成り立たないため失敗にする)
//! - 2本目を開いている間に、cpal がスタックの音の出力の途切れ(Xrun)を1回も知らせないこと。ただし cpal 0.18 の WASAPI(Windows)は
//!   出力の流れで途切れを知らせないため、Windows ではこの確かめは空振りであり、途切れが無かったことの証明にならない
//! - 2本目を開いている間も、スタックの音の出力が埋める標本の速さが1本だけのときの9割を下回らないこと。WASAPI は遅れた分を
//!   まとめて求めるため、この確かめで捕まえられるのは大きく求められなくなったときだけである
//!
//! `cargo xtask verify` が最後の工程で実行する。終了コードは、0 が確かめた、3 が装置が無いため実行しなかった、1 が失敗である。
//! 手で実行するとき(実行場所はリポジトリのルート): `cargo run -p audio_output --example device_check`

mod instruction;
mod measure;

use std::process::ExitCode;
use std::thread;

use audio_output::{行を混ぜる音声出力, 音声出力, 音声出力のエラー};
use instruction::{
    無音の区間を鳴らす指示, 行で打ち消し合う波を鳴らす指示
};
use measure::{二本を開いた間の測定, 落ち着くまで待つ時間, 速さを測る};

/// 装置が無いため確認を実行しなかったことを示す終了コード。xtask はこれを見て「実行しなかった」と表示する。
const 装置が無いときの終了コード: u8 = 3;

fn main() -> ExitCode {
    let スタックの音の出力 = match スタックの音の出力を開く() {
        Ok(出力) => 出力,
        Err(終了コード) => return 終了コード,
    };
    thread::sleep(落ち着くまで待つ時間);
    let 一本だけの速さ = 速さを測る(&スタックの音の出力);
    let 行の音の出力 = match 行の音の出力を開いて鳴らす() {
        Ok(出力) => 出力,
        Err(終了コード) => return 終了コード,
    };
    二本を開いた間の測定::測る(&スタックの音の出力, &行の音の出力, 一本だけの速さ).判定する()
}

/// スタックの音の出力を開き、無音の区間を音量0で鳴らし始める。開けなければ、表示を済ませた終了コードを返す。
fn スタックの音の出力を開く() -> Result<音声出力, ExitCode> {
    match 音声出力::既定の装置を開く() {
        Ok(出力) => {
            出力.指示を渡す(無音の区間を鳴らす指示(出力.周波数()));
            Ok(出力)
        }
        Err(音声出力のエラー::装置が無い) => {
            eprintln!("音声出力装置が無いため、確認を実行しなかった");
            Err(ExitCode::from(装置が無いときの終了コード))
        }
        Err(失敗) => {
            eprintln!("音声出力装置を開けない: {失敗}");
            Err(ExitCode::FAILURE)
        }
    }
}

/// 同じ装置に行の音の出力を開き、8行で打ち消し合う波を鳴らし始める。開けなければ、表示を済ませた終了コードを返す。
fn 行の音の出力を開いて鳴らす() -> Result<行を混ぜる音声出力, ExitCode> {
    let 出力 = match 行を混ぜる音声出力::既定の装置を開く() {
        Ok(出力) => 出力,
        Err(失敗) => {
            eprintln!("同じ音声出力装置に2本目の流れを開けない: {失敗}");
            return Err(ExitCode::FAILURE);
        }
    };
    match 行で打ち消し合う波を鳴らす指示(出力.周波数()) {
        Ok(指示) => 出力.指示を渡す(指示),
        Err(失敗) => {
            eprintln!("2本目の流れに渡す指示を組み立てられない: {失敗}");
            return Err(ExitCode::FAILURE);
        }
    }
    Ok(出力)
}
