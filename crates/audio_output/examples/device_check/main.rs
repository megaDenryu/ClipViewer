//! 音声出力装置の確認。既定の出力装置に1本目の流れ(スタックの作業場の音)を開いて音量0で鳴らし、装置が音を求める速さを測る。
//! 続けて同じ装置に2本目の流れ(重ね合わせの作業場の行を混ぜる音)を開いて音量0で鳴らし、2本目も音を求めることと、
//! 2本が同時に開いている間も1本目が埋める標本の速さが減らないこと(1本目の音が途切れないこと)を確かめる。
//! `cargo xtask verify` が最後の工程で実行する。終了コードは、0 が確かめた、3 が装置が無いため実行しなかった、1 が失敗である。
//! 2本目の流れを開けない環境は、重ね合わせの作業場の音の設計(同じ装置に2本目の流れを開く)が成り立たないため、失敗として知らせる。
//! 手で実行するとき(実行場所はリポジトリのルート): `cargo run -p audio_output --example device_check`

mod instruction;

use std::process::ExitCode;
use std::thread;
use std::time::{Duration, Instant};

use audio_output::{行を混ぜる音声出力, 音声出力, 音声出力のエラー};
use instruction::{無音の区間を鳴らす指示, 行で無音の区間を鳴らす指示};

/// 装置が無いため確認を実行しなかったことを示す終了コード。xtask はこれを見て「実行しなかった」と表示する。
const 装置が無いときの終了コード: u8 = 3;
/// 流れを開いてから測り始めるまで待つ時間。開いた直後に装置が先に多めに求める分を、測る窓から外す。
const 落ち着くまで待つ時間: Duration = Duration::from_millis(200);
/// 埋めた標本の速さを測る窓の長さ。
const 測る窓の長さ: Duration = Duration::from_millis(500);
/// 2本を開いている間の1本目の速さが、1本だけのときの速さのこの割合を下回ったら、途切れたとみなす。
/// 装置は数ミリ秒から数十ミリ秒ごとにまとめて求めるため、窓の端の分の揺れを許す。
const 減ったとみなす割合: f64 = 0.9;

fn main() -> ExitCode {
    let 一本目 = match 音声出力::既定の装置を開く() {
        Ok(出力) => 出力,
        Err(音声出力のエラー::装置が無い) => {
            eprintln!("音声出力装置が無いため、確認を実行しなかった");
            return ExitCode::from(装置が無いときの終了コード);
        }
        Err(失敗) => {
            eprintln!("音声出力装置を開けない: {失敗}");
            return ExitCode::FAILURE;
        }
    };
    一本目.指示を渡す(無音の区間を鳴らす指示(一本目.周波数()));
    thread::sleep(落ち着くまで待つ時間);
    let 一本だけの速さ = 一本目の速さを測る(&一本目);
    let 二本目 = match 行を混ぜる音声出力::既定の装置を開く() {
        Ok(出力) => 出力,
        Err(失敗) => {
            eprintln!("同じ音声出力装置に2本目の流れを開けない: {失敗}");
            return ExitCode::FAILURE;
        }
    };
    match 行で無音の区間を鳴らす指示(二本目.周波数()) {
        Ok(指示) => 二本目.指示を渡す(指示),
        Err(失敗) => {
            eprintln!("2本目の流れに渡す指示を組み立てられない: {失敗}");
            return ExitCode::FAILURE;
        }
    }
    thread::sleep(落ち着くまで待つ時間);
    let 二本目の前の数 = 二本目.埋めた標本数();
    let 二本の間の速さ = 一本目の速さを測る(&一本目);
    let 二本目が埋めた数 = 二本目.埋めた標本数().saturating_sub(二本目の前の数);
    if let Some(理由) = 一本目.使えなくなった理由().or(二本目.使えなくなった理由())
    {
        eprintln!("{理由}");
        return ExitCode::FAILURE;
    }
    if 一本だけの速さ <= 0.0 || 二本目が埋めた数 == 0 {
        eprintln!(
            "音声出力装置が音を求めなかった(1本目は毎秒{一本だけの速さ:.0}標本、2本目は{二本目が埋めた数}標本)"
        );
        return ExitCode::FAILURE;
    }
    if 二本の間の速さ < 一本だけの速さ * 減ったとみなす割合 {
        eprintln!(
            "2本目を開いている間に1本目が埋めた標本の速さが減った(1本だけで毎秒{一本だけの速さ:.0}標本、2本で毎秒{二本の間の速さ:.0}標本)"
        );
        return ExitCode::FAILURE;
    }
    println!(
        "音声出力装置を確かめた({}Hz。1本目は1本だけで毎秒{一本だけの速さ:.0}標本、2本目を開いている間も毎秒{二本の間の速さ:.0}標本を埋め、2本目は{}秒で{二本目が埋めた数}標本を埋めた)",
        一本目.周波数().毎秒の標本数(),
        測る窓の長さ.as_secs_f64()
    );
    ExitCode::SUCCESS
}

/// 測る窓の長さだけ待ち、その間に1本目が埋めた標本の数を、実際に経った秒数で割った速さ(毎秒の標本数)。
fn 一本目の速さを測る(一本目: &音声出力) -> f64 {
    let 始めの数 = 一本目.埋めた標本数();
    let 始め = Instant::now();
    thread::sleep(測る窓の長さ);
    let 増えた数 = 一本目.埋めた標本数().saturating_sub(始めの数);
    let 経った秒数 = 始め.elapsed().as_secs_f64();
    f64::from(u32::try_from(増えた数).unwrap_or(u32::MAX)) / 経った秒数
}
