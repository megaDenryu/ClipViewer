//! 確認の測定と判定。2本の流れを開いている間に、スタックの音の出力が途切れを知らされた回数と埋めた標本の速さ、
//! 行の音の出力が埋めた標本の数を測り、確かめる条件と比べる。

use std::process::ExitCode;
use std::thread;
use std::time::{Duration, Instant};

use audio_output::{行を混ぜる音声出力, 音声出力, 音声出力のエラー};

/// 流れを開いてから測り始めるまで待つ時間。開いた直後に装置が先に多めに求める分を、測る時間から外す。
pub(crate) const 落ち着くまで待つ時間: Duration = Duration::from_millis(200);
/// 埋めた標本の速さを測る時間の長さ。
const 測る時間の長さ: Duration = Duration::from_millis(500);
/// 2本を開いている間の速さが、1本だけのときの速さのこの割合を下回ったら、大きく減ったとみなす。
/// 装置は数ミリ秒から数十ミリ秒ごとにまとめて求めるため、測る時間の始めと終わりの分の揺れを許す。
const 減ったとみなす割合: f64 = 0.9;

/// 測る時間の長さだけ待ち、その間にスタックの音の出力が埋めた標本の数を、実際に経った秒数で割った速さ(毎秒の標本数)。
pub(crate) fn 速さを測る(スタックの音の出力: &音声出力) -> f64 {
    let 始めの数 = スタックの音の出力.埋めた標本数();
    let 始め = Instant::now();
    thread::sleep(測る時間の長さ);
    let 増えた数 = スタックの音の出力.埋めた標本数().saturating_sub(始めの数);
    let 経った秒数 = 始め.elapsed().as_secs_f64();
    f64::from(u32::try_from(増えた数).unwrap_or(u32::MAX)) / 経った秒数
}

/// 二本を開いた間の測定とは、1本だけのときと2本を開いている間のスタックの音の出力の速さ、2本を開いている間に
/// 2本それぞれが途切れを知らされた回数、行の音の出力が埋めた標本の数、どちらかが使えなくなった理由、周波数の組のことである。
pub(crate) struct 二本を開いた間の測定 {
    一本だけの速さ: f64,
    二本の間の速さ: f64,
    スタックの音の途切れの回数: u64,
    行の音の途切れの回数: u64,
    行の音の出力が埋めた数: u64,
    使えなくなった理由: Option<音声出力のエラー>,
    毎秒の標本数: u32,
}

impl 二本を開いた間の測定 {
    /// 行の音の出力を開いた後、落ち着くまで待ってから、測る時間の長さだけ2本を鳴らして測る。
    pub(crate) fn 測る(
        スタックの音の出力: &音声出力,
        行の音の出力: &行を混ぜる音声出力,
        一本だけの速さ: f64,
    ) -> Self {
        thread::sleep(落ち着くまで待つ時間);
        let スタックの前の途切れ = スタックの音の出力.途切れを知らされた回数();
        let 行の前の途切れ = 行の音の出力.途切れを知らされた回数();
        let 行の前の数 = 行の音の出力.埋めた標本数();
        let 二本の間の速さ = 速さを測る(スタックの音の出力);
        Self {
            一本だけの速さ,
            二本の間の速さ,
            スタックの音の途切れの回数: スタックの音の出力
                .途切れを知らされた回数()
                .saturating_sub(スタックの前の途切れ),
            行の音の途切れの回数: 行の音の出力
                .途切れを知らされた回数()
                .saturating_sub(行の前の途切れ),
            行の音の出力が埋めた数: 行の音の出力
                .埋めた標本数()
                .saturating_sub(行の前の数),
            使えなくなった理由: スタックの音の出力
                .使えなくなった理由()
                .or(行の音の出力.使えなくなった理由()),
            毎秒の標本数: スタックの音の出力.周波数().毎秒の標本数(),
        }
    }

    /// 確かめる条件と比べ、満たさなければ理由を表示して失敗を、満たせば測った値を表示して成功を返す。
    pub(crate) fn 判定する(&self) -> ExitCode {
        match self.満たさない理由() {
            Some(理由) => {
                eprintln!("{理由}");
                ExitCode::FAILURE
            }
            None => {
                println!(
                    "音声出力装置を確かめた({}Hz。スタックの音の出力は1本だけで毎秒{:.0}標本、2本目を開いている間も毎秒{:.0}標本を埋め、途切れの知らせは{}回(Windows の出力では cpal が知らせない)。行の音の出力は8行で{}秒に{}標本を埋め、途切れの知らせは{}回)",
                    self.毎秒の標本数,
                    self.一本だけの速さ,
                    self.二本の間の速さ,
                    self.スタックの音の途切れの回数,
                    測る時間の長さ.as_secs_f64(),
                    self.行の音の出力が埋めた数,
                    self.行の音の途切れの回数,
                );
                ExitCode::SUCCESS
            }
        }
    }

    fn 満たさない理由(&self) -> Option<String> {
        if let Some(理由) = &self.使えなくなった理由 {
            return Some(理由.to_string());
        }
        if self.一本だけの速さ <= 0.0 || self.行の音の出力が埋めた数 == 0 {
            return Some(format!(
                "音声出力装置が音を求めなかった(スタックの音の出力は毎秒{:.0}標本、行の音の出力は{}標本)",
                self.一本だけの速さ, self.行の音の出力が埋めた数
            ));
        }
        if self.スタックの音の途切れの回数 > 0 {
            return Some(format!(
                "2本目を開いている間に、スタックの音の出力の途切れを{}回知らされた",
                self.スタックの音の途切れの回数
            ));
        }
        if self.二本の間の速さ < self.一本だけの速さ * 減ったとみなす割合 {
            return Some(format!(
                "2本目を開いている間に、スタックの音の出力が埋めた標本の速さが減った(1本だけで毎秒{:.0}標本、2本で毎秒{:.0}標本)",
                self.一本だけの速さ, self.二本の間の速さ
            ));
        }
        None
    }
}
