//! 音声出力装置の確認。既定の出力装置を開き、音量0で0.3秒鳴らして、装置が音を求めたこと(埋めた標本数が増えたこと)を確かめる。
//! `cargo xtask verify` が最後の工程で実行する。終了コードは、0 が確かめた、3 が装置が無いため実行しなかった、1 が失敗である。
//! 手で実行するとき(実行場所はリポジトリのルート): `cargo run -p audio_output --example device_check`

use std::process::ExitCode;
use std::sync::Arc;
use std::thread;
use std::time::{Duration, Instant};

use audio_output::{
    再生の指示, 再生の様子, 終わりで続く音, 音の区間, 音声出力, 音声出力のエラー
};
use audio_pcm::{
    動画上の標本位置, 小数の標本の範囲, 小数の標本位置, 溜めた音, 音の出どころ, 音量
};

/// 装置が無いため確認を実行しなかったことを示す終了コード。xtask はこれを見て「実行しなかった」と表示する。
const 装置が無いときの終了コード: u8 = 3;

fn main() -> ExitCode {
    let 出力 = match 音声出力::既定の装置を開く() {
        Ok(出力) => 出力,
        Err(音声出力のエラー::装置が無い) => {
            eprintln!("音声出力装置が無いため、確認を実行しなかった");
            return ExitCode::from(装置が無いときの終了コード);
        }
        Err(失敗) => {
            eprintln!("音声出力装置を開けない: {失敗}");
            return ExitCode::FAILURE;
        }
    };
    出力.指示を渡す(無音の区間を鳴らす指示(&出力));
    thread::sleep(Duration::from_millis(300));
    let 埋めた数 = 出力.埋めた標本数();
    if let Some(理由) = 出力.使えなくなった理由() {
        eprintln!("{理由}");
        return ExitCode::FAILURE;
    }
    if 埋めた数 == 0 {
        eprintln!("音声出力装置が0.3秒の間に一度も音を求めなかった");
        return ExitCode::FAILURE;
    }
    println!(
        "音声出力装置を確かめた({}Hz、0.3秒で{埋めた数}標本を埋めた)",
        出力.周波数().毎秒の標本数()
    );
    ExitCode::SUCCESS
}

/// 1秒の無音を溜めた区間を、音量0で再生している指示。再生の経路(溜めた音の読み出し)を通すために使う。
fn 無音の区間を鳴らす指示(出力: &音声出力) -> 再生の指示 {
    let 一秒 = 出力.周波数().毎秒の標本数();
    let 先頭 = 動画上の標本位置::先頭;
    let 音 = 溜めた音::作成する(先頭, vec![[0.0, 0.0]; usize::try_from(一秒).unwrap_or(0)]);
    let 範囲 = 小数の標本の範囲::収めて作る(
        小数の標本位置::標本位置から作る(先頭),
        小数の標本位置::標本位置から作る(先頭.進める(音.標本数())),
    );
    let mut 指示 = 再生の指示::黙る(Instant::now());
    指示.様子 = 再生の様子::再生している;
    指示.音量 = 音量::無音;
    指示.区間 = Some(音の区間 {
        範囲,
        出どころ: Some(音の出どころ::溜めた音(Arc::new(音))),
    });
    指示.行き先 = 終わりで続く音::開始へ戻る;
    指示
}
