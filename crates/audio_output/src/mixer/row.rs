//! 混ぜる行の再生器。1つの行の音を作る音の再生器と、その行が手放した出どころの置き場と、その行の下書きを持つ。

use std::time::Instant;

use audio_pcm::{サンプリング周波数, ステレオの標本};

use crate::device::下書きの標本数;
use crate::instruction::再生の指示;
use crate::player::音の再生器;
use crate::retired::退いた出どころの置き場;

/// 混ぜる行の再生器とは、1つの行の音の再生器と、その再生器が手放した出どころを預かる置き場と、
/// 行の標本を一度置く下書き(下書きの標本数の大きさ)の組のことである。下書きは作るときに1回だけ確保する。
pub(super) struct 混ぜる行の再生器 {
    再生器: 音の再生器,
    置き場: 退いた出どころの置き場,
    下書き: Vec<ステレオの標本>,
}

impl 混ぜる行の再生器 {
    pub(super) fn 作成する(周波数: サンプリング周波数) -> Self {
        Self {
            再生器: 音の再生器::作成する(周波数),
            置き場: 退いた出どころの置き場::default(),
            下書き: vec![ステレオの標本::無音; 下書きの標本数],
        }
    }

    /// 指示に従って行の標本を下書きに作り、出力の標本へ1つずつ足し込む。
    /// 前提: 出力の長さは下書きの標本数以下である(行の音を混ぜる係が分けて呼ぶ)。
    pub(super) fn 足し込む(
        &mut self,
        指示: &再生の指示,
        今: Instant,
        出力: &mut [ステレオの標本],
    ) {
        let 下書き = &mut self.下書き[..出力.len()];
        self.再生器.埋める(指示, 今, 下書き, &mut self.置き場);
        for (足し先, 行の標本) in 出力.iter_mut().zip(下書き.iter()) {
            *足し先 = 足し先.足す(*行の標本);
        }
    }

    /// 置き場が預かっている出どころをすべて渡し、空にする。画面のスレッドが錠の中で呼び、錠の外で捨てる。
    pub(super) fn 置き場を引き渡す(&mut self) -> 退いた出どころの置き場 {
        self.置き場.引き渡す()
    }

    /// 下書きの先頭の番地と容量。試験で、埋めても下書きを確保し直さないことを確かめるために使う。
    #[cfg(test)]
    pub(super) fn 下書きの番地と容量(&self) -> (*const ステレオの標本, usize) {
        (self.下書き.as_ptr(), self.下書き.capacity())
    }

    /// 置き場が預かっている出どころの数。試験で、行ごとの置き場が手放した出どころを預かることを確かめるために使う。
    #[cfg(test)]
    pub(super) fn 預かっている数(&self) -> usize {
        self.置き場.預かっている数()
    }
}
