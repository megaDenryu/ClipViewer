//! 混ぜる行の再生器。1つの行の音を作る音の再生器と、その行が手放した出どころの置き場を持つ。

use std::time::Instant;

use audio_pcm::{サンプリング周波数, ステレオの標本};

use crate::instruction::再生の指示;
use crate::player::音の再生器;
use crate::retired::退いた出どころの置き場;

/// 混ぜる行の再生器とは、1つの行の音の再生器と、その再生器が手放した出どころを預かる置き場の組のことである。
pub(super) struct 混ぜる行の再生器 {
    再生器: 音の再生器,
    置き場: 退いた出どころの置き場,
}

impl 混ぜる行の再生器 {
    pub(super) fn 作成する(周波数: サンプリング周波数) -> Self {
        Self {
            再生器: 音の再生器::作成する(周波数),
            置き場: 退いた出どころの置き場::default(),
        }
    }

    /// 指示に従って行の標本を借りた下書きに作り、出力の標本へ1つずつ足し込む。
    /// 前提: 下書きは出力と同じ長さである(行の音を混ぜる係が自分の下書きを出力の長さに切って貸す)。
    pub(super) fn 足し込む(
        &mut self,
        指示: &再生の指示,
        今: Instant,
        出力: &mut [ステレオの標本],
        下書き: &mut [ステレオの標本],
    ) {
        self.再生器.埋める(指示, 今, 下書き, &mut self.置き場);
        for (足し先, 行の標本) in 出力.iter_mut().zip(下書き.iter()) {
            *足し先 = 足し先.足す(*行の標本);
        }
    }

    /// 置き場が預かっている出どころをすべて渡し、空にする。画面のスレッドが錠の中で呼び、錠の外で捨てる。
    pub(super) fn 置き場を引き渡す(&mut self) -> 退いた出どころの置き場 {
        self.置き場.引き渡す()
    }

    /// 置き場が預かっている出どころの数。試験で、行ごとの置き場が手放した出どころを預かることを確かめるために使う。
    #[cfg(test)]
    pub(super) fn 置き場が預かっている出どころの数(&self) -> usize {
        self.置き場.預かっている数()
    }
}
