//! 行の音を混ぜる係。重ね合わせのタイムラインの行ごとに音の再生器を持ち、行ごとの再生の指示で作った標本を足し合わせて
//! −1〜1 へ収める。装置から切り離した純粋な計算であり、装置なしで試験できる。
//! 注意: 音声のスレッドで呼ぶため、メモリの確保をしない。行の下書きは作るときに確保し、手放す出どころは行ごとの置き場へ移す。
//! 参照: _doc/設計/同時再生.md 5-3、_doc/設計/アーキテクチャ.md 判断8-9

mod instructions;
mod row;

#[cfg(test)]
mod tests;

pub use instructions::{行ごとの再生の指示, 行の番号が範囲の外にある};

use std::time::{Duration, Instant};

use audio_pcm::{サンプリング周波数, ステレオの標本};
use clip_domain::同時に重ねられる行の数;

use crate::device::下書きの標本数;
use crate::retired::退いた出どころの置き場;
use row::混ぜる行の再生器;

/// 行の音を混ぜる係とは、同時に重ねられる行の数だけの混ぜる行の再生器(添字は行の番号)と、周波数と、これまでに埋めた標本の数の組のことである。
/// 8行分の下書きは 8 × 4096標本 × 16バイト = 約0.5MB である。
pub(crate) struct 行の音を混ぜる係 {
    行の並び: [混ぜる行の再生器; 同時に重ねられる行の数],
    周波数: サンプリング周波数,
    埋めた標本数: u64,
}

impl 行の音を混ぜる係 {
    pub(crate) fn 作成する(周波数: サンプリング周波数) -> Self {
        Self {
            行の並び: std::array::from_fn(|_| 混ぜる行の再生器::作成する(周波数)),
            周波数,
            埋めた標本数: 0,
        }
    }

    /// 行ごとの指示で各行の標本を作って行の番号の順に足し合わせ、−1〜1 へ収めて出力の並びを埋める。
    /// 今は出力の並びの最初の標本を作る時刻である。出力が下書きの標本数より長ければ、分けて、分けた先頭の時刻を標本の分だけ進めて埋める。
    pub(crate) fn 埋める(
        &mut self,
        指示: &行ごとの再生の指示,
        今: Instant,
        出力: &mut [ステレオの標本],
    ) {
        let mut 済んだ数 = 0_u32;
        for 塊 in 出力.chunks_mut(下書きの標本数) {
            let 経過 = f64::from(済んだ数) / f64::from(self.周波数.毎秒の標本数());
            塊.fill(ステレオの標本::無音);
            for (行, 行の指示) in self.行の並び.iter_mut().zip(指示.並び()) {
                行.足し込む(行の指示, 今 + Duration::from_secs_f64(経過), 塊);
            }
            for 標本 in 塊.iter_mut() {
                *標本 = 標本.負の1から1へ収める();
            }
            済んだ数 = 済んだ数.saturating_add(u32::try_from(塊.len()).unwrap_or(u32::MAX));
        }
        self.埋めた標本数 = self
            .埋めた標本数
            .saturating_add(u64::try_from(出力.len()).unwrap_or(0));
    }

    /// 行ごとの置き場が預かっている出どころをすべて渡し、空にする。画面のスレッドが錠の中で呼び、錠の外で捨てる。
    pub(crate) fn 置き場を引き渡す(
        &mut self,
    ) -> [退いた出どころの置き場; 同時に重ねられる行の数] {
        self.行の並び
            .each_mut()
            .map(混ぜる行の再生器::置き場を引き渡す)
    }

    /// これまでに埋めた標本の数。
    pub(crate) fn 埋めた標本数(&self) -> u64 {
        self.埋めた標本数
    }
}
