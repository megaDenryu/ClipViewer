//! 行の音を混ぜる係。重ね合わせのタイムラインの行ごとに音の再生器を持ち、行ごとの再生の指示で作った標本を足し合わせて
//! −1〜1 へ収める。装置から切り離した純粋な計算であり、装置なしで試験できる。
//! 注意: 音声のスレッドで呼ぶため、メモリの確保をしない。行の下書きは作るときに確保し、手放す出どころは行ごとの置き場へ移す。
//! 参照: _doc/設計/同時再生.md 5-3、_doc/設計/アーキテクチャ.md 判断8-9

mod instructions;
mod row;

#[cfg(test)]
pub(crate) mod tests;

pub use instructions::{範囲の外の行の番号, 行ごとの再生の指示};

use std::time::Instant;

use audio_pcm::{サンプリング周波数, ステレオの標本};
use clip_domain::同時に重ねられる行の数;

use crate::draft_size::下書きの標本数;
use crate::retired::退いた出どころの置き場;
use row::混ぜる行の再生器;

/// 行の音を混ぜる係とは、同時に重ねられる行の数だけの混ぜる行の再生器(添字は行の番号)と、行の標本を一度置く1つの下書き
/// (下書きの標本数の大きさ。左右の f64 で1標本16バイトなので約64KB)と、これまでに埋めた標本の数の組のことである。
/// 下書きは作るときに1回だけ確保し、行ごとに順に貸して使い回す。
pub(crate) struct 行の音を混ぜる係 {
    行の並び: [混ぜる行の再生器; 同時に重ねられる行の数],
    下書き: Vec<ステレオの標本>,
    埋めた標本数: u64,
}

impl 行の音を混ぜる係 {
    pub(crate) fn 作成する(周波数: サンプリング周波数) -> Self {
        Self {
            行の並び: std::array::from_fn(|_| 混ぜる行の再生器::作成する(周波数)),
            下書き: vec![ステレオの標本::無音; 下書きの標本数],
            埋めた標本数: 0,
        }
    }

    /// 行ごとの指示で各行の標本を作って行の番号の順に足し合わせ、−1〜1 へ収めて出力の並びを埋める。今は出力の並びの最初の標本を作る時刻である。
    /// 前提: 出力の長さは下書きの標本数以下である。装置の境界の音を埋める係が、装置の並びを下書きの標本数ずつに分けて渡す。
    /// 注意: 長い出力が届いたら、それは呼び手の誤りであり、到達したらバグとして止める。
    pub(crate) fn 埋める(
        &mut self,
        指示: &行ごとの再生の指示,
        今: Instant,
        出力: &mut [ステレオの標本],
    ) {
        assert!(
            出力.len() <= 下書きの標本数,
            "行の音を混ぜる係へ下書きの標本数より長い出力が届いた(到達したらバグ)"
        );
        let 下書き = &mut self.下書き[..出力.len()];
        出力.fill(ステレオの標本::無音);
        for (行, 行の指示) in self.行の並び.iter_mut().zip(指示.再生の指示の並び())
        {
            行.足し込む(行の指示, 今, 出力, 下書き);
        }
        for 標本 in 出力.iter_mut() {
            *標本 = 標本.負の1から1へ収める();
        }
        self.埋めた標本数 = self
            .埋めた標本数
            .saturating_add(u64::try_from(出力.len()).unwrap_or(0));
    }

    /// 下書きの先頭の番地と容量。試験で、埋めても下書きを確保し直さないことを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 下書きの番地と容量(&self) -> (*const ステレオの標本, usize) {
        (self.下書き.as_ptr(), self.下書き.capacity())
    }
    /// 行ごとの置き場が預かっている出どころをすべて渡し、空にする。画面のスレッドが錠の中で呼び、錠の外で捨てる。
    pub(crate) fn 置き場を引き渡す(
        &mut self,
    ) -> [退いた出どころの置き場; 同時に重ねられる行の数] {
        self.行の並び
            .each_mut()
            .map(混ぜる行の再生器::置き場を引き渡す)
    }

    /// これまでに埋めた標本の数。
    pub(crate) fn 埋めた標本数(&self) -> u64 {
        self.埋めた標本数
    }
}
