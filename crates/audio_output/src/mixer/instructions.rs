//! 行ごとの再生の指示。重ね合わせの作業場が毎フレーム組み立てて、行を混ぜる音声出力へ渡す。

use std::time::Instant;

use clip_domain::{同時に重ねられる行の数, 行の番号};

use crate::instruction::再生の指示;

/// 行ごとの再生の指示とは、タイムラインの行ごとに1つずつ、同時に重ねられる行の数だけ並べた再生の指示のことである。
/// 添字は行の番号である。重ね合わせに無い行と、その時刻に置いたクリップが無い行は、止めている指示を持つ。
#[derive(Debug, Clone)]
pub struct 行ごとの再生の指示([再生の指示; 同時に重ねられる行の数]);

/// 行の番号が範囲の外にあるとは、指示を置き換えようとした行の番号が、同時に重ねられる行の数より後ろにあることである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("行の番号{}は、同時に重ねられる行の数({})より後ろにある", .0.番号(), 同時に重ねられる行の数)]
pub struct 行の番号が範囲の外にある(pub 行の番号);

impl 行ごとの再生の指示 {
    /// どの行も何も鳴らさない指示。行を混ぜる音声出力を開いたときの最初の指示に使う。
    pub fn 黙る(今: Instant) -> Self {
        Self(std::array::from_fn(|_| 再生の指示::黙る(今)))
    }

    /// 行の番号の行の指示を置き換え、前の指示を返す。行の番号が範囲の外なら置き換えずに拒む。
    pub fn 行の指示を置き換える(
        &mut self,
        行: 行の番号,
        指示: 再生の指示,
    ) -> Result<再生の指示, 行の番号が範囲の外にある> {
        let 置き換える先 = self
            .0
            .get_mut(行.番号())
            .ok_or(行の番号が範囲の外にある(行))?;
        Ok(std::mem::replace(置き換える先, 指示))
    }

    /// 行の番号の順に並べた指示。
    pub(crate) fn 並び(&self) -> &[再生の指示; 同時に重ねられる行の数] {
        &self.0
    }
}
