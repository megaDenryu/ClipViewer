//! 行の音を混ぜる係の試験の共通の道具。回帰試験(c)の見本と同じく、時刻を引数で渡して決まった値で鳴らす。
//! 行ごとに一定の値の溜めた音を鳴らし、行の音を混ぜる係の出力を、同じ時刻で別々に鳴らした音の再生器の和と比べる。

