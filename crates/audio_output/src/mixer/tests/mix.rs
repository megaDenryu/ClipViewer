//! 行の音を混ぜる係が、行ごとの標本を足し合わせて −1〜1 へ収めることの試験。

use std::time::Instant;

use audio_pcm::ステレオの標本;

use super::{
    一定の音の区間, 再生する指示, 周波数, 標本の分だけ後, 行ごとの指示を作る
};
use crate::mixer::行の音を混ぜる係;
use crate::{再生の指示, 退いた出どころの置き場, 音の再生器};

/// 1回に埋めさせる標本の数と回数。合わせて800標本(0.1秒)であり、傾ける長さ(40標本)を十分に超える。
const 一回の標本数: usize = 100;
const 埋める回数: u32 = 8;

/// 番号の回に埋めさせる最初の標本の時刻。
fn 何回目の時刻(今: Instant, 番号: u32) -> Instant {
    標本の分だけ後(
        今,
        番号 * u32::try_from(一回の標本数).expect("一回の標本数"),
    )
}

/// 3つの行の指示。0番と1番は音量1で鳴らし、左の和が1を超える。2番は音量0で鳴らす。
fn 三つの行の指示(今: Instant) -> Vec<(usize, 再生の指示)> {
    vec![
        (0, 再生する指示(今, 一定の音の区間(0.75, -0.5), 1.0)),
        (1, 再生する指示(今, 一定の音の区間(0.75, -0.25), 1.0)),
        (2, 再生する指示(今, 一定の音の区間(0.5, 0.5), 0.0)),
    ]
}

/// 行の音を混ぜる係で、一回の標本数ずつ回数だけ、時刻を標本の分だけ進めながら埋めさせて集める。
fn 行の音を混ぜる係で鳴らした標本を集める(
    今: Instant,
    行の指示: Vec<(usize, 再生の指示)>,
) -> Vec<ステレオの標本> {
    let 指示 = 行ごとの指示を作る(今, 行の指示);
    let mut 係 = 行の音を混ぜる係::作成する(周波数());
    let mut 集めた = Vec::new();
    let mut 出力 = [ステレオの標本::無音; 一回の標本数];
    for 番号 in 0..埋める回数 {
        let 時刻 = 何回目の時刻(今, 番号);
        係.埋める(&指示, 時刻, &mut 出力);
        集めた.extend_from_slice(&出力);
    }
    集めた
}

/// 同じ指示と時刻で、行ごとに別々の音の再生器に埋めさせ、行の番号の順に足して −1〜1 へ収めた並び。
fn 別々に鳴らして足す(
    今: Instant,
    行の指示: Vec<(usize, 再生の指示)>,
) -> Vec<ステレオの標本> {
    let 全部の標本数 = 一回の標本数 * usize::try_from(埋める回数).expect("埋める回数");
    let mut 和 = vec![ステレオの標本::無音; 全部の標本数];
    for (_, 指示) in 行の指示 {
        let mut 再生器 = 音の再生器::作成する(周波数());
        let mut 置き場 = 退いた出どころの置き場::default();
        for (番号, 足し先) in (0..埋める回数).zip(和.chunks_mut(一回の標本数)) {
            let mut 出力 = [ステレオの標本::無音; 一回の標本数];
            再生器.埋める(&指示, 何回目の時刻(今, 番号), &mut 出力, &mut 置き場);
            for (和の標本, 行の標本) in 足し先.iter_mut().zip(出力.iter()) {
                *和の標本 = 和の標本.足す(*行の標本);
            }
        }
    }
    和.into_iter()
        .map(ステレオの標本::負の1から1へ収める)
        .collect()
}

#[test]
fn 混ぜた標本は行ごとの標本の和を負の1から1へ収めたものと1標本も違わない() {
    let 今 = Instant::now();
    let 混ぜた = 行の音を混ぜる係で鳴らした標本を集める(今, 三つの行の指示(今));
    let 期待 = 別々に鳴らして足す(今, 三つの行の指示(今));
    assert_eq!(混ぜた.len(), 期待.len());
    for (番号, (出た, 見込み)) in 混ぜた.iter().zip(期待.iter()).enumerate() {
        assert!(
            出た.左.to_bits() == 見込み.左.to_bits() && 出た.右.to_bits() == 見込み.右.to_bits(),
            "{番号}番目の標本が和と違う(出た {出た:?}、和 {見込み:?})"
        );
    }
}

#[test]
fn 鳴り始めた後の標本は左が1へ収まり右は音量0の行を含まない和になる() {
    let 今 = Instant::now();
    let 混ぜた = 行の音を混ぜる係で鳴らした標本を集める(今, 三つの行の指示(今));
    for 標本 in &混ぜた[200..] {
        assert_eq!(標本.左, 1.0, "左の和1.5が1へ収まっていない");
        assert_eq!(
            標本.右, -0.75,
            "右が0番と1番の和でない(音量0の行が混ざった)"
        );
    }
}

#[test]
fn 音量0の行だけを鳴らすと混ぜた標本はすべて無音になる() {
    let 今 = Instant::now();
    let 混ぜた = 行の音を混ぜる係で鳴らした標本を集める(
        今,
        vec![(5, 再生する指示(今, 一定の音の区間(0.75, -0.75), 0.0))],
    );
    assert!(混ぜた.iter().all(|標本| 標本.左 == 0.0 && 標本.右 == 0.0));
}
