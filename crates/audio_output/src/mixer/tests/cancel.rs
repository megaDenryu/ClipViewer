//! 符号を反転した波を偶数番と奇数番の行で鳴らすと、混ぜた標本がちょうど0になることの試験。
//! 装置の確認(`examples/device_check/`)は、この性質を使って、8行に音量0でない音を作らせながら装置から音を出さない。

use std::sync::Arc;
use std::time::Instant;

use audio_pcm::{
    ステレオの標本, 動画上の標本位置, 小数の標本の範囲, 小数の標本位置, 標本数, 溜めた音,
    音の出どころ,
};
use clip_domain::同時に重ねられる行の数;

use super::{再生する指示, 周波数, 標本の分だけ後, 行ごとの指示を作る};
use crate::mixer::行の音を混ぜる係;
use crate::音の区間;

/// 周期200標本の三角の波に符号を掛けた、2000標本の溜めた音の区間。
fn 三角の波の区間(符号: f32) -> 音の区間 {
    let 値の並び = (0..2000_u16)
        .map(|番号| {
            let 値 = 符号 * f32::from((番号 % 200).abs_diff(100)) / 200.0;
            [値, -値]
        })
        .collect();
    let 先頭 = 動画上の標本位置::先頭;
    音の区間 {
        範囲: 小数の標本の範囲::収めて作る(
            小数の標本位置::標本位置から作る(先頭),
            小数の標本位置::標本位置から作る(先頭.進める(標本数::作成する(2000))),
        ),
        出どころ: Some(音の出どころ::溜めた音(
            Arc::new(溜めた音::作成する(先頭, 値の並び)),
        )),
    }
}

#[test]
fn 符号を反転した波を交互の行で鳴らすと混ぜた標本はすべて0になる() {
    let 今 = Instant::now();
    let 正の波 = 三角の波の区間(1.0);
    let 負の波 = 三角の波の区間(-1.0);
    let 行の指示 = (0..同時に重ねられる行の数)
        .map(|番号| {
            let 波 = if 番号 % 2 == 0 {
                &正の波
            } else {
                &負の波
            };
            (番号, 再生する指示(今, 波.clone(), 1.0))
        })
        .collect();
    let mut 正の波だけの係 = 行の音を混ぜる係::作成する(周波数());
    let mut 正の波だけの出力 = [ステレオの標本::無音; 500];
    正の波だけの係.埋める(
        &行ごとの指示を作る(今, vec![(0, 再生する指示(今, 正の波.clone(), 1.0))]),
        今,
        &mut 正の波だけの出力,
    );
    assert!(
        正の波だけの出力.iter().any(|標本| 標本.左 != 0.0),
        "打ち消す相手の無い行が鳴っていない"
    );
    let 指示 = 行ごとの指示を作る(今, 行の指示);
    let mut 係 = 行の音を混ぜる係::作成する(周波数());
    let mut 出力 = [ステレオの標本::無音; 500];
    for 回 in 0..6_u32 {
        係.埋める(&指示, 標本の分だけ後(今, 回 * 500), &mut 出力);
        assert!(
            出力.iter().all(|標本| 標本.左 == 0.0 && 標本.右 == 0.0),
            "{回}回目に打ち消し合わない標本がある"
        );
    }
}
