//! 行ごとの置き場と行ごとの再生の指示の試験。行の再生器が手放した出どころはその行の置き場が預かり、引き渡すと空になる。

use std::sync::Arc;
use std::time::Instant;

use audio_pcm::{ステレオの標本, 音の出どころ};
use clip_domain::{同時に重ねられる行の数, 行の番号};

use super::{
    一定の音の区間, 再生する指示, 周波数, 標本の分だけ後, 行ごとの指示を作る
};
use crate::mixer::行の音を混ぜる係;
use crate::{範囲の外の行の番号, 行ごとの再生の指示};

fn 参照の数(出どころ: &音の出どころ) -> usize {
    match 出どころ {
        音の出どころ::溜めた音(音) => Arc::strong_count(音),
        音の出どころ::流れてくる音(音) => Arc::strong_count(音),
    }
}

#[test]
fn 行の再生器が手放した出どころはその行の置き場が預かり引き渡すと空になる() {
    let 今 = Instant::now();
    let 前の区間 = 一定の音の区間(0.5, 0.5);
    let 前の出どころ = 前の区間.出どころ.clone().expect("出どころ");
    let mut 係 = 行の音を混ぜる係::作成する(周波数());
    let mut 出力 = [ステレオの標本::無音; 1000];
    let 最初 = 行ごとの指示を作る(今, vec![(3, 再生する指示(今, 前の区間, 1.0))]);
    係.埋める(&最初, 今, &mut 出力);
    drop(最初);

    let 次の時刻 = 標本の分だけ後(今, 1000);
    let mut 移す指示 = 再生する指示(次の時刻, 一定の音の区間(0.25, 0.25), 1.0);
    移す指示.飛ばした回数 = 移す指示.飛ばした回数.次();
    let 移す = 行ごとの指示を作る(次の時刻, vec![(3, 移す指示)]);
    係.埋める(&移す, 次の時刻, &mut 出力);

    let 預かっている数: Vec<usize> = 係
        .行の並び
        .iter()
        .map(|行| 行.置き場が預かっている出どころの数())
        .collect();
    assert!(
        預かっている数[3] >= 1,
        "3番の行の置き場が前の音を預かっていない"
    );
    assert!(
        預かっている数
            .iter()
            .enumerate()
            .all(|(番号, 数)| 番号 == 3 || *数 == 0),
        "ほかの行の置き場が預かっている({預かっている数:?})"
    );
    assert!(
        参照の数(&前の出どころ) >= 2,
        "音声のスレッドで前の音を捨てた"
    );

    let 引き取った = 係.置き場を引き渡す();
    assert!(
        係.行の並び
            .iter()
            .all(|行| 行.置き場が預かっている出どころの数() == 0)
    );
    drop(引き取った);
    drop(移す);
    assert_eq!(
        参照の数(&前の出どころ),
        1,
        "引き取った出どころを捨てても参照が残る"
    );
}

#[test]
fn 行の番号が同時に重ねられる行の数より後ろなら指示を置き換えずに拒む() {
    let 今 = Instant::now();
    let mut 指示 = 行ごとの再生の指示::黙る(今);
    let 範囲の外 = 行の番号::番号から作成する(同時に重ねられる行の数);
    let 結果 = 指示
        .行の指示を置き換える(範囲の外, 再生する指示(今, 一定の音の区間(0.5, 0.5), 1.0));
    assert_eq!(結果.err(), Some(範囲の外の行の番号(範囲の外)));
    let 最後 = 行の番号::番号から作成する(同時に重ねられる行の数 - 1);
    let 結果 =
        指示.行の指示を置き換える(最後, 再生する指示(今, 一定の音の区間(0.5, 0.5), 1.0));
    assert!(結果.is_ok());
}
