//! 行の音を混ぜる係が、下書きの標本数ちょうどの出力まで埋めることと、埋めても下書きを確保し直さないことと、
//! 下書きより長い出力を前提の違反として止めることの試験。
//! 音声のスレッドでメモリを確保しないことは、このクレートが `unsafe` を禁じているため数える割り当て器で直接は数えない。
//! 代わりに、確保が起こりうる唯一の入れ物である下書きの番地と容量が、埋める前後で変わらないことを確かめる。

use std::time::Instant;

use audio_pcm::ステレオの標本;

use super::{
    一定の音の区間, 再生する指示, 周波数, 標本の分だけ後, 行ごとの指示を作る
};
use crate::draft_size::下書きの標本数;
use crate::mixer::行の音を混ぜる係;

fn 二つの行を鳴らす指示(今: Instant) -> crate::行ごとの再生の指示 {
    行ごとの指示を作る(
        今,
        vec![
            (0, 再生する指示(今, 一定の音の区間(0.5, -0.5), 1.0)),
            (7, 再生する指示(今, 一定の音の区間(0.25, 0.75), 0.5)),
        ],
    )
}

#[test]
fn 下書きの標本数ちょうどの出力を埋めても下書きの番地と容量は変わらない() {
    let 今 = Instant::now();
    let 指示 = 二つの行を鳴らす指示(今);
    let mut 係 = 行の音を混ぜる係::作成する(周波数());
    let 埋める前 = 係.下書きの番地と容量();
    let mut 出力 = vec![ステレオの標本::無音; 下書きの標本数];
    係.埋める(&指示, 今, &mut 出力);
    let 次の時刻 = 標本の分だけ後(今, u32::try_from(下書きの標本数).expect("数"));
    係.埋める(&指示, 次の時刻, &mut 出力[..100]);
    assert_eq!(埋める前, 係.下書きの番地と容量());
    assert_eq!(係.下書きの番地と容量().1, 下書きの標本数);
    assert!(出力.iter().any(|標本| 標本.左 != 0.0), "鳴っていない");
    assert_eq!(
        係.埋めた標本数(),
        u64::try_from(下書きの標本数 + 100).expect("数")
    );
}

#[test]
#[should_panic(expected = "到達したらバグ")]
fn 下書きの標本数より長い出力は前提の違反として止める() {
    let 今 = Instant::now();
    let mut 係 = 行の音を混ぜる係::作成する(周波数());
    let mut 出力 = vec![ステレオの標本::無音; 下書きの標本数 + 1];
    係.埋める(&二つの行を鳴らす指示(今), 今, &mut 出力);
}
