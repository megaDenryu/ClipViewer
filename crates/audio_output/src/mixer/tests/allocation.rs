//! 行の音を混ぜる係が、下書きより長い出力を分けて埋めることと、埋めても行の下書きを確保し直さないことの試験。
//! 音声のスレッドでメモリを確保しないことは、このクレートが `unsafe` を禁じているため数える割り当て器で直接は数えない。
//! 代わりに、確保が起こりうる唯一の入れ物である行の下書きの番地と容量が、埋める前後で変わらないことを確かめる。

use std::time::Instant;

use audio_pcm::ステレオの標本;

use super::{
    一定の音の区間, 再生する指示, 周波数, 標本の分だけ後, 行ごとの指示を作る
};
use crate::device::下書きの標本数;
use crate::mixer::行の音を混ぜる係;

/// 下書きの標本数より長い出力の標本数。
const 長い出力の標本数: usize = 5_000;

fn 二つの行を鳴らす指示(今: Instant) -> crate::行ごとの再生の指示 {
    行ごとの指示を作る(
        今,
        vec![
            (0, 再生する指示(今, 一定の音の区間(0.5, -0.5), 1.0)),
            (7, 再生する指示(今, 一定の音の区間(0.25, 0.75), 0.5)),
        ],
    )
}

#[test]
fn 下書きより長い出力は分けた先頭の時刻を進めて埋めたものと同じになる() {
    let 今 = Instant::now();
    let 指示 = 二つの行を鳴らす指示(今);
    let mut 一度に埋める係 = 行の音を混ぜる係::作成する(周波数());
    let mut 一度に = vec![ステレオの標本::無音; 長い出力の標本数];
    一度に埋める係.埋める(&指示, 今, &mut 一度に);

    let mut 分けて埋める係 = 行の音を混ぜる係::作成する(周波数());
    let mut 分けて = vec![ステレオの標本::無音; 長い出力の標本数];
    let (前, 後) = 分けて.split_at_mut(下書きの標本数);
    分けて埋める係.埋める(&指示, 今, 前);
    let 前の数 = u32::try_from(下書きの標本数).expect("数");
    分けて埋める係.埋める(&指示, 標本の分だけ後(今, 前の数), 後);

    assert_eq!(一度に, 分けて);
    assert_eq!(一度に埋める係.埋めた標本数(), 5_000);
    assert!(一度に.iter().any(|標本| 標本.左 != 0.0), "鳴っていない");
}

#[test]
fn 埋めても行の下書きの番地と容量は変わらない() {
    let 今 = Instant::now();
    let 指示 = 二つの行を鳴らす指示(今);
    let mut 係 = 行の音を混ぜる係::作成する(周波数());
    let 埋める前: Vec<_> = 係
        .行の並び
        .iter()
        .map(|行| 行.下書きの番地と容量())
        .collect();
    let mut 出力 = vec![ステレオの標本::無音; 長い出力の標本数];
    係.埋める(&指示, 今, &mut 出力);
    係.埋める(&指示, 標本の分だけ後(今, 5_000), &mut 出力);
    let 埋めた後: Vec<_> = 係
        .行の並び
        .iter()
        .map(|行| 行.下書きの番地と容量())
        .collect();
    assert_eq!(埋める前, 埋めた後);
    assert!(埋めた後.iter().all(|(_, 容量)| *容量 == 下書きの標本数));
}
