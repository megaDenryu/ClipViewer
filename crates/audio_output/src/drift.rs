//! 映像とのずれの測り方。音の読み位置と、指示の位置を今まで進めた映像の位置とが、どれだけ離れているかを測る。

use audio_pcm::{小数の標本の範囲, 小数の標本位置, 標本の差};

/// 位置の比べ方とは、音の区間の終わりで何が起きるかに応じて、2つの位置の差をどう数えるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 位置の比べ方 {
    /// 範囲を繰り返す。映像の位置が終わりを越えていたら開始の側へ戻し、範囲の長さだけずらした差も比べる。
    繰り返す範囲(小数の標本の範囲),
    /// 範囲の終わりで別の所へ移る。映像の位置が終わりを越えていたら、映像がまだ移る前なので測らない。
    終わりで移る範囲(小数の標本の範囲),
    /// 区間が無い。差をそのまま測る。
    範囲なし,
}

impl 位置の比べ方 {
    /// 読み位置から映像の位置までの差の大きさ。測らないときは無い。
    pub(crate) fn ずれ(
        &self,
        読み位置: 小数の標本位置,
        映像の位置: 小数の標本位置,
    ) -> Option<標本の差> {
        match self {
            Self::繰り返す範囲(範囲) => {
                Some(繰り返しの中のずれ(範囲, 読み位置, 映像の位置))
            }
            Self::終わりで移る範囲(範囲)
                if 範囲.終了までの残り(映像の位置) <= 標本の差::ゼロ =>
            {
                None
            }
            Self::終わりで移る範囲(_) | Self::範囲なし => {
                Some(読み位置.他方からの差(映像の位置).大きさ())
            }
        }
    }
}

fn 繰り返しの中のずれ(
    範囲: &小数の標本の範囲,
    読み位置: 小数の標本位置,
    映像の位置: 小数の標本位置,
) -> 標本の差 {
    let 長さ = 範囲.長さ();
    let 映像の進み = 範囲.開始からの進み(映像の位置);
    let 映像 = if 範囲.終了までの残り(映像の位置) <= 標本の差::ゼロ {
        映像の進み.全体で割った余り(長さ)
    } else {
        映像の進み
    };
    let 差 = 範囲.開始からの進み(読み位置) - 映像;
    [差, 差 - 長さ, 差 + 長さ]
        .into_iter()
        .map(標本の差::大きさ)
        .fold(差.大きさ(), 標本の差::小さい方)
}
