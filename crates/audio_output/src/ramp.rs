//! 音の大きさの傾き。停止・再開・位置を合わせるときと、読む標本が途切れたときに、音量を0と1の間でなめらかに動かす。

use audio_pcm::{ステレオの標本, 標本の差};

/// 傾きの向きとは、音の大きさを1へ上げるか0へ下げるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 傾きの向き {
    上げる,
    下げる,
}

/// 音の大きさの傾きとは、0以上1以下の今の大きさと、1標本ごとに動かす量と、最後に読めた標本と、標本が途切れているかの組のことである。
/// 0から1まで(または1から0まで)を傾ける標本数で動くため、音が急に途切れたり始まったりしない。
/// 読む標本が途切れたら最後に読めた標本を保ったまま0まで下げ、標本が戻っても0まで下げ切ってから上げ直す。
/// 途切れた波形と戻った波形の値は違うため、下げ切らずに乗り換えると段差になるからである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 音の大きさの傾き {
    大きさ: f64,
    一歩: f64,
    最後の標本: ステレオの標本,
    途切れているか: bool,
}

impl 音の大きさの傾き {
    /// 大きさ0から始める。傾ける標本数は1以上に収める。
    pub(crate) fn 作成する(傾ける長さ: 標本の差) -> Self {
        Self {
            大きさ: 0.0,
            一歩: 1.0 / 傾ける長さ.値().max(1.0),
            最後の標本: ステレオの標本::無音,
            途切れているか: false,
        }
    }

    /// 読んだ標本(途切れていれば無い)に今の大きさを掛けて出し、大きさを1標本分動かす。
    /// 鳴らしたいときでも、標本が途切れている間と、途切れから戻って下げ切るまでは下げる。
    pub(crate) fn 標本を出す(
        &mut self,
        読んだ標本: Option<ステレオの標本>,
        鳴らしたいか: bool,
    ) -> ステレオの標本 {
        match 読んだ標本 {
            None => self.途切れているか = true,
            Some(標本) if !self.途切れているか || self.ゼロか() => {
                self.途切れているか = false;
                self.最後の標本 = 標本;
            }
            Some(_) => {}
        }
        let 上げるか = 鳴らしたいか && !self.途切れているか;
        let 向き = if 上げるか {
            傾きの向き::上げる
        } else {
            傾きの向き::下げる
        };
        self.最後の標本.倍にする(self.一歩進める(向き))
    }

    /// 向きへ1標本分動かし、動かした後の大きさを返す。
    pub(crate) fn 一歩進める(&mut self, 向き: 傾きの向き) -> f64 {
        self.大きさ = match 向き {
            傾きの向き::上げる => (self.大きさ + self.一歩).min(1.0),
            傾きの向き::下げる => (self.大きさ - self.一歩).max(0.0),
        };
        self.大きさ
    }

    /// 大きさが0か。
    pub(crate) fn ゼロか(&self) -> bool {
        self.大きさ <= 0.0
    }

    /// 大きさを0にする。継ぎ目で音を下げ切った後に、行き先から上げ直すために使う。
    pub(crate) fn ゼロにする(&mut self) {
        self.大きさ = 0.0;
    }
}
