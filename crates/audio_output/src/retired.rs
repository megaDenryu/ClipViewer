//! 退いた出どころの置き場。音声のスレッドが手放した出どころを、画面のスレッドが引き取って捨てるまで預かる。

use audio_pcm::音の出どころ;

use crate::section::{終わりで続く音, 音の区間};

/// 置き場の枠の数。画面のスレッドは毎フレーム引き取るため、1フレームの間に手放す数(多くて数個)より十分に大きくする。
const 枠の数: usize = 32;

/// 退いた出どころの置き場とは、決まった数の枠に、音声のスレッドが手放した出どころを預かるもののことである。
/// 出どころ(`Arc`)の最後の参照を音声のスレッドで捨てると、そこでメモリの解放が起きる。解放を画面のスレッドで行うため、
/// 音声のスレッドは捨てずにここへ移す。枠が埋まっているときだけ、その場で捨てる(画面のスレッドが止まっているときに限られる)。
pub struct 退いた出どころの置き場 {
    枠: [Option<音の出どころ>; 枠の数],
}

impl Default for 退いた出どころの置き場 {
    fn default() -> Self {
        Self {
            枠: std::array::from_fn(|_| None),
        }
    }
}

impl 退いた出どころの置き場 {
    /// 出どころを預かる。空いた枠が無ければ、その場で捨てる。
    pub(crate) fn 預かる(&mut self, 出どころ: 音の出どころ) {
        if let Some(空き) = self.枠.iter_mut().find(|枠| 枠.is_none()) {
            *空き = Some(出どころ);
        }
    }

    /// 音の区間が持つ出どころを預かる。
    pub(crate) fn 区間を預かる(&mut self, 区間: Option<音の区間>) {
        if let Some(出どころ) = 区間.and_then(|区間| 区間.出どころ) {
            self.預かる(出どころ);
        }
    }

    /// 終わりで続く音が持つ出どころを預かる。
    pub(crate) fn 行き先を預かる(&mut self, 行き先: Option<終わりで続く音>) {
        if let Some(終わりで続く音::別の区間へ進む(区間)) = 行き先 {
            self.区間を預かる(Some(区間));
        }
    }

    /// 預かっている出どころの数。試験で、同じ中身の指示が置き場を埋めないことを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 預かっている数(&self) -> usize {
        self.枠.iter().filter(|枠| 枠.is_some()).count()
    }

    /// 預かっている出どころをすべて渡し、空にする。画面のスレッドが錠の中で呼び、錠の外で捨てる。
    pub(crate) fn 引き渡す(&mut self) -> Self {
        std::mem::take(self)
    }
}
