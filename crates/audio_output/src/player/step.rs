//! 音の再生器の1標本ずつの手順。読み位置の標本を読み、区間の終わりで行き先の音と重ねて交差させ、読み位置を進める。
//! 行き先が止まるか、まだ分からない(画面のスレッドが次の指示を出す前に区間の終わりへ来た)ときは、終わりで下げて止まる。

use audio_pcm::{ステレオの標本, 標本の差};
use clip_domain::再生速度;

use super::音の再生器;
use crate::reading::速さを変える読み方;
use crate::retired::退いた出どころの置き場;
use crate::section::終わりで続く音;

impl<読み方: 速さを変える読み方> 音の再生器<読み方> {
    /// 今の読み位置の標本を作り、読み位置を速度の分だけ進める。読む標本が途切れていれば無い。
    pub(super) fn 一つの標本を作る(
        &mut self,
        速度: 再生速度,
        置き場: &mut 退いた出どころの置き場,
    ) -> Option<ステレオの標本> {
        let 標本 = self.今の標本();
        self.読み位置を進める(速度, 置き場);
        標本
    }

    fn 今の標本(&mut self) -> Option<ステレオの標本> {
        let 区間 = self.区間.as_ref()?;
        let 残り = 区間.範囲.終了までの残り(self.読み位置);
        if 残り <= 標本の差::ゼロ {
            return None;
        }
        let 基本 = self.読み方.読む(区間.出どころ.as_ref(), self.読み位置)?;
        let 重ねる長さ =
            標本の差::標本数から作る(self.重ねる長さ).小さい方(区間.範囲.長さ().半分());
        if 残り > 重ねる長さ {
            return Some(基本);
        }
        let 残りの割合 = 残り.全体に対する割合(重ねる長さ);
        let 下げた標本 = 基本.倍にする(残りの割合);
        let 相手 = match &self.行き先 {
            None | Some(終わりで続く音::止まる) => return Some(下げた標本),
            Some(終わりで続く音::開始へ戻る) => 区間,
            Some(終わりで続く音::別の区間へ進む(次)) => 次,
        };
        if !相手.開始の手前に音があるか(self.重ねる長さ) {
            return Some(下げた標本);
        }
        let 相手の位置 = 相手.範囲.開始().ずらす(-残り);
        Some(match self.読み方.読む(相手.出どころ.as_ref(), 相手の位置) {
            Some(相手の標本) => 基本.他方へ寄せる(相手の標本, 1.0 - 残りの割合),
            None => 下げた標本,
        })
    }

    fn 読み位置を進める(
        &mut self, 速度: 再生速度, 置き場: &mut 退いた出どころの置き場
    ) {
        let 進めた位置 = self.読み位置.速度の分だけ進める(速度);
        let Some(区間) = self.区間.as_ref() else {
            self.読み位置 = 進めた位置;
            return;
        };
        let 越えた分 = -区間.範囲.終了までの残り(進めた位置);
        if 越えた分 < 標本の差::ゼロ {
            self.読み位置 = 進めた位置;
            return;
        }
        let 重ねる長さ = self.重ねる長さ;
        match &self.行き先 {
            None | Some(終わりで続く音::止まる) => self.読み位置 = 区間.範囲.終了(),
            Some(終わりで続く音::開始へ戻る) => {
                if !区間.開始の手前に音があるか(重ねる長さ) {
                    self.傾き.ゼロにする();
                }
                let 周回の中 = 越えた分.全体で割った余り(区間.範囲.長さ());
                self.読み位置 = 区間.範囲.開始().ずらす(周回の中);
            }
            Some(終わりで続く音::別の区間へ進む(次)) => {
                if !次.開始の手前に音があるか(重ねる長さ) {
                    self.傾き.ゼロにする();
                }
                self.読み位置 = 次.範囲.開始().ずらす(越えた分);
                if let Some(終わりで続く音::別の区間へ進む(次)) = self.行き先.take()
                {
                    置き場.区間を預かる(self.区間.replace(次));
                }
            }
        }
    }

    /// 鳴らしている位置を出どころへ知らせる。流れてくる音の書き手は、これを見て古い標本の場所へ上書きする。
    pub(super) fn 鳴らしている位置を知らせる(&self) {
        if let Some(出どころ) = self.区間.as_ref().and_then(|区間| 区間.出どころ.as_ref())
        {
            出どころ.鳴らしている位置を知らせる(self.読み位置.切り捨てた位置());
        }
    }
}
