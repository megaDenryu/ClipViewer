//! 指示との関係。再生器が今鳴らしている区間と、指示の区間とがどういう関係にあるかを決める。

use audio_pcm::小数の標本の範囲;

use super::音の再生器;
use crate::instruction::再生の指示;
use crate::reading::速さを変える読み方;
use crate::section::{終わりで続く音, 音の区間};

/// 指示との関係とは、再生器が今鳴らしている区間と、指示の区間との関係の区別のことである。
pub(super) enum 指示との関係 {
    /// 同じ範囲の区間である。
    同じ区間,
    /// 再生器が区間の終わりで先に行き先へ移り、画面のスレッドがまだ前の区間を指している。
    先に行き先へ移った,
    /// 画面のスレッドが先に行き先へ移り、再生器は前の区間の終わりの手前(ずれの閾値の内)にいる。
    行き先へ移る手前,
    /// どれでもない。位置を合わせる。
    離れている,
}

pub(super) fn 範囲(区間: Option<&音の区間>) -> Option<小数の標本の範囲> {
    区間.map(|区間| 区間.範囲)
}

fn 進む先の範囲(
    行き先: Option<&終わりで続く音>
) -> Option<小数の標本の範囲> {
    match 行き先 {
        Some(終わりで続く音::別の区間へ進む(区間)) => Some(区間.範囲),
        Some(終わりで続く音::開始へ戻る | 終わりで続く音::止まる) | None => {
            None
        }
    }
}

impl<読み方: 速さを変える読み方> 音の再生器<読み方> {
    pub(super) fn 指示との関係(&self, 指示: &再生の指示) -> 指示との関係 {
        let 自分の範囲 = 範囲(self.区間.as_ref());
        let 指示の範囲 = 範囲(指示.区間.as_ref());
        if 自分の範囲 == 指示の範囲 {
            return 指示との関係::同じ区間;
        }
        if 自分の範囲.is_some() && 進む先の範囲(Some(&指示.行き先)) == 自分の範囲
        {
            return 指示との関係::先に行き先へ移った;
        }
        let 手前か =
            自分の範囲.is_some_and(|範囲| 範囲.終了までの残り(self.読み位置) <= self.ずれの閾値);
        if 手前か && 進む先の範囲(self.行き先.as_ref()) == 指示の範囲 {
            return 指示との関係::行き先へ移る手前;
        }
        指示との関係::離れている
    }
}
