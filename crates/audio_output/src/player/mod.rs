//! 音の再生器。出力装置が音を求めるたびに、再生の指示に従って次の標本を作る。装置からは切り離した純粋な計算であり、
//! 指示との関係の判定(`relation.rs`)と、指示との突き合わせ(`adopt.rs`)と、位置を合わせるときの跳ぶ先(`jump.rs`)と、1標本ずつの読み出しと継ぎ目の重ね合わせ(`step.rs`)に分ける。
//! 注意: 音声のスレッドで呼ぶため、メモリの確保をしない。手放す出どころは置き場へ移す。参照: _doc/設計/アーキテクチャ.md 判断8-5

mod adopt;
mod jump;
mod relation;
mod step;

use std::time::Instant;

use audio_pcm::{
    サンプリング周波数, ステレオの標本, 小数の標本位置, 標本の差, 標本数
};

use crate::instruction::{位置を飛ばした回数, 再生の指示, 再生の様子};
use crate::ramp::音の大きさの傾き;
use crate::reading::{線形補間で読む, 速さを変える読み方};
use crate::retired::退いた出どころの置き場;
use crate::section::{終わりで続く音, 音の区間};
use jump::跳ぶ先;

/// 区間の終わりで行き先の音と重ねる長さ(ミリ秒)。
const 重ねるミリ秒数: u32 = 8;
/// 停止・再開・位置を合わせるときに音の大きさを0と1の間で動かす長さ(秒)。
const 傾ける秒数: f64 = 0.005;
/// 映像とのずれがこれを超えたら読み位置を合わせる(秒)。
const ずれの閾値の秒数: f64 = 0.040;

/// 音の再生器とは、自分の読み位置と今の音の区間と行き先を持ち、再生の指示と突き合わせながら標本を作るもののことである。
/// 読み位置は速度に従って自分で進め、映像とのずれが閾値を超えたときと、位置を飛ばした回数が変わったときだけ合わせる。
pub struct 音の再生器<読み方: 速さを変える読み方 = 線形補間で読む> {
    周波数: サンプリング周波数,
    重ねる長さ: 標本数,
    ずれの閾値: 標本の差,
    読み位置: 小数の標本位置,
    区間: Option<音の区間>,
    行き先: Option<終わりで続く音>,
    飛ばした回数: Option<位置を飛ばした回数>,
    傾き: 音の大きさの傾き,
    跳ぶ先: Option<跳ぶ先>,
    読み方: 読み方,
    埋めた標本数: u64,
}

impl 音の再生器 {
    /// 出力装置の周波数で、線形補間で読む再生器を作る。最初の指示で位置を合わせる。
    pub fn 作成する(周波数: サンプリング周波数) -> Self {
        Self::読み方を指定して作る(周波数, 線形補間で読む)
    }
}

impl<読み方: 速さを変える読み方> 音の再生器<読み方> {
    /// 読み方を指定して作る。
    pub fn 読み方を指定して作る(
        周波数: サンプリング周波数, 読み方: 読み方
    ) -> Self {
        let 標本 = |秒数| 周波数.秒数の小数の標本数(秒数);
        Self {
            周波数,
            重ねる長さ: 標本数::作成する(周波数.毎秒の標本数() * 重ねるミリ秒数 / 1000),
            ずれの閾値: 標本(ずれの閾値の秒数),
            読み位置: 小数の標本位置::default(),
            区間: None,
            行き先: None,
            飛ばした回数: None,
            傾き: 音の大きさの傾き::作成する(標本(傾ける秒数)),
            跳ぶ先: None,
            読み方,
            埋めた標本数: 0,
        }
    }

    /// 指示と突き合わせてから、出力の並びを次の標本で埋める。今は、出力の並びの最初の標本を作る時刻である。
    pub fn 埋める(
        &mut self,
        指示: &再生の指示,
        今: Instant,
        出力: &mut [ステレオの標本],
        置き場: &mut 退いた出どころの置き場,
    ) {
        self.指示を取り込む(指示, 今, 置き場);
        let 再生している = 指示.様子 == 再生の様子::再生している;
        for 書き先 in 出力.iter_mut() {
            if self.跳ぶ先.is_some() && self.傾き.ゼロか() {
                self.跳ぶ(置き場);
            }
            let 鳴らしたいか = self.跳ぶ先.is_none() && 再生している;
            if !鳴らしたいか && self.傾き.ゼロか() {
                *書き先 = ステレオの標本::無音;
                continue;
            }
            let 読んだ標本 = self.一つの標本を作る(指示.速度, 置き場);
            let 出す標本 = self.傾き.標本を出す(読んだ標本, 鳴らしたいか);
            *書き先 = 出す標本.倍にする(指示.音量.値());
        }
        self.埋めた標本数 = self
            .埋めた標本数
            .saturating_add(u64::try_from(出力.len()).unwrap_or(0));
        self.鳴らしている位置を知らせる();
    }

    /// これまでに埋めた標本の数。出力装置が実際に音を求めたかを確かめるために使う。
    pub fn 埋めた標本数(&self) -> u64 {
        self.埋めた標本数
    }

    /// 今の読み位置。
    pub fn 読み位置(&self) -> 小数の標本位置 {
        self.読み位置
    }
}
