//! 音の再生器が指示と突き合わせる手順。位置を飛ばしたか、区間が同じか、映像とずれたかを見て、跳ぶ先を決める。

use std::time::Instant;

use audio_pcm::{小数の標本位置, 標本の差};

use super::relation::{指示との関係, 範囲};
use super::音の再生器;
use crate::drift::位置の比べ方;
use crate::instruction::{再生の指示, 再生の様子};
use crate::reading::速さを変える読み方;
use crate::retired::退いた出どころの置き場;
use crate::section::{終わりで続く音, 音の区間};

impl<読み方: 速さを変える読み方> 音の再生器<読み方> {
    /// 指示と突き合わせる。位置を飛ばした回数が変わったか、区間が離れたか、ずれが閾値を超えたら跳ぶ先を決める。
    pub(super) fn 指示を取り込む(
        &mut self,
        指示: &再生の指示,
        今: Instant,
        置き場: &mut 退いた出どころの置き場,
    ) {
        let 映像の位置 = 指示.今の位置(今, self.周波数);
        if self.飛ばした回数 != Some(指示.飛ばした回数) || self.跳ぶ先.is_some() {
            self.飛ばした回数 = Some(指示.飛ばした回数);
            return self.跳ぶ先を決める(指示, 映像の位置, 置き場);
        }
        match self.指示との関係(指示) {
            指示との関係::同じ区間 => {
                self.同じ区間の指示を取り込む(指示, 映像の位置, 置き場)
            }
            指示との関係::先に行き先へ移った => {
                if let 終わりで続く音::別の区間へ進む(次) = &指示.行き先 {
                    self.区間を新しくする(Some(次), 置き場);
                }
            }
            指示との関係::行き先へ移る手前 => {}
            指示との関係::離れている => {
                self.跳ぶ先を決める(指示, 映像の位置, 置き場)
            }
        }
    }

    /// 同じ区間の指示を取り込む。出どころを新しくし、行き先を置き換え、ずれが閾値を超えていたら跳ぶ先を決める。
    /// ただし映像が再生器より1周先(次の周回)にいるときは、行き先を置き換えない。
    /// 最後の周回へ入ると行き先が「開始へ戻る」から「別の区間へ進む」へ替わるが、再生器にとって今の周回はまだ戻る周回だからである。
    fn 同じ区間の指示を取り込む(
        &mut self,
        指示: &再生の指示,
        映像の位置: 小数の標本位置,
        置き場: &mut 退いた出どころの置き場,
    ) {
        self.区間を新しくする(指示.区間.as_ref(), 置き場);
        let 行き先が同じか = self
            .行き先
            .as_ref()
            .is_some_and(|行き先| 行き先.同じ中身か(&指示.行き先));
        if !行き先が同じか && !self.映像が1周先にいるか(映像の位置) {
            置き場.行き先を預かる(self.行き先.replace(指示.行き先.clone()));
        }
        let 再生している = 指示.様子 == 再生の様子::再生している;
        if 再生している && self.ずれが閾値を超えたか(映像の位置) {
            self.跳ぶ先を決める(指示, 映像の位置, 置き場);
        }
    }

    /// 映像が再生器より1周先(次の周回)にいるか。再生器が開始へ戻る周回を鳴らしていて、映像が同じ区間の中にいて、
    /// 再生器の進みから映像の進みを引いた差が区間の長さの半分を超え、その差から1周を引くと閾値の内に収まるときである。
    /// 繰り返しのずれの比べ方で「差−長さ」の候補が最も小さくなる場合と同じ意味であり、区間が閾値より短くても、
    /// 同じ周回の中の位置を1周先と取り違えない。
    fn 映像が1周先にいるか(&self, 映像の位置: 小数の標本位置) -> bool {
        let Some(範囲) = 範囲(self.区間.as_ref()) else {
            return false;
        };
        let 長さ = 範囲.長さ();
        let 映像の進み = 範囲.開始からの進み(映像の位置);
        let 差 = 範囲.開始からの進み(self.読み位置) - 映像の進み;
        matches!(self.行き先, Some(終わりで続く音::開始へ戻る))
            && 標本の差::ゼロ <= 映像の進み
            && 映像の進み < 長さ
            && 差 > 長さ.半分()
            && (差 - 長さ).大きさ() <= self.ずれの閾値
    }

    /// 区間を新しい指示の区間へ置き換える。同じ中身(範囲と入れ物)なら、複製も置き場への預け入れもしない。
    fn 区間を新しくする(
        &mut self,
        新しい区間: Option<&音の区間>,
        置き場: &mut 退いた出どころの置き場,
    ) {
        if !音の区間::無い場合を含めて同じ中身か(self.区間.as_ref(), 新しい区間)
        {
            置き場.区間を預かる(std::mem::replace(&mut self.区間, 新しい区間.cloned()));
        }
    }

    fn ずれが閾値を超えたか(&self, 映像の位置: 小数の標本位置) -> bool {
        let 比べ方 = match (範囲(self.区間.as_ref()), &self.行き先) {
            (Some(範囲), Some(終わりで続く音::開始へ戻る)) => {
                位置の比べ方::繰り返す範囲(範囲)
            }
            (Some(範囲), _) => 位置の比べ方::終わりで移る範囲(範囲),
            (None, _) => 位置の比べ方::範囲なし,
        };
        比べ方
            .ずれ(self.読み位置, 映像の位置)
            .is_some_and(|ずれ| ずれ > self.ずれの閾値)
    }
}
