//! 周回の途中で行き先の種類が替わる試験。最後から2番目の周回の終わりの手前で、映像が先に最後の周回へ入り行き先が
//! 「別の区間へ進む」に替わっても、音は今の周回を開始へ戻って交差させ、最後の周回を鳴らし切ってから次の区間へ移ること。

use audio_pcm::小数の標本位置;

use super::{
    区間, 正弦波の値, 正弦波の音, 継ぎ目を含めた期待する値, 鳴らし手
};
use crate::終わりで続く音;

const 開始: u32 = 48_000;
const 長さ: u32 = 23_977;
const 余白: u32 = 480;
const 次の開始: u32 = 200_000;

#[test]
fn 映像が先に最後の周回へ入っても音は今の周回を繰り返してから次の区間へ移る() {
    let mut 手 = 鳴らし手::作成する();
    let 今の音 = 正弦波の音(開始 - 余白, 長さ + 余白);
    let 次の音 = 正弦波の音(次の開始 - 余白, 長さ + 余白);
    let 今の区間 = 区間(開始, 開始 + 長さ, 今の音);
    let 次 = 区間(次の開始, 次の開始 + 長さ, 次の音);
    let 戻る指示 = 手.指示(開始, Some(今の区間.clone()), 終わりで続く音::開始へ戻る);
    let mut 並び = 手.鳴らす(&戻る指示, 長さ - 240);
    let mut 進む指示 = 手.指示(開始, Some(今の区間), 終わりで続く音::別の区間へ進む(次));
    進む指示.位置 = 小数の標本位置::収めて作る(f64::from(開始 + 144));
    並び.extend(手.鳴らす(&進む指示, 長さ + 2000 + 240));
    for (番号, 値) in 並び.iter().enumerate().skip(240) {
        let 番号 = u32::try_from(番号).expect("番号");
        let 期待 = if 番号 < 長さ {
            継ぎ目を含めた期待する値(開始 + 番号, 開始 + 長さ, 開始)
        } else if 番号 < 長さ * 2 {
            継ぎ目を含めた期待する値(開始 + 番号 - 長さ, 開始 + 長さ, 次の開始)
        } else {
            正弦波の値(f64::from(次の開始 + 番号 - 長さ * 2))
        };
        assert!(
            (値 - 期待).abs() < 1e-3,
            "{番号}番目が期待する音と違う({値} と {期待})"
        );
    }
}
