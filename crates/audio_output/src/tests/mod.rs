pub(super) use driver::鳴らし手;

use std::sync::Arc;

use audio_pcm::{
    サンプリング周波数, 動画上の標本位置, 小数の標本の範囲, 小数の標本位置, 溜めた音, 音の出どころ,
};

use crate::音の区間;

pub(super) const 毎秒の標本数: u32 = 48_000;

/// 試験の正弦波の振幅。
pub(super) const 振幅: f64 = 0.8;

pub(super) fn 周波数() -> サンプリング周波数 {
    サンプリング周波数::作成する(毎秒の標本数).expect("周波数")
}

/// 動画の先頭から鳴る 440Hz の正弦波の、その位置の値。
pub(super) fn 正弦波の値(位置: f64) -> f64 {
    振幅 * (std::f64::consts::TAU * 440.0 * 位置 / f64::from(毎秒の標本数)).sin()
}

/// 区間の終わりの重ねる長さ(8ミリ秒)。
pub(super) const 重ねる長さ: u32 = 384;

/// 再生器が区間の位置で出すはずの値。終わりの重ねる長さの内では、元の音と行き先の開始の手前の音を、残りに応じた重みで交差させる。
pub(super) fn 継ぎ目を含めた期待する値(
    位置: u32, 終了: u32, 行き先の開始: u32
) -> f64 {
    let 残り = f64::from(終了 - 位置);
    let 元 = 正弦波の値(f64::from(位置));
    if 残り > f64::from(重ねる長さ) {
        return 元;
    }
    let 重み = 1.0 - 残り / f64::from(重ねる長さ);
    let 相手 = 正弦波の値(f64::from(行き先の開始) - 残り);
    元 * (1.0 - 重み) + 相手 * 重み
}

/// 先頭から数だけの標本を持つ、正弦波の溜めた音。
pub(super) fn 正弦波の音(先頭: u32, 数: u32) -> 音の出どころ {
    let 値の並び = (先頭..先頭 + 数)
        .map(|番号| {
            let 単精度 =
                <f32 as cpal::FromSample<f64>>::from_sample_(正弦波の値(f64::from(番号)));
            [単精度, 単精度]
        })
        .collect();
    音の出どころ::溜めた音(Arc::new(溜めた音::作成する(
        動画上の標本位置::作成する(先頭),
        値の並び,
    )))
}

pub(super) fn 区間(開始: u32, 終了: u32, 出どころ: 音の出どころ) -> 音の区間 {
    音の区間 {
        範囲: 小数の標本の範囲::収めて作る(
            小数の標本位置::標本位置から作る(動画上の標本位置::作成する(開始)),
            小数の標本位置::標本位置から作る(動画上の標本位置::作成する(終了)),
        ),
        出どころ: Some(出どころ),
    }
}

/// 隣り合う標本の差のうち最も大きいもの。波形に不連続(雑音)があると大きくなる。
pub(super) fn 隣の差の最大(並び: &[f64]) -> f64 {
    並び
        .windows(2)
        .map(|組| (組[1] - 組[0]).abs())
        .fold(0.0, f64::max)
}

/// 440Hz・振幅0.8の正弦波の隣り合う標本の差の最大(約0.046)より少し大きい、不連続とみなす差。
pub(super) const 不連続とみなす差: f64 = 0.06;
