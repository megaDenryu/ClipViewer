//! 退いた出どころの置き場の試験。音の再生器が手放した出どころを、音声のスレッドで捨てずに置き場が預かること。

use std::sync::Arc;

use audio_pcm::音の出どころ;

use super::sync::{最初の指示で鳴らし始める, 長さ, 開始};
use super::{区間, 正弦波の音, 鳴らし手};

#[test]
fn 手放した出どころは置き場が預かり音声のスレッドで捨てない() {
    let mut 手 = 鳴らし手::作成する();
    let 前の音 = 正弦波の音(開始, 長さ);
    let mut 指示 = 最初の指示で鳴らし始める(&mut 手, &前の音);
    指示.区間 = Some(区間(0, 1000, 正弦波の音(0, 1000)));
    指示.飛ばした回数 = 指示.飛ばした回数.次();
    手.鳴らす(&指示, 1000);
    drop(指示);
    let 音声のスレッドの外の参照 = match &前の音 {
        音の出どころ::溜めた音(音) => Arc::strong_count(音),
        音の出どころ::流れてくる音(音) => Arc::strong_count(音),
    };
    assert!(
        音声のスレッドの外の参照 >= 2,
        "置き場が前の音を預かっていない"
    );
}
