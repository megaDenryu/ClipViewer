//! 標本の途切れと、行き先の分からない区間の終わりの試験。標本が後から届いても、読み手が書き手に追いついて切れても、
//! 画面のスレッドが止まって行き先が分からないまま区間の終わりへ来ても、波形に段差を作らないこと。

use std::sync::Arc;

use audio_pcm::{動画上の標本位置, 標本数, 流れてくる音, 音の出どころ};

use super::{
    不連続とみなす差, 区間, 正弦波の値, 正弦波の音, 隣の差の最大, 鳴らし手
};
use crate::終わりで続く音;

const 開始: u32 = 48_000;
const 長さ: u32 = 480_000;

fn 正弦波の並び(先頭: u32, 数: u32) -> Vec<[f32; 2]> {
    (先頭..先頭 + 数)
        .map(|番号| {
            let 値 = <f32 as cpal::FromSample<f64>>::from_sample_(正弦波の値(f64::from(番号)));
            [値, 値]
        })
        .collect()
}

#[test]
fn 標本が後から届いても切れても段差を作らない() {
    let 位置 = 動画上の標本位置::作成する(開始);
    let 音 = Arc::new(流れてくる音::作成する(
        位置,
        標本数::作成する(長さ),
        標本数::作成する(0),
    ));
    let 出どころ = 音の出どころ::流れてくる音(Arc::clone(&音));
    let mut 手 = 鳴らし手::作成する();
    let 指示 = 手.指示(
        開始,
        Some(区間(開始, 開始 + 長さ, 出どころ)),
        終わりで続く音::止まる,
    );
    let mut 並び = 手.鳴らす(&指示, 1000);
    assert!(並び.iter().all(|値| *値 == 0.0), "届く前は黙る");
    音.書き足す(&正弦波の並び(開始, 10_000));
    並び.extend(手.鳴らす(&指示, 12_000));
    assert!(
        隣の差の最大(&並び) < 不連続とみなす差,
        "{}",
        隣の差の最大(&並び)
    );
    let 期待 = 正弦波の値(f64::from(開始 + 5000));
    assert!(
        (並び[5000] - 期待).abs() < 1e-3,
        "届いた後は位置どおりの音を鳴らす"
    );
    assert!(
        並び[10_300..].iter().all(|値| *値 == 0.0),
        "切れた後は下げて黙る"
    );
}

#[test]
fn 画面が止まって行き先が分からないまま区間の終わりへ来ても下げて止まる() {
    let (次の開始, 次の長さ): (u32, u32) = (200_000, 4_800);
    let mut 手 = 鳴らし手::作成する();
    let 今の音 = 正弦波の音(開始 - 480, 2_000 + 480);
    let 次 = 区間(
        次の開始,
        次の開始 + 次の長さ,
        正弦波の音(次の開始 - 480, 次の長さ + 480),
    );
    let 指示 = 手.指示(
        開始,
        Some(区間(開始, 開始 + 2_000, 今の音)),
        終わりで続く音::別の区間へ進む(次),
    );
    let 並び = 手.鳴らす(&指示, 2_000 + 次の長さ + 1_000);
    assert!(
        隣の差の最大(&並び) < 不連続とみなす差,
        "{}",
        隣の差の最大(&並び)
    );
    let 期待 = 正弦波の値(f64::from(次の開始 + 1000));
    assert!((並び[3000] - 期待).abs() < 1e-3, "次の区間の音を鳴らす");
    assert!(
        並び[usize::try_from(2_000 + 次の長さ + 300).expect("長さ")..]
            .iter()
            .all(|値| *値 == 0.0)
    );
}

#[test]
fn 同じ中身の指示を続けても置き場を埋めない() {
    let mut 手 = 鳴らし手::作成する();
    let 指示 = 手.指示(
        開始,
        Some(区間(開始, 開始 + 長さ, 正弦波の音(開始, 長さ))),
        終わりで続く音::開始へ戻る,
    );
    手.鳴らす(&指示, 512 * 100);
    assert_eq!(手.置き場.預かっている数(), 0);
}
