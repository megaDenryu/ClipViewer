//! 継ぎ目の試験の続き。映像が先に次の区間へ移った後も音が前の区間を終えて交差させること、速度が1以外の繰り返し、
//! 端数のある区間を何周しても映像とのずれが溜まらないこと。

use audio_pcm::{小数の標本の範囲, 小数の標本位置};
use clip_domain::再生速度;

use super::{
    区間, 正弦波の値, 正弦波の音, 継ぎ目を含めた期待する値, 隣の差の最大, 鳴らし手
};
use crate::{終わりで続く音, 音の区間};

const 開始: u32 = 48_000;
const 長さ: u32 = 23_977;
const 余白: u32 = 480;

#[test]
fn 映像が先に次の区間へ移っても音は前の区間を終えて交差させる() {
    let 次の開始 = 200_000;
    let mut 手 = 鳴らし手::作成する();
    let 今 = 区間(開始, 開始 + 長さ, 正弦波の音(開始 - 余白, 長さ + 余白));
    let 次 = 区間(
        次の開始,
        次の開始 + 長さ,
        正弦波の音(次の開始 - 余白, 長さ + 余白),
    );
    let 前の指示 = 手.指示(開始, Some(今), 終わりで続く音::別の区間へ進む(次.clone()));
    let mut 並び = 手.鳴らす(&前の指示, 長さ - 240);
    let 次の指示 = 手.指示(次の開始 + 144, Some(次), 終わりで続く音::止まる);
    並び.extend(手.鳴らす(&次の指示, 2000));
    for (番号, 値) in 並び.iter().enumerate().skip(240) {
        let 番号 = u32::try_from(番号).expect("番号");
        let 期待 = if 番号 < 長さ {
            継ぎ目を含めた期待する値(開始 + 番号, 開始 + 長さ, 次の開始)
        } else {
            正弦波の値(f64::from(次の開始 + 番号 - 長さ))
        };
        assert!(
            (値 - 期待).abs() < 1e-3,
            "{番号}番目が期待する音と違う({値} と {期待})"
        );
    }
}

#[test]
fn 速度が1以外でも繰り返しの継ぎ目で波形が不連続にならない() {
    let mut 手 = 鳴らし手::作成する();
    let 出どころ = 正弦波の音(開始 - 余白, 長さ + 余白);
    let mut 指示 = 手.指示(
        開始,
        Some(区間(開始, 開始 + 長さ, 出どころ)),
        終わりで続く音::開始へ戻る,
    );
    指示.速度 = 再生速度::作成する(1.5).expect("速度");
    let 並び = 手.鳴らす(&指示, 長さ * 2);
    let 自然な差の最大 = 0.8 * std::f64::consts::TAU * 440.0 * 1.5 / 48_000.0;
    let 最大 = 隣の差の最大(&並び);
    assert!(
        最大 < 自然な差の最大 * 1.2,
        "継ぎ目で跳んだ: {最大}(自然な差 {自然な差の最大})"
    );
}

#[test]
fn 端数のある区間を何周しても映像とのずれが溜まらない() {
    let (始め, 周の長さ) = (f64::from(開始), 2_400.5);
    let mut 手 = 鳴らし手::作成する();
    let 範囲 = 小数の標本の範囲::収めて作る(
        小数の標本位置::収めて作る(始め),
        小数の標本位置::収めて作る(始め + 周の長さ),
    );
    let 出どころ = 正弦波の音(開始 - 余白, 2_402 + 余白);
    let 区間 = 音の区間 {
        範囲,
        出どころ: Some(出どころ),
    };
    let 指示 = 手.指示(開始, Some(区間), 終わりで続く音::開始へ戻る);
    let 数 = 240_000;
    手.鳴らす(&指示, 数);
    let 期待 = 始め + f64::from(数) % 周の長さ;
    let 読み位置 = 手.再生器.読み位置().値();
    assert!(
        (読み位置 - 期待).abs() < 1e-6,
        "100周でずれが溜まった: {読み位置} と {期待}"
    );
}
