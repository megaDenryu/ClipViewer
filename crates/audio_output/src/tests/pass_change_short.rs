//! 短い区間(1コマ・2コマ・ずれの閾値の前後)で周回の途中に行き先が替わる試験。区間の長さがずれの閾値(40ミリ秒 = 1920標本)
//! 以下でも、同じ周回の中で「別の区間へ進む」を取り込み、映像が1周先にいるときだけ今の周回を繰り返すこと。

use audio_pcm::小数の標本位置;

use super::{
    区間, 正弦波の値, 正弦波の音, 継ぎ目を含めた期待する値, 鳴らし手
};
use crate::終わりで続く音;

const 開始: u32 = 48_000;
const 余白: u32 = 480;
const 次の開始: u32 = 200_000;

/// 1コマ(30コマ/秒)・2コマ・閾値の少し下・閾値の少し上の区間の長さ(標本)。
const 短い長さ: [u32; 4] = [1_600, 3_200, 1_900, 1_950];

/// 開始へ戻る指示で音の番号まで鳴らし、その時点で映像が区間の開始から映像の進みにいる「別の区間へ進む」指示へ替え、
/// 替えた後の周回の数だけ続けて鳴らした並びを返す。
fn 替え目を鳴らす(
    長さ: u32, 音の番号: u32, 映像の進み: u32, 残りの周回: u32
) -> Vec<f64> {
    let mut 手 = 鳴らし手::作成する();
    let 今 = 区間(開始, 開始 + 長さ, 正弦波の音(開始 - 余白, 長さ + 余白));
    let 次 = 区間(
        次の開始,
        次の開始 + 長さ,
        正弦波の音(次の開始 - 余白, 長さ + 余白),
    );
    let 戻る指示 = 手.指示(開始, Some(今.clone()), 終わりで続く音::開始へ戻る);
    let mut 並び = 手.鳴らす(&戻る指示, 音の番号);
    let mut 進む指示 = 手.指示(開始, Some(今), 終わりで続く音::別の区間へ進む(次));
    進む指示.位置 = 小数の標本位置::収めて作る(f64::from(開始 + 映像の進み));
    並び.extend(手.鳴らす(&進む指示, 長さ * 残りの周回 - 音の番号 + 1000));
    並び
}

/// 開始へ戻る周回を戻る周回の数だけ鳴らしてから次の区間へ移ったときに出るはずの値と、並びを比べる。
fn 期待と比べる(並び: &[f64], 長さ: u32, 戻る周回: u32, 説明: &str) {
    for (番号, 値) in 並び.iter().enumerate().skip(240) {
        let 番号 = u32::try_from(番号).expect("番号");
        let (周回, 周回内の位置) = (番号 / 長さ, 番号 % 長さ);
        let 期待 = if 周回 < 戻る周回 {
            継ぎ目を含めた期待する値(開始 + 周回内の位置, 開始 + 長さ, 開始)
        } else if 周回 == 戻る周回 {
            継ぎ目を含めた期待する値(開始 + 周回内の位置, 開始 + 長さ, 次の開始)
        } else {
            正弦波の値(f64::from(次の開始 + 番号 - 長さ * (戻る周回 + 1)))
        };
        assert!(
            (値 - 期待).abs() < 1e-3,
            "{説明}: 長さ{長さ}の{番号}番目が違う({値} と {期待})"
        );
    }
}

#[test]
fn 短い区間でも同じ周回の中なら別の区間へ進むを取り込む() {
    for 長さ in 短い長さ {
        let 半分 = 長さ / 2;
        let 並び = 替え目を鳴らす(長さ, 長さ + 半分, 半分, 2);
        期待と比べる(&並び, 長さ, 1, "同じ周回");
    }
}

#[test]
fn 短い区間でも映像が1周先にいるときは今の周回を繰り返してから移る() {
    for 長さ in 短い長さ {
        let 並び = 替え目を鳴らす(長さ, 長さ - 100, 50, 2);
        期待と比べる(&並び, 長さ, 1, "1周先");
    }
}
