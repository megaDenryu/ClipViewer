//! 映像とのずれの測り方の試験。

use audio_pcm::{小数の標本の範囲, 小数の標本位置, 標本の差};

use crate::drift::位置の比べ方;

fn 位置(値: f64) -> 小数の標本位置 {
    小数の標本位置::収めて作る(値)
}

fn 差(値: f64) -> Option<標本の差> {
    Some(標本の差::収めて作る(値))
}

#[test]
fn 繰り返しのずれは区間の長さだけずらした差も比べる() {
    let 範囲 = 小数の標本の範囲::収めて作る(位置(1000.0), 位置(2000.0));
    let 比べ方 = 位置の比べ方::繰り返す範囲(範囲);
    assert_eq!(比べ方.ずれ(位置(1005.0), 位置(1995.0)), 差(10.0));
    assert_eq!(比べ方.ずれ(位置(1005.0), 位置(2003.0)), 差(2.0));
    let 移る = 位置の比べ方::終わりで移る範囲(範囲);
    assert_eq!(移る.ずれ(位置(1005.0), 位置(2003.0)), None);
    assert_eq!(移る.ずれ(位置(1005.0), 位置(1100.0)), 差(95.0));
}

#[test]
fn 端数のある範囲を繰り返しても映像の位置は端数を保って戻す() {
    let 範囲 = 小数の標本の範囲::収めて作る(位置(1000.25), 位置(2000.75));
    let 比べ方 = 位置の比べ方::繰り返す範囲(範囲);
    let ずれ = 比べ方.ずれ(位置(1000.75), 位置(2001.25)).expect("測る");
    assert!(
        ずれ.値().abs() < 1e-9,
        "1周の長さは端数を丸めずに数える: {ずれ:?}"
    );
}
