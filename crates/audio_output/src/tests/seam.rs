//! 区間の継ぎ目の試験。繰り返しと次の区間への移りで、波形が不連続にならず、継ぎ目の外は元の音のままであること。

use super::{
    不連続とみなす差, 区間, 正弦波の値, 正弦波の音, 継ぎ目を含めた期待する値, 隣の差の最大,
    鳴らし手,
};
use crate::終わりで続く音;

/// 区間の開始(1秒)と長さ。長さは 440Hz の周期で割り切れないため、そのまま戻すと継ぎ目で波形が跳ぶ。
const 開始: u32 = 48_000;
const 長さ: u32 = 23_977;
/// 開始の前に溜めた余白(10ミリ秒)。
const 余白: u32 = 480;

#[test]
fn 繰り返しの継ぎ目で波形が不連続にならない() {
    let 終了 = 開始 + 長さ;
    let そのまま戻したときの差 =
        (正弦波の値(f64::from(開始)) - 正弦波の値(f64::from(終了 - 1))).abs();
    assert!(
        そのまま戻したときの差 > 0.3,
        "試験の前提: そのまま戻すと継ぎ目で跳ぶ"
    );
    let mut 手 = 鳴らし手::作成する();
    let 出どころ = 正弦波の音(開始 - 余白, 長さ + 余白);
    let 指示 = 手.指示(
        開始,
        Some(区間(開始, 終了, 出どころ)),
        終わりで続く音::開始へ戻る,
    );
    let 並び = 手.鳴らす(&指示, 長さ * 3);
    for (番号, 値) in 並び.iter().enumerate().skip(240) {
        let 区間の中 = u32::try_from(番号).expect("番号") % 長さ;
        let 期待 = 継ぎ目を含めた期待する値(開始 + 区間の中, 終了, 開始);
        assert!(
            (値 - 期待).abs() < 1e-3,
            "{番号}番目が交差させた音と違う({値} と {期待})"
        );
    }
}

#[test]
fn 手前の音が無い区間は下げて戻し不連続にならない() {
    let mut 手 = 鳴らし手::作成する();
    let 出どころ = 正弦波の音(0, 長さ);
    let 指示 = 手.指示(0, Some(区間(0, 長さ, 出どころ)), 終わりで続く音::開始へ戻る);
    let 並び = 手.鳴らす(&指示, 長さ * 2 + 1000);
    assert!(隣の差の最大(&並び) < 不連続とみなす差);
    let 継ぎ目の直後 = usize::try_from(長さ).expect("長さ");
    assert!(
        並び[継ぎ目の直後].abs() < 0.01,
        "継ぎ目で0まで下げてから戻す"
    );
}

#[test]
fn 区間の終わりで画面を待たずに次の区間へ移る() {
    let 次の開始 = 200_000;
    let mut 手 = 鳴らし手::作成する();
    let 今の音 = 正弦波の音(開始 - 余白, 長さ + 余白);
    let 次の音 = 正弦波の音(次の開始 - 余白, 長さ + 余白);
    let 次 = 区間(次の開始, 次の開始 + 長さ, 次の音);
    let 指示 = 手.指示(
        開始,
        Some(区間(開始, 開始 + 長さ, 今の音)),
        終わりで続く音::別の区間へ進む(次),
    );
    let 並び = 手.鳴らす(&指示, 長さ + 2000);
    assert!(隣の差の最大(&並び) < 不連続とみなす差);
    let 最後 = 並び.last().copied().expect("標本");
    let 期待 = 正弦波の値(f64::from(次の開始 + 2000 - 1));
    assert!((最後 - 期待).abs() < 1e-3, "次の区間の音を鳴らしていない");
}

#[test]
fn 止まる区間は終わりで下げて黙る() {
    let mut 手 = 鳴らし手::作成する();
    let 出どころ = 正弦波の音(開始, 長さ);
    let 指示 = 手.指示(
        開始,
        Some(区間(開始, 開始 + 長さ, 出どころ)),
        終わりで続く音::止まる,
    );
    let 並び = 手.鳴らす(&指示, 長さ + 1000);
    assert!(隣の差の最大(&並び) < 不連続とみなす差);
    assert!(
        並び[並び.len() - 700..].iter().all(|値| *値 == 0.0),
        "終わりの後、最後の標本を5ミリ秒で0まで下げてから黙る"
    );
}
