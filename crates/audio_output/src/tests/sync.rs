//! 映像との同期の試験。位置を飛ばしたとき・ずれが閾値を超えたときだけ合わせ、停止・音量・速度が音に効くこと。

use audio_pcm::{小数の標本位置, 音の出どころ, 音量};
use clip_domain::再生速度;

use super::{不連続とみなす差, 区間, 正弦波の音, 隣の差の最大, 鳴らし手};
use crate::{再生の様子, 終わりで続く音};

pub(super) const 開始: u32 = 48_000;
pub(super) const 長さ: u32 = 480_000;

pub(super) fn 最初の指示で鳴らし始める(
    手: &mut 鳴らし手,
    出どころ: &音の出どころ,
) -> crate::再生の指示 {
    let 指示 = 手.指示(
        開始,
        Some(区間(開始, 開始 + 長さ, 出どころ.clone())),
        終わりで続く音::止まる,
    );
    手.鳴らす(&指示, 1000);
    指示
}

#[test]
fn 位置を飛ばしたら下げてから移り不連続にならない() {
    let mut 手 = 鳴らし手::作成する();
    let 出どころ = 正弦波の音(開始, 長さ);
    let mut 指示 = 最初の指示で鳴らし始める(&mut 手, &出どころ);
    let 飛んだ先 = 開始 + 100_000;
    指示.位置 = 小数の標本位置::収めて作る(f64::from(飛んだ先));
    指示.指示した時刻 = 手.今();
    指示.飛ばした回数 = 指示.飛ばした回数.次();
    let 並び = 手.鳴らす(&指示, 2000);
    assert!(隣の差の最大(&並び) < 不連続とみなす差);
    let 読み位置 = 手.再生器.読み位置().値();
    let 期待 = f64::from(飛んだ先 + 1760);
    assert!(
        (読み位置 - 期待).abs() <= 3.0,
        "下げ切った後に飛んだ先へ移っていない: {読み位置}"
    );
}

#[test]
fn ずれが閾値を超えたときだけ合わせ直す() {
    let mut 手 = 鳴らし手::作成する();
    let 出どころ = 正弦波の音(開始, 長さ);
    let mut 指示 = 最初の指示で鳴らし始める(&mut 手, &出どころ);
    指示.位置 = 小数の標本位置::収めて作る(f64::from(開始 + 1000 + 480));
    指示.指示した時刻 = 手.今();
    手.鳴らす(&指示, 1000);
    let 読み位置 = 手.再生器.読み位置().値();
    assert!(
        (読み位置 - f64::from(開始 + 2000)).abs() < 1.0,
        "10ミリ秒のずれでは合わせない"
    );
    指示.位置 = 小数の標本位置::収めて作る(f64::from(開始 + 2000 + 4800));
    指示.指示した時刻 = 手.今();
    let 並び = 手.鳴らす(&指示, 2000);
    assert!(隣の差の最大(&並び) < 不連続とみなす差);
    let 読み位置 = 手.再生器.読み位置().値();
    let 期待 = f64::from(開始 + 6800 + 1760);
    assert!(
        (読み位置 - 期待).abs() <= 3.0,
        "100ミリ秒のずれは合わせる: {読み位置}"
    );
}

#[test]
fn 停止すると下げて黙り音量0は無音になる() {
    let mut 手 = 鳴らし手::作成する();
    let 出どころ = 正弦波の音(開始, 長さ);
    let mut 指示 = 最初の指示で鳴らし始める(&mut 手, &出どころ);
    指示.様子 = 再生の様子::止めている;
    let 並び = 手.鳴らす(&指示, 1000);
    assert!(隣の差の最大(&並び) < 不連続とみなす差);
    assert!(並び[300..].iter().all(|値| *値 == 0.0));
    指示.様子 = 再生の様子::再生している;
    指示.音量 = 音量::無音;
    assert!(手.鳴らす(&指示, 1000).iter().all(|値| *値 == 0.0));
}

#[test]
fn 速度の分だけ読み位置が進む() {
    let mut 手 = 鳴らし手::作成する();
    let 出どころ = 正弦波の音(開始, 長さ);
    let mut 指示 = 手.指示(
        開始,
        Some(区間(開始, 開始 + 長さ, 出どころ)),
        終わりで続く音::止まる,
    );
    指示.速度 = 再生速度::作成する(2.0).expect("速度");
    手.鳴らす(&指示, 1000);
    assert!((手.再生器.読み位置().値() - f64::from(開始 + 2000)).abs() < 1e-9);
}
