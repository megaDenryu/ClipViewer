//! 再生の指示。画面のスレッドが毎フレーム組み立てて音声のスレッドへ渡す、鳴らし方の全部である。

use std::time::Instant;

use audio_pcm::{サンプリング周波数, 小数の標本位置, 音量};
use clip_domain::再生速度;

use crate::section::{終わりで続く音, 音の区間};

/// 再生の様子とは、画面の時計が進んでいるか止まっているかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 再生の様子 {
    /// 止めている。音は短く下げてから黙る。
    止めている,
    /// 再生している。
    再生している,
}

/// 位置を飛ばした回数とは、シーク・クリップの選択・モードの切り替えのように、再生位置を連続でなく移した回数のことである。
/// 音の再生器は、回数が変わったら即座に位置を合わせる。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 位置を飛ばした回数(u64);

impl 位置を飛ばした回数 {
    /// 次の回数。
    pub fn 次(self) -> Self {
        Self(self.0.wrapping_add(1))
    }
}

/// 再生の指示とは、再生の様子・指示した時刻の動画上の位置・速度・音量・今の音の区間・区間の終わりで続く音・
/// 位置を飛ばした回数の組のことである。画面のスレッドが毎フレーム作り直して渡す。
#[derive(Debug, Clone)]
pub struct 再生の指示 {
    /// 再生の様子。
    pub 様子: 再生の様子,
    /// 指示した時刻の、映像の動画上の位置。
    pub 位置: 小数の標本位置,
    /// 位置を求めた時刻。音声のスレッドはここからの経過で位置を進めて比べる。
    pub 指示した時刻: Instant,
    /// 再生速度。
    pub 速度: 再生速度,
    /// 音量。
    pub 音量: 音量,
    /// 今の音の区間。映すものが無いときは無い。
    pub 区間: Option<音の区間>,
    /// 区間の終わりで続く音。
    pub 行き先: 終わりで続く音,
    /// 位置を飛ばした回数。
    pub 飛ばした回数: 位置を飛ばした回数,
}

impl 再生の指示 {
    /// 何も鳴らさない指示。出力装置を開いたときの最初の指示に使う。
    pub fn 黙る(今: Instant) -> Self {
        Self {
            様子: 再生の様子::止めている,
            位置: 小数の標本位置::default(),
            指示した時刻: 今,
            速度: 再生速度::等倍,
            音量: 音量::既定,
            区間: None,
            行き先: 終わりで続く音::止まる,
            飛ばした回数: 位置を飛ばした回数::default(),
        }
    }

    /// 今の時刻の映像の位置。再生している間は、指示した時刻からの経過に速度を掛けた分だけ進める。
    pub(crate) fn 今の位置(
        &self,
        今: Instant,
        周波数: サンプリング周波数,
    ) -> 小数の標本位置 {
        match self.様子 {
            再生の様子::止めている => self.位置,
            再生の様子::再生している => {
                let 経過 = 今
                    .saturating_duration_since(self.指示した時刻)
                    .as_secs_f64();
                let 進み = 周波数.秒数の小数の標本数(経過).速度を掛ける(self.速度);
                self.位置.ずらす(進み)
            }
        }
    }
}
