//! 速さを変える読み方。読み位置の標本を出どころから読む方法であり、速度を変えたときの音の性質を決める。

use audio_pcm::{
    ステレオの標本, 動画上の標本位置, 小数の標本位置, 標本数, 音の出どころ
};

/// 速さを変える読み方とは、読み位置(標本の間も指せる)の標本を、出どころから読む方法のことである。
/// 音の再生器は、読み位置を1標本あたり速度の分だけ進めながらこれを呼ぶ。
/// 今は線形補間(音の高さも速度に合わせて変わる)だけを持つ。音の高さを保つ読み方(時間伸縮)は、
/// 自分の中に前の標本を覚える必要があるため、`&mut self` で呼ぶ形にしてある。
pub trait 速さを変える読み方: Send {
    /// 読み位置の標本を読む。出どころが無いか、その位置の標本がまだ届いていなければ無い(途切れている)。
    fn 読む(
        &mut self,
        出どころ: Option<&音の出どころ>,
        位置: 小数の標本位置,
    ) -> Option<ステレオの標本>;
}

/// 線形補間で読むとは、読み位置の前後2つの標本を、端数の重みで直線につないで読む読み方のことである。
#[derive(Debug, Clone, Copy, Default)]
pub struct 線形補間で読む;

impl 速さを変える読み方 for 線形補間で読む {
    fn 読む(
        &mut self,
        出どころ: Option<&音の出どころ>,
        位置: 小数の標本位置,
    ) -> Option<ステレオの標本> {
        let 出どころ = 出どころ?;
        let 前: 動画上の標本位置 = 位置.切り捨てた位置();
        let 後 = 前.進める(標本数::作成する(1));
        match (出どころ.標本(前), 出どころ.標本(後)) {
            (Some(前の標本), Some(後の標本)) => {
                Some(前の標本.他方へ寄せる(後の標本, 位置.端数()))
            }
            (Some(一つ), None) | (None, Some(一つ)) => Some(一つ),
            (None, None) => None,
        }
    }
}
