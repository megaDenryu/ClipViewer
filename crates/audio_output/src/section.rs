//! 音の区間と、区間の終わりで続く音。再生の指示が指す「どこの音を、終わりでどこへ続けて鳴らすか」の型である。

use audio_pcm::{小数の標本の範囲, 標本の差, 標本数, 音の出どころ};

/// 音の区間とは、繰り返しや行き先の単位になる小数の標本の範囲と、その範囲の音を読む出どころの組のことである。
/// 出どころが無いのは、音をまだ溜めておらず流し読みも開いていない間であり、その間は黙る。
#[derive(Debug, Clone)]
pub struct 音の区間 {
    /// 区間の範囲。
    pub 範囲: 小数の標本の範囲,
    /// 区間の音を読む出どころ。
    pub 出どころ: Option<音の出どころ>,
}

impl 音の区間 {
    /// 区間の開始の手前に、指定の長さの音があるか。音の再生器は、あれば行き先の手前の音と重ねて交差させ、無ければ下げて戻す。
    pub(crate) fn 開始の手前に音があるか(&self, 長さ: 標本数) -> bool {
        let 長さ = 標本の差::標本数から作る(長さ);
        let 開始 = self.範囲.開始();
        let 手前 = 開始.ずらす(-長さ).切り捨てた位置();
        開始.値() >= 長さ.値()
            && self
                .出どころ
                .as_ref()
                .is_some_and(|出どころ| 出どころ.標本(手前).is_some())
    }

    /// 2つの区間(無い場合を含む)が同じ中身か。どちらも無ければ同じとみなす。
    pub(crate) fn 無い場合を含めて同じ中身か(
        左: Option<&Self>,
        右: Option<&Self>,
    ) -> bool {
        match (左, 右) {
            (Some(左), Some(右)) => 左.同じ中身か(右),
            (None, None) => true,
            _ => false,
        }
    }

    /// 他方と同じ範囲で、同じ入れ物を指しているか(どちらも出どころが無い場合を含む)。
    /// 音の再生器は、同じなら複製して置き換えず、置き場へ預けるものを増やさない。
    pub(crate) fn 同じ中身か(&self, 他方: &Self) -> bool {
        self.範囲 == 他方.範囲
            && match (&self.出どころ, &他方.出どころ) {
                (Some(左), Some(右)) => 左.同じ入れ物か(右),
                (None, None) => true,
                _ => false,
            }
    }
}

/// 終わりで続く音とは、音の区間の終わりに達したとき、音がどこへ続くかの区別のことである。
#[derive(Debug, Clone)]
pub enum 終わりで続く音 {
    /// 同じ区間の開始へ戻る。
    開始へ戻る,
    /// 別の区間の開始へ進む。
    別の区間へ進む(音の区間),
    /// 止まる。
    止まる,
}

impl 終わりで続く音 {
    /// 他方と同じ種類で、進む先の区間が同じ中身か。
    pub(crate) fn 同じ中身か(&self, 他方: &Self) -> bool {
        match (self, 他方) {
            (Self::開始へ戻る, Self::開始へ戻る) | (Self::止まる, Self::止まる) => {
                true
            }
            (Self::別の区間へ進む(左), Self::別の区間へ進む(右)) => {
                左.同じ中身か(右)
            }
            _ => false,
        }
    }
}
