//! 見本の鳴らし手。出力装置の代わりに、決まった時刻の列で再生の共有に埋めさせ、出た標本を集める。

use std::time::{Duration, Instant};

use audio_pcm::{
    サンプリング周波数, ステレオの標本, 小数の標本位置, 音量
};
use clip_domain::再生速度;

use super::super::shared::再生の共有;
use crate::{
    位置を飛ばした回数, 再生の指示, 再生の様子, 終わりで続く音, 音の区間
};

/// 見本の周波数。標本の数を小さく保つため 8kHz にする。重ねる長さは64標本、傾ける長さは40標本、ずれの閾値は320標本になる。
const 毎秒の標本数: u32 = 8_000;
/// 1回に埋めさせる標本の数。
const 一回の標本数: usize = 100;

/// 共有の鳴らし手とは、再生の共有と、時刻の基準と、これまでに埋めさせた標本の数と、出た標本の並びの組のことである。
/// 埋めさせるたびに、時刻を埋めた標本の分だけ進める。
pub(super) struct 共有の鳴らし手 {
    共有: 再生の共有,
    基準: Instant,
    埋めた標本の数: u32,
    集めた標本: Vec<ステレオの標本>,
}

impl 共有の鳴らし手 {
    pub(super) fn 作成する() -> Self {
        let 周波数 = サンプリング周波数::作成する(毎秒の標本数).expect("周波数");
        let 基準 = Instant::now();
        Self {
            共有: 再生の共有::作成する(周波数, 基準),
            基準,
            埋めた標本の数: 0,
            集めた標本: Vec::new(),
        }
    }

    /// 次に埋める最初の標本の時刻。8kHz の1標本は125000ナノ秒で割り切れるため、時刻を丸めずに求まる。
    pub(super) fn 次に埋める標本の時刻(&self) -> Instant {
        let 一標本のナノ秒数 = 1_000_000_000 / u64::from(毎秒の標本数);
        self.基準 + Duration::from_nanos(u64::from(self.埋めた標本の数) * 一標本のナノ秒数)
    }

    /// 再生の指示を置き換える。前の指示と置き場の中身はここで捨てる。
    pub(super) fn 指示を渡す(&self, 指示: 再生の指示) {
        drop(self.共有.指示を置き換える(指示));
    }

    /// 一回の標本数ずつ、回数だけ埋めさせる。
    pub(super) fn 鳴らす(&mut self, 回数: u32) {
        let mut 出力 = [ステレオの標本::無音; 一回の標本数];
        for _ in 0..回数 {
            self.共有.埋める(self.次に埋める標本の時刻(), &mut 出力);
            self.集めた標本.extend_from_slice(&出力);
            self.埋めた標本の数 += u32::try_from(一回の標本数).expect("一回の標本数");
        }
    }

    /// 今の時刻に指示した、等倍・音量0.8で再生している指示。
    pub(super) fn 再生する指示を作る(
        &self,
        位置: f64,
        区間: 音の区間,
        行き先: 終わりで続く音,
    ) -> 再生の指示 {
        再生の指示 {
            様子: 再生の様子::再生している,
            位置: 小数の標本位置::収めて作る(位置),
            指示した時刻: self.次に埋める標本の時刻(),
            速度: 再生速度::等倍,
            音量: 音量::範囲へ収めて作る(0.8),
            区間: Some(区間),
            行き先,
            飛ばした回数: 位置を飛ばした回数::default(),
        }
    }

    /// これまでに出た標本の並び。
    pub(super) fn 集めた標本(self) -> Vec<ステレオの標本> {
        self.集めた標本
    }
}
