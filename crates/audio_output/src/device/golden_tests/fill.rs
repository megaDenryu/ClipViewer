//! 再生の共有が埋める標本の並びを、見本のファイル(`fill_samples.txt`)と1標本ずつ比べる試験。
//! 見本は第5段階の時点のコードで筋書きを通して書き出したものである。書き換えてよいのは、オーナーが今の音の変更を決めたときだけである。
//! 比べるのは倍精度の値のビットであり、丸めの違いも違いとみなす。

use audio_pcm::ステレオの標本;

use super::scenario::筋書きの標本を集める;

/// 見本。1行に1標本を「左 右」の形で、f64 の Debug 表記で並べる。空行と `#` で始まる説明の行は読まない。
const 見本の本文: &str = include_str!("fill_samples.txt");

fn 見本を読む() -> Vec<ステレオの標本> {
    見本の本文
        .lines()
        .map(str::trim)
        .filter(|行| !行.is_empty() && !行.starts_with('#'))
        .map(|行| {
            let mut 値 = 行
                .split_whitespace()
                .map(|値の文字列| 値の文字列.parse::<f64>().expect("見本の値"));
            let 左 = 値.next().expect("見本の左");
            let 右 = 値.next().expect("見本の右");
            ステレオの標本 { 左, 右 }
        })
        .collect()
}

fn 同じビットか(出た: ステレオの標本, 見本: ステレオの標本) -> bool {
    出た.左.to_bits() == 見本.左.to_bits() && 出た.右.to_bits() == 見本.右.to_bits()
}

#[test]
fn 再生の共有が埋める標本の並びは見本と1標本も違わない() {
    let 見本 = 見本を読む();
    let 出た並び = 筋書きの標本を集める();
    assert_eq!(出た並び.len(), 見本.len(), "標本の数が見本と違う");
    for (番号, (出た, 見本の値)) in 出た並び.iter().zip(見本.iter()).enumerate() {
        assert!(
            同じビットか(*出た, *見本の値),
            "{番号}番目の標本が見本と違う(出た {出た:?}、見本 {見本の値:?})"
        );
    }
}

#[test]
fn 見本は黙った標本だけではない() {
    let 鳴った数 = 見本を読む()
        .iter()
        .filter(|標本| 標本.左 != 0.0 && 標本.右 != 0.0)
        .count();
    assert!(
        鳴った数 > 1000,
        "筋書きが音を鳴らしていない({鳴った数}標本)"
    );
}

/// 後の段階で −1〜1 へ収める演算が今の音の経路に入ったら、見本との比較で捕まえるための前提を確かめる。
#[test]
fn 見本は1を超える大きさの標本を含む() {
    let 超えた数 = 見本を読む()
        .iter()
        .filter(|標本| 標本.左.abs() > 1.0 || 標本.右.abs() > 1.0)
        .count();
    assert!(
        超えた数 > 50,
        "筋書きが −1〜1 を超える音を鳴らしていない({超えた数}標本)"
    );
}
