//! 見本の筋書き。決まった溜めた音と決まった指示の列と決まった時刻の列で再生の共有に埋めさせ、出た標本を順に集める。
//! 筋書きは、黙る指示・区間の繰り返しの継ぎ目・別の区間への跳び(1.5倍速と小数の範囲)・映像とのずれを合わせる跳び・
//! 位置を飛ばした回数による跳びと別の区間への移り・区間の終わりで止まる・止める指示を、この順に通る。

use std::sync::Arc;

use audio_pcm::{
    ステレオの標本, 動画上の標本位置, 小数の標本の範囲, 小数の標本位置, 溜めた音, 音の出どころ,
    音量,
};
use clip_domain::再生速度;

use super::driver::共有の鳴らし手;
use crate::{位置を飛ばした回数, 再生の様子, 終わりで続く音, 音の区間};

/// 溜めた音の標本の数。動画の先頭から溜める。
const 溜めた数: u32 = 4_000;

/// 左は周期160標本の鋸の波、右は周期250標本の三角の波で、左右が違う値を持つ溜めた音。正弦は処理系で値が揺れうるため使わない。
fn 鋸と三角の音() -> 音の出どころ {
    let 値の並び = (0..溜めた数)
        .map(|番号| {
            let 鋸 = f32::from(u16::try_from(番号 % 160).expect("鋸")) / 80.0 - 1.0;
            let 三角の位置 = u16::try_from(番号 % 250).expect("三角");
            let 三角 = f32::from(三角の位置.abs_diff(125)) / 125.0 * 0.6 - 0.3;
            [鋸, 三角]
        })
        .collect();
    音の出どころ::溜めた音(Arc::new(溜めた音::作成する(
        動画上の標本位置::作成する(0),
        値の並び,
    )))
}

fn 区間(出どころ: &音の出どころ, 開始: f64, 終了: f64) -> 音の区間 {
    音の区間 {
        範囲: 小数の標本の範囲::収めて作る(
            小数の標本位置::収めて作る(開始),
            小数の標本位置::収めて作る(終了),
        ),
        出どころ: Some(出どころ.clone()),
    }
}

/// 筋書きを通して出た標本の並び。合わせて2200標本である。
pub(super) fn 筋書きの標本を集める() -> Vec<ステレオの標本> {
    let 出どころ = 鋸と三角の音();
    let mut 手 = 共有の鳴らし手::作成する();
    手.鳴らす(1);
    let 繰り返す = 区間(&出どころ, 1000.0, 1250.0);
    手.指示を渡す(手.再生する指示(1000.0, 繰り返す, 終わりで続く音::開始へ戻る));
    手.鳴らす(6);
    let 速い区間 = 区間(&出どころ, 1500.25, 2400.75);
    let mut 速い指示 = 手.再生する指示(1500.25, 速い区間, 終わりで続く音::開始へ戻る);
    速い指示.速度 = 再生速度::作成する(1.5).expect("速度");
    速い指示.音量 = 音量::範囲へ収めて作る(0.5);
    手.指示を渡す(速い指示.clone());
    手.鳴らす(3);
    速い指示.位置 = 小数の標本位置::収めて作る(2300.0);
    速い指示.指示した時刻 = 手.今();
    手.指示を渡す(速い指示);
    手.鳴らす(4);
    let 次 = 区間(&出どころ, 3300.0, 3500.0);
    let mut 移る指示 = 手.再生する指示(
        2600.0,
        区間(&出どころ, 2600.0, 2900.0),
        終わりで続く音::別の区間へ進む(次),
    );
    移る指示.飛ばした回数 = 位置を飛ばした回数::default().次();
    移る指示.音量 = 音量::範囲へ収めて作る(1.0);
    手.指示を渡す(移る指示.clone());
    手.鳴らす(6);
    移る指示.様子 = 再生の様子::止めている;
    移る指示.指示した時刻 = 手.今();
    手.指示を渡す(移る指示);
    手.鳴らす(2);
    手.集めた標本()
}
