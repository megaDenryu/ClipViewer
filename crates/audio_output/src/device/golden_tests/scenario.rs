//! 見本の筋書き。決まった音の出どころと決まった指示の列と決まった時刻の列で再生の共有に埋めさせ、出た標本を順に集める。
//! 前半は、黙る指示・−1〜1 を超える音の区間の繰り返しの継ぎ目・別の区間への跳び(1.5倍速と小数の範囲)・
//! 映像とのずれを合わせる跳び・位置を飛ばした回数による跳びと別の区間への移り・区間の終わりで止まるを、この順に通る。
//! 後半は、開始の手前に音が無い区間の繰り返し・溜めた音の外で出どころが途切れる区間・流れてくる音が途切れる区間・
//! 鳴っている途中の止める指示を通る。

use audio_pcm::{
    ステレオの標本, 小数の標本の範囲, 小数の標本位置, 音の出どころ, 音量
};
use clip_domain::再生速度;

use super::driver::共有の鳴らし手;
use super::source::{鋸と三角の流れてくる音, 鋸と三角の溜めた音};
use crate::{位置を飛ばした回数, 再生の様子, 終わりで続く音, 音の区間};

fn 区間(出どころ: &音の出どころ, 開始: f64, 終了: f64) -> 音の区間 {
    音の区間 {
        範囲: 小数の標本の範囲::収めて作る(
            小数の標本位置::収めて作る(開始),
            小数の標本位置::収めて作る(終了),
        ),
        出どころ: Some(出どころ.clone()),
    }
}

/// 筋書きを通して出た標本の並び。合わせて3800標本である。
pub(super) fn 筋書きの標本を集める() -> Vec<ステレオの標本> {
    let 出どころ = 鋸と三角の溜めた音();
    let mut 手 = 共有の鳴らし手::作成する();
    前半を鳴らす(&mut 手, &出どころ);
    後半を鳴らす(&mut 手, &出どころ);
    手.集めた標本()
}

fn 前半を鳴らす(手: &mut 共有の鳴らし手, 出どころ: &音の出どころ) {
    手.鳴らす(1);
    let 繰り返す = 区間(出どころ, 1000.0, 1250.0);
    手.指示を渡す(手.再生する指示(1000.0, 繰り返す, 終わりで続く音::開始へ戻る));
    手.鳴らす(6);
    let 速い区間 = 区間(出どころ, 1500.25, 2400.75);
    let mut 速い指示 = 手.再生する指示(1500.25, 速い区間, 終わりで続く音::開始へ戻る);
    速い指示.速度 = 再生速度::作成する(1.5).expect("速度");
    速い指示.音量 = 音量::範囲へ収めて作る(0.5);
    手.指示を渡す(速い指示.clone());
    手.鳴らす(3);
    速い指示.位置 = 小数の標本位置::収めて作る(2300.0);
    速い指示.指示した時刻 = 手.今();
    手.指示を渡す(速い指示);
    手.鳴らす(4);
    let 次 = 区間(出どころ, 3300.0, 3500.0);
    let mut 移る指示 = 手.再生する指示(
        2600.0,
        区間(出どころ, 2600.0, 2900.0),
        終わりで続く音::別の区間へ進む(次),
    );
    移る指示.飛ばした回数 = 位置を飛ばした回数::default().次();
    移る指示.音量 = 音量::範囲へ収めて作る(1.0);
    手.指示を渡す(移る指示);
    手.鳴らす(6);
}

/// 位置を飛ばした回数を1つずつ増やしながら、途切れと手前の音の無い経路を鳴らし、最後に止める。
fn 後半を鳴らす(手: &mut 共有の鳴らし手, 出どころ: &音の出どころ) {
    let 流れ = 鋸と三角の流れてくる音(500, 600);
    let 経路の並び = [
        (区間(出どころ, 10.0, 210.0), 終わりで続く音::開始へ戻る, 5),
        (区間(出どころ, 3800.0, 4100.0), 終わりで続く音::止まる, 3),
        (区間(&流れ, 600.0, 1300.0), 終わりで続く音::開始へ戻る, 6),
        (
            区間(出どころ, 2000.0, 2500.0),
            終わりで続く音::開始へ戻る,
            2,
        ),
    ];
    let mut 飛ばした回数 = 位置を飛ばした回数::default().次();
    for (経路の区間, 行き先, 回数) in 経路の並び {
        飛ばした回数 = 飛ばした回数.次();
        let 開始 = 経路の区間.範囲.開始().値();
        let mut 指示 = 手.再生する指示(開始, 経路の区間, 行き先);
        指示.飛ばした回数 = 飛ばした回数;
        指示.音量 = 音量::範囲へ収めて作る(1.0);
        手.指示を渡す(指示);
        手.鳴らす(回数);
    }
    let mut 止める指示 = 手.再生する指示(
        2200.0,
        区間(出どころ, 2000.0, 2500.0),
        終わりで続く音::開始へ戻る,
    );
    止める指示.様子 = 再生の様子::止めている;
    止める指示.飛ばした回数 = 飛ばした回数;
    手.指示を渡す(止める指示);
    手.鳴らす(2);
}
