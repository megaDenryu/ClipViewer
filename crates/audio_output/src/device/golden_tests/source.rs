//! 見本の音の出どころ。筋書きが鳴らす溜めた音と流れてくる音を、決まった値で組み立てる。

use std::sync::Arc;

use audio_pcm::{
    動画上の標本位置, 左右の値, 書き足した結果, 標本数, 流れてくる音, 溜めた音, 音の出どころ,
};

/// 溜めた音の標本の数。動画の先頭から溜める。
const 溜めた数: u32 = 4_000;
/// 鋸の波を1.5倍にして、−1〜1 を超える値にする範囲。この範囲の音は、装置へ渡す前に −1〜1 へ収めない今の経路を見本に写す。
const 大きい音の範囲: std::ops::Range<u32> = 1_000..1_500;

/// その位置の左右の値。左は周期160標本の鋸の波、右は周期250標本の三角の波で、左右が違う値を持つ。
/// 正弦は処理系で値が揺れうるため使わない。
fn 位置の左右の値(番号: u32) -> 左右の値 {
    let 鋸 = f32::from(u16::try_from(番号 % 160).expect("鋸")) / 80.0 - 1.0;
    let 倍率 = if 大きい音の範囲.contains(&番号) {
        1.5
    } else {
        1.0
    };
    let 三角の位置 = u16::try_from(番号 % 250).expect("三角");
    let 三角 = f32::from(三角の位置.abs_diff(125)) / 125.0 * 0.6 - 0.3;
    [鋸 * 倍率, 三角]
}

/// 動画の先頭から溜めた数だけ溜めた音。
pub(super) fn 鋸と三角の溜めた音() -> 音の出どころ {
    let 値の並び = (0..溜めた数).map(位置の左右の値).collect();
    音の出どころ::溜めた音(Arc::new(溜めた音::作成する(
        動画上の標本位置::作成する(0),
        値の並び,
    )))
}

/// 開始から数だけを書き足し終えた流れてくる音。容量は書き足す数より大きく、書き手は待たない。
pub(super) fn 鋸と三角の流れてくる音(開始: u32, 数: u32) -> 音の出どころ {
    let 音 = 流れてくる音::作成する(
        動画上の標本位置::作成する(開始),
        標本数::作成する(数 * 2),
        標本数::作成する(数),
    );
    let 値の並び: Vec<左右の値> = (開始..開始 + 数).map(位置の左右の値).collect();
    assert_eq!(音.書き足す(&値の並び), 書き足した結果::書き足した);
    音の出どころ::流れてくる音(Arc::new(音))
}
