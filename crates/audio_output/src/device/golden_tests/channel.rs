//! 左右の標本を装置のチャンネルへ写す処理の見本の試験。1・2・3チャンネルと f32・i16 の組で、写した値を表で固定する。
//! 表の値は第5段階の時点のコードで写した値であり、書き換えてよいのはオーナーが今の音の変更を決めたときだけである。
//! 写す前の並びは9で埋め、残りのチャンネルを無音で上書きすることも確かめる。

use audio_pcm::ステレオの標本;

use super::super::callback::チャンネルへ写す;

/// 写す見本とは、写す左右の標本と、1・2・3チャンネルへ f32 と i16 で写した値の見本の組のことである。
struct 写す見本 {
    標本: ステレオの標本,
    単精度: [&'static [f32]; 3],
    整数: [&'static [i16]; 3],
}

const fn 左右の値から標本を作る(左: f64, 右: f64) -> ステレオの標本 {
    ステレオの標本 { 左, 右 }
}

/// 範囲の内・両端・範囲の外・小さい値と端数を含む値を並べる。
const 見本の表: [写す見本; 5] = [
    写す見本 {
        標本: 左右の値から標本を作る(0.5, -0.25),
        単精度: [&[0.125], &[0.5, -0.25], &[0.5, -0.25, 0.0]],
        整数: [&[4096], &[16384, -8192], &[16384, -8192, 0]],
    },
    写す見本 {
        標本: 左右の値から標本を作る(1.0, -1.0),
        単精度: [&[0.0], &[1.0, -1.0], &[1.0, -1.0, 0.0]],
        整数: [&[0], &[32767, -32768], &[32767, -32768, 0]],
    },
    写す見本 {
        標本: 左右の値から標本を作る(0.3, 0.7),
        単精度: [&[0.5], &[0.3, 0.7], &[0.3, 0.7, 0.0]],
        整数: [&[16384], &[9830, 22937], &[9830, 22937, 0]],
    },
    写す見本 {
        標本: 左右の値から標本を作る(1.5, -2.0),
        単精度: [&[-0.25], &[1.5, -2.0], &[1.5, -2.0, 0.0]],
        整数: [&[-8192], &[32767, -32768], &[32767, -32768, 0]],
    },
    写す見本 {
        標本: 左右の値から標本を作る(-0.000_01, 0.123_456_789),
        単精度: [
            &[0.061_723_396],
            &[-0.000_01, 0.123_456_79],
            &[-0.000_01, 0.123_456_79, 0.0],
        ],
        整数: [&[2022], &[0, 4045], &[0, 4045, 0]],
    },
];

fn 写した並び<標本の形式: Copy + cpal::FromSample<f64>>(
    チャンネル数: usize,
    写す前: 標本の形式,
    標本: ステレオの標本,
) -> Vec<標本の形式> {
    let mut 一時点 = vec![写す前; チャンネル数];
    チャンネルへ写す(&mut 一時点, 標本);
    一時点
}

#[test]
fn 単精度で写した値は見本と同じ() {
    for 見本 in &見本の表 {
        for (番号, 期待) in 見本.単精度.iter().enumerate() {
            let 写した = 写した並び(番号 + 1, 9.0_f32, 見本.標本);
            let 写したビット: Vec<u32> = 写した.iter().map(|値| 値.to_bits()).collect();
            let 期待のビット: Vec<u32> = 期待.iter().map(|値| 値.to_bits()).collect();
            assert_eq!(
                写したビット,
                期待のビット,
                "{:?} を{}チャンネルへ写した値({写した:?})が見本と違う",
                見本.標本,
                番号 + 1
            );
        }
    }
}

#[test]
fn 整数で写した値は見本と同じ() {
    for 見本 in &見本の表 {
        for (番号, 期待) in 見本.整数.iter().enumerate() {
            let 写した = 写した並び(番号 + 1, 9_i16, 見本.標本);
            assert_eq!(
                &写した[..],
                *期待,
                "{:?} を{}チャンネルへ写した値が見本と違う",
                見本.標本,
                番号 + 1
            );
        }
    }
}
