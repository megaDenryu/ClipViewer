//! 音を埋める係。cpal が音声のスレッドで呼ぶ関数の本体であり、音の再生器が作った左右の標本を装置の形式とチャンネル数へ写す。

use std::sync::Arc;
use std::time::{Duration, Instant};

use audio_pcm::{サンプリング周波数, ステレオの標本};
use cpal::FromSample;

use super::shared::再生の共有;

/// 下書きに用意する標本の数。装置が1回に求める数がこれを超えたら、分けて埋める。
const 下書きの標本数: usize = 4096;

/// 音を埋める係とは、再生の共有と、左右の標本を一度置く下書きと、装置のチャンネル数と周波数の組のことである。
/// 下書きは作るときに1回だけ確保し、音声のスレッドでは確保しない。
pub(crate) struct 音を埋める係 {
    共有: Arc<再生の共有>,
    下書き: Vec<ステレオの標本>,
    チャンネル数: usize,
    周波数: サンプリング周波数,
}

impl 音を埋める係 {
    pub(crate) fn 作成する(
        共有: Arc<再生の共有>,
        チャンネル数: usize,
        周波数: サンプリング周波数,
    ) -> Self {
        Self {
            共有,
            下書き: vec![ステレオの標本::無音; 下書きの標本数],
            チャンネル数: チャンネル数.max(1),
            周波数,
        }
    }

    /// 装置の並び(チャンネルを交互に並べた標本)を埋める。時刻はこの関数の最初に1回だけ読む。
    pub(crate) fn 装置の並びを埋める<標本の形式: FromSample<f64>>(
        &mut self,
        並び: &mut [標本の形式],
    ) {
        let 今 = Instant::now();
        let mut 済んだ数 = 0_u32;
        for 塊 in 並び.chunks_mut(下書きの標本数 * self.チャンネル数) {
            let 標本の数 = 塊.len() / self.チャンネル数;
            let 下書き = &mut self.下書き[..標本の数];
            let 経過 = f64::from(済んだ数) / f64::from(self.周波数.毎秒の標本数());
            self.共有.埋める(今 + Duration::from_secs_f64(経過), 下書き);
            for (一時点, 標本) in 塊.chunks_mut(self.チャンネル数).zip(下書き.iter())
            {
                チャンネルへ写す(一時点, *標本);
            }
            済んだ数 = 済んだ数.saturating_add(u32::try_from(標本の数).unwrap_or(u32::MAX));
        }
    }
}

/// 1時点の左右の標本を、装置のチャンネルへ写す。1チャンネルなら左右の平均、2チャンネル以上なら最初の2つへ左右を入れて残りは無音にする。
pub(super) fn チャンネルへ写す<標本の形式: FromSample<f64>>(
    一時点: &mut [標本の形式],
    標本: ステレオの標本,
) {
    match 一時点 {
        [一つ] => *一つ = 標本の形式::from_sample_((標本.左 + 標本.右) / 2.0),
        [左, 右, 残り @ ..] => {
            *左 = 標本の形式::from_sample_(標本.左);
            *右 = 標本の形式::from_sample_(標本.右);
            for 余り in 残り {
                *余り = 標本の形式::from_sample_(0.0);
            }
        }
        [] => {}
    }
}
