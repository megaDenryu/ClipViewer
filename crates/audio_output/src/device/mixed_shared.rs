//! 行の音の共有。2本目の流れで、画面のスレッドと音声のスレッドが行ごとの再生の指示と行の音を混ぜる係を1つの錠に入れて共有する。

use std::sync::{Mutex, MutexGuard, PoisonError};
use std::time::Instant;

use audio_pcm::{サンプリング周波数, ステレオの標本};
use clip_domain::同時に重ねられる行の数;

use super::filling::時刻を渡して埋めさせる共有;
use crate::mixer::{行ごとの再生の指示, 行の音を混ぜる係};
use crate::retired::退いた出どころの置き場;

/// 行の音の共有の中身とは、画面のスレッドが置き換える行ごとの再生の指示と、音声のスレッドが進める行の音を混ぜる係の組のことである。
struct 行の音の共有の中身 {
    指示: 行ごとの再生の指示,
    混ぜる係: 行の音を混ぜる係,
}

/// 行の音の共有とは、行の音の共有の中身を入れた錠のことである。
/// 注意: 画面のスレッドは中身を入れ替えるだけで錠を放し、古い指示と行ごとの置き場の中身は錠の外で捨てる。
/// 音声のスレッドは錠を持ったまま標本を作るが、メモリの確保と解放はしない。
pub(crate) struct 行の音の共有(Mutex<行の音の共有の中身>);

/// 捨てる指示と出どころとは、行ごとの指示を置き換えたときに手放した前の指示と、行ごとの置き場から引き取った出どころの組のことである。
/// 呼び出し側が錠の外で落とし、落とすことで中の出どころの最後の参照を画面のスレッドで捨てる。
pub(crate) struct 捨てる指示と出どころ {
    _前の指示: 行ごとの再生の指示,
    _引き取った出どころ: [退いた出どころの置き場; 同時に重ねられる行の数],
}

#[cfg(test)]
impl 捨てる指示と出どころ {
    /// 手放した前の指示。試験で、置き換える前の指示が返ることを確かめるために使う。
    pub(crate) fn 前の指示(&self) -> &行ごとの再生の指示 {
        &self._前の指示
    }

    /// 行ごとの置き場から引き取った出どころの数(行の番号の順)。
    pub(crate) fn 行ごとの引き取った出どころの数(
        &self,
    ) -> [usize; 同時に重ねられる行の数] {
        self._引き取った出どころ
            .each_ref()
            .map(退いた出どころの置き場::預かっている数)
    }
}

impl 行の音の共有 {
    pub(crate) fn 作成する(周波数: サンプリング周波数, 今: Instant) -> Self {
        Self(Mutex::new(行の音の共有の中身 {
            指示: 行ごとの再生の指示::黙る(今),
            混ぜる係: 行の音を混ぜる係::作成する(周波数),
        }))
    }

    /// 行ごとの指示を置き換え、前の指示と、行ごとの置き場が預かっていた出どころを返す。呼び出し側が錠の外で捨てる。
    pub(crate) fn 指示を置き換える(
        &self,
        指示: 行ごとの再生の指示,
    ) -> 捨てる指示と出どころ {
        let mut 中身 = self.錠を取る();
        let 前の指示 = std::mem::replace(&mut 中身.指示, 指示);
        捨てる指示と出どころ {
            _前の指示: 前の指示,
            _引き取った出どころ: 中身.混ぜる係.置き場を引き渡す(),
        }
    }

    /// これまでに埋めた標本の数。
    pub(crate) fn 埋めた標本数(&self) -> u64 {
        self.錠を取る().混ぜる係.埋めた標本数()
    }

    /// 錠を取る。錠を持ったスレッドがパニックしても、指示の入れ替えは1回の代入なので、中身をそのまま使う。
    fn 錠を取る(&self) -> MutexGuard<'_, 行の音の共有の中身> {
        self.0.lock().unwrap_or_else(PoisonError::into_inner)
    }
}

impl 時刻を渡して埋めさせる共有 for 行の音の共有 {
    /// 行の音を混ぜる係で出力の並びを埋める。音声のスレッドから呼ぶ。
    fn 埋める(&self, 今: Instant, 出力: &mut [ステレオの標本]) {
        let mut 中身 = self.錠を取る();
        let 行の音の共有の中身 {
            指示, 混ぜる係
        } = &mut *中身;
        混ぜる係.埋める(指示, 今, 出力);
    }
}
