//! 時刻を渡して埋めさせる共有。音を埋める係が音声のスレッドから呼ぶ口であり、1本目の流れの再生の共有と、
//! 2本目の流れの行の音の共有が実装する。音を埋める係はこれを型の引数で受け取るため、流れごとに別の関数として組み立てられる。

use std::time::Instant;

use audio_pcm::ステレオの標本;

use super::shared::再生の共有;

/// 時刻を渡して埋めさせる共有とは、画面のスレッドと音声のスレッドが共有し、出力の並びの最初の標本を作る時刻を受け取って
/// 左右の標本で並びを埋めるもののことである。
/// 注意: 音声のスレッドで呼ぶため、実装はメモリの確保と `Arc` の最後の参照を捨てることをしない。
pub(crate) trait 時刻を渡して埋めさせる共有: Send + Sync + 'static {
    /// 出力の並びを左右の標本で埋める。今は、出力の並びの最初の標本を作る時刻である。
    fn 埋める(&self, 今: Instant, 出力: &mut [ステレオの標本]);
}

impl 時刻を渡して埋めさせる共有 for 再生の共有 {
    fn 埋める(&self, 今: Instant, 出力: &mut [ステレオの標本]) {
        再生の共有::埋める(self, 今, 出力);
    }
}
