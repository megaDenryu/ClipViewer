/// 音声出力とは、開いた出力装置の流れと、画面のスレッドと音声のスレッドが共有する再生の共有の組のことである。
/// 落とすと流れが止まり、音声のスレッドはもう呼ばれない。
/// 注意: `流れ` を `共有` より前に宣言する。Rust は宣言の順に落とすため、先に流れを止めて音声のスレッドの関数が持つ共有の参照を手放させてから、
/// 共有の最後の参照をここ(画面のスレッド)で捨てる。順を逆にすると、共有の最後の参照(溜めた音を持つ再生器ごと)を音声のスレッドで捨てうる。
pub struct 音声出力 {
    流れ: 開いた流れ,
    周波数: サンプリング周波数,
    共有: Arc<再生の共有>,
}

impl 音声出力 {
    /// 既定の出力装置を既定の設定で開き、黙る指示で鳴らし始める。
    pub fn 既定の装置を開く() -> Result<Self, 音声出力のエラー> {
        let 装置 = 選んだ装置::既定の装置を選ぶ()?;
        let 周波数 = 装置.周波数();
        let 共有 = Arc::new(再生の共有::作成する(周波数, Instant::now()));
        let 流れ = 装置.流れを始める(Arc::clone(&共有))?;
        Ok(Self {
            流れ, 周波数, 共有
        })
    }

    /// 出力装置のサンプリング周波数。FFmpeg にこの周波数で音を出させる。
    pub fn 周波数(&self) -> サンプリング周波数 {
        self.周波数
    }

    /// 再生の指示を置き換える。前の指示と、音声のスレッドが手放した出どころは、錠の外でここで捨てる。
    pub fn 指示を渡す(&self, 指示: 再生の指示) {
        let 捨てるもの = self.共有.指示を置き換える(指示);
        drop(捨てるもの);
    }

    /// 出力の途中で装置が使えなくなった理由。使えていれば無い。
    pub fn 使えなくなった理由(&self) -> Option<音声出力のエラー> {
        self.流れ.使えなくなった理由()
    }

    /// cpal が出力の途中で音の途切れを知らせた回数。
    /// 注意: Windows(WASAPI)の出力の流れでは cpal が途切れを知らせないため常に0であり、途切れが無かったことの証明にはならない。
    pub fn 途切れを知らされた回数(&self) -> u64 {
        self.流れ.途切れを知らされた回数()
    }

    /// 音声のスレッドがこれまでに埋めた標本の数。装置が実際に音を求めているかを確かめるために使う。
    pub fn 埋めた標本数(&self) -> u64 {
        self.共有.埋めた標本数()
    }
}
