//! 音声出力のエラー。

/// 音声出力のエラーとは、音声出力装置を開いて鳴らし始められなかったか、鳴らしている途中で使えなくなった理由のことである。
/// 画面はこれを知らせ、映像だけで続ける。
#[derive(Debug, Clone, thiserror::Error)]
pub enum 音声出力のエラー {
    /// 既定の出力装置が無い。
    #[error("音声出力装置が見つからない")]
    装置が無い,
    /// 出力装置の既定の設定を取れない。
    #[error("音声出力装置の設定を取れない: {0}")]
    設定を取れない(#[source] cpal::Error),
    /// 出力装置の標本の形式に対応していない。
    #[error("音声出力装置の標本の形式({0})に対応していない")]
    対応しない形式(cpal::SampleFormat),
    /// 出力装置のサンプリング周波数が0である。
    #[error("音声出力装置のサンプリング周波数が0である")]
    周波数が無い,
    /// 出力の流れを作れない。
    #[error("音声出力の流れを作れない: {0}")]
    流れを作れない(#[source] cpal::Error),
    /// 出力の流れを始められない。
    #[error("音声出力を始められない: {0}")]
    始められない(#[source] cpal::Error),
    /// 鳴らしている途中で出力装置が使えなくなった(抜いた等)。
    #[error("音声出力装置が使えなくなった: {0}")]
    使えなくなった(#[source] cpal::Error),
}
