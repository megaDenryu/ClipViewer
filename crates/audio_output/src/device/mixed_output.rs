//! 行を混ぜる音声出力。重ね合わせの作業場の音を、スタックの作業場の音声出力とは別に、同じ既定の装置へ開いた2本目の流れで鳴らす。
//! 参照: _doc/設計/同時再生.md 5-3、_doc/設計/アーキテクチャ.md 判断8-9

use std::sync::Arc;
use std::time::Instant;

use audio_pcm::サンプリング周波数;

use super::error::音声出力のエラー;
use super::mixed_shared::行の音の共有;
use super::stream::{選んだ装置, 開いた流れ};
use crate::mixer::行ごとの再生の指示;

/// 行を混ぜる音声出力とは、既定の出力装置に開いた2本目の流れと、画面のスレッドと音声のスレッドが共有する行の音の共有の組のことである。
/// 行ごとの再生の指示で行ごとの音を作り、足し合わせて −1〜1 へ収めて鳴らす。落とすと流れが止まり、音声のスレッドはもう呼ばれない。
/// 開けないとき(装置が無い・2本目の流れを作れない等)は `既定の装置を開く` が型付きのエラーで返し、使っている途中で使えなくなったときは
/// `使えなくなった理由` が返す。どちらもスタックの作業場の `音声出力` の状況とは別である。
/// 注意: `流れ` を `共有` より前に宣言する。Rust は宣言の順に落とすため、先に流れを止めて音声のスレッドの関数が持つ共有の参照を手放させてから、
/// 共有の最後の参照をここ(画面のスレッド)で捨てる。順を逆にすると、共有の最後の参照(溜めた音を持つ再生器ごと)を音声のスレッドで捨てうる。
pub struct 行を混ぜる音声出力 {
    流れ: 開いた流れ,
    周波数: サンプリング周波数,
    共有: Arc<行の音の共有>,
}

impl 行を混ぜる音声出力 {
    /// 既定の出力装置を既定の設定で開き、どの行も黙る指示で鳴らし始める。
    /// スタックの作業場の `音声出力` が同じ装置を開いていても、別の流れとして開く。
    pub fn 既定の装置を開く() -> Result<Self, 音声出力のエラー> {
        let 装置 = 選んだ装置::既定の装置を選ぶ()?;
        let 周波数 = 装置.周波数();
        let 共有 = Arc::new(行の音の共有::作成する(周波数, Instant::now()));
        let 流れ = 装置.流れを始める(Arc::clone(&共有))?;
        Ok(Self {
            流れ, 周波数, 共有
        })
    }

    /// 出力装置のサンプリング周波数。FFmpeg にこの周波数で音を出させる。
    pub fn 周波数(&self) -> サンプリング周波数 {
        self.周波数
    }

    /// 行ごとの再生の指示を置き換える。前の指示と、音声のスレッドが行ごとに手放した出どころは、錠の外でここで捨てる。
    pub fn 指示を渡す(&self, 指示: 行ごとの再生の指示) {
        let 捨てるもの = self.共有.指示を置き換える(指示);
        drop(捨てるもの);
    }

    /// 出力の途中で装置が使えなくなった理由。使えていれば無い。
    pub fn 使えなくなった理由(&self) -> Option<音声出力のエラー> {
        self.流れ.使えなくなった理由()
    }

    /// cpal が出力の途中で音の途切れを知らせた回数。
    /// 注意: Windows(WASAPI)の出力の流れでは cpal が途切れを知らせないため常に0であり、途切れが無かったことの証明にはならない。
    pub fn 途切れを知らされた回数(&self) -> u64 {
        self.流れ.途切れを知らされた回数()
    }

    /// 音声のスレッドがこれまでに埋めた標本の数。装置が実際に音を求めているかを確かめるために使う。
    pub fn 埋めた標本数(&self) -> u64 {
        self.共有.埋めた標本数()
    }
}
