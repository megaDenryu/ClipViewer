//! 行の音の共有の試験。行ごとの指示を置き換えると、前の指示と、行ごとの置き場が預かっていた出どころが返り、
//! 返った値を落としたときに初めて出どころの最後の参照が捨てられる(錠の外で捨てる)こと。

#![allow(clippy::expect_used)]

use std::sync::Arc;
use std::time::Instant;

use audio_pcm::{ステレオの標本, 音の出どころ};

use super::filling::時刻を渡して埋めさせる共有;
use super::mixed_shared::行の音の共有;
use crate::mixer::tests::{
    一定の音の区間, 再生する指示, 周波数, 標本の分だけ後, 行ごとの指示を作る,
};

fn 参照の数(出どころ: &音の出どころ) -> usize {
    match 出どころ {
        音の出どころ::溜めた音(音) => Arc::strong_count(音),
        音の出どころ::流れてくる音(音) => Arc::strong_count(音),
    }
}

#[test]
fn 指示を置き換えると前の指示と行ごとの置き場の出どころが返り落とすまで捨てない() {
    let 今 = Instant::now();
    let 共有 = 行の音の共有::作成する(周波数(), 今);
    let 前の区間 = 一定の音の区間(0.5, 0.5);
    let 前の出どころ = 前の区間.出どころ.clone().expect("出どころ");
    let mut 出力 = [ステレオの標本::無音; 1000];
    drop(共有.指示を置き換える(行ごとの指示を作る(
        今,
        vec![(3, 再生する指示(今, 前の区間, 0.75))],
    )));
    共有.埋める(今, &mut 出力);

    let 次の時刻 = 標本の分だけ後(今, 1000);
    let mut 移す指示 = 再生する指示(次の時刻, 一定の音の区間(0.25, 0.25), 1.0);
    移す指示.飛ばした回数 = 移す指示.飛ばした回数.次();
    drop(共有.指示を置き換える(行ごとの指示を作る(次の時刻, vec![(3, 移す指示)])));
    共有.埋める(次の時刻, &mut 出力);

    let 捨てるもの = 共有.指示を置き換える(行ごとの指示を作る(次の時刻, Vec::new()));
    let 前の三番の音量 = 捨てるもの.前の指示().再生の指示の並び()[3].音量.値();
    assert_eq!(前の三番の音量, 1.0, "置き換える前の指示が返っていない");
    let 引き取った数 = 捨てるもの.行ごとの引き取った出どころの数();
    assert!(
        引き取った数[3] >= 1,
        "3番の行の置き場の出どころが返っていない"
    );
    assert!(
        引き取った数
            .iter()
            .enumerate()
            .all(|(番号, 数)| 番号 == 3 || *数 == 0),
        "ほかの行の置き場から出どころが返った({引き取った数:?})"
    );
    assert_eq!(共有.埋めた標本数(), 2000, "返した後も錠を持ったままである");
    assert!(参照の数(&前の出どころ) >= 2, "落とす前に出どころを捨てた");
    drop(捨てるもの);
    assert_eq!(参照の数(&前の出どころ), 1, "落としても出どころが残る");
}
