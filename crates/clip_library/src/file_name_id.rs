//! ファイル名にする識別子。スタックの識別子と重ね合わせの識別子を、項目のファイルの置き方(`item_folder.rs`)が同じ名前の規則で使えるようにする。

use clip_domain::{スタックの識別子, 重ね合わせの識別子};

/// ファイル名にする識別子とは、ライブラリが項目のファイル名の本体(拡張子の前)に使う識別子のことである。
/// どちらの識別子も、ファイル名に使える文字だけからなることを作る口で保証している。
pub(crate) trait ファイル名にする識別子 {
    /// ファイル名の本体にする文字列。
    fn ファイル名の本体(&self) -> &str;
}

impl ファイル名にする識別子 for スタックの識別子 {
    fn ファイル名の本体(&self) -> &str {
        self.文字列()
    }
}

impl ファイル名にする識別子 for 重ね合わせの識別子 {
    fn ファイル名の本体(&self) -> &str {
        self.文字列()
    }
}
