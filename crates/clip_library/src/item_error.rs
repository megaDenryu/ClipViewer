//! 項目の操作エラー。スタックのライブラリと重ね合わせのライブラリの操作で起きるエラーを、識別子の型と読み込みエラーの型を引数に取る1つの型で表す。
//! 公開の名前は `ライブラリの操作エラー`(スタック)と `重ね合わせのライブラリの操作エラー` の別名で残す。

use std::io;
use std::path::Path;

use clip_domain::ライブラリのファイルの書き出しエラー;

use crate::item_folder::書き換えの失敗;
use crate::item_id::ライブラリの項目の識別子;

/// 項目の操作エラーとは、ライブラリのフォルダ(または重ね合わせのフォルダ)の読み書きや、ファイルの中身の変換ができなかった理由のことである。
#[derive(Debug, thiserror::Error)]
pub enum 項目の操作エラー<識別子: ライブラリの項目の識別子, 読み込みエラー> {
    /// ファイルかフォルダを読み書きできない。
    #[error("{パス} を読み書きできない: {原因}")]
    読み書きできない {
        /// 読み書きしようとしたパス(表示用)。
        パス: String,
        /// OS が返した理由。
        原因: io::Error,
    },
    /// 書き切った書きかけのファイルで、項目のファイルを置き換えられない。書いた中身は書きかけのファイルに残っている。
    #[error("{置き場所} を置き換えられない(書いた中身は {書きかけ} に残っている): {原因}")]
    置き換えられない {
        /// 置き換えようとした項目のファイルのパス(表示用)。
        置き場所: String,
        /// 書いた中身が残っている書きかけのファイルのパス(表示用)。利用者が拾い出せるように知らせる。
        書きかけ: String,
        /// OS が返した理由。
        原因: io::Error,
    },
    /// ファイルの中身が項目として読めない。
    #[error("{0}")]
    中身が読めない(読み込みエラー),
    /// 項目を本文へ書き出せない。
    #[error("{0}")]
    書き出せない(#[from] ライブラリのファイルの書き出しエラー),
    /// 指定の識別子の項目のファイルが無い。
    #[error("{呼び名} {0} のファイルが無い", 呼び名 = 識別子::項目の呼び名)]
    見つからない(識別子),
    /// 新しい項目の識別子のファイルが既にある。
    #[error("{呼び名} {0} のファイルが既にある", 呼び名 = 識別子::項目の呼び名)]
    既にある(識別子),
    /// ファイル名の識別子と中身の識別子が違う。
    #[error("ファイル名の識別子 {ファイル名の識別子} と中身の識別子 {中身の識別子} が違う")]
    識別子が違う {
        /// ファイル名から読んだ識別子。
        ファイル名の識別子: 識別子,
        /// 中身に書いてある識別子。
        中身の識別子: 識別子,
    },
}

impl<識別子: ライブラリの項目の識別子, 読み込みエラー>
    項目の操作エラー<識別子, 読み込みエラー>
{
    /// io のエラーを、どのパスで起きたかと組にする。
    pub(crate) fn 読み書きのエラー(パス: &Path, 原因: io::Error) -> Self {
        Self::読み書きできない {
            パス: パス.display().to_string(),
            原因,
        }
    }

    /// 項目のファイルを読み書きできなかった io のエラーを、ファイルが無いなら見つからない、それ以外なら読み書きできないにする。
    pub(crate) fn 無ければ見つからないとする(
        パス: &Path,
        項目: &識別子,
        原因: io::Error,
    ) -> Self {
        if 原因.kind() == io::ErrorKind::NotFound {
            Self::見つからない(項目.clone())
        } else {
            Self::読み書きのエラー(パス, 原因)
        }
    }
}

impl<識別子: ライブラリの項目の識別子, 読み込みエラー> From<書き換えの失敗>
    for 項目の操作エラー<識別子, 読み込みエラー>
{
    fn from(失敗: 書き換えの失敗) -> Self {
        match 失敗 {
            書き換えの失敗::書けない { パス, 原因 } => {
                Self::読み書きのエラー(&パス, 原因)
            }
            書き換えの失敗::置き換えられない {
                置き場所,
                書きかけ,
                原因,
            } => Self::置き換えられない {
                置き場所: 置き場所.display().to_string(),
                書きかけ: 書きかけ.display().to_string(),
                原因,
            },
        }
    }
}
