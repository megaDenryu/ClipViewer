//! 重ね合わせのライブラリへの頼み(裏のスレッドに行わせる操作)と、裏のスレッドから返る知らせ。
//! スタックの頼みと知らせの型(`ライブラリへの頼み`・`ライブラリからの知らせ`)には選択肢を足さず、重ね合わせの側に別の型を置く(同時再生.md 3-2)。

use clip_domain::{ライブラリの重ね合わせ, 重ね合わせの識別子};

use crate::background_threads::裏で行うライブラリ;
use crate::overlay_error::重ね合わせのライブラリの操作エラー;
use crate::overlay_library::重ね合わせのライブラリ;
use crate::overlay_listing::重ね合わせの一覧;
use crate::request::保存の番号;

/// 重ね合わせのライブラリへの頼みとは、裏のスレッドに順に行わせる、重ね合わせのライブラリへの1つの操作のことである。
#[derive(Debug, Clone)]
pub enum 重ね合わせのライブラリへの頼み {
    /// 重ね合わせを保存する。
    保存する(ライブラリの重ね合わせ, 保存の番号),
    /// フォルダを読んで一覧を作る。
    一覧を作る,
}

/// 重ね合わせのライブラリからの知らせとは、裏のスレッドが頼みを1つ行った結果のことである。
#[derive(Debug)]
pub enum 重ね合わせのライブラリからの知らせ {
    /// 保存を行った。
    保存した(
        重ね合わせの識別子,
        保存の番号,
        Result<(), 重ね合わせのライブラリの操作エラー>,
    ),
    /// 一覧を作った。
    一覧を作った(Result<重ね合わせの一覧, 重ね合わせのライブラリの操作エラー>),
}

impl 重ね合わせのライブラリへの頼み {
    /// 重ね合わせのファイルを書く頼みか。一覧を作る頼みだけが書かない。
    pub fn 書き込むか(&self) -> bool {
        !matches!(self, Self::一覧を作る)
    }

    /// 重ね合わせのライブラリに対して頼みを行い、知らせを返す。
    pub fn 行う(
        self,
        ライブラリ: &重ね合わせのライブラリ,
    ) -> 重ね合わせのライブラリからの知らせ {
        match self {
            Self::保存する(登録した, 番号) => {
                重ね合わせのライブラリからの知らせ::保存した(
                    登録した.識別子().clone(),
                    番号,
                    ライブラリ.保存する(&登録した),
                )
            }
            Self::一覧を作る => {
                重ね合わせのライブラリからの知らせ::一覧を作った(
                    ライブラリ.一覧を作る(),
                )
            }
        }
    }
}

impl 裏で行うライブラリ for 重ね合わせのライブラリ {
    type 頼み = 重ね合わせのライブラリへの頼み;
    type 知らせ = 重ね合わせのライブラリからの知らせ;

    fn 頼みを行う(
        &self,
        頼み: 重ね合わせのライブラリへの頼み,
    ) -> 重ね合わせのライブラリからの知らせ {
        頼み.行う(self)
    }

    fn 一覧を作った知らせ(&self) -> 重ね合わせのライブラリからの知らせ {
        重ね合わせのライブラリへの頼み::一覧を作る.行う(self)
    }

    fn 一覧を作る前に片付ける(&self) {
        self.フォルダ().置き方().置き去りの書きかけを片付ける();
    }
}
