//! 重ね合わせのライブラリへの頼み(裏のスレッドに行わせる操作)と、裏のスレッドから返る知らせ。
//! スタックの頼みと知らせの型(`ライブラリへの頼み`・`ライブラリからの知らせ`)には選択肢を足さず、重ね合わせの側に別の型を置く(同時再生.md 3-2)。

use clip_domain::{ライブラリの重ね合わせ, 重ね合わせの識別子};

use crate::overlay_library::{
    重ね合わせのライブラリ, 重ね合わせのライブラリの操作エラー
};
use crate::overlay_listing::重ね合わせの一覧;
use crate::request::保存の番号;

/// 重ね合わせのライブラリへの頼みとは、裏のスレッドに順に行わせる、重ね合わせのライブラリへの1つの操作のことである。
#[derive(Debug, Clone)]
pub enum 重ね合わせのライブラリへの頼み {
    /// 重ね合わせを保存する。
    保存する(ライブラリの重ね合わせ, 保存の番号),
    /// フォルダを読んで一覧を作る。
    一覧を作る,
}

/// 重ね合わせのライブラリからの知らせとは、裏のスレッドが頼みを1つ行った結果のことである。
#[derive(Debug)]
pub enum 重ね合わせのライブラリからの知らせ {
    /// 保存を行った。
    保存した(
        重ね合わせの識別子,
        保存の番号,
        Result<(), 重ね合わせのライブラリの操作エラー>,
    ),
    /// 一覧を作った。
    一覧を作った(Result<重ね合わせの一覧, 重ね合わせのライブラリの操作エラー>),
}

impl 重ね合わせのライブラリへの頼み {
    /// 重ね合わせのライブラリに対して頼みを行い、知らせを返す。
    pub fn 行う(
        self,
        ライブラリ: &重ね合わせのライブラリ,
    ) -> 重ね合わせのライブラリからの知らせ {
        match self {
            Self::保存する(登録した, 番号) => {
                重ね合わせのライブラリからの知らせ::保存した(
                    登録した.識別子().clone(),
                    番号,
                    ライブラリ.保存する(&登録した),
                )
            }
            Self::一覧を作る => {
                重ね合わせのライブラリからの知らせ::一覧を作った(
                    ライブラリ.一覧を作る(),
                )
            }
        }
    }
}
