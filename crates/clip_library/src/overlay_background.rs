//! 裏で動く重ね合わせのライブラリ。スタックの裏で動くライブラリと同じ型(`裏で動く項目のライブラリ`)を重ね合わせのライブラリで使い、
//! 自分の書き込みのスレッドが保存を受けた順に行い、自分の走査のスレッドが一覧を作り、自分の知らせを返す。スタックの頼みと知らせの型は変えない。
//! 参照: _doc/設計/同時再生.md 3-2(共有するものの表のライブラリの保存係)

use crate::background::裏で動く項目のライブラリ;
use crate::background_library::{裏で行うライブラリ, 頼みの扱い};
use crate::overlay_folder::重ね合わせのフォルダ;
use crate::overlay_library::重ね合わせのライブラリ;
use crate::overlay_lock::{重ね合わせの錠, 重ね合わせの錠を取れない理由};
use crate::overlay_request::{
    重ね合わせのライブラリからの知らせ, 重ね合わせのライブラリへの頼み
};

/// 裏で動く重ね合わせのライブラリとは、重ね合わせのライブラリを書き込みのスレッドと走査のスレッドに持たせ、頼みを行わせる係のことである。
/// 落とすと、送った頼みをすべて行い終えるまで待ってからスレッドを閉じ、その後で `overlays` の錠を放す。
pub type 裏で動く重ね合わせのライブラリ =
    裏で動く項目のライブラリ<重ね合わせのライブラリ>;

impl 裏で行うライブラリ for 重ね合わせのライブラリ {
    type 頼み = 重ね合わせのライブラリへの頼み;
    type 知らせ = 重ね合わせのライブラリからの知らせ;
    type フォルダ = 重ね合わせのフォルダ;
    type 錠 = 重ね合わせの錠;
    type 錠を取れない理由 = 重ね合わせの錠を取れない理由;

    fn フォルダ(&self) -> &重ね合わせのフォルダ {
        self.フォルダ()
    }

    fn 頼みの扱い(頼み: &重ね合わせのライブラリへの頼み) -> 頼みの扱い {
        match 頼み {
            重ね合わせのライブラリへの頼み::一覧を作る => {
                頼みの扱い::一覧を作る
            }
            重ね合わせのライブラリへの頼み::保存する(..) => {
                頼みの扱い::書き込む
            }
        }
    }

    fn 頼みを行う(
        &self,
        頼み: 重ね合わせのライブラリへの頼み,
    ) -> 重ね合わせのライブラリからの知らせ {
        頼み.行う(self)
    }

    fn 一覧を作った知らせ(&self) -> 重ね合わせのライブラリからの知らせ {
        重ね合わせのライブラリへの頼み::一覧を作る.行う(self)
    }

    fn 一覧を作る前に片付ける(&self) {
        self.フォルダ().置き方().置き去りの書きかけを片付ける();
    }
}
