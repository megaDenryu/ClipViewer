//! 裏で動く重ね合わせのライブラリ。スタックの裏で動くライブラリと同じ形で、自分の書き込みのスレッドが保存を受けた順に行い、
//! 自分の走査のスレッドが一覧を作り、自分の知らせを返す。スタックの裏で動くライブラリの頼みと知らせの型は変えない。
//! 参照: _doc/設計/同時再生.md 3-2(共有するものの表のライブラリの保存係)

use crate::background::頼めない理由;
use crate::background_threads::書き込みのスレッドへの頼み;
use crate::background_worker::裏のスレッドを持つ係;
use crate::overlay_folder::重ね合わせのフォルダ;
use crate::overlay_library::重ね合わせのライブラリ;
use crate::overlay_request::{
    重ね合わせのライブラリからの知らせ, 重ね合わせのライブラリへの頼み
};
use crate::overlay_tried_lock::{
    重ね合わせの書き込みの許し, 錠を試した重ね合わせのライブラリ
};

/// 裏で動く重ね合わせのライブラリとは、重ね合わせのライブラリを書き込みのスレッドと走査のスレッドに持たせ、頼みを行わせる係のことである。
/// 落とすと、送った頼みをすべて行い終えるまで待ってからスレッドを閉じ、その後で `overlays` の錠を放す。
pub struct 裏で動く重ね合わせのライブラリ {
    // 注意: 係を許しより先に並べる。項目は並べた順に落ちるため、係が書き込みを終えてから許しの錠を放す。
    係: 裏のスレッドを持つ係<重ね合わせのライブラリ>,
    フォルダ: 重ね合わせのフォルダ,
    許し: 重ね合わせの書き込みの許し,
}

impl 裏で動く重ね合わせのライブラリ {
    /// 錠を試した重ね合わせのライブラリの裏のスレッドを起こす。錠を取れていなければ読むだけで起こす。
    pub fn 錠を試した後で起動する(
        試した: 錠を試した重ね合わせのライブラリ
    ) -> Self {
        let 錠を試した重ね合わせのライブラリ {
            ライブラリ, 許し
        } = 試した;
        Self {
            フォルダ: ライブラリ.フォルダ().clone(),
            係: 裏のスレッドを持つ係::起こす(ライブラリ),
            許し,
        }
    }

    /// 重ね合わせのフォルダ。
    pub fn フォルダ(&self) -> &重ね合わせのフォルダ {
        &self.フォルダ
    }

    /// 重ね合わせの書き込みの許し。
    pub fn 許し(&self) -> &重ね合わせの書き込みの許し {
        &self.許し
    }

    /// 頼みを送る。待たない。読むだけのときは書き込む頼みを断る。
    pub fn 頼む(
        &self, 頼み: 重ね合わせのライブラリへの頼み
    ) -> Result<(), 頼めない理由> {
        if !self.許し.受け付けるか(&頼み) {
            return Err(頼めない理由::読むだけで開いている);
        }
        self.係.送る(match 頼み {
            重ね合わせのライブラリへの頼み::一覧を作る => {
                書き込みのスレッドへの頼み::一覧を作らせる(
                    self.許し.走査の前の片付け(),
                )
            }
            その他 => 書き込みのスレッドへの頼み::行う(その他),
        })
    }

    /// 届いている知らせをすべて受け取る。待たない。
    pub fn 届いた知らせを受け取る(
        &self,
    ) -> Vec<重ね合わせのライブラリからの知らせ> {
        self.係.届いた知らせを受け取る()
    }

    /// それまでに送った書き込みをすべて行い終えるまで待つ。一覧の走査は待たない。
    pub fn 書き込みを終えるまで待つ(&self) {
        self.係.書き込みを終えるまで待つ();
    }

    /// それまでに送った書き込みと一覧の走査をすべて行い終えるまで待つ。
    pub fn 走査も終えるまで待つ(&self) {
        self.係.走査も終えるまで待つ();
    }
}
