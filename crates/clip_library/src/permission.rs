//! 書き込みの許し。裏で動くライブラリがライブラリの錠を持っていて書けるか、錠を取れずに読むだけかと、
//! その区別から決まること(書き込む頼みを受け付けるか・一覧を作る前に片付けるか)を持つ。

use crate::folder::ライブラリのフォルダ;
use crate::lock::{ライブラリの錠, 錠を取れない理由};
use crate::pre_scan_cleanup::走査の前の片付け;
use crate::request::ライブラリへの頼み;

/// 書き込みの許しとは、ライブラリの錠を持っていて書けるか、錠を取れずに読むだけかの区別のことである。
#[derive(Debug)]
pub enum 書き込みの許し {
    /// 錠を持っていて書ける。
    書ける(ライブラリの錠),
    /// 錠を取れなかったため読むだけである。取れなかった理由を持つ。
    読むだけ(錠を取れない理由),
}

impl 書き込みの許し {
    /// フォルダの錠を取りに行き、取れれば書ける、取れなければ読むだけにする。
    pub(crate) fn 錠を取りに行って決める(
        フォルダ: &ライブラリのフォルダ
    ) -> Self {
        match フォルダ.錠を取る() {
            Ok(錠) => Self::書ける(錠),
            Err(理由) => Self::読むだけ(理由),
        }
    }

    /// 頼みを受け付けるか。読むだけのときは書き込む頼みを受け付けない。
    pub(crate) fn 受け付けるか(&self, 頼み: &ライブラリへの頼み) -> bool {
        match self {
            Self::書ける(_) => true,
            Self::読むだけ(_) => !頼み.書き込むか(),
        }
    }

    /// 一覧を作る前の片付け。錠を持って書けるときだけ、以前の版が置いたサムネイルと置き去りの書きかけのファイルを消す。
    pub(crate) fn 走査の前の片付け(&self) -> 走査の前の片付け {
        match self {
            Self::書ける(_) => 走査の前の片付け::片付けあり,
            Self::読むだけ(_) => 走査の前の片付け::片付けなし,
        }
    }
}
