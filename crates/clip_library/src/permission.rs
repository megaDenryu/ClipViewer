//! 書き込みの許し。裏で動くライブラリがフォルダの錠を持っていて書けるか、錠を取れずに読むだけかと、
//! その区別から決まること(一覧を作る前に片付けてよいことを示す書ける証しを作れるか)を持つ。スタックと重ね合わせが、錠と理由の型だけを替えて同じ型を使う。

use crate::background_library::封じた手順::書ける証し;
use crate::lock::{ライブラリの錠, 錠を取れない理由};

/// 錠による書き込みの許しとは、フォルダの錠を持っていて書けるか、錠を取れずに読むだけかの区別のことである。
#[derive(Debug)]
pub enum 錠による書き込みの許し<錠, 取れない理由> {
    /// 錠を持っていて書ける。
    書ける(錠),
    /// 錠を取れなかったか取りに行かなかったため読むだけである。理由を持つ。
    読むだけ(取れない理由),
}

/// 書き込みの許しとは、スタックのライブラリの錠を持っていて書けるか、錠を取れずに読むだけかの区別のことである。
pub type 書き込みの許し = 錠による書き込みの許し<ライブラリの錠, 錠を取れない理由>;

impl<錠, 取れない理由> 錠による書き込みの許し<錠, 取れない理由> {
    /// 錠を取りに行った結果から決める。取れれば書ける、取れなければ読むだけにする。
    pub(crate) fn 錠を取りに行った結果から決める(
        結果: Result<錠, 取れない理由>,
    ) -> Self {
        match 結果 {
            Ok(錠) => Self::書ける(錠),
            Err(理由) => Self::読むだけ(理由),
        }
    }

    /// 錠を持っていて書けるか。
    pub fn 書けるか(&self) -> bool {
        matches!(self, Self::書ける(_))
    }

    /// 錠を持って書けるときだけ、書ける証しを作る。一覧を作る前の片付けに渡す。
    pub(crate) fn 書ける証しを作る(&self) -> Option<書ける証し> {
        match self {
            Self::書ける(_) => Some(書ける証し::錠を持つと確かめて作る()),
            Self::読むだけ(_) => None,
        }
    }
}
