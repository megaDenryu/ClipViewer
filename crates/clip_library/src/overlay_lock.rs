//! 重ね合わせの錠。重ね合わせのフォルダ(`overlays`)の錠のファイルを OS の排他の錠で開き、重ね合わせを書けるアプリを1つに限る。
//! `overlays` の錠を持つアプリは、必ずライブラリのフォルダの錠も持つ。そのため錠を取る口はライブラリの錠を借りて受け取り、
//! ライブラリの錠を持たないアプリは取りに行かない。参照: _doc/設計/同時再生.md 3-2(共有するものの表のライブラリの錠)

use std::io;

use crate::lock::ライブラリの錠;
use crate::lock_file::{錠のファイル, 錠のファイルを取れない理由};
use crate::overlay_folder::重ね合わせのフォルダ;

/// 重ね合わせの錠とは、重ね合わせのフォルダの錠のファイルを OS の排他の錠で開いたもののことである。落とすと錠を放す。
#[derive(Debug)]
pub struct 重ね合わせの錠 {
    _錠: 錠のファイル,
}

/// 重ね合わせの錠を取れない理由とは、重ね合わせの錠を取れなかった理由の区別のことである。
#[derive(Debug, thiserror::Error)]
pub enum 重ね合わせの錠を取れない理由 {
    /// ライブラリの錠を持っていないため、取りに行かなかった(別の ClipViewer がライブラリを開いている等)。
    #[error("ライブラリの錠を持っていない(別の ClipViewer がライブラリを開いている等)")]
    ライブラリの錠を持っていない,
    /// 別のアプリ(別の ClipViewer)が重ね合わせの錠を持っている。
    #[error("別の ClipViewer が重ね合わせのライブラリを開いている")]
    別のアプリが持っている,
    /// 錠のファイルか重ね合わせのフォルダを作れない・開けない。
    #[error("重ね合わせのライブラリの錠を取れない: {パス} を読み書きできない: {原因}")]
    読み書きできない {
        /// 読み書きしようとしたパス(表示用)。
        パス: String,
        /// OS が返した理由。
        原因: io::Error,
    },
}

impl 重ね合わせのフォルダ {
    /// 錠を取る。フォルダが無ければ作る。別のアプリが持っていれば待たずに取れないと返す。
    /// ライブラリの錠を借りるのは、`overlays` の錠をライブラリの錠を持つアプリだけが取ることを型で守るためである。
    pub fn 錠を取る(
        &self,
        _持っているライブラリの錠: &ライブラリの錠,
    ) -> Result<重ね合わせの錠, 重ね合わせの錠を取れない理由> {
        match 錠のファイル::フォルダの中で取る(self.パス()) {
            Ok(錠) => Ok(重ね合わせの錠 { _錠: 錠 }),
            Err(錠のファイルを取れない理由::別のアプリが持っている) => {
                Err(重ね合わせの錠を取れない理由::別のアプリが持っている)
            }
            Err(錠のファイルを取れない理由::読み書きできない {
                パス,
                原因,
            }) => Err(重ね合わせの錠を取れない理由::読み書きできない {
                パス: パス.display().to_string(),
                原因,
            }),
        }
    }
}
