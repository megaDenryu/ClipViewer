//! 重ね合わせの錠。重ね合わせのフォルダ(`overlays`)の錠のファイルを OS の排他の錠で開き、重ね合わせを書けるアプリを1つに限る。
//! `overlays` の錠を持つアプリは、必ずスタックのライブラリの錠も持つ。そのため錠を取るメソッドはスタックのライブラリの錠を借りて受け取り、
//! スタックのライブラリの錠を持たないアプリは取りに行かない。参照: _doc/設計/同時再生.md 3-2(共有するものの表のライブラリの錠)

use crate::lock::ライブラリの錠;
use crate::lock_file::{錠のファイル, 錠のファイルを取れない理由};
use crate::overlay_folder::重ね合わせのフォルダ;
use crate::permission::錠による書き込みの許し;

/// 重ね合わせの錠とは、重ね合わせのフォルダの錠のファイルを OS の排他の錠で開いたもののことである。落とすと錠を放す。
#[derive(Debug)]
pub struct 重ね合わせの錠 {
    _錠: 錠のファイル,
}

/// 重ね合わせの錠を取れない理由とは、重ね合わせの錠を取れなかった理由の区別のことである。
#[derive(Debug, thiserror::Error)]
pub enum 重ね合わせの錠を取れない理由 {
    /// スタックのライブラリの錠を持っていないため、取りに行かなかった。
    #[error(
        "スタックのライブラリの錠を持っていない(別の ClipViewer がスタックのライブラリを開いている等)"
    )]
    スタックのライブラリの錠を持っていない,
    /// 錠のファイルを取れない(別の ClipViewer が持っている・作れない等)。
    #[error("重ね合わせのライブラリの錠を取れない: {0}")]
    錠のファイルを取れない(#[from] 錠のファイルを取れない理由),
}

/// 重ね合わせの書き込みの許しとは、重ね合わせの錠を持っていて書けるか、錠を取れずに読むだけかの区別のことである。
pub type 重ね合わせの書き込みの許し =
    錠による書き込みの許し<重ね合わせの錠, 重ね合わせの錠を取れない理由>;

impl 重ね合わせのフォルダ {
    /// 錠を取る。フォルダが無ければ作る。別のアプリが持っていれば待たずに取れないと返す。
    /// スタックのライブラリの錠を借りるのは、`overlays` の錠をスタックのライブラリの錠を持つアプリだけが取ることを型で守るためである。
    pub fn 錠を取る(
        &self,
        _持っているライブラリの錠: &ライブラリの錠,
    ) -> Result<重ね合わせの錠, 重ね合わせの錠を取れない理由> {
        let 錠 = 錠のファイル::フォルダの中で取る(self.パス())?;
        Ok(重ね合わせの錠 { _錠: 錠 })
    }
}
