//! 錠を試したライブラリ。裏のスレッドを起こす前に錠を取りに行き、取れたかどうかで起動の仕方を決められるようにする。
//! スタックと重ね合わせが、ライブラリの型だけを替えて同じ型を使う。スタックのライブラリの錠を試すメソッドと、取り直すメソッドもここに置く。
//! 参照: _doc/設計/ライブラリ.md 判断9、_doc/設計/画面.md 判断13

use crate::background_library::裏で行うライブラリ;
use crate::library::スタックのライブラリ;
use crate::lock::錠を取れない理由;
use crate::overlay_library::重ね合わせのライブラリ;
use crate::permission::錠による書き込みの許し;

/// 錠を試した保存物のライブラリとは、ライブラリと、そのフォルダの錠を取りに行った結果(書き込みの許し)の組のことである。
/// 許しは必ず同じライブラリのフォルダの錠から決めたものであり、組を作れるのはこのクレートの錠を試すメソッドだけである。
#[derive(Debug)]
pub struct 錠を試した保存物のライブラリ
<ライブラリ: 裏で行うライブラリ> {
    pub(crate) ライブラリ: ライブラリ,
    pub(crate) 許し:
        錠による書き込みの許し<ライブラリ::錠, ライブラリ::錠を取れない理由>,
}

/// 錠を試したライブラリとは、スタックのライブラリと、そのフォルダの錠を取りに行った結果の組のことである。
pub type 錠を試したライブラリ = 錠を試した保存物のライブラリ<スタックのライブラリ>;

/// 錠を試した重ね合わせのライブラリとは、重ね合わせのライブラリと、その `overlays` フォルダの錠を試した結果の組のことである。
pub type 錠を試した重ね合わせのライブラリ =
    錠を試した保存物のライブラリ<重ね合わせのライブラリ>;

impl<ライブラリ: 裏で行うライブラリ> 錠を試した保存物のライブラリ<ライブラリ> {
    /// 書き込みの許し。
    pub fn 許し(
        &self,
    ) -> &錠による書き込みの許し<ライブラリ::錠, ライブラリ::錠を取れない理由> {
        &self.許し
    }

    /// 錠を持っていて書けるか。
    pub fn 書けるか(&self) -> bool {
        self.許し.書けるか()
    }
}

impl スタックのライブラリ {
    /// フォルダの錠を取りに行く。取れれば書ける、取れなければ読むだけの組にする。
    pub fn 錠を試す(self) -> 錠を試したライブラリ {
        let 許し = 錠による書き込みの許し::錠を取りに行った結果から決める(
            self.フォルダ.錠を取る(),
        );
        錠を試した保存物のライブラリ {
            ライブラリ: self,
            許し,
        }
    }
}

impl 錠を試したライブラリ {
    /// 別のアプリ(別の ClipViewer)が錠を持っていて取れなかったか。
    pub fn 別のアプリが持っているか(&self) -> bool {
        matches!(
            self.許し,
            錠による書き込みの許し::読むだけ(
                錠を取れない理由::別のアプリが持っている
            )
        )
    }

    /// 錠を取れていなければ、もう一度取りに行く。錠を持っていたアプリが落ちて錠が解けた後なら取れる。
    pub fn 錠を取り直す(self) -> Self {
        match self.許し {
            錠による書き込みの許し::書ける(_) => self,
            錠による書き込みの許し::読むだけ(_) => self.ライブラリ.錠を試す(),
        }
    }
}
