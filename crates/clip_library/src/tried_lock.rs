//! 錠を試したライブラリ。裏のスレッドを起こす前に錠を取りに行き、取れたかどうかで起動の仕方を決められるようにする。
//! アプリの起動の部分は、錠を取れなかったとき(別のアプリが持っているとき)に、そのアプリへ開きたい動画を渡して終わるかを決める。
//! 参照: _doc/設計/ライブラリ.md 判断9、_doc/設計/画面.md 判断13

use crate::library::スタックのライブラリ;
use crate::lock::錠を取れない理由;
use crate::permission::書き込みの許し;

/// 錠を試したライブラリとは、スタックのライブラリと、そのフォルダの錠を取りに行った結果(書き込みの許し)の組のことである。
/// 許しは必ず同じライブラリのフォルダの錠から決めたものであり、組を作れるのは `スタックのライブラリ::錠を試す` だけである。
#[derive(Debug)]
pub struct 錠を試したライブラリ {
    pub(crate) ライブラリ: スタックのライブラリ,
    pub(crate) 許し: 書き込みの許し,
}

impl スタックのライブラリ {
    /// フォルダの錠を取りに行く。取れれば書ける、取れなければ読むだけの組にする。
    pub fn 錠を試す(self) -> 錠を試したライブラリ {
        let 許し = 書き込みの許し::錠を取りに行って決める(&self.フォルダ);
        錠を試したライブラリ {
            ライブラリ: self,
            許し,
        }
    }
}

impl 錠を試したライブラリ {
    /// 書き込みの許し。
    pub fn 許し(&self) -> &書き込みの許し {
        &self.許し
    }

    /// 錠を持っていて書けるか。
    pub fn 書けるか(&self) -> bool {
        matches!(self.許し, 書き込みの許し::書ける(_))
    }

    /// 別のアプリ(別の ClipViewer)が錠を持っていて取れなかったか。
    pub fn 別のアプリが持っているか(&self) -> bool {
        matches!(
            self.許し,
            書き込みの許し::読むだけ(錠を取れない理由::別のアプリが持っている)
        )
    }

    /// 錠を取れていなければ、もう一度取りに行く。錠を持っていたアプリが落ちて錠が解けた後なら取れる。
    pub fn 錠を取り直す(self) -> Self {
        match self.許し {
            書き込みの許し::書ける(_) => self,
            書き込みの許し::読むだけ(_) => self.ライブラリ.錠を試す(),
        }
    }
}
