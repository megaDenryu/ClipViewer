//! 裏のスレッドを持つ係。裏のスレッドたちと知らせの受け口を持ち、頼みを送り、知らせを受け取り、書き込みや走査を終えるまで待つ。
//! 落とすと、送った頼みをすべて行い終えるまで待ってからスレッドを閉じる(アプリを閉じる直前の保存を失わないため)。
//! 裏で動くライブラリと裏で動く重ね合わせのライブラリが、これを1つずつ持つ。

use std::sync::mpsc::{self, Receiver, Sender};

use crate::background::頼めない理由;
use crate::background_threads::{
    書き込みのスレッドへの頼み, 裏で行うライブラリ, 裏のスレッドたち
};

/// 裏のスレッドを持つ係とは、裏のスレッドたち(落とすまで在る)と、裏のスレッドから届く知らせの受け口の組のことである。
pub(crate) struct 裏のスレッドを持つ係<ライブラリ: 裏で行うライブラリ> {
    スレッド: Option<裏のスレッドたち<ライブラリ>>,
    知らせの受け口: Receiver<ライブラリ::知らせ>,
}

impl<ライブラリ: 裏で行うライブラリ> 裏のスレッドを持つ係<ライブラリ> {
    /// 書き込みのスレッドと走査のスレッドを起こす。
    pub(crate) fn 起こす(書き込むライブラリ: ライブラリ) -> Self {
        let (知らせの送り口, 知らせの受け口) = mpsc::channel();
        Self {
            スレッド: Some(裏のスレッドたち::起こす(
                書き込むライブラリ,
                知らせの送り口,
            )),
            知らせの受け口,
        }
    }

    /// 書き込みのスレッドへ送る。待たない。
    pub(crate) fn 送る(
        &self,
        送るもの: 書き込みのスレッドへの頼み<ライブラリ::頼み>,
    ) -> Result<(), 頼めない理由> {
        self.スレッド
            .as_ref()
            .ok_or(頼めない理由::裏のスレッドが止まっている)?
            .書き込みの送り口
            .send(送るもの)
            .map_err(|_| 頼めない理由::裏のスレッドが止まっている)
    }

    /// 届いている知らせをすべて受け取る。待たない。
    pub(crate) fn 届いた知らせを受け取る(&self) -> Vec<ライブラリ::知らせ> {
        self.知らせの受け口.try_iter().collect()
    }

    /// それまでに送った書き込みをすべて行い終えるまで待つ。一覧の走査は待たない。
    pub(crate) fn 書き込みを終えるまで待つ(&self) {
        self.返事を待つ(書き込みのスレッドへの頼み::終えたら返事をする);
    }

    /// それまでに送った書き込みと一覧の走査をすべて行い終えるまで待つ。
    pub(crate) fn 走査も終えるまで待つ(&self) {
        self.返事を待つ(書き込みのスレッドへの頼み::走査も終えたら返事をする);
    }

    fn 返事を待つ(
        &self,
        返事の口から頼みを作る: fn(
            Sender<()>,
        ) -> 書き込みのスレッドへの頼み<ライブラリ::頼み>,
    ) {
        let (返事の送り口, 返事の受け口) = mpsc::channel();
        if self.送る(返事の口から頼みを作る(返事の送り口)).is_ok() {
            let _ = 返事の受け口.recv();
        }
    }
}

impl<ライブラリ: 裏で行うライブラリ> Drop for 裏のスレッドを持つ係<ライブラリ> {
    fn drop(&mut self) {
        if let Some(スレッド) = self.スレッド.take() {
            スレッド.終えるまで待って閉じる();
        }
    }
}
