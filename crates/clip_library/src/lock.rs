//! ライブラリの錠。同じライブラリのフォルダを2つのアプリが書くと、名前の変更や削除が他方の自動保存で上書きされるため、
//! 書けるアプリを1つに限る。錠のファイルを OS の排他の錠で開き、アプリが生きている間持ち続ける。
//! 参照: _doc/設計/ライブラリ.md 判断9

use crate::error::ライブラリの操作エラー;
use crate::folder::ライブラリのフォルダ;
use crate::lock_file::{錠のファイル, 錠のファイルを取れない理由};

/// ライブラリの錠とは、ライブラリのフォルダの錠のファイルを OS の排他の錠で開いたもののことである。
/// 落とすと錠を放す。アプリが落ちたときは OS が錠を解くため、次に起動したアプリが取れる(ファイルが残っていても取れる)。
#[derive(Debug)]
pub struct ライブラリの錠 {
    _錠: 錠のファイル,
}

/// 錠を取れない理由とは、ライブラリの錠を取れなかった理由の区別のことである。
#[derive(Debug, thiserror::Error)]
pub enum 錠を取れない理由 {
    /// 別のアプリ(別の ClipViewer)が錠を持っている。
    #[error("別の ClipViewer がライブラリを開いている")]
    別のアプリが持っている,
    /// 錠のファイルを作れない・開けない。
    #[error("ライブラリの錠を取れない: {0}")]
    読み書きできない(ライブラリの操作エラー),
}

impl ライブラリのフォルダ {
    /// 錠を取る。フォルダが無ければ作る。別のアプリが持っていれば待たずに取れないと返す。
    pub fn 錠を取る(&self) -> Result<ライブラリの錠, 錠を取れない理由> {
        match 錠のファイル::フォルダの中で取る(self.パス()) {
            Ok(錠) => Ok(ライブラリの錠 { _錠: 錠 }),
            Err(錠のファイルを取れない理由::別のアプリが持っている) => {
                Err(錠を取れない理由::別のアプリが持っている)
            }
            Err(錠のファイルを取れない理由::読み書きできない {
                パス,
                原因,
            }) => Err(錠を取れない理由::読み書きできない(
                ライブラリの操作エラー::読み書きのエラー(&パス, 原因),
            )),
        }
    }
}
