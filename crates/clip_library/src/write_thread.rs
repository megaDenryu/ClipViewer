//! 書き込みのスレッド。裏で動くライブラリから送られた頼みを受けた順に行い、一覧を作る頼みと走査を待つ返事は走査のスレッドへ渡す。
//! 走査のスレッドの本体(`scan_thread.rs`)と対になる。

use std::sync::mpsc::{Receiver, Sender};

use crate::background_library::裏で行うライブラリ;
use crate::pre_scan_cleanup::走査の前の片付け;
use crate::scan_thread::走査のスレッドへの頼み;

/// 書き込みのスレッドへの頼みとは、書き込みのスレッドへ送るものの区別のことである。
pub(crate) enum 書き込みのスレッドへの頼み<頼み> {
    行う(頼み),
    一覧を作らせる(走査の前の片付け),
    終えたら返事をする(Sender<()>),
    走査も終えたら返事をする(Sender<()>),
}

/// 書き込みのスレッドの本体。受けた順に行い、一覧を作る頼みと走査を待つ返事は走査のスレッドへ渡す。
/// 一覧を作る前に片付けるよう頼まれていれば、片付けてから渡す(書き込みと同じスレッドで順に行うため、書いている途中のファイルを消さない)。
/// 送り口が閉じられるか、知らせの受け手がいなくなったら終わる。
pub(crate) fn 書き込みを続ける<ライブラリ: 裏で行うライブラリ>(
    ライブラリ: &ライブラリ,
    受け口: &Receiver<書き込みのスレッドへの頼み<ライブラリ::頼み>>,
    走査の送り口: &Sender<走査のスレッドへの頼み>,
    知らせの送り口: &Sender<ライブラリ::知らせ>,
) {
    for 届いた in 受け口 {
        match 届いた {
            書き込みのスレッドへの頼み::行う(頼み) => {
                if 知らせの送り口.send(ライブラリ.頼みを行う(頼み)).is_err() {
                    return;
                }
            }
            書き込みのスレッドへの頼み::一覧を作らせる(片付け) => {
                if 片付け == 走査の前の片付け::片付けあり {
                    ライブラリ.一覧を作る前に片付ける();
                }
                let _ = 走査の送り口.send(走査のスレッドへの頼み::一覧を作る);
            }
            書き込みのスレッドへの頼み::終えたら返事をする(返事の送り口) =>
            {
                let _ = 返事の送り口.send(());
            }
            書き込みのスレッドへの頼み::走査も終えたら返事をする(
                返事の送り口,
            ) => {
                let _ = 走査の送り口.send(走査のスレッドへの頼み::終えたら返事をする(返事の送り口));
            }
        }
    }
}
