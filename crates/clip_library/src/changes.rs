//! ライブラリのスタックを変える操作。ファイルを読み直してから変え、同じ置き方で保存する。

use clip_domain::{
    スタックの名前, スタックの識別子, ライブラリのスタック, ライブラリの日時, 正規化した動画パス,
};

use crate::error::ライブラリの操作エラー;
use crate::library::スタックのライブラリ;

impl スタックのライブラリ {
    /// 識別子のスタックの名前を変えて保存し、変えたスタックを返す。
    pub fn 名前を変える(
        &self,
        識別子: &スタックの識別子,
        名前: スタックの名前,
        今: ライブラリの日時,
    ) -> Result<ライブラリのスタック, ライブラリの操作エラー> {
        let 変えた = self.読む(識別子)?.名前を変えた(名前, 今);
        self.保存する(&変えた)?;
        Ok(変えた)
    }

    /// 識別子のスタックの動画のパスを変えて保存し、変えたスタックを返す。
    pub fn 動画の場所を変える(
        &self,
        識別子: &スタックの識別子,
        動画のパス: 正規化した動画パス,
        今: ライブラリの日時,
    ) -> Result<ライブラリのスタック, ライブラリの操作エラー> {
        let 変えた = self.読む(識別子)?.動画の場所を変えた(動画のパス, 今);
        self.保存する(&変えた)?;
        Ok(変えた)
    }

    /// 元のスタックを、新しい識別子と「のコピー」を足した名前で複製して保存し、複製したスタックを返す。
    /// 新しい識別子のファイルが既にあれば、上書きせずに拒む。
    pub fn 複製する(
        &self,
        元の識別子: &スタックの識別子,
        新しい識別子: スタックの識別子,
        今: ライブラリの日時,
    ) -> Result<ライブラリのスタック, ライブラリの操作エラー> {
        if self.あるか(&新しい識別子) {
            return Err(ライブラリの操作エラー::既にある(
                新しい識別子,
            ));
        }
        let 元 = self.読む(元の識別子)?;
        let 複製 = 元.複製した(新しい識別子, 元.名前().複製の名前(), 今);
        self.保存する(&複製)?;
        Ok(複製)
    }
}
