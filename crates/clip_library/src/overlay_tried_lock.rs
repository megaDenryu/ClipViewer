//! 錠を試した重ね合わせのライブラリ。起動の手順が、ライブラリの錠を試した後で `overlays` の錠を試した結果であり、
//! 書き込みの許しから、書き込む頼みを受け付けるかと一覧を作る前に片付けるかが決まる。参照: _doc/設計/同時再生.md 3-2

use crate::overlay_library::重ね合わせのライブラリ;
use crate::overlay_lock::{重ね合わせの錠, 重ね合わせの錠を取れない理由};
use crate::overlay_request::重ね合わせのライブラリへの頼み;
use crate::permission::書き込みの許し;
use crate::pre_scan_cleanup::走査の前の片付け;
use crate::tried_lock::錠を試したライブラリ;

/// 重ね合わせの書き込みの許しとは、重ね合わせの錠を持っていて書けるか、錠を取れずに読むだけかの区別のことである。
#[derive(Debug)]
pub enum 重ね合わせの書き込みの許し {
    /// 錠を持っていて書ける。
    書ける(重ね合わせの錠),
    /// 錠を取れなかったか取りに行かなかったため読むだけである。理由を持つ。
    読むだけ(重ね合わせの錠を取れない理由),
}

impl 重ね合わせの書き込みの許し {
    /// 頼みを受け付けるか。読むだけのときは書き込む頼みを受け付けない。
    pub(crate) fn 受け付けるか(
        &self, 頼み: &重ね合わせのライブラリへの頼み
    ) -> bool {
        match self {
            Self::書ける(_) => true,
            Self::読むだけ(_) => !頼み.書き込むか(),
        }
    }

    /// 一覧を作る前の片付け。錠を持って書けるときだけ、置き去りの書きかけのファイルを消す。
    pub(crate) fn 走査の前の片付け(&self) -> 走査の前の片付け {
        match self {
            Self::書ける(_) => 走査の前の片付け::片付けあり,
            Self::読むだけ(_) => 走査の前の片付け::片付けなし,
        }
    }
}

/// 錠を試した重ね合わせのライブラリとは、重ね合わせのライブラリと、その `overlays` フォルダの錠を試した結果(重ね合わせの書き込みの許し)の組のことである。
/// 組を作れるのは `錠を試したライブラリ::重ね合わせの錠を試す` だけである。
#[derive(Debug)]
pub struct 錠を試した重ね合わせのライブラリ {
    pub(crate) ライブラリ: 重ね合わせのライブラリ,
    pub(crate) 許し: 重ね合わせの書き込みの許し,
}

impl 錠を試したライブラリ {
    /// 同じライブラリのフォルダの下の重ね合わせのフォルダの錠を試す。ライブラリの錠を持っているときだけ取りに行き、
    /// 持っていなければ取りに行かずに読むだけにする(`overlays` の錠を持つアプリは、必ずライブラリの錠も持つ)。
    pub fn 重ね合わせの錠を試す(
        &self,
    ) -> 錠を試した重ね合わせのライブラリ {
        let フォルダ = self.ライブラリ.フォルダ().重ね合わせのフォルダ();
        let 許し = match &self.許し {
            書き込みの許し::書ける(ライブラリの錠) => match フォルダ.錠を取る(ライブラリの錠) {
                Ok(錠) => 重ね合わせの書き込みの許し::書ける(錠),
                Err(理由) => 重ね合わせの書き込みの許し::読むだけ(理由),
            },
            書き込みの許し::読むだけ(_) => 重ね合わせの書き込みの許し::読むだけ(
                重ね合わせの錠を取れない理由::ライブラリの錠を持っていない,
            ),
        };
        錠を試した重ね合わせのライブラリ {
            ライブラリ: 重ね合わせのライブラリ::作成する(フォルダ),
            許し,
        }
    }
}

impl 錠を試した重ね合わせのライブラリ {
    /// 重ね合わせの書き込みの許し。
    pub fn 許し(&self) -> &重ね合わせの書き込みの許し {
        &self.許し
    }

    /// 錠を持っていて書けるか。
    pub fn 書けるか(&self) -> bool {
        matches!(self.許し, 重ね合わせの書き込みの許し::書ける(_))
    }
}
