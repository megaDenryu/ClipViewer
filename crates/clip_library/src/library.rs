//! スタックのライブラリ。ライブラリのフォルダを保持し、スタック1つのファイルを保存する・読む・削除する。
//! 保存と読み込みの手順は重ね合わせのライブラリと共に使う項目のファイルの読み書き(`item_read.rs`)へ委ねる。

use clip_domain::{
    スタックの識別子, ライブラリのスタック, ライブラリのファイルの読み込みエラー
};

use crate::background_library::{裏で行うライブラリ, 頼みの扱い};
use crate::folder::ライブラリのフォルダ;
use crate::item_error::項目の操作エラー;
use crate::lock::{ライブラリの錠, 錠を取れない理由};
use crate::request::{ライブラリからの知らせ, ライブラリへの頼み};

/// ライブラリの操作エラーとは、ライブラリのフォルダの読み書きや、スタックのファイルの中身の変換ができなかった理由のことである。
pub type ライブラリの操作エラー =
    項目の操作エラー<スタックの識別子, ライブラリのファイルの読み込みエラー>;

/// スタックのライブラリとは、ライブラリのフォルダを保持し、その中のスタックのファイルを読み書きするもののことである。
/// 同じフォルダを2つの値から同時に書かない前提で作る(書き込みを順に行うのは `裏で動くライブラリ`)。
#[derive(Debug, Clone)]
pub struct スタックのライブラリ {
    pub(crate) フォルダ: ライブラリのフォルダ,
}

impl スタックのライブラリ {
    /// ライブラリのフォルダから作る。
    pub fn 作成する(フォルダ: ライブラリのフォルダ) -> Self {
        Self { フォルダ }
    }

    /// ライブラリのフォルダ。
    pub fn フォルダ(&self) -> &ライブラリのフォルダ {
        &self.フォルダ
    }

    /// スタックを保存する。書きかけのファイルへ書いて記憶装置まで書き切ってから、スタックのファイルへ置き換える。
    /// 書いている途中で落ちても、元のファイルは壊れず書きかけのファイルが残るだけである。
    /// 置き換えに失敗したとき(ほかのプロセスがスタックのファイルを排他で開いている等)は失敗として返し、理由の文に書きかけのファイルのパスを入れる。
    /// 初めての保存ではスタックのファイルが無く、書きかけが唯一の写しになるため、利用者が拾い出せるようにする。
    pub fn 保存する(
        &self,
        スタック: &ライブラリのスタック,
    ) -> Result<(), ライブラリの操作エラー> {
        self.フォルダ.置き方().項目を保存する(スタック)
    }

    /// 識別子のスタックを読む。中身の識別子がファイル名の識別子と違えば読めないとする。
    pub fn 読む(
        &self,
        識別子: &スタックの識別子,
    ) -> Result<ライブラリのスタック, ライブラリの操作エラー> {
        self.フォルダ.置き方().項目を読む(識別子)
    }

    /// 識別子のスタックのファイルと、そのスタックの書きかけのファイルを消す。書きかけを残すと、走査の前の片付けまで置き去りになるためである。
    /// 書きかけは無いことが多く、消せなくても走査の前の片付けがいずれ消すため、書きかけの失敗は返さない。
    pub fn 削除する(
        &self,
        識別子: &スタックの識別子,
    ) -> Result<(), ライブラリの操作エラー> {
        let 置き方 = self.フォルダ.置き方();
        let パス = 置き方.ファイルのパス(識別子);
        let 結果 = std::fs::remove_file(&パス).map_err(|原因| {
            ライブラリの操作エラー::無ければ見つからないとする(
                &パス, 識別子, 原因,
            )
        });
        let _ = std::fs::remove_file(置き方.書きかけのパス(識別子));
        結果
    }

    /// 識別子のスタックのファイルがあるか。
    pub(crate) fn あるか(&self, 識別子: &スタックの識別子) -> bool {
        self.フォルダ.置き方().ファイルのパス(識別子).is_file()
    }
}

impl 裏で行うライブラリ for スタックのライブラリ {
    type 頼み = ライブラリへの頼み;
    type 知らせ = ライブラリからの知らせ;
    type フォルダ = ライブラリのフォルダ;
    type 錠 = ライブラリの錠;
    type 錠を取れない理由 = 錠を取れない理由;

    fn フォルダ(&self) -> &ライブラリのフォルダ {
        &self.フォルダ
    }

    fn 頼みの扱い(頼み: &ライブラリへの頼み) -> 頼みの扱い {
        if 頼み.書き込むか() {
            頼みの扱い::書き込む
        } else {
            頼みの扱い::一覧を作る
        }
    }

    fn 頼みを行う(
        &self, 頼み: ライブラリへの頼み
    ) -> ライブラリからの知らせ {
        頼み.行う(self)
    }

    fn 一覧を作った知らせ(&self) -> ライブラリからの知らせ {
        ライブラリへの頼み::一覧を作る.行う(self)
    }

    fn 一覧を作る前に片付ける(&self) {
        self.走査の前に片付ける();
    }
}
