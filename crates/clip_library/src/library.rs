//! スタックのライブラリ。ライブラリのフォルダを保持し、スタック1つのファイルを保存する・読む・削除する。

use std::io;
use std::path::Path;

use clip_domain::{
    スタックの識別子, ライブラリのスタック, ライブラリのファイルの本文
};

use crate::error::ライブラリの操作エラー;
use crate::folder::ライブラリのフォルダ;

/// スタックのライブラリとは、ライブラリのフォルダを保持し、その中のスタックのファイルを読み書きするもののことである。
/// 同じフォルダを2つの値から同時に書かない前提で作る(書き込みを順に行うのは `裏で動くライブラリ`)。
#[derive(Debug, Clone)]
pub struct スタックのライブラリ {
    pub(crate) フォルダ: ライブラリのフォルダ,
}

impl スタックのライブラリ {
    /// ライブラリのフォルダから作る。
    pub fn 作成する(フォルダ: ライブラリのフォルダ) -> Self {
        Self { フォルダ }
    }

    /// ライブラリのフォルダ。
    pub fn フォルダ(&self) -> &ライブラリのフォルダ {
        &self.フォルダ
    }

    /// スタックを保存する。書きかけのファイルへ書いて記憶装置まで書き切ってから、スタックのファイルへ置き換える。
    /// 書いている途中で落ちても、元のファイルは壊れず書きかけのファイルが残るだけである。
    /// 置き換えに失敗したとき(ほかのプロセスがスタックのファイルを排他で開いている等)は失敗として返し、理由の文に書きかけのファイルのパスを入れる。
    /// 初めての保存ではスタックのファイルが無く、書きかけが唯一の写しになるため、利用者が拾い出せるようにする。
    pub fn 保存する(
        &self,
        スタック: &ライブラリのスタック,
    ) -> Result<(), ライブラリの操作エラー> {
        let 本文 = スタック.本文へ書き出す()?;
        Ok(self
            .フォルダ
            .置き方()
            .書き切って置き換える(スタック.識別子(), &本文)?)
    }

    /// 識別子のスタックを読む。中身の識別子がファイル名の識別子と違えば読めないとする。
    pub fn 読む(
        &self,
        識別子: &スタックの識別子,
    ) -> Result<ライブラリのスタック, ライブラリの操作エラー> {
        let パス = self.フォルダ.置き方().ファイルのパス(識別子);
        let 本文 = std::fs::read_to_string(&パス)
            .map_err(|原因| 無ければ見つからないとする(&パス, 識別子, 原因))?;
        ファイルの本文を読む(識別子, 本文)
    }

    /// 識別子のスタックのファイルと、そのスタックの書きかけのファイルを消す。書きかけを残すと、走査の前の片付けまで置き去りになるためである。
    /// 書きかけは無いことが多く、消せなくても走査の前の片付けがいずれ消すため、書きかけの失敗は返さない。
    pub fn 削除する(
        &self,
        識別子: &スタックの識別子,
    ) -> Result<(), ライブラリの操作エラー> {
        let 置き方 = self.フォルダ.置き方();
        let パス = 置き方.ファイルのパス(識別子);
        let 結果 = std::fs::remove_file(&パス)
            .map_err(|原因| 無ければ見つからないとする(&パス, 識別子, 原因));
        let _ = std::fs::remove_file(置き方.書きかけのパス(識別子));
        結果
    }

    /// 識別子のスタックのファイルがあるか。
    pub(crate) fn あるか(&self, 識別子: &スタックの識別子) -> bool {
        self.フォルダ.置き方().ファイルのパス(識別子).is_file()
    }
}

/// ファイルの本文をライブラリのスタックとして読み、中身の識別子がファイル名の識別子と同じかを確かめる。
pub(crate) fn ファイルの本文を読む(
    ファイル名の識別子: &スタックの識別子,
    本文: String,
) -> Result<ライブラリのスタック, ライブラリの操作エラー> {
    let スタック = ライブラリのスタック::本文から読み込む(
        &ライブラリのファイルの本文::作成する(本文),
    )?;
    if スタック.識別子() != ファイル名の識別子 {
        return Err(ライブラリの操作エラー::識別子が違う {
            ファイル名の識別子: ファイル名の識別子.clone(),
            中身の識別子: スタック.識別子().clone(),
        });
    }
    Ok(スタック)
}

fn 無ければ見つからないとする(
    パス: &Path,
    識別子: &スタックの識別子,
    原因: io::Error,
) -> ライブラリの操作エラー {
    if 原因.kind() == io::ErrorKind::NotFound {
        ライブラリの操作エラー::見つからない(識別子.clone())
    } else {
        ライブラリの操作エラー::読み書きのエラー(パス, 原因)
    }
}
