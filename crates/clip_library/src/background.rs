//! 裏で動くライブラリ。書き込みのスレッドが保存と変更を受けた順に行い、走査のスレッドが一覧を作り、どちらも知らせを返す。
//! 一覧を作る頼みは書き込みのスレッドを通してから走査のスレッドへ渡すため、先に頼んだ変更の後の中身を読む。
//! 書き込みと走査を分けるのは、一覧から開く前に書き込みだけを待ち、遅いドライブの走査で画面のスレッドを止めないためである。

use crate::background_threads::{
    書き込みのスレッドへの頼み, 裏で行うライブラリ
};
use crate::background_worker::裏のスレッドを持つ係;
use crate::folder::ライブラリのフォルダ;
use crate::library::スタックのライブラリ;
use crate::permission::書き込みの許し;
use crate::request::{ライブラリからの知らせ, ライブラリへの頼み};
use crate::tried_lock::錠を試したライブラリ;

/// 頼めない理由とは、裏で動くライブラリ(または裏で動く重ね合わせのライブラリ)へ頼みを送れない理由の区別のことである。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum 頼めない理由 {
    /// 裏のスレッドが異常終了していて、頼みを受け取れない。
    #[error("ライブラリの裏のスレッドが止まっている")]
    裏のスレッドが止まっている,
    /// 錠を取れず読むだけで開いているため、書き込む頼みを受け付けない。取れなかった理由は書き込みの許しが持つ。
    #[error("ライブラリは読み取り専用で開いている(錠を取れなかった)")]
    読むだけで開いている,
}

/// 裏で動くライブラリとは、スタックのライブラリを書き込みのスレッドと走査のスレッドに持たせ、頼みを行わせる係のことである。
/// 落とすと、送った頼みをすべて行い終えるまで待ってからスレッドを閉じ、その後で錠を放す(アプリを閉じる直前の保存を失わないため)。
pub struct 裏で動くライブラリ {
    // 注意: 係を許しより先に並べる。項目は並べた順に落ちるため、係が書き込みを終えてから許しの錠を放す。
    係: 裏のスレッドを持つ係<スタックのライブラリ>,
    フォルダ: ライブラリのフォルダ,
    許し: 書き込みの許し,
}

impl 裏で動くライブラリ {
    /// ライブラリの錠を取り、裏のスレッドを起こす。錠を取れなければ読むだけで起こす。
    pub fn 起動する(ライブラリ: スタックのライブラリ) -> Self {
        Self::錠を試した後で起動する(ライブラリ.錠を試す())
    }

    /// 錠を試したライブラリの裏のスレッドを起こす。錠を取れていなければ読むだけで起こす。
    pub fn 錠を試した後で起動する(試した: 錠を試したライブラリ) -> Self {
        let 錠を試したライブラリ {
            ライブラリ, 許し
        } = 試した;
        Self {
            フォルダ: ライブラリ.フォルダ().clone(),
            係: 裏のスレッドを持つ係::起こす(ライブラリ),
            許し,
        }
    }

    /// ライブラリのフォルダ。
    pub fn フォルダ(&self) -> &ライブラリのフォルダ {
        &self.フォルダ
    }

    /// 書き込みの許し。
    pub fn 許し(&self) -> &書き込みの許し {
        &self.許し
    }

    /// 頼みを送る。待たない。読むだけのときは書き込む頼みを断る。
    pub fn 頼む(&self, 頼み: ライブラリへの頼み) -> Result<(), 頼めない理由> {
        if !self.許し.受け付けるか(&頼み) {
            return Err(頼めない理由::読むだけで開いている);
        }
        self.係.送る(match 頼み {
            ライブラリへの頼み::一覧を作る => {
                書き込みのスレッドへの頼み::一覧を作らせる(
                    self.許し.走査の前の片付け(),
                )
            }
            その他 => 書き込みのスレッドへの頼み::行う(その他),
        })
    }

    /// 届いている知らせをすべて受け取る。待たない。
    pub fn 届いた知らせを受け取る(&self) -> Vec<ライブラリからの知らせ> {
        self.係.届いた知らせを受け取る()
    }

    /// それまでに送った書き込みをすべて行い終えるまで待つ。一覧の走査は待たない。
    pub fn 書き込みを終えるまで待つ(&self) {
        self.係.書き込みを終えるまで待つ();
    }

    /// それまでに送った書き込みと一覧の走査をすべて行い終えるまで待つ。
    pub fn 走査も終えるまで待つ(&self) {
        self.係.走査も終えるまで待つ();
    }
}

impl 裏で行うライブラリ for スタックのライブラリ {
    type 頼み = ライブラリへの頼み;
    type 知らせ = ライブラリからの知らせ;

    fn 頼みを行う(
        &self, 頼み: ライブラリへの頼み
    ) -> ライブラリからの知らせ {
        頼み.行う(self)
    }

    fn 一覧を作った知らせ(&self) -> ライブラリからの知らせ {
        ライブラリへの頼み::一覧を作る.行う(self)
    }

    fn 一覧を作る前に片付ける(&self) {
        self.走査の前に片付ける();
    }
}
