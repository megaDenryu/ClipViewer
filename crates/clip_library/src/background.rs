//! 裏で動く項目のライブラリ。書き込みのスレッドが保存と変更を受けた順に行い、走査のスレッドが一覧を作り、どちらも知らせを返す。
//! 一覧を作る頼みは書き込みのスレッドを通してから走査のスレッドへ渡すため、先に頼んだ変更の後の中身を読む。
//! 書き込みと走査を分けるのは、一覧から開く前に書き込みだけを待ち、遅いドライブの走査で画面のスレッドを止めないためである。
//! スタックと重ね合わせが、ライブラリの型だけを替えて同じ型を使う(公開の名前は `裏で動くライブラリ`・`裏で動く重ね合わせのライブラリ`)。

use std::sync::mpsc::{self, Receiver, Sender};

use crate::background_library::{裏で行うライブラリ, 頼みの扱い};
use crate::background_threads::裏のスレッドたち;
use crate::library::スタックのライブラリ;
use crate::permission::錠による書き込みの許し;
use crate::request_refusal::頼めない理由;
use crate::tried_lock::錠を試した項目のライブラリ;
use crate::write_thread::書き込みのスレッドへの頼み;

/// 裏で動く項目のライブラリとは、ライブラリを書き込みのスレッドと走査のスレッドに持たせ、頼みを行わせる係のことである。
/// 注意: 落とすときは、送った頼みをすべて行い終えるまで待ってスレッドを閉じてから、許しの錠を放す(アプリを閉じる直前の保存を失わないため)。
/// この順は `Drop` が項目を落とす前にスレッドを閉じることで守り、項目を並べる順には頼らない。
pub struct 裏で動く項目のライブラリ<ライブラリ: 裏で行うライブラリ> {
    スレッド: Option<裏のスレッドたち<ライブラリ>>,
    知らせの受け口: Receiver<ライブラリ::知らせ>,
    フォルダ: ライブラリ::フォルダ,
    許し: 錠による書き込みの許し<ライブラリ::錠, ライブラリ::錠を取れない理由>,
}

/// 裏で動くライブラリとは、スタックのライブラリを書き込みのスレッドと走査のスレッドに持たせ、頼みを行わせる係のことである。
pub type 裏で動くライブラリ = 裏で動く項目のライブラリ<スタックのライブラリ>;

impl 裏で動くライブラリ {
    /// ライブラリの錠を取り、裏のスレッドを起こす。錠を取れなければ読むだけで起こす。
    pub fn 起動する(ライブラリ: スタックのライブラリ) -> Self {
        Self::錠を試した後で起動する(ライブラリ.錠を試す())
    }
}

impl<ライブラリ: 裏で行うライブラリ> 裏で動く項目のライブラリ<ライブラリ> {
    /// 錠を試したライブラリの裏のスレッドを起こす。錠を取れていなければ読むだけで起こす。
    pub fn 錠を試した後で起動する(
        試した: 錠を試した項目のライブラリ<ライブラリ>,
    ) -> Self {
        let 錠を試した項目のライブラリ {
            ライブラリ: 書き込むライブラリ,
            許し,
        } = 試した;
        let (知らせの送り口, 知らせの受け口) = mpsc::channel();
        Self {
            フォルダ: 書き込むライブラリ.フォルダ().clone(),
            スレッド: Some(裏のスレッドたち::起こす(
                書き込むライブラリ,
                知らせの送り口,
            )),
            知らせの受け口,
            許し,
        }
    }

    /// ライブラリのフォルダ。
    pub fn フォルダ(&self) -> &ライブラリ::フォルダ {
        &self.フォルダ
    }

    /// 書き込みの許し。
    pub fn 許し(
        &self,
    ) -> &錠による書き込みの許し<ライブラリ::錠, ライブラリ::錠を取れない理由> {
        &self.許し
    }

    /// 頼みを送る。待たない。読むだけのときは書き込む頼みを断る。
    pub fn 頼む(&self, 頼み: ライブラリ::頼み) -> Result<(), 頼めない理由> {
        self.送る(match ライブラリ::頼みの扱い(&頼み) {
            頼みの扱い::一覧を作る => {
                書き込みのスレッドへの頼み::一覧を作らせる(
                    self.許し.走査の前の片付け(),
                )
            }
            頼みの扱い::書き込む if self.許し.書けるか() => {
                書き込みのスレッドへの頼み::行う(頼み)
            }
            頼みの扱い::書き込む => return Err(頼めない理由::読むだけで開いている),
        })
    }

    /// 届いている知らせをすべて受け取る。待たない。
    pub fn 届いた知らせを受け取る(&self) -> Vec<ライブラリ::知らせ> {
        self.知らせの受け口.try_iter().collect()
    }

    /// それまでに送った書き込みをすべて行い終えるまで待つ。一覧の走査は待たない。
    pub fn 書き込みを終えるまで待つ(&self) {
        self.返事を待つ(書き込みのスレッドへの頼み::終えたら返事をする);
    }

    /// それまでに送った書き込みと一覧の走査をすべて行い終えるまで待つ。
    pub fn 走査も終えるまで待つ(&self) {
        self.返事を待つ(書き込みのスレッドへの頼み::走査も終えたら返事をする);
    }

    fn 送る(
        &self,
        送るもの: 書き込みのスレッドへの頼み<ライブラリ::頼み>,
    ) -> Result<(), 頼めない理由> {
        self.スレッド
            .as_ref()
            .ok_or(頼めない理由::裏のスレッドが止まっている)?
            .送る(送るもの)
    }

    fn 返事を待つ(
        &self,
        返事の口から頼みを作る: fn(
            Sender<()>,
        ) -> 書き込みのスレッドへの頼み<ライブラリ::頼み>,
    ) {
        let (返事の送り口, 返事の受け口) = mpsc::channel();
        if self.送る(返事の口から頼みを作る(返事の送り口)).is_ok() {
            let _ = 返事の受け口.recv();
        }
    }
}

impl<ライブラリ: 裏で行うライブラリ> Drop for 裏で動く項目のライブラリ<ライブラリ> {
    /// 送った頼みを終えるまで待ってスレッドを閉じる。項目(許しの錠)はこの後で落ちる。
    fn drop(&mut self) {
        if let Some(スレッド) = self.スレッド.take() {
            スレッド.終えるまで待って閉じる();
        }
    }
}
