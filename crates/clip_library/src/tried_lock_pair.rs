//! 錠を試したライブラリの組。起動の手順が、スタックのライブラリの錠を試した後で、続けて `overlays` の錠を試した結果であり、
//! 2つは同時に生まれて同時に消える。参照: _doc/設計/同時再生.md 3-2(触れる所の表の起動の手順の行)

use crate::overlay_library::重ね合わせのライブラリ;
use crate::overlay_lock::重ね合わせの錠を取れない理由;
use crate::permission::錠による書き込みの許し;
use crate::tried_lock::{
    錠を試したライブラリ, 錠を試した重ね合わせのライブラリ, 錠を試した項目のライブラリ,
};

/// 錠を試したライブラリの組とは、錠を試したスタックのライブラリと、同じライブラリのフォルダの下の `overlays` の錠を試した重ね合わせのライブラリの組のことである。
/// 注意: `overlays` の錠を持つアプリは必ずスタックのライブラリの錠も持つため、この組を落とすときは、重ね合わせの側を先に落として
/// `overlays` の錠を先に放す。項目は並べた順に落ちるため、重ね合わせの項目を先に並べてこの順を守る。組から取り出した後の落とす順は、取り出した側が守る。
#[derive(Debug)]
pub struct 錠を試したライブラリの組 {
    /// `overlays` の錠を試した重ね合わせのライブラリ。
    pub 重ね合わせ: 錠を試した重ね合わせのライブラリ,
    /// 錠を試したスタックのライブラリ。
    pub スタック: 錠を試したライブラリ,
}

impl 錠を試したライブラリ {
    /// 同じライブラリのフォルダの下の `overlays` の錠も試して組にする。スタックのライブラリの錠を持っているときだけ取りに行き、
    /// 持っていなければ取りに行かずに読むだけにする(`overlays` の錠を持つアプリは、必ずスタックのライブラリの錠も持つ)。
    pub fn 重ね合わせの錠も試す(self) -> 錠を試したライブラリの組 {
        let フォルダ = self.ライブラリ.フォルダ().重ね合わせのフォルダ();
        let 結果 = match &self.許し {
            錠による書き込みの許し::書ける(ライブラリの錠) => フォルダ.錠を取る(ライブラリの錠),
            錠による書き込みの許し::読むだけ(_) => {
                Err(重ね合わせの錠を取れない理由::スタックのライブラリの錠を持っていない)
            }
        };
        錠を試したライブラリの組 {
            重ね合わせ: 錠を試した項目のライブラリ {
                ライブラリ: 重ね合わせのライブラリ::作成する(フォルダ),
                許し:
                    錠による書き込みの許し::錠を取りに行った結果から決める(
                        結果,
                    ),
            },
            スタック: self,
        }
    }
}
