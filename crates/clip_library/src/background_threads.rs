//! 裏のスレッドたち。書き込みのスレッドと走査のスレッドと、書き込みのスレッドへの送り口を1つにまとめ、書き込みのスレッドの本体を持つ。
//! 3つは同時に生まれて同時に消えるため、裏のスレッドを持つ係は `Option<裏のスレッドたち>` 1つで持つ。
//! スタックのライブラリと重ね合わせのライブラリが、同じ手順で書き込みと走査を分けるため、裏で行うライブラリの型を引数に取る。

use std::sync::mpsc::{self, Receiver, Sender};
use std::thread::JoinHandle;

use crate::pre_scan_cleanup::走査の前の片付け;
use crate::scan_thread::{走査のスレッドへの頼み, 走査を続ける};

/// 裏で行うライブラリとは、裏のスレッドに頼みを順に行わせ、一覧を作らせ、一覧を作る前に片付けさせられるライブラリのことである。
/// スタックのライブラリと重ね合わせのライブラリが満たす。
pub(crate) trait 裏で行うライブラリ: Clone + Send + 'static {
    /// 書き込みのスレッドに順に行わせる頼み。
    type 頼み: Send + 'static;
    /// 頼みを行った結果として返す知らせ。
    type 知らせ: Send + 'static;
    /// 頼みを1つ行い、知らせを返す。
    fn 頼みを行う(&self, 頼み: Self::頼み) -> Self::知らせ;
    /// フォルダを読んで一覧を作り、その知らせを返す。
    fn 一覧を作った知らせ(&self) -> Self::知らせ;
    /// 一覧を作る前に、置き去りの書きかけ等の残り物を消す。
    fn 一覧を作る前に片付ける(&self);
}

/// 書き込みのスレッドへの頼みとは、書き込みのスレッドへ送るものの区別のことである。
pub(crate) enum 書き込みのスレッドへの頼み<頼み> {
    行う(頼み),
    一覧を作らせる(走査の前の片付け),
    終えたら返事をする(Sender<()>),
    走査も終えたら返事をする(Sender<()>),
}

/// 裏のスレッドたちとは、書き込みのスレッドと、走査のスレッドと、書き込みのスレッドへの送り口の組のことである。
pub(crate) struct 裏のスレッドたち<ライブラリ: 裏で行うライブラリ> {
    pub(crate) 書き込みの送り口: Sender<書き込みのスレッドへの頼み<ライブラリ::頼み>>,
    書き込みのスレッド: JoinHandle<()>,
    走査のスレッド: JoinHandle<()>,
}

impl<ライブラリ: 裏で行うライブラリ> 裏のスレッドたち<ライブラリ> {
    pub(crate) fn 起こす(
        書き込みのライブラリ: ライブラリ,
        知らせの送り口: Sender<ライブラリ::知らせ>,
    ) -> Self {
        let (書き込みの送り口, 書き込みの受け口) = mpsc::channel();
        let (走査の送り口, 走査の受け口) = mpsc::channel();
        let 走査のライブラリ = 書き込みのライブラリ.clone();
        let 走査の知らせの送り口 = 知らせの送り口.clone();
        let 走査のスレッド = std::thread::spawn(move || {
            走査を続ける(&走査のライブラリ, &走査の受け口, &走査の知らせの送り口)
        });
        let 書き込みのスレッド = std::thread::spawn(move || {
            書き込みを続ける(
                &書き込みのライブラリ,
                &書き込みの受け口,
                &走査の送り口,
                &知らせの送り口,
            )
        });
        Self {
            書き込みの送り口,
            書き込みのスレッド,
            走査のスレッド,
        }
    }

    /// 送り口を閉じ、書き込みのスレッドが受けた頼みを終えるのを待ち、続けて走査のスレッドの終わりを待つ。
    pub(crate) fn 終えるまで待って閉じる(self) {
        drop(self.書き込みの送り口);
        let _ = self.書き込みのスレッド.join();
        let _ = self.走査のスレッド.join();
    }
}

/// 書き込みのスレッドの本体。受けた順に行い、一覧を作る頼みと走査を待つ返事は走査のスレッドへ渡す。
/// 一覧を作る前に片付けるよう頼まれていれば、片付けてから渡す(書き込みと同じスレッドで順に行うため、書いている途中のファイルを消さない)。
fn 書き込みを続ける<ライブラリ: 裏で行うライブラリ>(
    ライブラリ: &ライブラリ,
    受け口: &Receiver<書き込みのスレッドへの頼み<ライブラリ::頼み>>,
    走査の送り口: &Sender<走査のスレッドへの頼み>,
    知らせの送り口: &Sender<ライブラリ::知らせ>,
) {
    for 届いた in 受け口 {
        match 届いた {
            書き込みのスレッドへの頼み::行う(頼み) => {
                if 知らせの送り口.send(ライブラリ.頼みを行う(頼み)).is_err() {
                    return;
                }
            }
            書き込みのスレッドへの頼み::一覧を作らせる(片付け) => {
                if 片付け == 走査の前の片付け::片付けあり {
                    ライブラリ.一覧を作る前に片付ける();
                }
                let _ = 走査の送り口.send(走査のスレッドへの頼み::一覧を作る);
            }
            書き込みのスレッドへの頼み::終えたら返事をする(返事の口) => {
                let _ = 返事の口.send(());
            }
            書き込みのスレッドへの頼み::走査も終えたら返事をする(
                返事の口,
            ) => {
                let _ = 走査の送り口.send(走査のスレッドへの頼み::終えたら返事をする(返事の口));
            }
        }
    }
}
