//! 裏のスレッドたち。書き込みのスレッド(`write_thread.rs`)と走査のスレッド(`scan_thread.rs`)を起こして持ち、書き込みのスレッドへの送り口を私有に持つ。
//! 3つは同時に生まれて同時に消えるため、裏で動くライブラリは `Option<裏のスレッドたち>` 1つで持つ。

use std::sync::mpsc::{self, Sender};
use std::thread::JoinHandle;

use crate::background_library::裏で行うライブラリ;
use crate::request_refusal::頼めない理由;
use crate::scan_thread::走査を続ける;
use crate::write_thread::{書き込みのスレッドへの頼み, 書き込みを続ける};

/// 裏のスレッドたちとは、書き込みのスレッドと、走査のスレッドと、書き込みのスレッドへの送り口の組のことである。
pub(crate) struct 裏のスレッドたち<ライブラリ: 裏で行うライブラリ> {
    書き込みの送り口: Sender<書き込みのスレッドへの頼み<ライブラリ::頼み>>,
    書き込みのスレッド: JoinHandle<()>,
    走査のスレッド: JoinHandle<()>,
}

impl<ライブラリ: 裏で行うライブラリ> 裏のスレッドたち<ライブラリ> {
    /// 書き込みのスレッドと走査のスレッドを起こす。どちらも同じライブラリの写しを持ち、知らせを同じ送り口へ返す。
    pub(crate) fn 起こす(
        書き込みのライブラリ: ライブラリ,
        知らせの送り口: Sender<ライブラリ::知らせ>,
    ) -> Self {
        let (書き込みの送り口, 書き込みの受け口) = mpsc::channel();
        let (走査の送り口, 走査の受け口) = mpsc::channel();
        let 走査のライブラリ = 書き込みのライブラリ.clone();
        let 走査の知らせの送り口 = 知らせの送り口.clone();
        let 走査のスレッド = std::thread::spawn(move || {
            走査を続ける(&走査のライブラリ, &走査の受け口, &走査の知らせの送り口)
        });
        let 書き込みのスレッド = std::thread::spawn(move || {
            書き込みを続ける(
                &書き込みのライブラリ,
                &書き込みの受け口,
                &走査の送り口,
                &知らせの送り口,
            )
        });
        Self {
            書き込みの送り口,
            書き込みのスレッド,
            走査のスレッド,
        }
    }

    /// 書き込みのスレッドへ送る。待たない。書き込みのスレッドが止まっていれば送れない。
    pub(crate) fn 送る(
        &self,
        送るもの: 書き込みのスレッドへの頼み<ライブラリ::頼み>,
    ) -> Result<(), 頼めない理由> {
        self.書き込みの送り口
            .send(送るもの)
            .map_err(|_| 頼めない理由::裏のスレッドが止まっている)
    }

    /// 送り口を閉じ、書き込みのスレッドが受けた頼みを終えるのを待ち、続けて走査のスレッドの終わりを待つ。
    pub(crate) fn 終えるまで待って閉じる(self) {
        drop(self.書き込みの送り口);
        let _ = self.書き込みのスレッド.join();
        let _ = self.走査のスレッド.join();
    }
}
