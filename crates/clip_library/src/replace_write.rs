//! 書きかけを経て置き換える書き込み。保存物の本文を書きかけのファイルへ書いて記憶装置まで書き切ってから、保存物のファイルへ置き換える。
//! 書いている途中で落ちても元のファイルを壊さないための手順であり、スタックと重ね合わせが共に使う。参照: _doc/設計/ライブラリ.md 判断2

use std::io;
use std::path::{Path, PathBuf};

use clip_domain::ライブラリのファイルの本文;

use crate::item_folder::保存物のファイルの読み書き係;
use crate::item_id::ライブラリの保存物の識別子;

/// 書き換えの失敗とは、書きかけのファイルへ書けなかったか、書き切った書きかけで保存物のファイルを置き換えられなかったかの区別のことである。
#[derive(Debug)]
pub(crate) enum 書き換えの失敗 {
    書けない {
        パス: PathBuf,
        原因: io::Error,
    },
    置き換えられない {
        置き場所: PathBuf,
        書きかけ: PathBuf,
        原因: io::Error,
    },
}

impl 保存物のファイルの読み書き係<'_> {
    /// 本文を書きかけのファイルへ書いて記憶装置まで書き切ってから、保存物のファイルへ置き換える。フォルダが無ければ作る。
    /// 書いている途中で落ちても元のファイルは壊れず、書きかけのファイルが残るだけである。置き換えに失敗したときは書きかけのパスを返す
    /// (初めての保存では書きかけが唯一の写しになり、利用者が拾い出せるようにするため)。
    pub(crate) fn 書き切って置き換える(
        &self,
        識別子: &impl ライブラリの保存物の識別子,
        本文: &ライブラリのファイルの本文,
    ) -> Result<(), 書き換えの失敗> {
        std::fs::create_dir_all(self.フォルダ()).map_err(|原因| {
            書き換えの失敗::書けない {
                パス: self.フォルダ().to_path_buf(),
                原因,
            }
        })?;
        let 書きかけ = self.書きかけのパス(識別子);
        let 置き場所 = self.ファイルのパス(識別子);
        書きかけのファイルへ書き切る(&書きかけ, 本文.文字列()).map_err(|原因| {
            書き換えの失敗::書けない {
                パス: 書きかけ.clone(),
                原因,
            }
        })?;
        std::fs::rename(&書きかけ, &置き場所).map_err(|原因| {
            書き換えの失敗::置き換えられない {
                置き場所,
                書きかけ,
                原因,
            }
        })
    }
}

/// 書きかけのファイルへ本文を書き、OS の書き込みの溜めから記憶装置まで書き切る(sync_all)。
/// 書き切らずに置き換えると、電源が落ちたときに置き換えた後のファイルが空や途中になることがあるためである。
fn 書きかけのファイルへ書き切る(パス: &Path, 本文: &str) -> io::Result<()> {
    let mut ファイル = std::fs::File::create(パス)?;
    io::Write::write_all(&mut ファイル, 本文.as_bytes())?;
    ファイル.sync_all()
}
