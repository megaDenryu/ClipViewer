//! 裏で行うライブラリ。裏で動くライブラリ(`background.rs`)の型が引数に取るライブラリの性質であり、スタックのライブラリ(`library.rs`)と
//! 重ね合わせのライブラリ(`overlay_background.rs`)が満たす。型ごとに違うのは、頼み・知らせ・フォルダ・錠と錠を取れない理由の型と、
//! 頼みの行い方(スタックは保存と名前の変更・複製・動画の場所の変更・削除、重ね合わせは今は保存だけ)と、一覧の型(スタックは `ライブラリの一覧`、
//! 重ね合わせは `重ね合わせの一覧`)と、一覧を作る前の片付けの中身(スタックは置き去りの書きかけに加えて以前の版のサムネイルも消す)である。
//! 注意: 頼みを行う・一覧を作る・片付けるメソッドは、crate の外から名指せない封じた trait(`封じた手順::裏で行う手順`)に置き、crate の外は実装できない。
//! 片付けはさらに、crate の外では作れない `書ける証し` を受け取るため、錠を持たない呼び手は呼べない(公開の trait の境界を通しても呼べない)。

/// 裏で行うライブラリとは、裏のスレッドに頼みを順に行わせ、一覧を作らせ、一覧を作る前に片付けさせられるライブラリのことである。
/// 性質の型(頼み・知らせ・フォルダ・錠・錠を取れない理由)は封じた trait が持ち、この trait はそれを公開の型の引数として使えるようにする。
pub trait 裏で行うライブラリ: 封じた手順::裏で行う手順 {}

impl<ライブラリ: 封じた手順::裏で行う手順> 裏で行うライブラリ for ライブラリ {}

pub(crate) mod 封じた手順 {
    //! 封じた手順。crate の外から名指せないモジュールに置くため、crate の外は trait を実装できない。

    /// 頼みの扱いとは、頼みが保存物のファイルを書く(作る・変える・消す)ものか、フォルダを読んで一覧を作るものかの区別のことである。
    /// 読むだけのときに断るかと、一覧を作る前に片付けるかを、裏で動くライブラリがこの区別で決める。
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum 頼みの扱い {
        /// 保存物のファイルを書く。読むだけのときは断る。
        書き込む,
        /// フォルダを読んで一覧を作る。書き込みのスレッドを通してから走査のスレッドへ渡す。
        一覧を作る,
    }

    /// 書ける証しとは、裏で動くライブラリが錠を持って書けることを示す値のことである。フィールドを私有にし、作るメソッドを crate の中にだけ開くため、
    /// crate の外では作れない。一覧を作る前の片付けはこの値を受け取り、錠を持たない呼び手が片付けを呼べないようにする。
    #[derive(Debug)]
    pub struct 書ける証し {
        _私有: (),
    }

    impl 書ける証し {
        /// 錠を持って書けると確かめた呼び手(書き込みの許し)だけが作る。
        pub(crate) fn 錠を持つと確かめて作る() -> Self {
            Self { _私有: () }
        }
    }

    /// 裏で行う手順とは、裏で行うライブラリの性質の型と、裏のスレッドが行う手順の組のことである。
    pub trait 裏で行う手順: Clone + Send + 'static {
        /// 書き込みのスレッドに順に行わせる頼み。
        type 頼み: Send + 'static;
        /// 頼みを行った結果として返す知らせ。
        type 知らせ: Send + 'static;
        /// 保存物のファイルを置くフォルダ。
        type フォルダ: Clone;
        /// フォルダの錠。
        type 錠;
        /// フォルダの錠を取れない理由。
        type 錠を取れない理由;
        /// 保存物のファイルを置くフォルダ。
        fn フォルダ(&self) -> &Self::フォルダ;
        /// 頼みが書き込むものか、一覧を作るものか。
        fn 頼みの扱い(頼み: &Self::頼み) -> 頼みの扱い;
        /// 頼みを1つ行い、知らせを返す。
        fn 頼みを行う(&self, 頼み: Self::頼み) -> Self::知らせ;
        /// フォルダを読んで一覧を作り、その知らせを返す。
        fn 一覧を作って知らせる(&self) -> Self::知らせ;
        /// 一覧を作る前に、置き去りの書きかけ等の残り物を消す。錠を持って書けるときだけ、書き込みのスレッドが呼ぶ。
        fn 一覧を作る前に片付ける(&self, 証し: 書ける証し);
    }
}
