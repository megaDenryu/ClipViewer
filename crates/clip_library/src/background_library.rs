//! 裏で行うライブラリ。裏で動くライブラリ(`background.rs`)の型が引数に取るライブラリの性質であり、スタックのライブラリ(`library.rs`)と
//! 重ね合わせのライブラリ(`overlay_background.rs`)が満たす。型ごとに違うのは、頼み・知らせ・フォルダ・錠と錠を取れない理由の型と、頼みの行い方だけである。

/// 頼みの扱いとは、頼みが項目のファイルを書く(作る・変える・消す)ものか、フォルダを読んで一覧を作るものかの区別のことである。
/// 読むだけのときに断るかと、一覧を作る前に片付けるかを、裏で動くライブラリがこの区別で決める。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 頼みの扱い {
    /// 項目のファイルを書く。読むだけのときは断る。
    書き込む,
    /// フォルダを読んで一覧を作る。書き込みのスレッドを通してから走査のスレッドへ渡す。
    一覧を作る,
}

/// 裏で行うライブラリとは、裏のスレッドに頼みを順に行わせ、一覧を作らせ、一覧を作る前に片付けさせられるライブラリのことである。
pub trait 裏で行うライブラリ: Clone + Send + 'static {
    /// 書き込みのスレッドに順に行わせる頼み。
    type 頼み: Send + 'static;
    /// 頼みを行った結果として返す知らせ。
    type 知らせ: Send + 'static;
    /// 項目のファイルを置くフォルダ。
    type フォルダ: Clone;
    /// フォルダの錠。
    type 錠;
    /// フォルダの錠を取れない理由。
    type 錠を取れない理由;
    /// 項目のファイルを置くフォルダ。
    fn フォルダ(&self) -> &Self::フォルダ;
    /// 頼みが書き込むものか、一覧を作るものか。
    fn 頼みの扱い(頼み: &Self::頼み) -> 頼みの扱い;
    /// 頼みを1つ行い、知らせを返す。
    fn 頼みを行う(&self, 頼み: Self::頼み) -> Self::知らせ;
    /// フォルダを読んで一覧を作り、その知らせを返す。
    fn 一覧を作った知らせ(&self) -> Self::知らせ;
    /// 一覧を作る前に、置き去りの書きかけ等の残り物を消す。
    fn 一覧を作る前に片付ける(&self);
}
