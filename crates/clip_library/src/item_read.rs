//! 保存物のファイルの読み書き。スタックのフォルダと重ね合わせのフォルダで、保存物1つを保存する・読むことと、フォルダの保存物のファイルを全部読むことを
//! 同じ手順で行う。読めないファイルは黙って飛ばさず、ファイル名と理由の組にする。参照: _doc/設計/ライブラリ.md 判断2・判断3

use std::path::Path;

use clip_domain::{ライブラリのファイルの本文, 正規化した動画パス};

use crate::item_error::保存物の操作エラー;
use crate::item_folder::保存物のファイルの読み書き係;
use crate::item_id::ライブラリの保存物の識別子;
use crate::item_kind::ライブラリの保存物;
use crate::listing::{
    ライブラリのファイル名, 動画の有無, 読めないファイル
};

/// 保存物の操作エラーのうち、その保存物の識別子と読み込みエラーで決まるもの。
type その保存物の操作エラー<保存物> = 保存物の操作エラー<
    <保存物 as ライブラリの保存物>::識別子,
    <保存物 as ライブラリの保存物>::読み込みエラー,
>;

/// 保存物のファイルの名前とは、保存物のファイルのファイル名(拡張子を含む)と、識別子として読む拡張子を除いた名前の組のことである。
pub(crate) struct 保存物のファイルの名前 {
    ファイル名: ライブラリのファイル名,
    拡張子を除いた名前: String,
}

impl 保存物のファイルの名前 {
    /// 保存物のファイルのパスから取り出す。
    fn パスから取り出す(パス: &Path) -> Self {
        let 文字列にする = |名前: Option<&std::ffi::OsStr>| {
            名前.map_or_else(String::new, |名前| 名前.to_string_lossy().into_owned())
        };
        Self {
            ファイル名: ライブラリのファイル名::作成する(
                文字列にする(パス.file_name()),
            ),
            拡張子を除いた名前: 文字列にする(パス.file_stem()),
        }
    }
}

impl 保存物のファイルの読み書き係<'_> {
    /// 保存物を書く。書きかけのファイルへ書いて記憶装置まで書き切ってから、保存物のファイルへ置き換える。
    pub(crate) fn 保存物を書く<保存物: ライブラリの保存物>(
        &self,
        保存するもの: &保存物,
    ) -> Result<(), その保存物の操作エラー<保存物>> {
        let 本文 = 保存するもの.本文へ書く()?;
        Ok(self.書き切って置き換える(保存するもの.保存物の識別子(), &本文)?)
    }

    /// 識別子の保存物を読む。ファイルが無ければ見つからない、中身の識別子がファイル名の識別子と違えば識別子が違うとする。
    pub(crate) fn 保存物を読む<保存物: ライブラリの保存物>(
        &self,
        識別子: &保存物::識別子,
    ) -> Result<保存物, その保存物の操作エラー<保存物>> {
        let パス = self.ファイルのパス(識別子);
        let 本文 = std::fs::read_to_string(&パス).map_err(|原因| {
            保存物の操作エラー::無ければ見つからないとする(
                &パス, 識別子, 原因,
            )
        })?;
        本文から保存物を読む(識別子, 本文)
    }

    /// フォルダの `*.json` をすべて読む。読めないファイルは、ファイル名と理由の組にする。フォルダがまだ無ければ空である。
    pub(crate) fn 保存物のファイルを全部読む<保存物: ライブラリの保存物>(
        &self,
    ) -> Result<Vec<Result<保存物, 読めないファイル>>, その保存物の操作エラー<保存物>> {
        let 並び = self.保存物のファイルを並べる().map_err(|原因| {
            保存物の操作エラー::読み書きのエラー(self.フォルダ(), 原因)
        })?;
        Ok(並び.iter().map(|パス| ファイルを読む(パス)).collect())
    }
}

/// 保存物のファイル1つを読む。ファイル名から識別子を読めなければ読めないファイルにする。
fn ファイルを読む<保存物: ライブラリの保存物>(
    パス: &Path,
) -> Result<保存物, 読めないファイル> {
    let 名前 = 保存物のファイルの名前::パスから取り出す(パス);
    保存物::識別子::ファイル名の本体から読む(名前.拡張子を除いた名前)
        .and_then(|識別子| {
            let 本文 = std::fs::read_to_string(パス).map_err(|原因| 原因.to_string())?;
            本文から保存物を読む::<保存物>(&識別子, 本文).map_err(|エラー| エラー.to_string())
        })
        .map_err(|理由| 読めないファイル {
            ファイル名: 名前.ファイル名,
            理由,
        })
}

/// ファイルの本文を保存物として読み、中身の識別子がファイル名の識別子と同じかを確かめる。
fn 本文から保存物を読む<保存物: ライブラリの保存物>(
    ファイル名の識別子: &保存物::識別子,
    本文: String,
) -> Result<保存物, その保存物の操作エラー<保存物>> {
    let 読んだ = 保存物::本文から読む(&ライブラリのファイルの本文::作成する(本文))
        .map_err(保存物の操作エラー::中身が読めない)?;
    if 読んだ.保存物の識別子() != ファイル名の識別子 {
        return Err(保存物の操作エラー::識別子が違う {
            ファイル名の識別子: ファイル名の識別子.clone(),
            中身の識別子: 読んだ.保存物の識別子().clone(),
        });
    }
    Ok(読んだ)
}

impl 動画の有無 {
    /// 動画のパスにファイルがあるかを確かめる。空のパスは見つからないとする。スタックと重ね合わせの走査が使う。
    pub(crate) fn 確かめる(パス: &正規化した動画パス) -> Self {
        if !パス.空か() && Path::new(パス.文字列()).is_file() {
            Self::ある
        } else {
            Self::見つからない
        }
    }
}
