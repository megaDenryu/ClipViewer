//! 項目のファイルの読み書き。スタックのフォルダと重ね合わせのフォルダで、項目1つを保存する・読むことと、フォルダの項目のファイルを全部読むことを
//! 同じ手順で行う。読めないファイルは黙って飛ばさず、ファイル名と理由の組にする。参照: _doc/設計/ライブラリ.md 判断2・判断3

use std::path::Path;

use clip_domain::{ライブラリのファイルの本文, 正規化した動画パス};

use crate::item_error::項目の操作エラー;
use crate::item_folder::項目のファイルの置き方;
use crate::item_id::ライブラリの項目の識別子;
use crate::item_kind::ライブラリの項目;
use crate::listing::{
    ライブラリのファイル名, 動画の有無, 読めないファイル
};

/// 項目の操作エラーのうち、その項目の識別子と読み込みエラーで決まるもの。
type その項目の操作エラー<項目> = 項目の操作エラー<
    <項目 as ライブラリの項目>::識別子,
    <項目 as ライブラリの項目>::読み込みエラー,
>;

/// 項目のファイルの名前とは、項目のファイルのファイル名(拡張子を含む)と、識別子として読む拡張子を除いた名前の組のことである。
pub(crate) struct 項目のファイルの名前 {
    ファイル名: ライブラリのファイル名,
    拡張子を除いた名前: String,
}

impl 項目のファイルの名前 {
    /// 項目のファイルのパスから取り出す。
    fn パスから取り出す(パス: &Path) -> Self {
        let 文字列にする = |名前: Option<&std::ffi::OsStr>| {
            名前.map_or_else(String::new, |名前| 名前.to_string_lossy().into_owned())
        };
        Self {
            ファイル名: ライブラリのファイル名::作成する(
                文字列にする(パス.file_name()),
            ),
            拡張子を除いた名前: 文字列にする(パス.file_stem()),
        }
    }
}

impl 項目のファイルの置き方<'_> {
    /// 項目を保存する。書きかけのファイルへ書いて記憶装置まで書き切ってから、項目のファイルへ置き換える。
    pub(crate) fn 項目を保存する<項目: ライブラリの項目>(
        &self,
        保存するもの: &項目,
    ) -> Result<(), その項目の操作エラー<項目>> {
        let 本文 = 保存するもの.本文へ書く()?;
        Ok(self.書き切って置き換える(保存するもの.項目の識別子(), &本文)?)
    }

    /// 識別子の項目を読む。ファイルが無ければ見つからない、中身の識別子がファイル名の識別子と違えば識別子が違うとする。
    pub(crate) fn 項目を読む<項目: ライブラリの項目>(
        &self,
        識別子: &項目::識別子,
    ) -> Result<項目, その項目の操作エラー<項目>> {
        let パス = self.ファイルのパス(識別子);
        let 本文 = std::fs::read_to_string(&パス).map_err(|原因| {
            項目の操作エラー::無ければ見つからないとする(&パス, 識別子, 原因)
        })?;
        本文から項目を読む(識別子, 本文)
    }

    /// フォルダの `*.json` をすべて読む。読めないファイルは、ファイル名と理由の組にする。フォルダがまだ無ければ空である。
    pub(crate) fn 項目のファイルを全部読む<項目: ライブラリの項目>(
        &self,
    ) -> Result<Vec<Result<項目, 読めないファイル>>, その項目の操作エラー<項目>> {
        let 並び = self.項目のファイルを並べる().map_err(|原因| {
            項目の操作エラー::読み書きのエラー(self.フォルダ(), 原因)
        })?;
        Ok(並び.iter().map(|パス| ファイルを読む(パス)).collect())
    }
}

/// 項目のファイル1つを読む。ファイル名から識別子を読めなければ読めないファイルにする。
fn ファイルを読む<項目: ライブラリの項目>(
    パス: &Path,
) -> Result<項目, 読めないファイル> {
    let 名前 = 項目のファイルの名前::パスから取り出す(パス);
    項目::識別子::ファイル名の本体から読む(名前.拡張子を除いた名前)
        .and_then(|識別子| {
            let 本文 = std::fs::read_to_string(パス).map_err(|原因| 原因.to_string())?;
            本文から項目を読む::<項目>(&識別子, 本文).map_err(|エラー| エラー.to_string())
        })
        .map_err(|理由| 読めないファイル {
            ファイル名: 名前.ファイル名,
            理由,
        })
}

/// ファイルの本文を項目として読み、中身の識別子がファイル名の識別子と同じかを確かめる。
fn 本文から項目を読む<項目: ライブラリの項目>(
    ファイル名の識別子: &項目::識別子,
    本文: String,
) -> Result<項目, その項目の操作エラー<項目>> {
    let 読んだ = 項目::本文から読む(&ライブラリのファイルの本文::作成する(本文))
        .map_err(項目の操作エラー::中身が読めない)?;
    if 読んだ.項目の識別子() != ファイル名の識別子 {
        return Err(項目の操作エラー::識別子が違う {
            ファイル名の識別子: ファイル名の識別子.clone(),
            中身の識別子: 読んだ.項目の識別子().clone(),
        });
    }
    Ok(読んだ)
}

impl 動画の有無 {
    /// 動画のパスにファイルがあるかを確かめる。空のパスは見つからないとする。スタックと重ね合わせの走査が使う。
    pub(crate) fn 確かめる(パス: &正規化した動画パス) -> Self {
        if !パス.空か() && Path::new(パス.文字列()).is_file() {
            Self::ある
        } else {
            Self::見つからない
        }
    }
}
