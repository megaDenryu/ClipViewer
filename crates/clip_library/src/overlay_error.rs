//! 重ね合わせのライブラリの操作で起きるエラー。

use std::io;
use std::path::Path;

use clip_domain::{
    ライブラリのファイルの書き出しエラー, 重ね合わせのファイルの読み込みエラー, 重ね合わせの識別子,
};

use crate::item_folder::書き換えの失敗;

/// 重ね合わせのライブラリの操作エラーとは、重ね合わせのフォルダの読み書きや、ファイルの中身の変換ができなかった理由のことである。
#[derive(Debug, thiserror::Error)]
pub enum 重ね合わせのライブラリの操作エラー {
    /// ファイルかフォルダを読み書きできない。
    #[error("{パス} を読み書きできない: {原因}")]
    読み書きできない {
        /// 読み書きしようとしたパス(表示用)。
        パス: String,
        /// OS が返した理由。
        原因: io::Error,
    },
    /// 書き切った書きかけのファイルで、重ね合わせのファイルを置き換えられない。書いた中身は書きかけのファイルに残っている。
    #[error("{置き場所} を置き換えられない(書いた中身は {書きかけ} に残っている): {原因}")]
    置き換えられない {
        /// 置き換えようとした重ね合わせのファイルのパス(表示用)。
        置き場所: String,
        /// 書いた中身が残っている書きかけのファイルのパス(表示用)。利用者が拾い出せるように知らせる。
        書きかけ: String,
        /// OS が返した理由。
        原因: io::Error,
    },
    /// ファイルの中身がライブラリの重ね合わせとして読めない。
    #[error("{0}")]
    中身が読めない(#[from] 重ね合わせのファイルの読み込みエラー),
    /// ライブラリの重ね合わせを本文へ書き出せない。
    #[error("{0}")]
    書き出せない(#[from] ライブラリのファイルの書き出しエラー),
    /// 指定の識別子の重ね合わせのファイルが無い。
    #[error("重ね合わせ {0} のファイルが無い")]
    見つからない(重ね合わせの識別子),
    /// ファイル名の識別子と中身の識別子が違う。
    #[error("ファイル名の識別子 {ファイル名の識別子} と中身の識別子 {中身の識別子} が違う")]
    識別子が違う {
        /// ファイル名から読んだ識別子。
        ファイル名の識別子: 重ね合わせの識別子,
        /// 中身に書いてある識別子。
        中身の識別子: 重ね合わせの識別子,
    },
}

impl 重ね合わせのライブラリの操作エラー {
    /// io のエラーを、どのパスで起きたかと組にする。
    pub(crate) fn 読み書きのエラー(パス: &Path, 原因: io::Error) -> Self {
        Self::読み書きできない {
            パス: パス.display().to_string(),
            原因,
        }
    }
}

impl From<書き換えの失敗> for 重ね合わせのライブラリの操作エラー {
    fn from(失敗: 書き換えの失敗) -> Self {
        match 失敗 {
            書き換えの失敗::書けない { パス, 原因 } => {
                Self::読み書きのエラー(&パス, 原因)
            }
            書き換えの失敗::置き換えられない {
                置き場所,
                書きかけ,
                原因,
            } => Self::置き換えられない {
                置き場所: 置き場所.display().to_string(),
                書きかけ: 書きかけ.display().to_string(),
                原因,
            },
        }
    }
}
