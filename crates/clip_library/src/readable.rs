//! 保存物を読めるライブラリ。裏で動く保存物のライブラリ(`background.rs`)が、画面のスレッドで識別子の保存物を1つ読むために使う性質であり、
//! スタックのライブラリと重ね合わせのライブラリが満たす。一覧から開く前に、書き込みを終えるのを待ってから読むために使う。

use std::fmt;

use clip_domain::{
    スタックの識別子, ライブラリのスタック, ライブラリの重ね合わせ, 重ね合わせの識別子,
};

use crate::background_library::裏で行うライブラリ;
use crate::library::{スタックのライブラリ, ライブラリの操作エラー};
use crate::overlay_library::{
    重ね合わせのライブラリ, 重ね合わせのライブラリの操作エラー
};

/// 保存物を読めるライブラリとは、識別子の保存物をフォルダから1つ読めるライブラリの性質のことである。
pub trait 保存物を読めるライブラリ: 裏で行うライブラリ {
    /// 保存物を見分ける識別子。
    type 保存物の識別子;
    /// フォルダに1ファイルずつ置く保存物。
    type 保存物;
    /// 保存物を読めない理由。
    type 読めない理由: fmt::Display;
    /// 識別子の保存物を読む。中身の識別子がファイル名の識別子と違えば読めないとする。
    fn 保存物を読む(
        &self,
        識別子: &Self::保存物の識別子,
    ) -> Result<Self::保存物, Self::読めない理由>;
}

impl 保存物を読めるライブラリ for スタックのライブラリ {
    type 保存物の識別子 = スタックの識別子;
    type 保存物 = ライブラリのスタック;
    type 読めない理由 = ライブラリの操作エラー;

    fn 保存物を読む(
        &self,
        識別子: &スタックの識別子,
    ) -> Result<ライブラリのスタック, ライブラリの操作エラー> {
        self.読む(識別子)
    }
}

impl 保存物を読めるライブラリ for 重ね合わせのライブラリ {
    type 保存物の識別子 = 重ね合わせの識別子;
    type 保存物 = ライブラリの重ね合わせ;
    type 読めない理由 = 重ね合わせのライブラリの操作エラー;

    fn 保存物を読む(
        &self,
        識別子: &重ね合わせの識別子,
    ) -> Result<ライブラリの重ね合わせ, 重ね合わせのライブラリの操作エラー> {
        self.読む(識別子)
    }
}
