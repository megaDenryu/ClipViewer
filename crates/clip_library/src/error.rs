//! ライブラリの操作で起きるエラー。

use std::io;
use std::path::Path;

use clip_domain::{
    スタックの識別子, ライブラリのファイルの書き出しエラー, ライブラリのファイルの読み込みエラー,
};

/// ライブラリの操作エラーとは、ライブラリのフォルダの読み書きや、ファイルの中身の変換ができなかった理由のことである。
#[derive(Debug, thiserror::Error)]
pub enum ライブラリの操作エラー {
    /// ファイルかフォルダを読み書きできない。
    #[error("{パス} を読み書きできない: {原因}")]
    読み書きできない {
        /// 読み書きしようとしたパス(表示用)。
        パス: String,
        /// OS が返した理由。
        原因: io::Error,
    },
    /// 書き切った書きかけのファイルで、スタックのファイルを置き換えられない。書いた中身は書きかけのファイルに残っている。
    #[error("{置き場所} を置き換えられない(書いた中身は {書きかけ} に残っている): {原因}")]
    置き換えられない {
        /// 置き換えようとしたスタックのファイルのパス(表示用)。
        置き場所: String,
        /// 書いた中身が残っている書きかけのファイルのパス(表示用)。利用者が拾い出せるように知らせる。
        書きかけ: String,
        /// OS が返した理由。
        原因: io::Error,
    },
    /// ファイルの中身がライブラリのスタックとして読めない。
    #[error("{0}")]
    中身が読めない(#[from] ライブラリのファイルの読み込みエラー),
    /// ライブラリのスタックを本文へ書き出せない。
    #[error("{0}")]
    書き出せない(#[from] ライブラリのファイルの書き出しエラー),
    /// 指定の識別子のスタックのファイルが無い。
    #[error("スタック {0} のファイルが無い")]
    見つからない(スタックの識別子),
    /// 新しいスタックの識別子のファイルが既にある。
    #[error("スタック {0} のファイルが既にある")]
    既にある(スタックの識別子),
    /// ファイル名の識別子と中身の識別子が違う。
    #[error("ファイル名の識別子 {ファイル名の識別子} と中身の識別子 {中身の識別子} が違う")]
    識別子が違う {
        /// ファイル名から読んだ識別子。
        ファイル名の識別子: スタックの識別子,
        /// 中身に書いてある識別子。
        中身の識別子: スタックの識別子,
    },
}

impl ライブラリの操作エラー {
    /// io のエラーを、どのパスで起きたかと組にする。
    pub(crate) fn 読み書きのエラー(パス: &Path, 原因: io::Error) -> Self {
        Self::読み書きできない {
            パス: パス.display().to_string(),
            原因,
        }
    }
}
