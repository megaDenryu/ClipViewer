//! 以前の版が置いたサムネイルの片付け。以前の版はサムネイルをライブラリのフォルダの `<識別子>.jpg` に置き、書き込みの途中は
//! `<識別子>.jpg.tmp` に書いていた。今はサムネイルをライブラリの外のキャッシュに置き、ライブラリのフォルダにはスタックのファイルと
//! 錠のファイルだけを残す。参照: _doc/設計/ライブラリ.md 判断10(以前の置き方の片付け)

use crate::library::スタックのライブラリ;

/// 以前の版がサムネイルのファイル名の後ろに付けていた文字列。書きかけのファイルは `.jpg.tmp` で終わる。
const 以前のサムネイルの終わり: [&str; 2] = [".jpg", ".jpg.tmp"];

impl スタックのライブラリ {
    /// ライブラリのフォルダの `*.jpg` と `*.jpg.tmp` を消す。フォルダが無ければ何もしない。
    /// 消せなかったファイルは、次に一覧を作るときに消し直す(拡張子が json でないため一覧に出ず、残っても害は無い)。
    pub(crate) fn 以前のサムネイルを片付ける(&self) {
        let Ok(フォルダの中の並び) = std::fs::read_dir(self.フォルダ().パス())
        else {
            return;
        };
        for フォルダの中の項目 in フォルダの中の並び.flatten() {
            let 名前 = フォルダの中の項目.file_name();
            let 以前のサムネイルか = 名前.to_str().is_some_and(|名前| {
                以前のサムネイルの終わり
                    .iter()
                    .any(|終わり| 名前.ends_with(終わり))
            });
            if 以前のサムネイルか {
                let _ = std::fs::remove_file(フォルダの中の項目.path());
            }
        }
    }
}
