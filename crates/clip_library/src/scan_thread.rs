//! 走査のスレッド。書き込みのスレッドから渡された頼みを受けた順に行い、一覧を作って知らせを返す。
//! 走査を書き込みと別のスレッドにするのは、遅いドライブの走査の間も書き込みを待たせないためである。

use std::sync::mpsc::{Receiver, Sender};

use crate::library::スタックのライブラリ;
use crate::request::{ライブラリからの知らせ, ライブラリへの頼み};

/// 走査のスレッドへの頼みとは、走査のスレッドへ送るものの区別のことである。
pub(crate) enum 走査のスレッドへの頼み {
    一覧を作る,
    終えたら返事をする(Sender<()>),
}

/// 走査のスレッドの本体。一覧を作り、知らせを返す。送り口が閉じられるか、知らせの受け手がいなくなったら終わる。
pub(crate) fn 走査を続ける(
    ライブラリ: &スタックのライブラリ,
    受け口: &Receiver<走査のスレッドへの頼み>,
    知らせの送り口: &Sender<ライブラリからの知らせ>,
) {
    for 届いた in 受け口 {
        match 届いた {
            走査のスレッドへの頼み::一覧を作る => {
                let 知らせ = ライブラリへの頼み::一覧を作る.行う(ライブラリ);
                if 知らせの送り口.send(知らせ).is_err() {
                    return;
                }
            }
            走査のスレッドへの頼み::終えたら返事をする(返事の口) => {
                let _ = 返事の口.send(());
            }
        }
    }
}
