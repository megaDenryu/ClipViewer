//! 走査の前の片付け。書けるアプリは、一覧を作る前に、保存物のファイルを置くフォルダから保存物のファイルでない残り物を消す。
//! 残り物とは、1日より前から置き去りになっている書きかけのファイルと、スタックのフォルダでは以前の版が置いたサムネイル(`legacy_thumbnail.rs`)のことである。
//! 重ね合わせのフォルダ(`overlays`)も同じ規則で置き去りの書きかけを消す。参照: _doc/設計/ライブラリ.md 判断3、_doc/設計/同時再生.md 4-2

use std::fs::DirEntry;
use std::time::{Duration, SystemTime};

use crate::item_folder::保存物のファイルの読み書き係;
use crate::library::スタックのライブラリ;

/// 置き去りの書きかけを消すまでに待つ、最後に書き換えてからの時間(1日)。
const 書きかけを残す時間: Duration = Duration::from_secs(24 * 60 * 60);

/// 走査の前の片付けとは、一覧を作る前に保存物のファイルを置くフォルダの残り物を消すか、消さないかの区別のことである。
/// 消すのは錠を持って書けるアプリだけである(読むだけのアプリはフォルダを書き換えない)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 走査の前の片付け {
    片付けあり,
    片付けなし,
}

impl スタックのライブラリ {
    /// 以前の版のサムネイルと、置き去りの書きかけのファイルを消す。
    pub(crate) fn 走査の前に片付ける(&self) {
        self.以前のサムネイルを片付ける();
        self.フォルダ().置き方().置き去りの書きかけを片付ける();
    }
}

impl 保存物のファイルの読み書き係<'_> {
    /// 対応する保存物のファイルが無く、最後に書き換えてから1日より古い書きかけのファイル(`<識別子>.json.tmp`)を消す。
    /// 初めて保存する保存物の置き換えに失敗すると、保存物のファイルが無いまま書きかけだけが残り、それが唯一の写しになる。
    /// 1日待つのは、その写しを利用者が拾い出す時間を残すためである(削除したスタックの書きかけは、削除のときに一緒に消す)。
    /// 注意: 書き込みのスレッドだけが呼ぶ。書き込みは同じスレッドで順に行い、錠が書けるアプリを1つに限るため、今書いている途中の書きかけは無い。
    /// 今の時刻はここで1回だけ読む。消せなかったファイルは次の走査で消し直す。
    pub(crate) fn 置き去りの書きかけを片付ける(&self) {
        let Ok(フォルダの中の並び) = std::fs::read_dir(self.フォルダ()) else {
            return;
        };
        let 今 = SystemTime::now();
        for フォルダの中の項目 in フォルダの中の並び.flatten() {
            let 名前 = フォルダの中の項目.file_name();
            let Some(保存物のファイル) = 名前
                .to_str()
                .and_then(|名前| self.書きかけに対応するファイル(名前))
            else {
                continue;
            };
            if !保存物のファイル.exists() && 残す時間を過ぎたか(&フォルダの中の項目, 今)
            {
                let _ = std::fs::remove_file(フォルダの中の項目.path());
            }
        }
    }
}

/// ファイルを最後に書き換えてから、書きかけを残す時間を過ぎたか。書き換えた日時を読めないか、日時が今より後なら過ぎていないとする(消さない側へ倒す)。
fn 残す時間を過ぎたか(項目: &DirEntry, 今: SystemTime) -> bool {
    項目
        .metadata()
        .and_then(|情報| 情報.modified())
        .ok()
        .and_then(|書き換えた日時| 今.duration_since(書き換えた日時).ok())
        .is_some_and(|経過| 経過 > 書きかけを残す時間)
}
