//! 保存物のファイルの読み書き係。ライブラリの保存物(スタックか重ね合わせ)1つを `<識別子>.json` の1ファイルに書き、書き込みの途中は
//! `<識別子>.json.tmp` に書くフォルダについて、名前の規則と、保存物のファイルの並びを1箇所に閉じる。
//! 書きかけを経て置き換える書き込みは `replace_write.rs` に置く。
//! 置き去りの書きかけの片付けは `pre_scan_cleanup.rs` に置く。スタックのフォルダと重ね合わせのフォルダ(`overlays`)が同じ規則を使う。
//! 参照: _doc/設計/ライブラリ.md 判断2・判断3、_doc/設計/同時再生.md 4-2

use std::io;
use std::path::{Path, PathBuf};

use crate::item_id::ライブラリの保存物の識別子;

/// 保存物のファイルの拡張子。一覧はこの拡張子のファイルだけを読む。
const 保存物のファイルの拡張子: &str = "json";

/// 書きかけのファイルの印。保存物のファイルの名前の後ろに足す。
const 書きかけの印: &str = ".tmp";

/// 保存物のファイルの読み書き係とは、保存物のファイルを置くフォルダを借りて、その中の名前の規則と読み書きを行うもののことである。
pub(crate) struct 保存物のファイルの読み書き係<'フォルダ>(&'フォルダ Path);

impl<'フォルダ> 保存物のファイルの読み書き係<'フォルダ> {
    pub(crate) fn 作成する(フォルダ: &'フォルダ Path) -> Self {
        Self(フォルダ)
    }

    /// 保存物のファイルを置くフォルダのパス。
    pub(crate) fn フォルダ(&self) -> &'フォルダ Path {
        self.0
    }

    /// 保存物のファイルのパス。
    pub(crate) fn ファイルのパス(
        &self,
        識別子: &impl ライブラリの保存物の識別子,
    ) -> PathBuf {
        self.0.join(format!(
            "{}.{保存物のファイルの拡張子}",
            識別子.ファイル名の本体()
        ))
    }

    /// 書きかけのファイルのパス。書き終えたら保存物のファイルへ置き換える。
    pub(crate) fn 書きかけのパス(
        &self,
        識別子: &impl ライブラリの保存物の識別子,
    ) -> PathBuf {
        self.0.join(format!(
            "{}.{保存物のファイルの拡張子}{書きかけの印}",
            識別子.ファイル名の本体()
        ))
    }

    /// フォルダの直下の、拡張子が json のファイルのパスを並べる。書きかけとほかの拡張子のファイルとサブフォルダは含めない。
    /// フォルダがまだ無ければ空である。
    pub(crate) fn 保存物のファイルを並べる(&self) -> io::Result<Vec<PathBuf>> {
        let フォルダの中の並び = match std::fs::read_dir(self.0) {
            Ok(並び) => 並び,
            Err(原因) if 原因.kind() == io::ErrorKind::NotFound => return Ok(Vec::new()),
            Err(原因) => return Err(原因),
        };
        let mut 並び = Vec::new();
        for フォルダの中の項目 in フォルダの中の並び {
            let パス = フォルダの中の項目?.path();
            if パス
                .extension()
                .is_some_and(|拡張子| 拡張子 == 保存物のファイルの拡張子)
                && パス.is_file()
            {
                並び.push(パス);
            }
        }
        Ok(並び)
    }

    /// ファイル名が書きかけのファイルの名前(`<識別子>.json.tmp`)なら、それを置き換える先の保存物のファイルのパス。
    pub(crate) fn 書きかけに対応するファイル(
        &self,
        ファイル名: &str,
    ) -> Option<PathBuf> {
        let 保存物のファイル名 = ファイル名.strip_suffix(書きかけの印)?;
        let 拡張子 = 保存物のファイル名.rsplit_once('.')?.1;
        (拡張子 == 保存物のファイルの拡張子).then(|| self.0.join(保存物のファイル名))
    }
}
