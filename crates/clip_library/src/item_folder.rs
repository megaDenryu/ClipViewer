//! 保存物のファイルの読み書き係。ライブラリの保存物(スタックか重ね合わせ)1つを `<識別子>.json` の1ファイルに書き、書き込みの途中は
//! `<識別子>.json.tmp` に書くフォルダについて、名前の規則と、書きかけを経て置き換える書き込みと、保存物のファイルの並びを1箇所に閉じる。
//! 置き去りの書きかけの片付けは `pre_scan_cleanup.rs` に置く。スタックのフォルダと重ね合わせのフォルダ(`overlays`)が同じ規則を使う。
//! 参照: _doc/設計/ライブラリ.md 判断2・判断3、_doc/設計/同時再生.md 4-2

use std::io;
use std::path::{Path, PathBuf};

use clip_domain::ライブラリのファイルの本文;

use crate::item_id::ライブラリの保存物の識別子;

/// 保存物のファイルの拡張子。一覧はこの拡張子のファイルだけを読む。
const 保存物のファイルの拡張子: &str = "json";

/// 書きかけのファイルの印。保存物のファイルの名前の後ろに足す。
const 書きかけの印: &str = ".tmp";

/// 書き換えの失敗とは、書きかけのファイルへ書けなかったか、書き切った書きかけで保存物のファイルを置き換えられなかったかの区別のことである。
#[derive(Debug)]
pub(crate) enum 書き換えの失敗 {
    書けない {
        パス: PathBuf,
        原因: io::Error,
    },
    置き換えられない {
        置き場所: PathBuf,
        書きかけ: PathBuf,
        原因: io::Error,
    },
}

/// 保存物のファイルの読み書き係とは、保存物のファイルを置くフォルダを借りて、その中の名前の規則と読み書きを行うもののことである。
pub(crate) struct 保存物のファイルの読み書き係<'フォルダ>(&'フォルダ Path);

impl<'フォルダ> 保存物のファイルの読み書き係<'フォルダ> {
    pub(crate) fn 作成する(フォルダ: &'フォルダ Path) -> Self {
        Self(フォルダ)
    }

    /// 保存物のファイルを置くフォルダのパス。
    pub(crate) fn フォルダ(&self) -> &'フォルダ Path {
        self.0
    }

    /// 保存物のファイルのパス。
    pub(crate) fn ファイルのパス(
        &self,
        識別子: &impl ライブラリの保存物の識別子,
    ) -> PathBuf {
        self.0.join(format!(
            "{}.{保存物のファイルの拡張子}",
            識別子.ファイル名の本体()
        ))
    }

    /// 書きかけのファイルのパス。書き終えたら保存物のファイルへ置き換える。
    pub(crate) fn 書きかけのパス(
        &self,
        識別子: &impl ライブラリの保存物の識別子,
    ) -> PathBuf {
        self.0.join(format!(
            "{}.{保存物のファイルの拡張子}{書きかけの印}",
            識別子.ファイル名の本体()
        ))
    }

    /// 本文を書きかけのファイルへ書いて記憶装置まで書き切ってから、保存物のファイルへ置き換える。フォルダが無ければ作る。
    /// 書いている途中で落ちても元のファイルは壊れず、書きかけのファイルが残るだけである。置き換えに失敗したときは書きかけのパスを返す
    /// (初めての保存では書きかけが唯一の写しになり、利用者が拾い出せるようにするため)。
    pub(crate) fn 書き切って置き換える(
        &self,
        識別子: &impl ライブラリの保存物の識別子,
        本文: &ライブラリのファイルの本文,
    ) -> Result<(), 書き換えの失敗> {
        std::fs::create_dir_all(self.0).map_err(|原因| 書き換えの失敗::書けない {
            パス: self.0.to_path_buf(),
            原因,
        })?;
        let 書きかけ = self.書きかけのパス(識別子);
        let 置き場所 = self.ファイルのパス(識別子);
        書きかけのファイルへ書き切る(&書きかけ, 本文.文字列()).map_err(|原因| {
            書き換えの失敗::書けない {
                パス: 書きかけ.clone(),
                原因,
            }
        })?;
        std::fs::rename(&書きかけ, &置き場所).map_err(|原因| {
            書き換えの失敗::置き換えられない {
                置き場所,
                書きかけ,
                原因,
            }
        })
    }

    /// フォルダの直下の、拡張子が json のファイルのパスを並べる。書きかけとほかの拡張子のファイルとサブフォルダは含めない。
    /// フォルダがまだ無ければ空である。
    pub(crate) fn 保存物のファイルを並べる(&self) -> io::Result<Vec<PathBuf>> {
        let フォルダの中の並び = match std::fs::read_dir(self.0) {
            Ok(並び) => 並び,
            Err(原因) if 原因.kind() == io::ErrorKind::NotFound => return Ok(Vec::new()),
            Err(原因) => return Err(原因),
        };
        let mut 並び = Vec::new();
        for フォルダの中の項目 in フォルダの中の並び {
            let パス = フォルダの中の項目?.path();
            if パス
                .extension()
                .is_some_and(|拡張子| 拡張子 == 保存物のファイルの拡張子)
                && パス.is_file()
            {
                並び.push(パス);
            }
        }
        Ok(並び)
    }

    /// ファイル名が書きかけのファイルの名前(`<識別子>.json.tmp`)なら、それを置き換える先の保存物のファイルのパス。
    pub(crate) fn 書きかけに対応するファイル(
        &self,
        ファイル名: &str,
    ) -> Option<PathBuf> {
        let 保存物のファイル名 = ファイル名.strip_suffix(書きかけの印)?;
        let 拡張子 = 保存物のファイル名.rsplit_once('.')?.1;
        (拡張子 == 保存物のファイルの拡張子).then(|| self.0.join(保存物のファイル名))
    }
}

/// 書きかけのファイルへ本文を書き、OS の書き込みの溜めから記憶装置まで書き切る(sync_all)。
/// 書き切らずに置き換えると、電源が落ちたときに置き換えた後のファイルが空や途中になることがあるためである。
fn 書きかけのファイルへ書き切る(パス: &Path, 本文: &str) -> io::Result<()> {
    let mut ファイル = std::fs::File::create(パス)?;
    io::Write::write_all(&mut ファイル, 本文.as_bytes())?;
    ファイル.sync_all()
}
