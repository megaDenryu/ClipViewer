//! ライブラリの一覧の型。一覧の項目(読めたスタックと読めないファイル)と動画の有無を持つ。走査は `scan.rs` が行う。

use clip_domain::ライブラリのスタック;

/// ライブラリのファイル名とは、ライブラリのフォルダの中のファイルの名前(拡張子を含む)のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ライブラリのファイル名(String);

impl ライブラリのファイル名 {
    /// ファイル名の文字列から作る。
    pub fn 作成する(ファイル名: String) -> Self {
        Self(ファイル名)
    }

    /// ファイル名の文字列。表示で使う。
    pub fn 文字列(&self) -> &str {
        &self.0
    }
}

/// 動画の有無とは、スタックの動画のパスにファイルがあるか、無いかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 動画の有無 {
    /// 動画のパスにファイルがある。
    ある,
    /// 動画のパスにファイルが無い(移動した・消した・別の計算機のパス)。
    見つからない,
}

/// 読めたスタックとは、一覧の走査で読めたライブラリのスタックと、その動画の有無の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub struct 読めたスタック {
    /// 読めたスタック。
    pub スタック: ライブラリのスタック,
    /// 走査したときの動画の有無。
    pub 動画: 動画の有無,
}

/// 読めないファイルとは、一覧の走査で読めなかったスタックのファイルと、読めなかった理由の文の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub struct 読めないファイル {
    /// 読めなかったファイルの名前。
    pub ファイル名: ライブラリのファイル名,
    /// 読めなかった理由(表示用の文)。
    pub 理由: String,
}

/// 一覧の項目とは、ライブラリのフォルダの中のスタックのファイル1つを読んだ結果の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub enum 一覧の項目 {
    /// スタックとして読めた。
    読めた(読めたスタック),
    /// 読めなかった。一覧に出して、黙って飛ばさない。
    読めない(読めないファイル),
}

/// ライブラリの一覧とは、ライブラリのフォルダの中の、拡張子が json のファイルをすべて読んだ結果の並びのことである。
/// 並びの順はフォルダを読んだ順であり、見せる順は画面が決める。書きかけのファイル(`.json.tmp`)とほかの拡張子のファイルは、
/// スタックのファイルでないため含めない。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct ライブラリの一覧 {
    /// 読んだファイルごとの項目。
    pub 項目: Vec<一覧の項目>,
}
