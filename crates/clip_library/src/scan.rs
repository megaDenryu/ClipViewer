//! ライブラリの一覧の走査。フォルダの `*.json` をすべて読んで一覧を作り、読めないファイルは理由付きの項目にする。
//! 索引のファイルを持たないため、一覧とファイルの中身が食い違うことはない。読む手順は重ね合わせの走査と共に使う(`item_read.rs`)。

use clip_domain::ライブラリのスタック;

use crate::library::{スタックのライブラリ, ライブラリの操作エラー};
use crate::listing::{
    ライブラリの一覧, 一覧の項目, 動画の有無, 読めたスタック
};

impl スタックのライブラリ {
    /// フォルダの `*.json` をすべて読んで一覧を作る。フォルダがまだ無ければ空の一覧である。
    pub fn 一覧を作る(
        &self,
    ) -> Result<ライブラリの一覧, ライブラリの操作エラー> {
        let 読んだ並び = self
            .フォルダ()
            .置き方()
            .項目のファイルを全部読む::<ライブラリのスタック>()?;
        Ok(ライブラリの一覧 {
            項目: 読んだ並び
                .into_iter()
                .map(|読んだ| match 読んだ {
                    Ok(スタック) => 一覧の項目::読めた(読めたスタック {
                        動画: 動画の有無::確かめる(スタック.動画のパス()),
                        スタック,
                    }),
                    Err(読めない) => 一覧の項目::読めない(読めない),
                })
                .collect(),
        })
    }
}
