//! ライブラリの一覧の走査。フォルダの `*.json` をすべて読んで一覧を作り、読めないファイルは理由付きの項目にする。
//! 索引のファイルを持たないため、一覧とファイルの中身が食い違うことはない。

use std::path::Path;

use clip_domain::{スタックの識別子, 正規化した動画パス};

use crate::error::ライブラリの操作エラー;
use crate::library::{スタックのライブラリ, ファイルの本文を読む};
use crate::listing::{
    ライブラリのファイル名, ライブラリの一覧, 一覧の項目, 動画の有無, 読めたスタック,
    読めないファイル,
};

impl スタックのライブラリ {
    /// フォルダの `*.json` をすべて読んで一覧を作る。フォルダがまだ無ければ空の一覧である。
    pub fn 一覧を作る(
        &self,
    ) -> Result<ライブラリの一覧, ライブラリの操作エラー> {
        let 置き方 = self.フォルダ().置き方();
        let 並び = 置き方.項目のファイルを並べる().map_err(|原因| {
            ライブラリの操作エラー::読み書きのエラー(置き方.フォルダ(), 原因)
        })?;
        Ok(ライブラリの一覧 {
            項目: 並び
                .iter()
                .map(|パス| ファイルを一覧の項目にする(パス))
                .collect(),
        })
    }
}

/// スタックのファイル1つを読んで一覧の項目にする。ファイル名から識別子を読めなければ読めない項目にする。
fn ファイルを一覧の項目にする(パス: &Path) -> 一覧の項目 {
    let ファイル名 = ライブラリのファイル名::作成する(
        パス
            .file_name()
            .map_or_else(String::new, |名前| 名前.to_string_lossy().into_owned()),
    );
    let 拡張子を除いた名前 = パス
        .file_stem()
        .map_or_else(String::new, |拡張子を除いた名前| {
            拡張子を除いた名前.to_string_lossy().into_owned()
        });
    let 読んだ = スタックの識別子::文字列から作成する(拡張子を除いた名前)
        .map_err(|不備| 不備.to_string())
        .and_then(|識別子| {
            let 本文 = std::fs::read_to_string(パス).map_err(|原因| 原因.to_string())?;
            ファイルの本文を読む(&識別子, 本文).map_err(|エラー| エラー.to_string())
        });
    match 読んだ {
        Ok(スタック) => 一覧の項目::読めた(読めたスタック {
            動画: 動画を確かめる(スタック.動画のパス()),
            スタック,
        }),
        Err(理由) => 一覧の項目::読めない(読めないファイル {
            ファイル名, 理由
        }),
    }
}

/// 動画のパスにファイルがあるかを確かめる。空のパスは見つからないとする。
fn 動画を確かめる(パス: &正規化した動画パス) -> 動画の有無 {
    if !パス.空か() && Path::new(パス.文字列()).is_file() {
        動画の有無::ある
    } else {
        動画の有無::見つからない
    }
}
