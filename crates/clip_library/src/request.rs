//! ライブラリへの頼み(裏のスレッドに行わせる操作)と、裏のスレッドから返る知らせ。

use clip_domain::{
    スタックの名前, スタックの識別子, ライブラリのスタック, ライブラリの日時, 正規化した動画パス,
};

use crate::library::{スタックのライブラリ, ライブラリの操作エラー};
use crate::listing::ライブラリの一覧;

/// 保存の番号とは、同じ画面から頼んだ保存を頼んだ順に区別する番号のことである。
/// 保存の知らせがどの頼みの結果かを、画面が突き合わせるために使う。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Default)]
pub struct 保存の番号(u64);

impl 保存の番号 {
    /// 次の番号。
    pub fn 次(self) -> Self {
        Self(self.0.saturating_add(1))
    }
}

/// 変更の種類とは、保存以外のライブラリのスタックを変える頼みのどれを行ったかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 変更の種類 {
    /// 名前を変えた。
    名前を変えた,
    /// 複製した。
    複製した,
    /// 動画の場所を変えた。
    動画の場所を変えた,
    /// 削除した。
    削除した,
}

/// ライブラリへの頼みとは、裏のスレッドに順に行わせる、ライブラリへの1つの操作のことである。
#[derive(Debug, Clone)]
pub enum ライブラリへの頼み {
    /// スタックを保存する。
    保存する(ライブラリのスタック, 保存の番号),
    /// 名前を変える。
    名前を変える(スタックの識別子, スタックの名前, ライブラリの日時),
    /// 元の識別子のスタックを新しい識別子へ複製する。
    複製する(スタックの識別子, スタックの識別子, ライブラリの日時),
    /// 動画の場所を変える。
    動画の場所を変える(スタックの識別子, 正規化した動画パス, ライブラリの日時),
    /// 削除する。
    削除する(スタックの識別子),
    /// フォルダを読んで一覧を作る。
    一覧を作る,
}

/// ライブラリからの知らせとは、裏のスレッドが頼みを1つ行った結果のことである。
#[derive(Debug)]
pub enum ライブラリからの知らせ {
    /// 保存を行った。
    保存した(
        スタックの識別子,
        保存の番号,
        Result<(), ライブラリの操作エラー>,
    ),
    /// 保存以外の変更を行った。成功したときは、変えた後のスタック(削除なら無い)を持つ。
    変えた(
        変更の種類,
        スタックの識別子,
        Result<Option<ライブラリのスタック>, ライブラリの操作エラー>,
    ),
    /// 一覧を作った。
    一覧を作った(Result<ライブラリの一覧, ライブラリの操作エラー>),
}

impl ライブラリへの頼み {
    /// ライブラリのファイルを書く(作る・変える・消す)頼みか。一覧を作る頼みだけが書かない。
    pub fn 書き込むか(&self) -> bool {
        !matches!(self, Self::一覧を作る)
    }

    /// ライブラリに対して頼みを行い、知らせを返す。
    pub fn 行う(
        self, ライブラリ: &スタックのライブラリ
    ) -> ライブラリからの知らせ {
        let 変えた = |種類, 識別子, 結果: Result<ライブラリのスタック, _>| {
            ライブラリからの知らせ::変えた(種類, 識別子, 結果.map(Some))
        };
        match self {
            Self::保存する(スタック, 番号) => {
                let 結果 = ライブラリ.保存する(&スタック);
                ライブラリからの知らせ::保存した(
                    スタック.識別子().clone(),
                    番号,
                    結果,
                )
            }
            Self::名前を変える(識別子, 名前, 今) => {
                let 結果 = ライブラリ.名前を変える(&識別子, 名前, 今);
                変えた(変更の種類::名前を変えた, 識別子, 結果)
            }
            Self::複製する(元, 新しい識別子, 今) => {
                let 結果 = ライブラリ.複製する(&元, 新しい識別子, 今);
                変えた(変更の種類::複製した, 元, 結果)
            }
            Self::動画の場所を変える(識別子, パス, 今) => {
                let 結果 = ライブラリ.動画の場所を変える(&識別子, パス, 今);
                変えた(変更の種類::動画の場所を変えた, 識別子, 結果)
            }
            Self::削除する(識別子) => {
                let 結果 = ライブラリ.削除する(&識別子).map(|()| None);
                ライブラリからの知らせ::変えた(変更の種類::削除した, 識別子, 結果)
            }
            Self::一覧を作る => {
                ライブラリからの知らせ::一覧を作った(ライブラリ.一覧を作る())
            }
        }
    }
}
