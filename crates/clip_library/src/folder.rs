//! ライブラリのフォルダ。スタックのファイルと書きかけのファイルの置き方を1箇所に閉じる。

use std::path::{Path, PathBuf};

use clip_domain::スタックの識別子;

/// スタックのファイルの拡張子。一覧はこの拡張子のファイルだけを読む。
pub(crate) const スタックのファイルの拡張子: &str = "json";

/// 書きかけのファイルの拡張子。スタックのファイルの名前の後ろに足す。
const 書きかけの印: &str = ".tmp";

/// ライブラリのフォルダとは、スタックのライブラリのファイルを置くフォルダのことである。
/// スタック1つを `<識別子>.json` の1ファイルに書き、書き込みの途中は `<識別子>.json.tmp` に書く。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ライブラリのフォルダ(PathBuf);

impl ライブラリのフォルダ {
    /// フォルダのパスから作る。フォルダがまだ無くてもよい(最初の保存で作る)。
    pub fn 作成する(パス: PathBuf) -> Self {
        Self(パス)
    }

    /// フォルダのパス。std::fs へ渡す境界と表示で使う。
    pub fn パス(&self) -> &Path {
        &self.0
    }

    /// スタックのファイルのパス。
    pub(crate) fn スタックのファイルのパス(
        &self,
        識別子: &スタックの識別子,
    ) -> PathBuf {
        self.0
            .join(format!("{}.{スタックのファイルの拡張子}", 識別子.文字列()))
    }

    /// 書きかけのファイルのパス。書き終えたらスタックのファイルへ置き換える。
    pub(crate) fn 書きかけのファイルのパス(
        &self,
        識別子: &スタックの識別子,
    ) -> PathBuf {
        self.0.join(format!(
            "{}.{スタックのファイルの拡張子}{書きかけの印}",
            識別子.文字列()
        ))
    }

    /// ファイル名が書きかけのファイルの名前(`<識別子>.json.tmp`)なら、それを置き換える先のスタックのファイルのパス。
    pub(crate) fn 書きかけに対応するスタックのファイル(
        &self,
        ファイル名: &str,
    ) -> Option<PathBuf> {
        let スタックのファイル名 = ファイル名.strip_suffix(書きかけの印)?;
        let 拡張子 = スタックのファイル名.rsplit_once('.')?.1;
        (拡張子 == スタックのファイルの拡張子).then(|| self.0.join(スタックのファイル名))
    }
}
