//! ライブラリのフォルダ。スタックのファイルを直下に置き、重ね合わせのファイルをサブフォルダ `overlays` に置く。
//! 名前の規則と書き込みの手順は保存物のファイルの読み書き係(`item_folder.rs`)に閉じ、このフォルダはそれを貸す。

use std::path::{Path, PathBuf};

use crate::item_folder::保存物のファイルの読み書き係;

/// ライブラリのフォルダとは、スタックのライブラリのファイルを置くフォルダのことである。
/// スタック1つを `<識別子>.json` の1ファイルに書き、書き込みの途中は `<識別子>.json.tmp` に書く。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ライブラリのフォルダ(PathBuf);

impl ライブラリのフォルダ {
    /// フォルダのパスから作る。フォルダがまだ無くてもよい(最初の保存で作る)。
    pub fn 作成する(パス: PathBuf) -> Self {
        Self(パス)
    }

    /// フォルダのパス。std::fs へ渡す境界と表示で使う。
    pub fn パス(&self) -> &Path {
        &self.0
    }

    /// スタックのファイルの置き方。
    pub(crate) fn 置き方(&self) -> 保存物のファイルの読み書き係<'_> {
        保存物のファイルの読み書き係::作成する(&self.0)
    }
}
