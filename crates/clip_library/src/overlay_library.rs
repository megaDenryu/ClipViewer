//! 重ね合わせのライブラリ。重ね合わせのフォルダを保持し、重ね合わせ1つのファイルを保存する・読む。
//! 書き込み(一時ファイルへ書いてから置き換える)と読めないファイルの扱いは、スタックのファイルと同じ手順(`item_read.rs`)で行う(ライブラリ.md 判断2・3)。
//! 参照: _doc/設計/同時再生.md 4-2

use clip_domain::{
    ライブラリの重ね合わせ, 重ね合わせのファイルの読み込みエラー, 重ね合わせの識別子,
};

use crate::item_error::項目の操作エラー;
use crate::overlay_folder::重ね合わせのフォルダ;

/// 重ね合わせのライブラリの操作エラーとは、重ね合わせのフォルダの読み書きや、重ね合わせのファイルの中身の変換ができなかった理由のことである。
pub type 重ね合わせのライブラリの操作エラー =
    項目の操作エラー<重ね合わせの識別子, 重ね合わせのファイルの読み込みエラー>;

/// 重ね合わせのライブラリとは、重ね合わせのフォルダを保持し、その中の重ね合わせのファイルを読み書きするもののことである。
/// 同じフォルダを2つの値から同時に書かない前提で作る(書き込みを順に行うのは `裏で動く重ね合わせのライブラリ`)。
#[derive(Debug, Clone)]
pub struct 重ね合わせのライブラリ {
    フォルダ: 重ね合わせのフォルダ,
}

impl 重ね合わせのライブラリ {
    /// 重ね合わせのフォルダから作る。
    pub fn 作成する(フォルダ: 重ね合わせのフォルダ) -> Self {
        Self { フォルダ }
    }

    /// 重ね合わせのフォルダ。
    pub fn フォルダ(&self) -> &重ね合わせのフォルダ {
        &self.フォルダ
    }

    /// 重ね合わせを保存する。書きかけのファイルへ書いて記憶装置まで書き切ってから、重ね合わせのファイルへ置き換える。
    /// 置き換えに失敗したときは失敗として返し、理由の文に書きかけのファイルのパスを入れる。
    pub fn 保存する(
        &self,
        登録した: &ライブラリの重ね合わせ,
    ) -> Result<(), 重ね合わせのライブラリの操作エラー> {
        self.フォルダ.置き方().項目を保存する(登録した)
    }

    /// 識別子の重ね合わせを読む。中身の識別子がファイル名の識別子と違えば読めないとする。
    pub fn 読む(
        &self,
        識別子: &重ね合わせの識別子,
    ) -> Result<ライブラリの重ね合わせ, 重ね合わせのライブラリの操作エラー> {
        self.フォルダ.置き方().項目を読む(識別子)
    }
}
