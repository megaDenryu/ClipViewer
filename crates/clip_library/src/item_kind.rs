//! ライブラリの保存物。ライブラリのスタックとライブラリの重ね合わせを、保存物のファイルの読み書き(`item_read.rs`)が同じ手順で扱えるようにする。

use std::fmt;

use clip_domain::{
    スタックの識別子, ライブラリのスタック, ライブラリのファイルの書き出しエラー,
    ライブラリのファイルの本文, ライブラリのファイルの読み込みエラー, ライブラリの重ね合わせ,
    重ね合わせのファイルの読み込みエラー, 重ね合わせの識別子,
};

use crate::item_id::ライブラリの保存物の識別子;

/// ライブラリの保存物とは、ライブラリのフォルダの中のファイル1つに書く単位(ライブラリのスタックかライブラリの重ね合わせ)のことである。
pub(crate) trait ライブラリの保存物: Sized {
    /// 保存物を指す識別子。
    type 識別子: ライブラリの保存物の識別子;
    /// 本文から保存物を読めなかった理由。
    type 読み込みエラー: fmt::Display + fmt::Debug;
    /// ファイルの本文から読む。
    fn 本文から読む(
        本文: &ライブラリのファイルの本文,
    ) -> Result<Self, Self::読み込みエラー>;
    /// ファイルの本文へ書き出す。
    fn 本文へ書く(
        &self,
    ) -> Result<ライブラリのファイルの本文, ライブラリのファイルの書き出しエラー>;
    /// 保存物の識別子。
    fn 保存物の識別子(&self) -> &Self::識別子;
}

impl ライブラリの保存物 for ライブラリのスタック {
    type 識別子 = スタックの識別子;
    type 読み込みエラー = ライブラリのファイルの読み込みエラー;

    fn 本文から読む(
        本文: &ライブラリのファイルの本文,
    ) -> Result<Self, Self::読み込みエラー> {
        Self::本文から読み込む(本文)
    }

    fn 本文へ書く(
        &self,
    ) -> Result<ライブラリのファイルの本文, ライブラリのファイルの書き出しエラー> {
        self.本文へ書き出す()
    }

    fn 保存物の識別子(&self) -> &スタックの識別子 {
        self.識別子()
    }
}

impl ライブラリの保存物 for ライブラリの重ね合わせ {
    type 識別子 = 重ね合わせの識別子;
    type 読み込みエラー = 重ね合わせのファイルの読み込みエラー;

    fn 本文から読む(
        本文: &ライブラリのファイルの本文,
    ) -> Result<Self, Self::読み込みエラー> {
        Self::本文から読み込む(本文)
    }

    fn 本文へ書く(
        &self,
    ) -> Result<ライブラリのファイルの本文, ライブラリのファイルの書き出しエラー> {
        self.本文へ書き出す()
    }

    fn 保存物の識別子(&self) -> &重ね合わせの識別子 {
        self.識別子()
    }
}
