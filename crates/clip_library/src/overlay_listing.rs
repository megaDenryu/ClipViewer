//! 重ね合わせの一覧の型と走査。重ね合わせのフォルダの `*.json` をすべて読んで一覧を作り、読めないファイルは理由付きの項目にする。
//! 読めないファイルの型と動画の有無の型は、スタックの一覧と同じものを使う。参照: _doc/設計/同時再生.md 4-2、_doc/設計/ライブラリ.md 判断3

use clip_domain::ライブラリの重ね合わせ;

use crate::listing::{動画の有無, 読めないファイル};
use crate::overlay_library::{
    重ね合わせのライブラリ, 重ね合わせのライブラリの操作エラー
};

/// 読めた重ね合わせとは、一覧の走査で読めたライブラリの重ね合わせと、使う動画の表の動画ごとの有無の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub struct 読めた重ね合わせ {
    /// 読めた重ね合わせ。
    pub 重ね合わせ: ライブラリの重ね合わせ,
    /// 走査したときの、使う動画の表の番号の順の動画の有無。
    pub 動画の有無の並び: Vec<動画の有無>,
}

/// 重ね合わせの一覧の項目とは、重ね合わせのフォルダの中の重ね合わせのファイル1つを読んだ結果の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub enum 重ね合わせの一覧の項目 {
    /// 重ね合わせとして読めた。
    読めた(読めた重ね合わせ),
    /// 読めなかった。一覧に出して、黙って飛ばさない。
    読めない(読めないファイル),
}

/// 重ね合わせの一覧とは、重ね合わせのフォルダの中の、拡張子が json のファイルをすべて読んだ結果の並びのことである。
/// 並びの順はフォルダを読んだ順であり、見せる順は画面が決める。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct 重ね合わせの一覧 {
    /// 読んだファイルごとの項目。
    pub 項目: Vec<重ね合わせの一覧の項目>,
}

impl 重ね合わせのライブラリ {
    /// フォルダの `*.json` をすべて読んで一覧を作る。フォルダがまだ無ければ空の一覧である。錠のファイルは拡張子が違うため含めない。
    pub fn 一覧を作る(
        &self,
    ) -> Result<重ね合わせの一覧, 重ね合わせのライブラリの操作エラー> {
        let 読んだ並び = self
            .フォルダ()
            .置き方()
            .保存物のファイルを全部読む::<ライブラリの重ね合わせ>()?;
        Ok(重ね合わせの一覧 {
            項目: 読んだ並び
                .into_iter()
                .map(|読んだ| match 読んだ {
                    Ok(重ね合わせ) => {
                        重ね合わせの一覧の項目::読めた(読めた重ね合わせ {
                            動画の有無の並び: 重ね合わせ
                                .重ね合わせ()
                                .動画の表()
                                .動画のパスの並び()
                                .iter()
                                .map(動画の有無::確かめる)
                                .collect(),
                            重ね合わせ,
                        })
                    }
                    Err(読めない) => 重ね合わせの一覧の項目::読めない(読めない),
                })
                .collect(),
        })
    }
}
