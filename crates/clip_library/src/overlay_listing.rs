//! 重ね合わせの一覧の型と走査。重ね合わせのフォルダの `*.json` をすべて読んで一覧を作り、読めないファイルは理由付きの項目にする。
//! 読めないファイルの型と動画の有無の型は、スタックの一覧と同じものを使う。参照: _doc/設計/同時再生.md 4-2、_doc/設計/ライブラリ.md 判断3

use std::path::Path;

use clip_domain::{ライブラリの重ね合わせ, 重ね合わせの識別子};

use crate::listing::{動画の有無, 読めないファイル};
use crate::overlay_error::重ね合わせのライブラリの操作エラー;
use crate::overlay_library::{ファイルの本文を読む, 重ね合わせのライブラリ};
use crate::scan::{ファイル名と拡張子を除いた名前, 動画を確かめる};

/// 読めた重ね合わせとは、一覧の走査で読めたライブラリの重ね合わせと、使う動画の表の動画ごとの有無の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub struct 読めた重ね合わせ {
    /// 読めた重ね合わせ。
    pub 重ね合わせ: ライブラリの重ね合わせ,
    /// 走査したときの、使う動画の表の番号の順の動画の有無。
    pub 動画の有無の並び: Vec<動画の有無>,
}

/// 重ね合わせの一覧の項目とは、重ね合わせのフォルダの中の重ね合わせのファイル1つを読んだ結果の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub enum 重ね合わせの一覧の項目 {
    /// 重ね合わせとして読めた。
    読めた(読めた重ね合わせ),
    /// 読めなかった。一覧に出して、黙って飛ばさない。
    読めない(読めないファイル),
}

/// 重ね合わせの一覧とは、重ね合わせのフォルダの中の、拡張子が json のファイルをすべて読んだ結果の並びのことである。
/// 並びの順はフォルダを読んだ順であり、見せる順は画面が決める。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct 重ね合わせの一覧 {
    /// 読んだファイルごとの項目。
    pub 項目: Vec<重ね合わせの一覧の項目>,
}

impl 重ね合わせのライブラリ {
    /// フォルダの `*.json` をすべて読んで一覧を作る。フォルダがまだ無ければ空の一覧である。錠のファイルは拡張子が違うため含めない。
    pub fn 一覧を作る(
        &self,
    ) -> Result<重ね合わせの一覧, 重ね合わせのライブラリの操作エラー> {
        let 置き方 = self.フォルダ().置き方();
        let 並び = 置き方.項目のファイルを並べる().map_err(|原因| {
            重ね合わせのライブラリの操作エラー::読み書きのエラー(
                置き方.フォルダ(),
                原因,
            )
        })?;
        Ok(重ね合わせの一覧 {
            項目: 並び
                .iter()
                .map(|パス| ファイルを一覧の項目にする(パス))
                .collect(),
        })
    }
}

/// 重ね合わせのファイル1つを読んで一覧の項目にする。ファイル名から識別子を読めなければ読めない項目にする。
fn ファイルを一覧の項目にする(パス: &Path) -> 重ね合わせの一覧の項目 {
    let (ファイル名, 拡張子を除いた名前) = ファイル名と拡張子を除いた名前(パス);
    let 読んだ = 重ね合わせの識別子::文字列から作成する(拡張子を除いた名前)
        .map_err(|不備| 不備.to_string())
        .and_then(|識別子| {
            let 本文 = std::fs::read_to_string(パス).map_err(|原因| 原因.to_string())?;
            ファイルの本文を読む(&識別子, 本文).map_err(|エラー| エラー.to_string())
        });
    match 読んだ {
        Ok(重ね合わせ) => 重ね合わせの一覧の項目::読めた(読めた重ね合わせ {
            動画の有無の並び: 重ね合わせ
                .重ね合わせ()
                .動画の表()
                .動画のパスの並び()
                .iter()
                .map(動画を確かめる)
                .collect(),
            重ね合わせ,
        }),
        Err(理由) => 重ね合わせの一覧の項目::読めない(読めないファイル {
            ファイル名,
            理由,
        }),
    }
}
