//! 重ね合わせのフォルダ。ライブラリのフォルダの下のサブフォルダ `overlays` であり、重ね合わせのファイルと錠のファイルを置く。
//! ライブラリのフォルダの直下に新しいデータを置かないという互換の約束(ライブラリ.md 8節)に従い、サブフォルダに置く。
//! 今の版のスタックの走査はサブフォルダを読まないため、重ね合わせのファイルを読めない行として出さない。参照: _doc/設計/同時再生.md 4-2

use std::path::{Path, PathBuf};

use crate::folder::ライブラリのフォルダ;
use crate::item_folder::項目のファイルの置き方;

/// 重ね合わせのフォルダの名前。名前と置き場所(ライブラリのフォルダの直下)を変えない(互換の約束)。
const 重ね合わせのフォルダの名前: &str = "overlays";

/// 重ね合わせのフォルダとは、ライブラリのフォルダの下の `overlays` フォルダのことである。重ね合わせ1つを `<識別子>.json` の1ファイルに書き、
/// 書き込みの途中は `<識別子>.json.tmp` に書く。作るメソッドはライブラリのフォルダの `重ね合わせのフォルダ` だけであり、置き場所を取り違えない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 重ね合わせのフォルダ(PathBuf);

impl ライブラリのフォルダ {
    /// このライブラリのフォルダの下の重ね合わせのフォルダ。フォルダがまだ無くてもよい(錠を取るときか最初の保存で作る)。
    pub fn 重ね合わせのフォルダ(&self) -> 重ね合わせのフォルダ {
        重ね合わせのフォルダ(self.パス().join(重ね合わせのフォルダの名前))
    }
}

impl 重ね合わせのフォルダ {
    /// フォルダのパス。std::fs へ渡す境界と表示で使う。
    pub fn パス(&self) -> &Path {
        &self.0
    }

    /// 重ね合わせのファイルの置き方。
    pub(crate) fn 置き方(&self) -> 項目のファイルの置き方<'_> {
        項目のファイルの置き方::作成する(&self.0)
    }
}
