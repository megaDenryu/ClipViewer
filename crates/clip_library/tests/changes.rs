//! 名前の変更・複製・動画の場所の変更の試験。どれもファイルを読み直して変え、同じ置き方で保存する。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::スタックの名前;
use clip_library::ライブラリの操作エラー;
use support::{スタックを作る, 一時のライブラリ, 日時, 識別子};

#[test]
fn 名前を変えてもファイル名は変わらず_更新した日時が進む() {
    let 一時 = 一時のライブラリ::作る("名前");
    let 元 = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&元).expect("保存");
    let 名前 = スタックの名前::作成する("乙".into()).expect("名前");
    一時
        .ライブラリ
        .名前を変える(&識別子("stack-1-1"), 名前, 日時(5_000))
        .expect("変えられる");
    let 読んだ = 一時.ライブラリ.読む(&識別子("stack-1-1")).expect("読める");
    assert_eq!(読んだ.名前().文字列(), "乙");
    assert_eq!(読んだ.更新した日時(), 日時(5_000));
    assert_eq!(読んだ.並び(), 元.並び());
    assert_eq!(一時.ファイル名の一覧(), vec!["stack-1-1.json".to_string()]);
}

#[test]
fn 複製は新しいファイルに同じ動画と並びを書き_既にある識別子へは書かない() {
    let 一時 = 一時のライブラリ::作る("複製");
    let 元 = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&元).expect("保存");
    let 複製 = 一時
        .ライブラリ
        .複製する(&識別子("stack-1-1"), 識別子("stack-2-2"), 日時(9_000))
        .expect("複製できる");
    assert_eq!(複製.名前().文字列(), "甲のコピー");
    assert_eq!(
        一時.ライブラリ.読む(&識別子("stack-2-2")).expect("読める"),
        複製
    );
    assert_eq!(
        一時
            .ライブラリ
            .読む(&識別子("stack-1-1"))
            .expect("元は残る"),
        元
    );
    assert!(matches!(
        一時
            .ライブラリ
            .複製する(&識別子("stack-1-1"), 識別子("stack-2-2"), 日時(9_500)),
        Err(ライブラリの操作エラー::既にある(_))
    ));
}

#[test]
fn 動画の場所を指定し直すと新しいパスを書く() {
    let 一時 = 一時のライブラリ::作る("場所");
    let 元 = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&元).expect("保存");
    let 新しい = 一時.動画を置く("移した.mp4");
    一時
        .ライブラリ
        .動画の場所を変える(&識別子("stack-1-1"), 新しい.clone(), 日時(7_000))
        .expect("変えられる");
    let 読んだ = 一時.ライブラリ.読む(&識別子("stack-1-1")).expect("読める");
    assert_eq!(読んだ.動画のパス(), &新しい);
    assert_eq!(読んだ.作った日時(), 元.作った日時());
}
