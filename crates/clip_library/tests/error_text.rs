//! 項目の操作エラーの文の試験。スタックと重ね合わせが1つの型(`項目の操作エラー`)を使っても、エラーの文はそれぞれの項目の呼び名で出し、
//! スタックの文は1つにまとめる前と変わらないことを確かめる。
#![allow(clippy::expect_used)]

mod support;

use clip_library::{
    ライブラリの操作エラー, 重ね合わせのライブラリの操作エラー
};
use support::overlay::重ね合わせの識別子を作る;
use support::識別子;

#[test]
fn 見つからないと既にあるの文は項目の呼び名で出る() {
    assert_eq!(
        ライブラリの操作エラー::見つからない(識別子("stack-9-9")).to_string(),
        "スタック stack-9-9 のファイルが無い"
    );
    assert_eq!(
        ライブラリの操作エラー::既にある(識別子("stack-9-9")).to_string(),
        "スタック stack-9-9 のファイルが既にある"
    );
    assert_eq!(
        重ね合わせのライブラリの操作エラー::見つからない(
            重ね合わせの識別子を作る("overlay-9-9")
        )
        .to_string(),
        "重ね合わせ overlay-9-9 のファイルが無い"
    );
}
