//! 裏で動くライブラリの試験。頼みを受けた順に行い、知らせを返し、落とすときは頼まれた書き込みを終えてから閉じる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::スタックの名前;
use clip_library::{
    ライブラリからの知らせ, ライブラリへの頼み, 保存の番号, 変更の種類, 裏で動くライブラリ,
};
use support::{スタックを作る, 一時のライブラリ, 日時, 識別子};

#[test]
fn 頼みを順に行い_終えるまで待つと知らせがそろう() {
    let 一時 = 一時のライブラリ::作る("裏で順に");
    let 裏で動くライブラリ = 裏で動くライブラリ::起動する(一時.ライブラリ.clone());
    let スタック = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    let 番号 = 保存の番号::default().次();
    let 名前 = スタックの名前::作成する("乙".into()).expect("名前");
    for 頼み in [
        ライブラリへの頼み::保存する(スタック, 番号),
        ライブラリへの頼み::名前を変える(識別子("stack-1-1"), 名前, 日時(3_000)),
        ライブラリへの頼み::削除する(識別子("stack-1-1")),
        ライブラリへの頼み::一覧を作る,
    ] {
        裏で動くライブラリ.頼む(頼み).expect("送れる");
    }
    裏で動くライブラリ.走査も終えるまで待つ();
    let 知らせ = 裏で動くライブラリ.届いた知らせを受け取る();
    assert_eq!(知らせ.len(), 4, "{知らせ:?}");
    assert!(
        matches!(&知らせ[0], ライブラリからの知らせ::保存した(_, 届いた番号, Ok(())) if *届いた番号 == 番号)
    );
    assert!(matches!(
        &知らせ[1],
        ライブラリからの知らせ::変えた(変更の種類::名前を変えた, _, Ok(Some(変えた))) if 変えた.名前().文字列() == "乙"
    ));
    assert!(matches!(
        &知らせ[2],
        ライブラリからの知らせ::変えた(変更の種類::削除した, _, Ok(None))
    ));
    assert!(
        matches!(&知らせ[3], ライブラリからの知らせ::一覧を作った(Ok(一覧)) if 一覧.項目.is_empty())
    );
}

#[test]
fn 落とすと頼まれた保存を終えてから閉じる() {
    let 一時 = 一時のライブラリ::作る("落とす");
    let 動画 = 一時.動画を置く("a.mp4");
    {
        let 裏で動くライブラリ = 裏で動くライブラリ::起動する(一時.ライブラリ.clone());
        let mut 番号 = 保存の番号::default();
        for 連番 in 0..50 {
            番号 = 番号.次();
            let スタック = スタックを作る(&format!("stack-1-{連番}"), "甲", 動画.clone());
            裏で動くライブラリ
                .頼む(ライブラリへの頼み::保存する(スタック, 番号))
                .expect("送れる");
        }
    }
    let スタックのファイル = 一時
        .ファイル名の一覧()
        .into_iter()
        .filter(|名前| 名前.ends_with(".json"));
    assert_eq!(スタックのファイル.count(), 50);
}
