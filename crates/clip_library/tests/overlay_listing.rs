//! 重ね合わせの一覧の走査の試験。`overlays` の `*.json` をすべて読み、読めたものには動画ごとの有無を付け、読めないものは理由付きの項目にする。
//! 書きかけ・ほかの拡張子・錠のファイルは含めない。フォルダが無ければ空の一覧である。
#![allow(clippy::expect_used)]

mod support;

use clip_library::{動画の有無, 重ね合わせの一覧の項目};
use support::overlay::重ね合わせを作る;
use support::一時のライブラリ;

#[test]
fn フォルダが無ければ空の一覧である() {
    let 一時 = 一時のライブラリ::作る("重ね合わせの一覧が空");
    assert!(
        一時
            .重ね合わせのライブラリ()
            .一覧を作る()
            .expect("作れる")
            .項目
            .is_empty()
    );
}

#[test]
fn 読めたものと読めないものを並べ_書きかけとほかのファイルは含めない() {
    let 一時 = 一時のライブラリ::作る("重ね合わせの一覧");
    let ライブラリ = 一時.重ね合わせのライブラリ();
    let ある動画 = 一時.動画を置く("a.mp4");
    let 無い動画 = clip_domain::入力された動画パス::作成する(
        一時.一時フォルダ.join("無い.mp4").display().to_string(),
    )
    .正規化する();
    for 重ね合わせ in [
        重ね合わせを作る("overlay-1-1", "甲", ある動画),
        重ね合わせを作る("overlay-2-2", "乙", 無い動画),
    ] {
        ライブラリ.保存する(&重ね合わせ).expect("保存できる");
    }
    let フォルダ = ライブラリ.フォルダ().パス();
    std::fs::write(フォルダ.join("overlay-3-3.json"), b"{").expect("置ける");
    std::fs::write(フォルダ.join("overlay-4-4.json.tmp"), b"{").expect("置ける");
    std::fs::write(フォルダ.join("memo.txt"), b"").expect("置ける");
    let mut 項目 = ライブラリ.一覧を作る().expect("作れる").項目;
    項目.sort_by_key(|項目| match 項目 {
        重ね合わせの一覧の項目::読めた(読めた) => {
            読めた.重ね合わせ.識別子().文字列().to_string()
        }
        重ね合わせの一覧の項目::読めない(読めない) => {
            読めない.ファイル名.文字列().to_string()
        }
    });
    assert_eq!(項目.len(), 3, "{項目:?}");
    assert!(matches!(
        &項目[0],
        重ね合わせの一覧の項目::読めた(読めた) if 読めた.動画の有無の並び == [動画の有無::ある]
    ));
    assert!(matches!(
        &項目[1],
        重ね合わせの一覧の項目::読めた(読めた) if 読めた.動画の有無の並び == [動画の有無::見つからない]
    ));
    assert!(matches!(
        &項目[2],
        重ね合わせの一覧の項目::読めない(読めない) if 読めない.ファイル名.文字列() == "overlay-3-3.json"
    ));
}
