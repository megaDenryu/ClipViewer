//! スタックの保存と読み込みと削除の試験。書き込みは書きかけのファイルから置き換え、書きかけのファイルを残さない。
#![allow(clippy::expect_used)]

mod support;

use clip_library::ライブラリの操作エラー;
use support::{スタックを作る, 一時のライブラリ, 日時, 識別子};

#[test]
fn 保存したスタックを読むと同じスタックに戻り_書きかけのファイルは残らない() {
    let 一時 = 一時のライブラリ::作る("保存");
    let スタック = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&スタック).expect("保存できる");
    assert_eq!(
        一時.ライブラリ.読む(&識別子("stack-1-1")).expect("読める"),
        スタック
    );
    assert_eq!(一時.ファイル名の一覧(), vec!["stack-1-1.json".to_string()]);
}

#[test]
fn 同じスタックを保存し直すと置き換わる() {
    let 一時 = 一時のライブラリ::作る("置き換え");
    let スタック = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&スタック).expect("保存できる");
    let 変えた = スタック.名前を変えた(
        clip_domain::スタックの名前::作成する("乙".into()).expect("名前"),
        日時(2_000),
    );
    一時.ライブラリ.保存する(&変えた).expect("保存し直せる");
    assert_eq!(
        一時.ライブラリ.読む(&識別子("stack-1-1")).expect("読める"),
        変えた
    );
    assert_eq!(一時.ファイル名の一覧().len(), 1);
}

#[test]
fn 書きかけのファイルが残っていても次の保存で上書きして置き換える() {
    let 一時 = 一時のライブラリ::作る("書きかけ");
    let スタック = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&スタック).expect("保存できる");
    let 書きかけ = 一時.ライブラリ.フォルダ().パス().join("stack-1-1.json.tmp");
    std::fs::write(&書きかけ, "{途中で落ち").expect("書ける");
    assert_eq!(
        一時
            .ライブラリ
            .読む(&識別子("stack-1-1"))
            .expect("元は壊れない"),
        スタック
    );
    一時.ライブラリ.保存する(&スタック).expect("保存できる");
    assert_eq!(一時.ファイル名の一覧(), vec!["stack-1-1.json".to_string()]);
}

#[test]
fn 削除すると読めなくなり_無いスタックの削除と読み込みは見つからないと返す() {
    let 一時 = 一時のライブラリ::作る("削除");
    let スタック = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&スタック).expect("保存できる");
    一時
        .ライブラリ
        .削除する(&識別子("stack-1-1"))
        .expect("削除できる");
    assert!(matches!(
        一時.ライブラリ.読む(&識別子("stack-1-1")),
        Err(ライブラリの操作エラー::見つからない(_))
    ));
    assert!(matches!(
        一時.ライブラリ.削除する(&識別子("stack-1-1")),
        Err(ライブラリの操作エラー::見つからない(_))
    ));
}

/// ほかのプロセスがスタックのファイルを排他で開いている間は置き換えられず、書きかけのパスを入れた失敗として返す(呼び出し側が頼み直す)。
#[cfg(windows)]
#[test]
fn スタックのファイルを排他で開かれていると保存は失敗を返す() {
    use std::os::windows::fs::OpenOptionsExt;
    let 一時 = 一時のライブラリ::作る("排他");
    let スタック = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&スタック).expect("保存できる");
    let パス = 一時.ライブラリ.フォルダ().パス().join("stack-1-1.json");
    let 排他 = std::fs::OpenOptions::new()
        .read(true)
        .share_mode(0)
        .open(&パス)
        .expect("開ける");
    let エラー = 一時
        .ライブラリ
        .保存する(&スタック)
        .expect_err("置き換えられない");
    assert!(
        matches!(エラー, ライブラリの操作エラー::置き換えられない { .. }),
        "{エラー}"
    );
    assert!(
        エラー.to_string().contains("stack-1-1.json.tmp"),
        "{エラー}"
    );
    drop(排他);
    一時
        .ライブラリ
        .保存する(&スタック)
        .expect("放した後は保存できる");
}
