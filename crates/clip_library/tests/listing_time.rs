//! 数百件の一覧の走査が遅くならないことを、400件の走査の時間で確かめる試験。
//! 上限の5秒は、件数に対して時間が急に増える遅さ(2乗で増える等)を捕まえるためのものである。
//! ウイルス対策が読むファイルを検査する環境では、正しい実装でも400件に約2秒かかる(開発機の %TEMP% で測った)。
#![allow(clippy::expect_used)]

mod support;

use std::time::{Duration, Instant};

use support::{スタックを作る, 一時のライブラリ};

#[test]
fn 四百件の一覧を5秒未満で作る() {
    let 一時 = 一時のライブラリ::作る("四百件");
    let 動画 = 一時.動画を置く("a.mp4");
    for 番号 in 0..400 {
        let スタック = スタックを作る(
            &format!("stack-1-{番号}"),
            &format!("名前{番号}"),
            動画.clone(),
        );
        一時.ライブラリ.保存する(&スタック).expect("保存");
    }
    let 始め = Instant::now();
    let 一覧 = 一時.ライブラリ.一覧を作る().expect("作れる");
    let かかった = 始め.elapsed();
    println!("400件の一覧を作るのにかかった時間: {かかった:?}");
    assert_eq!(一覧.項目.len(), 400);
    assert!(かかった < Duration::from_secs(5), "{かかった:?}");
}
