//! ライブラリの錠の試験。2つ目に起動した裏で動くライブラリは読むだけになり、書き込む頼みを断り、一覧は作れる。
//! 錠を持つ側を落とすと、次に起動したものが錠を取れる。
#![allow(clippy::expect_used)]

mod support;

use clip_library::{
    ライブラリからの知らせ, ライブラリへの頼み, 保存の番号, 書き込みの許し, 裏で動くライブラリ,
    錠を取れない理由, 頼めない理由,
};
use support::{スタックを作る, 一時のライブラリ, 識別子};

#[test]
fn 二つ目は読むだけで書き込む頼みを断り_一覧は作れる() {
    let 一時 = 一時のライブラリ::作る("錠");
    let 一つ目 = 裏で動くライブラリ::起動する(一時.ライブラリ.clone());
    assert!(matches!(一つ目.許し(), 書き込みの許し::書ける(_)));
    let 二つ目 = 裏で動くライブラリ::起動する(一時.ライブラリ.clone());
    assert!(matches!(
        二つ目.許し(),
        書き込みの許し::読むだけ(錠を取れない理由::別のアプリが持っている)
    ));
    let スタック = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    for 頼み in [
        ライブラリへの頼み::保存する(スタック, 保存の番号::default().次()),
        ライブラリへの頼み::削除する(識別子("stack-1-1")),
    ] {
        assert!(matches!(
            二つ目.頼む(頼み),
            Err(頼めない理由::読むだけで開いている)
        ));
    }
    二つ目
        .頼む(ライブラリへの頼み::一覧を作る)
        .expect("一覧は頼める");
    二つ目.走査も終えるまで待つ();
    assert!(matches!(
        二つ目.届いた知らせを受け取る().as_slice(),
        [ライブラリからの知らせ::一覧を作った(Ok(_))]
    ));
}

#[test]
fn 錠を持つ側を落とすと次に起動したものが書ける() {
    let 一時 = 一時のライブラリ::作る("錠を放す");
    let 一つ目 = 裏で動くライブラリ::起動する(一時.ライブラリ.clone());
    drop(一つ目);
    let 次 = 裏で動くライブラリ::起動する(一時.ライブラリ.clone());
    assert!(matches!(次.許し(), 書き込みの許し::書ける(_)));
    assert!(
        一時
            .ライブラリ
            .フォルダ()
            .パス()
            .join("ClipViewer.lock")
            .is_file()
    );
    assert!(
        一時
            .ライブラリ
            .一覧を作る()
            .expect("作れる")
            .項目
            .is_empty(),
        "錠のファイルは一覧に出ない"
    );
}

#[test]
fn 錠を試すと別のアプリが持っているかが分かり_落ちた後に取り直せる() {
    let 一時 = 一時のライブラリ::作る("錠を試す");
    let 一つ目 = 一時.ライブラリ.clone().錠を試す();
    assert!(!一つ目.別のアプリが持っているか());
    let 二つ目 = 一時.ライブラリ.clone().錠を試す();
    assert!(二つ目.別のアプリが持っているか());
    let 二つ目 = 二つ目.錠を取り直す();
    assert!(
        二つ目.別のアプリが持っているか(),
        "一つ目が生きている間は取れない"
    );
    drop(一つ目);
    let 二つ目 = 二つ目.錠を取り直す();
    assert!(matches!(二つ目.許し(), 書き込みの許し::書ける(_)));
    let 裏で動くライブラリ = 裏で動くライブラリ::錠を試した後で起動する(二つ目);
    assert!(matches!(
        裏で動くライブラリ.許し(),
        書き込みの許し::書ける(_)
    ));
}
