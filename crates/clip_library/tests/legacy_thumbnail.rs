//! 以前の版が置いたサムネイルの片付けの試験。書けるアプリは一覧を作る前にライブラリのフォルダの jpg と書きかけの jpg を消し、
//! スタックのファイルと錠のファイルは残す。読み取り専用のアプリは消さない。
#![allow(clippy::expect_used)]

mod support;

use clip_library::{ライブラリへの頼み, 裏で動くライブラリ};
use support::{スタックを作る, 一時のライブラリ};

/// 以前の版の置き方で、スタックのファイルと並べてサムネイルと書きかけのサムネイルを置く。
fn 以前のサムネイルを置く(一時: &一時のライブラリ) {
    let スタック = スタックを作る("stack-1-1", "甲", 一時.動画を置く("a.mp4"));
    一時.ライブラリ.保存する(&スタック).expect("保存");
    let フォルダ = 一時.ライブラリ.フォルダ().パス();
    for 名前 in ["stack-1-1.jpg", "stack-2-2.jpg.tmp"] {
        std::fs::write(フォルダ.join(名前), b"jpeg").expect("置ける");
    }
}

fn 一覧を作らせて待つ(裏で動くライブラリ: &裏で動くライブラリ) {
    裏で動くライブラリ
        .頼む(ライブラリへの頼み::一覧を作る)
        .expect("頼める");
    裏で動くライブラリ.走査も終えるまで待つ();
}

#[test]
fn 書けるアプリは一覧を作る前に以前のサムネイルを消す() {
    let 一時 = 一時のライブラリ::作る("以前のサムネイルを消す");
    以前のサムネイルを置く(&一時);
    let 裏で動くライブラリ = 裏で動くライブラリ::起動する(一時.ライブラリ.clone());
    一覧を作らせて待つ(&裏で動くライブラリ);
    assert_eq!(
        一時.ファイル名の一覧(),
        vec!["ClipViewer.lock".to_string(), "stack-1-1.json".to_string()]
    );
}

#[test]
fn 読み取り専用のアプリは以前のサムネイルを消さない() {
    let 一時 = 一時のライブラリ::作る("以前のサムネイルを消さない");
    以前のサムネイルを置く(&一時);
    let _書ける方 = 一時.ライブラリ.フォルダ().錠を取る().expect("錠を取れる");
    let 読むだけ = 裏で動くライブラリ::起動する(一時.ライブラリ.clone());
    一覧を作らせて待つ(&読むだけ);
    assert!(
        一時
            .ファイル名の一覧()
            .contains(&"stack-1-1.jpg".to_string())
    );
    assert!(
        一時
            .ファイル名の一覧()
            .contains(&"stack-2-2.jpg.tmp".to_string())
    );
}
