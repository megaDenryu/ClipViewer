//! 重ね合わせのライブラリの試験の共有部品。試験用の重ね合わせと、一時フォルダの下の重ね合わせのライブラリを作る。

use clip_domain::*;
use clip_library::{ライブラリのフォルダ, 重ね合わせのライブラリ};

use super::{一時のライブラリ, 日時};

pub fn 重ね合わせの識別子を作る(文字列: &str) -> 重ね合わせの識別子 {
    重ね合わせの識別子::文字列から作成する(文字列.to_string()).expect("識別子")
}

/// 動画1本を表に持ち、0秒から1〜2秒の区間を1回映す置いたクリップを1つ置いた、指定の識別子と名前のライブラリの重ね合わせ。
pub fn 重ね合わせを作る(
    識別子: &str,
    名前: &str,
    動画: 正規化した動画パス,
) -> ライブラリの重ね合わせ {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    let 置いた = 置いたクリップの部品一式 {
        識別子: 置いたクリップの識別子::文字列から作成する(
            format!("{識別子}-p"),
        )
        .expect("識別子"),
        受け継いだ値: クリップから受け継いだ値 {
            名前: クリップ名::作成する("一".into()),
            区間: 動画上の区間::作成する(秒(1.0), 秒(2.0)).expect("区間"),
            リピート回数: リピート回数::一回,
            クロップ: クロップ範囲::全体,
        },
        動画: 動画の番号::最初,
        始まりの時刻: 重ね合わせ上の秒::作成する(0.0).expect("時刻"),
        映す矩形: 映す矩形::全体,
        音の設定: 置いたクリップの音の設定::最初の値,
    };
    let 重ね = 重ね合わせの部品一式 {
        縦横比: 重ねる画面の縦横比::ワイド16対9,
        動画の表: 使う動画の表::一本の動画から作成する(動画),
        行の並び: vec![タイムラインの行の部品一式 {
            置いたクリップの並び: vec![置いた],
        }],
    }
    .重ね合わせへ組み立てる()
    .expect("組み立てられる");
    ライブラリの重ね合わせ::新しく作る(
        重ね合わせの識別子を作る(識別子),
        重ね合わせの名前::作成する(名前.to_string()).expect("名前"),
        重ね,
        日時(1_000),
    )
}

impl 一時のライブラリ {
    /// 同じライブラリのフォルダの下の重ね合わせのライブラリ。
    pub fn 重ね合わせのライブラリ(&self) -> 重ね合わせのライブラリ {
        重ね合わせのライブラリ::作成する(
            self.ライブラリ.フォルダ().重ね合わせのフォルダ(),
        )
    }

    /// 重ね合わせのフォルダの中のファイル名を並べる。
    pub fn 重ね合わせのファイル名の一覧(&self) -> Vec<String> {
        let フォルダ: ライブラリのフォルダ = self.ライブラリ.フォルダ().clone();
        let mut 名前 = std::fs::read_dir(フォルダ.重ね合わせのフォルダ().パス())
            .expect("フォルダを読める")
            .map(|項目| {
                項目
                    .expect("項目")
                    .file_name()
                    .to_string_lossy()
                    .into_owned()
            })
            .collect::<Vec<_>>();
        名前.sort();
        名前
    }
}
