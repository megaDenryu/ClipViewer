//! 裏で動く重ね合わせのライブラリの試験。頼みを受けた順に行って知らせを返し、落とすときは頼まれた保存を終えてから閉じる。
//! 書けるアプリは一覧を作る前に、`overlays` の置き去りの書きかけ(対応するファイルが無く1日より古いもの)だけを消す。
#![allow(clippy::expect_used)]

mod support;

use std::time::{Duration, SystemTime};

use clip_library::{
    保存の番号, 裏で動く重ね合わせのライブラリ, 重ね合わせのライブラリからの知らせ,
    重ね合わせのライブラリへの頼み,
};
use support::overlay::重ね合わせを作る;
use support::一時のライブラリ;

fn 書ける裏で動く重ね合わせのライブラリ(
    一時: &一時のライブラリ,
) -> 裏で動く重ね合わせのライブラリ {
    裏で動く重ね合わせのライブラリ::錠を試した後で起動する(
        一時.ライブラリ.clone().錠を試す().重ね合わせの錠を試す(),
    )
}

#[test]
fn 頼みを順に行い_終えるまで待つと知らせがそろう() {
    let 一時 = 一時のライブラリ::作る("重ね合わせを裏で順に");
    let 裏 = 書ける裏で動く重ね合わせのライブラリ(&一時);
    let 番号 = 保存の番号::default().次();
    let 重ね合わせ = 重ね合わせを作る("overlay-1-1", "甲", 一時.動画を置く("a.mp4"));
    for 頼み in [
        重ね合わせのライブラリへの頼み::保存する(重ね合わせ, 番号),
        重ね合わせのライブラリへの頼み::一覧を作る,
    ] {
        裏.頼む(頼み).expect("送れる");
    }
    裏.走査も終えるまで待つ();
    let 知らせ = 裏.届いた知らせを受け取る();
    assert_eq!(知らせ.len(), 2, "{知らせ:?}");
    assert!(matches!(
        &知らせ[0],
        重ね合わせのライブラリからの知らせ::保存した(識別子, 届いた番号, Ok(()))
            if *届いた番号 == 番号 && 識別子.文字列() == "overlay-1-1"
    ));
    assert!(matches!(
        &知らせ[1],
        重ね合わせのライブラリからの知らせ::一覧を作った(Ok(一覧)) if 一覧.項目.len() == 1
    ));
}

#[test]
fn 落とすと頼まれた保存を終えてから閉じる() {
    let 一時 = 一時のライブラリ::作る("重ね合わせを落とす");
    let 動画 = 一時.動画を置く("a.mp4");
    {
        let 裏 = 書ける裏で動く重ね合わせのライブラリ(&一時);
        let mut 番号 = 保存の番号::default();
        for 連番 in 0..30 {
            番号 = 番号.次();
            let 重ね合わせ =
                重ね合わせを作る(&format!("overlay-1-{連番}"), "甲", 動画.clone());
            裏.頼む(重ね合わせのライブラリへの頼み::保存する(
                重ね合わせ,
                番号,
            ))
            .expect("送れる");
        }
    }
    let 重ね合わせのファイル = 一時
        .重ね合わせのファイル名の一覧()
        .into_iter()
        .filter(|名前| 名前.ends_with(".json"));
    assert_eq!(重ね合わせのファイル.count(), 30);
}

#[test]
fn 書けるアプリは対応するファイルが無く1日より古い書きかけだけを消す() {
    let 一時 = 一時のライブラリ::作る("重ね合わせの書きかけを消す");
    let 裏 = 書ける裏で動く重ね合わせのライブラリ(&一時);
    let 重ね合わせ = 重ね合わせを作る("overlay-1-1", "甲", 一時.動画を置く("a.mp4"));
    裏.頼む(重ね合わせのライブラリへの頼み::保存する(
        重ね合わせ,
        保存の番号::default().次(),
    ))
    .expect("送れる");
    裏.書き込みを終えるまで待つ();
    let フォルダ = 裏.フォルダ().パス();
    for 名前 in [
        "overlay-1-1.json.tmp",
        "overlay-9-9.json.tmp",
        "overlay-8-8.json.tmp",
    ] {
        std::fs::write(フォルダ.join(名前), b"{").expect("置ける");
    }
    let 二日前 = SystemTime::now() - Duration::from_secs(2 * 24 * 60 * 60);
    for 名前 in ["overlay-1-1.json.tmp", "overlay-9-9.json.tmp"] {
        std::fs::File::options()
            .write(true)
            .open(フォルダ.join(名前))
            .and_then(|ファイル| ファイル.set_modified(二日前))
            .expect("書き換えた日時を変えられる");
    }
    裏.頼む(重ね合わせのライブラリへの頼み::一覧を作る)
        .expect("頼める");
    裏.走査も終えるまで待つ();
    assert_eq!(
        一時.重ね合わせのファイル名の一覧(),
        vec![
            "ClipViewer.lock",
            "overlay-1-1.json",
            "overlay-1-1.json.tmp",
            "overlay-8-8.json.tmp",
        ]
    );
}
