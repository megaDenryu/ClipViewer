//! 重ね合わせのライブラリの保存と読み込みの試験。重ね合わせはライブラリのフォルダの下の `overlays` に1つ1ファイルで書き、
//! 読むと同じ値に戻り、スタックの一覧には出ない。無いファイルと、ファイル名と中身の識別子が違うファイルは型付きのエラーで拒む。
#![allow(clippy::expect_used)]

mod support;

use clip_library::重ね合わせのライブラリの操作エラー;
use support::overlay::{重ね合わせの識別子を作る, 重ね合わせを作る};
use support::一時のライブラリ;

#[test]
fn 保存して読むと同じ値に戻り_overlaysフォルダに置かれ_スタックの一覧に出ない() {
    let 一時 = 一時のライブラリ::作る("重ね合わせの保存");
    let 重ね合わせ = 重ね合わせを作る("overlay-1-1", "甲", 一時.動画を置く("a.mp4"));
    let ライブラリ = 一時.重ね合わせのライブラリ();
    ライブラリ.保存する(&重ね合わせ).expect("保存できる");
    assert_eq!(
        ライブラリ
            .読む(&重ね合わせの識別子を作る("overlay-1-1"))
            .expect("読める"),
        重ね合わせ
    );
    assert_eq!(
        一時.重ね合わせのファイル名の一覧(),
        vec!["overlay-1-1.json"]
    );
    assert_eq!(一時.ファイル名の一覧(), vec!["overlays"]);
    assert!(
        一時
            .ライブラリ
            .一覧を作る()
            .expect("作れる")
            .項目
            .is_empty(),
        "スタックの走査はサブフォルダを読まない"
    );
}

#[test]
fn 無い重ね合わせは見つからないとして拒む() {
    let 一時 = 一時のライブラリ::作る("重ね合わせが無い");
    assert!(matches!(
        一時
            .重ね合わせのライブラリ()
            .読む(&重ね合わせの識別子を作る("overlay-9-9")),
        Err(重ね合わせのライブラリの操作エラー::見つからない(識別子)) if 識別子.文字列() == "overlay-9-9"
    ));
}

#[test]
fn ファイル名と中身の識別子が違うと拒む() {
    let 一時 = 一時のライブラリ::作る("重ね合わせの識別子が違う");
    let ライブラリ = 一時.重ね合わせのライブラリ();
    let 重ね合わせ = 重ね合わせを作る("overlay-1-1", "甲", 一時.動画を置く("a.mp4"));
    ライブラリ.保存する(&重ね合わせ).expect("保存できる");
    let フォルダ = ライブラリ.フォルダ().パス();
    std::fs::rename(
        フォルダ.join("overlay-1-1.json"),
        フォルダ.join("overlay-2-2.json"),
    )
    .expect("名前を変えられる");
    assert!(matches!(
        ライブラリ.読む(&重ね合わせの識別子を作る("overlay-2-2")),
        Err(重ね合わせのライブラリの操作エラー::識別子が違う { .. })
    ));
}
