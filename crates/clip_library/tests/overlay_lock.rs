//! 重ね合わせの錠の試験。`overlays` の錠はライブラリの錠を持つアプリだけが試し、持たないアプリは取りに行かずに読むだけになる。
//! 読むだけの裏で動く重ね合わせのライブラリは保存を断り、一覧は作れる。錠を持つ側を落とすと、次に起動したものが取れる。
#![allow(clippy::expect_used)]

mod support;

use clip_library::{
    保存の番号, 裏で動く重ね合わせのライブラリ, 重ね合わせのライブラリからの知らせ,
    重ね合わせのライブラリへの頼み, 重ね合わせの書き込みの許し, 重ね合わせの錠を取れない理由,
    頼めない理由,
};
use support::overlay::重ね合わせを作る;
use support::一時のライブラリ;

#[test]
fn ライブラリの錠を持つアプリだけがoverlaysの錠を取り_二つ目は取りに行かない() {
    let 一時 = 一時のライブラリ::作る("重ね合わせの錠");
    let 一つ目 = 一時.ライブラリ.clone().錠を試す();
    let 一つ目の重ね合わせ = 一つ目.重ね合わせの錠を試す();
    assert!(一つ目の重ね合わせ.書けるか());
    assert!(
        一時
            .ライブラリ
            .フォルダ()
            .重ね合わせのフォルダ()
            .パス()
            .join("ClipViewer.lock")
            .is_file()
    );
    let 二つ目 = 一時.ライブラリ.clone().錠を試す();
    assert!(二つ目.別のアプリが持っているか());
    assert!(matches!(
        二つ目.重ね合わせの錠を試す().許し(),
        重ね合わせの書き込みの許し::読むだけ(
            重ね合わせの錠を取れない理由::ライブラリの錠を持っていない
        )
    ));
    drop((一つ目, 一つ目の重ね合わせ));
    let 次 = 一時.ライブラリ.clone().錠を試す();
    assert!(次.重ね合わせの錠を試す().書けるか());
}

#[test]
fn 読むだけの裏で動く重ね合わせのライブラリは保存を断り_一覧は作れる() {
    let 一時 = 一時のライブラリ::作る("重ね合わせの読むだけ");
    let _一つ目 = 一時.ライブラリ.clone().錠を試す();
    let 二つ目 = 一時.ライブラリ.clone().錠を試す();
    let 読むだけ = 裏で動く重ね合わせのライブラリ::錠を試した後で起動する(
        二つ目.重ね合わせの錠を試す(),
    );
    let 重ね合わせ = 重ね合わせを作る("overlay-1-1", "甲", 一時.動画を置く("a.mp4"));
    assert_eq!(
        読むだけ.頼む(重ね合わせのライブラリへの頼み::保存する(
            重ね合わせ,
            保存の番号::default().次()
        )),
        Err(頼めない理由::読むだけで開いている)
    );
    読むだけ
        .頼む(重ね合わせのライブラリへの頼み::一覧を作る)
        .expect("一覧は頼める");
    読むだけ.走査も終えるまで待つ();
    assert!(matches!(
        読むだけ.届いた知らせを受け取る().as_slice(),
        [重ね合わせのライブラリからの知らせ::一覧を作った(Ok(_))]
    ));
}
