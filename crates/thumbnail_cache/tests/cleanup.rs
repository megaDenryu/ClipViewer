//! サムネイルのキャッシュの片付けの試験。容量の上限を超えたら使った時刻の古いものから消し、落ちたアプリの古い書きかけと古い版の画像は消す。
#![allow(clippy::expect_used)]

mod support;

use std::path::Path;
use std::time::{Duration, SystemTime};

use support::{
    一時のキャッシュ, 画像, 試験の時計の始まり, 開始の違う撮り方
};

#[test]
fn 容量の上限を超えたら使った時刻の古いものから消す() {
    let 一時 = 一時のキャッシュ::作る("容量の上限");
    let キャッシュ = 一時.キャッシュ(250);
    let (甲, 乙, 丙) = (
        開始の違う撮り方(1.0),
        開始の違う撮り方(2.0),
        開始の違う撮り方(3.0),
    );
    // 使った時刻は置いたときと読んだときにキャッシュの時計で進む。甲を読み直すと、先に使ったのは乙になる。
    キャッシュ.置く(&甲, &画像(100)).expect("置ける");
    キャッシュ.置く(&乙, &画像(100)).expect("置ける");
    assert!(キャッシュ.読む(&甲).expect("読める").is_some());
    キャッシュ.置く(&丙, &画像(100)).expect("置ける");
    assert_eq!(
        一時.ファイル名の一覧().len(),
        2,
        "上限の250バイトに収まるまで消す"
    );
    assert!(
        キャッシュ.読む(&乙).expect("読める").is_none(),
        "甲より先に使った乙を消す"
    );
    assert!(キャッシュ.読む(&甲).expect("読める").is_some());
    assert!(キャッシュ.読む(&丙).expect("読める").is_some());
}

#[test]
fn 落ちたアプリの古い書きかけは消し_新しい書きかけは残す() {
    let 一時 = 一時のキャッシュ::作る("書きかけ");
    let キャッシュ = 一時.キャッシュ(1_000_000);
    std::fs::create_dir_all(一時.パス()).expect("フォルダを作れる");
    let 古い = 一時.パス().join("0123.99.tmp");
    let 新しい = 一時.パス().join("4567.98.tmp");
    更新日時を付けて書く(&古い, 試験の時計の始まり - 660);
    更新日時を付けて書く(&新しい, 試験の時計の始まり - 60);
    キャッシュ
        .置く(&開始の違う撮り方(1.0), &画像(10))
        .expect("置ける");
    assert!(!古い.exists(), "10分より古い書きかけは消す");
    assert!(
        新しい.exists(),
        "ほかのアプリが書いている途中かもしれない書きかけは残す"
    );
}

#[test]
fn 古い版の画像は置いたときに消し_今と次の版の画像とほかのファイルは残す() {
    let 一時 = 一時のキャッシュ::作る("古い版");
    let キャッシュ = 一時.キャッシュ(1_000_000);
    std::fs::create_dir_all(一時.パス()).expect("フォルダを作れる");
    let 版の印の無い画像 = 一時.パス().join("0123456789abcdef0123456789abcdef.jpg");
    let 前の版の画像 = 一時.パス().join("0123456789abcdef0123456789abcdef.v3.jpg");
    let 次の版の画像 = 一時.パス().join("0123456789abcdef0123456789abcdef.v5.jpg");
    let ほかのファイル = 一時.パス().join("読んでください.txt");
    for パス in [
        &版の印の無い画像,
        &前の版の画像,
        &次の版の画像,
        &ほかのファイル,
    ] {
        std::fs::write(パス, b"old").expect("書ける");
    }
    let 撮り方 = 開始の違う撮り方(1.0);
    キャッシュ.置く(&撮り方, &画像(10)).expect("置ける");
    assert!(!版の印の無い画像.exists(), "版3以前の名前の画像は消す");
    assert!(!前の版の画像.exists(), "前の版の画像は消す");
    assert!(
        次の版の画像.exists(),
        "新しい版のアプリが置いた画像は消さない(行き来する利用者で消し合わない)"
    );
    assert!(ほかのファイル.exists(), "画像でないファイルは消さない");
    assert!(
        キャッシュ.読む(&撮り方).expect("読める").is_some(),
        "今の版の画像は残す"
    );
}

fn 更新日時を付けて書く(パス: &Path, 紀元からの秒: u64) {
    std::fs::write(パス, b"half").expect("書ける");
    std::fs::File::options()
        .write(true)
        .open(パス)
        .and_then(|ファイル| {
            ファイル.set_modified(SystemTime::UNIX_EPOCH + Duration::from_secs(紀元からの秒))
        })
        .expect("更新日時を置ける");
}
