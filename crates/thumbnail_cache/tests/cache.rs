//! サムネイルのキャッシュの試験。置いたものを読め、無いものと空のものは無いとし、置き場所が無ければ何も持たない。
//! 容量の上限と書きかけの片付けは cleanup.rs で確かめる。
#![allow(clippy::expect_used)]

mod support;

use support::{一時のキャッシュ, 画像, 開始の違う撮り方};
use thumbnail_cache::{
    キャッシュの容量, キャッシュの時計, キャッシュの置き場所, サムネイルのキャッシュ,
    撮り方の要約値,
};

#[test]
fn 置いた画像を読むと同じ画像が返り_書きかけのファイルは残らない() {
    let 一時 = 一時のキャッシュ::作る("置いて読む");
    let キャッシュ = 一時.キャッシュ(1_000_000);
    let 撮り方 = 開始の違う撮り方(1.0);
    assert_eq!(
        キャッシュ.読む(&撮り方).expect("読める"),
        None,
        "置く前は無い"
    );
    キャッシュ.置く(&撮り方, &画像(10)).expect("置ける");
    assert_eq!(キャッシュ.読む(&撮り方).expect("読める"), Some(画像(10)));
    let 名前 = format!(
        "{}.v4.jpg",
        撮り方の要約値::求める(&撮り方).十六進の文字列()
    );
    assert_eq!(一時.ファイル名の一覧(), vec![名前]);
    assert_eq!(
        キャッシュ.読む(&開始の違う撮り方(2.0)).expect("読める"),
        None
    );
}

#[test]
fn 中身が空のファイルは無いとみなして消し_捨てたものは読めない() {
    let 一時 = 一時のキャッシュ::作る("空と捨てる");
    let キャッシュ = 一時.キャッシュ(1_000_000);
    let 撮り方 = 開始の違う撮り方(1.0);
    キャッシュ.置く(&撮り方, &画像(0)).expect("置ける");
    assert_eq!(キャッシュ.読む(&撮り方).expect("読める"), None);
    assert!(一時.ファイル名の一覧().is_empty(), "空のファイルは消す");
    キャッシュ.置く(&撮り方, &画像(10)).expect("置ける");
    キャッシュ.捨てる(&撮り方).expect("捨てられる");
    キャッシュ
        .捨てる(&撮り方)
        .expect("無いものを捨てても失敗しない");
    assert_eq!(キャッシュ.読む(&撮り方).expect("読める"), None);
}

#[test]
fn 置き場所が無いキャッシュは何も持たない() {
    let キャッシュ = サムネイルのキャッシュ::作成する(
        キャッシュの置き場所::使わない,
        キャッシュの容量::既定,
        キャッシュの時計::実時間(),
    );
    let 撮り方 = 開始の違う撮り方(1.0);
    キャッシュ
        .置く(&撮り方, &画像(10))
        .expect("置くことは失敗しない");
    assert_eq!(キャッシュ.読む(&撮り方).expect("読める"), None);
}
