//! サムネイルのキャッシュの試験の道具。試験ごとに重ならない一時フォルダ、撮り方を作ること、進み方を決めた時計。
#![allow(clippy::expect_used, dead_code)]

use std::cell::Cell;
use std::path::PathBuf;
use std::time::{Duration, SystemTime};

use clip_domain::{
    クリップ, クリップスタック, クリップ名, クリップ識別子, クロップ範囲, サムネイルの大きさ,
    サムネイルの撮り方, サムネイルの画像, スタックの名前, スタックの識別子, ライブラリのスタック,
    ライブラリの日時, 入力された動画パス, 動画上の区間, 動画上の秒,
};
use thumbnail_cache::{
    キャッシュのフォルダ, キャッシュの容量, キャッシュの時計, キャッシュの置き場所,
    サムネイルのキャッシュ,
};

/// 全部のバイトが同じ値の、バイト数の長さの画像。中身の形式は問わない(キャッシュは JPEG を解かない)。
pub fn 画像(バイト数: usize) -> サムネイルの画像 {
    サムネイルの画像::作成する(vec![7; バイト数])
}

/// 試験の時計が指し始める時刻(1970年1月1日からの秒)。
pub const 試験の時計の始まり: u64 = 1_800_000_000;

thread_local! {
    /// 試験の時計が返した回数。試験は1つのスレッドで動くため、試験ごとに別の数え方になる。
    static 時計を読んだ回数: Cell<u64> = const { Cell::new(0) };
}

/// 読むたびに1秒ずつ進む時計。実時間の刻みの粗さに左右されずに、使った時刻の順を決めるために使う。
fn 一秒ずつ進む今() -> SystemTime {
    let 回数 = 時計を読んだ回数.with(|回数| {
        回数.set(回数.get() + 1);
        回数.get()
    });
    SystemTime::UNIX_EPOCH + Duration::from_secs(試験の時計の始まり + 回数)
}

/// 試験の一時フォルダ。%LOCALAPPDATA% の本物のフォルダを使わない。落とすと消す。
pub struct 一時のキャッシュ {
    pub フォルダ: キャッシュのフォルダ,
}

impl 一時のキャッシュ {
    pub fn 作る(名前: &str) -> Self {
        let パス =
            std::env::temp_dir().join(format!("thumbnail_cache_{名前}_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&パス);
        Self {
            フォルダ: キャッシュのフォルダ::作成する(パス),
        }
    }

    /// 容量の上限と、読むたびに1秒進む時計を持つキャッシュ。
    pub fn キャッシュ(&self, 上限: u64) -> サムネイルのキャッシュ {
        サムネイルのキャッシュ::作成する(
            キャッシュの置き場所::フォルダ(self.フォルダ.clone()),
            キャッシュの容量::バイト数から作る(上限),
            キャッシュの時計::関数から作る(一秒ずつ進む今),
        )
    }

    /// フォルダの中のファイル名を並べる。
    pub fn ファイル名の一覧(&self) -> Vec<String> {
        let mut 一覧: Vec<String> = std::fs::read_dir(self.フォルダ.パス())
            .map(|フォルダの中の並び| {
                フォルダの中の並び
                    .flatten()
                    .map(|フォルダの中の項目| {
                        フォルダの中の項目
                            .file_name()
                            .to_string_lossy()
                            .into_owned()
                    })
                    .collect()
            })
            .unwrap_or_default();
        一覧.sort();
        一覧
    }

    pub fn パス(&self) -> PathBuf {
        self.フォルダ.パス().to_path_buf()
    }
}

impl Drop for 一時のキャッシュ {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(self.フォルダ.パス());
    }
}

/// 動画のパスと開始とクロップと大きさから撮り方を作る。
pub fn 撮り方(
    動画: &str,
    開始: f64,
    クロップ: クロップ範囲,
    大きさ: (u32, u32),
) -> サムネイルの撮り方 {
    let 識別子 = クリップ識別子::文字列から作成する("a".into()).expect("識別子");
    let mut クリップ =
        クリップ::既定値で作成する(識別子, クリップ名::作成する("一".into()));
    let 秒 = |値| 動画上の秒::作成する(値).expect("秒");
    クリップ.区間 = 動画上の区間::作成する(秒(開始), 秒(開始 + 1.0)).expect("区間");
    クリップ.クロップ = クロップ;
    ライブラリのスタック::新しく作る(
        スタックの識別子::文字列から作成する("stack-1-1".into()).expect("識別子"),
        スタックの名前::作成する("甲".into()).expect("名前"),
        入力された動画パス::作成する(動画.into()).正規化する(),
        クリップスタック::一覧から作成する(vec![クリップ]).expect("並び"),
        ライブラリの日時::紀元,
    )
    .サムネイルの撮り方(サムネイルの大きさ::作成する(大きさ.0, 大きさ.1).expect("大きさ"))
    .expect("撮り方")
}

/// 開始の時刻だけが違う、192x108 の全体のクロップの撮り方。
pub fn 開始の違う撮り方(開始: f64) -> サムネイルの撮り方 {
    撮り方(r"D:\動画\a.mp4", 開始, クロップ範囲::全体, (192, 108))
}
