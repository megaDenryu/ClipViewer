//! 撮り方の要約値の試験。撮り方の各値のどれを変えても別のファイル名になり、同じ撮り方は Rust の版に関わらず同じ名前になる。
//! 同じ画像になる違い(Windows での動画のパスの大文字小文字と区切り文字、0 の符号)は同じ名前になる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::{クロップ範囲, サムネイルの撮り方};
use support::撮り方;
use thumbnail_cache::撮り方の要約値;

fn 要約値の文字列(撮り方: &サムネイルの撮り方) -> String {
    撮り方の要約値::求める(撮り方).十六進の文字列()
}

#[test]
fn 撮り方の各値のどれを変えても別の名前になり_同じ撮り方は同じ名前になる() {
    let 全体 = クロップ範囲::全体;
    let 元 = 撮り方(r"D:\動画\a.mp4", 2.0, 全体, (192, 108));
    assert_eq!(
        要約値の文字列(&元),
        要約値の文字列(&撮り方(r"D:\動画\a.mp4", 2.0, 全体, (192, 108)))
    );
    let クロップ = クロップ範囲::各値を範囲へ収めて作成する;
    let 変えたもの = [
        撮り方(r"D:\動画\b.mp4", 2.0, 全体, (192, 108)),
        撮り方(r"D:\動画\a.mp4", 2.5, 全体, (192, 108)),
        撮り方(
            r"D:\動画\a.mp4",
            2.0,
            クロップ(10.0, 0.0, 90.0, 100.0),
            (192, 108),
        ),
        撮り方(
            r"D:\動画\a.mp4",
            2.0,
            クロップ(0.0, 10.0, 100.0, 90.0),
            (192, 108),
        ),
        撮り方(
            r"D:\動画\a.mp4",
            2.0,
            クロップ(0.0, 0.0, 50.0, 100.0),
            (192, 108),
        ),
        撮り方(
            r"D:\動画\a.mp4",
            2.0,
            クロップ(0.0, 0.0, 100.0, 50.0),
            (192, 108),
        ),
        撮り方(r"D:\動画\a.mp4", 2.0, 全体, (96, 54)),
        撮り方(r"D:\動画\a.mp4", 2.0, 全体, (108, 192)),
    ];
    let mut 要約値の文字列の一覧: Vec<String> = 変えたもの.iter().map(要約値の文字列).collect();
    要約値の文字列の一覧.push(要約値の文字列(&元));
    let 数 = 要約値の文字列の一覧.len();
    要約値の文字列の一覧.sort();
    要約値の文字列の一覧.dedup();
    assert_eq!(要約値の文字列の一覧.len(), 数, "どれも別の名前になる");
    assert_eq!(要約値の文字列(&元).len(), 32);
    assert!(
        要約値の文字列(&元)
            .chars()
            .all(|文字| 文字.is_ascii_hexdigit())
    );
}

#[test]
fn 同じ撮り方の名前は決まった値になる() {
    // 名前が Rust や依存の版で変わると、キャッシュが全部作り直しになる。変わっていないことを決まった値で確かめる。
    // キャッシュの形式の版を上げたときだけ、この値を書き換える。パスは Windows で揃えても変わらない表記にし、どの環境でも同じ値にする。
    let 元 = 撮り方(r"d:\動画\a.mp4", 2.0, クロップ範囲::全体, (192, 108));
    assert_eq!(要約値の文字列(&元), "b5e11a14d018751a78569d67a9e39159");
}

#[test]
fn 零の符号だけが違う撮り方は同じ名前になる() {
    let 正の零 = クロップ範囲::各値を範囲へ収めて作成する(0.0, 0.0, 50.0, 100.0);
    let 負の零 =
        クロップ範囲::各値を範囲へ収めて作成する(-0.0, -0.0, 50.0, 100.0);
    assert_eq!(
        要約値の文字列(&撮り方(r"D:\動画\a.mp4", 0.0, 正の零, (192, 108))),
        要約値の文字列(&撮り方(r"D:\動画\a.mp4", -0.0, 負の零, (192, 108))),
    );
}

#[cfg(windows)]
#[test]
fn windowsでは動画のパスの大文字小文字と区切り文字だけが違う撮り方は同じ名前になる() {
    let 全体 = クロップ範囲::全体;
    assert_eq!(
        要約値の文字列(&撮り方(r"D:\動画\Clip.MP4", 2.0, 全体, (192, 108))),
        要約値の文字列(&撮り方("d:/動画/clip.mp4", 2.0, 全体, (192, 108))),
    );
}
