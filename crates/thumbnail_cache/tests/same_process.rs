//! 同じプロセスの2つの供給が、1つのキャッシュから複製したキャッシュで同じ撮り方を同時に置く試験。書きかけの名前がプロセスの番号で重なっても、
//! 書き込みの錠で1つずつ置くため、どの置き方も失敗せず、置いた画像は読める。参照: _doc/設計/ライブラリ.md 判断11
#![allow(clippy::expect_used)]

mod support;

use std::thread;

use support::{一時のキャッシュ, 画像, 開始の違う撮り方};

/// 1つのスレッドが同じ撮り方を置く回数。
const 置く回数: usize = 50;

#[test]
fn 複製したキャッシュで同じ撮り方を同時に置いても失敗せず_書きかけも残らない() {
    let 一時 = 一時のキャッシュ::作る("同じプロセス");
    let 元 = 一時.キャッシュ(1_000_000);
    let 撮り方 = 開始の違う撮り方(1.0);
    let スレッドの並び: Vec<_> = [3_000, 5_000]
        .into_iter()
        .map(|バイト数| {
            let 複製 = 元.clone();
            let 撮り方 = 撮り方.clone();
            thread::spawn(move || {
                (0..置く回数)
                    .map(|_| 複製.置く(&撮り方, &画像(バイト数)))
                    .collect::<Vec<_>>()
            })
        })
        .collect();
    for スレッド in スレッドの並び {
        for 結果 in スレッド.join().expect("スレッドが終わる") {
            結果.expect("置ける");
        }
    }
    let 読んだ = 元.読む(&撮り方).expect("読める").expect("ある");
    assert!(読んだ == 画像(3_000) || 読んだ == 画像(5_000));
    assert_eq!(一時.ファイル名の一覧().len(), 1, "書きかけは残らない");
}
