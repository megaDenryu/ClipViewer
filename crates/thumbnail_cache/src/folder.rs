//! キャッシュのフォルダ。サムネイルのファイルと書きかけのファイルの置き方を1箇所に閉じる。

use std::ffi::OsStr;
use std::path::{Path, PathBuf};

use crate::format_version::{キャッシュの形式の版, 版の比べた結果};
use crate::summary::撮り方の要約値;

/// サムネイルのファイルの拡張子。刈り込みはこの拡張子のファイルだけを数える。
const 画像の拡張子: &str = "jpg";

/// 書きかけのファイルの拡張子。
const 書きかけの拡張子: &str = "tmp";

/// キャッシュのフォルダとは、サムネイルのキャッシュのファイルを置くフォルダのことである。
/// 撮り方1つを `<要約値>.<キャッシュの形式の版の印>.jpg` の1ファイルに置き、書き込みの途中は `<要約値>.<プロセスの番号>.tmp` に書く。
/// 書きかけの名前にプロセスの番号を入れるのは、2つのアプリが同じ撮り方を同時に撮っても、書きかけのファイルを取り合わないためである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct キャッシュのフォルダ(PathBuf);

impl キャッシュのフォルダ {
    /// フォルダのパスから作る。フォルダがまだ無くてもよい(最初に置くときに作る)。
    pub fn 作成する(パス: PathBuf) -> Self {
        Self(パス)
    }

    /// フォルダのパス。std::fs へ渡す境界と表示で使う。
    pub fn パス(&self) -> &Path {
        &self.0
    }

    /// 撮り方のサムネイルのファイルのパス。
    pub fn 画像のパス(&self, 要約値: 撮り方の要約値) -> PathBuf {
        self.0.join(format!(
            "{}.{}.{画像の拡張子}",
            要約値.十六進の文字列(),
            キャッシュの形式の版::今.ファイル名の印()
        ))
    }

    /// このプロセスが撮り方のサムネイルを書いている途中のファイルのパス。
    pub(crate) fn 書きかけのパス(
        &self,
        要約値: 撮り方の要約値,
        プロセスの番号: u32,
    ) -> PathBuf {
        self.0.join(format!(
            "{}.{プロセスの番号}.{書きかけの拡張子}",
            要約値.十六進の文字列()
        ))
    }
}

/// フォルダの中のファイルの種類とは、刈り込みが数える今の版のサムネイルのファイルか、消してよい古い版のサムネイルのファイルか、
/// 書きかけのファイルか、それ以外かの区別のことである。今より新しい版のサムネイルは「それ以外」に入り、数えも消しもしない。
/// 新しい版のアプリと行き来する利用者や、2つを同時に動かす利用者で、互いのキャッシュを消し合わないためである。
pub(crate) enum キャッシュのファイルの種類 {
    画像,
    古い版の画像,
    書きかけ,
    ほか,
}

impl キャッシュのファイルの種類 {
    /// パスの拡張子と、画像なら拡張子の前の版の印から見分ける。版の印の無い画像(版3以前)と、今より小さい番号の印の画像は
    /// 古い版の画像である。今より大きい番号の印の画像と、印の形でない画像は、それ以外として残す。
    pub(crate) fn 見分ける(パス: &Path) -> Self {
        match パス.extension().and_then(OsStr::to_str) {
            Some(画像の拡張子) => {
                let 版の印 = Path::new(パス.file_stem().unwrap_or_default())
                    .extension()
                    .and_then(OsStr::to_str);
                Self::版の印から見分ける(版の印)
            }
            Some(書きかけの拡張子) => Self::書きかけ,
            _ => Self::ほか,
        }
    }

    fn 版の印から見分ける(版の印: Option<&str>) -> Self {
        let Some(印) = 版の印 else {
            return Self::古い版の画像;
        };
        match キャッシュの形式の版::ファイル名の印から読む(印)
            .map(キャッシュの形式の版::今の版と比べる)
        {
            Some(版の比べた結果::今の版) => Self::画像,
            Some(版の比べた結果::古い) => Self::古い版の画像,
            Some(版の比べた結果::新しい) | None => Self::ほか,
        }
    }
}
