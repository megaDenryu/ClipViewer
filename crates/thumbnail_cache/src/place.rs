//! キャッシュの置き場所。サムネイルのキャッシュを置くフォルダがあるか、無いのでキャッシュを使わないかを持つ。

use crate::folder::キャッシュのフォルダ;

/// キャッシュの置き場所とは、サムネイルのキャッシュを置くフォルダがあるか、無いのでキャッシュを使わないかの区別のことである。
/// 使わないときも撮影は成り立つ(撮った画像を RAM に持って見せる)ため、使えないことを失敗にしない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum キャッシュの置き場所 {
    /// このフォルダに置く。
    フォルダ(キャッシュのフォルダ),
    /// 置き場所が決まらない(環境変数 LOCALAPPDATA が無い等)ので、キャッシュを使わない。
    使わない,
}
