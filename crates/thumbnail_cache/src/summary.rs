//! 撮り方の要約値。撮り方の各値を決まった順にバイト列へ並べ、128ビットの FNV-1a の手順で混ぜて、キャッシュのファイル名にする。
//! std の DefaultHasher は Rust の版で結果が変わりうるため使わない。FNV-1a は手順と定数が公開されていて版で変わらない。

use clip_domain::サムネイルの撮り方;

use crate::format_version::キャッシュの形式の版;

/// 128ビットの FNV-1a の初期値(公開されている offset basis)。
pub(crate) const 混ぜる初期値: u128 = 0x6c62_272e_07bb_0142_62b8_2175_6295_c58d;

/// 128ビットの FNV-1a の掛ける数(公開されている FNV prime)。
const 混ぜて掛ける数: u128 = 0x0000_0000_0100_0000_0000_0000_0000_013b;

/// 撮り方の要約値とは、撮り方の各値(キャッシュの形式の版・動画のパス・時刻・クロップの各値・大きさ)を決まった順にバイト列へ並べ、
/// 128ビットの FNV-1a の手順で混ぜて得る数のことである。撮り方が等しければ等しく、違えば数万件でも偶然に一致する見込みを無視できる。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 撮り方の要約値(u128);

impl 撮り方の要約値 {
    /// 撮り方から求める。可変長の値(形式の版と動画のパス)は長さを前に置き、値の境目がずれて別の撮り方と同じ並びにならないようにする。
    pub fn 求める(撮り方: &サムネイルの撮り方) -> Self {
        let クロップ = 撮り方.クロップ();
        let 大きさ = 撮り方.大きさ();
        let mut 混ぜ = 混ぜている値(混ぜる初期値);
        混ぜ.長さを付けて足す(キャッシュの形式の版::今.要約に混ぜる表記().as_bytes());
        混ぜ.長さを付けて足す(
            要約に使うパスの表記(撮り方.動画のパス().文字列()).as_bytes(),
        );
        for 数 in [
            撮り方.時刻().秒数(),
            クロップ.左端().割合(),
            クロップ.上端().割合(),
            クロップ.幅().割合(),
            クロップ.高さ().割合(),
        ] {
            混ぜ.足す(&零の符号を揃える(数).to_bits().to_le_bytes());
        }
        混ぜ.足す(&大きさ.幅().to_le_bytes());
        混ぜ.足す(&大きさ.高さ().to_le_bytes());
        Self(混ぜ.0)
    }

    /// 16進数32文字の文字列。キャッシュのファイル名の幹に使う。
    pub fn 十六進の文字列(self) -> String {
        format!("{:032x}", self.0)
    }
}

/// 要約に使う動画のパスの表記。Windows のパスは大文字小文字を区別せず、区切り文字は `/` と `\` のどちらでもよいため、
/// Windows では区切り文字を `\` に揃えて小文字にし、同じ動画が別の名前にならないようにする。動画を開く境界のパスは変えない。
fn 要約に使うパスの表記(パス: &str) -> String {
    if cfg!(windows) {
        パス.replace('/', "\\").to_lowercase()
    } else {
        パス.to_string()
    }
}

/// 0 の符号を揃える。-0.0 と 0.0 は同じ値だがビット列が違い、そのまま混ぜると同じ撮り方が別の名前になる。
fn 零の符号を揃える(数: f64) -> f64 {
    if 数 == 0.0 { 0.0 } else { 数 }
}

/// 混ぜている値とは、FNV-1a の手順でバイトを1つずつ混ぜている途中の数のことである。
pub(crate) struct 混ぜている値(pub(crate) u128);

impl 混ぜている値 {
    pub(crate) fn 足す(&mut self, バイト列: &[u8]) {
        for バイト in バイト列 {
            self.0 = (self.0 ^ u128::from(*バイト)).wrapping_mul(混ぜて掛ける数);
        }
    }

    fn 長さを付けて足す(&mut self, バイト列: &[u8]) {
        // 注意: usize から u64 への変換は、このアプリが動く64ビット以下の計算機では失敗しない。失敗したら最大値で数える。
        let 長さ = u64::try_from(バイト列.len()).unwrap_or(u64::MAX);
        self.足す(&長さ.to_le_bytes());
        self.足す(バイト列);
    }
}
