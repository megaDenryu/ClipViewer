//! サムネイルのキャッシュ。撮り方のサムネイルを置く・読む・捨てる。置き場所が無いときは何も持たないキャッシュとして振る舞う。

use std::fs::File;
use std::io::{self, Write};
use std::path::Path;
use std::sync::{Arc, Mutex, PoisonError};

use clip_domain::{サムネイルの撮り方, サムネイルの画像};

use crate::capacity::キャッシュの容量;
use crate::clock::キャッシュの時計;
use crate::error::キャッシュの読み書きエラー;
use crate::place::キャッシュの置き場所;
use crate::summary::撮り方の要約値;

/// サムネイルのキャッシュとは、キャッシュの置き場所と容量の上限と時計を保持し、撮り方ごとのサムネイルのファイルを読み書きするもののことである。
/// 2つのアプリが同じフォルダを同時に使ってよい(書きかけの名前をプロセスごとに分け、置き換えで書くため)。
/// 注意: 同じプロセスの中では、書きかけの名前が同じ撮り方で重なる。そのため、複製したキャッシュは書き込みの錠を共有し、
/// 置く(書きかけへ書く・置き換える・刈り込む)ことを1つずつ行う。同じプロセスで同じフォルダを使う値は、1つのキャッシュから複製して作る
/// (参照: _doc/設計/ライブラリ.md 判断11)。
#[derive(Debug, Clone)]
pub struct サムネイルのキャッシュ {
    置き場所: キャッシュの置き場所,
    pub(crate) 上限: キャッシュの容量,
    pub(crate) 時計: キャッシュの時計,
    プロセスの番号: u32,
    書き込みの錠: Arc<Mutex<()>>,
}

impl サムネイルのキャッシュ {
    /// 置き場所と容量の上限と時計から作る。フォルダはまだ無くてもよい。
    pub fn 作成する(
        置き場所: キャッシュの置き場所,
        上限: キャッシュの容量,
        時計: キャッシュの時計,
    ) -> Self {
        Self {
            置き場所,
            上限,
            時計,
            プロセスの番号: std::process::id(),
            書き込みの錠: Arc::default(),
        }
    }

    /// 撮り方のサムネイルを読む。無ければ無い。中身が空のファイルは壊れているので消して無いとする。
    /// 読めたら使った時刻を今へ進める。
    pub fn 読む(
        &self,
        撮り方: &サムネイルの撮り方,
    ) -> Result<Option<サムネイルの画像>, キャッシュの読み書きエラー> {
        let キャッシュの置き場所::フォルダ(フォルダ) = &self.置き場所 else {
            return Ok(None);
        };
        let パス = フォルダ.画像のパス(撮り方の要約値::求める(撮り方));
        let バイト列 = match std::fs::read(&パス) {
            Ok(バイト列) => バイト列,
            Err(原因) if 原因.kind() == io::ErrorKind::NotFound => return Ok(None),
            Err(原因) => {
                return Err(キャッシュの読み書きエラー::作る(&パス, 原因));
            }
        };
        if バイト列.is_empty() {
            self.捨てる(撮り方)?;
            return Ok(None);
        }
        self.使った時刻を今へ進める(&パス);
        Ok(Some(サムネイルの画像::作成する(バイト列)))
    }

    /// 撮り方のサムネイルを置く。書きかけのファイルへ書いてから置き換え、容量の上限を超えていれば古いものから消す。
    /// 複製したキャッシュの間では書き込みの錠を取って1つずつ置く(同じプロセスの書きかけの名前を取り合わないため)。
    pub fn 置く(
        &self,
        撮り方: &サムネイルの撮り方,
        画像: &サムネイルの画像,
    ) -> Result<(), キャッシュの読み書きエラー> {
        let キャッシュの置き場所::フォルダ(フォルダ) = &self.置き場所 else {
            return Ok(());
        };
        let _置いている間の錠 = self
            .書き込みの錠
            .lock()
            .unwrap_or_else(PoisonError::into_inner);
        let 失敗 = キャッシュの読み書きエラー::作る;
        std::fs::create_dir_all(フォルダ.パス()).map_err(|原因| 失敗(フォルダ.パス(), 原因))?;
        let 要約値 = 撮り方の要約値::求める(撮り方);
        let 書きかけ = フォルダ.書きかけのパス(要約値, self.プロセスの番号);
        let 置き場所 = フォルダ.画像のパス(要約値);
        File::create(&書きかけ)
            .and_then(|mut ファイル| ファイル.write_all(画像.バイト列()))
            .map_err(|原因| 失敗(&書きかけ, 原因))?;
        std::fs::rename(&書きかけ, &置き場所).map_err(|原因| 失敗(&置き場所, 原因))?;
        self.使った時刻を今へ進める(&置き場所);
        self.容量の上限まで古いものから消す(フォルダ);
        Ok(())
    }

    /// 撮り方のサムネイルを消す(画素へ戻せない壊れたファイル等)。もともと無ければ何もしない。
    pub fn 捨てる(
        &self,
        撮り方: &サムネイルの撮り方,
    ) -> Result<(), キャッシュの読み書きエラー> {
        let キャッシュの置き場所::フォルダ(フォルダ) = &self.置き場所 else {
            return Ok(());
        };
        let パス = フォルダ.画像のパス(撮り方の要約値::求める(撮り方));
        match std::fs::remove_file(&パス) {
            Ok(()) => Ok(()),
            Err(原因) if 原因.kind() == io::ErrorKind::NotFound => Ok(()),
            Err(原因) => Err(キャッシュの読み書きエラー::作る(&パス, 原因)),
        }
    }

    /// ファイルの使った時刻(更新日時)を、キャッシュの時計の今へ進める。進められなくても、容量の上限で消される順が
    /// 変わるだけなので失敗にしない。置いたときも時計の今にするのは、使った時刻をすべて同じ時計で数えるためである。
    fn 使った時刻を今へ進める(&self, パス: &Path) {
        let _ = File::options()
            .write(true)
            .open(パス)
            .and_then(|ファイル| ファイル.set_modified(self.時計.今()));
    }
}
