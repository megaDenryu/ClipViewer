//! 容量の上限までの刈り込み。フォルダのサムネイルのファイルの合計が上限を超えていれば、使った時刻(更新日時)の古いものから消す。
//! 落ちたアプリが残した古い書きかけのファイルと、形式の版を上げる前の古い版のファイルもここで消す。刈り込みは置いた後に行う片付けであり、失敗しても置いたことは成り立つため、
//! 消せなかったファイルは次に置くときに消し直す。

use std::path::PathBuf;
use std::time::{Duration, SystemTime};

use crate::cache::サムネイルのキャッシュ;
use crate::folder::{キャッシュのファイルの種類, キャッシュのフォルダ};

/// 書きかけのファイルを落ちたアプリの残りとみなすまでの時間。1枚を書く時間(数ミリ秒)より十分に長くし、
/// ほかのアプリが書いている途中のファイルを消さない。
const 書きかけを残しておく時間: Duration = Duration::from_secs(600);

/// 数えた画像とは、刈り込みで数えるサムネイルのファイルの、パスと大きさと使った時刻の組のことである。
struct 数えた画像 {
    パス: PathBuf,
    バイト数: u64,
    使った時刻: SystemTime,
}

impl サムネイルのキャッシュ {
    /// フォルダの画像の合計が上限を超えていれば、使った時刻の古いものから消す。古い書きかけのファイルと古い版の画像も消す。
    pub(crate) fn 容量の上限まで古いものから消す(
        &self,
        フォルダ: &キャッシュのフォルダ,
    ) {
        let Ok(フォルダの中の並び) = std::fs::read_dir(フォルダ.パス()) else {
            return;
        };
        let 今 = self.時計.今();
        let mut 画像 = Vec::new();
        for フォルダの中の項目 in フォルダの中の並び.flatten() {
            let パス = フォルダの中の項目.path();
            let Ok(情報) = フォルダの中の項目.metadata() else {
                continue;
            };
            let 使った時刻 = 情報.modified().unwrap_or(SystemTime::UNIX_EPOCH);
            match キャッシュのファイルの種類::見分ける(&パス) {
                キャッシュのファイルの種類::画像 => 画像.push(数えた画像 {
                    パス,
                    バイト数: 情報.len(),
                    使った時刻,
                }),
                キャッシュのファイルの種類::書きかけ
                    if 今.duration_since(使った時刻).unwrap_or_default()
                        > 書きかけを残しておく時間 =>
                {
                    let _ = std::fs::remove_file(&パス);
                }
                キャッシュのファイルの種類::古い版の画像 => {
                    let _ = std::fs::remove_file(&パス);
                }
                キャッシュのファイルの種類::書きかけ | キャッシュのファイルの種類::ほか =>
                    {}
            }
        }
        let mut 合計: u64 = 画像.iter().map(|一枚| 一枚.バイト数).sum();
        画像.sort_by_key(|一枚| 一枚.使った時刻);
        for 一枚 in 画像 {
            if !self.上限.超えるか(合計) {
                break;
            }
            if std::fs::remove_file(&一枚.パス).is_ok() {
                合計 -= 一枚.バイト数;
            }
        }
    }
}
