//! 混ぜ方の試験。128ビットの FNV-1a の公開されている試験の値と一致することを確かめる。

use crate::summary::{混ぜている値, 混ぜる初期値};

fn 混ぜる(バイト列: &[u8]) -> u128 {
    let mut 混ぜ = 混ぜている値(混ぜる初期値);
    混ぜ.足す(バイト列);
    混ぜ.0
}

#[test]
fn 公開されている試験の値と一致する() {
    assert_eq!(混ぜる(b""), 0x6c62_272e_07bb_0142_62b8_2175_6295_c58d);
    assert_eq!(混ぜる(b"a"), 0xd228_cb69_6f1a_8caf_7891_2b70_4e4a_8964);
    assert_eq!(混ぜる(b"foobar"), 0x343e_1662_793c_64bf_6f0d_3597_ba44_6f18);
}
