//! 表示するコマを求める規則の試験。末尾で止めたとき・時計が末尾で止まったときは、最後の再生できるクリップの最後のコマを表示する。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 秒, 試験用のスタック};

fn 表示するコマ(
    スタック: &クリップスタック, 位置: f64
) -> Option<(String, f64)> {
    スタック.表示するコマを求める(秒(位置)).map(|コマ| {
        (
            コマ.クリップ.識別子().文字列().to_string(),
            コマ.動画上の位置.秒数(),
        )
    })
}

#[test]
fn タイムラインの途中ではクリップが求まったの動画上の位置を表示する() {
    let スタック = 試験用のスタック();
    assert_eq!(表示するコマ(&スタック, 6.5), Some(("C".to_string(), 20.5)));
}

#[test]
fn タイムラインの末尾以降では最後の再生できるクリップの区間の終わりを表示する() {
    let スタック = 試験用のスタック();
    assert_eq!(表示するコマ(&スタック, 11.0), Some(("E".to_string(), 44.0)));
    assert_eq!(表示するコマ(&スタック, 30.0), Some(("E".to_string(), 44.0)));
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let 最後が長さ0 = クリップスタック::一覧から作成する(vec![
        クリップを作る("先", 3.0, 5.0, 一回, トリガー::自動進行),
        クリップを作る("零", 9.0, 9.0, 一回, トリガー::自動進行),
    ])
    .expect("重複しない");
    assert_eq!(
        表示するコマ(&最後が長さ0, 2.0),
        Some(("先".to_string(), 5.0))
    );
}

#[test]
fn 再生できるクリップが無ければ表示するコマは無い() {
    assert_eq!(表示するコマ(&クリップスタック::default(), 0.0), None);
}
