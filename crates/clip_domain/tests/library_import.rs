//! ブラウザ版の設定からライブラリのスタックへの取り込みと、スタックの識別子と名前の値の試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::連番の発行元;

fn 識別子(文字列: &str) -> スタックの識別子 {
    スタックの識別子::文字列から作成する(文字列.to_string()).expect("識別子")
}

fn 名前(文字列: &str) -> スタックの名前 {
    スタックの名前::作成する(文字列.to_string()).expect("名前")
}

fn 日時(ミリ秒: u64) -> ライブラリの日時 {
    ライブラリの日時::紀元からのミリ秒で作成する(ミリ秒).expect("日時")
}

fn 往復する(項目: &ライブラリのスタック) -> ライブラリのスタック {
    let 本文 = 項目.本文へ書き出す().expect("書き出せる");
    ライブラリのスタック::本文から読み込む(&本文).expect("読み込める")
}

#[test]
fn ブラウザ版の設定は動画のパスがあれば取り込み_無ければ理由を返す() {
    let 本文 = 設定ファイルの本文::作成する(
        include_str!("fixtures/browser_v4.json").to_string(),
    );
    let 設定 = スタック設定::本文から読み込む(&本文, &mut 連番の発行元::default()).expect("読める");
    let 並び = 設定.スタック.clone();
    let 項目 = 設定
        .clone()
        .ライブラリへ取り込む(識別子("stack-1-1"), 名前("取り込み"), 日時(5))
        .expect("取り込める");
    assert_eq!(項目.並び(), &並び);
    assert_eq!(Some(項目.動画のパス()), 設定.期待する動画のパス.as_ref());
    assert_eq!(往復する(&項目), 項目);
    let パスの無い設定 = スタック設定 {
        期待する動画のパス: None,
        ..設定
    };
    assert_eq!(
        パスの無い設定.ライブラリへ取り込む(識別子("stack-1-2"), 名前("x"), 日時(5)),
        Err(ライブラリへ取り込めない理由::動画のパスが無い)
    );
}

#[test]
fn 識別子は英小文字と数字とハイフンだけを受け付け_名前は空白だけを拒む() {
    assert!(スタックの識別子::文字列から作成する("stack-1-2".into()).is_ok());
    for 不正 in ["", "Stack-1", "a/b", "..", "スタック", "a b"] {
        assert!(
            スタックの識別子::文字列から作成する(不正.into()).is_err(),
            "{不正}"
        );
    }
    assert!(スタックの識別子::文字列から作成する("a".repeat(101)).is_err());
    assert_eq!(
        スタックの識別子::時刻と乱数から組み立てる(
            発行時刻::紀元からのミリ秒で作成する(12),
            識別子の乱数::乱数を畳んで作成する(10_034),
        )
        .文字列(),
        "stack-12-34"
    );
    assert_eq!(
        スタックの名前::作成する("   ".into()),
        Err(空のスタックの名前エラー)
    );
}
