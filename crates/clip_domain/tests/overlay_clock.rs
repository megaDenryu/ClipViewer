//! 重ね合わせの時計の規則の試験。等倍で進めることと、重ね合わせの長さに着いたときの全体ループの振る舞い。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{一本の動画の重ね合わせ, 二行の重ね合わせ, 重ねの秒};

fn 長さ(秒: f64) -> 時間の長さ {
    時間の長さ::作成する(秒).expect("有効な長さ")
}

fn 位置(秒: f64) -> 重ね合わせの再生位置 {
    重ね合わせの再生位置::時刻から作成する(重ねの秒(秒))
}

#[test]
fn 重ね合わせの長さの手前では実時間の経過だけ進めて続ける() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(重ね.重ね合わせの長さ(), 重ねの秒(4.0));
    for 全体の末尾 in [末尾での振る舞い::先頭へ戻る, 末尾での振る舞い::止まる]
    {
        assert_eq!(
            位置(1.0).再生で進める(長さ(0.5), &重ね, 全体の末尾),
            重ね合わせの時計を進めた結果::続ける(位置(1.5))
        );
    }
}

#[test]
fn 重ね合わせの長さに着くと全体ループなら先頭で続け無効なら長さで止まる() {
    let 重ね = 二行の重ね合わせ();
    for 進める秒 in [0.5, 2.0] {
        assert_eq!(
            位置(3.5).再生で進める(長さ(進める秒), &重ね, 末尾での振る舞い::先頭へ戻る),
            重ね合わせの時計を進めた結果::続ける(重ね合わせの再生位置::先頭),
            "{進める秒}秒進める"
        );
        assert_eq!(
            位置(3.5).再生で進める(長さ(進める秒), &重ね, 末尾での振る舞い::止まる),
            重ね合わせの時計を進めた結果::末尾で止まる(位置(4.0)),
            "{進める秒}秒進める"
        );
    }
}

#[test]
fn 置いたクリップが無い重ね合わせは0秒に留まる() {
    let 重ね = 一本の動画の重ね合わせ();
    assert_eq!(
        重ね合わせの再生位置::先頭.再生で進める(
            長さ(1.0),
            &重ね,
            末尾での振る舞い::先頭へ戻る
        ),
        重ね合わせの時計を進めた結果::続ける(重ね合わせの再生位置::先頭)
    );
    assert_eq!(
        重ね合わせの再生位置::先頭.再生で進める(長さ(1.0), &重ね, 末尾での振る舞い::止まる),
        重ね合わせの時計を進めた結果::末尾で止まる(重ね合わせの再生位置::先頭)
    );
}

#[test]
fn 末尾に着いた位置から再生を始めると先頭から再生し直す() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(
        位置(4.0).再生を始める位置(&重ね),
        重ね合わせの再生位置::先頭
    );
    assert_eq!(位置(2.5).再生を始める位置(&重ね), 位置(2.5));
    assert_eq!(位置(2.5).時刻(), 重ねの秒(2.5));
}
