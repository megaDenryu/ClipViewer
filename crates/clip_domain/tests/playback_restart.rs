//! 再生を始める位置の試験。末尾に達していればモードの先頭から再生し直し、達していなければ位置を変えない。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 秒, 長さ};

fn 一つのクリップの並び() -> クリップスタック {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let クリップ = クリップを作る("a", 0.0, 10.0, 一回, トリガー::自動進行);
    クリップスタック::一覧から作成する(vec![クリップ]).expect("1つ")
}

fn 動画上(値: f64) -> 動画上の秒 {
    動画上の秒::作成する(値).expect("有効な秒数")
}

#[test]
fn シーケンス再生で末尾に達していれば先頭から始め_途中なら位置を変えない() {
    let 並び = 一つのクリップの並び();
    let 末尾 = 再生位置::シーケンス再生(秒(10.0));
    assert_eq!(
        末尾.再生を始める位置(&並び, 長さ(60.0)),
        再生位置::シーケンス再生(秒(0.0))
    );
    let 途中 = 再生位置::シーケンス再生(秒(9.9));
    assert_eq!(途中.再生を始める位置(&並び, 長さ(60.0)), 途中);
}

#[test]
fn 元動画再生で動画の末尾に達していれば先頭から始める() {
    let 並び = 一つのクリップの並び();
    let 末尾 = 再生位置::元動画再生(動画上(60.0));
    assert_eq!(
        末尾.再生を始める位置(&並び, 長さ(60.0)),
        再生位置::元動画再生(動画上(0.0))
    );
    let 途中 = 再生位置::元動画再生(動画上(30.0));
    assert_eq!(途中.再生を始める位置(&並び, 長さ(60.0)), 途中);
}

#[test]
fn 単独クリップ再生と合計が0秒の並びでは位置を変えない() {
    let 並び = 一つのクリップの並び();
    let 単独 = 再生位置::単独クリップ再生(長さ(10.0));
    assert_eq!(単独.再生を始める位置(&並び, 長さ(60.0)), 単独);
    let 空の並び = クリップスタック::default();
    let 先頭 = 再生位置::シーケンス再生(秒(0.0));
    assert_eq!(先頭.再生を始める位置(&空の並び, 長さ(60.0)), 先頭);
}
