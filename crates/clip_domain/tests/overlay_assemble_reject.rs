//! 重ね合わせの部品一式から重ね合わせを組み立てるメソッドの試験。重ね合わせの不変条件(行の数の上限・行の中の時間の重なり・識別子の重なり・
//! 動画の番号・区間の長さ)を破る部品一式を、置けない置いたクリップの行と位置と理由付きの型付きのエラーで拒むことを確かめる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{置いた識別子, 行};
use support::overlay_library::{置くもの, 部品一式};

fn 置けない(
    結果: Result<重ね合わせ, 重ね合わせを組み立てられない理由>,
) -> (usize, usize, 重ね合わせの操作エラー) {
    match 結果 {
        Err(重ね合わせを組み立てられない理由::置いたクリップを置けない { 行, 位置, 理由 }) => {
            (行.番号(), 位置.番号(), 理由)
        }
        その他 => panic!("置けないはずが {その他:?}"),
    }
}

#[test]
fn 行の数が同時に重ねられる行の数を超えると拒む() {
    let 空の行: [&[置くもの<'_>]; 9] = [&[]; 9];
    assert_eq!(
        部品一式(1, &空の行).重ね合わせへ組み立てる(),
        Err(重ね合わせを組み立てられない理由::行の数が上限を超える {
            行の数: 9
        })
    );
    assert!(部品一式(1, &空の行[..8]).重ね合わせへ組み立てる().is_ok());
}

#[test]
fn 同じ行で時間が重なると_その置いたクリップの行と位置と相手を返して拒む() {
    let 甲 = 置くもの::既定("甲", (0.0, 2.0), 0.0);
    let 乙 = 置くもの::既定("乙", (0.0, 2.0), 1.0);
    let 丙 = 置くもの::既定("丙", (0.0, 2.0), 1.0);
    assert_eq!(
        置けない(部品一式(1, &[&[], &[甲, 乙], &[丙]]).重ね合わせへ組み立てる()),
        (
            1,
            1,
            重ね合わせの操作エラー::時間が重なる {
                行: 行(1),
                相手: 置いた識別子("甲"),
            }
        )
    );
}

#[test]
fn 識別子がほかの行と重なると拒む() {
    let 甲 = 置くもの::既定("同じ", (0.0, 1.0), 0.0);
    let 乙 = 置くもの::既定("同じ", (0.0, 1.0), 0.0);
    assert_eq!(
        置けない(部品一式(1, &[&[甲], &[乙]]).重ね合わせへ組み立てる()),
        (
            1,
            0,
            重ね合わせの操作エラー::識別子が重複している(置いた識別子("同じ"))
        )
    );
}

#[test]
fn 動画の番号が使う動画の表に無いと拒み_表にあれば使っていない動画があってもよい() {
    let mut 二番 = 置くもの::既定("甲", (0.0, 1.0), 0.0);
    二番.動画 = 2;
    assert_eq!(
        置けない(部品一式(2, &[&[二番]]).重ね合わせへ組み立てる()),
        (
            0,
            0,
            重ね合わせの操作エラー::動画の番号が表に無い {
                番号: 動画の番号::番号から作成する(2),
                動画の数: 2,
            }
        )
    );
    let mut 一番 = 置くもの::既定("甲", (0.0, 1.0), 0.0);
    一番.動画 = 1;
    assert!(部品一式(3, &[&[一番]]).重ね合わせへ組み立てる().is_ok());
}

#[test]
fn 区間の長さが0の置いたクリップを拒む() {
    let 零 = 置くもの::既定("甲", (3.0, 3.0), 0.0);
    assert_eq!(
        置けない(部品一式(1, &[&[零]]).重ね合わせへ組み立てる()),
        (0, 0, 重ね合わせの操作エラー::区間の長さが0)
    );
}

#[test]
fn 位置は部品の並びの中の順番であり_始まりの時刻の順に並べ直した後の順番ではない() {
    let 後に始まる = 置くもの::既定("後", (0.0, 1.0), 5.0);
    let 先に始まる零の長さ = 置くもの::既定("先", (3.0, 3.0), 0.0);
    assert_eq!(
        置けない(部品一式(1, &[&[後に始まる, 先に始まる零の長さ]]).重ね合わせへ組み立てる()),
        (0, 1, 重ね合わせの操作エラー::区間の長さが0)
    );
}
