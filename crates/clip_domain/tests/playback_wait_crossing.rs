//! 1回の増分で待つクリップの終わりを越えても、待つクリップを飛び越さないことの試験。
//! 大きな経過・高倍速・短い区間で、待たないクリップから次の待つクリップの終わりまで一度に越える場合を扱う。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 秒, 試験用のスタック, 試験用の条件, 長さ};

fn 進めた秒数(
    スタック: &クリップスタック,
    開始: f64,
    経過: f64,
    全体の末尾: 末尾での振る舞い,
) -> f64 {
    let 条件 = 試験用の条件(スタック, 全体の末尾);
    match 再生位置::シーケンス再生(秒(開始)).再生で進める(長さ(経過), &条件)
    {
        時計を進めた結果::続ける(再生位置::シーケンス再生(位置)) => {
            位置.秒数()
        }
        その他 => panic!("シーケンス再生のまま続くはず: {その他:?}"),
    }
}

fn 近い(実際: f64, 期待: f64) {
    assert!((実際 - 期待).abs() < 1e-9, "実際 {実際} 期待 {期待}");
}

/// 先[0,1) 自動進行 / 待つ[1,3) Enter待ち / 後[3,7) 自動進行 の並び。
fn 待つクリップを挟む並び() -> クリップスタック {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    クリップスタック::一覧から作成する(vec![
        クリップを作る("先", 0.0, 1.0, 一回, トリガー::自動進行),
        クリップを作る("待つ", 10.0, 12.0, 一回, トリガー::Enterキー待ち),
        クリップを作る("後", 20.0, 24.0, 一回, トリガー::自動進行),
    ])
    .expect("重複しない")
}

#[test]
fn 前のクリップから待つクリップの終わりを一度に越えても待つクリップの最後の周回へ戻る() {
    let スタック = 待つクリップを挟む並び();
    近い(
        進めた秒数(&スタック, 0.5, 3.0, 末尾での振る舞い::止まる),
        1.5,
    );
    近い(
        進めた秒数(&スタック, 0.5, 6.0, 末尾での振る舞い::止まる),
        2.5,
    );
}

#[test]
fn 待つクリップの終わりへちょうど達すると最後の周回の先頭へ戻る() {
    let スタック = 待つクリップを挟む並び();
    近い(
        進めた秒数(&スタック, 2.5, 0.5, 末尾での振る舞い::止まる),
        1.0,
    );
    近い(
        進めた秒数(&スタック, 1.0, 2.0, 末尾での振る舞い::止まる),
        1.0,
    );
}

#[test]
fn 待つクリップより後ろの位置からは戻らない() {
    let スタック = 待つクリップを挟む並び();
    近い(
        進めた秒数(&スタック, 3.5, 1.0, 末尾での振る舞い::止まる),
        4.5,
    );
}

#[test]
fn 全体ループが有効でも最後のクリップが待つなら先頭へ戻らずに最後の周回を繰り返す() {
    let スタック = 試験用のスタック();
    近い(
        進めた秒数(&スタック, 10.9, 0.2, 末尾での振る舞い::先頭へ戻る),
        7.1,
    );
    近い(
        進めた秒数(&スタック, 7.5, 10.0, 末尾での振る舞い::先頭へ戻る),
        9.5,
    );
}

#[test]
fn 長さ0の待つクリップは通っても戻る先にしない() {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let スタック = クリップスタック::一覧から作成する(vec![
        クリップを作る("先", 0.0, 1.0, 一回, トリガー::自動進行),
        クリップを作る("零", 5.0, 5.0, 一回, トリガー::Enterキー待ち),
        クリップを作る("後", 20.0, 24.0, 一回, トリガー::自動進行),
    ])
    .expect("重複しない");
    近い(
        進めた秒数(&スタック, 0.5, 1.0, 末尾での振る舞い::止まる),
        1.5,
    );
}
