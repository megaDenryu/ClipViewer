//! 重ね合わせへ置く操作の試験。空いている最も手前の行への置き方と、行が上限まであるときに拒むこと。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 写し, 置いた連番の発行元, 置く, 行ごとの識別子, 重ねの秒,
};

#[test]
fn 置くと空いている最も手前の行へ入り空きが無ければ手前に行を足す() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    置く(&mut 重ね, 写し(0.0, 2.0, 2), 0.0, &mut 発行元).expect("空の重ね合わせに置ける");
    置く(&mut 重ね, 写し(10.0, 11.0, 1), 1.0, &mut 発行元).expect("行を足して置ける");
    置く(&mut 重ね, 写し(20.0, 21.0, 1), 2.0, &mut 発行元).expect("端が接するだけなら重ならない");
    置く(&mut 重ね, 写し(30.0, 30.5, 1), 0.0, &mut 発行元).expect("手前の行が空いている");
    assert_eq!(
        行ごとの識別子(&重ね),
        vec![vec!["置-1"], vec!["置-4", "置-2", "置-3"]]
    );
    let 置いた = 重ね
        .識別子で探す(&support::overlay::置いた識別子("置-1"))
        .expect("置いた");
    assert_eq!(置いた.映す矩形(), 映す矩形::全体);
    assert_eq!(置いた.音量(), 置いたクリップの音量::最初の値);
    assert_eq!(置いた.終わりの時刻(), 重ねの秒(4.0));
    assert_eq!(重ね.重ね合わせの長さ(), 重ねの秒(4.0));
}

#[test]
fn 行が同時に重ねられる行の数まであってどれも空いていなければ拒む() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    for _ in 0..同時に重ねられる行の数 {
        置く(&mut 重ね, 写し(0.0, 1.0, 1), 0.0, &mut 発行元).expect("行を足して置ける");
    }
    let 置く前 = 重ね.clone();
    assert_eq!(
        置く(&mut 重ね, 写し(0.0, 1.0, 1), 0.5, &mut 発行元),
        Err(重ね合わせの操作エラー::空いている行が無い {
            始まりの時刻: 重ねの秒(0.5)
        })
    );
    assert_eq!(重ね, 置く前);
    置く(&mut 重ね, 写し(0.0, 1.0, 1), 1.0, &mut 発行元).expect("空いた時刻なら置ける");
    assert_eq!(重ね.行の並び().len(), 同時に重ねられる行の数);
}
