//! 置いたクリップを動かす操作の試験。同じ行の中での並び直しと、別の行への移動と、拒む場合。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    二行の重ね合わせ, 置いた識別子, 行, 行ごとの識別子, 重ねの秒
};

#[test]
fn 同じ行の中で動かすと始まりの時刻の順に並び直す() {
    let mut 重ね = 二行の重ね合わせ();
    重ね
        .置いたクリップを動かす(&置いた識別子("置-2"), 行(1), 重ねの秒(5.0))
        .expect("空いている");
    assert_eq!(
        行ごとの識別子(&重ね),
        vec![vec!["置-1"], vec!["置-3", "置-2"]]
    );
    let 動かした = 重ね.識別子で探す(&置いた識別子("置-2")).expect("ある");
    assert_eq!(動かした.始まりの時刻(), 重ねの秒(5.0));
    assert_eq!(重ね.重ね合わせの長さ(), 重ねの秒(6.0));
}

#[test]
fn 別の行へ動かすと重なりの順が変わる() {
    let mut 重ね = 二行の重ね合わせ();
    重ね
        .置いたクリップを動かす(&置いた識別子("置-3"), 行(0), 重ねの秒(2.0))
        .expect("端が接するだけ");
    assert_eq!(
        行ごとの識別子(&重ね),
        vec![vec!["置-1", "置-3"], vec!["置-2"]]
    );
    assert_eq!(
        重ね.行の並び().置いてある行の番号(&置いた識別子("置-3")),
        Ok(行(0))
    );
}

#[test]
fn 時間が重なる先と無い行と無い識別子へは動かさず重ね合わせを変えない() {
    let mut 重ね = 二行の重ね合わせ();
    let 動かす前 = 重ね.clone();
    assert_eq!(
        重ね.置いたクリップを動かす(&置いた識別子("置-3"), 行(1), 重ねの秒(0.5)),
        Err(重ね合わせの操作エラー::時間が重なる {
            行: 行(1),
            相手: 置いた識別子("置-2")
        })
    );
    assert_eq!(
        重ね.置いたクリップを動かす(&置いた識別子("置-3"), 行(2), 重ねの秒(0.0)),
        Err(重ね合わせの操作エラー::行の番号が範囲の外 {
            行: 行(2),
            行の数: 2
        })
    );
    assert_eq!(
        重ね.置いたクリップを動かす(&置いた識別子("無い"), 行(0), 重ねの秒(9.0)),
        Err(
            重ね合わせの操作エラー::置いたクリップが見つからない(
                置いた識別子("無い")
            )
        )
    );
    assert_eq!(重ね, 動かす前);
}
