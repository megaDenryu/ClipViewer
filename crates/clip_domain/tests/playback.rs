//! 再生の時計の試験。速度、全体の末尾での振る舞い、モードの先頭、単独クリップ再生、元動画再生。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 秒, 試験用のスタック, 試験用の条件, 長さ};

fn 動画上(値: f64) -> 動画上の秒 {
    動画上の秒::作成する(値).expect("有効な秒数")
}

#[test]
fn 時計は実時間の経過に速度を掛けて進む() {
    let スタック = 試験用のスタック();
    let mut 条件 = 試験用の条件(&スタック, 末尾での振る舞い::止まる);
    条件.速度 = 再生速度::作成する(2.0).expect("有効");
    let 結果 = 再生位置::シーケンス再生(秒(1.0)).実時間の経過で進める(長さ(0.5), &条件);
    assert_eq!(
        結果,
        時計を進めた結果::続ける(再生位置::シーケンス再生(秒(2.0)))
    );
    assert!(再生速度::作成する(0.0).is_err());
}

#[test]
fn 待たないクリップで合計に達すると先頭へ戻るか末尾で止まる() {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let クリップ = クリップを作る("a", 0.0, 10.0, 一回, トリガー::自動進行);
    let スタック = クリップスタック::一覧から作成する(vec![クリップ]).expect("1つ");
    let 位置 = 再生位置::シーケンス再生(秒(9.9));
    let 戻る = 位置.実時間の経過で進める(
        長さ(0.2),
        &試験用の条件(&スタック, 末尾での振る舞い::先頭へ戻る),
    );
    assert_eq!(
        戻る,
        時計を進めた結果::続ける(再生位置::シーケンス再生(秒(0.0)))
    );
    let 止まった = 位置.実時間の経過で進める(
        長さ(0.2),
        &試験用の条件(&スタック, 末尾での振る舞い::止まる),
    );
    assert_eq!(
        止まった,
        時計を進めた結果::末尾で止まる(再生位置::シーケンス再生(秒(10.0)))
    );
}

#[test]
fn モードを切り替えると各モードの先頭から始まる() {
    let シーケンス = 再生位置::モードの先頭(再生モード::シーケンス再生);
    assert_eq!(シーケンス, 再生位置::シーケンス再生(秒(0.0)));
    let 単独 = 再生位置::モードの先頭(再生モード::単独クリップ再生);
    assert_eq!(単独, 再生位置::単独クリップ再生(時間の長さ::ゼロ));
    let 元動画 = 再生位置::モードの先頭(再生モード::元動画再生);
    assert_eq!(元動画.モード(), 再生モード::元動画再生);
    assert_eq!(元動画.位置の秒数(), 0.0);
}

#[test]
fn 単独クリップ再生は区間の長さで先頭へ戻り全体の末尾の設定に関わらず止まらない() {
    let スタック = 試験用のスタック();
    let 条件 = 試験用の条件(&スタック, 末尾での振る舞い::止まる);
    let 結果 =
        再生位置::単独クリップ再生(長さ(1.9)).実時間の経過で進める(長さ(0.3), &条件);
    let 時計を進めた結果::続ける(再生位置::単独クリップ再生(経過)) = 結果
    else {
        panic!("単独クリップ再生のまま続くはず: {結果:?}");
    };
    assert!((経過.秒数() - 0.2).abs() < 1e-9);
    let クリップ = スタック.選択中のクリップ().expect("先頭が選択されている");
    assert_eq!(クリップ.単独再生での動画上の位置(長さ(1.5)).秒数(), 11.5);
    assert_eq!(クリップ.単独再生での動画上の位置(長さ(5.0)).秒数(), 12.0);
    let 空の並び = クリップスタック::default();
    let 選択なし = 再生位置::単独クリップ再生(長さ(1.0)).実時間の経過で進める(
        長さ(0.5),
        &試験用の条件(&空の並び, 末尾での振る舞い::止まる),
    );
    assert_eq!(
        選択なし,
        時計を進めた結果::続ける(再生位置::単独クリップ再生(長さ(1.0)))
    );
}

#[test]
fn 元動画再生は動画の長さに達すると全体の末尾の設定に従う() {
    let スタック = 試験用のスタック();
    let 位置 = 再生位置::元動画再生(動画上(99.9));
    let 止まった = 位置.実時間の経過で進める(
        長さ(0.2),
        &試験用の条件(&スタック, 末尾での振る舞い::止まる),
    );
    assert_eq!(
        止まった,
        時計を進めた結果::末尾で止まる(再生位置::元動画再生(動画上(100.0)))
    );
    let 戻る = 位置.実時間の経過で進める(
        長さ(0.2),
        &試験用の条件(&スタック, 末尾での振る舞い::先頭へ戻る),
    );
    assert_eq!(
        戻る,
        時計を進めた結果::続ける(再生位置::元動画再生(動画上(0.0)))
    );
}
