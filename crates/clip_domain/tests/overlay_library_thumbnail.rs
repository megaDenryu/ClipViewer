//! 重ね合わせのサムネイルの撮り方の試験。最も早く始まる置いたクリップ(同じ時刻なら奥の行のもの)の開始とクロップを、その動画のパスで撮る。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay_library::{日時, 置くもの, 部品一式};

fn 登録した(行の並び: &[&[置くもの<'_>]]) -> ライブラリの重ね合わせ {
    ライブラリの重ね合わせ::新しく作る(
        重ね合わせの識別子::文字列から作成する("overlay-1-1".into()).expect("識別子"),
        重ね合わせの名前::作成する("重ね".into()).expect("名前"),
        部品一式(2, 行の並び)
            .重ね合わせへ組み立てる()
            .expect("組み立てられる"),
        日時(1_000),
    )
}

fn 大きさ() -> サムネイルの大きさ {
    サムネイルの大きさ::作成する(192, 108).expect("大きさ")
}

#[test]
fn 最も早く始まる置いたクリップの開始とクロップをその動画で撮る() {
    let 遅い = 置くもの::既定("placed-1", (2.0, 3.0), 4.0);
    let mut 早い = 置くもの::既定("placed-2", (7.0, 9.0), 1.0);
    早い.動画 = 1;
    早い.クロップ = (10.0, 20.0, 30.0, 40.0);
    let 撮り方 = 登録した(&[&[遅い], &[早い]])
        .サムネイルの撮り方(大きさ())
        .expect("撮れる");
    assert_eq!(撮り方.時刻().秒数(), 7.0);
    assert_eq!(
        撮り方.クロップ(),
        クロップ範囲::各値を範囲へ収めて作成する(10.0, 20.0, 30.0, 40.0)
    );
    assert_eq!(撮り方.動画のパス().文字列(), r"D:\動画\1.mp4");
}

#[test]
fn 同じ時刻に始まるなら奥の行の置いたクリップで撮る() {
    let 奥 = 置くもの::既定("placed-1", (2.0, 3.0), 0.0);
    let 手前 = 置くもの::既定("placed-2", (5.0, 6.0), 0.0);
    let 撮り方 = 登録した(&[&[奥], &[手前]])
        .サムネイルの撮り方(大きさ())
        .expect("撮れる");
    assert_eq!(撮り方.時刻().秒数(), 2.0);
}

#[test]
fn 置いたクリップが無ければ撮らない() {
    assert_eq!(登録した(&[&[]]).サムネイルの撮り方(大きさ()), None);
    assert!(登録した(&[&[]]).重ね合わせ().顔の置いたクリップ().is_none());
}
