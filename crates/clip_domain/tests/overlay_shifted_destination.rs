//! 塊のドラッグの行き先を求める試験。同じ行のほかの置いたクリップにぶつかった所で止めることと、0秒より前へ行かないことと、
//! 行の差を行の数へ収めることと、動かした先の行で基点が塞がっているときは最も近い空きへ置くこと。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{二行の重ね合わせ, 置いた識別子, 行, 重ねの秒};

fn ずらす(秒: f64) -> 時刻をずらす量 {
    時刻をずらす量::符号付きの秒数から作成する(秒).expect("有限")
}

fn 差(行の数: i32) -> 行の差 {
    行の差::手前へ動かした行の数から作成する(行の数)
}

fn 行き先(
    重ね: &重ね合わせ,
    識別子: &str,
    秒: f64,
    行の数: i32,
) -> 置いたクリップの行き先 {
    重ね
        .行の並び()
        .ずらした行き先を求める(&置いた識別子(識別子), ずらす(秒), 差(行の数))
        .expect("置いたクリップがある")
}

fn 行と秒(番号: usize, 秒: f64) -> 置いたクリップの行き先 {
    置いたクリップの行き先 {
        行: 行(番号),
        始まりの時刻: 重ねの秒(秒),
    }
}

// 二行の重ね合わせは、行0に 置-1[0,2)、行1に 置-2[0,1) と 置-3[3,4) を置いている。

#[test]
fn 同じ行で後ろへずらすと次の置いたクリップにぶつかった所で止まる() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(行き先(&重ね, "置-2", 5.0, 0), 行と秒(1, 2.0));
}

#[test]
fn 同じ行で前へずらすと前の置いたクリップの終わりで止まり_何も無ければ0秒で止まる() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(行き先(&重ね, "置-3", -10.0, 0), 行と秒(1, 1.0));
    assert_eq!(行き先(&重ね, "置-1", -10.0, 0), 行と秒(0, 0.0));
}

#[test]
fn 空きの中ならずらした時刻へ置き_差0なら今の行き先のまま() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(行き先(&重ね, "置-3", 2.5, 0), 行と秒(1, 5.5));
    assert_eq!(行き先(&重ね, "置-3", 0.0, 0), 行と秒(1, 3.0));
    assert_eq!(
        重ね.行の並び().今の行き先(&置いた識別子("置-3")),
        Ok(行と秒(1, 3.0))
    );
}

#[test]
fn 行の差は行の数へ収める() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(行き先(&重ね, "置-3", 0.0, -5), 行と秒(0, 3.0));
    assert_eq!(行き先(&重ね, "置-3", 0.0, 7), 行と秒(1, 3.0));
    assert_eq!(行き先(&重ね, "置-3", 0.0, i32::MIN), 行と秒(0, 3.0));
    assert_eq!(行き先(&重ね, "置-3", 0.0, i32::MAX), 行と秒(1, 3.0));
}

#[test]
fn 動かした先の行で基点が塞がっていれば望む時刻に最も近い空きへ置く() {
    let 重ね = 二行の重ね合わせ();
    // 置-1(長さ2秒)を行1へ。行1で長さ2秒を置ける始まりは、1秒ちょうど(置-2 と 置-3 の間)と4秒以降である。
    assert_eq!(行き先(&重ね, "置-1", 0.0, 1), 行と秒(1, 1.0));
    assert_eq!(行き先(&重ね, "置-1", 3.0, 1), 行と秒(1, 4.0));
}

#[test]
fn 求めた行き先へは時間が重ならずに動かせる() {
    for (識別子, 秒, 行の数) in [
        ("置-2", 5.0, 0),
        ("置-3", -10.0, 0),
        ("置-1", 0.0, 1),
        ("置-1", 3.0, 1),
    ] {
        let mut 重ね = 二行の重ね合わせ();
        let 先 = 行き先(&重ね, 識別子, 秒, 行の数);
        重ね
            .置いたクリップを動かす(&置いた識別子(識別子), 先.行, 先.始まりの時刻)
            .expect("ぶつかった所で止めた行き先は重ならない");
    }
}

#[test]
fn 無い置いたクリップの行き先は求めない() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(
        重ね.行の並び().ずらした行き先を求める(
            &置いた識別子("無い"),
            ずらす(1.0),
            差(0)
        ),
        Err(
            重ね合わせの操作エラー::置いたクリップが見つからない(
                置いた識別子("無い")
            )
        )
    );
}

#[test]
fn 時刻をずらす量は有限でない秒数を拒み_前へずらしても0秒より前へ行かない() {
    assert!(時刻をずらす量::符号付きの秒数から作成する(f64::NAN).is_err());
    assert!(時刻をずらす量::符号付きの秒数から作成する(f64::NEG_INFINITY).is_err());
    assert_eq!(
        ずらす(-3.0).ずらした時刻を求める(重ねの秒(1.0)),
        重ねの秒(0.0)
    );
    assert_eq!(
        ずらす(1.5).ずらした時刻を求める(重ねの秒(1.0)),
        重ねの秒(2.5)
    );
}
