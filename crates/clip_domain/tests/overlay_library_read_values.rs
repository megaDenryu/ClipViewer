//! 重ね合わせのファイルの読み込みの試験。成立しない置いたクリップの値(映す矩形・繰り返しの回数・区間・時刻・識別子)を、
//! 行の番号と部品の並びの中の位置を付けて型付きのエラーで拒むことを確かめる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::行;
use support::overlay_library_text::{本文, 読む};

fn 置いたクリップの不備(壊し方: (&str, &str)) -> 置いたクリップの値の不備 {
    match 読む(&本文(&[壊し方])) {
        Err(重ね合わせのファイルの読み込みエラー::置いたクリップが不正 { 行: 番号, 位置, 理由 })
            if 番号 == 行(0) && 位置.番号() == 0 =>
        {
            理由
        }
        その他 => panic!("{壊し方:?} が置いたクリップの不備にならず {その他:?}"),
    }
}

#[test]
fn 成立しない置いたクリップの値を行と位置付きで拒む() {
    assert!(matches!(
        置いたクリップの不備((r#""rect":{"x":0.0"#, r#""rect":{"x":10.0"#)),
        置いたクリップの値の不備::映す矩形が不正(
            映す矩形エラー::右へはみ出す { .. }
        )
    ));
    assert!(matches!(
        置いたクリップの不備((r#""h":100.0},"volume""#, r#""h":4.0},"volume""#)),
        置いたクリップの値の不備::映す矩形が不正(
            映す矩形エラー::小さすぎる { .. }
        )
    ));
    assert!(matches!(
        置いたクリップの不備((r#""repeat":2"#, r#""repeat":0"#)),
        置いたクリップの値の不備::繰り返しの回数が不正(_)
    ));
    assert!(matches!(
        置いたクリップの不備((r#""start":1.0"#, r#""start":3.0"#)),
        置いたクリップの値の不備::区間が不正(_)
    ));
    assert!(matches!(
        置いたクリップの不備((r#""at":0.0"#, r#""at":-1.0"#)),
        置いたクリップの値の不備::時刻が不正(_)
    ));
    assert!(matches!(
        置いたクリップの不備((r#""id":"p1""#, r#""id":"""#)),
        置いたクリップの値の不備::識別子が不正(_)
    ));
}

#[test]
fn 位置はitemsの中の順番であり_始まりの時刻の順に並べ直した後の順番ではない() {
    let 先に始まる壊れた置いたクリップ = r#"{"id":"p0","name":"零","video":0,"start":1.0,"end":2.0,"repeat":0,"crop":{"x":0.0,"y":0.0,"w":100.0,"h":100.0},"at":0.0,"rect":{"x":0.0,"y":0.0,"w":100.0,"h":100.0},"volume":1.0,"muted":false}"#;
    let 本文 = 本文(&[
        (r#""at":0.0"#, r#""at":5.0"#),
        (
            r#""muted":false}]"#,
            &format!(r#""muted":false}},{先に始まる壊れた置いたクリップ}]"#),
        ),
    ]);
    match 読む(&本文) {
        Err(重ね合わせのファイルの読み込みエラー::置いたクリップが不正 { 行: 番号, 位置, .. }) => {
            assert_eq!(番号, 行(0));
            assert_eq!(位置, 部品の並びの中の位置::番号から作成する(1));
        }
        その他 => panic!("置いたクリップが不正にならず {その他:?}"),
    }
}
