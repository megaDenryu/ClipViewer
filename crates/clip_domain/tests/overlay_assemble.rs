//! 重ね合わせの部品一式から重ね合わせを組み立てる口の試験。行の中を始まりの時刻の順に並べ、写しを作ると同じ値に戻ることと、丸めの許容誤差の扱いを確かめる。
#![allow(clippy::expect_used)]

mod support;

use support::overlay::行ごとの識別子;
use support::overlay_library::{置くもの, 部品一式};

#[test]
fn 行の中は始まりの時刻の順に並び_空の行も残り_写しを作ると同じ値に戻る() {
    let 後 = 置くもの::既定("後", (0.0, 1.0), 5.0);
    let 先 = 置くもの::既定("先", (0.0, 2.0), 0.0);
    let 重ね = 部品一式(1, &[&[後, 先], &[]])
        .重ね合わせへ組み立てる()
        .expect("組み立てられる");
    assert_eq!(行ごとの識別子(&重ね), vec![vec!["先", "後"], vec![]]);
    let 並べた = 部品一式(
        1,
        &[
            &[
                置くもの::既定("先", (0.0, 2.0), 0.0),
                置くもの::既定("後", (0.0, 1.0), 5.0),
            ],
            &[],
        ],
    );
    assert_eq!(重ね.部品一式を複製する(), 並べた);
    assert_eq!(
        並べた.重ね合わせへ組み立てる().expect("組み立てられる"),
        重ね
    );
}

#[test]
fn 丸めの許容誤差以下の食い込みは接しているとみなす() {
    let 甲 = 置くもの::既定("甲", (0.0, 0.1), 0.0);
    let mut 乙 = 置くもの::既定("乙", (0.0, 1.0), 0.0);
    乙.始まり = 0.1 - 0.0000005;
    assert!(部品一式(1, &[&[甲, 乙]]).重ね合わせへ組み立てる().is_ok());
}
