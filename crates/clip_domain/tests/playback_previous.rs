//! 前のクリップへ戻す規則の試験。シーケンス再生のときだけ、前の再生できるクリップの開始へ戻す。
//! 無効なクリップと長さ0のクリップは飛ばし、先頭のクリップにいるときはそのクリップの開始へ、末尾以降は最後のクリップの前へ戻す。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{秒, 試験用のスタック, 長さ};

/// タイムライン上の秒の位置から戻したときの、戻した先の位置の秒とクリップの識別子。戻せなければ無い。
fn 戻す(スタック: &クリップスタック, 位置: f64) -> Option<(f64, String)> {
    match 再生位置::シーケンス再生(秒(位置)).前のクリップへ戻す(スタック)
    {
        前へ戻した結果::戻した {
            位置, クリップ
        } => Some((位置.位置の秒数(), クリップ.識別子().文字列().to_string())),
        前へ戻した結果::戻せない => None,
    }
}

#[test]
fn 前の再生できるクリップの開始へ戻し_無効と長さ0のクリップは飛ばす() {
    let スタック = 試験用のスタック();
    assert_eq!(戻す(&スタック, 8.0), Some((6.0, "C".into())));
    assert_eq!(戻す(&スタック, 6.5), Some((0.0, "A".into())));
}

#[test]
fn 先頭のクリップではその開始へ戻し_末尾以降では最後のクリップの前へ戻す() {
    let スタック = 試験用のスタック();
    assert_eq!(戻す(&スタック, 3.0), Some((0.0, "A".into())));
    assert_eq!(戻す(&スタック, 11.0), Some((6.0, "C".into())));
}

#[test]
fn シーケンス再生でなければ戻さない() {
    let スタック = 試験用のスタック();
    let 単独 = 再生位置::単独クリップ再生(長さ(1.0)).前のクリップへ戻す(&スタック);
    assert_eq!(単独, 前へ戻した結果::戻せない);
    let 空の並び = クリップスタック::default();
    assert_eq!(戻す(&空の並び, 0.0), None);
}
