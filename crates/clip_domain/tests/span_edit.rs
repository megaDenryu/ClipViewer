//! 区間の編集の決まりの試験。端を上限の内側へ収めることと、最小の長さを保つことと、長さを保って動かすことを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{動画上の区間, 区間の編集の決まり, 時刻, 時間の長さ};

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}

/// 上限10秒、最小の長さ0.5秒の決まり。
fn 決まり() -> 区間の編集の決まり {
    let 長さ = |秒| 時間の長さ::作成する(秒).expect("長さ");
    区間の編集の決まり::作成する(長さ(10.0), 長さ(0.5))
}

fn 近い(実際: 動画上の区間, 開始: f64, 終了: f64) -> bool {
    (実際.開始().秒数() - 開始).abs() < 1e-9 && (実際.終了().秒数() - 終了).abs() < 1e-9
}

#[test]
fn 開始は終了より最小の長さ以上前に止まり_負と非数は0秒になる() {
    assert!(近い(決まり().開始を動かす(区間(2.0, 4.0), 3.0), 3.0, 4.0));
    assert!(近い(決まり().開始を動かす(区間(2.0, 4.0), 3.9), 3.5, 4.0));
    assert!(近い(
        決まり().開始を動かす(区間(2.0, 4.0), -1.0),
        0.0,
        4.0
    ));
    assert!(近い(
        決まり().開始を動かす(区間(2.0, 4.0), f64::NAN),
        0.0,
        4.0
    ));
}

#[test]
fn 終了は開始より最小の長さ以上後ろで上限を超えない() {
    assert!(近い(決まり().終了を動かす(区間(2.0, 4.0), 2.1), 2.0, 2.5));
    assert!(近い(
        決まり().終了を動かす(区間(2.0, 4.0), 12.0),
        2.0,
        10.0
    ));
}

#[test]
fn 長さを保って動かすと終了が上限に着く位置で止まる() {
    assert!(近い(
        決まり().長さを保って動かす(区間(2.0, 4.0), 5.0),
        5.0,
        7.0
    ));
    assert!(近い(
        決まり().長さを保って動かす(区間(2.0, 4.0), 9.0),
        8.0,
        10.0
    ));
    assert!(近い(
        決まり().長さを保って動かす(区間(2.0, 4.0), -3.0),
        0.0,
        2.0
    ));
}

#[test]
fn 区間の帯の秒は刻みへ丸め_上限を超えるなら上限以下の刻みの倍数にする() {
    let 刻み = 時間の長さ::定数の秒数から作る(0.01);
    let 最小 = 時間の長さ::定数の秒数から作る(0.05);
    for 上限の秒 in [1.13, 58.43, 10.047] {
        let 上限 = 時間の長さ::作成する(上限の秒).expect("長さ");
        let 決まり = 区間の編集の決まり::作成する(上限, 最小);
        let 右端 = 決まり.刻みへ丸めて上限の内側へ収める(上限の秒, 刻み);
        assert!(右端 <= 上限の秒, "{上限の秒}: {右端} が上限を超える");
        let 区間 = 決まり.終了を動かす(区間(0.0, 0.5), 右端);
        assert!(
            区間.終了().秒数() <= 上限の秒,
            "{上限の秒}: 終了が上限を超える"
        );
        assert!(((区間.終了().秒数() * 100.0).round() / 100.0 - 区間.終了().秒数()).abs() < 1e-9);
    }
}

#[test]
fn 終了を上限ちょうどまで動かしても上限を超えない() {
    for 上限の秒 in [1.13, 58.43] {
        let 上限 = 時間の長さ::作成する(上限の秒).expect("長さ");
        let 決まり =
            区間の編集の決まり::作成する(上限, 時間の長さ::定数の秒数から作る(0.05));
        let 区間 = 決まり.終了を動かす(区間(0.37, 0.5), 上限の秒);
        assert_eq!(区間.終了().秒数(), 上限の秒);
    }
}
