//! 重ね合わせ上の時刻に行ごとに映すものを求める処理の試験。行の並び・周回と動画上の位置・同じ行の中の行き先・末尾のコマ。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 二行の重ね合わせ, 受け継いだ値, 置いた識別子, 置いた連番の発行元,
    重ねの秒, 零番の動画へ置く,
};
use support::overlay_playback::{
    再生の中身, 映すものの一覧, 映すものの要約, 行き先
};

const 止める: 末尾での振る舞い = 末尾での振る舞い::止まる;

fn 再生(識別子: &str, 動画上: f64) -> 映すものの要約 {
    映すものの要約::再生(識別子.to_string(), 動画上)
}

fn 末尾のコマ(識別子: &str, 動画上: f64) -> 映すものの要約 {
    映すものの要約::末尾のコマ(識別子.to_string(), 動画上)
}

#[test]
fn 行ごとに奥から手前の順で返し当たる置いたクリップが無い行は何も映さない() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(
        映すものの一覧(&重ね, 0.5, 止める),
        vec![再生("置-1", 0.5), 再生("置-2", 5.5)]
    );
    assert_eq!(
        映すものの一覧(&重ね, 2.5, 止める),
        vec![映すものの要約::無し, 映すものの要約::無し]
    );
    assert_eq!(
        映すものの一覧(&重ね, 3.25, 止める),
        vec![映すものの要約::無し, 再生("置-3", 7.25)]
    );
    let 空 = 一本の動画の重ね合わせ();
    assert_eq!(
        空.重ね合わせ上の時刻に映すものを求める(重ねの秒(0.0), 止める)
            .count(),
        0
    );
}

#[test]
fn 重ね合わせの長さ以降は各行が最後の置いたクリップの区間の終わりのコマを映す() {
    let mut 重ね = 二行の重ね合わせ();
    for 時刻 in [4.0, 30.0] {
        assert_eq!(
            映すものの一覧(&重ね, 時刻, 止める),
            vec![末尾のコマ("置-1", 2.0), 末尾のコマ("置-3", 8.0)],
            "{時刻}秒"
        );
    }
    重ね
        .置いたクリップを取り除く(&置いた識別子("置-1"))
        .expect("ある");
    assert_eq!(
        映すものの一覧(&重ね, 4.0, 止める),
        vec![映すものの要約::無し, 末尾のコマ("置-3", 8.0)],
        "置いたクリップの無い行は何も映さない"
    );
}

#[test]
fn 繰り返す置いたクリップは周回と区間の中の位置を返し最後の周回より前は開始へ戻る() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(10.0, 12.0, 3), 1.0, &mut 発行元).expect("置ける");
    let 二周目 = 再生の中身(&重ね, 4.5, 0, 止める);
    assert_eq!(二周目.周回.一から数えた順番(), 2);
    assert_eq!(二周目.動画上の位置.秒数(), 11.5);
    assert_eq!(行き先(&二周目), "開始へ戻る");
    let 三周目 = 再生の中身(&重ね, 5.0, 0, 止める);
    assert_eq!(三周目.周回.一から数えた順番(), 3);
    assert_eq!(三周目.動画上の位置.秒数(), 10.0);
    assert_eq!(行き先(&三周目), "止まる");
}

#[test]
fn 境目ちょうどの時刻は後ろの置いたクリップが映し前の最後の周回は次の置いたクリップへ進む() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(0.0, 1.0, 1), 0.0, &mut 発行元).expect("置ける");
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 1), 1.0, &mut 発行元).expect("接して置ける");
    零番の動画へ置く(&mut 重ね, 受け継いだ値(8.0, 9.0, 1), 2.5, &mut 発行元)
        .expect("隙間を空けて置ける");
    assert_eq!(映すものの一覧(&重ね, 1.0, 止める), vec![再生("置-2", 5.0)]);
    let 直前 = 再生の中身(&重ね, 0.999_999, 0, 止める);
    assert_eq!(直前.置いたクリップ.識別子().文字列(), "置-1");
    assert_eq!(行き先(&直前), "進む:置-2");
    assert_eq!(
        行き先(&再生の中身(&重ね, 1.5, 0, 止める)),
        "止まる",
        "次の置いたクリップとの間に隙間がある"
    );
}
