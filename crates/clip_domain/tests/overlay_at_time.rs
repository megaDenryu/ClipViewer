//! 重ね合わせ上の時刻に行ごとに映すものを求める処理の試験。行の並び・周回と動画上の位置・区間の終わりの行き先。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 二行の重ね合わせ, 受け継いだ値, 置いた連番の発行元, 重ねの秒,
    零番の動画へ置く,
};
use support::span_end::区間;

/// 時刻に行ごとに映すものを、映す置いたクリップの識別子(何も映さないなら無い)と動画上の秒数で表す。
fn 映すものの一覧(重ね: &重ね合わせ, 時刻: f64) -> Vec<Option<(String, f64)>> {
    重ね
        .その時刻に映すもの(重ねの秒(時刻))
        .map(|行| match 行.中身 {
            行が映す中身::置いたクリップを映す(中身) => Some((
                中身.置いたクリップ.識別子().文字列().to_string(),
                中身.動画上の位置.秒数(),
            )),
            行が映す中身::何も映さない => None,
        })
        .collect()
}

fn 再生の中身(
    重ね: &重ね合わせ,
    時刻: f64,
    行: usize,
) -> 置いたクリップの再生の中身<'_> {
    let 映すもの = 重ね
        .その時刻に映すもの(重ねの秒(時刻))
        .nth(行)
        .expect("行がある");
    assert_eq!(映すもの.行, 行の番号::番号から作成する(行));
    match 映すもの.中身 {
        行が映す中身::置いたクリップを映す(中身) => 中身,
        行が映す中身::何も映さない => panic!("{時刻}秒の行{行}は何も映さない"),
    }
}

#[test]
fn 行ごとに奥から手前の順で返し当たる置いたクリップが無い行は何も映さない() {
    let 重ね = 二行の重ね合わせ();
    assert_eq!(
        映すものの一覧(&重ね, 0.5),
        vec![
            Some(("置-1".to_string(), 0.5)),
            Some(("置-2".to_string(), 5.5))
        ]
    );
    assert_eq!(映すものの一覧(&重ね, 2.5), vec![None, None]);
    assert_eq!(
        映すものの一覧(&重ね, 3.25),
        vec![None, Some(("置-3".to_string(), 7.25))]
    );
    assert_eq!(映すものの一覧(&重ね, 4.0), vec![None, None]);
    assert_eq!(
        一本の動画の重ね合わせ()
            .その時刻に映すもの(重ねの秒(0.0))
            .count(),
        0
    );
}

#[test]
fn 繰り返す置いたクリップは周回と区間の中の位置を返し最後の周回より前は開始へ戻る() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(10.0, 12.0, 3), 1.0, &mut 発行元).expect("置ける");
    let 二周目 = 再生の中身(&重ね, 4.5, 0);
    assert_eq!(二周目.周回.一から数えた順番(), 2);
    assert_eq!(二周目.動画上の位置.秒数(), 11.5);
    assert_eq!(
        二周目.区間の終わりの行き先,
        区間の終わりの行き先::区間の開始へ戻る
    );
    let 三周目 = 再生の中身(&重ね, 5.0, 0);
    assert_eq!(三周目.周回.一から数えた順番(), 3);
    assert_eq!(三周目.動画上の位置.秒数(), 10.0);
    assert_eq!(三周目.区間の終わりの行き先, 区間の終わりの行き先::止まる);
    assert_eq!(映すものの一覧(&重ね, 7.0), vec![None]);
}

#[test]
fn 境目ちょうどの時刻は後ろの置いたクリップが映し前の最後の周回は次の区間へ進む() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(0.0, 1.0, 1), 0.0, &mut 発行元).expect("置ける");
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 1), 1.0, &mut 発行元).expect("接して置ける");
    零番の動画へ置く(&mut 重ね, 受け継いだ値(8.0, 9.0, 1), 2.5, &mut 発行元)
        .expect("隙間を空けて置ける");
    assert_eq!(
        映すものの一覧(&重ね, 1.0),
        vec![Some(("置-2".to_string(), 5.0))]
    );
    let 直前 = 再生の中身(&重ね, 0.999_999, 0);
    assert_eq!(直前.置いたクリップ.識別子().文字列(), "置-1");
    assert_eq!(
        直前.区間の終わりの行き先,
        区間の終わりの行き先::別の区間へ進む(区間(5.0, 6.0))
    );
    assert_eq!(
        再生の中身(&重ね, 1.5, 0).区間の終わりの行き先,
        区間の終わりの行き先::止まる,
        "次の置いたクリップとの間に隙間がある"
    );
}
