//! 最も手前に新しい行を足して置く操作の試験。空いている行があっても新しい行へ置くこと、行が上限まであるときと置く前の確かめに通らないときは拒むこと。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 受け継いだ値, 置いた連番の発行元, 行ごとの識別子, 重ねの秒,
};
use support::長さ;

fn 零番の動画の手前に新しい行を足して置く(
    重ね合わせ: &mut 重ね合わせ,
    受け継いだ値: クリップから受け継いだ値,
    始まり: f64,
    発行元: &mut 置いた連番の発行元,
) -> Result<置いたクリップの識別子, 重ね合わせの操作エラー> {
    重ね合わせ.手前に新しい行を足して置く(
        受け継いだ値,
        動画の番号::最初,
        重ねの秒(始まり),
        長さ(100.0),
        発行元,
    )
}

#[test]
fn 空いている行があっても最も手前に新しい行を足して置く() {
    let mut 重ね合わせ = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    for 始まり in [0.0, 5.0, 10.0] {
        零番の動画の手前に新しい行を足して置く(
            &mut 重ね合わせ,
            受け継いだ値(0.0, 1.0, 1),
            始まり,
            &mut 発行元,
        )
        .expect("行を足して置ける");
    }
    assert_eq!(
        行ごとの識別子(&重ね合わせ),
        vec![vec!["置-1"], vec!["置-2"], vec!["置-3"]]
    );
}

#[test]
fn 行が同時に重ねられる行の数まであれば拒み重ね合わせを変えない() {
    let mut 重ね合わせ = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    for _ in 0..同時に重ねられる行の数 {
        零番の動画の手前に新しい行を足して置く(
            &mut 重ね合わせ,
            受け継いだ値(0.0, 1.0, 1),
            0.0,
            &mut 発行元,
        )
        .expect("行を足して置ける");
    }
    let 置く前 = 重ね合わせ.clone();
    assert_eq!(
        零番の動画の手前に新しい行を足して置く(
            &mut 重ね合わせ,
            受け継いだ値(0.0, 1.0, 1),
            50.0,
            &mut 発行元,
        ),
        Err(重ね合わせの操作エラー::行の数が上限に達している)
    );
    assert_eq!(重ね合わせ, 置く前);
}

#[test]
fn 区間の終わりが動画の長さより後ろなら拒み行を足さない() {
    let mut 重ね合わせ = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    let 結果 = 零番の動画の手前に新しい行を足して置く(
        &mut 重ね合わせ,
        受け継いだ値(99.0, 101.0, 1),
        0.0,
        &mut 発行元,
    );
    assert!(matches!(
        結果,
        Err(重ね合わせの操作エラー::区間が動画の長さを超える { .. })
    ));
    assert_eq!(重ね合わせ.行の並び().行の数(), 0);
}
