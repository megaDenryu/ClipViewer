//! スタックからの読み替えの試験の共有部品。

use clip_domain::*;

use super::overlay::置いた連番の発行元;
use super::{クリップを作る, 長さ};

/// 開始の秒をずらした、1秒×1回の再生できるクリップを個数だけ並べたスタック。識別子は「1」「2」…である。
pub fn 再生できるクリップを並べたスタックを作る(
    個数: u32,
) -> クリップスタック {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    クリップスタック::一覧から作成する(
        (1..=個数)
            .map(|番号| {
                let 開始 = f64::from(番号);
                クリップを作る(
                    &番号.to_string(),
                    開始,
                    開始 + 1.0,
                    一回,
                    トリガー::自動進行,
                )
            })
            .collect(),
    )
    .expect("識別子は重複しない")
}

/// 動画の長さ100秒・16:9の出力で、スタックから並べる。
pub fn 十六対九の出力でスタックから重ね合わせを並べる(
    スタック: &クリップスタック,
) -> Result<スタックから並べた結果, スタックから並べるエラー> {
    出力のアスペクト比を指定してスタックから重ね合わせを並べる(
        スタック,
        アスペクト比設定::ワイド16対9,
    )
}

/// 動画の長さ100秒で、指定の出力のアスペクト比からスタックから並べる。
pub fn 出力のアスペクト比を指定してスタックから重ね合わせを並べる(
    スタック: &クリップスタック,
    出力のアスペクト比: アスペクト比設定,
) -> Result<スタックから並べた結果, スタックから並べるエラー> {
    重ね合わせ::スタックから並べる(
        スタック,
        入力された動画パス::作成する("D:\\動画\\練習.mp4".to_string()).正規化する(),
        長さ(100.0),
        出力のアスペクト比,
        &mut 置いた連番の発行元::default(),
    )
}

/// 奥の行から順に、各行の置いたクリップの映す矩形を(左端・上端・幅・高さ)の百分率の数値で並べる。
pub fn 奥の行から並べた映す矩形の数値(
    重ね合わせ: &重ね合わせ
) -> Vec<[f64; 4]> {
    重ね合わせ
        .行の並び()
        .奥から手前の順の行()
        .iter()
        .flat_map(|行| 行.置いたクリップの並び().iter())
        .map(|置いた| {
            let 矩形 = 置いた.映す矩形();
            [
                矩形.左端().数値(),
                矩形.上端().数値(),
                矩形.幅().数値(),
                矩形.高さ().数値(),
            ]
        })
        .collect()
}
