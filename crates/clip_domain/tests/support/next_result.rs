//! 次へ進めた結果の期待値と、それを作る試験の補助。

use clip_domain::*;

use super::秒;

/// 次へ進めた結果の期待値とは、試験で比べやすいように、次へ進めた結果を位置の秒数とクリップの識別子の文字列へ写したもののことである。
#[derive(Debug, PartialEq)]
pub enum 次へ進めた結果の期待値 {
    進んだ(f64, String),
    止めた(f64, String),
    進めない(進めない理由),
}

pub fn 進める(
    スタック: &クリップスタック,
    位置: f64,
    操作: 進める操作,
    全体の末尾: 末尾での振る舞い,
) -> 次へ進めた結果の期待値 {
    let 名前 = |クリップ: &クリップ| クリップ.識別子().文字列().to_string();
    match 再生位置::シーケンス再生(秒(位置)).操作で次へ進める(操作, スタック, 全体の末尾)
    {
        次へ進めた結果::進んだ {
            位置, クリップ
        } => 次へ進めた結果の期待値::進んだ(位置.位置の秒数(), 名前(クリップ)),
        次へ進めた結果::末尾で止めた {
            位置,
            最後のクリップ,
        } => 次へ進めた結果の期待値::止めた(位置.位置の秒数(), 名前(最後のクリップ)),
        次へ進めた結果::進めない(理由) => {
            次へ進めた結果の期待値::進めない(理由)
        }
    }
}

pub fn 進んだ(位置: f64, 名前: &str) -> 次へ進めた結果の期待値 {
    次へ進めた結果の期待値::進んだ(位置, 名前.to_string())
}

pub fn 止めた(位置: f64, 名前: &str) -> 次へ進めた結果の期待値 {
    次へ進めた結果の期待値::止めた(位置, 名前.to_string())
}
