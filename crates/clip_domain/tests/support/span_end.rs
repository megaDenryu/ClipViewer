//! 区間の終わりの行き先の試験の共有部品。
#![allow(dead_code, clippy::expect_used)]

use clip_domain::*;

use super::{クリップを作る, 秒, 試験用の条件};

pub fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 開始 = 動画上の秒::作成する(開始).expect("秒");
    let 終了 = 動画上の秒::作成する(終了).expect("秒");
    動画上の区間::作成する(開始, 終了).expect("区間")
}

/// 先[0,2) 2回 自動進行 → 後[5,9) 1回 自動進行 の並び。
pub fn 自動進行の二つ(先のトリガー: トリガー) -> クリップスタック {
    let 二回 = リピート設定::回数指定(リピート回数::作成する(2).expect("範囲内"));
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    クリップスタック::一覧から作成する(vec![
        クリップを作る("先", 0.0, 2.0, 二回, 先のトリガー),
        クリップを作る("後", 5.0, 9.0, 一回, トリガー::自動進行),
    ])
    .expect("重複しない")
}

pub fn シーケンスの行き先(
    スタック: &クリップスタック,
    位置: f64,
    全体の末尾: 末尾での振る舞い,
) -> 区間の終わりの行き先 {
    let 条件 = 試験用の条件(スタック, 全体の末尾);
    再生位置::シーケンス再生(秒(位置)).区間の終わりの行き先(&条件)
}
