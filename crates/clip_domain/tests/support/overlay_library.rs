//! 重ね合わせの各項目の試験の共有部品。置いたクリップの各項目と重ね合わせの各項目を短く作る。

use clip_domain::*;

/// 置いたクリップの各項目。区間は動画上の開始と終了、矩形は(左端, 上端, 幅, 高さ)の百分率で渡す。
pub struct 置くもの<'名前> {
    pub 識別子: &'名前 str,
    pub 名前: &'名前 str,
    pub 動画: usize,
    pub 区間: (f64, f64),
    pub 回数: u32,
    pub クロップ: (f64, f64, f64, f64),
    pub 始まり: f64,
    pub 矩形: (f64, f64, f64, f64),
    pub 音量: f64,
    pub 消音: bool,
}

impl 置くもの<'_> {
    /// 0番の動画の区間を1回、始まり0秒・全体の矩形・元の大きさで置くもの。
    pub fn 既定(識別子: &str, 区間: (f64, f64), 始まり: f64) -> 置くもの<'_> {
        置くもの {
            識別子,
            名前: "名前",
            動画: 0,
            区間,
            回数: 1,
            クロップ: (0.0, 0.0, 100.0, 100.0),
            始まり,
            矩形: (0.0, 0.0, 100.0, 100.0),
            音量: 1.0,
            消音: false,
        }
    }

    pub fn 各項目(&self) -> 置いたクリップの各項目 {
        let 秒 = |値| 時刻::作成する(値).expect("時刻");
        let (x, y, w, h) = self.矩形;
        let 百 = 百分率::範囲へ収める;
        置いたクリップの各項目 {
            識別子: 置いたクリップの識別子::文字列から作成する(
                self.識別子.to_string(),
            )
            .expect("識別子"),
            受け継いだ値: クリップから受け継いだ値 {
                名前: クリップ名::作成する(self.名前.to_string()),
                区間: 動画上の区間::作成する(秒(self.区間.0), 秒(self.区間.1)).expect("区間"),
                リピート回数: リピート回数::作成する(self.回数).expect("回数"),
                クロップ: クロップ範囲::各値を範囲へ収めて作成する(
                    self.クロップ.0,
                    self.クロップ.1,
                    self.クロップ.2,
                    self.クロップ.3,
                ),
            },
            動画: 動画の番号::番号から作成する(self.動画),
            始まりの時刻: 重ね合わせ上の秒::作成する(self.始まり).expect("時刻"),
            映す矩形: 映す矩形::作成する(百(x), 百(y), 百(w), 百(h)).expect("矩形"),
            音の設定: 置いたクリップの音の設定 {
                音量: 音量::範囲へ収めて作る(self.音量),
                消音しているか: self.消音,
            },
        }
    }
}

/// 行ごとの置くものから、16:9 で、渡した本数の動画を表に持つ重ね合わせの各項目を作る。
pub fn 各項目(
    動画の本数: usize, 行の並び: &[&[置くもの<'_>]]
) -> 重ね合わせの各項目 {
    重ね合わせの各項目 {
        縦横比: 重ねる画面の縦横比::ワイド16対9,
        動画の表: 使う動画の表::並びから作成する(
            (0..動画の本数)
                .map(|番号| {
                    入力された動画パス::作成する(format!(r"D:\動画\{番号}.mp4")).正規化する()
                })
                .collect(),
        ),
        行の並び: 行の並び
            .iter()
            .map(|行| タイムラインの行の各項目 {
                置いたクリップの並び: 行.iter().map(置くもの::各項目).collect(),
            })
            .collect(),
    }
}

pub fn 日時(ミリ秒: u64) -> ライブラリの日時 {
    ライブラリの日時::紀元からのミリ秒で作成する(ミリ秒).expect("日時")
}
