pub fn 識別子(文字列: &str) -> クリップ識別子 {
    クリップ識別子::文字列から作成する(文字列.to_string()).expect("空でない")
}

pub fn 秒(値: f64) -> タイムライン上の秒 {
    タイムライン上の秒::作成する(値).expect("有効な秒数")
}

pub fn クリップを作る(
    識別子: &str,
    開始: f64,
    終了: f64,
    リピート: リピート設定,
    トリガー: トリガー,
) -> クリップ {
    let 識別子 = self::識別子(識別子);
    let mut クリップ =
        クリップ::既定値で作成する(識別子, クリップ名::作成する("名前".to_string()));
    let 開始 = 動画上の秒::作成する(開始).expect("有効な秒数");
    let 終了 = 動画上の秒::作成する(終了).expect("有効な秒数");
    クリップ.区間 = 動画上の区間::作成する(開始, 終了).expect("開始が終了以前");
    クリップ.リピート = リピート;
    クリップ.トリガー = トリガー;
    クリップ
}

/// 試験用のスタックとは、A[0,6) 2秒×3回 Space待ち / B 無効 / D 長さ0 / C[6,7) 1秒無限 Enter待ち / E[7,11) 4秒×1回 クリック待ち の並びのことである。
pub fn 試験用のスタック() -> クリップスタック {
    let 三回 = リピート設定::回数指定(リピート回数::作成する(3).expect("範囲内"));
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let mut 無効 = クリップを作る("B", 0.0, 5.0, 一回, トリガー::自動進行);
    無効.有効か = false;
    クリップスタック::一覧から作成する(vec![
        クリップを作る("A", 10.0, 12.0, 三回, トリガー::Spaceキー待ち),
        無効,
        クリップを作る("D", 30.0, 30.0, 一回, トリガー::自動進行),
        クリップを作る(
            "C",
            20.0,
            21.0,
            リピート設定::無限ループ,
            トリガー::Enterキー待ち,
        ),
        クリップを作る("E", 40.0, 44.0, 一回, トリガー::クリック待ち),
    ])
    .expect("識別子は重複しない")
}

/// 連番の発行元とは、「発行-1」「発行-2」…の識別子を順に発行する、試験用の決定的な発行元のことである。
#[derive(Default)]
pub struct 連番の発行元 {
    発行した数: u32,
}

impl クリップ識別子の発行元 for 連番の発行元 {
    fn 新しい識別子を発行する(&mut self) -> クリップ識別子 {
        self.発行した数 += 1;
        識別子(&format!("発行-{}", self.発行した数))
    }
}

/// 試験用の条件とは、動画の長さ100秒・等倍で、指定のスタックと全体の末尾の振る舞いを参照する時計を進める条件のことである。
pub fn 試験用の条件(
    スタック: &クリップスタック,
    全体の末尾: 末尾での振る舞い,
) -> 時計を進める条件<'_> {
    時計を進める条件 {
        スタック,
        動画の長さ: 時間の長さ::作成する(100.0).expect("有効な長さ"),
        速度: 再生速度::等倍,
        全体の末尾,
    }
}

pub fn 長さ(値: f64) -> 時間の長さ {
    時間の長さ::作成する(値).expect("有効な長さ")
}
