//! 重ね合わせの再生の試験の共有部品。行ごとに映すものと区間の終わりの行き先を、比べやすい値へ写す。

use clip_domain::*;

use super::overlay::重ねの秒;

/// 映すものの要約とは、試験で行ごとに何を映すかを、識別子の文字列と動画上の秒数で表したもののことである。
#[derive(Debug, PartialEq)]
pub enum 映すものの要約 {
    再生(String, f64),
    末尾のコマ(String, f64),
    無し,
}

/// 時刻に行ごとに映すものを、奥の行から順に要約する。
pub fn 映すものの一覧(
    重ね: &重ね合わせ,
    時刻: f64,
    全体の末尾: 末尾での振る舞い,
) -> Vec<映すものの要約> {
    重ね
        .重ね合わせ上の時刻に映すものを求める(重ねの秒(時刻), 全体の末尾)
        .map(|行| match 行.映し方 {
            行の映し方::置いたクリップを映す(中身) => {
                映すものの要約::再生(
                    中身.置いたクリップ.識別子().文字列().to_string(),
                    中身.動画上の位置.秒数(),
                )
            }
            行の映し方::末尾で最後のコマを映す {
                置いたクリップ,
                動画上の位置,
            } => 映すものの要約::末尾のコマ(
                置いたクリップ.識別子().文字列().to_string(),
                動画上の位置.秒数(),
            ),
            行の映し方::何も映さない => 映すものの要約::無し,
        })
        .collect()
}

/// 時刻に行が再生して映している置いたクリップの再生の中身。再生して映していなければ試験を落とす。
pub fn 再生の中身(
    重ね: &重ね合わせ,
    時刻: f64,
    行: usize,
    全体の末尾: 末尾での振る舞い,
) -> 置いたクリップの再生の中身<'_> {
    let 映すもの = 重ね
        .重ね合わせ上の時刻に映すものを求める(重ねの秒(時刻), 全体の末尾)
        .nth(行)
        .expect("行がある");
    assert_eq!(映すもの.行, 行の番号::番号から作成する(行));
    match 映すもの.映し方 {
        行の映し方::置いたクリップを映す(中身) => 中身,
        _ => panic!("{時刻}秒の行{行}は置いたクリップを再生していない"),
    }
}

/// 区間の終わりの行き先を「開始へ戻る」「進む:<識別子>」「止まる」の文字列にする。
pub fn 行き先(中身: &置いたクリップの再生の中身<'_>) -> String {
    match 中身.区間の終わりの行き先 {
        置いたクリップの区間の終わりの行き先::区間の開始へ戻る => "開始へ戻る".to_string(),
        置いたクリップの区間の終わりの行き先::別の置いたクリップへ進む(先) => {
            format!("進む:{}", 先.識別子().文字列())
        }
        置いたクリップの区間の終わりの行き先::止まる => "止まる".to_string(),
    }
}
