//! 重ね合わせの試験の共有部品。

use clip_domain::*;

/// 置いた連番の発行元とは、「置-1」「置-2」…の置いたクリップの識別子を順に発行する、試験用の決定的な発行元のことである。
#[derive(Default)]
pub struct 置いた連番の発行元 {
    発行した数: u32,
}

impl 置いたクリップの識別子の発行元 for 置いた連番の発行元 {
    fn 新しい識別子を発行する(&mut self) -> 置いたクリップの識別子 {
        self.発行した数 += 1;
        置いた識別子(&format!("置-{}", self.発行した数))
    }
}

/// 同じ識別子の発行元とは、毎回「置-1」を発行する、識別子が重なる場合を試すための発行元のことである。
pub struct 同じ識別子の発行元;

impl 置いたクリップの識別子の発行元 for 同じ識別子の発行元 {
    fn 新しい識別子を発行する(&mut self) -> 置いたクリップの識別子 {
        置いた識別子("置-1")
    }
}

pub fn 置いた識別子(文字列: &str) -> 置いたクリップの識別子 {
    置いたクリップの識別子::文字列から作成する(文字列.to_string()).expect("空でない")
}

pub fn 重ねの秒(値: f64) -> 重ね合わせ上の秒 {
    重ね合わせ上の秒::作成する(値).expect("有効な秒数")
}

/// 動画上の開始から終了の区間を、リピート回数だけ繰り返すクリップから受け継いだ値を作る。
pub fn 受け継いだ値(
    開始: f64, 終了: f64, 回数: u32
) -> クリップから受け継いだ値 {
    クリップから受け継いだ値 {
        名前: クリップ名::作成する("名前".to_string()),
        区間: 動画上の区間::作成する(
            動画上の秒::作成する(開始).expect("有効な秒数"),
            動画上の秒::作成する(終了).expect("有効な秒数"),
        )
        .expect("開始が終了以前"),
        リピート回数: リピート回数::作成する(回数).expect("範囲内"),
        クロップ: クロップ範囲::全体,
    }
}

/// 16:9で、動画1本だけを表に持つ、行の無い重ね合わせ。
pub fn 一本の動画の重ね合わせ() -> 重ね合わせ {
    let 動画 = 入力された動画パス::作成する("D:\\動画\\練習.mp4".to_string()).正規化する();
    重ね合わせ::作成する(
        重ねる画面の縦横比::ワイド16対9,
        使う動画の表::一本の動画から作成する(動画),
    )
}

/// 動画の長さ100秒の0番の動画へ、開始時刻にクリップから受け継いだ値を置く。
pub fn 零番の動画へ置く(
    重ね: &mut 重ね合わせ,
    受け継いだ値: クリップから受け継いだ値,
    始まり: f64,
    発行元: &mut 置いた連番の発行元,
) -> Result<置いたクリップの識別子, 重ね合わせの操作エラー> {
    let 動画の長さ = 時間の長さ::作成する(100.0).expect("有効な長さ");
    重ね.クリップから受け継いだ値を置く(
        受け継いだ値,
        動画の番号::最初,
        重ねの秒(始まり),
        動画の長さ,
        発行元,
    )
}

/// 行ごとの置いたクリップの識別子の文字列。奥の行から並べる。
pub fn 行ごとの識別子(重ね: &重ね合わせ) -> Vec<Vec<String>> {
    重ね
        .行の並び()
        .iter()
        .map(|行| {
            行.置いたクリップの並び()
                .iter()
                .map(|置いた| 置いた.識別子().文字列().to_string())
                .collect()
        })
        .collect()
}

/// 行の番号0に 置-1[0,2)、行の番号1に 置-2[0,1) と 置-3[3,4) を置いた重ね合わせ。
pub fn 二行の重ね合わせ() -> 重ね合わせ {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(0.0, 2.0, 1), 0.0, &mut 発行元).expect("置ける");
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 1), 0.0, &mut 発行元).expect("置ける");
    零番の動画へ置く(&mut 重ね, 受け継いだ値(7.0, 8.0, 1), 3.0, &mut 発行元).expect("置ける");
    assert_eq!(
        行ごとの識別子(&重ね),
        vec![vec!["置-1"], vec!["置-2", "置-3"]]
    );
    重ね
}

pub fn 行(番号: usize) -> 行の番号 {
    行の番号::番号から作成する(番号)
}
