//! 映す矩形のドラッグの試験の部品。重ねる画面に対する百分率と映す矩形と移動量と、絵の縦横比を作り、映す矩形を数値の組にする。
#![allow(clippy::expect_used)]

use clip_domain::*;

pub fn 百(値: f64) -> 百分率<重ねる画面に対する> {
    百分率::範囲へ収める(値)
}

pub fn 矩形(左端: f64, 上端: f64, 幅: f64, 高さ: f64) -> 映す矩形 {
    映す矩形::作成する(百(左端), 百(上端), 百(幅), 百(高さ)).expect("映す矩形")
}

pub fn 移動量(横: f64, 縦: f64) -> 映す矩形の移動量 {
    映す矩形の移動量 {
        横: 百分率の差分::作成する(横).expect("有限"),
        縦: 百分率の差分::作成する(縦).expect("有限"),
    }
}

pub fn 数値の組(矩形: 映す矩形) -> [f64; 4] {
    [矩形.左端(), 矩形.上端(), 矩形.幅(), 矩形.高さ()].map(百分率::数値)
}

pub fn 絵の縦横比(幅: f64, 高さ: f64) -> 縦横比 {
    画素の寸法::作成する(幅, 高さ)
        .expect("寸法")
        .縦横比()
        .expect("高さが0でない")
}
