//! スタックから並べるときの格子の試験。1〜8個の列と行の数、ます目の順、丸めの誤差で映す矩形が拒まれないこと。
#![allow(clippy::expect_used)]

mod support;

use support::arrange::{
    再生できるクリップを並べたスタック, 十六対九の出力でスタックから並べる,
    奥の行から並べた映す矩形の数値,
};
use support::overlay::行ごとの識別子;

/// 個数ごとの(列の数, 行の数)。列の数は個数の平方根の切り上げ、行の数は個数を列の数で割った切り上げである。
const 個数ごとの格子: [(u32, usize, usize); 8] = [
    (1, 1, 1),
    (2, 2, 1),
    (3, 2, 2),
    (4, 2, 2),
    (5, 3, 2),
    (6, 3, 2),
    (7, 3, 3),
    (8, 3, 3),
];

#[test]
fn 一から八個は格子の左上から行ごとに左から右へ並べ最後の列と行の端は100ちょうどになる() {
    for (個数, 列の数, 行の数) in 個数ごとの格子 {
        let 結果 = 十六対九の出力でスタックから並べる(
            &再生できるクリップを並べたスタック(個数),
        )
        .expect("丸めの誤差で拒まれない");
        assert_eq!(結果.置かなかったクリップの数, 0);
        let 重ね = 結果.重ね合わせ;
        assert_eq!(
            重ね.行の並び().行の数(),
            usize::try_from(個数).expect("小さい数"),
            "個数{個数}"
        );
        assert!(行ごとの識別子(&重ね).iter().all(|行| 行.len() == 1));
        let 矩形 = 奥の行から並べた映す矩形の数値(&重ね);
        for (番号, [左端, 上端, 幅, 高さ]) in 矩形.iter().copied().enumerate() {
            let (列, 行) = (番号 % 列の数, 番号 / 列の数);
            let 期待する左端 = 100.0 * 小数にする(列) / 小数にする(列の数);
            let 期待する上端 = 100.0 * 小数にする(行) / 小数にする(行の数);
            assert_eq!(
                (左端, 上端),
                (期待する左端, 期待する上端),
                "個数{個数}の{番号}番"
            );
            assert!(左端 + 幅 <= 100.0 && 上端 + 高さ <= 100.0);
            if 列 + 1 == 列の数 {
                assert_eq!(左端 + 幅, 100.0, "個数{個数}の{番号}番の右端");
            }
            if 行 + 1 == 行の数 {
                assert_eq!(上端 + 高さ, 100.0, "個数{個数}の{番号}番の下端");
            }
        }
    }
}

#[test]
fn 二個は左右に五個は上の行に3つと下の行に2つを並べる() {
    let 二個 =
        十六対九の出力でスタックから並べる(&再生できるクリップを並べたスタック(2))
            .expect("並べられる");
    assert_eq!(
        奥の行から並べた映す矩形の数値(&二個.重ね合わせ),
        vec![[0.0, 0.0, 50.0, 100.0], [50.0, 0.0, 50.0, 100.0]]
    );
    let 五個 =
        十六対九の出力でスタックから並べる(&再生できるクリップを並べたスタック(5))
            .expect("並べられる");
    let 上端と高さ: Vec<(f64, f64)> =
        奥の行から並べた映す矩形の数値(&五個.重ね合わせ)
            .iter()
            .map(|[_, 上端, _, 高さ]| (*上端, *高さ))
            .collect();
    assert_eq!(
        上端と高さ,
        vec![
            (0.0, 50.0),
            (0.0, 50.0),
            (0.0, 50.0),
            (50.0, 50.0),
            (50.0, 50.0)
        ]
    );
}

fn 小数にする(数: usize) -> f64 {
    f64::from(u32::try_from(数).expect("小さい数"))
}
