//! ライブラリのファイル第1版の見本(`fixtures/library_v1.json`)の試験。
//! 見本は第1版で書いたファイルそのものであり、以後書き換えない。版を上げても、見本を読めることは永久に確かめ続ける。
//! 書き出しが見本と1バイトも違わないことは、第1版が最新の版である間だけ確かめる。参照: _doc/設計/ライブラリ.md「形式の版を上げる手順」
#![allow(clippy::expect_used)]

use clip_domain::*;

const 第1版の見本: &str = include_str!("fixtures/library_v1.json");

fn 日時(ミリ秒: u64) -> ライブラリの日時 {
    ライブラリの日時::紀元からのミリ秒で作成する(ミリ秒).expect("日時")
}

fn クリップを作る(
    識別子: &str,
    名前: &str,
    区間: (f64, f64),
    リピート: リピート設定,
    クロップ: クロップ範囲,
    トリガー: トリガー,
) -> クリップ {
    let 識別子 = クリップ識別子::文字列から作成する(識別子.to_string()).expect("識別子");
    let mut クリップ =
        クリップ::既定値で作成する(識別子, クリップ名::作成する(名前.to_string()));
    let 時刻 = |秒| 時刻::作成する(秒).expect("時刻");
    クリップ.区間 = 動画上の区間::作成する(時刻(区間.0), 時刻(区間.1)).expect("区間");
    クリップ.リピート = リピート;
    クリップ.クロップ = クロップ;
    クリップ.トリガー = トリガー;
    クリップ
}

fn 回数(回数: u32) -> リピート設定 {
    リピート設定::回数指定(リピート回数::作成する(回数).expect("回数"))
}

/// 見本と同じ中身を、ファイルを通さずに手で組んだもの。
fn 手で組んだ期待値() -> ライブラリのスタック {
    let mut 無効 = クリップを作る(
        "mod-1790000000001-8",
        "Clip Mod 2",
        (0.0, 5.0),
        回数(1),
        クロップ範囲::全体,
        トリガー::Enterキー待ち,
    );
    無効.有効か = false;
    let 並び = クリップスタック::一覧から作成する(vec![
        クリップを作る(
            "mod-1790000000000-7",
            "入り",
            (12.5, 14.0),
            回数(3),
            クロップ範囲::全体,
            トリガー::自動進行,
        ),
        無効,
        クリップを作る(
            "mod-1790000000002-9",
            "振り付け",
            (20.25, 21.75),
            リピート設定::無限ループ,
            クロップ範囲::各値を範囲へ収めて作成する(10.0, 20.0, 50.0, 60.0),
            トリガー::Spaceキー待ち,
        ),
        クリップを作る(
            "mod-1790000000003-10",
            "",
            (30.0, 30.5),
            回数(2),
            クロップ範囲::各値を範囲へ収めて作成する(0.0, 12.5, 25.5, 87.5),
            トリガー::クリック待ち,
        ),
    ])
    .expect("並び");
    ライブラリのスタック::新しく作る(
        スタックの識別子::文字列から作成する("stack-1790000000000-42".into()).expect("識別子"),
        スタックの名前::作成する("サビの振り付け \"本番\"".into()).expect("名前"),
        入力された動画パス::作成する(r"D:\動画\練習 2026\本番.mp4".into()).正規化する(),
        クリップスタック::default(),
        日時(1_790_000_000_000),
    )
    .並びを差し替えた(並び, 日時(1_790_000_123_456))
}

#[test]
fn 第1版の見本を読んだ結果は手で組んだ期待値と等しい() {
    let 読んだ = ライブラリのスタック::本文から読み込む(
        &ライブラリのファイルの本文::作成する(第1版の見本.to_string()),
    )
    .expect("見本を読める");
    assert_eq!(読んだ, 手で組んだ期待値());
}

#[test]
fn 期待値を書き出すと見本と1バイトも違わない() {
    let 本文 = 手で組んだ期待値().本文へ書き出す().expect("書き出せる");
    assert_eq!(本文.文字列().as_bytes(), 第1版の見本.as_bytes());
}
