//! 塊のドラッグの行き先の試験のうち、別の行へ動かしたときの空きの選び方と、同じ行き先かの判定。
//! ポインタに最も近いすき間が塊の入らない狭いすき間なら、そこを飛ばして入る空きへ置くことと、
//! 掴み始めの時刻が先の行の空きの中にあれば、その空きの中で前の置いたクリップにぶつかった所で止めることを確かめる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 二行の重ね合わせ, 受け継いだ値, 置いた識別子, 置いた連番の発行元, 行,
    行ごとの識別子, 重ねの秒, 零番の動画へ置く,
};

fn 行き先(
    重ね: &重ね合わせ,
    識別子: &str,
    秒: f64,
    行の数: i32,
) -> 置いたクリップの行き先 {
    重ね
        .行の並び()
        .ずらした行き先を求める(
            &置いた識別子(識別子),
            時刻をずらす量::符号付きの秒数から作成する(秒).expect("有限"),
            行の差::手前へ動かした行の数から作成する(行の数),
        )
        .expect("置いたクリップがある")
}

fn 行と秒(番号: usize, 秒: f64) -> 置いたクリップの行き先 {
    置いたクリップの行き先 {
        行: 行(番号),
        始まりの時刻: 重ねの秒(秒),
    }
}

/// 行0に 置-1[0,2)、行1に 置-2[0,1)・置-3[1.5,2.5)・置-4[5,6) を置いた重ね合わせ。行1の 置-2 と 置-3 の間は0.5秒しか空いていない。
fn 狭いすき間のある重ね合わせ() -> 重ね合わせ {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    for (開始, 終了, 始まり) in [
        (0.0, 2.0, 0.0),
        (5.0, 6.0, 0.0),
        (7.0, 8.0, 1.5),
        (9.0, 10.0, 5.0),
    ] {
        零番の動画へ置く(&mut 重ね, 受け継いだ値(開始, 終了, 1), 始まり, &mut 発行元)
            .expect("置ける");
    }
    assert_eq!(
        行ごとの識別子(&重ね),
        vec![vec!["置-1"], vec!["置-2", "置-3", "置-4"]]
    );
    重ね
}

#[test]
fn ポインタに最も近いすき間が塊の入らない狭いすき間なら_入る空きのうち最も近い所へ置く() {
    let 重ね = 狭いすき間のある重ね合わせ();
    // 長さ2秒の 置-1 は、行1では 2.5秒から3秒の間か、6秒より後ろにしか入らない。1.2秒(狭いすき間の中)を望んでも2.5秒へ置く。
    assert_eq!(行き先(&重ね, "置-1", 1.2, 1), 行と秒(1, 2.5));
    assert_eq!(行き先(&重ね, "置-1", 5.0, 1), 行と秒(1, 6.0));
}

#[test]
fn 掴み始めの時刻が先の行の空きの中にあれば_その空きの中で前の置いたクリップにぶつかった所で止める()
{
    let 重ね = 二行の重ね合わせ();
    // 置-3(行1の3秒)を行0へ動かす。行0の 置-1[0,2) の後ろの空きに3秒が入るため、前へずらしても2秒で止まる。
    assert_eq!(行き先(&重ね, "置-3", -5.0, -1), 行と秒(0, 2.0));
    assert_eq!(行き先(&重ね, "置-3", 1.0, -1), 行と秒(0, 4.0));
}

#[test]
fn 同じ行き先かは行が同じで始まりの時刻の差が丸めの許容誤差以下のとき() {
    let 基 = 行と秒(1, 2.0);
    assert!(基.同じ行き先か(&行と秒(1, 2.0 + 5e-7)));
    assert!(!基.同じ行き先か(&行と秒(1, 2.0 + 1e-3)));
    assert!(!基.同じ行き先か(&行と秒(0, 2.0)));
}
