//! 置いたクリップの継ぎ目と周回の境目の試験。秒の足し算と割り算の丸めで、浮動小数の時刻が等しくならない場合を扱う。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 受け継いだ値, 置いた識別子, 置いた連番の発行元, 行ごとの識別子,
    重ねの秒, 零番の動画へ置く,
};
use support::span_end::区間;

fn 再生の中身(
    重ね: &重ね合わせ, 時刻: f64
) -> 置いたクリップの再生の中身<'_> {
    match 重ね
        .重ね合わせ上の時刻に映すものを求める(重ねの秒(時刻))
        .next()
        .expect("行がある")
        .映し方
    {
        行の映し方::置いたクリップを映す(中身) => 中身,
        行の映し方::何も映さない => panic!("{時刻}秒は何も映さない"),
    }
}

/// 0.1秒の区間を3回繰り返す置いたクリップの終わりは 0.1×3 = 0.30000000000000004 秒であり、0.3秒と等しくない。
fn 丸めで食い込む継ぎ目の重ね合わせ() -> 重ね合わせ {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(0.0, 0.1, 3), 0.0, &mut 発行元).expect("置ける");
    let 先 = 重ね.識別子で探す(&置いた識別子("置-1")).expect("ある");
    assert_ne!(
        先.終わりの時刻(),
        重ねの秒(0.3),
        "丸めで終わりの時刻がずれる場合を試す"
    );
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 1), 0.3, &mut 発行元)
        .expect("食い込みが許容誤差以下なら接しているとみなす");
    重ね
}

#[test]
fn 丸めで僅かに食い込む継ぎ目は同じ行に接して置け隙間なく続くとみなす() {
    let 重ね = 丸めで食い込む継ぎ目の重ね合わせ();
    assert_eq!(行ごとの識別子(&重ね), vec![vec!["置-1", "置-2"]]);
    let 先 = 重ね.識別子で探す(&置いた識別子("置-1")).expect("ある");
    let 後 = 重ね.識別子で探す(&置いた識別子("置-2")).expect("ある");
    assert!(先.隙間なく続くか(後));
    let 直前 = 再生の中身(&重ね, 0.299_999);
    assert_eq!(直前.置いたクリップ.識別子().文字列(), "置-1");
    assert_eq!(直前.周回.一から数えた順番(), 3);
    assert_eq!(
        直前.区間の終わりの行き先,
        区間の終わりの行き先::別の区間へ進む(区間(5.0, 6.0))
    );
    let 境目 = 再生の中身(&重ね, 0.3);
    assert_eq!(
        境目.置いたクリップ.識別子().文字列(),
        "置-2",
        "境目は後ろの置いたクリップが映す"
    );
    assert_eq!(境目.動画上の位置.秒数(), 5.0);
}

#[test]
fn 許容誤差を超えて食い込むなら重なるとして拒む() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(0.0, 1.0, 1), 0.0, &mut 発行元).expect("置ける");
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 1), 0.999, &mut 発行元)
        .expect("別の行に置く");
    assert_eq!(行ごとの識別子(&重ね), vec![vec!["置-1"], vec!["置-2"]]);
}

#[test]
fn 周回の境目の商が丸めで整数へ上がっても周回と区間の中の位置が食い違わない() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(0.0, 0.1, 12), 0.0, &mut 発行元).expect("置ける");
    // 1.0 ÷ 0.1 は丸めで 10.0 になるが、1.0 を 0.1 で割った正確な余りは 0.09999999999999995 である。
    let 中身 = 再生の中身(&重ね, 1.0);
    assert_eq!(
        中身.周回.一から数えた順番(),
        10,
        "余りが一周に近いので10周目の終わりである"
    );
    assert!(中身.動画上の位置.秒数() > 0.099);
    assert_eq!(
        中身.区間の終わりの行き先,
        区間の終わりの行き先::区間の開始へ戻る
    );
}

#[test]
fn 同じ区間の置いたクリップが隙間なく続くなら開始へ戻る() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 2), 0.0, &mut 発行元).expect("置ける");
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 1), 2.0, &mut 発行元).expect("接して置ける");
    assert_eq!(
        再生の中身(&重ね, 1.5).区間の終わりの行き先,
        区間の終わりの行き先::区間の開始へ戻る
    );
}
