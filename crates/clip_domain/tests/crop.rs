//! クロップ枠の移動と、四隅のつまみによる大きさの変更の境界の試験。
#![allow(clippy::expect_used)]

use clip_domain::*;

fn 範囲(左端: f64, 上端: f64, 幅: f64, 高さ: f64) -> クロップ範囲 {
    クロップ範囲::各値を範囲へ収めて作成する(左端, 上端, 幅, 高さ)
}

fn 移動量(横: f64, 縦: f64) -> クロップの移動量 {
    クロップの移動量 {
        横: 百分率の差分::作成する(横).expect("有限"),
        縦: 百分率の差分::作成する(縦).expect("有限"),
    }
}

#[test]
fn 作成時は各値を範囲へ収める() {
    assert_eq!(範囲(-5.0, 120.0, 2.0, 300.0), 範囲(0.0, 100.0, 5.0, 100.0));
    assert!(百分率の差分::作成する(f64::NAN).is_err());
}

#[test]
fn 移動は大きさを保ったまま枠の中へ収める() {
    let 元 = 範囲(70.0, 10.0, 20.0, 50.0);
    assert_eq!(元.移動する(移動量(5.0, 5.0)), 範囲(75.0, 15.0, 20.0, 50.0));
    assert_eq!(
        元.移動する(移動量(30.0, 80.0)),
        範囲(80.0, 50.0, 20.0, 50.0)
    );
    assert_eq!(
        元.移動する(移動量(-100.0, -100.0)),
        範囲(0.0, 0.0, 20.0, 50.0)
    );
}

#[test]
fn 右下のつまみは幅と高さだけを変え100を超えない() {
    let 元 = 範囲(10.0, 10.0, 50.0, 50.0);
    let 少し = 元.つまみで大きさを変える(四隅のつまみ::右下, 移動量(10.0, 5.0));
    assert_eq!(少し, 範囲(10.0, 10.0, 60.0, 55.0));
    let 行き過ぎ = 元.つまみで大きさを変える(四隅のつまみ::右下, 移動量(80.0, 80.0));
    assert_eq!(行き過ぎ, 範囲(10.0, 10.0, 90.0, 90.0));
}

#[test]
fn 左上のつまみを行き過ぎると最小の大きさで止まり左端がずれる() {
    let 元 = 範囲(10.0, 10.0, 50.0, 50.0);
    let 結果 = 元.つまみで大きさを変える(四隅のつまみ::左上, 移動量(60.0, 0.0));
    assert_eq!(結果, 範囲(55.0, 10.0, 5.0, 50.0));
}

#[test]
fn 左上のつまみを枠の外へ出すと左端は0で止まり幅が縮む() {
    let 元 = 範囲(10.0, 10.0, 50.0, 50.0);
    let 結果 = 元.つまみで大きさを変える(四隅のつまみ::左上, 移動量(-20.0, -30.0));
    assert_eq!(結果, 範囲(0.0, 0.0, 60.0, 60.0));
}

#[test]
fn 右上のつまみを下へ行き過ぎると最小の高さで止まり上端がずれる() {
    let 元 = 範囲(10.0, 10.0, 50.0, 50.0);
    let 結果 = 元.つまみで大きさを変える(四隅のつまみ::右上, 移動量(0.0, 60.0));
    assert_eq!(結果, 範囲(10.0, 55.0, 50.0, 5.0));
}

#[test]
fn 左下のつまみは左端と幅と高さを変える() {
    let 元 = 範囲(10.0, 10.0, 50.0, 50.0);
    let 結果 = 元.つまみで大きさを変える(四隅のつまみ::左下, 移動量(5.0, 10.0));
    assert_eq!(結果, 範囲(15.0, 10.0, 45.0, 60.0));
}

#[test]
fn クロップ連動の縦横比は切り出し後の寸法から求める() {
    let 元の寸法 = 画素の寸法::作成する(1920.0, 1080.0).expect("有効");
    let 切り出し後 = 範囲(0.0, 0.0, 50.0, 100.0).切り出し後の寸法(元の寸法);
    let 比 = アスペクト比設定::クロップ連動.縦横比を求める(切り出し後);
    assert!((比.値() - 960.0 / 1080.0).abs() < 1e-9);
    let 高さ0 = 画素の寸法::作成する(100.0, 0.0).expect("有効");
    let 既定 = アスペクト比設定::クロップ連動.縦横比を求める(高さ0);
    assert!((既定.値() - 16.0 / 9.0).abs() < 1e-9);
    let 縦型 = アスペクト比設定::縦型9対16.縦横比を求める(元の寸法);
    assert!((縦型.値() - 9.0 / 16.0).abs() < 1e-9);
}
