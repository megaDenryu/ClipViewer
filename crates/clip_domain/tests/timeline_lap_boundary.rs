//! タイムライン上の位置の周回の境目の試験。商が丸めで整数へ上がる位置でも、周回と区間の中の位置が食い違わないこと。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 秒};

/// 0.1秒の区間を回数だけ繰り返す、Enterキーで進めるクリップ1つのスタック。
fn 短い区間を繰り返すスタック(回数: u32) -> クリップスタック {
    let リピート = リピート設定::回数指定(リピート回数::作成する(回数).expect("範囲内"));
    let クリップ = クリップを作る("短", 0.0, 0.1, リピート, トリガー::Enterキー待ち);
    クリップスタック::一覧から作成する(vec![クリップ]).expect("1つ")
}

#[test]
fn 商が丸めで整数へ上がる位置は余りの指す周回の終わりにする() {
    // 1.0 ÷ 0.1 は丸めで 10.0 になるが、1.0 を 0.1 で割った正確な余りは 0.09999999999999995 である。
    // 余りの指す位置は10周目の終わりであり、周回もそれに揃える(商を切り捨てると11周目の終わりと誤る)。
    let スタック = 短い区間を繰り返すスタック(11);
    let 求めたもの =
        スタック.タイムライン上の位置で再生するものを求める(秒(1.0));
    let タイムライン上の位置で再生するもの::クリップがある(再生の中身) = 求めたもの
    else {
        panic!("1.0秒にクリップがある");
    };
    assert_eq!(
        再生の中身.周回の状況(),
        周回の状況::回数指定中 {
            何周目: 10,
            回数: リピート回数::作成する(11).expect("範囲内"),
        }
    );
    assert!(再生の中身.動画上の位置.秒数() > 0.099);
    assert!(
        !再生の中身.待っているか,
        "10周目は最後の周回(11周目)でないので待たない"
    );
}
