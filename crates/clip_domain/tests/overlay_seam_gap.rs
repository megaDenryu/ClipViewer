//! 継ぎ目の許容誤差の内の隙間の試験。前の置いたクリップの終わりから丸めの許容誤差(1マイクロ秒)より短い隙間に当たった時刻は、
//! 前の置いたクリップの区間の終わりを映して次の置いたクリップへ進み、許容誤差以上の隙間は何も映さないことを確かめる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 受け継いだ値, 置いた連番の発行元, 零番の動画へ置く,
};
use support::overlay_playback::{映すものの一覧, 映すものの要約, 行き先};

/// 0〜1秒の区間を0秒から置き、5〜6秒の区間を1秒の後の隙間の後ろに置いた重ね合わせ。
fn 隙間のある重ね合わせ(後ろの始まり: f64) -> 重ね合わせ {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(0.0, 1.0, 1), 0.0, &mut 発行元).expect("置ける");
    零番の動画へ置く(
        &mut 重ね,
        受け継いだ値(5.0, 6.0, 1),
        後ろの始まり,
        &mut 発行元,
    )
    .expect("同じ行の隙間の後ろに置ける");
    重ね
}

#[test]
fn 許容誤差の内の隙間では前の置いたクリップの区間の終わりを映し_次の置いたクリップへ進む() {
    let 重ね = 隙間のある重ね合わせ(1.000_000_5);
    assert_eq!(
        映すものの一覧(&重ね, 1.000_000_2, 末尾での振る舞い::止まる),
        vec![映すものの要約::再生("置-1".to_string(), 1.0)]
    );
    let 中身 =
        support::overlay_playback::再生の中身(&重ね, 1.000_000_2, 0, 末尾での振る舞い::止まる);
    assert_eq!(中身.周回.一から数えた順番(), 1);
    assert_eq!(行き先(&中身), "進む:置-2");
}

#[test]
fn 許容誤差以上の隙間では何も映さない() {
    let 重ね = 隙間のある重ね合わせ(1.5);
    assert_eq!(
        映すものの一覧(&重ね, 1.000_002, 末尾での振る舞い::止まる),
        vec![映すものの要約::無し]
    );
}
