//! 置いたクリップの映す矩形を変える操作と、音の設定を変える操作と、取り除く操作の試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    二行の重ね合わせ, 置いた識別子, 行ごとの識別子, 重ねの秒
};

#[test]
fn 映す矩形を変えると置いたクリップの映す矩形だけが変わる() {
    let mut 重ね = 二行の重ね合わせ();
    let 百 = 百分率::範囲へ収める;
    let 左半分 = 映す矩形::作成する(百(0.0), 百(0.0), 百(50.0), 百(100.0)).expect("内側");
    重ね
        .映す矩形を変える(&置いた識別子("置-2"), 左半分)
        .expect("ある");
    let 変えた = 重ね.識別子で探す(&置いた識別子("置-2")).expect("ある");
    assert_eq!(変えた.映す矩形(), 左半分);
    assert_eq!(変えた.始まりの時刻(), 重ねの秒(0.0));
    assert_eq!(
        重ね.映す矩形を変える(&置いた識別子("無い"), 左半分),
        Err(
            重ね合わせの操作エラー::置いたクリップが見つからない(
                置いた識別子("無い")
            )
        )
    );
}

#[test]
fn 音を変えると置いたクリップの音の設定だけが変わり_音量と消音は別々に残る() {
    let mut 重ね = 二行の重ね合わせ();
    重ね
        .置いたクリップの音を変える(
            &置いた識別子("置-2"),
            置いたクリップの音の変更::音量を選ぶ(音量::範囲へ収めて作る(0.25)),
        )
        .expect("ある");
    重ね
        .置いたクリップの音を変える(
            &置いた識別子("置-2"),
            置いたクリップの音の変更::消音を設定する(true),
        )
        .expect("ある");
    let 音の設定 = |識別子| {
        重ね
            .識別子で探す(&置いた識別子(識別子))
            .expect("ある")
            .音の設定()
    };
    let 消した = 置いたクリップの音の設定 {
        音量: 音量::範囲へ収めて作る(0.25),
        消音しているか: true,
    };
    assert_eq!(音の設定("置-2"), 消した);
    assert_eq!(音の設定("置-1"), 置いたクリップの音の設定::最初の値);
    assert_eq!(音の設定("置-3"), 置いたクリップの音の設定::最初の値);
    assert_eq!(
        重ね.置いたクリップの音を変える(
            &置いた識別子("無い"),
            置いたクリップの音の変更::消音を設定する(true)
        ),
        Err(
            重ね合わせの操作エラー::置いたクリップが見つからない(
                置いた識別子("無い")
            )
        )
    );
}

#[test]
fn 取り除くと取り除いたものを返し空になった行も残る() {
    let mut 重ね = 二行の重ね合わせ();
    let 取り除いた = 重ね
        .置いたクリップを取り除く(&置いた識別子("置-1"))
        .expect("ある");
    assert_eq!(取り除いた.識別子(), &置いた識別子("置-1"));
    assert_eq!(行ごとの識別子(&重ね), vec![vec![], vec!["置-2", "置-3"]]);
    assert_eq!(重ね.重ね合わせの長さ(), 重ねの秒(4.0));
    assert_eq!(
        重ね.置いたクリップを取り除く(&置いた識別子("置-1")),
        Err(
            重ね合わせの操作エラー::置いたクリップが見つからない(
                置いた識別子("置-1")
            )
        )
    );
}
