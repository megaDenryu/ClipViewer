//! 区間の終わりの行き先の試験。音を鳴らす側が、時計と同じ行き先へ区間の終わりで移れること。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::span_end::{シーケンスの行き先, 区間, 自動進行の二つ};
use support::{クリップを作る, 試験用の条件};

#[test]
fn 最後でない周回は開始へ戻り最後の周回は次のクリップの区間へ進む() {
    let スタック = 自動進行の二つ(トリガー::自動進行);
    let 止める = 末尾での振る舞い::止まる;
    assert_eq!(
        シーケンスの行き先(&スタック, 0.5, 止める),
        区間の終わりの行き先::区間の開始へ戻る
    );
    assert_eq!(
        シーケンスの行き先(&スタック, 2.5, 止める),
        区間の終わりの行き先::別の区間へ進む(区間(5.0, 9.0))
    );
}

#[test]
fn 最後のクリップの終わりは全体の末尾での振る舞いに従う() {
    let スタック = 自動進行の二つ(トリガー::自動進行);
    assert_eq!(
        シーケンスの行き先(&スタック, 5.0, 末尾での振る舞い::止まる),
        区間の終わりの行き先::止まる
    );
    assert_eq!(
        シーケンスの行き先(&スタック, 5.0, 末尾での振る舞い::先頭へ戻る),
        区間の終わりの行き先::別の区間へ進む(区間(0.0, 2.0))
    );
}

#[test]
fn 待っている周回は開始へ戻る() {
    let スタック = 自動進行の二つ(トリガー::Enterキー待ち);
    assert_eq!(
        シーケンスの行き先(&スタック, 3.9, 末尾での振る舞い::止まる),
        区間の終わりの行き先::区間の開始へ戻る
    );
}

#[test]
fn 次のクリップが同じ区間なら開始へ戻る() {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let スタック = クリップスタック::一覧から作成する(vec![
        クリップを作る("一", 3.0, 4.0, 一回, トリガー::自動進行),
        クリップを作る("二", 3.0, 4.0, 一回, トリガー::自動進行),
    ])
    .expect("重複しない");
    assert_eq!(
        シーケンスの行き先(&スタック, 0.5, 末尾での振る舞い::止まる),
        区間の終わりの行き先::区間の開始へ戻る
    );
}

#[test]
fn 単独クリップ再生は開始へ戻り元動画再生は全体の末尾に従う() {
    let スタック = 自動進行の二つ(トリガー::自動進行);
    let 止まる条件 = 試験用の条件(&スタック, 末尾での振る舞い::止まる);
    let 単独 = 再生位置::単独クリップ再生(時間の長さ::ゼロ);
    assert_eq!(
        単独.区間の終わりの行き先(&止まる条件),
        区間の終わりの行き先::区間の開始へ戻る
    );
    let 元動画 = 再生位置::元動画再生(時刻::先頭);
    assert_eq!(
        元動画.区間の終わりの行き先(&止まる条件),
        区間の終わりの行き先::止まる
    );
    let 戻る条件 = 試験用の条件(&スタック, 末尾での振る舞い::先頭へ戻る);
    assert_eq!(
        元動画.区間の終わりの行き先(&戻る条件),
        区間の終わりの行き先::区間の開始へ戻る
    );
}
