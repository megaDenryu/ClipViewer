//! 区間の終わりの行き先を時計の規則で求める試験。待つクリップの周回と、区間の終わりの直前の位置。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::span_end::{シーケンスの行き先, 区間, 自動進行の二つ};

#[test]
fn 待つクリップはどの周回の終わりでも開始へ戻る() {
    let スタック = support::試験用のスタック();
    for 位置 in [0.5, 5.5, 6.5, 10.5] {
        assert_eq!(
            シーケンスの行き先(&スタック, 位置, 末尾での振る舞い::先頭へ戻る),
            区間の終わりの行き先::区間の開始へ戻る,
            "{位置}秒"
        );
    }
}

#[test]
fn 区間の終わりの直前でも時計と同じ行き先になる() {
    let スタック = 自動進行の二つ(トリガー::自動進行);
    assert_eq!(
        シーケンスの行き先(&スタック, 3.999_999, 末尾での振る舞い::止まる),
        区間の終わりの行き先::別の区間へ進む(区間(5.0, 9.0))
    );
}
