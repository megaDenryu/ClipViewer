//! 全体ループの継ぎ目の行き先の試験。最も遅く終わる行の最後の周回の終わりは、全体ループが有効ならその行の0秒の置いたクリップへ続く。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 二行の重ね合わせ, 受け継いだ値, 置いた連番の発行元, 零番の動画へ置く,
};
use support::overlay_playback::{再生の中身, 行き先};

const 戻る: 末尾での振る舞い = 末尾での振る舞い::先頭へ戻る;
const 止める: 末尾での振る舞い = 末尾での振る舞い::止まる;

#[test]
fn 最も遅く終わる行は全体ループなら0秒の置いたクリップへ進み無効なら止まる() {
    // 行0: 置-1[0,2)。行1: 置-2[0,1) と 置-3[3,4)。重ね合わせの長さは4秒で、行1が最も遅く終わる。
    let 重ね = 二行の重ね合わせ();
    assert_eq!(行き先(&再生の中身(&重ね, 3.5, 1, 戻る)), "進む:置-2");
    assert_eq!(行き先(&再生の中身(&重ね, 3.5, 1, 止める)), "止まる");
}

#[test]
fn 全体の末尾より前に終わる行は全体ループでも止まる() {
    // 行0の置-1は2秒で終わり、続く置いたクリップが無いまま隙間の後で全体の末尾(4秒)に達し、0秒から始まり直す。
    let 重ね = 二行の重ね合わせ();
    assert_eq!(行き先(&再生の中身(&重ね, 1.5, 0, 戻る)), "止まる");
}

#[test]
fn 全体ループで続く0秒の置いたクリップが同じ区間なら開始へ戻る() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 2), 0.0, &mut 発行元).expect("置ける");
    assert_eq!(行き先(&再生の中身(&重ね, 1.5, 0, 戻る)), "開始へ戻る");
    assert_eq!(行き先(&再生の中身(&重ね, 1.5, 0, 止める)), "止まる");
}

#[test]
fn 全体ループで0秒に置いたクリップが無い行は止まる() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 6.0, 1), 1.0, &mut 発行元).expect("置ける");
    assert_eq!(行き先(&再生の中身(&重ね, 1.5, 0, 戻る)), "止まる");
}
