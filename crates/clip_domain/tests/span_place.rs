//! 区間を再生の位置に合わせる決まりの試験。今の位置から区間を作ることと、開始か終了を今の位置に合わせることを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{動画上の区間, 区間の編集の決まり, 時刻, 時間の長さ};

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}

fn 位置(秒: f64) -> clip_domain::動画上の秒 {
    時刻::作成する(秒).expect("時刻")
}

fn 長さ(秒: f64) -> 時間の長さ {
    時間の長さ::作成する(秒).expect("長さ")
}

/// 上限10秒、最小の長さ0.5秒の決まり。
fn 決まり() -> 区間の編集の決まり {
    区間の編集の決まり::作成する(長さ(10.0), 長さ(0.5))
}

fn 近い(実際: 動画上の区間, 開始: f64, 終了: f64) -> bool {
    (実際.開始().秒数() - 開始).abs() < 1e-9 && (実際.終了().秒数() - 終了).abs() < 1e-9
}

#[test]
fn 位置から長さの区間を作り_上限の手前では終了を上限で止める() {
    assert!(近い(
        決まり().位置から始まる区間を作る(位置(2.0), 長さ(5.0)),
        2.0,
        7.0
    ));
    assert!(近い(
        決まり().位置から始まる区間を作る(位置(8.0), 長さ(5.0)),
        8.0,
        10.0
    ));
    assert!(
        近い(
            決まり().位置から始まる区間を作る(位置(10.0), 長さ(5.0)),
            9.5,
            10.0
        ),
        "上限ちょうどでは最小の長さを空けるため開始を前へ寄せる"
    );
}

#[test]
fn 開始を位置に合わせると_終了より前なら開始だけが動き_終了以降なら長さを保って動く() {
    assert!(近い(
        決まり().開始を位置に合わせる(区間(2.0, 4.0), 位置(3.0)),
        3.0,
        4.0
    ));
    assert!(近い(
        決まり().開始を位置に合わせる(区間(2.0, 4.0), 位置(6.0)),
        6.0,
        8.0
    ));
    assert!(近い(
        決まり().開始を位置に合わせる(区間(2.0, 4.0), 位置(9.0)),
        8.0,
        10.0
    ));
}

#[test]
fn 終了を位置に合わせると_開始より後ろなら終了だけが動き_開始以前なら長さを保って動く() {
    assert!(近い(
        決まり().終了を位置に合わせる(区間(2.0, 4.0), 位置(6.0)),
        2.0,
        6.0
    ));
    assert!(近い(
        決まり().終了を位置に合わせる(区間(4.0, 6.0), 位置(3.0)),
        1.0,
        3.0
    ));
    assert!(近い(
        決まり().終了を位置に合わせる(区間(4.0, 7.0), 位置(1.0)),
        0.0,
        3.0
    ));
}
