//! 重ね合わせのファイルの読み込みの試験。成立しない置いたクリップの値を行と位置付きで拒むことと、
//! 重ね合わせの不変条件(行の中の時間の重なり・識別子の重なり・動画の番号・行の数の上限)を破るファイルを型付きのエラーで拒むことを確かめる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{置いた識別子, 行};
use support::overlay_library_text::{本文, 読む};

fn 置いたクリップの不備(壊し方: (&str, &str)) -> 置いたクリップの値の不備 {
    match 読む(&本文(&[壊し方])) {
        Err(重ね合わせのファイルの読み込みエラー::置いたクリップが不正 { 行: 0, 位置: 0, 理由 }) => 理由,
        その他 => panic!("{壊し方:?} が置いたクリップの不備にならず {その他:?}"),
    }
}

#[test]
fn 成立しない置いたクリップの値を行と位置付きで拒む() {
    assert!(matches!(
        置いたクリップの不備((r#""rect":{"x":0.0"#, r#""rect":{"x":10.0"#)),
        置いたクリップの値の不備::映す矩形(映す矩形エラー::右へはみ出す { .. })
    ));
    assert!(matches!(
        置いたクリップの不備((r#""h":100.0},"volume""#, r#""h":4.0},"volume""#)),
        置いたクリップの値の不備::映す矩形(映す矩形エラー::小さすぎる { .. })
    ));
    assert!(matches!(
        置いたクリップの不備((r#""repeat":2"#, r#""repeat":0"#)),
        置いたクリップの値の不備::繰り返しの回数(_)
    ));
    assert!(matches!(
        置いたクリップの不備((r#""start":1.0"#, r#""start":3.0"#)),
        置いたクリップの値の不備::区間(_)
    ));
    assert!(matches!(
        置いたクリップの不備((r#""at":0.0"#, r#""at":-1.0"#)),
        置いたクリップの値の不備::時刻(_)
    ));
    assert!(matches!(
        置いたクリップの不備((r#""id":"p1""#, r#""id":"""#)),
        置いたクリップの値の不備::識別子(_)
    ));
}

fn 組み立てられない(本文: &str) -> 重ね合わせを組み立てられない理由 {
    match 読む(本文) {
        Err(重ね合わせのファイルの読み込みエラー::組み立てられない(
            理由,
        )) => 理由,
        その他 => panic!("組み立てられないはずが {その他:?}"),
    }
}

/// 2つ目の置いたクリップを、1つ目と同じ行の末尾へ足すように本文を広げる。
fn 同じ行へもう一つ置く(id: &str, at: &str, video: &str) -> String {
    let 二つ目 = format!(
        r#"{{"id":"{id}","name":"二","video":{video},"start":1.0,"end":2.0,"repeat":1,"crop":{{"x":0.0,"y":0.0,"w":100.0,"h":100.0}},"at":{at},"rect":{{"x":0.0,"y":0.0,"w":100.0,"h":100.0}},"volume":1.0,"muted":false}}"#
    );
    本文(&[(
        r#""muted":false}]"#,
        &format!(r#""muted":false}},{二つ目}]"#),
    )])
}

#[test]
fn 重ね合わせの不変条件を破るファイルを拒む() {
    assert_eq!(
        組み立てられない(&同じ行へもう一つ置く("p2", "1.5", "0")),
        重ね合わせを組み立てられない理由::置いたクリップを置けない {
            行: 行(0),
            位置: 1,
            理由: 重ね合わせの操作エラー::時間が重なる {
                行: 行(0),
                相手: 置いた識別子("p1"),
            },
        }
    );
    assert!(matches!(
        組み立てられない(&同じ行へもう一つ置く("p1", "5.0", "0")),
        重ね合わせを組み立てられない理由::置いたクリップを置けない {
            理由: 重ね合わせの操作エラー::識別子が重複している(_),
            ..
        }
    ));
    assert!(matches!(
        組み立てられない(&同じ行へもう一つ置く("p2", "5.0", "1")),
        重ね合わせを組み立てられない理由::置いたクリップを置けない {
            理由: 重ね合わせの操作エラー::動画の番号が表に無い { .. },
            ..
        }
    ));
    let 九行 = 本文(&[(
        r#""muted":false}]}]"#,
        &format!(r#""muted":false}}]}}{}]"#, r#",{"items":[]}"#.repeat(8)),
    )]);
    assert_eq!(
        組み立てられない(&九行),
        重ね合わせを組み立てられない理由::行の数が上限を超える {
            行の数: 9
        }
    );
}
