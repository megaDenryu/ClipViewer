//! タイムライン上の位置で再生するものを求める処理の試験。回数指定の各周回、無限ループ、無効なクリップの飛ばし、区間の長さ0、トリガー待ちの発生点。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 秒, 試験用のスタック};

fn 再生の中身を求める(
    スタック: &クリップスタック,
    位置: f64,
) -> タイムライン上の位置の再生の中身<'_> {
    match スタック.タイムライン上の位置で再生するものを求める(秒(位置))
    {
        タイムライン上の位置で再生するもの::クリップがある(再生の中身) => {
            再生の中身
        }
        タイムライン上の位置で再生するもの::クリップが無い => {
            panic!("{位置}秒がクリップが無い")
        }
    }
}

fn 回数指定中(何周目: u16) -> 周回の状況 {
    let 回数 = リピート回数::作成する(3).expect("範囲内");
    周回の状況::回数指定中 { 何周目, 回数 }
}

#[test]
fn 回数指定の各周回で動画上の位置と周回が求まる() {
    let スタック = 試験用のスタック();
    for (位置, 周, 動画上) in [(0.5, 1, 10.5), (2.5, 2, 10.5), (4.0, 3, 10.0)] {
        let 再生の中身 = 再生の中身を求める(&スタック, 位置);
        assert_eq!(再生の中身.対象クリップ.識別子().文字列(), "A");
        assert_eq!(再生の中身.周回の状況(), 回数指定中(周));
        assert!((再生の中身.動画上の位置.秒数() - 動画上).abs() < 1e-9);
    }
}

#[test]
fn トリガー付きの回数指定は最後の周回の間だけ待っている() {
    let スタック = 試験用のスタック();
    assert!(!再生の中身を求める(&スタック, 1.9).待っているか);
    assert!(!再生の中身を求める(&スタック, 3.0).待っているか);
    assert!(再生の中身を求める(&スタック, 4.0).待っているか);
    assert!(再生の中身を求める(&スタック, 5.9).待っているか);
    assert_eq!(
        再生の中身を求める(&スタック, 5.9).クリップの開始位置,
        秒(0.0)
    );
}

#[test]
fn 無限ループは一周分を占め入った直後から待っている() {
    let スタック = 試験用のスタック();
    let 再生の中身 = 再生の中身を求める(&スタック, 6.5);
    assert_eq!(再生の中身.対象クリップ.識別子().文字列(), "C");
    assert_eq!(再生の中身.周回の状況(), 周回の状況::無限ループ中);
    assert!(再生の中身.待っているか);
    assert_eq!(再生の中身.クリップの開始位置, 秒(6.0));
    assert_eq!(
        再生の中身を求める(&スタック, 7.0)
            .対象クリップ
            .識別子()
            .文字列(),
        "E"
    );
}

#[test]
fn 無効なクリップと長さ0のクリップは時間を占めない() {
    let スタック = 試験用のスタック();
    assert_eq!(
        再生の中身を求める(&スタック, 0.0)
            .対象クリップ
            .識別子()
            .文字列(),
        "A"
    );
    assert!((スタック.合計の占有時間().秒数() - 11.0).abs() < 1e-9);
    let 末尾 = スタック.タイムライン上の位置で再生するものを求める(秒(11.0));
    assert_eq!(末尾, タイムライン上の位置で再生するもの::クリップが無い);
}

#[test]
fn 長さ0のクリップだけのスタックはどの位置もクリップが無い() {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let クリップ = クリップを作る("D", 3.0, 3.0, 一回, トリガー::自動進行);
    let スタック = クリップスタック::一覧から作成する(vec![クリップ]).expect("1つ");
    assert_eq!(
        スタック.タイムライン上の位置で再生するものを求める(秒(0.0)),
        タイムライン上の位置で再生するもの::クリップが無い
    );
}
