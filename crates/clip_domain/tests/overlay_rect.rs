//! 映す矩形の不変条件(重ねる画面の内側にあり、幅と高さが5%以上)の試験。
#![allow(clippy::expect_used)]

use clip_domain::*;

fn 百(値: f64) -> 百分率<重ねる画面に対する> {
    百分率::範囲へ収める(値)
}

#[test]
fn 映す矩形は幅か高さが5パーセントより小さい矩形を渡された値のまま拒む() {
    assert_eq!(
        映す矩形::作成する(百(0.0), 百(0.0), 百(4.9), 百(50.0)),
        Err(映す矩形エラー::小さすぎる {
            幅: 百(4.9),
            高さ: 百(50.0)
        })
    );
    assert!(映す矩形::作成する(百(0.0), 百(0.0), 百(5.0), 百(5.0)).is_ok());
}

#[test]
fn 映す矩形は右端と下端がちょうど100なら受け取り100を超えると拒む() {
    let 右下の角 = 映す矩形::作成する(百(95.0), 百(95.0), 百(5.0), 百(5.0)).expect("内側");
    assert_eq!(右下の角.左端(), 百(95.0));
    assert_eq!(
        映す矩形::作成する(百(60.0), 百(0.0), 百(40.000001), 百(50.0)),
        Err(映す矩形エラー::右へはみ出す {
            左端: 百(60.0),
            幅: 百(40.000001)
        })
    );
    assert_eq!(
        映す矩形::作成する(百(0.0), 百(60.0), 百(50.0), 百(40.000001)),
        Err(映す矩形エラー::下へはみ出す {
            上端: 百(60.0),
            高さ: 百(40.000001)
        })
    );
}

#[test]
fn 三等分した格子の最後のます目は大きさを100から引いて求めれば受け取る() {
    let 二つ分 = 100.0 / 3.0 * 2.0;
    let 最後のます目 =
        映す矩形::作成する(百(二つ分), 百(0.0), 百(100.0 - 二つ分), 百(100.0));
    assert!(最後のます目.is_ok());
}
