//! 全体を等分した区間の試験。区間が隙間なく続き、最後の区間の終わりが丸めの誤差なく100ちょうどになること。
#![allow(clippy::expect_used)]

use std::num::NonZeroU32;

use clip_domain::*;

#[test]
fn 区間は0から隙間なく続き最後の区間の始まりと大きさを足すと100ちょうどになる() {
    for 分割数 in 1..=50 {
        let 区間の並び: Vec<等分した区間<元の動画に対する>> =
            百分率::全体を等分した区間の並び(
                NonZeroU32::new(分割数).expect("1以上"),
            )
            .collect();
        assert_eq!(区間の並び.len(), usize::try_from(分割数).expect("小さい数"));
        assert_eq!(区間の並び[0].始まり, 百分率::ゼロ);
        for (位置, 区間) in (0..分割数).zip(&区間の並び) {
            let 期待する始まり = 100.0 * f64::from(位置) / f64::from(分割数);
            assert_eq!(
                区間.始まり.数値(),
                期待する始まり,
                "分割数{分割数}の{位置}番"
            );
            assert!(区間.大きさ.数値() > 0.0);
        }
        let 最後 = 区間の並び[区間の並び.len() - 1];
        assert_eq!(
            最後.始まり.数値() + 最後.大きさ.数値(),
            100.0,
            "分割数{分割数}"
        );
    }
}

#[test]
fn 三等分の大きさは三分の百で最後の区間は百から始まりを引いた大きさになる() {
    let 区間の並び: Vec<等分した区間<元の動画に対する>> =
        百分率::全体を等分した区間の並び(NonZeroU32::new(3).expect("1以上")).collect();
    let 最後の始まり = 200.0 / 3.0;
    assert_eq!(区間の並び[2].始まり.数値(), 最後の始まり);
    assert_eq!(区間の並び[2].大きさ.数値(), 100.0 - 最後の始まり);
}
