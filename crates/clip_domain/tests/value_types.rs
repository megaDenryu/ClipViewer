//! 時間の型とリピート回数の型の試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{秒, 長さ};

#[test]
fn 時間の型は負と有限でない値を拒み引き算は0で止まる() {
    assert_eq!(
        時間の長さ::作成する(-1.0),
        Err(時間の値エラー::負である(-1.0))
    );
    assert_eq!(
        動画上の秒::作成する(f64::INFINITY),
        Err(時間の値エラー::有限でない)
    );
    assert_eq!(秒(1.0).起点から経過した長さ(秒(3.0)), 時間の長さ::ゼロ);
    assert_eq!(秒(1.0).戻す(長さ(3.0)), 秒(0.0));
    assert_eq!(長さ(1.0).差し引く(長さ(2.0)), 時間の長さ::ゼロ);
}

#[test]
fn リピート回数は範囲へ収め増減も範囲を出ない() {
    assert!(リピート回数::作成する(0).is_err());
    assert!(リピート回数::作成する(101).is_err());
    assert_eq!(リピート回数::切り捨てて範囲へ収める(0.4).回数(), 1);
    assert_eq!(リピート回数::切り捨てて範囲へ収める(99.9).回数(), 99);
    assert_eq!(リピート回数::一回.減らす().回数(), 1);
    assert_eq!(
        リピート回数::切り捨てて範囲へ収める(1e9).増やす().回数(),
        100
    );
}
