//! スタックからの読み替えの試験。再生できるクリップだけを1つずつ別の行へ時刻0で置くこと、受け継ぐ値、縦横比の決め方。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::arrange::{
    出力のアスペクト比を指定してスタックから重ね合わせを並べる,
    十六対九の出力でスタックから重ね合わせを並べる,
};
use support::overlay::{行ごとの識別子, 重ねの秒};
use support::試験用のスタック;

#[test]
fn 再生できるクリップだけをスタックの順に1つずつ別の行へ時刻0で置く() {
    let スタック = 試験用のスタック();
    let 元のスタック = スタック.clone();
    let 結果 = 十六対九の出力でスタックから重ね合わせを並べる(&スタック).expect("並べられる");
    assert!(結果.置かなかったクリップの一覧.is_empty());
    assert_eq!(
        行ごとの識別子(&結果.重ね合わせ),
        vec![vec!["置-1"], vec!["置-2"], vec!["置-3"]]
    );
    let 始まりの時刻: Vec<重ね合わせ上の秒> = 結果
        .重ね合わせ
        .行の並び()
        .奥から手前の順の行()
        .iter()
        .flat_map(|行| 行.置いたクリップの並び().iter())
        .map(置いたクリップ::始まりの時刻)
        .collect();
    assert_eq!(始まりの時刻, vec![重ねの秒(0.0); 3]);
    assert_eq!(スタック, 元のスタック, "元のスタックは変えない");
}

#[test]
fn 回数指定はその回数で無限ループは1回にして受け継ぎ動画の表は開いている動画1本にする() {
    let 結果 =
        十六対九の出力でスタックから重ね合わせを並べる(&試験用のスタック()).expect("並べられる");
    let 重ね合わせ = 結果.重ね合わせ;
    let 置いたクリップの一覧: Vec<&置いたクリップ> = 重ね合わせ
        .行の並び()
        .奥から手前の順の行()
        .iter()
        .flat_map(|行| 行.置いたクリップの並び().iter())
        .collect();
    let 区間と回数: Vec<(f64, f64, u8)> = 置いたクリップの一覧
        .iter()
        .map(|置いた| {
            let 値 = 置いた.受け継いだ値();
            (
                値.区間.開始().秒数(),
                値.区間.終了().秒数(),
                値.リピート回数.回数(),
            )
        })
        .collect();
    assert_eq!(
        区間と回数,
        vec![(10.0, 12.0, 3), (20.0, 21.0, 1), (40.0, 44.0, 1)]
    );
    assert!(
        置いたクリップの一覧
            .iter()
            .all(|置いた| 置いた.動画の番号() == 動画の番号::最初)
    );
    assert_eq!(重ね合わせ.動画の表().動画の数(), 1);
    assert_eq!(重ね合わせ.重ね合わせの長さ(), 重ねの秒(6.0));
}

#[test]
fn 縦横比は出力の固定の比ならその比でクロップ連動なら16対9にする() {
    let スタック = 試験用のスタック();
    let 縦横比を決める = |設定| {
        出力のアスペクト比を指定してスタックから重ね合わせを並べる(
            &スタック,
            設定,
        )
        .expect("並べられる")
        .重ね合わせ
        .縦横比()
        .設定()
    };
    assert_eq!(
        縦横比を決める(アスペクト比設定::クロップ連動),
        アスペクト比設定::ワイド16対9
    );
    assert_eq!(
        縦横比を決める(アスペクト比設定::縦型9対16),
        アスペクト比設定::縦型9対16
    );
    assert_eq!(
        縦横比を決める(アスペクト比設定::スタンダード4対3),
        アスペクト比設定::スタンダード4対3
    );
}
