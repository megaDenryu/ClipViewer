//! クリップの終わりで待つ規則の試験(オーナーの決定)。
//! 待つクリップとは、無限ループか、トリガーが自動進行以外のクリップのことである。
//! 待つクリップは、最後の周回の終わりに達すると1区間長戻して同じ周回を繰り返す。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 秒, 試験用のスタック, 試験用の条件, 長さ};

fn シーケンスを進める(
    スタック: &クリップスタック, 開始: f64, 経過: f64
) -> f64 {
    let 条件 = 試験用の条件(スタック, 末尾での振る舞い::止まる);
    match 再生位置::シーケンス再生(秒(開始)).実時間の経過で進める(長さ(経過), &条件)
    {
        時計を進めた結果::続ける(再生位置::シーケンス再生(位置)) => {
            位置.秒数()
        }
        その他 => panic!("シーケンス再生のまま続くはず: {その他:?}"),
    }
}

fn 近い(実際: f64, 期待: f64) {
    assert!((実際 - 期待).abs() < 1e-9, "実際 {実際} 期待 {期待}");
}

fn 二つのクリップ(
    リピート: リピート設定, トリガー: トリガー
) -> クリップスタック {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let 先 = クリップを作る("先", 0.0, 2.0, リピート, トリガー);
    let 後 = クリップを作る("後", 5.0, 9.0, 一回, トリガー::自動進行);
    クリップスタック::一覧から作成する(vec![先, 後]).expect("重複しない")
}

#[test]
fn 待つクリップの判定は無限ループかトリガーが自動進行以外である() {
    let 二回 = リピート設定::回数指定(リピート回数::作成する(2).expect("範囲内"));
    let 判定 =
        |リピート, トリガー| クリップを作る("a", 0.0, 1.0, リピート, トリガー).終わりで待つか();
    assert!(!判定(二回, トリガー::自動進行));
    assert!(判定(二回, トリガー::Enterキー待ち));
    assert!(判定(リピート設定::無限ループ, トリガー::自動進行));
    assert!(判定(リピート設定::無限ループ, トリガー::クリック待ち));
}

#[test]
fn 自動進行の回数指定は終わりで次のクリップへ進む() {
    let 二回 = リピート設定::回数指定(リピート回数::作成する(2).expect("範囲内"));
    近い(
        シーケンスを進める(&二つのクリップ(二回, トリガー::自動進行), 3.9, 0.2),
        4.1,
    );
}

#[test]
fn トリガー付きの回数指定は最後の周回を繰り返して待つ() {
    let スタック = 試験用のスタック();
    近い(シーケンスを進める(&スタック, 5.9, 0.2), 4.1);
    近い(シーケンスを進める(&スタック, 5.9, 2.3), 4.2);
    近い(シーケンスを進める(&スタック, 1.9, 0.2), 2.1);
}

#[test]
fn 無限ループはトリガーが自動進行でも同じ周回を繰り返す() {
    近い(
        シーケンスを進める(
            &二つのクリップ(リピート設定::無限ループ, トリガー::自動進行),
            1.9,
            0.2,
        ),
        0.1,
    );
    近い(シーケンスを進める(&試験用のスタック(), 6.9, 0.2), 6.1);
}

#[test]
fn 最後のクリップが待つなら全体の末尾に達しても止まらない() {
    let スタック = 試験用のスタック();
    近い(シーケンスを進める(&スタック, 10.9, 0.2), 7.1);
}
