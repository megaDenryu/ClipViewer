//! スタックからの読み替えが拒む場合の試験。再生できるクリップが無いときと、置けないクリップがあるとき。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::arrange::十六対九の出力でスタックから並べる;
use support::クリップを作る;

#[test]
fn 再生できるクリップが無ければ拒む() {
    assert_eq!(
        十六対九の出力でスタックから並べる(&クリップスタック::default()),
        Err(スタックから並べるエラー::再生できるクリップが無い)
    );
    let mut 無効 = クリップを作る(
        "無効",
        0.0,
        1.0,
        リピート設定::無限ループ,
        トリガー::自動進行,
    );
    無効.有効か = false;
    let 長さ0 = クリップを作る(
        "長さ0",
        3.0,
        3.0,
        リピート設定::無限ループ,
        トリガー::自動進行,
    );
    let スタック = クリップスタック::一覧から作成する(vec![無効, 長さ0]).expect("重複しない");
    assert_eq!(
        十六対九の出力でスタックから並べる(&スタック),
        Err(スタックから並べるエラー::再生できるクリップが無い)
    );
}

#[test]
fn 区間の終わりが動画の長さより後ろのクリップがあれば全体を拒む() {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let mut はみ出す = クリップを作る("はみ出す", 99.0, 101.0, 一回, トリガー::自動進行);
    はみ出す.名前 = クリップ名::作成する("はみ出す".to_string());
    let スタック = クリップスタック::一覧から作成する(vec![
        クリップを作る("収まる", 0.0, 1.0, 一回, トリガー::自動進行),
        はみ出す,
    ])
    .expect("重複しない");
    let エラー = 十六対九の出力でスタックから並べる(&スタック).expect_err("拒む");
    let スタックから並べるエラー::クリップを置けない { 名前, 理由 } = エラー
    else {
        panic!("置けないクリップの理由で拒む: {エラー:?}");
    };
    assert_eq!(名前.文字列(), "はみ出す");
    assert!(matches!(
        理由,
        重ね合わせの操作エラー::区間が動画の長さを超える { .. }
    ));
}
