//! スタックからの読み替えが置けないクリップを扱う試験。置けないクリップは飛ばして名前と理由を返し、再生できるクリップが無いときと
//! 置けるクリップが1つも無いときだけ拒むこと。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::arrange::{
    十六対九の出力でスタックから重ね合わせを並べる, 奥の行から並べた映す矩形の数値,
    置かなかったクリップの名前と理由,
};
use support::クリップを作る;

#[test]
fn 再生できるクリップが無ければ拒む() {
    assert_eq!(
        十六対九の出力でスタックから重ね合わせを並べる(
            &クリップスタック::default()
        ),
        Err(スタックから並べるエラー::再生できるクリップが無い)
    );
    let mut 無効 = クリップを作る(
        "無効",
        0.0,
        1.0,
        リピート設定::無限ループ,
        トリガー::自動進行,
    );
    無効.有効か = false;
    let 長さ0 = クリップを作る(
        "長さ0",
        3.0,
        3.0,
        リピート設定::無限ループ,
        トリガー::自動進行,
    );
    let スタック = クリップスタック::一覧から作成する(vec![無効, 長さ0]).expect("重複しない");
    assert_eq!(
        十六対九の出力でスタックから重ね合わせを並べる(&スタック),
        Err(スタックから並べるエラー::再生できるクリップが無い)
    );
}

fn はみ出すクリップを作る() -> クリップ {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let mut はみ出すクリップ =
        クリップを作る("はみ出す", 99.0, 101.0, 一回, トリガー::自動進行);
    はみ出すクリップ.名前 = クリップ名::作成する("はみ出す".to_string());
    はみ出すクリップ
}

#[test]
fn 区間の終わりが動画の長さより後ろのクリップは置かずに名前と理由を返す() {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let スタック = クリップスタック::一覧から作成する(vec![
        クリップを作る("収まる", 0.0, 1.0, 一回, トリガー::自動進行),
        はみ出すクリップを作る(),
    ])
    .expect("重複しない");
    let 結果 = 十六対九の出力でスタックから重ね合わせを並べる(&スタック).expect("並べられる");
    let 名前と理由 = 置かなかったクリップの名前と理由(&結果);
    assert_eq!(名前と理由.len(), 1);
    assert_eq!(名前と理由[0].0, "はみ出す");
    assert!(matches!(
        名前と理由[0].1,
        置かなかった理由::置く操作が拒んだ(
            重ね合わせの操作エラー::区間が動画の長さを超える { .. }
        )
    ));
    assert_eq!(
        奥の行から並べた映す矩形の数値(&結果.重ね合わせ),
        vec![[0.0, 0.0, 100.0, 100.0]]
    );
}

#[test]
fn 置けるクリップが1つも無ければ置かなかったクリップの一覧を持って拒む() {
    let スタック =
        クリップスタック::一覧から作成する(vec![はみ出すクリップを作る()]).expect("重複しない");
    let エラー = 十六対九の出力でスタックから重ね合わせを並べる(&スタック).expect_err("拒む");
    let スタックから並べるエラー::置けるクリップが無い(一覧) = エラー
    else {
        panic!("置けるクリップが無いとして拒む: {エラー:?}");
    };
    assert_eq!(一覧.len(), 1);
    assert_eq!(一覧[0].名前.文字列(), "はみ出す");
}
