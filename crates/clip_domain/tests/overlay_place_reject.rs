//! 重ね合わせへ置く前の確かめの試験。表に無い動画・動画の長さを超える区間・長さ0の区間・重なる識別子を拒むこと。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 受け継いだ値, 同じ識別子の発行元, 置いた連番の発行元, 重ねの秒,
    零番の動画へ置く,
};
use support::長さ;

#[test]
fn 表に無い動画と動画の長さを超える区間と長さ0の区間を拒む() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 置いた連番の発行元::default();
    let 二番 = 動画の番号::番号から作成する(1);
    assert_eq!(
        重ね.クリップから受け継いだ値を置く(
            受け継いだ値(0.0, 1.0, 1),
            二番,
            重ねの秒(0.0),
            長さ(100.0),
            &mut 発行元
        ),
        Err(重ね合わせの操作エラー::動画の番号が表に無い {
            番号: 二番,
            動画の数: 1
        })
    );
    assert_eq!(
        重ね.クリップから受け継いだ値を置く(
            受け継いだ値(9.0, 12.0, 1),
            動画の番号::最初,
            重ねの秒(0.0),
            長さ(10.0),
            &mut 発行元
        ),
        Err(重ね合わせの操作エラー::区間が動画の長さを超える {
            区間の終わり: 動画上の秒::作成する(12.0).expect("有効な秒数"),
            動画の長さ: 長さ(10.0),
        })
    );
    assert_eq!(
        零番の動画へ置く(&mut 重ね, 受け継いだ値(5.0, 5.0, 3), 0.0, &mut 発行元),
        Err(重ね合わせの操作エラー::区間の長さが0)
    );
    assert!(重ね.行の並び().is_empty());
    重ね
        .クリップから受け継いだ値を置く(
            受け継いだ値(9.0, 10.0, 1),
            動画の番号::最初,
            重ねの秒(0.0),
            長さ(10.0),
            &mut 発行元,
        )
        .expect("区間の終わりが動画の終わりと同じなら置ける");
}

#[test]
fn 発行した識別子が既にあれば拒み重ね合わせを変えない() {
    let mut 重ね = 一本の動画の重ね合わせ();
    let mut 発行元 = 同じ識別子の発行元;
    let 十秒 = 長さ(10.0);
    重ね
        .クリップから受け継いだ値を置く(
            受け継いだ値(0.0, 1.0, 1),
            動画の番号::最初,
            重ねの秒(0.0),
            十秒,
            &mut 発行元,
        )
        .expect("最初は重ならない");
    let 置く前 = 重ね.clone();
    assert_eq!(
        重ね.クリップから受け継いだ値を置く(
            受け継いだ値(0.0, 1.0, 1),
            動画の番号::最初,
            重ねの秒(5.0),
            十秒,
            &mut 発行元
        ),
        Err(
            重ね合わせの操作エラー::識別子が重複している(
                support::overlay::置いた識別子("置-1")
            )
        )
    );
    assert_eq!(重ね, 置く前);
}
