//! 設定ファイルを書き出してから読み込む往復と、書き出しの前提(空でないスタック・検証済みの動画パス)の試験。
#![allow(clippy::expect_used)]

mod support;

use std::time::{Duration, SystemTime};

use clip_domain::*;
use support::{クリップを作る, 試験用のスタック, 連番の発行元};

fn 読み込む(
    本文: &str,
) -> Result<スタック設定, 設定ファイルの読み込みエラー> {
    let 本文 = 設定ファイルの本文::作成する(本文.to_string());
    スタック設定::本文から読み込む(&本文, &mut 連番の発行元::default())
}

fn 検証済みのパス(
    入力: &str, 期待: Option<&動画ファイル名>
) -> 検証済みの動画パス {
    match 入力された動画パス::作成する(入力.to_string()).検証する(期待) {
        動画パスの検証結果::有効(パス) => パス,
        動画パスの検証結果::不正 { 不備, .. } => panic!("有効なはず: {不備}"),
    }
}

fn 日時() -> 書き出し日時 {
    let 時刻 = SystemTime::UNIX_EPOCH + Duration::from_millis(1_725_000_000_000);
    書き出し日時::時刻から作成する(時刻).expect("1970年より後")
}

#[test]
fn 書き出してから読み込むと同じスタックと動画の手がかりに戻る() {
    let mut 追加 = クリップを作る(
        "F",
        1.25,
        2.5,
        リピート設定::無限ループ,
        トリガー::Spaceキー待ち,
    );
    追加.クロップ =
        クロップ範囲::各値を範囲へ収めて作成する(12.5, 33.3, 40.0, 50.0);
    let mut スタック = 試験用のスタック();
    スタック.追加する(追加).expect("識別子は重複しない");
    let 動画 = 動画ファイル名::作成する("movie.mp4".to_string()).expect("空でない");
    let パス = 検証済みのパス(" \"D:\\movie.mp4\" ", Some(&動画));
    let 書き出す = 書き出す設定 {
        スタック: スタック.空でないことを確かめる().expect("空でない"),
        動画のパス: &パス,
    };
    let 本文 = 書き出す.本文へ書き出す(&日時()).expect("書き出せる");
    let mut 読み戻し = 読み込む(本文.文字列()).expect("読める");
    let 最後 = スタック.一覧().last().expect("ある").識別子().clone();
    読み戻し.スタック.選択する(&最後).expect("ある");
    assert_eq!(読み戻し.スタック, スタック);
    assert_eq!(パス.期待する動画(), Some(&動画));
    assert_eq!(読み戻し.期待する動画, Some(動画));
    assert_eq!(
        読み戻し.期待する動画のパス.as_ref(),
        Some(パス.正規化したパス())
    );
}

#[test]
fn 空のスタックは書き出しに使えない() {
    assert!(
        クリップスタック::default()
            .空でないことを確かめる()
            .is_none()
    );
}

#[test]
fn 書き出し日時はブラウザの日時の文字列と同じ形になる() {
    let 形 = |ミリ秒: u64| {
        let 時刻 = SystemTime::UNIX_EPOCH + Duration::from_millis(ミリ秒);
        書き出し日時::時刻から作成する(時刻)
            .expect("1970年より後")
            .文字列()
            .to_string()
    };
    assert_eq!(形(0), "1970-01-01T00:00:00.000Z");
    assert_eq!(形(1_725_000_000_000), "2024-08-30T06:40:00.000Z");
    assert_eq!(形(1_709_164_800_000), "2024-02-29T00:00:00.000Z");
    assert_eq!(形(951_782_400_123), "2000-02-29T00:00:00.123Z");
    assert_eq!(形(4_102_444_799_999), "2099-12-31T23:59:59.999Z");
    let 紀元より前 = SystemTime::UNIX_EPOCH - Duration::from_millis(1);
    assert_eq!(
        書き出し日時::時刻から作成する(紀元より前),
        Err(書き出し日時エラー)
    );
}
