//! クリップスタックの操作(選択・追加・更新・削除)と識別子の組み立ての試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 識別子};

fn クリップ(文字列: &str) -> クリップ {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    クリップを作る(文字列, 0.0, 1.0, 一回, トリガー::自動進行)
}

fn 二つのスタック() -> クリップスタック {
    クリップスタック::一覧から作成する(vec![クリップ("a"), クリップ("b")]).expect("重複しない")
}

fn 選択中の識別子(スタック: &クリップスタック) -> Option<&str> {
    スタック
        .選択中のクリップ()
        .map(|クリップ| クリップ.識別子().文字列())
}

#[test]
fn 作成すると先頭を選択し重複した識別子を拒む() {
    assert_eq!(選択中の識別子(&二つのスタック()), Some("a"));
    assert_eq!(選択中の識別子(&クリップスタック::default()), None);
    let 重複 =
        クリップスタック::一覧から作成する(vec![クリップ("a"), クリップ("a")]);
    let 期待 =
        クリップスタックの操作エラー::識別子が重複している(識別子("a"));
    assert_eq!(重複, Err(期待));
}

#[test]
fn 追加すると追加したクリップを選択し次の名前が決まる() {
    let mut スタック = クリップスタック::default();
    assert_eq!(スタック.次に追加するクリップの名前().文字列(), "Clip Mod 1");
    スタック.追加する(クリップ("a")).expect("追加できる");
    スタック.追加する(クリップ("b")).expect("追加できる");
    assert_eq!(選択中の識別子(&スタック), Some("b"));
    assert_eq!(スタック.次に追加するクリップの名前().文字列(), "Clip Mod 3");
    assert!(スタック.追加する(クリップ("a")).is_err());
}

#[test]
fn 選択と更新は存在しない識別子を拒む() {
    let mut スタック = 二つのスタック();
    スタック.選択する(&識別子("b")).expect("ある");
    assert_eq!(選択中の識別子(&スタック), Some("b"));
    let 無い = クリップスタックの操作エラー::見つからない(識別子("z"));
    assert_eq!(スタック.選択する(&識別子("z")), Err(無い));
    let mut 更新後 = クリップ("a");
    更新後.有効か = false;
    スタック.更新する(更新後.clone()).expect("ある");
    assert_eq!(スタック.識別子で探す(&識別子("a")), Some(&更新後));
    assert_eq!(選択中の識別子(&スタック), Some("b"));
    assert!(スタック.更新する(クリップ("z")).is_err());
}

#[test]
fn 削除は最後の1つを拒み選択中を消したら先頭を選ぶ() {
    let mut スタック = 二つのスタック();
    スタック.選択する(&識別子("b")).expect("ある");
    スタック.削除する(&識別子("b")).expect("削除できる");
    assert_eq!(選択中の識別子(&スタック), Some("a"));
    let 最後 = クリップスタックの操作エラー::最後の1つは削除できない;
    assert_eq!(スタック.削除する(&識別子("a")), Err(最後));
    let 無い = クリップスタックの操作エラー::見つからない(識別子("z"));
    assert_eq!(スタック.削除する(&識別子("z")), Err(無い));
}

#[test]
fn 新しい識別子は移植元と同じ表記で組み立てる() {
    let 識別子 = クリップ識別子::時刻と乱数から組み立てる(
        発行時刻::紀元からのミリ秒で作成する(1_725_000_000_000),
        識別子の乱数::乱数を畳んで作成する(123_456),
    );
    assert_eq!(識別子.文字列(), "mod-1725000000000-3456");
    assert!(クリップ識別子::文字列から作成する(String::new()).is_err());
}
