//! クリップの開始位置と、次の再生できるクリップの探索の試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{秒, 試験用のスタック, 識別子};

#[test]
fn クリップの開始位置は前のクリップの占有時間の合計である() {
    let スタック = 試験用のスタック();
    assert_eq!(スタック.クリップの開始位置(&識別子("A")), Some(秒(0.0)));
    assert_eq!(スタック.クリップの開始位置(&識別子("C")), Some(秒(6.0)));
    assert_eq!(スタック.クリップの開始位置(&識別子("E")), Some(秒(7.0)));
    assert_eq!(スタック.クリップの開始位置(&識別子("無い")), None);
}

#[test]
fn 次の再生できるクリップは無効なクリップと長さ0のクリップを飛ばす() {
    let スタック = 試験用のスタック();
    let 次のクリップの探索結果::見つかった {
        クリップ, 開始位置
    } = スタック.次の再生できるクリップを探す(秒(0.5))
    else {
        panic!("次のクリップが見つからない");
    };
    assert_eq!(クリップ.識別子().文字列(), "C");
    assert_eq!(開始位置, 秒(6.0));
}

#[test]
fn 最後のクリップの次は末尾に達したことを返す() {
    let スタック = 試験用のスタック();
    assert_eq!(
        スタック.次の再生できるクリップを探す(秒(7.5)),
        次のクリップの探索結果::末尾に達した
    );
    assert_eq!(
        スタック.次の再生できるクリップを探す(秒(20.0)),
        次のクリップの探索結果::現在の位置にクリップが無い
    );
    let 最初 = スタック
        .最初の再生できるクリップ()
        .expect("有効なクリップがある");
    assert_eq!(最初.識別子().文字列(), "A");
}
