//! 重ね合わせを組み立てる値の型(重ねる画面の縦横比・置いたクリップの識別子・置いたクリップの音の設定・クリップから受け継いだ値・使う動画の表)の試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::受け継いだ値;
use support::{クリップを作る, 長さ};

#[test]
fn 重ねる画面の縦横比はクロップ連動を拒み固定の比を受け取る() {
    assert_eq!(
        重ねる画面の縦横比::作成する(アスペクト比設定::クロップ連動),
        Err(重ねる画面の縦横比エラー)
    );
    let 正方形 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    assert_eq!(正方形.設定(), アスペクト比設定::正方形);
}

#[test]
fn 置いたクリップの音の設定は元の大きさで始まり消音なら鳴らす音量が無音になる() {
    let mut 音の設定 = 置いたクリップの音の設定::最初の値;
    assert_eq!(音の設定.鳴らす音量(), 音量::元の大きさ);
    音の設定.音量 = 音量::範囲へ収めて作る(0.25);
    assert_eq!(音の設定.鳴らす音量().値(), 0.25);
    音の設定.消音しているか = true;
    assert_eq!(音の設定.鳴らす音量(), 音量::無音);
}

#[test]
fn 受け継ぐときは無限ループを1回にし回数指定の回数を保つ() {
    let 三回 = リピート設定::回数指定(リピート回数::作成する(3).expect("範囲内"));
    let 回数指定 = クリップを作る("A", 10.0, 12.0, 三回, トリガー::Spaceキー待ち);
    let 受け継いだ =
        クリップから受け継いだ値::クリップから受け継ぐ(&回数指定);
    assert_eq!(受け継いだ.リピート回数.回数(), 3);
    assert_eq!(受け継いだ.区間, 回数指定.区間);
    assert_eq!(受け継いだ.占める長さ(), 長さ(6.0));
    let 無限 = クリップを作る(
        "C",
        20.0,
        21.0,
        リピート設定::無限ループ,
        トリガー::Enterキー待ち,
    );
    assert_eq!(
        クリップから受け継いだ値::クリップから受け継ぐ(&無限).リピート回数,
        リピート回数::一回
    );
}

#[test]
fn 受け継いだ値の占める長さは区間の長さとリピート回数の積である() {
    assert_eq!(受け継いだ値(1.0, 1.5, 4).占める長さ(), 長さ(2.0));
}

#[test]
fn 使う動画の表は並びの位置を動画の番号として指す() {
    let パス = |文字列: &str| 入力された動画パス::作成する(文字列.to_string()).正規化する();
    let 表 =
        使う動画の表::並びから作成する(vec![パス("D:\\a.mp4"), パス("D:\\b.mp4")]);
    let 一番 = 動画の番号::番号から作成する(1);
    assert_eq!(表.動画のパス(一番), Some(&パス("D:\\b.mp4")));
    assert!(!表.持っているか(動画の番号::番号から作成する(2)));
    assert_eq!(表.動画の数(), 2);
}

#[test]
fn 置いたクリップの識別子は空文字列を専用のエラーで拒む() {
    assert_eq!(
        置いたクリップの識別子::文字列から作成する(String::new()),
        Err(空の置いたクリップの識別子エラー)
    );
    let 時刻 = 発行時刻::紀元からのミリ秒で作成する(1790000000000);
    let 乱数 = 識別子の乱数::乱数を畳んで作成する(42);
    let 識別子 =
        置いたクリップの識別子::時刻と乱数から組み立てる(時刻, 乱数);
    assert_eq!(識別子.文字列(), "placed-1790000000000-42");
}
