//! サムネイルの撮り方の試験。最初の再生できるクリップの開始とクロップ、動画のパス、大きさが変わったときだけ撮り方が変わる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::クリップを作る;

fn 並べる(一覧: Vec<クリップ>) -> クリップスタック {
    クリップスタック::一覧から作成する(一覧).expect("並び")
}

fn スタック(パス: &str, 並び: クリップスタック) -> ライブラリのスタック {
    ライブラリのスタック::新しく作る(
        スタックの識別子::文字列から作成する("stack-1-1".into()).expect("識別子"),
        スタックの名前::作成する("甲".into()).expect("名前"),
        入力された動画パス::作成する(パス.into()).正規化する(),
        並び,
        ライブラリの日時::紀元からのミリ秒で作成する(1_000).expect("日時"),
    )
}

fn 大きさ() -> サムネイルの大きさ {
    サムネイルの大きさ::作成する(192, 108).expect("大きさ")
}

fn 一回() -> リピート設定 {
    リピート設定::回数指定(リピート回数::一回)
}

fn 二つのクリップ() -> Vec<クリップ> {
    vec![
        クリップを作る("A", 2.0, 4.0, 一回(), トリガー::自動進行),
        クリップを作る("B", 6.0, 8.0, 一回(), トリガー::自動進行),
    ]
}

fn 撮り方(並び: Vec<クリップ>) -> Option<サムネイルの撮り方> {
    スタック(r"D:\動画\a.mp4", 並べる(並び)).サムネイルの撮り方(大きさ())
}

#[test]
fn 最初の再生できるクリップの開始とクロップで撮る() {
    let mut 一覧 = 二つのクリップ();
    一覧[0].有効か = false;
    一覧[1].クロップ =
        クロップ範囲::各値を範囲へ収めて作成する(10.0, 20.0, 50.0, 60.0);
    let 撮り方 = 撮り方(一覧.clone()).expect("撮れる");
    assert_eq!(撮り方.時刻().秒数(), 6.0);
    assert_eq!(撮り方.クロップ(), 一覧[1].クロップ);
    assert_eq!(撮り方.動画のパス().文字列(), r"D:\動画\a.mp4");
}

#[test]
fn 名前や繰り返しや二つ目のクリップを変えても撮り方は変わらない() {
    let 元 = 撮り方(二つのクリップ());
    let mut 一覧 = 二つのクリップ();
    一覧[0].名前 = クリップ名::作成する("別名".into());
    一覧[0].区間 = 区間(2.0, 5.0);
    一覧[0].トリガー = トリガー::Enterキー待ち;
    一覧[1].クロップ =
        クロップ範囲::各値を範囲へ収めて作成する(1.0, 1.0, 50.0, 50.0);
    assert_eq!(撮り方(一覧), 元);
}

#[test]
fn 最初のクリップの開始かクロップか動画のパスか大きさを変えると撮り方が変わる() {
    let 元 = 撮り方(二つのクリップ());
    let mut 開始を変えた = 二つのクリップ();
    開始を変えた[0].区間 = 区間(3.0, 4.0);
    assert_ne!(撮り方(開始を変えた), 元);
    let mut クロップを変えた = 二つのクリップ();
    クロップを変えた[0].クロップ =
        クロップ範囲::各値を範囲へ収めて作成する(0.0, 0.0, 50.0, 50.0);
    assert_ne!(撮り方(クロップを変えた), 元);
    let 別の動画 =
        スタック(r"D:\動画\b.mp4", 並べる(二つのクリップ())).サムネイルの撮り方(大きさ());
    assert_ne!(別の動画, 元);
    let 別の大きさ = サムネイルの大きさ::作成する(96, 54).expect("大きさ");
    let 大きさを変えた = スタック(r"D:\動画\a.mp4", 並べる(二つのクリップ()))
        .サムネイルの撮り方(別の大きさ);
    assert_ne!(大きさを変えた, 元);
}

#[test]
fn 幅か高さが0の大きさは作らない() {
    assert_eq!(サムネイルの大きさ::作成する(0, 108), None);
    assert_eq!(サムネイルの大きさ::作成する(192, 0), None);
}

#[test]
fn 再生できるクリップが無いか動画のパスが空なら撮らない() {
    let mut 一覧 = 二つのクリップ();
    一覧[0].有効か = false;
    一覧[1].区間 = 区間(6.0, 6.0);
    assert_eq!(撮り方(一覧), None);
    assert_eq!(
        スタック("", 並べる(二つのクリップ())).サムネイルの撮り方(大きさ()),
        None
    );
    assert_eq!(撮り方(Vec::new()), None);
}

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 動画上の秒::作成する(値).expect("秒");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}
