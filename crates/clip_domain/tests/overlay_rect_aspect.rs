//! 映す矩形の縦横比を保つ大きさの変更の試験。向かいの隅を動かさず、絵の形の比(百分率では絵の縦横比を重ねる画面の縦横比で割った比)で、
//! 5%以上かつ重ねる画面の内側に収まることと、収まる大きさが無いときは縦横比を保たない大きさの変更にすることを確かめる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::rect_drag::{数値の組, 矩形, 移動量, 絵の縦横比};
#[test]
fn 縦横比を保つと向かいの隅を動かさず大きい方へ合わせる() {
    let 正方形の画面 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    let 正方形の絵 = 絵の縦横比(100.0, 100.0);
    let 元 = 矩形(0.0, 0.0, 50.0, 50.0);
    let 大きくした = 元.縦横比を保ってつまみで大きさを変える(
        四隅のつまみ::右下,
        移動量(10.0, 30.0),
        正方形の絵,
        正方形の画面,
    );
    assert_eq!(数値の組(大きくした), [0.0, 0.0, 80.0, 80.0]);
    let 中 = 矩形(50.0, 50.0, 40.0, 40.0);
    let 左上を広げた = 中.縦横比を保ってつまみで大きさを変える(
        四隅のつまみ::左上,
        移動量(-10.0, 0.0),
        正方形の絵,
        正方形の画面,
    );
    assert_eq!(数値の組(左上を広げた), [40.0, 40.0, 50.0, 50.0]);
}

#[test]
fn 縦横比を保つ大きさは重ねる画面の内側と5パーセント以上に収まる() {
    let 正方形の画面 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    let 中 = 矩形(50.0, 50.0, 40.0, 40.0);
    let 右下の外まで = 中.縦横比を保ってつまみで大きさを変える(
        四隅のつまみ::右下,
        移動量(100.0, 0.0),
        絵の縦横比(100.0, 100.0),
        正方形の画面,
    );
    assert_eq!(数値の組(右下の外まで), [50.0, 50.0, 50.0, 50.0]);
    let 横長 = 矩形(0.0, 0.0, 40.0, 20.0);
    let 縮めきった = 横長.縦横比を保ってつまみで大きさを変える(
        四隅のつまみ::右下,
        移動量(-100.0, -100.0),
        絵の縦横比(200.0, 100.0),
        正方形の画面,
    );
    assert_eq!(数値の組(縮めきった), [0.0, 0.0, 10.0, 5.0]);
}

#[test]
fn 百分率の比は絵の縦横比を重ねる画面の縦横比で割った値になる() {
    let ワイドの画面 = 重ねる画面の縦横比::ワイド16対9;
    let 元 = 矩形(0.0, 0.0, 50.0, 50.0);
    let 同じ形の絵 = 元.縦横比を保ってつまみで大きさを変える(
        四隅のつまみ::右下,
        移動量(10.0, 0.0),
        絵の縦横比(1920.0, 1080.0),
        ワイドの画面,
    );
    assert_eq!(数値の組(同じ形の絵), [0.0, 0.0, 60.0, 60.0]);
}

#[test]
fn 今の形を保つと開始時の百分率の幅と高さの比のまま大きさを変える() {
    let 横長 = 矩形(0.0, 0.0, 40.0, 20.0);
    let 広げた = 横長.今の形を保ってつまみで大きさを変える(
        四隅のつまみ::右下,
        移動量(20.0, 0.0),
    );
    assert_eq!(数値の組(広げた), [0.0, 0.0, 60.0, 30.0]);
}

#[test]
fn その比で収まる大きさが無いか比が0なら縦横比を保たない大きさの変更にする() {
    let 正方形の画面 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    let 元 = 矩形(10.0, 10.0, 50.0, 50.0);
    let 量 = 移動量(5.0, -20.0);
    let 保たない = 数値の組(元.つまみで大きさを変える(四隅のつまみ::右下, 量));
    for 絵 in [絵の縦横比(3000.0, 100.0), 絵の縦横比(0.0, 100.0)] {
        assert_eq!(
            数値の組(元.縦横比を保ってつまみで大きさを変える(
                四隅のつまみ::右下,
                量,
                絵,
                正方形の画面
            )),
            保たない
        );
    }
}
