//! ライブラリのスタックを本文へ書き出して読み込む往復と、変える操作の試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::試験用のスタック;

fn 識別子(文字列: &str) -> スタックの識別子 {
    スタックの識別子::文字列から作成する(文字列.to_string()).expect("識別子")
}

fn 名前(文字列: &str) -> スタックの名前 {
    スタックの名前::作成する(文字列.to_string()).expect("名前")
}

fn 日時(ミリ秒: u64) -> ライブラリの日時 {
    ライブラリの日時::紀元からのミリ秒で作成する(ミリ秒).expect("日時")
}

fn 動画(パス: &str) -> 正規化した動画パス {
    入力された動画パス::作成する(パス.to_string()).正規化する()
}

fn 試験用の項目() -> ライブラリのスタック {
    ライブラリのスタック::新しく作る(
        識別子("stack-1790000000000-42"),
        名前("サビの振り付け"),
        動画(r"D:\動画\練習.mp4"),
        試験用のスタック(),
        日時(1_790_000_000_000),
    )
}

fn 往復する(項目: &ライブラリのスタック) -> ライブラリのスタック {
    let 本文 = 項目.本文へ書き出す().expect("書き出せる");
    ライブラリのスタック::本文から読み込む(&本文).expect("読み込める")
}

#[test]
fn 書き出してから読み込むと同じ項目に戻る() {
    let 項目 = 試験用の項目();
    assert_eq!(往復する(&項目), 項目);
}

#[test]
fn 本文は形式の名前と版1を持ち空白を入れずに書く() {
    let 本文 = 試験用の項目().本文へ書き出す().expect("書き出せる");
    let 文字列 = 本文.文字列();
    assert!(文字列.starts_with(
        r#"{"format":"ClipViewer.library","version":1,"identifier":"stack-1790000000000-42""#
    ));
    assert!(!文字列.contains('\n'));
    assert!(文字列.contains(r#""repeat":"infinite""#));
    assert!(文字列.contains(r#""createdAtMs":1790000000000,"updatedAtMs":1790000000000"#));
}

#[test]
fn 変える操作は更新した日時だけを進め_作った日時を保つ() {
    let 項目 = 試験用の項目()
        .名前を変えた(名前("  前奏  "), 日時(1_790_000_000_500))
        .動画の場所を変えた(動画(r#""E:\移した\練習.mp4""#), 日時(1_790_000_001_000));
    assert_eq!(項目.名前().文字列(), "前奏");
    assert_eq!(項目.動画のパス().文字列(), r"E:\移した\練習.mp4");
    assert_eq!(項目.作った日時(), 日時(1_790_000_000_000));
    assert_eq!(項目.更新した日時(), 日時(1_790_000_001_000));
    let 差し替え = 項目
        .clone()
        .並びを差し替えた(クリップスタック::default(), 日時(1_790_000_002_000));
    assert!(差し替え.並び().一覧().is_empty());
    assert_eq!(往復する(&差し替え), 差し替え);
}

#[test]
fn 複製は同じ動画と並びを持ち_識別子と名前と作った日時が新しい() {
    let 元 = 試験用の項目();
    let 複製 = 元.複製した(識別子("stack-2-3"), 元.名前().複製の名前(), 日時(2_000));
    assert_eq!(複製.名前().文字列(), "サビの振り付けのコピー");
    assert_eq!(複製.並び(), 元.並び());
    assert_eq!(複製.動画のパス(), 元.動画のパス());
    assert_eq!(複製.作った日時(), 日時(2_000));
    assert_ne!(複製.識別子(), 元.識別子());
}

#[test]
fn 区間の長さの合計は全クリップの区間の長さの和である() {
    let 合計 = 試験用の項目().区間の長さの合計().秒数();
    assert!((合計 - 12.0).abs() < 1e-9, "合計 {合計}");
}
