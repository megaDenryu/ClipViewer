//! 進める操作で次のクリップへ進める規則の試験。次へボタン(画面の Next Clip・PageDown・Enterキー)はどのクリップでも、
//! 出力のクリックはクリック待ちのときだけ進める。次へ進めるのはシーケンス再生のときだけである。長さ0のクリップは進む先に選ばない。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::next_result::{次へ進めた結果の期待値, 止めた, 進める, 進んだ};
use support::{クリップを作る, 試験用のスタック, 長さ};

#[test]
fn 次へボタンは自動進行の無限ループからも進め_出力のクリックでは進めない() {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    let 無限 = クリップを作る(
        "無限",
        0.0,
        1.0,
        リピート設定::無限ループ,
        トリガー::自動進行,
    );
    let 後 = クリップを作る("後", 5.0, 9.0, 一回, トリガー::自動進行);
    let スタック = クリップスタック::一覧から作成する(vec![無限, 後]).expect("重複しない");
    let 止まる設定 = 末尾での振る舞い::止まる;
    assert_eq!(
        進める(&スタック, 0.5, 進める操作::次へボタン, 止まる設定),
        進んだ(1.0, "後")
    );
    let クリック = 進める(&スタック, 0.5, 進める操作::出力のクリック, 止まる設定);
    assert_eq!(
        クリック,
        次へ進めた結果の期待値::進めない(進めない理由::操作がトリガーと合わない)
    );
}

#[test]
fn 次へボタンはキー待ちのクリップを待つ前の周回からでも進め_出力のクリックは合わず_長さ0のクリップは飛ばす()
 {
    let スタック = 試験用のスタック();
    let 止まる設定 = 末尾での振る舞い::止まる;
    assert_eq!(
        進める(&スタック, 0.5, 進める操作::次へボタン, 止まる設定),
        進んだ(6.0, "C")
    );
    let 合わない = 進める(&スタック, 0.5, 進める操作::出力のクリック, 止まる設定);
    assert_eq!(
        合わない,
        次へ進めた結果の期待値::進めない(進めない理由::操作がトリガーと合わない)
    );
    assert_eq!(
        進める(&スタック, 6.5, 進める操作::次へボタン, 止まる設定),
        進んだ(7.0, "E")
    );
}

#[test]
fn 最後のクリップの次は全体ループなら先頭へ戻り止まる設定なら再生を止める() {
    let スタック = 試験用のスタック();
    let クリック = 進める操作::出力のクリック;
    assert_eq!(
        進める(&スタック, 8.0, クリック, 末尾での振る舞い::先頭へ戻る),
        進んだ(0.0, "A")
    );
    let 止めた結果 = 進める(&スタック, 8.0, クリック, 末尾での振る舞い::止まる);
    assert_eq!(止めた結果, 止めた(11.0, "E"));
    let 範囲外 = 進める(
        &スタック,
        20.0,
        進める操作::次へボタン,
        末尾での振る舞い::止まる,
    );
    assert_eq!(
        範囲外,
        次へ進めた結果の期待値::進めない(進めない理由::現在の位置にクリップが無い)
    );
}

#[test]
fn シーケンス再生でなければ次へ進めない() {
    let スタック = 試験用のスタック();
    let 単独 = 再生位置::単独クリップ再生(長さ(0.5));
    let 結果 = 単独.操作で次へ進める(
        進める操作::次へボタン,
        &スタック,
        末尾での振る舞い::先頭へ戻る,
    );
    assert_eq!(
        結果,
        次へ進めた結果::進めない(進めない理由::シーケンス再生でない)
    );
}
