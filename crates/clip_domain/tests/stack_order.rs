//! クリップスタックの並びを変える操作の試験。並べ替えは選択を変えずに順を変え、複製は元の直後へ新しい識別子で差し込んで選ぶ。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::{クリップを作る, 識別子};

fn 三つの並び() -> クリップスタック {
    let 一回 = リピート設定::回数指定(リピート回数::一回);
    クリップスタック::一覧から作成する(vec![
        クリップを作る("甲", 0.0, 1.0, 一回, トリガー::自動進行),
        クリップを作る("乙", 1.0, 2.0, 一回, トリガー::Enterキー待ち),
        クリップを作る("丙", 2.0, 3.0, 一回, トリガー::自動進行),
    ])
    .expect("重複しない")
}

fn 並びの識別子(スタック: &クリップスタック) -> Vec<String> {
    スタック
        .一覧()
        .iter()
        .map(|クリップ| クリップ.識別子().文字列().to_string())
        .collect()
}

#[test]
fn 並べ替えると順だけが変わり選択は変わらない() {
    let mut スタック = 三つの並び();
    スタック.選択する(&識別子("乙")).expect("ある");
    スタック.並べ替える(0, 2).expect("範囲の内");
    assert_eq!(並びの識別子(&スタック), ["乙", "丙", "甲"]);
    スタック.並べ替える(2, 1).expect("範囲の内");
    assert_eq!(並びの識別子(&スタック), ["乙", "甲", "丙"]);
    assert_eq!(スタック.番号を探す(&識別子("甲")), Ok(1));
    assert_eq!(
        スタック
            .選択中のクリップ()
            .map(|クリップ| クリップ.識別子().clone()),
        Some(識別子("乙"))
    );
}

#[test]
fn 範囲の外の番号へは並べ替えない() {
    let mut スタック = 三つの並び();
    assert_eq!(
        スタック.並べ替える(0, 3),
        Err(クリップスタックの操作エラー::番号が範囲の外 {
            番号: 3, 数: 3
        })
    );
    assert_eq!(並びの識別子(&スタック), ["甲", "乙", "丙"]);
}

#[test]
fn 複製は元の直後へ新しい識別子で差し込んで選び_中身は名前のほか元と同じ() {
    let mut スタック = 三つの並び();
    スタック
        .直後へ複製する(&識別子("乙"), 識別子("乙の写し"))
        .expect("複製できる");
    assert_eq!(並びの識別子(&スタック), ["甲", "乙", "乙の写し", "丙"]);
    let 元 = スタック.識別子で探す(&識別子("乙")).expect("ある").clone();
    let 写し = スタック.選択中のクリップ().expect("選んでいる").clone();
    assert_eq!(写し.識別子(), &識別子("乙の写し"));
    assert_eq!(写し.名前.文字列(), "名前のコピー");
    assert_eq!(
        (
            写し.有効か,
            写し.区間,
            写し.リピート,
            写し.クロップ,
            写し.トリガー
        ),
        (元.有効か, 元.区間, 元.リピート, 元.クロップ, 元.トリガー)
    );
    assert_eq!(
        スタック.直後へ複製する(&識別子("甲"), 識別子("丙")),
        Err(
            クリップスタックの操作エラー::識別子が重複している(
                識別子("丙")
            )
        )
    );
}
