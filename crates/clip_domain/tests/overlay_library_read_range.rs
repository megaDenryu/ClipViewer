//! 重ね合わせのファイルの読み込みの試験。範囲の外の音量とクロップと映す矩形の値を範囲へ収めて読むことと、
//! 成立しない値を拒むときに、2つ目の行と行の中の2つ目の置いたクリップでも行の番号と部品の並びの中の位置が正しく付くことを確かめる。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::行;
use support::overlay_library_text::{本文, 読む};

fn 最初の置いたクリップ(
    読んだ: &ライブラリの重ね合わせ
) -> 置いたクリップ {
    読んだ.重ね合わせ().行の並び().奥から手前の順の行()[0].置いたクリップの並び()[0].clone()
}

#[test]
fn 範囲の外の音量とクロップと映す矩形の値は範囲へ収めて読む() {
    let 読んだ = 読む(&本文(&[
        (r#""volume":1.0"#, r#""volume":1.5"#),
        (
            r#""crop":{"x":0.0,"y":0.0,"w":100.0"#,
            r#""crop":{"x":-5.0,"y":0.0,"w":150.0"#,
        ),
        (
            r#""rect":{"x":0.0,"y":0.0,"w":100.0"#,
            r#""rect":{"x":0.0,"y":0.0,"w":150.0"#,
        ),
    ]))
    .expect("範囲へ収めて読める");
    let 置いた = 最初の置いたクリップ(&読んだ);
    assert_eq!(置いた.音の設定().音量, 音量::元の大きさ);
    let クロップ = 置いた.受け継いだ値().クロップ;
    assert_eq!((クロップ.左端().数値(), クロップ.幅().数値()), (0.0, 100.0));
    assert_eq!(置いた.映す矩形(), 映す矩形::全体);
    let 負の音量 = 読む(&本文(&[(r#""volume":1.0"#, r#""volume":-0.5"#)])).expect("読める");
    assert_eq!(最初の置いたクリップ(&負の音量).音の設定().音量, 音量::無音);
}

/// 1行目に1つ、2行目に2つの置いたクリップを持つ本文。2行目の2つ目の repeat を壊し方で置き換える。
fn 二行目の二つ目を壊した本文(repeat: &str) -> String {
    let 置いた = |id: &str, at: &str, repeat: &str| {
        format!(
            r#"{{"id":"{id}","name":"二","video":0,"start":1.0,"end":2.0,"repeat":{repeat},"crop":{{"x":0.0,"y":0.0,"w":100.0,"h":100.0}},"at":{at},"rect":{{"x":0.0,"y":0.0,"w":100.0,"h":100.0}},"volume":1.0,"muted":false}}"#
        )
    };
    let 二行目 = format!(
        r#",{{"items":[{},{}]}}"#,
        置いた("p2", "0.0", "1"),
        置いた("p3", "5.0", repeat)
    );
    本文(&[(
        r#""muted":false}]}]"#,
        &format!(r#""muted":false}}]}}{二行目}]"#),
    )])
}

#[test]
fn 二行目の二つ目の置いたクリップの値の不備は_その行の番号と位置を付けて拒む() {
    assert!(読む(&二行目の二つ目を壊した本文("1")).is_ok());
    match 読む(&二行目の二つ目を壊した本文("0")) {
        Err(重ね合わせのファイルの読み込みエラー::置いたクリップが不正 {
            行: 番号,
            位置,
            理由: 置いたクリップの値の不備::繰り返しの回数が不正(_),
        }) => {
            assert_eq!(番号, 行(1));
            assert_eq!(位置, 部品の並びの中の位置::番号から作成する(1));
        }
        その他 => panic!("置いたクリップが不正にならず {その他:?}"),
    }
}
