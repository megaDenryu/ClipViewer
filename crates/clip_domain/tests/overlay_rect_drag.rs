//! 映す矩形の移動と、四隅のつまみによる縦横比を保たない大きさの変更がクロップ枠と同じ規則であることと、
//! 重ね合わせの縦横比を変える操作と、パスから動画の番号を探すことの試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::rect_drag::{数値の組, 矩形, 移動量};

fn クロップの移動量にする(横: f64, 縦: f64) -> クロップの移動量 {
    クロップの移動量 {
        横: 百分率の差分::作成する(横).expect("有限"),
        縦: 百分率の差分::作成する(縦).expect("有限"),
    }
}

fn クロップの数値の組(範囲: クロップ範囲) -> [f64; 4] {
    [範囲.左端(), 範囲.上端(), 範囲.幅(), 範囲.高さ()].map(百分率::数値)
}
const 一覧: [四隅のつまみ; 4] = [
    四隅のつまみ::左上,
    四隅のつまみ::右上,
    四隅のつまみ::左下,
    四隅のつまみ::右下,
];

#[test]
fn 縦横比を保たない移動と大きさの変更はクロップ枠と同じ値になる() {
    let 元の値 = [
        (70.0, 10.0, 20.0, 50.0),
        (10.0, 10.0, 50.0, 50.0),
        (33.3, 66.7, 12.5, 30.0),
    ];
    let 量の並び = [
        (5.0, 5.0),
        (30.0, 80.0),
        (-100.0, -100.0),
        (-47.5, 12.25),
        (200.0, -3.0),
    ];
    for (左端, 上端, 幅, 高さ) in 元の値 {
        let 映す = 矩形(左端, 上端, 幅, 高さ);
        let クロップ =
            クロップ範囲::各値を範囲へ収めて作成する(左端, 上端, 幅, 高さ);
        for (横, 縦) in 量の並び {
            assert_eq!(
                数値の組(映す.移動する(移動量(横, 縦))),
                クロップの数値の組(クロップ.移動する(クロップの移動量にする(横, 縦)))
            );
            for つまみ in 一覧 {
                assert_eq!(
                    数値の組(映す.つまみで大きさを変える(つまみ, 移動量(横, 縦))),
                    クロップの数値の組(
                        クロップ.つまみで大きさを変える(
                            つまみ,
                            クロップの移動量にする(横, 縦)
                        )
                    ),
                    "{つまみ:?} {横} {縦}"
                );
            }
        }
    }
}

#[test]
fn 縦横比を変えると縦横比が変わり_動画の番号はパスの等しさで探す() {
    let mut 重ね合わせ = 重ね合わせ::作成する(
        重ねる画面の縦横比::ワイド16対9,
        使う動画の表::一本の動画から作成する(
            入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
        ),
    );
    let 縦型 = 重ねる画面の縦横比::作成する(アスペクト比設定::縦型9対16).expect("固定の比");
    重ね合わせ.縦横比を変える(縦型);
    assert_eq!(重ね合わせ.縦横比(), 縦型);
    let 表 = 重ね合わせ.動画の表();
    assert_eq!(
        表.パスの動画の番号(
            &入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する()
        ),
        Some(動画の番号::最初)
    );
    assert_eq!(
        表.パスの動画の番号(
            &入力された動画パス::作成する(r"C:\別.mp4".to_string()).正規化する()
        ),
        None
    );
}
