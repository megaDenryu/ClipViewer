//! 空の行を消す操作と、空の新しい行を最も手前に足す操作の試験。
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay::{
    一本の動画の重ね合わせ, 二行の重ね合わせ, 置いた識別子, 行, 行ごとの識別子,
};

#[test]
fn 取り除いて空になった行を消すと手前の行の番号が1つ小さくなる() {
    let mut 重ね = 二行の重ね合わせ();
    重ね
        .置いたクリップを取り除く(&置いた識別子("置-1"))
        .expect("ある");
    assert_eq!(行ごとの識別子(&重ね), vec![vec![], vec!["置-2", "置-3"]]);
    重ね.空の行を消す(行(0)).expect("空の行");
    assert_eq!(行ごとの識別子(&重ね), vec![vec!["置-2", "置-3"]]);
    assert_eq!(
        重ね.行の並び().置いてある行の番号(&置いた識別子("置-3")),
        Ok(行(0))
    );
}

#[test]
fn 置いたクリップを持つ行と無い行は消さず重ね合わせを変えない() {
    let mut 重ね = 二行の重ね合わせ();
    let 消す前 = 重ね.clone();
    assert_eq!(
        重ね.空の行を消す(行(1)),
        Err(重ね合わせの操作エラー::行が空でない { 行: 行(1) })
    );
    assert_eq!(
        重ね.空の行を消す(行(2)),
        Err(重ね合わせの操作エラー::行の番号が範囲の外 {
            行: 行(2),
            行の数: 2
        })
    );
    assert_eq!(重ね, 消す前);
}

#[test]
fn 空の行は最も手前に足し_行は8つまで() {
    let mut 重ね = 二行の重ね合わせ();
    assert_eq!(重ね.空の行を手前に足す(), Ok(行(2)));
    assert_eq!(
        行ごとの識別子(&重ね),
        vec![vec!["置-1"], vec!["置-2", "置-3"], vec![]]
    );
    for 番号 in 3..同時に重ねられる行の数 {
        assert_eq!(重ね.空の行を手前に足す(), Ok(行(番号)));
    }
    let 足す前 = 重ね.clone();
    assert_eq!(
        重ね.空の行を手前に足す(),
        Err(重ね合わせの操作エラー::行の数が上限に達している)
    );
    assert_eq!(重ね, 足す前);
}

#[test]
fn 行の無い重ね合わせにも空の行を足せる() {
    let mut 重ね = 一本の動画の重ね合わせ();
    assert_eq!(重ね.空の行を手前に足す(), Ok(行(0)));
    assert_eq!(重ね.重ね合わせの長さ(), 時刻::先頭);
}
