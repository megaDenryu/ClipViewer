//! 重ね合わせのファイル第1版の見本(`fixtures/overlay_v1.json`)の試験。
//! 見本は第1版で書いたファイルそのものであり、以後書き換えない。版を上げても、見本を読めることは永久に確かめ続ける。
//! 書き出しが見本と1バイトも違わないことは、第1版が最新の版である間だけ確かめる。参照: _doc/設計/ライブラリ.md「形式の版を上げる手順」
#![allow(clippy::expect_used)]

mod support;

use clip_domain::*;
use support::overlay_library::{日時, 置くもの};
use support::overlay_library_text::読む;

const 第1版の見本: &str = include_str!("fixtures/overlay_v1.json");

/// 見本と同じ中身を、ファイルを通さずに手で組んだもの。2本の動画を持ち、奥の行に2つ、手前の行に1つ置く。
fn 手で組んだ期待値() -> ライブラリの重ね合わせ {
    let 奥の一つ目 = 置くもの {
        識別子: "placed-1790000000000-7",
        名前: "Clip Mod 1",
        動画: 0,
        区間: (12.5, 14.0),
        回数: 4,
        クロップ: (10.0, 0.0, 50.0, 100.0),
        始まり: 0.0,
        矩形: (0.0, 0.0, 50.0, 100.0),
        音量: 1.0,
        消音: false,
    };
    let 奥の二つ目 = 置くもの {
        識別子: "placed-1790000000000-9",
        名前: "",
        動画: 1,
        区間: (3.25, 4.0),
        回数: 1,
        クロップ: (0.0, 0.0, 100.0, 100.0),
        始まり: 8.0,
        矩形: (25.0, 12.5, 50.0, 75.0),
        音量: 0.25,
        消音: false,
    };
    let 手前 = 置くもの {
        識別子: "placed-1790000000000-8",
        名前: "Clip Mod 2",
        動画: 0,
        区間: (30.0, 31.5),
        回数: 4,
        クロップ: (40.0, 0.0, 50.0, 100.0),
        始まり: 0.0,
        矩形: (50.0, 0.0, 50.0, 100.0),
        音量: 0.5,
        消音: true,
    };
    let 動画 = |パス: &str| 入力された動画パス::作成する(パス.to_string()).正規化する();
    let 重ね = 重ね合わせの部品一式 {
        縦横比: 重ねる画面の縦横比::作成する(アスペクト比設定::スタンダード4対3)
            .expect("固定の比"),
        動画の表: 使う動画の表::並びから作成する(vec![
            動画(r"D:\動画\練習 2026\本番.mp4"),
            動画(r"E:\撮影\横から.mp4"),
        ]),
        行の並び: vec![
            タイムラインの行の部品一式 {
                置いたクリップの並び: vec![奥の一つ目.部品一式(), 奥の二つ目.部品一式()],
            },
            タイムラインの行の部品一式 {
                置いたクリップの並び: vec![手前.部品一式()],
            },
        ],
    }
    .重ね合わせへ組み立てる()
    .expect("組み立てられる");
    ライブラリの重ね合わせ::新しく作る(
        重ね合わせの識別子::文字列から作成する("overlay-1790000000000-42".into()).expect("識別子"),
        重ね合わせの名前::作成する("ふたりの振り付け \"本番\"".into()).expect("名前"),
        重ね.clone(),
        日時(1_790_000_000_000),
    )
    .重ね合わせを差し替えた(重ね, 日時(1_790_000_123_456))
}

#[test]
fn 第1版の見本を読んだ結果は手で組んだ期待値と等しい() {
    assert_eq!(読む(第1版の見本).expect("見本を読める"), 手で組んだ期待値());
}

#[test]
fn 期待値を書き出すと見本と1バイトも違わない() {
    let 本文 = 手で組んだ期待値().本文へ書き出す().expect("書き出せる");
    assert_eq!(本文.文字列(), 第1版の見本);
}

#[test]
fn 書き出した本文を読むと同じ値に戻る() {
    let 期待値 = 手で組んだ期待値();
    let 本文 = 期待値.本文へ書き出す().expect("書き出せる");
    assert_eq!(読む(本文.文字列()).expect("読める"), 期待値);
}
