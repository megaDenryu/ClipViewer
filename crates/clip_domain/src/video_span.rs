//! 動画上の区間の値オブジェクト。

use crate::duration::時間の長さ;
use crate::time::動画上の秒;

/// 動画上の区間とは、元の動画から切り出す開始位置と終了位置の組のことである。
/// 不変条件: 開始は終了より後ろにない。開始と終了が等しい長さ0の区間は許す。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 動画上の区間 {
    開始: 動画上の秒,
    終了: 動画上の秒,
}

/// 区間エラーとは、区間の開始が終了より後ろにあることである。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
#[error("区間の開始({開始}秒)が終了({終了}秒)より後ろにある")]
pub struct 区間エラー {
    /// 渡された開始の秒数。
    pub 開始: f64,
    /// 渡された終了の秒数。
    pub 終了: f64,
}

impl 動画上の区間 {
    /// 開始と終了から作成する。開始が終了より後ろにあれば拒む。
    pub fn 作成する(
        開始: 動画上の秒, 終了: 動画上の秒
    ) -> Result<Self, 区間エラー> {
        if 開始 > 終了 {
            return Err(区間エラー {
                開始: 開始.秒数(),
                終了: 終了.秒数(),
            });
        }
        Ok(Self { 開始, 終了 })
    }

    /// 開始が終了より後ろにないことを呼び出し側が保証する開始と終了から作る。
    /// 注意: 開始 ≦ 終了 を満たす値だけを渡すこと。
    pub(crate) fn 検査済みの開始と終了から作る(
        開始: 動画上の秒,
        終了: 動画上の秒,
    ) -> Self {
        Self { 開始, 終了 }
    }

    /// 開始から指定の長さの区間を作る。
    pub fn 開始と長さから作る(開始: 動画上の秒, 長さ: 時間の長さ) -> Self {
        Self {
            開始,
            終了: 開始.進める(長さ),
        }
    }

    /// 開始位置。
    pub fn 開始(&self) -> 動画上の秒 {
        self.開始
    }

    /// 終了位置。
    pub fn 終了(&self) -> 動画上の秒 {
        self.終了
    }

    /// 区間の長さ。
    pub fn 長さ(&self) -> 時間の長さ {
        self.終了.起点から経過した長さ(self.開始)
    }

    /// 位置を区間の中へ収める。
    pub fn 位置を区間の中へ収める(&self, 位置: 動画上の秒) -> 動画上の秒 {
        if 位置 < self.開始 {
            self.開始
        } else if 位置 > self.終了 {
            self.終了
        } else {
            位置
        }
    }
}
