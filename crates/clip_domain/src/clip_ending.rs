//! クリップの終わりでの振る舞いの規則。クリップの終わりで次へ進むか、最後の周回を繰り返して待つかを決める。
//! 移植元は、無限ループを1周で次へ進め、トリガー待ちでは占有時間ぶん巻き戻して最初の周回へ戻していた。
//! 本クレートはオーナーの決定により、待つクリップは最後の周回を繰り返しながら待つ規則にしている。

use crate::clip::クリップ;
use crate::repeat::{リピート回数, リピート設定, 周回番号};
use crate::stack::クリップスタック;
use crate::time::タイムライン上の秒;
use crate::trigger::進める操作;

impl クリップ {
    /// クリップの終わりで待つか。無限ループか、トリガーが自動進行以外なら待つ。
    /// 待つクリップは、最後の周回の終わりに達すると同じ周回を繰り返し、進める操作が来るまで次へ進まない。
    pub fn 終わりで待つか(&self) -> bool {
        matches!(self.リピート, リピート設定::無限ループ) || self.トリガー.利用者の操作が必要か()
    }

    /// タイムライン上で占める周回の数。回数指定ならその回数、無限ループなら1周である。
    pub fn タイムライン上の周回数(&self) -> リピート回数 {
        match self.リピート {
            リピート設定::無限ループ => リピート回数::一回,
            リピート設定::回数指定(回数) => 回数,
        }
    }

    /// この周回が、タイムライン上の最後の周回か。無限ループでは0周目が最後の周回である。
    pub fn 最後の周回か(&self, 周回: 周回番号) -> bool {
        self.タイムライン上の周回数().最後の周回か(周回)
    }

    /// この周回で待っているか。終わりで待つクリップの、最後の周回を再生している状態を指す。
    /// 画面はこの間「トリガー待機中」を表示する。
    pub fn 待っているか(&self, 周回: 周回番号) -> bool {
        self.終わりで待つか() && self.最後の周回か(周回)
    }

    /// この操作で次のクリップへ進むか。次へボタンはどのクリップでも進める。
    /// キーとクリックは、クリップのトリガーと合うときだけ進める(待つ前の周回でも進める。移植元のクリックと同じ)。
    /// 自動進行の無限ループは次へボタンでだけ進める。
    pub fn この操作で次へ進むか(&self, 操作: 進める操作) -> bool {
        self.トリガー.この操作で進むか(操作)
    }
}

impl クリップ {
    /// タイムライン上でこのクリップが終わる位置を越えた位置を、最後の周回の中へ1区間長ずつ戻す。
    /// 注意: 浮動小数の丸めで戻した位置が終わりに一致したときは、最後の周回の先頭にする。
    fn 最後の周回の中へ戻す(
        &self,
        終わり: タイムライン上の秒,
        進めた位置: タイムライン上の秒,
    ) -> タイムライン上の秒 {
        let 一周 = self.区間.長さ();
        let 最後の周回の開始 = 終わり.戻す(一周);
        let 余り = 進めた位置
            .起点から経過した長さ(最後の周回の開始)
            .一周の中での余り(一周);
        let 戻した位置 = 最後の周回の開始.進める(余り);
        if 戻した位置 < 終わり {
            戻した位置
        } else {
            最後の周回の開始
        }
    }
}

impl クリップスタック {
    /// 位置から進めた位置までの間に通る、最初の待つクリップの終わりを探し、越えていればその最後の周回の中へ戻す。
    /// 1回の増分が大きく、待たないクリップから待つクリップの終わりまで一度に越える場合も、待つクリップを飛び越さない。
    /// 通る待つクリップが無ければ戻さない。再生できないクリップ(無効・長さ0)は通らないものとして扱う。
    pub(crate) fn 通る待つクリップの最後の周回へ戻す(
        &self,
        位置: タイムライン上の秒,
        進めた位置: タイムライン上の秒,
    ) -> Option<タイムライン上の秒> {
        self.開始位置付きで並べる()
            .find(|並び| {
                let 終わり = 並び.終わりの位置();
                let 通って越えるか = 終わり > 位置 && 進めた位置 >= 終わり;
                並び.クリップ.再生できるか()
                    && 並び.クリップ.終わりで待つか()
                    && 通って越えるか
            })
            .map(|並び| {
                並び
                    .クリップ
                    .最後の周回の中へ戻す(並び.終わりの位置(), 進めた位置)
            })
    }
}
