//! クリップスタックの並びを変える操作。末尾への追加・置き換え・削除と、クリップを別の番号へ動かすことと、
//! あるクリップの直後へ複製を差し込むこと。選択は識別子で持つため、並びの順が変わっても選択中のクリップは変わらない。

use super::クリップスタック;
use crate::clip::クリップ;
use crate::clip_id::クリップ識別子;
use crate::stack_error::クリップスタックの操作エラー;

impl クリップスタック {
    /// クリップを末尾へ追加し、追加したクリップを選択する。識別子の重複を拒む。
    pub fn 追加する(
        &mut self,
        クリップ: クリップ,
    ) -> Result<(), クリップスタックの操作エラー> {
        let 識別子 = クリップ.識別子().clone();
        self.末尾へ積む(クリップ)?;
        self.選択中 = Some(識別子);
        Ok(())
    }

    /// 同じ識別子のクリップを、渡したクリップで置き換える。選択は変えない。
    pub fn 更新する(
        &mut self,
        更新後: クリップ,
    ) -> Result<(), クリップスタックの操作エラー> {
        let 位置 = self.番号を探す(更新後.識別子())?;
        self.一覧[位置] = 更新後;
        Ok(())
    }

    /// 指定の識別子のクリップを削除する。最後の1つは削除できない。
    /// 選択中のクリップを削除したときは、先頭のクリップを選択する。
    pub fn 削除する(
        &mut self,
        識別子: &クリップ識別子,
    ) -> Result<(), クリップスタックの操作エラー> {
        let 位置 = self.番号を探す(識別子)?;
        if self.一覧.len() <= 1 {
            return Err(クリップスタックの操作エラー::最後の1つは削除できない);
        }
        self.一覧.remove(位置);
        if self.選択中.as_ref() == Some(識別子) {
            self.選択中 = self.一覧.first().map(|先頭| 先頭.識別子().clone());
        }
        Ok(())
    }

    pub(super) fn 末尾へ積む(
        &mut self,
        クリップ: クリップ,
    ) -> Result<(), クリップスタックの操作エラー> {
        if self.識別子で探す(クリップ.識別子()).is_some() {
            return Err(
                クリップスタックの操作エラー::識別子が重複している(
                    クリップ.識別子().clone(),
                ),
            );
        }
        self.一覧.push(クリップ);
        Ok(())
    }

    /// 元の番号のクリップを取り出し、先の番号へ差し込む。番号は0から数え、先の番号は取り出した後の並びでの番号である。
    /// 選択は変えない。どちらかの番号がクリップの数の範囲の外なら拒む。
    pub fn 並べ替える(
        &mut self,
        元の番号: usize,
        先の番号: usize,
    ) -> Result<(), クリップスタックの操作エラー> {
        let 数 = self.一覧.len();
        for 番号 in [元の番号, 先の番号] {
            if 番号 >= 数 {
                return Err(クリップスタックの操作エラー::番号が範囲の外 {
                    番号,
                    数,
                });
            }
        }
        let クリップ = self.一覧.remove(元の番号);
        self.一覧.insert(先の番号, クリップ);
        Ok(())
    }

    /// 元のクリップを新しい識別子で写し、名前に「のコピー」を足して、元のクリップの直後へ差し込み、差し込んだクリップを選ぶ。
    /// 元のクリップが無いか、新しい識別子が既にあれば拒む。
    pub fn 直後へ複製する(
        &mut self,
        元の識別子: &クリップ識別子,
        新しい識別子: クリップ識別子,
    ) -> Result<(), クリップスタックの操作エラー> {
        let 位置 = self.番号を探す(元の識別子)?;
        if self.識別子で探す(&新しい識別子).is_some() {
            return Err(
                クリップスタックの操作エラー::識別子が重複している(
                    新しい識別子,
                ),
            );
        }
        let 写し = self.一覧[位置].別の識別子で複製する(新しい識別子);
        self.選択中 = Some(写し.識別子().clone());
        self.一覧.insert(位置 + 1, 写し);
        Ok(())
    }
}
