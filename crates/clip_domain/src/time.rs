//! 時刻の型。動画上の時刻とタイムライン上の時刻を、基準を表す型引数で区別する。
//! 移植元では「ビデオシーク秒」と「仮想シーク秒」がどちらも number であり、取り違えても型が通っていた。

use std::marker::PhantomData;

use crate::duration::{
    時間の値エラー, 時間の長さ, 非負の有限な秒数か検査する
};

/// 動画上とは、元の動画ファイルの先頭を0秒とする時間軸のことである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub enum 動画上 {}

/// タイムライン上とは、クリップスタックを順に再生したときの先頭を0秒とする仮想の時間軸のことである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub enum タイムライン上 {}

/// 時刻とは、基準の時間軸の上の、0秒以上の有限の位置のことである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 時刻<基準> {
    秒: f64,
    基準: PhantomData<基準>,
}

/// 動画上の秒とは、元の動画ファイルの中の位置のことである。
pub type 動画上の秒 = 時刻<動画上>;

/// タイムライン上の秒とは、クリップスタックを順に再生する仮想の時間軸の中の位置のことである。
pub type タイムライン上の秒 = 時刻<タイムライン上>;

impl<基準> 時刻<基準> {
    /// 時間軸の先頭(0秒)。
    pub const 先頭: Self = Self::検査済みの秒数から作る(0.0);

    /// 秒数から作成する。有限でない値と負の値を拒む。
    pub fn 作成する(秒: f64) -> Result<Self, 時間の値エラー> {
        非負の有限な秒数か検査する(秒).map(Self::検査済みの秒数から作る)
    }

    const fn 検査済みの秒数から作る(秒: f64) -> Self {
        Self {
            秒,
            基準: PhantomData,
        }
    }

    /// 秒数を返す。表示や外部の仕組みへ渡す境界で使う。
    pub fn 秒数(self) -> f64 {
        self.秒
    }

    /// 時刻を指定の長さだけ後ろへ進める。
    pub fn 進める(self, 長さ: 時間の長さ) -> Self {
        Self::検査済みの秒数から作る(self.秒 + 長さ.秒数())
    }

    /// 時刻を指定の長さだけ前へ戻す。先頭より前には戻らない。
    pub fn 戻す(self, 長さ: 時間の長さ) -> Self {
        Self::検査済みの秒数から作る((self.秒 - 長さ.秒数()).max(0.0))
    }

    /// 起点からこの時刻までの長さを求める。この時刻が起点より前なら0秒とする。
    pub fn 起点から経過した長さ(self, 起点: Self) -> 時間の長さ {
        時間の長さ::検査済みの秒数から作る(self.秒 - 起点.秒)
    }
}
