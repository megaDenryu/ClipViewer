//! クリップの各項目。クリップを成す項目を隠さずに並べた組と、クリップとの両方向の変換と、識別子を変えた複製を持つ。
//! 保存の形式との変換はこの組を `..` を使わずに分解・組み立てるため、クリップに項目を足すと変換の側がコンパイルエラーになる。
//! 複製もこの組を通すため、クリップに項目を足しても写し漏れが起きない。
//! 参照: _doc/設計/ライブラリ.md 判断4

use super::{クリップ, クリップ名};
use crate::clip_id::クリップ識別子;
use crate::crop::クロップ範囲;
use crate::repeat::リピート設定;
use crate::trigger::トリガー;
use crate::video_span::動画上の区間;

/// クリップの各項目とは、クリップを成すすべての項目(識別子・名前・有効か・区間・リピート・クロップ・トリガー)を、隠さずに並べた組のことである。
/// 保存の形式との変換と、識別子を変えた複製が使う。項目を足し忘れた変換がコンパイルを通らないようにするための型である。
pub(crate) struct クリップの各項目 {
    pub(crate) 識別子: クリップ識別子,
    pub(crate) 名前: クリップ名,
    pub(crate) 有効か: bool,
    pub(crate) 区間: 動画上の区間,
    pub(crate) リピート: リピート設定,
    pub(crate) クロップ: クロップ範囲,
    pub(crate) トリガー: トリガー,
}

impl クリップ {
    /// 各項目からクリップを組み立てる。各項目の値はそれぞれの型が不変条件を持つため、組み立てで検査することは無い。
    pub(crate) fn 各項目から組み立てる(各項目: クリップの各項目) -> Self {
        let クリップの各項目 {
            識別子,
            名前,
            有効か,
            区間,
            リピート,
            クロップ,
            トリガー,
        } = 各項目;
        Self {
            識別子,
            名前,
            有効か,
            区間,
            リピート,
            クロップ,
            トリガー,
        }
    }

    /// すべての項目の写しを作る。
    pub(crate) fn 各項目の写しを作る(&self) -> クリップの各項目 {
        let Self {
            識別子,
            名前,
            有効か,
            区間,
            リピート,
            クロップ,
            トリガー,
        } = self;
        クリップの各項目 {
            識別子: 識別子.clone(),
            名前: 名前.clone(),
            有効か: *有効か,
            区間: *区間,
            リピート: *リピート,
            クロップ: *クロップ,
            トリガー: *トリガー,
        }
    }

    /// 識別子を新しい識別子に替え、名前に「 のコピー」を足した複製。ほかの項目はすべて写す。
    pub fn 別の識別子で複製する(
        &self, 新しい識別子: クリップ識別子
    ) -> Self {
        let mut 各項目 = self.各項目の写しを作る();
        各項目.識別子 = 新しい識別子;
        各項目.名前 = クリップ名::作成する(format!("{} のコピー", self.名前.文字列()));
        Self::各項目から組み立てる(各項目)
    }
}
