//! 再生位置と、実時間の経過から再生位置を進める時計の規則。
//! 移植元 `ClipViewerAppアニメーションサービス.ts` の「時間を進める」部分と、トリガー待ちの巻き戻しの移植である。
//! 待つクリップは、移植元のように占有時間ぶん戻さず、最後の周回を1区間長ずつ戻して繰り返す(オーナーの決定)。

use crate::duration::時間の長さ;
use crate::play_mode::再生モード;
use crate::playback_clock::{時計を進めた結果, 時計を進める条件};
use crate::stack::クリップスタック;
use crate::time::{タイムライン上の秒, 動画上の秒, 時刻};

/// 再生位置とは、再生モードごとに意味の違う現在の位置のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 再生位置 {
    /// シーケンス再生の、クリップを並べたタイムライン上の位置。
    シーケンス再生(タイムライン上の秒),
    /// 単独クリップ再生の、選択中のクリップの区間の開始からの経過。
    単独クリップ再生(時間の長さ),
    /// 元動画再生の、元の動画の中の位置。
    元動画再生(動画上の秒),
}

impl 再生位置 {
    /// 再生モードの先頭の位置。再生モードを切り替えたときは、この位置から再生する(移植元と同じ)。
    pub fn モードの先頭(モード: 再生モード) -> Self {
        match モード {
            再生モード::シーケンス再生 => Self::シーケンス再生(時刻::先頭),
            再生モード::単独クリップ再生 => {
                Self::単独クリップ再生(時間の長さ::ゼロ)
            }
            再生モード::元動画再生 => Self::元動画再生(時刻::先頭),
        }
    }

    /// この位置の再生モード。
    pub fn モード(&self) -> 再生モード {
        match self {
            Self::シーケンス再生(_) => 再生モード::シーケンス再生,
            Self::単独クリップ再生(_) => 再生モード::単独クリップ再生,
            Self::元動画再生(_) => 再生モード::元動画再生,
        }
    }

    /// 位置の秒数を返す。再生コントロールの表示へ渡す境界で使う。
    pub fn 位置の秒数(&self) -> f64 {
        match self {
            Self::シーケンス再生(位置) => 位置.秒数(),
            Self::単独クリップ再生(経過) => 経過.秒数(),
            Self::元動画再生(位置) => 位置.秒数(),
        }
    }

    /// 再生を始める位置。シーケンス再生と元動画再生で位置が合計の長さに達しているときは、モードの先頭を返す。
    /// 末尾のまま再生を始めると時計がすぐにまた止めるため、利用者が再生を押したときは先頭から再生し直す(オーナーの決定)。
    /// 単独クリップ再生は末尾で止まらないので、位置を変えない。
    pub fn 再生を始める位置(
        self,
        スタック: &クリップスタック,
        動画の長さ: 時間の長さ,
    ) -> Self {
        let 末尾に達しているか = match self {
            Self::シーケンス再生(位置) => {
                位置.末尾に達しているか(スタック.合計の占有時間())
            }
            Self::単独クリップ再生(_) => false,
            Self::元動画再生(位置) => 位置.末尾に達しているか(動画の長さ),
        };
        if 末尾に達しているか {
            Self::モードの先頭(self.モード())
        } else {
            self
        }
    }

    /// 実時間の経過と時計を進める条件から再生位置を進める。
    /// 単独クリップ再生は区間の長さで先頭へ戻り続け、止まらない。選択中のクリップが無ければ進まない。
    pub fn 実時間の経過で進める(
        self,
        実時間の経過: 時間の長さ,
        条件: &時計を進める条件<'_>,
    ) -> 時計を進めた結果 {
        let 増分 = 条件.速度.進む長さ(実時間の経過);
        match self {
            Self::シーケンス再生(位置) => {
                条件.シーケンスの位置を進める(位置, 増分)
            }
            Self::単独クリップ再生(経過) => 時計を進めた結果::続ける(
                Self::単独クリップ再生(条件.単独再生の経過を進める(経過, 増分)),
            ),
            Self::元動画再生(位置) => 位置.進める(増分).末尾を判定する(
                条件.動画の長さ,
                条件.全体の末尾,
                Self::元動画再生,
            ),
        }
    }
}
