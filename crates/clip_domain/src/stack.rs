//! クリップスタック。クリップの並びと、選択中のクリップを所有する。並びを変える操作(追加・更新・削除・並べ替え・複製)は
//! `stack/edit.rs` に置く。

mod edit;

use crate::clip::{クリップ, クリップ名};
use crate::clip_id::クリップ識別子;
use crate::stack_error::クリップスタックの操作エラー;

/// クリップスタックとは、再生順に並んだクリップの一覧と、編集の対象として選択中のクリップの組のことである。
/// 不変条件: 識別子は重複しない。一覧が空でなければ、選択中の識別子は一覧の中に必ずある。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct クリップスタック {
    一覧: Vec<クリップ>,
    選択中: Option<クリップ識別子>,
}

impl クリップスタック {
    /// クリップの一覧から作成し、先頭のクリップを選択する。識別子の重複を拒む。
    pub fn 一覧から作成する(
        一覧: Vec<クリップ>,
    ) -> Result<Self, クリップスタックの操作エラー> {
        let mut スタック = Self::default();
        for クリップ in 一覧 {
            スタック.末尾へ積む(クリップ)?;
        }
        スタック.選択中 = スタック.一覧.first().map(|先頭| 先頭.識別子().clone());
        Ok(スタック)
    }

    /// 再生順のクリップの一覧。
    pub fn 一覧(&self) -> &[クリップ] {
        &self.一覧
    }

    /// 識別子でクリップを探す。
    pub fn 識別子で探す(&self, 識別子: &クリップ識別子) -> Option<&クリップ> {
        self.一覧
            .iter()
            .find(|クリップ| クリップ.識別子() == 識別子)
    }

    /// 選択中のクリップ。スタックが空なら無い。
    pub fn 選択中のクリップ(&self) -> Option<&クリップ> {
        self.選択中
            .as_ref()
            .and_then(|識別子| self.識別子で探す(識別子))
    }

    /// 指定の識別子のクリップを選択する。
    pub fn 選択する(
        &mut self,
        識別子: &クリップ識別子,
    ) -> Result<(), クリップスタックの操作エラー> {
        let 位置 = self.番号を探す(識別子)?;
        self.選択中 = Some(self.一覧[位置].識別子().clone());
        Ok(())
    }

    /// 先頭のクリップを選んだスタック。空なら空のまま。
    pub fn 先頭を選ぶ(mut self) -> Self {
        self.選択中 = self.一覧.first().map(|先頭| 先頭.識別子().clone());
        self
    }

    /// 次に追加するクリップの既定の名前「Clip Mod <個数+1>」を求める(移植元と同じ文字列)。
    pub fn 次に追加するクリップの名前(&self) -> クリップ名 {
        クリップ名::作成する(format!("Clip Mod {}", self.一覧.len() + 1))
    }

    /// 識別子のクリップの並びの中の番号(0から数える)。無ければ見つからないとして拒む。
    pub fn 番号を探す(
        &self,
        識別子: &クリップ識別子,
    ) -> Result<usize, クリップスタックの操作エラー> {
        self.一覧
            .iter()
            .position(|クリップ| クリップ.識別子() == 識別子)
            .ok_or_else(|| {
                クリップスタックの操作エラー::見つからない(識別子.clone())
            })
    }
}
