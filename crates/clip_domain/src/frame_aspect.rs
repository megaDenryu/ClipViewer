//! 縦横比を保って、四隅のつまみで枠の大きさを変える計算。掴んだ隅の向かいの隅を動かさず、幅と高さの比を保ったまま、
//! 最小の大きさ以上で基準の0〜100%に収まる大きさにする。今のクロップ枠には無い規則であり、映す矩形だけが使う(同時再生.md 2-4)。
//! 最小の大きさと0〜100%に収める規則は、縦横比を保たない大きさの変更(`frame_drag.rs`)と同じ規則の枠へ最後に通す。

use crate::frame_drag::{
    四隅のつまみ, 枠の最小の大きさ, 枠の移動量, 百分率の枠
};
use crate::frame_resize::作業中の矩形;
use crate::pixel::縦横比;

impl<基準: Copy> 百分率の枠<基準> {
    /// ドラッグの開始時の枠を、つまみの角を移動量だけ動かして、幅÷高さが保つ比になる大きさへ変える。
    /// 動かした角が示す幅と高さのうち、保つ比で大きい方へ合わせる。保つ比のまま最小の大きさ以上で0〜100%に収まる大きさが無いときは、
    /// 縦横比を保たない大きさの変更にする(保つ比が極端なときだけであり、その比の枠を作れないため)。
    pub(crate) fn 縦横比を保ってつまみで大きさを変える(
        &self,
        つまみ: 四隅のつまみ,
        移動量: 枠の移動量<基準>,
        保つ比: 縦横比,
    ) -> Self {
        let 比 = 保つ比.値();
        let 始め = 作業中の矩形::枠から作る(self);
        let mut 動かした = 作業中の矩形::枠から作る(self);
        動かした.つまみの角を動かす(つまみ, 移動量.横.数値(), 移動量.縦.数値());
        let 向かいの横 = if つまみ.左側か() {
            始め.左端 + 始め.幅
        } else {
            始め.左端
        };
        let 向かいの縦 = if つまみ.上側か() {
            始め.上端 + 始め.高さ
        } else {
            始め.上端
        };
        let 横の空き = if つまみ.左側か() {
            向かいの横
        } else {
            100.0 - 向かいの横
        };
        let 縦の空き = if つまみ.上側か() {
            向かいの縦
        } else {
            100.0 - 向かいの縦
        };
        let 最大の幅 = 横の空き.min(縦の空き * 比);
        let 最小の幅 = 枠の最小の大きさ.max(枠の最小の大きさ * 比);
        if !(比.is_finite() && 比 > 0.0) || 最小の幅 > 最大の幅 {
            return self.つまみで大きさを変える(つまみ, 移動量);
        }
        let 幅 = 動かした
            .幅
            .max(動かした.高さ * 比)
            .clamp(最小の幅, 最大の幅);
        let 高さ = 幅 / 比;
        作業中の矩形 {
            左端: if つまみ.左側か() {
                向かいの横 - 幅
            } else {
                向かいの横
            },
            上端: if つまみ.上側か() {
                向かいの縦 - 高さ
            } else {
                向かいの縦
            },
            幅,
            高さ,
        }
        .枠へ収める()
    }
}
