//! 四隅のつまみによるクロップ枠の大きさの変更の計算。
//! 移植元 `ClipViewerAppクロップギズモハンドラ.ts` の `リサイズを適用する` の移植であり、工程の順序と各工程の式は移植元と同じである。

use crate::crop::クロップ範囲;
use crate::crop_drag::四隅のつまみ;
use crate::percent::百分率;

/// 大きさの変更の途中の、範囲へ収める前の矩形。計算の工程を段階ごとに分けるために置く。
pub(crate) struct 作業中の矩形 {
    左端: f64,
    上端: f64,
    幅: f64,
    高さ: f64,
}

impl 作業中の矩形 {
    pub(crate) fn クロップ範囲から作る(範囲: &クロップ範囲) -> Self {
        Self {
            左端: 範囲.左端().数値(),
            上端: 範囲.上端().数値(),
            幅: 範囲.幅().数値(),
            高さ: 範囲.高さ().数値(),
        }
    }

    pub(crate) fn つまみの角を動かす(
        &mut self, つまみ: 四隅のつまみ, 横: f64, 縦: f64
    ) {
        if つまみ.左側か() {
            self.左端 += 横;
            self.幅 -= 横;
        } else {
            self.幅 += 横;
        }
        if つまみ.上側か() {
            self.上端 += 縦;
            self.高さ -= 縦;
        } else {
            self.高さ += 縦;
        }
    }

    pub(crate) fn 最小の大きさを保つ(&mut self, つまみ: 四隅のつまみ) {
        let 最小 = クロップ範囲::最小の大きさ;
        if self.幅 < 最小 {
            if つまみ.左側か() {
                self.左端 -= 最小 - self.幅;
            }
            self.幅 = 最小;
        }
        if self.高さ < 最小 {
            if つまみ.上側か() {
                self.上端 -= 最小 - self.高さ;
            }
            self.高さ = 最小;
        }
    }

    pub(crate) fn はみ出しを削る(&mut self) {
        if self.左端 < 0.0 {
            self.幅 += self.左端;
            self.左端 = 0.0;
        }
        if self.上端 < 0.0 {
            self.高さ += self.上端;
            self.上端 = 0.0;
        }
        self.幅 = self.幅.min(100.0 - self.左端);
        self.高さ = self.高さ.min(100.0 - self.上端);
    }

    pub(crate) fn クロップ範囲へ収める(&self) -> クロップ範囲 {
        let 最小 = クロップ範囲::最小の大きさ;
        let 左端 = 百分率::下限と上限の間へ収める(self.左端, 0.0, 100.0 - 最小);
        let 上端 = 百分率::下限と上限の間へ収める(self.上端, 0.0, 100.0 - 最小);
        let 幅 = 百分率::下限と上限の間へ収める(self.幅, 最小, 100.0 - 左端.数値());
        let 高さ =
            百分率::下限と上限の間へ収める(self.高さ, 最小, 100.0 - 上端.数値());
        クロップ範囲::検査済みの値から作る(左端, 上端, 幅, 高さ)
    }
}
