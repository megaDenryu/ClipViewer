//! 第1版の繰り返しとトリガーの表記と、最新の値の、読み込みと書き出しの両方向の変換。対応を1箇所に置き、食い違いを防ぐ。

use super::error::ライブラリのクリップの不備;
use super::v1::{無限ループの表記, 第1版のトリガー, 第1版の繰り返し};
use crate::repeat::{リピート回数, リピート設定};
use crate::trigger::トリガー;

impl 第1版の繰り返し {
    pub(super) fn 最新へ変換する(
        self,
    ) -> Result<リピート設定, ライブラリのクリップの不備> {
        match self {
            Self::回数(回数) => Ok(リピート設定::回数指定(リピート回数::作成する(
                回数,
            )?)),
            Self::文字列(表記) if 表記 == 無限ループの表記 => {
                Ok(リピート設定::無限ループ)
            }
            Self::文字列(表記) => Err(ライブラリのクリップの不備::繰り返しの表記(表記)),
        }
    }

    pub(super) fn 最新から作る(リピート: リピート設定) -> Self {
        match リピート {
            リピート設定::回数指定(回数) => Self::回数(u32::from(回数.回数())),
            リピート設定::無限ループ => Self::文字列(無限ループの表記.to_string()),
        }
    }
}

impl 第1版のトリガー {
    pub(super) fn 最新へ変換する(self) -> トリガー {
        match self {
            Self::自動進行 => トリガー::自動進行,
            Self::Enterキー待ち => トリガー::Enterキー待ち,
            Self::Spaceキー待ち => トリガー::Spaceキー待ち,
            Self::クリック待ち => トリガー::クリック待ち,
        }
    }

    pub(super) fn 最新から作る(トリガー: トリガー) -> Self {
        match トリガー {
            トリガー::自動進行 => Self::自動進行,
            トリガー::Enterキー待ち => Self::Enterキー待ち,
            トリガー::Spaceキー待ち => Self::Spaceキー待ち,
            トリガー::クリック待ち => Self::クリック待ち,
        }
    }
}
