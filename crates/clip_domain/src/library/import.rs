//! ブラウザ版の設定ファイル(v4.0 形式)から読んだスタック設定を、ライブラリのスタックとして取り込む。

use super::date::ライブラリの日時;
use super::error::ライブラリへ取り込めない理由;
use super::item::ライブラリのスタック;
use super::name::スタックの名前;
use super::stack_id::スタックの識別子;
use crate::settings::スタック設定;

impl スタック設定 {
    /// 期待する動画のパスを動画のパスにして、新しいライブラリのスタックにする。
    /// 動画のパスが無い設定は、どの動画のスタックか分からないため取り込まない。
    pub fn ライブラリへ取り込む(
        self,
        識別子: スタックの識別子,
        名前: スタックの名前,
        今: ライブラリの日時,
    ) -> Result<ライブラリのスタック, ライブラリへ取り込めない理由> {
        let 動画のパス = self
            .期待する動画のパス
            .ok_or(ライブラリへ取り込めない理由::動画のパスが無い)?;
        Ok(ライブラリのスタック::新しく作る(
            識別子,
            名前,
            動画のパス,
            self.スタック,
            今,
        ))
    }
}
