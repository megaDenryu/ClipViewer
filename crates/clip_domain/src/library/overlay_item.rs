//! ライブラリの重ね合わせ。ライブラリに登録した重ね合わせ1つの中身であり、`overlays` フォルダのファイル1つに書く単位である。

use super::date::ライブラリの日時;
use super::overlay_id::重ね合わせの識別子;
use super::overlay_name::重ね合わせの名前;
use crate::overlay::重ね合わせ;

/// ライブラリの重ね合わせとは、ライブラリに名前を付けて登録した重ね合わせと、作った日時と更新した日時の組のことである。
/// 動画そのものは持たず、使う動画の表のパスとどこを切り抜いてどこへ映すかだけを持つ。
#[derive(Debug, Clone, PartialEq)]
pub struct ライブラリの重ね合わせ {
    pub(super) 識別子: 重ね合わせの識別子,
    pub(super) 名前: 重ね合わせの名前,
    pub(super) 重ね合わせ: 重ね合わせ,
    pub(super) 作った日時: ライブラリの日時,
    pub(super) 更新した日時: ライブラリの日時,
}

impl ライブラリの重ね合わせ {
    /// 新しく登録する重ね合わせを作る。作った日時と更新した日時は、どちらも渡された日時にする。
    pub fn 新しく作る(
        識別子: 重ね合わせの識別子,
        名前: 重ね合わせの名前,
        重ね合わせ: 重ね合わせ,
        今: ライブラリの日時,
    ) -> Self {
        Self::各項目から組み立てる(識別子, 名前, 重ね合わせ, 今, 今)
    }

    /// ファイルから読んだ各項目から組み立てる。
    pub(super) fn 各項目から組み立てる(
        識別子: 重ね合わせの識別子,
        名前: 重ね合わせの名前,
        重ね合わせ: 重ね合わせ,
        作った日時: ライブラリの日時,
        更新した日時: ライブラリの日時,
    ) -> Self {
        Self {
            識別子,
            名前,
            重ね合わせ,
            作った日時,
            更新した日時,
        }
    }

    /// 重ね合わせを差し替え、更新した日時を渡された日時にしたもの。作った日時は保つ。
    pub fn 重ね合わせを差し替えた(
        self,
        重ね合わせ: 重ね合わせ,
        今: ライブラリの日時,
    ) -> Self {
        Self {
            重ね合わせ,
            更新した日時: 今,
            ..self
        }
    }

    /// 識別子。
    pub fn 識別子(&self) -> &重ね合わせの識別子 {
        &self.識別子
    }

    /// 名前。
    pub fn 名前(&self) -> &重ね合わせの名前 {
        &self.名前
    }

    /// 重ね合わせ。
    pub fn 重ね合わせ(&self) -> &重ね合わせ {
        &self.重ね合わせ
    }

    /// 作った日時。
    pub fn 作った日時(&self) -> ライブラリの日時 {
        self.作った日時
    }

    /// 最後に更新した日時。
    pub fn 更新した日時(&self) -> ライブラリの日時 {
        self.更新した日時
    }
}
