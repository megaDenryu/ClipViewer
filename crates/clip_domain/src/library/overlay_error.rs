//! 重ね合わせのファイルの読み込みで起きるエラー。公開の型に serde_json の型を出さず、JSONの不備は位置と理由を自前の型で持つ。
//! 書き出しのエラーはスタックと同じ `ライブラリのファイルの書き出しエラー` を使う。

use super::date::ライブラリの日時エラー;
use super::overlay_id::重ね合わせの識別子の不備;
use super::overlay_name::空の重ね合わせの名前エラー;
use crate::duration::時間の値エラー;
use crate::overlay::{
    映す矩形エラー, 空の置いたクリップの識別子エラー, 重ねる画面の縦横比エラー,
    重ね合わせを組み立てられない理由,
};
use crate::repeat::リピート回数エラー;
use crate::settings::{JSONの不備, JSONの誤りの種類};
use crate::video_span::区間エラー;

/// 重ね合わせのファイルの読み込みエラーとは、重ね合わせのファイルの本文からライブラリの重ね合わせを作れなかった理由のことである。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 重ね合わせのファイルの読み込みエラー {
    /// 本文がJSONとして解析できない。
    #[error("JSONとして読めない: {0}")]
    JSONとして解析できない(JSONの不備),
    /// format が重ね合わせのファイルの形式の名前でない。
    #[error("重ね合わせのファイルでない(format が {0:?})")]
    形式の名前が違う(Option<String>),
    /// version がこのアプリの知っている最新の版より大きい。このアプリより新しい ClipViewer が書いたファイルである。
    #[error(
        "このアプリより新しい ClipViewer で保存された(version が {0})。ClipViewer を更新すれば開ける"
    )]
    版が新しすぎる(u64),
    /// version が無いか、どの版の番号でもない(0 等)。
    #[error("このアプリが読めない版である(version が {0:?})")]
    対応していない版(Option<u64>),
    /// 項目の型や表記が、その版の形式に合わない。
    #[error("形式が不正: {0}")]
    形式が不正(JSONの不備),
    /// 作った日時か更新した日時が、ライブラリの日時として表せない。
    #[error("{0}")]
    日時が不正(#[from] ライブラリの日時エラー),
    /// 重ね合わせの識別子が成立しない。
    #[error("{0}")]
    識別子が不正(#[from] 重ね合わせの識別子の不備),
    /// 重ね合わせの名前が空である。
    #[error("{0}")]
    名前が空(#[from] 空の重ね合わせの名前エラー),
    /// 縦横比が「クロップ枠に合わせる」(crop)である。
    #[error("{0}")]
    縦横比が不正(#[from] 重ねる画面の縦横比エラー),
    /// 指定の行(0から数える)の、指定の位置(0から数える)の置いたクリップの値が成立しない。
    #[error("{行}番目の行の{位置}番目の置いたクリップが不正(0から数える): {理由}")]
    置いたクリップが不正 {
        /// 0から数えた行の番号。
        行: usize,
        /// 0から数えた行の中の位置。
        位置: usize,
        /// 成立しない理由。
        理由: 置いたクリップの値の不備,
    },
    /// 値はそれぞれ成立するが、重ね合わせの不変条件(行の数の上限・時間の重なり・識別子の重なり・動画の番号)を満たさない。
    #[error("重ね合わせが不正: {0}")]
    組み立てられない(#[from] 重ね合わせを組み立てられない理由),
}

impl 重ね合わせのファイルの読み込みエラー {
    /// serde_json の解析のエラーを、構文の誤りなら「解析できない」、型や表記の誤りなら「形式が不正」へ分けて変換する。
    pub(crate) fn 解析のエラーから作る(エラー: serde_json::Error) -> Self {
        match JSONの誤りの種類::解析のエラーから作る(&エラー) {
            JSONの誤りの種類::形(不備) => Self::形式が不正(不備),
            JSONの誤りの種類::構文(不備) => Self::JSONとして解析できない(不備),
        }
    }
}

/// 置いたクリップの値の不備とは、重ね合わせのファイルの置いたクリップの値がドメインの型として成立しない理由のことである。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 置いたクリップの値の不備 {
    /// 置いたクリップの識別子が空である。
    #[error("{0}")]
    識別子(#[from] 空の置いたクリップの識別子エラー),
    /// start・end・at のどれかが時刻として成立しない。
    #[error("時刻が不正: {0}")]
    時刻(#[from] 時間の値エラー),
    /// start が end より後ろにある。
    #[error("{0}")]
    区間(#[from] 区間エラー),
    /// repeat の回数が範囲(1〜100)の外にある。
    #[error("{0}")]
    繰り返しの回数(#[from] リピート回数エラー),
    /// rect が重ねる画面の外へ出るか、小さすぎる。
    #[error("{0}")]
    映す矩形(#[from] 映す矩形エラー),
}
