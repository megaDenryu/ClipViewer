//! 最新のライブラリのスタックから第1版のライブラリのファイルへの変換。書き出しは常に最新の版(第1版)で行う。
//! ライブラリのスタックを `..` を使わずに分解するため、スタックに項目を足すとここがコンパイルエラーになる。

use super::item::ライブラリのスタック;
use super::v1::{
    形式の名前, 第1版のクリップ, 第1版のファイル, 第1版の番号
};

impl 第1版のファイル {
    pub(crate) fn 最新から作る(スタック: &ライブラリのスタック) -> Self {
        let ライブラリのスタック {
            識別子,
            名前,
            動画のパス,
            並び,
            作った日時,
            更新した日時,
        } = スタック;
        Self {
            format: 形式の名前.to_string(),
            version: 第1版の番号,
            identifier: 識別子.文字列().to_string(),
            name: 名前.文字列().to_string(),
            video_path: 動画のパス.文字列().to_string(),
            created_at_ms: 作った日時.紀元からのミリ秒(),
            updated_at_ms: 更新した日時.紀元からのミリ秒(),
            clips: 並び
                .一覧()
                .iter()
                .map(第1版のクリップ::最新から作る)
                .collect(),
        }
    }
}
