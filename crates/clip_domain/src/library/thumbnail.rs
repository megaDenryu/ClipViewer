//! サムネイルの撮り方とサムネイルの画像。一覧に出すスタックの顔を、どの動画のどのコマからどう切り抜いて撮るかと、撮った画像のバイト列。
//! 撮るのは FFmpeg を知る層であり、ここは撮るものを決める規則と、層の間で受け渡す値だけを持つ。
//! 参照: _doc/設計/ライブラリ.md 判断10

use std::fmt;

use super::item::ライブラリのスタック;
use super::thumbnail_size::サムネイルの大きさ;
use crate::crop::クロップ範囲;
use crate::time::動画上の秒;
use crate::video_path::正規化した動画パス;

/// サムネイルの撮り方とは、スタックの顔として撮る1コマの、動画のパスと動画上の時刻と切り抜くクロップ範囲と、収める大きさの組のことである。
/// スタックの顔とは、最初の再生できるクリップの開始のコマに、そのクリップのクロップを掛けたもののことである。
/// 2つの撮り方が等しければ同じ画像になるため、サムネイルのキャッシュは撮り方からファイル名を決める。
#[derive(Debug, Clone, PartialEq)]
pub struct サムネイルの撮り方 {
    動画のパス: 正規化した動画パス,
    時刻: 動画上の秒,
    クロップ: クロップ範囲,
    大きさ: サムネイルの大きさ,
}

impl サムネイルの撮り方 {
    /// 動画のパスと動画上の時刻とクロップ範囲と収める大きさから作成する。動画のパスが空なら撮るものが無いため作らない。
    pub fn 作成する(
        動画のパス: 正規化した動画パス,
        時刻: 動画上の秒,
        クロップ: クロップ範囲,
        大きさ: サムネイルの大きさ,
    ) -> Option<Self> {
        (!動画のパス.空か()).then_some(Self {
            動画のパス,
            時刻,
            クロップ,
            大きさ,
        })
    }

    /// 撮る動画のパス。
    pub fn 動画のパス(&self) -> &正規化した動画パス {
        &self.動画のパス
    }

    /// 撮るコマの動画上の時刻。
    pub fn 時刻(&self) -> 動画上の秒 {
        self.時刻
    }

    /// 撮ったコマから切り抜く範囲。
    pub fn クロップ(&self) -> クロップ範囲 {
        self.クロップ
    }

    /// 切り抜いた顔を縦横比を保って収める大きさ。
    pub fn 大きさ(&self) -> サムネイルの大きさ {
        self.大きさ
    }
}

impl ライブラリのスタック {
    /// このスタックの顔を大きさへ収める撮り方。再生できるクリップが無いか、動画のパスが空なら撮らないため無い。
    pub fn サムネイルの撮り方(
        &self,
        大きさ: サムネイルの大きさ,
    ) -> Option<サムネイルの撮り方> {
        let 顔のクリップ = self
            .並び()
            .一覧()
            .iter()
            .find(|クリップ| クリップ.再生できるか())?;
        サムネイルの撮り方::作成する(
            self.動画のパス().clone(),
            顔のクリップ.区間.開始(),
            顔のクリップ.クロップ,
            大きさ,
        )
    }
}

/// サムネイルの画像とは、スタックの顔を撮って JPEG の形式で書いたバイト列のことである。サムネイルのキャッシュに置く。
#[derive(Clone, PartialEq, Eq)]
pub struct サムネイルの画像(Vec<u8>);

impl サムネイルの画像 {
    /// JPEG のバイト列から作る。形式は検査しない(読む側が画素へ戻すときに確かめる)。
    pub fn 作成する(バイト列: Vec<u8>) -> Self {
        Self(バイト列)
    }

    /// JPEG のバイト列。ファイルへ書く境界と画素へ戻す境界で使う。
    pub fn バイト列(&self) -> &[u8] {
        &self.0
    }
}

impl fmt::Debug for サムネイルの画像 {
    /// バイト列の中身は出さず、長さだけを出す(数KBのバイト列を試験の失敗の表示に並べないため)。
    fn fmt(&self, 書き込み先: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(書き込み先, "サムネイルの画像({}バイト)", self.0.len())
    }
}
