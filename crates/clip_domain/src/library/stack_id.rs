//! スタックの識別子。ライブラリの中でスタックを一意に指し、ライブラリはファイル名にも使う。

use std::fmt;

use crate::clip_id::{発行時刻, 識別子の乱数};

/// 識別子に許す最も長い文字数。ファイル名の長さの上限(255)より十分短くする。
const 最も長い文字数: usize = 100;

/// スタックの識別子とは、ライブラリの中でスタックを一意に指す、英小文字・数字・ハイフンだけからなる空でない文字列のことである。
/// ライブラリはこれをファイル名に使うため、ファイル名に使えない文字を含まないことを作る口で保証する。
/// 新しく発行するときの形式は「stack-<ミリ秒>-<0〜9999の乱数>」である。
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct スタックの識別子(String);

/// スタックの識別子の不備とは、文字列が空か、100文字より長いか、英小文字・数字・ハイフン以外の文字を含むことである。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error(
    "スタックの識別子は英小文字・数字・ハイフンだけからなる1〜100文字でなければならない: {0:?}"
)]
pub struct スタックの識別子の不備(pub String);

impl スタックの識別子 {
    /// ファイル等にある既存の識別子の文字列から作成する。
    pub fn 文字列から作成する(
        文字列: String,
    ) -> Result<Self, スタックの識別子の不備> {
        if ファイル名に使える識別子か(&文字列) {
            Ok(Self(文字列))
        } else {
            Err(スタックの識別子の不備(文字列))
        }
    }

    /// 発行時刻と乱数から「stack-<ミリ秒>-<乱数>」の識別子を組み立てる。
    pub fn 時刻と乱数から組み立てる(
        時刻: 発行時刻, 乱数: 識別子の乱数
    ) -> Self {
        Self(format!("stack-{}-{}", 時刻.0, 乱数.0))
    }

    /// 識別子の文字列を返す。ファイル名やファイルの本文へ渡す境界で使う。
    pub fn 文字列(&self) -> &str {
        &self.0
    }
}

/// 文字列が、英小文字・数字・ハイフンだけからなる1〜100文字であり、ライブラリがファイル名に使える識別子の形か。
/// スタックの識別子と重ね合わせの識別子が同じ規則で確かめる。
pub(super) fn ファイル名に使える識別子か(文字列: &str) -> bool {
    let 使える文字だけか = 文字列
        .chars()
        .all(|文字| 文字.is_ascii_lowercase() || 文字.is_ascii_digit() || 文字 == '-');
    使える文字だけか && !文字列.is_empty() && 文字列.len() <= 最も長い文字数
}

impl fmt::Display for スタックの識別子 {
    fn fmt(&self, 書き込み先: &mut fmt::Formatter<'_>) -> fmt::Result {
        書き込み先.write_str(&self.0)
    }
}
