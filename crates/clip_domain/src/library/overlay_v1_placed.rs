//! 重ね合わせのファイル第1版の置いたクリップと、最新の置いたクリップの部品一式の、読み込みと書き出しの両方向の変換。
//! どちらの向きも `..` を使わずに組み立て・分解するため、置いたクリップに項目を足すとここがコンパイルエラーになる。

use super::overlay_error::置いたクリップの値の不備;
use super::overlay_v1::{
    重ね合わせの第1版の矩形, 重ね合わせの第1版の置いたクリップ
};
use crate::clip::クリップ名;
use crate::overlay::{
    クリップから受け継いだ値, 動画の番号, 置いたクリップの識別子, 置いたクリップの部品一式,
    置いたクリップの音の設定, 重ね合わせ上の秒,
};
use crate::repeat::リピート回数;
use crate::time::時刻;
use crate::video_span::動画上の区間;
use crate::volume::音量;

impl 重ね合わせの第1版の置いたクリップ {
    /// 最新の置いたクリップの部品一式へ変換する。音量は0〜1へ収める(このアプリが書いた値は範囲の中にあるため、収めても変わらない)。
    /// 動画の番号が表にあるかと、行の中の重なりは、重ね合わせを組み立てるときに確かめる。
    pub(super) fn 最新へ変換する(
        self,
    ) -> Result<置いたクリップの部品一式, 置いたクリップの値の不備> {
        let Self {
            id,
            name,
            video,
            start,
            end,
            repeat,
            crop,
            at,
            rect,
            volume,
            muted,
        } = self;
        Ok(置いたクリップの部品一式 {
            識別子: 置いたクリップの識別子::文字列から作成する(id)?,
            受け継いだ値: クリップから受け継いだ値 {
                名前: クリップ名::作成する(name),
                区間: 動画上の区間::作成する(
                    時刻::作成する(start)?,
                    時刻::作成する(end)?,
                )?,
                リピート回数: リピート回数::作成する(repeat)?,
                クロップ: crop.クロップ範囲にする(),
            },
            動画: 動画の番号::番号から作成する(video),
            始まりの時刻: 重ね合わせ上の秒::作成する(at)?,
            映す矩形: rect.映す矩形にする()?,
            音の設定: 置いたクリップの音の設定 {
                音量: 音量::範囲へ収めて作る(volume),
                消音しているか: muted,
            },
        })
    }

    /// 最新の置いたクリップの部品一式から作る。
    pub(super) fn 最新から作る(部品一式: 置いたクリップの部品一式) -> Self {
        let 置いたクリップの部品一式 {
            識別子,
            受け継いだ値,
            動画,
            始まりの時刻,
            映す矩形,
            音の設定,
        } = 部品一式;
        let クリップから受け継いだ値 {
            名前,
            区間,
            リピート回数,
            クロップ,
        } = 受け継いだ値;
        let 置いたクリップの音の設定 {
            音量,
            消音しているか,
        } = 音の設定;
        Self {
            id: 識別子.文字列().to_string(),
            name: 名前.文字列().to_string(),
            video: 動画.番号(),
            start: 区間.開始().秒数(),
            end: 区間.終了().秒数(),
            repeat: u32::from(リピート回数.回数()),
            crop: 重ね合わせの第1版の矩形::クロップ範囲から作る(クロップ),
            at: 始まりの時刻.秒数(),
            rect: 重ね合わせの第1版の矩形::映す矩形から作る(映す矩形),
            volume: 音量.値(),
            muted: 消音しているか,
        }
    }
}
