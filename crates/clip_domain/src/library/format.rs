//! ライブラリのスタックとライブラリのファイルの本文の変換。読み込みは版を判別してから、版に合う型で読んで最新へ変換する。
//! 版を足すときは、版に合う型で読む選択肢をここへ足す。参照: _doc/設計/ライブラリ.md「形式の版を上げる手順」

use super::error::{
    ライブラリのファイルの書き出しエラー, ライブラリのファイルの読み込みエラー
};
use super::file_text::ライブラリのファイルの本文;
use super::item::ライブラリのスタック;
use super::v1::{形式の名前, 版の見出し, 第1版のファイル, 第1版の番号};

/// このアプリが知っている最新の版の番号。これより大きい版は、このアプリより新しい ClipViewer が書いたファイルである。
const 最新の版の番号: u64 = 第1版の番号;

impl ライブラリのスタック {
    /// ライブラリのファイルの本文から読み込む。形式の名前が違うか、読めない版なら拒む。
    pub fn 本文から読み込む(
        本文: &ライブラリのファイルの本文,
    ) -> Result<Self, ライブラリのファイルの読み込みエラー> {
        let 見出し: 版の見出し = serde_json::from_str(本文.文字列()).map_err(
            ライブラリのファイルの読み込みエラー::解析のエラーから作る,
        )?;
        if 見出し.format.as_deref() != Some(形式の名前) {
            return Err(
                ライブラリのファイルの読み込みエラー::形式の名前が違う(
                    見出し.format,
                ),
            );
        }
        match 見出し.version {
            Some(第1版の番号) => serde_json::from_str::<第1版のファイル>(本文.文字列())
                .map_err(ライブラリのファイルの読み込みエラー::解析のエラーから作る)?
                .最新へ変換する(),
            Some(版) if 版 > 最新の版の番号 => {
                Err(ライブラリのファイルの読み込みエラー::版が新しすぎる(版))
            }
            その他 => Err(ライブラリのファイルの読み込みエラー::対応していない版(その他)),
        }
    }

    /// 最新の版の形で、空白を入れないJSONの本文へ書き出す。
    pub fn 本文へ書き出す(
        &self,
    ) -> Result<ライブラリのファイルの本文, ライブラリのファイルの書き出しエラー> {
        serde_json::to_string(&第1版のファイル::最新から作る(self))
            .map(ライブラリのファイルの本文::作成する)
            .map_err(|原因| ライブラリのファイルの書き出しエラー {
                理由: 原因.to_string(),
            })
    }
}
