//! 最新のライブラリの重ね合わせから重ね合わせのファイル第1版への変換。書き出しは常に最新の版(第1版)で行う。
//! ライブラリの重ね合わせと重ね合わせの各項目を `..` を使わずに分解するため、項目を足すとここがコンパイルエラーになる。

use super::overlay_item::ライブラリの重ね合わせ;
use super::overlay_v1::{
    重ね合わせの形式の名前, 重ね合わせの第1版のファイル, 重ね合わせの第1版の番号,
    重ね合わせの第1版の縦横比, 重ね合わせの第1版の置いたクリップ, 重ね合わせの第1版の行,
};
use crate::overlay::{タイムラインの行の各項目, 重ね合わせの各項目};

impl 重ね合わせの第1版のファイル {
    pub(crate) fn 最新から作る(登録した: &ライブラリの重ね合わせ) -> Self {
        let ライブラリの重ね合わせ {
            識別子,
            名前,
            重ね合わせ,
            作った日時,
            更新した日時,
        } = 登録した;
        let 重ね合わせの各項目 {
            縦横比,
            動画の表,
            行の並び,
        } = 重ね合わせ.各項目の写しを作る();
        Self {
            format: 重ね合わせの形式の名前.to_string(),
            version: 重ね合わせの第1版の番号,
            identifier: 識別子.文字列().to_string(),
            name: 名前.文字列().to_string(),
            created_at_ms: 作った日時.紀元からのミリ秒(),
            updated_at_ms: 更新した日時.紀元からのミリ秒(),
            aspect: 重ね合わせの第1版の縦横比::最新から作る(縦横比),
            videos: 動画の表
                .動画のパスの並び()
                .iter()
                .map(|パス| パス.文字列().to_string())
                .collect(),
            rows: 行の並び.into_iter().map(行を作る).collect(),
        }
    }
}

fn 行を作る(行: タイムラインの行の各項目) -> 重ね合わせの第1版の行 {
    let タイムラインの行の各項目 {
        置いたクリップの並び,
    } = 行;
    重ね合わせの第1版の行 {
        items: 置いたクリップの並び
            .into_iter()
            .map(重ね合わせの第1版の置いたクリップ::最新から作る)
            .collect(),
    }
}
