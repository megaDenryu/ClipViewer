//! 重ね合わせの顔とサムネイルの撮り方。重ね合わせの一覧に出すサムネイルを、どの置いたクリップのどのコマから撮るかを決める。
//! 参照: _doc/設計/同時再生.md 2-7、_doc/設計/ライブラリ.md 判断11

use super::overlay_item::ライブラリの重ね合わせ;
use super::thumbnail::サムネイルの撮り方;
use super::thumbnail_size::サムネイルの大きさ;
use crate::overlay::{置いたクリップ, 重ね合わせ};

impl 重ね合わせ {
    /// 顔の置いたクリップ。重ね合わせの顔とは、最も早く始まる置いたクリップ(同じ時刻なら奥の行のもの)の開始のコマに、そのクロップを掛けたもののことである。
    /// 置いたクリップが無ければ無い。行の中は始まりの時刻の順に並ぶため、各行の最初の置いたクリップだけを比べる。
    pub fn 顔の置いたクリップ(&self) -> Option<&置いたクリップ> {
        self.行の並び()
            .奥から手前の順の行()
            .iter()
            .filter_map(|行| 行.置いたクリップの並び().first())
            .reduce(|早い, 次| {
                if 次.始まりの時刻() < 早い.始まりの時刻() {
                    次
                } else {
                    早い
                }
            })
    }
}

impl ライブラリの重ね合わせ {
    /// この重ね合わせの顔を大きさへ収める撮り方。置いたクリップが無いか、顔の動画のパスが空なら撮らないため無い。
    pub fn サムネイルの撮り方(
        &self,
        大きさ: サムネイルの大きさ,
    ) -> Option<サムネイルの撮り方> {
        let 顔 = self.重ね合わせ().顔の置いたクリップ()?;
        let 動画のパス = self.重ね合わせ().動画の表().動画のパス(顔.動画の番号())?;
        サムネイルの撮り方::作成する(
            動画のパス.clone(),
            顔.受け継いだ値().区間.開始(),
            顔.受け継いだ値().クロップ,
            大きさ,
        )
    }
}
