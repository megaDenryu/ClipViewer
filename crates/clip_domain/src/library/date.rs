//! ライブラリの日時。ライブラリのスタックを作った日時と更新した日時に使う。

use std::time::{Duration, SystemTime};

/// 表せる最も遅い日時(協定世界時の9999年12月31日23時59分59.999秒)の、1970年1月1日からのミリ秒。
/// どの環境の `SystemTime` と chrono の日時も、ここまでは加算で溢れずに表せる。
const 最も遅い日時のミリ秒: u64 = 253_402_300_799_999;

/// ライブラリの日時とは、ライブラリのスタックを作った日時や更新した日時を、1970年1月1日(協定世界時)からのミリ秒で表したもののことである。
/// 時間帯を持たない。表示するときの時間帯への変換は画面が行う。
/// 注意: 値は常に 9999年12月31日(協定世界時)以前である。`時刻にする` はこの不変条件に頼って溢れない。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ライブラリの日時(u64);

/// ライブラリの日時エラーとは、時刻が1970年1月1日(協定世界時)より前か、9999年12月31日(協定世界時)より後であることである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("ライブラリの日時にできない時刻である(1970年より前か、9999年より後)")]
pub struct ライブラリの日時エラー;

impl ライブラリの日時 {
    /// 1970年1月1日0時(協定世界時)。時計が壊れていて今の日時を作れないときの代わりに使う。
    pub const 紀元: Self = Self(0);

    /// 時刻から作成する。時刻の取得は呼び出し側が行う(ドメインが時計を直接読まないため)。
    pub fn 時刻から作成する(
        時刻: SystemTime,
    ) -> Result<Self, ライブラリの日時エラー> {
        let 経過 = 時刻
            .duration_since(SystemTime::UNIX_EPOCH)
            .map_err(|_| ライブラリの日時エラー)?;
        u64::try_from(経過.as_millis())
            .map_err(|_| ライブラリの日時エラー)
            .and_then(Self::紀元からのミリ秒で作成する)
    }

    /// 1970年1月1日(協定世界時)からのミリ秒から作成する。9999年より後の値は拒む(ファイルから読んだ値が大きすぎても溢れないため)。
    pub fn 紀元からのミリ秒で作成する(
        ミリ秒: u64,
    ) -> Result<Self, ライブラリの日時エラー> {
        if ミリ秒 > 最も遅い日時のミリ秒 {
            return Err(ライブラリの日時エラー);
        }
        Ok(Self(ミリ秒))
    }

    /// 1970年1月1日(協定世界時)からのミリ秒。ファイルの本文や表示の変換へ渡す境界で使う。
    pub fn 紀元からのミリ秒(self) -> u64 {
        self.0
    }

    /// 時刻へ戻す。表示の変換へ渡す境界で使う。値が9999年以前であるため溢れない。
    pub fn 時刻にする(self) -> SystemTime {
        SystemTime::UNIX_EPOCH + Duration::from_millis(self.0)
    }
}
