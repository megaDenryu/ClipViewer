//! 重ね合わせのファイル第1版の縦横比と矩形の表記と、最新の値の、読み込みと書き出しの両方向の変換。対応を1箇所に置き、食い違いを防ぐ。

use super::overlay_v1::{
    重ね合わせの第1版の矩形, 重ね合わせの第1版の縦横比
};
use crate::aspect::アスペクト比設定;
use crate::crop::クロップ範囲;
use crate::overlay::{
    映す矩形, 映す矩形エラー, 重ねる画面の縦横比, 重ねる画面の縦横比エラー
};
use crate::percent::百分率;

impl 重ね合わせの第1版の縦横比 {
    /// 重ねる画面の縦横比へ変換する。crop(クロップ枠に合わせる)は拒む。
    pub(super) fn 最新へ変換する(
        self,
    ) -> Result<重ねる画面の縦横比, 重ねる画面の縦横比エラー> {
        重ねる画面の縦横比::作成する(match self {
            Self::ワイド16対9 => アスペクト比設定::ワイド16対9,
            Self::スタンダード4対3 => アスペクト比設定::スタンダード4対3,
            Self::正方形 => アスペクト比設定::正方形,
            Self::縦型9対16 => アスペクト比設定::縦型9対16,
            Self::クロップ枠に合わせる => アスペクト比設定::クロップ連動,
        })
    }

    pub(super) fn 最新から作る(縦横比: 重ねる画面の縦横比) -> Self {
        match 縦横比.設定() {
            アスペクト比設定::ワイド16対9 => Self::ワイド16対9,
            アスペクト比設定::スタンダード4対3 => Self::スタンダード4対3,
            アスペクト比設定::正方形 => Self::正方形,
            アスペクト比設定::縦型9対16 => Self::縦型9対16,
            アスペクト比設定::クロップ連動 => {
                panic!("重ねる画面の縦横比はクロップ連動を持たない(到達したらバグ)")
            }
        }
    }
}

impl 重ね合わせの第1版の矩形 {
    /// 映す矩形へ変換する。各値は0〜100へ収めてから、重ねる画面の外へ出る矩形と小さすぎる矩形を拒む(このアプリが書いた値は範囲の中にあるため、収めても変わらない)。
    pub(super) fn 映す矩形にする(self) -> Result<映す矩形, 映す矩形エラー> {
        映す矩形::作成する(
            百分率::範囲へ収める(self.x),
            百分率::範囲へ収める(self.y),
            百分率::範囲へ収める(self.w),
            百分率::範囲へ収める(self.h),
        )
    }

    /// クロップ範囲へ変換する。スタックのファイル第1版と同じく、各値は範囲へ収める(書いた値は範囲の中にあるため、収めても変わらない)。
    pub(super) fn クロップ範囲にする(self) -> クロップ範囲 {
        クロップ範囲::各値を範囲へ収めて作成する(self.x, self.y, self.w, self.h)
    }

    pub(super) fn 映す矩形から作る(矩形: 映す矩形) -> Self {
        Self {
            x: 矩形.左端().数値(),
            y: 矩形.上端().数値(),
            w: 矩形.幅().数値(),
            h: 矩形.高さ().数値(),
        }
    }

    pub(super) fn クロップ範囲から作る(クロップ: クロップ範囲) -> Self {
        Self {
            x: クロップ.左端().数値(),
            y: クロップ.上端().数値(),
            w: クロップ.幅().数値(),
            h: クロップ.高さ().数値(),
        }
    }
}
