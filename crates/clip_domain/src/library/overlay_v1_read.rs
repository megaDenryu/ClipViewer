//! 重ね合わせのファイル第1版から最新のライブラリの重ね合わせへの変換。置いたクリップの値を変換してから、
//! 重ね合わせの部品一式として重ね合わせを組み立て、重ね合わせの不変条件を全部確かめる。

use super::date::ライブラリの日時;
use super::overlay_error::重ね合わせのファイルの読み込みエラー;
use super::overlay_id::重ね合わせの識別子;
use super::overlay_item::ライブラリの重ね合わせ;
use super::overlay_name::重ね合わせの名前;
use super::overlay_v1::{
    重ね合わせの第1版のファイル, 重ね合わせの第1版の行
};
use crate::overlay::{
    タイムラインの行の部品一式, 使う動画の表, 行の番号, 部品の並びの中の位置, 重ね合わせの部品一式,
};
use crate::video_path::入力された動画パス;

impl 重ね合わせの第1版のファイル {
    /// 最新のライブラリの重ね合わせへ変換する。動画のパスは読み込みの時点で正規化する。
    /// 形式の名前と版は読み込みの前に確かめ終えているため、ここでは使わない。
    pub(crate) fn 最新へ変換する(
        self,
    ) -> Result<ライブラリの重ね合わせ, 重ね合わせのファイルの読み込みエラー> {
        let Self {
            format: _,
            version: _,
            identifier,
            name,
            created_at_ms,
            updated_at_ms,
            aspect,
            videos,
            rows,
        } = self;
        let mut 行の並び = Vec::with_capacity(rows.len());
        for (番号, 第1版の行) in rows.into_iter().enumerate() {
            行の並び.push(第1版の行.最新へ変換する(行の番号::番号から作成する(番号))?);
        }
        let 重ね合わせ = 重ね合わせの部品一式 {
            縦横比: aspect.最新へ変換する()?,
            動画の表: 使う動画の表::並びから作成する(
                videos
                    .into_iter()
                    .map(|パス| 入力された動画パス::作成する(パス).正規化する())
                    .collect(),
            ),
            行の並び,
        }
        .重ね合わせへ組み立てる()?;
        Ok(
            ライブラリの重ね合わせ::各項目から組み立てる(
                重ね合わせの識別子::文字列から作成する(identifier)?,
                重ね合わせの名前::作成する(name)?,
                重ね合わせ,
                ライブラリの日時::紀元からのミリ秒で作成する(created_at_ms)?,
                ライブラリの日時::紀元からのミリ秒で作成する(updated_at_ms)?,
            ),
        )
    }
}

impl 重ね合わせの第1版の行 {
    // 行の置いたクリップの値を変換する。行の番号は、成立しない値の場所を知らせるために使う。
    fn 最新へ変換する(
        self,
        行: 行の番号,
    ) -> Result<タイムラインの行の部品一式, 重ね合わせのファイルの読み込みエラー> {
        let mut 置いたクリップの並び = Vec::with_capacity(self.items.len());
        for (番号, 置いた) in self.items.into_iter().enumerate() {
            置いたクリップの並び.push(置いた.最新へ変換する().map_err(|理由| {
                重ね合わせのファイルの読み込みエラー::置いたクリップが不正 {
                    行,
                    位置: 部品の並びの中の位置::番号から作成する(番号),
                    理由,
                }
            })?);
        }
        Ok(タイムラインの行の部品一式 {
            置いたクリップの並び,
        })
    }
}
