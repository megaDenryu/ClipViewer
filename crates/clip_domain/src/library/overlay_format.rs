//! ライブラリの重ね合わせとライブラリのファイルの本文の変換。読み込みは版を判別してから、版に合う型で読んで最新へ変換する。
//! 版を足すときは、版に合う型で読む選択肢をここへ足す。参照: _doc/設計/ライブラリ.md「形式の版を上げる手順」

use super::error::ライブラリのファイルの書き出しエラー;
use super::file_text::ライブラリのファイルの本文;
use super::overlay_error::重ね合わせのファイルの読み込みエラー;
use super::overlay_item::ライブラリの重ね合わせ;
use super::overlay_v1::{
    重ね合わせの形式の名前, 重ね合わせの第1版のファイル, 重ね合わせの第1版の番号,
};
use super::v1::版の見出し;

/// このアプリが知っている重ね合わせのファイルの最新の版の番号。これより大きい版は、このアプリより新しい ClipViewer が書いたファイルである。
const 重ね合わせの最新の版の番号: u64 = 重ね合わせの第1版の番号;

impl ライブラリの重ね合わせ {
    /// ライブラリのファイルの本文から読み込む。形式の名前が違うか、読めない版なら拒む。読めた値が重ね合わせの不変条件を満たさなければ拒む。
    pub fn 本文から読み込む(
        本文: &ライブラリのファイルの本文,
    ) -> Result<Self, 重ね合わせのファイルの読み込みエラー> {
        let 見出し: 版の見出し = serde_json::from_str(本文.文字列()).map_err(
            重ね合わせのファイルの読み込みエラー::解析のエラーから作る,
        )?;
        if 見出し.format.as_deref() != Some(重ね合わせの形式の名前) {
            return Err(
                重ね合わせのファイルの読み込みエラー::形式の名前が違う(
                    見出し.format,
                ),
            );
        }
        match 見出し.version {
            Some(重ね合わせの第1版の番号) => {
                serde_json::from_str::<重ね合わせの第1版のファイル>(本文.文字列())
                    .map_err(重ね合わせのファイルの読み込みエラー::解析のエラーから作る)?
                    .最新へ変換する()
            }
            Some(版) if 版 > 重ね合わせの最新の版の番号 => {
                Err(重ね合わせのファイルの読み込みエラー::版が新しすぎる(版))
            }
            その他 => Err(重ね合わせのファイルの読み込みエラー::対応していない版(その他)),
        }
    }

    /// 最新の版の形で、空白を入れないJSONの本文へ書き出す。
    pub fn 本文へ書き出す(
        &self,
    ) -> Result<ライブラリのファイルの本文, ライブラリのファイルの書き出しエラー> {
        serde_json::to_string(&重ね合わせの第1版のファイル::最新から作る(self))
            .map(ライブラリのファイルの本文::作成する)
            .map_err(|原因| ライブラリのファイルの書き出しエラー {
                理由: 原因.to_string(),
            })
    }
}
