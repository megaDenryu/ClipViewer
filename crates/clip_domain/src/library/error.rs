//! ライブラリのファイルの読み込みと書き出しと、ブラウザ版の設定からの取り込みで起きるエラー。
//! 公開の型に serde_json の型を出さず、JSONの不備は位置と理由を自前の型で持つ。

use super::date::ライブラリの日時エラー;
use super::name::空のスタックの名前エラー;
use super::stack_id::スタックの識別子の不備;
use crate::clip_id::空の識別子エラー;
use crate::duration::時間の値エラー;
use crate::repeat::リピート回数エラー;
use crate::settings::{JSONの不備, JSONの誤りの種類};
use crate::stack_error::クリップスタックの操作エラー;
use crate::video_span::区間エラー;

/// ライブラリのファイルの読み込みエラーとは、ライブラリのファイルの本文からライブラリのスタックを作れなかった理由のことである。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum ライブラリのファイルの読み込みエラー {
    /// 本文がJSONとして解析できない。
    #[error("JSONとして読めない: {0}")]
    JSONとして解析できない(JSONの不備),
    /// format がライブラリのファイルの形式の名前でない。
    #[error("ライブラリのファイルでない(format が {0:?})")]
    形式の名前が違う(Option<String>),
    /// version がこのアプリの知っている最新の版より大きい。このアプリより新しい ClipViewer が書いたファイルである。
    #[error(
        "このアプリより新しい ClipViewer で保存された(version が {0})。ClipViewer を更新すれば開ける"
    )]
    版が新しすぎる(u64),
    /// version が無いか、どの版の番号でもない(0 等)。
    #[error("このアプリが読めない版である(version が {0:?})")]
    対応していない版(Option<u64>),
    /// 項目の型や表記が、その版の形式に合わない。
    #[error("形式が不正: {0}")]
    形式が不正(JSONの不備),
    /// 作った日時か更新した日時が、ライブラリの日時として表せない。
    #[error("{0}")]
    日時が不正(#[from] ライブラリの日時エラー),
    /// スタックの識別子が成立しない。
    #[error("{0}")]
    識別子が不正(#[from] スタックの識別子の不備),
    /// スタックの名前が空である。
    #[error("{0}")]
    名前が空(#[from] 空のスタックの名前エラー),
    /// 指定の番号(0から数える)のクリップの値が成立しない。
    #[error("{番号}番目のクリップが不正: {理由}")]
    クリップが不正 {
        /// 0から数えたクリップの番号。
        番号: usize,
        /// 成立しない理由。
        理由: ライブラリのクリップの不備,
    },
    /// クリップの一覧からスタックを作れない(識別子の重複)。
    #[error("クリップの並びが不正: {0}")]
    並びを作れない(#[from] クリップスタックの操作エラー),
}

impl ライブラリのファイルの読み込みエラー {
    /// serde_json の解析のエラーを、構文の誤りなら「解析できない」、型や表記の誤りなら「形式が不正」へ分けて変換する。
    pub(crate) fn 解析のエラーから作る(エラー: serde_json::Error) -> Self {
        match JSONの誤りの種類::解析のエラーから作る(&エラー) {
            JSONの誤りの種類::形(不備) => Self::形式が不正(不備),
            JSONの誤りの種類::構文(不備) => Self::JSONとして解析できない(不備),
        }
    }
}

/// ライブラリのクリップの不備とは、ライブラリのファイルのクリップの値がドメインの型として成立しない理由のことである。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum ライブラリのクリップの不備 {
    /// クリップの識別子が空である。
    #[error("{0}")]
    識別子(#[from] 空の識別子エラー),
    /// start か end が時刻として成立しない。
    #[error("時刻が不正: {0}")]
    時刻(#[from] 時間の値エラー),
    /// start が end より後ろにある。
    #[error("{0}")]
    区間(#[from] 区間エラー),
    /// repeat の回数が範囲の外にある。
    #[error("{0}")]
    繰り返しの回数(#[from] リピート回数エラー),
    /// repeat が数値でも "infinite" でもない。
    #[error("repeat が数値でも \"infinite\" でもない: {0}")]
    繰り返しの表記(String),
}

/// ライブラリのファイルの書き出しエラーとは、ライブラリのスタックをJSONの本文へ変換できなかった理由のことである。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("ライブラリのファイルの書き出しに失敗: {理由}")]
pub struct ライブラリのファイルの書き出しエラー {
    /// 変換できなかった理由。
    pub 理由: String,
}

/// ライブラリへ取り込めない理由とは、ブラウザ版の設定ファイルをライブラリのスタックにできない理由のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum ライブラリへ取り込めない理由 {
    /// 設定ファイルに expectedVideoPath が無く、どの動画のスタックか分からない。
    #[error(
        "設定ファイルに動画のパス(expectedVideoPath)が無いため、どの動画のスタックか分からない"
    )]
    動画のパスが無い,
}
