//! ライブラリのスタックを変える操作。どれも変えた新しい値を返し、更新した日時を渡された日時にして、作った日時を保つ。
//! 複製だけは新しいスタックを作るため、作った日時も渡された日時にする。

use super::date::ライブラリの日時;
use super::item::ライブラリのスタック;
use super::name::スタックの名前;
use super::stack_id::スタックの識別子;
use crate::stack::クリップスタック;
use crate::video_path::正規化した動画パス;

impl ライブラリのスタック {
    /// クリップの並びを差し替えたスタック。
    pub fn 並びを差し替えた(
        self, 並び: クリップスタック, 今: ライブラリの日時
    ) -> Self {
        Self {
            並び,
            更新した日時: 今,
            ..self
        }
    }

    /// 名前を変えたスタック。
    pub fn 名前を変えた(
        self, 名前: スタックの名前, 今: ライブラリの日時
    ) -> Self {
        Self {
            名前,
            更新した日時: 今,
            ..self
        }
    }

    /// 動画のパスを変えたスタック。動画を移動したときに、場所を指定し直すために使う。
    pub fn 動画の場所を変えた(
        self,
        動画のパス: 正規化した動画パス,
        今: ライブラリの日時,
    ) -> Self {
        Self {
            動画のパス,
            更新した日時: 今,
            ..self
        }
    }

    /// 同じ動画と同じクリップの並びを持つ、別の識別子と名前の新しいスタック。作った日時も渡された日時にする。
    pub fn 複製した(
        &self,
        識別子: スタックの識別子,
        名前: スタックの名前,
        今: ライブラリの日時,
    ) -> Self {
        Self::新しく作る(識別子, 名前, self.動画のパス.clone(), self.並び.clone(), 今)
    }
}
