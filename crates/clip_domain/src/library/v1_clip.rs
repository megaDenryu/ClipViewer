//! 第1版のクリップと最新のクリップの、読み込みと書き出しの両方向の変換。対応を1箇所に置き、食い違いを防ぐ。
//! どちらの向きもクリップの各項目を `..` を使わずに組み立て・分解するため、クリップに項目を足すとここがコンパイルエラーになる。

use super::error::ライブラリのクリップの不備;
use super::v1::{
    第1版のクリップ, 第1版のクロップ, 第1版のトリガー, 第1版の繰り返し
};
use crate::clip::{クリップ, クリップの各項目, クリップ名};
use crate::clip_id::クリップ識別子;
use crate::crop::クロップ範囲;
use crate::time::時刻;
use crate::video_span::動画上の区間;

impl 第1版のクリップ {
    /// 最新のクリップへ変換する。クロップの各値は範囲へ収める(書いた値は範囲の中にあるため、収めても変わらない)。
    pub(crate) fn 最新へ変換する(
        self,
    ) -> Result<クリップ, ライブラリのクリップの不備> {
        let Self {
            id,
            name,
            active,
            start,
            end,
            repeat,
            crop,
            trigger,
        } = self;
        Ok(クリップ::各項目から組み立てる(
            クリップの各項目 {
                識別子: クリップ識別子::文字列から作成する(id)?,
                名前: クリップ名::作成する(name),
                有効か: active,
                区間: 動画上の区間::作成する(
                    時刻::作成する(start)?,
                    時刻::作成する(end)?,
                )?,
                リピート: repeat.最新へ変換する()?,
                クロップ: クロップ範囲::各値を範囲へ収めて作成する(
                    crop.x, crop.y, crop.w, crop.h,
                ),
                トリガー: trigger.最新へ変換する(),
            },
        ))
    }

    /// 最新のクリップから作る。
    pub(crate) fn 最新から作る(クリップ: &クリップ) -> Self {
        let クリップの各項目 {
            識別子,
            名前,
            有効か,
            区間,
            リピート,
            クロップ,
            トリガー,
        } = クリップ.各項目の写しを作る();
        Self {
            id: 識別子.文字列().to_string(),
            name: 名前.文字列().to_string(),
            active: 有効か,
            start: 区間.開始().秒数(),
            end: 区間.終了().秒数(),
            repeat: 第1版の繰り返し::最新から作る(リピート),
            crop: 第1版のクロップ {
                x: クロップ.左端().数値(),
                y: クロップ.上端().数値(),
                w: クロップ.幅().数値(),
                h: クロップ.高さ().数値(),
            },
            trigger: 第1版のトリガー::最新から作る(トリガー),
        }
    }
}
