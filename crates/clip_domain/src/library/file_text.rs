//! ライブラリのファイルの本文。

/// ライブラリのファイルの本文とは、ライブラリのスタック1つか、ライブラリの重ね合わせ1つを書いたファイルの中身(JSONの文字列)そのもののことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ライブラリのファイルの本文(String);

impl ライブラリのファイルの本文 {
    /// ファイルから読んだ文字列から作成する。
    pub fn 作成する(本文: String) -> Self {
        Self(本文)
    }

    /// 本文の文字列を返す。ファイルへ書く境界で使う。
    pub fn 文字列(&self) -> &str {
        &self.0
    }
}
