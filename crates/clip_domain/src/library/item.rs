//! ライブラリのスタック。ライブラリに登録したスタック1つの中身であり、ファイル1つに書く単位である。

use super::date::ライブラリの日時;
use super::name::スタックの名前;
use super::stack_id::スタックの識別子;
use crate::duration::時間の長さ;
use crate::stack::クリップスタック;
use crate::video_path::正規化した動画パス;

/// ライブラリのスタックとは、ライブラリに名前を付けて登録したクリップスタックと、それを再生する動画のパスと、作った日時と更新した日時の組のことである。
/// 動画そのものは持たず、どの動画のどこを切り抜くかだけを持つ。変える操作は `item_change.rs` にある。
#[derive(Debug, Clone, PartialEq)]
pub struct ライブラリのスタック {
    pub(super) 識別子: スタックの識別子,
    pub(super) 名前: スタックの名前,
    pub(super) 動画のパス: 正規化した動画パス,
    pub(super) 並び: クリップスタック,
    pub(super) 作った日時: ライブラリの日時,
    pub(super) 更新した日時: ライブラリの日時,
}

impl ライブラリのスタック {
    /// 新しく登録するスタックを作る。作った日時と更新した日時は、どちらも渡された日時にする。
    pub fn 新しく作る(
        識別子: スタックの識別子,
        名前: スタックの名前,
        動画のパス: 正規化した動画パス,
        並び: クリップスタック,
        今: ライブラリの日時,
    ) -> Self {
        Self::各項目から組み立てる(識別子, 名前, 動画のパス, 並び, 今, 今)
    }

    /// ファイルから読んだ各項目から組み立てる。
    pub(crate) fn 各項目から組み立てる(
        識別子: スタックの識別子,
        名前: スタックの名前,
        動画のパス: 正規化した動画パス,
        並び: クリップスタック,
        作った日時: ライブラリの日時,
        更新した日時: ライブラリの日時,
    ) -> Self {
        Self {
            識別子,
            名前,
            動画のパス,
            並び,
            作った日時,
            更新した日時,
        }
    }

    /// 識別子。
    pub fn 識別子(&self) -> &スタックの識別子 {
        &self.識別子
    }

    /// 名前。
    pub fn 名前(&self) -> &スタックの名前 {
        &self.名前
    }

    /// スタックを再生する動画のパス。
    pub fn 動画のパス(&self) -> &正規化した動画パス {
        &self.動画のパス
    }

    /// クリップの並び。読み込み直後は先頭のクリップが選択されている。
    pub fn 並び(&self) -> &クリップスタック {
        &self.並び
    }

    /// 作った日時。
    pub fn 作った日時(&self) -> ライブラリの日時 {
        self.作った日時
    }

    /// 最後に更新した日時。
    pub fn 更新した日時(&self) -> ライブラリの日時 {
        self.更新した日時
    }

    /// 全クリップの区間の長さの和。繰り返しの回数は掛けない(無限ループがあると再生の長さが決まらないため)。
    pub fn 区間の長さの合計(&self) -> 時間の長さ {
        self.並び
            .一覧()
            .iter()
            .fold(時間の長さ::ゼロ, |合計, クリップ| {
                合計.足す(クリップ.区間.長さ())
            })
    }
}
