//! 重ね合わせの識別子。ライブラリの中で重ね合わせを一意に指し、ライブラリはファイル名にも使う。

use std::fmt;

use super::stack_id::ファイル名に使える識別子か;
use crate::clip_id::{発行時刻, 識別子の乱数};

/// 重ね合わせの識別子とは、ライブラリの中で重ね合わせを一意に指す、英小文字・数字・ハイフンだけからなる1〜100文字の文字列のことである。
/// ライブラリはこれをファイル名に使うため、ファイル名に使えない文字を含まないことを作るメソッドで保証する。
/// 新しく発行するときの形式は「overlay-<ミリ秒>-<0〜9999の乱数>」である。スタックの識別子とは別の型であり、取り違えても型が通らない。
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct 重ね合わせの識別子(String);

/// 重ね合わせの識別子の不備とは、文字列が空か、100文字より長いか、英小文字・数字・ハイフン以外の文字を含むことである。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error(
    "重ね合わせの識別子は英小文字・数字・ハイフンだけからなる1〜100文字でなければならない: {0:?}"
)]
pub struct 重ね合わせの識別子の不備(pub String);

impl 重ね合わせの識別子 {
    /// ファイル等にある既存の識別子の文字列から作成する。
    pub fn 文字列から作成する(
        文字列: String,
    ) -> Result<Self, 重ね合わせの識別子の不備> {
        if ファイル名に使える識別子か(&文字列) {
            Ok(Self(文字列))
        } else {
            Err(重ね合わせの識別子の不備(文字列))
        }
    }

    /// 発行時刻と乱数から「overlay-<ミリ秒>-<乱数>」の識別子を組み立てる。
    pub fn 時刻と乱数から組み立てる(
        時刻: 発行時刻, 乱数: 識別子の乱数
    ) -> Self {
        Self(format!("overlay-{}-{}", 時刻.0, 乱数.0))
    }

    /// 識別子の文字列を返す。ファイル名やファイルの本文へ渡す境界で使う。
    pub fn 文字列(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for 重ね合わせの識別子 {
    fn fmt(&self, 書き込み先: &mut fmt::Formatter<'_>) -> fmt::Result {
        書き込み先.write_str(&self.0)
    }
}
