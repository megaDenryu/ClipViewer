//! 縦横比を保って、四隅のつまみで枠の大きさを変える計算。掴んだ隅の向かいの隅を動かさず、幅と高さの比を保ったまま、
//! 最小の大きさ以上で基準の0〜100%に収まる大きさにする。今のクロップ枠には無い規則であり、映す矩形だけが使う(同時再生.md 2-4)。
//! 最小の大きさと0〜100%に収める規則は、縦横比を保たない大きさの変更(`rect.rs`)と同じ規則の枠へ最後に通す。

use super::grab::四隅のつまみ;
use super::movement::枠の移動量;
use super::rect::百分率の枠;
use super::resize::作業中の矩形;
use super::枠の最小の大きさ;
use crate::pixel::縦横比;

/// 向かいの隅と空きとは、掴んだ隅の向かいの隅の位置と、そこから掴んだ隅の側の基準の端(0か100)までの横と縦の空きの組のことである。
struct 向かいの隅と空き {
    横: f64,
    縦: f64,
    横の空き: f64,
    縦の空き: f64,
}

impl 向かいの隅と空き {
    fn 求める(始め: &作業中の矩形, つまみ: 四隅のつまみ) -> Self {
        let 横 = if つまみ.左側か() {
            始め.左端 + 始め.幅
        } else {
            始め.左端
        };
        let 縦 = if つまみ.上側か() {
            始め.上端 + 始め.高さ
        } else {
            始め.上端
        };
        Self {
            横,
            縦,
            横の空き: if つまみ.左側か() {
                横
            } else {
                100.0 - 横
            },
            縦の空き: if つまみ.上側か() {
                縦
            } else {
                100.0 - 縦
            },
        }
    }

    /// 比のまま収まる幅の下限と上限。下限は幅と高さの両方が最小の大きさ以上になる幅、上限は横と縦の空きに収まる幅である。
    /// 下限が上限を超える(空きがその比のまま最小の大きさを保てない)ときは無い。
    fn 比のまま収まる幅の範囲(&self, 比: f64) -> Option<(f64, f64)> {
        let 最大の幅 = self.横の空き.min(self.縦の空き * 比);
        let 最小の幅 = 枠の最小の大きさ.max(枠の最小の大きさ * 比);
        (最小の幅 <= 最大の幅).then_some((最小の幅, 最大の幅))
    }

    /// 向かいの隅を動かさずに、掴んだ隅の側へ幅と高さを広げた矩形。
    fn 大きさから矩形を作る(
        &self,
        つまみ: 四隅のつまみ,
        幅: f64,
        高さ: f64,
    ) -> 作業中の矩形 {
        作業中の矩形 {
            左端: if つまみ.左側か() {
                self.横 - 幅
            } else {
                self.横
            },
            上端: if つまみ.上側か() {
                self.縦 - 高さ
            } else {
                self.縦
            },
            幅,
            高さ,
        }
    }
}

impl<基準: Copy> 百分率の枠<基準> {
    /// ドラッグの開始時の枠を、つまみの角を移動量だけ動かして、幅÷高さが保つ比になる大きさへ変える。
    /// 動かした角が示す幅と高さのうち、保つ比で大きい方へ合わせる。掴んだ隅の向かいの隅から基準の端までの空きが、
    /// 保つ比のまま最小の大きさを保てないときは、縦横比を保たない大きさの変更にする(比と隅の位置の両方で決まる)。
    /// 前提: 保つ比は有限で正である(`縦横比` の作る口が確かめる)。
    pub(crate) fn 縦横比を保ってつまみで大きさを変える(
        &self,
        つまみ: 四隅のつまみ,
        移動量: 枠の移動量<基準>,
        保つ比: 縦横比,
    ) -> Self {
        let 比 = 保つ比.値();
        let 始め = 作業中の矩形::枠から作る(self);
        let 隅 = 向かいの隅と空き::求める(&始め, つまみ);
        let Some((最小の幅, 最大の幅)) = 隅.比のまま収まる幅の範囲(比) else {
            return self.つまみで大きさを変える(つまみ, 移動量);
        };
        let mut 動かした = 作業中の矩形::枠から作る(self);
        動かした.つまみの角を動かす(つまみ, 移動量.横.数値(), 移動量.縦.数値());
        let 幅 = 動かした
            .幅
            .max(動かした.高さ * 比)
            .clamp(最小の幅, 最大の幅);
        隅.大きさから矩形を作る(つまみ, 幅, 幅 / 比).枠へ収める()
    }
}
