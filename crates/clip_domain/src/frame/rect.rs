//! 百分率の枠と、そのドラッグによる移動と、四隅のつまみによる縦横比を保たない大きさの変更。

use super::grab::四隅のつまみ;
use super::movement::枠の移動量;
use super::resize::作業中の矩形;
use crate::percent::百分率;

/// 百分率の枠とは、基準の幅と高さに対する百分率で、左端・上端・幅・高さを持つ枠のことである。
/// 移動と大きさの変更の結果は、左端と上端が0以上、幅と高さが最小の大きさ以上で、左端+幅と上端+高さが100以下である。
/// 注意: 結果の左端+幅は、100から左端を引いた値を幅の上限にして求める。倍精度の小数で左端と(100−左端)を足すと
/// 丸めても100を超えないため、映す矩形のように誤差を許さない型へもそのまま渡せる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 百分率の枠<基準> {
    pub(crate) 左端: 百分率<基準>,
    pub(crate) 上端: 百分率<基準>,
    pub(crate) 幅: 百分率<基準>,
    pub(crate) 高さ: 百分率<基準>,
}

impl<基準: Copy> 百分率の枠<基準> {
    /// ドラッグの開始時の枠を移動量だけ動かす。大きさは変えず、枠が0〜100%からはみ出さないよう収める。
    pub(crate) fn 移動する(&self, 移動量: 枠の移動量<基準>) -> Self {
        let 左端 = self.左端.数値() + 移動量.横.数値();
        let 上端 = self.上端.数値() + 移動量.縦.数値();
        Self {
            左端: 百分率::下限と上限の間へ収める(左端, 0.0, 100.0 - self.幅.数値()),
            上端: 百分率::下限と上限の間へ収める(
                上端,
                0.0,
                100.0 - self.高さ.数値(),
            ),
            幅: self.幅,
            高さ: self.高さ,
        }
    }

    /// ドラッグの開始時の枠を、つまみの角を移動量だけ動かして大きさを変える。幅と高さは最小の大きさ以上に保ち、枠は0〜100%に収める。
    pub(crate) fn つまみで大きさを変える(
        &self,
        つまみ: 四隅のつまみ,
        移動量: 枠の移動量<基準>,
    ) -> Self {
        let mut 矩形 = 作業中の矩形::枠から作る(self);
        矩形.つまみの角を動かす(つまみ, 移動量.横.数値(), 移動量.縦.数値());
        矩形.最小の大きさを保つ(つまみ);
        矩形.はみ出しを削る();
        矩形.枠へ収める()
    }
}
