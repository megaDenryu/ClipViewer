//! 枠の移動量。ドラッグの開始点からの移動を、基準の幅・高さに対する百分率の差分で表す。

use crate::percent::百分率の差分;

/// 枠の移動量とは、ドラッグの開始点からの移動を、基準の幅・高さに対する百分率で表したもののことである。基準は型引数が決める。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 枠の移動量<基準> {
    /// 横方向の移動量。右が正。
    pub 横: 百分率の差分<基準>,
    /// 縦方向の移動量。下が正。
    pub 縦: 百分率の差分<基準>,
}

impl<基準> Default for 枠の移動量<基準> {
    fn default() -> Self {
        Self {
            横: 百分率の差分::default(),
            縦: 百分率の差分::default(),
        }
    }
}
