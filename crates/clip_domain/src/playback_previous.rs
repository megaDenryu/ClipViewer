//! 利用者の操作で前のクリップへ戻す規則。次へ進める規則(`playback_next.rs`)と対になり、シーケンス再生のときだけ戻す。
//! 先頭のクリップにいるときは、そのクリップの開始へ戻す。参照: _doc/設計/画面.md 判断14

use crate::clip::クリップ;
use crate::playback_position::再生位置;
use crate::stack::クリップスタック;
use crate::stack_previous::前のクリップの探索結果;

/// 前へ戻した結果とは、前へ戻す操作を受けて、クリップの開始へ戻したか、戻せなかったかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 前へ戻した結果<'スタック> {
    /// 戻した。画面は再生位置を差し替え、クリップを選択する。
    戻した {
        /// 戻した先の再生位置(そのクリップの開始)。
        位置: 再生位置,
        /// 戻した先のクリップ。
        クリップ: &'スタック クリップ,
    },
    /// シーケンス再生でないか、現在の位置に当たるクリップが無いので戻せない。
    戻せない,
}

impl 再生位置 {
    /// 前の再生できるクリップの開始へ戻す。前に再生できるクリップが無ければ(先頭のクリップにいれば)、今のクリップの開始へ戻す。
    pub fn 前のクリップへ戻す(
        self,
        スタック: &クリップスタック,
    ) -> 前へ戻した結果<'_> {
        let Self::シーケンス再生(位置) = self else {
            return 前へ戻した結果::戻せない;
        };
        match スタック.前の再生できるクリップを探す(位置) {
            前のクリップの探索結果::見つかった {
                クリップ, 開始位置
            }
            | 前のクリップの探索結果::先頭にいる {
                クリップ, 開始位置
            } => 前へ戻した結果::戻した {
                位置: Self::シーケンス再生(開始位置),
                クリップ,
            },
            前のクリップの探索結果::現在の位置にクリップが無い => {
                前へ戻した結果::戻せない
            }
        }
    }
}
