//! タイムライン上の位置で再生するものを求める処理。タイムライン上の位置から、映すべき動画上の位置と再生の状況を求める。
//! 移植元 `Service/タイムライン解決.ts` の `タイムラインを解決する` の移植である。
//! 待ちの判定は移植元の「終了間際0.15秒」をやめ、`clip_ending.rs` の規則(最後の周回を繰り返して待つ)に従う。

use crate::clip::クリップ;
use crate::duration::時間の長さ;
use crate::stack::クリップスタック;
use crate::time::{タイムライン上の秒, 時刻};
use crate::timeline_result::{
    タイムライン上の位置で再生するもの, タイムライン上の位置の再生の中身, 表示するコマの位置,
};

impl クリップスタック {
    /// タイムライン上の位置で再生するものを求める。有効なクリップのうち、開始位置から終わりの位置の手前までに位置が収まるものを探す。
    pub fn タイムライン上の位置で再生するものを求める(
        &self,
        位置: タイムライン上の秒,
    ) -> タイムライン上の位置で再生するもの<'_> {
        self.開始位置付きで並べる()
            .find(|並び| {
                並び.クリップ.有効か && 位置 >= 並び.開始位置 && 位置 < 並び.終わりの位置()
            })
            .map_or(
                タイムライン上の位置で再生するもの::クリップが無い,
                |並び| {
                    並び.クリップ.クリップの中の位置で再生するものを求める(
                        並び.番号,
                        並び.開始位置,
                        位置,
                    )
                },
            )
    }

    /// 表示するコマを求める。位置がタイムラインの末尾以降(末尾で止めたとき・時計が末尾で止まったとき)なら、
    /// 最後の再生できるクリップの区間の終わりを返す。動画側は区間の終わり以降の時刻に最後のコマを返すため、
    /// 画面は最後のクリップの最後のコマを表示できる。どのクリップにも当たらなければ無い。
    pub fn 表示するコマを求める(
        &self,
        位置: タイムライン上の秒,
    ) -> Option<表示するコマの位置<'_>> {
        match self.タイムライン上の位置で再生するものを求める(位置) {
            タイムライン上の位置で再生するもの::クリップがある(
                再生の中身,
            ) => Some(表示するコマの位置 {
                クリップ: 再生の中身.対象クリップ,
                動画上の位置: 再生の中身.動画上の位置,
            }),
            タイムライン上の位置で再生するもの::クリップが無い
                if 位置 >= 時刻::先頭.進める(self.合計の占有時間()) =>
            {
                self.最後の再生できるクリップ()
                    .map(|クリップ| 表示するコマの位置 {
                        クリップ,
                        動画上の位置: クリップ.区間.終了(),
                    })
            }
            タイムライン上の位置で再生するもの::クリップが無い => None,
        }
    }
}

impl クリップ {
    /// タイムライン上で開始位置から始まるこのクリップについて、クリップの中にある位置で再生するものを求める。
    /// 区間の長さが0ならクリップが無い(占有時間も0なので、スタックから求めるときは到達しない防御である)。
    fn クリップの中の位置で再生するものを求める(
        &self,
        番号: usize,
        クリップの開始位置: タイムライン上の秒,
        位置: タイムライン上の秒,
    ) -> タイムライン上の位置で再生するもの<'_> {
        let 一周: 時間の長さ = self.区間.長さ();
        if 一周.ゼロか() {
            return タイムライン上の位置で再生するもの::クリップが無い;
        }
        let クリップ内の経過 = 位置.起点から経過した長さ(クリップの開始位置);
        let 周回 = クリップ内の経過.周回番号を求める(一周);
        let 周回の中の位置 = クリップ内の経過.一周の中での余り(一周);
        タイムライン上の位置で再生するもの::クリップがある(
            タイムライン上の位置の再生の中身 {
                対象クリップ: self,
                クリップの開始位置,
                動画上の位置: self.区間.開始().進める(周回の中の位置),
                周回,
                待っているか: self.待っているか(周回),
                スタック内の番号: 番号,
            },
        )
    }
}
