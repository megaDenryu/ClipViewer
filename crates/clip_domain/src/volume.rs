//! 音量の型。スタックの再生の音量のつまみ(audio_pcm が再公開して音の再生器が使う)と、置いたクリップごとの音量の両方に使う。

/// 音量とは、0以上1以下の音の大きさのことである。0で無音、1で元の大きさである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 音量(f64);

impl 音量 {
    /// 起動したときの音量とは、アプリを起動したときのスタックの再生の音量のつまみの値(移植元と同じ0.5)のことである。
    /// 見る側の設定に音量が無いときに使う。置いたクリップの最初の音量(`元の大きさ`)とは別の値である。
    pub const 起動したときの音量: 音量 = 音量(0.5);

    /// 無音。
    pub const 無音: 音量 = 音量(0.0);

    /// 元の大きさとは、音を元の動画の大きさのまま鳴らす音量(1)のことである。新しく置いたクリップの音量である。
    pub const 元の大きさ: 音量 = 音量(1.0);

    /// 0未満は0に、1を超える値は1に、非数は0に収めて作る。つまみの値を受け取る境界で使う。
    pub fn 範囲へ収めて作る(値: f64) -> Self {
        if 値.is_nan() {
            return Self(0.0);
        }
        Self(値.clamp(0.0, 1.0))
    }

    /// 2つの音量を掛けた音量。どちらも0以上1以下なので、積も0以上1以下に収まる。
    /// 置いたクリップの音量に音量のつまみの値を掛けて、鳴らす大きさを求めるときに使う(同時再生.md 2-6)。
    pub fn 掛ける(self, 他方: 音量) -> 音量 {
        Self(self.0 * 他方.0)
    }

    /// 0以上1以下の値。つまみへ渡す境界と、標本に掛ける倍率に使う。
    pub fn 値(self) -> f64 {
        self.0
    }
}
