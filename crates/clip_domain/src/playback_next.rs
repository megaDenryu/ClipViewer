//! 利用者の操作で次のクリップへ進める規則。
//! 移植元 `ClipViewerApp出力ハンドラ.ts` の `on次クリップ` と `on出力クリック` の移植である。
//! 移植元は再生モードを確かめずにシーケンスのタイムライン上の位置で再生するものを求めていたが、本クレートはシーケンス再生のときだけ進める。

use crate::clip::クリップ;
use crate::playback_clock::末尾での振る舞い;
use crate::playback_position::再生位置;
use crate::stack::クリップスタック;
use crate::stack_navigation::次のクリップの探索結果;
use crate::time::時刻;
use crate::timeline_result::タイムライン上の位置で再生するもの;
use crate::trigger::進める操作;

/// 次へ進めた結果とは、進める操作を受けて、次のクリップへ進んだか、末尾で止めたか、進めなかったかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 次へ進めた結果<'スタック> {
    /// 進んだ。画面は再生位置を差し替え、クリップを選択する。
    進んだ {
        /// 進んだ先の再生位置。
        位置: 再生位置,
        /// 進んだ先のクリップ。
        クリップ: &'スタック クリップ,
    },
    /// 最後のクリップで、全体の末尾が「止まる」なので再生を止めた。画面は最後のクリップの最後のコマを表示して止まる。
    末尾で止めた {
        /// 止めた再生位置(タイムラインの末尾)。
        位置: 再生位置,
        /// 止めたときに再生していたクリップ。
        最後のクリップ: &'スタック クリップ,
    },
    /// 進めなかった。
    進めない(進めない理由),
}

/// 進めない理由とは、進める操作を受けても次のクリップへ進まなかった理由のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 進めない理由 {
    /// 再生モードがシーケンス再生でない。
    シーケンス再生でない,
    /// 現在の位置に当たるクリップが無い。
    現在の位置にクリップが無い,
    /// 操作が現在のクリップのトリガーと合わない。
    操作がトリガーと合わない,
}

impl 再生位置 {
    /// 進める操作を受けて次のクリップへ進める。最後のクリップの次は、全体の末尾が「先頭へ戻る」なら最初の再生できるクリップへ進み、
    /// 「止まる」なら再生を止める(オーナーの裁定。移植元は何もしなかった)。
    pub fn 操作で次へ進める<'スタック>(
        self,
        操作: 進める操作,
        スタック: &'スタック クリップスタック,
        全体の末尾: 末尾での振る舞い,
    ) -> 次へ進めた結果<'スタック> {
        let Self::シーケンス再生(位置) = self else {
            return 次へ進めた結果::進めない(進めない理由::シーケンス再生でない);
        };
        let タイムライン上の位置で再生するもの::クリップがある(再生の中身) =
            スタック.タイムライン上の位置で再生するものを求める(位置)
        else {
            return 次へ進めた結果::進めない(進めない理由::現在の位置にクリップが無い);
        };
        if !再生の中身.対象クリップ.この操作で次へ進むか(操作) {
            return 次へ進めた結果::進めない(進めない理由::操作がトリガーと合わない);
        }
        match スタック.次の再生できるクリップを探す(位置) {
            次のクリップの探索結果::見つかった {
                クリップ, 開始位置
            } => 次へ進めた結果::進んだ {
                位置: Self::シーケンス再生(開始位置),
                クリップ,
            },
            次のクリップの探索結果::現在の位置にクリップが無い => {
                次へ進めた結果::進めない(進めない理由::現在の位置にクリップが無い)
            }
            次のクリップの探索結果::末尾に達した => {
                スタック.末尾の次へ進める(全体の末尾, 再生の中身.対象クリップ)
            }
        }
    }
}

impl クリップスタック {
    fn 末尾の次へ進める<'スタック>(
        &'スタック self,
        全体の末尾: 末尾での振る舞い,
        最後のクリップ: &'スタック クリップ,
    ) -> 次へ進めた結果<'スタック> {
        match (全体の末尾, self.最初の再生できるクリップ()) {
            (末尾での振る舞い::先頭へ戻る, Some(クリップ)) => {
                次へ進めた結果::進んだ {
                    位置: 再生位置::シーケンス再生(時刻::先頭),
                    クリップ,
                }
            }
            _ => 次へ進めた結果::末尾で止めた {
                位置: 再生位置::シーケンス再生(
                    時刻::先頭.進める(self.合計の占有時間()),
                ),
                最後のクリップ,
            },
        }
    }
}
