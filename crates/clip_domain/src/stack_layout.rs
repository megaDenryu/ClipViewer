//! クリップスタックのタイムライン上の並び。占有時間を並び順に積み上げて各クリップの開始位置を求める計算を、ここ1か所に置く。

use crate::clip::クリップ;
use crate::duration::時間の長さ;
use crate::stack::クリップスタック;
use crate::time::{タイムライン上の秒, 時刻};

/// 開始位置付きのクリップとは、クリップと、そのクリップのタイムライン上の開始位置と、スタック内の番号の組のことである。
/// 無効なクリップも占有時間0で並びに含まれる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 開始位置付きのクリップ<'スタック> {
    /// クリップ。
    pub クリップ: &'スタック クリップ,
    /// タイムライン上の開始位置。前にあるクリップの占有時間の合計である。
    pub 開始位置: タイムライン上の秒,
    pub(crate) 番号: usize,
}

impl 開始位置付きのクリップ<'_> {
    /// タイムライン上の終わりの位置(この位置は次のクリップに属する)。
    pub fn 終わりの位置(&self) -> タイムライン上の秒 {
        self.開始位置.進める(self.クリップ.占有時間())
    }
}

impl クリップスタック {
    /// クリップを並び順に、タイムライン上の開始位置と組にして並べる。
    pub fn 開始位置付きで並べる(
        &self,
    ) -> impl Iterator<Item = 開始位置付きのクリップ<'_>> {
        self.一覧()
            .iter()
            .enumerate()
            .scan(時刻::先頭, |次の開始位置, (番号, クリップ)| {
                let 並べたもの = 開始位置付きのクリップ {
                    クリップ,
                    開始位置: *次の開始位置,
                    番号,
                };
                *次の開始位置 = 並べたもの.終わりの位置();
                Some(並べたもの)
            })
    }

    /// スタック全体のタイムライン上の長さ。有効なクリップの占有時間の合計である。
    pub fn 合計の占有時間(&self) -> 時間の長さ {
        self.一覧().iter().fold(時間の長さ::ゼロ, |合計, クリップ| {
            合計.足す(クリップ.占有時間())
        })
    }
}
