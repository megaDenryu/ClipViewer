//! 0以上の小数を整数へ丸める純粋な計算。映像のコマ番号・音の標本位置・リピートの周回の数え方が共通に使う。
//! lint が `as` による変換を禁じており、標準ライブラリに小数から整数への TryFrom が無いため、二分探索で求める。

/// 境目の許容誤差(数える単位で)。コマや標本の境目ちょうどの時刻を秒の小数表現で持つと、丸めの誤差で境目の手前へ
/// 落ちることがある。数える前にこの分だけ境目の向こうへ寄せ、1つ前のコマや標本へ落ちることを防ぐ。
const 境目の許容誤差: f64 = 1e-6;

/// 小数を切り捨てた整数を求める。負と非数は0に、u32の最大を超える値は最大に飽和させる。
pub fn 小数を切り捨てた整数(値: f64) -> u32 {
    if 値.is_nan() || 値 < 1.0 {
        return 0;
    }
    if 値 >= f64::from(u32::MAX) {
        return u32::MAX;
    }
    let (mut 下, mut 上) = (0_u32, u32::MAX);
    while 上 - 下 > 1 {
        let 候補 = 下 + (上 - 下) / 2;
        if f64::from(候補) <= 値 {
            下 = 候補;
        } else {
            上 = 候補;
        }
    }
    下
}

/// 小数を切り上げた整数を求める。飽和の規則は切り捨てと同じである。
pub fn 小数を切り上げた整数(値: f64) -> u32 {
    let 切り捨て = 小数を切り捨てた整数(値);
    if f64::from(切り捨て) < 値 {
        切り捨て.saturating_add(1)
    } else {
        切り捨て
    }
}

/// 小数を四捨五入した整数を求める。飽和の規則は切り捨てと同じである。
pub fn 小数を四捨五入した整数(値: f64) -> u32 {
    小数を切り捨てた整数(値 + 0.5)
}

/// 境目の許容誤差だけ大きい側へ寄せてから切り捨てる。時刻を含むコマや標本の番号を求めるときに使う。
pub fn 境目を許容して切り捨てた整数(値: f64) -> u32 {
    小数を切り捨てた整数(値 + 境目の許容誤差)
}

/// 境目の許容誤差だけ小さい側へ寄せてから切り上げる。時刻より前に始まるコマの次の番号を求めるときに使う。
pub fn 境目を許容して切り上げた整数(値: f64) -> u32 {
    小数を切り上げた整数(値 - 境目の許容誤差)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 切り捨てと切り上げと四捨五入は整数の境目で正しく分かれる() {
        assert_eq!(小数を切り捨てた整数(0.0), 0);
        assert_eq!(小数を切り捨てた整数(2.999), 2);
        assert_eq!(小数を切り捨てた整数(3.0), 3);
        assert_eq!(小数を切り上げた整数(3.0), 3);
        assert_eq!(小数を切り上げた整数(3.001), 4);
        assert_eq!(小数を切り捨てた整数(123_456.7), 123_456);
        assert_eq!(小数を四捨五入した整数(2.5), 3);
        assert_eq!(小数を四捨五入した整数(2.49), 2);
    }

    #[test]
    fn 境目の許容誤差の内側の値は境目に揃える() {
        assert_eq!(境目を許容して切り捨てた整数(2.999_999_9), 3);
        assert_eq!(境目を許容して切り上げた整数(3.000_000_1), 3);
        assert_eq!(境目を許容して切り捨てた整数(2.99), 2);
        assert_eq!(境目を許容して切り上げた整数(3.01), 4);
    }

    #[test]
    fn 負と非数と大きすぎる値は飽和する() {
        assert_eq!(小数を切り捨てた整数(-5.0), 0);
        assert_eq!(小数を切り捨てた整数(f64::NAN), 0);
        assert_eq!(小数を切り捨てた整数(1e20), u32::MAX);
        assert_eq!(小数を切り上げた整数(1e20), u32::MAX);
    }
}
