//! 区間を再生の位置に合わせる決まり。今見ている位置から新しい区間を作ることと、区間の開始か終了を今の位置に合わせること。
//! どれも `区間の編集の決まり` の端を動かす規則(0秒から上限の間へ収める・開始と終了の間を最小の長さ以上に保つ)を通す。
//! 参照: _doc/設計/画面.md 判断14

use crate::duration::時間の長さ;
use crate::span_edit::区間の編集の決まり;
use crate::time::{動画上の秒, 時刻};
use crate::video_span::動画上の区間;

impl 区間の編集の決まり {
    /// 位置から始まる長さの区間を作る。開始は位置であり、終了が最小の長さを空けられないほど上限に近ければ開始を前へ寄せる。
    /// 終了は開始に長さを足した位置であり、上限を超えるなら上限で止める(長さが縮む)。
    pub fn 位置から始まる区間を作る(
        &self,
        位置: 動画上の秒,
        長さ: 時間の長さ,
    ) -> 動画上の区間 {
        let 全体 = 動画上の区間::開始と長さから作る(時刻::先頭, self.上限());
        let 開始を合わせた = self.開始を動かす(全体, 位置.秒数());
        let 終了 = 開始を合わせた.開始().秒数() + 長さ.秒数();
        self.終了を動かす(開始を合わせた, 終了)
    }

    /// 開始を位置に合わせた区間。位置が終了より前なら開始だけを動かす。位置が終了以降なら、開始が終了を越えないよう、
    /// 長さを保って開始を位置へ動かす(終了が上限を超えるなら、終了が上限に着く位置で止める)。
    pub fn 開始を位置に合わせる(
        &self,
        区間: 動画上の区間,
        位置: 動画上の秒,
    ) -> 動画上の区間 {
        if 位置 < 区間.終了() {
            self.開始を動かす(区間, 位置.秒数())
        } else {
            self.長さを保って動かす(区間, 位置.秒数())
        }
    }

    /// 終了を位置に合わせた区間。位置が開始より後ろなら終了だけを動かす。位置が開始以前なら、終了が開始を越えないよう、
    /// 長さを保って終了を位置へ動かす(開始が0秒より前になるなら、開始が0秒に着く位置で止める)。
    pub fn 終了を位置に合わせる(
        &self,
        区間: 動画上の区間,
        位置: 動画上の秒,
    ) -> 動画上の区間 {
        if 位置 > 区間.開始() {
            self.終了を動かす(区間, 位置.秒数())
        } else {
            self.長さを保って動かす(区間, 位置.秒数() - 区間.長さ().秒数())
        }
    }
}
