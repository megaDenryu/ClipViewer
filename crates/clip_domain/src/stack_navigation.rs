//! クリップスタックのクリップ間の移動の規則。
//! 移植元 `Service/タイムライン解決.ts` の合計時間・開始位置と、
//! `ClipViewerApp出力ハンドラ.ts` の `on次クリップ` の探索部分の移植である。

use crate::clip::クリップ;
use crate::clip_id::クリップ識別子;
use crate::stack::クリップスタック;
use crate::time::タイムライン上の秒;
use crate::timeline_result::タイムライン上の位置で再生するもの;

/// 次のクリップの探索結果とは、現在の位置の次にある再生できるクリップを探した結果のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 次のクリップの探索結果<'スタック> {
    /// 次の再生できるクリップがあった。
    見つかった {
        /// 次の再生できるクリップ。
        クリップ: &'スタック クリップ,
        /// そのクリップのタイムライン上の開始位置。
        開始位置: タイムライン上の秒,
    },
    /// 現在のクリップより後ろに再生できるクリップが無い。全体ループなら先頭へ戻るかを画面の側が決める。
    末尾に達した,
    /// 現在の位置に当たるクリップが無い。移植元はこの場合に何もしない。
    現在の位置にクリップが無い,
}

impl クリップスタック {
    /// 指定のクリップのタイムライン上の開始位置。前にあるクリップの占有時間の合計である。
    pub fn クリップの開始位置(
        &self,
        識別子: &クリップ識別子,
    ) -> Option<タイムライン上の秒> {
        self.開始位置付きで並べる()
            .find(|並び| 並び.クリップ.識別子() == 識別子)
            .map(|並び| 並び.開始位置)
    }

    /// 並び順で最初の再生できるクリップ(有効で長さが0でないクリップ)。
    pub fn 最初の再生できるクリップ(&self) -> Option<&クリップ> {
        self.一覧().iter().find(|クリップ| クリップ.再生できるか())
    }

    /// 並び順で最後の再生できるクリップ(有効で長さが0でないクリップ)。
    pub fn 最後の再生できるクリップ(&self) -> Option<&クリップ> {
        self.一覧()
            .iter()
            .rev()
            .find(|クリップ| クリップ.再生できるか())
    }

    /// タイムライン上の位置に当たるクリップの、次にある再生できるクリップを探す。
    /// 無効なクリップと長さ0のクリップは飛ばす(移植元は長さ0のクリップを選んでいた)。
    pub fn 次の再生できるクリップを探す(
        &self,
        位置: タイムライン上の秒,
    ) -> 次のクリップの探索結果<'_> {
        let タイムライン上の位置で再生するもの::クリップがある(再生の中身) =
            self.タイムライン上の位置で再生するものを求める(位置)
        else {
            return 次のクリップの探索結果::現在の位置にクリップが無い;
        };
        self.開始位置付きで並べる()
            .skip(再生の中身.スタック内の番号 + 1)
            .find(|並び| 並び.クリップ.再生できるか())
            .map_or(
                次のクリップの探索結果::末尾に達した,
                |並び| 次のクリップの探索結果::見つかった {
                    クリップ: 並び.クリップ,
                    開始位置: 並び.開始位置,
                },
            )
    }
}
