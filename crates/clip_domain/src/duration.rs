//! 時間の長さの型と、時間の値の検査で起きるエラー。

use crate::repeat::周回番号;

/// 時間の長さとは、2つの時刻の間の、0秒以上の有限の秒数のことである。
/// 時間軸の基準を持たないため、動画上の区間の長さにもタイムライン上の占有時間にも使う。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd, Default)]
#[repr(transparent)]
pub struct 時間の長さ(f64);

/// 時間の値エラーとは、秒数が時刻や時間の長さとして成立しない理由のことである。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 時間の値エラー {
    /// 秒数が無限大か非数である。
    #[error("時間の値が有限でない")]
    有限でない,
    /// 秒数が負である。
    #[error("時間の値が負である: {0}秒")]
    負である(f64),
}

impl 時間の長さ {
    /// 0秒の長さ。
    pub const ゼロ: Self = Self(0.0);

    /// 定数の秒数から作る。有限でない値と負の値は、定数の評価の時点(コンパイル時)で失敗させる。
    /// 注意: 実行時の値には使わない。実行時に渡すと、不正な値でパニックする。
    pub const fn 定数の秒数から作る(秒: f64) -> Self {
        assert!(秒.is_finite() && 秒 >= 0.0, "定数の秒数が有限で非負でない");
        Self(秒)
    }

    /// 秒数から作成する。有限でない値と負の値を拒む。
    pub fn 作成する(秒: f64) -> Result<Self, 時間の値エラー> {
        非負の有限な秒数か検査する(秒).map(Self)
    }

    /// 算術の結果が有限かつ非負であると呼び出し側が保証する値から作る。
    /// 注意: 有限で非負の値どうしの加算・乗算・飽和減算の結果だけを渡すこと。
    pub(crate) fn 検査済みの秒数から作る(秒: f64) -> Self {
        Self(秒.max(0.0))
    }

    /// 秒数を返す。表示や外部の仕組みへ渡す境界で使う。
    pub fn 秒数(self) -> f64 {
        self.0
    }

    /// 長さが0秒か。
    pub fn ゼロか(self) -> bool {
        self.0 <= 0.0
    }

    /// 2つの長さを足す。
    pub fn 足す(self, 他方: Self) -> Self {
        Self::検査済みの秒数から作る(self.0 + 他方.0)
    }

    /// 長さを差し引く。結果が負になる場合は0秒にする。
    pub fn 差し引く(self, 他方: Self) -> Self {
        Self::検査済みの秒数から作る(self.0 - 他方.0)
    }

    /// この長さの中に、一周の長さが何回まるごと収まるかを求める。一周が0秒なら0周とする。
    pub fn 何周分か(self, 一周: Self) -> 周回番号 {
        if 一周.ゼロか() {
            return 周回番号::最初;
        }
        周回番号::商から求める(self.0 / 一周.0)
    }

    /// この長さを一周の長さで割った余りを求める。一周が0秒なら0秒とする。
    pub fn 一周の中での余り(self, 一周: Self) -> Self {
        if 一周.ゼロか() {
            return Self::ゼロ;
        }
        Self::検査済みの秒数から作る(self.0 % 一周.0)
    }
}

/// 秒数が有限かつ非負かを検査する。時刻と時間の長さの両方の作成で共有する。
pub(crate) fn 非負の有限な秒数か検査する(
    秒: f64,
) -> Result<f64, 時間の値エラー> {
    if !秒.is_finite() {
        return Err(時間の値エラー::有限でない);
    }
    if 秒 < 0.0 {
        return Err(時間の値エラー::負である(秒));
    }
    Ok(秒)
}
