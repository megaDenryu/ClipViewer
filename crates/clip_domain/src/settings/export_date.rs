//! 設定ファイルの exportDate に書く書き出し日時。
//! ブラウザの `Date.prototype.toISOString` と同じ形(協定世界時・ミリ秒まで・末尾Z)を時刻から組み立てる。

use std::time::SystemTime;

/// 書き出し日時とは、設定ファイルの exportDate に書く、書き出した日時の「YYYY-MM-DDTHH:MM:SS.mmmZ」の文字列のことである。
/// 作る口は時刻から組み立てる関数だけなので、形の崩れた日時は作れない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 書き出し日時(String);

/// 書き出し日時エラーとは、時刻が1970年1月1日(協定世界時)より前か、表せないほど後であることである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("書き出し日時にできない時刻である(1970年より前か、表せないほど後)")]
pub struct 書き出し日時エラー;

const 一日のミリ秒: u64 = 86_400_000;

impl 書き出し日時 {
    /// 時刻から組み立てる。時刻の取得は呼び出し側が行う(ドメインが時計を直接読まないため)。
    pub fn 時刻から作成する(
        時刻: SystemTime
    ) -> Result<Self, 書き出し日時エラー> {
        let 経過 = 時刻
            .duration_since(SystemTime::UNIX_EPOCH)
            .map_err(|_| 書き出し日時エラー)?;
        let ミリ秒 = u64::try_from(経過.as_millis()).map_err(|_| 書き出し日時エラー)?;
        let (年, 月, 日) = 紀元からの日数を暦の日付にする(ミリ秒 / 一日のミリ秒);
        let 日の中 = ミリ秒 % 一日のミリ秒;
        Ok(Self(format!(
            "{年:04}-{月:02}-{日:02}T{:02}:{:02}:{:02}.{:03}Z",
            日の中 / 3_600_000,
            日の中 / 60_000 % 60,
            日の中 / 1_000 % 60,
            日の中 % 1_000,
        )))
    }

    /// 日時の文字列を返す。設定ファイルへ書く境界で使う。
    pub fn 文字列(&self) -> &str {
        &self.0
    }
}

/// 1970年1月1日からの日数を、先発グレゴリオ暦の(年, 月, 日)にする。
/// 参照: Howard Hinnant「chrono-Compatible Low-Level Date Algorithms」の civil_from_days。
fn 紀元からの日数を暦の日付にする(日数: u64) -> (u64, u64, u64) {
    let 通日 = 日数 + 719_468;
    let 四百年周期 = 通日 / 146_097;
    let 周期内の日 = 通日 - 四百年周期 * 146_097;
    let 周期内の年 =
        (周期内の日 - 周期内の日 / 1_460 + 周期内の日 / 36_524 - 周期内の日 / 146_096) / 365;
    let 年内の日 = 周期内の日 - (365 * 周期内の年 + 周期内の年 / 4 - 周期内の年 / 100);
    let 三月始まりの月 = (5 * 年内の日 + 2) / 153;
    let 日 = 年内の日 - (153 * 三月始まりの月 + 2) / 5 + 1;
    let 月 = if 三月始まりの月 < 10 {
        三月始まりの月 + 3
    } else {
        三月始まりの月 - 9
    };
    let 年 = 周期内の年 + 四百年周期 * 400 + u64::from(月 <= 2);
    (年, 月, 日)
}
