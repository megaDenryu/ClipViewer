//! 設定ファイルの書き出し。書き出しの前提(クリップが1つ以上あること、動画パスが検証済みであること)を型で要求する。

use super::error::設定ファイルの書き出しエラー;
use super::export_date::書き出し日時;
use super::v4::第4版の設定ファイル;
use super::設定ファイルの本文;
use crate::stack_non_empty::空でないクリップスタック;
use crate::video_path_check::検証済みの動画パス;

/// 書き出す設定とは、設定ファイルへ書き出す内容、すなわち空でないクリップスタックと、検証済みの動画パスの組のことである。
/// 期待する動画のファイル名は、検証済みの動画パスが持つ検証に使った名前を書く。
#[derive(Debug, Clone, Copy)]
pub struct 書き出す設定<'設定> {
    /// 書き出すクリップの並び。
    pub スタック: 空でないクリップスタック<'設定>,
    /// スタックを作った動画の、検証を通ったパスと検証に使ったファイル名。
    pub 動画のパス: &'設定 検証済みの動画パス,
}

impl 書き出す設定<'_> {
    /// 第4版の形で、2文字字下げのJSONの本文へ書き出す。
    pub fn 本文へ書き出す(
        &self,
        日時: &書き出し日時,
    ) -> Result<設定ファイルの本文, 設定ファイルの書き出しエラー> {
        let 第4版 = 第4版の設定ファイル::最新から作る(self, 日時);
        serde_json::to_string_pretty(&第4版)
            .map(設定ファイルの本文)
            .map_err(|原因| 設定ファイルの書き出しエラー {
                理由: 原因.to_string(),
            })
    }
}
