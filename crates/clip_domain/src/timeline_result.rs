//! タイムライン上の位置で再生するものを求めた結果の型。
//! 移植元はステータスの文字列を組み立てて返していたが、文字列化は表示の都合なので、
//! ここでは構造化した値だけを返し、文字列化は画面の側が行う。

use crate::clip::クリップ;
use crate::repeat::{リピート回数, リピート設定, 周回番号};
use crate::time::{タイムライン上の秒, 動画上の秒};

/// タイムライン上の位置で再生するものとは、タイムライン上の位置が、どのクリップのどの動画上の位置に当たるかを求めた結果のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum タイムライン上の位置で再生するもの<'スタック> {
    /// 位置に当たるクリップがあった。
    クリップがある(タイムライン上の位置の再生の中身<'スタック>),
    /// 位置に当たるクリップが無い(スタックの合計時間以降、または有効なクリップが無い)。
    クリップが無い,
}

/// タイムライン上の位置の再生の中身とは、タイムライン上の位置に当たるクリップと、その中での再生の状況の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct タイムライン上の位置の再生の中身<'スタック> {
    /// 位置に当たるクリップ。
    pub 対象クリップ: &'スタック クリップ,
    /// 対象クリップのタイムライン上の開始位置。
    pub クリップの開始位置: タイムライン上の秒,
    /// 動画のどこを映すか。
    pub 動画上の位置: 動画上の秒,
    /// 区間を繰り返している何周目か。
    pub 周回: 周回番号,
    /// 終わりで待つクリップの最後の周回を再生していて、進める操作を待っているか。
    pub 待っているか: bool,
    pub(crate) スタック内の番号: usize,
}

/// 表示するコマの位置とは、画面に映すコマが、どのクリップの動画上のどの位置にあるかの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 表示するコマの位置<'スタック> {
    /// 映すコマを持つクリップ。
    pub クリップ: &'スタック クリップ,
    /// 映すコマの動画上の位置。
    pub 動画上の位置: 動画上の秒,
}

/// 周回の状況とは、表示の「(Loop)」「(2/3)」に当たる、繰り返しの進み具合のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 周回の状況 {
    /// 無限ループの最中である。
    無限ループ中,
    /// 回数指定の繰り返しの最中である。
    回数指定中 {
        /// 1から数えた現在の周回。
        何周目: u16,
        /// 繰り返す回数。
        回数: リピート回数,
    },
}

impl タイムライン上の位置の再生の中身<'_> {
    /// 周回の状況を求める。表示の側が「クリップ名 (2/3) [Trigger: ...]」のような文字列を組み立てるために使う。
    pub fn 周回の状況(&self) -> 周回の状況 {
        match self.対象クリップ.リピート {
            リピート設定::無限ループ => 周回の状況::無限ループ中,
            リピート設定::回数指定(回数) => 周回の状況::回数指定中 {
                何周目: self.周回.一から数えた順番(),
                回数,
            },
        }
    }
}
