//! 出力のアスペクト比の設定。

use crate::pixel::{画素の寸法, 縦横比};

/// アスペクト比設定とは、出力画面の縦横比をどう決めるかの設定のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum アスペクト比設定 {
    /// 切り出したクロップ範囲の縦横比に合わせる。
    クロップ連動,
    /// 16:9に固定する。
    #[default]
    ワイド16対9,
    /// 4:3に固定する。
    スタンダード4対3,
    /// 1:1に固定する。
    正方形,
    /// 9:16に固定する。
    縦型9対16,
}

impl アスペクト比設定 {
    /// 出力の縦横比を求める。クロップ連動で切り出し後の高さが0のときは16:9とする(移植元と同じ)。
    pub fn 縦横比を求める(self, 切り出し後の寸法: 画素の寸法) -> 縦横比 {
        match self {
            Self::クロップ連動 => 切り出し後の寸法
                .縦横比()
                .unwrap_or_else(|| 縦横比::整数比から求める(16, 9)),
            Self::ワイド16対9 => 縦横比::整数比から求める(16, 9),
            Self::スタンダード4対3 => 縦横比::整数比から求める(4, 3),
            Self::正方形 => 縦横比::整数比から求める(1, 1),
            Self::縦型9対16 => 縦横比::整数比から求める(9, 16),
        }
    }
}
