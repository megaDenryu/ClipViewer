//! 空でないクリップスタック。クリップが1つ以上あることを型で示し、それを要求する操作(設定ファイルの書き出し)へ渡す。

use crate::stack::クリップスタック;

/// 空でないクリップスタックとは、クリップが1つ以上あると確かめたクリップスタックへの参照のことである。
/// 移植元はクリップが0件なら書き出しを拒んでいたため、書き出しはこの型を要求する。
#[derive(Debug, Clone, Copy)]
pub struct 空でないクリップスタック<'スタック>(&'スタック クリップスタック);

impl クリップスタック {
    /// クリップが1つ以上あることを確かめる。空なら無い。
    pub fn 空でないことを確かめる(
        &self,
    ) -> Option<空でないクリップスタック<'_>> {
        (!self.一覧().is_empty()).then_some(空でないクリップスタック(self))
    }
}

impl<'スタック> 空でないクリップスタック<'スタック> {
    /// 確かめたクリップスタック。
    pub fn スタック(&self) -> &'スタック クリップスタック {
        self.0
    }
}
