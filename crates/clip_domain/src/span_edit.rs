//! 区間の編集の決まり。区間の端を動かすときに、端を0秒から上限の間へ収め、開始と終了の間を最小の長さ以上に保つ規則である。
//! クリップカードの区間の帯・秒の数値入力・ずらすボタンが同じ決まりを使う。
//! 秒は利用者の操作から来る値なので、負の値と非数も受け取り、この決まりの中で収める。

use crate::duration::時間の長さ;
use crate::time::時刻;
use crate::video_span::動画上の区間;

/// 区間の編集の決まりとは、区間の端を動かせる上限と、開始と終了の間に必ず空ける最小の長さの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 区間の編集の決まり {
    上限: 時間の長さ,
    最小の長さ: 時間の長さ,
}

/// 上限を刻みで割るときの誤差の許し。10.04 / 0.01 が 1003.999… になって1刻み少なく切り下げないためである。
const 小数の割り算の誤差の許し: f64 = 1e-9;

impl 区間の編集の決まり {
    /// 上限(動画の先頭からの長さ)と最小の長さから作る。
    pub fn 作成する(上限: 時間の長さ, 最小の長さ: 時間の長さ) -> Self {
        Self {
            上限, 最小の長さ
        }
    }

    /// 区間の端を動かせる上限(動画の先頭からの長さ)。
    pub(crate) fn 上限(&self) -> 時間の長さ {
        self.上限
    }

    /// 秒を刻みの倍数へ丸め、上限を超えるなら上限以下で最大の刻みの倍数にした秒。区間の帯から受け取った秒にだけ使う。
    /// 決まりの上限そのものは丸めないため、数値入力で上限ちょうどに合わせた端を、区間の帯で別の端を動かしても変えない。
    /// 刻みが0秒なら丸めない。非数は0秒にする。
    pub fn 刻みへ丸めて上限の内側へ収める(
        &self, 秒: f64, 刻み: 時間の長さ
    ) -> f64 {
        let 刻み = 刻み.秒数();
        if 刻み <= 0.0 {
            return self.上限の内側へ収める(秒);
        }
        let 上限 = self.上限.秒数();
        let 丸めた秒 = (self.上限の内側へ収める(秒) / 刻み).round() * 刻み;
        if 丸めた秒 <= 上限 {
            return 丸めた秒;
        }
        let 刻みの数 = (上限 / 刻み + 小数の割り算の誤差の許し).floor();
        (刻みの数 * 刻み).min(上限)
    }

    /// 開始を秒の位置へ動かした区間。開始は終了より最小の長さ以上前に止める。
    pub fn 開始を動かす(&self, 区間: 動画上の区間, 秒: f64) -> 動画上の区間 {
        let 終了 = 区間.終了().秒数();
        let 開始 = self
            .上限の内側へ収める(秒)
            .min(終了 - self.最小の長さ.秒数());
        self.整える(開始, 終了)
    }

    /// 終了を秒の位置へ動かした区間。終了は開始より最小の長さ以上後ろに止める。
    pub fn 終了を動かす(&self, 区間: 動画上の区間, 秒: f64) -> 動画上の区間 {
        let 開始 = 区間.開始().秒数();
        let 終了 = self
            .上限の内側へ収める(秒)
            .max(開始 + self.最小の長さ.秒数());
        self.整える(開始, 終了)
    }

    /// 長さを保って、開始を秒の位置へ動かした区間。終了が上限を超えるなら、終了が上限に着く位置で止める。
    pub fn 長さを保って動かす(
        &self, 区間: 動画上の区間, 秒: f64
    ) -> 動画上の区間 {
        let 長さ = 区間.長さ().秒数();
        let 最も後ろの開始 = (self.上限.秒数() - 長さ).max(0.0);
        let 開始 = self.上限の内側へ収める(秒).min(最も後ろの開始);
        self.整える(開始, 開始 + 長さ)
    }

    /// 秒を0秒から上限の間へ収める。非数は0秒にする。
    fn 上限の内側へ収める(&self, 秒: f64) -> f64 {
        if 秒.is_nan() {
            return 0.0;
        }
        秒.clamp(0.0, self.上限.秒数())
    }

    /// 開始を0秒から上限の間へ収め、終了を上限以下かつ開始より最小の長さ以上後ろにして区間を作る。
    /// 開始が上限に着いたときは、最小の長さを保つために終了が上限を超える。開始と長さから作ると加算の丸めで終了が上限を
    /// 超えることがあるため、開始と終了をそれぞれ時刻にして作る。
    fn 整える(&self, 開始: f64, 終了: f64) -> 動画上の区間 {
        let 開始 = self.上限の内側へ収める(開始);
        let 終了 = 終了
            .min(self.上限.秒数())
            .max(開始 + self.最小の長さ.秒数());
        let 時刻にする =
            |秒| 時刻::先頭.進める(時間の長さ::検査済みの秒数から作る(秒));
        動画上の区間::検査済みの開始と終了から作る(
            時刻にする(開始),
            時刻にする(終了),
        )
    }
}
