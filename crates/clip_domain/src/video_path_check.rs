//! 動画パスの検証。設定ファイルへ書き出す前に、パスがWindowsの絶対パスで、期待する動画を指しているかを確かめる。
//! 検証を通ったパスは `検証済みの動画パス` になり、書き出しはこの型だけを受け付ける。

use crate::video_path::{
    入力された動画パス, 動画ファイル名, 正規化した動画パス
};

/// 動画パスの不備とは、動画パスが書き出しに使えない理由のことである。表示の文言は移植元と同じである。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum 動画パスの不備 {
    /// パスが空である。
    #[error("動画のPC内絶対パスを入力してください")]
    空である,
    /// 前後の引用符の一方だけがある。
    #[error("パス前後の引用符を確認してください")]
    引用符が釣り合っていない,
    /// Windowsの絶対パスの形でない。
    #[error("Windowsの絶対パスを入力してください")]
    絶対パスでない,
    /// パスのファイル名が期待する動画のファイル名と違う。
    #[error("動画ファイル名が一致しません: {}", .0.文字列())]
    ファイル名が一致しない(動画ファイル名),
}

/// 検証済みの動画パスとは、書き出しに使えると検証を通った、正規化した動画パスと、検証に使った期待する動画のファイル名の組のことである。
/// 作る口は `入力された動画パス::検証する` だけである。書き出しは期待する動画のファイル名もここから取るため、
/// ある名前で検証したパスを別の名前と組にして書き出すことはできない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 検証済みの動画パス {
    パス: 正規化した動画パス,
    期待する動画: Option<動画ファイル名>,
}

impl 検証済みの動画パス {
    /// 正規化した動画パスを返す。
    pub fn 正規化したパス(&self) -> &正規化した動画パス {
        &self.パス
    }

    /// 検証に使った期待する動画のファイル名。
    pub fn 期待する動画(&self) -> Option<&動画ファイル名> {
        self.期待する動画.as_ref()
    }
}

/// 動画パスの検証結果とは、正規化したパスと、それが書き出しに使えるかの判定の組のことである。
/// 移植元は不正な場合も正規化したパスを入力欄へ書き戻すため、どちらの場合も正規化したパスを持つ。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 動画パスの検証結果 {
    /// 書き出しに使える。
    有効(検証済みの動画パス),
    /// 書き出しに使えない。
    不正 {
        /// 正規化したパス。
        正規化したパス: 正規化した動画パス,
        /// 使えない理由。
        不備: 動画パスの不備,
    },
}

impl 入力された動画パス {
    /// 正規化してから検証する。期待する動画のファイル名があれば、パスのファイル名がそれと一致するかも確かめる。
    pub fn 検証する(
        &self,
        期待する動画: Option<&動画ファイル名>,
    ) -> 動画パスの検証結果 {
        let 正規化したパス = self.正規化する();
        match 正規化したパス.書き出しに使えない理由を探す(期待する動画) {
            None => 動画パスの検証結果::有効(検証済みの動画パス {
                パス: 正規化したパス,
                期待する動画: 期待する動画.cloned(),
            }),
            Some(不備) => 動画パスの検証結果::不正 {
                正規化したパス,
                不備,
            },
        }
    }
}

impl 正規化した動画パス {
    /// 書き出しに使えない理由を、空・引用符・絶対パス・ファイル名の一致の順に探す。使えるなら無い。
    fn 書き出しに使えない理由を探す(
        &self,
        期待する動画: Option<&動画ファイル名>,
    ) -> Option<動画パスの不備> {
        if self.空か() {
            return Some(動画パスの不備::空である);
        }
        if self.前後の引用符が釣り合っていないか() {
            return Some(動画パスの不備::引用符が釣り合っていない);
        }
        if !self.ウィンドウズの絶対パスに見えるか() {
            return Some(動画パスの不備::絶対パスでない);
        }
        let 期待する動画 = 期待する動画?;
        let 一致するか = self
            .ファイル名()
            .is_some_and(|実際| 実際.大文字小文字を区別せず等しいか(期待する動画));
        (!一致するか)
            .then(|| 動画パスの不備::ファイル名が一致しない(期待する動画.clone()))
    }
}
