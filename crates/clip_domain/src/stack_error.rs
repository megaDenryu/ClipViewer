//! クリップスタックへの操作が拒まれた理由。

use crate::clip_id::クリップ識別子;

/// クリップスタックの操作エラーとは、スタックへの操作が不変条件を破るために拒まれた理由のことである。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum クリップスタックの操作エラー {
    /// 指定の識別子のクリップが無い。
    #[error("識別子「{0}」のクリップは存在しない")]
    見つからない(クリップ識別子),
    /// 同じ識別子のクリップが既にある。
    #[error("識別子「{0}」のクリップは既に存在する")]
    識別子が重複している(クリップ識別子),
    /// スタックに残る最後の1つを削除しようとした。
    #[error("最後の1つのクリップは削除できない")]
    最後の1つは削除できない,
    /// 並びの番号が、クリップの数の範囲の外を指した。
    #[error("並びの{番号}番目は無い(クリップは{数}個)")]
    番号が範囲の外 {
        /// 指した番号(0から数える)。
        番号: usize,
        /// クリップの数。
        数: usize,
    },
}
