//! 再生の時計の入力の型と、時計を進める条件を参照して位置を進める工程。
//! 再生速度、合計の長さに達したときの振る舞い、時計を進める条件を定め、
//! シーケンス再生と単独クリップ再生の位置の進め方と、合計の長さに達したときの判定を時計を進める条件のメソッドに置く。

use crate::duration::時間の長さ;
use crate::playback_position::再生位置;
use crate::stack::クリップスタック;
use crate::time::{タイムライン上の秒, 時刻};

/// 再生速度とは、実時間の1秒あたりに再生位置が進む秒数のことであり、0より大きい有限の数である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 再生速度(f64);

/// 再生速度エラーとは、速度が0より大きい有限の数でないことである。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
#[error("再生速度は0より大きい有限の数でなければならない: {0}")]
pub struct 再生速度エラー(pub f64);

impl 再生速度 {
    /// 等倍。
    pub const 等倍: Self = Self(1.0);

    /// 倍率から作成する。
    pub fn 作成する(倍率: f64) -> Result<Self, 再生速度エラー> {
        if 倍率.is_finite() && 倍率 > 0.0 {
            Ok(Self(倍率))
        } else {
            Err(再生速度エラー(倍率))
        }
    }

    /// 倍率を返す。表示へ渡す境界で使う。
    pub fn 倍率(self) -> f64 {
        self.0
    }

    /// 実時間の経過の間に、再生位置が進む長さを求める。
    pub fn 進む長さ(self, 実時間の経過: 時間の長さ) -> 時間の長さ {
        時間の長さ::検査済みの秒数から作る(実時間の経過.秒数() * self.0)
    }
}

/// 末尾での振る舞いとは、シーケンス再生と元動画再生で、再生位置が合計の長さに達したときに先頭へ戻るか止まるかの区別のことである。
/// 移植元の「グローバルループ」の真偽に当たる。単独クリップ再生はこの設定に関わらず常に先頭へ戻る。
/// 重ね合わせの再生位置が重ね合わせの長さに着いたときの振る舞い(重ね合わせの作業場の全体ループ)にも同じ型を使う。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 末尾での振る舞い {
    /// 先頭へ戻って再生を続ける。
    先頭へ戻る,
    /// 末尾で再生を止める。
    止まる,
}

/// 時計を進めた結果とは、再生位置を進めた後の位置と、再生を止めるべきかの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 時計を進めた結果 {
    /// 再生を続ける。
    続ける(再生位置),
    /// 末尾に達したので、この位置で再生を止める。
    末尾で止まる(再生位置),
}

/// 時計を進める条件とは、時計を進めるときに参照する、再生位置の外にある事実の組のことである。
#[derive(Debug, Clone, Copy)]
pub struct 時計を進める条件<'スタック> {
    /// シーケンス再生の並びと、単独クリップ再生の対象(選択中のクリップ)。
    pub スタック: &'スタック クリップスタック,
    /// 元動画再生の合計の長さ。
    pub 動画の長さ: 時間の長さ,
    /// 再生速度。
    pub 速度: 再生速度,
    /// シーケンス再生と元動画再生で、合計の長さに達したときの振る舞い。
    pub 全体の末尾: 末尾での振る舞い,
}

impl 時計を進める条件<'_> {
    pub(crate) fn シーケンスの位置を進める(
        &self,
        位置: タイムライン上の秒,
        増分: 時間の長さ,
    ) -> 時計を進めた結果 {
        let 進めた位置 = 位置.進める(増分);
        if let Some(戻した位置) = self
            .スタック
            .通る待つクリップの最後の周回へ戻す(位置, 進めた位置)
        {
            return 時計を進めた結果::続ける(再生位置::シーケンス再生(戻した位置));
        }
        let 合計 = self.スタック.合計の占有時間();
        進めた位置.末尾を判定する(合計, self.全体の末尾, 再生位置::シーケンス再生)
    }

    pub(crate) fn 単独再生の経過を進める(
        &self,
        経過: 時間の長さ,
        増分: 時間の長さ,
    ) -> 時間の長さ {
        let Some(クリップ) = self.スタック.選択中のクリップ() else {
            return 経過;
        };
        let 一周 = クリップ.区間.長さ();
        let 進めた経過 = 経過.足す(増分);
        if 進めた経過 < 一周 {
            進めた経過
        } else {
            進めた経過.一周の中での余り(一周)
        }
    }
}

impl<基準: Copy + PartialOrd> 時刻<基準> {
    /// 進めた位置が合計の長さに達したかを判定し、先頭へ戻るか止まる。合計が0秒のときは判定しない(移植元と同じ)。
    /// 包む関数は、時刻を再生モードの再生位置へ包む列挙子である。
    pub(crate) fn 末尾を判定する(
        self,
        合計: 時間の長さ,
        全体の末尾: 末尾での振る舞い,
        包む: fn(Self) -> 再生位置,
    ) -> 時計を進めた結果 {
        if !self.末尾に達しているか(合計) {
            return 時計を進めた結果::続ける(包む(self));
        }
        match 全体の末尾 {
            末尾での振る舞い::先頭へ戻る => {
                時計を進めた結果::続ける(包む(Self::先頭))
            }
            末尾での振る舞い::止まる => {
                時計を進めた結果::末尾で止まる(包む(Self::先頭.進める(合計)))
            }
        }
    }

    /// この位置が合計の長さに達しているか。合計が0秒のときは達していないとみなす(末尾を判定しないのと同じ)。
    pub(crate) fn 末尾に達しているか(self, 合計: 時間の長さ) -> bool {
        !合計.ゼロか() && self >= Self::先頭.進める(合計)
    }
}
