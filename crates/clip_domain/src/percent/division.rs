//! 全体を等分した区間。基準を保ったまま、全体(100)を n 等分した区間の始まりと大きさを百分率で求める。

use std::num::NonZeroU32;

use super::百分率;

/// 等分した区間とは、基準の全体を等分したときの1つの区間を、始まりの境界と大きさの百分率で表したもののことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 等分した区間<基準> {
    /// 区間の始まりの境界。
    pub 始まり: 百分率<基準>,
    /// 区間の大きさ。次の境界から始まりの境界を引いた値である。
    pub 大きさ: 百分率<基準>,
}

impl<基準> 百分率<基準> {
    /// 全体を分割数で等分した区間を、0から近い順に返す。k番目の区間の始まりの境界は 100×k/分割数 であり、大きさは次の境界との差である。
    /// 注意: 最後の区間の終わりの境界は 100×分割数/分割数 で100ちょうどになる。最後の区間の始まりは50以上(分割数が1なら0)なので、
    /// 100からの引き算は誤差を持たず(Sterbenz の補題)、最後の区間の始まりと大きさを足すと100ちょうどになる。映す矩形は誤差を許さないため、この性質を保つ。
    pub fn 全体を等分した区間の並び(
        分割数: NonZeroU32,
    ) -> impl Iterator<Item = 等分した区間<基準>> {
        let 境界 = move |位置: u32| {
            Self::検査済みの数値から作る(
                100.0 * f64::from(位置) / f64::from(分割数.get()),
            )
        };
        (0..分割数.get()).map(move |位置| {
            let 始まり = 境界(位置);
            let 大きさ = Self::検査済みの数値から作る(境界(位置 + 1).数値 - 始まり.数値);
            等分した区間 {
                始まり, 大きさ
            }
        })
    }
}
