//! クロップ枠のドラッグによる移動と、四隅のつまみによる大きさの変更。計算は映す矩形と共有する百分率の枠の規則(`frame_drag.rs`)に委ねる。

use crate::crop::クロップ範囲;
use crate::frame_drag::{四隅のつまみ, 枠の移動量, 百分率の枠};
use crate::percent::元の動画に対する;

/// クロップの移動量とは、ドラッグの開始点からの移動を、画像の幅・高さに対する百分率で表したもののことである。
pub type クロップの移動量 = 枠の移動量<元の動画に対する>;

impl クロップ範囲 {
    /// ドラッグの開始時のクロップ範囲を移動量だけ動かす。大きさは変えず、枠が0〜100%からはみ出さないよう収める。
    pub fn 移動する(&self, 移動量: クロップの移動量) -> Self {
        Self::枠から作る(self.枠にする().移動する(移動量))
    }

    /// ドラッグの開始時のクロップ範囲を、つまみの角を移動量だけ動かして大きさを変える。
    /// 幅と高さは5%以上に保ち、枠は0〜100%に収める。
    pub fn つまみで大きさを変える(
        &self,
        つまみ: 四隅のつまみ,
        移動量: クロップの移動量,
    ) -> Self {
        Self::枠から作る(self.枠にする().つまみで大きさを変える(つまみ, 移動量))
    }

    fn 枠にする(&self) -> 百分率の枠<元の動画に対する> {
        百分率の枠 {
            左端: self.左端(),
            上端: self.上端(),
            幅: self.幅(),
            高さ: self.高さ(),
        }
    }

    // 百分率の枠の移動と大きさの変更の結果は、幅と高さが5以上でクロップ範囲の不変条件を満たす。
    fn 枠から作る(枠: 百分率の枠<元の動画に対する>) -> Self {
        Self::検査済みの値から作る(枠.左端, 枠.上端, 枠.幅, 枠.高さ)
    }
}
