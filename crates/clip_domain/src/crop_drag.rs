//! クロップ枠のドラッグによる移動と、四隅のつまみによる大きさの変更の計算。
//! 移植元 `ClipViewerAppクロップギズモハンドラ.ts` の `クロップ操作を適用する` と `リサイズを適用する` の移植である。

use crate::crop::クロップ範囲;
use crate::crop_resize::作業中の矩形;
use crate::percent::{百分率, 百分率の差分};

/// クロップの移動量とは、ドラッグの開始点からの移動を、画像の幅・高さに対する百分率で表したもののことである。
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct クロップの移動量 {
    /// 横方向の移動量。右が正。
    pub 横: 百分率の差分,
    /// 縦方向の移動量。下が正。
    pub 縦: 百分率の差分,
}

/// 四隅のつまみとは、クロップ枠の大きさを変えるためにドラッグする角の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 四隅のつまみ {
    /// 左上の角。
    左上,
    /// 右上の角。
    右上,
    /// 左下の角。
    左下,
    /// 右下の角。
    右下,
}

impl 四隅のつまみ {
    pub(crate) fn 左側か(self) -> bool {
        matches!(self, Self::左上 | Self::左下)
    }

    pub(crate) fn 上側か(self) -> bool {
        matches!(self, Self::左上 | Self::右上)
    }
}

impl クロップ範囲 {
    /// ドラッグの開始時のクロップ範囲を移動量だけ動かす。大きさは変えず、枠が0〜100%からはみ出さないよう収める。
    pub fn 移動する(&self, 移動量: クロップの移動量) -> Self {
        let 左端 = self.左端().数値() + 移動量.横.数値();
        let 上端 = self.上端().数値() + 移動量.縦.数値();
        Self::検査済みの値から作る(
            百分率::下限と上限の間へ収める(左端, 0.0, 100.0 - self.幅().数値()),
            百分率::下限と上限の間へ収める(上端, 0.0, 100.0 - self.高さ().数値()),
            self.幅(),
            self.高さ(),
        )
    }

    /// ドラッグの開始時のクロップ範囲を、つまみの角を移動量だけ動かして大きさを変える。
    /// 幅と高さは5%以上に保ち、枠は0〜100%に収める。
    pub fn つまみで大きさを変える(
        &self,
        つまみ: 四隅のつまみ,
        移動量: クロップの移動量,
    ) -> Self {
        let mut 矩形 = 作業中の矩形::クロップ範囲から作る(self);
        矩形.つまみの角を動かす(つまみ, 移動量.横.数値(), 移動量.縦.数値());
        矩形.最小の大きさを保つ(つまみ);
        矩形.はみ出しを削る();
        矩形.クロップ範囲へ収める()
    }
}
