//! クリップスタックの前のクリップへ戻る規則。現在の位置に当たるクリップの前にある再生できるクリップを探す。
//! 次のクリップを探す規則(`stack_navigation.rs`)と逆向きであり、トリガーを見ない(前へ戻る操作はボタンだけが発するため)。

use crate::clip::クリップ;
use crate::stack::クリップスタック;
use crate::stack_layout::開始位置付きのクリップ;
use crate::time::{タイムライン上の秒, 時刻};
use crate::timeline_result::タイムライン上の位置で再生するもの;

/// 前のクリップの探索結果とは、現在の位置の前にある再生できるクリップを探した結果のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 前のクリップの探索結果<'スタック> {
    /// 前の再生できるクリップがあった。
    見つかった {
        /// 前の再生できるクリップ。
        クリップ: &'スタック クリップ,
        /// そのクリップのタイムライン上の開始位置。
        開始位置: タイムライン上の秒,
    },
    /// 現在のクリップより前に再生できるクリップが無い。
    先頭にいる {
        /// 現在のクリップ。
        クリップ: &'スタック クリップ,
        /// 現在のクリップのタイムライン上の開始位置。
        開始位置: タイムライン上の秒,
    },
    /// 現在の位置に当たるクリップが無い。
    現在の位置にクリップが無い,
}

impl クリップスタック {
    /// タイムライン上の位置に当たるクリップの、前にある再生できるクリップを探す。位置がタイムラインの末尾以降なら、
    /// 最後の再生できるクリップを現在のクリップとみなす(末尾で止めた画面は最後のクリップの最後のコマを映しているため)。
    pub fn 前の再生できるクリップを探す(
        &self,
        位置: タイムライン上の秒,
    ) -> 前のクリップの探索結果<'_> {
        let Some(現在) = self.位置に当たる再生できるクリップ(位置) else {
            return 前のクリップの探索結果::現在の位置にクリップが無い;
        };
        self.開始位置付きで並べる()
            .take(現在.番号)
            .filter(|並び| 並び.クリップ.再生できるか())
            .last()
            .map_or(
                前のクリップの探索結果::先頭にいる {
                    クリップ: 現在.クリップ,
                    開始位置: 現在.開始位置,
                },
                |並び| 前のクリップの探索結果::見つかった {
                    クリップ: 並び.クリップ,
                    開始位置: 並び.開始位置,
                },
            )
    }

    /// 位置に当たる再生できるクリップを、開始位置と番号とともに返す。末尾以降なら最後の再生できるクリップである。
    fn 位置に当たる再生できるクリップ(
        &self,
        位置: タイムライン上の秒,
    ) -> Option<開始位置付きのクリップ<'_>> {
        let 番号 = match self.タイムライン上の位置で再生するものを求める(位置)
        {
            タイムライン上の位置で再生するもの::クリップがある(
                再生の中身,
            ) => 再生の中身.スタック内の番号,
            タイムライン上の位置で再生するもの::クリップが無い
                if 位置 >= 時刻::先頭.進める(self.合計の占有時間()) =>
            {
                self.一覧().iter().rposition(クリップ::再生できるか)?
            }
            タイムライン上の位置で再生するもの::クリップが無い => {
                return None;
            }
        };
        self.開始位置付きで並べる().nth(番号)
    }
}
