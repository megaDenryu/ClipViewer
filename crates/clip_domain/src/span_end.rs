//! 区間の終わりの行き先の規則。今映している区間の終わりに達したとき、再生がどの区間のどこへ続くかを求める。
//! 音を鳴らす側は、区間の終わりで画面の時計を待たずに行き先へ移るため、時計の規則そのもので少し先まで進めて答えを先に求める。
//! 参照: _doc/設計/アーキテクチャ.md 判断6・判断8

use crate::duration::時間の長さ;
use crate::playback_clock::{
    再生速度, 時計を進めた結果, 時計を進める条件, 末尾での振る舞い
};
use crate::playback_position::再生位置;
use crate::time::タイムライン上の秒;
use crate::timeline_result::タイムライン上の位置で再生するもの;
use crate::video_span::動画上の区間;

/// 区間の終わりの行き先とは、今映している区間の終わりに達したとき、再生がどこへ続くかの区別のことである。
/// 元動画再生では動画の全体を1つの区間とみなす。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 区間の終わりの行き先 {
    /// 同じ区間の開始へ戻って繰り返す。
    区間の開始へ戻る,
    /// 別の区間の開始へ進む。
    別の区間へ進む(動画上の区間),
    /// 再生が止まる。
    止まる,
}

impl 再生位置 {
    /// この位置で映している区間の終わりの行き先を求める。単独クリップ再生は常に開始へ戻り、
    /// 元動画再生は全体の末尾での振る舞いに従い、シーケンス再生は周回と待ちと次のクリップから決める。
    pub fn 区間の終わりの行き先(
        &self,
        条件: &時計を進める条件<'_>,
    ) -> 区間の終わりの行き先 {
        match self {
            Self::単独クリップ再生(_) => {
                区間の終わりの行き先::区間の開始へ戻る
            }
            Self::元動画再生(_) => match 条件.全体の末尾 {
                末尾での振る舞い::先頭へ戻る => {
                    区間の終わりの行き先::区間の開始へ戻る
                }
                末尾での振る舞い::止まる => 区間の終わりの行き先::止まる,
            },
            Self::シーケンス再生(位置) => {
                条件.シーケンスの周回の終わりの行き先(*位置)
            }
        }
    }
}

impl 時計を進める条件<'_> {
    /// シーケンス再生で、位置に当たるクリップの今の周回の終わりの行き先を、時計の規則から求める。
    /// 周回の終わりを丸めの許容誤差だけ越える長さだけ等倍で時計を進め、映すクリップの区間が同じなら開始へ戻る、違えば別の区間へ進む、
    /// 末尾で止まれば止まるとする。時計の規則(待つクリップの最後の周回を繰り返すこと・全体の末尾)を二重に書かないためである。
    fn シーケンスの周回の終わりの行き先(
        &self,
        位置: タイムライン上の秒,
    ) -> 区間の終わりの行き先 {
        let 中身 = match self
            .スタック
            .タイムライン上の位置で再生するものを求める(位置)
        {
            タイムライン上の位置で再生するもの::クリップがある(中身) => {
                中身
            }
            タイムライン上の位置で再生するもの::クリップが無い => {
                return 区間の終わりの行き先::止まる;
            }
        };
        let 区間 = 中身.対象クリップ.区間;
        let 周回の中の位置 = 中身.動画上の位置.起点から経過した長さ(区間.開始());
        // 周回の終わりちょうどでなく、次の周回やクリップの頭へ確かに入る位置を求めるため、丸めの許容誤差だけ越えて進める。
        let 進める長さ = 区間
            .長さ()
            .差し引く(周回の中の位置)
            .足す(時間の長さ::丸めの許容誤差);
        let 等倍の条件 = 時計を進める条件 {
            速度: 再生速度::等倍,
            ..*self
        };
        let 進めた位置 = match 再生位置::シーケンス再生(位置)
            .実時間の経過で進める(進める長さ, &等倍の条件)
        {
            時計を進めた結果::続ける(再生位置::シーケンス再生(進めた位置)) => {
                進めた位置
            }
            時計を進めた結果::続ける(_) | 時計を進めた結果::末尾で止まる(_) =>
            {
                return 区間の終わりの行き先::止まる;
            }
        };
        match self.スタック.表示するコマを求める(進めた位置) {
            Some(コマ) if コマ.クリップ.区間 == 区間 => {
                区間の終わりの行き先::区間の開始へ戻る
            }
            Some(コマ) => {
                区間の終わりの行き先::別の区間へ進む(コマ.クリップ.区間)
            }
            None => 区間の終わりの行き先::止まる,
        }
    }
}
