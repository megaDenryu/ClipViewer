//! クリップから次のクリップへ進む条件と、次へ進めるための利用者の操作。

/// トリガーとは、クリップの再生を終えて次のクリップへ進むための条件のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum トリガー {
    /// 利用者の操作を待たずに進む。
    #[default]
    自動進行,
    /// Enterキーが押されるまで待つ。
    Enterキー待ち,
    /// 移植元の Space待ち。このアプリは Space を再生と停止に使うため、Enterキー待ちと同じく Enterキーで進む。
    /// 移植元の設定ファイルとライブラリのファイルを読み書きするため、データとしては区別して残す。
    Spaceキー待ち,
    /// 出力画面がクリックされるまで待つ。
    クリック待ち,
}

/// 進める操作とは、利用者が次のクリップへ進めるために行う操作の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 進める操作 {
    /// 次へボタン(Next)。どのクリップでも進める。
    次へボタン,
    /// Enterキー。
    Enterキー,
    /// 出力画面のクリック。
    出力のクリック,
}

impl トリガー {
    /// 次へ進むのに利用者の操作が必要か。
    pub fn 利用者の操作が必要か(self) -> bool {
        !matches!(self, Self::自動進行)
    }

    /// この操作で進むか。次へボタンは常に進む。キーとクリックはトリガーと合うときだけ進む。Space待ちは Enterキーで進む。
    pub fn この操作で進むか(self, 操作: 進める操作) -> bool {
        matches!(
            (self, 操作),
            (_, 進める操作::次へボタン)
                | (
                    Self::Enterキー待ち | Self::Spaceキー待ち,
                    進める操作::Enterキー
                )
                | (Self::クリック待ち, 進める操作::出力のクリック)
        )
    }
}
