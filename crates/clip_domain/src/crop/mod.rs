//! クロップ範囲の値オブジェクト。座標と大きさはすべて元の動画に対する百分率で持つ。クロップ枠のドラッグによる移動と大きさの変更は子の `drag.rs` に置く。

mod drag;

pub use drag::クロップの移動量;

use crate::frame::枠の最小の大きさ;
use crate::percent::{元の動画に対する, 百分率};
use crate::pixel::画素の寸法;

/// クロップ範囲とは、元の動画から出力へ切り出す矩形のことであり、座標と大きさを元の動画に対する百分率で持つ。
/// 不変条件: 左端と上端は0以上100以下、幅と高さは5以上100以下である。
/// 注意: 左端+幅が100以下であることは不変条件に含めない。移植元の設定ファイルの読み込みがこれを保証しないためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct クロップ範囲 {
    左端: 百分率<元の動画に対する>,
    上端: 百分率<元の動画に対する>,
    幅: 百分率<元の動画に対する>,
    高さ: 百分率<元の動画に対する>,
}

impl クロップ範囲 {
    /// 元の動画全体を切り出すクロップ範囲。
    pub const 全体: Self = Self {
        左端: 百分率::ゼロ,
        上端: 百分率::ゼロ,
        幅: 百分率::全体,
        高さ: 百分率::全体,
    };

    /// 各値を範囲へ収めて作成する。左端と上端は0以上100以下、幅と高さは5以上100以下へ収める。
    /// 移植元の `クロップ範囲を生成する` と同じ規則である。
    pub fn 各値を範囲へ収めて作成する(
        左端: f64,
        上端: f64,
        幅: f64,
        高さ: f64,
    ) -> Self {
        Self {
            左端: 百分率::範囲へ収める(左端),
            上端: 百分率::範囲へ収める(上端),
            幅: 百分率::下限と上限の間へ収める(幅, 枠の最小の大きさ, 100.0),
            高さ: 百分率::下限と上限の間へ収める(高さ, 枠の最小の大きさ, 100.0),
        }
    }

    /// 不変条件を満たすことを呼び出し側が保証した値から作る。
    /// 注意: 幅と高さは5以上であること。移動と大きさの変更の計算だけが使う。
    pub(crate) fn 検査済みの値から作る(
        左端: 百分率<元の動画に対する>,
        上端: 百分率<元の動画に対する>,
        幅: 百分率<元の動画に対する>,
        高さ: 百分率<元の動画に対する>,
    ) -> Self {
        Self {
            左端,
            上端,
            幅,
            高さ,
        }
    }

    /// 左端の位置。
    pub fn 左端(&self) -> 百分率<元の動画に対する> {
        self.左端
    }

    /// 上端の位置。
    pub fn 上端(&self) -> 百分率<元の動画に対する> {
        self.上端
    }

    /// 幅。
    pub fn 幅(&self) -> 百分率<元の動画に対する> {
        self.幅
    }

    /// 高さ。
    pub fn 高さ(&self) -> 百分率<元の動画に対する> {
        self.高さ
    }

    /// 元の動画の画素の寸法から、切り出した後の画素の寸法を求める。
    pub fn 切り出し後の寸法(&self, 元の寸法: 画素の寸法) -> 画素の寸法 {
        元の寸法.割合で縮める(self.幅.割合(), self.高さ.割合())
    }
}
