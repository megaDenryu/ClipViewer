//! 再生モード。モードごとにタイムラインの解釈が根本的に異なる。

/// 再生モードとは、再生位置を何に対する位置として解釈するかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum 再生モード {
    /// 有効なクリップを並び順に続けて再生する。位置はタイムライン上の秒である。
    #[default]
    シーケンス再生,
    /// 選択中のクリップの区間だけを再生する。位置はクリップの開始からの経過である。
    単独クリップ再生,
    /// クリップを無視して元の動画全体を再生する。位置は動画上の秒である。
    元動画再生,
}
