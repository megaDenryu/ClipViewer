//! クリップ。スタックに積む最小単位であり、元の動画の区間を切り出し、繰り返し・クロップ・進む条件を持つ。

mod parts;

pub(crate) use parts::クリップの各項目;

use crate::clip_id::クリップ識別子;
use crate::crop::クロップ範囲;
use crate::duration::時間の長さ;
use crate::repeat::{リピート回数, リピート設定};
use crate::time::{動画上の秒, 時刻};
use crate::trigger::トリガー;
use crate::video_span::動画上の区間;

/// クリップ名とは、利用者がクリップに付けた表示用の名前のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct クリップ名(String);

impl クリップ名 {
    /// 文字列から作成する。空の名前も許す(移植元の編集画面が許すため)。
    pub fn 作成する(名前: String) -> Self {
        Self(名前)
    }

    /// 名前の文字列を返す。表示や設定ファイルへ渡す境界で使う。
    pub fn 文字列(&self) -> &str {
        &self.0
    }
}

/// クリップとは、元の動画の区間を切り出し、繰り返し・クロップ・次へ進む条件を持つ、スタックの最小単位のことである。
/// 識別子だけは作成後に変えられない。スタックが識別子でクリップを指すためである。
/// 他の属性はそれぞれの型が不変条件を持つため、公開のフィールドとして直接書き換えてよい。
#[derive(Debug, Clone, PartialEq)]
pub struct クリップ {
    識別子: クリップ識別子,
    /// 表示用の名前。
    pub 名前: クリップ名,
    /// 偽ならシーケンス再生で飛ばし、タイムライン上の時間を占めない。
    pub 有効か: bool,
    /// 元の動画から切り出す区間。
    pub 区間: 動画上の区間,
    /// 区間の繰り返し方。
    pub リピート: リピート設定,
    /// 出力へ切り出す矩形。
    pub クロップ: クロップ範囲,
    /// 次のクリップへ進む条件。
    pub トリガー: トリガー,
}

impl クリップ {
    /// 移植元の `クリップモディファイアを生成する` と同じ既定値で作成する。
    /// 既定値は、有効・0秒から5秒の区間・1回・全体のクロップ・自動進行である。
    pub fn 既定値で作成する(
        識別子: クリップ識別子, 名前: クリップ名
    ) -> Self {
        let 五秒 = 時間の長さ::検査済みの秒数から作る(5.0);
        Self {
            識別子,
            名前,
            有効か: true,
            区間: 動画上の区間::開始と長さから作る(時刻::先頭, 五秒),
            リピート: リピート設定::回数指定(リピート回数::一回),
            クロップ: クロップ範囲::全体,
            トリガー: トリガー::自動進行,
        }
    }

    /// 識別子。
    pub fn 識別子(&self) -> &クリップ識別子 {
        &self.識別子
    }

    /// タイムライン上で占める時間。無効なら0秒、有効なら区間の長さ×タイムライン上の周回数である。
    /// 無限ループはタイムライン上では1周分だけを占め、繰り返しは再生の時計が1周ずつ戻して作る。
    pub fn 占有時間(&self) -> 時間の長さ {
        if !self.有効か {
            return 時間の長さ::ゼロ;
        }
        self.タイムライン上の周回数()
            .リピートした長さ(self.区間.長さ())
    }

    /// 再生できるか。有効で、区間の長さが0でなければ再生できる。
    /// 長さ0のクリップはタイムライン上の時間を占めず、映すコマも無いため、次へ進む先に選ばない。
    pub fn 再生できるか(&self) -> bool {
        self.有効か && !self.区間.長さ().ゼロか()
    }

    /// 単独クリップ再生で、区間の開始からの経過に対応する動画上の位置を求める。区間の外へは出ない。
    pub fn 単独再生での動画上の位置(
        &self,
        開始からの経過: 時間の長さ,
    ) -> 動画上の秒 {
        self.区間
            .位置を区間の中へ収める(self.区間.開始().進める(開始からの経過))
    }
}
