//! 重ね合わせの部品一式から重ね合わせを組み立てられない理由。

use super::error::重ね合わせの操作エラー;
use super::rows::{同時に重ねられる行の数, 行の番号};

/// 重ね合わせを組み立てられない理由とは、重ね合わせの部品一式が重ね合わせの不変条件を満たさず、重ね合わせへ変えられない理由のことである。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 重ね合わせを組み立てられない理由 {
    /// 行の数が同時に重ねられる行の数を超える。
    #[error("行が{行の数}つある(行は{}つまで)", 同時に重ねられる行の数)]
    行の数が上限を超える {
        /// 部品一式が持つ行の数。
        行の数: usize,
    },
    /// 行の番号の行の、行の中の位置(0から数える)の置いたクリップを置けない。
    #[error("行の番号{}の行の{位置}番目(0から数える)の置いたクリップを置けない: {理由}", 行.番号())]
    置いたクリップを置けない {
        /// 置こうとした行の番号。
        行: 行の番号,
        /// 部品一式の行の中の位置(0から数える)。
        位置: usize,
        /// 置けない理由(識別子の重複・動画の番号が表に無い・区間の長さが0・時間が重なる)。
        理由: 重ね合わせの操作エラー,
    },
}
