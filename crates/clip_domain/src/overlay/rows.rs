//! タイムラインの行の並び。行の数の上限と、行の中で時間が重ならないことを守る型と、その中身を読む口。
//! 置く操作は `rows_place.rs`、置いたクリップを動かす・書き換える・取り除く操作は `rows_edit.rs` に置く。

use super::basis::重ね合わせ上の秒;
use super::error::重ね合わせの操作エラー;
use super::placed::置いたクリップ;
use super::placed_id::置いたクリップの識別子;
use super::row::{タイムラインの行, 行の番号};
use crate::time::時刻;

/// 同時に重ねられる行の数とは、1つの重ね合わせが持てるタイムラインの行の数の上限のことである。
/// 根拠は同時再生.md 5-4 であり、行ごとの音の再生器の配列の大きさもこの値から決める。
pub const 同時に重ねられる行の数: usize = 8;

/// タイムラインの行の並びとは、重ね合わせのタイムラインの行を、奥から手前の順に並べたもののことである。
/// 先頭の行が最も奥、末尾の行が最も手前に映る。
/// 不変条件: 行の数は同時に重ねられる行の数以下である。どの行も、置いたクリップが始まりの時刻の順に並び、
/// 占める時間が重ならない。置いたクリップの識別子は、すべての行を通して重ならない(新しい識別子は置く前に重ね合わせが確かめる)。
/// 中身を変える操作は、確かめを全部済ませてから変えるため、拒んだときは操作の前のまま残る。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct タイムラインの行の並び {
    行の並び: Vec<タイムラインの行>,
}

/// 置いてある場所とは、置いたクリップがどの行の、行の中のどの位置にあるかの組のことである。
/// 動かす・書き換える・取り除く操作が、置いたクリップを1回だけ探して使うために置く。
pub(super) struct 置いてある場所 {
    pub(super) 行: 行の番号,
    pub(super) 行の中の位置: usize,
}

impl タイムラインの行の並び {
    /// 奥から手前の順のタイムラインの行。
    pub fn 奥から手前の順の行(&self) -> &[タイムラインの行] {
        &self.行の並び
    }

    /// 行の数。
    pub fn 行の数(&self) -> usize {
        self.行の並び.len()
    }

    /// 識別子の置いたクリップを探す。
    pub fn 識別子で探す(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Option<&置いたクリップ> {
        self.行の並び.iter().find_map(|行| 行.識別子で探す(識別子))
    }

    /// 識別子の置いたクリップがある行の番号。無ければ置いたクリップが見つからないとして拒む。
    pub fn 置いてある行の番号(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Result<行の番号, 重ね合わせの操作エラー> {
        self.置いてある場所を探す(識別子).map(|場所| 場所.行)
    }

    /// すべての置いたクリップの終わりの時刻のうち最も遅い時刻。置いたクリップが無ければ0秒である。
    pub fn 最も遅い終わりの時刻(&self) -> 重ね合わせ上の秒 {
        self.行の並び
            .iter()
            .flat_map(|行| {
                行.置いたクリップの並び()
                    .iter()
                    .map(置いたクリップ::終わりの時刻)
            })
            .fold(時刻::先頭, |最も遅い, 終わり| {
                if 終わり > 最も遅い {
                    終わり
                } else {
                    最も遅い
                }
            })
    }

    pub(super) fn 置いてある場所を探す(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Result<置いてある場所, 重ね合わせの操作エラー> {
        self.行の並び
            .iter()
            .enumerate()
            .find_map(|(行, 中身)| {
                中身
                    .識別子の位置(識別子)
                    .map(|行の中の位置| 置いてある場所 {
                        行: 行の番号::番号から作成する(行),
                        行の中の位置,
                    })
            })
            .ok_or_else(|| {
                重ね合わせの操作エラー::置いたクリップが見つからない(
                    識別子.clone(),
                )
            })
    }

    pub(super) fn 行(&self, 行: 行の番号) -> &タイムラインの行 {
        &self.行の並び[行.番号()]
    }

    pub(super) fn 行を書き換えるために借りる(
        &mut self,
        行: 行の番号,
    ) -> &mut タイムラインの行 {
        &mut self.行の並び[行.番号()]
    }

    pub(super) fn 手前に空の行を足す(&mut self) -> 行の番号 {
        self.行の並び.push(タイムラインの行::default());
        行の番号::番号から作成する(self.行の並び.len() - 1)
    }
}
