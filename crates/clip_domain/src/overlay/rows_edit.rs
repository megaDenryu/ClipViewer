//! タイムラインの行の並びに置いてある置いたクリップを、動かす・書き換える・取り除く操作。
//! どの操作も置いてある場所を1回だけ探し、確かめを全部済ませてから中身を変える。

use super::basis::重ね合わせ上の秒;
use super::error::重ね合わせの操作エラー;
use super::placed::置いたクリップ;
use super::placed_id::置いたクリップの識別子;
use super::row::行の番号;
use super::rows::タイムラインの行の並び;

impl タイムラインの行の並び {
    /// 置いたクリップを、先の行の始まりの時刻へ動かす。先の行が無いとき、先の行でほかの置いたクリップと時間が重なるときは拒む。
    pub(super) fn 置いたクリップを動かす(
        &mut self,
        識別子: &置いたクリップの識別子,
        先の行: 行の番号,
        始まりの時刻: 重ね合わせ上の秒,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let 場所 = self.置いてある場所を探す(識別子)?;
        if 先の行.番号() >= self.行の数() {
            return Err(重ね合わせの操作エラー::行の番号が範囲の外 {
                行: 先の行,
                行の数: self.行の数(),
            });
        }
        let 元の行 = self.行(場所.行);
        let 占める長さ = 元の行.置いたクリップの並び()[場所.行の中の位置].占める長さ();
        let 先 = self.行(先の行);
        if let Some(相手) = 先.時間が重なる置いたクリップを探す(
            始まりの時刻,
            占める長さ,
            Some(識別子),
        ) {
            return Err(重ね合わせの操作エラー::時間が重なる {
                行: 先の行,
                相手: 相手.識別子().clone(),
            });
        }
        let mut 動かすもの = self
            .行を書き換えるために借りる(場所.行)
            .位置から取り出す(場所.行の中の位置);
        動かすもの.始まりの時刻を変える(始まりの時刻);
        self.行を書き換えるために借りる(先の行).差し込む(動かすもの);
        Ok(())
    }

    /// 置いたクリップを、始まりの時刻にかかわらない値(映す矩形・音の設定)を書き換えるために借りる。無ければ拒む。
    pub(super) fn 置いたクリップを書き換えるために借りる(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) -> Result<&mut 置いたクリップ, 重ね合わせの操作エラー> {
        let 場所 = self.置いてある場所を探す(識別子)?;
        Ok(self
            .行を書き換えるために借りる(場所.行)
            .位置で書き換えるために借りる(場所.行の中の位置))
    }

    /// 置いたクリップを取り除き、取り除いたものを返す。行は空になっても残す(ほかの行の番号と重なりの順を変えないため)。
    pub(super) fn 置いたクリップを取り除く(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) -> Result<置いたクリップ, 重ね合わせの操作エラー> {
        let 場所 = self.置いてある場所を探す(識別子)?;
        Ok(self
            .行を書き換えるために借りる(場所.行)
            .位置から取り出す(場所.行の中の位置))
    }
}
