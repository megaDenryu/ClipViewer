//! 塊のドラッグでずらす量。始まりの時刻を後ろか前へずらす量と、行を手前か奥へずらす行の数を、裸の符号付きの数で渡さずに型で表す。
//! 時刻は0秒より前へ行かず、行の差は行の数へ収めてから使う(収めるのはタイムラインの行の並び)。参照: _doc/設計/同時再生.md 2-6

use crate::duration::{時間の値エラー, 時間の長さ};
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::rows::行の番号;

/// 時刻をずらす量とは、重ね合わせ上の時刻を後ろ(遅い方)か前(早い方)へずらす長さのことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 時刻をずらす量 {
    /// 後ろへずらす。
    後ろへ(時間の長さ),
    /// 前へずらす。
    前へ(時間の長さ),
}

impl 時刻をずらす量 {
    /// 符号付きの秒数(後ろへが正)から作成する。有限でない値を拒む。
    pub fn 符号付きの秒数から作成する(
        秒: f64
    ) -> Result<Self, 時間の値エラー> {
        if 秒 >= 0.0 {
            時間の長さ::作成する(秒).map(Self::後ろへ)
        } else {
            時間の長さ::作成する(-秒).map(Self::前へ)
        }
    }

    /// 時刻をこの量だけずらす。前へずらすときは0秒より前へ行かない。
    pub fn ずらした時刻を求める(
        self,
        時刻: 重ね合わせ上の秒,
    ) -> 重ね合わせ上の秒 {
        match self {
            Self::後ろへ(長さ) => 時刻.進める(長さ),
            Self::前へ(長さ) => 時刻.戻す(長さ),
        }
    }
}

/// 行の差とは、置いたクリップを手前の行(番号の大きい方)へ動かした行の数のことであり、奥の行へ動かしたときは負である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[repr(transparent)]
pub struct 行の差(i32);

impl 行の差 {
    /// 手前へ動かした行の数(奥へは負)から作成する。
    pub fn 手前へ動かした行の数から作成する(行の数: i32) -> Self {
        Self(行の数)
    }
}

impl 行の番号 {
    /// 行の差だけ動かし、0番から最も手前の行までへ収めた行の番号。
    pub(in crate::overlay) fn 行の差だけ動かして収める(
        self,
        差: 行の差,
        最も手前: 行の番号,
    ) -> 行の番号 {
        // 注意: i32 の大きさの数は usize に収まる(このクレートは32ビット以上の計算機だけを相手にする)。
        let 大きさ = usize::try_from(差.0.unsigned_abs()).unwrap_or(usize::MAX);
        let 動かした = if 差.0 < 0 {
            self.番号().saturating_sub(大きさ)
        } else {
            self.番号().saturating_add(大きさ)
        };
        行の番号::番号から作成する(動かした.min(最も手前.番号()))
    }
}
