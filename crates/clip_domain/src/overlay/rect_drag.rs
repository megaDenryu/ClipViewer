//! 映す矩形のドラッグによる移動と、四隅のつまみによる大きさの変更。縦横比を保たない移動と大きさの変更は、クロップ枠と同じ百分率の枠の規則
//! (`frame_drag.rs`)に委ね、縦横比を保つ大きさの変更(`frame_aspect.rs`)は、置いたクリップの絵の形の縦横比を重ねる画面の上で保つ。
//! 参照: _doc/設計/同時再生.md 2-4

use super::aspect::重ねる画面の縦横比;
use super::basis::重ねる画面に対する;
use super::rect::映す矩形;
use crate::frame::{四隅のつまみ, 枠の移動量, 百分率の枠};
use crate::pixel::縦横比;

/// 映す矩形の移動量とは、ドラッグの開始点からの移動を、重ねる画面の幅・高さに対する百分率で表したもののことである。
pub type 映す矩形の移動量 = 枠の移動量<重ねる画面に対する>;

impl 映す矩形 {
    /// ドラッグの開始時の映す矩形を移動量だけ動かす。大きさは変えず、重ねる画面の外へ出ないよう収める(クロップ枠と同じ規則)。
    pub fn 移動する(&self, 移動量: 映す矩形の移動量) -> Self {
        Self::枠から作る(self.枠にする().移動する(移動量))
    }

    /// ドラッグの開始時の映す矩形を、つまみの角を移動量だけ動かして大きさを変える。幅と高さは5%以上に保ち、重ねる画面の外へ出ない
    /// (クロップ枠と同じ規則)。縦横比は保たない。
    pub fn つまみで大きさを変える(
        &self,
        つまみ: 四隅のつまみ,
        移動量: 映す矩形の移動量,
    ) -> Self {
        Self::枠から作る(self.枠にする().つまみで大きさを変える(つまみ, 移動量))
    }

    /// ドラッグの開始時の映す矩形を、掴んだ隅の向かいの隅を動かさずに、重ねる画面の上で絵の縦横比(幅÷高さ。画素で測った形)になる大きさへ変える。
    /// 映す矩形は重ねる画面に対する百分率で持つため、百分率の幅÷高さは絵の縦横比を重ねる画面の縦横比で割った値になる。
    /// 割った比が有限で正でない(絵の幅が0の)ときと、掴んだ隅の向かいの隅から画面の端までの空きがその比のまま5%以上を保てないときは、縦横比を保たない大きさの変更にする。
    pub fn 縦横比を保ってつまみで大きさを変える(
        &self,
        つまみ: 四隅のつまみ,
        移動量: 映す矩形の移動量,
        絵の縦横比: 縦横比,
        画面の縦横比: 重ねる画面の縦横比,
    ) -> Self {
        match 絵の縦横比.割る(画面の縦横比.縦横比()) {
            Some(百分率の比) => {
                Self::枠から作る(self.枠にする().縦横比を保ってつまみで大きさを変える(
                    つまみ,
                    移動量,
                    百分率の比,
                ))
            }
            None => self.つまみで大きさを変える(つまみ, 移動量),
        }
    }

    /// ドラッグの開始時の映す矩形を、掴んだ隅の向かいの隅を動かさずに、開始時の映す矩形と同じ形(百分率の幅÷高さ)のまま大きさを変える。
    /// 絵の縦横比が分からない(動画を開けない)ときに、縦横比を保つ大きさの変更の代わりに使う。
    pub fn 今の形を保ってつまみで大きさを変える(
        &self,
        つまみ: 四隅のつまみ,
        移動量: 映す矩形の移動量,
    ) -> Self {
        match 縦横比::幅と高さから求める(self.幅().数値(), self.高さ().数値()) {
            Some(百分率の比) => {
                Self::枠から作る(self.枠にする().縦横比を保ってつまみで大きさを変える(
                    つまみ,
                    移動量,
                    百分率の比,
                ))
            }
            None => {
                panic!("映す矩形の幅と高さは5%以上なので形の比は有限で正である(到達したらバグ)")
            }
        }
    }

    fn 枠にする(&self) -> 百分率の枠<重ねる画面に対する> {
        百分率の枠 {
            左端: self.左端(),
            上端: self.上端(),
            幅: self.幅(),
            高さ: self.高さ(),
        }
    }

    // 百分率の枠の移動と大きさの変更の結果は、幅と高さが5%以上で、左端+幅と上端+高さが丸めても100を超えない(`百分率の枠` の注意)。
    fn 枠から作る(枠: 百分率の枠<重ねる画面に対する>) -> Self {
        match Self::作成する(枠.左端, 枠.上端, 枠.幅, 枠.高さ) {
            Ok(矩形) => 矩形,
            Err(エラー) => {
                panic!("百分率の枠の規則が映す矩形の不変条件を満たさない(到達したらバグ): {エラー}")
            }
        }
    }
}
