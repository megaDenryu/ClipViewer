//! 使う動画の表と、表の中の1本を指す動画の番号。

use crate::video_path::正規化した動画パス;

/// 動画の番号とは、使う動画の表の中で、1本の動画を指す0から始まる番号のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(transparent)]
pub struct 動画の番号(usize);

impl 動画の番号 {
    /// 最初とは、使う動画の表の先頭の動画を指す番号(0番)のことである。
    pub const 最初: Self = Self(0);

    /// 0から数えた番号から作成する。表にあるかは、置く操作が表と照らして確かめる。
    pub fn 番号から作成する(番号: usize) -> Self {
        Self(番号)
    }

    /// 0から数えた番号を返す。表示やファイルへ書く境界で使う。
    pub fn 番号(self) -> usize {
        self.0
    }
}

/// 使う動画の表とは、重ね合わせが使う動画のパスを、動画の番号で指せる並びのことである。
/// どの置いたクリップも使っていない動画を持ってもよい(別々の動画のクリップを置くとき、先に表へ足してから置くため)。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 使う動画の表 {
    動画の並び: Vec<正規化した動画パス>,
}

impl 使う動画の表 {
    /// 1本の動画だけを持つ表を作成する。その動画の番号は `動画の番号::最初` である。
    pub fn 一本の動画から作成する(動画: 正規化した動画パス) -> Self {
        Self {
            動画の並び: vec![動画],
        }
    }

    /// 動画のパスの並びから作成する。並びの順の位置がそのまま動画の番号になる。
    pub fn 並びから作成する(動画の並び: Vec<正規化した動画パス>) -> Self {
        Self { 動画の並び }
    }

    /// 番号の動画のパス。表に無い番号なら無い。
    pub fn 動画のパス(&self, 番号: 動画の番号) -> Option<&正規化した動画パス> {
        self.動画の並び.get(番号.0)
    }

    /// 番号の動画が表にあるか。
    pub fn 持っているか(&self, 番号: 動画の番号) -> bool {
        番号.0 < self.動画の並び.len()
    }

    /// 表にある動画の数。
    pub fn 動画の数(&self) -> usize {
        self.動画の並び.len()
    }

    /// 番号の順の動画のパスの並び。
    pub fn 動画のパスの並び(&self) -> &[正規化した動画パス] {
        &self.動画の並び
    }
}
