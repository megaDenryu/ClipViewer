//! タイムラインの行と、重ね合わせの中の行を指す番号。

use super::basis::重ね合わせの上の秒;
use super::placed::置いたクリップ;
use super::placed_id::置いたクリップの識別子;
use crate::duration::時間の長さ;

/// 行の番号とは、重ね合わせのタイムラインの行の並びの中で、1つの行を指す0から始まる番号のことである。
/// 0番が最も奥であり、番号が大きい行ほど重ねる画面の手前に映る。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(transparent)]
pub struct 行の番号(usize);

impl 行の番号 {
    /// 0から数えた番号から作成する。重ね合わせにあるかは、操作が行の数と照らして確かめる。
    pub fn 番号から作成する(番号: usize) -> Self {
        Self(番号)
    }

    /// 0から数えた番号を返す。表示や画面の行の位置へ渡す境界で使う。
    pub fn 番号(self) -> usize {
        self.0
    }
}

/// タイムラインの行とは、タイムラインの横1本の帯であり、時間の重ならない置いたクリップを始まりの時刻の順に並べたもののことである。
/// 1つの行は、同時に高々1つの置いたクリップを映し、1つの音を鳴らす。
/// 不変条件: 置いたクリップは始まりの時刻の順に並び、占める時間が重ならない。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct タイムラインの行 {
    並び: Vec<置いたクリップ>,
}

impl タイムラインの行 {
    /// 始まりの時刻の順の置いたクリップ。
    pub fn 並び(&self) -> &[置いたクリップ] {
        &self.並び
    }

    /// 識別子の置いたクリップを探す。
    pub fn 識別子で探す(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Option<&置いたクリップ> {
        self.並び.iter().find(|置いた| 置いた.識別子() == 識別子)
    }

    /// 始まりから長さの間に重なる置いたクリップのうち、除く識別子でない最初のもの。無ければこの行はその間空いている。
    pub(crate) fn 重なる相手(
        &self,
        始まり: 重ね合わせの上の秒,
        長さ: 時間の長さ,
        除く識別子: Option<&置いたクリップの識別子>,
    ) -> Option<&置いたクリップ> {
        self.並び.iter().find(|置いた| {
            Some(置いた.識別子()) != 除く識別子 && 置いた.時間が重なるか(始まり, 長さ)
        })
    }

    /// 始まりの時刻の順を保つ位置へ差し込む。
    /// 注意: 重なる相手が無いことを、呼び出し側が `重なる相手` で確かめてから呼ぶこと。
    pub(crate) fn 差し込む(&mut self, 置いた: 置いたクリップ) {
        let 位置 = self
            .並び
            .partition_point(|先| 先.始まりの時刻() <= 置いた.始まりの時刻());
        self.並び.insert(位置, 置いた);
    }

    /// 識別子の置いたクリップを並びから取り出す。無ければ無い。
    pub(crate) fn 取り出す(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) -> Option<置いたクリップ> {
        let 位置 = self
            .並び
            .iter()
            .position(|置いた| 置いた.識別子() == 識別子)?;
        Some(self.並び.remove(位置))
    }

    pub(crate) fn 識別子で探して変える(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) -> Option<&mut 置いたクリップ> {
        self.並び
            .iter_mut()
            .find(|置いた| 置いた.識別子() == 識別子)
    }
}
