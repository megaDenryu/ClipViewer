//! 重ね合わせの部品一式。重ね合わせを成す値を、不変条件を確かめる前の形で隠さずに並べた組である。
//! ファイルから読んだ値から重ね合わせを組み立てるとき(`重ね合わせの部品一式::重ね合わせへ組み立てる`)と、重ね合わせを書き出すとき(`重ね合わせ::部品一式を複製する`)に受け渡す。
//! 保存の形式との変換はこの組を `..` を使わずに分解・組み立てるため、重ね合わせに項目を足すと変換の側がコンパイルエラーになる。
//! 参照: _doc/設計/同時再生.md 4-1・4-2

use super::aspect::重ねる画面の縦横比;
use super::basis::重ね合わせ上の秒;
use super::inherited::クリップから受け継いだ値;
use super::placed_id::置いたクリップの識別子;
use super::rect::映す矩形;
use super::video_table::{使う動画の表, 動画の番号};
use super::volume::置いたクリップの音の設定;

/// 重ね合わせの部品一式とは、重ねる画面の縦横比と使う動画の表と、奥から手前の順の行ごとの置いたクリップの値を、
/// 行の数の上限・行の中の時間の重なり・識別子の重なり・動画の番号を確かめる前の形で並べたもののことである。
/// 完成した重ね合わせが持ってはならない半端な値を代わりに持ち、`重ね合わせへ組み立てる` だけが重ね合わせへ変える(規約のビルダー)。
#[derive(Debug, Clone, PartialEq)]
pub struct 重ね合わせの部品一式 {
    /// 重ねる画面の縦横比。
    pub 縦横比: 重ねる画面の縦横比,
    /// 使う動画の表。
    pub 動画の表: 使う動画の表,
    /// 奥(先頭)から手前(末尾)の順の行。
    pub 行の並び: Vec<タイムラインの行の部品一式>,
}

/// タイムラインの行の部品一式とは、1つの行に置く置いたクリップの値の並びのことである。並びの順は問わず、組み立てるときに始まりの時刻の順へ並べる。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct タイムラインの行の部品一式 {
    /// 行に置く置いたクリップの値。
    pub 置いたクリップの並び: Vec<置いたクリップの部品一式>,
}

/// 置いたクリップの部品一式とは、置いたクリップを成すすべての項目(識別子・受け継いだ値・動画の番号・始まりの時刻・映す矩形・音の設定)を隠さずに並べた組のことである。
#[derive(Debug, Clone, PartialEq)]
pub struct 置いたクリップの部品一式 {
    /// 重ね合わせの中で置いたクリップを指す識別子。
    pub 識別子: 置いたクリップの識別子,
    /// スタックのクリップから受け継いだ名前・区間・リピート回数・クロップ範囲。
    pub 受け継いだ値: クリップから受け継いだ値,
    /// 使う動画の表の中の、この置いたクリップの動画の番号。
    pub 動画: 動画の番号,
    /// 重ね合わせ上で映り始める時刻。
    pub 始まりの時刻: 重ね合わせ上の秒,
    /// 重ねる画面のどこにどの大きさで映すか。
    pub 映す矩形: 映す矩形,
    /// 音量と消音しているか。
    pub 音の設定: 置いたクリップの音の設定,
}

/// 部品の並びの中の位置とは、タイムラインの行の部品一式の置いたクリップの並び(ファイルでは items の並び)の中で、
/// 置いたクリップの部品一式が何番目にあるか(0から数える)のことである。組み立てると行の中は始まりの時刻の順に並べ直すため、
/// 組み立てた後の行の中の順番とは別のものである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(transparent)]
pub struct 部品の並びの中の位置(usize);

impl 部品の並びの中の位置 {
    /// 0から数えた番号から作成する。
    pub fn 番号から作成する(番号: usize) -> Self {
        Self(番号)
    }

    /// 0から数えた番号を返す。表示へ渡す境界で使う。
    pub fn 番号(self) -> usize {
        self.0
    }
}
