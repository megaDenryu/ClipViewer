//! 置いたクリップの音量。

/// 音の大きさとは、置いたクリップの音を元の大きさの何倍で鳴らすかを表す、0以上1以下の値のことである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 音の大きさ(f64);

impl 音の大きさ {
    /// 元の大きさ(1)。新しく置いたクリップの最初の値である。
    pub const 元の大きさ: Self = Self(1.0);

    /// 0未満は0に、1を超える値は1に、非数は0に収めて作成する。つまみの値を受け取る境界で使う。
    pub fn 範囲へ収めて作成する(値: f64) -> Self {
        if 値.is_nan() {
            return Self(0.0);
        }
        Self(値.clamp(0.0, 1.0))
    }

    /// 0以上1以下の値を返す。つまみや音の再生の指示へ渡す境界で使う。
    pub fn 値(self) -> f64 {
        self.0
    }
}

/// 置いたクリップの音量とは、置いたクリップごとの音の大きさと、消音しているかの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 置いたクリップの音量 {
    /// 消音していないときに鳴らす大きさ。
    pub 大きさ: 音の大きさ,
    /// 真なら大きさにかかわらず鳴らさない。
    pub 消音しているか: bool,
}

impl 置いたクリップの音量 {
    /// 新しく置いたクリップの音量。元の大きさで、消音していない。
    pub const 最初の値: Self = Self {
        大きさ: 音の大きさ::元の大きさ,
        消音しているか: false,
    };

    /// 実際に鳴らす大きさ。消音しているなら0である。
    pub fn 鳴らす大きさ(self) -> 音の大きさ {
        if self.消音しているか {
            音の大きさ(0.0)
        } else {
            self.大きさ
        }
    }
}
