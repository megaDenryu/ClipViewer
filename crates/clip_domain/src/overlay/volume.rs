//! 置いたクリップの音の設定。

use crate::volume::音量;

/// 置いたクリップの音の設定とは、置いたクリップごとの音量と、消音しているかの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 置いたクリップの音の設定 {
    /// 消音していないときに鳴らす音量。
    pub 音量: 音量,
    /// 真なら音量にかかわらず鳴らさない。
    pub 消音しているか: bool,
}

impl 置いたクリップの音の設定 {
    /// 最初の値とは、新しく置いたクリップの音の設定のことであり、元の大きさで消音していない。
    pub const 最初の値: Self = Self {
        音量: 音量::元の大きさ,
        消音しているか: false,
    };

    /// 実際に鳴らす音量。消音しているなら無音である。
    pub fn 鳴らす音量(self) -> 音量 {
        if self.消音しているか {
            音量::無音
        } else {
            self.音量
        }
    }
}
