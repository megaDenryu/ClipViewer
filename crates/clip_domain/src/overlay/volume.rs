//! 置いたクリップの音の設定。

use crate::volume::音量;

/// 置いたクリップの音の変更とは、置いたクリップの音の設定に当てる、音量を選ぶか、消音するかしないかを設定するかの区別のことである。
/// 音量を選んでも消音しているかは変えず、消音を設定しても音量は変えない(消音を戻すと前の音量で鳴る)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 置いたクリップの音の変更 {
    /// 消音していないときに鳴らす音量を選ぶ。
    音量を選ぶ(音量),
    /// 真なら消音し、偽なら消音を戻す。
    消音を設定する(bool),
}

/// 置いたクリップの音の設定とは、置いたクリップごとの音量と、消音しているかの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 置いたクリップの音の設定 {
    /// 消音していないときに鳴らす音量。
    pub 音量: 音量,
    /// 真なら音量にかかわらず鳴らさない。
    pub 消音しているか: bool,
}

impl 置いたクリップの音の設定 {
    /// 最初の値とは、新しく置いたクリップの音の設定のことであり、元の大きさで消音していない。
    pub const 最初の値: Self = Self {
        音量: 音量::元の大きさ,
        消音しているか: false,
    };

    /// 変更を当てた音の設定。
    pub fn 変更を当てる(self, 変更: 置いたクリップの音の変更) -> Self {
        match 変更 {
            置いたクリップの音の変更::音量を選ぶ(音量) => {
                Self { 音量, ..self }
            }
            置いたクリップの音の変更::消音を設定する(消音しているか) => {
                Self {
                    消音しているか,
                    ..self
                }
            }
        }
    }

    /// 実際に鳴らす音量。消音しているなら無音である。
    pub fn 鳴らす音量(self) -> 音量 {
        if self.消音しているか {
            音量::無音
        } else {
            self.音量
        }
    }
}
