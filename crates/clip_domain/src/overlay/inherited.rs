//! クリップから受け継いだ値。置いたクリップが持つ値のうち、スタックのクリップから受け継ぐもの。

use crate::clip::{クリップ, クリップ名};
use crate::crop::クロップ範囲;
use crate::duration::時間の長さ;
use crate::repeat::{リピート回数, リピート設定};
use crate::video_span::動画上の区間;

/// クリップから受け継いだ値とは、置いたクリップが持つ値のうち、スタックのクリップから受け継ぐ名前・区間・リピート回数・クロップ範囲の組のことである。
/// 受け継ぐときに値を複製するため、元のクリップを後で直しても変わらない。トリガーと無限ループを持たない(同時再生.md 7節の決定1)。
#[derive(Debug, Clone, PartialEq)]
pub struct クリップから受け継いだ値 {
    /// 表示用の名前。
    pub 名前: クリップ名,
    /// 元の動画から切り出す区間。
    pub 区間: 動画上の区間,
    /// 区間を続けて映す回数。
    pub リピート回数: リピート回数,
    /// 映す矩形へ映す前に切り出す矩形。
    pub クロップ: クロップ範囲,
}

impl クリップから受け継いだ値 {
    /// スタックのクリップの値を受け継ぐ。回数指定はその回数、無限ループは1回にし、トリガーと有効かは受け継がない。
    pub fn クリップから受け継ぐ(クリップ: &クリップ) -> Self {
        let リピート回数 = match クリップ.リピート {
            リピート設定::回数指定(回数) => 回数,
            リピート設定::無限ループ => リピート回数::一回,
        };
        Self {
            名前: クリップ.名前.clone(),
            区間: クリップ.区間,
            リピート回数,
            クロップ: クリップ.クロップ,
        }
    }

    /// 区間の長さにリピート回数を掛けた長さ。この値を受け継いだ置いたクリップが重ね合わせ上で占める長さ(置いたクリップの占める長さ)になる。
    pub fn 占める長さ(&self) -> 時間の長さ {
        self.リピート回数.リピートした長さ(self.区間.長さ())
    }
}
