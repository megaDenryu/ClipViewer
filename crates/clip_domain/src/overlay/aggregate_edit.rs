//! 置いてある置いたクリップを変える操作。動かす・映す矩形を変える・取り除く。
//! どの操作も、先に確かめを全部済ませてから中身を変える。拒んだときは重ね合わせを操作の前のまま残す。

use super::aggregate::重ね合わせ;
use super::basis::重ね合わせの上の秒;
use super::error::重ね合わせの操作エラー;
use super::placed::置いたクリップ;
use super::placed_id::置いたクリップの識別子;
use super::rect::映す矩形;
use super::row::行の番号;

impl 重ね合わせ {
    /// 置いたクリップを、先の行の始まりの時刻へ動かす。同じ行の中で時刻だけを変えるときも、先の行に今の行を渡す。
    /// 先の行が無いとき、先の行でほかの置いたクリップと時間が重なるときは拒む。
    pub fn 動かす(
        &mut self,
        識別子: &置いたクリップの識別子,
        先の行: 行の番号,
        始まりの時刻: 重ね合わせの上の秒,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let 元の行 = self.置いてある行の番号(識別子)?;
        let 占める長さ = self.行の並び[元の行.番号()]
            .識別子で探す(識別子)
            .ok_or_else(|| 重ね合わせの操作エラー::見つからない(識別子.clone()))?
            .占める長さ();
        let 行の数 = self.行の並び.len();
        let Some(先) = self.行の並び.get(先の行.番号()) else {
            return Err(重ね合わせの操作エラー::行が範囲の外 {
                行: 先の行,
                行の数,
            });
        };
        if let Some(相手) = 先.重なる相手(始まりの時刻, 占める長さ, Some(識別子))
        {
            return Err(重ね合わせの操作エラー::時間が重なる {
                行: 先の行,
                相手: 相手.識別子().clone(),
            });
        }
        let 動かすもの = self.行の並び[元の行.番号()]
            .取り出す(識別子)
            .ok_or_else(|| 重ね合わせの操作エラー::見つからない(識別子.clone()))?;
        self.行の並び[先の行.番号()].差し込む(動かすもの.始まりの時刻を替える(始まりの時刻));
        Ok(())
    }

    /// 置いたクリップの映す矩形を変える。映す矩形の不変条件は型が守るため、識別子が無いときだけ拒む。
    pub fn 映す矩形を変える(
        &mut self,
        識別子: &置いたクリップの識別子,
        映す矩形: 映す矩形,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.行の並び
            .iter_mut()
            .find_map(|行| 行.識別子で探して変える(識別子))
            .map(|置いた| 置いた.映す矩形を替える(映す矩形))
            .ok_or_else(|| 重ね合わせの操作エラー::見つからない(識別子.clone()))
    }

    /// 置いたクリップを取り除き、取り除いたものを返す。行は空になっても残す(ほかの行の番号と重なりの順を変えないため)。
    pub fn 取り除く(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) -> Result<置いたクリップ, 重ね合わせの操作エラー> {
        self.行の並び
            .iter_mut()
            .find_map(|行| 行.取り出す(識別子))
            .ok_or_else(|| 重ね合わせの操作エラー::見つからない(識別子.clone()))
    }
}
