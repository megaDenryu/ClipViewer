//! タイムラインの行の並びへの問い合わせ。行があるか・空の行か・空の行を足せるか・画面の上から数えた順番を答える。
//! 画面と状態が、行の番号を生の数で比べたり数えたりせずに済むよう、行の並びの側に置く。参照: _doc/設計/同時再生.md 2-6

use super::{タイムラインの行の並び, 同時に重ねられる行の数, 行の番号};

/// 上から数えた行の順番とは、タイムラインの行を画面の上(最も手前の行)から1, 2, …と数えた順番のことである。利用者に見せる文に使う。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 上から数えた行の順番(usize);

impl std::fmt::Display for 上から数えた行の順番 {
    fn fmt(&self, 出力: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(出力, "上から{}番目", self.0)
    }
}

impl タイムラインの行の並び {
    /// 行の番号の行があるか。
    pub fn 行があるか(&self, 行: 行の番号) -> bool {
        行.番号() < self.行の並び.len()
    }

    /// 行の番号の行が、置いたクリップを1つも持たない空の行か。行が無ければ無い。
    pub fn 空の行か(&self, 行: 行の番号) -> Option<bool> {
        self.行の並び
            .get(行.番号())
            .map(|中身| 中身.置いたクリップの並び().is_empty())
    }

    /// 空の行を手前に足せるか。行が同時に重ねられる行の数より少ないときだけ足せる。
    pub fn 行を足せるか(&self) -> bool {
        self.行の並び.len() < 同時に重ねられる行の数
    }

    /// 行の番号の行を、画面の上(最も手前)から数えた順番。行が無ければ無い。
    pub fn 上から数えた順番(
        &self, 行: 行の番号
    ) -> Option<上から数えた行の順番> {
        self.行があるか(行)
            .then(|| 上から数えた行の順番(self.行の並び.len() - 行.番号()))
    }
}
