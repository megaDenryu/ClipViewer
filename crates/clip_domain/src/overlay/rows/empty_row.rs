//! 空の行の操作。置いたクリップを1つも持たない行を消す操作と、空の新しい行を最も手前に足す操作。
//! 取り除く操作は空になった行も残す(ほかの行の番号と重なりの順を変えないため)ので、利用者が選んで消す口をここに置く。参照: _doc/設計/同時再生.md 2-6・4-1

use super::{タイムラインの行, タイムラインの行の並び, 行の番号};
use crate::overlay::error::重ね合わせの操作エラー;

impl タイムラインの行の並び {
    /// 行の番号の空の行を消す。後ろ(手前)の行の番号は1つずつ小さくなる。行が無いときと、置いたクリップを持つ行のときは拒む。
    pub(in crate::overlay) fn 空の行を消す(
        &mut self,
        行: 行の番号,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let Some(中身) = self.行の並び.get(行.番号()) else {
            return Err(重ね合わせの操作エラー::行の番号が範囲の外 {
                行,
                行の数: self.行の数(),
            });
        };
        if !中身.置いたクリップの並び().is_empty() {
            return Err(重ね合わせの操作エラー::行が空でない { 行 });
        }
        self.行の並び.remove(行.番号());
        Ok(())
    }

    /// 空の新しい行を最も手前に足し、足した行の番号を返す。行がすでに同時に重ねられる行の数まであるときは拒む。
    pub(in crate::overlay) fn 空の行を手前に足す(
        &mut self,
    ) -> Result<行の番号, 重ね合わせの操作エラー> {
        if !self.行を足せるか() {
            return Err(重ね合わせの操作エラー::行の数が上限に達している);
        }
        self.行の並び.push(タイムラインの行::default());
        Ok(行の番号::番号から作成する(
            self.行の並び.len() - 1,
        ))
    }
}
