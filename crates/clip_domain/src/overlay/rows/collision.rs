//! ぶつかった所で止める規則。塊のドラッグで置いたクリップの始まりの時刻を動かすとき、同じ行のほかの置いたクリップと重ならないよう、
//! ぶつかった所で止めた始まりの時刻を求める。行の中で始まりを置ける範囲(ほかの置いたクリップの間の空き)を求め、
//! 動かす前の始まりがある範囲の中へ望む始まりを収める。参照: _doc/設計/同時再生.md 2-6・4-1

use super::row::タイムラインの行;
use crate::duration::時間の長さ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::placed_id::置いたクリップの識別子;
use crate::time::時刻;

/// 始まりを置ける範囲とは、長さの決まった置いたクリップを、行のほかの置いたクリップと重ならずに置ける始まりの時刻の範囲のことである。
/// 最も遅い始まりが無い範囲は、行の最後の置いたクリップの後ろの空きであり、後ろへ限りが無い。
#[derive(Debug, Clone, Copy, PartialEq)]
struct 始まりを置ける範囲 {
    最も早い始まり: 重ね合わせ上の秒,
    最も遅い始まり: Option<重ね合わせ上の秒>,
}

impl 始まりを置ける範囲 {
    /// 時刻がこの範囲の中にあるか。端は丸めの許容誤差だけ外も中とみなす(接する端は始まりと長さの足し算で僅かに食い込むため)。
    fn 含むか(self, 時刻: 重ね合わせ上の秒) -> bool {
        let 許容誤差 = 時間の長さ::丸めの許容誤差;
        let 早すぎないか = 時刻.進める(許容誤差) >= self.最も早い始まり;
        早すぎないか
            && self
                .最も遅い始まり
                .is_none_or(|遅い| 時刻 <= 遅い.進める(許容誤差))
    }

    /// 時刻をこの範囲の中へ収める。
    fn 収める(self, 時刻: 重ね合わせ上の秒) -> 重ね合わせ上の秒 {
        if 時刻 < self.最も早い始まり {
            return self.最も早い始まり;
        }
        match self.最も遅い始まり {
            Some(遅い) if 時刻 > 遅い => 遅い,
            _ => 時刻,
        }
    }

    /// 時刻からこの範囲までの隔たり。範囲の中なら0秒である。
    fn 隔たり(self, 時刻: 重ね合わせ上の秒) -> 時間の長さ {
        let 収めた = self.収める(時刻);
        if 収めた > 時刻 {
            収めた.起点から経過した長さ(時刻)
        } else {
            時刻.起点から経過した長さ(収めた)
        }
    }
}

impl タイムラインの行 {
    /// 長さの置いたクリップを、動かす前の始まり(基点)から望む始まりへ動かしたとき、この行のほかの置いたクリップにぶつかった所で止めた始まり。
    /// 除く識別子は、動かしている置いたクリップ自身である(同じ行の中で動かすとき、自分とはぶつからない)。
    /// 基点がこの行で置ける範囲の中にあれば、望む始まりをその範囲へ収める(動かした向きの最初の置いたクリップの手前で止まり、0秒より前へは行かない)。
    /// 基点が置ける範囲の外にあれば(別の行へ動かしたとき)、望む始まりに最も近い置ける始まりを選ぶ。後ろの最後の空きは限りが無いため、必ず見つかる。
    pub(in crate::overlay) fn ぶつかった所で止めた始まりの時刻(
        &self,
        除く識別子: &置いたクリップの識別子,
        長さ: 時間の長さ,
        基点: 重ね合わせ上の秒,
        望む始まり: 重ね合わせ上の秒,
    ) -> 重ね合わせ上の秒 {
        let 範囲の並び = self.始まりを置ける範囲を並べる(除く識別子, 長さ);
        if let Some(基点の範囲) = 範囲の並び.iter().find(|範囲| 範囲.含むか(基点))
        {
            return 基点の範囲.収める(望む始まり);
        }
        範囲の並び
            .iter()
            .min_by(|甲, 乙| {
                甲.隔たり(望む始まり)
                    .秒数()
                    .total_cmp(&乙.隔たり(望む始まり).秒数())
            })
            .map_or(望む始まり, |最も近い| 最も近い.収める(望む始まり))
    }

    // 除く識別子のほかの置いたクリップの間の空きのうち、長さの置いたクリップが入るものを早い順に並べる。最後の範囲は後ろへ限りが無い。
    fn 始まりを置ける範囲を並べる(
        &self,
        除く識別子: &置いたクリップの識別子,
        長さ: 時間の長さ,
    ) -> Vec<始まりを置ける範囲> {
        let 許容誤差 = 時間の長さ::丸めの許容誤差;
        let mut 並び = Vec::new();
        let mut 前の終わり = 時刻::先頭;
        for 相手 in self
            .置いたクリップの並び()
            .iter()
            .filter(|置いた| 置いた.識別子() != 除く識別子)
        {
            if 前の終わり.進める(長さ) <= 相手.始まりの時刻().進める(許容誤差)
            {
                let 遅い = 相手.始まりの時刻().戻す(長さ);
                並び.push(始まりを置ける範囲 {
                    最も早い始まり: 前の終わり,
                    最も遅い始まり: Some(if 遅い > 前の終わり {
                        遅い
                    } else {
                        前の終わり
                    }),
                });
            }
            if 相手.終わりの時刻() > 前の終わり {
                前の終わり = 相手.終わりの時刻();
            }
        }
        並び.push(始まりを置ける範囲 {
            最も早い始まり: 前の終わり,
            最も遅い始まり: None,
        });
        並び
    }
}
