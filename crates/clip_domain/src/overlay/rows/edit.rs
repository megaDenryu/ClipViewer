//! タイムラインの行の並びに置いてある置いたクリップを、動かす・映す矩形を変える・取り除く操作。
//! どの操作も置いてある場所を1回だけ探し、確かめを全部済ませてから中身を変える。

use super::{タイムラインの行の並び, 置いたクリップ, 行の番号};
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::error::重ね合わせの操作エラー;
use crate::overlay::placed_id::置いたクリップの識別子;
use crate::overlay::rect::映す矩形;

impl タイムラインの行の並び {
    /// 置いたクリップを、先の行の始まりの時刻へ動かす。先の行が無いとき、先の行でほかの置いたクリップと時間が重なるときは拒む。
    pub(in crate::overlay) fn 置いたクリップを動かす(
        &mut self,
        識別子: &置いたクリップの識別子,
        先の行: 行の番号,
        始まりの時刻: 重ね合わせ上の秒,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let 場所 = self.置いてある場所を探す(識別子)?;
        let Some(先) = self.行の並び.get(先の行.番号()) else {
            return Err(重ね合わせの操作エラー::行の番号が範囲の外 {
                行: 先の行,
                行の数: self.行の数(),
            });
        };
        let 元の行 = &self.行の並び[場所.行.番号()];
        let 占める長さ = 元の行.置いたクリップの並び()[場所.行の中の位置].占める長さ();
        if let Some(相手) = 先.時間が重なる置いたクリップを探す(
            始まりの時刻,
            占める長さ,
            Some(識別子),
        ) {
            return Err(重ね合わせの操作エラー::時間が重なる {
                行: 先の行,
                相手: 相手.識別子().clone(),
            });
        }
        let mut 動かすもの =
            self.行の並び[場所.行.番号()].位置から取り出す(場所.行の中の位置);
        動かすもの.始まりの時刻を変える(始まりの時刻);
        self.行の並び[先の行.番号()].差し込む(動かすもの);
        Ok(())
    }

    /// 置いたクリップの映す矩形を変える。映す矩形の不変条件は型が守るため、識別子が無いときだけ拒む。
    pub(in crate::overlay) fn 置いたクリップの映す矩形を変える(
        &mut self,
        識別子: &置いたクリップの識別子,
        映す矩形: 映す矩形,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let 場所 = self.置いてある場所を探す(識別子)?;
        self.行の並び[場所.行.番号()]
            .位置で書き換えるために借りる(場所.行の中の位置)
            .映す矩形を変える(映す矩形);
        Ok(())
    }

    /// 置いたクリップを取り除き、取り除いたものを返す。行は空になっても残す(ほかの行の番号と重なりの順を変えないため)。
    pub(in crate::overlay) fn 置いたクリップを取り除く(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) -> Result<置いたクリップ, 重ね合わせの操作エラー> {
        let 場所 = self.置いてある場所を探す(識別子)?;
        Ok(self.行の並び[場所.行.番号()].位置から取り出す(場所.行の中の位置))
    }
}
