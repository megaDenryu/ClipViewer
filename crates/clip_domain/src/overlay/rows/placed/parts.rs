//! 置いたクリップと置いたクリップの各項目の、両方向の変換。どちらの向きも `..` を使わずに分解・組み立てるため、
//! 置いたクリップに項目を足すとここがコンパイルエラーになり、保存の形式との変換で写し漏れが起きない。

use super::置いたクリップ;
use crate::overlay::parts::置いたクリップの各項目;

impl 置いたクリップ {
    /// 各項目から作る。各項目の値はそれぞれの型が不変条件を持つ。動画の番号が表にあることと、行の中で時間が重ならないことは、
    /// 置く側(重ね合わせとタイムラインの行の並び)が確かめる。
    pub(in crate::overlay) fn 各項目から作る(
        各項目: 置いたクリップの各項目
    ) -> Self {
        let 置いたクリップの各項目 {
            識別子,
            受け継いだ値,
            動画,
            始まりの時刻,
            映す矩形,
            音の設定,
        } = 各項目;
        Self {
            識別子,
            受け継いだ値,
            動画,
            始まりの時刻,
            映す矩形,
            音の設定,
        }
    }

    /// すべての項目の写しを作る。保存の形式へ書き出すときに使う。
    pub fn 各項目の写しを作る(&self) -> 置いたクリップの各項目 {
        let Self {
            識別子,
            受け継いだ値,
            動画,
            始まりの時刻,
            映す矩形,
            音の設定,
        } = self;
        置いたクリップの各項目 {
            識別子: 識別子.clone(),
            受け継いだ値: 受け継いだ値.clone(),
            動画: *動画,
            始まりの時刻: *始まりの時刻,
            映す矩形: *映す矩形,
            音の設定: *音の設定,
        }
    }
}
