//! タイムラインの行と、重ね合わせの中の行を指す番号。行の中の並びを変える口は、親のタイムラインの行の並びのモジュールだけが使う。

use super::placed::置いたクリップ;
use crate::duration::時間の長さ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::placed_id::置いたクリップの識別子;

/// 行の番号とは、重ね合わせのタイムラインの行の並びの中で、1つの行を指す0から始まる番号のことである。
/// 0番が最も奥であり、番号が大きい行ほど重ねる画面の手前に映る。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(transparent)]
pub struct 行の番号(usize);

impl 行の番号 {
    /// 0から数えた番号から作成する。重ね合わせにあるかは、操作が行の数と照らして確かめる。
    pub fn 番号から作成する(番号: usize) -> Self {
        Self(番号)
    }

    /// 0から数えた番号を返す。表示や画面の行の位置へ渡す境界で使う。
    pub fn 番号(self) -> usize {
        self.0
    }
}

/// タイムラインの行とは、タイムラインの横1本の帯であり、時間の重ならない置いたクリップを始まりの時刻の順に並べたもののことである。
/// 1つの行は、同時に高々1つの置いたクリップを映し、1つの音を鳴らす。
/// 不変条件: 置いたクリップは始まりの時刻の順に並び、占める時間が重ならない。
/// 並びを変える口はタイムラインの行の並びのモジュールの中にだけ開き、差し込む前の重なりはその型が確かめる。
#[derive(Debug, Clone, PartialEq, Default)]
pub struct タイムラインの行 {
    置いたクリップの並び: Vec<置いたクリップ>,
}

impl タイムラインの行 {
    /// 始まりの時刻の順の置いたクリップ。
    pub fn 置いたクリップの並び(&self) -> &[置いたクリップ] {
        &self.置いたクリップの並び
    }

    /// 識別子の置いたクリップを探す。
    pub fn 識別子で探す(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Option<&置いたクリップ> {
        self.置いたクリップの並び
            .iter()
            .find(|置いた| 置いた.識別子() == 識別子)
    }

    /// 始まりから長さの間に時間が重なる置いたクリップのうち、除く識別子でない最初のもの。無ければこの行はその間空いている。
    pub(super) fn 時間が重なる置いたクリップを探す(
        &self,
        始まり: 重ね合わせ上の秒,
        長さ: 時間の長さ,
        除く識別子: Option<&置いたクリップの識別子>,
    ) -> Option<&置いたクリップ> {
        self.置いたクリップの並び.iter().find(|置いた| {
            Some(置いた.識別子()) != 除く識別子 && 置いた.時間が重なるか(始まり, 長さ)
        })
    }

    /// 識別子の置いたクリップの、行の中の位置(0から数える)。
    pub(super) fn 識別子の位置(
        &self, 識別子: &置いたクリップの識別子
    ) -> Option<usize> {
        self.置いたクリップの並び
            .iter()
            .position(|置いた| 置いた.識別子() == 識別子)
    }

    /// 始まりの時刻の順を保つ位置へ差し込む。
    /// 注意: 時間が重なる置いたクリップが無いことを、呼び出し側が確かめてから呼ぶこと。
    pub(super) fn 差し込む(&mut self, 置いた: 置いたクリップ) {
        let 位置 = self
            .置いたクリップの並び
            .partition_point(|先| 先.始まりの時刻() <= 置いた.始まりの時刻());
        self.置いたクリップの並び.insert(位置, 置いた);
    }

    /// 行の中の位置の置いたクリップを並びから取り出す。
    /// 注意: 位置は `識別子の位置` で得た、行を変える前の位置であること。
    pub(super) fn 位置から取り出す(&mut self, 位置: usize) -> 置いたクリップ {
        self.置いたクリップの並び.remove(位置)
    }

    /// 行の中の位置の置いたクリップを、始まりの時刻にかかわらない値を書き換えるために借りる。
    /// 注意: 位置は `識別子の位置` で得た位置であること。始まりの時刻を変えるときは取り出して差し込み直す。
    pub(super) fn 位置で書き換えるために借りる(
        &mut self,
        位置: usize,
    ) -> &mut 置いたクリップ {
        &mut self.置いたクリップの並び[位置]
    }
}
