//! タイムラインの行の並びへ置く操作。識別子が重ならないことを確かめ、始まりの時刻から占める長さの間が空いている
//! 最も手前の行を選び、どの行も空いていなければ手前に行を足す。行が上限まであってどれも空いていなければ拒む。
//! 空いているかを問わず、最も手前に新しい行を足してそこへ置く操作も置く。

use super::{
    タイムラインの行, タイムラインの行の並び, 同時に重ねられる行の数, 置いたクリップ, 行の番号,
};
use crate::duration::時間の長さ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::error::重ね合わせの操作エラー;

/// 置く行とは、置いたクリップをどの行へ置くかの決定のことである。
enum 置く行 {
    /// 今ある行のうち、時間が空いている最も手前の行。
    空いている行(行の番号),
    /// どの行も空いていないため、最も手前に新しく足す行。
    手前に足す行,
}

impl タイムラインの行の並び {
    /// 置いたクリップを、始まりの時刻から占める長さの間が空いている最も手前の行へ置き、置いた行の番号を返す。
    /// 識別子がすでにあるときと、行が同時に重ねられる行の数まであってどれも空いていないときは拒む。
    pub(in crate::overlay) fn 空いている最も手前の行へ置く(
        &mut self,
        置いた: 置いたクリップ,
    ) -> Result<行の番号, 重ね合わせの操作エラー> {
        self.識別子が重ならないか確かめる(&置いた)?;
        let 置く先 = match self.置く行を選ぶ(置いた.始まりの時刻(), 置いた.占める長さ())?
        {
            置く行::空いている行(行) => 行,
            置く行::手前に足す行 => {
                self.行の並び.push(タイムラインの行::default());
                行の番号::番号から作成する(self.行の並び.len() - 1)
            }
        };
        self.行の並び[置く先.番号()].差し込む(置いた);
        Ok(置く先)
    }

    // 最も手前に新しい行を足して置き、足した行の番号を返す。識別子がすでにあるときと、行が同時に重ねられる行の数まであるときは拒む。
    pub(in crate::overlay) fn 手前に新しい行を足して置く(
        &mut self,
        置いた: 置いたクリップ,
    ) -> Result<行の番号, 重ね合わせの操作エラー> {
        self.識別子が重ならないか確かめる(&置いた)?;
        if self.行の並び.len() >= 同時に重ねられる行の数 {
            return Err(重ね合わせの操作エラー::行の数が上限に達している);
        }
        let mut 新しい行 = タイムラインの行::default();
        新しい行.差し込む(置いた);
        self.行の並び.push(新しい行);
        Ok(行の番号::番号から作成する(
            self.行の並び.len() - 1,
        ))
    }

    pub(super) fn 識別子が重ならないか確かめる(
        &self,
        置いた: &置いたクリップ,
    ) -> Result<(), 重ね合わせの操作エラー> {
        match self.識別子で探す(置いた.識別子()) {
            Some(_) => Err(
                重ね合わせの操作エラー::識別子が重複している(
                    置いた.識別子().clone(),
                ),
            ),
            None => Ok(()),
        }
    }

    fn 置く行を選ぶ(
        &self,
        始まり: 重ね合わせ上の秒,
        長さ: 時間の長さ,
    ) -> Result<置く行, 重ね合わせの操作エラー> {
        let 空いている行 = self.行の並び.iter().rposition(|行| {
            行.時間が重なる置いたクリップを探す(始まり, 長さ, None)
                .is_none()
        });
        match 空いている行 {
            Some(位置) => Ok(置く行::空いている行(行の番号::番号から作成する(
                位置,
            ))),
            None if self.行の並び.len() < 同時に重ねられる行の数 => {
                Ok(置く行::手前に足す行)
            }
            None => Err(重ね合わせの操作エラー::空いている行が無い {
                始まりの時刻: 始まり,
            }),
        }
    }
}
