//! 組み立てるときに、置いたクリップを指定の行へ差し込む口。ファイルから読んだ値は行が決まっているため、空いている行を選ぶ置く操作と別に置く。
//! 識別子が重ならないことと、行の中で時間が重ならないことを確かめてから差し込む。参照: _doc/設計/同時再生.md 4-1

use super::{タイムラインの行の並び, 置いたクリップ, 行の番号};
use crate::overlay::error::重ね合わせの操作エラー;

impl タイムラインの行の並び {
    /// 置いたクリップを行の番号の行へ、始まりの時刻の順を保って差し込む。識別子がすでにあるとき、行が無いとき、
    /// その行のほかの置いたクリップと時間が重なるとき(丸めの許容誤差以下の食い込みは接しているとみなす)は拒み、並びを変えない。
    pub(in crate::overlay) fn 確かめて行へ差し込む(
        &mut self,
        行: 行の番号,
        置いた: 置いたクリップ,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.識別子が重ならないか確かめる(&置いた)?;
        let 行の数 = self.行の数();
        let Some(先) = self.行の並び.get_mut(行.番号()) else {
            return Err(重ね合わせの操作エラー::行の番号が範囲の外 {
                行,
                行の数,
            });
        };
        if let Some(相手) = 先.時間が重なる置いたクリップを探す(
            置いた.始まりの時刻(),
            置いた.占める長さ(),
            None,
        ) {
            return Err(重ね合わせの操作エラー::時間が重なる {
                行,
                相手: 相手.識別子().clone(),
            });
        }
        先.差し込む(置いた);
        Ok(())
    }
}
