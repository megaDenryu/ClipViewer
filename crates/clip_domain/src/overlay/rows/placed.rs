//! 置いたクリップ。重ね合わせの中のタイムラインの行に置かれた、映す場所と音の設定と始まりの時刻を持つ、スタックのクリップとは別の型。

use crate::duration::時間の長さ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::inherited::クリップから受け継いだ値;
use crate::overlay::placed_id::置いたクリップの識別子;
use crate::overlay::rect::映す矩形;
use crate::overlay::video_table::動画の番号;
use crate::overlay::volume::置いたクリップの音の設定;

/// 継ぎ目の許容誤差とは、2つの置いたクリップの終わりと始まりが接しているかを判定するときに、ずれを無視する長さのことである。
/// 1コマ(数十ミリ秒)より十分に短く、秒の足し算の丸めの誤差(1秒あたり1e-16程度)より十分に長い。
const 継ぎ目の許容誤差: 時間の長さ = 時間の長さ::定数の秒数から作る(1e-6);

/// 置いたクリップとは、1本の動画の区間に、リピート回数・クロップ範囲・動画の番号・重ね合わせ上の始まりの時刻・
/// 映す矩形・置いたクリップの音の設定を付けたもののことである。スタックのクリップ(`クリップ`)とは別の型である。
/// 置いたあとの値を変える口はタイムラインの行の並びのモジュールの中にだけ開き、始まりの時刻は行から取り出してから変える。
#[derive(Debug, Clone, PartialEq)]
pub struct 置いたクリップ {
    識別子: 置いたクリップの識別子,
    受け継いだ値: クリップから受け継いだ値,
    動画: 動画の番号,
    始まりの時刻: 重ね合わせ上の秒,
    映す矩形: 映す矩形,
    音の設定: 置いたクリップの音の設定,
}

impl 置いたクリップ {
    /// 映す矩形を重ねる画面の全体、音の設定を最初の値にして作る。動画の番号が表にあることは呼び出し側(重ね合わせ)が確かめる。
    pub(in crate::overlay) fn 既定値で作成する(
        識別子: 置いたクリップの識別子,
        受け継いだ値: クリップから受け継いだ値,
        動画: 動画の番号,
        始まりの時刻: 重ね合わせ上の秒,
    ) -> Self {
        Self {
            識別子,
            受け継いだ値,
            動画,
            始まりの時刻,
            映す矩形: 映す矩形::全体,
            音の設定: 置いたクリップの音の設定::最初の値,
        }
    }

    /// 識別子。
    pub fn 識別子(&self) -> &置いたクリップの識別子 {
        &self.識別子
    }

    /// スタックのクリップから受け継いだ名前・区間・リピート回数・クロップ範囲。
    pub fn 受け継いだ値(&self) -> &クリップから受け継いだ値 {
        &self.受け継いだ値
    }

    /// 使う動画の表の中で、このクリップの動画を指す番号。
    pub fn 動画の番号(&self) -> 動画の番号 {
        self.動画
    }

    /// 重ね合わせ上で映り始める時刻。
    pub fn 始まりの時刻(&self) -> 重ね合わせ上の秒 {
        self.始まりの時刻
    }

    /// 映り終わる時刻。始まりの時刻に占める長さを足した時刻であり、この時刻にはもう映っていない。
    pub fn 終わりの時刻(&self) -> 重ね合わせ上の秒 {
        self.始まりの時刻.進める(self.占める長さ())
    }

    /// 占める長さ。区間の長さにリピート回数を掛けた長さである。
    pub fn 占める長さ(&self) -> 時間の長さ {
        self.受け継いだ値.占める長さ()
    }

    /// 重ねる画面のどこにどの大きさで映すか。
    pub fn 映す矩形(&self) -> 映す矩形 {
        self.映す矩形
    }

    /// 音量と消音しているか。
    pub fn 音の設定(&self) -> 置いたクリップの音の設定 {
        self.音の設定
    }

    /// 始まりの時刻から占める長さの間が、別の時間の範囲と重なるか。端が接するだけなら重ならない。
    /// 重なりが継ぎ目の許容誤差以下なら、端が接しているとみなす(始まりと長さの足し算の丸めで、接する端が僅かに食い込むため)。
    pub(super) fn 時間が重なるか(
        &self, 始まり: 重ね合わせ上の秒, 長さ: 時間の長さ
    ) -> bool {
        let 終わり = 始まり.進める(長さ);
        self.始まりの時刻.進める(継ぎ目の許容誤差) < 終わり
            && 始まり.進める(継ぎ目の許容誤差) < self.終わりの時刻()
    }

    /// 次の置いたクリップが、このクリップの終わりから隙間なく続くか。次の始まりの時刻と終わりの時刻の差が、
    /// 前後どちらへも継ぎ目の許容誤差以下なら続くとみなす。浮動小数の時刻の等しさで判定しないためである。
    pub fn 隙間なく続くか(&self, 次: &置いたクリップ) -> bool {
        let 終わり = self.終わりの時刻();
        次.始まりの時刻 <= 終わり.進める(継ぎ目の許容誤差)
            && 終わり <= 次.始まりの時刻.進める(継ぎ目の許容誤差)
    }

    /// 注意: 行の中の並びの順と重なりは変えた後で崩れうるため、行から取り出してから変え、確かめた行へ差し込み直すこと。
    pub(super) fn 始まりの時刻を変える(
        &mut self, 始まりの時刻: 重ね合わせ上の秒
    ) {
        self.始まりの時刻 = 始まりの時刻;
    }

    pub(super) fn 映す矩形を変える(&mut self, 映す矩形: 映す矩形) {
        self.映す矩形 = 映す矩形;
    }
}
