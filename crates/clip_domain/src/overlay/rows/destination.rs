//! 置いたクリップの行き先。塊のドラッグで、掴み始めた置いたクリップの今の行と始まりの時刻に、時刻をずらす量と行の差を当てた行き先を求める。
//! 行の差は行の数へ収め、始まりの時刻は先の行のほかの置いたクリップにぶつかった所で止める(`collision.rs`)。
//! 求めるだけで並びは変えない。決めた行き先へ動かすのは `置いたクリップを動かす` である。参照: _doc/設計/同時再生.md 2-6

use super::{
    タイムラインの行の並び, 置いたクリップ, 置いてある場所, 行の番号
};
use crate::duration::時間の長さ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::error::重ね合わせの操作エラー;
use crate::overlay::placed_id::置いたクリップの識別子;
use crate::overlay::shift::{時刻をずらす量, 行の差};

/// 置いたクリップの行き先とは、置いたクリップを置く行の番号と始まりの時刻の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 置いたクリップの行き先 {
    /// 置く行の番号。
    pub 行: 行の番号,
    /// 重ね合わせ上の始まりの時刻。
    pub 始まりの時刻: 重ね合わせ上の秒,
}

impl 置いたクリップの行き先 {
    /// 別の行き先と同じ行き先か。行が同じで、始まりの時刻の差が丸めの許容誤差(1マイクロ秒)以下なら同じとみなす。
    pub fn 同じ行き先か(&self, 他方: &Self) -> bool {
        let 差 = if self.始まりの時刻 > 他方.始まりの時刻 {
            self.始まりの時刻.起点から経過した長さ(他方.始まりの時刻)
        } else {
            他方.始まりの時刻.起点から経過した長さ(self.始まりの時刻)
        };
        self.行 == 他方.行 && 差 <= 時間の長さ::丸めの許容誤差
    }
}

impl タイムラインの行の並び {
    /// 識別子の置いたクリップの今の行き先(置いてある行と始まりの時刻)。無ければ置いたクリップが見つからないとして拒む。
    pub fn 今の行き先(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Result<置いたクリップの行き先, 重ね合わせの操作エラー> {
        let 場所 = self.置いてある場所を探す(識別子)?;
        let 置いた = self.場所の置いたクリップ(&場所);
        Ok(置いたクリップの行き先 {
            行: 場所.行,
            始まりの時刻: 置いた.始まりの時刻(),
        })
    }

    /// 識別子の置いたクリップの今の行き先に、時刻をずらす量と行の差を当てた行き先。並びは変えない。
    /// 行の差は0番から最も手前の行までへ収める。始まりの時刻は、先の行のほかの置いたクリップにぶつかった所で止め、0秒より前へ行かない。
    /// 識別子の置いたクリップが無いときは拒む。
    pub fn ずらした行き先を求める(
        &self,
        識別子: &置いたクリップの識別子,
        ずらす量: 時刻をずらす量,
        行の差: 行の差,
    ) -> Result<置いたクリップの行き先, 重ね合わせの操作エラー> {
        let 場所 = self.置いてある場所を探す(識別子)?;
        let 置いた = self.場所の置いたクリップ(&場所);
        let (今, 長さ) = (置いた.始まりの時刻(), 置いた.占める長さ());
        let 最も手前 = 行の番号::番号から作成する(self.行の数().saturating_sub(1));
        let 先の行 = 場所.行.行の差だけ動かして収める(行の差, 最も手前);
        let 始まりの時刻 = self.行の並び[先の行.番号()].ぶつかった所で止めた始まりの時刻(
            識別子,
            長さ,
            今,
            ずらす量.ずらした時刻を求める(今),
        );
        Ok(置いたクリップの行き先 {
            行: 先の行,
            始まりの時刻,
        })
    }

    fn 場所の置いたクリップ(
        &self, 場所: &置いてある場所
    ) -> &置いたクリップ {
        &self.行の並び[場所.行.番号()].置いたクリップの並び()[場所.行の中の位置]
    }
}
