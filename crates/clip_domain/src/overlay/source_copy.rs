//! 置くクリップの写し。スタックのクリップから、置いたクリップが持つ値だけを写し取ったもの。

use crate::clip::{クリップ, クリップ名};
use crate::crop::クロップ範囲;
use crate::duration::時間の長さ;
use crate::repeat::{リピート回数, リピート設定};
use crate::video_span::動画上の区間;

/// 置くクリップの写しとは、置いたクリップが持つ値のうち、スタックのクリップから写す名前・区間・繰り返しの回数・クロップ範囲の組のことである。
/// 写しなので、元のクリップを後で直しても変わらない。トリガーと無限ループを持たない(同時再生.md 7節の決定1)。
#[derive(Debug, Clone, PartialEq)]
pub struct 置くクリップの写し {
    /// 表示用の名前。
    pub 名前: クリップ名,
    /// 元の動画から切り出す区間。
    pub 区間: 動画上の区間,
    /// 区間を続けて映す回数。
    pub 繰り返しの回数: リピート回数,
    /// 映す矩形へ映す前に切り出す矩形。
    pub クロップ: クロップ範囲,
}

impl 置くクリップの写し {
    /// スタックのクリップの値を写す。回数指定はその回数、無限ループは1回にし、トリガーと有効かは写さない。
    pub fn クリップから写す(クリップ: &クリップ) -> Self {
        let 繰り返しの回数 = match クリップ.リピート {
            リピート設定::回数指定(回数) => 回数,
            リピート設定::無限ループ => リピート回数::一回,
        };
        Self {
            名前: クリップ.名前.clone(),
            区間: クリップ.区間,
            繰り返しの回数,
            クロップ: クリップ.クロップ,
        }
    }

    /// 置いたクリップの占める長さとは、区間の長さに繰り返しの回数を掛けた長さのことである。
    pub fn 占める長さ(&self) -> 時間の長さ {
        self.繰り返しの回数.繰り返した長さ(self.区間.長さ())
    }
}
