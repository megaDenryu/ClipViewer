//! 置いたクリップの識別子と、その発行の仕組み。

use std::fmt;

use crate::clip_id::{発行時刻, 識別子の乱数};

/// 置いたクリップの識別子とは、重ね合わせの中で置いたクリップを一意に指す、空でない文字列のことである。
/// 新しく発行するときの表記は「placed-<ミリ秒>-<乱数>」である。クリップ識別子とは別の型であり、取り違えても型が通らない。
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct 置いたクリップの識別子(String);

/// 空の置いたクリップの識別子エラーとは、置いたクリップの識別子の文字列が空であることである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("置いたクリップの識別子が空である")]
pub struct 空の置いたクリップの識別子エラー;

impl 置いたクリップの識別子 {
    /// ファイル等にある既存の識別子の文字列から作成する。空文字列を拒む。
    pub fn 文字列から作成する(
        文字列: String,
    ) -> Result<Self, 空の置いたクリップの識別子エラー> {
        if 文字列.is_empty() {
            Err(空の置いたクリップの識別子エラー)
        } else {
            Ok(Self(文字列))
        }
    }

    /// 発行時刻と乱数から、表記「placed-<ミリ秒>-<乱数>」の識別子を組み立てる。
    pub fn 時刻と乱数から組み立てる(
        時刻: 発行時刻, 乱数: 識別子の乱数
    ) -> Self {
        Self(format!("placed-{}-{}", 時刻.0, 乱数.0))
    }

    /// 識別子の文字列を返す。ファイルへ書き出す境界で使う。
    pub fn 文字列(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for 置いたクリップの識別子 {
    fn fmt(&self, 書き込み先: &mut fmt::Formatter<'_>) -> fmt::Result {
        書き込み先.write_str(&self.0)
    }
}

/// 置いたクリップの識別子の発行元とは、新しい置いたクリップの識別子を1つずつ発行するもののことである。
/// 時刻と乱数の取得をドメインの外へ出し、試験では決まった識別子を発行できるようにするために置く。
pub trait 置いたクリップの識別子の発行元 {
    /// 新しい識別子を1つ発行する。
    fn 新しい置いたクリップの識別子を発行する(
        &mut self,
    ) -> 置いたクリップの識別子;
}
