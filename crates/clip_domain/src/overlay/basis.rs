//! 重ね合わせ上の時刻の基準。スタックのタイムライン上の時刻と取り違えても型が通らないように、別の基準の型を置く。

use crate::time::時刻;

/// 重ね合わせ上とは、重ね合わせの始まりを0秒とする時間軸のことである。
/// タイムライン上(クリップスタックを順に再生する時間軸)とは別の基準である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub enum 重ね合わせ上 {}

/// 重ね合わせ上の秒とは、重ね合わせの始まりからの経過の秒のことである。
pub type 重ね合わせ上の秒 = 時刻<重ね合わせ上>;

/// 重ねる画面に対するとは、重ねる画面の幅または高さを100とする百分率の基準のことである。映す矩形が使う。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
pub enum 重ねる画面に対する {}
