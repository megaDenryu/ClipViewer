//! 重ね合わせの型と、その中身を読む口。置く操作は `aggregate_place.rs`、置いたクリップを変える操作は `aggregate_edit.rs` に置く。

use super::aspect::重ねる画面の縦横比;
use super::basis::重ね合わせの上の秒;
use super::error::重ね合わせの操作エラー;
use super::placed::置いたクリップ;
use super::placed_id::置いたクリップの識別子;
use super::row::{タイムラインの行, 行の番号};
use super::video_table::使う動画の表;
use crate::time::時刻;

/// 同時に重ねられる行の数とは、1つの重ね合わせが持てるタイムラインの行の数の上限のことである。
/// 根拠は同時再生.md 5-4 であり、行ごとの音の再生器の配列の大きさもこの値から決める。
pub const 同時に重ねられる行の数: usize = 8;

/// 重ね合わせとは、重ねる画面の縦横比と、使う動画の表と、タイムラインの行の並びの組のことである。
/// 重ね合わせは、同時再生で再生するものの全部であり、ライブラリへ1ファイルとして保存する単位である。
/// 行の並びは先頭が最も奥、末尾が最も手前である。
/// 不変条件: 重ねる画面の縦横比はクロップ連動でない(型が守る)。行の数は同時に重ねられる行の数以下である。
/// 同じ行の置いたクリップは始まりの時刻の順に並び、占める時間が重ならない。置いたクリップの識別子は重ならない。
/// 置いたクリップの動画の番号は使う動画の表にある。映す矩形は重ねる画面の内側にあり、幅と高さは5%以上である(型が守る)。
#[derive(Debug, Clone, PartialEq)]
pub struct 重ね合わせ {
    pub(super) 縦横比: 重ねる画面の縦横比,
    pub(super) 動画の表: 使う動画の表,
    pub(super) 行の並び: Vec<タイムラインの行>,
}

impl 重ね合わせ {
    /// 行を1つも持たない重ね合わせを作成する。
    pub fn 作成する(
        縦横比: 重ねる画面の縦横比, 動画の表: 使う動画の表
    ) -> Self {
        Self {
            縦横比,
            動画の表,
            行の並び: Vec::new(),
        }
    }

    /// 重ねる画面の縦横比。
    pub fn 縦横比(&self) -> 重ねる画面の縦横比 {
        self.縦横比
    }

    /// 使う動画の表。
    pub fn 動画の表(&self) -> &使う動画の表 {
        &self.動画の表
    }

    /// 奥から手前の順のタイムラインの行。
    pub fn 行の並び(&self) -> &[タイムラインの行] {
        &self.行の並び
    }

    /// 識別子の置いたクリップを探す。
    pub fn 識別子で探す(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Option<&置いたクリップ> {
        self.行の並び.iter().find_map(|行| 行.識別子で探す(識別子))
    }

    /// 識別子の置いたクリップがある行の番号。無ければ見つからないとして拒む。
    pub fn 置いてある行の番号(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Result<行の番号, 重ね合わせの操作エラー> {
        self.行の並び
            .iter()
            .position(|行| 行.識別子で探す(識別子).is_some())
            .map(行の番号::番号から作成する)
            .ok_or_else(|| 重ね合わせの操作エラー::見つからない(識別子.clone()))
    }

    /// 重ね合わせの長さとは、すべての置いたクリップの終わりの時刻のうち最も遅い時刻のことである。置いたクリップが無ければ0秒である。
    pub fn 重ね合わせの長さ(&self) -> 重ね合わせの上の秒 {
        self.行の並び
            .iter()
            .flat_map(|行| 行.並び().iter().map(置いたクリップ::終わりの時刻))
            .fold(時刻::先頭, |最も遅い, 終わり| {
                if 終わり > 最も遅い {
                    終わり
                } else {
                    最も遅い
                }
            })
    }
}
