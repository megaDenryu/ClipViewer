//! 重ね合わせへの操作が拒まれた理由。

use super::basis::重ね合わせ上の秒;
use super::placed_id::置いたクリップの識別子;
use super::row::行の番号;
use super::rows::同時に重ねられる行の数;
use super::video_table::動画の番号;
use crate::duration::時間の長さ;
use crate::time::動画上の秒;

/// 重ね合わせの操作エラーとは、重ね合わせへの操作が不変条件を破るか、置く前の確かめに通らないために拒まれた理由のことである。
/// 操作が拒まれたとき、重ね合わせは操作の前のまま変わらない。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 重ね合わせの操作エラー {
    /// 指定の識別子の置いたクリップが無い。
    #[error("識別子「{0}」の置いたクリップは存在しない")]
    置いたクリップが見つからない(置いたクリップの識別子),
    /// 同じ識別子の置いたクリップが既にある。
    #[error("識別子「{0}」の置いたクリップは既に存在する")]
    識別子が重複している(置いたクリップの識別子),
    /// 動画の番号が使う動画の表に無い。
    #[error("動画の番号{}は使う動画の表に無い(動画は{動画の数}本)", 番号.番号())]
    動画の番号が表に無い {
        /// 指した番号。
        番号: 動画の番号,
        /// 表にある動画の数。
        動画の数: usize,
    },
    /// 区間の終わりが動画の長さより後ろにある。
    #[error("区間の終わり({}秒)が動画の長さ({}秒)より後ろにある", 区間の終わり.秒数(), 動画の長さ.秒数())]
    区間が動画の長さを超える {
        /// 置こうとした区間の終わり。
        区間の終わり: 動画上の秒,
        /// 置く動画の長さ。
        動画の長さ: 時間の長さ,
    },
    /// 区間の長さが0であり、重ね合わせ上で時間を占めない。
    #[error("区間の長さが0のクリップは置けない")]
    区間の長さが0,
    /// その時刻に空いている行が無く、行も同時に重ねられる行の数まである。
    #[error("{}秒に空いている行が無い(行は{}つまで)", 始まりの時刻.秒数(), 同時に重ねられる行の数)]
    空いている行が無い {
        /// 置こうとした始まりの時刻。
        始まりの時刻: 重ね合わせ上の秒,
    },
    /// 行の番号が、重ね合わせの行の数の範囲の外を指した。
    #[error("行の番号{}の行は無い(行は{行の数}つ)", 行.番号())]
    行の番号が範囲の外 {
        /// 指した行の番号。
        行: 行の番号,
        /// 重ね合わせの行の数。
        行の数: usize,
    },
    /// 動かした先の行で、ほかの置いたクリップと占める時間が重なる。
    #[error("行の番号{}の行で、置いたクリップ「{相手}」と時間が重なる", 行.番号())]
    時間が重なる {
        /// 動かした先の行の番号。
        行: 行の番号,
        /// 時間が重なる置いたクリップ。
        相手: 置いたクリップの識別子,
    },
}
