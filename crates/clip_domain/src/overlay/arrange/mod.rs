//! スタックからの読み替え。スタックの再生できるクリップを1つずつ新しい行へ時刻0で置き、映す矩形を格子のます目にした重ね合わせを作る。
//! 公開の操作(手前に新しい行を足して置く・映す矩形を変える)だけで組み立て、タイムラインの行の並びの私有の中身に触れない。
//! 参照: _doc/設計/同時再生.md 2-2 と 4-3

