impl 重ね合わせ {
    /// スタックの再生できるクリップを、スタックの順に、同時に重ねられる行の数に達するまで1つずつ新しい行へ始まりの時刻0で置いた
    /// 重ね合わせを作る。使う動画の表はスタックの作業場で開いている動画1本、縦横比は出力のアスペクト比から決め、映す矩形は置いた数で
    /// 重ねる画面を等分した格子の、置いた順のます目にする。回数指定はその回数、無限ループは1回にし、トリガーは写さない。
    /// 置く操作が拒んだクリップ(区間の終わりが動画の長さより後ろにある等)と、行の数の上限に達した後ろのクリップは置かずに、
    /// 結果の置かなかったクリップの一覧へ名前と理由を入れる。置けるクリップが1つも無いときだけ拒む。元のスタックは変えない。
    pub fn スタックから並べる(
        スタック: &クリップスタック,
        動画: 正規化した動画パス,
        動画の長さ: 時間の長さ,
        出力のアスペクト比: アスペクト比設定,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) -> Result<スタックから並べた結果, スタックから並べるエラー> {
        let mut 重ね合わせ = Self::作成する(
            重ねる画面の縦横比::スタックの出力のアスペクト比から決める(
                出力のアスペクト比,
            ),
            使う動画の表::一本の動画から作成する(動画),
        );
        let mut 再生できるクリップ = スタック
            .一覧()
            .iter()
            .filter(|クリップ| クリップ.再生できるか())
            .peekable();
        if 再生できるクリップ.peek().is_none() {
            return Err(スタックから並べるエラー::再生できるクリップが無い);
        }
        let mut 置いた識別子の並び = Vec::new();
        let mut 置かなかったクリップの一覧 = Vec::new();
        for クリップ in 再生できるクリップ {
            match 重ね合わせ.新しい行へ置けたら識別子を返す(
                クリップ,
                置いた識別子の並び.len(),
                動画の長さ,
                発行元,
            ) {
                Ok(識別子) => 置いた識別子の並び.push(識別子),
                Err(置かなかった) => 置かなかったクリップの一覧.push(置かなかった),
            }
        }
        let Some(個数) = 格子に並べる個数::作成する(置いた識別子の並び.len())
        else {
            return Err(
                スタックから並べるエラー::置けるクリップが無い(
                    置かなかったクリップの一覧,
                ),
            );
        };
        重ね合わせ.置いたクリップを格子のます目へ映す(&置いた識別子の並び, 個数);
        Ok(スタックから並べた結果 {
            重ね合わせ,
            置かなかったクリップの一覧,
        })
    }

    // すでに置いた数が同時に重ねられる行の数に達していれば置かない。そうでなければ最も手前に新しい行を足して始まりの時刻0で置く。
    fn 新しい行へ置けたら識別子を返す(
        &mut self,
        クリップ: &クリップ,
        すでに置いた数: usize,
        動画の長さ: 時間の長さ,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) -> Result<置いたクリップの識別子, 置かなかったクリップ> {
        let 置かなかったクリップを作る = |理由| 置かなかったクリップ {
            名前: クリップ.名前.clone(),
            理由,
        };
        if すでに置いた数 >= 同時に重ねられる行の数 {
            return Err(置かなかったクリップを作る(
                置かなかった理由::行の数の上限を超える,
            ));
        }
        self.手前に新しい行を足して置く(
            クリップから受け継いだ値::クリップから受け継ぐ(クリップ),
            動画の番号::最初,
            時刻::先頭,
            動画の長さ,
            発行元,
        )
        .map_err(|理由| {
            置かなかったクリップを作る(置かなかった理由::置く操作が拒んだ(理由))
        })
    }
}
