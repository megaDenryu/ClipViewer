pub use error::スタックから並べるエラー;
pub use result::{
    スタックから並べた結果, 置かなかったクリップ, 置かなかった理由
};

use grid::格子に並べる個数;

use crate::aspect::アスペクト比設定;
use crate::clip::クリップ;
