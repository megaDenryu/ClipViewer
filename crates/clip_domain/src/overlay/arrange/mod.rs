/// スタックから並べた結果とは、スタックから並べた重ね合わせと、行の数の上限を超えたために置かなかったクリップの数の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub struct スタックから並べた結果 {
    /// 並べた重ね合わせ。
    pub 重ね合わせ: 重ね合わせ,
    /// 再生できるクリップのうち、同時に重ねられる行の数を超えたために置かなかった後ろのクリップの数。
    pub 置かなかったクリップの数: usize,
}

impl 重ね合わせ {
    /// スタックの再生できるクリップを、スタックの順に先頭から同時に重ねられる行の数まで、1つずつ別の行へ始まりの時刻0で置いた
    /// 重ね合わせを作る。使う動画の表はスタックの作業場で開いている動画1本、縦横比は出力のアスペクト比から決め、
    /// 映す矩形は置いた数で重ねる画面を等分した格子の、置いた順の番号のます目にする。回数指定はその回数、無限ループは1回にし、
    /// トリガーは写さない。元のスタックは変えない。区間の終わりを動画の長さで確かめ、置けないクリップがあれば全体を拒む。
    pub fn スタックから並べる(
        スタック: &クリップスタック,
        動画: 正規化した動画パス,
        動画の長さ: 時間の長さ,
        出力のアスペクト比: アスペクト比設定,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) -> Result<スタックから並べた結果, スタックから並べるエラー> {
        let 再生できるクリップ: Vec<&クリップ> = スタック
            .一覧()
            .iter()
            .filter(|クリップ| クリップ.再生できるか())
            .collect();
        if 再生できるクリップ.is_empty() {
            return Err(スタックから並べるエラー::再生できるクリップが無い);
        }
        let 置くクリップ =
            &再生できるクリップ[..再生できるクリップ.len().min(同時に重ねられる行の数)];
        let 格子 = 格子の分割::個数から決める(
            u32::try_from(置くクリップ.len()).unwrap_or(u32::MAX),
        );
        let mut 重ね合わせ = Self::作成する(
            重ねる画面の縦横比::スタックの出力のアスペクト比から決める(
                出力のアスペクト比,
            ),
            使う動画の表::一本の動画から作成する(動画),
        );
        for (番号, クリップ) in (0..).zip(置くクリップ) {
            let ます目 = 格子
                .ます目の映す矩形(番号)
                .map_err(スタックから並べるエラー::ます目を映す矩形にできない)?;
            重ね合わせ.ます目へ置く(クリップ, ます目, 動画の長さ, 発行元)?;
        }
        Ok(スタックから並べた結果 {
            重ね合わせ,
            置かなかったクリップの数: 再生できるクリップ.len() - 置くクリップ.len(),
        })
    }

    /// クリップから受け継いだ値を始まりの時刻0で置き、その映す矩形を格子のます目に変える。
    fn ます目へ置く(
        &mut self,
        クリップ: &クリップ,
        ます目: 映す矩形,
        動画の長さ: 時間の長さ,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) -> Result<(), スタックから並べるエラー> {
        let 置けない = |理由| スタックから並べるエラー::クリップを置けない {
            名前: クリップ.名前.clone(),
            理由,
        };
        let 識別子 = self
            .クリップから受け継いだ値を置く(
                クリップから受け継いだ値::クリップから受け継ぐ(クリップ),
                動画の番号::最初,
                時刻::先頭,
                動画の長さ,
                発行元,
            )
            .map_err(置けない)?;
        self.映す矩形を変える(&識別子, ます目).map_err(置けない)
    }
}
