//! スタックから並べるときの格子。並べる個数から列と行の数を決め、置いたクリップの映す矩形を左上から順のます目に変える。

use std::num::NonZeroU32;

use crate::overlay::aggregate::重ね合わせ;
use crate::overlay::basis::重ねる画面に対する;
use crate::overlay::placed_id::置いたクリップの識別子;
use crate::overlay::rect::映す矩形;
use crate::overlay::rows::同時に重ねられる行の数;
use crate::percent::{百分率, 等分した区間};

/// 格子に並べる個数とは、スタックから並べるときに格子のます目へ入れる置いたクリップの数のことであり、
/// 1以上、同時に重ねられる行の数以下である。
#[derive(Debug, Clone, Copy)]
pub(super) struct 格子に並べる個数(NonZeroU32);

impl 格子に並べる個数 {
    // 1以上・同時に重ねられる行の数以下でなければ無い。
    pub(super) fn 作成する(個数: usize) -> Option<Self> {
        if 個数 > 同時に重ねられる行の数 {
            return None;
        }
        u32::try_from(個数).ok().and_then(NonZeroU32::new).map(Self)
    }
}

/// 格子とは、重ねる画面を縦横に等分した区切りのことであり、ます目とは、格子の1つの区切り(1列と1行が交わる所)のことである。
/// 格子の分割とは、格子の列の数と行の数の組のことである。列の数は個数の平方根を切り上げた数、行の数は個数を列の数で割って
/// 切り上げた数である(同時再生.md 2-2)。
struct 格子の分割 {
    列の数: NonZeroU32,
    行の数: NonZeroU32,
}

impl 格子の分割 {
    fn 個数から決める(個数: 格子に並べる個数) -> Self {
        let 個数 = 個数.0.get();
        let mut 列の数 = NonZeroU32::MIN;
        while 列の数.get() * 列の数.get() < 個数 {
            列の数 = 列の数.saturating_add(1);
        }
        Self {
            列の数,
            行の数: NonZeroU32::MIN.saturating_add((個数 - 1) / 列の数.get()),
        }
    }

    // ます目の映す矩形を、左上から、行ごとに左から右へ、上の行から下の行への順に返す。最後の行の余るます目も含む。
    fn ます目の映す矩形の並び(&self) -> Vec<映す矩形> {
        let 列の並び: Vec<等分した区間<重ねる画面に対する>> =
            百分率::全体を等分した区間の並び(self.列の数).collect();
        百分率::全体を等分した区間の並び(self.行の数)
            .flat_map(|行| 列の並び.iter().map(move |列| ます目の映す矩形(*列, 行)))
            .collect()
    }
}

impl 重ね合わせ {
    // 置いた順の識別子の置いたクリップの映す矩形を、格子の左上から順のます目に変える。識別子は直前に置いたものなので必ずある。
    pub(super) fn 置いたクリップを格子のます目へ映す(
        &mut self,
        置いた識別子の並び: &[置いたクリップの識別子],
        個数: 格子に並べる個数,
    ) {
        let ます目の並び = 格子の分割::個数から決める(個数).ます目の映す矩形の並び();
        for (識別子, ます目) in 置いた識別子の並び.iter().zip(ます目の並び) {
            if let Err(エラー) = self.映す矩形を変える(識別子, ます目) {
                panic!("直前に置いた置いたクリップが見つからない(到達したらバグ): {エラー}");
            }
        }
    }
}

// 等分した区間はどれも5%以上(分割数は3以下)で全体の内側に収まるため、映す矩形は拒まない。
fn ます目の映す矩形(
    列: 等分した区間<重ねる画面に対する>,
    行: 等分した区間<重ねる画面に対する>,
) -> 映す矩形 {
    match 映す矩形::作成する(列.始まり, 行.始まり, 列.大きさ, 行.大きさ) {
        Ok(矩形) => 矩形,
        Err(エラー) => panic!("格子のます目を映す矩形にできない(到達したらバグ): {エラー}"),
    }
}
