//! スタックから並べるときの格子。置いたクリップの数から列と行の数を決め、並べた順の番号のます目を映す矩形にする。

use crate::overlay::basis::重ねる画面に対する;
use crate::overlay::rect::{映す矩形, 映す矩形エラー};
use crate::percent::百分率;

/// 格子の分割とは、重ねる画面を縦横に等分するときの列の数と行の数の組のことである。
/// 列の数は個数の平方根を切り上げた数、行の数は個数を列の数で割って切り上げた数である(同時再生.md 2-2)。
/// ます目は左上から、行ごとに左から右へ、上の行から下の行への順に番号を振る。
pub(super) struct 格子の分割 {
    列の数: u32,
    行の数: u32,
}

impl 格子の分割 {
    /// 並べる個数から決める。個数は1以上であること(0なら1つのます目にする)。
    pub(super) fn 個数から決める(個数: u32) -> Self {
        let 個数 = 個数.max(1);
        let mut 列の数 = 1;
        while 列の数 * 列の数 < 個数 {
            列の数 += 1;
        }
        Self {
            列の数,
            行の数: 個数.div_ceil(列の数),
        }
    }

    /// 並べた順の番号のます目を映す矩形にする。
    /// 注意: 映す矩形は誤差を許さないため、各ます目の大きさは隣の境界との差で求め、最後の列と行の境界は100ちょうどにする。
    /// そのため最後の列と行の大きさは100から左端・上端を引いた値になり、左端+幅と上端+高さは100を超えない。
    pub(super) fn ます目の映す矩形(
        &self,
        並べた順の番号: u32,
    ) -> Result<映す矩形, 映す矩形エラー> {
        let 列 = 並べた順の番号 % self.列の数;
        let 行 = 並べた順の番号 / self.列の数;
        let 左端 = 境界(列, self.列の数);
        let 上端 = 境界(行, self.行の数);
        映す矩形::作成する(
            百分率::範囲へ収める(左端),
            百分率::範囲へ収める(上端),
            百分率::範囲へ収める(境界(列 + 1, self.列の数) - 左端),
            百分率::範囲へ収める(境界(行 + 1, self.行の数) - 上端),
        )
    }
}

/// 分割数で等分した境界のうち、位置番目の境界の百分率の数値。最後の境界(位置が分割数)は100ちょうどである。
fn 境界(位置: u32, 分割数: u32) -> f64 {
    if 位置 >= 分割数 {
        return 百分率::<重ねる画面に対する>::全体.数値();
    }
    百分率::<重ねる画面に対する>::全体.数値() * f64::from(位置) / f64::from(分割数)
}
