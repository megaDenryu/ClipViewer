//! スタックから並べることが拒まれた理由。

use super::result::置かなかったクリップ;

/// スタックから並べるエラーとは、スタックから重ね合わせを並べられなかった理由のことであり、置けるクリップが1つも無いときだけ起きる。
/// 拒んだときは重ね合わせを返さず、元のスタックも変えない。一部のクリップを置けないときは拒まず、結果の置かなかったクリップの一覧で知らせる。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum スタックから並べるエラー {
    /// スタックに再生できるクリップ(有効で区間の長さが0でないもの)が1つも無い。
    #[error("スタックに再生できるクリップが無い")]
    再生できるクリップが無い,
    /// 再生できるクリップはあるが、置く操作がどれも拒んだ。置かなかったクリップの一覧に、名前と理由を並べる。
    #[error("スタックの再生できるクリップをどれも置けない({}件)", .0.len())]
    置けるクリップが無い(Vec<置かなかったクリップ>),
}
