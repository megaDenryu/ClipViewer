//! スタックから並べることが拒まれた理由。

use crate::clip::クリップ名;
use crate::overlay::error::重ね合わせの操作エラー;
use crate::overlay::rect::映す矩形エラー;

/// スタックから並べるエラーとは、スタックから重ね合わせを並べられなかった理由のことである。
/// 拒んだときは重ね合わせを返さず、元のスタックも変えない。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum スタックから並べるエラー {
    /// スタックに再生できるクリップ(有効で区間の長さが0でないもの)が1つも無い。
    #[error("スタックに再生できるクリップが無い")]
    再生できるクリップが無い,
    /// 置く操作がクリップを拒んだ(区間の終わりが動画の長さより後ろにある等)。
    #[error("クリップ「{}」を置けない: {理由}", 名前.文字列())]
    クリップを置けない {
        /// 置けなかったクリップの名前。
        名前: クリップ名,
        /// 置く操作が拒んだ理由。
        理由: 重ね合わせの操作エラー,
    },
    /// 格子のます目が映す矩形の不変条件を満たさない。並べる個数を同時に重ねられる行の数までに限るため、起きない。
    #[error("格子のます目を映す矩形にできない: {0}")]
    ます目を映す矩形にできない(映す矩形エラー),
}
