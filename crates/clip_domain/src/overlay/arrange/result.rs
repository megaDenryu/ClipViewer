//! スタックから並べた結果と、その中の置かなかったクリップと置かなかった理由。

use crate::clip::クリップ名;
use crate::overlay::aggregate::重ね合わせ;
use crate::overlay::error::重ね合わせの操作エラー;

/// スタックから並べた結果とは、スタックから並べた重ね合わせと、再生できるのに置かなかったクリップの一覧の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub struct スタックから並べた結果 {
    /// 並べた重ね合わせ。置いたクリップを1つ以上持つ。
    pub 重ね合わせ: 重ね合わせ,
    /// 再生できるのに置かなかったクリップを、スタックの順に並べたもの。全部を置いたときは空である。
    pub 置かなかったクリップの一覧: Vec<置かなかったクリップ>,
}

/// 置かなかったクリップとは、スタックから並べるときに、再生できるのに重ね合わせへ置かなかったクリップの名前と理由の組のことである。
/// 画面は、この一覧で利用者に何を置かなかったかを知らせる。
#[derive(Debug, Clone, PartialEq)]
pub struct 置かなかったクリップ {
    /// 置かなかったクリップの名前。
    pub 名前: クリップ名,
    /// 置かなかった理由。
    pub 理由: 置かなかった理由,
}

/// 置かなかった理由とは、スタックから並べるときに、再生できるクリップを重ね合わせへ置かなかった理由のことである。
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum 置かなかった理由 {
    /// 同時に重ねられる行の数だけ置き終えた後ろのクリップであり、置く行が無い。
    #[error("同時に重ねられる行の数だけ置き終えた後ろにある")]
    行の数の上限を超える,
    /// 置く操作が拒んだ(区間の終わりが動画の長さより後ろにある等)。
    #[error("置けない: {0}")]
    置く操作が拒んだ(重ね合わせの操作エラー),
}
