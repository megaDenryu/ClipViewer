//! 置いたクリップ。重ね合わせの中のタイムラインの行に置かれた、映す場所と音量と始まりの時刻を持つ、スタックのクリップとは別の型。

use super::basis::重ね合わせ上の秒;
use super::inherited::クリップから受け継いだ値;
use super::placed_id::置いたクリップの識別子;
use super::rect::映す矩形;
use super::video_table::動画の番号;
use super::volume::置いたクリップの音量;
use crate::duration::時間の長さ;

/// 置いたクリップとは、1本の動画の区間に、リピート回数・クロップ範囲・動画の番号・重ね合わせ上の始まりの時刻・
/// 映す矩形・置いたクリップの音量を付けたもののことである。スタックのクリップ(`クリップ`)とは別の型である。
/// 識別子・動画の番号・始まりの時刻は重ね合わせの不変条件にかかわるため、重ね合わせの操作だけが変える。
#[derive(Debug, Clone, PartialEq)]
pub struct 置いたクリップ {
    識別子: 置いたクリップの識別子,
    受け継いだ値: クリップから受け継いだ値,
    動画: 動画の番号,
    始まりの時刻: 重ね合わせ上の秒,
    映す矩形: 映す矩形,
    音量: 置いたクリップの音量,
}

impl 置いたクリップ {
    /// 映す矩形を重ねる画面の全体、音量を最初の値にして作る。動画の番号が表にあることは呼び出し側(重ね合わせ)が確かめる。
    pub(crate) fn 既定値で作成する(
        識別子: 置いたクリップの識別子,
        受け継いだ値: クリップから受け継いだ値,
        動画: 動画の番号,
        始まりの時刻: 重ね合わせ上の秒,
    ) -> Self {
        Self {
            識別子,
            受け継いだ値,
            動画,
            始まりの時刻,
            映す矩形: 映す矩形::全体,
            音量: 置いたクリップの音量::最初の値,
        }
    }

    /// 識別子。
    pub fn 識別子(&self) -> &置いたクリップの識別子 {
        &self.識別子
    }

    /// スタックのクリップから受け継いだ名前・区間・リピート回数・クロップ範囲。
    pub fn 受け継いだ値(&self) -> &クリップから受け継いだ値 {
        &self.受け継いだ値
    }

    /// 使う動画の表の中で、このクリップの動画を指す番号。
    pub fn 動画の番号(&self) -> 動画の番号 {
        self.動画
    }

    /// 重ね合わせ上で映り始める時刻。
    pub fn 始まりの時刻(&self) -> 重ね合わせ上の秒 {
        self.始まりの時刻
    }

    /// 映り終わる時刻。始まりの時刻に占める長さを足した時刻であり、この時刻にはもう映っていない。
    pub fn 終わりの時刻(&self) -> 重ね合わせ上の秒 {
        self.始まりの時刻.進める(self.占める長さ())
    }

    /// 占める長さ。区間の長さにリピート回数を掛けた長さである。
    pub fn 占める長さ(&self) -> 時間の長さ {
        self.受け継いだ値.占める長さ()
    }

    /// 重ねる画面のどこにどの大きさで映すか。
    pub fn 映す矩形(&self) -> 映す矩形 {
        self.映す矩形
    }

    /// 音の大きさと消音しているか。
    pub fn 音量(&self) -> 置いたクリップの音量 {
        self.音量
    }

    /// 始まりの時刻から占める長さの間が、別の時間の範囲と重なるか。端が接するだけなら重ならない。
    pub(crate) fn 時間が重なるか(
        &self, 始まり: 重ね合わせ上の秒, 長さ: 時間の長さ
    ) -> bool {
        self.始まりの時刻 < 始まり.進める(長さ) && 始まり < self.終わりの時刻()
    }

    pub(crate) fn 始まりの時刻を変えたもの(
        mut self,
        始まりの時刻: 重ね合わせ上の秒,
    ) -> Self {
        self.始まりの時刻 = 始まりの時刻;
        self
    }

    pub(crate) fn 映す矩形を変える(&mut self, 映す矩形: 映す矩形) {
        self.映す矩形 = 映す矩形;
    }
}
