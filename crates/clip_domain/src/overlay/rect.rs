//! 映す矩形の値オブジェクト。座標と大きさはすべて重ねる画面に対する百分率で持つ。

use super::basis::重ねる画面に対する;
use crate::crop::クロップ範囲;
use crate::percent::百分率;

/// 映す矩形とは、置いたクリップのクロップを掛けた絵を、重ねる画面のどこにどの大きさで映すかを表す矩形のことであり、
/// 重ねる画面の幅と高さに対する百分率で左端・上端・幅・高さを持つ。
/// 不変条件: 重ねる画面の内側にあり(左端+幅と上端+高さが100以下)、幅と高さは5以上である(クロップ枠と同じ最小の大きさ)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 映す矩形 {
    左端: 百分率<重ねる画面に対する>,
    上端: 百分率<重ねる画面に対する>,
    幅: 百分率<重ねる画面に対する>,
    高さ: 百分率<重ねる画面に対する>,
}

/// 映す矩形エラーとは、矩形が映す矩形の不変条件を満たさない理由のことである。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 映す矩形エラー {
    /// 幅か高さが5%より小さい。
    #[error("映す矩形の幅({幅}%)か高さ({高さ}%)が5%より小さい")]
    小さすぎる {
        /// 渡された幅の数値。
        幅: f64,
        /// 渡された高さの数値。
        高さ: f64,
    },
    /// 右端か下端が重ねる画面の外へ出る。
    #[error("映す矩形の右端({右端}%)か下端({下端}%)が重ねる画面の外へ出る")]
    画面の外へ出る {
        /// 左端+幅の数値。
        右端: f64,
        /// 上端+高さの数値。
        下端: f64,
    },
}

impl 映す矩形 {
    /// 右端と下端が100を超えたとみなさない誤差。等分した格子のます目を足し合わせたときの丸めの誤差を許すために置く。
    const 許す誤差: f64 = 1e-9;

    /// 重ねる画面の全体を覆う矩形。新しく置いたクリップの映す矩形である。
    pub const 全体: Self = Self {
        左端: 百分率::ゼロ,
        上端: 百分率::ゼロ,
        幅: 百分率::全体,
        高さ: 百分率::全体,
    };

    /// 左端・上端・幅・高さから作成する。小さすぎる矩形と、重ねる画面の外へ出る矩形を拒む。
    pub fn 作成する(
        左端: 百分率<重ねる画面に対する>,
        上端: 百分率<重ねる画面に対する>,
        幅: 百分率<重ねる画面に対する>,
        高さ: 百分率<重ねる画面に対する>,
    ) -> Result<Self, 映す矩形エラー> {
        if 幅.数値() < クロップ範囲::最小の大きさ
            || 高さ.数値() < クロップ範囲::最小の大きさ
        {
            return Err(映す矩形エラー::小さすぎる {
                幅: 幅.数値(),
                高さ: 高さ.数値(),
            });
        }
        let 右端 = 左端.数値() + 幅.数値();
        let 下端 = 上端.数値() + 高さ.数値();
        if 右端 > 100.0 + Self::許す誤差 || 下端 > 100.0 + Self::許す誤差 {
            return Err(映す矩形エラー::画面の外へ出る { 右端, 下端 });
        }
        Ok(Self {
            左端,
            上端,
            幅,
            高さ,
        })
    }

    /// 左端の位置。
    pub fn 左端(&self) -> 百分率<重ねる画面に対する> {
        self.左端
    }

    /// 上端の位置。
    pub fn 上端(&self) -> 百分率<重ねる画面に対する> {
        self.上端
    }

    /// 幅。
    pub fn 幅(&self) -> 百分率<重ねる画面に対する> {
        self.幅
    }

    /// 高さ。
    pub fn 高さ(&self) -> 百分率<重ねる画面に対する> {
        self.高さ
    }
}
