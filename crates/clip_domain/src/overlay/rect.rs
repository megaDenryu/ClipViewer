//! 映す矩形の値オブジェクト。座標と大きさはすべて重ねる画面に対する百分率で持つ。

use super::basis::重ねる画面に対する;
use crate::crop::クロップ範囲;
use crate::percent::百分率;

/// 映す矩形とは、置いたクリップのクロップを掛けた絵を、重ねる画面のどこにどの大きさで映すかを表す矩形のことであり、
/// 重ねる画面の幅と高さに対する百分率で左端・上端・幅・高さを持つ。
/// 不変条件: 重ねる画面の内側にあり(左端+幅と上端+高さが100以下)、幅と高さは5以上である(クロップ枠と同じ最小の大きさ)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 映す矩形 {
    左端: 百分率<重ねる画面に対する>,
    上端: 百分率<重ねる画面に対する>,
    幅: 百分率<重ねる画面に対する>,
    高さ: 百分率<重ねる画面に対する>,
}

/// 映す矩形エラーとは、渡された左端・上端・幅・高さが映す矩形の不変条件を満たさない理由のことである。
#[derive(Debug, Clone, Copy, PartialEq, thiserror::Error)]
pub enum 映す矩形エラー {
    /// 幅か高さが5%より小さい。
    #[error("映す矩形の幅({}%)か高さ({}%)が5%より小さい", 幅.数値(), 高さ.数値())]
    小さすぎる {
        /// 渡された幅。
        幅: 百分率<重ねる画面に対する>,
        /// 渡された高さ。
        高さ: 百分率<重ねる画面に対する>,
    },
    /// 左端と幅を足すと100%を超え、右端が重ねる画面の外へ出る。
    #[error("映す矩形の左端({}%)と幅({}%)を足すと100%を超える", 左端.数値(), 幅.数値())]
    右へはみ出す {
        /// 渡された左端。
        左端: 百分率<重ねる画面に対する>,
        /// 渡された幅。
        幅: 百分率<重ねる画面に対する>,
    },
    /// 上端と高さを足すと100%を超え、下端が重ねる画面の外へ出る。
    #[error("映す矩形の上端({}%)と高さ({}%)を足すと100%を超える", 上端.数値(), 高さ.数値())]
    下へはみ出す {
        /// 渡された上端。
        上端: 百分率<重ねる画面に対する>,
        /// 渡された高さ。
        高さ: 百分率<重ねる画面に対する>,
    },
}

impl 映す矩形 {
    /// 全体とは、重ねる画面の全体を覆う映す矩形のことである。新しく置いたクリップの映す矩形である。
    pub const 全体: Self = Self {
        左端: 百分率::ゼロ,
        上端: 百分率::ゼロ,
        幅: 百分率::全体,
        高さ: 百分率::全体,
    };

    /// 左端・上端・幅・高さから作成する。小さすぎる矩形と、重ねる画面の外へ出る矩形を拒む。
    /// 注意: 誤差を許さない。等分した格子のます目を作る側が、最後の列と行の大きさを100から引いて求め、丸めの誤差を吸収する。
    pub fn 作成する(
        左端: 百分率<重ねる画面に対する>,
        上端: 百分率<重ねる画面に対する>,
        幅: 百分率<重ねる画面に対する>,
        高さ: 百分率<重ねる画面に対する>,
    ) -> Result<Self, 映す矩形エラー> {
        let 最小 = クロップ範囲::最小の大きさ;
        if 幅.数値() < 最小 || 高さ.数値() < 最小 {
            return Err(映す矩形エラー::小さすぎる { 幅, 高さ });
        }
        if 左端.数値() + 幅.数値() > 100.0 {
            return Err(映す矩形エラー::右へはみ出す { 左端, 幅 });
        }
        if 上端.数値() + 高さ.数値() > 100.0 {
            return Err(映す矩形エラー::下へはみ出す { 上端, 高さ });
        }
        Ok(Self {
            左端,
            上端,
            幅,
            高さ,
        })
    }

    /// 左端の位置。
    pub fn 左端(&self) -> 百分率<重ねる画面に対する> {
        self.左端
    }

    /// 上端の位置。
    pub fn 上端(&self) -> 百分率<重ねる画面に対する> {
        self.上端
    }

    /// 幅。
    pub fn 幅(&self) -> 百分率<重ねる画面に対する> {
        self.幅
    }

    /// 高さ。
    pub fn 高さ(&self) -> 百分率<重ねる画面に対する> {
        self.高さ
    }
}
