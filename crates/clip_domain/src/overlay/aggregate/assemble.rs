//! 重ね合わせの部品一式から重ね合わせを組み立てる口と、重ね合わせから部品一式を複製する口。
//! 組み立ては、ファイルから読んだ全部の値を持つ重ね合わせを作るときに使い、重ね合わせの不変条件を全部確かめる。
//! 縦横比と映す矩形と音量の条件は、部品一式を作る時点でそれぞれの型が守っている。参照: _doc/設計/同時再生.md 4-1・4-2

use super::重ね合わせ;
use crate::overlay::assemble_error::重ね合わせを組み立てられない理由;
use crate::overlay::error::重ね合わせの操作エラー;
use crate::overlay::parts::{
    タイムラインの行の部品一式, 置いたクリップの部品一式, 部品の並びの中の位置,
    重ね合わせの部品一式,
};
use crate::overlay::rows::{置いたクリップ, 行の番号};

impl 重ね合わせの部品一式 {
    /// 重ね合わせを組み立てる。行の数が同時に重ねられる行の数を超えるときと、置いたクリップの識別子が重なるとき・動画の番号が表に無いとき・
    /// 区間の長さが0のとき・同じ行のほかの置いたクリップと時間が重なるときは拒む。行の中の置いたクリップは始まりの時刻の順に並べる。
    /// 区間の終わりが動画の長さより後ろにあるかは確かめない(動画の長さは保存しないため。同時再生.md 4-1)。
    pub fn 重ね合わせへ組み立てる(
        self,
    ) -> Result<重ね合わせ, 重ね合わせを組み立てられない理由> {
        let Self {
            縦横比,
            動画の表,
            行の並び,
        } = self;
        let 行の数 = 行の並び.len();
        let mut 重ね = 重ね合わせ::作成する(縦横比, 動画の表);
        for 行の部品一式 in 行の並び {
            let 行 =
                重ね.行の並び.空の行を手前に足す().map_err(|_| {
                    重ね合わせを組み立てられない理由::行の数が上限を超える { 行の数 }
                })?;
            for (位置, 部品一式) in 行の部品一式.置いたクリップの並び.into_iter().enumerate()
            {
                重ね.行へ差し込む(行, 部品一式).map_err(|理由| {
                    重ね合わせを組み立てられない理由::置いたクリップを置けない {
                        行,
                        位置: 部品の並びの中の位置::番号から作成する(位置),
                        理由,
                    }
                })?;
            }
        }
        Ok(重ね)
    }
}

impl 重ね合わせ {
    /// すべての値の写しを、奥から手前の順の行ごとに、行の中は始まりの時刻の順に作る。保存の形式へ書き出すときに使う。
    pub fn 部品一式を複製する(&self) -> 重ね合わせの部品一式 {
        let Self {
            縦横比,
            動画の表,
            行の並び,
        } = self;
        重ね合わせの部品一式 {
            縦横比: *縦横比,
            動画の表: 動画の表.clone(),
            行の並び: 行の並び
                .奥から手前の順の行()
                .iter()
                .map(|行| タイムラインの行の部品一式 {
                    置いたクリップの並び: 行
                        .置いたクリップの並び()
                        .iter()
                        .map(置いたクリップ::部品一式を複製する)
                        .collect(),
                })
                .collect(),
        }
    }

    // 置いたクリップの値を、動画の番号が表にあることと区間の長さが0でないことを確かめてから、行の番号の行へ差し込む。
    fn 行へ差し込む(
        &mut self,
        行: 行の番号,
        部品一式: 置いたクリップの部品一式,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.動画が表にあるか確かめる(部品一式.動画)?;
        if 部品一式.受け継いだ値.占める長さ().ゼロか() {
            return Err(重ね合わせの操作エラー::区間の長さが0);
        }
        self.行の並び
            .確かめて行へ差し込む(行, 置いたクリップ::部品一式から作る(部品一式))
    }
}
