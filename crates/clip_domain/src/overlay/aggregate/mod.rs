//! 重ね合わせの型と、その中身を読む口と、置いたクリップを動かす・映す矩形を変える・音の設定を変える・取り除く操作。
//! 行と時間と識別子の不変条件はタイムラインの行の並びが守り、重ね合わせは委ねる。置く操作は子の `place.rs`に置く。

mod place;

use super::aspect::重ねる画面の縦横比;
use super::basis::重ね合わせ上の秒;
use super::error::重ね合わせの操作エラー;
use super::placed_id::置いたクリップの識別子;
use super::rect::映す矩形;
use super::rows::{タイムラインの行の並び, 置いたクリップ, 行の番号};
use super::video_table::使う動画の表;
use super::volume::置いたクリップの音の変更;

/// 重ね合わせとは、重ねる画面の縦横比と、使う動画の表と、タイムラインの行の並びの組のことである。
/// 重ね合わせは、同時再生で再生するものの全部であり、ライブラリへ1ファイルとして保存する単位である。
/// 不変条件: 置いたクリップの動画の番号は使う動画の表にある(置く操作が確かめる)。ほかの不変条件は部品の型が守る。
#[derive(Debug, Clone, PartialEq)]
pub struct 重ね合わせ {
    縦横比: 重ねる画面の縦横比,
    動画の表: 使う動画の表,
    行の並び: タイムラインの行の並び,
}

impl 重ね合わせ {
    /// 行を1つも持たない重ね合わせを作成する。
    pub fn 作成する(
        縦横比: 重ねる画面の縦横比, 動画の表: 使う動画の表
    ) -> Self {
        Self {
            縦横比,
            動画の表,
            行の並び: タイムラインの行の並び::default(),
        }
    }

    /// 重ねる画面の縦横比。
    pub fn 縦横比(&self) -> 重ねる画面の縦横比 {
        self.縦横比
    }

    /// 重ねる画面の縦横比を変える。映す矩形は重ねる画面に対する百分率のまま残るため、置いたクリップの形は新しい縦横比に合わせて伸びる(同時再生.md 2-5)。
    pub fn 縦横比を変える(&mut self, 縦横比: 重ねる画面の縦横比) {
        self.縦横比 = 縦横比;
    }

    /// 使う動画の表。
    pub fn 動画の表(&self) -> &使う動画の表 {
        &self.動画の表
    }

    /// タイムラインの行の並び。
    pub fn 行の並び(&self) -> &タイムラインの行の並び {
        &self.行の並び
    }

    /// 識別子の置いたクリップを探す。
    pub fn 識別子で探す(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Option<&置いたクリップ> {
        self.行の並び.識別子で探す(識別子)
    }

    /// 重ね合わせの長さとは、すべての置いたクリップの終わりの時刻のうち最も遅い時刻のことである。置いたクリップが無ければ0秒である。
    pub fn 重ね合わせの長さ(&self) -> 重ね合わせ上の秒 {
        self.行の並び.最も遅い終わりの時刻()
    }

    /// 置いたクリップを、先の行の始まりの時刻へ動かす。同じ行の中で時刻だけを変えるときも、先の行に今の行を渡す。
    /// 先の行が無いとき、先の行でほかの置いたクリップと時間が重なるときは拒む。
    pub fn 置いたクリップを動かす(
        &mut self,
        識別子: &置いたクリップの識別子,
        先の行: 行の番号,
        始まりの時刻: 重ね合わせ上の秒,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.行の並び
            .置いたクリップを動かす(識別子, 先の行, 始まりの時刻)
    }

    /// 置いたクリップの映す矩形を変える。映す矩形の不変条件は型が守るため、識別子が無いときだけ拒む。
    pub fn 映す矩形を変える(
        &mut self,
        識別子: &置いたクリップの識別子,
        映す矩形: 映す矩形,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.行の並び
            .置いたクリップの映す矩形を変える(識別子, 映す矩形)
    }

    /// 置いたクリップの音の設定(音量と消音しているか)を、音量を選ぶか消音を設定するかの変更で変える。識別子が無いときだけ拒む。
    /// 置いたクリップごとに別々の値であり、ほかの置いたクリップの音の設定は変わらない(同時再生.md 2-6)。
    pub fn 置いたクリップの音を変える(
        &mut self,
        識別子: &置いたクリップの識別子,
        変更: 置いたクリップの音の変更,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.行の並び.置いたクリップの音を変える(識別子, 変更)
    }

    /// 行の番号の空の行を消す。後ろ(手前)の行の番号は1つずつ小さくなる。行が無いときと、置いたクリップを持つ行のときは拒む。
    pub fn 空の行を消す(
        &mut self,
        行: 行の番号,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.行の並び.空の行を消す(行)
    }

    /// 空の新しい行を最も手前に足し、足した行の番号を返す。行がすでに同時に重ねられる行の数まであるときは拒む。
    pub fn 空の行を手前に足す(
        &mut self,
    ) -> Result<行の番号, 重ね合わせの操作エラー> {
        self.行の並び.空の行を手前に足す()
    }

    /// 置いたクリップを取り除き、取り除いたものを返す。行は空になっても残す(ほかの行の番号と重なりの順を変えないため)。
    pub fn 置いたクリップを取り除く(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) -> Result<置いたクリップ, 重ね合わせの操作エラー> {
        self.行の並び.置いたクリップを取り除く(識別子)
    }
}
