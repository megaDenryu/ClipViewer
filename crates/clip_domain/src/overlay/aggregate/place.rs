//! 重ね合わせへ置く操作と、置く前に重ね合わせが受け持つ確かめ(動画の番号・区間と動画の長さ・区間の長さ)。
//! 置く操作は、空いている最も手前の行へ置くものと、最も手前に新しい行を足して置くものの2つである。
//! 確かめを全部済ませてからタイムラインの行の並びへ置く。拒んだときは重ね合わせを操作の前のまま残す。

use super::重ね合わせ;
use crate::duration::時間の長さ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::error::重ね合わせの操作エラー;
use crate::overlay::inherited::クリップから受け継いだ値;
use crate::overlay::placed_id::{
    置いたクリップの識別子, 置いたクリップの識別子の発行元
};
use crate::overlay::rows::置いたクリップ;
use crate::overlay::video_table::動画の番号;
use crate::time::時刻;

impl 重ね合わせ {
    /// クリップから受け継いだ値から置いたクリップを作り、始まりの時刻に空いている最も手前の行へ置いて、発行した識別子を返す。
    /// どの行も空いていなければ、最も手前に新しい行を足して置く。映す矩形は重ねる画面の全体、音の設定は最初の値である。
    /// 動画の長さは、置く動画を開いた呼び出し側が渡す。動画の番号が表に無いとき、区間の終わりが動画の長さより後ろのとき、
    /// 区間の長さが0のとき、発行した識別子が重なるとき、行が同時に重ねられる行の数まであってどれも空いていないときは拒む。
    pub fn クリップから受け継いだ値を置く(
        &mut self,
        受け継いだ値: クリップから受け継いだ値,
        動画: 動画の番号,
        始まりの時刻: 重ね合わせ上の秒,
        動画の長さ: 時間の長さ,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) -> Result<置いたクリップの識別子, 重ね合わせの操作エラー> {
        let 置いた = self.確かめてから置いたクリップを作る(
            受け継いだ値,
            動画,
            始まりの時刻,
            動画の長さ,
            発行元,
        )?;
        let 識別子 = 置いた.識別子().clone();
        self.行の並び.空いている最も手前の行へ置く(置いた)?;
        Ok(識別子)
    }

    /// クリップから受け継いだ値から置いたクリップを作り、ほかの行の空きを問わず、最も手前に新しい行を足してそこへ置いて、
    /// 発行した識別子を返す。映す矩形は重ねる画面の全体、音の設定は最初の値である。拒む場合は `クリップから受け継いだ値を置く`
    /// と同じ確かめに通らないときと、行がすでに同時に重ねられる行の数まであるときである。
    pub fn 手前に新しい行を足して置く(
        &mut self,
        受け継いだ値: クリップから受け継いだ値,
        動画: 動画の番号,
        始まりの時刻: 重ね合わせ上の秒,
        動画の長さ: 時間の長さ,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) -> Result<置いたクリップの識別子, 重ね合わせの操作エラー> {
        let 置いた = self.確かめてから置いたクリップを作る(
            受け継いだ値,
            動画,
            始まりの時刻,
            動画の長さ,
            発行元,
        )?;
        let 識別子 = 置いた.識別子().clone();
        self.行の並び.手前に新しい行を足して置く(置いた)?;
        Ok(識別子)
    }

    // 動画の番号・区間と動画の長さ・区間の長さを確かめてから識別子を発行し、映す矩形と音の設定を最初の値にした置いたクリップを作る。
    fn 確かめてから置いたクリップを作る(
        &self,
        受け継いだ値: クリップから受け継いだ値,
        動画: 動画の番号,
        始まりの時刻: 重ね合わせ上の秒,
        動画の長さ: 時間の長さ,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) -> Result<置いたクリップ, 重ね合わせの操作エラー> {
        self.動画が表にあるか確かめる(動画)?;
        let 動画の終わり = 時刻::先頭.進める(動画の長さ);
        if 受け継いだ値.区間.終了() > 動画の終わり {
            return Err(重ね合わせの操作エラー::区間が動画の長さを超える {
                区間の終わり: 受け継いだ値.区間.終了(),
                動画の長さ,
            });
        }
        if 受け継いだ値.占める長さ().ゼロか() {
            return Err(重ね合わせの操作エラー::区間の長さが0);
        }
        Ok(置いたクリップ::既定値で作成する(
            発行元.新しい置いたクリップの識別子を発行する(),
            受け継いだ値,
            動画,
            始まりの時刻,
        ))
    }

    pub(super) fn 動画が表にあるか確かめる(
        &self,
        動画: 動画の番号,
    ) -> Result<(), 重ね合わせの操作エラー> {
        if self.動画の表().持っているか(動画) {
            return Ok(());
        }
        Err(重ね合わせの操作エラー::動画の番号が表に無い {
            番号: 動画,
            動画の数: self.動画の表().動画の数(),
        })
    }
}
