//! 重ね合わせの行の操作。空の行を消す操作と、空の新しい行を最も手前に足す操作を、タイムラインの行の並びへ委ねる。
//! 塊のドラッグの行き先を求める口は、読むだけなので `重ね合わせ::行の並び()` から呼ぶ。参照: _doc/設計/同時再生.md 2-6・4-1

use super::重ね合わせ;
use crate::overlay::error::重ね合わせの操作エラー;
use crate::overlay::rows::行の番号;

impl 重ね合わせ {
    /// 行の番号の空の行を消す。後ろ(手前)の行の番号は1つずつ小さくなる。行が無いときと、置いたクリップを持つ行のときは拒む。
    pub fn 空の行を消す(
        &mut self,
        行: 行の番号,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.行の並び.空の行を消す(行)
    }

    /// 空の新しい行を最も手前に足し、足した行の番号を返す。行がすでに同時に重ねられる行の数まであるときは拒む。
    pub fn 空の行を手前に足す(
        &mut self,
    ) -> Result<行の番号, 重ね合わせの操作エラー> {
        self.行の並び.空の行を手前に足す()
    }
}
