//! 重ね合わせの時計の規則。実時間の経過で再生位置を進め、重ね合わせの長さに達したら全体ループに従って先頭へ戻るか止まる。
//! 重ね合わせの作業場は速度のつまみを持たないため、等倍で進める。置いたクリップは待たないため、待ちの巻き戻しも無い。
//! 参照: _doc/設計/同時再生.md 2-6・5-2

use crate::duration::時間の長さ;
use crate::overlay::aggregate::重ね合わせ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::playback_clock::末尾での振る舞い;
use crate::time::時刻;

/// 重ね合わせの再生位置とは、重ね合わせの作業場が再生している、重ね合わせ上の時刻のことである。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 重ね合わせの再生位置(重ね合わせ上の秒);

/// 重ね合わせの時計を進めた結果とは、重ね合わせの再生位置を進めた後の位置と、再生を止めるべきかの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 重ね合わせの時計を進めた結果 {
    /// 再生を続ける。
    続ける(重ね合わせの再生位置),
    /// 重ね合わせの長さに達したので、この位置で再生を止める。
    末尾で止まる(重ね合わせの再生位置),
}

impl 重ね合わせの再生位置 {
    /// 重ね合わせの始まり(0秒)。
    pub const 先頭: Self = Self(時刻::先頭);

    /// 重ね合わせ上の時刻から作成する。区間の終わりの行き先を求めるとき(`span_end.rs`)と、時間の軸で再生の位置を動かすときに使う。
    /// 注意: これで再生位置を指定して移すときは、`clip_viewer` の重ね合わせの供給が行ごとに覚える続く先
    /// (`overlay/feed/continuation.rs`)を全部の行で `止まる` にすること(`開いている重ね合わせ::位置を動かす` はそうしている)。
    /// そうしないと、移る前の置いたクリップの最後のコマが、移った先の置いたクリップの代わりに描かれる(同時再生.md 5-2 の7)。
    pub fn 時刻から作成する(時刻: 重ね合わせ上の秒) -> Self {
        Self(時刻)
    }

    /// 重ね合わせ上の時刻。その時刻に映すものを求めるときに渡す。
    pub fn 時刻(self) -> 重ね合わせ上の秒 {
        self.0
    }

    /// 実時間の経過だけ等倍で進める。進めた位置が重ね合わせの長さ以上なら、全体の末尾での振る舞いが先頭へ戻るなら0秒で続け、
    /// 止まるなら重ね合わせの長さで止まる。置いたクリップが無い重ね合わせは長さが0秒なので、0秒に留まる。
    pub fn 実時間の経過で進める(
        self,
        実時間の経過: 時間の長さ,
        重ね合わせ: &重ね合わせ,
        全体の末尾: 末尾での振る舞い,
    ) -> 重ね合わせの時計を進めた結果 {
        let 進めた位置 = self.0.進める(実時間の経過);
        let 長さ = 重ね合わせ.重ね合わせの長さ();
        if 進めた位置 < 長さ {
            return 重ね合わせの時計を進めた結果::続ける(Self(進めた位置));
        }
        match 全体の末尾 {
            末尾での振る舞い::先頭へ戻る => {
                重ね合わせの時計を進めた結果::続ける(Self::先頭)
            }
            末尾での振る舞い::止まる => {
                重ね合わせの時計を進めた結果::末尾で止まる(Self(長さ))
            }
        }
    }

    /// 再生を始める位置。位置が重ね合わせの長さに達しているときは先頭を返す。
    /// 末尾のまま再生を始めると時計がすぐにまた止めるため、スタックの再生位置と同じく先頭から再生し直す。
    pub fn 再生を始める位置(self, 重ね合わせ: &重ね合わせ) -> Self {
        if self.0 >= 重ね合わせ.重ね合わせの長さ() {
            Self::先頭
        } else {
            self
        }
    }
}
