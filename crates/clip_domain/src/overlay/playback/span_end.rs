//! 置いたクリップの区間の終わりの行き先の規則。行が映している置いたクリップの今の周回の終わりに達したとき、
//! その行の再生がどこへ続くかを、重ね合わせの時計の規則そのもので少し先まで進めて求める。
//! スタックの `区間の終わりの行き先` と同じ求め方であり、時計の規則(全体ループ・末尾で止まる)を二重に書かない。
//! 参照: _doc/設計/同時再生.md 5-2、_doc/設計/アーキテクチャ.md 判断8

use super::at_time::行の再生を求める条件;
use super::clock::{重ね合わせの再生位置, 重ね合わせの時計を進めた結果};
use crate::duration::時間の長さ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::rows::置いたクリップ;

/// 置いたクリップの区間の終わりの行き先とは、行が映している置いたクリップの今の周回の区間の終わりに達したとき、
/// その行の再生がどこへ続くかの区別のことである。進む先は置いたクリップで持ち、動画の番号と区間を落とさない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 置いたクリップの区間の終わりの行き先<'重ね合わせ> {
    /// 同じ区間の開始へ戻って繰り返す。次の周回へ入るとき、および続く置いたクリップが同じ動画の同じ区間のとき。
    区間の開始へ戻る,
    /// 別の置いたクリップの区間の開始へ進む。同じ行で隙間なく続く置いたクリップか、全体ループで0秒の置いたクリップである。
    別の置いたクリップへ進む(&'重ね合わせ 置いたクリップ),
    /// この行の再生が止まる(続く置いたクリップが無い、または重ね合わせの末尾で止まる)。
    止まる,
}

impl<'重ね合わせ> 行の再生を求める条件<'重ね合わせ> {
    /// 当たる置いたクリップの今の周回の終わりを丸めの許容誤差だけ越える時刻まで、等倍で時計を進め、
    /// 進めた時刻にこの行が映す置いたクリップから行き先を決める。同じ動画の同じ区間なら開始へ戻る、違えば別の置いたクリップへ進む、
    /// 何も映さないか時計が末尾で止まるなら止まる。
    pub(super) fn 区間の終わりの行き先を求める(
        &self,
        当たる置いたクリップ: &置いたクリップ,
        時刻: 重ね合わせ上の秒,
        周回の終わりまでの長さ: 時間の長さ,
    ) -> 置いたクリップの区間の終わりの行き先<'重ね合わせ> {
        let 進める長さ = 周回の終わりまでの長さ.足す(時間の長さ::丸めの許容誤差);
        let 進めた位置 = match 重ね合わせの再生位置::時刻から作成する(時刻).実時間の経過で進める(
            進める長さ,
            self.重ね合わせ,
            self.全体の末尾,
        ) {
            重ね合わせの時計を進めた結果::続ける(位置) => 位置,
            重ね合わせの時計を進めた結果::末尾で止まる(_) => {
                return 置いたクリップの区間の終わりの行き先::止まる;
            }
        };
        let Some(進んだ先の置いたクリップ) = self
            .行
            .重ね合わせ上の時刻に当たる置いたクリップ(進めた位置.時刻())
        else {
            return 置いたクリップの区間の終わりの行き先::止まる;
        };
        if 進んだ先の置いたクリップ.動画の番号() == 当たる置いたクリップ.動画の番号()
            && 進んだ先の置いたクリップ.受け継いだ値().区間
                == 当たる置いたクリップ.受け継いだ値().区間
        {
            置いたクリップの区間の終わりの行き先::区間の開始へ戻る
        } else {
            置いたクリップの区間の終わりの行き先::別の置いたクリップへ進む(進んだ先の置いたクリップ)
        }
    }
}
