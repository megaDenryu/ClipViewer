//! 重ね合わせ上の時刻にタイムラインの行が映すものを求めた結果の型。
//! スタックの `タイムライン上の位置で再生するもの` と同じく構造化した値だけを返し、文字列化は画面の側が行う。

use crate::overlay::rows::{置いたクリップ, 行の番号};
use crate::repeat::周回番号;
use crate::span_end::区間の終わりの行き先;
use crate::time::動画上の秒;

/// 行が映すものとは、重ね合わせ上のある時刻に、1つのタイムラインの行が何を映すかを求めた結果のことである。
/// 置いたクリップが無い行も、その行を止める指示を組み立てるために結果に含める。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 行が映すもの<'重ね合わせ> {
    /// 求めた行の番号。
    pub 行: 行の番号,
    /// その時刻にその行が映す中身。
    pub 中身: 行が映す中身<'重ね合わせ>,
}

/// 行が映す中身とは、ある時刻に1つの行が置いたクリップを映しているか、何も映していないかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 行が映す中身<'重ね合わせ> {
    /// その時刻に当たる置いたクリップがある。
    置いたクリップを映す(置いたクリップの再生の中身<'重ね合わせ>),
    /// その時刻に当たる置いたクリップが無い(行の置いたクリップの間の隙間、最初の置いたクリップの前、最後の置いたクリップの後)。
    何も映さない,
}

/// 置いたクリップの再生の中身とは、ある時刻に行が映している置いたクリップと、その中での再生の状況の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 置いたクリップの再生の中身<'重ね合わせ> {
    /// その時刻に当たる置いたクリップ。
    pub 置いたクリップ: &'重ね合わせ 置いたクリップ,
    /// 動画のどこを映すか。区間の開始に、始まりの時刻からの経過を区間の長さで割った余りを足した時刻である。
    pub 動画上の位置: 動画上の秒,
    /// 区間を繰り返している何周目か。
    pub 周回: 周回番号,
    /// 今の周回の区間の終わりに達したとき、この行の再生がどこへ続くか。
    pub 区間の終わりの行き先: 区間の終わりの行き先,
}
