//! 重ね合わせ上の時刻にタイムラインの行が映すものを求めた結果の型。
//! スタックの `タイムライン上の位置で再生するもの` と同じく構造化した値だけを返し、文字列化は画面の側が行う。

use super::span_end::置いたクリップの区間の終わりの行き先;
use crate::overlay::rows::{置いたクリップ, 行の番号};
use crate::repeat::周回番号;
use crate::time::動画上の秒;

/// 行が映すものとは、重ね合わせ上のある時刻に、1つのタイムラインの行が何を映すかを求めた結果のことである。
/// 置いたクリップが無い行も、その行を止める指示を組み立てるために結果に含める。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 行が映すもの<'重ね合わせ> {
    /// 求めた行の番号。
    pub 行: 行の番号,
    /// その時刻にその行が置いたクリップを再生して映すか、末尾で止めたコマを映すか、何も映さないか。
    pub 映し方: 行の映し方<'重ね合わせ>,
}

/// 行の映し方とは、ある時刻に1つの行が、置いたクリップを再生して映すか、重ね合わせの末尾で止めたコマを映すか、
/// 何も映さないかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 行の映し方<'重ね合わせ> {
    /// その時刻に当たる置いたクリップを再生して映す。
    置いたクリップを映す(置いたクリップの再生の中身<'重ね合わせ>),
    /// 時刻が重ね合わせの長さ以降であり、この行の最後の置いたクリップの区間の終わりのコマを映す。
    /// スタックが末尾で最後の再生できるクリップの区間の終わりを映すのと揃える。
    末尾で最後のコマを映す {
        /// この行の最後の(始まりの時刻が最も遅い)置いたクリップ。
        置いたクリップ: &'重ね合わせ 置いたクリップ,
        /// 映すコマの動画上の位置。区間の終わりである。
        動画上の位置: 動画上の秒,
    },
    /// 何も映さない(行の置いたクリップの間の隙間、最初の置いたクリップの前、置いたクリップの無い行)。
    何も映さない,
}

/// 置いたクリップの再生の中身とは、ある時刻に行が映している置いたクリップと、その中での再生の状況の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 置いたクリップの再生の中身<'重ね合わせ> {
    /// その時刻に当たる置いたクリップ。
    pub 置いたクリップ: &'重ね合わせ 置いたクリップ,
    /// 動画のどこを映すか。区間の開始に、始まりの時刻からの経過を区間の長さで割った余りを足した時刻である。
    pub 動画上の位置: 動画上の秒,
    /// 区間を繰り返している何周目か。
    pub 周回: 周回番号,
    /// 今の周回の区間の終わりに達したとき、この行の再生がどこへ続くか。
    pub 区間の終わりの行き先: 置いたクリップの区間の終わりの行き先<'重ね合わせ>,
}
