//! タイムラインの行の中で、重ね合わせ上の時刻に当たる置いたクリップを探すこと。置いたクリップは始まりの時刻から終わりの時刻の手前までを映す
//! (半開区間)。前の置いたクリップの終わりから丸めの許容誤差の内の隙間では、前の置いたクリップを当たるものの代わりに使う。
//! 参照: _doc/設計/同時再生.md 5-2

use crate::duration::時間の長さ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::rows::{タイムラインの行, 置いたクリップ};

impl タイムラインの行 {
    /// 重ね合わせ上の時刻に当たる置いたクリップ。始まりの時刻がその時刻以前の置いたクリップのうち最も後ろのものを選び、
    /// 終わりの時刻の手前ならそれとする。丸めの許容誤差だけ食い込んだ継ぎ目でも、後ろの置いたクリップが当たる。
    pub(super) fn 重ね合わせ上の時刻に当たる置いたクリップ(
        &self,
        時刻: 重ね合わせ上の秒,
    ) -> Option<&置いたクリップ> {
        let 並び = self.置いたクリップの並び();
        let 始まった数 =
            並び.partition_point(|置いたクリップ| 置いたクリップ.始まりの時刻() <= 時刻);
        let 並びの添字 = 始まった数.checked_sub(1)?;
        並び
            .get(並びの添字)
            .filter(|当たる置いたクリップ| 時刻 < 当たる置いたクリップ.終わりの時刻())
    }

    /// 時刻より前に終わった置いたクリップのうち、終わりの時刻から時刻までが丸めの許容誤差より短いもの。
    /// 置く操作は許容誤差以下の食い込みを接しているとみなし、区間の終わりの行き先も許容誤差の内なら続くとするため、
    /// 許容誤差の内の隙間に当たった時刻は、前の置いたクリップの区間の終わり(区間の中の最後のコマ)を映し、行の再生を途切れさせない。
    pub(super) fn 許容誤差の内で終わった置いたクリップ(
        &self,
        時刻: 重ね合わせ上の秒,
    ) -> Option<&置いたクリップ> {
        let 並び = self.置いたクリップの並び();
        let 始まった数 =
            並び.partition_point(|置いたクリップ| 置いたクリップ.始まりの時刻() <= 時刻);
        let 並びの添字 = 始まった数.checked_sub(1)?;
        並び.get(並びの添字).filter(|前の置いたクリップ| {
            let 終わり = 前の置いたクリップ.終わりの時刻();
            時刻 >= 終わり && 時刻 < 終わり.進める(時間の長さ::丸めの許容誤差)
        })
    }
}
