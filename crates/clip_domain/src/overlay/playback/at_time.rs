//! 重ね合わせ上の時刻に、行ごとに映すものを求める処理。
//! 置いたクリップは始まりの時刻から終わりの時刻の手前までを映す(半開区間)。境目ちょうどの時刻は後ろの置いたクリップが映す。
//! 置いたクリップはトリガーと無限ループを持たないため、待ちを考えずに周回と行き先が決まる(同時再生.md 7節の決定1)。
//! 参照: _doc/設計/同時再生.md 5-2

use super::at_time_result::{
    置いたクリップの再生の中身, 行が映すもの, 行が映す中身
};
use crate::overlay::aggregate::重ね合わせ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::rows::{タイムラインの行, 置いたクリップ, 行の番号};
use crate::span_end::区間の終わりの行き先;

impl 重ね合わせ {
    /// 重ね合わせ上の時刻に、行ごとに映すものを、奥の行から手前の行の順に求める。行の数だけ必ず返す。
    pub fn その時刻に映すもの(
        &self,
        時刻: 重ね合わせ上の秒,
    ) -> impl Iterator<Item = 行が映すもの<'_>> {
        self.行の並び()
            .奥から手前の順の行()
            .iter()
            .enumerate()
            .map(move |(番号, 行)| 行が映すもの {
                行: 行の番号::番号から作成する(番号),
                中身: 行.その時刻に映す中身(時刻),
            })
    }
}

impl タイムラインの行 {
    /// 始まりの時刻がその時刻以前の置いたクリップのうち最も後ろのものを選び、終わりの時刻の手前ならそれを映す。
    fn その時刻に映す中身(
        &self, 時刻: 重ね合わせ上の秒
    ) -> 行が映す中身<'_> {
        let 並び = self.置いたクリップの並び();
        let 始まった数 = 並び.partition_point(|置いた| 置いた.始まりの時刻() <= 時刻);
        let Some(位置) = 始まった数.checked_sub(1) else {
            return 行が映す中身::何も映さない;
        };
        let 置いた = &並び[位置];
        if 時刻 >= 置いた.終わりの時刻() {
            return 行が映す中身::何も映さない;
        }
        行が映す中身::置いたクリップを映す(
            置いた.その時刻の再生の中身(時刻, 並び.get(位置 + 1)),
        )
    }
}

impl 置いたクリップ {
    /// その時刻に映している周回と動画上の位置と、今の周回の区間の終わりの行き先を求める。
    /// 注意: 時刻は始まりの時刻から終わりの時刻の手前までにあること。丸めで最後の周回を越えた周回が出たときは、
    /// 最後の周回の区間の終わりとみなす。
    fn その時刻の再生の中身(
        &self,
        時刻: 重ね合わせ上の秒,
        同じ行の次: Option<&置いたクリップ>,
    ) -> 置いたクリップの再生の中身<'_> {
        let 区間 = self.受け継いだ値().区間;
        let 一周 = 区間.長さ();
        let 最後の周回 = self.受け継いだ値().リピート回数.最後の周回();
        let 経過 = 時刻.起点から経過した長さ(self.始まりの時刻());
        let 求めた周回 = 経過.余りと揃えて何周分か(一周);
        let (周回, 周回の中の位置) = if 求めた周回 > 最後の周回 {
            (最後の周回, 一周)
        } else {
            (求めた周回, 経過.一周の中での余り(一周))
        };
        let 区間の終わりの行き先 = if 周回 < 最後の周回 {
            区間の終わりの行き先::区間の開始へ戻る
        } else {
            self.最後の周回の終わりの行き先(同じ行の次)
        };
        置いたクリップの再生の中身 {
            置いたクリップ: self,
            動画上の位置: 区間.開始().進める(周回の中の位置),
            周回,
            区間の終わりの行き先,
        }
    }

    /// 最後の周回の終わりの行き先。同じ行の次の置いたクリップが隙間なく続くならその区間へ進み、続かなければ止まる。
    /// 続く置いたクリップが同じ動画の同じ区間なら、映すものは区間の開始へ戻るのと同じなので開始へ戻るとする
    /// (スタックの行き先が、区間が同じなら開始へ戻るとするのと揃える)。全体ループで先頭へ戻ることは行き先に含めない。
    fn 最後の周回の終わりの行き先(
        &self,
        同じ行の次: Option<&置いたクリップ>,
    ) -> 区間の終わりの行き先 {
        let Some(次) = 同じ行の次.filter(|次| self.隙間なく続くか(次)) else {
            return 区間の終わりの行き先::止まる;
        };
        let 次の区間 = 次.受け継いだ値().区間;
        if 次.動画の番号() == self.動画の番号() && 次の区間 == self.受け継いだ値().区間
        {
            区間の終わりの行き先::区間の開始へ戻る
        } else {
            区間の終わりの行き先::別の区間へ進む(次の区間)
        }
    }
}
