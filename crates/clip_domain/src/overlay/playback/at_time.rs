//! 重ね合わせ上の時刻に、行ごとに映すものを求める処理。
//! 置いたクリップは始まりの時刻から終わりの時刻の手前までを映す(半開区間)。境目ちょうどの時刻は後ろの置いたクリップが映す。
//! 時刻が重ね合わせの長さ以降なら、各行は最後の置いたクリップの区間の終わりのコマを映す。前の置いたクリップの終わりから丸めの許容誤差の内の隙間では、
//! 前の置いたクリップの区間の終わりを映す。
//! 置いたクリップはトリガーと無限ループを持たないため、待ちを考えずに周回と行き先が決まる(同時再生.md 7節の決定1)。
//! 参照: _doc/設計/同時再生.md 5-2

use super::at_time_result::{
    置いたクリップの再生の中身, 行が映すもの, 行の映し方
};
use crate::overlay::aggregate::重ね合わせ;
use crate::overlay::basis::重ね合わせ上の秒;
use crate::overlay::rows::{タイムラインの行, 置いたクリップ, 行の番号};
use crate::playback_clock::末尾での振る舞い;

impl 重ね合わせ {
    /// 重ね合わせ上の時刻に、行ごとに映すものを、奥の行から手前の行の順に求める。行の数だけ必ず返す。
    /// 全体の末尾での振る舞いは、最も遅く終わる置いたクリップの最後の周回の終わりの行き先を決めるために使う。
    pub fn 重ね合わせ上の時刻に映すものを求める(
        &self,
        時刻: 重ね合わせ上の秒,
        全体の末尾: 末尾での振る舞い,
    ) -> impl Iterator<Item = 行が映すもの<'_>> {
        self.行の並び()
            .奥から手前の順の行()
            .iter()
            .enumerate()
            .map(move |(行の添字, 行)| 行が映すもの {
                行: 行の番号::番号から作成する(行の添字),
                映し方: 行の再生を求める条件 {
                    重ね合わせ: self,
                    行,
                    全体の末尾,
                }
                .映し方を求める(時刻),
            })
    }
}

/// 行の再生を求める条件とは、1つの行の映し方と区間の終わりの行き先を求めるときに参照する、行の外にある事実の組のことである。
pub(super) struct 行の再生を求める条件<'重ね合わせ> {
    pub(super) 重ね合わせ: &'重ね合わせ 重ね合わせ,
    pub(super) 行: &'重ね合わせ タイムラインの行,
    pub(super) 全体の末尾: 末尾での振る舞い,
}

impl<'重ね合わせ> 行の再生を求める条件<'重ね合わせ> {
    fn 映し方を求める(
        &self, 時刻: 重ね合わせ上の秒
    ) -> 行の映し方<'重ね合わせ> {
        if 時刻 >= self.重ね合わせ.重ね合わせの長さ() {
            return match self.行.置いたクリップの並び().last() {
                Some(置いたクリップ) => 行の映し方::末尾で最後のコマを映す {
                    置いたクリップ,
                    動画上の位置: 置いたクリップ.受け継いだ値().区間.終了(),
                },
                None => 行の映し方::何も映さない,
            };
        }
        let 当たる置いたクリップ = self
            .行
            .重ね合わせ上の時刻に当たる置いたクリップ(時刻)
            .or_else(|| self.行.許容誤差の内で終わった置いたクリップ(時刻));
        match 当たる置いたクリップ {
            Some(当たる置いたクリップ) => 行の映し方::置いたクリップを映す(
                self.再生の中身を求める(当たる置いたクリップ, 時刻),
            ),
            None => 行の映し方::何も映さない,
        }
    }

    /// 当たる置いたクリップの、時刻に映している周回と動画上の位置と、今の周回の区間の終わりの行き先を求める。
    /// 丸めで最後の周回を越えた周回が出たときと、許容誤差の内の隙間に当たったときは、最後の周回の区間の終わりとみなす。
    fn 再生の中身を求める(
        &self,
        当たる置いたクリップ: &'重ね合わせ 置いたクリップ,
        時刻: 重ね合わせ上の秒,
    ) -> 置いたクリップの再生の中身<'重ね合わせ> {
        let 区間 = 当たる置いたクリップ.受け継いだ値().区間;
        let 一周 = 区間.長さ();
        let 最後の周回 = 当たる置いたクリップ
            .受け継いだ値()
            .リピート回数
            .最後の周回();
        let 経過 = 時刻.起点から経過した長さ(当たる置いたクリップ.始まりの時刻());
        let 求めた周回 = 経過.周回番号を求める(一周);
        let (周回, 周回の中の位置) = if 求めた周回 > 最後の周回 {
            (最後の周回, 一周)
        } else {
            (求めた周回, 経過.一周の中での余り(一周))
        };
        let 周回の終わりまでの長さ = 一周.差し引く(周回の中の位置);
        置いたクリップの再生の中身 {
            置いたクリップ: 当たる置いたクリップ,
            動画上の位置: 区間.開始().進める(周回の中の位置),
            周回,
            区間の終わりの行き先: self.区間の終わりの行き先を求める(
                当たる置いたクリップ,
                時刻,
                周回の終わりまでの長さ,
            ),
        }
    }
}
