//! 重ね合わせの進み具合。再生位置が重ね合わせの長さのどこにあるかを、画面の位置の棒へ渡す割合で表す。

use super::clock::重ね合わせの再生位置;
use crate::overlay::aggregate::重ね合わせ;

/// 重ね合わせの進み具合とは、重ね合わせの再生位置が重ね合わせの長さのどこにあるかを、0(始まり)以上1(末尾)以下の割合で表したもののことである。
/// 長さが0秒の重ね合わせ(置いたクリップが無い)では0である。
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct 重ね合わせの進み具合(f64);

impl 重ね合わせの進み具合 {
    /// 0以上1以下の割合。画面の位置の棒へ渡す境界で使う。
    pub fn 割合(self) -> f64 {
        self.0
    }
}

impl 重ね合わせの再生位置 {
    /// 重ね合わせの長さに対する進み具合。位置が長さを越えていれば1、長さが0秒なら0にする。
    pub fn 進み具合(self, 重ね合わせ: &重ね合わせ) -> 重ね合わせの進み具合 {
        let 長さ = 重ね合わせ.重ね合わせの長さ().秒数();
        if 長さ <= 0.0 {
            return 重ね合わせの進み具合(0.0);
        }
        重ね合わせの進み具合((self.時刻().秒数() / 長さ).clamp(0.0, 1.0))
    }
}
