//! 重ねる画面の縦横比。固定の比だけを持ち、クロップ連動を型で締め出す。

use crate::aspect::アスペクト比設定;
use crate::pixel::縦横比;

/// 重ねる画面とは、重ね合わせの縦横比を持つ四角の画面であり、置いたクリップを好きな場所に好きな大きさで映す画面のことである。
/// 重ねる画面の縦横比とは、重ねる画面の幅と高さの比を、アスペクト比設定の固定の比(16:9・4:3・1:1・9:16)で表したもののことである。
/// 不変条件: クロップ連動でない。置いたクリップごとにクロップが違うため、クロップに合わせる比は重ね合わせでは意味を持たない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 重ねる画面の縦横比(アスペクト比設定);

/// 重ねる画面の縦横比エラーとは、クロップ連動を重ねる画面の縦横比にしようとしたことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error("重ねる画面の縦横比に「クロップ枠に合わせる」は選べない")]
pub struct 重ねる画面の縦横比エラー;

impl 重ねる画面の縦横比 {
    /// ワイド16対9とは、幅16に対して高さ9の重ねる画面の縦横比のことである。
    pub const ワイド16対9: Self = Self(アスペクト比設定::ワイド16対9);

    /// 選べる比の一覧とは、重ねる画面の縦横比が取りうる固定の比(16:9・4:3・1:1・9:16)を、選択欄に並べる順に並べたもののことである。
    pub const 選べる比の一覧: [Self; 4] = [
        Self::ワイド16対9,
        Self(アスペクト比設定::スタンダード4対3),
        Self(アスペクト比設定::正方形),
        Self(アスペクト比設定::縦型9対16),
    ];

    /// アスペクト比設定から作成する。クロップ連動を拒む。
    pub fn 作成する(
        設定: アスペクト比設定,
    ) -> Result<Self, 重ねる画面の縦横比エラー> {
        match 設定 {
            アスペクト比設定::クロップ連動 => Err(重ねる画面の縦横比エラー),
            固定の比 => Ok(Self(固定の比)),
        }
    }

    /// スタックの作業場の出力のアスペクト比から、スタックから並べる重ね合わせの縦横比を決める。
    /// 固定の比ならその比、クロップ連動(クロップ枠に合わせる)なら16:9にする(同時再生.md 2-2)。
    pub fn スタックの出力のアスペクト比から決める(
        設定: アスペクト比設定,
    ) -> Self {
        match 設定 {
            アスペクト比設定::クロップ連動 => Self::ワイド16対9,
            固定の比 => Self(固定の比),
        }
    }

    /// 重ねる画面の幅を高さで割った縦横比。重ねる画面を出力の区画に収める寸法の計算に使う。
    /// 固定の比は切り出し後の寸法に依らないため、寸法を渡さずに求める。
    pub fn 縦横比(self) -> 縦横比 {
        match self.0 {
            アスペクト比設定::ワイド16対9 => 縦横比::整数比から求める(16, 9),
            アスペクト比設定::スタンダード4対3 => {
                縦横比::整数比から求める(4, 3)
            }
            アスペクト比設定::正方形 => 縦横比::整数比から求める(1, 1),
            アスペクト比設定::縦型9対16 => 縦横比::整数比から求める(9, 16),
            アスペクト比設定::クロップ連動 => {
                panic!("重ねる画面の縦横比はクロップ連動を持たない(到達したらバグ)")
            }
        }
    }

    /// アスペクト比設定として返す。縦横比の計算や選択欄へ渡す境界で使う。
    pub fn 設定(self) -> アスペクト比設定 {
        self.0
    }
}
