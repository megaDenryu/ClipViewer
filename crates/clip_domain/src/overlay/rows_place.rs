//! タイムラインの行の並びへ置く操作。始まりの時刻から占める長さの間が空いている最も手前の行を選び、
//! どの行も空いていなければ手前に行を足す。行が上限まであってどれも空いていなければ拒む。

use super::basis::重ね合わせ上の秒;
use super::error::重ね合わせの操作エラー;
use super::placed::置いたクリップ;
use super::row::行の番号;
use super::rows::{タイムラインの行の並び, 同時に重ねられる行の数};
use crate::duration::時間の長さ;

/// 置く行とは、置いたクリップをどの行へ置くかの決定のことである。
enum 置く行 {
    /// 今ある行のうち、時間が空いている最も手前の行。
    空いている行(行の番号),
    /// どの行も空いていないため、最も手前に新しく足す行。
    手前に足す行,
}

impl タイムラインの行の並び {
    /// 置いたクリップを、始まりの時刻から占める長さの間が空いている最も手前の行へ置き、置いた行の番号を返す。
    /// どの行も空いていなければ手前に行を足して置き、行が同時に重ねられる行の数まであればどれも空いていないとして拒む。
    /// 注意: 識別子が並びの中で重ならないことは、呼び出し側(重ね合わせ)が確かめてから呼ぶこと。
    pub(super) fn 空いている最も手前の行へ置く(
        &mut self,
        置いた: 置いたクリップ,
    ) -> Result<行の番号, 重ね合わせの操作エラー> {
        let 置く先 = match self.置く行を選ぶ(置いた.始まりの時刻(), 置いた.占める長さ())?
        {
            置く行::空いている行(行) => 行,
            置く行::手前に足す行 => self.手前に空の行を足す(),
        };
        self.行を書き換えるために借りる(置く先).差し込む(置いた);
        Ok(置く先)
    }

    fn 置く行を選ぶ(
        &self,
        始まり: 重ね合わせ上の秒,
        長さ: 時間の長さ,
    ) -> Result<置く行, 重ね合わせの操作エラー> {
        let 空いている行 = self.奥から手前の順の行().iter().rposition(|行| {
            行.時間が重なる置いたクリップを探す(始まり, 長さ, None)
                .is_none()
        });
        match 空いている行 {
            Some(位置) => Ok(置く行::空いている行(行の番号::番号から作成する(
                位置,
            ))),
            None if self.行の数() < 同時に重ねられる行の数 => {
                Ok(置く行::手前に足す行)
            }
            None => Err(重ね合わせの操作エラー::空いている行が無い {
                始まりの時刻: 始まり,
            }),
        }
    }
}
