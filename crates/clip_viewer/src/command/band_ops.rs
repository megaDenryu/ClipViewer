//! 区間の帯の操作。カードの区間の帯の掴み始め・動かしている・放したを状態へ適用する。
//! 掴み始めで時計を止め、ドラッグの間は仮の値だけを動かす。放したときに区間か再生位置を決めて再生を戻すのは `band_commit.rs` である。
//! 参照: _doc/設計/画面.md 判断11「操作契約」

use clip_domain::クリップ識別子;

use crate::state::{
    アプリの状態, 区間の帯で掴んだもの, 区間の帯に置いた値, 区間の帯のドラッグ, 区間の帯の種類,
};

/// 区間の帯の段階とは、区間の帯のドラッグの段階の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 区間の帯の段階 {
    掴み始めた,
    動かしている,
    放した,
}

/// クリップの区間の帯の操作とは、カードの区間の帯が発する、どちらの帯か・ドラッグの段階・掴んだもの・その値(動画上の秒)の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct クリップの区間の帯の操作 {
    pub(crate) 帯: 区間の帯の種類,
    pub(crate) 段階: 区間の帯の段階,
    pub(crate) 掴んだもの: 区間の帯で掴んだもの,
    pub(crate) 秒: f64,
}

impl アプリの状態 {
    /// 動かしているか放したは、今のドラッグと同じクリップの同じ区間の帯のものだけを当てる。放したときの値は使わず、最後に動かした値で決める。
    /// 掴んだだけで放したときも部品は今の値を発するが、動かしていなければ何も決めないためである。
    pub(super) fn 区間の帯の操作を適用する(
        &mut self,
        識別子: &クリップ識別子,
        操作: クリップの区間の帯の操作,
    ) {
        let 今のドラッグのものか = self.区間の帯のドラッグ.as_ref().is_some_and(|ドラッグ| {
            ドラッグ.そのクリップのその区間の帯のものか(識別子, 操作.帯)
        });
        if 操作.段階 != 区間の帯の段階::掴み始めた && !今のドラッグのものか
        {
            return;
        }
        match 操作.段階 {
            区間の帯の段階::掴み始めた => self.区間の帯を掴む(識別子, 操作),
            区間の帯の段階::動かしている => {
                self.区間の帯のドラッグを動かす(操作.秒)
            }
            区間の帯の段階::放した => self.区間の帯を放す(),
        }
    }

    /// そのクリップを選び(選ぶクリップが変わるなら、カードを押したときと同じ規則で再生位置を合わせる)、再生していたかを覚えて時計を止める。掴んだときの位置は、今の再生の位置を再生モードの写し方で収めた位置である。
    /// 位置の印は押した位置へすぐ移す(区間の外を押したとき)。
    fn 区間の帯を掴む(
        &mut self, 識別子: &クリップ識別子, 操作: クリップの区間の帯の操作
    ) {
        let Some(クリップ) = self.並び.識別子で探す(識別子).cloned() else {
            return;
        };
        let 区間 = クリップ.区間;
        let 再生していたか = self.再生.再生しているか();
        let 選ぶクリップが変わるか =
            self.並び.選択中のクリップ().map(|選択中| 選択中.識別子()) != Some(識別子);
        if 選ぶクリップが変わるか {
            self.クリップを選ぶ(識別子);
        }
        self.再生.止める();
        let 今の位置 = self
            .再生位置の求め()
            .map_or(区間.開始(), |求め| 求め.動画上の位置);
        let 位置 = self
            .位置の印の行き先(&クリップ, 今の位置.秒数())
            .動画上の位置();
        self.区間の帯のドラッグ = Some(区間の帯のドラッグ::掴み始める(
            識別子.clone(),
            操作.帯,
            操作.掴んだもの,
            区間の帯に置いた値 { 区間, 位置 },
            self.拡大の帯の範囲(&区間),
            self.編集の範囲(&区間).決まり,
            再生していたか,
        ));
        if 操作.掴んだもの == 区間の帯で掴んだもの::位置の印 {
            self.区間の帯のドラッグを動かす(操作.秒);
        }
    }

    /// 仮の区間か仮の位置を動かす。区間は区間の編集の決まりで、位置は再生モードの写し方で収める。
    fn 区間の帯のドラッグを動かす(&mut self, 秒: f64) {
        let Some(ドラッグ) = self.区間の帯のドラッグ.as_ref() else {
            return;
        };
        let Some(クリップ) = self.並び.識別子で探す(ドラッグ.クリップ()) else {
            return;
        };
        let 位置 = self.位置の印の行き先(クリップ, 秒).動画上の位置();
        let Some(ドラッグ) = self.区間の帯のドラッグ.as_mut() else {
            return;
        };
        match ドラッグ.掴んだもの() {
            区間の帯で掴んだもの::位置の印 => ドラッグ.位置を置く(位置),
            _ => ドラッグ.区間を動かす(秒),
        }
    }

    /// 位置を渡していない区間の帯(選ばれていないカード)の区間の外を押したとき、掴み始めたでそのカードを選ぶ。
    /// カードを押したときと同じ規則で再生位置も合わせる。区間の帯のドラッグは作らない。既に選ばれているなら何もしない。
    pub(super) fn 区間の帯の区間の外を押す(
        &mut self,
        識別子: &クリップ識別子,
        段階: 区間の帯の段階,
    ) {
        let 選ばれているか =
            self.並び.選択中のクリップ().map(|選択中| 選択中.識別子()) == Some(識別子);
        if 段階 == 区間の帯の段階::掴み始めた && !選ばれているか {
            self.クリップを選ぶ(識別子);
        }
    }
}
