//! クリップの並べ替え・複製と、区間の端を今見ている位置に合わせること。参照: _doc/設計/画面.md 判断14

use clip_domain::{クリップ識別子, クリップ識別子の発行元};

use super::applier::操作の適用係;
use super::span_edit::区間の端;
use crate::state::アプリの状態;

/// 動かす向きとは、クリップを並びの中で1つ前へ動かすか、1つ後ろへ動かすかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 動かす向き {
    前へ,
    後ろへ,
}

impl アプリの状態 {
    /// クリップを並びの中で1つ前か後ろへ動かし、そのクリップを選ぶ(再生位置はカードを押したときと同じ規則で合わせる)。
    /// 先頭を前へ・末尾を後ろへは動かさない。
    pub(super) fn クリップを並びで動かす(
        &mut self,
        識別子: &クリップ識別子,
        向き: 動かす向き,
    ) {
        let Ok(番号) = self.並び.番号を探す(識別子) else {
            return;
        };
        let 先 = match 向き {
            動かす向き::前へ => 番号.checked_sub(1),
            動かす向き::後ろへ => Some(番号 + 1).filter(|先| *先 < self.並び.一覧().len()),
        };
        let Some(先) = 先 else {
            return;
        };
        match self.並び.並べ替える(番号, 先) {
            Ok(()) => self.クリップを選ぶ(識別子),
            Err(理由) => self.通知.出す(理由.to_string()),
        }
    }

    /// クリップの区間の端を、今見ている動画上の位置に合わせる。端が相手の端を越えるときは長さを保って動かす
    /// (`区間の編集の決まり` の `開始を位置に合わせる`・`終了を位置に合わせる`)。区間が変わったら、区間の帯を放したときと同じく
    /// 再生位置をそのクリップの開始へ移す。
    pub(super) fn 区間の端を今の位置にする(
        &mut self,
        識別子: &クリップ識別子,
        端: 区間の端,
    ) {
        let Some(mut クリップ) = self.並び.識別子で探す(識別子).cloned() else {
            return;
        };
        let 位置 = self.今見ている動画上の位置();
        let 決まり = self.編集の範囲(&クリップ.区間).決まり;
        let 前の区間 = クリップ.区間;
        クリップ.区間 = match 端 {
            区間の端::開始 => 決まり.開始を位置に合わせる(前の区間, 位置),
            区間の端::終了 => 決まり.終了を位置に合わせる(前の区間, 位置),
        };
        if クリップ.区間 == 前の区間 {
            return;
        }
        match self.並び.更新する(クリップ) {
            Ok(()) => self.クリップの開始へ移る(識別子),
            Err(理由) => self.通知.出す(理由.to_string()),
        }
    }

    /// 選択中のクリップの区間の端を、今見ている動画上の位置に合わせる。I キーと O キーが使う。
    pub(super) fn 選択中の区間の端を今の位置にする(&mut self, 端: 区間の端) {
        if let Some(識別子) = self
            .並び
            .選択中のクリップ()
            .map(|クリップ| クリップ.識別子().clone())
        {
            self.区間の端を今の位置にする(&識別子, 端);
        }
    }
}

impl 操作の適用係 {
    /// クリップを新しい識別子で複製して直後へ差し込み、複製を選んで再生位置を合わせる。
    pub(super) fn クリップを複製する(
        &mut self,
        状態: &mut アプリの状態,
        識別子: &クリップ識別子,
    ) {
        let 新しい識別子 = self.発行元.新しい識別子を発行する();
        match 状態.並び.直後へ複製する(識別子, 新しい識別子) {
            Ok(()) => {
                状態.選んだクリップへ再生位置を合わせる();
                状態.通知.出す("クリップを複製しました");
            }
            Err(理由) => 状態.通知.出す(理由.to_string()),
        }
    }
}
