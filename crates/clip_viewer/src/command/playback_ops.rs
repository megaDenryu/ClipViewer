//! 再生の操作。再生と停止、再生位置の移動、コマ送り、速度・全体ループ・音量の変更と消音の切り替えを状態へ適用する。

use clip_domain::{再生速度, 時間の長さ, 末尾での振る舞い};

use crate::state::{アプリの状態, シークの様子, 速度を変える向き, 音量};

/// 送る向きとは、再生位置を前へ戻すか後ろへ進めるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 送る向き {
    戻す,
    進める,
}

/// 再生の操作とは、再生コントロールとキーが発する操作の区別のことである。秒と倍率と音量は部品が渡した値である。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 再生の操作 {
    再生を切り替える,
    位置を動かしている(f64),
    位置を決めた(f64),
    五秒ずらす(送る向き),
    コマ送り(送る向き),
    速度を選ぶ(f64),
    速度を一段変える(速度を変える向き),
    全体ループを切り替える(bool),
    音量を選ぶ(f64),
    消音を切り替える,
}

/// 5秒ずらす量(移植元の -5s / +5s ボタン)。
const 五秒: f64 = 5.0;

impl アプリの状態 {
    pub(crate) fn 再生の操作を適用する(&mut self, 操作: 再生の操作) {
        match 操作 {
            再生の操作::再生を切り替える => {
                if self.動画.is_some() {
                    self.再生.再生を切り替える();
                }
            }
            再生の操作::位置を動かしている(秒) => {
                self.再生.シーク = シークの様子::ドラッグしている;
                self.秒の位置へ移す(秒);
            }
            再生の操作::位置を決めた(秒) => {
                self.再生.シーク = シークの様子::していない;
                self.秒の位置へ移す(秒);
            }
            再生の操作::五秒ずらす(向き) => self.位置をずらす(向き, 五秒),
            再生の操作::コマ送り(向き) => {
                let 一コマ = self.一コマの長さ();
                self.位置をずらす(向き, 一コマ.秒数());
            }
            再生の操作::速度を選ぶ(倍率) => match 再生速度::作成する(倍率) {
                Ok(速度) => self.再生.速度 = 速度,
                Err(不正) => self.通知.出す(不正.to_string()),
            },
            再生の操作::全体ループを切り替える(有効) => {
                self.再生.全体の末尾 = if 有効 {
                    末尾での振る舞い::先頭へ戻る
                } else {
                    末尾での振る舞い::止まる
                };
            }
            再生の操作::速度を一段変える(向き) => {
                self.再生.速度を一段変える(向き)
            }
            再生の操作::音量を選ぶ(値) => {
                self.再生.音量.音量を選ぶ(音量::範囲へ収めて作る(値))
            }
            再生の操作::消音を切り替える => self.再生.音量.消音を切り替える(),
        }
    }

    fn 位置をずらす(&mut self, 向き: 送る向き, 量: f64) {
        let 今の秒 = self.再生.位置().位置の秒数();
        let 秒 = match 向き {
            送る向き::戻す => 今の秒 - 量,
            送る向き::進める => 今の秒 + 量,
        };
        self.秒の位置へ移す(秒);
    }

    /// 動画の1コマの長さ。動画が無ければ移植元と同じ1/30秒。
    pub(crate) fn 一コマの長さ(&self) -> 時間の長さ {
        let 一コマ = video_source::コマ数::作成する(1);
        self.動画.as_ref().map_or_else(
            || 時間の長さ::作成する(1.0 / 30.0).unwrap_or(時間の長さ::ゼロ),
            |動画| 動画.情報().コマの速さ().コマ数の長さ(一コマ),
        )
    }
}
