//! キーの設定の操作。キーの一覧のダイアログで、操作のキーを変えること・既定に戻すことを状態へ適用する。
//! 割り当ての規則(重なりを断る・既定へ戻す)は `viewer_settings::キーの割り当て` が持ち、ここは待ちの状態と知らせを扱う。
//! 参照: _doc/設計/画面.md 判断18

use sengen_egui::{キー, キーの組};

use crate::state::{アプリの状態, キーの一覧のダイアログ};
use crate::viewer_settings::{
    キーで行う操作, キーの割り当て, キーを変えられない理由
};

/// キーの設定の操作とは、キーの一覧のダイアログが発する、キーの割り当てを変える操作の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum キーの設定の操作 {
    変更を待ち始める(キーで行う操作),
    押されたキーを受け取る(キーの組),
    変更の待ちをやめる,
    既定に戻す(キーで行う操作),
    すべて既定に戻す,
}

/// 待ちをやめるキー。待っている間にこのキーを含む組(修飾キーを問わない。Shift+Escape 等)を押しても新しいキーにせず、待ちをやめる
/// (Escape を新しく割り当てない理由は 画面.md 判断18)。
const 待ちをやめるキー: キー = キー::Escape;

impl アプリの状態 {
    pub(crate) fn キーの設定の操作を適用する(
        &mut self, 操作: キーの設定の操作
    ) {
        match 操作 {
            キーの設定の操作::変更を待ち始める(待つ操作) => {
                self.キーの一覧 =
                    キーの一覧のダイアログ::キーを待っている(待つ操作)
            }
            キーの設定の操作::押されたキーを受け取る(組) => {
                self.押されたキーを当てる(組)
            }
            キーの設定の操作::変更の待ちをやめる => self.キーの待ちを終える(),
            キーの設定の操作::既定に戻す(戻す操作) => {
                self.キーの待ちを終える();
                let 結果 = self.キーの割り当て.既定に戻した(戻す操作);
                self.キーの割り当てを変えた結果を当てる(戻す操作, 結果);
            }
            キーの設定の操作::すべて既定に戻す => {
                self.キーの待ちを終える();
                self.キーの割り当て = キーの割り当て::既定();
            }
        }
    }

    /// 待っている操作のキーを押された組にする。待っていなければ何もしない。Escape のキーを含む組なら変えずに待ちをやめる。
    fn 押されたキーを当てる(&mut self, 組: キーの組) {
        let Some(待っている操作) = self.キーの一覧.待っている操作() else {
            return;
        };
        self.キーの待ちを終える();
        if 組.キー() == 待ちをやめるキー {
            return;
        }
        let 結果 = self.キーの割り当て.キーを変えた(待っている操作, 組);
        self.キーの割り当てを変えた結果を当てる(待っている操作, 結果);
    }

    /// 待っていれば、ダイアログを開いたまま待ちを終える。
    fn キーの待ちを終える(&mut self) {
        if self.キーの一覧.待っている操作().is_some() {
            self.キーの一覧 = キーの一覧のダイアログ::開いている;
        }
    }

    /// 変えられたら割り当てを置き換え、ほかの操作と重なって変えられなければ知らせる。
    fn キーの割り当てを変えた結果を当てる(
        &mut self,
        変える操作: キーで行う操作,
        結果: Result<キーの割り当て, キーを変えられない理由>,
    ) {
        match 結果 {
            Ok(割り当て) => self.キーの割り当て = 割り当て,
            Err(キーを変えられない理由::ほかの操作のキーと重なる {
                組,
                持っている操作,
            }) => self.通知.出す(format!(
                "{} は「{}」のキーなので、「{}」のキーを変えなかった",
                組.表記(),
                持っている操作.働き(),
                変える操作.働き()
            )),
        }
    }
}
