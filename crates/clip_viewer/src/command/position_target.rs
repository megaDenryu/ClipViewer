//! 位置の印の写し方。カードの区間の帯の位置の印が指した動画上の位置を、今の再生モードの再生位置へ写す。
//! 参照: _doc/設計/画面.md 判断11「位置の写し方」

use clip_domain::{クリップ, 再生位置, 動画上の秒, 時刻};

use crate::state::アプリの状態;

/// 位置の印の行き先とは、位置の印が指した位置を今の再生モードへ写した結果の区別のことである。
/// どちらも、再生モードの収め方で収めた動画上の位置を持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 位置の印の行き先 {
    移れる {
        動画上の位置: 動画上の秒,
        再生位置: 再生位置,
    },
    /// シーケンス再生で、クリップが再生できない(無効か長さ0)ため、タイムライン上に移る先が無い。
    移れない { 動画上の位置: 動画上の秒 },
}

impl 位置の印の行き先 {
    pub(crate) fn 動画上の位置(&self) -> 動画上の秒 {
        match *self {
            Self::移れる {
                動画上の位置, ..
            }
            | Self::移れない { 動画上の位置 } => 動画上の位置,
        }
    }
}

impl アプリの状態 {
    /// 区間の帯の秒をクリップの区間の上限の内側へ収めてから、今の再生モードへ写す。シーケンス再生と単独クリップ再生は、
    /// 区間の開始から区間の中の最後のコマの始まり(終了 − 1コマ)までへ収める。区間の終了ちょうどは、シーケンス再生では
    /// 次のクリップの先頭、単独クリップ再生では区間の先頭を指すためである。シーケンス再生は最初の周回を指す。
    pub(crate) fn 位置の印の行き先(
        &self,
        クリップ: &クリップ,
        秒: f64,
    ) -> 位置の印の行き先 {
        let 上限 = self.区間の上限(&クリップ.区間).秒数();
        let 収めた秒 = if 秒.is_nan() {
            0.0
        } else {
            秒.clamp(0.0, 上限)
        };
        let 位置 = 時刻::作成する(収めた秒).unwrap_or(時刻::先頭);
        let 区間の中 = self.区間の最後のコマまでへ収める(クリップ, 位置);
        let 経過 = 区間の中.起点から経過した長さ(クリップ.区間.開始());
        match self.再生.位置() {
            再生位置::元動画再生(_) => 位置の印の行き先::移れる {
                動画上の位置: 位置,
                再生位置: 再生位置::元動画再生(位置),
            },
            再生位置::単独クリップ再生(_) => 位置の印の行き先::移れる {
                動画上の位置: 区間の中,
                再生位置: 再生位置::単独クリップ再生(経過),
            },
            再生位置::シーケンス再生(_) => match self
                .並び
                .クリップの開始位置(クリップ.識別子())
                .filter(|_| クリップ.再生できるか())
            {
                Some(開始位置) => 位置の印の行き先::移れる {
                    動画上の位置: 区間の中,
                    再生位置: 再生位置::シーケンス再生(開始位置.進める(経過)),
                },
                None => 位置の印の行き先::移れない {
                    動画上の位置: 区間の中,
                },
            },
        }
    }

    /// 位置を、区間の開始から区間の中の最後のコマの始まり(終了 − 1コマ。区間が1コマより短ければ開始)までへ収める。
    fn 区間の最後のコマまでへ収める(
        &self,
        クリップ: &クリップ,
        位置: 動画上の秒,
    ) -> 動画上の秒 {
        let 区間 = クリップ.区間;
        let 最後のコマ = 区間.終了().戻す(self.一コマの長さ());
        let 最後 = if 最後のコマ < 区間.開始() {
            区間.開始()
        } else {
            最後のコマ
        };
        if 位置 < 区間.開始() {
            区間.開始()
        } else if 位置 > 最後 {
            最後
        } else {
            位置
        }
    }
}
