//! ファイルの操作。操作を振り分け、設定ファイルを読んで当てる。動画を開く・解除する・設定ファイルを読み込む・落としたファイルを開くは、
//! 開いているスタックとの関係を終えるため、ファイルを選ぶダイアログと読み込みを済ませてから確かめる(`relation_end.rs`)。
//! 保存は `stack_export.rs`、動画は `video_ops.rs` が行う。

use clip_domain::スタック設定;

use super::applier::操作の適用係;
use super::file_drop::{落としたファイル, 落としたファイルの見分け方};
use crate::persistence::設定ファイルのパス;
use crate::state::library::{開いたときの添え書き, 関係を終える操作};
use crate::state::{アプリの状態, 並びの出どころ, 画面の構え};

/// ファイルの操作とは、ヘッダーとサイドバーと窓へのファイルの落下が発する、ファイルと動画を扱う操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum ファイルの操作 {
    設定ファイルを読み込む,
    設定ファイルを保存する,
    動画を選んで開く,
    動画を解除する,
    落としたファイルを開く(落としたファイル),
}

impl 操作の適用係 {
    pub(super) fn ファイルの操作を適用する(
        &mut self,
        状態: &mut アプリの状態,
        操作: ファイルの操作,
    ) {
        let 続ける操作 = match 操作 {
            ファイルの操作::設定ファイルを保存する => {
                return self.設定ファイルを保存する(状態);
            }
            ファイルの操作::設定ファイルを読み込む => {
                let Some(パス) = self.窓口.設定ファイルを選ぶ() else {
                    return;
                };
                return self.設定ファイルを読んで当てる(状態, &パス);
            }
            ファイルの操作::動画を選んで開く => match self.窓口.動画を選ぶ() {
                Some(入力) => {
                    関係を終える操作::動画を開く(入力, 開いたときの添え書き::無し)
                }
                None => return,
            },
            ファイルの操作::動画を解除する => {
                関係を終える操作::動画を解除する
            }
            ファイルの操作::落としたファイルを開く(ファイル) => {
                return self.落としたファイルを開く(状態, ファイル);
            }
        };
        self.確かめてから関係を終える操作を行う(状態, 続ける操作);
    }

    /// 落としたファイルを拡張子で見分ける。動画は開く。設定ファイルは、ライブラリの構えならライブラリへ取り込み、
    /// それ以外の構えなら「JSON読込」と同じく読んで当てる。
    fn 落としたファイルを開く(
        &mut self,
        状態: &mut アプリの状態,
        ファイル: 落としたファイル,
    ) {
        match ファイル.見分ける() {
            落としたファイルの見分け方::動画(入力) => self
                .確かめてから関係を終える操作を行う(
                    状態,
                    関係を終える操作::動画を開く(入力, 開いたときの添え書き::無し),
                ),
            落としたファイルの見分け方::設定ファイル(パス) => {
                if 状態.出力.構え == 画面の構え::ライブラリ {
                    self.設定ファイルを取り込む(状態, &パス);
                } else {
                    self.設定ファイルを読んで当てる(状態, &パス);
                }
            }
        }
    }

    /// 設定ファイルを読み、読めたら確かめてから当てる。読めなければ理由を知らせ、今の並びは変えない。
    fn 設定ファイルを読んで当てる(
        &mut self,
        状態: &mut アプリの状態,
        パス: &設定ファイルのパス,
    ) {
        let 読んだ = self
            .窓口
            .設定ファイルを読む(パス)
            .map_err(|原因| 原因.to_string())
            .and_then(|本文| {
                スタック設定::本文から読み込む(&本文, &mut self.発行元)
                    .map_err(|エラー| エラー.to_string())
            });
        match 読んだ {
            Ok(設定) => self.確かめてから関係を終える操作を行う(
                状態,
                関係を終える操作::設定を当てる(設定),
            ),
            Err(理由) => 状態.通知.出す(format!("読み込み失敗: {理由}")),
        }
    }
}

impl アプリの状態 {
    /// 読み込んだ設定のクリップの並びと動画の手がかりを入れる。読み込んだ動画はそのまま残す(移植元と同じ)。
    /// ライブラリの構えで読み込んだときは、読み込んだ並びが見えるよう編集の構えへ移る。
    pub(crate) fn 設定を当てる(&mut self, 設定: スタック設定) {
        let クリップの数 = 設定.スタック.一覧().len();
        self.並びを置き換える(設定.スタック, 並びの出どころ::ファイルから読んだ);
        self.手がかり
            .設定ファイルに合わせる(設定.期待する動画, 設定.期待する動画のパス.as_ref());
        self.ライブラリの構えなら編集へ移る();
        self.通知
            .出す(format!("設定を読み込みました ({クリップの数}クリップ)"));
    }
}
