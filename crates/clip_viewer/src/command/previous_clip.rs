//! 前のクリップへ戻る操作。シーケンス再生のときだけ、前の再生できるクリップの開始へ戻す(先頭のクリップではその開始へ)。
//! 規則は `clip_domain` の `前のクリップへ戻す` が持つ。参照: _doc/設計/画面.md 判断14

use clip_domain::前へ戻した結果;

use crate::state::アプリの状態;

impl アプリの状態 {
    /// 前のクリップへ戻り、そのクリップを選ぶ。戻せなければ何もしない。再生しているか止めているかは変えない。
    pub(super) fn 前のクリップへ戻る(&mut self) {
        let 戻る先 = match self.再生.位置().前のクリップへ戻す(&self.並び) {
            前へ戻した結果::戻した {
                位置, クリップ
            } => Some((位置, クリップ.識別子().clone())),
            前へ戻した結果::戻せない => None,
        };
        let Some((位置, 識別子)) = 戻る先 else {
            return;
        };
        self.再生.位置を移す(位置);
        // 注意: 識別子は並びから取ったばかりなので、選択は失敗しない。
        let _ = self.並び.選択する(&識別子);
    }
}
