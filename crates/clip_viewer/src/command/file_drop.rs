//! ウインドウへ落とされたファイル。1回に落としたファイルをまとめて持ち、1つずつ拡張子で、動画として開くか、
//! 設定ファイル(JSON)として扱うかを見分けて扱う。参照: _doc/設計/画面.md 判断14

use std::path::PathBuf;

use clip_domain::入力された動画パス;

use super::applier::操作の適用係;
use crate::persistence::設定ファイルのパス;
use crate::state::library::{開いたときの添え書き, 関係を終える操作};
use crate::state::{アプリの状態, 画面の構え};

/// 落としたファイルとは、利用者がウインドウへ落とした OS のファイルのパスのことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct 落としたファイル(PathBuf);

/// 落としたファイルの見分け方とは、落としたファイルを設定ファイルとして扱うか、動画として開くかの区別のことである。
pub(crate) enum 落としたファイルの見分け方 {
    設定ファイル(設定ファイルのパス),
    動画(入力された動画パス),
}

/// 一度に落としたファイルとは、利用者が1回のドラッグ＆ドロップでウインドウへ落としたファイルを、落とした順に並べたもののことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct 一度に落としたファイル(Vec<落としたファイル>);

impl 一度に落としたファイル {
    pub(crate) fn 作成する(パス一覧: Vec<PathBuf>) -> Self {
        Self(パス一覧.into_iter().map(落としたファイル).collect())
    }

    /// 落とした順に1つずつ取り出す。
    pub(crate) fn 順に取り出す(self) -> impl Iterator<Item = 落としたファイル> {
        self.0.into_iter()
    }
}

impl 落としたファイル {
    /// 拡張子が json(大文字と小文字を区別しない)なら設定ファイル、それ以外は動画として見分ける。
    pub(crate) fn 見分ける(self) -> 落としたファイルの見分け方 {
        let 設定ファイルか = self
            .0
            .extension()
            .is_some_and(|拡張子| 拡張子.eq_ignore_ascii_case("json"));
        if 設定ファイルか {
            return 落としたファイルの見分け方::設定ファイル(
                設定ファイルのパス::落とされたファイルから作る(self.0),
            );
        }
        落としたファイルの見分け方::動画(入力された動画パス::作成する(
            self.0.to_string_lossy().into_owned(),
        ))
    }
}

impl 操作の適用係 {
    /// 一度に落としたファイルを順に開く。ダイアログ(ライブラリのダイアログとキーの一覧のダイアログ)を開いている間は、残りのファイルを開かずに、
    /// ダイアログを閉じてから落とし直すよう1件だけ知らせる(落とす前から開いていたダイアログも、前のファイルで出た確かめるダイアログも上書きしないため)。
    /// 開いているかの判定は、2つ目のアプリから届いた頼みと同じ `ダイアログを開いているか` である。
    pub(super) fn 落としたファイルを順に開く(
        &mut self,
        状態: &mut アプリの状態,
        一度に: 一度に落としたファイル,
    ) {
        for ファイル in 一度に.順に取り出す() {
            if 状態.ダイアログを開いているか() {
                状態.通知.出す(
                    "開いているダイアログを閉じてから、もう一度ドラッグ＆ドロップしてください",
                );
                return;
            }
            self.落としたファイルを開く(状態, ファイル);
        }
    }

    /// 落としたファイルを拡張子で見分ける。動画は開く。設定ファイルは、ライブラリの構えならライブラリへ取り込み、
    /// それ以外の構えなら「JSON読込」と同じく読んで当てる。
    fn 落としたファイルを開く(
        &mut self,
        状態: &mut アプリの状態,
        ファイル: 落としたファイル,
    ) {
        match ファイル.見分ける() {
            落としたファイルの見分け方::動画(入力) => self
                .確かめてから関係を終える操作を行う(
                    状態,
                    関係を終える操作::動画を開く(入力, 開いたときの添え書き::無し),
                ),
            落としたファイルの見分け方::設定ファイル(パス) => {
                if 状態.出力.構え == 画面の構え::ライブラリ {
                    self.設定ファイルを取り込む(状態, &パス);
                } else {
                    self.設定ファイルを読んで当てる(状態, &パス);
                }
            }
        }
    }
}
