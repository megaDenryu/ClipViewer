//! 動画を開くことと解除すること。開いた動画を状態へ入れ、同じ動画なら並びを残し、残せなければ最初のクリップ1つの新しい並びで始め、再生を始める。
//! 参照: _doc/設計/画面.md 判断14

use clip_domain::{クリップスタック, 入力された動画パス, 時刻};

use super::applier::操作の適用係;
use super::clip_add::最初のクリップの長さの上限;
use crate::state::library::{開いたときの添え書き, 関係を終える操作};
use crate::state::{アプリの状態, 並びの出どころ};
use crate::video_feed::動画を開く経路;

/// 動画を開いた結果とは、動画を開く操作で動画を開いたか、開けなかったかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 動画を開いた結果 {
    開いた,
    開かなかった,
}

impl 操作の適用係 {
    /// 失われる変更が無いことを確かめてから動画を開く。添え書きは、開けたときだけ開いた結果の通知へ書き足す
    /// (確かめるダイアログを経て開いたときも書き足す)。起動の受け口に届いた頼みの適用と試験が使う。
    pub(crate) fn 確かめてから動画を開く(
        &mut self,
        状態: &mut アプリの状態,
        入力: &入力された動画パス,
        添え書き: 開いたときの添え書き,
    ) {
        let 続ける操作 = 関係を終える操作::動画を開く(入力.clone(), 添え書き);
        self.確かめてから関係を終える操作を行う(状態, 続ける操作);
    }

    /// 動画を開く。開けなければ理由を知らせ、今の動画と並びはそのまま残す。保存は呼ぶ前に確かめておく。
    /// 同じ動画の並びなら(`並びを残して動画を開けるか`)、並びと編集の履歴を引き継いで先頭を選ぶ(関係はパス全体が同じときだけ保つ)。
    /// そうでなければ最初のクリップ1つの新しい並びに置き換える(関係を終え、履歴を空にする)。
    pub(super) fn 動画を開く(
        &mut self,
        状態: &mut アプリの状態,
        入力: &入力された動画パス,
    ) -> 動画を開いた結果 {
        let パス = 入力.正規化する();
        let 動画 = match self.開き手.開く(&パス, 状態.音の出力.周波数()) {
            Ok(動画) => 動画,
            Err(理由) => {
                状態
                    .通知
                    .出す(理由.案内を添えた文(動画を開く経路::パスを指定して));
                return 動画を開いた結果::開かなかった;
            }
        };
        let 並びを残すか = 状態.並びを残して動画を開けるか(&パス);
        状態.動画 = Some(動画);
        if 並びを残すか {
            状態.並びを残して動画を開き直す(&パス);
        } else {
            let 並び = self.最初のクリップだけの並び(状態);
            状態.並びを置き換える(並び, 並びの出どころ::新しく作った);
        }
        状態.手がかり.開いた動画に合わせる(&パス);
        状態.再生.再生を始める();
        状態.ライブラリの構えなら編集へ移る();
        let 名前 = パス.ファイル名().map_or_else(
            || パス.文字列().to_string(),
            |名前| 名前.文字列().to_string(),
        );
        状態.通知.出す(format!("動画を読み込みました: {名前}"));
        動画を開いた結果::開いた
    }

    /// 動画の先頭から始まる最初のクリップ(移植元と同じ「Clip Mod 1」)だけの並び。
    fn 最初のクリップだけの並び(
        &mut self,
        状態: &mut アプリの状態,
    ) -> クリップスタック {
        let mut 並び = クリップスタック::default();
        let クリップ = self.位置からのクリップを作る(
            状態,
            並び.次に追加するクリップの名前(),
            時刻::先頭,
            最初のクリップの長さの上限,
        );
        if let Err(理由) = 並び.追加する(クリップ) {
            状態.通知.出す(理由.to_string());
        }
        並び
    }
}

impl アプリの状態 {
    /// 動画とクリップの並びを捨て、再生を止める(移植元と同じ)。動画の手がかりは残す。
    pub(crate) fn 動画を解除する(&mut self) {
        self.動画 = None;
        self.並びを置き換える(クリップスタック::default(), 並びの出どころ::新しく作った);
        self.再生.止める();
        self.通知.出す("動画を解除しました");
    }
}
