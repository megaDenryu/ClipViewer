//! 設定ファイルの保存。パスのメモを期待する動画で検証し、保存先を選ばせて第4版の形で書き出す。

use clip_domain::{
    動画パスの検証結果, 書き出す設定, 検証済みの動画パス, 設定ファイルの本文
};

use super::applier::操作の適用係;
use crate::persistence::設定ファイルの既定の名前;
use crate::state::アプリの状態;

impl 操作の適用係 {
    /// クリップが無いか、パスのメモが検証に落ちたら知らせて書き出さない(移植元と同じ)。
    pub(super) fn 設定ファイルを保存する(&mut self, 状態: &mut アプリの状態) {
        let Some(検証済み) = 状態.書き出しに使う動画パスを確かめる() else {
            return;
        };
        let 本文 = match self.本文を作る(状態, &検証済み) {
            Ok(本文) => 本文,
            Err(理由) => return 状態.通知.出す(理由),
        };
        let 既定の名前 =
            設定ファイルの既定の名前::動画から作る(状態.手がかり.期待する動画());
        let Some(パス) = self.入出力係.設定ファイルの保存先を選ぶ(&既定の名前)
        else {
            return;
        };
        match self.入出力係.設定ファイルを書く(&パス, &本文) {
            Ok(()) => 状態.通知.出す("スタック構成をJSON保存しました"),
            Err(原因) => 状態.通知.出す(format!("保存失敗: {原因}")),
        }
    }

    fn 本文を作る(
        &self,
        状態: &アプリの状態,
        検証済み: &検証済みの動画パス,
    ) -> Result<設定ファイルの本文, String> {
        let Some(空でない) = 状態.並び.空でないことを確かめる() else {
            return Err("エクスポートする構成がありません".to_string());
        };
        let 日時 = self
            .入出力係
            .今の書き出し日時()
            .map_err(|エラー| エラー.to_string())?;
        let 設定 = 書き出す設定 {
            スタック: 空でない,
            動画のパス: 検証済み,
        };
        設定
            .本文へ書き出す(&日時)
            .map_err(|エラー| エラー.to_string())
    }
}

impl アプリの状態 {
    /// クリップがあり、パスのメモが期待する動画で検証を通るかを確かめる。パスのメモは正規化した形へ書き戻す。
    /// 確かめられなければ理由を知らせて無いを返す。
    fn 書き出しに使う動画パスを確かめる(
        &mut self,
    ) -> Option<検証済みの動画パス> {
        if self.並び.一覧().is_empty() {
            self.通知.出す("エクスポートする構成がありません");
            return None;
        }
        match self
            .手がかり
            .パスのメモ()
            .検証する(self.手がかり.期待する動画())
        {
            動画パスの検証結果::有効(検証済み) => {
                let 正規化 = 検証済み.正規化したパス().文字列().to_string();
                self.手がかり.パスのメモを書き換える(正規化);
                Some(検証済み)
            }
            動画パスの検証結果::不正 {
                正規化したパス,
                不備,
            } => {
                self.手がかり
                    .パスのメモを書き換える(正規化したパス.文字列().to_string());
                self.通知.出す(不備.to_string());
                None
            }
        }
    }
}
