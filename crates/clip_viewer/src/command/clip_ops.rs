//! クリップの操作。クリップの選択・削除・開始へ移る・編集・区間の帯の操作・単独再生の切り替え・並べ替え・区間の端を今の位置にすること・
//! 編集の取り消しとやり直しを状態へ適用する。追加と複製は識別子の発行元を持つ係が行う(`clip_add.rs`・`clip_arrange.rs`)。

use clip_domain::クリップ識別子;

use super::band_ops::{クリップの区間の帯の操作, 区間の帯の段階};
use super::clip_arrange::動かす向き;
use super::clip_edit::クリップの編集;
use super::span_edit::区間の端;
use crate::state::{アプリの状態, 続けて変える値};

/// クリップの操作とは、スタックの一覧とクリップカードが発する操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum クリップの操作 {
    追加する,
    選ぶ(クリップ識別子),
    削除する(クリップ識別子),
    開始へ移る(クリップ識別子),
    編集する(クリップ識別子, クリップの編集),
    区間の帯を操作する(クリップ識別子, クリップの区間の帯の操作),
    単独再生を切り替える(クリップ識別子),
    区間の帯の区間の外を押す(クリップ識別子, 区間の帯の段階),
    並びで動かす(クリップ識別子, 動かす向き),
    複製する(クリップ識別子),
    区間の端を今の位置にする(クリップ識別子, 区間の端),
    選択中の区間の端を今の位置にする(区間の端),
    編集を取り消す,
    編集をやり直す,
    続けて変える操作を終えた,
}

impl アプリの状態 {
    /// 追加すると複製する以外のクリップの操作を適用する。この2つは識別子の発行元が要るため `操作の適用係` が適用する。
    pub(crate) fn クリップの操作を適用する(&mut self, 操作: クリップの操作) {
        match 操作 {
            クリップの操作::追加する | クリップの操作::複製する(_) => {}
            クリップの操作::選ぶ(識別子) => self.クリップを選ぶ(&識別子),
            クリップの操作::削除する(識別子) => match self.並び.削除する(&識別子)
            {
                Ok(()) => self.通知.出す("クリップを削除しました"),
                Err(理由) => self.通知.出す(理由.to_string()),
            },
            クリップの操作::開始へ移る(識別子) => {
                self.クリップの開始へ移る(&識別子)
            }
            クリップの操作::編集する(識別子, 編集) => {
                self.クリップを編集する(&識別子, 編集)
            }
            クリップの操作::区間の帯を操作する(識別子, 操作) => {
                self.区間の帯の操作を適用する(&識別子, 操作)
            }
            クリップの操作::単独再生を切り替える(識別子) => {
                self.単独再生を切り替える(&識別子)
            }
            クリップの操作::区間の帯の区間の外を押す(識別子, 段階) => {
                self.区間の帯の区間の外を押す(&識別子, 段階)
            }
            クリップの操作::並びで動かす(識別子, 向き) => {
                self.クリップを並びで動かす(&識別子, 向き)
            }
            クリップの操作::区間の端を今の位置にする(識別子, 端) => {
                self.区間の端を今の位置にする(&識別子, 端)
            }
            クリップの操作::選択中の区間の端を今の位置にする(端) => {
                self.選択中の区間の端を今の位置にする(端)
            }
            クリップの操作::編集を取り消す => self.編集を取り消す(),
            クリップの操作::編集をやり直す => self.編集をやり直す(),
            クリップの操作::続けて変える操作を終えた => {
                self.履歴.操作の区切りを覚える()
            }
        }
    }

    /// クリップを選び、再生位置を選んだクリップへ合わせる(`seek.rs`)。
    pub(super) fn クリップを選ぶ(&mut self, 識別子: &クリップ識別子) {
        if self.並び.選択する(識別子).is_ok() {
            self.選んだクリップへ再生位置を合わせる();
        }
    }

    fn クリップを編集する(
        &mut self, 識別子: &クリップ識別子, 編集: クリップの編集
    ) {
        let Some(クリップ) = self.並び.識別子で探す(識別子).cloned() else {
            return;
        };
        if let クリップの編集::区間の端を決める(端, _) = &編集 {
            self.履歴.次の変化の値を覚える(match 端 {
                区間の端::開始 => 続けて変える値::区間の開始(識別子.clone()),
                区間の端::終了 => 続けて変える値::区間の終了(識別子.clone()),
            });
        }
        let 範囲 = self.編集の範囲(&クリップ.区間);
        let 編集後 = 編集.当てたクリップ(クリップ, &範囲);
        if let Err(理由) = self.並び.更新する(編集後) {
            self.通知.出す(理由.to_string());
        }
    }
}
