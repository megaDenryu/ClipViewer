//! 動画の開き手。FFmpeg が見つかっていれば動画の読み手で動画を開き、映像のテクスチャを egui へ登録する。

use audio_pcm::サンプリング周波数;
use clip_domain::正規化した動画パス;
use eframe::egui;
use video_source::動画の読み手;

use crate::video_feed::{動画を開けない理由, 読み込んだ動画};

/// 読み手の有無とは、FFmpeg が見つかって動画の読み手があるか、見つからずに無いかの区別のことである。
enum 読み手の有無 {
    ある(動画の読み手),
    無い,
}

/// 動画の開き手とは、テクスチャの登録に使う egui の本体と、動画の読み手の有無の組のことである。
/// 読み手が無い間は、開こうとすると FFmpeg が無いことを理由に失敗する。
pub(crate) struct 動画の開き手 {
    eguiの本体: egui::Context,
    読み手: 読み手の有無,
}

impl 動画の開き手 {
    pub(crate) fn 読み手なしで作る(eguiの本体: egui::Context) -> Self {
        Self {
            eguiの本体,
            読み手: 読み手の有無::無い,
        }
    }

    /// FFmpeg が見つかったときに読み手を持たせる。
    pub(crate) fn 読み手を持たせる(&mut self, 読み手: 動画の読み手) {
        self.読み手 = 読み手の有無::ある(読み手);
    }

    /// 動画を開く。ffprobe が終わるまで待つ。出力の周波数は開く時点で使える音声出力装置の周波数であり、
    /// 装置が使えなければ(無ければ)音の倉庫を開かずに映像だけで開く。
    pub(crate) fn 開く(
        &self,
        パス: &正規化した動画パス,
        出力の周波数: Option<サンプリング周波数>,
    ) -> Result<読み込んだ動画, 動画を開けない理由> {
        match &self.読み手 {
            読み手の有無::ある(読み手) => {
                読み込んだ動画::開く(読み手.clone(), パス, &self.eguiの本体, 出力の周波数)
            }
            読み手の有無::無い => Err(動画を開けない理由::FFmpegが無い),
        }
    }
}
