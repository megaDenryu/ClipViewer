//! 出力の操作。再生モード・アスペクト比・表示サイズ・左右の向き・画面の構えの選択とシアターと編集の切り替えと、次と前のクリップへ動く操作と、キーの一覧のダイアログの開け閉めを状態へ適用する。
//! 次のクリップへ進める処理は next_clip.rs、前のクリップへ戻る処理は previous_clip.rs が持つ。

use clip_domain::{アスペクト比設定, 再生モード, 再生位置, 進める操作};

use crate::state::{
    アプリの状態, キーの一覧のダイアログ, 左右の向き, 画面の構え, 表示サイズ
};

/// 出力の操作とは、出力の欄とキーが発する、出力の見せ方と進行の操作の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 出力の操作 {
    再生モードを選ぶ(再生モード),
    アスペクト比を選ぶ(アスペクト比設定),
    表示サイズを選ぶ(表示サイズ),
    左右の向きを選ぶ(左右の向き),
    構えを選ぶ(画面の構え),
    全画面かシアターを抜ける,
    シアターと編集を切り替える,
    全画面を切り替える,
    次へ進める(進める操作),
    Enterキーで次へ進める,
    前のクリップへ戻る,
    キーの一覧を開く,
    キーの一覧を切り替える,
    キーの一覧を閉じる,
}

impl アプリの状態 {
    pub(crate) fn 出力の操作を適用する(&mut self, 操作: 出力の操作) {
        match 操作 {
            出力の操作::再生モードを選ぶ(モード) => {
                self.再生.位置を移す(再生位置::モードの先頭(モード));
            }
            出力の操作::アスペクト比を選ぶ(比) => self.出力.アスペクト比 = 比,
            出力の操作::表示サイズを選ぶ(サイズ) => {
                self.出力.表示サイズ = サイズ
            }
            出力の操作::左右の向きを選ぶ(向き) => self.出力.左右 = 向き,
            出力の操作::構えを選ぶ(構え) => self.構えを変える(構え),
            出力の操作::全画面かシアターを抜ける => {
                self.全画面かシアターを抜ける()
            }
            出力の操作::シアターと編集を切り替える => {
                self.シアターと編集を切り替える()
            }
            出力の操作::全画面を切り替える => self.ウインドウ.全画面を切り替える(),
            出力の操作::次へ進める(進める操作) => self.次へ進める(進める操作),
            出力の操作::Enterキーで次へ進める => self.enterキーで次へ進める(),
            出力の操作::前のクリップへ戻る => self.前のクリップへ戻る(),
            出力の操作::キーの一覧を開く => self.キーの一覧.開く(),
            出力の操作::キーの一覧を切り替える => self.キーの一覧.切り替える(),
            出力の操作::キーの一覧を閉じる => {
                self.キーの一覧 = キーの一覧のダイアログ::閉じている
            }
        }
    }

    /// Escape の操作。全画面なら全画面だけを抜け(構えは変えない)、全画面でなくシアターなら編集の構えへ戻る。
    fn 全画面かシアターを抜ける(&mut self) {
        if !self.ウインドウ.全画面なら抜ける() && self.出力.構え == 画面の構え::シアター
        {
            self.構えを変える(画面の構え::編集);
        }
    }

    /// T キーの操作。編集の構えならシアターへ、シアターなら編集の構えへ移る。ライブラリの構えでは何もしない(キーの表が効かせない)。
    fn シアターと編集を切り替える(&mut self) {
        match self.出力.構え {
            画面の構え::編集 => self.構えを変える(画面の構え::シアター),
            画面の構え::シアター => self.構えを変える(画面の構え::編集),
            画面の構え::ライブラリ => {}
        }
    }

    /// 構えが変わったときだけ移して知らせる。構えと一緒に揃える再生の状況は `構えを移す`(state/view_stance.rs)が変える。
    fn 構えを変える(&mut self, 構え: 画面の構え) {
        if !self.構えを移す(構え) {
            return;
        }
        self.通知.出す(match 構え {
            画面の構え::シアター => "シアター",
            画面の構え::編集 => "編集",
            画面の構え::ライブラリ => "ライブラリ",
        });
    }
}
