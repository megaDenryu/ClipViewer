//! 出力の操作。再生モード・アスペクト比・表示サイズ・左右の向き・画面の構えの選択と、次のクリップへ進める操作と、キーの一覧の窓の開け閉めを状態へ適用する。

use clip_domain::{
    アスペクト比設定, 再生モード, 再生位置, 次へ進めた結果, 進める操作
};

use crate::state::{
    アプリの状態, キーの一覧の窓, 左右の向き, 画面の構え, 表示サイズ
};

/// 出力の操作とは、出力の欄とキーが発する、出力の見せ方と進行の操作の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 出力の操作 {
    再生モードを選ぶ(再生モード),
    アスペクト比を選ぶ(アスペクト比設定),
    表示サイズを選ぶ(表示サイズ),
    左右の向きを選ぶ(左右の向き),
    構えを選ぶ(画面の構え),
    全画面かシアターを抜ける,
    全画面を切り替える,
    次へ進める(進める操作),
    前のクリップへ戻る,
    キーの一覧を切り替える,
    キーの一覧を閉じる,
}

/// 次へ進めた後にすることとは、次へ進めた結果から借用を外して取り出した、状態へ行う変更の区別のことである。
enum 次へ進めた後にすること {
    進む(再生位置, clip_domain::クリップ識別子),
    止める(再生位置),
    何もしない,
}

impl アプリの状態 {
    pub(crate) fn 出力の操作を適用する(&mut self, 操作: 出力の操作) {
        match 操作 {
            出力の操作::再生モードを選ぶ(モード) => {
                self.再生.位置を移す(再生位置::モードの先頭(モード));
            }
            出力の操作::アスペクト比を選ぶ(比) => self.出力.アスペクト比 = 比,
            出力の操作::表示サイズを選ぶ(サイズ) => {
                self.出力.表示サイズ = サイズ
            }
            出力の操作::左右の向きを選ぶ(向き) => self.出力.左右 = 向き,
            出力の操作::構えを選ぶ(構え) => self.構えを変える(構え),
            出力の操作::全画面かシアターを抜ける => {
                self.全画面かシアターを抜ける()
            }
            出力の操作::全画面を切り替える => self.窓.全画面を切り替える(),
            出力の操作::次へ進める(進める操作) => self.次へ進める(進める操作),
            出力の操作::前のクリップへ戻る => self.前のクリップへ戻る(),
            出力の操作::キーの一覧を切り替える => self.キーの一覧.切り替える(),
            出力の操作::キーの一覧を閉じる => {
                self.キーの一覧 = キーの一覧の窓::閉じている
            }
        }
    }

    /// Escape の操作。全画面なら全画面だけを抜け(構えは変えない)、全画面でなくシアターなら編集の構えへ戻る。
    fn 全画面かシアターを抜ける(&mut self) {
        if !self.窓.全画面なら抜ける() && self.出力.構え == 画面の構え::シアター
        {
            self.構えを変える(画面の構え::編集);
        }
    }

    /// 構えが変わったときだけ移して知らせる。構えと一緒に揃える再生の状況は `構えを移す`(state/view_stance.rs)が変える。
    fn 構えを変える(&mut self, 構え: 画面の構え) {
        if !self.構えを移す(構え) {
            return;
        }
        self.通知.出す(match 構え {
            画面の構え::シアター => "閲覧シアターモード",
            画面の構え::編集 => "編集モード",
            画面の構え::ライブラリ => "ライブラリ",
        });
    }

    /// 進める操作で次のクリップへ進める。規則は `clip_domain` の `操作で次へ進める` が持つ。
    fn 次へ進める(&mut self, 操作: 進める操作) {
        let 全体の末尾 = self.再生.全体の末尾;
        let すること = match self
            .再生
            .位置()
            .操作で次へ進める(操作, &self.並び, 全体の末尾)
        {
            次へ進めた結果::進んだ {
                位置, クリップ
            } => 次へ進めた後にすること::進む(位置, クリップ.識別子().clone()),
            次へ進めた結果::末尾で止めた { 位置, .. } => {
                次へ進めた後にすること::止める(位置)
            }
            次へ進めた結果::進めない(_) => {
                次へ進めた後にすること::何もしない
            }
        };
        match すること {
            次へ進めた後にすること::進む(位置, 識別子) => {
                self.再生.位置を移す(位置);
                // 注意: 識別子は並びから取ったばかりなので、選択は失敗しない。
                let _ = self.並び.選択する(&識別子);
            }
            次へ進めた後にすること::止める(位置) => {
                self.再生.位置を移す(位置);
                self.再生.止める();
            }
            次へ進めた後にすること::何もしない => {}
        }
    }
}
