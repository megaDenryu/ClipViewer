//! クリップの追加。識別子の発行元を保持する係が、今見ている動画上の位置から始まるクリップを作って並びの末尾へ足す。
//! 参照: _doc/設計/画面.md 判断14

use clip_domain::{
    クリップ, クリップ名, クリップ識別子の発行元, 動画上の秒, 時間の長さ
};

use super::applier::操作の適用係;
use crate::state::アプリの状態;

/// 新規Clipを追加したときの区間の長さ(移植元と同じ5秒)。動画か上限までの残りがこれより短ければ、その長さにする。
const 追加するクリップの長さ: f64 = 5.0;

/// 動画を開いて並びを残さないときに作る最初のクリップの長さの上限(移植元と同じ10秒)。
pub(super) const 最初のクリップの長さの上限: f64 = 10.0;

/// 動画が要る操作(新規Clipを追加・新しいスタックを始める)を、動画を開いていないときに押したときの知らせ(移植元と同じ文)。
pub(super) const 動画が無いときの知らせ: &str = "先に動画ファイルをロードしてください";

impl 操作の適用係 {
    /// 今見ている動画上の位置から始まるクリップを末尾へ足して選び、再生位置を選んだクリップへ合わせる。
    /// 動画が無ければ足さない(移植元と同じ)。
    pub(super) fn クリップを追加する(&mut self, 状態: &mut アプリの状態) {
        if 状態.動画.is_none() {
            状態.通知.出す(動画が無いときの知らせ);
            return;
        }
        let 位置 = 状態.今見ている動画上の位置();
        let 名前 = 状態.並び.次に追加するクリップの名前();
        let クリップ =
            self.位置からのクリップを作る(状態, 名前, 位置, 追加するクリップの長さ);
        let 開始 = クリップ.区間.開始().秒数();
        match 状態.並び.追加する(クリップ) {
            Ok(()) => {
                状態.選んだクリップへ再生位置を合わせる();
                状態
                    .通知
                    .出す(format!("クリップを追加しました({開始:.2}秒から)"));
            }
            Err(理由) => 状態.通知.出す(理由.to_string()),
        }
    }

    /// 名前のクリップを、位置から長さ(動画がそれより短ければ動画の長さ)の区間で作る。区間は区間の編集の決まりで上限の内側へ収める。
    pub(super) fn 位置からのクリップを作る(
        &mut self,
        状態: &アプリの状態,
        名前: クリップ名,
        位置: 動画上の秒,
        長さの上限の秒: f64,
    ) -> クリップ {
        let mut クリップ =
            クリップ::既定値で作成する(self.発行元.新しい識別子を発行する(), 名前);
        let 上限 = 時間の長さ::作成する(長さの上限の秒).unwrap_or(時間の長さ::ゼロ);
        let 動画の長さ = 状態.動画の長さ();
        let 長さ = if 動画の長さ < 上限 {
            動画の長さ
        } else {
            上限
        };
        let 決まり = 状態.編集の範囲(&クリップ.区間).決まり;
        クリップ.区間 = 決まり.位置から始まる区間を作る(位置, 長さ);
        クリップ
    }
}
