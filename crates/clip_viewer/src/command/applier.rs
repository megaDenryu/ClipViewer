//! 操作の適用係。応答を振り分け、状態だけで決まる操作は状態のメソッドへ、外界に触る操作は自分が保持する依存で適用する。
//! 参照: _doc/設計/画面.md 判断1

use eframe::egui;
use video_source::実行ファイルの検索パス;

use super::id_issuer::実時間の識別子発行元;
use super::video_opener::動画の開き手;
use super::{出力の操作, 応答};
use crate::persistence::{アプリの設定の保管場所, ファイルの窓口};
use crate::state::{アプリの状態, 画面の構え};

/// 操作の適用係とは、応答を状態へ適用するときに要る依存(識別子の発行元・ファイルの窓口・アプリの設定の保管場所・
/// FFmpeg の検索パス・動画の開き手)を保持し、応答を適用するもののことである。状態は処理の対象として毎回受け取る。
pub(crate) struct 操作の適用係 {
    pub(super) 発行元: 実時間の識別子発行元,
    pub(super) 窓口: ファイルの窓口,
    pub(super) 保管場所: アプリの設定の保管場所,
    pub(super) 検索パス: 実行ファイルの検索パス,
    pub(super) 開き手: 動画の開き手,
}

impl 操作の適用係 {
    /// 依存を受け取って作る。FFmpeg はまだ探していないので、動画の開き手は読み手を持たない。
    pub(crate) fn 作成する(
        保管場所: アプリの設定の保管場所,
        検索パス: 実行ファイルの検索パス,
        eguiの本体: egui::Context,
    ) -> Self {
        Self {
            発行元: 実時間の識別子発行元::時刻から種を取って作る(),
            窓口: ファイルの窓口::default(),
            保管場所,
            検索パス,
            開き手: 動画の開き手::読み手なしで作る(eguiの本体),
        }
    }

    /// 応答を状態へ適用する。
    pub(crate) fn 適用する(&mut self, 状態: &mut アプリの状態, 応答: 応答) {
        match 応答 {
            応答::ファイル(操作) => self.ファイルの操作を適用する(状態, 操作),
            応答::手がかり(操作) => 状態.手がかりの操作を適用する(操作),
            応答::クリップ(super::クリップの操作::追加する) => {
                self.クリップを追加する(状態)
            }
            応答::クリップ(super::クリップの操作::複製する(識別子)) => {
                self.クリップを複製する(状態, &識別子)
            }
            応答::クリップ(操作) => 状態.クリップの操作を適用する(操作),
            応答::クロップ枠(操作) => 状態.クロップ枠の操作を適用する(操作),
            応答::出力(出力の操作::構えを選ぶ(画面の構え::ライブラリ)) => {
                状態.出力の操作を適用する(出力の操作::構えを選ぶ(画面の構え::ライブラリ));
                状態.一覧を読み直す();
            }
            応答::出力(操作) => 状態.出力の操作を適用する(操作),
            応答::再生(操作) => 状態.再生の操作を適用する(操作),
            応答::FFmpeg(操作) => self.ffmpegの操作を適用する(状態, 操作),
            応答::ライブラリ(操作) => {
                self.ライブラリの操作を適用する(状態, 操作)
            }
        }
    }
}
