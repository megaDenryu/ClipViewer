//! 一覧の項目を変える操作。名前の変更・複製・削除・動画の場所の指定し直し。どれも裏のスレッドへ頼み、続けて一覧を読み直す。
//! 開いているスタックに対する名前と動画の場所の変更は、頼むと同時に開いている中身へも当てる(後の自動保存が上書きしないため)。

use clip_domain::{スタックの名前, スタックの識別子};
use clip_library::ライブラリへの頼み;

use crate::command::applier::操作の適用係;
use crate::library_common::save::入力中の名前;
use crate::state::library::ライブラリのダイアログ;
use crate::state::アプリの状態;

impl アプリの状態 {
    pub(super) fn 名前を変えるダイアログを開く(
        &mut self, 識別子: &スタックの識別子
    ) {
        let 今の名前 = self
            .ライブラリ
            .一覧の名前(識別子)
            .map(|名前| 名前.文字列().to_string());
        self.ライブラリ.ダイアログ = ライブラリのダイアログ::名前を変える(
            識別子.clone(),
            入力中の名前::作成する(今の名前.unwrap_or_default()),
        );
    }

    pub(super) fn 削除の確認を開く(&mut self, 識別子: &スタックの識別子) {
        match self.ライブラリ.一覧の名前(識別子) {
            Some(名前) => {
                self.ライブラリ.ダイアログ =
                    ライブラリのダイアログ::削除の確認(識別子.clone(), 名前)
            }
            None => self.通知.出す("削除するスタックが一覧に無い"),
        }
    }
}

impl 操作の適用係 {
    pub(super) fn 名前を変える(&mut self, 状態: &mut アプリの状態) {
        let ライブラリのダイアログ::名前を変える(識別子, 入力) = &状態.ライブラリ.ダイアログ
        else {
            return;
        };
        let Some(名前) = 入力.名前として読む::<スタックの名前>() else {
            return 状態.通知.出す("名前を入力してください");
        };
        let (識別子, 今) = (識別子.clone(), 状態.ライブラリ.接続.今の日時());
        if let Some(登録済み) = 状態.ライブラリ.開いている.識別子が同じなら(&識別子)
        {
            登録済み.名前を変えた(名前.clone(), 今);
        }
        状態.ライブラリ.ダイアログ = ライブラリのダイアログ::無し;
        状態.変更を頼んで一覧を読み直す(ライブラリへの頼み::名前を変える(
            識別子, 名前, 今,
        ));
    }

    /// 削除の確認で決定した。開いているスタックなら、先に未登録へ戻して自動保存がファイルを作り直さないようにする。
    pub(super) fn 削除する(&mut self, 状態: &mut アプリの状態) {
        let ライブラリのダイアログ::削除の確認(識別子, _) =
            std::mem::take(&mut 状態.ライブラリ.ダイアログ)
        else {
            return;
        };
        if 状態.ライブラリ.開いている.識別子() == Some(&識別子) {
            状態.削除したスタックとの関係を終える();
        }
        状態.変更を頼んで一覧を読み直す(ライブラリへの頼み::削除する(識別子));
    }

    pub(super) fn 複製する(
        &mut self, 状態: &mut アプリの状態, 識別子: スタックの識別子
    ) {
        let 新しい識別子 = self.発行元.新しいスタックの識別子を発行する();
        let 今 = 状態.ライブラリ.接続.今の日時();
        状態.変更を頼んで一覧を読み直す(ライブラリへの頼み::複製する(
            識別子,
            新しい識別子,
            今,
        ));
    }

    /// 動画を選ぶダイアログで新しい場所を選ばせ、スタックの動画のパスを変える。
    pub(super) fn 動画の場所を指定し直す(
        &mut self,
        状態: &mut アプリの状態,
        識別子: スタックの識別子,
    ) {
        let Some(入力) = self.入出力係.動画を選ぶ() else {
            return;
        };
        let (パス, 今) = (入力.正規化する(), 状態.ライブラリ.接続.今の日時());
        if let Some(登録済み) = 状態.ライブラリ.開いている.識別子が同じなら(&識別子)
        {
            登録済み.動画の場所を変えた(パス.clone(), 今);
        }
        状態.変更を頼んで一覧を読み直す(ライブラリへの頼み::動画の場所を変える(
            識別子, パス, 今,
        ));
    }
}
