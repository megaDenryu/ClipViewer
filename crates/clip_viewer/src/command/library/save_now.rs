//! Ctrl+S の保存。未登録のスタックなら名前を付けて登録する窓を開き、登録済みなら落ち着くのを待たずに今の並びの保存を頼む。
//! 参照: _doc/設計/画面.md 判断14「キーの割り当て」、_doc/設計/ライブラリ.md 判断5

use crate::state::library::{登録の後にすること, 開いているスタック};
use crate::state::アプリの状態;

impl アプリの状態 {
    /// 今の並びをライブラリへ保存する。登録済みで保存を待っている変更が無ければ、保存済みであることを知らせる。
    pub(in crate::command) fn 今すぐライブラリへ保存する(&mut self) {
        if let 開いているスタック::未登録 = self.ライブラリ.開いている {
            return self.登録の窓を開く(登録の後にすること::何もしない);
        }
        if self.ライブラリ.保存されていないか(self.並び.一覧()) {
            self.今の並びの保存を頼む();
        } else {
            self.通知
                .出す("保存済みである(登録済みのスタックは変えるたびに自動で保存している)");
        }
    }
}
