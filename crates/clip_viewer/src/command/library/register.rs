//! 最初の登録。動画を開いてクリップを作ったスタックに名前を付けて、ライブラリへ登録する。
//! 試しに開いただけの動画が勝手に溜まらないよう、登録は利用者が名前を付けて決定したときだけ行う(ライブラリ.md 判断5)。

use clip_domain::{スタックの名前, ライブラリのスタック};

use crate::command::applier::操作の適用係;
use crate::library_common::save::入力中の名前;
use crate::state::library::{
    ライブラリのダイアログ, ライブラリの使える様子, 保存の目的, 登録の後にすること,
    登録済みのスタック, 開いているスタック,
};
use crate::state::アプリの状態;

impl アプリの状態 {
    /// 名前を付けて登録するダイアログを開く。名前の初期値は動画のファイル名から拡張子を除いたものである。
    /// 登録の後にすることは、登録を頼めたときに続けて行う(登録していない変更を捨てるかを確かめるダイアログから来たとき)。
    pub(super) fn 登録のダイアログを開く(
        &mut self, 後にすること: 登録の後にすること
    ) {
        if let 開いているスタック::登録済み(_) = self.ライブラリ.開いている {
            return self.通知.出す("このスタックは既にライブラリに登録してある");
        }
        if let ライブラリの使える様子::読むだけ(_, 理由) = self.ライブラリ.接続.使える様子()
        {
            return self
                .通知
                .出す(format!("ライブラリは読み取り専用である({理由})"));
        }
        let Some(動画) = &self.動画 else {
            return self.通知.出す("先に動画を開いてクリップを作ってください");
        };
        if self.並び.一覧().is_empty() {
            return self.通知.出す("登録するクリップがありません");
        }
        let 初期値 = 動画
            .情報()
            .パス()
            .ファイル名()
            .map(|名前| 名前.拡張子を除いた名前().to_string())
            .unwrap_or_default();
        self.ライブラリ.ダイアログ = ライブラリのダイアログ::名前を付けて登録(
            入力中の名前::作成する(初期値),
            後にすること,
        );
    }
}

impl 操作の適用係 {
    /// ダイアログの名前でスタックを登録し、開いているスタックを登録済みにする。書き込みは裏のスレッドが行い、保存したことは結果を受けてから通知する。
    /// 登録の後にすることがあれば、続けてその操作を確かめてから行う(確かめは登録の書き込みを終えるまで待つ)。
    pub(super) fn 登録する(&mut self, 状態: &mut アプリの状態) {
        let ライブラリのダイアログ::名前を付けて登録(入力, 後にすること) =
            &状態.ライブラリ.ダイアログ
        else {
            return;
        };
        let 後にすること = 後にすること.clone();
        let Some(名前) = 入力.名前として読む::<スタックの名前>() else {
            return 状態.通知.出す("名前を入力してください");
        };
        let Some(動画) = &状態.動画 else {
            return 状態.通知.出す("先に動画を開いてください");
        };
        let スタック = ライブラリのスタック::新しく作る(
            self.発行元.新しいスタックの識別子を発行する(),
            名前.clone(),
            動画.情報().パス().clone(),
            状態.並び.clone(),
            状態.ライブラリ.接続.今の日時(),
        );
        let 番号 = match 状態
            .ライブラリ
            .接続
            .保存を頼む(スタック.clone(), 保存の目的::登録(名前))
        {
            Ok(番号) => 番号,
            Err(理由) => return 状態.通知.出す(format!("ライブラリへ保存できない: {理由}")),
        };
        状態.ライブラリ.開いている = 開いているスタック::登録済み(
            登録済みのスタック::登録を頼んだ(スタック, 番号),
        );
        状態.ライブラリ.ダイアログ = ライブラリのダイアログ::無し;
        状態.一覧を読み直す();
        if let 登録の後にすること::続ける(続ける操作) = 後にすること {
            self.確かめてから関係を終える操作を行う(状態, 続ける操作);
        }
    }
}
