//! ブラウザ版の設定ファイル(v4.0 形式)をライブラリへ取り込む。expectedVideoPath があれば新しいスタックとして登録し、開きはしない。
//! 取り込んだことは、書き込みを終えた知らせを受けてから通知する。
//! 参照: _doc/設計/ライブラリ.md 判断4

use clip_domain::{
    スタックの名前, スタック設定, ライブラリのスタック, ライブラリの日時
};

use crate::command::applier::操作の適用係;
use crate::persistence::設定ファイルのパス;
use crate::state::library::保存の目的;
use crate::state::アプリの状態;

/// 名前にできるものが無いときの取り込んだスタックの名前。
const 取り込んだスタックの既定の名前: &str = "取り込んだスタック";

impl 操作の適用係 {
    /// 設定ファイルを選ばせて取り込む。
    pub(super) fn 設定ファイルを選んで取り込む(
        &mut self, 状態: &mut アプリの状態
    ) {
        if let Some(パス) = self.窓口.設定ファイルを選ぶ() {
            self.設定ファイルを取り込む(状態, &パス);
        }
    }

    /// 設定ファイルを読み、動画のパスがあればライブラリへ保存を頼む。名前は設定ファイルの名前から拡張子を除いたもの。
    /// 一覧の画面へ落とした設定ファイルもこの口で取り込む。
    pub(in crate::command) fn 設定ファイルを取り込む(
        &mut self,
        状態: &mut アプリの状態,
        パス: &設定ファイルのパス,
    ) {
        let 今 = 状態.ライブラリ.接続.今の日時();
        let スタック = match self.設定ファイルからスタックを作る(パス, 今) {
            Ok(スタック) => スタック,
            Err(理由) => return 状態.通知.出す(format!("取り込めない: {理由}")),
        };
        let 目的 = 保存の目的::取り込み(スタック.名前().clone());
        match 状態.ライブラリ.接続.保存を頼む(スタック, 目的) {
            Ok(_) => 状態.一覧を読み直す(),
            Err(理由) => 状態.通知.出す(format!("ライブラリへ書き込めない: {理由}")),
        }
    }

    fn 設定ファイルからスタックを作る(
        &mut self,
        パス: &設定ファイルのパス,
        今: ライブラリの日時,
    ) -> Result<ライブラリのスタック, String> {
        let 本文 = self
            .窓口
            .設定ファイルを読む(パス)
            .map_err(|原因| 原因.to_string())?;
        let 設定 = スタック設定::本文から読み込む(&本文, &mut self.発行元)
            .map_err(|エラー| エラー.to_string())?;
        let 名前 = スタックの名前::作成する(パス.拡張子を除いた名前())
            .or_else(|_| {
                スタックの名前::作成する(取り込んだスタックの既定の名前.to_string())
            })
            .map_err(|エラー| エラー.to_string())?;
        let 識別子 = self.発行元.新しいスタックの識別子を発行する();
        設定
            .ライブラリへ取り込む(識別子, 名前, 今)
            .map_err(|理由| 理由.to_string())
    }
}
