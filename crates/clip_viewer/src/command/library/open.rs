//! 一覧から開く。動画を既存の動画を開く経路で読み込み、クリップの並びを置き換え、開いているスタックをそのスタックにする。
//! 参照: _doc/設計/ライブラリ.md 判断7

use clip_domain::{スタックの識別子, ライブラリのスタック};

use crate::command::applier::操作の適用係;
use crate::state::library::{
    ライブラリの窓, 登録済みのスタック, 開いているスタック
};
use crate::state::{アプリの状態, 並びの出どころ, 画面の構え};
use crate::video_feed::{動画を開く経路, 読み込んだ動画};

impl 操作の適用係 {
    /// スタックを読み、動画を開いて、状態へ入れる。動画を開けなければ理由を知らせ、今の画面は変えない。
    /// 開いているスタックの保存は、呼ぶ前に確かめておく。
    pub(crate) fn ライブラリのスタックを開く(
        &mut self,
        状態: &mut アプリの状態,
        識別子: &スタックの識別子,
    ) {
        let スタック = match 状態.ライブラリ.接続.書き込みを終えてから読む(識別子)
        {
            Ok(スタック) => スタック,
            Err(理由) => {
                return 状態
                    .通知
                    .出す(format!("ライブラリのスタックを開けない: {理由}"));
            }
        };
        match self
            .開き手
            .開く(スタック.動画のパス(), 状態.音の出力.周波数())
        {
            Ok(動画) => 状態.ライブラリのスタックを入れる(スタック, 動画),
            Err(理由) => 状態.通知.出す(format!(
                "動画を開けない({}): {}",
                スタック.動画のパス().文字列(),
                理由.案内を添えた文(動画を開く経路::ライブラリの一覧から)
            )),
        }
    }
}

impl アプリの状態 {
    /// 開いた動画とライブラリのスタックを入れ、先頭のクリップを選び、今の再生モードの先頭から再生を始めて編集の構えへ移る。
    pub(crate) fn ライブラリのスタックを入れる(
        &mut self,
        スタック: ライブラリのスタック,
        動画: 読み込んだ動画,
    ) {
        self.手がかり.開いた動画に合わせる(スタック.動画のパス());
        self.動画 = Some(動画);
        self.並びを置き換える(スタック.並び().clone(), 並びの出どころ::ファイルから読んだ);
        self.再生.再生を始める();
        self.構えを移す(画面の構え::編集);
        self.ライブラリ.窓 = ライブラリの窓::無し;
        if self.ライブラリ.接続.書けるか() {
            self.通知
                .出す(format!("ライブラリから開きました: {}", スタック.名前()));
            self.ライブラリ.開いている = 開いているスタック::登録済み(
                登録済みのスタック::ファイルから開いた(スタック),
            );
        } else {
            self.通知.出す(format!(
                "ライブラリから読み取り専用で開きました: {}。変更はライブラリへ保存しない",
                スタック.名前()
            ));
            self.ライブラリ.開いている = 開いているスタック::未登録;
        }
    }
}
