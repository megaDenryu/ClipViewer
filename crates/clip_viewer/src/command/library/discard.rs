//! 確かめる窓(登録していない変更を捨てるか・保存できないまま続けるか)で、利用者が決めたときの操作。
//! 「変更を捨てて続ける」は、窓が持つ続ける操作を確かめずに行う。開いているスタックとの関係は、続ける操作が成功したときだけ終える
//! (通常の経路と同じ)。取り消し・失敗のときは関係を残し、頼み直しと閉じるときの確かめを続けるためである。
//! 「ライブラリに保存する」は、続ける操作を持たせた名前を付けて登録する窓を開く。

use crate::command::applier::操作の適用係;
use crate::state::library::登録の後にすること;
use crate::state::アプリの状態;

impl 操作の適用係 {
    pub(super) fn 変更を捨てて続ける(&mut self, 状態: &mut アプリの状態) {
        if let Some(続ける操作) = 状態.ライブラリ.窓.続ける操作を取り出す() {
            self.関係を終える操作を行う(状態, 続ける操作);
        }
    }
}

impl アプリの状態 {
    /// 登録していない変更を捨てるかを確かめる窓で「ライブラリに保存する」を選んだ。登録したら元の操作を続ける。
    pub(super) fn 登録してから続ける(&mut self) {
        if let Some(続ける操作) = self.ライブラリ.窓.続ける操作を取り出す() {
            self.登録の窓を開く(登録の後にすること::続ける(続ける操作));
        }
    }
}
