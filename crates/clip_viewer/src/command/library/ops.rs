//! ライブラリの操作。ヘッダーと一覧の画面とダイアログが発する操作を列挙し、振り分ける。参照: _doc/設計/ライブラリ.md

use clip_domain::スタックの識別子;

use crate::command::applier::操作の適用係;
use crate::library_common::list::{
    並べ替え方, 絞り込みの語, 見えている行の範囲
};
use crate::state::library::{
    ライブラリのダイアログ, 登録の後にすること, 関係を終える操作
};
use crate::state::アプリの状態;

/// ライブラリの操作とは、スタックのライブラリについて画面が発する操作の区別のことである。
/// 識別子を持たない決定の操作(登録する・名前を変える・削除する・変更を捨てて続ける・登録してから続ける)は、開いているダイアログが持つ値を使う。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum ライブラリの操作 {
    登録のダイアログを開く,
    今すぐ保存する,
    名前の入力を書き換える(String),
    登録する,
    名前を変えるダイアログを開く(スタックの識別子),
    名前を変える,
    削除の確認を開く(スタックの識別子),
    削除する,
    ダイアログを閉じる,
    開く(スタックの識別子),
    変更を捨てて続ける,
    登録してから続ける,
    複製する(スタックの識別子),
    動画の場所を指定し直す(スタックの識別子),
    取り込む,
    読み直す,
    絞り込みを書き換える(String),
    並べ替えを選ぶ(並べ替え方),
    一覧の見えている行を知らせる(見えている行の範囲),
}

impl 操作の適用係 {
    pub(in crate::command) fn ライブラリの操作を適用する(
        &mut self,
        状態: &mut アプリの状態,
        操作: ライブラリの操作,
    ) {
        match 操作 {
            ライブラリの操作::登録のダイアログを開く => {
                状態.登録のダイアログを開く(登録の後にすること::何もしない)
            }
            ライブラリの操作::今すぐ保存する => 状態.今すぐライブラリへ保存する(),
            ライブラリの操作::名前の入力を書き換える(文字列) => {
                状態.ライブラリ.ダイアログ.名前の入力を書き換える(文字列)
            }
            ライブラリの操作::登録する => self.登録する(状態),
            ライブラリの操作::名前を変えるダイアログを開く(識別子) => {
                状態.名前を変えるダイアログを開く(&識別子)
            }
            ライブラリの操作::名前を変える => self.名前を変える(状態),
            ライブラリの操作::削除の確認を開く(識別子) => {
                状態.削除の確認を開く(&識別子)
            }
            ライブラリの操作::削除する => self.削除する(状態),
            ライブラリの操作::ダイアログを閉じる => {
                状態.ライブラリ.ダイアログ = ライブラリのダイアログ::無し
            }
            ライブラリの操作::開く(識別子) => self.確かめてから関係を終える操作を行う(
                状態,
                関係を終える操作::一覧から開く(識別子),
            ),
            ライブラリの操作::変更を捨てて続ける => {
                self.変更を捨てて続ける(状態)
            }
            ライブラリの操作::登録してから続ける => 状態.登録してから続ける(),
            ライブラリの操作::複製する(識別子) => self.複製する(状態, 識別子),
            ライブラリの操作::動画の場所を指定し直す(識別子) => {
                self.動画の場所を指定し直す(状態, 識別子)
            }
            ライブラリの操作::取り込む => {
                self.設定ファイルを選んで取り込む(状態)
            }
            ライブラリの操作::読み直す => 状態.一覧を読み直す(),
            ライブラリの操作::絞り込みを書き換える(文字列) => 状態
                .ライブラリ
                .一覧
                .絞り込みを変える(絞り込みの語::作成する(文字列)),
            ライブラリの操作::並べ替えを選ぶ(並べ替え) => {
                状態.ライブラリ.一覧.並べ替えを変える(並べ替え)
            }
            ライブラリの操作::一覧の見えている行を知らせる(範囲) => {
                状態.ライブラリ.見えている行 = Some(範囲)
            }
        }
    }
}
