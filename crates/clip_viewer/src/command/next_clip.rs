//! 次のクリップへ進める操作。Next Clip・PageDown・出力のクリックと、Enter キーの操作を状態へ当てる。
//! 進めるかの規則は `clip_domain` の `操作で次へ進める` が持つ。Enter キーはトリガーを待たずに Next Clip と同じく進め、
//! シーケンス再生でなければ進まないことを知らせる(オーナーの決定 2026-10-03)。参照: _doc/設計/画面.md 判断14

use clip_domain::{
    クリップ識別子, 再生位置, 次へ進めた結果, 進めない理由, 進める操作
};

use crate::state::アプリの状態;
use crate::viewer_settings::キーで行う操作;

/// Enter キーで進めなかったときの知らせの、キーの表記より後の部分。単独クリップ再生と元動画再生では、押しても何も起きないように見えるため知らせる。
/// 知らせは、この操作の今のキーの表記(既定は Enter)の後に続けて「Enter で次へ進めるのは…」の形にする(キーを変えても嘘にならないため)。
const ENTERキーで進めないときの知らせ: &str = "で次へ進めるのはシーケンス再生のときだけです";

/// 次へ進めた後にすることとは、次へ進めた結果から借用を外して取り出した、状態へ行う変更の区別のことである。
enum 次へ進めた後にすること {
    進む(再生位置, クリップ識別子),
    止める(再生位置),
    何もしない(進めない理由),
}

impl アプリの状態 {
    /// 進める操作で次のクリップへ進める。進めなければ何もしない。
    pub(super) fn 次へ進める(&mut self, 操作: 進める操作) {
        let すること = self.次へ進めた後にすることを求める(操作);
        self.次へ進めた後にすることを行う(すること);
    }

    /// Enter キーの操作。トリガーを待たずに次へボタンと同じく進め、シーケンス再生でなければ進めずに知らせる。
    /// 再生位置にクリップが無いときは、次へボタンと同じく何もしない。
    pub(super) fn enterキーで次へ進める(&mut self) {
        match self.次へ進めた後にすることを求める(進める操作::次へボタン) {
            次へ進めた後にすること::何もしない(
                進めない理由::シーケンス再生でない,
            ) => {
                let キー = self
                    .キーの割り当て
                    .操作のキー(キーで行う操作::次のクリップへ進めるか知らせる)
                    .表記();
                self.通知
                    .出す(format!("{キー} {ENTERキーで進めないときの知らせ}"));
            }
            すること => self.次へ進めた後にすることを行う(すること),
        }
    }

    fn 次へ進めた後にすることを求める(
        &self,
        操作: 進める操作,
    ) -> 次へ進めた後にすること {
        let 全体の末尾 = self.再生.全体の末尾;
        match self
            .再生
            .位置()
            .操作で次へ進める(操作, &self.並び, 全体の末尾)
        {
            次へ進めた結果::進んだ {
                位置, クリップ
            } => 次へ進めた後にすること::進む(位置, クリップ.識別子().clone()),
            次へ進めた結果::末尾で止めた { 位置, .. } => {
                次へ進めた後にすること::止める(位置)
            }
            次へ進めた結果::進めない(理由) => {
                次へ進めた後にすること::何もしない(理由)
            }
        }
    }

    fn 次へ進めた後にすることを行う(
        &mut self, すること: 次へ進めた後にすること
    ) {
        match すること {
            次へ進めた後にすること::進む(位置, 識別子) => {
                self.再生.位置を移す(位置);
                // 注意: 識別子は並びから取ったばかりなので、選択は失敗しない。
                let _ = self.並び.選択する(&識別子);
            }
            次へ進めた後にすること::止める(位置) => {
                self.再生.位置を移す(位置);
                self.再生.止める();
            }
            次へ進めた後にすること::何もしない(_) => {}
        }
    }
}
