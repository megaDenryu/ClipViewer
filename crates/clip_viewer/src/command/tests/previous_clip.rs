//! 前のクリップへ戻る操作の試験。シーケンス再生で前の再生できるクリップの開始へ移って選び、先頭のクリップではその開始へ移る。
#![allow(clippy::expect_used)]

use clip_domain::{再生位置, 時刻};

use super::clip_arrange::甲乙丙;
use super::選択中の名前;
use crate::command::出力の操作;

#[test]
fn 前のクリップへ戻るとその開始へ移って選ぶ() {
    let mut 状態 = 甲乙丙();
    状態.再生.位置を移す(再生位置::シーケンス再生(
        時刻::作成する(3.5).expect("時刻"),
    ));
    状態.出力の操作を適用する(出力の操作::前のクリップへ戻る);
    assert_eq!(
        状態.再生.位置(),
        再生位置::シーケンス再生(時刻::作成する(1.0).expect("時刻"))
    );
    assert_eq!(選択中の名前(&状態), "乙");
    状態.出力の操作を適用する(出力の操作::前のクリップへ戻る);
    assert_eq!(選択中の名前(&状態), "甲");
    状態.出力の操作を適用する(出力の操作::前のクリップへ戻る);
    assert_eq!(状態.再生.位置(), 再生位置::シーケンス再生(時刻::先頭));
}
