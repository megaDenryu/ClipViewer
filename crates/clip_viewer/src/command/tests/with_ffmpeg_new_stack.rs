//! 今の動画で新しいスタックを始める操作の結合試験。動画は開いたまま「Clip Mod 1」だけの未登録のスタックで始めること、
//! 登録していない変更があれば確かめること、取り消しの履歴を空にすることを確かめる。登録済みのスタックから始める試験は `with_ffmpeg_new_stack_library.rs` にある。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::with_ffmpeg_video::{試験動画を作る, 読み手のある試験};
use super::{
    並びのクリップの名前, 今の動画で新しいスタックを始める応答
};
use crate::command::{クリップの操作, ライブラリの操作, 応答};
use crate::state::library::{
    ライブラリのダイアログ, 並びを捨てる理由, 開いたときの添え書き, 開いているスタック,
    関係を終える操作,
};

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 押すと動画を開いたまま最初のクリップだけの未登録のスタックで始める() {
    let (mut 試験, mut 状態) = 読み手のある試験("新しいスタックを始める");
    let 動画 = 試験動画を作る("新しいスタックを始める");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &動画, 開いたときの添え書き::無し);
    let 前のクリップ = 状態.並び.一覧()[0].識別子().clone();
    試験
        .適用係
        .適用する(&mut 状態, 今の動画で新しいスタックを始める応答);
    assert_eq!(
        状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::無し,
        "開いただけの「Clip Mod 1」は変更に数えない"
    );
    assert!(状態.動画.is_some(), "動画は開いたまま");
    assert_eq!(並びのクリップの名前(&状態), ["Clip Mod 1"]);
    let クリップ = &状態.並び.一覧()[0];
    assert_ne!(クリップ.識別子(), &前のクリップ, "新しく作ったクリップ");
    assert!(クリップ.区間.開始().秒数().abs() < 1e-9);
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    assert_eq!(
        状態.通知.最新().map(|(_, 文)| 文.to_string()),
        Some("新しいスタックを始めました".to_string())
    );
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 変えていれば確かめ_変更を捨てて続けると履歴を空にして始める() {
    let (mut 試験, mut 状態) = 読み手のある試験("変えてから新しいスタック");
    let 動画 = 試験動画を作る("変えてから新しいスタック");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &動画, 開いたときの添え書き::無し);
    試験
        .適用係
        .適用する(&mut 状態, 応答::クリップ(クリップの操作::追加する));
    状態.フレームを進める(Instant::now());
    assert!(状態.取り消せるか());
    試験
        .適用係
        .適用する(&mut 状態, 今の動画で新しいスタックを始める応答);
    assert_eq!(
        状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(
            並びを捨てる理由::登録していない変更がある,
            関係を終える操作::今の動画で新しいスタックを始める
        )
    );
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::ダイアログを閉じる),
    );
    assert_eq!(状態.並び.一覧().len(), 2, "やめると何もしない");
    試験
        .適用係
        .適用する(&mut 状態, 今の動画で新しいスタックを始める応答);
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    assert_eq!(並びのクリップの名前(&状態), ["Clip Mod 1"]);
    assert!(状態.動画.is_some());
    状態.フレームを進める(Instant::now());
    assert!(
        !状態.取り消せるか() && !状態.やり直せるか(),
        "取り消しの履歴を空にする"
    );
}
