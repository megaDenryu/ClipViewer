//! 取り消しの区切りの備えと、開いているスタックを削除した後の確かめの試験。
//! 主ボタンを押していないフレームは、数値入力の区切りの応答が届かなくても取り消しのまとめを区切る。
//! 開いているスタックを削除した後の並びはファイルに残っていないため、捨てる前に確かめる窓を出す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::トリガー;

use super::library_support::試験のライブラリ;
use super::{クリップを並べた状態, クリップを作る, 編集する, 識別子};
use crate::command::{
    クリップの操作, クリップの編集, ファイルの操作, ライブラリの操作, 主ボタンの様子, 区間の端,
    応答,
};
use crate::state::library::{
    ライブラリの窓, 並びを捨てる理由, 関係を終える操作
};
use crate::state::アプリの状態;

fn 甲の開始(状態: &アプリの状態) -> Option<f64> {
    状態
        .並び
        .識別子で探す(&識別子("甲"))
        .map(|クリップ| クリップ.区間.開始().秒数())
}

/// 甲の開始を2回続けて数値入力で変え、その間の主ボタンの様子で取り残されたドラッグの安全網を通す。取り消した後の開始を返す。
fn 続けて変えて取り消す(主ボタン: 主ボタンの様子) -> Option<f64> {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    let 今 = Instant::now();
    編集する(
        &mut 状態,
        クリップの編集::区間の端を決める(区間の端::開始, 0.1),
    );
    状態.取り残されたドラッグを捨てる(主ボタン);
    状態.フレームを進める(今);
    編集する(
        &mut 状態,
        クリップの編集::区間の端を決める(区間の端::開始, 0.2),
    );
    状態.フレームを進める(今);
    状態.クリップの操作を適用する(クリップの操作::編集を取り消す);
    甲の開始(&状態)
}

#[test]
fn 主ボタンを押していないフレームは取り消しのまとめを区切り_押している間は区切らない() {
    assert_eq!(
        続けて変えて取り消す(主ボタンの様子::押していない),
        Some(0.1)
    );
    assert_eq!(続けて変えて取り消す(主ボタンの様子::押している), Some(0.0));
}

#[test]
fn 開いているスタックを削除した後の並びは_捨てる前に確かめる() {
    let mut 試験 = 試験のライブラリ::作る("削除した後の並びを確かめる");
    let 甲 = クリップを作る("甲", 0.0, 1.0, トリガー::自動進行);
    let mut 状態 = 試験.接続した状態(vec![甲]);
    let スタック = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    for 操作 in [
        ライブラリの操作::削除の確認を開く(スタック),
        ライブラリの操作::削除する,
    ] {
        試験.適用係.適用する(&mut 状態, 応答::ライブラリ(操作));
    }
    試験
        .適用係
        .適用する(&mut 状態, 応答::ファイル(ファイルの操作::動画を解除する));
    assert_eq!(
        状態.ライブラリ.窓,
        ライブラリの窓::並びを捨てる確認(
            並びを捨てる理由::登録していない変更がある,
            関係を終える操作::動画を解除する
        )
    );
}
