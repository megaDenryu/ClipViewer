//! 再生と出力の操作の試験。

use clip_domain::{
    トリガー, 再生モード, 再生位置, 末尾での振る舞い, 進める操作
};

use super::{クリップを並べた状態, クリップを作る, 選択中の名前};
use crate::command::{再生の操作, 出力の操作, 送る向き};
use crate::state::{シークの様子, 画面の構え};

fn 位置の秒(状態: &crate::state::アプリの状態) -> f64 {
    状態.再生.位置().位置の秒数()
}

#[test]
fn 再生位置の帯のドラッグ中はシーク中になり_決めると外れ_位置は合計の長さへ収める() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        4.0,
        トリガー::自動進行,
    )]);
    状態.再生の操作を適用する(再生の操作::位置を動かしている(2.5));
    assert_eq!(状態.再生.シーク, シークの様子::ドラッグしている);
    assert!((位置の秒(&状態) - 2.5).abs() < 1e-9);
    状態.再生の操作を適用する(再生の操作::位置を決めた(99.0));
    assert_eq!(状態.再生.シーク, シークの様子::していない);
    assert!((位置の秒(&状態) - 4.0).abs() < 1e-9);
    状態.再生の操作を適用する(再生の操作::五秒ずらす(送る向き::戻す));
    assert!(位置の秒(&状態).abs() < 1e-9);
}

#[test]
fn 動画が無ければ一コマは30分の1秒で送る() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        4.0,
        トリガー::自動進行,
    )]);
    状態.再生の操作を適用する(再生の操作::コマ送り(送る向き::進める));
    assert!((位置の秒(&状態) - 1.0 / 30.0).abs() < 1e-9);
}

#[test]
fn トリガーと合うキーで次へ進み_合わないキーでは進まない() {
    let mut 状態 = クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::Enterキー待ち),
        クリップを作る("乙", 2.0, 3.0, トリガー::自動進行),
    ]);
    状態.出力の操作を適用する(出力の操作::次へ進める(進める操作::出力のクリック));
    assert_eq!(選択中の名前(&状態), "甲");
    状態.出力の操作を適用する(出力の操作::次へ進める(進める操作::Enterキー));
    assert_eq!(選択中の名前(&状態), "乙");
    assert!((位置の秒(&状態) - 1.0).abs() < 1e-9);
}

#[test]
fn 全体ループが無効なら最後のクリップの次へで再生を止めて末尾へ移る() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    状態.再生の操作を適用する(再生の操作::全体ループを切り替える(false));
    assert_eq!(状態.再生.全体の末尾, 末尾での振る舞い::止まる);
    状態.出力の操作を適用する(出力の操作::次へ進める(進める操作::次へボタン));
    assert!(!状態.再生.再生しているか());
    assert!((位置の秒(&状態) - 1.0).abs() < 1e-9);
}

#[test]
fn 再生モードを選ぶとそのモードの先頭へ移り_同じ構えを選んでも知らせない() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        4.0,
        トリガー::自動進行,
    )]);
    状態.再生の操作を適用する(再生の操作::位置を決めた(3.0));
    状態.出力の操作を適用する(出力の操作::再生モードを選ぶ(
        再生モード::単独クリップ再生,
    ));
    assert!(matches!(状態.再生.位置(), 再生位置::単独クリップ再生(経過) if 経過.ゼロか()));
    状態.出力の操作を適用する(出力の操作::構えを選ぶ(画面の構え::編集));
    assert!(状態.通知.最新().is_none());
    状態.出力の操作を適用する(出力の操作::構えを選ぶ(画面の構え::シアター));
    assert_eq!(
        状態.通知.最新().map(|(_, 文面)| 文面.to_string()),
        Some("シアター".into())
    );
}
