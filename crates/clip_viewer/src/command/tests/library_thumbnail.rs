//! いつ撮るかの試験。起動して一覧を読んだだけでは、キャッシュも見ず撮りもしない。ライブラリの構えを開くと、キャッシュを見て、
//! 無いものを撮りに行く。FFmpeg の無い状態で流し、撮りに行く判定は「撮らない(FFmpeg が無い)」で観察する。
#![allow(clippy::expect_used)]

use super::library_check::終えるまで待って当てる;
use super::library_support::試験のライブラリ;
use super::thumbnail_check::{見えている行で進める, 見せ方};
use super::thumbnail_place::動画のあるスタックを置く;
use crate::thumbnail_feed::{
    サムネイルの見せ方, サムネイルを撮らない理由, 途中の段階
};

#[test]
fn 一覧を読んだだけでは撮らず_ライブラリの構えを開くと撮りに行く() {
    let 試験 = 試験のライブラリ::作る("サムネイルを撮るとき");
    let 識別子の一覧: Vec<_> = ["stack-1-1", "stack-2-2", "stack-3-3"]
        .into_iter()
        .map(|識別子| 動画のあるスタックを置く(&試験, 識別子, None))
        .collect();
    let mut 状態 = 試験.接続した状態(Vec::new());
    状態.一覧を読み直す();
    終えるまで待って当てる(&mut 状態);
    for _ in 0..5 {
        状態.サムネイルを進める();
    }
    assert!(
        !状態.ライブラリ.サムネイル.返事を待っているか(),
        "何も頼んでいない"
    );
    for 識別子 in &識別子の一覧 {
        assert!(
            matches!(
                見せ方(&状態, 識別子),
                Some(サムネイルの見せ方::途中(途中の段階::読んでいる))
            ),
            "キャッシュを見る前のまま"
        );
    }
    見えている行で進める(&mut 状態, 0..=0);
    for 識別子 in &識別子の一覧 {
        assert!(
            matches!(
                見せ方(&状態, 識別子),
                Some(サムネイルの見せ方::撮らない(
                    サムネイルを撮らない理由::FFmpegが無い
                ))
            ),
            "見えている行を終えたら、残りの行もキャッシュを見て撮りに行く"
        );
    }
}
