//! 区間の帯の秒の丸めの試験。区間の帯から受け取った秒だけを0.01秒の倍数へ丸め、動かさなかった端は変えないことと、
//! 右端まで動かした端が上限を超えない0.01秒の倍数になることを確かめる。

use clip_domain::トリガー;

use super::band::{区間の帯を操作する, 甲の区間};
use super::{クリップを並べた状態, クリップを作る};
use crate::command::区間の帯の段階;
use crate::state::{アプリの状態, 区間の帯で掴んだもの};

/// 甲[1, 10.047) の状態。動画が無いので上限は区間の終了の10.047秒であり、数値入力で動画の長さに合わせた終了にあたる。
fn 終了が丸めていない甲() -> アプリの状態 {
    クリップを並べた状態(vec![クリップを作る(
        "甲",
        1.0,
        10.047,
        トリガー::自動進行,
    )])
}

fn 動かして放す(
    状態: &mut アプリの状態, 掴んだもの: 区間の帯で掴んだもの, 秒: f64
) {
    区間の帯を操作する(状態, "甲", 区間の帯の段階::掴み始めた, 掴んだもの, 秒);
    区間の帯を操作する(
        状態,
        "甲",
        区間の帯の段階::動かしている,
        掴んだもの,
        秒 + 0.5,
    );
    区間の帯を操作する(状態, "甲", 区間の帯の段階::動かしている, 掴んだもの, 秒);
    区間の帯を操作する(状態, "甲", 区間の帯の段階::放した, 掴んだもの, 秒);
}

#[test]
fn 開始だけを動かしたら丸めていない終了は変わらない() {
    let mut 状態 = 終了が丸めていない甲();
    動かして放す(&mut 状態, 区間の帯で掴んだもの::開始のつまみ, 2.004);
    let 区間 = 甲の区間(&状態).expect("甲");
    assert!((区間.開始().秒数() - 2.0).abs() < 1e-9);
    assert_eq!(区間.終了().秒数(), 10.047);
}

#[test]
fn 終了を右端まで動かすと上限以下の0点01秒の倍数になる() {
    let mut 状態 = 終了が丸めていない甲();
    区間の帯を操作する(
        &mut 状態,
        "甲",
        区間の帯の段階::掴み始めた,
        区間の帯で掴んだもの::終了のつまみ,
        10.047,
    );
    区間の帯を操作する(
        &mut 状態,
        "甲",
        区間の帯の段階::動かしている,
        区間の帯で掴んだもの::終了のつまみ,
        9.0,
    );
    区間の帯を操作する(
        &mut 状態,
        "甲",
        区間の帯の段階::動かしている,
        区間の帯で掴んだもの::終了のつまみ,
        10.047,
    );
    区間の帯を操作する(
        &mut 状態,
        "甲",
        区間の帯の段階::放した,
        区間の帯で掴んだもの::終了のつまみ,
        10.047,
    );
    let 終了 = 甲の区間(&状態).expect("甲").終了().秒数();
    assert!(終了 <= 10.047 && (終了 - 10.04).abs() < 1e-9, "終了 {終了}");
}
