//! 区間の上限の結合試験。1秒より短い動画でも、全体の帯・区間の端の編集・クリップの追加・区間が動画の外にあるかの判定が
//! 動画の終わりを上限にすることと、1秒以上の動画で上限が動画の長さのままであることを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use clip_domain::{クリップ, クリップスタック, トリガー, 再生位置, 時刻};

use super::library_support::試験のライブラリ;
use super::with_ffmpeg_video::{読み手のある試験, 長さを決めて試験動画を作る};
use super::クリップを作る;
use crate::command::{クリップの操作, クリップの編集, 区間の端, 応答};
use crate::state::library::開いたときの添え書き;
use crate::state::{アプリの状態, 並びの出どころ};

/// 小数の比較で許す誤差の秒数。
const 誤差: f64 = 1e-9;

/// 秒数の長さの試験動画を開き、止めた状態にする。
fn 動画を開いた試験(
    試験の名前: &str,
    秒数: f64,
) -> (試験のライブラリ, アプリの状態) {
    let (mut 試験, mut 状態) = 読み手のある試験(試験の名前);
    let 動画 = 長さを決めて試験動画を作る(試験の名前, "練習動画.mp4", 秒数);
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &動画, 開いたときの添え書き::無し);
    状態.再生.止める();
    (試験, 状態)
}

fn 先頭のクリップ(状態: &アプリの状態) -> クリップ {
    状態.並び.一覧()[0].clone()
}

/// 秒数の長さの試験動画を開き、全体の帯の右端と、先頭のクリップの終了を動かす先へ決めた後の終了が、どちらも動画の長さで
/// あることを確かめる。動かす先は動画の終わりより後ろを渡す。確かめた動画の長さを返す。
fn 全体の帯と終了の上限が動画の長さであることを確かめる(
    試験の名前: &str,
    秒数: f64,
    動かす先: f64,
) -> f64 {
    let (mut 試験, mut 状態) = 動画を開いた試験(試験の名前, 秒数);
    let 動画の長さ = 状態.動画の長さ().秒数();
    let 先頭 = 先頭のクリップ(&状態);
    let 帯 = 状態.カードの区間の帯に描く値(&先頭, true);
    assert!((帯.全体の範囲.終了().秒数() - 動画の長さ).abs() < 誤差);
    let 編集 = クリップの編集::区間の端を決める(区間の端::終了, 動かす先);
    let 操作 = クリップの操作::編集する(先頭.識別子().clone(), 編集);
    試験.適用係.適用する(&mut 状態, 応答::クリップ(操作));
    let 終了 = 先頭のクリップ(&状態).区間.終了().秒数();
    assert!((終了 - 動画の長さ).abs() < 誤差, "終了 {終了}");
    動画の長さ
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 一秒より短い動画では全体の帯が動画の終わりまでで_終了を動画の終わりより後ろへ動かせない() {
    let 動画の長さ = 全体の帯と終了の上限が動画の長さであることを確かめる(
        "短い動画の帯",
        0.5,
        0.9,
    );
    assert!(
        動画の長さ > 0.0 && 動画の長さ < 1.0,
        "動画の長さ {動画の長さ}"
    );
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 一秒以上の動画では全体の帯と終了の上限が動画の長さのままである() {
    let 動画の長さ = 全体の帯と終了の上限が動画の長さであることを確かめる(
        "長い動画の帯",
        2.0,
        5.0,
    );
    assert!(動画の長さ > 1.9, "動画の長さ {動画の長さ}");
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 一秒より短い動画で今の位置からクリップを追加しても終了は動画の終わりを越えない() {
    let (mut 試験, mut 状態) = 動画を開いた試験("短い動画へ追加", 0.5);
    let 動画の長さ = 状態.動画の長さ().秒数();
    状態.再生.位置を移す(再生位置::元動画再生(
        時刻::作成する(0.3).expect("時刻"),
    ));
    試験
        .適用係
        .適用する(&mut 状態, 応答::クリップ(クリップの操作::追加する));
    let 区間 = 状態.並び.一覧().last().expect("足したクリップ").区間;
    assert!((区間.開始().秒数() - 0.3).abs() < 誤差);
    let 終了 = 区間.終了().秒数();
    assert!(終了 <= 動画の長さ + 誤差, "終了 {終了}");
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 一秒より短い動画の終わりより後ろまである区間だけを動画の外とみなす() {
    let (_試験, mut 状態) = 動画を開いた試験("短い動画の外", 0.5);
    let 外 = クリップを作る("外", 0.1, 0.8, トリガー::自動進行);
    let 内 = クリップを作る("内", 0.1, 0.4, トリガー::自動進行);
    let 並び = クリップスタック::一覧から作成する(vec![外.clone(), 内.clone()]);
    状態.並びを置き換える(並び.expect("スタック"), 並びの出どころ::ファイルから読んだ);
    let 外にあるか = |クリップ| {
        状態
            .カードの区間の帯に描く値(クリップ, false)
            .区間が動画の外にあるか
    };
    assert!(外にあるか(&外));
    assert!(!外にあるか(&内));
}
