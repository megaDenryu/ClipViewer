//! 動画を開いて編集する操作の結合試験。今見ている位置からの追加と、同じ動画と別の動画を開いたときの並びを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use clip_domain::{再生位置, 時刻};

use super::with_ffmpeg_video::{名前を付けて試験動画を作る, 読み手のある試験};
use crate::command::{クリップの操作, ライブラリの操作, 応答};
use crate::state::library::{
    ライブラリのダイアログ, 並びを捨てる理由, 開いたときの添え書き, 関係を終える操作,
};
use crate::state::アプリの状態;

fn 並びの区間(状態: &アプリの状態) -> Vec<(f64, f64)> {
    状態
        .並び
        .一覧()
        .iter()
        .map(|クリップ| (クリップ.区間.開始().秒数(), クリップ.区間.終了().秒数()))
        .collect()
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 新しいクリップを追加すると今見ている位置から始まり_動画の終わりで止める() {
    let (mut 試験, mut 状態) = 読み手のある試験("今の位置から追加");
    let 動画 = 名前を付けて試験動画を作る("今の位置から追加", "練習動画.mp4");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &動画, 開いたときの添え書き::無し);
    状態.再生.止める();
    状態.再生.位置を移す(再生位置::元動画再生(
        時刻::作成する(1.0).expect("時刻"),
    ));
    試験
        .適用係
        .適用する(&mut 状態, 応答::クリップ(クリップの操作::追加する));
    let 区間 = 並びの区間(&状態);
    assert_eq!(区間.len(), 2);
    let (開始, 終了) = 区間[1];
    assert!((開始 - 1.0).abs() < 1e-9, "{開始}");
    assert!(
        終了 > 1.9 && 終了 <= 2.1,
        "5秒より短い動画の終わりで止める: {終了}"
    );
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 同じ動画を開き直すと並びを残し_別の動画は確かめてから新しい並びで始める() {
    let (mut 試験, mut 状態) = 読み手のある試験("別の動画");
    let 練習 = 名前を付けて試験動画を作る("別の動画", "練習動画.mp4");
    let 別の動画のパス = 名前を付けて試験動画を作る("別の動画", "別の動画.mp4");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &練習, 開いたときの添え書き::無し);
    試験
        .適用係
        .適用する(&mut 状態, 応答::クリップ(クリップの操作::追加する));
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &練習, 開いたときの添え書き::無し);
    assert_eq!(状態.並び.一覧().len(), 2, "同じ動画なら並びを残す");
    assert!(
        状態.取り消せるか(),
        "同じ動画を開き直しても編集の履歴を引き継ぐ"
    );
    試験
        .適用係
        .適用する(&mut 状態, 応答::クリップ(クリップの操作::追加する));
    let 開く = 関係を終える操作::動画を開く(
        別の動画のパス.clone(),
        開いたときの添え書き::無し,
    );
    試験.適用係.確かめてから動画を開く(
        &mut 状態,
        &別の動画のパス,
        開いたときの添え書き::無し,
    );
    assert_eq!(
        状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(
            並びを捨てる理由::登録していない変更がある,
            開く
        )
    );
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    assert_eq!(
        状態.並び.一覧().len(),
        1,
        "別の動画は最初のクリップ1つで始める"
    );
    assert!(!状態.取り消せるか(), "動画を開くと履歴を空にする");
}
