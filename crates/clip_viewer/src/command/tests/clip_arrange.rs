//! クリップの並べ替え・複製・区間の端を今の位置にすることの試験。
#![allow(clippy::expect_used)]

use clip_domain::{トリガー, 再生位置, 時刻};

use super::library_support::試験のライブラリ;
use super::{クリップを並べた状態, クリップを作る, 識別子, 選択中の名前};
use crate::command::{クリップの操作, 動かす向き, 区間の端, 応答};
use crate::state::アプリの状態;

pub(super) fn 甲乙丙() -> アプリの状態 {
    クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
        クリップを作る("丙", 10.0, 13.0, トリガー::自動進行),
    ])
}

fn 並びの名前(状態: &アプリの状態) -> Vec<String> {
    状態
        .並び
        .一覧()
        .iter()
        .map(|クリップ| クリップ.名前.文字列().to_string())
        .collect()
}

fn 区間の秒(状態: &アプリの状態, 名前: &str) -> Option<(f64, f64)> {
    状態
        .並び
        .識別子で探す(&識別子(名前))
        .map(|クリップ| (クリップ.区間.開始().秒数(), クリップ.区間.終了().秒数()))
}

#[test]
fn 前へと後ろへ動かすとそのクリップを選び_先頭は前へ末尾は後ろへ動かない() {
    let mut 状態 = 甲乙丙();
    状態.クリップの操作を適用する(クリップの操作::並びで動かす(
        識別子("丙"),
        動かす向き::前へ,
    ));
    assert_eq!(並びの名前(&状態), ["甲", "丙", "乙"]);
    assert_eq!(選択中の名前(&状態), "丙");
    assert!(
        (状態.再生.位置().位置の秒数() - 1.0).abs() < 1e-9,
        "止めているので動かしたクリップの開始へ移る"
    );
    状態.クリップの操作を適用する(クリップの操作::並びで動かす(
        識別子("甲"),
        動かす向き::前へ,
    ));
    状態.クリップの操作を適用する(クリップの操作::並びで動かす(
        識別子("乙"),
        動かす向き::後ろへ,
    ));
    assert_eq!(並びの名前(&状態), ["甲", "丙", "乙"]);
}

#[test]
fn 複製すると直後へ差し込んで選ぶ() {
    let mut 試験 = 試験のライブラリ::作る("複製");
    let mut 状態 = 甲乙丙();
    試験.適用係.適用する(
        &mut 状態,
        応答::クリップ(クリップの操作::複製する(識別子("甲"))),
    );
    assert_eq!(並びの名前(&状態), ["甲", "甲のコピー", "乙", "丙"]);
    assert_eq!(選択中の名前(&状態), "甲のコピー");
}

#[test]
fn 区間の端を今見ている位置に合わせ_区間が変わったらそのクリップの開始へ移る() {
    let mut 状態 = 甲乙丙();
    状態.再生.位置を移す(再生位置::元動画再生(
        時刻::作成する(6.0).expect("時刻"),
    ));
    状態.クリップの操作を適用する(クリップの操作::区間の端を今の位置にする(
        識別子("乙"),
        区間の端::開始,
    ));
    assert_eq!(区間の秒(&状態, "乙"), Some((6.0, 7.0)));
    assert_eq!(
        状態.再生.位置(),
        再生位置::元動画再生(時刻::作成する(6.0).expect("時刻"))
    );
    assert_eq!(選択中の名前(&状態), "乙");
    状態.クリップの操作を適用する(クリップの操作::選ぶ(識別子("丙")));
    状態.再生.位置を移す(再生位置::元動画再生(
        時刻::作成する(12.0).expect("時刻"),
    ));
    状態.クリップの操作を適用する(
        クリップの操作::選択中の区間の端を今の位置にする(区間の端::終了),
    );
    assert_eq!(区間の秒(&状態, "丙"), Some((10.0, 12.0)));
}
