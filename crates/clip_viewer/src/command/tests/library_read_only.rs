//! 同じライブラリを2つのアプリで開いたときの試験。2つ目は読み取り専用になり、一覧は読めるが、登録と変更は理由を出して断る。
#![allow(clippy::expect_used)]

use clip_domain::トリガー;

use super::library_check::終えるまで待って当てる;
use super::library_support::試験のライブラリ;
use super::クリップを作る;
use crate::command::{ライブラリの操作, 応答};
use crate::state::library::{ライブラリのダイアログ, 最後に読んだ一覧};

fn 最後の通知(状態: &crate::state::アプリの状態) -> String {
    状態
        .通知
        .最新()
        .map(|(_, 文面)| 文面.to_string())
        .unwrap_or_default()
}

#[test]
fn 二つ目のアプリは一覧を読めるが_登録と名前の変更を断る() {
    let mut 試験 = 試験のライブラリ::作る("読み取り専用");
    let 甲 = || vec![クリップを作る("甲", 0.0, 1.0, トリガー::自動進行)];
    let mut 一つ目 = 試験.接続した状態(甲());
    let 識別子 = 試験.登録済みにする(&mut 一つ目, "stack-1-1", "練習");
    let mut 二つ目 = 試験.接続した状態(甲());
    assert!(一つ目.ライブラリ.接続.書けるか());
    assert!(!二つ目.ライブラリ.接続.書けるか());
    二つ目.一覧を読み直す();
    終えるまで待って当てる(&mut 二つ目);
    assert!(
        matches!(二つ目.ライブラリ.一覧.一覧(), 最後に読んだ一覧::読めた(一覧) if 一覧.項目.len() == 1)
    );
    試験.適用係.適用する(
        &mut 二つ目,
        応答::ライブラリ(ライブラリの操作::登録のダイアログを開く),
    );
    assert_eq!(二つ目.ライブラリ.ダイアログ, ライブラリのダイアログ::無し);
    assert!(
        最後の通知(&二つ目).contains("読み取り専用"),
        "{}",
        最後の通知(&二つ目)
    );
    試験.適用係.適用する(
        &mut 二つ目,
        応答::ライブラリ(ライブラリの操作::名前を変えるダイアログを開く(識別子.clone())),
    );
    試験.適用係.適用する(
        &mut 二つ目,
        応答::ライブラリ(ライブラリの操作::名前の入力を書き換える(
            "乗っ取り".into(),
        )),
    );
    試験.適用係.適用する(
        &mut 二つ目,
        応答::ライブラリ(ライブラリの操作::名前を変える),
    );
    assert!(
        最後の通知(&二つ目).contains("読み取り専用"),
        "{}",
        最後の通知(&二つ目)
    );
    終えるまで待って当てる(&mut 二つ目);
    assert_eq!(
        試験.ファイルを読む(&識別子).expect("ある").名前().文字列(),
        "練習"
    );
}
