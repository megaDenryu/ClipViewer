/// 件数のスタックを保存し、どれも同じ撮り方なので、FFmpeg で1枚撮ってキャッシュへ置く。置いた画像のバイト数を返す。
fn 同じ顔のスタックとキャッシュを置く(
    試験: &試験のライブラリ,
    状態: &アプリの状態,
    件数: usize,
) -> usize {
    let ライブラリ = スタックのライブラリ::作成する(試験.フォルダ.clone());
    let 最初 = ライブラリのスタック::新しく作る(
        スタックの識別子::文字列から作成する("stack-0-0".into()).expect("識別子"),
        スタックの名前::作成する("甲".into()).expect("名前"),
        試験動画を作る("サムネイルの時間").正規化する(),
        状態.並び.clone(),
        ライブラリの日時::紀元からのミリ秒で作成する(1_000).expect("日時"),
    );
    let 撮り方 = 最初
        .サムネイルの撮り方(一覧のサムネイルの大きさ)
        .expect("撮り方");
    let 画像 = 動画の読み手::作成する(実行ファイルを探す())
        .サムネイルを作る(&撮り方, &取り消しの合図::default())
        .expect("撮れる");
    試験.キャッシュ().置く(&撮り方, &画像).expect("置ける");
    for 番号 in 0..件数 {
        let 識別子 =
            スタックの識別子::文字列から作成する(format!("stack-{番号}-0")).expect("識別子");
        let 名前 = 最初.名前().clone();
        let スタック = 最初.複製した(
            識別子,
            名前,
            ライブラリの日時::紀元からのミリ秒で作成する(1_000).expect("日時"),
        );
        ライブラリ.保存する(&スタック).expect("保存");
    }
    画像.バイト列().len()
}

/// 撮る順番を待っているか撮っている行の数。キャッシュを見終えてキャッシュに無かった行である。
fn キャッシュに無かった数(状態: &アプリの状態) -> usize {
    状態
        .ライブラリ
        .サムネイル
        .項目の表()
        .values()
        .filter(|項目| {
            matches!(
                項目.見せ方(),
                サムネイルの見せ方::途中(
                    途中の段階::撮る順番を待っている | 途中の段階::撮っている
                )
            )
        })
        .count()
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 四百件の一覧の見えている行を見せて残りのキャッシュを見終えるまでの時間を測る() {
    const 件数: usize = 400;
    let 試験 = 試験のライブラリ::作る("サムネイルの四百件");
    let mut 状態 = 試験.接続した状態(vec![クリップを作る(
        "甲",
        0.5,
        1.0,
        トリガー::自動進行,
    )]);
    let バイト数 = 同じ顔のスタックとキャッシュを置く(&試験, &状態, 件数);
    let 始め = Instant::now();
    状態.一覧を読み直す();
    終えるまで待って当てる(&mut 状態);
    見えている行で進める(&mut 状態, 0..=11);
    let かかった = 始め.elapsed();
    println!(
        "{件数}件の一覧を走査し、見えている12行のサムネイル(1枚 {バイト数}バイト)を見せて残りのキャッシュを見終えるまで: {かかった:?}"
    );
    assert_eq!(見せられる数(&状態), 12);
    assert_eq!(
        キャッシュに無かった数(&状態),
        0,
        "同じ撮り方なのでどれもキャッシュにある"
    );
    assert!(かかった < Duration::from_secs(10), "{かかった:?}");
}
