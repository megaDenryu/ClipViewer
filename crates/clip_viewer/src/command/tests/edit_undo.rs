//! 編集の取り消しとやり直しの試験。フレームの最初に並びの変化を積み、取り消しとやり直しで並びを戻し、選択は今のままにする。
//! クロップ枠のドラッグと、数値入力で続けて変えた区間の端は1つの編集にまとめる。並びを置き換えると履歴を空にすることは
//! `with_ffmpeg_edit.rs`(動画を開く)が確かめる。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{
    クロップの移動量, クロップ範囲, トリガー, 枠の掴む所, 百分率の差分
};

use super::{
    クリップを並べた状態, クリップを作る, 編集する, 識別子, 選択中の名前
};
use crate::command::{
    クリップの操作, クリップの編集, クロップ枠の操作, 区間の端
};
use crate::state::アプリの状態;

fn 甲と乙() -> アプリの状態 {
    クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
    ])
}

fn 甲の名前(状態: &アプリの状態) -> String {
    状態
        .並び
        .識別子で探す(&識別子("甲"))
        .map(|クリップ| クリップ.名前.文字列().to_string())
        .unwrap_or_default()
}

#[test]
fn 取り消しとやり直しで並びを戻し_選択は今のままにする() {
    let mut 状態 = 甲と乙();
    let 今 = Instant::now();
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    状態.フレームを進める(今);
    状態.クリップの操作を適用する(クリップの操作::選ぶ(識別子("乙")));
    状態.フレームを進める(今);
    assert!(状態.取り消せるか() && !状態.やり直せるか());
    状態.クリップの操作を適用する(クリップの操作::編集を取り消す);
    assert_eq!(甲の名前(&状態), "甲");
    assert_eq!(選択中の名前(&状態), "乙", "選択は取り消さない");
    状態.フレームを進める(今);
    assert!(
        !状態.取り消せるか() && 状態.やり直せるか(),
        "戻した並びを変化として積まない"
    );
    状態.クリップの操作を適用する(クリップの操作::編集をやり直す);
    assert_eq!(甲の名前(&状態), "変えた");
}

#[test]
fn クロップ枠のドラッグは放した時点で1つの編集として積む() {
    let mut 状態 = 甲と乙();
    let 今 = Instant::now();
    let 移動量 = |横| クロップの移動量 {
        横: 百分率の差分::作成する(横).expect("差分"),
        縦: 百分率の差分::作成する(0.0).expect("差分"),
    };
    状態.クロップ枠の操作を適用する(クロップ枠の操作::掴み始めた);
    for 横 in [-5.0, -10.0] {
        状態.クロップ枠の操作を適用する(クロップ枠の操作::動かしている {
            掴む所: 枠の掴む所::隅(clip_domain::四隅のつまみ::右下),
            移動量: 移動量(横),
        });
        状態.フレームを進める(今);
    }
    状態.クロップ枠の操作を適用する(クロップ枠の操作::放した {
        掴む所: 枠の掴む所::隅(clip_domain::四隅のつまみ::右下),
        移動量: 移動量(-20.0),
    });
    状態.フレームを進める(今);
    状態.クリップの操作を適用する(クリップの操作::編集を取り消す);
    let 甲のクロップ = 状態
        .並び
        .識別子で探す(&識別子("甲"))
        .map(|クリップ| クリップ.クロップ);
    assert_eq!(甲のクロップ, Some(クロップ範囲::全体));
    assert!(!状態.取り消せるか(), "ドラッグの途中の値は積まない");
}

#[test]
fn 数値入力で続けて変えた区間の端は操作を終えるまで1つの編集にまとめる() {
    let mut 状態 = 甲と乙();
    let 今 = Instant::now();
    let 開始を決める = |秒| クリップの編集::区間の端を決める(区間の端::開始, 秒);
    for 秒 in [0.1, 0.2, 0.3] {
        編集する(&mut 状態, 開始を決める(秒));
        状態.フレームを進める(今);
    }
    編集する(&mut 状態, 開始を決める(0.4));
    状態.クリップの操作を適用する(クリップの操作::続けて変える操作を終えた);
    状態.フレームを進める(今);
    編集する(&mut 状態, 開始を決める(0.5));
    状態.フレームを進める(今);
    let 甲の開始 = |状態: &アプリの状態| {
        状態
            .並び
            .識別子で探す(&識別子("甲"))
            .map(|クリップ| クリップ.区間.開始().秒数())
    };
    状態.クリップの操作を適用する(クリップの操作::編集を取り消す);
    assert_eq!(甲の開始(&状態), Some(0.4), "操作を終えた後の変化は別の編集");
    状態.クリップの操作を適用する(クリップの操作::編集を取り消す);
    assert_eq!(甲の開始(&状態), Some(0.0));
    assert!(!状態.取り消せるか());
}
