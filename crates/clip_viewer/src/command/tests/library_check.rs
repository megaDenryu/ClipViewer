//! ライブラリの試験で結果を確かめる道具。裏のスレッドの書き込みと走査を待って知らせを当てることと、ファイルのクリップの名前を並べること。

use clip_domain::ライブラリのスタック;

use crate::state::アプリの状態;

/// 裏のスレッドが頼まれた書き込みと走査を終えるまで待ち、届いた知らせを状態へ当てる。
pub(super) fn 終えるまで待って当てる(状態: &mut アプリの状態) {
    状態.ライブラリ.接続.走査も終えるまで待つ();
    状態.ライブラリの知らせを受け取る();
}

pub(super) fn ファイルのクリップの名前(
    スタック: &ライブラリのスタック
) -> Vec<String> {
    スタック
        .並び()
        .一覧()
        .iter()
        .map(|クリップ| クリップ.名前.文字列().to_string())
        .collect()
}
