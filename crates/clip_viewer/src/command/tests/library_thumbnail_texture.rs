//! 見えている行のテクスチャの試験。テクスチャは見えている行だけ作り、上限を超えたら見えなくなったものから捨てる。
#![allow(clippy::expect_used)]

use super::library_support::試験のライブラリ;
use super::library_thumbnail_list::一覧を読んだ状態;
use super::thumbnail_check::{
    見えている行で進める, 見せられるか, 見せられる数, 見せる順の識別子
};
use super::thumbnail_place::{動画のあるスタックを置く, 赤い画像};

#[test]
fn 見えなくなったテクスチャは上限を超えたら捨て_見えている行は残す() {
    let 試験 = 試験のライブラリ::作る("サムネイルのテクスチャの上限");
    let 赤い画像 = 赤い画像();
    for 番号 in 0..60 {
        動画のあるスタックを置く(&試験, &format!("stack-{番号}-0"), Some(&赤い画像));
    }
    let mut 状態 = 一覧を読んだ状態(&試験);
    見えている行で進める(&mut 状態, 0..=40);
    assert_eq!(見せられる数(&状態), 41);
    見えている行で進める(&mut 状態, 41..=59);
    assert_eq!(
        見せられる数(&状態),
        48,
        "上限の48枚まで、見えていないものを捨てる"
    );
    let 見せる順 = 見せる順の識別子(&状態);
    assert!(
        見せる順[41..=59]
            .iter()
            .all(|識別子| 見せられるか(&状態, 識別子)),
        "見えている行のテクスチャは捨てない"
    );
}
