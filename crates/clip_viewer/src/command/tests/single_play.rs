//! 「このクリップを再生」の試験のうち、動画が要らないもの。動画を開いて単独クリップ再生を始めて止めることは、
//! FFmpeg の結合試験(`state/with_ffmpeg_band_tests.rs`)で確かめる。

use clip_domain::トリガー;

use super::{クリップを並べた状態, クリップを作る, 識別子};
use crate::command::クリップの操作;

#[test]
fn 動画が無ければ再生せずに動画のロードを促す() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        1.0,
        3.0,
        トリガー::自動進行,
    )]);
    状態.クリップの操作を適用する(クリップの操作::単独再生を切り替える(
        識別子("甲"),
    ));
    assert!(!状態.再生.再生しているか());
    assert!(
        状態
            .通知
            .最新()
            .is_some_and(|(_, 文面)| 文面.contains("動画ファイルをロード"))
    );
}
