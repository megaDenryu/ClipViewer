//! クリップの区間の端の編集の試験。

use clip_domain::トリガー;

use super::{
    クリップを並べた状態, クリップを作る, 区間, 編集する, 識別子
};
use crate::command::{クリップの編集, 区間の端, 端のずらし方};

fn 甲の区間(状態: &crate::state::アプリの状態) -> clip_domain::動画上の区間 {
    状態
        .並び
        .識別子で探す(&識別子("甲"))
        .map(|クリップ| クリップ.区間)
        .unwrap_or(区間(0.0, 0.0))
}

fn 区間が近い(実際: clip_domain::動画上の区間, 開始: f64, 終了: f64) -> bool {
    (実際.開始().秒数() - 開始).abs() < 1e-9 && (実際.終了().秒数() - 終了).abs() < 1e-9
}

#[test]
fn 区間の端は開始と終了の間を0点05秒以上に保つ() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        1.0,
        3.0,
        トリガー::自動進行,
    )]);
    編集する(
        &mut 状態,
        クリップの編集::区間の端を決める(区間の端::開始, 3.5),
    );
    assert!(区間が近い(甲の区間(&状態), 2.95, 3.0));
    編集する(
        &mut 状態,
        クリップの編集::区間の端を決める(区間の端::終了, 0.0),
    );
    assert!(区間が近い(甲の区間(&状態), 2.95, 3.0));
    編集する(
        &mut 状態,
        クリップの編集::区間の端を決める(区間の端::開始, -4.0),
    );
    assert_eq!(甲の区間(&状態), 区間(0.0, 3.0));
}

#[test]
fn 動画が無ければ区間の終了を上限にし_半秒と一コマでずらせる() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        1.0,
        3.0,
        トリガー::自動進行,
    )]);
    編集する(
        &mut 状態,
        クリップの編集::区間の端をずらす(区間の端::終了, 端のずらし方::半秒進める),
    );
    assert_eq!(甲の区間(&状態), 区間(1.0, 3.0));
    編集する(
        &mut 状態,
        クリップの編集::区間の端をずらす(区間の端::開始, 端のずらし方::半秒戻す),
    );
    assert_eq!(甲の区間(&状態), 区間(0.5, 3.0));
    編集する(
        &mut 状態,
        クリップの編集::区間の端をずらす(区間の端::開始, 端のずらし方::一コマ進める),
    );
    let 開始 = 甲の区間(&状態).開始().秒数();
    assert!((開始 - (0.5 + 1.0 / 30.0)).abs() < 1e-9);
}

#[test]
fn 開始を後ろへ終了を前へずらして区間を縮め_縮めすぎても0点05秒を残す() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        1.0,
        3.0,
        トリガー::自動進行,
    )]);
    編集する(
        &mut 状態,
        クリップの編集::区間の端をずらす(区間の端::開始, 端のずらし方::半秒進める),
    );
    assert_eq!(甲の区間(&状態), 区間(1.5, 3.0));
    編集する(
        &mut 状態,
        クリップの編集::区間の端をずらす(区間の端::終了, 端のずらし方::半秒戻す),
    );
    assert_eq!(甲の区間(&状態), 区間(1.5, 2.5));
    編集する(
        &mut 状態,
        クリップの編集::区間の端をずらす(区間の端::終了, 端のずらし方::一コマ戻す),
    );
    assert!(区間が近い(甲の区間(&状態), 1.5, 2.5 - 1.0 / 30.0));
    for _ in 0..4 {
        編集する(
            &mut 状態,
            クリップの編集::区間の端をずらす(
                区間の端::開始,
                端のずらし方::半秒進める,
            ),
        );
    }
    assert!(区間が近い(
        甲の区間(&状態),
        2.45 - 1.0 / 30.0,
        2.5 - 1.0 / 30.0
    ));
}
