//! 区間の帯を掴んだときに、時計を止める前にクリップを選ぶ順序の試験。再生中のシーケンス再生で選ばれていないカードを
//! 掴んでも再生位置が動かないことと、単独クリップ再生で選ばれているカードを掴んでも経過が0へ戻らないことを確かめる。

use clip_domain::{トリガー, 再生モード, 再生位置, 時刻, 時間の長さ};

use super::band::区間の帯を操作する;
use super::{クリップを並べた状態, クリップを作る};
use crate::command::{出力の操作, 区間の帯の段階};
use crate::state::{アプリの状態, 区間の帯で掴んだもの};

const つまみ: 区間の帯で掴んだもの = 区間の帯で掴んだもの::開始のつまみ;

fn 甲と乙() -> アプリの状態 {
    クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
    ])
}

#[test]
fn 再生中のシーケンス再生で選ばれていないカードを掴んでも再生位置は動かない() {
    let mut 状態 = 甲と乙();
    let 位置 = 再生位置::シーケンス再生(時刻::作成する(0.3).expect("時刻"));
    状態.再生.位置を移す(位置);
    状態.再生.再生を始める();
    区間の帯を操作する(&mut 状態, "乙", 区間の帯の段階::掴み始めた, つまみ, 5.0);
    assert_eq!(
        状態.再生.位置(),
        位置,
        "再生中に選んだときは再生位置を動かさない規則を、時計を止める前に通す"
    );
    区間の帯を操作する(&mut 状態, "乙", 区間の帯の段階::放した, つまみ, 5.0);
    assert_eq!(状態.再生.位置(), 位置);
    assert!(状態.再生.再生しているか());
}

#[test]
fn 単独クリップ再生で選ばれているカードを掴んでも経過は0へ戻らない() {
    let mut 状態 = 甲と乙();
    状態.出力の操作を適用する(出力の操作::再生モードを選ぶ(
        再生モード::単独クリップ再生,
    ));
    let 位置 = 再生位置::単独クリップ再生(時間の長さ::作成する(0.7).expect("長さ"));
    状態.再生.位置を移す(位置);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::掴み始めた, つまみ, 0.0);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::放した, つまみ, 0.0);
    assert_eq!(状態.再生.位置(), 位置);
}
