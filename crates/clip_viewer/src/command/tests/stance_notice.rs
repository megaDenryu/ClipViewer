//! 構えを変えたときの知らせの試験。知らせの語は、画面の上の構えのボタンの名前(「編集」「シアター」「ライブラリ」)と同じである。

use super::クリップを並べた状態;
use crate::command::出力の操作;
use crate::state::画面の構え;

#[test]
fn 構えを変えるとヘッダーのボタンと同じ名前で知らせる() {
    let mut 状態 = クリップを並べた状態(Vec::new());
    for (構え, 知らせ) in [
        (画面の構え::シアター, "シアター"),
        (画面の構え::編集, "編集"),
        (画面の構え::ライブラリ, "ライブラリ"),
    ] {
        状態.出力の操作を適用する(出力の操作::構えを選ぶ(構え));
        assert_eq!(
            状態.通知.最新().map(|(_, 文面)| 文面.to_string()),
            Some(知らせ.to_string())
        );
    }
}
