//! 動画を開いて再生する操作の結合試験。全体ループを外して末尾にあるときに再生を押すと、モードの先頭から再生し直すことを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use clip_domain::{再生モード, 再生位置};

use super::with_ffmpeg_video::{名前を付けて試験動画を作る, 読み手のある試験};
use crate::command::{再生の操作, 出力の操作};
use crate::state::library::開いたときの添え書き;
use crate::state::アプリの状態;

/// 全体ループを外し、止めて、再生の位置を今のモードの末尾へ移す。
fn 末尾で止める(状態: &mut アプリの状態) {
    状態.再生の操作を適用する(再生の操作::全体ループを切り替える(false));
    状態.再生.止める();
    状態.再生の操作を適用する(再生の操作::位置を決めた(f64::MAX));
    assert!(状態.再生.位置().位置の秒数() > 1.9, "末尾へ移っている");
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 末尾にあるときに再生を押すとシーケンス再生と元動画再生の先頭から再生し直す() {
    let (mut 試験, mut 状態) = 読み手のある試験("末尾から再生");
    let 動画 = 名前を付けて試験動画を作る("末尾から再生", "練習動画.mp4");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &動画, 開いたときの添え書き::無し);
    末尾で止める(&mut 状態);
    状態.再生の操作を適用する(再生の操作::再生を切り替える);
    assert!(状態.再生.再生しているか());
    assert_eq!(
        状態.再生.位置(),
        再生位置::モードの先頭(再生モード::シーケンス再生)
    );

    状態.出力の操作を適用する(出力の操作::再生モードを選ぶ(
        再生モード::元動画再生,
    ));
    末尾で止める(&mut 状態);
    状態.再生の操作を適用する(再生の操作::再生を切り替える);
    assert!(状態.再生.再生しているか());
    assert_eq!(
        状態.再生.位置(),
        再生位置::モードの先頭(再生モード::元動画再生)
    );
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 末尾でないときに再生を押すと位置を変えない() {
    let (mut 試験, mut 状態) = 読み手のある試験("途中から再生");
    let 動画 = 名前を付けて試験動画を作る("途中から再生", "練習動画.mp4");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &動画, 開いたときの添え書き::無し);
    状態.再生.止める();
    状態.再生の操作を適用する(再生の操作::位置を決めた(1.0));
    状態.再生の操作を適用する(再生の操作::再生を切り替える);
    assert!(状態.再生.再生しているか());
    assert!((状態.再生.位置().位置の秒数() - 1.0).abs() < 1e-9);
}
