//! ライブラリへの登録から一覧で開くまでの結合試験。動画を開き、名前を付けて登録し、動画を解除してから一覧で開き直す。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use video_source::動画の読み手;

use super::library_check::{
    ファイルのクリップの名前, 終えるまで待って当てる
};
use super::library_support::試験のライブラリ;
use super::with_ffmpeg_video::試験動画を作る;
use crate::command::{ファイルの操作, ライブラリの操作, 応答};
use crate::state::library::{
    ライブラリのダイアログ, 開いたときの添え書き, 開いているスタック
};
use crate::state::{アプリの状態, 画面の構え};
use crate::video_feed::with_ffmpeg_support::実行ファイルを探す;

fn 当てる(
    試験: &mut 試験のライブラリ, 状態: &mut アプリの状態, 応答: 応答
) {
    試験.適用係.適用する(状態, 応答);
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 動画を開いて登録し_解除してから一覧で開き直すと同じ並びと動画に戻る() {
    let mut 試験 = 試験のライブラリ::作る("結合");
    試験
        .適用係
        .開き手
        .読み手を持たせる(動画の読み手::作成する(実行ファイルを探す()));
    let mut 状態 = 試験.接続した状態(Vec::new());
    試験.適用係.確かめてから動画を開く(
        &mut 状態,
        &試験動画を作る("結合"),
        開いたときの添え書き::無し,
    );
    assert!(状態.動画.is_some(), "動画を開ける");
    当てる(
        &mut 試験,
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::登録のダイアログを開く),
    );
    assert!(
        matches!(&状態.ライブラリ.ダイアログ, ライブラリのダイアログ::名前を付けて登録(入力, _) if 入力.文字列() == "練習動画")
    );
    当てる(
        &mut 試験,
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::登録する),
    );
    let 識別子 = 状態
        .ライブラリ
        .開いている
        .識別子()
        .cloned()
        .expect("登録済み");
    終えるまで待って当てる(&mut 状態);
    let ファイル = 試験
        .ファイルを読む(&識別子)
        .expect("登録したファイルがある");
    assert_eq!(ファイル.名前().文字列(), "練習動画");
    assert_eq!(ファイルのクリップの名前(&ファイル), ["Clip Mod 1"]);
    当てる(
        &mut 試験,
        &mut 状態,
        応答::ファイル(ファイルの操作::動画を解除する),
    );
    assert!(状態.動画.is_none() && 状態.並び.一覧().is_empty());
    状態.出力.構え = 画面の構え::ライブラリ;
    当てる(
        &mut 試験,
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::開く(識別子.clone())),
    );
    assert!(状態.動画.is_some(), "一覧から開くと動画を読み込む");
    assert_eq!(状態.並び.一覧(), ファイル.並び().一覧());
    assert_eq!(状態.出力.構え, 画面の構え::編集);
    assert!(
        matches!(&状態.ライブラリ.開いている, 開いているスタック::登録済み(登録済み) if 登録済み.識別子() == &識別子)
    );
}
