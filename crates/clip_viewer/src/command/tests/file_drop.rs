//! 窓へ落としたファイルの試験。拡張子が json なら設定ファイルとして扱い、編集の構えでは読み込んで並びを置き換え、
//! ライブラリの構えではライブラリへ取り込む。
#![allow(clippy::expect_used)]

use clip_domain::入力された動画パス;

use super::library_check::終えるまで待って当てる;
use super::library_support::試験のライブラリ;

use crate::command::{ファイルの操作, 応答, 落としたファイル};
use crate::state::library::{
    ライブラリの窓, 並びを捨てる理由, 最後に読んだ一覧, 開いたときの添え書き, 関係を終える操作,
};
use crate::state::画面の構え;

/// 2つのクリップを持つ第4版の設定ファイル。期待する動画のパスを持つので、ライブラリへ取り込める。
const 設定ファイルの本文: &str = r#"{"application":"ModifierVideoStack","version":"4.0",
"expectedVideoName":"sample.mp4","expectedVideoPath":"C:/videos/sample.mp4",
"modifiers":[{"id":"mod-1-1","name":"一つ目","active":true,"start":1.5,"end":3,"repeat":1,
"crop":{"x":0,"y":0,"w":100,"h":100},"triggerEvent":"none"},
{"id":"mod-1-2","name":"二つ目","active":true,"start":4,"end":5,"repeat":1,
"crop":{"x":0,"y":0,"w":100,"h":100},"triggerEvent":"none"}]}"#;

fn 設定ファイルを置く(
    試験: &試験のライブラリ,
    ファイル名: &str,
) -> 落としたファイル {
    let パス = 試験.一時フォルダ.join(ファイル名);
    std::fs::write(&パス, 設定ファイルの本文).expect("置ける");
    落としたファイル::作成する(パス)
}

#[test]
fn 編集の構えで落とした設定ファイルは読み込んで並びを置き換える() {
    let mut 試験 = 試験のライブラリ::作る("落とした設定ファイルを読む");
    let mut 状態 = 試験.接続した状態(Vec::new());
    let ファイル = 設定ファイルを置く(&試験, "練習.JSON");
    試験.適用係.適用する(
        &mut 状態,
        応答::ファイル(ファイルの操作::落としたファイルを開く(
            ファイル,
        )),
    );
    assert_eq!(状態.並び.一覧().len(), 2);
    assert_eq!(状態.出力.構え, 画面の構え::編集);
}

#[test]
fn ライブラリの構えで落とした設定ファイルはライブラリへ取り込む() {
    let mut 試験 = 試験のライブラリ::作る("落とした設定ファイルを取り込む");
    let mut 状態 = 試験.接続した状態(Vec::new());
    状態.出力.構え = 画面の構え::ライブラリ;
    let ファイル = 設定ファイルを置く(&試験, "取り込む.json");
    試験.適用係.適用する(
        &mut 状態,
        応答::ファイル(ファイルの操作::落としたファイルを開く(
            ファイル,
        )),
    );
    終えるまで待って当てる(&mut 状態);
    assert!(状態.並び.一覧().is_empty(), "編集中の並びは変えない");
    assert_eq!(状態.出力.構え, 画面の構え::ライブラリ);
    let 最後に読んだ一覧::読めた(一覧) = 状態.ライブラリ.一覧.一覧() else {
        panic!("一覧を読めた");
    };
    assert_eq!(一覧.項目.len(), 1, "取り込んだスタックが一覧に出る");
}

#[test]
fn 読み込んだ並びは変えていなくても名前の違う動画を開く前に確かめ_同じ名前なら確かめない() {
    let mut 試験 = 試験のライブラリ::作る("読み込んだ並びを名前の違う動画で捨てる");
    let mut 状態 = 試験.接続した状態(Vec::new());
    let ファイル = 設定ファイルを置く(&試験, "練習.json");
    試験.適用係.適用する(
        &mut 状態,
        応答::ファイル(ファイルの操作::落としたファイルを開く(
            ファイル,
        )),
    );
    let 同じ名前 = 入力された動画パス::作成する("D:/別/SAMPLE.mp4".into());
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &同じ名前, 開いたときの添え書き::無し);
    assert_eq!(状態.ライブラリ.窓, ライブラリの窓::無し);
    let 違う名前 = 入力された動画パス::作成する("C:/videos/other.mp4".into());
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &違う名前, 開いたときの添え書き::無し);
    assert_eq!(
        状態.ライブラリ.窓,
        ライブラリの窓::並びを捨てる確認(
            並びを捨てる理由::読み込んだ並びを名前の違う動画で捨てる,
            関係を終える操作::動画を開く(違う名前, 開いたときの添え書き::無し)
        )
    );
    assert_eq!(状態.並び.一覧().len(), 2, "確かめる間は並びを変えない");
}
