//! キーで発する再生の操作を状態へ当てる試験。速度を1段ずつ変えること、音を消して戻すこと、Ctrl+S の保存を確かめる。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{トリガー, 再生速度};

