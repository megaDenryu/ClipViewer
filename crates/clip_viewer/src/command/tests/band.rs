//! 区間の帯の操作の試験。つまみと区間の内側のドラッグの間は仮の区間だけが動いてプレビューがその位置を求め、
//! 放すと区間が決まって再生が戻ることを確かめる。

use clip_domain::トリガー;

use super::{クリップを並べた状態, クリップを作る, 区間, 識別子};
use crate::command::{
    クリップの区間の帯の操作, クリップの操作, 区間の帯の段階
};
use crate::state::{アプリの状態, 区間の帯で掴んだもの, 区間の帯の種類};

/// 甲のクリップの区間の帯を操作する。
pub(super) fn 区間の帯を操作する(
    状態: &mut アプリの状態,
    名前: &str,
    段階: 区間の帯の段階,
    掴んだもの: 区間の帯で掴んだもの,
    秒: f64,
) {
    let 操作 = クリップの区間の帯の操作 {
        帯: 区間の帯の種類::全体の帯,
        段階,
        掴んだもの,
        秒,
    };
    状態.クリップの操作を適用する(クリップの操作::区間の帯を操作する(
        識別子(名前),
        操作,
    ));
}

pub(super) fn 甲の区間(状態: &アプリの状態) -> Option<clip_domain::動画上の区間> {
    状態
        .並び
        .識別子で探す(&識別子("甲"))
        .map(|クリップ| クリップ.区間)
}

fn 求めの秒と区間(
    状態: &アプリの状態,
) -> Option<(f64, Option<clip_domain::動画上の区間>)> {
    状態
        .表示するコマの求め()
        .map(|求め| (求め.動画上の位置.秒数(), 求め.区間))
}

/// 甲[1,3) を並べ、再生している状態。動画が無いので区間の上限は3秒である。
pub(super) fn 再生している甲() -> アプリの状態 {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        1.0,
        3.0,
        トリガー::自動進行,
    )]);
    状態.再生.再生を始める();
    状態
}

#[test]
fn 開始のつまみを動かす間は仮の区間だけが動き_放すと区間が決まって再生が戻る() {
    let mut 状態 = 再生している甲();
    let つまみ = 区間の帯で掴んだもの::開始のつまみ;
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::掴み始めた, つまみ, 0.0);
    assert!(!状態.再生.再生しているか(), "掴んだら時計を止める");
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::動かしている, つまみ, 1.234);
    assert_eq!(
        甲の区間(&状態),
        Some(区間(1.0, 3.0)),
        "ドラッグの間はスタックを書き換えない"
    );
    let (秒, 求めの区間) = 求めの秒と区間(&状態).expect("求め");
    assert!(
        (秒 - 1.23).abs() < 1e-9,
        "0.01秒へ丸めた新しい開始のコマを求める"
    );
    assert!(求めの区間.is_some_and(|区間| (区間.終了().秒数() - 3.0).abs() < 1e-9));
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::放した, つまみ, 9.0);
    let 決めた = 甲の区間(&状態).expect("甲");
    assert!(
        (決めた.開始().秒数() - 1.23).abs() < 1e-9,
        "放した値でなく最後に動かした値で決める"
    );
    assert!(状態.区間の帯のドラッグ.is_none());
    assert!(状態.再生.再生しているか(), "掴む前に再生していたので戻す");
}

#[test]
fn 終了のつまみは終了の位置を区間付きで求め_区間の内側は長さを保って動き上限で止まる() {
    let mut 状態 = 再生している甲();
    let 終了 = 区間の帯で掴んだもの::終了のつまみ;
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::掴み始めた, 終了, 3.0);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::動かしている, 終了, 2.5);
    assert_eq!(求めの秒と区間(&状態), Some((2.5, Some(区間(1.0, 2.5)))));
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::放した, 終了, 2.5);
    let 内側 = 区間の帯で掴んだもの::区間の内側;
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::掴み始めた, 内側, 1.0);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::動かしている, 内側, 0.5);
    assert_eq!(求めの秒と区間(&状態), Some((0.5, Some(区間(0.5, 2.0)))));
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::動かしている, 内側, 2.9);
    assert_eq!(
        求めの秒と区間(&状態),
        Some((1.0, Some(区間(1.0, 2.5)))),
        "動画が無いと上限は区間の終了(2.5秒)なので、終了がそこに着く位置で止める"
    );
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::動かしている, 内側, 0.25);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::放した, 内側, 2.9);
    assert_eq!(
        甲の区間(&状態),
        Some(区間(0.25, 1.75)),
        "長さを保って動かした区間が決まる"
    );
}
