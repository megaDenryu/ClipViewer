//! 再生位置の帯のドラッグと構えの切り替えの試験。帯をドラッグしたまま構えを変える(シアターを Escape で抜ける等)と、
//! 帯は別の部品に描き直されて放したを受け取れないため、ドラッグの様子を終える(残ると音が黙ったままになる)。

use clip_domain::トリガー;

use super::{クリップを並べた状態, クリップを作る};
use crate::command::{再生の操作, 出力の操作};
use crate::state::{シークの様子, 画面の構え};

#[test]
fn 再生位置の帯をドラッグしたまま構えを変えるとドラッグの様子を終える() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    状態.出力の操作を適用する(出力の操作::構えを選ぶ(画面の構え::シアター));
    状態.再生の操作を適用する(再生の操作::位置を動かしている(0.5));
    assert_eq!(状態.再生.シーク, シークの様子::ドラッグしている);
    状態.出力の操作を適用する(出力の操作::全画面かシアターを抜ける);
    assert_eq!(状態.再生.シーク, シークの様子::していない);
}

#[test]
fn 動画を開いたときにライブラリの構えから編集へ移っても_ドラッグの様子を終える() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    状態.出力の操作を適用する(出力の操作::構えを選ぶ(画面の構え::ライブラリ));
    状態.再生.シーク = シークの様子::ドラッグしている;
    状態.ライブラリの構えなら編集へ移る();
    assert_eq!(状態.出力.構え, 画面の構え::編集);
    assert_eq!(状態.再生.シーク, シークの様子::していない);
}
