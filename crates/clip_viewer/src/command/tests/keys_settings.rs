//! キーの設定の試験。キーの一覧のダイアログで「変更」を押した後に押したキーが、ほかのキー操作を起こさずにその操作の新しいキーになり、
//! 新しいキーで操作が起き古いキーでは起きないこと(Escape の扱いは keys_settings_escape.rs)、ほかの操作のキーへは変えずに知らせること、
//! 既定に戻すこととすべて既定に戻すことを確かめる。
#![allow(clippy::expect_used)]

use eframe::egui;

use super::key_support::キーを押して集める;
use super::クリップを並べた状態;
use crate::command::{キーの設定の操作, 出力の操作, 応答};
use crate::state::{アプリの状態, キーの一覧のダイアログ};
use crate::viewer_settings::{キーで行う操作, キーの割り当て, 操作のキー};
use sengen_egui::{キー, キーの組};

const 無し: egui::Modifiers = egui::Modifiers::NONE;
const シアター: キーで行う操作 = キーで行う操作::シアターと編集を切り替える;

/// キーの一覧を開き、その操作の「変更」を押した状態。
pub(super) fn 待っている状態(操作: キーで行う操作) -> アプリの状態 {
    let mut 状態 = クリップを並べた状態(Vec::new());
    状態.出力の操作を適用する(出力の操作::キーの一覧を切り替える);
    状態.キーの設定の操作を適用する(キーの設定の操作::変更を待ち始める(操作));
    状態
}

/// キーを押して描き、発した応答を状態へ当てる。応答はキーの設定の操作だけであることを確かめる。
pub(super) fn 押して当てる(
    状態: &mut アプリの状態,
    キー: egui::Key,
    修飾キー: egui::Modifiers,
) {
    for 応答 in キーを押して集める(状態, キー, 修飾キー) {
        let 応答::キーの設定(操作) = 応答 else {
            panic!("キーの設定の操作でない応答: {応答:?}");
        };
        状態.キーの設定の操作を適用する(操作);
    }
}

#[test]
fn 待っている間に押したキーはほかの操作を起こさず_その操作の新しいキーになる() {
    let mut 状態 = 待っている状態(シアター);
    let シフト = egui::Modifiers::SHIFT;
    assert_eq!(
        キーを押して集める(&状態, egui::Key::F1, 無し),
        [応答::キーの設定(
            キーの設定の操作::押されたキーを受け取る(キーの組::単独(キー::F1))
        )],
        "待っている間は F1 もキーの一覧を閉じない"
    );
    押して当てる(&mut 状態, egui::Key::Y, シフト);
    assert_eq!(状態.キーの一覧, キーの一覧のダイアログ::開いている);
    assert_eq!(
        状態.キーの割り当て.操作のキー(シアター),
        操作のキー::一つ(キーの組::生成する(シフト, キー::Y))
    );
    状態.出力の操作を適用する(出力の操作::キーの一覧を閉じる);
    let 切り替える = 応答::出力(出力の操作::シアターと編集を切り替える);
    assert_eq!(
        キーを押して集める(&状態, egui::Key::Y, シフト),
        std::slice::from_ref(&切り替える)
    );
    assert!(!キーを押して集める(&状態, egui::Key::T, 無し).contains(&切り替える));
}

#[test]
fn ほかの操作のキーを押すと変えずに知らせ_待ちをやめる() {
    let mut 状態 = 待っている状態(シアター);
    押して当てる(&mut 状態, egui::Key::M, 無し);
    assert_eq!(状態.キーの割り当て, キーの割り当て::既定());
    assert_eq!(状態.キーの一覧, キーの一覧のダイアログ::開いている);
    let 最新 = 状態.通知.最新().map(|(_, 文)| 文.to_string());
    assert_eq!(
        最新.as_deref(),
        Some(
            "M は「音を消す・戻す」のキーなので、「編集ならシアターへ、シアターなら編集へ切り替える」のキーを変えなかった"
        )
    );
}

#[test]
fn 既定に戻すとその操作だけが戻り_すべて既定に戻すと全部が戻る() {
    let mut 状態 = 待っている状態(シアター);
    押して当てる(&mut 状態, egui::Key::Y, 無し);
    状態.キーの設定の操作を適用する(キーの設定の操作::変更を待ち始める(
        キーで行う操作::消音を切り替える,
    ));
    押して当てる(&mut 状態, egui::Key::U, 無し);
    状態.キーの設定の操作を適用する(キーの設定の操作::既定に戻す(シアター));
    assert_eq!(
        状態.キーの割り当て.操作のキー(シアター),
        シアター.既定のキー()
    );
    assert_ne!(状態.キーの割り当て, キーの割り当て::既定());
    状態.キーの設定の操作を適用する(キーの設定の操作::すべて既定に戻す);
    assert_eq!(状態.キーの割り当て, キーの割り当て::既定());
}

#[test]
fn 待っている間にダイアログを閉じると待ちも終わる() {
    let mut 状態 = 待っている状態(シアター);
    状態.出力の操作を適用する(出力の操作::キーの一覧を閉じる);
    assert_eq!(状態.キーの一覧, キーの一覧のダイアログ::閉じている);
    状態.キーの設定の操作を適用する(キーの設定の操作::押されたキーを受け取る(
        キーの組::単独(キー::Y),
    ));
    assert_eq!(状態.キーの割り当て, キーの割り当て::既定());
}
