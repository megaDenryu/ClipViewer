//! アプリを閉じる要求の試験。保存できないまま閉じようとすると確かめるダイアログを出して閉じるのをやめ、変更を捨てると確かめずに閉じる。
//! 保存できていれば確かめずに閉じてよい。
#![allow(clippy::expect_used)]

use clip_domain::トリガー;

use super::library_support::試験のライブラリ;
use super::クリップを作る;
use crate::state::閉じる要求への答え;

#[test]
fn 保存できていれば閉じてよい() {
    let 試験 = 試験のライブラリ::作る("保存できていれば閉じる");
    let mut 状態 = 試験.接続した状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    assert_eq!(状態.閉じる要求を確かめる(), 閉じる要求への答え::閉じてよい);
}

#[cfg(windows)]
#[test]
fn 保存できないままアプリを閉じようとすると確かめ_変更を捨てると確かめずに閉じる() {
    use super::library_failure::保存に失敗した状態;
    use crate::command::{ライブラリの操作, 応答};
    use crate::state::library::{ライブラリのダイアログ, 関係を終える操作};

    let mut 試験 = 試験のライブラリ::作る("閉じる前に確かめる");
    let (mut 状態, _, _排他, _) = 保存に失敗した状態(&試験);
    assert_eq!(
        状態.閉じる要求を確かめる(),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(matches!(
        &状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::保存できずに続ける確認(
            _,
            関係を終える操作::アプリを閉じる
        )
    ));
    assert!(!状態.閉じると決めたか());
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    assert!(状態.閉じると決めたか());
    assert_eq!(状態.閉じる要求を確かめる(), 閉じる要求への答え::閉じてよい);
}
