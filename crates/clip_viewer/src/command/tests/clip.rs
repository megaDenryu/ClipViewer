//! クリップの操作と、区間以外の編集の試験。

use clip_domain::{トリガー, リピート回数, リピート設定};

use super::{
    クリップを並べた状態, クリップを作る, 編集する, 識別子, 選択中の名前
};
use crate::command::{クリップの操作, クリップの編集};

#[test]
fn 無限ループの回数を増やすと1回から数え直した2回になる() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    編集する(&mut 状態, クリップの編集::無限ループを切り替える(true));
    編集する(&mut 状態, クリップの編集::リピートを増やす);
    let リピート = 状態
        .並び
        .識別子で探す(&識別子("甲"))
        .map(|クリップ| クリップ.リピート);
    let 二回 = リピート回数::作成する(2).ok().map(リピート設定::回数指定);
    assert_eq!(リピート, 二回);
}

#[test]
fn 最後の1つは削除できずに知らせ_開始へ移るとそのクリップの先頭へ移る() {
    let mut 状態 = クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
    ]);
    状態.クリップの操作を適用する(クリップの操作::開始へ移る(識別子("乙")));
    assert_eq!(選択中の名前(&状態), "乙");
    assert!((状態.再生.位置().位置の秒数() - 1.0).abs() < 1e-9);
    状態.クリップの操作を適用する(クリップの操作::削除する(識別子("甲")));
    状態.クリップの操作を適用する(クリップの操作::削除する(識別子("乙")));
    assert_eq!(状態.並び.一覧().len(), 1);
    assert_eq!(
        状態.通知.最新().map(|(_, 文面)| 文面.to_string()),
        Some("最後の1つのクリップは削除できない".into())
    );
}

#[test]
fn シーケンス再生で止めている間に選ぶとそのクリップの開始へ移り_再生中は動かさない() {
    let mut 状態 = クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
    ]);
    状態.クリップの操作を適用する(クリップの操作::選ぶ(識別子("乙")));
    assert!((状態.再生.位置().位置の秒数() - 1.0).abs() < 1e-9);
    状態.再生.再生を始める();
    状態.クリップの操作を適用する(クリップの操作::選ぶ(識別子("甲")));
    assert_eq!(選択中の名前(&状態), "甲");
    assert!((状態.再生.位置().位置の秒数() - 1.0).abs() < 1e-9);
}
