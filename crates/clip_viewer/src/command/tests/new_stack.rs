//! 今の動画で新しいスタックを始める操作の試験のうち、動画を開かずに確かめられるもの。動画が無いときは、確かめるダイアログを出さずに知らせ、
//! 並びをそのまま残す。動画を開いて始める試験は `with_ffmpeg_new_stack.rs` にある。

use clip_domain::トリガー;

use super::library_support::試験のライブラリ;
use super::{
    クリップを並べた状態, クリップを作る, 今の動画で新しいスタックを始める応答, 編集する
};
use crate::command::クリップの編集;
use crate::state::library::ライブラリのダイアログ;

#[test]
fn 動画が無いときは確かめずに知らせ_並びを残す() {
    let mut 試験 = 試験のライブラリ::作る("動画が無いときに新しいスタックを始める");
    let 甲 = クリップを作る("甲", 0.0, 1.0, トリガー::自動進行);
    let mut 状態 = クリップを並べた状態(vec![甲]);
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    let 前の並び = 状態.並び.clone();
    試験
        .適用係
        .適用する(&mut 状態, 今の動画で新しいスタックを始める応答);
    assert_eq!(状態.ライブラリ.ダイアログ, ライブラリのダイアログ::無し);
    assert_eq!(状態.並び, 前の並び, "並びを捨てない");
    assert_eq!(
        状態.通知.最新().map(|(_, 文)| 文.to_string()),
        Some("先に動画ファイルをロードしてください".to_string())
    );
}
