//! 登録済みのスタックの動画を開き直したときの試験。関係を保つのは動画のパス全体が同じときだけであり、ファイル名が同じでもフォルダが違えば、
//! 関係を終える前に保存を確かめ、並びは残して関係を終える(古いパスのスタックへ、別の動画に合わせた区間を上書きしないため)。
#![allow(clippy::expect_used)]

use clip_domain::{トリガー, 入力された動画パス};

use super::library_check::ファイルのクリップの名前;
use super::library_support::試験のライブラリ;
use super::{クリップを作る, 編集する};
use crate::command::クリップの編集;
use crate::state::library::{
    開いたときの添え書き, 開いているスタック, 関係を終える操作
};
use crate::state::{確かめた結果, 閉じる要求への答え};

fn 動画を開く操作(文字列: &str) -> 関係を終える操作 {
    関係を終える操作::動画を開く(
        入力された動画パス::作成する(文字列.to_string()),
        開いたときの添え書き::無し,
    )
}

fn パス(文字列: &str) -> clip_domain::正規化した動画パス {
    入力された動画パス::作成する(文字列.to_string()).正規化する()
}

#[test]
fn 登録済みのスタックとの関係は動画のパス全体が同じときだけ保ち_フォルダが違えば保存を確かめて関係を終える()
 {
    let 試験 = 試験のライブラリ::作る("動画のパス全体で関係を保つ");
    let mut 状態 = 試験.接続した状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    let 識別子 = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    let 同じパス = 試験.一時フォルダ.join("無い動画.mp4").display().to_string();
    assert_eq!(
        状態.関係を終える前に確かめる(動画を開く操作(&同じパス)),
        確かめた結果::続けてよい
    );
    状態.並びを残して動画を開き直す(&パス(&同じパス));
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::登録済み(_)
    ));

    編集する(
        &mut 状態,
        クリップの編集::名前を変える("別の動画に合わせた".into()),
    );
    let 別のフォルダ = 試験
        .一時フォルダ
        .join("別")
        .join("無い動画.mp4")
        .display()
        .to_string();
    assert_eq!(
        状態.関係を終える前に確かめる(動画を開く操作(&別のフォルダ)),
        確かめた結果::続けてよい
    );
    let ファイル = 試験.ファイルを読む(&識別子).expect("ファイルがある");
    assert_eq!(
        ファイルのクリップの名前(&ファイル),
        ["別の動画に合わせた"],
        "関係を終える前に保存を確かめた"
    );
    状態.並びを残して動画を開き直す(&パス(&別のフォルダ));
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    assert_eq!(状態.並び.一覧().len(), 1, "並びは残す");
    assert_eq!(
        状態.閉じる要求を確かめる(),
        閉じる要求への答え::閉じてよい,
        "書けた並びなので確かめない"
    );
}
