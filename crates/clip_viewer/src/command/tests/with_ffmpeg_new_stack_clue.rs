//! 今の動画で新しいスタックを始めたときの動画の手がかりの結合試験。別の動画を期待する JSON を読み込んだ後に始めても、
//! 期待する動画と「PC内絶対パス:」のメモを今の動画にし、今の動画を開き直すと並びを残すことを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use clip_domain::{スタック設定, 入力された動画パス};

use super::with_ffmpeg_new_stack::始める;
use super::with_ffmpeg_video::{試験動画を作る, 読み手のある試験};
use crate::state::library::{ライブラリのダイアログ, 開いたときの添え書き};

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 別の動画を期待する設定ファイルを読んだ後に始めても手がかりを今の動画にする() {
    let (mut 試験, mut 状態) = 読み手のある試験("新しいスタックの手がかり");
    let 今の動画 = 試験動画を作る("新しいスタックの手がかり");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &今の動画, 開いたときの添え書き::無し);
    let 別の動画 =
        入力された動画パス::作成する("C:/別のフォルダ/別の動画.mp4".to_string()).正規化する();
    状態.設定を当てる(スタック設定 {
        スタック: 状態.並び.clone(),
        期待する動画: 別の動画.ファイル名(),
        期待する動画のパス: Some(別の動画),
    });
    試験.適用係.適用する(&mut 状態, 始める);
    assert_eq!(状態.ライブラリ.ダイアログ, ライブラリのダイアログ::無し);
    let 今の動画のパス = 今の動画.正規化する();
    assert_eq!(
        状態
            .手がかり
            .期待する動画()
            .map(|名前| 名前.文字列().to_string()),
        今の動画のパス
            .ファイル名()
            .map(|名前| 名前.文字列().to_string()),
        "期待する動画を今の動画にする"
    );
    assert_eq!(
        状態.手がかり.パスのメモ().文字列(),
        今の動画のパス.文字列(),
        "パスの欄を今の動画にする"
    );
    assert!(
        状態.並びを残して動画を開けるか(&今の動画のパス),
        "今の動画を開き直すと並びを残す"
    );
}
