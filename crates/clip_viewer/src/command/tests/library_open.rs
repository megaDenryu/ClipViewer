//! 一覧から開く操作の試験。動画を開くところは FFmpeg が要るため、
//! ここでは読み手の無い(FFmpeg が見つからない)適用係で、開く前の確かめと保存と、開けないときに画面を変えないことを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::トリガー;

use super::library_check::{
    ファイルのクリップの名前, 終えるまで待って当てる
};
use super::library_support::試験のライブラリ;
use super::{クリップを作る, 編集する};
use crate::command::{クリップの編集, ライブラリの操作, 応答};
use crate::state::library::{
    ライブラリの窓, 並びを捨てる理由, 開いているスタック, 関係を終える操作,
};
use crate::state::アプリの状態;

fn 甲だけの状態(試験: &試験のライブラリ) -> アプリの状態 {
    試験.接続した状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )])
}

fn ライブラリの操作(
    試験: &mut 試験のライブラリ,
    状態: &mut アプリの状態,
    操作: ライブラリの操作,
) {
    試験.適用係.適用する(状態, 応答::ライブラリ(操作));
}

#[test]
fn 登録していない変更があれば開く前に確かめ_変更を捨てて続けても動画を開けなければ並びを変えない() {
    let mut 試験 = 試験のライブラリ::作る("確かめる");
    let mut 状態 = 甲だけの状態(&試験);
    let 識別子 = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    状態.ライブラリ.開いている = 開いているスタック::未登録;
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    ライブラリの操作(&mut 試験, &mut 状態, ライブラリの操作::開く(識別子.clone()));
    assert_eq!(
        状態.ライブラリ.窓,
        ライブラリの窓::並びを捨てる確認(
            並びを捨てる理由::登録していない変更がある,
            関係を終える操作::一覧から開く(識別子)
        )
    );
    ライブラリの操作(&mut 試験, &mut 状態, ライブラリの操作::変更を捨てて続ける);
    assert_eq!(状態.ライブラリ.窓, ライブラリの窓::無し);
    assert!(状態.動画.is_none());
    assert_eq!(状態.並び.一覧().len(), 1);
    let 通知 = 状態
        .通知
        .最新()
        .map(|(_, 文面)| 文面.to_string())
        .unwrap_or_default();
    assert!(通知.contains("動画を開けない"), "{通知}");
}

#[test]
fn 登録していなくても並びを置き換えてから変えていなければ確かめずに開こうとする() {
    let mut 試験 = 試験のライブラリ::作る("一覧から開く前に変えていなければ確かめない");
    let mut 状態 = 甲だけの状態(&試験);
    let 識別子 = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    状態.ライブラリ.開いている = 開いているスタック::未登録;
    ライブラリの操作(&mut 試験, &mut 状態, ライブラリの操作::開く(識別子));
    assert_eq!(状態.ライブラリ.窓, ライブラリの窓::無し);
    let 通知 = 状態
        .通知
        .最新()
        .map(|(_, 文面)| 文面.to_string())
        .unwrap_or_default();
    assert!(通知.contains("動画を開けない"), "{通知}");
}

#[test]
fn 登録済みのスタックから開くときは落ち着く前の変更を先に保存する() {
    let mut 試験 = 試験のライブラリ::作る("先に保存");
    let mut 状態 = 甲だけの状態(&試験);
    let 識別子 = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    ライブラリの操作(&mut 試験, &mut 状態, ライブラリの操作::開く(識別子.clone()));
    assert_eq!(
        状態.ライブラリ.窓,
        ライブラリの窓::無し,
        "登録済みなら確かめずに開く"
    );
    終えるまで待って当てる(&mut 状態);
    let ファイル = 試験.ファイルを読む(&識別子).expect("ファイルがある");
    assert_eq!(ファイルのクリップの名前(&ファイル), ["変えた"]);
}
