//! 一覧のサムネイルの試験。キャッシュにあるものは見えている行だけテクスチャにし、壊れたキャッシュは消して撮りに行き、
//! 読み取り専用のアプリもキャッシュを見せる。FFmpeg の無い状態で流し、撮りに行く判定は「撮らない(FFmpeg が無い)」で観察する。
#![allow(clippy::expect_used)]

use clip_domain::スタックの識別子;
use thumbnail_cache::撮り方の要約値;

use super::library_check::終えるまで待って当てる;
use super::library_support::試験のライブラリ;
use super::thumbnail_check::{
    見えている行で進める, 見せられるか, 見せる順の識別子, 見せ方
};
use super::thumbnail_place::{動画のあるスタックを置く, 赤い画像};
use crate::state::アプリの状態;
use crate::thumbnail_feed::{
    サムネイルの見せ方, サムネイルを撮らない理由, 一覧のサムネイルの大きさ, 途中の段階,
};

pub(super) fn 一覧を読んだ状態(試験: &試験のライブラリ) -> アプリの状態 {
    let mut 状態 = 試験.接続した状態(Vec::new());
    状態.一覧を読み直す();
    終えるまで待って当てる(&mut 状態);
    状態
}

fn 撮りに行ったか(
    状態: &アプリの状態, 識別子: &スタックの識別子
) -> bool {
    matches!(
        見せ方(状態, 識別子),
        Some(サムネイルの見せ方::撮らない(
            サムネイルを撮らない理由::FFmpegが無い
        ))
    )
}

#[test]
fn キャッシュにあるものは見えている行だけ見せ_無いものは撮りに行く() {
    let 試験 = 試験のライブラリ::作る("サムネイルの見えている行");
    let 赤い画像 = 赤い画像();
    let ある = ["stack-1-1", "stack-2-2"]
        .map(|識別子| 動画のあるスタックを置く(&試験, 識別子, Some(&赤い画像)));
    let 無い = 動画のあるスタックを置く(&試験, "stack-3-3", None);
    let mut 状態 = 一覧を読んだ状態(&試験);
    let 見せる順 = 見せる順の識別子(&状態);
    let 最初の行 = 見せる順
        .iter()
        .position(|識別子| 識別子 == &ある[0])
        .expect("行がある");
    見えている行で進める(&mut 状態, 最初の行..=最初の行);
    assert!(
        見せられるか(&状態, &ある[0]),
        "見えている行はテクスチャにする"
    );
    assert!(
        matches!(
            見せ方(&状態, &ある[1]),
            Some(サムネイルの見せ方::途中(途中の段階::読んでいる))
        ),
        "見えていない行は JPEG を持つだけでテクスチャにしない"
    );
    assert!(撮りに行ったか(&状態, &無い));
}

#[test]
fn 壊れたキャッシュは消して撮りに行く() {
    let 試験 = 試験のライブラリ::作る("サムネイルの壊れたキャッシュ");
    let 壊れた = 動画のあるスタックを置く(&試験, "stack-1-1", Some(b"not a jpeg"));
    let mut 状態 = 一覧を読んだ状態(&試験);
    見えている行で進める(&mut 状態, 0..=0);
    assert!(撮りに行ったか(&状態, &壊れた), "壊れたキャッシュは撮り直す");
    let 撮り方 = 試験
        .ファイルを読む(&壊れた)
        .and_then(|スタック| スタック.サムネイルの撮り方(一覧のサムネイルの大きさ))
        .expect("撮り方");
    let キャッシュのファイル = 試験
        .キャッシュのフォルダ()
        .画像のパス(撮り方の要約値::求める(&撮り方));
    assert!(
        !キャッシュのファイル.exists(),
        "壊れたキャッシュのファイルは消す"
    );
}

#[test]
fn 読み取り専用のアプリもキャッシュのサムネイルを見せる() {
    let 試験 = 試験のライブラリ::作る("サムネイルと読み取り専用");
    let 識別子 = 動画のあるスタックを置く(&試験, "stack-1-1", Some(&赤い画像()));
    let _書ける方 = 試験.接続した状態(Vec::new());
    let mut 読むだけ = 一覧を読んだ状態(&試験);
    assert!(!読むだけ.ライブラリ.接続.書けるか());
    見えている行で進める(&mut 読むだけ, 0..=0);
    assert!(見せられるか(&読むだけ, &識別子));
}
