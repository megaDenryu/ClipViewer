//! 同じ動画を開き直したときの試験。並びを残すときは、編集の履歴と起点を引き継ぐため、
//! その後で並びを捨てる操作をすると確かめるダイアログが出る。動画の名前を持たない設定ファイルを読んだ後も同じである。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{トリガー, 入力された動画パス, 正規化した動画パス};

use super::{クリップを並べた状態, クリップを作る, 編集する};
use crate::command::クリップの編集;
use crate::library_common::確かめた結果;
use crate::state::library::{
    ライブラリのダイアログ, 並びを捨てる理由, 開いたときの添え書き, 関係を終える操作,
};
use crate::state::{アプリの状態, 閉じる要求への答え};

fn パス(文字列: &str) -> 正規化した動画パス {
    入力された動画パス::作成する(文字列.to_string()).正規化する()
}

fn 動画を開く操作(文字列: &str) -> 関係を終える操作 {
    関係を終える操作::動画を開く(
        入力された動画パス::作成する(文字列.to_string()),
        開いたときの添え書き::無し,
    )
}

fn 変えた甲だけ() -> アプリの状態 {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    状態.フレームを進める(Instant::now());
    状態
}

#[test]
fn 同じ動画を開き直して並びを残しても_閉じる前に確かめ_取り消しも残る() {
    let mut 状態 = 変えた甲だけ();
    状態.手がかり.開いた動画に合わせる(&パス("C:/動画/a.mp4"));
    let 開き直す = 動画を開く操作("D:/別/A.MP4");
    assert_eq!(
        状態.関係を終える前に確かめる(開き直す),
        確かめた結果::続けてよい
    );
    状態.並びを残して動画を開き直す(&パス("D:/別/A.MP4"));
    assert!(状態.取り消せるか(), "編集の履歴を引き継ぐ");
    assert_eq!(
        状態.閉じる要求を確かめる(),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(matches!(
        状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(
            並びを捨てる理由::登録していない変更がある,
            _
        )
    ));
}

#[test]
fn 動画の名前が分からない並びで動画を開いても_閉じる前に確かめる() {
    let mut 状態 = 変えた甲だけ();
    assert_eq!(
        状態.関係を終える前に確かめる(動画を開く操作("C:/動画/b.mp4")),
        確かめた結果::続けてよい
    );
    状態.並びを残して動画を開き直す(&パス("C:/動画/b.mp4"));
    assert_eq!(
        状態.閉じる要求を確かめる(),
        閉じる要求への答え::閉じるのをやめる
    );
}
