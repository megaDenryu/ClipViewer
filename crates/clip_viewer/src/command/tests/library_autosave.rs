//! 自動保存の試験。登録済みのスタックは並びが変わって落ち着いてから保存し、未登録の並びは保存しない。
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use clip_domain::トリガー;

use super::library_check::{
    ファイルのクリップの名前, 終えるまで待って当てる
};
use super::library_support::試験のライブラリ;
use super::{クリップを作る, 編集する};
use crate::command::{クリップの編集, ファイルの操作, 応答};
use crate::state::library::{保存の段階, 開いているスタック};

fn 甲だけの状態(試験: &試験のライブラリ) -> crate::state::アプリの状態 {
    試験.接続した状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )])
}

fn 段階(状態: &crate::state::アプリの状態) -> Option<保存の段階<'_>> {
    状態.開いているスタックの保存の段階()
}

#[test]
fn 登録済みのスタックは変えてから落ち着くまで保存せず_落ち着いたら保存する() {
    let 試験 = 試験のライブラリ::作る("自動保存");
    let mut 状態 = 甲だけの状態(&試験);
    let 識別子 = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    let 始め = Instant::now();
    状態.ライブラリの書き込みを進める(始め);
    状態.ライブラリの書き込みを進める(始め + Duration::from_millis(200));
    終えるまで待って当てる(&mut 状態);
    let ファイル = 試験.ファイルを読む(&識別子).expect("ファイルがある");
    assert_eq!(
        ファイルのクリップの名前(&ファイル),
        ["甲"],
        "落ち着く前は保存しない"
    );
    assert!(matches!(段階(&状態), Some(保存の段階::変更を保存待ち)));
    状態.ライブラリの書き込みを進める(始め + Duration::from_millis(900));
    assert!(matches!(段階(&状態), Some(保存の段階::保存中)));
    終えるまで待って当てる(&mut 状態);
    let ファイル = 試験.ファイルを読む(&識別子).expect("ファイルがある");
    assert_eq!(ファイルのクリップの名前(&ファイル), ["変えた"]);
    assert_eq!(ファイル.名前().文字列(), "練習");
    assert!(matches!(段階(&状態), Some(保存の段階::保存済み)));
}

#[test]
fn 未登録の並びは変えても保存しない() {
    let 試験 = 試験のライブラリ::作る("未登録");
    let mut 状態 = 甲だけの状態(&試験);
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    let 始め = Instant::now();
    状態.ライブラリの書き込みを進める(始め);
    状態.ライブラリの書き込みを進める(始め + Duration::from_secs(2));
    終えるまで待って当てる(&mut 状態);
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    assert!(!状態.ライブラリ.保存されていないか(状態.並び.一覧()));
}

#[test]
fn 動画を解除すると落ち着く前の変更を保存してから未登録へ戻る() {
    let mut 試験 = 試験のライブラリ::作る("解除");
    let mut 状態 = 甲だけの状態(&試験);
    let 識別子 = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    試験
        .適用係
        .適用する(&mut 状態, 応答::ファイル(ファイルの操作::動画を解除する));
    終えるまで待って当てる(&mut 状態);
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    let ファイル = 試験.ファイルを読む(&識別子).expect("ファイルがある");
    assert_eq!(ファイルのクリップの名前(&ファイル), ["変えた"]);
}
