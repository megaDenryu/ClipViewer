//! 動画を開く経路と登録していない変更の結合試験。一覧の構えへ落とした動画と、登録していない変更を登録してから元の操作を続けることを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::path::PathBuf;

use super::library_check::{
    ファイルのクリップの名前, 終えるまで待って当てる
};
use super::with_ffmpeg_video::{名前を付けて試験動画を作る, 読み手のある試験};
use crate::command::{
    クリップの操作, クリップの編集, ファイルの操作, ライブラリの操作, 応答, 落としたファイル,
};
use crate::state::library::{
    ライブラリの窓, 最後に読んだ一覧, 開いたときの添え書き, 開いているスタック,
};
use crate::state::画面の構え;

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 一覧の構えへ動画を落とすと編集の構えへ移って開く() {
    let (mut 試験, mut 状態) = 読み手のある試験("一覧へ落とす");
    状態.出力.構え = 画面の構え::ライブラリ;
    let 動画 = 名前を付けて試験動画を作る("一覧へ落とす", "練習動画.mp4");
    let ファイル = 落としたファイル::作成する(PathBuf::from(動画.文字列()));
    試験.適用係.適用する(
        &mut 状態,
        応答::ファイル(ファイルの操作::落としたファイルを開く(
            ファイル,
        )),
    );
    assert!(状態.動画.is_some());
    assert_eq!(状態.出力.構え, 画面の構え::編集);
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 登録していない変更をライブラリに保存すると登録してから元の操作を続ける() {
    let (mut 試験, mut 状態) = 読み手のある試験("登録してから続ける");
    let 動画 = 名前を付けて試験動画を作る("登録してから続ける", "練習動画.mp4");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &動画, 開いたときの添え書き::無し);
    let 識別子 = 状態.並び.一覧()[0].識別子().clone();
    試験.適用係.適用する(
        &mut 状態,
        応答::クリップ(クリップの操作::編集する(
            識別子,
            クリップの編集::名前を変える("変えた".into()),
        )),
    );
    試験
        .適用係
        .適用する(&mut 状態, 応答::ファイル(ファイルの操作::動画を解除する));
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::登録してから続ける),
    );
    assert!(matches!(
        &状態.ライブラリ.窓,
        ライブラリの窓::名前を付けて登録(..)
    ));
    試験
        .適用係
        .適用する(&mut 状態, 応答::ライブラリ(ライブラリの操作::登録する));
    assert!(
        状態.動画.is_none() && 状態.並び.一覧().is_empty(),
        "登録してから解除する"
    );
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    終えるまで待って当てる(&mut 状態);
    let 最後に読んだ一覧 = 状態.ライブラリ.一覧.一覧().clone();
    let 最後に読んだ一覧::読めた(一覧) = 最後に読んだ一覧 else {
        panic!("一覧を読めた");
    };
    let clip_library::一覧の項目::読めた(読めた) = &一覧.項目[0] else {
        panic!("読めた項目");
    };
    let ファイル = 試験
        .ファイルを読む(読めた.スタック.識別子())
        .expect("登録したファイルがある");
    assert_eq!(ファイルのクリップの名前(&ファイル), ["変えた"]);
}
