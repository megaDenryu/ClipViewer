//! 登録していない変更の確かめの試験。未登録の並びを置き換えたときから変えていれば、並びを捨てる操作(動画の解除・アプリを閉じる等)の前に
//! 確かめるダイアログを出し、「変更を捨てて続ける」で続け、「やめる」で何もしない。変えていなければ確かめない。
#![allow(clippy::expect_used)]

use clip_domain::{トリガー, 入力された動画パス, 正規化した動画パス};

use super::library_support::試験のライブラリ;
use super::{クリップを並べた状態, クリップを作る, 編集する};
use crate::command::{
    クリップの編集, ファイルの操作, ライブラリの操作, 応答
};
use crate::state::library::{
    ライブラリのダイアログ, 並びを捨てる理由, 関係を終える操作
};
use crate::state::{アプリの状態, 閉じる要求への答え};

fn 甲だけ() -> アプリの状態 {
    let 甲 = クリップを作る("甲", 0.0, 1.0, トリガー::自動進行);
    クリップを並べた状態(vec![甲])
}

fn 変えた甲だけ() -> アプリの状態 {
    let mut 状態 = 甲だけ();
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    状態
}

#[test]
fn 変えていれば動画を解除する前に確かめ_やめると何もせず_変更を捨てて続けると解除する() {
    let mut 試験 = 試験のライブラリ::作る("登録していない変更を解除する前に確かめる");
    let mut 状態 = 変えた甲だけ();
    試験
        .適用係
        .適用する(&mut 状態, 応答::ファイル(ファイルの操作::動画を解除する));
    assert_eq!(
        状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(
            並びを捨てる理由::登録していない変更がある,
            関係を終える操作::動画を解除する
        )
    );
    assert_eq!(状態.並び.一覧().len(), 1, "確かめる間は解除しない");
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::ダイアログを閉じる),
    );
    assert_eq!(状態.ライブラリ.ダイアログ, ライブラリのダイアログ::無し);
    assert_eq!(状態.並び.一覧().len(), 1);
    試験
        .適用係
        .適用する(&mut 状態, 応答::ファイル(ファイルの操作::動画を解除する));
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    assert_eq!(状態.ライブラリ.ダイアログ, ライブラリのダイアログ::無し);
    assert!(状態.並び.一覧().is_empty());
}

#[test]
fn 変えていなければ確かめずに解除する() {
    let mut 試験 = 試験のライブラリ::作る("変えていなければ確かめない");
    let mut 状態 = 甲だけ();
    試験
        .適用係
        .適用する(&mut 状態, 応答::ファイル(ファイルの操作::動画を解除する));
    assert_eq!(状態.ライブラリ.ダイアログ, ライブラリのダイアログ::無し);
    assert!(状態.並び.一覧().is_empty());
}

#[test]
fn 変えていればアプリを閉じる前に確かめ_変更を捨てると閉じる() {
    let mut 試験 = 試験のライブラリ::作る("登録していない変更を閉じる前に確かめる");
    let mut 状態 = 変えた甲だけ();
    assert_eq!(
        状態.閉じる要求を確かめる(),
        閉じる要求への答え::閉じるのをやめる
    );
    assert_eq!(
        状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(
            並びを捨てる理由::登録していない変更がある,
            関係を終える操作::アプリを閉じる
        )
    );
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    assert!(状態.閉じると決めたか());
}

#[test]
fn 並びを作った動画と同じ名前の動画なら並びを残して開ける() {
    let mut 状態 = 甲だけ();
    let パス = |文字列: &str| -> 正規化した動画パス {
        入力された動画パス::作成する(文字列.to_string()).正規化する()
    };
    assert!(
        状態.並びを残して動画を開けるか(&パス("C:/動画/a.mp4")),
        "期待する動画が分からない"
    );
    状態.手がかり.開いた動画に合わせる(&パス("C:/動画/a.mp4"));
    assert!(状態.並びを残して動画を開けるか(&パス("D:/別/A.MP4")));
    assert!(!状態.並びを残して動画を開けるか(&パス("C:/動画/b.mp4")));
    let 空の並び = クリップを並べた状態(Vec::new());
    assert!(!空の並び.並びを残して動画を開けるか(&パス("C:/動画/a.mp4")));
}
