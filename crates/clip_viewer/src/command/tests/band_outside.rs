//! 位置を渡していない区間の帯(選ばれていないカード)の区間の外を押したときの試験。掴み始めたでそのカードを選び、
//! カードを押したときと同じ規則で再生位置を合わせ、区間の帯のドラッグを作らないことを確かめる。

use clip_domain::トリガー;

use super::{クリップを並べた状態, クリップを作る, 識別子, 選択中の名前};
use crate::command::{クリップの操作, 区間の帯の段階};

#[test]
fn 選ばれていないカードの区間の帯の区間の外を押すとそのカードを選ぶ() {
    let mut 状態 = クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
    ]);
    for 段階 in [区間の帯の段階::掴み始めた, 区間の帯の段階::放した] {
        let 押した =
            クリップの操作::区間の帯の区間の外を押す(識別子("乙"), 段階);
        状態.クリップの操作を適用する(押した);
    }
    assert_eq!(選択中の名前(&状態), "乙");
    assert!(
        (状態.再生.位置().位置の秒数() - 1.0).abs() < 1e-9,
        "止めているので乙の開始へ移る"
    );
    assert!(状態.区間の帯のドラッグ.is_none());
}
