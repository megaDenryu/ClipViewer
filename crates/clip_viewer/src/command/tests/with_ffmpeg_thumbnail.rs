/// 動画を開いて登録した状態と、登録したスタックの識別子。FFmpeg を見つけた状態にする。
fn 動画を開いて登録した状態(
    試験: &mut 試験のライブラリ,
) -> (アプリの状態, スタックの識別子) {
    試験
        .適用係
        .開き手
        .読み手を持たせる(動画の読み手::作成する(実行ファイルを探す()));
    let mut 状態 = 試験.接続した状態(Vec::new());
    状態.ffmpegの状況 = FFmpegの状況::見つかった(実行ファイルを探す());
    試験.適用係.確かめてから動画を開く(
        &mut 状態,
        &試験動画を作る("サムネイル"),
        開いたときの添え書き::無し,
    );
    for 操作 in [ライブラリの操作::登録の窓を開く, ライブラリの操作::登録する]
    {
        試験.適用係.適用する(&mut 状態, 応答::ライブラリ(操作));
    }
    let 識別子 = 状態
        .ライブラリ
        .開いている
        .識別子()
        .cloned()
        .expect("登録済み");
    終えるまで待って当てる(&mut 状態);
    (状態, 識別子)
}

/// ライブラリのフォルダに jpg のファイルが無いか。
fn ライブラリのフォルダにサムネイルが無いか(
    試験: &試験のライブラリ
) -> bool {
    std::fs::read_dir(試験.フォルダ.パス())
        .expect("ライブラリのフォルダ")
        .flatten()
        .all(|フォルダの中の項目| {
            フォルダの中の項目
                .path()
                .extension()
                .is_none_or(|拡張子| 拡張子 != "jpg")
        })
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 登録したスタックは見えている行でサムネイルを撮ってキャッシュへ置き_見せる() {
    let mut 試験 = 試験のライブラリ::作る("サムネイルの結合");
    let (mut 状態, 識別子) = 動画を開いて登録した状態(&mut 試験);
    見えている行で進める(&mut 状態, 0..=0);
    let Some(サムネイルの見せ方::見せられる(テクスチャ)) = 見せ方(&状態, &識別子)
    else {
        panic!("見せられるはずである")
    };
    assert_eq!(
        (テクスチャ.寸法().幅(), テクスチャ.寸法().高さ()),
        (192, 108)
    );
    let 撮り方 = 試験
        .ファイルを読む(&識別子)
        .and_then(|スタック| スタック.サムネイルの撮り方(一覧のサムネイルの大きさ))
        .expect("撮り方");
    let 置いた = 試験
        .キャッシュ()
        .読む(&撮り方)
        .expect("読める")
        .expect("キャッシュへ置いた");
    println!(
        "撮ったサムネイルの大きさ: {}バイト",
        置いた.バイト列().len()
    );
    assert!(
        ライブラリのフォルダにサムネイルが無いか(&試験),
        "ライブラリのフォルダにはサムネイルを置かない"
    );
}
