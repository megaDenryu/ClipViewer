//! ライブラリのダイアログを開いている間にウインドウへ落としたファイルの試験。落としたファイルは開かず、開いているダイアログを残し、
//! まとめて落としたファイルが何個あっても知らせは1件だけ出す。前のファイルで出た確かめるダイアログも、後のファイルで上書きしない。
#![allow(clippy::expect_used)]

use clip_domain::トリガー;

use super::library_support::試験のライブラリ;
use super::{クリップを作る, 編集する};
use crate::command::{
    クリップの編集, ファイルの操作, ライブラリの操作, 一度に落としたファイル, 応答,
};
use crate::state::library::{
    ライブラリのダイアログ, 入力中の名前, 登録の後にすること
};
use crate::state::アプリの状態;

const 閉じてから落とし直す知らせ: &str =
    "開いているダイアログを閉じてから、もう一度ドラッグ＆ドロップしてください";

/// クリップを2つ持つ設定ファイルの本文。
const 二つの設定: &str = r#"{"application":"ModifierVideoStack","version":"4.0","expectedVideoName":"sample.mp4",
"modifiers":[{"id":"mod-1-1","name":"一つ目","active":true,"start":1.5,"end":3,"repeat":1,
"crop":{"x":0,"y":0,"w":100,"h":100},"triggerEvent":"none"},
{"id":"mod-1-2","name":"二つ目","active":true,"start":4,"end":5,"repeat":1,
"crop":{"x":0,"y":0,"w":100,"h":100},"triggerEvent":"none"}]}"#;

/// クリップを1つ持つ設定ファイルの本文。
const 一つの設定: &str = r#"{"application":"ModifierVideoStack","version":"4.0","expectedVideoName":"sample.mp4",
"modifiers":[{"id":"mod-1-1","name":"一つ目","active":true,"start":1.5,"end":3,"repeat":1,
"crop":{"x":0,"y":0,"w":100,"h":100},"triggerEvent":"none"}]}"#;

fn 設定ファイルを置いて落とす(
    試験: &試験のライブラリ,
    ファイル: &[(&str, &str)],
) -> 応答 {
    let パス一覧 = ファイル
        .iter()
        .map(|(名前, 本文)| {
            let パス = 試験.一時フォルダ.join(名前);
            std::fs::write(&パス, 本文).expect("置ける");
            パス
        })
        .collect();
    応答::ファイル(ファイルの操作::落としたファイルを開く(
        一度に落としたファイル::作成する(パス一覧),
    ))
}

/// 閉じてから落とし直す知らせだけが1件出ていることを確かめる。
fn 知らせが1件だけ出ている(状態: &アプリの状態) {
    assert_eq!(
        状態.通知.最新().map(|(_, 文面)| 文面.to_string()),
        Some(閉じてから落とし直す知らせ.to_string())
    );
    assert_eq!(状態.通知.並べる通知().len(), 1);
}

#[test]
fn ダイアログを開いている間にまとめて落としたファイルは開かず知らせを1件だけ出す() {
    let mut 試験 = 試験のライブラリ::作る("ダイアログの間に落とす");
    let mut 状態 = 試験.接続した状態(Vec::new());
    let 開いていたダイアログ = ライブラリのダイアログ::名前を付けて登録(
        入力中の名前::作成する("練習".into()),
        登録の後にすること::何もしない,
    );
    状態.ライブラリ.ダイアログ = 開いていたダイアログ.clone();
    let 落とす = 設定ファイルを置いて落とす(
        &試験,
        &[
            ("甲.json", 二つの設定),
            ("乙.json", 一つの設定),
            ("丙.mp4", ""),
        ],
    );
    試験.適用係.適用する(&mut 状態, 落とす);
    assert!(状態.並び.一覧().is_empty(), "設定ファイルを読み込まない");
    assert_eq!(状態.ライブラリ.ダイアログ, 開いていたダイアログ);
    知らせが1件だけ出ている(&状態);
}

#[test]
fn 前のファイルで出た確かめるダイアログを後のファイルで上書きしない() {
    let mut 試験 = 試験のライブラリ::作る("確かめるダイアログを上書きしない");
    let mut 状態 = 試験.接続した状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    let 落とす = 設定ファイルを置いて落とす(
        &試験,
        &[("二つ.json", 二つの設定), ("一つ.json", 一つの設定)],
    );
    試験.適用係.適用する(&mut 状態, 落とす);
    assert!(状態.ライブラリ.ダイアログ.開いているか());
    知らせが1件だけ出ている(&状態);
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    assert_eq!(
        状態.並び.一覧().len(),
        2,
        "先に落とした設定ファイルを当てる"
    );
}
