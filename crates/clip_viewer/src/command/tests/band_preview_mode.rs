//! 区間の帯のドラッグのプレビューの求めが、再生モードに従うことの試験。元動画再生はクロップを掛けず、
//! シーケンス再生と単独クリップ再生は、位置の印のドラッグの間も通常の再生と同じくクリップの区間とクロップで求める。

use clip_domain::{クロップ範囲, トリガー, 再生モード};

use super::band::区間の帯を操作する;
use super::{クリップを並べた状態, クリップを作る, 区間};
use crate::command::{出力の操作, 区間の帯の段階};
use crate::state::{アプリの状態, 区間の帯で掴んだもの};
use crate::video_feed::表示するコマの求め;

fn 甲のクロップ() -> クロップ範囲 {
    クロップ範囲::各値を範囲へ収めて作成する(10.0, 10.0, 50.0, 50.0)
}

/// クロップした甲[1,3) を並べ、指定の再生モードの先頭で止めている状態。
fn クロップした甲の状態(モード: 再生モード) -> アプリの状態 {
    let mut 甲 = クリップを作る("甲", 1.0, 3.0, トリガー::自動進行);
    甲.クロップ = 甲のクロップ();
    let mut 状態 = クリップを並べた状態(vec![甲]);
    状態.出力の操作を適用する(出力の操作::再生モードを選ぶ(モード));
    状態
}

/// 甲の区間の帯で掴んだものを掴み、秒の位置へ動かしている間の求め。
fn 掴んで動かしている間の求め(
    状態: &mut アプリの状態,
    掴んだもの: 区間の帯で掴んだもの,
    秒: f64,
) -> 表示するコマの求め {
    区間の帯を操作する(状態, "甲", 区間の帯の段階::掴み始めた, 掴んだもの, 秒);
    区間の帯を操作する(状態, "甲", 区間の帯の段階::動かしている, 掴んだもの, 秒);
    状態.表示するコマの求め().expect("求め")
}

#[test]
fn 元動画再生で区間の帯をドラッグしている間は_クロップを掛けない() {
    for 掴んだもの in [
        区間の帯で掴んだもの::開始のつまみ,
        区間の帯で掴んだもの::終了のつまみ,
        区間の帯で掴んだもの::区間の内側,
        区間の帯で掴んだもの::位置の印,
    ] {
        let mut 状態 = クロップした甲の状態(再生モード::元動画再生);
        let 求め = 掴んで動かしている間の求め(&mut 状態, 掴んだもの, 1.5);
        assert_eq!(
            求め.クロップ,
            クロップ範囲::全体,
            "{掴んだもの:?} のドラッグの間も、元動画再生はクロップを掛けない"
        );
    }
}

#[test]
fn シーケンス再生でつまみをドラッグしている間は_クリップのクロップを掛ける() {
    let mut 状態 = クロップした甲の状態(再生モード::シーケンス再生);
    let 求め =
        掴んで動かしている間の求め(&mut 状態, 区間の帯で掴んだもの::開始のつまみ, 1.5);
    assert_eq!(求め.クロップ, 甲のクロップ());
}

#[test]
fn シーケンス再生と単独クリップ再生で位置の印をドラッグしている間は_クリップの区間で求める() {
    for モード in [再生モード::シーケンス再生, 再生モード::単独クリップ再生]
    {
        let mut 状態 = クロップした甲の状態(モード);
        let 求め =
            掴んで動かしている間の求め(&mut 状態, 区間の帯で掴んだもの::位置の印, 2.0);
        assert_eq!(
            求め.区間,
            Some(区間(1.0, 3.0)),
            "{モード:?} の位置の印のドラッグの間は、元動画再生の求め(区間の無い求め)にしない"
        );
        assert_eq!(求め.クロップ, 甲のクロップ());
    }
}

#[test]
fn 元動画再生で位置の印をドラッグしている間は_区間を持たずに求める() {
    let mut 状態 = クロップした甲の状態(再生モード::元動画再生);
    let 求め =
        掴んで動かしている間の求め(&mut 状態, 区間の帯で掴んだもの::位置の印, 2.0);
    assert!(求め.区間.is_none());
}
