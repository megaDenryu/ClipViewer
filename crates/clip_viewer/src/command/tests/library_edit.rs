//! 開いているスタックの削除と名前の変更の試験。どちらも、その後の自動保存がファイルを古い中身で書かないことを確かめる。
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use clip_domain::トリガー;

use super::library_check::{
    ファイルのクリップの名前, 終えるまで待って当てる
};
use super::library_support::試験のライブラリ;
use super::{クリップを作る, 編集する};
use crate::command::{クリップの編集, ライブラリの操作, 応答};
use crate::state::library::開いているスタック;
use crate::state::アプリの状態;

fn 甲だけの状態(試験: &試験のライブラリ) -> アプリの状態 {
    試験.接続した状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )])
}

fn ライブラリの操作(
    試験: &mut 試験のライブラリ,
    状態: &mut アプリの状態,
    操作: ライブラリの操作,
) {
    試験.適用係.適用する(状態, 応答::ライブラリ(操作));
}

#[test]
fn 開いているスタックを削除すると未登録へ戻り_その後の変更でファイルを作り直さない() {
    let mut 試験 = 試験のライブラリ::作る("削除");
    let mut 状態 = 甲だけの状態(&試験);
    let 識別子 = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    ライブラリの操作(
        &mut 試験,
        &mut 状態,
        ライブラリの操作::削除の確認を開く(識別子.clone()),
    );
    ライブラリの操作(&mut 試験, &mut 状態, ライブラリの操作::削除する);
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    let 始め = Instant::now();
    状態.ライブラリの書き込みを進める(始め);
    状態.ライブラリの書き込みを進める(始め + Duration::from_secs(1));
    終えるまで待って当てる(&mut 状態);
    assert!(試験.ファイルを読む(&識別子).is_none());
}

#[test]
fn 開いているスタックの名前を変えると後の自動保存も新しい名前で書く() {
    let mut 試験 = 試験のライブラリ::作る("名前");
    let mut 状態 = 甲だけの状態(&試験);
    let 識別子 = 試験.登録済みにする(&mut 状態, "stack-1-1", "練習");
    ライブラリの操作(
        &mut 試験,
        &mut 状態,
        ライブラリの操作::名前を変えるダイアログを開く(識別子.clone()),
    );
    ライブラリの操作(
        &mut 試験,
        &mut 状態,
        ライブラリの操作::名前の入力を書き換える("本番".into()),
    );
    ライブラリの操作(&mut 試験, &mut 状態, ライブラリの操作::名前を変える);
    編集する(&mut 状態, クリップの編集::名前を変える("変えた".into()));
    let 始め = Instant::now();
    状態.ライブラリの書き込みを進める(始め);
    状態.ライブラリの書き込みを進める(始め + Duration::from_secs(1));
    終えるまで待って当てる(&mut 状態);
    let ファイル = 試験.ファイルを読む(&識別子).expect("ファイルがある");
    assert_eq!(ファイル.名前().文字列(), "本番");
    assert_eq!(ファイルのクリップの名前(&ファイル), ["変えた"]);
}
