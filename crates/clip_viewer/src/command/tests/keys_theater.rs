//! シアターの構えへ入る・戻るキー(T)の試験。編集の構えで T を押すとシアターへ、シアターで押すと編集の構えへ戻ることと、
//! ライブラリの構えと入力欄に文字を打っている間は T が効かないことを確かめる。

use eframe::egui;

use super::key_support::{キーの押下, キーを押して集める, 事象を渡して描く};
use super::keys_text_field::入力欄へフォーカスを移した本体;
use super::クリップを並べた状態;
use crate::command::{出力の操作, 応答};
use crate::state::{アプリの状態, 画面の構え};

const 無し: egui::Modifiers = egui::Modifiers::NONE;
const 切り替える: 応答 = 応答::出力(出力の操作::シアターと編集を切り替える);

/// T を押して発した応答を状態へ当てる。
fn tを押して当てる(状態: &mut アプリの状態) {
    let 集めた = キーを押して集める(状態, egui::Key::T, 無し);
    assert_eq!(
        集めた,
        [切り替える],
        "{:?} の構えで T が効かない",
        状態.出力.構え
    );
    状態.出力の操作を適用する(出力の操作::シアターと編集を切り替える);
}

#[test]
fn 編集の構えでtを押すとシアターへ入り_もう一度押すと編集の構えへ戻る() {
    let mut 状態 = クリップを並べた状態(Vec::new());
    assert_eq!(状態.出力.構え, 画面の構え::編集);
    tを押して当てる(&mut 状態);
    assert_eq!(状態.出力.構え, 画面の構え::シアター);
    tを押して当てる(&mut 状態);
    assert_eq!(状態.出力.構え, 画面の構え::編集);
}

#[test]
fn ライブラリの構えではtが効かず_当てても構えを変えない() {
    let mut 状態 = クリップを並べた状態(Vec::new());
    状態.出力.構え = 画面の構え::ライブラリ;
    assert!(キーを押して集める(&状態, egui::Key::T, 無し).is_empty());
    状態.出力の操作を適用する(出力の操作::シアターと編集を切り替える);
    assert_eq!(状態.出力.構え, 画面の構え::ライブラリ);
}

#[test]
fn 入力欄に文字を打っている間はtを入力欄に任せる() {
    let 状態 = クリップを並べた状態(Vec::new());
    let eguiの本体 = 入力欄へフォーカスを移した本体(&状態);
    let mut 集めた = 事象を渡して描く(
        &eguiの本体,
        &状態,
        vec![キーの押下(egui::Key::T, 無し)],
        無し,
    );
    集めた.extend(事象を渡して描く(
        &eguiの本体,
        &状態,
        Vec::new(),
        無し,
    ));
    assert!(!集めた.contains(&切り替える), "{集めた:?}");
}
