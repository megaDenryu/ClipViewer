//! 登録済みのスタックで、今の動画で新しいスタックを始める操作の結合試験。元のスタックは捨てる前の変更まで保存されたままライブラリに残り、
//! 新しいスタックは未登録で始まることを確かめる。ライブラリは一時フォルダに置く(`library_support.rs`)。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::library_check::{
    ファイルのクリップの名前, 終えるまで待って当てる
};
use super::with_ffmpeg_new_stack::{クリップの名前, 始める};
use super::with_ffmpeg_video::{試験動画を作る, 読み手のある試験};
use crate::command::{クリップの操作, ライブラリの操作, 応答};
use crate::state::library::{
    ライブラリのダイアログ, 開いたときの添え書き, 開いているスタック
};

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 登録済みのスタックで押すと元のスタックを保存して残し_新しいスタックは未登録で始める() {
    let (mut 試験, mut 状態) = 読み手のある試験("登録済みから新しいスタック");
    let 動画 = 試験動画を作る("登録済みから新しいスタック");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &動画, 開いたときの添え書き::無し);
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::登録のダイアログを開く),
    );
    試験
        .適用係
        .適用する(&mut 状態, 応答::ライブラリ(ライブラリの操作::登録する));
    let 識別子 = 状態
        .ライブラリ
        .開いている
        .識別子()
        .cloned()
        .expect("登録済み");
    終えるまで待って当てる(&mut 状態);
    試験
        .適用係
        .適用する(&mut 状態, 応答::クリップ(クリップの操作::追加する));
    状態.フレームを進める(Instant::now());
    試験.適用係.適用する(&mut 状態, 始める);
    assert_eq!(
        状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::無し,
        "保存できていれば確かめるダイアログを出さない"
    );
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    assert_eq!(クリップの名前(&状態), ["Clip Mod 1"]);
    assert!(状態.動画.is_some());
    状態.フレームを進める(Instant::now());
    assert!(!状態.取り消せるか());
    終えるまで待って当てる(&mut 状態);
    let ファイル = 試験
        .ファイルを読む(&識別子)
        .expect("元のスタックのファイルが残る");
    assert_eq!(
        ファイルのクリップの名前(&ファイル).len(),
        2,
        "捨てる前に追加したクリップまで保存してあり、新しいスタックで上書きしない"
    );
}
