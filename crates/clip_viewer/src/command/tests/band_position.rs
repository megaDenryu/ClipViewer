//! 区間の帯の位置の印の試験。位置の印の値を再生モードごとの写し方で再生位置へ写すことを確かめる。

use clip_domain::{トリガー, 再生モード, 再生位置};

use super::band::区間の帯を操作する;
use super::{クリップを並べた状態, クリップを作る, 識別子};
use crate::command::{出力の操作, 区間の帯の段階};
use crate::state::{アプリの状態, 区間の帯で掴んだもの};

const 印: 区間の帯で掴んだもの = 区間の帯で掴んだもの::位置の印;

/// 甲[0,1) と乙[5,7) を並べ、指定の再生モードの先頭で止めている状態。
fn 二つの状態(モード: 再生モード) -> アプリの状態 {
    let mut 状態 = クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
    ]);
    状態.出力の操作を適用する(出力の操作::再生モードを選ぶ(モード));
    状態
}

/// 乙の区間の帯の、区間の外を押して秒の位置へ動かし、放したときの再生位置。
fn 乙の位置の印を動かす(状態: &mut アプリの状態, 秒: f64) -> 再生位置 {
    区間の帯を操作する(状態, "乙", 区間の帯の段階::掴み始めた, 印, 秒);
    区間の帯を操作する(状態, "乙", 区間の帯の段階::放した, 印, 秒);
    状態.再生.位置()
}

fn 近い(実際: f64, 期待: f64) -> bool {
    (実際 - 期待).abs() < 1e-9
}

#[test]
fn シーケンス再生は区間の中の最初の周回へ写し_終了ちょうどは最後のコマで止める() {
    let mut 状態 = 二つの状態(再生モード::シーケンス再生);
    区間の帯を操作する(&mut 状態, "乙", 区間の帯の段階::掴み始めた, 印, 5.5);
    let 求め = 状態.表示するコマの求め().expect("求め");
    assert!(近い(求め.動画上の位置.秒数(), 5.5));
    assert!(求め.区間.is_none(), "位置の印は区間を持たずに求める");
    区間の帯を操作する(&mut 状態, "乙", 区間の帯の段階::放した, 印, 5.5);
    assert!(
        近い(状態.再生.位置().位置の秒数(), 1.5),
        "甲の1秒の後の0.5秒"
    );
    let 末尾 = 乙の位置の印を動かす(&mut 状態, 7.0);
    assert!(近い(末尾.位置の秒数(), 1.0 + 2.0 - 1.0 / 30.0));
}

#[test]
fn 単独クリップ再生は区間の開始からの経過へ_元動画再生はそのままの位置へ写す() {
    let mut 状態 = 二つの状態(再生モード::単独クリップ再生);
    let 単独 = 乙の位置の印を動かす(&mut 状態, 2.0);
    assert!(
        matches!(単独, 再生位置::単独クリップ再生(経過) if 経過.ゼロか()),
        "区間の前は開始へ収める"
    );
    let 区間内の位置 = 乙の位置の印を動かす(&mut 状態, 6.25);
    assert!(近い(区間内の位置.位置の秒数(), 1.25));
    状態.出力の操作を適用する(出力の操作::再生モードを選ぶ(
        再生モード::元動画再生,
    ));
    let 元動画 = 乙の位置の印を動かす(&mut 状態, 3.0);
    assert!(matches!(元動画, 再生位置::元動画再生(_)));
    assert!(近い(元動画.位置の秒数(), 3.0));
}

#[test]
fn シーケンス再生で無効なクリップの中へは移らずに知らせる() {
    let mut 状態 = 二つの状態(再生モード::シーケンス再生);
    let mut 乙 = 状態.並び.識別子で探す(&識別子("乙")).cloned().expect("乙");
    乙.有効か = false;
    状態.並び.更新する(乙).expect("更新");
    区間の帯を操作する(&mut 状態, "乙", 区間の帯の段階::掴み始めた, 印, 5.5);
    let 前 = 状態.再生.位置();
    区間の帯を操作する(&mut 状態, "乙", 区間の帯の段階::放した, 印, 5.5);
    assert_eq!(状態.再生.位置(), 前);
    assert!(
        状態
            .通知
            .最新()
            .is_some_and(|(_, 文面)| 文面.contains("移れない"))
    );
}
