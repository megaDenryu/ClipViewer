//! 区間の帯を掴むときと放すときの規則の試験。選ばれていないカードの区間の帯を掴むと、カードを押したときと同じ規則で再生位置も
//! そのクリップへ合わせることと、掴んで放しただけでは区間を書き換えないことと、主ボタンを放しているのに残った
//! ドラッグを捨てて再生を戻すことを確かめる。

use clip_domain::トリガー;

use super::band::{再生している甲, 区間の帯を操作する, 甲の区間};
use super::{クリップを並べた状態, クリップを作る, 選択中の名前};
use crate::command::{主ボタンの様子, 区間の帯の段階};
use crate::state::区間の帯で掴んだもの;

const つまみ: 区間の帯で掴んだもの = 区間の帯で掴んだもの::開始のつまみ;

#[test]
fn 止めているシーケンス再生で選ばれていないカードの区間の帯を掴むと再生位置もそのクリップの開始へ移る()
 {
    let mut 状態 = クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
    ]);
    区間の帯を操作する(&mut 状態, "乙", 区間の帯の段階::掴み始めた, つまみ, 5.0);
    区間の帯を操作する(&mut 状態, "乙", 区間の帯の段階::放した, つまみ, 5.0);
    assert_eq!(選択中の名前(&状態), "乙");
    assert!(
        (状態.再生.位置().位置の秒数() - 1.0).abs() < 1e-9,
        "乙のタイムライン上の開始"
    );
    let 求め = 状態.表示するコマの求め().expect("求め");
    assert!(
        (求め.動画上の位置.秒数() - 5.0).abs() < 1e-9,
        "プレビューも乙のコマを求める"
    );
}

#[test]
fn 主ボタンを放しているのに残った区間の帯のドラッグは捨てて再生を戻す() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        1.0,
        3.0,
        トリガー::自動進行,
    )]);
    状態.再生.再生を始める();
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::掴み始めた, つまみ, 1.0);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::動かしている, つまみ, 2.0);
    状態.取り残されたドラッグを捨てる(主ボタンの様子::押している);
    assert!(状態.区間の帯のドラッグ.is_some(), "押している間は捨てない");
    状態.取り残されたドラッグを捨てる(主ボタンの様子::押していない);
    assert!(状態.区間の帯のドラッグ.is_none());
    assert!(状態.再生.再生しているか());
    let 甲 = 状態
        .並び
        .一覧()
        .first()
        .map(|クリップ| クリップ.区間.開始().秒数());
    assert_eq!(甲, Some(1.0), "捨てたドラッグの仮の区間は決めない");
}

#[test]
fn 掴んで放しただけでは区間を書き換えない() {
    let mut 状態 = 再生している甲();
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::掴み始めた, つまみ, 0.0);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::放した, つまみ, 0.0);
    assert_eq!(甲の区間(&状態), Some(super::区間(1.0, 3.0)));
    assert!(状態.再生.再生しているか());
}
