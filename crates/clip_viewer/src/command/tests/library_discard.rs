//! 保存できないまま続けるかを確かめるダイアログで「変更を捨てて続ける」を選んだときの試験。
//! 続ける操作が成功したときだけ開いているスタックとの関係を終え、失敗したときは関係を残して頼み直しを続ける。
//! 保存を失敗させるため、スタックのファイルを排他で開いて置き換えられなくする(Windows だけで流す)。
#![cfg(windows)]
#![allow(clippy::expect_used)]

use clip_domain::スタックの識別子;

use super::library_failure::保存に失敗した状態;
use super::library_support::試験のライブラリ;
use crate::command::{ファイルの操作, ライブラリの操作, 応答};
use crate::state::library::{
    ライブラリのダイアログ, 開いているスタック, 関係を終える操作
};

#[test]
fn 保存できないまま別のスタックを開こうとすると確かめ_開けなければ変更を捨てても関係を残す() {
    let mut 試験 = 試験のライブラリ::作る("開く前に確かめる");
    let (mut 状態, _, _排他, _) = 保存に失敗した状態(&試験);
    let 無いスタック = スタックの識別子::文字列から作成する("stack-2-2".into()).expect("識別子");
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::開く(無いスタック.clone())),
    );
    assert!(matches!(
        &状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::保存できずに続ける確認(_, 関係を終える操作::一覧から開く(識別子)) if *識別子 == 無いスタック
    ));
    assert!(
        matches!(状態.ライブラリ.開いている, 開いているスタック::登録済み(_)),
        "確かめる間は関係を終えない"
    );
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    assert_eq!(状態.ライブラリ.ダイアログ, ライブラリのダイアログ::無し);
    assert!(
        matches!(状態.ライブラリ.開いている, 開いているスタック::登録済み(_)),
        "開けなかったので、関係を残して頼み直しを続ける"
    );
    let 通知 = 状態
        .通知
        .最新()
        .map(|(_, 文面)| 文面.to_string())
        .unwrap_or_default();
    assert!(通知.contains("ライブラリのスタックを開けない"), "{通知}");
}

#[test]
fn 保存できないまま動画を解除しようとすると確かめ_変更を捨てて続けると関係を終えて解除する() {
    let mut 試験 = 試験のライブラリ::作る("解除する前に確かめる");
    let (mut 状態, _, _排他, _) = 保存に失敗した状態(&試験);
    試験
        .適用係
        .適用する(&mut 状態, 応答::ファイル(ファイルの操作::動画を解除する));
    assert!(matches!(
        &状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::保存できずに続ける確認(
            _,
            関係を終える操作::動画を解除する
        )
    ));
    assert_eq!(状態.並び.一覧().len(), 1, "確かめる間は解除しない");
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    assert!(matches!(
        状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    assert!(状態.並び.一覧().is_empty());
}
