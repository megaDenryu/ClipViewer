//! 操作コマンドの試験の道具。動画を開いていない状態にクリップを並べることと、クリップと区間を作ることと、選択中の名前と並びのクリップの名前を読むことと、
//! 試験が当てる応答。
#![allow(clippy::expect_used)]

use clip_domain::{
    クリップ, クリップスタック, クリップ名, クリップ識別子, トリガー, 動画上の区間, 時刻,
};
use video_source::FFmpegが見つからないエラー;

use crate::command::{クリップの操作, 応答};
use crate::state::{
    FFmpegの状況, アプリの状態, 並びの出どころ, 入力中のフォルダ, 音の出力の状況
};
use crate::thumbnail_feed::一覧のサムネイル;

/// 動画を開いていない状態に、指定の区間のクリップを並べる。先頭のクリップが選ばれている。
/// 並びは `並びを置き換える` で入れるため、編集の履歴はこの並びを起点にして空である。
pub(super) fn クリップを並べた状態(
    クリップ一覧: Vec<クリップ>
) -> アプリの状態 {
    let ffmpegの状況 = FFmpegの状況::見つからない {
        理由: FFmpegが見つからないエラー {
            見つからない道具: Vec::new(),
            探した場所: Vec::new(),
        },
        入力中のフォルダ: 入力中のフォルダ::default(),
    };
    let 音の出力 = 音の出力の状況::使えない(audio_output::音声出力のエラー::装置が無い);
    let サムネイル = 一覧のサムネイル::キャッシュを使わずに作る(
        eframe::egui::Context::default(),
    );
    let mut 状態 = アプリの状態::起動時(ffmpegの状況, 音の出力, サムネイル);
    状態.並びを置き換える(
        クリップスタック::一覧から作成する(クリップ一覧).expect("スタック"),
        並びの出どころ::新しく作った,
    );
    状態
}

pub(super) fn 識別子(名前: &str) -> クリップ識別子 {
    クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子")
}

pub(super) fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}

pub(super) fn クリップを作る(
    名前: &str,
    開始: f64,
    終了: f64,
    トリガー: トリガー,
) -> クリップ {
    let mut クリップ = クリップ::既定値で作成する(
        識別子(名前),
        クリップ名::作成する(名前.to_string()),
    );
    クリップ.区間 = 区間(開始, 終了);
    クリップ.トリガー = トリガー;
    クリップ
}

pub(super) fn 選択中の名前(状態: &アプリの状態) -> String {
    状態
        .並び
        .選択中のクリップ()
        .map(|クリップ| クリップ.名前.文字列().to_string())
        .unwrap_or_default()
}

/// 甲のクリップへ編集を適用する。
pub(super) fn 編集する(
    状態: &mut アプリの状態, 編集: crate::command::クリップの編集
) {
    状態.クリップの操作を適用する(crate::command::クリップの操作::編集する(
        識別子("甲"),
        編集,
    ));
}

/// 「新しいスタックを始める」を押したときに画面が発する応答。
pub(super) const 今の動画で新しいスタックを始める応答: 応答 =
    応答::クリップ(クリップの操作::今の動画で新しいスタックを始める);

/// 今の並びのクリップの名前を、並び順に読む。
pub(super) fn 並びのクリップの名前(状態: &アプリの状態) -> Vec<String> {
    状態
        .並び
        .一覧()
        .iter()
        .map(|クリップ| クリップ.名前.文字列().to_string())
        .collect()
}
