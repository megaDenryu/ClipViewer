//! Enter キーで次のクリップへ進める操作の試験。シーケンス再生ではトリガーを待たずに Next Clip と同じく進み、
//! 単独クリップ再生と元動画再生では進まずに今のキーの表記で知らせる。再生位置にクリップが無いときは何もしない。参照: _doc/使い方.md 6.4節
#![allow(clippy::expect_used)]

use clip_domain::{トリガー, 再生モード};

use super::{クリップを並べた状態, クリップを作る, 選択中の名前};
use crate::command::出力の操作;
use crate::state::アプリの状態;
use crate::viewer_settings::キーで行う操作;
use sengen_egui::{キー, キーの組};

const シーケンス再生でないときの知らせ: &str = "Enter で次へ進めるのはシーケンス再生のときだけです";

fn 位置の秒(状態: &アプリの状態) -> f64 {
    状態.再生.位置().位置の秒数()
}

fn 最新の知らせ(状態: &アプリの状態) -> Option<String> {
    状態.通知.最新().map(|(_, 文面)| 文面.to_string())
}

/// 先頭のクリップのトリガーだけを変えた、甲[0,1) と乙[2,3) の2つの並び。
fn 二つの並び(先頭のトリガー: トリガー) -> アプリの状態 {
    クリップを並べた状態(vec![
        クリップを作る("甲", 0.0, 1.0, 先頭のトリガー),
        クリップを作る("乙", 2.0, 3.0, トリガー::自動進行),
    ])
}

#[test]
fn シーケンス再生ではトリガーが自動進行でもクリック待ちでも_enterキーで次のクリップへ進む() {
    for 先頭のトリガー in [トリガー::自動進行, トリガー::クリック待ち] {
        let mut 状態 = 二つの並び(先頭のトリガー);
        状態.出力の操作を適用する(出力の操作::Enterキーで次へ進める);
        assert_eq!(選択中の名前(&状態), "乙", "{先頭のトリガー:?}");
        assert!((位置の秒(&状態) - 1.0).abs() < 1e-9, "{先頭のトリガー:?}");
        assert_eq!(最新の知らせ(&状態), None, "{先頭のトリガー:?}");
    }
}

#[test]
fn 単独クリップ再生と元動画再生では_enterキーで進まずに知らせる() {
    for モード in [再生モード::単独クリップ再生, 再生モード::元動画再生] {
        let mut 状態 = 二つの並び(トリガー::Enterキー待ち);
        状態.出力の操作を適用する(出力の操作::再生モードを選ぶ(モード));
        let 押す前の位置 = 状態.再生.位置();
        状態.出力の操作を適用する(出力の操作::Enterキーで次へ進める);
        assert_eq!(選択中の名前(&状態), "甲", "{モード:?}");
        assert_eq!(状態.再生.位置(), 押す前の位置, "{モード:?}");
        assert_eq!(
            最新の知らせ(&状態).as_deref(),
            Some(シーケンス再生でないときの知らせ),
            "{モード:?}"
        );
    }
}

#[test]
fn キーを変えた後の知らせは今のキーの表記で始まる() {
    let mut 状態 = 二つの並び(トリガー::Enterキー待ち);
    状態.キーの割り当て = 状態
        .キーの割り当て
        .キーを変えた(
            キーで行う操作::次のクリップへ進めるか知らせる,
            キーの組::単独(キー::F2),
        )
        .expect("空いたキーへは変えられる");
    状態.出力の操作を適用する(出力の操作::再生モードを選ぶ(
        再生モード::元動画再生,
    ));
    状態.出力の操作を適用する(出力の操作::Enterキーで次へ進める);
    assert_eq!(
        最新の知らせ(&状態).as_deref(),
        Some("F2 で次へ進めるのはシーケンス再生のときだけです")
    );
}

#[test]
fn シーケンス再生で再生位置にクリップが無いときは_enterキーで何もせず知らせない() {
    let mut 状態 = クリップを並べた状態(Vec::new());
    状態.出力の操作を適用する(出力の操作::Enterキーで次へ進める);
    assert!(位置の秒(&状態).abs() < 1e-9);
    assert_eq!(最新の知らせ(&状態), None);
}
