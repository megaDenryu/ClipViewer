//! 全画面の試験。F11 の操作は全画面の出入りを頼み、Escape の操作は全画面なら全画面だけを抜け(構えを変えない)、
//! 全画面でなくシアターなら編集の構えへ戻る。同じフレームで2回切り替えると、2回目は1回目の頼みから切り替える。

use super::クリップを並べた状態;
use crate::command::出力の操作;
use crate::state::{
    ウインドウの形, ウインドウの様子, 全画面の様子, 画面の構え
};

/// 全画面の様子だけを決めたウインドウの様子。大きさと画面の大きさは知らせていない。
fn 様子(全画面か: 全画面の様子) -> ウインドウの様子 {
    ウインドウの様子 {
        全画面: 全画面か,
        形: ウインドウの形::普通(None),
        画面: None,
    }
}

#[test]
fn 全画面を切り替える操作は今の様子の逆を頼み_同じフレームの2回目は1回目の頼みから切り替える() {
    let mut 状態 = クリップを並べた状態(Vec::new());
    状態.出力の操作を適用する(出力の操作::全画面を切り替える);
    assert_eq!(状態.ウインドウ.全画面の様子(), 全画面の様子::全画面);
    状態.出力の操作を適用する(出力の操作::全画面を切り替える);
    assert_eq!(
        状態.ウインドウ.頼みを取り出す().全画面,
        Some(全画面の様子::全画面でない)
    );
    assert_eq!(状態.ウインドウ.頼みを取り出す().全画面, None);
}

#[test]
fn エスケープは全画面なら全画面だけを抜け_次にシアターを抜ける() {
    let mut 状態 = クリップを並べた状態(Vec::new());
    状態.出力.構え = 画面の構え::シアター;
    状態.ウインドウ.様子を知らせる(様子(全画面の様子::全画面));
    状態.出力の操作を適用する(
        出力の操作::全画面を抜けるか全画面でなければシアターを抜ける,
    );
    assert_eq!(状態.出力.構え, 画面の構え::シアター);
    assert_eq!(
        状態.ウインドウ.頼みを取り出す().全画面,
        Some(全画面の様子::全画面でない)
    );
    状態
        .ウインドウ
        .様子を知らせる(様子(全画面の様子::全画面でない));
    状態.出力の操作を適用する(
        出力の操作::全画面を抜けるか全画面でなければシアターを抜ける,
    );
    assert_eq!(状態.出力.構え, 画面の構え::編集);
    assert_eq!(状態.ウインドウ.頼みを取り出す().全画面, None);
}

#[test]
fn 全画面でもシアターでもなければエスケープは何もしない() {
    let mut 状態 = クリップを並べた状態(Vec::new());
    状態.出力の操作を適用する(
        出力の操作::全画面を抜けるか全画面でなければシアターを抜ける,
    );
    assert_eq!(状態.出力.構え, 画面の構え::編集);
    assert_eq!(状態.ウインドウ.頼みを取り出す().全画面, None);
}
