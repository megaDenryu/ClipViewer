//! 動画を開いたときの添え書きの結合試験。起動の引数の添え書き(最初の1つだけを開いた)は、確かめるダイアログを経て開いたときも書き足す。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use super::with_ffmpeg_video::{名前を付けて試験動画を作る, 読み手のある試験};
use crate::command::{クリップの操作, ライブラリの操作, 応答};
use crate::state::library::{ライブラリのダイアログ, 開いたときの添え書き};

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 確かめるダイアログを経て開いたときも添え書きを書き足す() {
    let (mut 試験, mut 状態) = 読み手のある試験("ダイアログを経た添え書き");
    let 練習 = 名前を付けて試験動画を作る("ダイアログを経た添え書き", "練習動画.mp4");
    let 別 = 名前を付けて試験動画を作る("ダイアログを経た添え書き", "別の動画.mp4");
    試験
        .適用係
        .確かめてから動画を開く(&mut 状態, &練習, 開いたときの添え書き::無し);
    試験
        .適用係
        .適用する(&mut 状態, 応答::クリップ(クリップの操作::追加する));
    let 添え書き = 開いたときの添え書き::書き足す("最初の1つだけを開いた".into());
    試験.適用係.確かめてから動画を開く(&mut 状態, &別, 添え書き);
    assert!(matches!(
        状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(..)
    ));
    試験.適用係.適用する(
        &mut 状態,
        応答::ライブラリ(ライブラリの操作::変更を捨てて続ける),
    );
    let 通知 = 状態
        .通知
        .最新()
        .map(|(_, 文面)| 文面.to_string())
        .unwrap_or_default();
    assert!(
        通知.contains("別の動画.mp4") && 通知.contains("最初の1つだけを開いた"),
        "{通知}"
    );
}
