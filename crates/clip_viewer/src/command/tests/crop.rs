//! クロップ枠のドラッグの試験。

use clip_domain::{
    クロップの移動量, クロップ範囲, トリガー, 四隅のつまみ, 百分率の差分
};

use super::{クリップを並べた状態, クリップを作る, 識別子};
use crate::command::クロップ枠の操作;
use clip_domain::枠の掴む所;

fn 移動量(横: f64, 縦: f64) -> クロップの移動量 {
    クロップの移動量 {
        横: 百分率の差分::作成する(横).expect("差分"),
        縦: 百分率の差分::作成する(縦).expect("差分"),
    }
}

fn 甲のクロップ(状態: &crate::state::アプリの状態) -> Option<クロップ範囲> {
    状態
        .並び
        .識別子で探す(&識別子("甲"))
        .map(|クリップ| クリップ.クロップ)
}

#[test]
fn 掴み始めのクロップへ累積の移動量を当て_放すと掴み始めを忘れる() {
    let mut 甲 = クリップを作る("甲", 0.0, 1.0, トリガー::自動進行);
    甲.クロップ =
        クロップ範囲::各値を範囲へ収めて作成する(10.0, 10.0, 50.0, 50.0);
    let mut 状態 = クリップを並べた状態(vec![甲]);
    状態.クロップ枠の操作を適用する(クロップ枠の操作::掴み始めた);
    let 内側を掴む = 枠の掴む所::内側;
    状態.クロップ枠の操作を適用する(クロップ枠の操作::動かしている {
        掴む所: 内側を掴む,
        移動量: 移動量(5.0, 0.0),
    });
    状態.クロップ枠の操作を適用する(クロップ枠の操作::動かしている {
        掴む所: 内側を掴む,
        移動量: 移動量(20.0, 0.0),
    });
    let 期待 = クロップ範囲::各値を範囲へ収めて作成する(30.0, 10.0, 50.0, 50.0);
    assert_eq!(甲のクロップ(&状態), Some(期待));
    let 右下 = 枠の掴む所::隅(四隅のつまみ::右下);
    状態.クロップ枠の操作を適用する(クロップ枠の操作::放した {
        掴む所: 右下,
        移動量: 移動量(-10.0, -10.0),
    });
    let 期待 = クロップ範囲::各値を範囲へ収めて作成する(10.0, 10.0, 40.0, 40.0);
    assert_eq!(甲のクロップ(&状態), Some(期待));
    assert!(状態.掴み始め.is_none());
    状態.クロップ枠の操作を適用する(クロップ枠の操作::動かしている {
        掴む所: 内側を掴む,
        移動量: 移動量(5.0, 0.0),
    });
    assert_eq!(甲のクロップ(&状態), Some(期待));
}

#[test]
fn 放したを受け取れずに主ボタンを離していたら_クロップ枠の掴み始めを忘れる() {
    let mut 状態 = クリップを並べた状態(vec![クリップを作る(
        "甲",
        0.0,
        1.0,
        トリガー::自動進行,
    )]);
    状態.クロップ枠の操作を適用する(クロップ枠の操作::掴み始めた);
    状態.取り残されたドラッグを捨てる(crate::command::主ボタンの様子::押している);
    assert!(状態.掴み始め.is_some(), "押している間は捨てない");
    状態.取り残されたドラッグを捨てる(crate::command::主ボタンの様子::押していない);
    assert!(状態.掴み始め.is_none());
}
