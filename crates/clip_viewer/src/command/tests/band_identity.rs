//! 区間の帯の応答の持ち主の試験。今のドラッグと別のクリップや別の帯(全体の帯と拡大の帯)の動かしていると放したでは、
//! 今のドラッグを動かしも確定もしないことを確かめる。

use clip_domain::トリガー;

use super::band::{区間の帯を操作する, 甲の区間};
use super::{クリップを並べた状態, クリップを作る, 区間, 識別子};
use crate::command::{
    クリップの区間の帯の操作, クリップの操作, 区間の帯の段階
};
use crate::state::{アプリの状態, 区間の帯で掴んだもの, 区間の帯の種類};

const つまみ: 区間の帯で掴んだもの = 区間の帯で掴んだもの::開始のつまみ;

fn 別の応答(
    状態: &mut アプリの状態, 名前: &str, 帯: 区間の帯の種類, 段階: 区間の帯の段階
) {
    let 操作 = クリップの区間の帯の操作 {
        帯,
        段階,
        掴んだもの: つまみ,
        秒: 0.2,
    };
    状態.クリップの操作を適用する(クリップの操作::区間の帯を操作する(
        識別子(名前),
        操作,
    ));
}

#[test]
fn 別のクリップや別の区間の帯の応答では今のドラッグを動かしも確定もしない() {
    let mut 状態 = クリップを並べた状態(vec![
        クリップを作る("甲", 1.0, 3.0, トリガー::自動進行),
        クリップを作る("乙", 5.0, 7.0, トリガー::自動進行),
    ]);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::掴み始めた, つまみ, 1.0);
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::動かしている, つまみ, 1.5);
    別の応答(
        &mut 状態,
        "甲",
        区間の帯の種類::拡大の帯,
        区間の帯の段階::動かしている,
    );
    別の応答(
        &mut 状態,
        "乙",
        区間の帯の種類::全体の帯,
        区間の帯の段階::放した,
    );
    別の応答(
        &mut 状態,
        "甲",
        区間の帯の種類::拡大の帯,
        区間の帯の段階::放した,
    );
    assert!(
        状態.区間の帯のドラッグ.is_some(),
        "別の区間の帯の放したでは確定しない"
    );
    assert_eq!(甲の区間(&状態), Some(区間(1.0, 3.0)));
    区間の帯を操作する(&mut 状態, "甲", 区間の帯の段階::放した, つまみ, 0.2);
    assert_eq!(
        甲の区間(&状態),
        Some(区間(1.5, 3.0)),
        "拡大の帯の0.2秒で動かしていない"
    );
}
