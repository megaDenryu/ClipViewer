//! 再生位置を移す。秒で指した位置へ移すことと、選んだクリップへ合わせることと、クリップの開始へ移ること。再生モードごとに移し方が違う。

use clip_domain::{クリップ識別子, 再生位置, 時刻, 時間の長さ};

use crate::state::アプリの状態;

impl アプリの状態 {
    /// 今の再生モードのまま、秒で指した位置へ移す。0秒から合計の長さの間へ収め、非数は0秒にする。
    pub(crate) fn 秒の位置へ移す(&mut self, 秒: f64) {
        let 合計 = self.合計の長さ().秒数();
        let 収めた秒 = if 秒.is_nan() {
            0.0
        } else {
            秒.clamp(0.0, 合計)
        };
        // 注意: 収めた秒は0以上の有限の数なので、時刻と時間の長さの作成は失敗しない。
        let 新しい位置 = match self.再生.位置() {
            再生位置::シーケンス再生(_) => {
                時刻::作成する(収めた秒).map(再生位置::シーケンス再生)
            }
            再生位置::単独クリップ再生(_) => {
                時間の長さ::作成する(収めた秒).map(再生位置::単独クリップ再生)
            }
            再生位置::元動画再生(_) => 時刻::作成する(収めた秒).map(再生位置::元動画再生),
        };
        if let Ok(位置) = 新しい位置 {
            self.再生.位置を移す(位置);
        }
    }

    /// 選んだクリップへ再生位置を合わせる。単独クリップ再生はその区間の先頭から再生し(移植元と同じ)、
    /// シーケンス再生で止めている間はそのクリップの開始へ移す(プレビューの絵を選んだクリップのコマにするため)。
    /// シーケンス再生の再生中は再生位置に付いていくので動かさない。元動画再生はクリップに属さないので動かさない。
    pub(crate) fn 選んだクリップへ再生位置を合わせる(&mut self) {
        let 開始位置 = self
            .並び
            .選択中のクリップ()
            .and_then(|クリップ| self.並び.クリップの開始位置(クリップ.識別子()));
        let 新しい位置 = match self.再生.位置() {
            再生位置::単独クリップ再生(_) => {
                Some(再生位置::単独クリップ再生(時間の長さ::ゼロ))
            }
            再生位置::シーケンス再生(_) if !self.再生.再生しているか() => {
                開始位置.map(再生位置::シーケンス再生)
            }
            再生位置::シーケンス再生(_) | 再生位置::元動画再生(_) => None,
        };
        if let Some(位置) = 新しい位置 {
            self.再生.位置を移す(位置);
        }
    }

    /// クリップを選び、今の再生モードでそのクリップの先頭へ再生位置を移す。
    pub(super) fn クリップの開始へ移る(&mut self, 識別子: &クリップ識別子) {
        let Some(クリップ) = self.並び.識別子で探す(識別子) else {
            return;
        };
        let 位置 = match self.再生.位置() {
            再生位置::シーケンス再生(今) => 再生位置::シーケンス再生(
                self.並び.クリップの開始位置(識別子).unwrap_or(今),
            ),
            再生位置::単独クリップ再生(_) => {
                再生位置::単独クリップ再生(時間の長さ::ゼロ)
            }
            再生位置::元動画再生(_) => 再生位置::元動画再生(クリップ.区間.開始()),
        };
        self.再生.位置を移す(位置);
        // 注意: 識別子のクリップがあることは上で確かめたので、選択は失敗しない。
        let _ = self.並び.選択する(識別子);
    }
}
