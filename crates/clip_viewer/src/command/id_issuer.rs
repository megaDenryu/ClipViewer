//! 実時間の識別子の発行元。移植元と同じ「mod-<ミリ秒>-<乱数>」の識別子を、今の時刻と疑似乱数から発行する。

use std::time::{SystemTime, UNIX_EPOCH};

use clip_domain::{
    クリップ識別子, クリップ識別子の発行元, スタックの識別子, 発行時刻, 識別子の乱数,
};

/// 実時間の識別子発行元とは、時計を読み、疑似乱数の種を進めて識別子を発行するもののことである。
/// 時計を読む境界はここ1箇所である。疑似乱数は xorshift であり、同じミリ秒の識別子を見分けるためだけに使う。
#[derive(Debug)]
pub(crate) struct 実時間の識別子発行元 {
    乱数の種: u64,
}

impl 実時間の識別子発行元 {
    /// 今の時刻のナノ秒から種を取って作る。種は0にしない(xorshift は0から進まないため)。
    pub(crate) fn 時刻から種を取って作る() -> Self {
        let ナノ秒 = 紀元からの経過().as_nanos();
        let 下位 = u64::try_from(ナノ秒 % (u128::from(u64::MAX) + 1)).unwrap_or(1);
        Self {
            乱数の種: 下位 | 1
        }
    }

    fn 次の乱数(&mut self) -> u32 {
        let mut 値 = self.乱数の種;
        値 ^= 値 << 13;
        値 ^= 値 >> 7;
        値 ^= 値 << 17;
        self.乱数の種 = 値;
        u32::try_from(値 >> 32).unwrap_or(0)
    }
}

impl クリップ識別子の発行元 for 実時間の識別子発行元 {
    fn 新しい識別子を発行する(&mut self) -> クリップ識別子 {
        let (時刻, 乱数) = self.今の時刻と乱数();
        クリップ識別子::時刻と乱数から組み立てる(時刻, 乱数)
    }
}

impl 実時間の識別子発行元 {
    /// 新しいスタックの識別子「stack-<ミリ秒>-<乱数>」を発行する。
    pub(crate) fn 新しいスタックの識別子を発行する(
        &mut self,
    ) -> スタックの識別子 {
        let (時刻, 乱数) = self.今の時刻と乱数();
        スタックの識別子::時刻と乱数から組み立てる(時刻, 乱数)
    }

    fn 今の時刻と乱数(&mut self) -> (発行時刻, 識別子の乱数) {
        let ミリ秒 = u64::try_from(紀元からの経過().as_millis()).unwrap_or(u64::MAX);
        let 乱数 = 識別子の乱数::乱数を畳んで作成する(self.次の乱数());
        (発行時刻::紀元からのミリ秒で作成する(ミリ秒), 乱数)
    }
}

/// 1970年1月1日(協定世界時)からの経過。時計がそれより前を指していれば0とする。
fn 紀元からの経過() -> std::time::Duration {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
}
