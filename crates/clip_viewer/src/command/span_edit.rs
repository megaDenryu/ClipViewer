//! 区間の端の編集。カードの秒の数値入力とずらすボタンで区間の開始か終了を動かす。端を収める規則は
//! `clip_domain` の `区間の編集の決まり` が持ち、カードの区間の帯(`band_ops.rs`)も同じ決まりを使う。

use clip_domain::{動画上の区間, 区間の編集の決まり, 時間の長さ};

use crate::state::アプリの状態;

/// 区間の開始と終了の間に必ず空ける秒数(移植元と同じ0.05秒)。
const 最小の区間の長さ: 時間の長さ = 時間の長さ::定数の秒数から作る(0.05);

/// ずらすボタンが動かす秒数(移植元の -0.5s / +0.5s)。
const 半秒: f64 = 0.5;

/// 区間の端とは、区間の開始と終了のどちらを動かすかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 区間の端 {
    開始,
    終了,
}

/// 端のずらし方とは、区間の端をずらすボタンの量と向きの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 端のずらし方 {
    半秒戻す,
    半秒進める,
    一コマ戻す,
    一コマ進める,
}

/// 編集の範囲とは、区間の端を動かすときの決まりと、1コマの長さの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 編集の範囲 {
    pub(crate) 決まり: 区間の編集の決まり,
    pub(crate) 一コマの長さ: 時間の長さ,
}

impl 区間の端 {
    /// 端を秒の位置へ動かした区間。
    pub(crate) fn 決めた区間(
        self,
        区間: 動画上の区間,
        秒: f64,
        範囲: &編集の範囲,
    ) -> 動画上の区間 {
        match self {
            Self::開始 => 範囲.決まり.開始を動かす(区間, 秒),
            Self::終了 => 範囲.決まり.終了を動かす(区間, 秒),
        }
    }

    /// 端をずらした区間。
    pub(crate) fn ずらした区間(
        self,
        区間: 動画上の区間,
        ずらし方: 端のずらし方,
        範囲: &編集の範囲,
    ) -> 動画上の区間 {
        let 今の秒 = match self {
            Self::開始 => 区間.開始().秒数(),
            Self::終了 => 区間.終了().秒数(),
        };
        let 一コマ = 範囲.一コマの長さ.秒数();
        let 秒 = match ずらし方 {
            端のずらし方::半秒戻す => 今の秒 - 半秒,
            端のずらし方::半秒進める => 今の秒 + 半秒,
            端のずらし方::一コマ戻す => 今の秒 - 一コマ,
            端のずらし方::一コマ進める => 今の秒 + 一コマ,
        };
        self.決めた区間(区間, 秒, 範囲)
    }
}

impl アプリの状態 {
    /// 区間を編集するときの範囲。上限は区間の上限(動画があればその長さ、無ければ区間の終了。どちらも1秒以上)である。
    pub(super) fn 編集の範囲(&self, 区間: &動画上の区間) -> 編集の範囲 {
        編集の範囲 {
            決まり: 区間の編集の決まり::作成する(
                self.区間の上限(区間),
                最小の区間の長さ,
            ),
            一コマの長さ: self.一コマの長さ(),
        }
    }
}
