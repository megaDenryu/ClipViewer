//! 今の動画で新しいスタックを始める。動画は開いたまま、今のスタックを捨て、最初のクリップ「Clip Mod 1」だけの未登録のスタックで始める。
//! 今のスタックとの関係を終える操作であるため、動画の解除と同じく失われる変更を確かめてから行う(`relation_end.rs`)。
//! 参照: _doc/設計/画面.md 判断14・_doc/設計/ライブラリ.md 判断5

use super::applier::操作の適用係;
use super::clip_add::動画が無いときの知らせ;
use crate::state::library::関係を終える操作;
use crate::state::{アプリの状態, 並びの出どころ};

impl 操作の適用係 {
    /// 動画を開いていれば、失われる変更が無いことを確かめてから新しいスタックを始める。動画が無ければ確かめる前に知らせて止める
    /// (始められない操作のために確かめるダイアログを出さないため)。
    pub(super) fn 確かめてから今の動画で新しいスタックを始める(
        &mut self,
        状態: &mut アプリの状態,
    ) {
        if 状態.動画.is_none() {
            状態.通知.出す(動画が無いときの知らせ);
            return;
        }
        self.確かめてから関係を終える操作を行う(
            状態,
            関係を終える操作::今の動画で新しいスタックを始める,
        );
    }

    /// 確かめずに新しいスタックを始める。動画の手がかり(期待する動画とパスのメモ)を今の動画に合わせる。読み込んだ JSON が別の動画を
    /// 期待していても、新しい並びは今の動画の並びであり、JSON保存の名前とパスの検証と開き直しを今の動画で行うためである。並びを置き換えるため、開いているスタックとの関係を終え、取り消しの履歴を空にし、再生位置を
    /// 今の再生モードの先頭へ戻す。再生しているか止めているかは変えない。動画が無ければ知らせて何もしない。
    pub(super) fn 今の動画で新しいスタックを始める(
        &mut self,
        状態: &mut アプリの状態,
    ) {
        let Some(動画のパス) = 状態.動画.as_ref().map(|動画| 動画.情報().パス().clone())
        else {
            状態.通知.出す(動画が無いときの知らせ);
            return;
        };
        状態.手がかり.開いた動画に合わせる(&動画のパス);
        let 並び = self.最初のクリップだけの並び(状態);
        状態.並びを置き換える(並び, 並びの出どころ::新しく作った);
        状態.通知.出す("新しいスタックを始めました");
    }
}
