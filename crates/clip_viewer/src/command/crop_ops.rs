//! クロップ枠の操作。プレビューの範囲枠のドラッグを、選択中のクリップのクロップ範囲へ適用する。
//! 枠の新しい値は、掴み始めのクロップ範囲へ開始点からの累積の移動量を当てて毎回計算する。掴む所は映す矩形の枠と共有する `clip_domain` の `枠の掴む所` である。

use clip_domain::{クロップの移動量, 枠の掴む所};

use crate::state::{アプリの状態, クロップ枠の掴み始め};

/// クロップ枠の操作とは、範囲枠のドラッグの段階ごとの操作の区別のことである。移動量は百分率へ直してある。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum クロップ枠の操作 {
    掴み始めた,
    動かしている {
        掴む所: 枠の掴む所,
        移動量: クロップの移動量,
    },
    放した {
        掴む所: 枠の掴む所,
        移動量: クロップの移動量,
    },
    移動量が数でない,
}

impl アプリの状態 {
    pub(crate) fn クロップ枠の操作を適用する(
        &mut self, 操作: クロップ枠の操作
    ) {
        match 操作 {
            クロップ枠の操作::掴み始めた => {
                self.掴み始め =
                    self.並び
                        .選択中のクリップ()
                        .map(|クリップ| クロップ枠の掴み始め {
                            対象: クリップ.識別子().clone(),
                            クロップ: クリップ.クロップ,
                        });
            }
            クロップ枠の操作::動かしている {
                掴む所, 移動量
            } => self.クロップ枠を動かす(掴む所, 移動量),
            クロップ枠の操作::放した {
                掴む所, 移動量
            } => {
                self.クロップ枠を動かす(掴む所, 移動量);
                self.掴み始め = None;
            }
            クロップ枠の操作::移動量が数でない => {
                self.通知
                    .出す("クロップ枠の移動量が数でない(到達したらバグ)");
            }
        }
    }

    fn クロップ枠を動かす(
        &mut self, 掴む所: 枠の掴む所, 移動量: クロップの移動量
    ) {
        let Some(始め) = &self.掴み始め else {
            return;
        };
        let Some(mut クリップ) = self.並び.識別子で探す(&始め.対象).cloned() else {
            return;
        };
        クリップ.クロップ = match 掴む所 {
            枠の掴む所::内側 => 始め.クロップ.移動する(移動量),
            枠の掴む所::隅(つまみ) => {
                始め.クロップ.つまみで大きさを変える(つまみ, 移動量)
            }
        };
        if let Err(理由) = self.並び.更新する(クリップ) {
            self.通知.出す(理由.to_string());
        }
    }
}
