//! 動画の手がかりの操作。サイドバーのパスのメモの入力を状態へ適用する。

use crate::state::アプリの状態;

/// 手がかりの操作とは、動画の手がかりの欄が発する操作の区別のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 手がかりの操作 {
    パスのメモを書き換える(String),
}

impl アプリの状態 {
    pub(crate) fn 手がかりの操作を適用する(&mut self, 操作: 手がかりの操作) {
        match 操作 {
            手がかりの操作::パスのメモを書き換える(入力) => {
                self.手がかり.パスのメモを書き換える(入力)
            }
        }
    }
}
