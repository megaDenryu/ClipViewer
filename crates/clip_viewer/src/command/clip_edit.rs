//! クリップの編集。カードの部品が発する1つの編集を、クリップへ当てた新しいクリップを求める。

use clip_domain::{
    クリップ, クリップ名, トリガー, リピート回数, リピート設定
};

use super::span_edit::{区間の端, 端のずらし方, 編集の範囲};

/// クリップの編集とは、クリップカードの部品が発する、1つのクリップへの編集の区別のことである。秒は部品が渡した値である。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum クリップの編集 {
    有効を切り替える(bool),
    名前を変える(String),
    区間の端を決める(区間の端, f64),
    区間の端をずらす(区間の端, 端のずらし方),
    リピートを増やす,
    リピートを減らす,
    無限ループを切り替える(bool),
    トリガーを選ぶ(トリガー),
}

impl クリップの編集 {
    /// クリップへ編集を当てたクリップ。無限ループのクリップの回数を増減すると、1回から数え直した回数指定にする(移植元と同じ)。
    pub(crate) fn 当てたクリップ(
        self,
        mut クリップ: クリップ,
        範囲: &編集の範囲,
    ) -> クリップ {
        let 今の回数 = match クリップ.リピート {
            リピート設定::回数指定(回数) => 回数,
            リピート設定::無限ループ => リピート回数::一回,
        };
        match self {
            Self::有効を切り替える(有効) => クリップ.有効か = 有効,
            Self::名前を変える(名前) => クリップ.名前 = クリップ名::作成する(名前),
            Self::区間の端を決める(端, 秒) => {
                クリップ.区間 = 端.決めた区間(クリップ.区間, 秒, 範囲)
            }
            Self::区間の端をずらす(端, ずらし方) => {
                クリップ.区間 = 端.ずらした区間(クリップ.区間, ずらし方, 範囲);
            }
            Self::リピートを増やす => {
                クリップ.リピート = リピート設定::回数指定(今の回数.増やす())
            }
            Self::リピートを減らす => {
                クリップ.リピート = リピート設定::回数指定(今の回数.減らす())
            }
            Self::無限ループを切り替える(無限) => {
                クリップ.リピート = if 無限 {
                    リピート設定::無限ループ
                } else {
                    リピート設定::回数指定(リピート回数::一回)
                };
            }
            Self::トリガーを選ぶ(トリガー) => クリップ.トリガー = トリガー,
        }
        クリップ
    }
}
