//! 関係を終える操作を行う。確かめてから行う経路と、確かめるダイアログで利用者が続けると決めたときに確かめずに行う経路がある。
//! どちらも同じ1つの振り分けを通す。参照: _doc/設計/ライブラリ.md 判断5・判断7

use clip_domain::入力された動画パス;

use super::applier::操作の適用係;
use super::video_ops::動画を開いた結果;
use crate::library_common::確かめた結果;
use crate::state::library::{開いたときの添え書き, 関係を終える操作};
use crate::state::アプリの状態;

impl 操作の適用係 {
    /// 失われる変更が無いことを確かめてから行う。あれば確かめるダイアログを出して止める(ダイアログで続けると決めたら `関係を終える操作を行う`)。
    pub(super) fn 確かめてから関係を終える操作を行う(
        &mut self,
        状態: &mut アプリの状態,
        操作: 関係を終える操作,
    ) {
        if 状態.関係を終える前に確かめる(操作.clone()) == 確かめた結果::続けてよい
        {
            self.関係を終える操作を行う(状態, 操作);
        }
    }

    /// 確かめずに行う。開いているスタックとの関係は、操作が成功したときだけ終える(開けなかったときは関係を残す)。
    pub(super) fn 関係を終える操作を行う(
        &mut self,
        状態: &mut アプリの状態,
        操作: 関係を終える操作,
    ) {
        match 操作 {
            関係を終える操作::一覧から開く(識別子) => {
                self.ライブラリのスタックを開く(状態, &識別子)
            }
            関係を終える操作::動画を開く(入力, 添え書き) => {
                self.動画を開いて添え書きする(状態, &入力, 添え書き)
            }
            関係を終える操作::動画を解除する => 状態.動画を解除する(),
            関係を終える操作::今の動画で新しいスタックを始める => {
                self.今の動画で新しいスタックを始める(状態)
            }
            関係を終える操作::設定を当てる(設定) => 状態.設定を当てる(設定),
            関係を終える操作::アプリを閉じる => {
                状態.ライブラリ.閉じる決め.閉じてよいと決める()
            }
        }
    }

    /// 動画を開き、開けたときだけ添え書きを開いた結果の通知へ書き足す。
    fn 動画を開いて添え書きする(
        &mut self,
        状態: &mut アプリの状態,
        入力: &入力された動画パス,
        添え書き: 開いたときの添え書き,
    ) {
        let 前の回 = 状態.通知.最新().map(|(回, _)| 回);
        let 結果 = self.動画を開く(状態, 入力);
        if let (動画を開いた結果::開いた, 開いたときの添え書き::書き足す(文)) = (結果, 添え書き)
        {
            状態.通知.この回の後に書き足す(前の回, vec![文]);
        }
    }
}
