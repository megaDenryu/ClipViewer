//! 区間の帯のドラッグの結末を状態へ当てる。帯を放したときに、区間か再生位置を決め、掴む前に再生していたなら再生を戻す。
//! 応答を適用した後の安全網(主ボタンの様子を受け取り、放したを受け取れずに残った区間の帯とクロップ枠のドラッグを捨て、再生を戻す)も置く。
//! 参照: _doc/設計/画面.md 判断11「操作契約」

use clip_domain::{クリップ識別子, 動画上の区間, 動画上の秒};

use super::position_target::位置の印の行き先;
use crate::primary_button::主ボタンの様子;
use crate::state::{アプリの状態, 区間の帯のドラッグの結末};

impl アプリの状態 {
    /// 応答を適用した後に呼ぶ安全網。主ボタンを押していないのにドラッグが残っていたら(放したを受け取る前に部品が描かれなくなった等)、
    /// 区間の帯のドラッグは仮の値を決めずに捨て、掴む前に再生していたなら再生を戻す。時計が止まったまま・プレビューが固定されたままになるのを防ぐ。
    /// クロップ枠のドラッグは、動かした値を並びへ当て終えているので、掴み始めだけを忘れる(残ると編集の履歴へ積めず、取り消しも止まる)。
    /// 取り消しのまとめも区切る(数値入力の区切りの応答が届かなかったときの備え。ドラッグの間は主ボタンを押しているので区切らない)。
    /// 放したフレームでは、放したの適用でドラッグが無くなっているので何もしない。
    pub(crate) fn 取り残されたドラッグを捨てる(
        &mut self, 主ボタン: 主ボタンの様子
    ) {
        if 主ボタン == 主ボタンの様子::押している {
            return;
        }
        self.掴み始め = None;
        self.履歴.操作の区切りを覚える();
        if let Some(ドラッグ) = self.区間の帯のドラッグ.take()
            && ドラッグ.掴む前に再生していたか()
        {
            self.再生.再生を始める();
        }
    }

    /// 区間か再生位置を決め、掴む前に再生していたなら再生を戻す。区間が変わったときは再生位置をそのクリップの開始へ移す。
    pub(super) fn 区間の帯を放す(&mut self) {
        let Some(ドラッグ) = self.区間の帯のドラッグ.take() else {
            return;
        };
        let 識別子 = ドラッグ.クリップ().clone();
        let 再生していたか = ドラッグ.掴む前に再生していたか();
        match ドラッグ.放す() {
            区間の帯のドラッグの結末::区間を決める(区間) => {
                self.区間の帯で決めた区間を当てる(&識別子, 区間)
            }
            区間の帯のドラッグの結末::位置を決める(位置) => {
                self.区間の帯で決めた位置へ移す(&識別子, 位置)
            }
            区間の帯のドラッグの結末::何も決めない => {}
        }
        if 再生していたか {
            self.再生.再生を始める();
        }
    }

    fn 区間の帯で決めた区間を当てる(
        &mut self,
        識別子: &クリップ識別子,
        区間: 動画上の区間,
    ) {
        let Some(mut クリップ) = self.並び.識別子で探す(識別子).cloned() else {
            return;
        };
        クリップ.区間 = 区間;
        match self.並び.更新する(クリップ) {
            Ok(()) => self.クリップの開始へ移る(識別子),
            Err(理由) => self.通知.出す(理由.to_string()),
        }
    }

    fn 区間の帯で決めた位置へ移す(
        &mut self,
        識別子: &クリップ識別子,
        位置: 動画上の秒,
    ) {
        let Some(クリップ) = self.並び.識別子で探す(識別子) else {
            return;
        };
        match self.位置の印の行き先(クリップ, 位置.秒数()) {
            位置の印の行き先::移れる { 再生位置, .. } => {
                self.再生.位置を移す(再生位置)
            }
            位置の印の行き先::移れない { .. } => self
                .通知
                .出す("無効か長さ0のクリップの中へは、シーケンス再生では移れない"),
        }
    }
}
