//! 1つのクリップのプレビュー。カードの「このクリップを再生」で、単独クリップ再生に切り替えてそのクリップを開始から再生し、
//! そのクリップを単独クリップ再生で再生している間に押すと止める。参照: _doc/設計/画面.md 判断11「1つのクリップのプレビュー」

use clip_domain::{クリップ識別子, 再生位置, 時間の長さ};

use crate::state::アプリの状態;

impl アプリの状態 {
    /// 単独再生を切り替える。止めるときは再生モードと位置を変えない。動画が無ければ再生せずに知らせる。
    pub(super) fn 単独再生を切り替える(&mut self, 識別子: &クリップ識別子) {
        if self.単独で再生しているか(識別子) {
            self.再生.止める();
            return;
        }
        if self.動画.is_none() {
            self.通知.出す("先に動画ファイルをロードしてください");
            return;
        }
        if self.並び.選択する(識別子).is_err() {
            return;
        }
        self.再生
            .位置を移す(再生位置::単独クリップ再生(時間の長さ::ゼロ));
        self.再生.再生を始める();
    }
}
