//! 時間の軸で再生の位置を動かしたときの絵の結合試験。同じ行で隙間なく続く2つの置いたクリップの前の方を映しているときに、位置を後ろの置いたクリップの中へ動かすと、
//! 後ろの置いたクリップのコマが載るまでその行を描かない(前の置いたクリップの最後のコマを、前の置いたクリップの場所に描き続けない)ことを、作業場の口から確かめる。
//! 位置を動かす操作が全部の行の続く先を止まるにしなければ、前の置いたクリップの続く先が後ろの置いたクリップのままであり、この試験は落ちる(同時再生.md 5-2 の7)。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{正規化した動画パス, 重ね合わせ上の秒, 音量};
use video_source::動画の読み手;

use super::command::タイムラインの操作;
use super::sound_test_support::装置の無い作業場を作る;
use super::test_support::{置き方, 置き方を並べた重ね合わせ};
use super::timeline_test_support::タイムラインの操作を当てる;
use super::workspace::重ね合わせの作業場;
use crate::video_feed::with_ffmpeg_support::{
    実行ファイルを探す, 成り立つまで待つ, 試験動画を作る,
};

/// 試験動画のファイル。落とすとファイルを消す。
struct 試験動画のファイル(正規化した動画パス);

impl Drop for 試験動画のファイル {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(self.0.文字列());
    }
}

fn 描く行の数(作業場: &重ね合わせの作業場) -> usize {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ねる画面に描く行の並び()
        .len()
}

fn 進めて描く行の数(作業場: &mut 重ね合わせの作業場) -> usize {
    作業場.フレームを進める(Instant::now(), 音量::起動したときの音量);
    描く行の数(作業場)
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 位置を動かすと_前の置いたクリップのコマを後ろの置いたクリップの代わりに描かない() {
    let 実行ファイル = 実行ファイルを探す();
    let ファイル = 試験動画のファイル(試験動画を作る(&実行ファイル, "位置を動かす"));
    let 重ね合わせ = 置き方を並べた重ね合わせ(
        ファイル.0.clone(),
        4.0,
        &[&[
            置き方 {
                動画上の区間の開始: 0.5,
                動画上の区間の終了: 1.5,
                始まり: 0.0,
            },
            置き方 {
                動画上の区間の開始: 2.0,
                動画上の区間の終了: 3.0,
                始まり: 1.0,
            },
        ]],
    );
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.重ね合わせを開く(重ね合わせ, Some(&動画の読み手::作成する(実行ファイル)));
    成り立つまで待つ(
        "0秒の置いたクリップのコマが載ること",
        || 進めて描く行の数(&mut 作業場) == 1,
    );
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::位置を動かす(
            重ね合わせ上の秒::作成する(1.5).expect("時刻"),
        ),
    );
    assert_eq!(
        描く行の数(&作業場),
        0,
        "動かした先の置いたクリップのコマが載るまで、前の置いたクリップのコマを描かない"
    );
    成り立つまで待つ(
        "動かした先の置いたクリップのコマが載って描くこと",
        || 進めて描く行の数(&mut 作業場) == 1,
    );
}
