//! 開いている重ね合わせ。重ね合わせと、その再生の状況と、映像の様子を持ち、長さが0秒の重ね合わせは再生を始めない。

use std::time::Instant;

use clip_domain::{
    時刻, 重ね合わせ, 重ね合わせの再生位置, 重ね合わせ上の秒
};

use super::playback::重ね合わせの再生の状況;
use crate::overlay::feed::重ね合わせの映像の様子;
use crate::stream_rules::流し読みの開き直し;

/// 開いている重ね合わせとは、重ね合わせの作業場が開いている重ね合わせと、その再生の状況と、その映像の様子の組のことである。
/// 映像の様子は重ね合わせを開くときに作り、重ね合わせと一緒に捨てる。
pub(crate) struct 開いている重ね合わせ {
    重ね合わせ: 重ね合わせ,
    再生: 重ね合わせの再生の状況,
    映像: 重ね合わせの映像の様子,
}

impl 開いている重ね合わせ {
    pub(crate) fn 先頭で止まって開く(
        重ね合わせ: 重ね合わせ,
        映像: 重ね合わせの映像の様子,
    ) -> Self {
        Self {
            重ね合わせ,
            再生: 重ね合わせの再生の状況::起動時(),
            映像,
        }
    }

    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "第8段階で重ねる画面に行を描くときに読む。それまでは試験からだけ読む(同時再生.md 6節)"
        )
    )]
    pub(crate) fn 映像(&self) -> &重ね合わせの映像の様子 {
        &self.映像
    }

    /// 再生の位置に行ごとに映すコマを載せる。重ね合わせの作業場は再生位置の帯のドラッグをまだ持たないため、流し読みはいつ開き直してもよい。
    pub(crate) fn 映像を供給する(&mut self, 今: Instant) {
        self.映像.供給する(
            &self.重ね合わせ,
            self.再生.位置().時刻(),
            self.再生.全体の末尾(),
            流し読みの開き直し::してよい,
            今,
        );
    }

    pub(crate) fn 再生しているか(&self) -> bool {
        self.再生.再生しているか()
    }

    pub(crate) fn 再生の位置(&self) -> 重ね合わせの再生位置 {
        self.再生.位置()
    }

    pub(crate) fn 重ね合わせの長さ(&self) -> 重ね合わせ上の秒 {
        self.重ね合わせ.重ね合わせの長さ()
    }

    /// 再生を始められるか。置いたクリップが無い(長さが0秒の)重ね合わせは、映すものが無く時計も0秒に留まるため、再生を始めない。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.重ね合わせの長さ() > 時刻::先頭
    }

    /// 再生と停止を切り替える。再生を始められないときは、止まったままにする。
    pub(crate) fn 再生を切り替える(&mut self) {
        if self.再生しているか() || self.再生を始められるか() {
            self.再生.再生を切り替える(&self.重ね合わせ);
        }
    }

    pub(crate) fn 再生を止める(&mut self) {
        self.再生.止める();
    }

    pub(crate) fn 時計を進める(&mut self, 今: Instant) {
        self.再生.時計を進める(今, &self.重ね合わせ);
    }
}
