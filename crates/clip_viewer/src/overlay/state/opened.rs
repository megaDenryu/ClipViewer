//! 開いている重ね合わせ。重ね合わせと、その再生の状況と、映像の供給を作れたかを持ち、長さが0秒の重ね合わせは再生を始めない。

use std::time::Instant;

use clip_domain::{
    時刻, 重ね合わせ, 重ね合わせの再生位置, 重ね合わせ上の秒
};

use super::playback::重ね合わせの再生の状況;
use crate::overlay::feed::重ね合わせの映像の供給を作れたか;

/// 開いている重ね合わせとは、重ね合わせの作業場が開いている重ね合わせと、その再生の状況と、その映像の供給を作れたかの組のことである。
/// 映像の供給を作れたかは重ね合わせを開くときに求め、重ね合わせと一緒に捨てる。
pub(crate) struct 開いている重ね合わせ {
    重ね合わせ: 重ね合わせ,
    再生: 重ね合わせの再生の状況,
    映像: 重ね合わせの映像の供給を作れたか,
}

impl 開いている重ね合わせ {
    pub(crate) fn 先頭で止まって開く(
        重ね合わせ: 重ね合わせ,
        映像: 重ね合わせの映像の供給を作れたか,
    ) -> Self {
        Self {
            重ね合わせ,
            再生: 重ね合わせの再生の状況::起動時(),
            映像,
        }
    }

    /// 映像の供給を作れたか。試験で、供給を作れたかと行に載ったコマを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 映像の供給を作れたか(
        &self,
    ) -> &重ね合わせの映像の供給を作れたか {
        &self.映像
    }

    /// 再生の位置に行ごとに映すコマを載せる。
    pub(crate) fn 行ごとのコマを載せる(&mut self, 今: Instant) {
        self.映像.行ごとのコマを載せる(
            &self.重ね合わせ,
            self.再生.映すものを求める条件(),
            今,
        );
    }

    pub(crate) fn 再生しているか(&self) -> bool {
        self.再生.再生しているか()
    }

    pub(crate) fn 再生の位置(&self) -> 重ね合わせの再生位置 {
        self.再生.位置()
    }

    pub(crate) fn 重ね合わせの長さ(&self) -> 重ね合わせ上の秒 {
        self.重ね合わせ.重ね合わせの長さ()
    }

    /// 再生を始められるか。置いたクリップが無い(長さが0秒の)重ね合わせは、映すものが無く時計も0秒に留まるため、再生を始めない。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.重ね合わせの長さ() > 時刻::先頭
    }

    /// 再生と停止を切り替える。再生を始められないときは、止まったままにする。
    pub(crate) fn 再生を切り替える(&mut self) {
        if self.再生しているか() || self.再生を始められるか() {
            self.再生.再生を切り替える(&self.重ね合わせ);
        }
    }

    /// 作業場を控える前に呼ぶ。再生を止め、全部の行の流し読みを閉じる。重ね合わせと再生の位置と、行のテクスチャに載せたコマは残す。
    pub(crate) fn 控える前に再生を止めて流し読みを閉じる(&mut self) {
        self.再生.止める();
        self.映像.流し読みを閉じる();
    }

    pub(crate) fn 時計を進める(&mut self, 今: Instant) {
        self.再生.時計を進める(今, &self.重ね合わせ);
    }
}
