//! 開いている重ね合わせ。重ね合わせと、その再生の状況と、映像の供給を作れたかと、置き方の編集を持ち、長さが0秒の重ね合わせは再生を始めない。
//! 置き方の編集の操作は `placement_ops.rs`・`placement_drag.rs`、読む口は `placement_read.rs` に置く。

use std::time::Instant;

use clip_domain::{
    時刻, 重ねる画面の縦横比, 重ね合わせ, 重ね合わせの再生位置, 重ね合わせの進み具合,
    重ね合わせ上の秒,
};

use super::drawn_rows::重ねる画面に描く行;
use super::placement::置き方の編集;
use super::playback::重ね合わせの再生の状況;
use crate::overlay::feed::重ね合わせの映像の供給を作れたか;

/// 開いている重ね合わせとは、重ね合わせの作業場が開いている重ね合わせと、その再生の状況と、その映像の供給を作れたかと、置き方の編集の組のことである。
/// 映像の供給を作れたかは重ね合わせを開くときに求め、重ね合わせと一緒に捨てる。
pub(crate) struct 開いている重ね合わせ {
    pub(super) 重ね合わせ: 重ね合わせ,
    pub(super) 再生: 重ね合わせの再生の状況,
    pub(super) 映像: 重ね合わせの映像の供給を作れたか,
    pub(super) 編集: 置き方の編集,
}

impl 開いている重ね合わせ {
    pub(crate) fn 先頭で止まって開く(
        重ね合わせ: 重ね合わせ,
        映像: 重ね合わせの映像の供給を作れたか,
    ) -> Self {
        Self {
            重ね合わせ,
            再生: 重ね合わせの再生の状況::起動時(),
            映像,
            編集: 置き方の編集::開いた直後(),
        }
    }

    /// 開いている重ね合わせ。画面が置いたクリップの名前と区間を並べるときと、作業場が置くクリップの一覧を作るときに読む。
    pub(crate) fn 重ね合わせ(&self) -> &重ね合わせ {
        &self.重ね合わせ
    }

    /// 映像の供給を作れたか。試験で、供給を作れたかと行に載ったコマを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 映像の供給を作れたか(
        &self,
    ) -> &重ね合わせの映像の供給を作れたか {
        &self.映像
    }

    /// 再生の位置に行ごとに映すコマを載せる。
    pub(crate) fn 行ごとのコマを載せる(&mut self, 今: Instant) {
        self.映像.行ごとのコマを載せる(
            &self.重ね合わせ,
            self.再生.映すものを求める条件(),
            今,
        );
    }

    pub(crate) fn 再生しているか(&self) -> bool {
        self.再生.再生しているか()
    }

    pub(crate) fn 再生の位置(&self) -> 重ね合わせの再生位置 {
        self.再生.位置()
    }

    pub(crate) fn 重ね合わせの長さ(&self) -> 重ね合わせ上の秒 {
        self.重ね合わせ.重ね合わせの長さ()
    }

    /// 再生を始められるか。置いたクリップが無い(長さが0秒の)重ね合わせは、映すものが無く時計も0秒に留まるため、再生を始めない。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.重ね合わせの長さ() > 時刻::先頭
    }

    /// 再生と停止を切り替える。再生を始められないときは、止まったままにする。
    pub(crate) fn 再生を切り替える(&mut self) {
        if self.再生しているか() || self.再生を始められるか() {
            self.再生.再生を切り替える(&self.重ね合わせ);
        }
    }

    /// 作業場を控える前に呼ぶ。再生を止め、全部の行の流し読みを閉じる。重ね合わせと再生の位置と、行のテクスチャに載せたコマは残す。
    pub(crate) fn 控える前に再生を止めて流し読みを閉じる(&mut self) {
        self.再生.止める();
        self.映像.流し読みを閉じる();
    }

    pub(crate) fn 時計を進める(&mut self, 今: Instant) {
        self.再生.時計を進める(今, &self.重ね合わせ);
    }

    pub(crate) fn 全体ループか(&self) -> bool {
        self.再生.全体ループか()
    }

    pub(crate) fn 全体ループを設定する(&mut self, 有効: bool) {
        self.再生.全体ループを設定する(有効);
    }

    pub(crate) fn 重ねる画面の縦横比(&self) -> 重ねる画面の縦横比 {
        self.重ね合わせ.縦横比()
    }

    /// 重ね合わせの長さに対する再生の位置の進み具合。画面の位置の棒が読む。
    pub(crate) fn 進み具合(&self) -> 重ね合わせの進み具合 {
        self.再生.位置().進み具合(&self.重ね合わせ)
    }

    /// 入力が無くても描き直しを続ける必要があるか。再生している間と、映像の供給が区間を溜めているか行のコマを待っている間は進め続ける。
    pub(crate) fn 描き直しを続ける必要があるか(&self) -> bool {
        self.再生しているか() || self.映像.描き直しを続ける必要があるか()
    }

    /// 重ねる画面に描く行を、奥の行から手前の行の順に並べる(`重ねる画面に描く行::並びを求める`)。
    pub(crate) fn 重ねる画面に描く行の並び(&self) -> Vec<重ねる画面に描く行> {
        重ねる画面に描く行::並びを求める(
            &self.重ね合わせ,
            self.再生.映すものを求める条件(),
            &self.映像,
            &self.編集,
        )
    }
}
