//! 重ね合わせの再生の状況。重ね合わせの再生位置と時計の進み方と全体の末尾での振る舞いを持ち、実時間の経過で時計を進める。
//! 時計の規則(末尾で先頭へ戻るか止まるか)は `clip_domain` の `重ね合わせの再生位置` が持ち、ここは実時間の経過を測って渡すだけである。
//! 参照: _doc/設計/同時再生.md 5-2

use std::time::Instant;

use crate::overlay::feed::映すものを求める条件;
use clip_domain::{
    時間の長さ, 末尾での振る舞い, 重ね合わせ, 重ね合わせの再生位置, 重ね合わせの時計を進めた結果,
};

/// 時計の進み方とは、重ね合わせの時計を進めているか止めているかの区別のことである。進めている間は前回に進めた時刻を覚える。
#[derive(Debug, Clone, Copy, PartialEq)]
enum 時計の進み方 {
    止まっている,
    進んでいる { 前回の時刻: Option<Instant> },
}

/// 重ね合わせの再生の状況とは、重ね合わせの再生位置と、時計の進み方と、全体の末尾での振る舞いの組のことである。
/// 重ね合わせの作業場は速度のつまみを持たないため、時計は等倍で進む。
#[derive(Debug, Clone)]
pub(crate) struct 重ね合わせの再生の状況 {
    位置: 重ね合わせの再生位置,
    進み方: 時計の進み方,
    全体の末尾: 末尾での振る舞い,
}

impl 重ね合わせの再生の状況 {
    /// 初めて重ね合わせの作業場へ移ったときの状況。先頭で止まり、全体ループが有効である(スタックの作業場と同じ)。
    pub(crate) fn 起動時() -> Self {
        Self {
            位置: 重ね合わせの再生位置::先頭,
            進み方: 時計の進み方::止まっている,
            全体の末尾: 末尾での振る舞い::先頭へ戻る,
        }
    }

    pub(crate) fn 位置(&self) -> 重ね合わせの再生位置 {
        self.位置
    }

    /// 今の位置の時刻と全体の末尾での振る舞いの組。映像の供給が行ごとに映すものを求めるときに渡す。
    pub(crate) fn 映すものを求める条件(&self) -> 映すものを求める条件 {
        映すものを求める条件 {
            時刻: self.位置.時刻(),
            全体の末尾: self.全体の末尾,
        }
    }

    pub(crate) fn 再生しているか(&self) -> bool {
        matches!(self.進み方, 時計の進み方::進んでいる { .. })
    }

    /// 全体ループか。全体の末尾で先頭へ戻るなら全体ループである。
    pub(crate) fn 全体ループか(&self) -> bool {
        self.全体の末尾 == 末尾での振る舞い::先頭へ戻る
    }

    /// 全体ループを有効か無効にする。有効なら末尾で先頭へ戻り、無効なら末尾で止まる。
    pub(crate) fn 全体ループを設定する(&mut self, 有効: bool) {
        self.全体の末尾 = if 有効 {
            末尾での振る舞い::先頭へ戻る
        } else {
            末尾での振る舞い::止まる
        };
    }

    /// 再生の位置を移す。再生しているかは変えない。行の続く先を止まるにするのは呼び出し側(開いている重ね合わせ)である。
    pub(crate) fn 再生の位置を移す(&mut self, 位置: 重ね合わせの再生位置) {
        self.位置 = 位置;
    }

    pub(crate) fn 止める(&mut self) {
        self.進み方 = 時計の進み方::止まっている;
    }

    /// 再生と停止を切り替える。再生を始めるときに位置が重ね合わせの長さに達していれば、先頭から再生し直す。
    /// 最初のフレームの経過は0秒として数える。
    pub(crate) fn 再生を切り替える(&mut self, 重ね合わせ: &重ね合わせ) {
        if self.再生しているか() {
            self.止める();
            return;
        }
        self.位置 = self.位置.再生を始める位置(重ね合わせ);
        self.進み方 = 時計の進み方::進んでいる {
            前回の時刻: None
        };
    }

    /// 再生している間だけ、前回からの実時間の経過で時計を進める。末尾で止まったら再生を止める。
    pub(crate) fn 時計を進める(&mut self, 今: Instant, 重ね合わせ: &重ね合わせ) {
        let 時計の進み方::進んでいる { 前回の時刻 } = self.進み方 else {
            return;
        };
        self.進み方 = 時計の進み方::進んでいる {
            前回の時刻: Some(今),
        };
        // 注意: Duration は常に有限で非負のため、時間の長さへの変換は失敗しない。
        let 経過 = 前回の時刻.map_or(時間の長さ::ゼロ, |前回| {
            時間の長さ::作成する(今.duration_since(前回).as_secs_f64()).unwrap_or(時間の長さ::ゼロ)
        });
        match self
            .位置
            .実時間の経過で進める(経過, 重ね合わせ, self.全体の末尾)
        {
            重ね合わせの時計を進めた結果::続ける(位置) => self.位置 = 位置,
            重ね合わせの時計を進めた結果::末尾で止まる(位置) => {
                self.位置 = 位置;
                self.止める();
            }
        }
    }
}
