//! 重ね合わせのライブラリの様子。配線(`クリップビューアー`)が持つ裏で動く重ね合わせのライブラリから、重ね合わせの作業場の画面が
//! 書けるか・読み取り専用か・置き場所が無くて使えないかを出し分けるために求める。参照: _doc/設計/同時再生.md 2-7・6節の第16段階

use clip_library::{
    裏で動く重ね合わせのライブラリ, 重ね合わせの書き込みの許し, 重ね合わせの錠を取れない理由,
};

/// 重ね合わせのライブラリの様子とは、重ね合わせのライブラリへ書けるか、`overlays` の錠を取れずに読み取り専用か、
/// アプリのデータの置き場所が無くて使えないかの区別のことである。
#[derive(Debug, Clone, Copy)]
pub(crate) enum 重ね合わせのライブラリの様子<'ライブラリ> {
    書ける,
    読み取り専用(&'ライブラリ 重ね合わせの錠を取れない理由),
    置き場所が無い,
}

impl<'ライブラリ> 重ね合わせのライブラリの様子<'ライブラリ> {
    /// 裏で動く重ね合わせのライブラリ(置き場所が無ければ無い)の書き込みの許しから求める。
    pub(crate) fn 裏で動くライブラリから求める(
        ライブラリ: Option<&'ライブラリ 裏で動く重ね合わせのライブラリ>,
    ) -> Self {
        match ライブラリ.map(裏で動く重ね合わせのライブラリ::許し) {
            None => Self::置き場所が無い,
            Some(重ね合わせの書き込みの許し::書ける(_)) => Self::書ける,
            Some(重ね合わせの書き込みの許し::読むだけ(理由)) => {
                Self::読み取り専用(理由)
            }
        }
    }
}
