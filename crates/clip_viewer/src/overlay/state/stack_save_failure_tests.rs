//! 写したスタックの保存の失敗の試験。新しい失敗だけを知らせの文にし、頼み直した保存の結果を待つ間は覚えた理由を残し、
//! 保存が成功した後の同じ理由の失敗は知らせ直すことを確かめる。

use super::stack_save_failure::{
    写したスタックの保存の失敗, 見たスタックの保存
};

fn 失敗(理由: &str) -> 見たスタックの保存 {
    見たスタックの保存::失敗した {
        理由: 理由.to_string(),
    }
}

#[test]
fn 新しい失敗だけを知らせ_結果を待つ間は覚えた理由を残し_成功した後の失敗は知らせ直す() {
    let mut 写した = 写したスタックの保存の失敗::default();
    let mut 見る = |見た| 写した.覚えて新しい失敗なら知らせの文を返す(見た);
    assert_eq!(
        見る(失敗("書けない")),
        Some("スタックをライブラリへ保存できない: 書けない".to_string())
    );
    assert_eq!(見る(見たスタックの保存::結果を待っている), None);
    assert_eq!(見る(失敗("書けない")), None, "頼み直して同じ理由で失敗した");
    assert_eq!(
        見る(失敗("別の理由")),
        Some("スタックをライブラリへ保存できない: 別の理由".to_string())
    );
    assert_eq!(見る(見たスタックの保存::失敗していない), None);
    assert_eq!(
        見る(失敗("別の理由")),
        Some("スタックをライブラリへ保存できない: 別の理由".to_string())
    );
}
