//! 知らせ済みのスタックの保存の失敗の試験。新しい失敗だけを知らせの文にし、頼み直した保存の結果を待つ間は覚えた理由を残し、
//! 保存が成功した後の同じ理由の失敗は知らせ直すことを確かめる。

use super::stack_save_failure::{
    スタックの保存の観測結果, 知らせ済みのスタックの保存の失敗
};

fn 失敗(理由: &str) -> スタックの保存の観測結果 {
    スタックの保存の観測結果::失敗した {
        理由: 理由.to_string(),
    }
}

#[test]
fn 新しい失敗だけを知らせ_結果を待つ間は覚えた理由を残し_成功した後の失敗は知らせ直す() {
    let mut 知らせ済み = 知らせ済みのスタックの保存の失敗::default();
    let mut 見る =
        |観測結果| 知らせ済み.覚えて新しい失敗なら知らせの文を返す(観測結果);
    assert_eq!(
        見る(失敗("書けない")),
        Some("スタックをライブラリへ保存できない: 書けない".to_string())
    );
    assert_eq!(見る(スタックの保存の観測結果::結果を待っている), None);
    assert_eq!(見る(失敗("書けない")), None, "頼み直して同じ理由で失敗した");
    assert_eq!(
        見る(失敗("別の理由")),
        Some("スタックをライブラリへ保存できない: 別の理由".to_string())
    );
    assert_eq!(見る(スタックの保存の観測結果::失敗していない), None);
    assert_eq!(
        見る(失敗("別の理由")),
        Some("スタックをライブラリへ保存できない: 別の理由".to_string())
    );
}
