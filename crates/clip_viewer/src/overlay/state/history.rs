//! 重ね合わせの作業場の編集の履歴。重ね合わせ(縦横比・使う動画の表・行の並び。置いたクリップの音の設定を含む)が変わるたびに変わる前の重ね合わせを積み、
//! 取り消しとやり直しで重ね合わせを戻す。積んで戻す仕組みは2つの作業場が共有する取り消しの履歴(`edit_history/`)であり、ここは重ね合わせを積む値にすることと、
//! 続けて変える値(つまみをドラッグしている間の置いたクリップの音量)の区別だけを足す。参照: _doc/設計/同時再生.md 2-6、画面.md 判断14

use clip_domain::{置いたクリップの識別子, 重ね合わせ};

use crate::edit_history::{取り消しの履歴, 履歴に積む値};

/// 重ね合わせの続けて変える値とは、つまみのドラッグのように、1つの操作の間に何度も変わる重ね合わせの中の値の区別のことである。
/// 同じ値の変化が操作の区切り(主ボタンを押していないフレーム)まで続く間は、履歴には1つの変化として積む。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 重ね合わせの続けて変える値 {
    置いたクリップの音量(置いたクリップの識別子),
}

/// 重ね合わせは、値の全部(置いたクリップの音の設定を含む)が等しいときだけ編集として同じである。選んでいるものと掴んでいるものは重ね合わせの外に持つため、比べるものに入らない。
impl 履歴に積む値 for 重ね合わせ {
    fn 編集として同じか(&self, 他: &Self) -> bool {
        self == 他
    }
}

/// 重ね合わせの編集の履歴とは、重ね合わせを積む取り消しの履歴のことである。重ね合わせを開いたとき(並べたとき・ライブラリから開いたとき)に空で始まり、
/// 重ね合わせと一緒に捨てる。登録して未登録から登録済みになっても続く。
pub(crate) type 重ね合わせの編集の履歴 =
    取り消しの履歴<重ね合わせ, 重ね合わせの続けて変える値>;
