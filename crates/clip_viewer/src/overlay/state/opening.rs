//! 重ね合わせの開き方。重ね合わせの作業場が重ね合わせを開いていないか、1つを開いているかを持ち、開いていればそれを貸す。
//! 重ね合わせの作業場の状態が重ね合わせを開くことと閉じることもここに置く。

use clip_domain::重ね合わせ;

use super::library::重ね合わせとライブラリの関係;
use super::opened::開いている重ね合わせ;
use super::sound::開いている重ね合わせの音;
use super::重ね合わせの作業場の状態;
use crate::overlay::feed::{
    重ね合わせの映像の供給を作れたか, 重ね合わせの音の供給
};

/// 重ね合わせの開き方とは、重ね合わせの作業場が重ね合わせを開いていないか、1つを開いているかの区別のことである。
/// 開いていない間は、再生する重ね合わせが無いため再生できない。
#[expect(
    clippy::large_enum_variant,
    reason = "重ね合わせの作業場に1つだけ持ち、重ね合わせを開くときに置き換えるだけなので、選択肢の大きさの差は問題にならない"
)]
pub(crate) enum 重ね合わせの開き方 {
    開いていない,
    開いている(開いている重ね合わせ),
}

impl 重ね合わせの開き方 {
    /// 開いている重ね合わせ。開いていなければ無い。
    pub(crate) fn 開いている重ね合わせ(&self) -> Option<&開いている重ね合わせ> {
        match self {
            Self::開いている(開いている) => Some(開いている),
            Self::開いていない => None,
        }
    }

    /// 書き換えられる開いている重ね合わせ。開いていなければ無い。
    pub(crate) fn 開いている重ね合わせを書き換える(
        &mut self,
    ) -> Option<&mut 開いている重ね合わせ> {
        match self {
            Self::開いている(開いている) => Some(開いている),
            Self::開いていない => None,
        }
    }
}

impl 重ね合わせの作業場の状態 {
    /// 重ね合わせを、その映像の供給を作れたかと音の供給とライブラリとの関係と一緒に開く。先頭で止まった再生の状況で始める。
    /// 映像の供給を作れなかったときと開けなかった動画があるときは、その理由を知らせる。
    pub(crate) fn 重ね合わせを開く(
        &mut self,
        重ね合わせ: 重ね合わせ,
        映像: 重ね合わせの映像の供給を作れたか,
        音: 重ね合わせの音の供給,
        ライブラリとの関係: 重ね合わせとライブラリの関係,
    ) {
        for 文 in 映像.開けなかった知らせの文() {
            self.知らせ.出す(文);
        }
        self.開き方 = 重ね合わせの開き方::開いている(
            開いている重ね合わせ::先頭で止まって開く(
                重ね合わせ,
                映像,
                開いている重ね合わせの音::開く(音),
                ライブラリとの関係,
            ),
        );
    }

    /// 開いている重ね合わせを閉じて、開いていない間へ戻す。重ね合わせと供給を捨て、一覧を読み直す。保存は呼ぶ前に確かめておく。
    pub(crate) fn 重ね合わせを閉じる(&mut self) {
        self.開き方 = 重ね合わせの開き方::開いていない;
        self.ライブラリ.一覧を読み直す();
    }
}
