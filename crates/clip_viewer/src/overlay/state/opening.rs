//! 重ね合わせの開き方。重ね合わせの作業場が重ね合わせを開いていないか、1つを開いているかを持ち、開いていればそれを貸す。

use super::opened::開いている重ね合わせ;

/// 重ね合わせの開き方とは、重ね合わせの作業場が重ね合わせを開いていないか、1つを開いているかの区別のことである。
/// 開いていない間は、再生する重ね合わせが無いため再生できない。
#[expect(
    clippy::large_enum_variant,
    reason = "重ね合わせの作業場に1つだけ持ち、重ね合わせを開くときに置き換えるだけなので、選択肢の大きさの差は問題にならない"
)]
pub(crate) enum 重ね合わせの開き方 {
    開いていない,
    開いている(開いている重ね合わせ),
}

impl 重ね合わせの開き方 {
    /// 開いている重ね合わせ。開いていなければ無い。
    pub(crate) fn 開いている重ね合わせ(&self) -> Option<&開いている重ね合わせ> {
        match self {
            Self::開いている(開いている) => Some(開いている),
            Self::開いていない => None,
        }
    }

    /// 書き換えられる開いている重ね合わせ。開いていなければ無い。
    pub(crate) fn 開いている重ね合わせを書き換える(
        &mut self,
    ) -> Option<&mut 開いている重ね合わせ> {
        match self {
            Self::開いている(開いている) => Some(開いている),
            Self::開いていない => None,
        }
    }
}
