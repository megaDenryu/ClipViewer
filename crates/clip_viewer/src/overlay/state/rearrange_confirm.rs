//! 並べ直す前の確かめ。置き方を手で直した重ね合わせを「今のスタックから並べ直す」で捨てる前に、確かめるダイアログを出しているかを持つ。
//! 参照: _doc/設計/同時再生.md 2-2

use super::重ね合わせの作業場の状態;

/// 並べ直す前の確かめとは、手で直した置き方が並べ直しで失われることを確かめるダイアログを、出しているかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 並べ直す前の確かめ {
    出していない,
    出している,
}

impl 重ね合わせの作業場の状態 {
    /// 並べ直す前の確かめのダイアログを出す。重ね合わせを開いていないときは出さない。
    pub(crate) fn 並べ直す前の確かめを出す(&mut self) {
        if self.開いている重ね合わせ().is_some() {
            self.並べ直す前の確かめ = 並べ直す前の確かめ::出している;
        }
    }

    /// 並べ直す前の確かめのダイアログを閉じる。「やめる」と、並べ直しを当てたとき(並べられなかったときを含む)に呼ぶ。
    pub(crate) fn 並べ直す前の確かめを閉じる(&mut self) {
        self.並べ直す前の確かめ = 並べ直す前の確かめ::出していない;
    }

    /// 並べ直す前の確かめのダイアログを出しているか。
    pub(crate) fn 並べ直す前の確かめを出しているか(&self) -> bool {
        self.並べ直す前の確かめ == 並べ直す前の確かめ::出している
    }
}
