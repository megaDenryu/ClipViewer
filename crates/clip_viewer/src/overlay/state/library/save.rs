//! 重ね合わせの自動保存。登録済みの重ね合わせが変わって落ち着いたら保存を頼み、失敗したら間隔を置いて頼み直す。
//! 作業場を控えるときとアプリを落とすときは、落ち着くのを待たずに書けていない重ね合わせの保存を頼む。参照: _doc/設計/同時再生.md 2-7、_doc/設計/ライブラリ.md 判断5
//! 関係と今の重ね合わせの両方を使う手順は、開いている重ね合わせ(`opened/library_relation.rs`)が持つ。関係を終える前の確かめは `check.rs` が行う。

use std::time::Instant;

use crate::overlay::state::重ね合わせの作業場の状態;

impl 重ね合わせの作業場の状態 {
    /// 毎フレーム呼ぶ(作業場を控えている間も)。届いた知らせを当て、登録済みの重ね合わせが落ち着いたか、頼み直すときなら保存を頼む。
    /// 最後に、次に重ね合わせを見るまでの時間を決める(入力が無くてもその時刻に画面を進めるため)。
    pub(crate) fn ライブラリの書き込みを進める(&mut self, 今: Instant) {
        self.ライブラリの知らせを受け取る();
        let 接続 = &mut self.ライブラリ.接続;
        let 次に見るまでの時間 =
            self.開き方
                .開いている重ね合わせを書き換える()
                .and_then(|開いている| {
                    if 開いている.保存を頼むときか(今) {
                        開いている.今の重ね合わせの保存を頼む(接続);
                    }
                    開いている.次に重ね合わせを見るまでの時間(今)
                });
        self.ライブラリ.次に見るまでの時間 = 次に見るまでの時間;
    }

    /// 書けていない重ね合わせがあれば、落ち着くのを待たずに保存を頼む。作業場を控えるときとアプリを落とすときに呼ぶ。
    pub(crate) fn 書けていない重ね合わせの保存を頼む(&mut self) {
        let 接続 = &mut self.ライブラリ.接続;
        if let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
            && 開いている.保存されていないか()
        {
            開いている.今の重ね合わせの保存を頼む(接続);
        }
    }
}
