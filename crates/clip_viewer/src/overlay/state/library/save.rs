//! 重ね合わせの自動保存。登録済みの重ね合わせが変わって落ち着いたら保存を頼み、失敗したら間隔を置いて頼み直す。
//! 作業場を控えるときとアプリを落とすときは、落ち着くのを待たずに書けていない重ね合わせの保存を頼む。参照: _doc/設計/同時再生.md 2-7、_doc/設計/ライブラリ.md 判断5
//! 関係を終える前の確かめは `check.rs` が行う。

use std::time::Instant;

use crate::library_common::save::見た結果;
use crate::overlay::state::opened::開いている重ね合わせ;
use crate::overlay::state::重ね合わせの作業場の状態;

use super::purpose::重ね合わせの保存の目的;
use super::relation::重ね合わせとライブラリの関係;
use super::重ね合わせのライブラリの接続;

impl 重ね合わせの作業場の状態 {
    /// 毎フレーム呼ぶ(作業場を控えている間も)。届いた知らせを当て、登録済みの重ね合わせが落ち着いたか、頼み直すときなら保存を頼む。
    /// 最後に、次に重ね合わせを見るまでの時間を決める(入力が無くてもその時刻に画面を進めるため)。
    pub(crate) fn ライブラリの書き込みを進める(&mut self, 今: Instant) {
        self.ライブラリの知らせを受け取る();
        let 接続 = &mut self.ライブラリ.接続;
        let 次に見るまでの時間 =
            self.開き方
                .開いている重ね合わせを書き換える()
                .and_then(|開いている| {
                    if 開いている.保存を頼むときか(今) {
                        開いている.今の重ね合わせの保存を頼む(接続);
                    }
                    開いている.次に重ね合わせを見るまでの時間(今)
                });
        self.ライブラリ.次に見るまでの時間 = 次に見るまでの時間;
    }

    /// 書けていない重ね合わせがあれば、落ち着くのを待たずに保存を頼む。作業場を控えるときとアプリを落とすときに呼ぶ。
    pub(crate) fn 書けていない重ね合わせの保存を頼む(&mut self) {
        let 接続 = &mut self.ライブラリ.接続;
        if let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
            && 開いている.保存されていないか()
        {
            開いている.今の重ね合わせの保存を頼む(接続);
        }
    }
}

impl 開いている重ね合わせ {
    /// 登録済みなら今の重ね合わせを見て、保存を頼むときか。未登録なら保存しない。
    fn 保存を頼むときか(&mut self, 今: Instant) -> bool {
        let (関係, 重ね合わせ) = self.ライブラリとの関係と重ね合わせ();
        match 関係 {
            重ね合わせとライブラリの関係::登録済み(登録済み) => {
                登録済み.並びを見る(重ね合わせ, 今) == 見た結果::保存する
            }
            重ね合わせとライブラリの関係::未登録 => false,
        }
    }

    /// 登録済みで、今の重ね合わせがファイルに書けていないか。未登録なら書くものが無い。
    pub(super) fn 保存されていないか(&self) -> bool {
        match self.ライブラリとの関係() {
            重ね合わせとライブラリの関係::登録済み(登録済み) => {
                登録済み.保存の様子().保存されていないか(self.重ね合わせ())
            }
            重ね合わせとライブラリの関係::未登録 => false,
        }
    }

    /// 登録済みなら、今の重ね合わせで中身を差し替えて保存を頼む。頼めなければ失敗として覚え、間隔を置いて頼み直す。
    pub(super) fn 今の重ね合わせの保存を頼む(
        &mut self,
        接続: &mut 重ね合わせのライブラリの接続,
    ) {
        let 今の日時 = 接続.今の日時();
        let (関係, 重ね合わせ) = self.ライブラリとの関係と重ね合わせ();
        let 重ね合わせとライブラリの関係::登録済み(登録済み) = 関係 else {
            return;
        };
        let 中身 = 登録済み
            .中身()
            .clone()
            .重ね合わせを差し替えた(重ね合わせ.clone(), 今の日時);
        match 接続.保存を頼む(中身.clone(), 重ね合わせの保存の目的::自動保存)
        {
            Ok(番号) => 登録済み.保存を頼んだ(中身, 番号),
            Err(理由) => 登録済み.保存を頼めなかった(理由),
        }
    }

    /// 次に重ね合わせを見て保存を頼むかもしれない時刻までの残り。未登録なら無い。
    fn 次に重ね合わせを見るまでの時間(
        &self,
        今: Instant,
    ) -> Option<std::time::Duration> {
        match self.ライブラリとの関係() {
            重ね合わせとライブラリの関係::登録済み(登録済み) => {
                登録済み.次に並びを見るまでの時間(今)
            }
            重ね合わせとライブラリの関係::未登録 => None,
        }
    }
}
