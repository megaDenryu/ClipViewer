//! 重ね合わせのライブラリの状態を画面が読むこと。ライブラリの使える様子・ダイアログ・一覧・サムネイルの項目の表と、控えている間の描き直すまでの時間は
//! 重ね合わせのライブラリの状態のメソッドにし、開いている重ね合わせを読むもの(登録の様子・一覧を見せている間の描き直すまでの時間)を作業場の状態に置く。

use std::time::Duration;

use clip_domain::{
    ライブラリの重ね合わせ, 重ね合わせの名前, 重ね合わせの識別子
};
use clip_library::{重ね合わせのライブラリの操作エラー, 重ね合わせの一覧};

use crate::library_common::list::並べた一覧;
use crate::library_common::save::保存の段階;
use crate::overlay::state::重ね合わせの作業場の状態;
use crate::redraw_interval::{サムネイルの返事を待つ間隔, 描き直しの間隔};
use crate::thumbnail_feed::サムネイルの項目の表;

use super::dialog::重ね合わせのダイアログ;
use super::relation::重ね合わせとライブラリの関係;
