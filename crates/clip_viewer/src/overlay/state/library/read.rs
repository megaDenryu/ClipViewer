/// 開いている重ね合わせのライブラリの様子とは、開いている重ね合わせが未登録か、登録済みならその名前と今の重ね合わせでの保存の段階かの区別のことである。ヘッダーに出す。
pub(crate) enum 開いている重ね合わせのライブラリの様子<'状態> {
    未登録,
    登録済み {
        名前: &'状態 重ね合わせの名前,
        段階: 保存の段階<'状態, 重ね合わせのライブラリの操作エラー>,
    },
}

impl 重ね合わせのライブラリの状態 {
    pub(crate) fn 使える様子(
        &self,
    ) -> 重ね合わせのライブラリの使える様子<'_> {
        self.接続.使える様子()
    }

    /// 重ね合わせのライブラリへ書けるか。
    pub(crate) fn 書けるか(&self) -> bool {
        self.接続.書けるか()
    }

    /// 頼んだ書き込みを終えてから、識別子の重ね合わせを読む。一覧から開くときに画面のスレッドで読む(ライブラリ.md 判断6)。
    pub(crate) fn 書き込みを終えてから重ね合わせを読む(
        &self,
        識別子: &重ね合わせの識別子,
    ) -> Result<ライブラリの重ね合わせ, String> {
        self.接続.書き込みを終えてから読む(識別子)
    }

    pub(crate) fn ダイアログ(&self) -> &重ね合わせのダイアログ {
        &self.ダイアログ
    }

    pub(crate) fn 一覧(&self) -> &並べた一覧<重ね合わせの一覧> {
        &self.一覧
    }

    /// 一覧のサムネイルの項目の表。見えている行を組む閉包へ持ち込む。
    pub(crate) fn サムネイルの項目の表(
        &self,
    ) -> サムネイルの項目の表<重ね合わせの識別子> {
        self.サムネイル.項目の表()
    }

    /// 作業場を控えている間も、ライブラリの書き込みとサムネイルの結果の受け取りのために画面を進めるなら、次に描き直すまでの時間。
    /// 裏のスレッドの返事を待っている間は描き直しの間隔で、登録済みの重ね合わせが書けるのを待っている間(落ち着き待ちと頼み直し)は次に見る時刻に合わせて、
    /// サムネイルの返事を待つ間は0.1秒ごとに進める。スタックの作業場が前の間は、スタックの作業場の画面がこの時間でも描き直しを予約する。
    pub(crate) fn 控えている間に描き直すまでの時間(&self) -> Option<Duration> {
        if self.接続.返事を待っているか() {
            return Some(描き直しの間隔);
        }
        let 見るまで = self.次に見るまでの時間.map(|残り| 残り.max(描き直しの間隔));
        let サムネイル = self
            .サムネイル
            .返事を待っているか()
            .then_some(サムネイルの返事を待つ間隔);
        [見るまで, サムネイル].into_iter().flatten().min()
    }

    /// 次に重ね合わせを見て保存を頼むまでの時間を置く。試験で、保存の頼み直しを待っている様子を作るために使う。
    #[cfg(test)]
    pub(crate) fn 次に見るまでの時間を置く(&mut self, 時間: Duration) {
        self.次に見るまでの時間 = Some(時間);
    }

    /// 頼んだ書き込みと一覧の走査を終えるまで待つ。試験で知らせがそろうのを待つために使う。
    #[cfg(test)]
    pub(crate) fn 書き込みと走査を終えるまで待つ(&self) {
        self.接続.走査も終えるまで待つ();
    }
}

impl 重ね合わせの作業場の状態 {
    /// 重ね合わせのライブラリの状態を読む。画面と試験が読む。
    pub(crate) fn ライブラリ(&self) -> &重ね合わせのライブラリの状態 {
        &self.ライブラリ
    }

    /// 開いている重ね合わせのライブラリの様子。重ね合わせを開いていなければ無い。
    pub(crate) fn 開いている重ね合わせのライブラリの様子(
        &self,
    ) -> Option<開いている重ね合わせのライブラリの様子<'_>> {
        let 開いている = self.開いている重ね合わせ()?;
        Some(match 開いている.ライブラリとの関係() {
            重ね合わせとライブラリの関係::未登録 => {
                開いている重ね合わせのライブラリの様子::未登録
            }
            重ね合わせとライブラリの関係::登録済み(登録済み) => {
                開いている重ね合わせのライブラリの様子::登録済み {
                    名前: 登録済み.名前(),
                    段階: 登録済み.保存の様子().段階(開いている.重ね合わせ()),
                }
            }
        })
    }

    /// 入力が無くても、ライブラリとサムネイルのために画面を進めるなら、次に描き直すまでの時間。一覧を見せていてキャッシュを見る前の行が残っている間は
    /// 描き直しの間隔で、それ以外は控えている間と同じ規則で進める(スタックの作業場の `view/invisible.rs` と同じ規則)。
    pub(crate) fn ライブラリのために描き直すまでの時間(
        &self,
    ) -> Option<Duration> {
        if self.見せる行にキャッシュを見る前の行があるか() {
            return Some(描き直しの間隔);
        }
        self.ライブラリ.控えている間に描き直すまでの時間()
    }

    /// 一覧を見せていて、見せる行(絞り込みの後の行)にキャッシュを見る前の行が残っているか。
    fn 見せる行にキャッシュを見る前の行があるか(&self) -> bool {
        let 並び = self.ライブラリ.一覧.行の並び(None);
        self.一覧を見せているか()
            && self
                .ライブラリ
                .サムネイル
                .キャッシュを見る前の行があるか(&並び)
    }
}
