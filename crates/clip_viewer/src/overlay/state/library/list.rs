//! 重ね合わせの一覧を読み直すことと、一覧の見せ方を変えることと、一覧のサムネイルを状態の側から動かすこと。
//! 一覧とサムネイルだけに触れる操作は重ね合わせのライブラリの状態のメソッドにし、開いている重ね合わせ(一覧を見せているか)を読むものだけを作業場の状態に置く。
//! 一覧は重ね合わせを開いていない間に出すため、サムネイルの仕事はその間だけ進めさせる。結果はどの間も受け取る。
//! 何をいつ撮るかの判断は共有の `一覧のサムネイル` が持つ。参照: _doc/設計/ライブラリ.md 判断3・判断10・判断11

use video_source::動画の読み手;

use crate::library_common::list::{
    並べ替え方, 最後に読んだ一覧, 絞り込みの語, 見えている行の範囲
};
use crate::library_common::save::ライブラリを使えない理由;
use crate::overlay::state::重ね合わせの作業場の状態;
use crate::thumbnail_feed::撮る手立て;

use super::重ね合わせのライブラリの状態;

impl 重ね合わせのライブラリの状態 {
    /// 一覧を読み直すことを頼む。置き場所が無ければ、ヘッダーの文で知らせているので黙る。
    /// 裏のスレッドが止まっていて頼めなければ、一覧を読めないとして理由を一覧に出す(黙って古い一覧を見せ続けないため)。
    pub(crate) fn 一覧を読み直す(&mut self) {
        match self.接続.一覧を作ることを頼む() {
            Ok(()) | Err(ライブラリを使えない理由::置き場所が無い) => {}
            Err(理由 @ ライブラリを使えない理由::頼めない(_)) => self
                .一覧
                .一覧を置き換える(最後に読んだ一覧::読めない(理由.to_string())),
        }
    }

    pub(crate) fn 絞り込みを変える(&mut self, 文字列: String) {
        self.一覧.絞り込みを変える(絞り込みの語::作成する(文字列));
    }

    pub(crate) fn 並べ替えを変える(&mut self, 並べ替え: 並べ替え方) {
        self.一覧.並べ替えを変える(並べ替え);
    }

    /// 一覧の仮想縦スクロールが描画のたびに発した、見えている行の範囲を置く。次のフレームのサムネイルの仕事が取り出す。
    pub(crate) fn 見えている行を置く(&mut self, 範囲: 見えている行の範囲) {
        self.見えている行 = Some(範囲);
    }

    /// 毎フレーム呼ぶ(作業場を控えている間も)。届いたサムネイルの結果を当てる。
    pub(crate) fn サムネイルの結果を受け取る(&mut self) {
        self.サムネイル.結果を受け取る();
    }
}

impl 重ね合わせの作業場の状態 {
    /// 前に出ている間、毎フレーム呼ぶ。一覧を見せている(重ね合わせを開いていない)なら、前のフレームで見えていた行から先に仕事を進めさせる。
    /// 撮る動画の読み手は、配線がスタックの作業場の動画の開き手から借りる(FFmpeg が見つかっていなければ無い)。
    pub(crate) fn サムネイルの仕事を進める(
        &mut self, 読み手: Option<&動画の読み手>
    ) {
        let 見えている = self.ライブラリ.見えている行.take();
        if !self.一覧を見せているか() {
            return;
        }
        let 手立て = match 読み手 {
            Some(読み手) => 撮る手立て::撮れる(読み手.clone()),
            None => 撮る手立て::FFmpegが無い,
        };
        let ライブラリ = &mut self.ライブラリ;
        let 並び = ライブラリ.一覧.行の並び(見えている);
        ライブラリ.サムネイル.仕事を進める(&並び, &手立て);
    }

    /// 重ね合わせの一覧を見せているか。一覧は重ね合わせを開いていない間に出す。
    pub(crate) fn 一覧を見せているか(&self) -> bool {
        self.開いている重ね合わせ().is_none()
    }
}
