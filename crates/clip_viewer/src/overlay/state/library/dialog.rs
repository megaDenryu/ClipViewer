//! 重ね合わせのダイアログ。名前を付けて登録する・捨てる前に確かめる・保存できないまま続けるかを確かめるダイアログの状態と、
//! 確かめるダイアログが続けると決めたときに行う、重ね合わせとの関係を終える操作を持つ。参照: _doc/設計/同時再生.md 2-2・2-7

use clip_domain::重ね合わせの識別子;

use crate::library_common::save::{入力中の名前, 登録の後にすること};
use crate::library_common::続ける操作を持つダイアログ;

/// 重ね合わせとの関係を終える操作とは、開いている重ね合わせを捨てる(登録済みならライブラリとの関係を終える)操作の区別のことである。
/// 確かめるダイアログが、利用者が続けると決めたときに行う操作として持つ。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 重ね合わせとの関係を終える操作 {
    今のスタックから並べ直す,
    重ね合わせを閉じる,
    一覧から開く(重ね合わせの識別子),
    アプリを閉じる,
}

/// 重ね合わせのダイアログとは、重ね合わせの作業場の画面を覆って開いているダイアログの区別のことである。同時に開くダイアログは1つである。
#[derive(Debug, Clone, Default, PartialEq)]
pub(crate) enum 重ね合わせのダイアログ {
    #[default]
    無し,
    名前を付けて登録(
        入力中の名前,
        登録の後にすること<重ね合わせとの関係を終える操作>,
    ),
    捨てる前の確かめ(重ね合わせとの関係を終える操作),
    保存できずに続ける確認(String, 重ね合わせとの関係を終える操作),
}

impl 続ける操作を持つダイアログ for 重ね合わせのダイアログ {
    type 操作 = 重ね合わせとの関係を終える操作;

    fn 確かめるダイアログを操作へ分ける(
        self,
    ) -> Result<重ね合わせとの関係を終える操作, Self> {
        match self {
            Self::捨てる前の確かめ(操作) | Self::保存できずに続ける確認(_, 操作) => {
                Ok(操作)
            }
            ほかのダイアログ => Err(ほかのダイアログ),
        }
    }

    fn 続ける操作(&self) -> Option<&重ね合わせとの関係を終える操作> {
        match self {
            Self::捨てる前の確かめ(操作)
            | Self::保存できずに続ける確認(_, 操作)
            | Self::名前を付けて登録(_, 登録の後にすること::続ける(操作)) => {
                Some(操作)
            }
            Self::無し | Self::名前を付けて登録(_, 登録の後にすること::何もしない) => {
                None
            }
        }
    }

    fn 名前の入力欄(&mut self) -> Option<&mut 入力中の名前> {
        match self {
            Self::名前を付けて登録(入力, _) => Some(入力),
            Self::無し | Self::捨てる前の確かめ(_) | Self::保存できずに続ける確認(..) => {
                None
            }
        }
    }
}
