//! 重ね合わせとの関係を終える前の確かめ。開いている重ね合わせを捨てる操作(並べ直す・閉じる・一覧から開く・アプリを閉じる)の前に、失われる変更が無いかを確かめる。
//! 登録済みなら、今の重ね合わせがファイルに書けたことを確かめ、書けていなければ保存を頼み直して書き込みを終えるまで待ち、それでも書けなければダイアログを出す。
//! 未登録なら、並べた後に置き方を手で直していればダイアログを出す(自動保存の対象でなく、黙って捨てると失われるため)。
//! 参照: _doc/設計/同時再生.md 2-2・2-7、_doc/設計/ライブラリ.md 判断5

use crate::library_common::save::アプリの閉じ方;
use crate::overlay::state::重ね合わせの作業場の状態;

use super::dialog::{
    重ね合わせとの関係を終える操作, 重ね合わせのダイアログ
};
use super::relation::重ね合わせとライブラリの関係;

/// 確かめた結果とは、関係を終える前に確かめて、操作を続けてよいか、確かめるダイアログを出したので止めるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 確かめた結果 {
    続けてよい,
    確かめるダイアログを出した,
}

impl 重ね合わせの作業場の状態 {
    /// 関係を終える前に、失われる変更が無いことを確かめる。あれば、続ける操作を持った確かめるダイアログを出す。
    pub(crate) fn 関係を終える前に確かめる(
        &mut self,
        続ける操作: 重ね合わせとの関係を終える操作,
    ) -> 確かめた結果 {
        let Some(開いている) = self.開き方.開いている重ね合わせ() else {
            return 確かめた結果::続けてよい;
        };
        let ダイアログ = match 開いている.ライブラリとの関係() {
            重ね合わせとライブラリの関係::未登録 if 開いている.置き方を手で直したか() => {
                重ね合わせのダイアログ::捨てる前の確かめ(続ける操作)
            }
            重ね合わせとライブラリの関係::未登録 => {
                return 確かめた結果::続けてよい;
            }
            重ね合わせとライブラリの関係::登録済み(_) => match self
                .保存を確かめる()
            {
                Ok(()) => return 確かめた結果::続けてよい,
                Err(理由) => 重ね合わせのダイアログ::保存できずに続ける確認(
                    理由,
                    続ける操作,
                ),
            },
        };
        self.ライブラリ.ダイアログ = ダイアログ;
        確かめた結果::確かめるダイアログを出した
    }

    /// 登録済みの重ね合わせがファイルに書けたことを確かめる。書けていなければ保存を頼み直し、書き込みを終えるまで待って知らせを受け取り、もう一度確かめる。
    fn 保存を確かめる(&mut self) -> Result<(), String> {
        if self.書けたことを確かめる().is_ok() {
            return Ok(());
        }
        self.書けていない重ね合わせの保存を頼む();
        self.ライブラリ.接続.書き込みを終えるまで待つ();
        self.ライブラリの知らせを受け取る();
        self.書けたことを確かめる()
    }

    fn 書けたことを確かめる(&self) -> Result<(), String> {
        match self
            .開き方
            .開いている重ね合わせ()
            .map(|開いている| (開いている.ライブラリとの関係(), 開いている.重ね合わせ()))
        {
            Some((重ね合わせとライブラリの関係::登録済み(登録済み), 重ね合わせ)) => {
                登録済み
                    .保存の様子()
                    .書けたことを確かめる(重ね合わせ)
                    .map_err(|理由| 理由.to_string())
            }
            _ => Ok(()),
        }
    }

    /// ウインドウを閉じる要求を受けた。利用者が既に変更を捨てると決めていれば閉じてよい。そうでなければ開いている重ね合わせを確かめ、
    /// 確かめるダイアログを出したら閉じてよくない。
    pub(crate) fn 閉じる要求を確かめる(&mut self) -> 確かめた結果 {
        if self.閉じると決めたか() {
            return 確かめた結果::続けてよい;
        }
        self.関係を終える前に確かめる(重ね合わせとの関係を終える操作::アプリを閉じる)
    }

    /// 利用者が捨てる前の確かめで変更を捨てて閉じると決めた。以後のウインドウを閉じる要求では確かめない。
    pub(crate) fn 変更を捨てて閉じると決める(&mut self) {
        self.ライブラリ.閉じ方 = アプリの閉じ方::確かめずに閉じる;
    }

    /// 利用者が変更を捨てて閉じると決めたか。
    pub(crate) fn 閉じると決めたか(&self) -> bool {
        self.ライブラリ.閉じ方 == アプリの閉じ方::確かめずに閉じる
    }
}
