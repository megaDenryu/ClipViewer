//! 開いている重ね合わせのライブラリの様子。ヘッダーに出す、開いている重ね合わせが未登録か、登録済みならその名前と今の重ね合わせでの保存の段階かを読む。
//! 参照: _doc/設計/同時再生.md 2-3・2-7

use clip_domain::重ね合わせの名前;
use clip_library::重ね合わせのライブラリの操作エラー;

use crate::library_common::save::保存の段階;
use crate::overlay::state::重ね合わせの作業場の状態;

use super::relation::重ね合わせとライブラリの関係;

/// 開いている重ね合わせのライブラリの様子とは、開いている重ね合わせが未登録か、登録済みならその名前と今の重ね合わせでの保存の段階かの区別のことである。ヘッダーに出す。
pub(crate) enum 開いている重ね合わせのライブラリの様子<'状態> {
    未登録,
    登録済み {
        名前: &'状態 重ね合わせの名前,
        段階: 保存の段階<'状態, 重ね合わせのライブラリの操作エラー>,
    },
}

impl 重ね合わせの作業場の状態 {
    /// 開いている重ね合わせのライブラリの様子。重ね合わせを開いていなければ無い。
    pub(crate) fn 開いている重ね合わせのライブラリの様子(
        &self,
    ) -> Option<開いている重ね合わせのライブラリの様子<'_>> {
        let 開いている = self.開いている重ね合わせ()?;
        Some(match 開いている.ライブラリとの関係() {
            重ね合わせとライブラリの関係::未登録 => {
                開いている重ね合わせのライブラリの様子::未登録
            }
            重ね合わせとライブラリの関係::登録済み(登録済み) => {
                開いている重ね合わせのライブラリの様子::登録済み {
                    名前: 登録済み.名前(),
                    段階: 登録済み
                        .保存の様子()
                        .保存の段階を読む(開いている.重ね合わせ()),
                }
            }
        })
    }
}
