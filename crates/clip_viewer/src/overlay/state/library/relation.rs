//! 重ね合わせとライブラリの関係。開いている重ね合わせが、ライブラリに登録していないものか、登録済みの重ね合わせかを持つ。
//! 登録済みの重ね合わせの保存の追跡は、2つの作業場が共有する `library_common::save::登録済みの保存物` が持つ。参照: _doc/設計/同時再生.md 2-7

use clip_domain::{ライブラリの重ね合わせ, 重ね合わせの識別子};

use crate::library_common::save::登録済みの保存物;

/// 登録済みの重ね合わせとは、ライブラリの重ね合わせを保存物にした登録済みの保存物のことである。
pub(crate) type 登録済みの重ね合わせ = 登録済みの保存物<ライブラリの重ね合わせ>;

/// 重ね合わせとライブラリの関係とは、開いている重ね合わせがライブラリに登録していないものか、登録済みの重ね合わせかの区別のことである。
/// 開いている重ね合わせ(`opened/`)が持つ。重ね合わせを開いていない間は関係そのものが無い。
#[derive(Debug, Default)]
#[expect(
    clippy::large_enum_variant,
    reason = "開いている重ね合わせに1つしか持たないため、選択肢の大きさの差は問題にならない"
)]
pub(crate) enum 重ね合わせとライブラリの関係 {
    #[default]
    未登録,
    登録済み(登録済みの重ね合わせ),
}

impl 重ね合わせとライブラリの関係 {
    /// ライブラリのファイルから読んで開いた重ね合わせとの関係。登録済みであり、ファイルにある中身は読んだ重ね合わせである。
    pub(crate) fn ファイルから開いた(
        読んだ: ライブラリの重ね合わせ
    ) -> Self {
        Self::登録済み(登録済みの保存物::ファイルから開いた(
            読んだ,
        ))
    }

    /// 登録済みで、識別子が同じなら、その登録済みの重ね合わせ。
    pub(crate) fn 識別子が同じなら(
        &mut self,
        識別子: &重ね合わせの識別子,
    ) -> Option<&mut 登録済みの重ね合わせ> {
        match self {
            Self::登録済み(登録済み) if 登録済み.識別子() == 識別子 => {
                Some(登録済み)
            }
            _ => None,
        }
    }
}
