//! 重ね合わせのライブラリからの知らせを状態へ当てる。開いている重ね合わせの保存なら保存の様子へ、登録は結果を受けてから知らせ、
//! 一覧を作ったら並べた一覧を置き換えて、一覧のサムネイルへ各重ね合わせの撮り方を知らせる。
//! 開いている重ね合わせの自動保存の失敗は、頼み直すたびに知らせを繰り返さないよう、ヘッダーの保存の段階だけで知らせる。参照: _doc/設計/ライブラリ.md 判断5

use std::rc::Rc;

use clip_domain::重ね合わせの識別子;
use clip_library::{
    保存の番号, 重ね合わせのライブラリからの知らせ, 重ね合わせのライブラリの操作エラー,
};

use crate::library_common::list::最後に読んだ一覧;
use crate::overlay::state::重ね合わせの作業場の状態;

use super::purpose::重ね合わせの保存の目的;

impl 重ね合わせの作業場の状態 {
    /// 届いた知らせをすべて状態へ当てる。
    pub(super) fn ライブラリの知らせを受け取る(&mut self) {
        for 知らせ in self.ライブラリ.接続.届いた知らせを受け取る() {
            match 知らせ {
                重ね合わせのライブラリからの知らせ::保存した(
                    識別子,
                    番号,
                    結果,
                ) => self.保存の知らせを当てる(&識別子, 番号, 結果),
                重ね合わせのライブラリからの知らせ::一覧を作った(
                    Ok(一覧),
                ) => {
                    self.ライブラリ.サムネイル.重ね合わせの一覧を読んだ(&一覧);
                    self.ライブラリ
                        .一覧
                        .一覧を置き換える(最後に読んだ一覧::読めた(Rc::new(一覧)));
                }
                重ね合わせのライブラリからの知らせ::一覧を作った(
                    Err(エラー),
                ) => self
                    .ライブラリ
                    .一覧
                    .一覧を置き換える(最後に読んだ一覧::読めない(エラー.to_string())),
            }
        }
    }

    fn 保存の知らせを当てる(
        &mut self,
        識別子: &重ね合わせの識別子,
        番号: 保存の番号,
        結果: Result<(), 重ね合わせのライブラリの操作エラー>,
    ) {
        let 失敗 = 結果.as_ref().err().map(ToString::to_string);
        let 開いているか =
            match self
                .開き方
                .開いている重ね合わせを書き換える()
                .and_then(|開いている| {
                    開いている
                        .ライブラリとの関係を書き換える()
                        .識別子が同じなら(識別子)
                }) {
                Some(登録済み) => {
                    登録済み.保存を終えた(番号, 結果);
                    true
                }
                None => false,
            };
        match (self.ライブラリ.接続.保存の目的を取り出す(番号), 失敗) {
            (重ね合わせの保存の目的::登録(名前), None) => self
                .知らせ
                .出す(format!("重ね合わせをライブラリに保存しました: {名前}")),
            (重ね合わせの保存の目的::自動保存, None) => {}
            (重ね合わせの保存の目的::自動保存, Some(_)) if 開いているか => {}
            (_, Some(理由)) => self
                .知らせ
                .出す(format!("重ね合わせをライブラリへ保存できない: {理由}")),
        }
    }
}
