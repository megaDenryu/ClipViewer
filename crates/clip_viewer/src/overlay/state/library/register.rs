//! 重ね合わせの最初の登録。開いている重ね合わせに名前を付けて、ライブラリへ登録する。試しに並べただけの重ね合わせが勝手に溜まらないよう、
//! 登録は利用者が名前を付けて決定したときだけ行う(ライブラリ.md 判断5 と同じ)。参照: _doc/設計/同時再生.md 2-7

use clip_domain::{
    ライブラリの重ね合わせ, 重ね合わせの名前, 重ね合わせの識別子
};

use crate::library_common::save::{登録の後にすること, 登録済みの保存物};
use crate::overlay::state::重ね合わせの作業場の状態;

use super::dialog::{
    重ね合わせとの関係を終える操作, 重ね合わせのダイアログ
};
use super::purpose::重ね合わせの保存の目的;
use super::relation::重ね合わせとライブラリの関係;

/// 登録した後に続ける操作。登録を頼めなかったときと、続ける操作が無いときは無い。
type 続ける操作 = Option<重ね合わせとの関係を終える操作>;

impl 重ね合わせの作業場の状態 {
    /// ダイアログの名前で開いている重ね合わせを登録し、ライブラリとの関係を登録済みにする。書き込みは裏のスレッドが行い、保存したことは結果を受けてから知らせる。
    /// 登録の後にすることがあれば、それを返す(呼び手が確かめてから行う。確かめは登録の書き込みを終えるまで待つ)。
    pub(crate) fn ダイアログの名前で登録する(
        &mut self,
        識別子: 重ね合わせの識別子,
    ) -> 続ける操作 {
        let 重ね合わせのダイアログ::名前を付けて登録(入力, 後にすること) =
            &self.ライブラリ.ダイアログ
        else {
            return None;
        };
        let 後にすること = 後にすること.clone();
        let Some(名前) = 入力.名前として読む::<重ね合わせの名前>() else {
            self.知らせ.出す("名前を入力してください");
            return None;
        };
        let 今 = self.ライブラリ.接続.今の日時();
        let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
        else {
            self.知らせ
                .出す("重ね合わせを開いていないため、登録できない");
            return None;
        };
        let 中身 = ライブラリの重ね合わせ::新しく作る(
            識別子,
            名前.clone(),
            開いている.重ね合わせ().clone(),
            今,
        );
        let 目的 = 重ね合わせの保存の目的::登録(名前);
        match self.ライブラリ.接続.保存を頼む(中身.clone(), 目的) {
            Ok(番号) => 開いている.ライブラリとの関係を置き換える(
                重ね合わせとライブラリの関係::登録済み(
                    登録済みの保存物::登録を頼んだ(中身, 番号),
                ),
            ),
            Err(理由) => {
                self.知らせ
                    .出す(format!("重ね合わせをライブラリへ保存できない: {理由}"));
                return None;
            }
        }
        self.ライブラリ.ダイアログ = 重ね合わせのダイアログ::無し;
        self.重ね合わせの一覧を読み直す();
        match 後にすること {
            登録の後にすること::続ける(操作) => Some(操作),
            登録の後にすること::何もしない => None,
        }
    }
}
