//! 名前を付けて登録するダイアログを開くことと、ダイアログを閉じる・入力を書き換える・続ける操作を取り出すこと。開いている重ね合わせが未登録で、重ね合わせのライブラリへ書けるときだけ開き、名前の初期値を決める。
//! 読み取り専用のときは開かずにその旨を知らせる。参照: _doc/設計/同時再生.md 2-7、_doc/設計/ライブラリ.md 判断5・判断9

use crate::library_common::save::{入力中の名前, 登録の後にすること};
use crate::library_common::続ける操作を持つダイアログ;
use crate::overlay::state::重ね合わせの作業場の状態;

use super::dialog::{
    重ね合わせとの関係を終える操作, 重ね合わせのダイアログ
};
use super::relation::重ね合わせとライブラリの関係;
use super::{
    重ね合わせのライブラリの使える様子, 重ね合わせのライブラリの状態
};

/// 名前にできるものが無いときの、登録する名前の初期値。
const 名前の初期値: &str = "重ね合わせ";

impl 重ね合わせの作業場の状態 {
    /// 名前を付けて登録するダイアログを開く。名前の初期値は、使う動画の表の最初の動画のファイル名から拡張子を除いたものである。
    /// 登録の後にすることは、登録を頼めたときに続けて行う(捨てる前に確かめるダイアログから来たとき)。
    pub(crate) fn 登録のダイアログを開く(&mut self) {
        self.登録の後にすることと登録のダイアログを開く(
            登録の後にすること::何もしない,
        );
    }

    pub(crate) fn 登録の後にすることと登録のダイアログを開く(
        &mut self,
        後にすること: 登録の後にすること<重ね合わせとの関係を終える操作>,
    ) {
        let Some(開いている) = self.開いている重ね合わせ() else {
            return self
                .知らせ
                .出す("重ね合わせを開いていないため、登録できない");
        };
        if let 重ね合わせとライブラリの関係::登録済み(_) = 開いている.ライブラリとの関係()
        {
            return self
                .知らせ
                .出す("この重ね合わせは既にライブラリに登録してある");
        }
        if let 重ね合わせのライブラリの使える様子::読むだけ(_, 理由) = self.ライブラリ.使える様子()
        {
            let 文 = format!("重ね合わせのライブラリは読み取り専用である({理由})");
            return self.知らせ.出す(文);
        }
        let 初期値 = 開いている
            .重ね合わせ()
            .動画の表()
            .動画のパスの並び()
            .first()
            .and_then(|パス| パス.ファイル名())
            .map_or(名前の初期値.to_string(), |名前| {
                名前.拡張子を除いた名前().to_string()
            });
        self.ライブラリ.ダイアログ = 重ね合わせのダイアログ::名前を付けて登録(
            入力中の名前::作成する(初期値),
            後にすること,
        );
    }
}

impl 重ね合わせのライブラリの状態 {
    /// 開いているダイアログを閉じる。
    pub(crate) fn ダイアログを閉じる(&mut self) {
        self.ダイアログ = 重ね合わせのダイアログ::無し;
    }

    /// 名前を付けて登録するダイアログなら、その入力を書き換える。
    pub(crate) fn 名前の入力を書き換える(&mut self, 文字列: String) {
        self.ダイアログ.名前の入力を書き換える(文字列);
    }

    /// 確かめるダイアログなら、利用者が続けると決めたときに行う操作を取り出してダイアログを閉じる。
    pub(crate) fn 続ける操作を取り出す(
        &mut self,
    ) -> Option<重ね合わせとの関係を終える操作> {
        self.ダイアログ.続ける操作を取り出す()
    }
}
