/// 重ね合わせのライブラリの接続とは、重ね合わせのライブラリへのライブラリの接続のことである。
pub(crate) type 重ね合わせのライブラリの接続 =
    保存物のライブラリの接続<重ね合わせのライブラリ, 重ね合わせの保存の目的>;

/// 重ね合わせのライブラリの使える様子とは、重ね合わせのライブラリへ書けるか、`overlays` の錠を取れずに読むだけか、置き場所が無くて使えないかの区別のことである。
pub(crate) type 重ね合わせのライブラリの使える様子<'接続> =
    保存物のライブラリの使える様子<'接続, 重ね合わせのライブラリ>;

/// 重ね合わせのライブラリの状態とは、重ね合わせのライブラリの接続と、並べた重ね合わせの一覧と、開いているダイアログと、アプリを閉じてよいとの決めと、
/// 次に重ね合わせを見て保存を頼むまでの時間と、一覧のサムネイルと、前のフレームで一覧に見えていた行の組のことである。
/// 項目どうしに不変条件は無く、各項目の型がそれぞれの不変条件を持つ。
pub(crate) struct 重ね合わせのライブラリの状態 {
    pub(super) 接続: 重ね合わせのライブラリの接続,
    pub(super) 一覧: 並べた一覧<重ね合わせの一覧>,
    pub(super) ダイアログ: 重ね合わせのダイアログ,
    pub(super) 閉じる決め: アプリを閉じてよいとの決め,
    pub(super) 次に見るまでの時間: Option<Duration>,
    pub(super) サムネイル: 一覧のサムネイル<重ね合わせの識別子>,
    pub(super) 見えている行: Option<見えている行の範囲>,
}

impl 重ね合わせのライブラリの状態 {
    /// 裏で動く重ね合わせのライブラリ(置き場所が無ければ無い)と、サムネイルを置くキャッシュから作る。
    /// キャッシュはスタックの一覧のサムネイルと同じ値から複製したものを受け取る(同じプロセスの書き込みを錠で1つずつ行うため。ライブラリ.md 判断11)。
    pub(crate) fn 作成する(
        ライブラリ: Option<裏で動く重ね合わせのライブラリ>,
        画面描画の共有状態: egui::Context,
        キャッシュ: サムネイルのキャッシュ,
    ) -> Self {
        Self {
            接続:
                重ね合わせのライブラリの接続::裏で動くライブラリから作る(
                    ライブラリ,
                ),
            一覧: 並べた一覧::default(),
            ダイアログ: 重ね合わせのダイアログ::default(),
            閉じる決め: アプリを閉じてよいとの決め::default(),
            次に見るまでの時間: None,
            サムネイル: 一覧のサムネイル::作成する(画面描画の共有状態, キャッシュ),
            見えている行: None,
        }
    }

    /// 置き場所の無い(重ね合わせのライブラリを使えない)状態。サムネイルのキャッシュも使わない。ライブラリを確かめない試験で、本物の置き場所を使わないために使う。
    #[cfg(test)]
    pub(crate) fn 置き場所の無い試験の状態() -> Self {
        use thumbnail_cache::{
            キャッシュの容量, キャッシュの時計, キャッシュの置き場所
        };
        Self::作成する(
            None,
            egui::Context::default(),
            サムネイルのキャッシュ::作成する(
                キャッシュの置き場所::使わない,
                キャッシュの容量::既定,
                キャッシュの時計::実時間(),
            ),
        )
    }
}
