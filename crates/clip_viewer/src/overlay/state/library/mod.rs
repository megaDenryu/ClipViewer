//! 重ね合わせのライブラリの状態。重ね合わせのライブラリの接続と、重ね合わせの一覧と、開いているダイアログと、アプリを閉じてよいとの決めと、
//! 一覧のサムネイルと、前のフレームで一覧に見えていた行を持つ。開いている重ね合わせとライブラリの関係(未登録か登録済みか)は、
//! 開いている重ね合わせ(`opened/`)が持つ。接続・保存の追跡・一覧の見せ方・サムネイルは、スタックの作業場と共有する型を使う。
//! 参照: _doc/設計/同時再生.md 2-7、_doc/設計/ライブラリ.md 判断11

