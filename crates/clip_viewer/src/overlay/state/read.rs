//! 重ね合わせの作業場の状態を読む口。画面が表示する値(再生しているか・画面を進め続けるか・再生を始められるか・再生の位置と長さ・進み具合・全体ループか・
//! 置かなかったクリップの報告の文・並べる知らせ)を返す。
//! 書き換える口(`mod.rs`・`overlay/command`)と分け、画面が読むものをここに集める。参照: _doc/設計/同時再生.md 3-3

use clip_domain::{
    重ね合わせの再生位置, 重ね合わせの進み具合, 重ね合わせ上の秒
};
use sengen_egui::並べる通知;

use super::{重ね合わせの作業場の状態, 開いている重ね合わせ};

impl 重ね合わせの作業場の状態 {
    /// 開いている重ね合わせを再生しているか。開いていなければ再生していない。
    pub(crate) fn 再生しているか(&self) -> bool {
        self.開いている重ね合わせ()
            .is_some_and(|開いている| 開いている.再生しているか())
    }

    /// 入力が無くても画面を進め続けるか。重ね合わせを開いていなければ進め続けない。
    pub(crate) fn 画面を進め続けるか(&self) -> bool {
        self.開いている重ね合わせ()
            .is_some_and(開いている重ね合わせ::画面を進め続けるか)
    }

    /// 再生を始められるか。重ね合わせを開いていて、長さが0秒でないときだけ始められる。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.開いている重ね合わせ()
            .is_some_and(|開いている| 開いている.再生を始められるか())
    }

    /// 開いている重ね合わせの再生の位置と長さ。開いていなければ無い。
    pub(crate) fn 再生の位置と長さ(
        &self,
    ) -> Option<(重ね合わせの再生位置, 重ね合わせ上の秒)> {
        self.開いている重ね合わせ()
            .map(|開いている| (開いている.再生の位置(), 開いている.重ね合わせの長さ()))
    }

    /// 開いている重ね合わせの、重ね合わせの長さに対する再生の位置の進み具合。開いていなければ無い。
    pub(crate) fn 再生の進み具合(&self) -> Option<重ね合わせの進み具合> {
        self.開いている重ね合わせ()
            .map(開いている重ね合わせ::進み具合)
    }

    /// 開いている重ね合わせの全体ループか。開いていなければ無い。
    pub(crate) fn 全体ループか(&self) -> Option<bool> {
        self.開いている重ね合わせ()
            .map(開いている重ね合わせ::全体ループか)
    }

    /// 最後に並べたときに置かなかったクリップの、画面に出す文の並び。
    pub(crate) fn 置かなかったクリップの報告の文(&self) -> Vec<String> {
        self.置かなかったクリップの報告.画面に出す文の並び()
    }

    /// 画面に並べる最近の知らせ(古い順)。
    pub(crate) fn 並べる知らせ(&self) -> Vec<並べる通知> {
        self.知らせ.並べる通知()
    }
}
