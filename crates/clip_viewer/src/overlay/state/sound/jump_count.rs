//! 行ごとの位置を飛ばした回数。行の音の再生器に読み位置を即座に合わせさせる回数を、タイムラインの行ごとに持ち、毎フレームその時刻に行ごとに映すもので進める。
//! 参照: _doc/設計/同時再生.md 5-3

use audio_output::位置を飛ばした回数;
use clip_domain::{
    同時に重ねられる行の数, 行が映すもの, 行の映し方, 行の番号
};

/// 行の飛ばした回数とは、1つの行の位置を飛ばした回数と、前のフレームでその行が置いたクリップを映していたかの組のことである。
#[derive(Debug, Clone, Copy, Default)]
struct 行の飛ばした回数 {
    回数: 位置を飛ばした回数,
    前のフレームで映していたか: bool,
}

/// 行ごとの位置を飛ばした回数とは、同時に重ねられる行の数だけの行の飛ばした回数(添字は行の番号)のことである。
/// 回数は、行が隙間の後に置いたクリップを映し始めたとき(前のフレームで何も映していなかった行が映し始めたとき)だけ進める。
/// 隙間なく続く継ぎ目(前のフレームも置いたクリップを映していた)では進めない。進めると、区間の終わりの行き先に従って音を重ねる処理が、
/// 回数の変化で跳ぶ処理に打ち消されるためである。
#[derive(Debug, Clone, Default)]
pub(crate) struct 行ごとの位置を飛ばした回数(
    [行の飛ばした回数; 同時に重ねられる行の数],
);

impl 行ごとの位置を飛ばした回数 {
    /// その時刻に行ごとに映すものを受け取り、隙間の後に置いたクリップを映し始めた行だけ回数を進める。映すものに無い行は何も映していないとみなす。
    pub(crate) fn 映すものに合わせて進める(
        &mut self, 映すもの: &[行が映すもの<'_>]
    ) {
        for (添字, 行) in self.0.iter_mut().enumerate() {
            let 映しているか = 映すもの.iter().any(|行が映すもの| {
                行が映すもの.行.番号() == 添字
                    && !matches!(行が映すもの.映し方, 行の映し方::何も映さない)
            });
            if 映しているか && !行.前のフレームで映していたか {
                行.回数 = 行.回数.次();
            }
            行.前のフレームで映していたか = 映しているか;
        }
    }

    /// 全部の行の位置を飛ばした回数を進める。再生の位置を飛ばしたときと、行の中身や番号が変わったときに呼ぶ。
    pub(crate) fn 全部の行を進める(&mut self) {
        for 行 in &mut self.0 {
            行.回数 = 行.回数.次();
        }
    }

    /// 行の番号の行の位置を飛ばした回数。同時に重ねられる行の数より後ろの番号なら最初の回数である。
    pub(crate) fn 行の回数(&self, 行: 行の番号) -> 位置を飛ばした回数 {
        self.0
            .get(行.番号())
            .map_or_else(位置を飛ばした回数::default, |行| 行.回数)
    }
}
