//! 重ね合わせの音の出力の状況。2本目の流れ(行を混ぜる音声出力)を開けたか、開けなかったか途中で使えなくなったかを、重ね合わせの作業場の画面と知らせに出すために持つ。
//! スタックの作業場の音の出力の状況(`state` の `音の出力の状況`)とは別に持ち、そちらは変えない。参照: _doc/設計/同時再生.md 5-3

use audio_output::音声出力のエラー;
use audio_pcm::サンプリング周波数;

use crate::audio_feed::鳴らせない様子の文;

/// 重ね合わせの音の出力の状況とは、2本目の流れを開いて鳴らしているか、使えないかの区別のことである。使えない間も映像は再生を続ける。
#[derive(Debug, Clone)]
pub(crate) enum 重ね合わせの音の出力の状況 {
    使える(サンプリング周波数),
    使えない(音声出力のエラー),
}

impl 重ね合わせの音の出力の状況 {
    /// 使えるなら2本目の流れの周波数。重ね合わせの音の倉庫は、この周波数で FFmpeg に音を出させる。
    pub(crate) fn 周波数(&self) -> Option<サンプリング周波数> {
        match self {
            Self::使える(周波数) => Some(*周波数),
            Self::使えない(_) => None,
        }
    }

    /// 2本目の流れを開けなかったときに知らせる文。使えるなら無い。
    pub(crate) fn 開けなかった知らせの文(&self) -> Option<String> {
        match self {
            Self::使える(_) => None,
            Self::使えない(理由) => Some(format!(
                "{理由}。重ね合わせの作業場は音を鳴らさずに映像だけで再生する"
            )),
        }
    }

    /// 2本目の流れが途中で使えなくなったことを受け取る。使える状況からだけ使えないへ移し、知らせる文を返す。
    /// 既に使えなければ、何度受け取っても最初の理由を残して知らせない。
    pub(crate) fn 使えなくなったら知らせの文を返す(
        &mut self,
        失敗: 音声出力のエラー,
    ) -> Option<String> {
        let Self::使える(_) = self else {
            return None;
        };
        let 文 = format!("{失敗}。重ね合わせの作業場は映像だけで再生を続ける");
        *self = Self::使えない(失敗);
        Some(文)
    }

    /// 画面の音の様子に出す文。使えるなら無い。
    pub(crate) fn 様子の文(&self) -> Option<String> {
        match self {
            Self::使える(_) => None,
            Self::使えない(理由) => Some(鳴らせない様子の文(理由)),
        }
    }
}
