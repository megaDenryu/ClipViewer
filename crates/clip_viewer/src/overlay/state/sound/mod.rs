//! 重ね合わせの作業場の状態の音の側。重ね合わせの音の出力の状況(`output.rs`)と、行ごとの位置を飛ばした回数(`jump_count.rs`)と、
//! 開いている重ね合わせの音の操作(`opened.rs`)と行ごとの再生の指示の組み立て(`instruction.rs`)を持ち、ここには作業場の状態の音の口
//! (毎フレーム行ごとの音を整えること・行ごとの再生の指示・2本目の流れを開けなかったことと途中で使えなくなったことの知らせ・画面が読む音の様子の文)を置く。
//! 参照: _doc/設計/同時再生.md 5-3

mod instruction;
mod jump_count;
mod opened;
mod output;

#[cfg(test)]
mod jump_count_tests;

pub(crate) use jump_count::行ごとの位置を飛ばした回数;
pub(crate) use output::重ね合わせの音の出力の状況;

use std::time::Instant;

use audio_output::{行ごとの再生の指示, 音声出力のエラー};
use audio_pcm::サンプリング周波数;
use clip_domain::音量;

use super::{重ね合わせの作業場の状態, 開いている重ね合わせ};

impl 重ね合わせの作業場の状態 {
    /// 2本目の流れの周波数。使えなければ無い。重ね合わせを開くとき、音の倉庫をこの周波数で開く。
    pub(crate) fn 音の出力の周波数(&self) -> Option<サンプリング周波数> {
        self.音の出力.周波数()
    }

    /// 毎フレーム、行ごとのコマを載せた後に呼ぶ。重ね合わせを開いていれば、再生の位置で行ごとの音を整える。
    pub(crate) fn 行ごとの音を整える(&mut self, 今: Instant) {
        if let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
        {
            開いている.行ごとの音を整える(今);
        }
    }

    /// 行ごとの再生の指示を組み立てる。重ね合わせを開いていなければ、どの行も黙る。
    pub(crate) fn 行ごとの再生の指示(
        &self,
        今: Instant,
        つまみの音量: 音量,
    ) -> 行ごとの再生の指示 {
        self.開いている重ね合わせ().map_or_else(
            || 行ごとの再生の指示::黙る(今),
            |開いている| 開いている.行ごとの再生の指示(今, つまみの音量),
        )
    }

    /// 2本目の流れを今開けなかったとき、配線が1回だけ呼ぶ。音の出力が使えなければ、その理由を知らせる。
    pub(crate) fn 開けなかった音の出力を知らせる(&mut self) {
        if let Some(文) = self.音の出力.開けなかった知らせの文() {
            self.知らせ.出す(文);
        }
    }

    /// 2本目の流れが途中で使えなくなったことを受け取る。使えていた間に初めて受け取ったときだけ知らせる。
    pub(crate) fn 音の出力が使えなくなった(
        &mut self, 失敗: 音声出力のエラー
    ) {
        if let Some(文) = self.音の出力.使えなくなったら知らせの文を返す(失敗)
        {
            self.知らせ.出す(文);
        }
    }

    /// 画面の音の様子に出す文の並び。2本目の流れが使えなければその理由だけを、使えるなら開いている重ね合わせの動画ごとの音の様子を出す。
    pub(crate) fn 音の様子の文の並び(&self) -> Vec<String> {
        if let Some(文) = self.音の出力.様子の文() {
            return vec![文];
        }
        self.開いている重ね合わせ()
            .map(開いている重ね合わせ::音の様子の文の並び)
            .unwrap_or_default()
    }
}
