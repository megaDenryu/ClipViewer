//! 重ね合わせの作業場の状態の音の側。重ね合わせの音の出力の状況(`output.rs`)と、開いている重ね合わせの音(`opened.rs`。音の供給と
//! 行ごとの位置を飛ばした回数(`jump_count.rs`)を所有し、行ごとの再生の指示を組み立てる(`instruction.rs`))を持ち、ここには作業場の状態の音の口
//! (2本目の流れを開けなかったことと途中で使えなくなったことの知らせ・画面が読む音の様子の文)を置く。
//! 参照: _doc/設計/同時再生.md 5-3

mod instruction;
mod jump_count;
mod opened;
mod output;

#[cfg(test)]
mod jump_count_tests;

pub(crate) use opened::開いている重ね合わせの音;
pub(crate) use output::重ね合わせの音の出力の状況;

use audio_output::音声出力のエラー;
use audio_pcm::サンプリング周波数;

use super::{重ね合わせの作業場の状態, 開いている重ね合わせ};

impl 重ね合わせの作業場の状態 {
    /// 2本目の流れの周波数。使えなければ無い。重ね合わせを開くとき、音の倉庫をこの周波数で開く。
    pub(crate) fn 音の出力の周波数(&self) -> Option<サンプリング周波数> {
        self.音の出力.周波数()
    }

    /// 2本目の流れを今開けなかったとき、作業場を作る時点で呼ぶ。音の出力が使えなければ、その理由を知らせる。
    pub(crate) fn 開けなかった音の出力を知らせる(&mut self) {
        if let Some(文) = self.音の出力.開けなかった知らせの文() {
            self.知らせ.出す(文);
        }
    }

    /// 2本目の流れが途中で使えなくなったことを受け取る。使えていた間に初めて受け取ったときだけ知らせ、
    /// 開いている重ね合わせの音の流し読みと音の倉庫の読み込みを止める。
    pub(crate) fn 音の出力が使えなくなったことを知らせる(
        &mut self,
        失敗: 音声出力のエラー,
    ) {
        let Some(文) = self
            .音の出力
            .使えなくなったことを受け取って知らせの文を返す(失敗)
        else {
            return;
        };
        self.知らせ.出す(文);
        if let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
        {
            開いている.出力が使えないため音を止める();
        }
    }

    /// 画面の音の様子に出す文の並び。2本目の流れが使えなければその理由だけを、使えるなら開いている重ね合わせの動画ごとの音の様子を出す。
    pub(crate) fn 音の様子の文の並び(&self) -> Vec<String> {
        if let Some(文) = self.音の出力.様子の文() {
            return vec![文];
        }
        self.開いている重ね合わせ()
            .map(開いている重ね合わせ::音の様子の文の並び)
            .unwrap_or_default()
    }
}
