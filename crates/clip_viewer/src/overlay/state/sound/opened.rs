//! 開いている重ね合わせの音の側の操作。毎フレーム行ごとの音の流し読みと位置を飛ばした回数を整えることと、置いたクリップの音量と消音を変えることと、
//! 画面が音の様子の文を読むことを持つ。参照: _doc/設計/同時再生.md 2-6・5-3

use std::time::Instant;

use clip_domain::{
    置いたクリップ, 置いたクリップの識別子, 置いたクリップの音の設定, 重ね合わせの操作エラー, 音量,
};

use crate::overlay::state::開いている重ね合わせ;

impl 開いている重ね合わせ {
    /// 映像のコマを載せた後に毎フレーム呼ぶ。再生の位置で、動画ごとに音の先読みの並びを渡し、行ごとに音の流し読みを整え、
    /// 隙間の後に置いたクリップを映し始めた行の位置を飛ばした回数を進める。
    pub(crate) fn 行ごとの音を整える(&mut self, 今: Instant) {
        let 条件 = self.再生.映すものを求める条件();
        self.音
            .行ごとの音を整える(&self.重ね合わせ, 条件, &self.映像, 今);
        self.飛ばした回数
            .映すものに合わせて進める(&条件.行ごとに映すものを求める(&self.重ね合わせ));
    }

    /// 置いたクリップの音量を選ぶ。消音しているかは変えない。識別子の置いたクリップが無ければ拒む。
    pub(crate) fn 置いたクリップの音量を選ぶ(
        &mut self,
        識別子: &置いたクリップの識別子,
        選んだ音量: 音量,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let mut 音の設定 = self.置いたクリップの音の設定(識別子)?;
        音の設定.音量 = 選んだ音量;
        self.重ね合わせ
            .置いたクリップの音の設定を変える(識別子, 音の設定)
    }

    /// 置いたクリップを消音するか、消音を戻す。音量は変えないため、戻すと前の音量で鳴る。識別子の置いたクリップが無ければ拒む。
    pub(crate) fn 置いたクリップの消音を設定する(
        &mut self,
        識別子: &置いたクリップの識別子,
        消音するか: bool,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let mut 音の設定 = self.置いたクリップの音の設定(識別子)?;
        音の設定.消音しているか = 消音するか;
        self.重ね合わせ
            .置いたクリップの音の設定を変える(識別子, 音の設定)
    }

    /// 動画ごとの音の様子の文の並び(鳴らせる動画の分は出さない)。画面の再生の操作の行が読む。
    pub(crate) fn 音の様子の文の並び(&self) -> Vec<String> {
        self.音.様子の文の並び()
    }

    fn 置いたクリップの音の設定(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> Result<置いたクリップの音の設定, 重ね合わせの操作エラー> {
        self.重ね合わせ
            .識別子で探す(識別子)
            .map(置いたクリップ::音の設定)
            .ok_or_else(|| {
                重ね合わせの操作エラー::置いたクリップが見つからない(
                    識別子.clone(),
                )
            })
    }
}
