//! 開いている重ね合わせの音。開いている重ね合わせの音の供給と行ごとの位置を飛ばした回数を所有し、毎フレームの音の流し読みと溜める並びの整え、
//! 2本目の流れが使えなくなったときの停止、画面が読む音の様子の文を持つ。行ごとの再生の指示の組み立ては `instruction.rs` に置く。
//! 参照: _doc/設計/同時再生.md 5-3

use std::time::Instant;

use super::jump_count::行ごとの位置を飛ばした回数;
use crate::overlay::feed::{
    このフレームで映すもの, 重ね合わせの映像の供給を作れたか, 重ね合わせの音の供給,
};

/// 開いている重ね合わせの音とは、開いている重ね合わせの音の供給と、行ごとの位置を飛ばした回数の組のことである。重ね合わせと一緒に作り、一緒に捨てる。
pub(crate) struct 開いている重ね合わせの音 {
    pub(super) 供給: 重ね合わせの音の供給,
    pub(super) 飛ばした回数: 行ごとの位置を飛ばした回数,
}

impl 開いている重ね合わせの音 {
    /// 開いた音の供給で作る。どの行も、まだ位置を飛ばしていない。
    pub(crate) fn 開く(供給: 重ね合わせの音の供給) -> Self {
        Self {
            供給,
            飛ばした回数: 行ごとの位置を飛ばした回数::default(),
        }
    }

    /// 映像のコマを載せた後に毎フレーム呼ぶ。このフレームで映すものから、動画ごとに音の溜める並びを渡し、行ごとに音の流し読みを整える。
    pub(crate) fn 行ごとの溜める並びと流し読みを整える(
        &mut self,
        映すもの: &このフレームで映すもの<'_>,
        映像: &重ね合わせの映像の供給を作れたか,
        今: Instant,
    ) {
        self.供給
            .行ごとの溜める並びと流し読みを整える(映すもの, 映像, 今);
    }

    /// 作業場を控えるときに、全部の行の音の流し読みを閉じる。
    pub(crate) fn 流し読みを閉じる(&mut self) {
        self.供給.流し読みを閉じる();
    }

    /// 2本目の流れが途中で使えなくなったときに、音の流し読みと音の倉庫の読み込みを止める。
    pub(crate) fn 出力が使えないため止める(&mut self) {
        self.供給.出力が使えないため止める();
    }

    /// 動画ごとの音の様子の文の並び(鳴らせる動画の分は出さない)。
    pub(crate) fn 様子の文の並び(&self) -> Vec<String> {
        self.供給.様子の文の並び()
    }
}
