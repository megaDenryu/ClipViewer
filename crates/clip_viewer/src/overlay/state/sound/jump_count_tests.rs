//! 行ごとの位置を飛ばした回数の試験。隙間の後に置いたクリップを映し始めた行だけ回数が進み、隙間なく続く間とほかの行は進まないことを確かめる。
#![allow(clippy::expect_used)]

use audio_output::位置を飛ばした回数;
use clip_domain::{時刻, 行が映すもの, 行の映し方, 行の番号};

use super::jump_count::行ごとの位置を飛ばした回数;
use crate::overlay::test_support::五秒の重ね合わせ;

fn 行(番号: usize) -> 行の番号 {
    行の番号::番号から作成する(番号)
}

#[test]
fn 隙間の後に映し始めた行だけ回数が進み_続けて映す間とほかの行は進まない() {
    let 重ね合わせ = 五秒の重ね合わせ();
    let 置いたクリップ = &重ね合わせ.行の並び().奥から手前の順の行()[0].置いたクリップの並び()[0];
    let 映す = |番号| 行が映すもの {
        行: 行(番号),
        映し方: 行の映し方::末尾で最後のコマを映す {
            置いたクリップ,
            動画上の位置: 時刻::作成する(5.0).expect("時刻"),
        },
    };
    let 映さない = |番号| 行が映すもの {
        行: 行(番号),
        映し方: 行の映し方::何も映さない,
    };
    let 最初 = 位置を飛ばした回数::default();
    let mut 回数 = 行ごとの位置を飛ばした回数::default();
    回数.映すものに合わせて進める(&[映す(0), 映さない(1)]);
    assert_eq!(
        回数.行の回数(行(0)),
        最初.次(),
        "最初のフレームで映し始めた行は進む"
    );
    assert_eq!(回数.行の回数(行(1)), 最初);
    回数.映すものに合わせて進める(&[映す(0), 映さない(1)]);
    assert_eq!(回数.行の回数(行(0)), 最初.次(), "続けて映す間は進まない");
    回数.映すものに合わせて進める(&[映さない(0), 映す(1)]);
    assert_eq!(回数.行の回数(行(0)), 最初.次(), "映し終えても進まない");
    assert_eq!(回数.行の回数(行(1)), 最初.次());
    回数.映すものに合わせて進める(&[映す(0)]);
    assert_eq!(
        回数.行の回数(行(0)),
        最初.次().次(),
        "隙間の後に映し始めると進む"
    );
    assert_eq!(
        回数.行の回数(行(1)),
        最初.次(),
        "映すものに無い行は何も映していない"
    );
    assert_eq!(
        回数.行の回数(行(8)),
        最初,
        "行の数の上限より後ろは最初の回数"
    );
}
