//! 開いている重ね合わせの音から行ごとの再生の指示を組み立てる。行ごとに映している置いたクリップの区間とその行き先を、溜めた音か流し読みの出どころと組にし、
//! 置いたクリップの音の設定の音量に、全体の鳴らす音量(音量のつまみの値。全体を消音していれば無音)を掛けた音量で渡す。参照: _doc/設計/同時再生.md 2-6・5-3

use std::time::Instant;

use audio_output::{
    再生の指示, 再生の様子, 終わりで続く音, 行ごとの再生の指示
};
use clip_domain::{
    置いたクリップの区間の終わりの行き先, 行が映すもの, 行の映し方, 音量
};

use super::opened::開いている重ね合わせの音;
use crate::overlay::feed::このフレームで映すもの;

impl 開いている重ね合わせの音 {
    /// このフレームで映すものから行ごとの再生の指示を組み立てる。1フレームに1回だけ呼び、隙間の後に映し始めた行の位置を飛ばした回数を先に進める。
    /// 今は指示の位置を求めた時刻、再生の様子は時計が進んでいるかである。その時刻に置いたクリップを映さない行と、重ね合わせに無い行と、
    /// 動画の音を鳴らせない行は止めている指示にする。重ね合わせの作業場は速度のつまみを持たないため、速度は等倍である。
    pub(crate) fn 行ごとの再生の指示を組み立てる(
        &mut self,
        映すもの: &このフレームで映すもの<'_>,
        再生の様子: 再生の様子,
        今: Instant,
        全体の鳴らす音量: 音量,
    ) -> 行ごとの再生の指示 {
        self.飛ばした回数.映すものに合わせて進める(&映すもの.行ごと);
        let mut 指示 = 行ごとの再生の指示::黙る(今);
        for 行が映すもの in &映すもの.行ごと {
            let 行の指示 =
                self.行の再生の指示(行が映すもの, 再生の様子, 今, 全体の鳴らす音量);
            // 注意: 行の数はタイムラインの行の並びの不変条件で同時に重ねられる行の数以下なので、置き換えは拒まれない。
            let _ = 指示.行の指示を置き換える(行が映すもの.行, 行の指示);
        }
        指示
    }

    fn 行の再生の指示(
        &self,
        行が映すもの: &行が映すもの<'_>,
        再生の様子: 再生の様子,
        今: Instant,
        全体の鳴らす音量: 音量,
    ) -> 再生の指示 {
        let mut 指示 = 再生の指示::黙る(今);
        指示.飛ばした回数 = self.飛ばした回数.行の回数(行が映すもの.行);
        let (置いたクリップ, 動画上の位置, 行き先, 様子) = match 行が映すもの.映し方 {
            行の映し方::置いたクリップを映す(中身) => (
                中身.置いたクリップ,
                中身.動画上の位置,
                self.終わりで続く音(中身.区間の終わりの行き先),
                再生の様子,
            ),
            行の映し方::末尾で最後のコマを映す {
                置いたクリップ,
                動画上の位置,
            } => (
                置いたクリップ,
                動画上の位置,
                終わりで続く音::止まる,
                再生の様子::止めている,
            ),
            行の映し方::何も映さない => return 指示,
        };
        let (Some(周波数), Some(区間)) = (
            self.供給.周波数(),
            self.供給
                .映している音の区間(行が映すもの.行, 置いたクリップ, 動画上の位置),
        ) else {
            return 指示;
        };
        指示.様子 = 様子;
        指示.位置 = 周波数.時刻の小数の位置(動画上の位置);
        指示.音量 = 置いたクリップ
            .音の設定()
            .鳴らす音量()
            .掛ける(全体の鳴らす音量);
        指示.区間 = Some(区間);
        指示.行き先 = 行き先;
        指示
    }

    /// 置いたクリップの区間の終わりの行き先を、音の再生器へ渡す終わりで続く音にする。進む先の置いたクリップの動画の音を鳴らせなければ止まる。
    fn 終わりで続く音(
        &self,
        行き先: 置いたクリップの区間の終わりの行き先<'_>,
    ) -> 終わりで続く音 {
        match 行き先 {
            置いたクリップの区間の終わりの行き先::区間の開始へ戻る => {
                終わりで続く音::開始へ戻る
            }
            置いたクリップの区間の終わりの行き先::止まる => 終わりで続く音::止まる,
            置いたクリップの区間の終わりの行き先::別の置いたクリップへ進む(次) => self
                .供給
                .進む先の音の区間(次)
                .map_or(終わりで続く音::止まる, 終わりで続く音::別の区間へ進む),
        }
    }
}
