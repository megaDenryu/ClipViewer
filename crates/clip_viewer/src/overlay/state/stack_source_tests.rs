//! 今のスタックの値の試験。「今のスタックから並べる」を押せるのは、動画を開いていて再生できるクリップがあるときだけであることを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::クリップスタック;

use super::stack_source::{今のスタックから並べる状況, 今のスタックの値};
use crate::overlay::arrange_test_support::{クリップ, 値, 練習の動画};

#[test]
fn 動画を開いていて再生できるクリップがあるときだけ並べられる() {
    let パス = 練習の動画();
    let 無効 = {
        let mut クリップ = クリップ("無効", 0.0, 1.0);
        クリップ.有効か = false;
        クリップ
    };
    let 再生できない = クリップスタック::一覧から作成する(vec![無効]).expect("スタック");
    let 再生できる =
        クリップスタック::一覧から作成する(vec![クリップ("甲", 0.0, 1.0)]).expect("スタック");
    let 動画なし = 今のスタックの値 {
        開いている動画: None,
        ..値(&再生できる, &パス, 60.0)
    };
    assert_eq!(
        動画なし.並べる状況(),
        今のスタックから並べる状況::動画を開いていない
    );
    assert_eq!(
        値(&再生できない, &パス, 60.0).並べる状況(),
        今のスタックから並べる状況::再生できるクリップが無い
    );
    assert_eq!(
        値(&再生できる, &パス, 60.0).並べる状況(),
        今のスタックから並べる状況::並べられる
    );
}
