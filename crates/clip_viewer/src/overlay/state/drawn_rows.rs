//! 重ねる画面に描く行。今の再生の位置で行ごとに映すもの(第2段階の `重ね合わせ上の時刻に映すものを求める`)と、行のテクスチャから、
//! 重ねる画面に描く行を奥から手前の順に並べる。画面はこの並びを、割合の矩形へ置く容器へ書いた順に置く。参照: _doc/設計/同時再生.md 5-2 の7

use clip_domain::{クロップ範囲, 映す矩形, 行の映し方, 重ね合わせ};
use sengen_egui::登録したテクスチャの参照;

use super::placement::置き方の編集;
use crate::overlay::feed::{
    映すものを求める条件, 重ね合わせの映像の供給を作れたか
};

/// 重ねる画面に描く行とは、重ねる画面に描く1つの行の、映す矩形と、行のテクスチャのうち描く部分(置いたクリップのクロップ範囲)と、
/// 行のテクスチャの組のことである。
#[derive(Clone)]
pub(crate) struct 重ねる画面に描く行 {
    pub(crate) 映す矩形: 映す矩形,
    pub(crate) クロップ: クロップ範囲,
    pub(crate) テクスチャ: 登録したテクスチャの参照,
}

impl 重ねる画面に描く行 {
    /// 重ねる画面に描く行を、奥の行から手前の行の順に並べる。何も映さない行と、まだ動画のコマを1つも載せていない行(最初の黒の1画素)と、
    /// 置いたばかりの置いたクリップのコマがまだ届かず、行のテクスチャに前の置いたクリップのコマが残っている行は描かない。
    /// 映す行は、重ね合わせ上の条件の時刻に行ごとに映すものから選ぶ。映像の供給を作れなかったときは、描く行が無い。
    /// 映す矩形は置き方の編集の今映す矩形であり、ドラッグしている置いたクリップは仮の矩形に描く。
    pub(super) fn 並びを求める(
        重ね合わせ: &重ね合わせ,
        条件: 映すものを求める条件,
        映像: &重ね合わせの映像の供給を作れたか,
        編集: &置き方の編集,
    ) -> Vec<Self> {
        let 重ね合わせの映像の供給を作れたか::作れた(供給) = 映像 else {
            return Vec::new();
        };
        条件
            .行ごとに映すものを求める(重ね合わせ)
            .into_iter()
            .filter_map(|行が映すもの| {
                let 置いたクリップ = match 行が映すもの.映し方 {
                    行の映し方::置いたクリップを映す(中身) => 中身.置いたクリップ,
                    行の映し方::末尾で最後のコマを映す {
                        置いたクリップ,
                    ..
                    } => 置いたクリップ,
                    行の映し方::何も映さない => return None,
                };
                let テクスチャ = 供給.行のコマの載せ先(行が映すもの.行)?.テクスチャ();
                let 置いたばかりでコマを待っているか = 編集
                    .置いたばかりか(置いたクリップ.識別子())
                    && !供給.行に置いたクリップのコマが載っているか(
                        行が映すもの.行,
                        置いたクリップ.識別子(),
                    );
                (!テクスチャ.まだ映していないか()
                    && !置いたばかりでコマを待っているか)
                    .then(|| Self {
                        映す矩形: 編集.今映す矩形(置いたクリップ),
                        クロップ: 置いたクリップ.受け継いだ値().クロップ,
                        テクスチャ: テクスチャ.テクスチャ().参照を複製する(),
                    })
            })
            .collect()
    }
}
