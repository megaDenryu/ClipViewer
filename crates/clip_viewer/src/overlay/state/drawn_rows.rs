//! 重ねる画面に描く行。今の再生の位置で行ごとに映すもの(第2段階の `重ね合わせ上の時刻に映すものを求める`)と、行のテクスチャから、
//! 重ねる画面に描く行を奥から手前の順に並べる。画面はこの並びを、割合の矩形へ置く容器へ書いた順に置く。参照: _doc/設計/同時再生.md 5-2 の7

use clip_domain::{クロップ範囲, 映す矩形, 行の映し方, 重ねる画面の縦横比};
use sengen_egui::登録したテクスチャの参照;

use super::opened::開いている重ね合わせ;
use crate::overlay::feed::重ね合わせの映像の供給を作れたか;

/// 重ねる画面に描く行とは、重ねる画面に描く1つの行の、映す矩形と、行のテクスチャのうち描く部分(置いたクリップのクロップ範囲)と、
/// 行のテクスチャの組のことである。
#[derive(Clone)]
pub(crate) struct 重ねる画面に描く行 {
    pub(crate) 映す矩形: 映す矩形,
    pub(crate) クロップ: クロップ範囲,
    pub(crate) テクスチャ: 登録したテクスチャの参照,
}

impl 開いている重ね合わせ {
    pub(crate) fn 重ねる画面の縦横比(&self) -> 重ねる画面の縦横比 {
        self.重ね合わせ.縦横比()
    }

    /// 入力が無くても画面を進め続けるか。再生している間と、映像の供給が区間を溜めているか行のコマを待っている間は進め続ける。
    pub(crate) fn 画面を進め続けるか(&self) -> bool {
        self.再生しているか() || self.映像.進め続けるか()
    }

    /// 重ねる画面に描く行を、奥の行から手前の行の順に並べる。何も映さない行と、まだ動画のコマを1つも載せていない行(最初の黒の1画素)は描かない。
    /// 映像の供給を作れなかったときは、描く行が無い。
    pub(crate) fn 重ねる画面に描く行の並び(&self) -> Vec<重ねる画面に描く行> {
        let 重ね合わせの映像の供給を作れたか::作れた(供給) = &self.映像
        else {
            return Vec::new();
        };
        self.再生
            .映すものを求める条件()
            .行ごとに映すものを求める(&self.重ね合わせ)
            .into_iter()
            .filter_map(|行が映すもの| {
                let 置いたクリップ = match 行が映すもの.映し方 {
                    行の映し方::置いたクリップを映す(中身) => 中身.置いたクリップ,
                    行の映し方::末尾で最後のコマを映す {
                        置いたクリップ,
                    ..
                    } => 置いたクリップ,
                    行の映し方::何も映さない => return None,
                };
                let テクスチャ = 供給.行のコマの載せ先(行が映すもの.行)?.テクスチャ();
                (!テクスチャ.まだ映していないか()).then(|| 重ねる画面に描く行 {
                    映す矩形: 置いたクリップ.映す矩形(),
                    クロップ: 置いたクリップ.受け継いだ値().クロップ,
                    テクスチャ: テクスチャ.テクスチャ().参照を複製する(),
                })
            })
            .collect()
    }
}
