//! 重ねる画面に描く行。今の再生の位置で行ごとに映すもの(第2段階の `重ね合わせ上の時刻に映すものを求める`)と、行のテクスチャから、
//! 重ねる画面に描く行を奥から手前の順に並べる。画面はこの並びを、割合の矩形へ置く容器へ書いた順に置く。参照: _doc/設計/同時再生.md 5-2 の7

use clip_domain::{
    クロップ範囲, 映す矩形, 行が映すもの, 行の映し方, 重ね合わせ
};
use sengen_egui::登録したテクスチャの参照;

use super::grab::掴んでいるもの;
use super::placement::置き方の編集;
use crate::overlay::feed::{
    映すものを求める条件, 重ね合わせの映像の供給, 重ね合わせの映像の供給を作れたか,
};

/// 重ねる画面に描く行とは、重ねる画面に描く1つの行の、映す矩形と、行のテクスチャのうち描く部分(置いたクリップのクロップ範囲)と、
/// 行のテクスチャの組のことである。
#[derive(Clone)]
pub(crate) struct 重ねる画面に描く行 {
    pub(crate) 映す矩形: 映す矩形,
    pub(crate) クロップ: クロップ範囲,
    pub(crate) テクスチャ: 登録したテクスチャの参照,
}

impl 重ねる画面に描く行 {
    /// 重ねる画面に描く行を、条件の時刻に行ごとに映すものから、奥の行から手前の行の順に並べる。どの行をどう描くかは `置き方の編集::描く置いたクリップを選ぶ` が決める。
    /// 映像の供給を作れなかったときは、描く行が無い。
    pub(super) fn 並びを求める(
        重ね合わせ: &重ね合わせ,
        条件: 映すものを求める条件,
        映像: &重ね合わせの映像の供給を作れたか,
        編集: &置き方の編集,
        掴んでいるもの: &掴んでいるもの,
    ) -> Vec<Self> {
        let 重ね合わせの映像の供給を作れたか::作れた(供給) = 映像 else {
            return Vec::new();
        };
        条件
            .行ごとに映すものを求める(重ね合わせ)
            .into_iter()
            .filter_map(|行が映すもの| {
                Self::行を描くなら作る(重ね合わせ, 供給, 編集, 掴んでいるもの, 行が映すもの)
            })
            .collect()
    }

    /// 行が置いたクリップを映し、その行に描く置いたクリップがあれば、その置いたクリップの今映す矩形(ドラッグの間は仮の矩形)とクロップで行のテクスチャを描く行を作る。
    fn 行を描くなら作る(
        重ね合わせ: &重ね合わせ,
        供給: &重ね合わせの映像の供給,
        編集: &置き方の編集,
        掴んでいるもの: &掴んでいるもの,
        行が映すもの: 行が映すもの<'_>,
    ) -> Option<Self> {
        let 映す置いたクリップ = match 行が映すもの.映し方 {
            行の映し方::置いたクリップを映す(中身) => 中身.置いたクリップ,
            行の映し方::末尾で最後のコマを映す {
                置いたクリップ,
            ..
            } => 置いたクリップ,
            行の映し方::何も映さない => return None,
        };
        let 行の映像 = 供給.行の映像(行が映すもの.行)?;
        let 描き方 = 行の映像.行の描き方を決める(映す置いたクリップ.識別子());
        let 描く置いたクリップ =
            編集.描く置いたクリップを選ぶ(重ね合わせ, 映す置いたクリップ, 描き方)?;
        Some(Self {
            映す矩形: 掴んでいるもの.今映す矩形(描く置いたクリップ),
            クロップ: 描く置いたクリップ.受け継いだ値().クロップ,
            テクスチャ: 行の映像.テクスチャの参照を複製する(),
        })
    }
}
