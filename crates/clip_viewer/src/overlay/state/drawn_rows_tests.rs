//! 重ねる画面に描く行の試験。行の描き方から描く置いたクリップを選ぶ3つの場合(前の置いたクリップで描く・置いたばかりなら描かない・
//! 前の置いたクリップを取り除いたら描かない)を、FFmpeg を使わずに確かめる。参照: _doc/設計/同時再生.md 5-2 の7
#![allow(clippy::expect_used)]

use clip_domain::重ね合わせ;

use super::drawn_rows::重ねる画面に描く行;
use super::placement::置き方の編集;
use crate::overlay::arrange_test_support::練習の動画;
use crate::overlay::feed::行の描き方;
use crate::overlay::placement_test_support::置いたクリップの識別子を作る;
use crate::overlay::test_support::{置き方, 置き方を並べた重ね合わせ};

/// 1つの行に、0秒から1秒の区間を0秒に(置-1)、1秒から2秒の区間を1秒に(置-2)、隙間なく続けて置いた重ね合わせ。
fn 続けて置いた重ね合わせ() -> 重ね合わせ {
    let 置く = |開始: f64| 置き方 {
        動画上の区間の開始: 開始,
        動画上の区間の終了: 開始 + 1.0,
        始まり: 開始,
    };
    置き方を並べた重ね合わせ(練習の動画(), 60.0, &[&[置く(0.0), 置く(1.0)]])
}

fn 選んだ識別子(
    重ね合わせ: &重ね合わせ,
    編集: &置き方の編集,
    描き方: 行の描き方<'_>,
) -> Option<String> {
    let 映す = 重ね合わせ
        .識別子で探す(&置いたクリップの識別子を作る("置-2"))
        .expect("置-2 がある");
    重ねる画面に描く行::描く置いたクリップを選ぶ(
        重ね合わせ,
        編集,
        映す,
        描き方,
    )
    .map(|置いたクリップ| 置いたクリップ.識別子().文字列().to_string())
}

#[test]
fn 映す置いたクリップのコマが載っていれば映す置いたクリップで描き_描かないなら描かない() {
    let 重ね合わせ = 続けて置いた重ね合わせ();
    let 編集 = 置き方の編集::開いた直後();
    assert_eq!(
        選んだ識別子(&重ね合わせ, &編集, 行の描き方::映す置いたクリップのコマ).as_deref(),
        Some("置-2")
    );
    assert_eq!(選んだ識別子(&重ね合わせ, &編集, 行の描き方::描かない), None);
}

#[test]
fn 前の置いたクリップのコマを描き続けるときは前の置いたクリップの矩形とクロップで描く() {
    let 重ね合わせ = 続けて置いた重ね合わせ();
    let 前 = 置いたクリップの識別子を作る("置-1");
    assert_eq!(
        選んだ識別子(
            &重ね合わせ,
            &置き方の編集::開いた直後(),
            行の描き方::前の置いたクリップのコマ(&前)
        )
        .as_deref(),
        Some("置-1")
    );
}

#[test]
fn 映す置いたクリップが置いたばかりなら前の置いたクリップのコマを描かない() {
    let 重ね合わせ = 続けて置いた重ね合わせ();
    let mut 編集 = 置き方の編集::開いた直後();
    編集.置いたばかりとして覚える(置いたクリップの識別子を作る("置-2"));
    let 前 = 置いたクリップの識別子を作る("置-1");
    assert_eq!(
        選んだ識別子(
            &重ね合わせ,
            &編集,
            行の描き方::前の置いたクリップのコマ(&前)
        ),
        None
    );
}

#[test]
fn 前の置いたクリップを取り除いた後は描かない() {
    let mut 重ね合わせ = 続けて置いた重ね合わせ();
    let 前 = 置いたクリップの識別子を作る("置-1");
    重ね合わせ
        .置いたクリップを取り除く(&前)
        .expect("置-1 がある");
    assert_eq!(
        選んだ識別子(
            &重ね合わせ,
            &置き方の編集::開いた直後(),
            行の描き方::前の置いたクリップのコマ(&前)
        ),
        None
    );
}
