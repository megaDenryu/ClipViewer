//! 掴んでいるもの。重ね合わせの作業場で利用者が今ドラッグしているもの(重ねる画面の映す矩形の枠か、タイムラインの塊か、時間の軸の位置の線か、無し)を1つの型で持つ。
//! ポインタは1つなので、2つを同時には掴まない。ドラッグの間は重ね合わせを書き換えずに仮の値を持ち、放したときに1回だけ確定する。
//! 放したを受け取れずに残ったドラッグは、安全網(`overlay/command/drag_safety.rs`)が `捨てる` で捨てる。参照: _doc/設計/同時再生.md 2-4・2-6

use clip_domain::{
    映す矩形, 置いたクリップ, 置いたクリップの行き先, 置いたクリップの識別子
};

use super::placement::映す矩形のドラッグ;
use super::timeline::塊のドラッグ;

/// 掴んでいるものとは、利用者が今ドラッグしているものの区別のことである。
#[derive(Debug, Clone, PartialEq, Default)]
pub(crate) enum 掴んでいるもの {
    #[default]
    無し,
    映す矩形(映す矩形のドラッグ),
    塊(塊のドラッグ),
    位置の線,
}

/// 位置の線の段階とは、時間の軸で再生の位置を動かすドラッグの段階の区別のことである。押しただけでも掴み始めたと放したの両方が届く。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 位置の線の段階 {
    掴み始めた,
    動かしている,
    放した,
}

impl 掴んでいるもの {
    /// 置いたクリップを今映す矩形。その置いたクリップの映す矩形をドラッグしている間は仮の矩形、そうでなければ置いたクリップの映す矩形である。
    pub(crate) fn 今映す矩形(
        &self, 置いたクリップ: &置いたクリップ
    ) -> 映す矩形 {
        self.対象の映す矩形のドラッグ(置いたクリップ.識別子())
            .map_or_else(|| 置いたクリップ.映す矩形(), 映す矩形のドラッグ::仮の矩形)
    }

    /// 対象の置いたクリップの映す矩形をドラッグしていれば、そのドラッグ。
    pub(crate) fn 対象の映す矩形のドラッグ(
        &self,
        対象: &置いたクリップの識別子,
    ) -> Option<&映す矩形のドラッグ> {
        match self {
            Self::映す矩形(ドラッグ) if ドラッグ.対象か(対象) => Some(ドラッグ),
            Self::無し | Self::映す矩形(_) | Self::塊(_) | Self::位置の線 => None,
        }
    }

    /// 対象の置いたクリップの塊をドラッグしていれば、そのドラッグ。
    pub(crate) fn 対象の塊のドラッグ(
        &self,
        対象: &置いたクリップの識別子,
    ) -> Option<&塊のドラッグ> {
        match self {
            Self::塊(ドラッグ) if ドラッグ.対象か(対象) => Some(ドラッグ),
            Self::無し | Self::映す矩形(_) | Self::塊(_) | Self::位置の線 => None,
        }
    }

    /// 対象の置いたクリップの映す矩形をドラッグしていれば、その仮の矩形を変える。
    pub(crate) fn 仮の矩形を変える(
        &mut self,
        対象: &置いたクリップの識別子,
        仮の矩形: 映す矩形,
    ) {
        if let Self::映す矩形(ドラッグ) = self
            && ドラッグ.対象か(対象)
        {
            ドラッグ.仮の矩形を変える(仮の矩形);
        }
    }

    /// 対象の置いたクリップの塊をドラッグしていれば、その仮の行き先を変える。
    pub(crate) fn 仮の行き先を変える(
        &mut self,
        対象: &置いたクリップの識別子,
        仮の行き先: 置いたクリップの行き先,
    ) {
        if let Self::塊(ドラッグ) = self
            && ドラッグ.対象か(対象)
        {
            ドラッグ.仮の行き先を変える(仮の行き先);
        }
    }

    /// 対象の置いたクリップの映す矩形をドラッグしていれば、ドラッグを終えて取り出す。別のもののドラッグは終えない。
    pub(crate) fn 映す矩形のドラッグを終えて取り出す(
        &mut self,
        対象: &置いたクリップの識別子,
    ) -> Option<映す矩形のドラッグ> {
        self.対象の映す矩形のドラッグ(対象)?;
        match std::mem::take(self) {
            Self::映す矩形(ドラッグ) => Some(ドラッグ),
            Self::無し | Self::塊(_) | Self::位置の線 => None,
        }
    }

    /// 対象の置いたクリップの塊をドラッグしていれば、ドラッグを終えて取り出す。別のもののドラッグは終えない。
    pub(crate) fn 塊のドラッグを終えて取り出す(
        &mut self,
        対象: &置いたクリップの識別子,
    ) -> Option<塊のドラッグ> {
        self.対象の塊のドラッグ(対象)?;
        match std::mem::take(self) {
            Self::塊(ドラッグ) => Some(ドラッグ),
            Self::無し | Self::映す矩形(_) | Self::位置の線 => None,
        }
    }

    /// 時間の軸の位置の線を掴んでいるか。掴んでいる間は、流し読みを開き直さず音を黙らせる(画面.md 判断5・判断10)。
    pub(crate) fn 位置の線を掴んでいるか(&self) -> bool {
        matches!(self, Self::位置の線)
    }

    /// 掴んでいるものを、仮の値を確定せずに捨てる。
    pub(crate) fn 捨てる(&mut self) {
        *self = Self::無し;
    }
}
