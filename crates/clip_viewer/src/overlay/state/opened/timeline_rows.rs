//! タイムラインの行の操作。行を選ぶ・選んでいる空の行を消す・空の行を手前に足すことと、行ごとの再生のつながりを断つこと(位置を動かす操作も呼ぶ)。
//! 重ね合わせを変える操作は `clip_domain` の重ね合わせの操作を通し、通ったら置き方を手で直したことを覚える。
//! 行の番号や時刻と行のつながりが変わった後は、行ごとの続く先を断つ(`行ごとの再生のつながりを断つ`)。参照: _doc/設計/同時再生.md 2-6・5-2 の7

use clip_domain::{行の番号, 重ね合わせの操作エラー};

use super::開いている重ね合わせ;

impl 開いている重ね合わせ {
    /// タイムラインの行を選ぶ。選んでいた置いたクリップの選びは外れる。重ね合わせに無い行は選ばない。
    pub(crate) fn 行を選ぶ(&mut self, 行: 行の番号) {
        if 行.番号() < self.重ね合わせ.行の並び().行の数() {
            self.編集.行を選ぶ(行);
        }
    }

    /// 選んでいる行を消す。行を選んでいなければ何もしない。選んでいる行が空でなければ拒む。消したら行の選びを外す。
    pub(crate) fn 選んでいる空の行を消す(
        &mut self,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let Some(行) = self.編集.選んでいる行() else {
            return Ok(());
        };
        self.重ね合わせ.空の行を消す(行)?;
        self.編集.選びを外す();
        self.編集.手で直したことを覚える();
        self.行ごとの再生のつながりを断つ();
        Ok(())
    }

    /// 空の新しい行を最も手前に足し、足した行を選ぶ。行が8つあるときは拒む。
    pub(crate) fn 空の行を手前に足す(
        &mut self,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let 行 = self.重ね合わせ.空の行を手前に足す()?;
        self.編集.行を選ぶ(行);
        self.編集.手で直したことを覚える();
        Ok(())
    }

    /// 全部の行の続く先を止まるにし、全部の行の位置を飛ばした回数を進める。再生の位置を飛ばしたときと、行の中身や番号を変えたときに呼ぶ。
    /// 続く先を止まるにすると、行のテクスチャに残る前の置いたクリップのコマを別の置いたクリップの代わりに描かない(同時再生.md 5-2 の7)。
    /// 位置を飛ばした回数を進めると、行の音の再生器がずれを待たずに新しい位置へ合わせる。
    pub(super) fn 行ごとの再生のつながりを断つ(&mut self) {
        self.映像.行ごとの続く先を止まるにする();
        self.音.全部の行の位置を飛ばす();
    }
}
