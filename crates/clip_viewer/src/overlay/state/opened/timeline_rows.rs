//! タイムラインの行の操作。行を選ぶ・選んでいる空の行を消す・空の行を手前に足すこと。
//! 重ね合わせを変える操作は `clip_domain` の重ね合わせの操作を通し、通ったら置き方を手で直したことを覚える。
//! 空の行を消したら、番号が変わる行(消した行から上の行)の続く先を止まるにする。参照: _doc/設計/同時再生.md 2-6・5-2 の7

use clip_domain::{行の番号, 重ね合わせの操作エラー};

use super::開いている重ね合わせ;

impl 開いている重ね合わせ {
    /// タイムラインの行を選ぶ。選んでいた置いたクリップの選びは外れる。重ね合わせに無い行は選ばない。
    pub(crate) fn 行を選ぶ(&mut self, 行: 行の番号) {
        if self.重ね合わせ.行の並び().行があるか(行) {
            self.編集.行を選ぶ(行);
        }
    }

    /// 選んでいる行を消す。行を選んでいなければ何もしない。選んでいる行が空でなければ拒む。消したら行の選びを外す。
    /// 消した行の番号から、消す前の最も手前の行の番号までの行は、番号が変わるため続く先を止まるにする。それより奥の行は変えない。
    pub(crate) fn 選んでいる空の行を消す(
        &mut self,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let Some(行) = self.編集.選んでいる行() else {
            return Ok(());
        };
        let 消す前の行の数 = self.重ね合わせ.行の並び().行の数();
        self.重ね合わせ.空の行を消す(行)?;
        self.編集.選びを外す();
        self.編集.手で直したことを覚える();
        for 番号 in 行.番号()..消す前の行の数 {
            self.行の続く先を止まるにする(行の番号::番号から作成する(番号));
        }
        Ok(())
    }

    /// 空の新しい行を最も手前に足し、足した行を選ぶ。行が同時に重ねられる行の数まであるときは拒む。
    pub(crate) fn 空の行を手前に足す(
        &mut self,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let 行 = self.重ね合わせ.空の行を手前に足す()?;
        self.編集.行を選ぶ(行);
        self.編集.手で直したことを覚える();
        Ok(())
    }
}
