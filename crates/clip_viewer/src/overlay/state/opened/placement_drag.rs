//! 映す矩形のドラッグを、開いている重ね合わせの置き方の編集へ当てる。掴み始めで掴み始めの矩形を覚え、動かしている間は仮の矩形だけを変え、
//! 放したときに重ね合わせの `映す矩形を変える` で1回だけ確定する。掴んだ枠が無くなったら、確定せずにドラッグを閉じる。
//! 移動・大きさの変更・縦横比を保つ計算は `clip_domain` の映す矩形が持ち、ここは掴む所と縦横比の扱いで選ぶだけである。参照: _doc/設計/同時再生.md 2-4

use clip_domain::{
    映す矩形, 置いたクリップの識別子, 重ね合わせの操作エラー
};

use super::開いている重ね合わせ;
use crate::overlay::state::placement::{
    映す矩形のドラッグ, 映す矩形のドラッグの動き, 映す矩形の掴む所, 隅の縦横比の扱い,
};

impl 開いている重ね合わせ {
    /// 置いたクリップの映す矩形のドラッグを始め、今の映す矩形を掴み始めの矩形として覚える。置いたクリップが無ければドラッグしない。
    pub(crate) fn 映す矩形のドラッグを始める(
        &mut self,
        対象: &置いたクリップの識別子,
    ) {
        self.編集.ドラッグ =
            self.重ね合わせ
                .識別子で探す(対象)
                .map(|置いた| 映す矩形のドラッグ {
                    対象: 対象.clone(),
                    掴み始めの矩形: 置いた.映す矩形(),
                    仮の矩形: 置いた.映す矩形(),
                });
    }

    /// ドラッグしている置いたクリップの仮の矩形を、掴み始めの矩形へ移動量を当てた矩形にする。別の置いたクリップの動きは当てない。
    pub(crate) fn 映す矩形のドラッグを動かす(
        &mut self,
        動き: &映す矩形のドラッグの動き,
    ) {
        let Some(始め) = self.ドラッグしている掴み始めの矩形(&動き.対象)
        else {
            return;
        };
        let 仮の矩形 = self.移動量を当てた矩形(始め, 動き);
        if let Some(ドラッグ) = &mut self.編集.ドラッグ {
            ドラッグ.仮の矩形 = 仮の矩形;
        }
    }

    /// 最後の動きを当ててからドラッグを終え、仮の矩形を重ね合わせへ確定する。掴み始めから矩形が変わっていなければ(押しただけなら)確定しない。
    pub(crate) fn 映す矩形のドラッグを放す(
        &mut self,
        動き: &映す矩形のドラッグの動き,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.映す矩形のドラッグを動かす(動き);
        if self.ドラッグしている掴み始めの矩形(&動き.対象).is_none() {
            return Ok(());
        }
        let Some(ドラッグ) = self.編集.ドラッグ.take() else {
            return Ok(());
        };
        if ドラッグ.仮の矩形 == ドラッグ.掴み始めの矩形 {
            return Ok(());
        }
        self.重ね合わせ
            .映す矩形を変える(&ドラッグ.対象, ドラッグ.仮の矩形)?;
        self.編集.手で直したことを覚える();
        Ok(())
    }

    /// 掴んだ枠が無くなったときに呼ぶ。その置いたクリップのドラッグを、確定せずに閉じる。
    pub(crate) fn 映す矩形のドラッグを閉じる(
        &mut self,
        対象: &置いたクリップの識別子,
    ) {
        if self.ドラッグしている掴み始めの矩形(対象).is_some() {
            self.編集.ドラッグ = None;
        }
    }

    fn ドラッグしている掴み始めの矩形(
        &self,
        対象: &置いたクリップの識別子,
    ) -> Option<映す矩形> {
        self.編集
            .ドラッグ
            .as_ref()
            .filter(|ドラッグ| &ドラッグ.対象 == 対象)
            .map(|ドラッグ| ドラッグ.掴み始めの矩形)
    }

    /// 絵の形を保つときは、置いたクリップのクロップを掛けた絵の縦横比(動画の元の寸法から求める)を保つ。
    /// 動画を開けず絵の縦横比が分からないときは、掴み始めの映す矩形の形を保つ。
    fn 移動量を当てた矩形(
        &self,
        始め: 映す矩形,
        動き: &映す矩形のドラッグの動き,
    ) -> 映す矩形 {
        let 量 = 動き.移動量;
        let 映す矩形の掴む所::隅(つまみ) = 動き.掴む所 else {
            return 始め.移動する(量);
        };
        if 動き.縦横比 == 隅の縦横比の扱い::保たない {
            return 始め.つまみで大きさを変える(つまみ, 量);
        }
        match self.絵の縦横比(&動き.対象) {
            Some(絵) => 始め.縦横比を保ってつまみで大きさを変える(
                つまみ,
                量,
                絵,
                self.重ね合わせ.縦横比(),
            ),
            None => 始め.今の形を保ってつまみで大きさを変える(つまみ, 量),
        }
    }

    fn 絵の縦横比(
        &self, 対象: &置いたクリップの識別子
    ) -> Option<clip_domain::縦横比> {
        let 置いた = self.重ね合わせ.識別子で探す(対象)?;
        let 元の寸法 = self
            .映像
            .開いた動画の情報(置いた.動画の番号())?
            .元の寸法()
            .画素の寸法へ変換する()
            .ok()?;
        置いた
            .受け継いだ値()
            .クロップ
            .切り出し後の寸法(元の寸法)
            .縦横比()
    }
}
