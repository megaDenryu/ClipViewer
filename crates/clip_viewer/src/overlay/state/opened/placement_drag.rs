//! 映す矩形のドラッグを、開いている重ね合わせの置き方の編集へ当てる。掴み始めで掴み始めの矩形を覚え、動かしている間は仮の矩形だけを変え、
//! 放したときに重ね合わせの `映す矩形を変える` で1回だけ確定する。掴んだ枠が無くなったら、確定せずにドラッグを閉じる。
//! 動きをどの計算で当てるかの選び方は `state/placement/drag_motion.rs` に置き、ここは絵の縦横比を求めて渡すだけである。参照: _doc/設計/同時再生.md 2-4

use clip_domain::{
    縦横比, 置いたクリップの識別子, 重ね合わせの操作エラー
};

use super::開いている重ね合わせ;
use crate::overlay::state::placement::{
    映す矩形のドラッグ, 映す矩形のドラッグの動き
};

impl 開いている重ね合わせ {
    /// 置いたクリップの映す矩形のドラッグを始め、今の映す矩形を掴み始めの矩形として覚える。置いたクリップが無ければドラッグしない。
    pub(crate) fn 映す矩形のドラッグを始める(
        &mut self,
        対象: &置いたクリップの識別子,
    ) {
        if let Some(置いた) = self.重ね合わせ.識別子で探す(対象) {
            let ドラッグ =
                映す矩形のドラッグ::掴み始める(対象.clone(), 置いた.映す矩形());
            self.編集.ドラッグを始める(ドラッグ);
        }
    }

    /// ドラッグしている置いたクリップの仮の矩形を、掴み始めの矩形へ移動量を当てた矩形にする。別の置いたクリップの動きは当てない。
    pub(crate) fn 映す矩形のドラッグを動かす(
        &mut self,
        動き: &映す矩形のドラッグの動き,
    ) {
        let Some(始め) = self
            .編集
            .対象のドラッグ(&動き.対象)
            .map(映す矩形のドラッグ::掴み始めの矩形)
        else {
            return;
        };
        let 仮の矩形 = 動き.掴み始めの矩形へ当てる(
            始め,
            self.絵の縦横比(&動き.対象),
            self.重ね合わせ.縦横比(),
        );
        self.編集.仮の矩形を変える(&動き.対象, 仮の矩形);
    }

    /// 最後の動きを当ててからドラッグを終え、仮の矩形を重ね合わせへ確定する。掴み始めから矩形が変わっていなければ(押しただけなら)確定しない。
    pub(crate) fn 映す矩形のドラッグを放す(
        &mut self,
        動き: &映す矩形のドラッグの動き,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.映す矩形のドラッグを動かす(動き);
        let Some(ドラッグ) = self.編集.ドラッグを終えて取り出す(&動き.対象)
        else {
            return Ok(());
        };
        if !ドラッグ.矩形が変わったか() {
            return Ok(());
        }
        self.重ね合わせ
            .映す矩形を変える(ドラッグ.対象(), ドラッグ.仮の矩形())?;
        self.編集.手で直したことを覚える();
        Ok(())
    }

    /// 掴んだ枠が無くなったときに呼ぶ。その置いたクリップのドラッグを、確定せずに閉じる。
    pub(crate) fn 映す矩形のドラッグを閉じる(
        &mut self,
        対象: &置いたクリップの識別子,
    ) {
        self.編集.ドラッグを終えて取り出す(対象);
    }

    /// 置いたクリップのクロップを掛けた絵の縦横比(動画の元の寸法から求める)。動画を開けず元の寸法が分からなければ無い。
    fn 絵の縦横比(&self, 対象: &置いたクリップの識別子) -> Option<縦横比> {
        let 置いた = self.重ね合わせ.識別子で探す(対象)?;
        let 元の寸法 = self
            .映像
            .開いた動画の情報(置いた.動画の番号())?
            .元の寸法()
            .画素の寸法へ変換する()
            .ok()?;
        置いた
            .受け継いだ値()
            .クロップ
            .切り出し後の寸法(元の寸法)
            .縦横比()
    }
}
