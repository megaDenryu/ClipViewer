//! 開いている重ね合わせ。重ね合わせと、その再生の状況と、映像の供給を作れたかと、開いている重ね合わせの音(`sound/`)を持ち、
//! 毎フレームこのフレームで映すものを1回だけ求めて映像と音へ渡す。長さが0秒の重ね合わせは再生を始めない。画面が読む口は `read.rs` に置く。
//! 置き方の編集(`state/placement/`)も持ち、その操作は `placement_ops.rs`・`placement_drag.rs`、読む口は `placement_read.rs` に置く。

mod placement_drag;
mod placement_ops;
mod placement_read;
mod read;

pub(crate) use placement_read::重ねる枠;

use std::time::Instant;

use audio_output::{再生の様子, 行ごとの再生の指示};
use clip_domain::{
    時刻, 置いたクリップの識別子, 置いたクリップの音の変更, 重ね合わせ, 重ね合わせの操作エラー,
    音量,
};

use crate::overlay::feed::{
    このフレームで映すもの, 重ね合わせの映像の供給を作れたか
};
use crate::overlay::state::placement::置き方の編集;
use crate::overlay::state::playback::重ね合わせの再生の状況;
use crate::overlay::state::sound::開いている重ね合わせの音;

/// 開いている重ね合わせとは、重ね合わせの作業場が開いている重ね合わせと、その再生の状況と、その映像の供給を作れたかと、
/// 開いている重ね合わせの音と、置き方の編集の組のことである。供給は重ね合わせを開くときに作り、重ね合わせと一緒に捨てる。
pub(crate) struct 開いている重ね合わせ {
    重ね合わせ: 重ね合わせ,
    再生: 重ね合わせの再生の状況,
    映像: 重ね合わせの映像の供給を作れたか,
    音: 開いている重ね合わせの音,
    編集: 置き方の編集,
}

impl 開いている重ね合わせ {
    pub(crate) fn 先頭で止まって開く(
        重ね合わせ: 重ね合わせ,
        映像: 重ね合わせの映像の供給を作れたか,
        音: 開いている重ね合わせの音,
    ) -> Self {
        let 再生 = 重ね合わせの再生の状況::起動時();
        Self {
            重ね合わせ,
            再生,
            映像,
            音,
            編集: 置き方の編集::開いた直後(),
        }
    }

    /// 開いている重ね合わせ。画面が置いたクリップの名前と音の設定を並べるときに読む。
    pub(crate) fn 重ね合わせ(&self) -> &重ね合わせ {
        &self.重ね合わせ
    }

    /// 映像の供給を作れたか。試験で、供給を作れたかと行に載ったコマを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 映像の供給を作れたか(
        &self,
    ) -> &重ね合わせの映像の供給を作れたか {
        &self.映像
    }

    /// 毎フレーム呼ぶ。時計を進め、進めた位置でこのフレームで映すものを1回だけ求め、行ごとに映すコマを載せ、行ごとの音を整え、行ごとの再生の指示を組み立てて返す。
    pub(crate) fn フレームを進める(
        &mut self,
        今: Instant,
        全体の鳴らす音量: 音量,
    ) -> 行ごとの再生の指示 {
        self.再生.時計を進める(今, &self.重ね合わせ);
        let 映すもの = このフレームで映すもの::求める(
            &self.重ね合わせ,
            self.再生.映すものを求める条件(),
        );
        self.映像.行ごとのコマを載せる(&映すもの, 今);
        self.音
            .行ごとの溜める並びと流し読みを整える(&映すもの, &self.映像, 今);
        let 様子 = if self.再生.再生しているか() {
            再生の様子::再生している
        } else {
            再生の様子::止めている
        };
        let 指示 = self.音.行ごとの再生の指示を組み立てる(
            &映すもの,
            様子,
            今,
            全体の鳴らす音量,
        );
        self.コマが載った置いたばかりの置いたクリップを外す();
        指示
    }

    pub(crate) fn 再生しているか(&self) -> bool {
        self.再生.再生しているか()
    }

    /// 再生を始められるか。置いたクリップが無い(長さが0秒の)重ね合わせは、映すものが無く時計も0秒に留まるため、再生を始めない。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.重ね合わせの長さ() > 時刻::先頭
    }

    /// 再生と停止を切り替える。再生を始められないときは、止まったままにする。
    pub(crate) fn 再生を切り替える(&mut self) {
        if self.再生しているか() || self.再生を始められるか() {
            self.再生.再生を切り替える(&self.重ね合わせ);
        }
    }

    /// 作業場を控える前に呼ぶ。再生を止め、全部の行の映像と音の流し読みを閉じる。重ね合わせと再生の位置と、行のテクスチャに載せたコマは残す。
    pub(crate) fn 控える前に再生を止めて流し読みを閉じる(&mut self) {
        self.再生.止める();
        self.映像.流し読みを閉じる();
        self.音.流し読みを閉じる();
    }

    pub(crate) fn 全体ループを設定する(&mut self, 有効: bool) {
        self.再生.全体ループを設定する(有効);
    }

    /// 置いたクリップの音の設定に変更(音量を選ぶか消音を設定するか)を当てる。識別子の置いたクリップが無ければ拒む。
    /// 当てたら置き方を手で直したことを覚える(並べ直すと音の設定も失われるため。同時再生.md 2-2)。
    pub(crate) fn 置いたクリップの音を変える(
        &mut self,
        識別子: &置いたクリップの識別子,
        変更: 置いたクリップの音の変更,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.重ね合わせ.置いたクリップの音を変える(識別子, 変更)?;
        self.編集.手で直したことを覚える();
        Ok(())
    }

    /// 2本目の流れが途中で使えなくなったときに、音の流し読みと音の倉庫の読み込みを止める。
    pub(crate) fn 出力が使えないため音を止める(&mut self) {
        self.音.出力が使えないため止める();
    }
}
