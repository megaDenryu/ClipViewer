/// 開いている重ね合わせとは、重ね合わせの作業場が開いている重ね合わせと、その再生の状況と、その映像の供給を作れたかと、
/// 開いている重ね合わせの音と、置き方の編集と、掴んでいるもの(ドラッグの間の仮の値)の組のことである。供給は重ね合わせを開くときに作り、重ね合わせと一緒に捨てる。
pub(crate) struct 開いている重ね合わせ {
    重ね合わせ: 重ね合わせ,
    再生: 重ね合わせの再生の状況,
    映像: 重ね合わせの映像の供給を作れたか,
    音: 開いている重ね合わせの音,
    編集: 置き方の編集,
    掴んでいるもの: 掴んでいるもの,
}

impl 開いている重ね合わせ {
    pub(crate) fn 先頭で止まって開く(
        重ね合わせ: 重ね合わせ,
        映像: 重ね合わせの映像の供給を作れたか,
        音: 開いている重ね合わせの音,
    ) -> Self {
        let 再生 = 重ね合わせの再生の状況::起動時();
        Self {
            重ね合わせ,
            再生,
            映像,
            音,
            編集: 置き方の編集::開いた直後(),
            掴んでいるもの: 掴んでいるもの::無し,
        }
    }

    /// 開いている重ね合わせ。画面が置いたクリップの名前と音の設定を並べるときに読む。
    pub(crate) fn 重ね合わせ(&self) -> &重ね合わせ {
        &self.重ね合わせ
    }

    /// 映像の供給を作れたか。試験で、供給を作れたかと行に載ったコマを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 映像の供給を作れたか(
        &self,
    ) -> &重ね合わせの映像の供給を作れたか {
        &self.映像
    }

    /// 毎フレーム呼ぶ。時計を進め、進めた位置でこのフレームで映すものを1回だけ求め、行ごとに映すコマを載せ、行ごとの音を整え、行ごとの再生の指示を組み立てて返す。
    pub(crate) fn フレームを進める(
        &mut self,
        今: Instant,
        全体の鳴らす音量: 音量,
    ) -> 行ごとの再生の指示 {
        self.再生.時計を進める(今, &self.重ね合わせ);
        let 映すもの = このフレームで映すもの::求める(
            &self.重ね合わせ,
            self.再生.映すものを求める条件(),
        );
        self.映像.行ごとのコマを載せる(&映すもの, 今);
        self.音
            .行ごとの溜める並びと流し読みを整える(&映すもの, &self.映像, 今);
        let 様子 = if self.再生.再生しているか() {
            再生の様子::再生している
        } else {
            再生の様子::止めている
        };
        let 指示 = self.音.行ごとの再生の指示を組み立てる(
            &映すもの,
            様子,
            今,
            全体の鳴らす音量,
        );
        self.コマが載った置いたばかりの置いたクリップを外す();
        指示
    }

    pub(crate) fn 再生しているか(&self) -> bool {
        self.再生.再生しているか()
    }

    /// 作業場を控える前に呼ぶ。再生を止め、全部の行の映像と音の流し読みを閉じる。重ね合わせと再生の位置と、行のテクスチャに載せたコマは残す。
    pub(crate) fn 控える前に再生を止めて流し読みを閉じる(&mut self) {
        self.再生.止める();
        self.映像.流し読みを閉じる();
        self.音.流し読みを閉じる();
    }

    /// 2本目の流れが途中で使えなくなったときに、音の流し読みと音の倉庫の読み込みを止める。
    pub(crate) fn 出力が使えないため音を止める(&mut self) {
        self.音.出力が使えないため止める();
    }
}
