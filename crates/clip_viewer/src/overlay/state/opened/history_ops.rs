//! 開いている重ね合わせの取り消しとやり直し。重ね合わせの変化を編集の履歴へ積むのは毎フレームの最初の1箇所(`mod.rs` の `フレームを進める`)であり、
//! ここは取り消しとやり直しで重ね合わせを戻すことと、つまみのドラッグの間の音量の変化をまとめる区別と区切りを履歴へ知らせることを持つ。
//! 映す矩形と塊のドラッグの間は重ね合わせを変えない(放したときに1回だけ確定する)ため、放した時点で1つの変化になる。参照: _doc/設計/同時再生.md 2-6、画面.md 判断14

use clip_domain::{置いたクリップの識別子, 重ね合わせ};

use super::開いている重ね合わせ;
use crate::overlay::state::history::重ね合わせの続けて変える値;

impl 開いている重ね合わせ {
    /// 最後の編集を取り消す。映す矩形か塊のドラッグの途中と、取り消せる編集が無いときは何もしない。
    pub(crate) fn 編集を取り消す(&mut self) {
        if self.掴んでいるもの.確定を待つドラッグの途中か() {
            return;
        }
        if let Some(戻す重ね合わせ) = self.履歴.取り消す(&self.重ね合わせ) {
            self.履歴から重ね合わせを戻す(戻す重ね合わせ);
        }
    }

    /// 取り消した編集をやり直す。映す矩形か塊のドラッグの途中と、やり直せる編集が無いときは何もしない。
    pub(crate) fn 編集をやり直す(&mut self) {
        if self.掴んでいるもの.確定を待つドラッグの途中か() {
            return;
        }
        if let Some(進める重ね合わせ) = self.履歴.やり直す(&self.重ね合わせ) {
            self.履歴から重ね合わせを戻す(進める重ね合わせ);
        }
    }

    /// 取り消しのボタンを押せるか。
    pub(crate) fn 取り消せるか(&self) -> bool {
        !self.掴んでいるもの.確定を待つドラッグの途中か()
            && self.履歴.取り消せるか(&self.重ね合わせ)
    }

    /// やり直しのボタンを押せるか。
    pub(crate) fn やり直せるか(&self) -> bool {
        !self.掴んでいるもの.確定を待つドラッグの途中か()
            && self.履歴.やり直せるか(&self.重ね合わせ)
    }

    /// 次に見る変化が、置いたクリップの音量のつまみの変化であることを履歴へ知らせる。つまみのドラッグの間の変化を1つにまとめるためである。
    pub(super) fn 音量の変化を履歴へ知らせる(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) {
        self.履歴.次の変化の値を覚える(
            重ね合わせの続けて変える値::置いたクリップの音量(識別子.clone()),
        );
    }

    /// 操作の区切りを履歴へ知らせる。主ボタンを押していないフレームごとに安全網が呼ぶ(つまみのドラッグの間は主ボタンを押しているので区切らない)。
    pub(crate) fn 取り消しのまとめを区切る(&mut self) {
        self.履歴.操作の区切りを覚える();
    }

    /// 履歴の重ね合わせへ戻す。選んでいるものは今のままにし、戻した重ね合わせに無ければ選びを外す。
    /// 戻した重ね合わせは行の中身も番号も変わりうるため、再生の位置を今の位置(長さより後ろなら長さ)へ動かし直して全部の行の続く先を止まるにする。
    /// 取り消しとやり直しも重ね合わせを変えるため、置き方を手で直したとして扱う(並べ直すとやり直せる編集も失われるため。同時再生.md 2-2)。
    fn 履歴から重ね合わせを戻す(&mut self, 重ね合わせ: 重ね合わせ) {
        self.重ね合わせ = 重ね合わせ;
        self.編集.重ね合わせに無いものの選びを外す(&self.重ね合わせ);
        self.編集.手で直したことを覚える();
        self.再生の位置を動かす(self.再生.位置().時刻());
    }
}
