//! 置き方の編集を読む口。重ねる画面に重ねる枠の並び(今の時刻に映している置いたクリップと、選んでいる置いたクリップ)と、
//! サイドバーに並べる置いたクリップと、選んでいる置いたクリップと、置き方を手で直したかを返す。参照: _doc/設計/同時再生.md 2-3・2-4

use clip_domain::{
    映す矩形, 置いたクリップ, 置いたクリップの識別子, 行の映し方
};

use super::開いている重ね合わせ;

/// 重ねる枠とは、重ねる画面の上に重ねて描く1つの置いたクリップの枠の、識別子と、今映す矩形と、選んでいるかの組のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 重ねる枠 {
    pub(crate) 識別子: 置いたクリップの識別子,
    pub(crate) 矩形: 映す矩形,
    pub(crate) 選んでいるか: bool,
}

impl 開いている重ね合わせ {
    /// 重ねる画面に重ねる枠を、奥の行から手前の行の順に並べる。今の時刻に映している置いたクリップ(止まった末尾で最後のコマを映すものを含む)と、
    /// 選んでいる置いたクリップの枠を出す。選んでいる置いたクリップは、今の時刻に映していなくても枠を出し、サイドバーで選んだものを動かせるようにする。
    pub(crate) fn 重ねる枠の並び(&self) -> Vec<重ねる枠> {
        let 映している識別子: Vec<&置いたクリップの識別子> = self
            .再生
            .映すものを求める条件()
            .行ごとに映すものを求める(&self.重ね合わせ)
            .into_iter()
            .filter_map(|行が映すもの| match 行が映すもの.映し方 {
                行の映し方::置いたクリップを映す(中身) => {
                    Some(中身.置いたクリップ.識別子())
                }
                行の映し方::末尾で最後のコマを映す {
                    置いたクリップ,
                ..
                } => Some(置いたクリップ.識別子()),
                行の映し方::何も映さない => None,
            })
            .collect();
        self.奥から手前の順の置いたクリップ()
            .filter(|置いた| {
                映している識別子.contains(&置いた.識別子())
                    || self.編集.選んでいるか(置いた.識別子())
            })
            .map(|置いた| 重ねる枠 {
                識別子: 置いた.識別子().clone(),
                矩形: self.掴んでいるもの.今映す矩形(置いた),
                選んでいるか: self.編集.選んでいるか(置いた.識別子()),
            })
            .collect()
    }

    /// 全部の置いたクリップを、奥の行から手前の行の順、行の中は始まりの時刻の順に並べる。
    pub(crate) fn 奥から手前の順の置いたクリップ(
        &self,
    ) -> impl Iterator<Item = &置いたクリップ> {
        self.重ね合わせ
            .行の並び()
            .奥から手前の順の行()
            .iter()
            .flat_map(|行| 行.置いたクリップの並び())
    }

    /// 選んでいる置いたクリップ。選んでいないか、選んでいた置いたクリップが無くなっていれば無い。
    pub(crate) fn 選んでいる置いたクリップ(&self) -> Option<&置いたクリップ> {
        self.重ね合わせ
            .識別子で探す(self.編集.選んでいる置いたクリップの識別子()?)
    }

    /// 置いたクリップを選んでいるか。
    pub(crate) fn 置いたクリップを選んでいるか(
        &self,
        識別子: &置いたクリップの識別子,
    ) -> bool {
        self.編集.選んでいるか(識別子)
    }

    /// 並べた後に置き方を手で直したか。「今のスタックから並べ直す」の前に確かめるかを決める。
    pub(crate) fn 置き方を手で直したか(&self) -> bool {
        self.編集.手で直したか()
    }
}
