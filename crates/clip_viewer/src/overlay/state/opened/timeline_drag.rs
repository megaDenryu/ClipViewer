//! 塊のドラッグを、開いている重ね合わせの掴んでいるものへ当てる。掴み始めで置いたクリップの今の行き先を覚え、動かしている間は仮の行き先だけを変え、
//! 放したときに重ね合わせの `置いたクリップを動かす` で1回だけ確定する。掴み始めから行き先が変わっていなければ(差0の放した等)確定せず、手で直したとしても扱わない。
//! 掴んだ塊が無くなったら、確定せずにドラッグを閉じる。行き先の計算(行の数へ収める・ぶつかった所で止める)は `clip_domain` が持つ。参照: _doc/設計/同時再生.md 2-6

use clip_domain::{置いたクリップの識別子, 重ね合わせの操作エラー};

use super::開いている重ね合わせ;
use crate::overlay::state::grab::掴んでいるもの;
use crate::overlay::state::timeline::{塊のドラッグ, 塊のドラッグの動き};

impl 開いている重ね合わせ {
    /// 置いたクリップの塊のドラッグを始め、今の行き先を掴み始めの行き先として覚える。置いたクリップが無ければドラッグしない。
    pub(crate) fn 塊のドラッグを始める(
        &mut self, 対象: &置いたクリップの識別子
    ) {
        if let Ok(今の行き先) = self.重ね合わせ.行の並び().今の行き先(対象) {
            self.掴んでいるもの = 掴んでいるもの::塊(塊のドラッグ::掴み始める(
                対象.clone(),
                今の行き先,
            ));
        }
    }

    /// ドラッグしている置いたクリップの仮の行き先を、今の行き先へ動きを当てた行き先にする。別の置いたクリップの動きは当てない。
    pub(crate) fn 塊のドラッグを動かす(&mut self, 動き: &塊のドラッグの動き) {
        if self.掴んでいるもの.対象の塊のドラッグ(&動き.対象).is_none() {
            return;
        }
        if let Ok(仮の行き先) = self.重ね合わせ.行の並び().ずらした行き先を求める(
            &動き.対象,
            動き.ずらす量,
            動き.行の差,
        ) {
            self.掴んでいるもの
                .仮の行き先を変える(&動き.対象, 仮の行き先);
        }
    }

    /// 最後の動きを当ててからドラッグを終え、仮の行き先を重ね合わせへ確定する。掴み始めから行き先が変わっていなければ確定しない。
    /// 確定したら、置き方を手で直したことを覚え、行ごとの続く先を断つ(行の中身と時刻の関係が変わるため。`全部の行の続く先を止まるにする`)。
    pub(crate) fn 塊のドラッグを放す(
        &mut self,
        動き: &塊のドラッグの動き,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.塊のドラッグを動かす(動き);
        let Some(ドラッグ) =
            self.掴んでいるもの.塊のドラッグを終えて取り出す(&動き.対象)
        else {
            return Ok(());
        };
        if !ドラッグ.行き先が変わったか() {
            return Ok(());
        }
        let 行き先 = ドラッグ.仮の行き先();
        self.重ね合わせ.置いたクリップを動かす(
            ドラッグ.対象(),
            行き先.行,
            行き先.始まりの時刻,
        )?;
        self.編集.手で直したことを覚える();
        self.全部の行の続く先を止まるにする();
        Ok(())
    }

    /// 掴んだ塊が無くなったときに呼ぶ。その置いたクリップのドラッグを、確定せずに閉じる。
    pub(crate) fn 塊のドラッグを閉じる(
        &mut self, 対象: &置いたクリップの識別子
    ) {
        self.掴んでいるもの.塊のドラッグを終えて取り出す(対象);
    }

    /// 放したを受け取れずに残ったドラッグ(映す矩形と塊のどちらも)を、確定せずに捨てる。安全網が呼ぶ。
    pub(crate) fn 取り残されたドラッグを捨てる(&mut self) {
        self.掴んでいるもの.捨てる();
    }
}
