//! 置き方の編集の操作のうち、ドラッグ(`placement_drag.rs`)を除くもの。置いたクリップを選ぶ・選びを外す・重ねる画面の縦横比を変える・
//! 置いたクリップを取り除く・スタックのクリップから受け継いだ値を今の再生の位置に置く。重ね合わせを変える操作は、`clip_domain` の重ね合わせの操作を通し、
//! 通ったら置き方を手で直したことを覚える。参照: _doc/設計/同時再生.md 2-4・2-5

use clip_domain::{
    クリップから受け継いだ値, 動画の番号, 時間の長さ, 置いたクリップの識別子,
    置いたクリップの識別子の発行元, 重ねる画面の縦横比, 重ね合わせの操作エラー,
};

use super::開いている重ね合わせ;

impl 開いている重ね合わせ {
    /// 毎フレーム、行ごとのコマを載せた後に呼ぶ。置いたばかりの置いたクリップのうち、行のテクスチャにそのコマが載ったものと、
    /// もう重ね合わせに無いものを、置いたばかりから外す。
    pub(super) fn コマが載った置いたばかりの置いたクリップを外す(&mut self) {
        let 重ね合わせ = &self.重ね合わせ;
        let 映像 = &self.映像;
        self.編集.置いたばかりのうち待つものだけ残す(|識別子| {
            重ね合わせ
                .行の並び()
                .置いてある行の番号(識別子)
                .is_ok_and(|行| {
                    !映像.行に置いたクリップのコマが載っているか(行, 識別子)
                })
        });
    }

    /// 置いたクリップを選ぶ。重ね合わせに無い置いたクリップは選ばない。
    pub(crate) fn 置いたクリップを選ぶ(
        &mut self, 識別子: &置いたクリップの識別子
    ) {
        if self.重ね合わせ.識別子で探す(識別子).is_some() {
            self.編集.選ぶ(識別子.clone());
        }
    }

    /// 選びを外す。重ねる画面の何も無い所を押したときに呼ぶ。
    pub(crate) fn 選びを外す(&mut self) {
        self.編集.選びを外す();
    }

    /// 重ねる画面の縦横比を変える。今と同じ縦横比なら何も変えない。
    pub(crate) fn 重ねる画面の縦横比を変える(
        &mut self, 縦横比: 重ねる画面の縦横比
    ) {
        if self.重ね合わせ.縦横比() == 縦横比 {
            return;
        }
        self.重ね合わせ.縦横比を変える(縦横比);
        self.編集.手で直したことを覚える();
    }

    /// 置いたクリップを取り除く。選んでいた置いたクリップなら選びも外す。
    pub(crate) fn 置いたクリップを取り除く(
        &mut self,
        識別子: &置いたクリップの識別子,
    ) -> Result<(), 重ね合わせの操作エラー> {
        self.重ね合わせ.置いたクリップを取り除く(識別子)?;
        if self.編集.選んでいるか(識別子) {
            self.編集.選びを外す();
        }
        self.編集.手で直したことを覚える();
        Ok(())
    }

    /// クリップから受け継いだ値を、今の再生の位置を始まりの時刻にして、その時刻に空いている最も手前の行へ置き、置いた置いたクリップを選ぶ。
    /// 動画の長さは、置く動画をスタックの作業場で開いた情報から配線が渡す。拒まれたら重ね合わせを変えない。
    pub(crate) fn クリップを今の位置に置く(
        &mut self,
        受け継いだ値: クリップから受け継いだ値,
        動画: 動画の番号,
        動画の長さ: 時間の長さ,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) -> Result<(), 重ね合わせの操作エラー> {
        let 始まり = self.再生.位置().時刻();
        let 識別子 = self.重ね合わせ.クリップから受け継いだ値を置く(
            受け継いだ値,
            動画,
            始まり,
            動画の長さ,
            発行元,
        )?;
        self.編集.選ぶ(識別子.clone());
        self.編集.置いたばかりとして覚える(識別子);
        self.編集.手で直したことを覚える();
        Ok(())
    }
}
