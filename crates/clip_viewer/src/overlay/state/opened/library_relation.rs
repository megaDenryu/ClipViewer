//! 開いている重ね合わせとライブラリの関係を読む口と書き換える口。自動保存(`state/library/save.rs`)は、関係(書き換える)と重ね合わせ(読む)を同時に借りる。

use clip_domain::重ね合わせ;

use super::開いている重ね合わせ;
use crate::overlay::state::library::重ね合わせとライブラリの関係;

impl 開いている重ね合わせ {
    /// ライブラリとの関係(未登録か登録済みか)。
    pub(crate) fn ライブラリとの関係(
        &self,
    ) -> &重ね合わせとライブラリの関係 {
        &self.ライブラリとの関係
    }

    /// 書き換えられるライブラリとの関係。保存の知らせを当てるときに使う。
    pub(crate) fn ライブラリとの関係を書き換える(
        &mut self,
    ) -> &mut 重ね合わせとライブラリの関係 {
        &mut self.ライブラリとの関係
    }

    /// 書き換えられるライブラリとの関係と、今の重ね合わせを同時に借りる。今の重ね合わせで保存を頼むときに使う。
    pub(crate) fn ライブラリとの関係と重ね合わせ(
        &mut self,
    ) -> (&mut 重ね合わせとライブラリの関係, &重ね合わせ) {
        (&mut self.ライブラリとの関係, &self.重ね合わせ)
    }

    /// ライブラリとの関係を置き換える。登録したときに使う。
    pub(crate) fn ライブラリとの関係を置き換える(
        &mut self,
        関係: 重ね合わせとライブラリの関係,
    ) {
        self.ライブラリとの関係 = 関係;
    }
}
