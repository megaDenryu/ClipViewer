//! 開いている重ね合わせとライブラリの関係。関係を読むことと置き換えることと、関係と今の重ね合わせの両方を使う自動保存の手順
//! (保存を頼むときかを見る・今の重ね合わせで保存を頼む・保存の知らせを当てる・次に見るまでの時間)を、開いている重ね合わせのメソッドとして持つ。
//! 参照: _doc/設計/同時再生.md 2-7、_doc/設計/ライブラリ.md 判断5

use std::time::{Duration, Instant};

use clip_domain::重ね合わせの識別子;
use clip_library::{保存の番号, 重ね合わせのライブラリの操作エラー};

use super::開いている重ね合わせ;
use crate::library_common::save::見た結果;
use crate::overlay::state::library::{
    重ね合わせとライブラリの関係, 重ね合わせのライブラリの接続, 重ね合わせの保存の目的,
};

impl 開いている重ね合わせ {
    /// ライブラリとの関係(未登録か登録済みか)。
    pub(crate) fn ライブラリとの関係(
        &self,
    ) -> &重ね合わせとライブラリの関係 {
        &self.ライブラリとの関係
    }

    /// ライブラリとの関係を置き換える。登録したときに使う。
    pub(crate) fn ライブラリとの関係を置き換える(
        &mut self,
        関係: 重ね合わせとライブラリの関係,
    ) {
        self.ライブラリとの関係 = 関係;
    }

    /// 登録済みなら今の重ね合わせを見て、保存を頼むときか。未登録なら保存しない。
    pub(crate) fn 保存を頼むときか(&mut self, 今: Instant) -> bool {
        match &mut self.ライブラリとの関係 {
            重ね合わせとライブラリの関係::登録済み(登録済み) => {
                登録済み.並びを見る(&self.重ね合わせ, 今) == 見た結果::保存する
            }
            重ね合わせとライブラリの関係::未登録 => false,
        }
    }

    /// 登録済みで、今の重ね合わせがファイルに書けていないか。未登録なら書くものが無い。
    pub(crate) fn 保存されていないか(&self) -> bool {
        match &self.ライブラリとの関係 {
            重ね合わせとライブラリの関係::登録済み(登録済み) => {
                登録済み.保存の様子().保存されていないか(&self.重ね合わせ)
            }
            重ね合わせとライブラリの関係::未登録 => false,
        }
    }

    /// 登録済みなら、今の重ね合わせで中身を差し替えて保存を頼む。頼めなければ失敗として覚え、間隔を置いて頼み直す。
    pub(crate) fn 今の重ね合わせの保存を頼む(
        &mut self,
        接続: &mut 重ね合わせのライブラリの接続,
    ) {
        let 重ね合わせとライブラリの関係::登録済み(登録済み) = &mut self.ライブラリとの関係
        else {
            return;
        };
        let 中身 = 登録済み
            .中身()
            .clone()
            .重ね合わせを差し替えた(self.重ね合わせ.clone(), 接続.今の日時());
        match 接続.保存を頼む(中身.clone(), 重ね合わせの保存の目的::自動保存)
        {
            Ok(番号) => 登録済み.保存を頼んだ(中身, 番号),
            Err(理由) => 登録済み.保存を頼めなかった(理由),
        }
    }

    /// 識別子の重ね合わせの保存の知らせを当てる。開いている重ね合わせがその識別子の登録済みなら保存の様子へ当てて真を返し、そうでなければ偽を返す。
    pub(crate) fn 保存の知らせを当てる(
        &mut self,
        識別子: &重ね合わせの識別子,
        番号: 保存の番号,
        結果: Result<(), 重ね合わせのライブラリの操作エラー>,
    ) -> bool {
        match self.ライブラリとの関係.識別子が同じなら(識別子) {
            Some(登録済み) => {
                登録済み.保存を終えた(番号, 結果);
                true
            }
            None => false,
        }
    }

    /// 次に重ね合わせを見て保存を頼むかもしれない時刻までの残り。未登録なら無い。
    pub(crate) fn 次に重ね合わせを見るまでの時間(
        &self,
        今: Instant,
    ) -> Option<Duration> {
        match &self.ライブラリとの関係 {
            重ね合わせとライブラリの関係::登録済み(登録済み) => {
                登録済み.次に並びを見るまでの時間(今)
            }
            重ね合わせとライブラリの関係::未登録 => None,
        }
    }
}
