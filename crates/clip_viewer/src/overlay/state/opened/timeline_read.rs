//! タイムラインを画面が読む口。行ごとに描く塊の並び(塊のドラッグの間はドラッグしている塊を仮の行き先で並べる)と、選んでいる行の番号と空かと、
//! 空の行を足せるかを返す。書き換える口(`timeline_drag.rs`・`timeline_rows.rs`)と分ける。参照: _doc/設計/同時再生.md 2-6

use clip_domain::{同時に重ねられる行の数, 置いたクリップ};

use super::開いている重ね合わせ;
use crate::overlay::state::timeline::{
    タイムラインに描く塊, 選んでいる行の番号と空か
};

impl 開いている重ね合わせ {
    /// タイムラインに描く塊を、奥の行から手前の行の順の行ごとに並べる(重ね合わせの行の数だけの並びを返す)。
    /// 塊をドラッグしている間は、ドラッグしている塊を仮の行き先の行と始まりの時刻で並べる(重ね合わせは変えない)。
    pub(crate) fn タイムラインに描く行の並び(
        &self,
    ) -> Vec<Vec<タイムラインに描く塊>> {
        let 行の並び = self.重ね合わせ.行の並び();
        let mut 描く並び = vec![Vec::new(); 行の並び.行の数()];
        for (番号, 行) in 行の並び.奥から手前の順の行().iter().enumerate() {
            for 置いた in 行.置いたクリップの並び() {
                let (描く行, 塊) = self.描く行と塊(番号, 置いた);
                if let Some(行の塊) = 描く並び.get_mut(描く行) {
                    行の塊.push(塊);
                }
            }
        }
        描く並び
    }

    /// 選んでいる行の番号と、その行が空か。行を選んでいないか、選んでいた行が無くなっていれば無い。
    pub(crate) fn 選んでいる行の番号と空か(
        &self,
    ) -> Option<選んでいる行の番号と空か> {
        let 行 = self.編集.選んでいる行()?;
        let 中身 = self
            .重ね合わせ
            .行の並び()
            .奥から手前の順の行()
            .get(行.番号())?;
        Some(選んでいる行の番号と空か {
            行,
            空か: 中身.置いたクリップの並び().is_empty(),
        })
    }

    /// 空の行を手前に足せるか。行が同時に重ねられる行の数(8)より少ないときだけ足せる。
    pub(crate) fn 空の行を足せるか(&self) -> bool {
        self.重ね合わせ.行の並び().行の数() < 同時に重ねられる行の数
    }

    // 置いてある行の番号の置いたクリップを、描く行の番号と描く塊にする。塊をドラッグしている間は仮の行き先で描く。
    fn 描く行と塊(
        &self,
        置いてある行: usize,
        置いた: &置いたクリップ,
    ) -> (usize, タイムラインに描く塊) {
        let (描く行, 始まりの時刻) = self
            .掴んでいるもの
            .対象の塊のドラッグ(置いた.識別子())
            .map_or(
                (置いてある行, 置いた.始まりの時刻()),
                |ドラッグ| {
                    let 行き先 = ドラッグ.仮の行き先();
                    (行き先.行.番号(), 行き先.始まりの時刻)
                },
            );
        let 塊 = タイムラインに描く塊 {
            識別子: 置いた.識別子().clone(),
            始まりの時刻,
            占める長さ: 置いた.占める長さ(),
            繰り返しの回数: 置いた.受け継いだ値().リピート回数,
            選んでいるか: self.編集.選んでいるか(置いた.識別子()),
        };
        (描く行, 塊)
    }
}
