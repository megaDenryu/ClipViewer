//! タイムラインの中身を画面が読むメソッド。行ごとに描く塊の並び(塊のドラッグの間はドラッグしている塊を仮の行き先で並べる)と、選んでいる行の番号と空の行かの組を返す。
//! 書き換えるメソッド(`timeline_drag.rs`・`timeline_rows.rs`)と分ける。行があるか・空か・足せるか・上から何番目かは、`clip_domain` の
//! タイムラインの行の並びが答える。参照: _doc/設計/同時再生.md 2-6

use clip_domain::{
    置いたクリップ, 置いたクリップの行き先, 行の番号, 重ね合わせ上の秒
};

use super::開いている重ね合わせ;
use crate::overlay::state::timeline::{
    タイムラインに描く塊, 選んでいる行の番号と空の行かの組
};

impl 開いている重ね合わせ {
    /// タイムラインに描く塊を、奥の行から手前の行の順の行ごとに並べる(重ね合わせの行の数だけの並びを返す)。
    /// 塊をドラッグしている間は、ドラッグしている塊を仮の行き先の行と始まりの時刻で並べる(重ね合わせは変えない)。
    pub(crate) fn タイムラインに描く行の並び(
        &self,
    ) -> Vec<Vec<タイムラインに描く塊>> {
        let 行の並び = self.重ね合わせ.行の並び();
        let mut 描く並び = vec![Vec::new(); 行の並び.行の数()];
        for (番号, 行) in 行の並び.奥から手前の順の行().iter().enumerate() {
            for 置いた in 行.置いたクリップの並び() {
                let 行き先 = self.描く行き先(置いた, 行の番号::番号から作成する(番号));
                if let Some(行の塊) = 描く並び.get_mut(行き先.行.番号()) {
                    行の塊.push(self.描く塊(置いた, 行き先.始まりの時刻));
                }
            }
        }
        描く並び
    }

    /// 選んでいる行の番号と、その行が空か。行を選んでいないか、選んでいた行が無くなっていれば無い。
    pub(crate) fn 選んでいる行の番号と空の行かの組(
        &self,
    ) -> Option<選んでいる行の番号と空の行かの組> {
        let 行 = self.編集.選んでいる行()?;
        let 空か = self.重ね合わせ.行の並び().空の行か(行)?;
        Some(選んでいる行の番号と空の行かの組 { 行, 空か })
    }

    // 置いたクリップを描く行き先。塊をドラッグしている間は仮の行き先、そうでなければ置いてある行と始まりの時刻である。
    fn 描く行き先(
        &self,
        置いた: &置いたクリップ,
        置いてある行: 行の番号,
    ) -> 置いたクリップの行き先 {
        self.掴んでいるもの
            .対象の塊のドラッグ(置いた.識別子())
            .map_or(
                置いたクリップの行き先 {
                    行: 置いてある行,
                    始まりの時刻: 置いた.始まりの時刻(),
                },
                |ドラッグ| ドラッグ.仮の行き先(),
            )
    }

    fn 描く塊(
        &self,
        置いた: &置いたクリップ,
        始まりの時刻: 重ね合わせ上の秒,
    ) -> タイムラインに描く塊 {
        タイムラインに描く塊 {
            識別子: 置いた.識別子().clone(),
            始まりの時刻,
            占める長さ: 置いた.占める長さ(),
            繰り返しの回数: 置いた.受け継いだ値().リピート回数,
            選んでいるか: self.編集.選んでいるか(置いた.識別子()),
        }
    }
}
