//! 開いている重ね合わせを画面が読む口。再生の位置と長さ・全体ループか・重ねる画面の縦横比・進み具合・描き直しを続ける必要があるか・
//! 重ねる画面に描く行の並び・音の様子の文の並びを返す。書き換える口(`mod.rs`)と分ける。

use clip_domain::{
    重ねる画面の縦横比, 重ね合わせの再生位置, 重ね合わせの進み具合, 重ね合わせ上の秒,
};

use super::開いている重ね合わせ;
use crate::overlay::state::drawn_rows::重ねる画面に描く行;

impl 開いている重ね合わせ {
    pub(crate) fn 再生の位置(&self) -> 重ね合わせの再生位置 {
        self.再生.位置()
    }
    pub(crate) fn 重ね合わせの長さ(&self) -> 重ね合わせ上の秒 {
        self.重ね合わせ.重ね合わせの長さ()
    }
    pub(crate) fn 全体ループか(&self) -> bool {
        self.再生.全体ループか()
    }
    pub(crate) fn 重ねる画面の縦横比(&self) -> 重ねる画面の縦横比 {
        self.重ね合わせ.縦横比()
    }
    /// 重ね合わせの長さに対する再生の位置の進み具合。画面の位置の棒が読む。
    pub(crate) fn 進み具合(&self) -> 重ね合わせの進み具合 {
        self.再生.位置().進み具合(&self.重ね合わせ)
    }
    /// 入力が無くても描き直しを続ける必要があるか。再生している間と、映像の供給が区間を溜めているか行のコマを待っている間は進め続ける。
    pub(crate) fn 描き直しを続ける必要があるか(&self) -> bool {
        self.再生しているか() || self.映像.描き直しを続ける必要があるか()
    }
    /// 重ねる画面に描く行を、奥の行から手前の行の順に並べる(`重ねる画面に描く行::並びを求める`)。
    pub(crate) fn 重ねる画面に描く行の並び(&self) -> Vec<重ねる画面に描く行> {
        let 条件 = self.再生.映すものを求める条件();
        重ねる画面に描く行::並びを求める(
            &self.重ね合わせ,
            条件,
            &self.映像,
            &self.編集,
        )
    }
    /// 動画ごとの音の様子の文の並び(鳴らせる動画の分は出さない)。
    pub(crate) fn 音の様子の文の並び(&self) -> Vec<String> {
        self.音.様子の文の並び()
    }
}
