//! 開いている重ね合わせを画面と試験が読む口。重ね合わせ・再生しているか・再生の位置と長さ・全体ループか・重ねる画面の縦横比・描き直しを続ける必要があるか・
//! 重ねる画面に描く行の並び・音の様子の文の並びと、試験が読む映像の供給と音を返す。書き換える口(`mod.rs`)と分ける。

use clip_domain::{
    重ねる画面の縦横比, 重ね合わせ, 重ね合わせの再生位置, 重ね合わせ上の秒
};

use super::開いている重ね合わせ;
use crate::overlay::state::drawn_rows::重ねる画面に描く行;
#[cfg(test)]
use crate::overlay::{
    feed::重ね合わせの映像の供給を作れたか, state::sound::開いている重ね合わせの音,
};

impl 開いている重ね合わせ {
    /// 開いている重ね合わせ。画面が置いたクリップの名前と音の設定を並べるときに読む。
    pub(crate) fn 重ね合わせ(&self) -> &重ね合わせ {
        &self.重ね合わせ
    }

    /// 映像の供給を作れたか。試験で、供給を作れたかと行に載ったコマを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 映像の供給を作れたか(
        &self,
    ) -> &重ね合わせの映像の供給を作れたか {
        &self.映像
    }

    /// 開いている重ね合わせの音。試験が、音の供給が受け取った開き直し方を読むために使う。
    #[cfg(test)]
    pub(crate) fn 音(&self) -> &開いている重ね合わせの音 {
        &self.音
    }

    pub(crate) fn 再生しているか(&self) -> bool {
        self.再生.再生しているか()
    }
    pub(crate) fn 再生の位置(&self) -> 重ね合わせの再生位置 {
        self.再生.位置()
    }
    pub(crate) fn 重ね合わせの長さ(&self) -> 重ね合わせ上の秒 {
        self.重ね合わせ.重ね合わせの長さ()
    }
    pub(crate) fn 全体ループか(&self) -> bool {
        self.再生.全体ループか()
    }
    pub(crate) fn 重ねる画面の縦横比(&self) -> 重ねる画面の縦横比 {
        self.重ね合わせ.縦横比()
    }
    /// 入力が無くても描き直しを続ける必要があるか。再生している間と、映像の供給が区間を溜めているか行のコマを待っている間は進め続ける。
    pub(crate) fn 描き直しを続ける必要があるか(&self) -> bool {
        self.再生しているか() || self.映像.描き直しを続ける必要があるか()
    }
    /// 重ねる画面に描く行を、奥の行から手前の行の順に並べる(`重ねる画面に描く行::並びを求める`)。
    pub(crate) fn 重ねる画面に描く行の並び(&self) -> Vec<重ねる画面に描く行> {
        let 条件 = self.再生.映すものを求める条件();
        重ねる画面に描く行::並びを求める(
            &self.重ね合わせ,
            条件,
            &self.映像,
            &self.編集,
            &self.掴んでいるもの,
        )
    }
    /// 動画ごとの音の様子の文の並び(鳴らせる動画の分は出さない)。
    pub(crate) fn 音の様子の文の並び(&self) -> Vec<String> {
        self.音.様子の文の並び()
    }
}
