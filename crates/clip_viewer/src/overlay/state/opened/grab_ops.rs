//! 掴んでいるもの全体の操作。時間の軸の位置の線のドラッグを当てることと、掴んでいるものから流し読みの開き直し方と音の再生の様子を決めることと、
//! 放したを受け取れずに残ったドラッグを捨てること。位置の線を掴んでいる間は、スタックの作業場の再生位置の帯と同じく、
//! 位置だけを動かし、流し読みを開き直さず、音を黙らせる。放したら開き直し、鳴らし直す。参照: _doc/設計/画面.md 判断5・判断10、同時再生.md 2-6

use audio_output::再生の様子;
use clip_domain::重ね合わせ上の秒;

use super::開いている重ね合わせ;
use crate::overlay::state::grab::{位置の線の段階, 掴んでいるもの};
use crate::stream_rules::流し読みの開き直し;

impl 開いている重ね合わせ {
    /// 時間の軸の位置の線のドラッグを当てる。どの段階も再生の位置をその時刻へ動かし、掴み始めた・動かしているでは位置の線を掴み、放したでは離す。
    /// ほかのものを掴んでいる間に届いた位置の線の段階は、位置だけを動かす。
    pub(crate) fn 位置の線のドラッグを当てる(
        &mut self,
        段階: 位置の線の段階,
        時刻: 重ね合わせ上の秒,
    ) {
        match 段階 {
            位置の線の段階::掴み始めた | 位置の線の段階::動かしている => {
                if matches!(self.掴んでいるもの, 掴んでいるもの::無し) {
                    self.掴んでいるもの = 掴んでいるもの::位置の線;
                }
            }
            位置の線の段階::放した => {
                if self.掴んでいるもの.位置の線を掴んでいるか() {
                    self.掴んでいるもの.捨てる();
                }
            }
        }
        self.再生の位置を動かす(時刻);
    }

    /// このフレームで流し読みを開き直してよいか。位置の線を掴んでいる間は映像も音も控える(画面.md 判断5)。
    pub(crate) fn 流し読みの開き直し(&self) -> 流し読みの開き直し {
        if self.掴んでいるもの.位置の線を掴んでいるか() {
            流し読みの開き直し::控える
        } else {
            流し読みの開き直し::してよい
        }
    }

    /// 行ごとの再生の指示に載せる再生の様子。再生していても、位置の線を掴んでいる間は止めている指示にして黙らせる(画面.md 判断10)。
    pub(super) fn 音の再生の様子(&self) -> 再生の様子 {
        if self.再生しているか() && !self.掴んでいるもの.位置の線を掴んでいるか()
        {
            再生の様子::再生している
        } else {
            再生の様子::止めている
        }
    }

    /// 放したを受け取れずに残ったドラッグ(映す矩形・塊・位置の線)を、確定せずに捨てる。安全網が呼ぶ。位置の線なら、動かした位置はそのまま残る。
    pub(crate) fn 取り残されたドラッグを捨てる(&mut self) {
        self.掴んでいるもの.捨てる();
    }
}
