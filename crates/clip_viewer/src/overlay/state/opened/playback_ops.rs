//! 開いている重ね合わせの再生の操作。再生と停止を切り替えることと、全体ループを設定することと、再生の位置を動かすことと、
//! 行の続く先を止まるにすること。続く先を止まるにするとは、行のテクスチャに残る前の置いたクリップのコマを別の置いたクリップの代わりに描かないようにし、
//! その行の位置を飛ばした回数を進めて、行の音の再生器にずれを待たずに新しい位置へ合わせさせることである。
//! 長さが0秒の重ね合わせは再生を始めない。参照: _doc/設計/同時再生.md 2-6・5-2 の7・5-3

use clip_domain::{
    同時に重ねられる行の数, 時刻, 行の番号, 重ね合わせの再生位置, 重ね合わせ上の秒
};

use super::開いている重ね合わせ;

impl 開いている重ね合わせ {
    /// 再生を始められるか。置いたクリップが無い(長さが0秒の)重ね合わせは、映すものが無く時計も0秒に留まるため、再生を始めない。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.重ね合わせの長さ() > 時刻::先頭
    }

    /// 再生と停止を切り替える。再生を始められないときは、止まったままにする。
    pub(crate) fn 再生を切り替える(&mut self) {
        if self.再生しているか() || self.再生を始められるか() {
            self.再生.再生を切り替える(&self.重ね合わせ);
        }
    }

    pub(crate) fn 全体ループを設定する(&mut self, 有効: bool) {
        self.再生.全体ループを設定する(有効);
    }

    /// 再生の位置を時刻へ動かす。重ね合わせの長さより後ろは長さで止める。再生しているかは変えない。
    /// 注意: 位置を飛ばすので、全部の行の続く先を止まるにする(`clip_domain` の `重ね合わせの再生位置::時刻から作成する` の注意。
    /// そうしないと、前の置いたクリップの最後のコマが、動かした先で前の映す矩形に残る)。
    pub(super) fn 再生の位置を動かす(&mut self, 時刻: 重ね合わせ上の秒) {
        let 長さ = self.重ね合わせ.重ね合わせの長さ();
        let 収めた時刻 = if 時刻 > 長さ { 長さ } else { 時刻 };
        self.再生
            .再生の位置を移す(重ね合わせの再生位置::時刻から作成する(
                収めた時刻,
            ));
        for 番号 in 0..同時に重ねられる行の数 {
            self.行の続く先を止まるにする(行の番号::番号から作成する(番号));
        }
    }

    /// 行の番号の行の続く先を止まるにする(映像の続く先と、音の位置を飛ばした回数)。行の中身や番号や再生の位置が変わったとき、影響のある行について呼ぶ。
    pub(super) fn 行の続く先を止まるにする(&mut self, 行: 行の番号) {
        self.映像.行の続く先を止まるにする(行);
        self.音.行の位置を飛ばした回数を進める(行);
    }
}
