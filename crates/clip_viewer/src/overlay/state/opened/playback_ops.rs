//! 開いている重ね合わせの再生の操作。再生と停止を切り替えることと、全体ループを設定することと、時間の軸で再生の位置を動かすこと。
//! 長さが0秒の重ね合わせは再生を始めない。位置を動かしたら、行ごとの再生のつながりを断つ(`timeline_rows.rs`)。参照: _doc/設計/同時再生.md 2-6・5-2

use clip_domain::{時刻, 重ね合わせの再生位置, 重ね合わせ上の秒};

use super::開いている重ね合わせ;

impl 開いている重ね合わせ {
    /// 再生を始められるか。置いたクリップが無い(長さが0秒の)重ね合わせは、映すものが無く時計も0秒に留まるため、再生を始めない。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.重ね合わせの長さ() > 時刻::先頭
    }

    /// 再生と停止を切り替える。再生を始められないときは、止まったままにする。
    pub(crate) fn 再生を切り替える(&mut self) {
        if self.再生しているか() || self.再生を始められるか() {
            self.再生.再生を切り替える(&self.重ね合わせ);
        }
    }

    pub(crate) fn 全体ループを設定する(&mut self, 有効: bool) {
        self.再生.全体ループを設定する(有効);
    }

    /// 再生の位置を、時間の軸で指した時刻へ動かす。重ね合わせの長さより後ろは長さで止める。再生しているかは変えない。
    /// 注意: 位置を飛ばすので、全部の行の続く先を止まるにする(`clip_domain` の `重ね合わせの再生位置::時刻から作成する` の注意。
    /// そうしないと、前の置いたクリップの最後のコマが、動かした先で前の映す矩形に残る)。
    pub(crate) fn 位置を動かす(&mut self, 時刻: 重ね合わせ上の秒) {
        let 長さ = self.重ね合わせ.重ね合わせの長さ();
        let 収めた時刻 = if 時刻 > 長さ { 長さ } else { 時刻 };
        self.再生.位置を移す(重ね合わせの再生位置::時刻から作成する(
            収めた時刻,
        ));
        self.行ごとの再生のつながりを断つ();
    }
}
