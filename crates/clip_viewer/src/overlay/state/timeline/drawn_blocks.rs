//! タイムラインに描くものの値の型。画面が時間の行の並びへ渡す塊と、選んでいる行の番号と空の行かの組を、状態を借りずに持つ。
//! 塊のドラッグの間は、ドラッグしている塊を仮の行き先の行と始まりの時刻で持つ(重ね合わせは変えない)。参照: _doc/設計/同時再生.md 2-6

use clip_domain::{
    リピート回数, 時間の長さ, 置いたクリップの識別子, 行の番号, 重ね合わせ上の秒
};

/// タイムラインに描く塊とは、タイムラインの行に描く1つの置いたクリップの、識別子と、描く始まりの時刻と、占める長さと、
/// 周回の区切りを描くための繰り返しの回数と、選んでいるかの組のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct タイムラインに描く塊 {
    pub(crate) 識別子: 置いたクリップの識別子,
    pub(crate) 始まりの時刻: 重ね合わせ上の秒,
    pub(crate) 占める長さ: 時間の長さ,
    pub(crate) 繰り返しの回数: リピート回数,
    pub(crate) 選んでいるか: bool,
}

/// 選んでいる行の番号と空の行かの組とは、選んでいるタイムラインの行の番号と、その行が置いたクリップを持たない空の行かの組のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 選んでいる行の番号と空の行かの組 {
    pub(crate) 行: 行の番号,
    pub(crate) 空か: bool,
}
