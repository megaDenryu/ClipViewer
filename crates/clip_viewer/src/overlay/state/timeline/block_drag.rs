//! 塊のドラッグ。タイムラインの塊をドラッグしている置いたクリップと、掴み始めの行き先と、今の動きを当てた仮の行き先を持つ。
//! 時間の行の並びの部品は掴み始めからの累積の時間の差と行の差を発するため、毎回、置いたクリップの掴み始めの行き先から求め直す
//! (映す矩形のドラッグと同じ流儀)。参照: _doc/設計/同時再生.md 2-6

use clip_domain::{
    時刻をずらす量, 置いたクリップの行き先, 置いたクリップの識別子, 行の差
};

/// 塊のドラッグの動きとは、ドラッグしている置いたクリップと、掴み始めからの時刻をずらす量と行の差の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 塊のドラッグの動き {
    pub(crate) 対象: 置いたクリップの識別子,
    pub(crate) ずらす量: 時刻をずらす量,
    pub(crate) 行の差: 行の差,
}

/// 塊のドラッグとは、ドラッグしている置いたクリップと、掴み始めたときの行き先と、今の動きを当てた仮の行き先の組のことである。
/// 不変条件: 掴み始めた直後の仮の行き先は掴み始めの行き先と同じである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 塊のドラッグ {
    対象: 置いたクリップの識別子,
    掴み始めの行き先: 置いたクリップの行き先,
    仮の行き先: 置いたクリップの行き先,
}

impl 塊のドラッグ {
    /// 置いたクリップの今の行き先を掴み始めの行き先にしてドラッグを始める。
    pub(crate) fn 掴み始める(
        対象: 置いたクリップの識別子,
        今の行き先: 置いたクリップの行き先,
    ) -> Self {
        Self {
            対象,
            掴み始めの行き先: 今の行き先,
            仮の行き先: 今の行き先,
        }
    }

    /// ドラッグしている置いたクリップか。
    pub(crate) fn 対象か(&self, 識別子: &置いたクリップの識別子) -> bool {
        &self.対象 == 識別子
    }

    pub(crate) fn 対象(&self) -> &置いたクリップの識別子 {
        &self.対象
    }

    pub(crate) fn 仮の行き先(&self) -> 置いたクリップの行き先 {
        self.仮の行き先
    }

    pub(crate) fn 仮の行き先を変える(
        &mut self, 仮の行き先: 置いたクリップの行き先
    ) {
        self.仮の行き先 = 仮の行き先;
    }

    pub(crate) fn 掴み始めの行き先(&self) -> 置いたクリップの行き先 {
        self.掴み始めの行き先
    }

    /// 掴み始めから行き先が変わったか。動かさずに放したときと、ぶつかってすぐに止まったときは変わっていない。
    /// 始まりの時刻は丸めの許容誤差で比べる(`置いたクリップの行き先::同じ行き先か`)。
    pub(crate) fn 行き先が変わったか(&self) -> bool {
        !self.仮の行き先.同じ行き先か(&self.掴み始めの行き先)
    }
}
