//! 置かなかったクリップの報告。「今のスタックから並べる」で置かなかったクリップの名前と理由を、次に並べるまで画面に出し続けるために持つ。
//! 知らせは3秒で消えるため、名前の並びが長くなる一覧は知らせに入れず、この報告として画面の上に出す。参照: _doc/設計/同時再生.md 2-2・4-3

use clip_domain::{
    スタックから並べるエラー, 同時に重ねられる行の数, 置かなかったクリップ, 置かなかった理由,
};

use super::重ね合わせの作業場の状態;

/// 置かなかったクリップの報告とは、最後に「今のスタックから並べる」を押したときに、再生できるのに置かなかったクリップを、スタックの順に並べたもののことである。
/// 全部を置いたとき(と、まだ並べていないとき)は空である。
#[derive(Debug, Default)]
pub(crate) struct 置かなかったクリップの報告(Vec<置かなかったクリップ>);

impl 置かなかったクリップの報告 {
    /// 画面に出す文の並び。置く操作が拒んだクリップは1つずつ理由を添えて出し、行の数の上限で置かなかったクリップは数と名前を1つの文にまとめる。
    pub(crate) fn 画面に出す文の並び(&self) -> Vec<String> {
        let mut 文の並び: Vec<String> = self
            .0
            .iter()
            .filter_map(|置かなかった| match &置かなかった.理由 {
                置かなかった理由::置く操作が拒んだ(理由) => Some(format!(
                    "「{}」を置かなかった: 置けない({理由})",
                    置かなかった.名前.文字列()
                )),
                置かなかった理由::行の数の上限を超える => None,
            })
            .collect();
        let 上限で置かなかった名前: Vec<String> = self
            .0
            .iter()
            .filter(|置かなかった| {
                置かなかった.理由 == 置かなかった理由::行の数の上限を超える
            })
            .map(|置かなかった| format!("「{}」", 置かなかった.名前.文字列()))
            .collect();
        if !上限で置かなかった名前.is_empty() {
            文の並び.push(format!(
                "並べられるのは{同時に重ねられる行の数}つまでのため置かなかったクリップ({}個): {}",
                上限で置かなかった名前.len(),
                上限で置かなかった名前.concat()
            ));
        }
        文の並び
    }
}

impl 重ね合わせの作業場の状態 {
    /// 並べた重ね合わせを開いた後に呼ぶ。置かなかったクリップを報告として覚え、並べた数と、置かなかったクリップがあればその数を知らせる。
    pub(crate) fn 並べた結果を知らせる(
        &mut self,
        並べた数: usize,
        置かなかったクリップの一覧: Vec<置かなかったクリップ>,
    ) {
        let 置かなかった数 = 置かなかったクリップの一覧.len();
        self.置かなかったクリップの報告 =
            置かなかったクリップの報告(置かなかったクリップの一覧);
        self.知らせ.出す(match 置かなかった数 {
            0 => format!("今のスタックから{並べた数}個のクリップを並べた"),
            _ => format!(
                "今のスタックから{並べた数}個のクリップを並べた。{置かなかった数}個のクリップは置かなかった(理由は画面の上に出す)"
            ),
        });
    }

    /// 置けるクリップが1つも無く、重ね合わせを作れなかったことを知らせる。開いている重ね合わせは変えない。
    pub(crate) fn 並べられなかったことを知らせる(
        &mut self,
        エラー: スタックから並べるエラー,
    ) {
        match エラー {
            スタックから並べるエラー::再生できるクリップが無い => {
                self.置かなかったクリップの報告 = 置かなかったクリップの報告::default();
                self.知らせ
                    .出す("スタックに再生できるクリップが無いため、並べられない");
            }
            スタックから並べるエラー::置けるクリップが無い(一覧) => {
                self.置かなかったクリップの報告 = 置かなかったクリップの報告(一覧);
                self.知らせ.出す(
                    "今のスタックのクリップをどれも置けないため、並べられない(理由は画面の上に出す)",
                );
            }
        }
    }
}
