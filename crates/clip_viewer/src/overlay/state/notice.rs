//! 重ね合わせの作業場の知らせ。重ね合わせの作業場の操作の結果を利用者へ知らせる一時的な文を、最近のものから数個だけ持つ。
//! スタックの作業場の通知(`state::通知`)とは別に持つ。重ね合わせの作業場の層はスタックの作業場の `state` を使わず、
//! スタックの作業場の通知は重ね合わせが前の間は見えないためである。

use std::collections::VecDeque;

use sengen_egui::{並べる通知, 通知の回};

/// 並べて出す知らせの数の上限。スタックの作業場の通知と同じ数にする。
const 並べる数の上限: usize = 4;

/// 重ね合わせの作業場の知らせとは、最近出した知らせの文とそれぞれの回の並び(古い順)と、次に出す知らせの回の組のことである。
#[derive(Debug, Default)]
pub(crate) struct 重ね合わせの作業場の知らせ {
    最近: VecDeque<(通知の回, String)>,
    次の回: 通知の回,
}

impl 重ね合わせの作業場の知らせ {
    /// 新しい知らせを出す。同じ文を続けて出しても、回を進めるので表示し直される。
    pub(crate) fn 出す(&mut self, 文面: impl Into<String>) {
        let 回 = self.次の回;
        self.次の回 = 回.次();
        self.最近.push_back((回, 文面.into()));
        if self.最近.len() > 並べる数の上限 {
            self.最近.pop_front();
        }
    }

    /// 画面に並べる最近の知らせ(古い順)。
    pub(crate) fn 並べる通知(&self) -> Vec<並べる通知> {
        self.最近
            .iter()
            .map(|(回, 文面)| 並べる通知::作成する(*回, 文面.clone()))
            .collect()
    }
}
