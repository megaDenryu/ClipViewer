//! 全体の音量。重ね合わせの作業場の音量のつまみと「全体を消音」が表示し、行ごとの再生の指示に掛ける、スタックの作業場と共有する見る側の設定の音量。
//! 配線(`app/stack_values.rs`)がスタックの作業場の音量の設定から読んで渡す。消音の規則はスタックの作業場の1か所にあり、ここでは繰り返さない。
//! 参照: _doc/設計/同時再生.md 2-6

use clip_domain::音量;

/// 全体の音量とは、スタックの作業場と共有する見る側の設定の、つまみで選んだ音量と、全体を消音しているかと、
/// それらからスタックの作業場の規則で決まる鳴らす音量(消音しているなら無音)の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 全体の音量 {
    pub(crate) つまみの値: 音量,
    pub(crate) 消音しているか: bool,
    pub(crate) 鳴らす音量: 音量,
}

impl 全体の音量 {
    /// 試験で使う、起動したときの音量で消音していない全体の音量。
    #[cfg(test)]
    pub(crate) const 試験で使う起動時の値: Self = Self {
        つまみの値: 音量::起動したときの音量,
        消音しているか: false,
        鳴らす音量: 音量::起動したときの音量,
    };
}
