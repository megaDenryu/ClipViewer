//! 写したスタックの保存の失敗。重ね合わせが前の間に、作業場を移る前に頼んだスタックの保存が失敗したら、重ね合わせの作業場の知らせにも出す。
//! スタックの作業場の画面(ヘッダーの保存の様子)は、重ね合わせが前の間は見えないためである。参照: _doc/設計/同時再生.md 2-8

/// 見たスタックの保存とは、配線が毎フレーム見た、スタックの作業場の開いているスタックの保存の様子の区別のことである。
/// 登録していないスタックは保存しないため、失敗していないとして渡す。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 見たスタックの保存 {
    失敗した { 理由: String },
    結果を待っている,
    失敗していない,
}

/// 写したスタックの保存の失敗とは、重ね合わせの作業場の知らせへ最後に写したスタックの保存の失敗の理由(写していないか、その後に保存が成功していれば無い)のことである。
/// 失敗した保存は間隔を置いて頼み直され(頼み直した保存の結果を待つ間は保存中になる)、同じ理由で失敗し続けるため、
/// 同じ理由を頼み直すたびに知らせ直さないよう覚えておく。
#[derive(Debug, Default)]
pub(crate) struct 写したスタックの保存の失敗(Option<String>);

impl 写したスタックの保存の失敗 {
    /// 見たスタックの保存を覚え、前に写した理由と違う失敗なら、知らせに出す文を返す。結果を待っている間は覚えた理由を残し、
    /// 失敗していなければ消す。そのため、保存が一度成功した後にまた失敗すると、同じ理由でも知らせ直す。
    pub(crate) fn 覚えて新しい失敗なら知らせの文を返す(
        &mut self,
        見た: 見たスタックの保存,
    ) -> Option<String> {
        match 見た {
            見たスタックの保存::失敗した { 理由 } => {
                let 新しい失敗か = self.0.as_ref() != Some(&理由);
                let 文 =
                    新しい失敗か.then(|| format!("スタックをライブラリへ保存できない: {理由}"));
                self.0 = Some(理由);
                文
            }
            見たスタックの保存::結果を待っている => None,
            見たスタックの保存::失敗していない => {
                self.0 = None;
                None
            }
        }
    }
}
