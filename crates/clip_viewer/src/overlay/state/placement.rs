//! 置き方の編集。選んでいる置いたクリップと、映す矩形のドラッグと、並べた後に置き方を手で直したかを持つ。映す矩形のドラッグの動き(掴む所・移動量・縦横比の扱い)の型も置く。
//! 映す矩形のドラッグの間は、重ね合わせを書き換えずに仮の矩形を持ち、放したときに1回だけ重ね合わせの `映す矩形を変える` で確定する。
//! 参照: _doc/設計/同時再生.md 2-2・2-4

use clip_domain::{
    四隅のつまみ, 映す矩形, 映す矩形の移動量, 置いたクリップ, 置いたクリップの識別子,
};

/// 映す矩形のドラッグとは、ドラッグしている置いたクリップと、掴み始めたときの映す矩形と、今の移動量を当てた仮の映す矩形の組のことである。
/// 複数の範囲枠の部品は掴み始めからの累積の移動量を発するため、毎回掴み始めの矩形から計算し直す(今のクロップ枠と同じ流儀)。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 映す矩形のドラッグ {
    pub(super) 対象: 置いたクリップの識別子,
    pub(super) 掴み始めの矩形: 映す矩形,
    pub(super) 仮の矩形: 映す矩形,
}

/// 置き方の変更とは、開いている重ね合わせの置き方(映す矩形・置いたクリップの並び・縦横比)を、並べた後に利用者が手で直したかの区別のことである。
/// 手で直した重ね合わせを「今のスタックから並べ直す」で捨てる前に確かめるために持つ(同時再生.md 2-2)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 置き方の変更 {
    並べたまま,
    手で直した,
}

/// 置き方の編集とは、選んでいる置いたクリップ(選んでいなければ無い)と、映す矩形のドラッグ(ドラッグしていなければ無い)と、置き方の変更の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 置き方の編集 {
    pub(super) 選んでいる: Option<置いたクリップの識別子>,
    pub(super) ドラッグ: Option<映す矩形のドラッグ>,
    pub(super) 変更: 置き方の変更,
}

impl 置き方の編集 {
    /// 重ね合わせを開いた直後の編集。何も選ばず、ドラッグせず、並べたままである。
    pub(crate) fn 開いた直後() -> Self {
        Self {
            選んでいる: None,
            ドラッグ: None,
            変更: 置き方の変更::並べたまま,
        }
    }

    /// 置いたクリップを今映す矩形。その置いたクリップをドラッグしている間は仮の矩形、そうでなければ置いたクリップの映す矩形である。
    pub(crate) fn 今映す矩形(
        &self, 置いたクリップ: &置いたクリップ
    ) -> 映す矩形 {
        match &self.ドラッグ {
            Some(ドラッグ) if &ドラッグ.対象 == 置いたクリップ.識別子() => {
                ドラッグ.仮の矩形
            }
            _ => 置いたクリップ.映す矩形(),
        }
    }

    /// 識別子の置いたクリップを選んでいるか。
    pub(crate) fn 選んでいるか(&self, 識別子: &置いたクリップの識別子) -> bool {
        self.選んでいる.as_ref() == Some(識別子)
    }

    pub(super) fn 手で直したことを覚える(&mut self) {
        self.変更 = 置き方の変更::手で直した;
    }
}

/// 映す矩形の掴む所とは、ドラッグで映す矩形の内側を掴んだか、四隅のつまみのどれかを掴んだかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 映す矩形の掴む所 {
    内側,
    隅(四隅のつまみ),
}

/// 隅の縦横比の扱いとは、隅のつまみで大きさを変えるときに、置いたクリップの絵の形の縦横比を保つかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 隅の縦横比の扱い {
    絵の形を保つ,
    保たない,
}

/// 映す矩形のドラッグの動きとは、ドラッグしている置いたクリップと、掴む所と、掴み始めからの移動量と、隅の縦横比の扱いの組のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 映す矩形のドラッグの動き {
    pub(crate) 対象: 置いたクリップの識別子,
    pub(crate) 掴む所: 映す矩形の掴む所,
    pub(crate) 移動量: 映す矩形の移動量,
    pub(crate) 縦横比: 隅の縦横比の扱い,
}
