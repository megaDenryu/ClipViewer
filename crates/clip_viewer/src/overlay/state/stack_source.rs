//! 今のスタックの値。「今のスタックから並べる」とサイドバーの「置く」がスタックの作業場から読む値(スタック・開いている動画・出力のアスペクト比)と、全体の音量(音量のつまみと全体の消音)を、
//! 配線(`app/workspace.rs`)が `アプリの状態` から読んで渡す形にする。重ね合わせの作業場の層は `アプリの状態` を知らないためである。
//! 参照: _doc/設計/同時再生.md 2-2・3-3

use clip_domain::{
    アスペクト比設定, クリップスタック, 時間の長さ, 正規化した動画パス
};

use super::whole_volume::全体の音量;

/// 今のスタックの値とは、スタックの作業場の今のスタックと、開いている動画(開いていなければ無い)と、出力のアスペクト比と、
/// 全体の音量(見る側の設定の、つまみで選んだ音量と全体の消音と鳴らす音量)の組のことである。
/// 配線が毎フレーム `アプリの状態` から借りて作り、重ね合わせの作業場はこの値からだけスタックの作業場の様子を読む。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 今のスタックの値<'状態> {
    pub(crate) スタック: &'状態 クリップスタック,
    pub(crate) 開いている動画: Option<開いている動画の値<'状態>>,
    pub(crate) 出力のアスペクト比: アスペクト比設定,
    pub(crate) 全体の音量: 全体の音量,
}

/// 開いている動画の値とは、スタックの作業場で開いている動画のパスと長さの組のことである。長さは置く操作が区間の終わりを確かめるのに使う。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 開いている動画の値<'状態> {
    pub(crate) パス: &'状態 正規化した動画パス,
    pub(crate) 長さ: 時間の長さ,
}

/// 今のスタックから並べる状況とは、「今のスタックから並べる」を押せるか、押せないならその理由の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 今のスタックから並べる状況 {
    並べられる,
    動画を開いていない,
    再生できるクリップが無い,
}

impl 今のスタックの値<'_> {
    /// 「今のスタックから並べる」を押せるか。スタックの作業場で動画を開いていて、スタックに再生できるクリップ(有効で長さが0でないもの)が
    /// 1つ以上あるときだけ押せる(同時再生.md 2-2)。
    pub(crate) fn 並べる状況(&self) -> 今のスタックから並べる状況 {
        if self.開いている動画.is_none() {
            return 今のスタックから並べる状況::動画を開いていない;
        }
        if !self
            .スタック
            .一覧()
            .iter()
            .any(|クリップ| クリップ.再生できるか())
        {
            return 今のスタックから並べる状況::再生できるクリップが無い;
        }
        今のスタックから並べる状況::並べられる
    }
}
