//! 重ね合わせの作業場の状態。開いている重ね合わせと、その再生の状況を持つ。
//! 画面は `&重ね合わせの作業場の状態` を読んで組み、書き換えは応答(`overlay/command`)を通す。参照: _doc/設計/同時再生.md 3-3

mod playback;

pub(crate) use playback::重ね合わせの再生の状況;

use std::time::Instant;

use clip_domain::{使う動画の表, 重ねる画面の縦横比, 重ね合わせ};

/// 重ね合わせの作業場の状態とは、重ね合わせの作業場の画面が読むすべての値の組のことである。
/// 重ね合わせは、利用者がスタックから並べるまで、置いたクリップも使う動画も持たない(長さは0秒)。
pub(crate) struct 重ね合わせの作業場の状態 {
    pub(crate) 重ね合わせ: 重ね合わせ,
    pub(crate) 再生: 重ね合わせの再生の状況,
}

impl 重ね合わせの作業場の状態 {
    /// 初めて重ね合わせの作業場へ移ったときの状態。何も置いていない16:9の重ね合わせの先頭で止まっている。
    pub(crate) fn 何も置いていない() -> Self {
        Self {
            重ね合わせ: 重ね合わせ::作成する(
                重ねる画面の縦横比::ワイド16対9,
                使う動画の表::並びから作成する(Vec::new()),
            ),
            再生: 重ね合わせの再生の状況::起動時(),
        }
    }

    /// 毎フレーム呼ぶ。再生している間だけ、重ね合わせの時計を実時間の経過で進める。
    pub(crate) fn 時計を進める(&mut self, 今: Instant) {
        self.再生.時計を進める(今, &self.重ね合わせ);
    }
}
