//! 重ね合わせの作業場の状態。重ね合わせを開いているか(開いていればその重ね合わせと再生の状況と映像の様子)と、重ね合わせの作業場の知らせを持つ。
//! 画面は状態を読む口(再生しているか・再生を始められるか・再生の位置と長さ・並べる知らせ)だけを読み、書き換えは応答(`overlay/command`)と、作業場(`overlay/workspace.rs`)の口を通す。参照: _doc/設計/同時再生.md 3-3

mod notice;
mod opened;
mod playback;

pub(crate) use notice::重ね合わせの作業場の知らせ;
pub(crate) use opened::開いている重ね合わせ;

use std::time::Instant;

use clip_domain::{重ね合わせ, 重ね合わせの再生位置, 重ね合わせ上の秒};
use sengen_egui::並べる通知;

use crate::overlay::feed::重ね合わせの映像の様子;

/// 重ね合わせの開き方とは、重ね合わせの作業場が重ね合わせを開いていないか、1つを開いているかの区別のことである。
/// 開いていない間は、再生する重ね合わせが無いため再生できない。
pub(crate) enum 重ね合わせの開き方 {
    開いていない,
    開いている(開いている重ね合わせ),
}

/// 重ね合わせの作業場の状態とは、重ね合わせの開き方と、重ね合わせの作業場の知らせの組のことである。
/// 知らせは重ね合わせを開いているかにかかわらず出すため、開き方の外に持つ。
pub(crate) struct 重ね合わせの作業場の状態 {
    pub(crate) 開き方: 重ね合わせの開き方,
    pub(crate) 知らせ: 重ね合わせの作業場の知らせ,
}

impl 重ね合わせの作業場の状態 {
    /// 初めて重ね合わせの作業場へ移ったときの状態。重ね合わせを開いておらず、知らせも無い。
    pub(crate) fn 開いていない() -> Self {
        Self {
            開き方: 重ね合わせの開き方::開いていない,
            知らせ: 重ね合わせの作業場の知らせ::default(),
        }
    }

    /// 重ね合わせを、その映像の様子と一緒に開く。先頭で止まった再生の状況で始める。映像の供給を作れなかったときと開けなかった動画があるときは、その理由を知らせる。
    pub(crate) fn 重ね合わせを開く(
        &mut self,
        重ね合わせ: 重ね合わせ,
        映像: 重ね合わせの映像の様子,
    ) {
        for 文 in 映像.開けなかった知らせの文() {
            self.知らせ.出す(文);
        }
        self.開き方 = 重ね合わせの開き方::開いている(
            開いている重ね合わせ::先頭で止まって開く(重ね合わせ, 映像),
        );
    }

    /// 開いている重ね合わせ。開いていなければ無い。
    pub(crate) fn 開いている重ね合わせ(&self) -> Option<&開いている重ね合わせ> {
        match &self.開き方 {
            重ね合わせの開き方::開いている(開いている) => Some(開いている),
            重ね合わせの開き方::開いていない => None,
        }
    }

    /// 毎フレーム呼ぶ。重ね合わせを開いていて再生している間だけ、時計を実時間の経過で進める。
    pub(crate) fn 時計を進める(&mut self, 今: Instant) {
        if let 重ね合わせの開き方::開いている(開いている) = &mut self.開き方 {
            開いている.時計を進める(今);
        }
    }

    /// 毎フレーム、時計を進めた後に呼ぶ。重ね合わせを開いていれば、再生の位置に行ごとに映すコマを載せる。
    pub(crate) fn 映像を供給する(&mut self, 今: Instant) {
        if let 重ね合わせの開き方::開いている(開いている) = &mut self.開き方 {
            開いている.映像を供給する(今);
        }
    }

    /// 作業場を控える前に呼ぶ。開いている重ね合わせの再生を止め、行ごとの流し読みを閉じて ffmpeg を止める。重ね合わせと再生の位置と載せたコマは残す。
    pub(crate) fn 控える前に再生を止める(&mut self) {
        if let 重ね合わせの開き方::開いている(開いている) = &mut self.開き方 {
            開いている.控える前に再生を止めて流し読みを閉じる();
        }
    }

    /// 開いている重ね合わせを再生しているか。開いていなければ再生していない。
    pub(crate) fn 再生しているか(&self) -> bool {
        self.開いている重ね合わせ()
            .is_some_and(|開いている| 開いている.再生しているか())
    }

    /// 再生を始められるか。重ね合わせを開いていて、長さが0秒でないときだけ始められる。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.開いている重ね合わせ()
            .is_some_and(|開いている| 開いている.再生を始められるか())
    }

    /// 開いている重ね合わせの再生の位置と長さ。開いていなければ無い。
    pub(crate) fn 再生の位置と長さ(
        &self,
    ) -> Option<(重ね合わせの再生位置, 重ね合わせ上の秒)> {
        self.開いている重ね合わせ()
            .map(|開いている| (開いている.再生の位置(), 開いている.重ね合わせの長さ()))
    }

    /// 画面に並べる最近の知らせ(古い順)。
    pub(crate) fn 並べる知らせ(&self) -> Vec<並べる通知> {
        self.知らせ.並べる通知()
    }
}
