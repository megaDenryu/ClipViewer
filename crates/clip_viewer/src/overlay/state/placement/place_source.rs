//! 置くクリップの出どころ。サイドバーの置くクリップの一覧が、スタックの作業場の今のスタックの値から、並べるクリップと、
//! それらを開いている重ね合わせへ置けるかを求める。置けるかの規則は、一覧を押せるかと、置く操作の確かめの両方がここを使う。
//! 参照: _doc/設計/同時再生.md 2-4

use clip_domain::{
    クリップ名, クリップ識別子, 使う動画の表, 動画の番号, 時間の長さ
};

use crate::overlay::state::{今のスタックの値, 重ね合わせの作業場の状態};

/// 置くクリップの動画とは、今のスタックのクリップを開いている重ね合わせへ置けるか、置けるならその動画の番号と長さ、置けないならその理由の区別のことである。
/// スタックの作業場で開いている動画のパスが、重ね合わせの使う動画の表の動画のパスと `正規化した動画パス` の等しさで同じときだけ置ける(同時再生.md 2-4)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 置くクリップの動画 {
    置ける {
        番号: 動画の番号,
        長さ: 時間の長さ,
    },
    動画を開いていない,
    動画が違う,
}

/// 置くクリップとは、サイドバーの置くクリップの一覧の1行に出す、今のスタックのクリップの識別子と名前の組のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 置くクリップ {
    pub(crate) 識別子: クリップ識別子,
    pub(crate) 名前: クリップ名,
}

/// 置くクリップの一覧とは、今のスタックのクリップをスタックの順に並べたものと、それらを開いている重ね合わせへ置けるかの組のことである。
/// 配線が毎フレーム今のスタックの値から作って画面へ渡す。画面は今のスタックの値を借りずに、この値だけを読む。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 置くクリップの一覧 {
    pub(crate) 並び: Vec<置くクリップ>,
    pub(crate) 動画: 置くクリップの動画,
}

impl 重ね合わせの作業場の状態 {
    /// 画面へ渡す置くクリップの一覧。開いている重ね合わせの使う動画の表へ置けるかを添える。重ね合わせを開いていなければ無い。
    pub(crate) fn 置くクリップの一覧(
        &self,
        今のスタック: 今のスタックの値<'_>,
    ) -> Option<置くクリップの一覧> {
        self.開いている重ね合わせ().map(|開いている| {
            今のスタック.置くクリップの一覧(開いている.重ね合わせ().動画の表())
        })
    }
}

impl 今のスタックの値<'_> {
    /// 今のスタックのクリップを、この使う動画の表の重ね合わせへ置けるか。
    pub(crate) fn 置くクリップの動画(
        &self,
        表: &使う動画の表,
    ) -> 置くクリップの動画 {
        let Some(動画) = self.開いている動画 else {
            return 置くクリップの動画::動画を開いていない;
        };
        match 表.パスの動画の番号(動画.パス) {
            Some(番号) => 置くクリップの動画::置ける {
                番号,
                長さ: 動画.長さ,
            },
            None => 置くクリップの動画::動画が違う,
        }
    }

    /// 今のスタックのクリップを、この使う動画の表の重ね合わせへ置く一覧にする。
    pub(crate) fn 置くクリップの一覧(
        &self,
        表: &使う動画の表,
    ) -> 置くクリップの一覧 {
        置くクリップの一覧 {
            並び: self
                .スタック
                .一覧()
                .iter()
                .map(|クリップ| 置くクリップ {
                    識別子: クリップ.識別子().clone(),
                    名前: クリップ.名前.clone(),
                })
                .collect(),
            動画: self.置くクリップの動画(表),
        }
    }
}
