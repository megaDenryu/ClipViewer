//! 選んでいるもの。重ね合わせの作業場で利用者が選んでいるのが、置いたクリップか、タイムラインの行か、何も選んでいないかを1つの型で持つ。
//! 置いたクリップは重ねる画面の枠・タイムラインの塊・サイドバーのどこで選んでも同じ選びになり、行を選ぶと置いたクリップの選びは外れる(逆も同じ)。
//! 参照: _doc/設計/同時再生.md 2-4・2-6

use clip_domain::{置いたクリップの識別子, 行の番号};

/// 選んでいるものとは、重ね合わせの作業場で利用者が選んでいるものの区別のことである。置いたクリップと行を同時には選ばない。
#[derive(Debug, Clone, PartialEq, Default)]
pub(crate) enum 選んでいるもの {
    #[default]
    無し,
    置いたクリップ(置いたクリップの識別子),
    行(行の番号),
}

impl 選んでいるもの {
    /// 選んでいる置いたクリップの識別子。置いたクリップを選んでいなければ無い。
    pub(crate) fn 置いたクリップの識別子(
        &self,
    ) -> Option<&置いたクリップの識別子> {
        match self {
            Self::置いたクリップ(識別子) => Some(識別子),
            Self::無し | Self::行(_) => None,
        }
    }

    /// 選んでいる行の番号。行を選んでいなければ無い。
    pub(crate) fn 行(&self) -> Option<行の番号> {
        match self {
            Self::行(行) => Some(*行),
            Self::無し | Self::置いたクリップ(_) => None,
        }
    }
}
