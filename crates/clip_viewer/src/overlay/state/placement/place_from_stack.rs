//! 今のスタックのクリップを置くこと。サイドバーの置くクリップの一覧の「置く」で、スタックの作業場の今のスタックのクリップの写しを、
//! 開いている重ね合わせの今の再生の位置に置く。置けないときは理由を重ね合わせの作業場の知らせに出す。参照: _doc/設計/同時再生.md 2-4

use clip_domain::{
    クリップから受け継いだ値, クリップ識別子, 置いたクリップの識別子の発行元
};

use super::place_source::置くクリップの動画;
use crate::overlay::state::今のスタックの値;
use crate::overlay::state::{重ね合わせの作業場の状態, 重ね合わせの開き方};

/// スタックの動画が重ね合わせの動画と違うために置けないことを、一覧の上と知らせに出す文(同時再生.md 2-4)。
pub(crate) const 動画が違うため置けない文: &str =
    "スタックの動画が、この重ね合わせの動画と違います";

/// スタックの作業場で動画を開いていないために置けないことを、一覧の上と知らせに出す文。
pub(crate) const 動画を開いていないため置けない文: &str =
    "スタックの作業場で動画を開いていないため、置けない";

/// 置こうとしたクリップが今のスタックに無いために置けないことを、知らせに出す文。画面がクリップを並べた後に、スタックの作業場でそのクリップが消えたときに出る。
pub(crate) const 置こうとしたクリップが無いため置けない文: &str =
    "置こうとしたクリップが今のスタックに無いため、置けない";

impl 重ね合わせの作業場の状態 {
    /// 今のスタックのクリップから受け継いだ値で置いたクリップを作り、開いている重ね合わせの今の再生の位置に置いて選ぶ。
    /// 重ね合わせを開いていないときは何もしない。スタックの動画が違うとき・クリップがスタックに無いとき・置く操作が拒んだときは、理由を知らせる。
    pub(crate) fn 今のスタックのクリップを置く(
        &mut self,
        クリップ: &クリップ識別子,
        今のスタック: 今のスタックの値<'_>,
        発行元: &mut impl 置いたクリップの識別子の発行元,
    ) {
        let 重ね合わせの開き方::開いている(開いている) = &mut self.開き方
        else {
            return;
        };
        let (番号, 長さ) = match 今のスタック
            .置くクリップの動画(開いている.重ね合わせ().動画の表())
        {
            置くクリップの動画::置ける { 番号, 長さ } => (番号, 長さ),
            置くクリップの動画::動画が違う => {
                return self.知らせ.出す(動画が違うため置けない文);
            }
            置くクリップの動画::動画を開いていない => {
                return self.知らせ.出す(動画を開いていないため置けない文);
            }
        };
        let Some(置くクリップ) = 今のスタック.スタック.識別子で探す(クリップ)
        else {
            return self.知らせ.出す(置こうとしたクリップが無いため置けない文);
        };
        let 名前 = 置くクリップ.名前.文字列().to_string();
        let 受け継いだ値 =
            クリップから受け継いだ値::クリップから受け継ぐ(置くクリップ);
        if let Err(拒んだ理由) =
            開いている.クリップを今の位置に置く(受け継いだ値, 番号, 長さ, 発行元)
        {
            self.知らせ
                .出す(format!("「{名前}」を置けない: {拒んだ理由}"));
        }
    }
}
