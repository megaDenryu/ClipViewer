//! 置いたばかりの置いたクリップ。サイドバーの「置く」で置いた後、まだ行のテクスチャにそのコマが載っていない置いたクリップを覚える。
//! 行のテクスチャは行の中で置いたクリップが入れ替わっても作り直さないため、前の置いたクリップのコマが残る行へ置くと一瞬前の絵が出る。
//! 重ねる画面は、ここにある置いたクリップの行を、そのコマが載るまで描かない。参照: _doc/設計/同時再生.md 2-4

use clip_domain::置いたクリップの識別子;

/// 置いたばかりの置いたクリップとは、置いた後まだ行のテクスチャにそのコマが載っていない置いたクリップの識別子の並びのことである。
#[derive(Debug, Clone, PartialEq, Default)]
pub(crate) struct 置いたばかりの置いたクリップ(Vec<置いたクリップの識別子>);

impl 置いたばかりの置いたクリップ {
    /// 置いたばかりの置いたクリップとして覚える。
    pub(crate) fn 覚える(&mut self, 識別子: 置いたクリップの識別子) {
        self.0.push(識別子);
    }

    pub(crate) fn 含むか(&self, 識別子: &置いたクリップの識別子) -> bool {
        self.0.contains(識別子)
    }

    /// まだ待つもの(待つかの判定が真のもの)だけを残す。
    pub(crate) fn 待つものだけ残す(
        &mut self,
        待つか: impl Fn(&置いたクリップの識別子) -> bool,
    ) {
        self.0.retain(待つか);
    }
}
