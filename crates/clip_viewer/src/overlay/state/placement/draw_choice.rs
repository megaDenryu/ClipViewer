//! 描く置いたクリップの選び方。重ねる画面を描くための読み取りであり、置き方の編集の状態を変える操作ではない(操作は edit.rs と
//! opened/placement_*.rs が受け持つ)。行の描き方と、置き方の編集が覚える置いたばかりの置いたクリップから、重ねる画面のその行に、
//! どの置いたクリップの映す矩形とクロップで行のテクスチャを描くかを選ぶ。参照: _doc/設計/同時再生.md 2-4・5-2 の7

use clip_domain::{置いたクリップ, 重ね合わせ};

use super::edit::置き方の編集;
use crate::overlay::feed::行の描き方;

impl 置き方の編集 {
    /// 行の描き方から、その行に描く置いたクリップを選ぶ。映す置いたクリップのコマが載っていれば映す置いたクリップである。
    /// 前の置いたクリップのコマを描き続けるときは、重ね合わせから探した前の置いたクリップであるが、映す置いたクリップが置いたばかりのとき
    /// (使い方.md 15.7節)と、前の置いたクリップがもう重ね合わせに無いときは描かない。
    pub(crate) fn 描く置いたクリップを選ぶ<'重ね合わせ>(
        &self,
        重ね合わせ: &'重ね合わせ 重ね合わせ,
        映す置いたクリップ: &'重ね合わせ 置いたクリップ,
        描き方: 行の描き方<'_>,
    ) -> Option<&'重ね合わせ 置いたクリップ> {
        match 描き方 {
            行の描き方::映す置いたクリップのコマ => Some(映す置いたクリップ),
            行の描き方::前の置いたクリップのコマ(前の置いたクリップの識別子)
                if !self.置いたばかりか(映す置いたクリップ.識別子()) =>
            {
                重ね合わせ.識別子で探す(前の置いたクリップの識別子)
            }
            行の描き方::前の置いたクリップのコマ(_) | 行の描き方::描かない => {
                None
            }
        }
    }
}
