//! 置き方の手直しの有無。並べた後に利用者が置き方を手で直したかを持つ。参照: _doc/設計/同時再生.md 2-2

/// 置き方の手直しの有無とは、開いている重ね合わせの置き方(映す矩形・置いたクリップの並び・縦横比・置いたクリップの音)を、並べた後に利用者が手で直したかの区別のことである。
/// 手で直した重ね合わせを「今のスタックから並べ直す」で捨てる前に確かめるために持つ(同時再生.md 2-2)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 置き方の手直しの有無 {
    並べたまま,
    手で直した,
}

impl 置き方の手直しの有無 {
    /// 手で直したことを覚える。一度手で直したら、並べ直すまで並べたままへは戻らない。
    pub(super) fn 手で直したことを覚える(&mut self) {
        *self = Self::手で直した;
    }

    pub(super) fn 手で直したか(self) -> bool {
        self == Self::手で直した
    }
}
