//! 映す矩形のドラッグ。ドラッグしている置いたクリップと、掴み始めの映す矩形と、今の移動量を当てた仮の映す矩形を持つ。
//! 複数の範囲枠の部品は掴み始めからの累積の移動量を発するため、毎回掴み始めの矩形から計算し直す(今のクロップ枠と同じ流儀)。

use clip_domain::{映す矩形, 置いたクリップの識別子};

/// 映す矩形のドラッグとは、ドラッグしている置いたクリップと、掴み始めたときの映す矩形と、今の移動量を当てた仮の映す矩形の組のことである。
/// 不変条件: 掴み始めた直後の仮の矩形は掴み始めの矩形と同じである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 映す矩形のドラッグ {
    対象: 置いたクリップの識別子,
    掴み始めの矩形: 映す矩形,
    仮の矩形: 映す矩形,
}

impl 映す矩形のドラッグ {
    /// 置いたクリップの今の映す矩形を掴み始めの矩形にしてドラッグを始める。
    pub(crate) fn 掴み始める(
        対象: 置いたクリップの識別子, 今の矩形: 映す矩形
    ) -> Self {
        Self {
            対象,
            掴み始めの矩形: 今の矩形,
            仮の矩形: 今の矩形,
        }
    }

    /// ドラッグしている置いたクリップか。
    pub(crate) fn 対象か(&self, 識別子: &置いたクリップの識別子) -> bool {
        &self.対象 == 識別子
    }

    pub(crate) fn 対象(&self) -> &置いたクリップの識別子 {
        &self.対象
    }

    pub(crate) fn 掴み始めの矩形(&self) -> 映す矩形 {
        self.掴み始めの矩形
    }

    pub(crate) fn 仮の矩形(&self) -> 映す矩形 {
        self.仮の矩形
    }

    pub(crate) fn 仮の矩形を変える(&mut self, 仮の矩形: 映す矩形) {
        self.仮の矩形 = 仮の矩形;
    }

    /// 掴み始めから矩形が変わったか。押しただけで動かしていなければ変わっていない。
    pub(crate) fn 矩形が変わったか(&self) -> bool {
        self.仮の矩形 != self.掴み始めの矩形
    }
}
