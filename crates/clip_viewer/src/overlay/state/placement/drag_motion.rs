//! 映す矩形のドラッグの動きの語彙。掴む所と掴み始めからの移動量と隅の縦横比の扱いの組と、その動きを掴み始めの矩形へ当てる規則の選び方を置く。
//! 移動・大きさの変更・縦横比を保つ計算そのものは `clip_domain` の映す矩形が持ち、ここは掴む所と縦横比の扱いでどれを使うかを選ぶだけである。
//! 参照: _doc/設計/同時再生.md 2-4

use clip_domain::{
    映す矩形, 映す矩形の移動量, 枠の掴む所, 縦横比, 置いたクリップの識別子, 重ねる画面の縦横比,
};

/// 隅の縦横比の扱いとは、隅のつまみで大きさを変えるときに、置いたクリップの絵の形の縦横比を保つかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 隅の縦横比の扱い {
    絵の形を保つ,
    保たない,
}

/// 映す矩形のドラッグの動きとは、ドラッグしている置いたクリップと、掴む所と、掴み始めからの移動量と、隅の縦横比の扱いの組のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 映す矩形のドラッグの動き {
    pub(crate) 対象: 置いたクリップの識別子,
    pub(crate) 掴む所: 枠の掴む所,
    pub(crate) 移動量: 映す矩形の移動量,
    pub(crate) 縦横比: 隅の縦横比の扱い,
}

impl 映す矩形のドラッグの動き {
    /// 掴み始めの矩形へこの動きを当てた矩形。内側なら動かし、隅なら大きさを変える。絵の形を保つときは絵の縦横比を保ち、
    /// 絵の縦横比が分からない(動画を開けない)ときは掴み始めの矩形の形を保つ。
    pub(crate) fn 掴み始めの矩形へ当てる(
        &self,
        始め: 映す矩形,
        絵の縦横比: Option<縦横比>,
        画面の縦横比: 重ねる画面の縦横比,
    ) -> 映す矩形 {
        let 枠の掴む所::隅(つまみ) = self.掴む所 else {
            return 始め.移動する(self.移動量);
        };
        match (self.縦横比, 絵の縦横比) {
            (隅の縦横比の扱い::保たない, _) => {
                始め.つまみで大きさを変える(つまみ, self.移動量)
            }
            (隅の縦横比の扱い::絵の形を保つ, Some(絵)) => 始め
                .縦横比を保ってつまみで大きさを変える(
                    つまみ,
                    self.移動量,
                    絵,
                    画面の縦横比,
                ),
            (隅の縦横比の扱い::絵の形を保つ, None) => {
                始め.今の形を保ってつまみで大きさを変える(つまみ, self.移動量)
            }
        }
    }
}
