//! 置き方の編集。選んでいる置いたクリップと、映す矩形のドラッグと、並べた後に置き方を手で直したかを持ち、その変え方をメソッドに閉じる。
//! 映す矩形のドラッグの間は、重ね合わせを書き換えずに仮の矩形を持ち、放したときに1回だけ重ね合わせの `映す矩形を変える` で確定する。
//! 参照: _doc/設計/同時再生.md 2-2・2-4

use clip_domain::{映す矩形, 置いたクリップ, 置いたクリップの識別子};

use super::drag::映す矩形のドラッグ;
use super::fresh::置いたばかりの置いたクリップ;

/// 置き方の手直しの有無とは、開いている重ね合わせの置き方(映す矩形・置いたクリップの並び・縦横比・置いたクリップの音)を、並べた後に利用者が手で直したかの区別のことである。
/// 手で直した重ね合わせを「今のスタックから並べ直す」で捨てる前に確かめるために持つ(同時再生.md 2-2)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 置き方の手直しの有無 {
    並べたまま,
    手で直した,
}

/// 置き方の編集とは、選んでいる置いたクリップ(選んでいなければ無い)と、映す矩形のドラッグ(ドラッグしていなければ無い)と、置き方の手直しの有無と、
/// 置いたばかりでまだ行のテクスチャにコマが載っていない置いたクリップの組のことである。
/// 不変条件: ドラッグは1つだけであり、ドラッグを終えるか閉じるまで、別の置いたクリップの動きを当てない。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 置き方の編集 {
    選んでいる置いたクリップの識別子: Option<置いたクリップの識別子>,
    ドラッグ: Option<映す矩形のドラッグ>,
    手直しの有無: 置き方の手直しの有無,
    pub(crate) 置いたばかり: 置いたばかりの置いたクリップ,
}

impl 置き方の編集 {
    /// 重ね合わせを開いた直後の編集。何も選ばず、ドラッグせず、並べたままである。
    pub(crate) fn 開いた直後() -> Self {
        Self {
            選んでいる置いたクリップの識別子: None,
            ドラッグ: None,
            手直しの有無: 置き方の手直しの有無::並べたまま,
            置いたばかり: 置いたばかりの置いたクリップ::default(),
        }
    }

    /// 置いたクリップを今映す矩形。その置いたクリップをドラッグしている間は仮の矩形、そうでなければ置いたクリップの映す矩形である。
    pub(crate) fn 今映す矩形(
        &self, 置いたクリップ: &置いたクリップ
    ) -> 映す矩形 {
        match &self.ドラッグ {
            Some(ドラッグ) if ドラッグ.対象か(置いたクリップ.識別子()) => {
                ドラッグ.仮の矩形()
            }
            _ => 置いたクリップ.映す矩形(),
        }
    }

    /// 選んでいる置いたクリップの識別子。選んでいなければ無い。
    pub(crate) fn 選んでいる置いたクリップの識別子(
        &self,
    ) -> Option<&置いたクリップの識別子> {
        self.選んでいる置いたクリップの識別子.as_ref()
    }

    /// 識別子の置いたクリップを選んでいるか。
    pub(crate) fn 選んでいるか(&self, 識別子: &置いたクリップの識別子) -> bool {
        self.選んでいる置いたクリップの識別子.as_ref() == Some(識別子)
    }

    pub(crate) fn 選ぶ(&mut self, 識別子: 置いたクリップの識別子) {
        self.選んでいる置いたクリップの識別子 = Some(識別子);
    }

    pub(crate) fn 選びを外す(&mut self) {
        self.選んでいる置いたクリップの識別子 = None;
    }

    /// 映す矩形のドラッグを始める。前のドラッグがあれば置き換える。
    pub(crate) fn ドラッグを始める(&mut self, ドラッグ: 映す矩形のドラッグ) {
        self.ドラッグ = Some(ドラッグ);
    }

    /// 対象の置いたクリップをドラッグしていれば、そのドラッグ。
    pub(crate) fn 対象のドラッグ(
        &self,
        対象: &置いたクリップの識別子,
    ) -> Option<&映す矩形のドラッグ> {
        self.ドラッグ
            .as_ref()
            .filter(|ドラッグ| ドラッグ.対象か(対象))
    }

    /// 対象の置いたクリップをドラッグしていれば、その仮の矩形を変える。
    pub(crate) fn 仮の矩形を変える(
        &mut self,
        対象: &置いたクリップの識別子,
        仮の矩形: 映す矩形,
    ) {
        if let Some(ドラッグ) = self
            .ドラッグ
            .as_mut()
            .filter(|ドラッグ| ドラッグ.対象か(対象))
        {
            ドラッグ.仮の矩形を変える(仮の矩形);
        }
    }

    /// 対象の置いたクリップをドラッグしていれば、ドラッグを終えて取り出す。別の置いたクリップのドラッグは終えない。
    pub(crate) fn ドラッグを終えて取り出す(
        &mut self,
        対象: &置いたクリップの識別子,
    ) -> Option<映す矩形のドラッグ> {
        self.対象のドラッグ(対象)?;
        self.ドラッグ.take()
    }

    pub(crate) fn 手で直したことを覚える(&mut self) {
        self.手直しの有無 = 置き方の手直しの有無::手で直した;
    }

    /// 並べた後に置き方を手で直したか。
    pub(crate) fn 手で直したか(&self) -> bool {
        self.手直しの有無 == 置き方の手直しの有無::手で直した
    }
}
