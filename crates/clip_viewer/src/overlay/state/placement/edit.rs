//! 置き方の編集。選んでいるもの(置いたクリップか行。`selection.rs`)と、並べた後に置き方を手で直したかと、置いたばかりの置いたクリップを持ち、
//! その変え方をメソッドに閉じる。ドラッグの間の仮の値は、掴んでいるもの(`state/grab.rs`)が持つ。参照: _doc/設計/同時再生.md 2-2・2-4・2-6

use clip_domain::{置いたクリップの識別子, 行の番号};

use super::fresh::置いたばかりの置いたクリップ;
use super::hand_fix::置き方の手直しの有無;
use super::selection::選んでいるもの;

/// 置き方の編集とは、選んでいるもの(置いたクリップか行か無し)と、置き方の手直しの有無と、
/// 置いたばかりでまだ行のテクスチャにコマが載っていない置いたクリップの組のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 置き方の編集 {
    選んでいるもの: 選んでいるもの,
    手直しの有無: 置き方の手直しの有無,
    置いたばかり: 置いたばかりの置いたクリップ,
}

impl 置き方の編集 {
    /// 重ね合わせを開いた直後の編集。何も選ばず、並べたままである。
    pub(crate) fn 開いた直後() -> Self {
        Self {
            選んでいるもの: 選んでいるもの::無し,
            手直しの有無: 置き方の手直しの有無::並べたまま,
            置いたばかり: 置いたばかりの置いたクリップ::default(),
        }
    }

    /// 選んでいる置いたクリップの識別子。置いたクリップを選んでいなければ無い。
    pub(crate) fn 選んでいる置いたクリップの識別子(
        &self,
    ) -> Option<&置いたクリップの識別子> {
        self.選んでいるもの.置いたクリップの識別子()
    }

    /// 識別子の置いたクリップを選んでいるか。
    pub(crate) fn 選んでいるか(&self, 識別子: &置いたクリップの識別子) -> bool {
        self.選んでいる置いたクリップの識別子() == Some(識別子)
    }

    /// 選んでいるタイムラインの行の番号。行を選んでいなければ無い。
    pub(crate) fn 選んでいる行(&self) -> Option<行の番号> {
        self.選んでいるもの.行()
    }

    /// 置いたクリップを選ぶ。選んでいた行の選びは外れる。
    pub(crate) fn 選ぶ(&mut self, 識別子: 置いたクリップの識別子) {
        self.選んでいるもの = 選んでいるもの::置いたクリップ(識別子);
    }

    /// タイムラインの行を選ぶ。選んでいた置いたクリップの選びは外れる。
    pub(crate) fn 行を選ぶ(&mut self, 行: 行の番号) {
        self.選んでいるもの = 選んでいるもの::行(行);
    }

    /// 置いたクリップと行のどちらも選んでいない状態にする。
    pub(crate) fn 選びを外す(&mut self) {
        self.選んでいるもの = 選んでいるもの::無し;
    }

    pub(crate) fn 手で直したことを覚える(&mut self) {
        self.手直しの有無.手で直したことを覚える();
    }

    /// 並べた後に置き方を手で直したか。
    pub(crate) fn 手で直したか(&self) -> bool {
        self.手直しの有無.手で直したか()
    }

    /// サイドバーの「置く」で置いた置いたクリップを、置いたばかりとして覚える。
    pub(crate) fn 置いたばかりとして覚える(
        &mut self, 識別子: 置いたクリップの識別子
    ) {
        self.置いたばかり.覚える(識別子);
    }

    /// 置いたばかりで、まだ行のテクスチャにそのコマが載っていない置いたクリップか。
    pub(crate) fn 置いたばかりか(
        &self, 識別子: &置いたクリップの識別子
    ) -> bool {
        self.置いたばかり.含むか(識別子)
    }

    /// 置いたばかりの置いたクリップのうち、まだコマを待つもの(待つかの判定が真のもの)だけを残す。
    pub(crate) fn 置いたばかりのうち待つものだけ残す(
        &mut self,
        待つか: impl Fn(&置いたクリップの識別子) -> bool,
    ) {
        self.置いたばかり.待つものだけ残す(待つか);
    }
}
