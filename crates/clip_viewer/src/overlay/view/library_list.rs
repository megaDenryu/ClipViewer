//! 重ね合わせの一覧の区画。重ね合わせを開いていない間に、出力の区画の案内の下に、道具の帯(見出し・件数・絞り込み・並べ替え・読み直す)と、
//! 置き場所の文と、一覧の本体を縦に並べる。行は仮想縦スクロールで見えている行だけを組む。参照: _doc/設計/同時再生.md 2-2・2-7、_doc/設計/ライブラリ.md 判断11

use sengen_egui::{ノード, 子, 縦積み};

use super::library_rows::重ね合わせの一覧の行の材料;
use crate::library_common::list::見えている行の範囲;
use crate::library_common::view::{
    一覧の文言, 一覧の本体の出し方, 一覧の行の並び, 読み取り専用の理由の出し方,
};
use crate::overlay::command::{
    一覧とダイアログの操作, 重ね合わせの作業場の応答
};
use crate::overlay::state::重ね合わせの作業場の状態;

pub(super) fn 一覧の区画(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    縦積み(子![
        super::library_toolbar::道具の帯(状態),
        一覧の文言.置き場所の文(状態.ライブラリ().使える様子()),
        一覧の本体(状態)
    ])
    .into()
}

/// 重ね合わせの一覧の文言。ヘッダーの重ね合わせのライブラリの様子(`library_header.rs`)も使う。
pub(super) const 一覧の文言: 一覧の文言 = 一覧の文言 {
    ライブラリの呼び名: "重ね合わせのライブラリ",
    フォルダの呼び名: "重ね合わせのフォルダ",
    読み取り専用でできないこと: "登録・保存",
    置き場所が無いときにできないこと: "重ね合わせの保存も一覧もできない",
    空のときの文: "ライブラリに重ね合わせがありません",
    空のときの案内: "「今のスタックから並べる」で並べ、ヘッダーの「ライブラリに保存」で登録する",
    読み取り専用の理由: 読み取り専用の理由の出し方::その場で出す,
};

/// 一覧の本体。置き場所が無いときは何も出さず、読めた一覧が空でなければ行を並べる。
fn 一覧の本体(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    let ライブラリ = 状態.ライブラリ();
    match 一覧の文言.一覧の本体の出し方(ライブラリ.使える様子(), ライブラリ.一覧().一覧())
    {
        一覧の本体の出し方::文を出す(文) => 文,
        一覧の本体の出し方::行を並べる(一覧) => 一覧の行の並び(
            "重ね合わせの一覧",
            重ね合わせの一覧の行の材料::状態から作る(状態, &一覧),
            見えている行を知らせる,
        ),
    }
}

fn 見えている行を知らせる(
    範囲: 見えている行の範囲,
) -> 重ね合わせの作業場の応答 {
    一覧とダイアログの操作::一覧の見えている行を知らせる(範囲).応答にする()
}
