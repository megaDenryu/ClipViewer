//! 重ね合わせの一覧の区画。重ね合わせを開いていない間に、出力の区画の案内の下に、道具の帯(見出し・件数・絞り込み・並べ替え・読み直す)と、
//! 置き場所の文と、一覧の本体を縦に並べる。行は仮想縦スクロールで見えている行だけを組む。参照: _doc/設計/同時再生.md 2-2・2-7、_doc/設計/ライブラリ.md 判断11

use sengen_egui::{ノード, 子, 文字表示, 無し, 縦積み};

use super::library_rows::重ね合わせの一覧の行の材料;
use crate::library_common::list::{
    並べられる一覧, 最後に読んだ一覧, 見えている行の範囲
};
use crate::library_common::view::一覧の行の並び;
use crate::overlay::command::{
    一覧とダイアログの操作, 重ね合わせの作業場の応答
};
use crate::overlay::state::library::重ね合わせのライブラリの使える様子;
use crate::overlay::state::重ね合わせの作業場の状態;
use crate::styles;

pub(super) fn 一覧の区画(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    縦積み(子![
        super::library_toolbar::道具の帯(状態),
        置き場所の文(状態),
        一覧の本体(状態)
    ])
    .into()
}

fn 置き場所の文(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    match 状態.ライブラリ().使える様子() {
        重ね合わせのライブラリの使える様子::書ける(フォルダ) => {
            文字表示(format!("置き場所: {}", フォルダ.パス().display()))
                .装飾(styles::補足)
                .into()
        }
        重ね合わせのライブラリの使える様子::読むだけ(フォルダ, 理由) => 文字表示(format!(
            "読み取り専用: {理由}。開くことはできるが、登録・保存はできない(置き場所: {})",
            フォルダ.パス().display()
        ))
        .装飾(styles::不備の文)
        .into(),
        重ね合わせのライブラリの使える様子::置き場所が無い => 文字表示(
            "ライブラリの置き場所が無い(環境変数 APPDATA が無い)ため、重ね合わせの保存も一覧もできない",
        )
        .装飾(styles::不備の文)
        .into(),
    }
}

/// 一覧の本体。置き場所が無いときは一覧を読まないため、置き場所の文だけにして「一覧を読んでいる」を出さない。
fn 一覧の本体(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    if let 重ね合わせのライブラリの使える様子::置き場所が無い = 状態.ライブラリ().使える様子()
    {
        return 無し();
    }
    match 状態.ライブラリ().一覧().一覧() {
        最後に読んだ一覧::まだ無い => {
            文字表示("一覧を読んでいる").装飾(styles::補足).into()
        }
        最後に読んだ一覧::読めない(理由) => {
            文字表示(format!("重ね合わせのフォルダを読めない: {理由}"))
                .装飾(styles::不備の文)
                .into()
        }
        最後に読んだ一覧::読めた(一覧) if 一覧.項目の数() == 0 => {
            縦積み(子![
                文字表示("ライブラリに重ね合わせがありません"),
                文字表示(
                    "「今のスタックから並べる」で並べ、ヘッダーの「ライブラリに保存」で登録する"
                )
                .装飾(styles::補足),
            ])
            .into()
        }
        最後に読んだ一覧::読めた(一覧) => 一覧の行の並び(
            "重ね合わせの一覧",
            重ね合わせの一覧の行の材料::状態から作る(状態, 一覧),
            見えている行を知らせる,
        ),
    }
}

fn 見えている行を知らせる(
    範囲: 見えている行の範囲,
) -> 重ね合わせの作業場の応答 {
    一覧とダイアログの操作::一覧の見えている行を知らせる(範囲).応答にする()
}
