//! 並べ直す前の確かめの試験。置き方を手で直した重ね合わせでは「今のスタックから並べ直す」が確かめるダイアログを出す応答を発し、
//! ダイアログが「やめる」と並べ直す応答を発することを、egui に描かせて押して確かめる。
#![allow(clippy::expect_used)]

use clip_domain::四隅のつまみ;
use eframe::egui;

use super::rearrange_dialog::{並べ直すボタンの文, 並べ直す前に確かめる文};
use super::screen_press_support::文字を押して集める;
use super::screen_press_support::試験の全体の音量;
use super::test_support::{押して集める, 描いた文字の範囲, 描いて集める};
use crate::overlay::command::{
    映す矩形の枠の操作, 置き方の操作, 重ね合わせの作業場の応答, 重ね合わせの操作,
};
use crate::overlay::placement_test_support::{
    動き, 当てる, 枠を当てる, 置いた, 開いた作業場
};
use crate::overlay::state::placement::{映す矩形の掴む所, 隅の縦横比の扱い};
use crate::overlay::state::今のスタックから並べる状況;
use crate::overlay::workspace::重ね合わせの作業場;

fn 置き方(操作: 置き方の操作) -> 重ね合わせの作業場の応答 {
    重ね合わせの作業場の応答::操作(重ね合わせの操作::置き方(操作))
}

/// 作業場の画面を3回描いてから(ダイアログは最初の回に大きさだけを測るため)、その文字の真ん中を押して発した応答を返す。描いていなければ無い。
fn ダイアログを描いて押す(
    作業場: &重ね合わせの作業場,
    文字: &str,
) -> Option<Vec<重ね合わせの作業場の応答>> {
    let 画面描画の共有状態 = egui::Context::default();
    let 木 = || {
        super::画面(
            作業場.状態(),
            今のスタックから並べる状況::並べられる,
            None,
            試験の全体の音量,
            None,
        )
    };
    let mut 出力 = 描いて集める(&画面描画の共有状態, Vec::new(), &木).1;
    for _ in 0..2 {
        出力 = 描いて集める(&画面描画の共有状態, Vec::new(), &木).1;
    }
    let 位置 = 描いた文字の範囲(&出力, 文字)?.center();
    Some(押して集める(&画面描画の共有状態, 位置, &木))
}

#[test]
fn 置き方を手で直した重ね合わせでは並べ直す前に確かめ_ダイアログはやめると並べ直すを発する() {
    let mut 作業場 = 開いた作業場();
    let 押せる = 今のスタックから並べる状況::並べられる;
    let 並べ直す = "今のスタックから並べ直す";
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::掴み始めた(置いた("置-1")));
    let 縮める = 動き(
        "置-1",
        映す矩形の掴む所::隅(四隅のつまみ::右下),
        -50.0,
        -50.0,
        隅の縦横比の扱い::保たない,
    );
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::放した(縮める));
    assert_eq!(
        文字を押して集める(&作業場, 押せる, 並べ直す),
        [置き方(置き方の操作::並べ直す前の確かめを出す)]
    );
    assert_eq!(
        ダイアログを描いて押す(&作業場, 並べ直す前に確かめる文),
        None
    );
    当てる(&mut 作業場, 置き方の操作::並べ直す前の確かめを出す);
    assert!(ダイアログを描いて押す(&作業場, 並べ直す前に確かめる文).is_some());
    assert_eq!(
        ダイアログを描いて押す(&作業場, "やめる"),
        Some(vec![置き方(置き方の操作::並べ直す前の確かめを閉じる)])
    );
    assert_eq!(
        ダイアログを描いて押す(&作業場, 並べ直すボタンの文),
        Some(vec![重ね合わせの作業場の応答::今のスタックから並べる])
    );
    当てる(&mut 作業場, 置き方の操作::並べ直す前の確かめを閉じる);
    assert!(!作業場.状態().並べ直す前の確かめを出しているか());
}
