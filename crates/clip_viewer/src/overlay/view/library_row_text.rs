//! 重ね合わせの一覧の行の説明の文。最初の動画のファイル名と、置いたクリップの数と、重ね合わせの長さと、更新した日時を並べる。参照: _doc/設計/同時再生.md 2-7

use clip_library::読めた重ね合わせ;

use crate::library_common::view::日時の表示;

/// 行の説明。「<最初の動画のファイル名> ・ <N>クリップ ・ 長さ <秒>秒 ・ 更新 <日時>」の形。
pub(super) fn 行の説明(読めた: &読めた重ね合わせ) -> String {
    let 重ね合わせ = 読めた.重ね合わせ.重ね合わせ();
    let 動画 = 重ね合わせ
        .動画の表()
        .動画のパスの並び()
        .first()
        .and_then(|パス| パス.ファイル名())
        .map_or_else(
            || "(動画のパスが空)".to_string(),
            |名前| 名前.文字列().to_string(),
        );
    let クリップの数: usize = 重ね合わせ
        .行の並び()
        .奥から手前の順の行()
        .iter()
        .map(|行| 行.置いたクリップの並び().len())
        .sum();
    format!(
        "{動画} ・ {クリップの数}クリップ ・ 長さ {:.2}秒 ・ 更新 {}",
        重ね合わせ.重ね合わせの長さ().秒数(),
        日時の表示(読めた.重ね合わせ.更新した日時()),
    )
}
