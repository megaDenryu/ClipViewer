//! 左のサイドバーの試験。置くクリップの一覧はスタックの動画が同じときだけ「置く」を押せ、違うときは理由を出すことと、置いたクリップの一覧を押すと選ぶ応答を発し、
//! 選んでいる置いたクリップの設定に名前と区間と繰り返しの回数と「取り除く」を出すことを、egui に描かせて押して確かめる。
#![allow(clippy::expect_used)]

use clip_domain::クリップ識別子;

use super::sidebar::置くクリップの見出し;
use super::sidebar_placed::選んでいないときの文;
use super::sidebar_test_support::{
    サイドバーを描いて文字を押す, 乙だけの置くクリップの一覧を作る
};
use crate::overlay::command::{
    置き方の操作, 重ね合わせの作業場の応答, 重ね合わせの操作
};
use crate::overlay::placement_test_support::{
    置いたクリップの識別子を作る, 置き方の操作を当てる, 開いた作業場,
};
use crate::overlay::state::placement::{
    動画が違うため置けない文, 置くクリップの動画
};

#[test]
fn 置くは動画が同じときだけ押せ_違うときは理由を出す() {
    let 作業場 = 開いた作業場();
    let 置ける = 乙だけの置くクリップの一覧を作る(置くクリップの動画::置ける {
        番号: clip_domain::動画の番号::最初,
        長さ: clip_domain::時間の長さ::作成する(60.0).expect("長さ"),
    });
    assert!(サイドバーを描いて文字を押す(&作業場, &置ける, 置くクリップの見出し).is_some());
    assert_eq!(
        サイドバーを描いて文字を押す(&作業場, &置ける, "置く").expect("置くを描いた"),
        [
            重ね合わせの作業場の応答::今のスタックのクリップを置く(
                クリップ識別子::文字列から作成する("乙".to_string()).expect("識別子")
            )
        ]
    );
    let 違う = 乙だけの置くクリップの一覧を作る(置くクリップの動画::動画が違う);
    assert!(サイドバーを描いて文字を押す(&作業場, &違う, 動画が違うため置けない文).is_some());
    assert_eq!(
        サイドバーを描いて文字を押す(&作業場, &違う, "置く"),
        Some(Vec::new())
    );
}

#[test]
fn 置いたクリップの一覧を押すと選び_選んでいる置いたクリップの設定と取り除くを出す() {
    let mut 作業場 = 開いた作業場();
    let 一覧 = 乙だけの置くクリップの一覧を作る(置くクリップの動画::動画が違う);
    assert!(サイドバーを描いて文字を押す(&作業場, &一覧, 選んでいないときの文).is_some());
    let 選ぶ = 重ね合わせの作業場の応答::操作(重ね合わせの操作::置き方(
        置き方の操作::置いたクリップを選ぶ(置いたクリップの識別子を作る("置-1")),
    ));
    assert_eq!(
        サイドバーを描いて文字を押す(&作業場, &一覧, "選ぶ(0.00秒から)"),
        Some(vec![選ぶ])
    );
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを選ぶ(置いたクリップの識別子を作る("置-1")),
    );
    assert!(サイドバーを描いて文字を押す(&作業場, &一覧, "名前: 甲").is_some());
    assert!(サイドバーを描いて文字を押す(&作業場, &一覧, "区間: 0.00秒 〜 5.00秒").is_some());
    assert!(サイドバーを描いて文字を押す(&作業場, &一覧, "繰り返しの回数: 1回").is_some());
    assert_eq!(
        サイドバーを描いて文字を押す(&作業場, &一覧, "取り除く"),
        Some(vec![重ね合わせの作業場の応答::操作(
            重ね合わせの操作::置き方(置き方の操作::置いたクリップを取り除く(
                置いたクリップの識別子を作る("置-1")
            ))
        )])
    );
}
