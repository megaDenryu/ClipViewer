fn 乙の一覧(動画: 置くクリップの動画) -> 置くクリップの一覧 {
    置くクリップの一覧 {
        並び: vec![置くクリップ {
            識別子: クリップ識別子::文字列から作成する("乙".to_string()).expect("識別子"),
            名前: クリップ名::作成する("乙".to_string()),
        }],
        動画,
    }
}

/// 置くクリップの一覧を渡して作業場の画面を1回描いてから、その文字の真ん中を押して発した応答を返す。描いていなければ無い。
fn 押す(
    作業場: &重ね合わせの作業場,
    一覧: &置くクリップの一覧,
    文字: &str,
) -> Option<Vec<重ね合わせの作業場の応答>> {
    let 画面描画の共有状態 = egui::Context::default();
    let 木 = || {
        super::画面(
            作業場.状態(),
            今のスタックから並べる状況::並べられる,
            Some(一覧),
            試験の全体の音量,
            None,
        )
    };
    let (_, 出力) = 描いて集める(&画面描画の共有状態, Vec::new(), &木);
    let 位置 = 描いた文字の範囲(&出力, 文字)?.center();
    Some(押して集める(&画面描画の共有状態, 位置, &木))
}

fn 開いた作業場() -> 重ね合わせの作業場 {
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    作業場
}

#[test]
fn 置くは動画が同じときだけ押せ_違うときは理由を出す() {
    let 作業場 = 開いた作業場();
    let 置ける = 乙の一覧(置くクリップの動画::置ける {
        番号: clip_domain::動画の番号::最初,
        長さ: clip_domain::時間の長さ::作成する(60.0).expect("長さ"),
    });
    assert!(押す(&作業場, &置ける, 置くクリップの見出し).is_some());
    assert_eq!(
        押す(&作業場, &置ける, "置く").expect("置くを描いた"),
        [
            重ね合わせの作業場の応答::今のスタックのクリップを置く(
                クリップ識別子::文字列から作成する("乙".to_string()).expect("識別子")
            )
        ]
    );
    let 違う = 乙の一覧(置くクリップの動画::動画が違う);
    assert!(押す(&作業場, &違う, 動画が違うため置けない文).is_some());
    assert_eq!(押す(&作業場, &違う, "置く"), Some(Vec::new()));
}

#[test]
fn 置いたクリップの一覧を押すと選び_選んでいる置いたクリップの設定と取り除くを出す() {
    let mut 作業場 = 開いた作業場();
    let 一覧 = 乙の一覧(置くクリップの動画::動画が違う);
    assert!(押す(&作業場, &一覧, 選んでいないときの文).is_some());
    let 選ぶ = 重ね合わせの作業場の応答::操作(重ね合わせの操作::置き方(
        置き方の操作::置いたクリップを選ぶ(置いた("置-1")),
    ));
    assert_eq!(押す(&作業場, &一覧, "甲(0.00秒から)"), Some(vec![選ぶ]));
    当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを選ぶ(置いた("置-1")),
    );
    assert!(押す(&作業場, &一覧, "名前: 甲").is_some());
    assert!(押す(&作業場, &一覧, "区間: 0.00秒 〜 5.00秒").is_some());
    assert!(押す(&作業場, &一覧, "繰り返しの回数: 1回").is_some());
    assert_eq!(
        押す(&作業場, &一覧, "取り除く"),
        Some(vec![重ね合わせの作業場の応答::操作(
            重ね合わせの操作::置き方(置き方の操作::置いたクリップを取り除く(
                置いた("置-1")
            ))
        )])
    );
}
