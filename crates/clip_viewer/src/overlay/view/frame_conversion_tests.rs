//! 複数の範囲枠の操作の変換の試験。隅の掴んだ部分と縦横比の扱いを、百分率へ直した置き方の操作の応答にすることと、
//! 移動量が数でないときはそれを表す操作にすることを確かめる。

use clip_domain::{四隅のつまみ, 枠の掴む所};
use sengen_egui::{
    割合の差, 範囲枠の掴んだ部分, 縦横の割合の差, 縦横比の扱い, 複数の範囲枠の操作
};

use super::frame_conversion::範囲枠の操作を変換する;
use crate::overlay::command::{映す矩形の枠の操作, 置き方の操作};
use crate::overlay::placement_test_support::{動き, 置いた};
use crate::overlay::state::placement::隅の縦横比の扱い;
#[test]
fn 縦横比の扱いと隅の掴んだ部分を百分率の操作へ直す() {
    let 割合 = |横, 縦| {
        縦横の割合の差::生成する(割合の差::生成する(横), 割合の差::生成する(縦))
    };
    let 応答 = 範囲枠の操作を変換する(
        置いた("置-1"),
        複数の範囲枠の操作::動かしている {
            掴んだ部分: 範囲枠の掴んだ部分::右下の隅,
            開始点からの移動量: 割合(0.25, -0.5),
            縦横比の扱い: 縦横比の扱い::保たない,
        },
    );
    assert_eq!(
        応答,
        置き方の操作::映す矩形の枠(映す矩形の枠の操作::動かしている(動き(
            "置-1",
            枠の掴む所::隅(四隅のつまみ::右下),
            25.0,
            -50.0,
            隅の縦横比の扱い::保たない,
        )))
        .応答にする()
    );
    let 数でない = 範囲枠の操作を変換する(
        置いた("置-1"),
        複数の範囲枠の操作::放した {
            掴んだ部分: 範囲枠の掴んだ部分::内側,
            開始点からの移動量: 割合(f32::NAN, 0.0),
            縦横比の扱い: 縦横比の扱い::保つ,
        },
    );
    assert_eq!(
        数でない,
        置き方の操作::映す矩形の枠(映す矩形の枠の操作::移動量が数でない).応答にする()
    );
}
