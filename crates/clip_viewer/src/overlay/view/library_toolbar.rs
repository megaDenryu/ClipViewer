//! 重ね合わせの一覧の道具の帯。見出し・件数・名前の絞り込み・並べ替え・読み直すを横に並べる。絞り込みと並べ替えの部品は、スタックの作業場と共有する `library_common::view` が組む。
//! 参照: _doc/設計/同時再生.md 2-7

use sengen_egui::{ノード, ボタン, 子, 文字表示, 横並び};

use crate::library_common::list::{
    並べられる一覧, 並べ替え方, 最後に読んだ一覧
};
use crate::library_common::view::絞り込みと並べ替えの材料;
use crate::overlay::command::{
    一覧とダイアログの操作, 重ね合わせの作業場の応答
};
use crate::overlay::state::重ね合わせの作業場の状態;
use crate::styles;

pub(super) fn 道具の帯(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    let 件数 = match 状態.ライブラリ().一覧().一覧() {
        最後に読んだ一覧::読めた(一覧) => format!("{}件", 一覧.項目の数()),
        最後に読んだ一覧::まだ無い | 最後に読んだ一覧::読めない(_) => {
            String::new()
        }
    };
    let 見せ方 = 状態.ライブラリ().一覧().見せ方();
    let 絞り込みと並べ替え = 絞り込みと並べ替えの材料 {
        絞り込みの文字列: 見せ方.絞り込み.文字列(),
        並べ替え: 見せ方.並べ替え,
        並べ替えの識別子: "重ね合わせの一覧の並べ替え",
        絞り込みを書き換えた,
        並べ替えを選んだ,
    };
    横並び(
        子![
            文字表示("重ね合わせの一覧").装飾(styles::見出し),
            文字表示(件数).装飾(styles::補足),
        ]
        .into_iter()
        .chain(絞り込みと並べ替え.部品の並び())
        .chain(子![ボタン(
            "読み直す",
            一覧とダイアログの操作::読み直す.応答にする()
        )])
        .collect(),
    )
    .into()
}

fn 絞り込みを書き換えた(文字列: String) -> 重ね合わせの作業場の応答 {
    一覧とダイアログの操作::絞り込みを書き換える(文字列).応答にする()
}

fn 並べ替えを選んだ(並べ替え: 並べ替え方) -> 重ね合わせの作業場の応答 {
    一覧とダイアログの操作::並べ替えを選ぶ(並べ替え).応答にする()
}
