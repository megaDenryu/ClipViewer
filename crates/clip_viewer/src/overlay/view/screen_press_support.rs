//! 重ね合わせの作業場の画面全体を描いて文字を探し、押す試験の道具。作業場の状態と今のスタックから並べる状況を渡して画面を組む。
//! egui の下のパネルは、最初のフレームでは中身の高さを知らないまま決まった高さで描き、はみ出した中身(タイムライン)を描かない。
//! そのため、どの道具もまず1フレーム描いてパネルの高さを決めさせてから、文字を探す。

use eframe::egui;

use super::test_support::{押して集める, 描いた文字の範囲, 描いて集める};
use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::state::library_status::重ね合わせのライブラリの様子;
use crate::overlay::state::{今のスタックから並べる状況, 全体の音量};
use crate::overlay::workspace::重ね合わせの作業場;

/// 試験で画面へ渡す全体の音量。
pub(super) const 試験の全体の音量: 全体の音量 = 全体の音量::試験で使う起動時の値;

/// 作業場の画面を描いてから、その文字の真ん中を押して発した応答を返す。
pub(super) fn 文字を押して集める(
    作業場: &重ね合わせの作業場,
    並べられるか: 今のスタックから並べる状況,
    文字: &str,
) -> Vec<重ね合わせの作業場の応答> {
    let 画面描画の共有状態 = egui::Context::default();
    let 木 = || {
        super::画面(
            作業場.状態(),
            並べられるか,
            None,
            試験の全体の音量,
            None,
            重ね合わせのライブラリの様子::書ける,
        )
    };
    let _ = 描いて集める(&画面描画の共有状態, Vec::new(), &木);
    let (_, 出力) = 描いて集める(&画面描画の共有状態, Vec::new(), &木);
    let 位置 = 描いた文字の範囲(&出力, 文字)
        .unwrap_or_else(|| panic!("「{文字}」を描いていない"))
        .center();
    押して集める(&画面描画の共有状態, 位置, &木)
}

/// 作業場の画面を描き、その文字を描いたか。重ね合わせのライブラリは書ける様子で描く。
pub(super) fn 描いたか(
    作業場: &重ね合わせの作業場,
    並べられるか: 今のスタックから並べる状況,
    文字: &str,
) -> bool {
    ライブラリの様子で描いたか(
        作業場,
        並べられるか,
        重ね合わせのライブラリの様子::書ける,
        文字,
    )
}

/// 作業場の画面を、渡した重ね合わせのライブラリの様子で描き、その文字を描いたか。
pub(super) fn ライブラリの様子で描いたか(
    作業場: &重ね合わせの作業場,
    並べられるか: 今のスタックから並べる状況,
    ライブラリの様子: 重ね合わせのライブラリの様子<'_>,
    文字: &str,
) -> bool {
    let 画面描画の共有状態 = egui::Context::default();
    let 木 = || {
        super::画面(
            作業場.状態(),
            並べられるか,
            None,
            試験の全体の音量,
            None,
            ライブラリの様子,
        )
    };
    let _ = 描いて集める(&画面描画の共有状態, Vec::new(), &木);
    let (_, 出力) = 描いて集める(&画面描画の共有状態, Vec::new(), &木);
    描いた文字の範囲(&出力, 文字).is_some()
}
