//! 重ね合わせの再生の操作の行。再生と停止のボタンと、再生の位置と重ね合わせの長さと、全体ループのチェックボックスと、音量のつまみと、
//! 「全体を消音」のチェックボックスを並べる。音量のつまみと全体の消音はスタックの作業場と同じ見る側の設定であり、値は配線が渡す(同時再生.md 2-6)。
//! 「全体を消音」は、置いたクリップごとの「消音」(サイドバー)と別のものなので、文字を分ける。
//! 再生のボタンの説明に再生と停止のキー(Space)を出す。再生のボタンは、再生している間か再生を始められるとき(重ね合わせを開いていて長さが0秒でない)だけ押せる。全体ループは重ね合わせを開いている間だけ押せる。
//! 再生の位置を見せて動かす帯は、下のタイムラインの時間の軸が兼ねる(`timeline.rs`。第15段階で位置の棒をやめた)。

use sengen_egui::{
    スライダー, チェックボックス, ノード, ボタン, 付け足せる, 子, 文字表示, 横並び
};

use super::keys::再生と停止のキー;
use crate::overlay::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::overlay::state::{全体の音量, 重ね合わせの作業場の状態};
use crate::volume_step::音量のつまみの刻み;

pub(super) fn 再生の操作の行(
    状態: &重ね合わせの作業場の状態,
    全体の音量: 全体の音量,
) -> ノード<重ね合わせの作業場の応答> {
    let 再生しているか = 状態.再生しているか();
    let 再生のボタンの文字 = if 再生しているか {
        "停止"
    } else {
        "再生"
    };
    let 位置の文字 = match 状態.再生の位置と長さ() {
        Some((位置, 長さ)) => format!("{:.2}秒 / {:.2}秒", 位置.時刻().秒数(), 長さ.秒数()),
        None => "重ね合わせを開いていない".to_string(),
    };
    // 注意: 開いていない間は全体ループを持つ重ね合わせが無いため、印を付けたまま押せなくする(開いたときの最初の値は全体ループである)。
    let 全体ループ = 状態.全体ループか();
    横並び(子![
        ボタン(
            再生のボタンの文字,
            重ね合わせの作業場の応答::操作(重ね合わせの操作::再生を切り替える)
        )
        .有効(再生しているか || 状態.再生を始められるか())
        .説明(再生と停止のキー.表記()),
        文字表示(位置の文字),
        横並び(子![チェックボックス(
            "全体ループ",
            全体ループ.unwrap_or(true),
            全体ループを設定する
        )])
        .有効(全体ループ.is_some()),
        文字表示("音量"),
        スライダー(
            全体の音量.つまみの値.値(),
            0.0..=1.0,
            重ね合わせの作業場の応答::音量のつまみの値を選ぶ
        )
        .刻み(音量のつまみの刻み)
        .説明("スタックの作業場と同じ音量のつまみ。置いたクリップごとの音量に掛けて鳴らす"),
        チェックボックス(
            "全体を消音",
            全体の音量.消音しているか,
            |_| { 重ね合わせの作業場の応答::全体の消音を切り替える }
        )
        .説明("スタックの作業場の消音(M キー)と同じ設定。置いたクリップごとの「消音」とは別"),
    ])
    .into()
}

fn 全体ループを設定する(有効: bool) -> 重ね合わせの作業場の応答 {
    重ね合わせの作業場の応答::操作(重ね合わせの操作::全体ループを設定する(
        有効,
    ))
}
