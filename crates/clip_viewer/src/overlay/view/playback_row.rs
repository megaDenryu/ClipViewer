//! 重ね合わせの再生の操作の行。再生と停止のボタンと、再生の位置と重ね合わせの長さと、位置の棒と、全体ループのチェックボックスを並べる。
//! 再生のボタンは、再生している間か再生を始められるとき(重ね合わせを開いていて長さが0秒でない)だけ押せる。
//! 位置の棒は位置を見せるだけであり、押して位置を動かす再生位置の帯は後の段階で足す。

use sengen_egui::{
    チェックボックス, ノード, ボタン, 割合, 子, 文字表示, 横並び, 画素, 論理画素, 進捗バー,
};

use crate::overlay::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::overlay::state::重ね合わせの作業場の状態;

/// 位置の棒の幅。幅を決めないと棒が行の残りの幅を全部使い、後ろの全体ループのチェックボックスを区画の外へ押し出す。
const 位置の棒の幅: 論理画素 = 画素(240.0);

pub(super) fn 再生の操作の行(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    let 再生しているか = 状態.再生しているか();
    let 再生のボタンの文字 = if 再生しているか {
        "停止"
    } else {
        "再生"
    };
    let (位置の文字, 進み具合) = match 状態.再生の位置と長さ() {
        Some((位置, 長さ)) => {
            let 秒 = 位置.時刻().秒数();
            let 進み具合 = if 長さ.秒数() > 0.0 {
                秒 / 長さ.秒数()
            } else {
                0.0
            };
            (format!("{秒:.2}秒 / {:.2}秒", 長さ.秒数()), 進み具合)
        }
        None => ("重ね合わせを開いていない".to_string(), 0.0),
    };
    let 全体ループ = 状態
        .開いている重ね合わせ()
        .is_none_or(|開いている| 開いている.全体ループか());
    横並び(子![
        ボタン(
            再生のボタンの文字,
            重ね合わせの作業場の応答::操作(重ね合わせの操作::再生を切り替える)
        )
        .有効(再生しているか || 状態.再生を始められるか()),
        文字表示(位置の文字),
        進捗バー(割合::倍精度の小数から範囲へ丸めて生成する(進み具合)).幅(位置の棒の幅),
        チェックボックス("全体ループ", 全体ループ, 全体ループを切り替える),
    ])
    .into()
}

fn 全体ループを切り替える(有効: bool) -> 重ね合わせの作業場の応答 {
    重ね合わせの作業場の応答::操作(重ね合わせの操作::全体ループを切り替える(
        有効,
    ))
}
