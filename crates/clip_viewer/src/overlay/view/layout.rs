//! 重ね合わせの作業場の画面の区画の配置。上にヘッダー、下に再生の操作とタイムライン、左にサイドバー、中央に出力を置き、知らせの並びと
//! 重ね合わせのダイアログと見えない部品を重ねて、1フレーム分の画面の木を組む。各区画の中身は兄弟のモジュールが組む。

use std::time::Duration;

use sengen_egui::{
    ノード, パネル, パネルの位置, 一定時間で消える通知の並び, 子, 無し, 縦積み
};

use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::state::{
    placement::置くクリップの一覧, 今のスタックから並べる状況, 全体の音量, 重ね合わせの作業場の状態,
};

/// 重ね合わせの作業場の画面。今のスタックから並べる状況と、置くクリップの一覧(重ね合わせを開いていなければ無い)と、全体の音量と、
/// スタックの作業場の描き直すまでの時間は、配線がスタックの作業場の状態から求めて渡す。重ね合わせのライブラリの様子は状態から読む。
/// 重ね合わせが前の間はスタックの作業場の画面を組まないため、スタックの保存待ちの時刻に描き直しを予約する役もこの画面が受け持つ。
/// 左のサイドバーは中央の出力より先に置く(egui は中央のパネルを最後に置き、残りの場所を使わせるため)。
pub(crate) fn 画面(
    状態: &重ね合わせの作業場の状態,
    並べられるか: 今のスタックから並べる状況,
    置くクリップ: Option<&置くクリップの一覧>,
    全体の音量: 全体の音量,
    スタックの作業場の描き直すまでの時間: Option<Duration>,
) -> ノード<重ね合わせの作業場の応答> {
    let 開いている = 状態.開いている重ね合わせ();
    縦積み(子![
        super::invisible::ファイルとキーの受け取りと描き直しの予約(
            状態,
            スタックの作業場の描き直すまでの時間
        ),
        パネル(
            "重ね合わせのヘッダー",
            パネルの位置::上,
            子![super::header::ヘッダー(状態, 並べられるか)]
        ),
        パネル(
            "重ね合わせの再生の操作",
            パネルの位置::下,
            子![
                super::playback_row::再生の操作の行(状態, 全体の音量),
                開いている.map_or_else(無し, super::timeline::タイムライン),
            ]
        ),
        開いている.map_or_else(無し, |開いている| {
            super::sidebar::サイドバーのパネル(開いている, 置くクリップ)
        }),
        パネル(
            "重ね合わせの出力",
            パネルの位置::中央,
            子![super::output_area::出力の区画(状態, 並べられるか)]
        ),
        一定時間で消える通知の並び("重ね合わせの作業場の知らせ", 状態.並べる知らせ()),
        super::library_dialog::開いているダイアログ(状態),
    ])
    .into()
}
