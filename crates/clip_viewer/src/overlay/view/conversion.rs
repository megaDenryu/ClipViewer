//! 映す矩形の百分率と割合の変換の境界。ドメインは映す矩形を重ねる画面に対する百分率(0〜100)で持ち、SengenEgui は割合(0〜1)で受け取るため、
//! その変換をここ1箇所に置く。映す矩形は重ね合わせの作業場にだけあるため、ここに置く。クロップ範囲の変換はスタックの作業場と共有する
//! `output_measure` にある。参照: _doc/設計/同時再生.md 3-4

use clip_domain::映す矩形;
use sengen_egui::{割合, 割合で表した矩形};

/// 映す矩形を、重ねる画面(割合の矩形へ置く容器)の中で占める割合で表した矩形にする。
pub(super) fn 映す矩形を割合の矩形にする(
    矩形: 映す矩形
) -> 割合で表した矩形 {
    左上と大きさを割合の矩形にする(
        矩形.左端().割合(),
        矩形.上端().割合(),
        矩形.幅().割合(),
        矩形.高さ().割合(),
    )
}

/// 左上と大きさ(0〜1)から割合で表した矩形を作る。右端と下端は倍精度の小数で足してから割合へ丸めるため、
/// 単精度の小数で足すと1をわずかに超える組(格子の3等分の最後の列等)も、端が1を超えずに受け取れる(クロップ範囲の変換と同じ規則)。
fn 左上と大きさを割合の矩形にする(
    左端: f64,
    上端: f64,
    幅: f64,
    高さ: f64,
) -> 割合で表した矩形 {
    let 割合にする = 割合::倍精度の小数から範囲へ丸めて生成する;
    match 割合で表した矩形::生成する(
        割合にする(左端),
        割合にする(上端),
        割合にする(左端 + 幅),
        割合にする(上端 + 高さ),
    ) {
        Ok(矩形) => 矩形,
        Err(不正) => {
            panic!("映す矩形の幅と高さは5%以上なので左端と右端は逆転しない(到達したらバグ): {不正}")
        }
    }
}
