//! 複数の範囲枠の操作を、重ね合わせの作業場の応答へ直す境界。SengenEgui は移動量を重ねる画面の幅と高さを1とした割合の差(f32)で発し、
//! ドメインは重ねる画面に対する百分率の差分(f64)で受け取るため、その変換をここ1箇所に置く。
//! スタックの作業場のクロップ枠の変換(`view/conversion.rs`)と同じ形だが、重ね合わせの作業場の層はスタックの作業場の `view` を使わないため別に持つ。
//! 参照: _doc/設計/同時再生.md 2-4・3-4

use clip_domain::{
    四隅のつまみ, 映す矩形の移動量, 百分率の差分, 置いたクリップの識別子
};
use sengen_egui::{
    割合の差, 範囲枠の掴んだ部分, 縦横の割合の差, 縦横比の扱い, 複数の範囲枠の操作
};

use crate::overlay::command::{
    映す矩形の枠の操作, 置き方の操作, 重ね合わせの作業場の応答, 重ね合わせの操作,
};
use crate::overlay::state::{
    映す矩形のドラッグの動き, 映す矩形の掴む所, 隅の縦横比の扱い
};

/// 置き方の操作を、重ね合わせの作業場の応答にする。
pub(super) fn 置き方の応答(
    操作: 置き方の操作
) -> 重ね合わせの作業場の応答 {
    重ね合わせの作業場の応答::操作(重ね合わせの操作::置き方(操作))
}

/// 枠の鍵(置いたクリップの識別子)と複数の範囲枠の操作を、百分率へ直した置き方の操作の応答にする。選んだは置いたクリップを選ぶ操作にする。
pub(super) fn 範囲枠の操作を変換する(
    鍵: 置いたクリップの識別子,
    操作: 複数の範囲枠の操作,
) -> 重ね合わせの作業場の応答 {
    let 枠の操作 = match 操作 {
        複数の範囲枠の操作::選んだ => {
            return 置き方の応答(置き方の操作::置いたクリップを選ぶ(鍵));
        }
        複数の範囲枠の操作::掴み始めた { .. } => {
            映す矩形の枠の操作::掴み始めた(鍵)
        }
        複数の範囲枠の操作::動かしている {
            掴んだ部分,
            開始点からの移動量,
            縦横比の扱い,
        } => 動きにする(鍵, 掴んだ部分, 開始点からの移動量, 縦横比の扱い).map_or(
            映す矩形の枠の操作::移動量が数でない,
            映す矩形の枠の操作::動かしている,
        ),
        複数の範囲枠の操作::放した {
            掴んだ部分,
            開始点からの移動量,
            縦横比の扱い,
        } => 動きにする(鍵, 掴んだ部分, 開始点からの移動量, 縦横比の扱い).map_or(
            映す矩形の枠の操作::移動量が数でない,
            映す矩形の枠の操作::放した,
        ),
        複数の範囲枠の操作::掴んだ枠が無くなった => {
            映す矩形の枠の操作::掴んだ枠が無くなった(鍵)
        }
    };
    置き方の応答(置き方の操作::映す矩形の枠(枠の操作))
}

/// 移動量が有限でなければ無い。
fn 動きにする(
    鍵: 置いたクリップの識別子,
    掴んだ部分: 範囲枠の掴んだ部分,
    移動量: 縦横の割合の差,
    縦横比: 縦横比の扱い,
) -> Option<映す矩形のドラッグの動き> {
    let 百分率にする =
        |差: 割合の差| 百分率の差分::作成する(f64::from(差.生の値()) * 100.0).ok();
    Some(映す矩形のドラッグの動き {
        対象: 鍵,
        掴む所: 掴む所にする(掴んだ部分),
        移動量: 映す矩形の移動量 {
            横: 百分率にする(移動量.横)?,
            縦: 百分率にする(移動量.縦)?,
        },
        縦横比: match 縦横比 {
            縦横比の扱い::保つ => 隅の縦横比の扱い::絵の形を保つ,
            縦横比の扱い::保たない => 隅の縦横比の扱い::保たない,
        },
    })
}

fn 掴む所にする(部分: 範囲枠の掴んだ部分) -> 映す矩形の掴む所 {
    match 部分 {
        範囲枠の掴んだ部分::内側 => 映す矩形の掴む所::内側,
        範囲枠の掴んだ部分::左上の隅 => {
            映す矩形の掴む所::隅(四隅のつまみ::左上)
        }
        範囲枠の掴んだ部分::右上の隅 => {
            映す矩形の掴む所::隅(四隅のつまみ::右上)
        }
        範囲枠の掴んだ部分::左下の隅 => {
            映す矩形の掴む所::隅(四隅のつまみ::左下)
        }
        範囲枠の掴んだ部分::右下の隅 => {
            映す矩形の掴む所::隅(四隅のつまみ::右下)
        }
    }
}
