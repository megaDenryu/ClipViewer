//! 複数の範囲枠の操作を、重ね合わせの作業場の応答へ直す境界。掴んだ部分と割合の差の変換は、スタックの作業場のクロップ枠と共有する
//! `output_measure/frame_operation.rs` を使い、ここは枠の鍵(置いたクリップの識別子)と縦横比の扱いを添えて置き方の操作にするだけである。
//! 参照: _doc/設計/同時再生.md 2-4・3-4

use clip_domain::置いたクリップの識別子;
use sengen_egui::{
    範囲枠の掴んだ部分, 縦横の割合の差, 縦横比の扱い, 複数の範囲枠の操作
};

use crate::output_measure::{
    割合の差を枠の移動量にする, 掴んだ部分を掴む所にする
};
use crate::overlay::command::{
    映す矩形の枠の操作, 置き方の操作, 重ね合わせの作業場の応答
};
use crate::overlay::state::placement::{
    映す矩形のドラッグの動き, 隅の縦横比の扱い
};

/// 枠の鍵(置いたクリップの識別子)と複数の範囲枠の操作を、百分率へ直した置き方の操作の応答にする。選んだは置いたクリップを選ぶ操作にする。
pub(super) fn 範囲枠の操作を変換する(
    鍵: 置いたクリップの識別子,
    操作: 複数の範囲枠の操作,
) -> 重ね合わせの作業場の応答 {
    let 枠の操作 = match 操作 {
        複数の範囲枠の操作::選んだ => {
            return 置き方の操作::置いたクリップを選ぶ(鍵).応答にする();
        }
        複数の範囲枠の操作::掴み始めた { .. } => {
            映す矩形の枠の操作::掴み始めた(鍵)
        }
        複数の範囲枠の操作::動かしている {
            掴んだ部分,
            開始点からの移動量,
            縦横比の扱い,
        } => 動きにする(鍵, 掴んだ部分, 開始点からの移動量, 縦横比の扱い).map_or(
            映す矩形の枠の操作::移動量が数でない,
            映す矩形の枠の操作::動かしている,
        ),
        複数の範囲枠の操作::放した {
            掴んだ部分,
            開始点からの移動量,
            縦横比の扱い,
        } => 動きにする(鍵, 掴んだ部分, 開始点からの移動量, 縦横比の扱い).map_or(
            映す矩形の枠の操作::移動量が数でない,
            映す矩形の枠の操作::放した,
        ),
        複数の範囲枠の操作::掴んだ枠が無くなった => {
            映す矩形の枠の操作::掴んだ枠が無くなった(鍵)
        }
    };
    置き方の操作::映す矩形の枠(枠の操作).応答にする()
}

/// 移動量が有限でなければ無い。
fn 動きにする(
    鍵: 置いたクリップの識別子,
    掴んだ部分: 範囲枠の掴んだ部分,
    移動量: 縦横の割合の差,
    縦横比: 縦横比の扱い,
) -> Option<映す矩形のドラッグの動き> {
    Some(映す矩形のドラッグの動き {
        対象: 鍵,
        掴む所: 掴んだ部分を掴む所にする(掴んだ部分),
        移動量: 割合の差を枠の移動量にする(移動量)?,
        縦横比の扱い: match 縦横比 {
            縦横比の扱い::保つ => 隅の縦横比の扱い::絵の形を保つ,
            縦横比の扱い::保たない => 隅の縦横比の扱い::絵の形を保たない,
        },
    })
}
