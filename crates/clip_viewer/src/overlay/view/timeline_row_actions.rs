//! タイムラインの行の操作の部品。「行を足す」と「選んだ空の行を消す」のボタンと、選んでいる行を画面の上から数えた順番で表す文を横に並べる。
//! 「選んだ空の行を消す」は、空の行を選んでいるときだけ押せる。「行を足す」は、行が同時に重ねられる行の数より少ないときだけ押せる。
//! 行を足せるかと上から数えた順番は、`clip_domain` のタイムラインの行の並びが求める。参照: _doc/設計/同時再生.md 2-6

use clip_domain::{タイムラインの行の並び, 同時に重ねられる行の数};
use sengen_egui::{ノード, ボタン, 付け足せる, 子, 文字表示, 横並び};

use crate::overlay::command::{タイムラインの操作, 重ね合わせの作業場の応答};
use crate::overlay::state::timeline::選んでいる行の番号と空か;
use crate::overlay::state::開いている重ね合わせ;

/// 行を選んでいないときに出す文。
const 行を選んでいないときの文: &str = "行の何も無い所を押すと、その行を選ぶ";

pub(super) fn 行の操作の部品を並べる(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let 選んでいる行 = 開いている.選んでいる行の番号と空か();
    let 行の並び = 開いている.重ね合わせ().行の並び();
    横並び(子![
        ボタン(
            "行を足す",
            タイムラインの操作::空の行を手前に足す.応答にする()
        )
        .有効(行の並び.行を足せるか())
        .説明(format!(
            "空の行を最も手前(いちばん上)に足す。行は{同時に重ねられる行の数}つまで"
        )),
        ボタン(
            "選んだ空の行を消す",
            タイムラインの操作::選んでいる空の行を消す.応答にする()
        )
        .有効(選んでいる行.is_some_and(|様子| 様子.空か))
        .説明("選んでいる空の行を消す。置いたクリップがある行は消せない"),
        文字表示(選んでいる行の説明文を作る(
            選んでいる行,
            行の並び
        )),
    ])
    .into()
}

/// 選んでいる行を、画面の上から数えた順番で表す文。
fn 選んでいる行の説明文を作る(
    選んでいる行: Option<選んでいる行の番号と空か>,
    行の並び: &タイムラインの行の並び,
) -> String {
    let Some(様子) = 選んでいる行 else {
        return 行を選んでいないときの文.to_string();
    };
    let 中身 = if 様子.空か {
        "空の行"
    } else {
        "置いたクリップがある行"
    };
    match 行の並び.上から数えた順番(様子.行) {
        Some(順番) => format!("選んでいる行: {順番}({中身})"),
        None => 行を選んでいないときの文.to_string(),
    }
}
