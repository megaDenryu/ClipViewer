//! タイムラインの行の操作の行。「行を足す」と「選んだ空の行を消す」のボタンと、選んでいる行を画面の上から数えた番号で表す文を並べる。
//! 「選んだ空の行を消す」は、空の行を選んでいるときだけ押せる。「行を足す」は、行が8つより少ないときだけ押せる。参照: _doc/設計/同時再生.md 2-6

use sengen_egui::{ノード, ボタン, 付け足せる, 子, 文字表示, 横並び};

use crate::overlay::command::{タイムラインの操作, 重ね合わせの作業場の応答};
use crate::overlay::state::timeline::選んでいる行の様子;
use crate::overlay::state::開いている重ね合わせ;

pub(super) fn 行の操作の行(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let 選んでいる行 = 開いている.選んでいる行の様子();
    let 行の数 = 開いている.重ね合わせ().行の並び().行の数();
    横並び(子![
        ボタン(
            "行を足す",
            タイムラインの操作::空の行を手前に足す.応答にする()
        )
        .有効(開いている.空の行を足せるか())
        .説明("空の行を最も手前(いちばん上)に足す。行は8つまで"),
        ボタン(
            "選んだ空の行を消す",
            タイムラインの操作::選んでいる空の行を消す.応答にする()
        )
        .有効(選んでいる行.is_some_and(|様子| 様子.空か))
        .説明("選んでいる空の行を消す。置いたクリップがある行は消せない"),
        文字表示(選んでいる行の文(選んでいる行, 行の数)),
    ])
    .into()
}

/// 選んでいる行を、画面の上から数えた番号で表す文。手前の行ほど上に描くため、上からの番号は行の数から行の番号を引いた数である。
fn 選んでいる行の文(
    選んでいる行: Option<選んでいる行の様子>, 行の数: usize
) -> String {
    match 選んでいる行 {
        None => "行の何も無い所を押すと、その行を選ぶ".to_string(),
        Some(様子) => {
            let 上からの番号 = 行の数.saturating_sub(様子.行.番号());
            let 中身 = if 様子.空か {
                "空の行"
            } else {
                "置いたクリップがある行"
            };
            format!("選んでいる行: 上から{上からの番号}番目({中身})")
        }
    }
}
