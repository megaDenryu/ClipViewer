/// 重ね合わせの作業場の画面。今のスタックから並べる状況と、音量のつまみの値と、スタックの作業場の描き直すまでの時間は、配線がスタックの作業場の状態から求めて渡す。
/// 重ね合わせが前の間はスタックの作業場の画面を組まないため、スタックの保存待ちの時刻に描き直しを予約する役もこの画面が受け持つ。
/// 左のサイドバーは中央の出力より先に置く(egui は中央のパネルを最後に置き、残りの場所を使わせるため)。
pub(crate) fn 画面(
    状態: &重ね合わせの作業場の状態,
    並べられるか: 今のスタックから並べる状況,
    つまみの音量: 音量,
    スタックの作業場の描き直すまでの時間: Option<Duration>,
) -> ノード<重ね合わせの作業場の応答> {
    let mut 区画: Vec<ノード<重ね合わせの作業場の応答>> = 子![
        invisible::ファイルとキーの受け取りと描き直しの予約(
            状態,
            スタックの作業場の描き直すまでの時間
        ),
        パネル(
            "重ね合わせのヘッダー",
            パネルの位置::上,
            子![header::ヘッダー(
                状態.開いている重ね合わせ().is_some(),
                並べられるか
            )]
        ),
        パネル(
            "重ね合わせの再生の操作",
            パネルの位置::下,
            子![playback_row::再生の操作の行(状態, つまみの音量)]
        ),
    ];
    区画.extend(
        状態
            .開いている重ね合わせ()
            .map(sound_sidebar::置いたクリップの音のパネル),
    );
    区画.extend(子![
        パネル(
            "重ね合わせの出力",
            パネルの位置::中央,
            子![出力の区画(状態, 並べられるか)]
        ),
        一定時間で消える通知の並び("重ね合わせの作業場の知らせ", 状態.並べる知らせ()),
    ]);
    縦積み(区画).into()
}

/// 出力の区画。置かなかったクリップの報告と音の様子(音を鳴らせない理由)があれば上に出し、重ね合わせを開いていれば重ねる画面を、開いていなければ案内と「今のスタックから並べる」を出す。
fn 出力の区画(
    状態: &重ね合わせの作業場の状態,
    並べられるか: 今のスタックから並べる状況,
) -> ノード<重ね合わせの作業場の応答> {
    let 報告 = 縦積み(
        状態
            .置かなかったクリップの報告の文()
            .into_iter()
            .chain(状態.音の様子の文の並び())
            .map(|文| 文字表示(文).into())
            .collect(),
    );
    let 中身 = match 状態.開いている重ね合わせ() {
        Some(開いている) => screen::重ねる画面(開いている),
        None => not_open::開いていない間の案内(並べられるか),
    };
    縦積み(子![報告, 中身]).into()
}
