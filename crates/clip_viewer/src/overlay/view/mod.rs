//! 重ね合わせの作業場の画面。重ね合わせの作業場を借りて1フレーム分の画面を組み、操作を重ね合わせの作業場の応答として発する。
//! 今はヘッダー(「スタックへ戻る」・再生と停止・再生位置)と知らせと、落とされたファイルの受け取りだけを置く。重ねる画面等は後の段階で足す。
//! SengenEgui の口だけで組み、素の egui を呼ばない。参照: _doc/設計/同時再生.md 2-3・2-8・3-3

use std::path::PathBuf;
use std::time::Duration;

use sengen_egui::{
    ノード, パネル, パネルの位置, ボタン, 一定時間で消える通知の並び, 子, 描き直しを予約する,
    文字表示, 横並び, 無し, 縦積み, 落とされたファイルをまとめて受け取る,
};

use super::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use super::workspace::重ね合わせの作業場;
use crate::redraw_interval::描き直しの間隔;

/// 重ね合わせの作業場の画面。スタックの作業場の描き直すまでの時間は、配線がスタックの作業場の状態から求めて渡す。
/// 重ね合わせが前の間はスタックの作業場の画面を組まないため、スタックの保存待ちの時刻に描き直しを予約する役もこの画面が受け持つ。
pub(crate) fn 画面(
    作業場: &重ね合わせの作業場,
    スタックの作業場の描き直すまでの時間: Option<Duration>,
) -> ノード<重ね合わせの作業場の応答> {
    縦積み(子![
        落とされたファイルをまとめて受け取る(
            落とされたファイルを開かずに知らせる
        ),
        描き直しの予約(作業場, スタックの作業場の描き直すまでの時間),
        パネル(
            "重ね合わせのヘッダー",
            パネルの位置::上,
            子![ヘッダー(作業場)]
        ),
        一定時間で消える通知の並び(
            "重ね合わせの作業場の知らせ",
            作業場.並べる知らせ()
        ),
    ])
    .into()
}

/// 落とされたファイルの受け取りが発する応答。動画と JSON はスタックの作業場で開くため、パスは使わずに知らせだけを頼む。
fn 落とされたファイルを開かずに知らせる(
    _パス一覧: Vec<PathBuf>,
) -> 重ね合わせの作業場の応答 {
    重ね合わせの作業場の応答::操作(重ね合わせの操作::ファイルを落とされた)
}

/// ヘッダー。スタックの作業場へ戻るボタンと、再生と停止のボタンと、再生位置と重ね合わせの長さを並べる。
/// 再生のボタンは、再生している間か再生を始められるとき(重ね合わせを開いていて長さが0秒でない)だけ押せる。
fn ヘッダー(
    作業場: &重ね合わせの作業場
) -> ノード<重ね合わせの作業場の応答> {
    let 再生しているか = 作業場.再生しているか();
    let 再生のボタンの文字 = if 再生しているか {
        "停止"
    } else {
        "再生"
    };
    let 位置の文字 = match 作業場.再生の位置と長さ() {
        Some((位置, 長さ)) => format!("{:.2}秒 / {:.2}秒", 位置.時刻().秒数(), 長さ.秒数()),
        None => "重ね合わせを開いていない".to_string(),
    };
    横並び(子![
        ボタン(
            "スタックへ戻る",
            重ね合わせの作業場の応答::スタックの作業場へ戻る
        ),
        ボタン(
            再生のボタンの文字,
            重ね合わせの作業場の応答::操作(重ね合わせの操作::再生を切り替える)
        )
        .有効(再生しているか || 作業場.再生を始められるか()),
        文字表示(位置の文字),
    ])
    .into()
}

/// 入力が無くても画面を進めるなら、描き直しを予約する。重ね合わせの作業場の時間と、スタックの作業場の時間の短い方で予約する。
fn 描き直しの予約(
    作業場: &重ね合わせの作業場,
    スタックの作業場の描き直すまでの時間: Option<Duration>,
) -> ノード<重ね合わせの作業場の応答> {
    let 重ね合わせの描き直すまでの時間 = 作業場.再生しているか().then_some(描き直しの間隔);
    match [
        重ね合わせの描き直すまでの時間,
        スタックの作業場の描き直すまでの時間,
    ]
    .into_iter()
    .flatten()
    .min()
    {
        Some(待つ時間) => 描き直しを予約する(待つ時間).into(),
        None => 無し(),
    }
}
