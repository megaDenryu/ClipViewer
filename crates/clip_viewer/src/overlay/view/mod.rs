//! 重ね合わせの作業場の画面。重ね合わせの作業場の状態を借りて1フレーム分の画面を組み、操作を重ね合わせの操作として発する。
//! 今はヘッダー(「スタックへ戻る」・再生と停止・再生位置)だけを置く。重ねる画面・タイムライン・サイドバーは後の段階で足す。
//! SengenEgui の口だけで組み、素の egui を呼ばない。参照: _doc/設計/同時再生.md 2-3・3-3

use std::time::Duration;

use sengen_egui::{
    ノード, パネル, パネルの位置, ボタン, 子, 描き直しを予約する, 文字表示, 横並び, 無し, 縦積み,
};

use super::command::重ね合わせの操作;
use super::state::重ね合わせの作業場の状態;

/// 再生中に描き直す間隔(約60回/秒)。スタックの作業場の描き直しの間隔と同じ値である。
const 再生中に描き直す間隔: Duration = Duration::from_millis(16);

/// 重ね合わせの作業場の画面。スタックの作業場の描き直すまでの時間は、配線がスタックの作業場の状態から求めて渡す。
/// 重ね合わせが前の間はスタックの作業場の画面を組まないため、スタックの保存待ちの時刻に描き直しを予約する役もこの画面が受け持つ。
pub(crate) fn 画面(
    状態: &重ね合わせの作業場の状態,
    スタックの作業場の描き直すまで: Option<Duration>,
) -> ノード<重ね合わせの操作> {
    縦積み(子![
        描き直しの予約(状態, スタックの作業場の描き直すまで),
        パネル(
            "重ね合わせのヘッダー",
            パネルの位置::上,
            子![ヘッダー(状態)]
        ),
    ])
    .into()
}

/// ヘッダー。スタックの作業場へ戻るボタンと、再生と停止のボタンと、再生位置と重ね合わせの長さを並べる。
fn ヘッダー(
    状態: &重ね合わせの作業場の状態
) -> ノード<重ね合わせの操作> {
    let 再生のボタンの文字 = if 状態.再生.再生しているか() {
        "停止"
    } else {
        "再生"
    };
    横並び(子![
        ボタン("スタックへ戻る", 重ね合わせの操作::スタックの作業場へ戻る),
        ボタン(再生のボタンの文字, 重ね合わせの操作::再生を切り替える),
        文字表示(format!(
            "{:.2}秒 / {:.2}秒",
            状態.再生.位置().時刻().秒数(),
            状態.重ね合わせ.重ね合わせの長さ().秒数()
        )),
    ])
    .into()
}

/// 入力が無くても画面を進めるなら、描き直しを予約する。重ね合わせの作業場の時間と、スタックの作業場の時間の短い方で予約する。
fn 描き直しの予約(
    状態: &重ね合わせの作業場の状態,
    スタックの作業場の描き直すまで: Option<Duration>,
) -> ノード<重ね合わせの操作> {
    let 重ね合わせの描き直すまで = 状態.再生.再生しているか().then_some(再生中に描き直す間隔);
    match [重ね合わせの描き直すまで, スタックの作業場の描き直すまで]
        .into_iter()
        .flatten()
        .min()
    {
        Some(待つ時間) => 描き直しを予約する(待つ時間).into(),
        None => 無し(),
    }
}
