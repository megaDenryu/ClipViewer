//! 重ね合わせの作業場のヘッダー。スタックの作業場へ戻るボタンと、重ね合わせを開いている間の「今のスタックから並べ直す」と、
//! この版では重ね合わせを保存できないことの案内を並べる。保存とライブラリへの登録は第16段階と第17段階で足すため、
//! それまでの版では保存できないことを画面に出す(同時再生.md 6節)。開いている間に並べ直す入口が無いと、重ね合わせの一覧(第17段階)が
//! できるまで、スタックを直した後に並べ直せないため、ヘッダーに置く。

use sengen_egui::{
    ノード, ボタン, 付け足せる, 子, 文字表示, 条件付き表示, 横並び
};

use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::state::今のスタックから並べる状況;

/// 保存できないことの案内の文。並べた重ね合わせはアプリを閉じると消える。
pub(crate) const 保存できない案内: &str =
    "この版では重ね合わせを保存できない(アプリを閉じると消える)";

/// ヘッダー。重ね合わせを開いている間だけ「今のスタックから並べ直す」を出し、今のスタックから並べられるときだけ押せる。
pub(super) fn ヘッダー(
    開いているか: bool,
    並べられるか: 今のスタックから並べる状況,
) -> ノード<重ね合わせの作業場の応答> {
    横並び(子![
        ボタン(
            "スタックへ戻る",
            重ね合わせの作業場の応答::スタックの作業場へ戻る
        ),
        条件付き表示(開いているか, || ボタン(
            "今のスタックから並べ直す",
            重ね合わせの作業場の応答::今のスタックから並べる
        )
        .有効(並べられるか == 今のスタックから並べる状況::並べられる)
        .説明(
            "開いている重ね合わせを捨てて、今のスタックの再生できるクリップを並べ直す"
        )),
        文字表示(保存できない案内),
    ])
    .into()
}
