//! 重ね合わせの作業場のヘッダー。スタックの作業場へ戻るボタンと、重ね合わせを開いている間の「今のスタックから並べ直す」と重ねる画面の縦横比の選択欄と、
//! この版では重ね合わせを保存できないことの案内を並べる。この版は重ね合わせを保存しないため、保存できないことを画面に出す(同時再生.md 6節)。
//! 開いた後に並べ直す入口がほかに無く、スタックを直した後に並べ直せるよう、「今のスタックから並べ直す」をヘッダーに置く。置き方を手で直した重ね合わせでは、並べ直す前に確かめる(同時再生.md 2-2)。

use clip_domain::重ねる画面の縦横比;
use sengen_egui::{
    ノード, ボタン, 付け足せる, 子, 文字表示, 条件付き表示, 横並び, 無し, 選択欄, 選択肢,
};

use crate::aspect_name::アスペクト比の名前;
use crate::overlay::command::{置き方の操作, 重ね合わせの作業場の応答};
use crate::overlay::state::{
    今のスタックから並べる状況, 開いている重ね合わせ
};

/// 保存できないことの案内の文。並べた重ね合わせはアプリを閉じると消える。
pub(crate) const 保存できない案内: &str =
    "この版では重ね合わせを保存できない(アプリを閉じると消える)";

/// ヘッダー。重ね合わせを開いている間だけ「今のスタックから並べ直す」と縦横比の選択欄を出す。「今のスタックから並べ直す」は今のスタックから並べられるときだけ押せ、
/// 置き方を手で直した重ね合わせでは、並べ直す代わりに確かめるダイアログを出す応答を発する。
pub(super) fn ヘッダー(
    開いている: Option<&開いている重ね合わせ>,
    並べられるか: 今のスタックから並べる状況,
) -> ノード<重ね合わせの作業場の応答> {
    let 並べ直すときの応答 = match 開いている {
        Some(開いている) if 開いている.置き方を手で直したか() => {
            置き方の操作::並べ直す前の確かめを出す.応答にする()
        }
        _ => 重ね合わせの作業場の応答::今のスタックから並べる,
    };
    横並び(子![
        ボタン(
            "スタックへ戻る",
            重ね合わせの作業場の応答::スタックの作業場へ戻る
        ),
        条件付き表示(開いている.is_some(), || ボタン(
            "今のスタックから並べ直す",
            並べ直すときの応答
        )
        .有効(並べられるか == 今のスタックから並べる状況::並べられる)
        .説明(
            "開いている重ね合わせを捨てて、今のスタックの再生できるクリップを並べ直す"
        )),
        開いている.map_or_else(無し, 縦横比の選択),
        文字表示(保存できない案内),
    ])
    .into()
}

/// 重ねる画面の縦横比の選択欄。「クロップ枠に合わせる」は出さない(同時再生.md 2-5)。
fn 縦横比の選択(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let 今の名前 = アスペクト比の名前(開いている.重ねる画面の縦横比().設定());
    横並び(子![
        文字表示("縦横比:"),
        選択欄(
            "重ねる画面の縦横比",
            今の名前,
            重ねる画面の縦横比::選べる比の一覧
                .map(|比| 選択肢(
                    アスペクト比の名前(比.設定()),
                    置き方の操作::重ねる画面の縦横比を選ぶ(比).応答にする()
                ))
                .into_iter()
                .collect(),
        ),
    ])
    .into()
}
