//! 重ね合わせの作業場のヘッダー。スタックの作業場へ戻るボタンと、重ね合わせを開いている間の「今のスタックから並べ直す」と「重ね合わせを閉じる」と重ねる画面の縦横比の選択欄と、
//! 取り消しとやり直しのボタンと、重ね合わせのライブラリの様子(`library_header.rs`)を並べる。
//! 開いた後に並べ直す入口がほかに無く、スタックを直した後に並べ直せるよう、「今のスタックから並べ直す」をヘッダーに置く。並べ直す前の確かめは作業場が行う(同時再生.md 2-2)。
//! 重ね合わせの一覧は開いていない間に出すため、開いている間に一覧へ戻る入口として「重ね合わせを閉じる」を置く(同時再生.md 2-7)。

use clip_domain::重ねる画面の縦横比;
use sengen_egui::{
    ノード, ボタン, 付け足せる, 子, 文字表示, 条件付き表示, 横並び, 無し, 選択欄, 選択肢,
};

use super::keys::{やり直すキー, 取り消すキー};
use crate::aspect_name::アスペクト比の名前;
use crate::overlay::command::{
    編集の履歴の操作, 置き方の操作, 重ね合わせのライブラリの操作, 重ね合わせの作業場の応答,
};
use crate::overlay::state::{
    今のスタックから並べる状況, 重ね合わせの作業場の状態, 開いている重ね合わせ,
};

/// ヘッダー。重ね合わせを開いている間だけ「今のスタックから並べ直す」「重ね合わせを閉じる」と縦横比の選択欄を出す。
/// 「今のスタックから並べ直す」は今のスタックから並べられるときだけ押せる。
pub(super) fn ヘッダー(
    状態: &重ね合わせの作業場の状態,
    並べられるか: 今のスタックから並べる状況,
) -> ノード<重ね合わせの作業場の応答> {
    let 開いている = 状態.開いている重ね合わせ();
    横並び(子![
        ボタン(
            "スタックへ戻る",
            重ね合わせの作業場の応答::スタックの作業場へ戻る
        ),
        条件付き表示(開いている.is_some(), || ボタン(
            "今のスタックから並べ直す",
            重ね合わせの作業場の応答::今のスタックから並べる
        )
        .有効(並べられるか == 今のスタックから並べる状況::並べられる)
        .説明(
            "開いている重ね合わせを捨てて、今のスタックの再生できるクリップを並べ直す"
        )),
        条件付き表示(開いている.is_some(), || ボタン(
            "重ね合わせを閉じる",
            重ね合わせのライブラリの操作::重ね合わせを閉じる.応答にする()
        )
        .説明("開いている重ね合わせを閉じて、重ね合わせの一覧を出す")),
        開いている.map_or_else(無し, 縦横比の選択),
        条件付き表示(開いている.is_some(), || 取り消しとやり直し(
            状態
        )),
        super::library_header::ヘッダーのライブラリの様子(状態),
    ])
    .into()
}

/// 編集の取り消しとやり直しのボタン。取り消せる・やり直せる編集が無ければ押せない。キーは説明に出す(割り当ては変えられない)。
fn 取り消しとやり直し(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    横並び(子![
        ボタン("取り消す", 編集の履歴の操作::編集を取り消す.応答にする())
            .有効(状態.取り消せるか())
            .説明(取り消すキー.表記()),
        ボタン("やり直す", 編集の履歴の操作::編集をやり直す.応答にする())
            .有効(状態.やり直せるか())
            .説明(やり直すキー.表記()),
    ])
    .into()
}

/// 重ねる画面の縦横比の選択欄。「クロップ枠に合わせる」は出さない(同時再生.md 2-5)。
fn 縦横比の選択(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let 今の名前 = アスペクト比の名前(開いている.重ねる画面の縦横比().設定());
    横並び(子![
        文字表示("縦横比:"),
        選択欄(
            "重ねる画面の縦横比",
            今の名前,
            重ねる画面の縦横比::選べる比の一覧
                .map(|比| 選択肢(
                    アスペクト比の名前(比.設定()),
                    置き方の操作::重ねる画面の縦横比を選ぶ(比).応答にする()
                ))
                .into_iter()
                .collect(),
        ),
    ])
    .into()
}
