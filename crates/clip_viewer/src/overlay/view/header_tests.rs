//! 重ね合わせの作業場のヘッダーの試験。「スタックへ戻る」がスタックの作業場へ戻る応答を発し、保存できない案内を出すことと、
//! 「今のスタックから並べ直す」は重ね合わせを開いている間だけ出て、並べられるときだけ並べる応答を発することと、
//! 重ね合わせのライブラリへ書けないとき(読み取り専用・置き場所が無い)にその旨を出し、書けるときは出さないことを確かめる。
#![allow(clippy::expect_used)]

use super::header::{
    保存できない案内, 重ね合わせのライブラリへ書けないことの文
};
use super::screen_press_support::{
    ライブラリの様子で描いたか, 描いたか, 文字を押して集める
};
use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::sound_test_support::装置の無い作業場を作る;
use crate::overlay::state::library_status::重ね合わせのライブラリの様子;
use crate::overlay::state::今のスタックから並べる状況;
use crate::overlay::test_support::五秒の重ね合わせ;
use clip_library::重ね合わせの錠を取れない理由;

#[test]
fn ヘッダーのスタックへ戻るはスタックの作業場へ戻る応答を発し_保存できない案内を出す() {
    let 作業場 = 装置の無い作業場を作る();
    assert!(描いたか(
        &作業場,
        今のスタックから並べる状況::並べられる,
        保存できない案内
    ));
    assert_eq!(
        文字を押して集める(
            &作業場,
            今のスタックから並べる状況::並べられる,
            "スタックへ戻る"
        ),
        [重ね合わせの作業場の応答::スタックの作業場へ戻る]
    );
}

#[test]
fn 今のスタックから並べ直すは開いている間だけ出て_並べられるときだけ並べる応答を発する() {
    let mut 作業場 = 装置の無い作業場を作る();
    let 並べ直す = "今のスタックから並べ直す";
    assert!(!描いたか(
        &作業場,
        今のスタックから並べる状況::並べられる,
        並べ直す
    ));
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    assert_eq!(
        文字を押して集める(&作業場, 今のスタックから並べる状況::並べられる, 並べ直す),
        [重ね合わせの作業場の応答::今のスタックから並べる]
    );
    assert!(
        文字を押して集める(
            &作業場,
            今のスタックから並べる状況::動画を開いていない,
            並べ直す
        )
        .is_empty()
    );
}

fn 様子で描いたか(
    様子: 重ね合わせのライブラリの様子<'_>, 文字: &str
) -> bool {
    let 作業場 = 装置の無い作業場を作る();
    ライブラリの様子で描いたか(
        &作業場,
        今のスタックから並べる状況::並べられる,
        様子,
        文字,
    )
}

#[test]
fn 読み取り専用のときは理由と共にその旨を出す() {
    let 理由 =
        重ね合わせの錠を取れない理由::スタックのライブラリの錠を持っていない;
    let 様子 = 重ね合わせのライブラリの様子::読み取り専用(&理由);
    let 文 = 重ね合わせのライブラリへ書けないことの文(様子).expect("書けない文がある");
    assert_eq!(
        文,
        "重ね合わせのライブラリ: 読み取り専用(スタックのライブラリの錠を持っていない(別の ClipViewer がスタックのライブラリを開いている等))"
    );
    assert!(様子で描いたか(様子, &文));
}

#[test]
fn 置き場所が無いときは使えない旨を出し_書けるときは出さない() {
    let 使えない = "重ね合わせのライブラリ: 使えない(アプリのデータの置き場所が無い)";
    assert!(様子で描いたか(
        重ね合わせのライブラリの様子::置き場所が無い,
        使えない
    ));
    assert_eq!(
        重ね合わせのライブラリへ書けないことの文(
            重ね合わせのライブラリの様子::書ける
        ),
        None
    );
    assert!(!様子で描いたか(
        重ね合わせのライブラリの様子::書ける,
        使えない
    ));
}
