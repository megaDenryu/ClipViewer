//! 重ね合わせの作業場のヘッダーの試験。「スタックへ戻る」がスタックの作業場へ戻る応答を発し、「この版では保存できない」の案内を出さないことと、
//! 「今のスタックから並べ直す」と「重ね合わせを閉じる」は重ね合わせを開いている間だけ出て、それぞれの応答を発することと、
//! 重ね合わせのライブラリへ書けないとき(読み取り専用・置き場所が無い)にその旨を出し、書けるときは出さないことを確かめる。
#![allow(clippy::expect_used)]

use std::path::PathBuf;

use clip_library::{ライブラリのフォルダ, 重ね合わせの錠を取れない理由};

use super::library_header::重ね合わせのライブラリへ書けないことの文;
use super::screen_press_support::{描いたか, 文字を押して集める};
use crate::overlay::command::{
    重ね合わせのライブラリの操作, 重ね合わせの作業場の応答
};
use crate::overlay::sound_test_support::装置の無い作業場を作る;
use crate::overlay::state::library::重ね合わせのライブラリの使える様子;
use crate::overlay::state::今のスタックから並べる状況;
use crate::overlay::test_support::五秒の重ね合わせ;

#[test]
fn ヘッダーのスタックへ戻るはスタックの作業場へ戻る応答を発し_保存できない案内は出さない() {
    let 作業場 = 装置の無い作業場を作る();
    assert!(!描いたか(
        &作業場,
        今のスタックから並べる状況::並べられる,
        "この版では重ね合わせを保存できない(アプリを閉じると消える)"
    ));
    assert_eq!(
        文字を押して集める(
            &作業場,
            今のスタックから並べる状況::並べられる,
            "スタックへ戻る"
        ),
        [重ね合わせの作業場の応答::スタックの作業場へ戻る]
    );
}

#[test]
fn 並べ直すと閉じるは開いている間だけ出て_並べ直すは並べられるときだけ並べる応答を発する() {
    let mut 作業場 = 装置の無い作業場を作る();
    let 並べ直す = "今のスタックから並べ直す";
    let 押せる = 今のスタックから並べる状況::並べられる;
    assert!(!描いたか(&作業場, 押せる, 並べ直す));
    assert!(!描いたか(&作業場, 押せる, "重ね合わせを閉じる"));
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    assert_eq!(
        文字を押して集める(&作業場, 押せる, 並べ直す),
        [重ね合わせの作業場の応答::今のスタックから並べる]
    );
    assert!(
        文字を押して集める(
            &作業場,
            今のスタックから並べる状況::動画を開いていない,
            並べ直す
        )
        .is_empty()
    );
    assert_eq!(
        文字を押して集める(&作業場, 押せる, "重ね合わせを閉じる"),
        [重ね合わせのライブラリの操作::重ね合わせを閉じる.応答にする()]
    );
}

#[test]
fn 読み取り専用のときは理由と共にその旨を出し_書けるときは出さない() {
    let フォルダ =
        ライブラリのフォルダ::作成する(PathBuf::from(r"C:\試験\library")).重ね合わせのフォルダ();
    let 理由 =
        重ね合わせの錠を取れない理由::スタックのライブラリの錠を持っていない;
    assert_eq!(
        重ね合わせのライブラリへ書けないことの文(
            重ね合わせのライブラリの使える様子::読むだけ(&フォルダ, &理由)
        )
        .expect("書けない文がある"),
        "重ね合わせのライブラリ: 読み取り専用(ライブラリの錠を持っていない(別の ClipViewer がライブラリを開いている等))"
    );
    assert_eq!(
        重ね合わせのライブラリへ書けないことの文(
            重ね合わせのライブラリの使える様子::書ける(&フォルダ)
        ),
        None
    );
}

#[test]
fn 置き場所が無い作業場のヘッダーには使えない旨を出す() {
    let 作業場 = 装置の無い作業場を作る();
    assert!(描いたか(
        &作業場,
        今のスタックから並べる状況::並べられる,
        "重ね合わせのライブラリ: 使えない(置き場所が無い)"
    ));
}
