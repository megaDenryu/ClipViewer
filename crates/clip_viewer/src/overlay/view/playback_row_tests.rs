//! 重ね合わせの再生の操作の行の試験。開いている間は「再生」と「全体ループ」が応答を発し、位置と長さを出し、開いた重ね合わせでは
//! 「今のスタックから並べる」を出さないことを確かめる。
#![allow(clippy::expect_used)]

use super::screen_press_support::{描いたか, 文字を押して集める};
use crate::overlay::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::overlay::sound_test_support::装置の無い作業場を作る;
use crate::overlay::state::今のスタックから並べる状況;
use crate::overlay::test_support::五秒の重ね合わせ;

#[test]
fn 開いている間は再生と全体ループを押せ_開いた重ね合わせでは今のスタックから並べるを出さない() {
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    let 押せる = 今のスタックから並べる状況::並べられる;
    assert_eq!(
        文字を押して集める(&作業場, 押せる, "再生"),
        [重ね合わせの作業場の応答::操作(
            重ね合わせの操作::再生を切り替える
        )]
    );
    assert_eq!(
        文字を押して集める(&作業場, 押せる, "全体ループ"),
        [重ね合わせの作業場の応答::操作(
            重ね合わせの操作::全体ループを設定する(false)
        )]
    );
    assert!(描いたか(&作業場, 押せる, "0.00秒 / 5.00秒"));
    assert!(!描いたか(&作業場, 押せる, "今のスタックから並べる"));
    作業場.操作を適用する(重ね合わせの操作::全体ループを設定する(
        false,
    ));
    assert!(
        !作業場
            .状態()
            .開いている重ね合わせ()
            .expect("開いている")
            .全体ループか()
    );
}

#[test]
fn 開いていない間は全体ループを押しても応答を発しない() {
    let 作業場 = 装置の無い作業場を作る();
    assert!(
        文字を押して集める(
            &作業場,
            今のスタックから並べる状況::並べられる,
            "全体ループ"
        )
        .is_empty()
    );
}
