//! 重ねる画面の試験。使える大きさに縦横比を保って収めた黒の地の中へ、行の絵を映す矩形の位置と大きさで、奥の行から手前の行の順に描き、
//! 行のテクスチャのうちクロップの範囲だけを貼ることを、egui に描かせた形から確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{クロップ範囲, 映す矩形, 百分率, 重ねる画面の縦横比};
use eframe::egui;
use sengen_egui::{
    差し替えられるテクスチャ, 拡大縮小の仕方, 画素の並び, 画素数の寸法, 縦横の論理画素, 論理画素,
};

use super::screen::重ねる画面の材料;
use super::test_support::{
    テクスチャを貼った形, 描いて集める, 黒く塗った矩形
};
use crate::overlay::state::重ねる画面に描く行;

fn 行(
    画面描画の共有状態: &egui::Context,
    左端: f64,
    クロップ: クロップ範囲,
) -> 重ねる画面に描く行 {
    let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
        画素数の寸法::生成する(2, 1),
        &[255; 8],
    )
    .expect("画素の並び");
    let テクスチャ = 差し替えられるテクスチャ::登録して作る(
        画面描画の共有状態,
        "試験の行",
        画素,
        拡大縮小の仕方::隣の画素と混ぜる,
    );
    重ねる画面に描く行 {
        映す矩形: 映す矩形::作成する(
            百分率::範囲へ収める(左端),
            百分率::範囲へ収める(0.0),
            百分率::範囲へ収める(50.0),
            百分率::範囲へ収める(100.0),
        )
        .expect("映す矩形"),
        クロップ,
        テクスチャ: テクスチャ.参照を複製する(),
    }
}

/// 2つの矩形の4つの端が、描画の丸め(1論理画素未満)の差で等しいか。
fn ほぼ同じ矩形(左: egui::Rect, 右: egui::Rect) -> bool {
    (左.min - 右.min).length() < 1.0 && (左.max - 右.max).length() < 1.0
}

#[test]
fn 縦横比を保って収めた重ねる画面の中へ_行の絵を映す矩形へ奥から順に描き_クロップの範囲だけを貼る()
{
    let 画面描画の共有状態 = egui::Context::default();
    let 材料 = 重ねる画面の材料 {
        縦横比: 重ねる画面の縦横比::ワイド16対9,
        描く行: vec![
            行(&画面描画の共有状態, 0.0, クロップ範囲::全体),
            行(
                &画面描画の共有状態,
                50.0,
                クロップ範囲::各値を範囲へ収めて作成する(25.0, 0.0, 50.0, 100.0),
            ),
        ],
    };
    let 使える大きさ = 縦横の論理画素::生成する(
        論理画素::倍精度の小数から生成する(1000.0),
        論理画素::倍精度の小数から生成する(600.0),
    );
    let (_, 出力) = 描いて集める(&画面描画の共有状態, Vec::new(), &|| {
        材料.組む(使える大きさ)
    });
    let 地 = 黒く塗った矩形(&出力).expect("黒の地を描いた");
    // 縁の余白32を引いた968×568へ16:9を収めると、幅に合わせて968×544.5になり、四捨五入して968×545になる。
    assert!(
        ほぼ同じ矩形(
            地,
            egui::Rect::from_min_size(地.min, egui::vec2(968.0, 545.0))
        ),
        "{地:?}"
    );
    let 形 = テクスチャを貼った形(&出力);
    assert_eq!(形.len(), 2, "{形:?}");
    let (奥の矩形, 奥の範囲) = 形[0];
    let (手前の矩形, 手前の範囲) = 形[1];
    let 真ん中 = 地.center().x;
    assert!(
        ほぼ同じ矩形(奥の矩形, 地.with_max_x(真ん中)),
        "{奥の矩形:?} {地:?}"
    );
    assert!(
        ほぼ同じ矩形(手前の矩形, 地.with_min_x(真ん中)),
        "{手前の矩形:?} {地:?}"
    );
    assert_eq!(
        奥の範囲,
        egui::Rect::from_min_max(egui::Pos2::ZERO, egui::pos2(1.0, 1.0))
    );
    assert_eq!(
        手前の範囲,
        egui::Rect::from_min_max(egui::pos2(0.25, 0.0), egui::pos2(0.75, 1.0))
    );
}
