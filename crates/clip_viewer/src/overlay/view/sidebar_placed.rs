//! 左のサイドバーの、置いたクリップの一覧と選んでいる置いたクリップの設定。置いたクリップの一覧は手前の行から奥の行の順に並べ、押すと選ぶ。
//! 重ねる画面の上では、選んでいない置いたクリップどうしが重なった場所は手前のものしか押せないため、奥の置いたクリップはこの一覧から選ぶ。
//! 選んでいる置いたクリップの設定は、名前・区間・繰り返しの回数と、音量のつまみと「消音」(`placed_sound.rs`)と、「取り除く」を出す。参照: _doc/設計/同時再生.md 2-3・2-4

use clip_domain::置いたクリップ;
use sengen_egui::{ノード, ボタン, 子, 文字表示, 縦積み, 選択ボタン};

use super::placed_sound::置いたクリップの音の行;
use crate::overlay::command::{置き方の操作, 重ね合わせの作業場の応答};
use crate::overlay::state::開いている重ね合わせ;

/// 置いたクリップの一覧の見出し。
pub(crate) const 置いたクリップの見出し: &str = "置いたクリップ(手前から)";

/// 置いたクリップを選んでいないときに、設定の代わりに出す文。
pub(crate) const 選んでいないときの文: &str =
    "置いたクリップを選んでいない。重ねる画面の枠か、上の一覧を押して選ぶ";

/// 置いたクリップの欄。置いたクリップの一覧と、選んでいる置いたクリップの設定を縦に並べる。
pub(super) fn 置いたクリップの欄(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let mut 手前から: Vec<&置いたクリップ> = 開いている.奥から手前の順の置いたクリップ().collect();
    手前から.reverse();
    let 一覧 = 手前から
        .into_iter()
        .map(|置いた| 置いたクリップを選ぶ行(開いている, 置いた))
        .collect();
    let 設定 = match 開いている.選んでいる置いたクリップ() {
        Some(置いた) => 選んでいる置いたクリップの設定(置いた),
        None => 文字表示(選んでいないときの文).into(),
    };
    縦積み(子![文字表示(置いたクリップの見出し), 縦積み(一覧), 設定]).into()
}

/// 置いたクリップを選ぶ行。名前と、重ね合わせ上で始まる時刻を出す。
fn 置いたクリップを選ぶ行(
    開いている: &開いている重ね合わせ,
    置いた: &置いたクリップ,
) -> ノード<重ね合わせの作業場の応答> {
    選択ボタン(
        format!(
            "{}({:.2}秒から)",
            置いた.受け継いだ値().名前.文字列(),
            置いた.始まりの時刻().秒数()
        ),
        開いている.置いたクリップを選んでいるか(置いた.識別子()),
        置き方の操作::置いたクリップを選ぶ(置いた.識別子().clone()).応答にする(),
    )
    .into()
}

/// 選んでいる置いたクリップの設定。名前・区間・繰り返しの回数と、音量のつまみと「消音」と、「取り除く」を出す。
fn 選んでいる置いたクリップの設定(
    置いた: &置いたクリップ,
) -> ノード<重ね合わせの作業場の応答> {
    let 受け継いだ値 = 置いた.受け継いだ値();
    縦積み(子![
        文字表示(format!("名前: {}", 受け継いだ値.名前.文字列())),
        文字表示(format!(
            "区間: {:.2}秒 〜 {:.2}秒",
            受け継いだ値.区間.開始().秒数(),
            受け継いだ値.区間.終了().秒数()
        )),
        文字表示(format!(
            "繰り返しの回数: {}回",
            受け継いだ値.リピート回数.回数()
        )),
        置いたクリップの音の行(置いた),
        ボタン(
            "取り除く",
            置き方の操作::置いたクリップを取り除く(置いた.識別子().clone(),).応答にする()
        ),
    ])
    .into()
}
