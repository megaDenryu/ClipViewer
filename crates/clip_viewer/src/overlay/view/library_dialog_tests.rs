//! 重ね合わせのダイアログの試験。手で直した未登録の重ね合わせを並べ直すと並べ直す前の確かめを、閉じると捨てる前の確かめ(スタックと同じ文)を出し、
//! ダイアログの「やめる」と続けるボタンがそれぞれの応答を発することを、egui に描かせて押して確かめる。
#![allow(clippy::expect_used)]

use eframe::egui;

use super::library_dialog::{
    並べ直すボタンの文, 並べ直す前に確かめる文, 捨てる前に確かめる文
};
use super::screen_press_support::試験の全体の音量;
use super::test_support::{押して集める, 描いた文字の範囲, 描いて集める};
use crate::overlay::arrange_test_support::{値, 練習の動画};
use crate::overlay::command::{
    一覧とダイアログの操作, 重ね合わせのライブラリの操作, 重ね合わせの作業場の応答,
};
use crate::overlay::placement_test_support::{左上の4分の1へ縮める, 開いた作業場};
use crate::overlay::state::今のスタックから並べる状況;
use crate::overlay::workspace::{
    スタックの作業場から借りるもの, 重ね合わせの作業場
};

/// 作業場の画面を3回描いてから(ダイアログは最初の回に大きさだけを測るため)、その文字の真ん中を押して発した応答を返す。描いていなければ無い。
fn ダイアログを描いて押す(
    作業場: &重ね合わせの作業場,
    文字: &str,
) -> Option<Vec<重ね合わせの作業場の応答>> {
    let 画面描画の共有状態 = egui::Context::default();
    let 木 = || {
        super::画面(
            作業場.状態(),
            今のスタックから並べる状況::並べられる,
            None,
            試験の全体の音量,
            None,
        )
    };
    let mut 出力 = 描いて集める(&画面描画の共有状態, Vec::new(), &木).1;
    for _ in 0..2 {
        出力 = 描いて集める(&画面描画の共有状態, Vec::new(), &木).1;
    }
    let 位置 = 描いた文字の範囲(&出力, 文字)?.center();
    Some(押して集める(&画面描画の共有状態, 位置, &木))
}

fn やめる() -> Vec<重ね合わせの作業場の応答> {
    vec![一覧とダイアログの操作::ダイアログを閉じる.応答にする()]
}

#[test]
fn 手で直した重ね合わせを並べ直すと確かめ_ダイアログはやめると変更を捨てて続けるを発する() {
    let mut 作業場 = 開いた作業場();
    左上の4分の1へ縮める(&mut 作業場);
    assert_eq!(
        ダイアログを描いて押す(&作業場, 並べ直す前に確かめる文),
        None
    );
    let スタック = clip_domain::クリップスタック::default();
    let パス = 練習の動画();
    作業場.今のスタックから並べる(値(&スタック, &パス, 60.0), None);
    assert!(ダイアログを描いて押す(&作業場, 並べ直す前に確かめる文).is_some());
    assert_eq!(ダイアログを描いて押す(&作業場, "やめる"), Some(やめる()));
    assert_eq!(
        ダイアログを描いて押す(&作業場, 並べ直すボタンの文),
        Some(vec![
            重ね合わせのライブラリの操作::変更を捨てて続ける.応答にする()
        ])
    );
}

#[test]
fn 手で直した重ね合わせを閉じるとスタックと同じ文で確かめ_変更を捨てて続けると閉じる() {
    let mut 作業場 = 開いた作業場();
    左上の4分の1へ縮める(&mut 作業場);
    let スタック = clip_domain::クリップスタック::default();
    let パス = 練習の動画();
    let 借りるもの = || スタックの作業場から借りるもの {
        今のスタック: 値(&スタック, &パス, 60.0),
        読み手: None,
    };
    作業場.ライブラリの操作を当てる(
        重ね合わせのライブラリの操作::重ね合わせを閉じる,
        借りるもの(),
    );
    assert!(
        作業場.状態().開いている重ね合わせ().is_some(),
        "確かめている間は閉じない"
    );
    assert!(ダイアログを描いて押す(&作業場, 捨てる前に確かめる文).is_some());
    assert_eq!(
        ダイアログを描いて押す(&作業場, "ライブラリに保存する"),
        Some(Vec::new()),
        "置き場所が無いため押せない"
    );
    作業場.ライブラリの操作を当てる(
        重ね合わせのライブラリの操作::変更を捨てて続ける,
        借りるもの(),
    );
    assert!(作業場.状態().開いている重ね合わせ().is_none());
}
