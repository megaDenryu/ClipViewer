//! 並べ直す前の確かめのダイアログ。置き方を手で直した重ね合わせで「今のスタックから並べ直す」を押したときに出し、
//! 並べ直すと直した置き方が失われることを確かめる。外側を押すか Escape で閉じようとしたら、並べ直さずに閉じる。参照: _doc/設計/同時再生.md 2-2

use sengen_egui::{ノード, ボタン, モーダル, 子, 文字表示, 横並び, 無し};

use super::frame_conversion::置き方の応答;
use crate::overlay::command::{置き方の操作, 重ね合わせの作業場の応答};
use crate::overlay::state::重ね合わせの作業場の状態;

/// 並べ直す前に確かめる文。
pub(crate) const 並べ直す前に確かめる文: &str =
    "この重ね合わせは置き方を直してある。今のスタックから並べ直すと、直した置き方は失われる";

/// 確かめるダイアログで並べ直すボタンの文。
pub(crate) const 並べ直すボタンの文: &str = "直した置き方を捨てて並べ直す";

/// 並べ直す前の確かめを出している間だけダイアログを出す。
pub(super) fn 並べ直す前の確かめのダイアログ(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    if !状態.並べ直す前の確かめを出しているか() {
        return 無し();
    }
    let 閉じる = 置き方の応答(置き方の操作::並べ直す前の確かめを閉じる);
    モーダル(
        "並べ直す前の確かめ",
        true,
        子![
            文字表示(並べ直す前に確かめる文),
            横並び(子![
                ボタン(
                    並べ直すボタンの文,
                    重ね合わせの作業場の応答::今のスタックから並べる
                ),
                ボタン("やめる", 閉じる.clone()),
            ]),
        ],
    )
    .閉じたら(閉じる)
    .into()
}
