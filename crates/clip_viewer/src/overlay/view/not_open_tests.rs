//! 重ね合わせを開いていない間の案内の試験。案内と「今のスタックから並べる」を出し、押せるときだけ押すと並べる応答を発し、
//! 押せないときは理由を出すことと、再生を押せないことを、egui に描かせて押して確かめる。

use super::not_open::並べ方の案内;
use super::screen_press_support::{描いたか, 文字を押して集める};
use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::sound_test_support::装置の無い作業場を作る;
use crate::overlay::state::今のスタックから並べる状況;

#[test]
fn 開いていない間は案内と今のスタックから並べるを出し_押せるときだけ並べる応答を発する() {
    let 作業場 = 装置の無い作業場を作る();
    assert!(描いたか(
        &作業場,
        今のスタックから並べる状況::並べられる,
        並べ方の案内
    ));
    assert_eq!(
        文字を押して集める(
            &作業場,
            今のスタックから並べる状況::並べられる,
            "今のスタックから並べる"
        ),
        [重ね合わせの作業場の応答::今のスタックから並べる]
    );
    for (並べられない, 理由) in [
        (
            今のスタックから並べる状況::動画を開いていない,
            "スタックの作業場で動画を開いていないため、押せない。「スタックへ戻る」を押して動画を開く",
        ),
        (
            今のスタックから並べる状況::再生できるクリップが無い,
            "スタックに再生できるクリップ(有効で、区間の長さが0でないもの)が無いため、押せない",
        ),
    ] {
        assert!(描いたか(&作業場, 並べられない, 理由), "{理由}");
        assert!(
            文字を押して集める(&作業場, 並べられない, "今のスタックから並べる").is_empty(),
            "{並べられない:?}"
        );
    }
    assert!(
        文字を押して集める(&作業場, 今のスタックから並べる状況::並べられる, "再生").is_empty(),
        "開いていない間は再生を押せない"
    );
    assert!(描いたか(
        &作業場,
        今のスタックから並べる状況::並べられる,
        "重ね合わせを開いていない"
    ));
}
