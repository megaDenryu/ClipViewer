//! 重ね合わせの作業場の出力の区画。置かなかったクリップの報告と音の様子を上に出し、重ねる画面か、重ね合わせを開いていない間の案内と重ね合わせの一覧を出す。

use sengen_egui::{ノード, 子, 文字表示, 縦積み};

use super::{not_open, screen};
use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::state::{
    今のスタックから並べる状況, 重ね合わせの作業場の状態
};

/// 出力の区画。置かなかったクリップの報告と音の様子(音を鳴らせない理由)があれば上に出し、重ね合わせを開いていれば重ねる画面を、開いていなければ案内と「今のスタックから並べる」を出す。
pub(super) fn 出力の区画(
    状態: &重ね合わせの作業場の状態,
    並べられるか: 今のスタックから並べる状況,
) -> ノード<重ね合わせの作業場の応答> {
    let 報告 = 縦積み(
        状態
            .置かなかったクリップの報告の文()
            .into_iter()
            .chain(状態.音の様子の文の並び())
            .map(|文| 文字表示(文).into())
            .collect(),
    );
    let 中身 = match 状態.開いている重ね合わせ() {
        Some(開いている) => screen::重ねる画面(開いている),
        None => not_open::開いていない間の案内(状態, 並べられるか),
    };
    縦積み(子![報告, 中身]).into()
}
