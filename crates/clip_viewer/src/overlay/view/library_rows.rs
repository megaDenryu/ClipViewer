//! 重ね合わせの一覧の行の材料。見えている行を組む閉包が所有し、番号の行に、サムネイル・名前・動画が見つからない印・説明・「開く」を並べる。
//! 行の形と仮想縦スクロールは、スタックの作業場と共有する `library_common::view` が組む。参照: _doc/設計/同時再生.md 2-7、_doc/設計/ライブラリ.md 判断11

use std::rc::Rc;

use clip_domain::重ね合わせの識別子;
use clip_library::{動画の有無, 読めた重ね合わせ, 重ね合わせの一覧};
use sengen_egui::{ノード, ボタン};

use crate::library_common::list::{一覧の項目の参照, 並べられる一覧, 見せる行};
use crate::library_common::view::{
    一覧の行の材料, 行の印, 読めた行, 読めない行
};
use crate::overlay::command::{
    重ね合わせのライブラリの操作, 重ね合わせの作業場の応答
};
use crate::overlay::state::重ね合わせの作業場の状態;
use crate::styles;
use crate::thumbnail_feed::サムネイルの項目の表;

/// 重ね合わせの一覧の行の材料とは、読んだ重ね合わせの一覧と見せる行の順と、サムネイルの項目の表の組のことである。一覧と順と表は状態と共有する。
pub(super) struct 重ね合わせの一覧の行の材料 {
    一覧: Rc<重ね合わせの一覧>,
    見せる行の順: Rc<Vec<見せる行>>,
    サムネイル: サムネイルの項目の表<重ね合わせの識別子>,
}

impl 重ね合わせの一覧の行の材料 {
    pub(super) fn 状態から作る(
        状態: &重ね合わせの作業場の状態,
        一覧: &Rc<重ね合わせの一覧>,
    ) -> Self {
        Self {
            一覧: Rc::clone(一覧),
            見せる行の順: 状態.重ね合わせの一覧().見せる行の順(),
            サムネイル: 状態.サムネイルの項目の表(),
        }
    }
}

impl 一覧の行の材料<重ね合わせの作業場の応答> for 重ね合わせの一覧の行の材料 {
    fn 行の数(&self) -> usize {
        self.見せる行の順.len()
    }

    fn 行を組む(
        &self, 番号: usize
    ) -> Option<ノード<重ね合わせの作業場の応答>> {
        let 位置 = match *self.見せる行の順.get(番号)? {
            見せる行::読めた(位置) | 見せる行::読めない(位置) => 位置,
        };
        Some(match self.一覧.項目(位置)? {
            一覧の項目の参照::読めた(読めた) => {
                self.読めた重ね合わせの行(読めた)
            }
            一覧の項目の参照::読めない(ファイル) => {
                読めない行(ファイル.ファイル名.文字列(), &ファイル.理由)
            }
        })
    }
}

impl 重ね合わせの一覧の行の材料 {
    fn 読めた重ね合わせの行(
        &self,
        読めた: &読めた重ね合わせ,
    ) -> ノード<重ね合わせの作業場の応答> {
        let 登録した = &読めた.重ね合わせ;
        let 識別子 = 登録した.識別子();
        let 動画が見つからないか = 読めた.動画の有無の並び.contains(&動画の有無::見つからない);
        読めた行(
            self.サムネイル
                .get(識別子)
                .map(|項目| 項目.見せ方())
                .as_ref(),
            登録した.名前().文字列().to_string(),
            &[行の印 {
                文: "動画が見つからない",
                出すか: 動画が見つからないか,
                不備か: true,
            }],
            super::library_row_text::行の説明(読めた),
            ボタン(
                "開く",
                重ね合わせのライブラリの操作::開く(識別子.clone()).応答にする(),
            )
            .装飾(styles::強調ボタン)
            .into(),
        )
    }
}
