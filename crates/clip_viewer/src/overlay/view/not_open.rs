//! 重ね合わせを開いていない間の案内。並べ方の案内と「今のスタックから並べる」のボタンと、押せないときの理由と、その下に重ね合わせの一覧(`library_list.rs`)を出す。
//! 参照: _doc/設計/同時再生.md 2-2・2-7

use sengen_egui::{ノード, ボタン, 子, 文字表示, 縦積み};

use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::state::{
    今のスタックから並べる状況, 重ね合わせの作業場の状態
};

/// 並べ方の案内の文。
pub(crate) const 並べ方の案内: &str =
    "スタックの再生できるクリップを、上から順に8つまで格子に並べ、同時に再生する";

pub(super) fn 開いていない間の案内(
    状態: &重ね合わせの作業場の状態,
    並べられるか: 今のスタックから並べる状況,
) -> ノード<重ね合わせの作業場の応答> {
    let 押せない理由 = match 並べられるか {
        今のスタックから並べる状況::並べられる => None,
        今のスタックから並べる状況::動画を開いていない => Some(
            "スタックの作業場で動画を開いていないため、押せない。「スタックへ戻る」を押して動画を開く",
        ),
        今のスタックから並べる状況::再生できるクリップが無い => Some(
            "スタックに再生できるクリップ(有効で、区間の長さが0でないもの)が無いため、押せない",
        ),
    };
    縦積み(子![
        文字表示(並べ方の案内),
        ボタン(
            "今のスタックから並べる",
            重ね合わせの作業場の応答::今のスタックから並べる
        )
        .有効(押せない理由.is_none()),
        文字表示(押せない理由.unwrap_or_default()),
        super::library_list::一覧の区画(状態),
    ])
    .into()
}
