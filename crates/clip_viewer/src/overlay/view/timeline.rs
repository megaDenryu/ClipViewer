//! 重ね合わせのタイムライン。行の操作の部品を並べる(`timeline_row_actions.rs`)と、SengenEgui の時間の行の並びを縦に置く。
//! 時間の行の並びには、奥の行から手前の行の順に行を置き(部品は最初に置いた行をいちばん下に描くため、手前の行が上に来る)、行ごとに置いたクリップの塊を、
//! 繰り返しの回数で周回の区切りを付けて並べる。上の時間の軸が再生位置の帯を兼ね、押すかドラッグすると再生の位置を動かす。
//! 帯の左端から右端までは、0秒から重ね合わせの長さ(10秒より短いときは10秒)までである。参照: _doc/設計/同時再生.md 2-3・2-6

use clip_domain::{時刻, 時間の長さ, 置いたクリップの識別子, 行の番号};
use sengen_egui::{
    ノード, 子, 帯の値, 帯の値の差, 帯の全体の範囲, 時間の塊, 時間の行, 時間の行の並び, 時間の行型,
    縦積み,
};

use super::timeline_conversion::{
    位置の線の操作を変換する, 塊の操作を変換する, 押した行を選ぶ応答を作る, 秒を帯の値にする,
};
use super::timeline_row_actions::行の操作の部品を並べる;
use crate::overlay::command::{置き方の操作, 重ね合わせの作業場の応答};
use crate::overlay::state::timeline::タイムラインに描く塊;
use crate::overlay::state::開いている重ね合わせ;

/// 帯の右端の最も短い長さ。置いたクリップが短くても、塊が帯の幅いっぱいに引き伸ばされないようにする。
const 帯の最も短い長さ: 時間の長さ = 時間の長さ::定数の秒数から作る(10.0);

pub(super) fn タイムライン(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    縦積み(子![
        行の操作の部品を並べる(開いている),
        時間の行の並びを組む(開いている)
    ])
    .into()
}

fn 時間の行の並びを組む(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let 長さ = 開いている
        .重ね合わせの長さ()
        .起点から経過した長さ(時刻::先頭);
    let 帯の長さ = if 長さ.比べる(&帯の最も短い長さ).is_lt() {
        帯の最も短い長さ
    } else {
        長さ
    };
    let 全体 = match 帯の全体の範囲::生成する(
        帯の値::倍精度の小数から生成する(0.0),
        帯の値::倍精度の小数から生成する(帯の長さ.秒数()),
    ) {
        Ok(全体) => 全体,
        Err(不正) => {
            panic!("帯の右端は10秒以上の有限の秒数なので範囲を作れる(到達したらバグ): {不正}")
        }
    };
    let 選んでいる行 = 開いている
        .選んでいる行の番号と空の行かの組()
        .map(|様子| 様子.行);
    開いている
        .タイムラインに描く行の並び()
        .iter()
        .enumerate()
        .fold(
            時間の行の並び(全体, 塊の操作を変換する),
            |並び, (番号, 行の塊)| {
                let 選んでいるか =
                    選んでいる行 == Some(行の番号::番号から作成する(番号));
                並び.行を置く(
                    行の塊
                        .iter()
                        .fold(選びを添えた時間の行を作る(選んでいるか), 塊を置く),
                )
            },
        )
        .位置の線を置く(秒を帯の値にする(開いている.再生の位置().時刻()))
        .位置の線を動かしたら発する(位置の線の操作を変換する)
        .何も無い所を押したら発する(置き方の操作::選びを外す.応答にする())
        .行の何も無い所を押したら発する(押した行を選ぶ応答を作る)
        .into()
}

/// 塊を置く前の時間の行。選んでいる行なら、部品が背景をテーマの選択の色で描き分ける。
fn 選びを添えた時間の行を作る(
    選んでいるか: bool,
) -> 時間の行型<置いたクリップの識別子> {
    if 選んでいるか {
        時間の行().選んでいる行にする()
    } else {
        時間の行()
    }
}

/// 塊を行に置く。選んでいる置いたクリップの塊は選んでいる塊として置く。繰り返しの回数で等しい間隔の周回の区切りを付ける。
fn 塊を置く(
    行: 時間の行型<置いたクリップの識別子>,
    塊: &タイムラインに描く塊,
) -> 時間の行型<置いたクリップの識別子> {
    let 時間の塊 = match 時間の塊::生成する(
        秒を帯の値にする(塊.始まりの時刻),
        帯の値の差::倍精度の小数から生成する(塊.占める長さ.秒数()),
    ) {
        Ok(時間の塊) => 時間の塊,
        Err(不正) => {
            panic!("置く操作が区間の長さ0を拒むため、塊の長さは正である(到達したらバグ): {不正}")
        }
    };
    let 区切った塊 =
        時間の塊.等しい間隔の区切りを付ける(塊.繰り返しの回数.回数を0でない数にする());
    if 塊.選んでいるか {
        行.選んでいる塊を置く(塊.識別子.clone(), 区切った塊)
    } else {
        行.塊を置く(塊.識別子.clone(), 区切った塊)
    }
}
