//! 時間の行の並びの操作を応答へ直す境界の試験。塊を選んだら重ねる画面とサイドバーと同じ選びにすることと、移動量を時刻をずらす量と行の差へ直すことと、
//! 位置の線の値で再生の位置を動かすことと、押した行を選ぶことを確かめる。
#![allow(clippy::expect_used)]

use sengen_egui::{
    位置の線の操作, 帯の値, 帯の値の差, 時間の塊の操作, 時間の塊の移動量, 時間の行の差,
    時間の行の番号,
};

use clip_domain::{行の番号, 重ね合わせ上の秒};

use super::timeline_conversion::{
    位置の線の操作を変換する, 塊の操作を変換する, 押した行を選ぶ応答,
};
use crate::overlay::command::{タイムラインの操作, 塊の操作, 置き方の操作};
use crate::overlay::placement_test_support::置いたクリップの識別子を作る;
use crate::overlay::timeline_test_support::塊の動き;

fn 移動量(秒: f64, 上への行の数: i32) -> 時間の塊の移動量 {
    時間の塊の移動量 {
        時間: 帯の値の差::倍精度の小数から生成する(秒),
        行: 時間の行の差::上へ動かした行の数から生成する(上への行の数),
    }
}

#[test]
fn 塊を選んだら置いたクリップを選び_移動量は時刻をずらす量と行の差へ直す() {
    let 鍵 = || 置いたクリップの識別子を作る("置-2");
    assert_eq!(
        塊の操作を変換する(鍵(), 時間の塊の操作::選んだ),
        置き方の操作::置いたクリップを選ぶ(鍵()).応答にする()
    );
    assert_eq!(
        塊の操作を変換する(
            鍵(),
            時間の塊の操作::動かしている {
                開始点からの移動量: 移動量(-2.5, 1)
            }
        ),
        タイムラインの操作::塊(塊の操作::動かしている(塊の動き("置-2", -2.5, 1))).応答にする()
    );
    assert_eq!(
        塊の操作を変換する(
            鍵(),
            時間の塊の操作::放した {
                開始点からの移動量: 移動量(f64::NAN, 0)
            }
        ),
        タイムラインの操作::塊(塊の操作::移動量が数でない).応答にする()
    );
    assert_eq!(
        塊の操作を変換する(
            鍵(),
            時間の塊の操作::掴み始めた {
                行: 時間の行の番号::置いた順の番号から生成する(1)
            }
        ),
        タイムラインの操作::塊(塊の操作::掴み始めた(鍵())).応答にする()
    );
}

#[test]
fn 位置の線の値で再生の位置を動かし_押した行の番号の行を選ぶ() {
    let 値 = 帯の値::倍精度の小数から生成する(1.25);
    let 動かす = タイムラインの操作::位置を動かす(
        重ね合わせ上の秒::作成する(1.25).expect("時刻"),
    )
    .応答にする();
    for 操作 in [
        位置の線の操作::掴み始めた { 値 },
        位置の線の操作::動かしている { 値 },
        位置の線の操作::放した { 値 },
    ] {
        assert_eq!(位置の線の操作を変換する(操作), 動かす);
    }
    assert_eq!(
        押した行を選ぶ応答(時間の行の番号::置いた順の番号から生成する(1)),
        タイムラインの操作::行を選ぶ(行の番号::番号から作成する(1)).応答にする()
    );
}
