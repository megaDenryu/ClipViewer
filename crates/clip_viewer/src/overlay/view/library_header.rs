//! ヘッダーに出す、重ね合わせのライブラリの様子。書けないときは読み取り専用か使えない旨を、書けるときは開いている重ね合わせの登録の様子
//! (未登録なら「ライブラリに保存」のボタン、登録済みなら名前と保存の段階)を出す。保存の段階の文字は、スタックの作業場と共有する `library_common::view` が組む。
//! 参照: _doc/設計/同時再生.md 2-3・2-7

use sengen_egui::{ノード, ボタン, 子, 文字表示, 横並び, 無し};

use crate::library_common::view::保存の段階の文字;
use crate::overlay::command::{
    一覧とダイアログの操作, 重ね合わせの作業場の応答
};
use crate::overlay::state::library::{
    重ね合わせのライブラリの使える様子, 開いている重ね合わせのライブラリの様子,
};
use crate::overlay::state::重ね合わせの作業場の状態;
use crate::styles;

pub(super) fn ヘッダーのライブラリの様子(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    if let Some(文) =
        重ね合わせのライブラリへ書けないことの文(状態.ライブラリの使える様子())
    {
        return 文字表示(文).装飾(styles::不備の文).into();
    }
    match 状態.開いている重ね合わせのライブラリの様子() {
        None => 無し(),
        Some(開いている重ね合わせのライブラリの様子::未登録) => {
            横並び(子![
                文字表示("重ね合わせのライブラリ: 未登録").装飾(styles::補足),
                ボタン(
                    "ライブラリに保存",
                    一覧とダイアログの操作::登録のダイアログを開く.応答にする()
                ),
            ])
            .into()
        }
        Some(開いている重ね合わせのライブラリの様子::登録済み {
            名前,
            段階,
        }) => 横並び(子![
            文字表示(format!("重ね合わせのライブラリ: {名前}")).装飾(styles::動画の名前),
            保存の段階の文字(段階),
        ])
        .into(),
    }
}

/// 重ね合わせのライブラリへ書けないことの文。書けるときは無い。
pub(super) fn 重ね合わせのライブラリへ書けないことの文(
    様子: 重ね合わせのライブラリの使える様子<'_>,
) -> Option<String> {
    match 様子 {
        重ね合わせのライブラリの使える様子::書ける(_) => None,
        重ね合わせのライブラリの使える様子::読むだけ(_, 理由) => {
            Some(format!("重ね合わせのライブラリ: 読み取り専用({理由})"))
        }
        重ね合わせのライブラリの使える様子::置き場所が無い => {
            Some("重ね合わせのライブラリ: 使えない(置き場所が無い)".to_string())
        }
    }
}
