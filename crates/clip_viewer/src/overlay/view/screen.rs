//! 重ねる画面。出力の区画の使える大きさに、重ねる画面の縦横比を保って収め(スタックの作業場の表示サイズの「大きめ」と同じ収め方)、
//! 割合の矩形へ置く容器の中へ、行のテクスチャのクロップを映す矩形へ引き伸ばして、奥の行から手前の行の順に置く。
//! その上に複数の範囲枠を重ね、置いたクリップの映す矩形の枠を選び・動かし・大きさを変えられるようにする。
//! 左右反転と表示サイズの設定は使わない(同時再生.md 2-5)。参照: _doc/設計/同時再生.md 2-4・2-5・5-2 の7

use clip_domain::重ねる画面の縦横比;
use sengen_egui::{
    スタイル, ノード, 余白, 使える大きさから組む, 修飾キー, 割合の矩形へ置く, 大きさを決めた領域,
    子, 画像, 縦横の論理画素, 色, 複数の範囲枠, 複数の範囲枠の周りの余白, 論理画素,
};

use super::conversion::映す矩形を割合の矩形にする;
use super::frame_conversion::{範囲枠の操作を変換する, 置き方の応答};
use crate::output_measure::{
    クロップを描く部分にする, 丸める前の論理画素の寸法, 描く縦横比
};
use crate::overlay::command::{置き方の操作, 重ね合わせの作業場の応答};
use crate::overlay::state::{
    重ねる枠, 重ねる画面に描く行, 開いている重ね合わせ
};

/// 重ねる画面の黒い背景。置いたクリップを映していない所は黒で塗る。
const 重ねる画面の黒い背景: スタイル = スタイル {
    背景色: Some(色::BLACK),
    ..スタイル::無指定
};

/// 重ねる画面の材料とは、使える大きさが分かってから重ねる画面を組むために、状態から先に取り出しておく値の組のことである。
/// 描く時点で使える大きさを測る部品へ所有させて渡すため、状態を借りずに持つ。
#[derive(Clone)]
pub(super) struct 重ねる画面の材料 {
    pub(super) 縦横比: 重ねる画面の縦横比,
    pub(super) 描く行: Vec<重ねる画面に描く行>,
    pub(super) 枠の並び: Vec<重ねる枠>,
}

pub(super) fn 重ねる画面(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let 材料 = 重ねる画面の材料 {
        縦横比: 開いている.重ねる画面の縦横比(),
        描く行: 開いている.重ねる画面に描く行の並び(),
        枠の並び: 開いている.重ねる枠の並び(),
    };
    使える大きさから組む(move |大きさ| 材料.組む(大きさ)).into()
}

impl 重ねる画面の材料 {
    /// 使える大きさの欄の中央へ重ねる画面を描き、行の絵を書いた順(奥から手前)に置く。後に置いた行ほど手前に重なる。
    pub(super) fn 組む(
        &self,
        使える大きさ: 縦横の論理画素,
    ) -> ノード<重ね合わせの作業場の応答> {
        let 寸法 = self.寸法を求める(使える大きさ);
        let 枠の余白の合計 = 複数の範囲枠の周りの余白 * 2.0;
        let 上の余白 =
            ((使える大きさ.縦 - 寸法.縦 - 枠の余白の合計) * 0.5).大きい方(論理画素::ゼロ);
        let 容器 = self.描く行.iter().fold(
            割合の矩形へ置く(寸法).装飾(重ねる画面の黒い背景),
            |容器, 行| 容器.子を置く(映す矩形を割合の矩形にする(行.映す矩形), 行の絵(行)),
        );
        大きさを決めた領域(
            使える大きさ,
            子![余白(上の余白), self.枠を重ねる(寸法, 容器)],
        )
        .中央寄せ()
        .into()
    }

    /// 重ねる画面の上に、置いたクリップの映す矩形の枠を奥から順に重ねる。選んでいる枠は太い線と4隅のつまみで、選んでいない枠は細い線で描かれる。
    /// 隅のつまみは、Shift を押していない間は絵の形の縦横比を保つと発する。何も無い所を押したら選びを外す(同時再生.md 2-4)。
    fn 枠を重ねる(
        &self,
        寸法: 縦横の論理画素,
        重ねる画面: impl Into<ノード<重ね合わせの作業場の応答>>,
    ) -> ノード<重ね合わせの作業場の応答> {
        self.枠の並び
            .iter()
            .fold(
                複数の範囲枠(寸法, 重ねる画面, 範囲枠の操作を変換する)
                    .何も無い所を押したら発する(置き方の応答(置き方の操作::選びを外す))
                    .縦横比を保つ(修飾キー::SHIFT),
                |部品, 枠| {
                    let 割合の矩形 = 映す矩形を割合の矩形にする(枠.矩形);
                    if 枠.選んでいるか {
                        部品.選んでいる枠を置く(枠.識別子.clone(), 割合の矩形)
                    } else {
                        部品.枠を置く(枠.識別子.clone(), 割合の矩形)
                    }
                },
            )
            .into()
    }

    /// 出力の欄の余白の内側いっぱいに、重ねる画面の縦横比を保って収める寸法。スタックの作業場の表示サイズの「大きめ」と同じ式である。
    fn 寸法を求める(
        &self, 使える大きさ: 縦横の論理画素
    ) -> 縦横の論理画素 {
        丸める前の論理画素の寸法::出力の欄の余白の内側(使える大きさ)
            .縦横比を保って収める(描く縦横比::求める(Some(self.縦横比.縦横比())))
            .四捨五入して論理画素の組にする()
    }
}

/// 行の絵。映す矩形いっぱいに、行のテクスチャのクロップを引き伸ばして描く。
fn 行の絵(行: &重ねる画面に描く行) -> ノード<重ね合わせの作業場の応答> {
    let テクスチャ = 行.テクスチャ.clone();
    let 描く部分 = クロップを描く部分にする(行.クロップ);
    使える大きさから組む(move |大きさ| {
        画像(&テクスチャ)
            .描く部分(描く部分)
            .表示寸法へ引き伸ばす(大きさ)
            .into()
    })
    .into()
}
