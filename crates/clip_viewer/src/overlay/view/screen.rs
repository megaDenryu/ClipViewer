//! 重ねる画面。出力の区画の使える大きさに、重ねる画面の縦横比を保って収め(スタックの作業場の表示サイズの「大きめ」と同じ収め方)、
//! 割合の矩形へ置く容器の中へ、行のテクスチャのクロップを映す矩形へ引き伸ばして、奥の行から手前の行の順に置く。
//! 左右反転と表示サイズの設定は使わない(同時再生.md 2-5)。参照: _doc/設計/同時再生.md 2-5・5-2 の7

use clip_domain::重ねる画面の縦横比;
use sengen_egui::{
    スタイル, ノード, 余白, 使える大きさから組む, 割合の矩形へ置く, 大きさを決めた領域, 子, 画像,
    縦横の論理画素, 色, 論理画素,
};

use super::conversion::{
    クロップを描く部分にする, 映す矩形を割合の矩形にする
};
use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::state::{重ねる画面に描く行, 開いている重ね合わせ};

const 縁の余白: f64 = 32.0; // 出力の区画の縁に空ける余白の幅と高さそれぞれの合計(スタックの作業場の出力と同じ)
const 最小の幅: f64 = 320.0; // 区画が小さくても保つ最小の幅(スタックの作業場の出力と同じ)
const 最小の高さ: f64 = 180.0; // 区画が小さくても保つ最小の高さ(スタックの作業場の出力と同じ)

/// 重ねる画面の地。置いたクリップを映していない所は黒で塗る。
const 重ねる画面の地: スタイル = スタイル {
    背景色: Some(色::BLACK),
    ..スタイル::無指定
};

/// 重ねる画面の材料とは、使える大きさが分かってから重ねる画面を組むために、状態から先に取り出しておく値の組のことである。
/// 描く時点で使える大きさを測る部品へ所有させて渡すため、状態を借りずに持つ。
#[derive(Clone)]
pub(super) struct 重ねる画面の材料 {
    pub(super) 縦横比: 重ねる画面の縦横比,
    pub(super) 描く行: Vec<重ねる画面に描く行>,
}

pub(super) fn 重ねる画面(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let 材料 = 重ねる画面の材料 {
        縦横比: 開いている.重ねる画面の縦横比(),
        描く行: 開いている.重ねる画面に描く行の並び(),
    };
    使える大きさから組む(move |大きさ| 材料.組む(大きさ)).into()
}

impl 重ねる画面の材料 {
    /// 使える大きさの欄の中央へ重ねる画面を描き、行の絵を書いた順(奥から手前)に置く。後に置いた行ほど手前に重なる。
    pub(super) fn 組む(
        &self,
        使える大きさ: 縦横の論理画素,
    ) -> ノード<重ね合わせの作業場の応答> {
        let 寸法 = self.寸法を求める(使える大きさ);
        let 上の余白 = ((使える大きさ.縦 - 寸法.縦) * 0.5).大きい方(論理画素::ゼロ);
        let 容器 = self.描く行.iter().fold(
            割合の矩形へ置く(寸法).装飾(重ねる画面の地),
            |容器, 行| 容器.子を置く(映す矩形を割合の矩形にする(行.映す矩形), 行の絵(行)),
        );
        大きさを決めた領域(使える大きさ, 子![余白(上の余白), 容器])
            .中央寄せ()
            .into()
    }

    /// 縁の余白を引いた内側いっぱいに、重ねる画面の縦横比を保って収める寸法。内側は最小の幅と高さより小さくしない。
    fn 寸法を求める(
        &self, 使える大きさ: 縦横の論理画素
    ) -> 縦横の論理画素 {
        let 比 = self.縦横比.縦横比().値();
        let 幅 = (使える大きさ.横.倍精度の小数にする() - 縁の余白).max(最小の幅);
        let 高さ = (使える大きさ.縦.倍精度の小数にする() - 縁の余白).max(最小の高さ);
        let (収めた幅, 収めた高さ) = if 高さ * 比 <= 幅 {
            (高さ * 比, 高さ)
        } else {
            (幅, 幅 / 比)
        };
        縦横の論理画素::生成する(
            論理画素::倍精度の小数から生成する(収めた幅.round()),
            論理画素::倍精度の小数から生成する(収めた高さ.round()),
        )
    }
}

/// 行の絵。映す矩形いっぱいに、行のテクスチャのクロップを引き伸ばして描く。
fn 行の絵(行: &重ねる画面に描く行) -> ノード<重ね合わせの作業場の応答> {
    let テクスチャ = 行.テクスチャ.clone();
    let 描く部分 = クロップを描く部分にする(行.クロップ);
    使える大きさから組む(move |大きさ| {
        画像(&テクスチャ)
            .描く部分(描く部分)
            .表示寸法へ引き伸ばす(大きさ)
            .into()
    })
    .into()
}
