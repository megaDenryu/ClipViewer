//! 重ね合わせの作業場のキーの表。F11 で全画面を切り替える(同時再生.md 2-8)。割り当ては変えられず、スタックの作業場のキーの割り当てを使わない。
//! この表に再生と停止・取り消し・やり直しのキーは無く、重ね合わせの作業場ではそれらのキーが効かない(使い方.md 15.8節)。

use sengen_egui::{キー, キーの組, キー操作, ノード, 縦積み};

use crate::overlay::command::重ね合わせの作業場の応答;

/// 重ね合わせの作業場のキーの表。キーの組と、押したときに発する応答の組を並べる。画面のキー操作と、回帰試験(b)が除くキーの組の両方をこの表から作る。
const キーの表: [(キーの組, 重ね合わせの作業場の応答); 1] = [(
    キーの組::単独(キー::F11),
    重ね合わせの作業場の応答::全画面を切り替える,
)];

pub(super) fn キー操作の一覧() -> ノード<重ね合わせの作業場の応答> {
    縦積み(
        キーの表
            .iter()
            .map(|(組, 応答)| キー操作(*組, 応答.clone()).into())
            .collect(),
    )
    .into()
}

/// 重ね合わせの作業場が受け取るキーの組の全部。回帰試験(b)は、スタックの作業場のキーのうちこれと重なる組を、重ね合わせの作業場のキーとして別に確かめる。
#[cfg(test)]
pub(crate) fn 重ね合わせの作業場が受け取るキーの組() -> impl Iterator<Item = キーの組> {
    キーの表.iter().map(|(組, _)| *組)
}
