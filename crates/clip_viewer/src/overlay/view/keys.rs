//! 重ね合わせの作業場のキーの表。Space で再生と停止を、F11 で全画面を、Ctrl+Z で取り消しを、Ctrl+Y でやり直しを行う(同時再生.md 2-8)。
//! 割り当ては変えられず、スタックの作業場のキーの割り当てと settings.json の keyBindings を使わない。F11 のほかは、重ね合わせのダイアログを開いている間は効かない
//! (ダイアログがキーを受け取る。スタックの作業場の「ダイアログを開いている間は効かない」と同じ)。Ctrl+Z と Ctrl+Y は、入力欄にフォーカスがある間は入力欄に任せる
//! (入力欄の文字の取り消しになる)。参照: _doc/設計/画面.md 判断23

use sengen_egui::{キー, キーの組, キー操作, ノード, 修飾キー, 縦積み};

use crate::overlay::command::{
    編集の履歴の操作, 重ね合わせの作業場の応答, 重ね合わせの操作
};
use crate::overlay::state::重ね合わせの作業場の状態;

/// 再生と停止のキー。再生のボタンの説明にも出す。
pub(super) const 再生と停止のキー: キーの組 = キーの組::単独(キー::Space);
/// 取り消すキー。ヘッダーの「取り消す」の説明にも出す。
pub(super) const 取り消すキー: キーの組 = キーの組::生成する(修飾キー::COMMAND, キー::Z);
/// やり直すキー。ヘッダーの「やり直す」の説明にも出す。
pub(super) const やり直すキー: キーの組 = キーの組::生成する(修飾キー::COMMAND, キー::Y);

/// キーが効く範囲とは、重ね合わせの作業場のキーが、重ね合わせのダイアログを開いている間も効くかの区別のことである。
#[derive(Clone, Copy, PartialEq, Eq)]
enum キーが効く範囲 {
    いつでも,
    ダイアログを開いていない間,
}

/// 入力欄との関係とは、入力欄にフォーカスがある間に、修飾キーの組を入力欄から奪うか入力欄に任せるかの区別のことである(修飾キーの無い組はどちらでも入力欄に任せる)。
#[derive(Clone, Copy, PartialEq, Eq)]
enum 入力欄との関係 {
    修飾キーの組なら奪う,
    入力欄に任せる,
}

/// キーの決まりとは、1つのキーの組と、押したときに発する応答と、効く範囲と、入力欄との関係の組のことである。
struct キーの決まり {
    組: キーの組,
    応答: 重ね合わせの作業場の応答,
    効く範囲: キーが効く範囲,
    入力欄: 入力欄との関係,
}

/// 重ね合わせの作業場のキーの表。画面のキー操作と、回帰試験(b)が除くキーの組の両方をこの表から作る。
fn キーの表() -> [キーの決まり; 4] {
    [
        キーの決まり {
            組: 再生と停止のキー,
            応答: 重ね合わせの作業場の応答::操作(
                重ね合わせの操作::再生を切り替える,
            ),
            効く範囲: キーが効く範囲::ダイアログを開いていない間,
            入力欄: 入力欄との関係::修飾キーの組なら奪う,
        },
        キーの決まり {
            組: キーの組::単独(キー::F11),
            応答: 重ね合わせの作業場の応答::全画面を切り替える,
            効く範囲: キーが効く範囲::いつでも,
            入力欄: 入力欄との関係::修飾キーの組なら奪う,
        },
        キーの決まり {
            組: 取り消すキー,
            応答: 編集の履歴の操作::編集を取り消す.応答にする(),
            効く範囲: キーが効く範囲::ダイアログを開いていない間,
            入力欄: 入力欄との関係::入力欄に任せる,
        },
        キーの決まり {
            組: やり直すキー,
            応答: 編集の履歴の操作::編集をやり直す.応答にする(),
            効く範囲: キーが効く範囲::ダイアログを開いていない間,
            入力欄: 入力欄との関係::入力欄に任せる,
        },
    ]
}

/// 今効くキーの組を、見えないキー操作の部品にして並べる。
pub(super) fn キー操作の一覧(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    let ダイアログを開いているか = 状態.ダイアログを開いているか();
    縦積み(
        キーの表()
            .into_iter()
            .filter(|決まり| {
                決まり.効く範囲 == キーが効く範囲::いつでも || !ダイアログを開いているか
            })
            .map(キー操作の部品にする)
            .collect(),
    )
    .into()
}

fn キー操作の部品にする(
    決まり: キーの決まり,
) -> ノード<重ね合わせの作業場の応答> {
    let 部品 = キー操作(決まり.組, 決まり.応答);
    match 決まり.入力欄 {
        入力欄との関係::修飾キーの組なら奪う => 部品.into(),
        入力欄との関係::入力欄に任せる => {
            部品.入力欄にフォーカスがある間は発しない().into()
        }
    }
}

/// 重ね合わせの作業場のキーのうち、応答を重ね合わせの作業場の中で当てずに配線が受け取るもの(F11 の全画面。全画面の様子は2つの作業場で共有する)のキーの組。
/// 回帰試験(b)は、スタックの作業場のキーのうちこれと重なる組を除き、`app/tests/workspace_overlay_tests.rs` で別に確かめる。
#[cfg(test)]
pub(crate) fn 重ね合わせの作業場の外へ届くキーの組() -> impl Iterator<Item = キーの組> {
    キーの表()
        .into_iter()
        .filter(|決まり| !matches!(決まり.応答, 重ね合わせの作業場の応答::操作(_)))
        .map(|決まり| 決まり.組)
}
