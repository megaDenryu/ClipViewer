//! 重ね合わせの作業場のキー。F11 で全画面を切り替える(同時再生.md 2-8)。割り当ては変えられず、スタックの作業場のキーの割り当てを使わない。
//! 再生と停止・取り消し・やり直しのキーは第18段階で足す。

use sengen_egui::{キー, キーの組, キー操作, ノード};

use crate::overlay::command::重ね合わせの作業場の応答;

/// 重ね合わせの作業場で全画面を切り替えるキー。
const 全画面を切り替えるキー: キーの組 = キーの組::単独(キー::F11);

/// 重ね合わせの作業場が受け取るキーの組の全部。回帰試験(b)は、スタックの作業場のキーのうちこれと重なるものを、重ね合わせの作業場のキーとして別に確かめる。
#[cfg(test)]
pub(crate) const 重ね合わせの作業場のキーの並び: [キーの組; 1] = [全画面を切り替えるキー];

pub(super) fn キー操作の一覧() -> ノード<重ね合わせの作業場の応答> {
    キー操作(
        全画面を切り替えるキー,
        重ね合わせの作業場の応答::全画面を切り替える,
    )
    .into()
}
