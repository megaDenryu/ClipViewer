//! タイムラインの画面の試験。行の操作の部品を並べるの「行を足す」が応答を発し、「選んだ空の行を消す」は空の行を選んだときだけ押せることを、画面を描いて押して確かめる。
#![allow(clippy::expect_used)]

use super::screen_press_support::{描いたか, 文字を押して集める};
use crate::overlay::command::タイムラインの操作;
use crate::overlay::state::今のスタックから並べる状況;
use crate::overlay::timeline_test_support::{
    タイムラインの操作を当てる, 二行を開いた作業場
};

#[test]
fn 行を足すは応答を発し_選んだ空の行を消すは空の行を選んだときだけ押せる() {
    let mut 作業場 = 二行を開いた作業場();
    let 押せる = 今のスタックから並べる状況::並べられる;
    assert!(描いたか(
        &作業場,
        押せる,
        "行の何も無い所を押すと、その行を選ぶ"
    ));
    assert_eq!(
        文字を押して集める(&作業場, 押せる, "行を足す"),
        [タイムラインの操作::空の行を手前に足す.応答にする()]
    );
    assert!(文字を押して集める(&作業場, 押せる, "選んだ空の行を消す").is_empty());
    タイムラインの操作を当てる(&mut 作業場, タイムラインの操作::空の行を手前に足す);
    assert!(描いたか(
        &作業場,
        押せる,
        "選んでいる行: 上から1番目(空の行)"
    ));
    assert_eq!(
        文字を押して集める(&作業場, 押せる, "選んだ空の行を消す"),
        [タイムラインの操作::選んでいる空の行を消す.応答にする()]
    );
}
