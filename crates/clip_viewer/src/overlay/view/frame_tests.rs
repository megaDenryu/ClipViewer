//! 重ねる画面の上の映す矩形の枠の試験。枠の内側をドラッグすると選んで掴み始め、内側の移動を発して放すことと、押しただけでも選ぶことと、何も無い所を押すと選びを外すことと、
//! 縦横比の扱いと隅の掴んだ部分を百分率の操作へ直すことを、egui に描かせて確かめる。
#![allow(clippy::expect_used)]

use clip_domain::四隅のつまみ;
use eframe::egui;
use sengen_egui::{
    割合の差, 範囲枠の掴んだ部分, 縦横の割合の差, 縦横比の扱い, 複数の範囲枠の操作
};

use super::frame_conversion::範囲枠の操作を変換する;
use super::test_support::{描いて集める, 黒く塗った矩形};
use crate::overlay::command::{
    映す矩形の枠の操作, 置き方の操作, 重ね合わせの作業場の応答, 重ね合わせの操作,
};
use crate::overlay::placement_test_support::{動き, 置いた, 開いた作業場};
use crate::overlay::state::{
    今のスタックから並べる状況, 映す矩形の掴む所, 隅の縦横比の扱い
};
use crate::overlay::workspace::重ね合わせの作業場;

fn 置き方(操作: 置き方の操作) -> 重ね合わせの作業場の応答 {
    重ね合わせの作業場の応答::操作(重ね合わせの操作::置き方(操作))
}

/// 1フレームずつ、押す・動かす・放すの事象を描かせて、発した応答をつなげて返す。
fn ドラッグして集める(
    作業場: &重ね合わせの作業場,
    始め: egui::Pos2,
    終わり: egui::Pos2,
) -> (egui::Rect, Vec<重ね合わせの作業場の応答>) {
    let 画面描画の共有状態 = egui::Context::default();
    let 木 = || {
        super::画面(
            作業場.状態(),
            今のスタックから並べる状況::並べられる,
            None,
            None,
        )
    };
    let (_, 出力) = 描いて集める(&画面描画の共有状態, Vec::new(), &木);
    let 地 = 黒く塗った矩形(&出力).expect("重ねる画面を描いた");
    let ボタン = |位置, 押した| egui::Event::PointerButton {
        pos: 位置,
        button: egui::PointerButton::Primary,
        pressed: 押した,
        modifiers: egui::Modifiers::NONE,
    };
    let 始め = 始め + 地.min.to_vec2();
    let 終わり = 終わり + 地.min.to_vec2();
    let 間 = 始め + (終わり - 始め) * 0.5;
    let 事象の並び = [
        vec![egui::Event::PointerMoved(始め), ボタン(始め, true)],
        vec![egui::Event::PointerMoved(間)],
        vec![egui::Event::PointerMoved(終わり)],
        vec![ボタン(終わり, false)],
    ];
    let 集まり = 事象の並び
        .into_iter()
        .flat_map(|事象| 描いて集める(&画面描画の共有状態, 事象, &木).0)
        .collect();
    (地, 集まり)
}

#[test]
fn 枠の内側をドラッグすると選んで掴み始め_内側の移動を発して放す() {
    let 作業場 = 開いた作業場();
    let (_, 集まり) =
        ドラッグして集める(&作業場, egui::pos2(200.0, 100.0), egui::pos2(260.0, 100.0));
    assert_eq!(
        集まり[..2],
        [
            置き方(置き方の操作::置いたクリップを選ぶ(
                置いた("置-1")
            )),
            置き方(置き方の操作::映す矩形の枠(
                映す矩形の枠の操作::掴み始めた(置いた("置-1"))
            )),
        ]
    );
    let 放した = 集まり.last().expect("放したを発した");
    let 重ね合わせの作業場の応答::操作(重ね合わせの操作::置き方(
        置き方の操作::映す矩形の枠(映す矩形の枠の操作::放した(動き)),
    )) = 放した
    else {
        panic!("最後は放した: {放した:?}");
    };
    assert_eq!(動き.掴む所, 映す矩形の掴む所::内側);
    assert!(動き.移動量.横 > clip_domain::百分率の差分::default());
}

#[test]
fn 何も無い所を押すと選びを外す() {
    let 作業場 = 開いた作業場();
    let (_, 集まり) =
        ドラッグして集める(&作業場, egui::pos2(-4.0, -4.0), egui::pos2(-4.0, 30.0));
    assert_eq!(集まり, [置き方(置き方の操作::選びを外す)]);
}

#[test]
fn 縦横比の扱いと隅の掴んだ部分を百分率の操作へ直す() {
    let 割合 = |横, 縦| {
        縦横の割合の差::生成する(割合の差::生成する(横), 割合の差::生成する(縦))
    };
    let 応答 = 範囲枠の操作を変換する(
        置いた("置-1"),
        複数の範囲枠の操作::動かしている {
            掴んだ部分: 範囲枠の掴んだ部分::右下の隅,
            開始点からの移動量: 割合(0.25, -0.5),
            縦横比の扱い: 縦横比の扱い::保たない,
        },
    );
    assert_eq!(
        応答,
        置き方(置き方の操作::映す矩形の枠(
            映す矩形の枠の操作::動かしている(動き(
                "置-1",
                映す矩形の掴む所::隅(四隅のつまみ::右下),
                25.0,
                -50.0,
                隅の縦横比の扱い::保たない,
            ))
        ))
    );
    let 数でない = 範囲枠の操作を変換する(
        置いた("置-1"),
        複数の範囲枠の操作::放した {
            掴んだ部分: 範囲枠の掴んだ部分::内側,
            開始点からの移動量: 割合(f32::NAN, 0.0),
            縦横比の扱い: 縦横比の扱い::保つ,
        },
    );
    assert_eq!(
        数でない,
        置き方(置き方の操作::映す矩形の枠(
            映す矩形の枠の操作::移動量が数でない
        ))
    );
}

#[test]
fn 枠を押しただけでも選び_当てても置き方は変わらない() {
    let mut 作業場 = 開いた作業場();
    let (_, 集まり) =
        ドラッグして集める(&作業場, egui::pos2(200.0, 100.0), egui::pos2(200.0, 100.0));
    for 応答 in 集まり {
        let 重ね合わせの作業場の応答::操作(操作) = 応答 else {
            panic!("重ね合わせの作業場の中の操作だけを発する: {応答:?}");
        };
        作業場.操作を適用する(操作);
    }
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert!(開いている.置いたクリップを選んでいるか(&置いた("置-1")));
    assert!(!開いている.置き方を手で直したか());
}
