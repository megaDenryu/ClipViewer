//! 重ね合わせの左のサイドバーの、置いたクリップの音の並び。奥の行から手前の行の順に、置いたクリップごとに名前と、音量のつまみと「消音」のチェックボックスを並べる。
//! 今のスタックから並べた重ね合わせでは、この順はスタックの順であり、格子の左上の枠からの順である。
//! 置いたクリップを選ぶ操作は第13段階で足すため、それまでは全部の置いたクリップの音の設定を並べる。
//! 参照: _doc/設計/同時再生.md 2-3・2-6

use clip_domain::置いたクリップ;
use sengen_egui::{
    スライダー, チェックボックス, ノード, パネル, パネルの位置, 子, 文字表示, 横並び, 画素,
    縦スクロール, 縦積み,
};

use crate::overlay::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::overlay::state::開いている重ね合わせ;

/// 音量のつまみの刻み。スタックの作業場の音量のつまみと同じにする。
const 音量の刻み: f64 = 0.05;

/// 左のサイドバーのパネル。重ね合わせを開いている間だけ出す。
pub(super) fn 置いたクリップの音のパネル(
    開いている: &開いている重ね合わせ,
) -> ノード<重ね合わせの作業場の応答> {
    let 置いたクリップの並び = 開いている
        .重ね合わせ()
        .行の並び()
        .奥から手前の順の行()
        .iter()
        .flat_map(|行| 行.置いたクリップの並び())
        .map(置いたクリップの音)
        .collect();
    パネル(
        "重ね合わせの置いたクリップの音",
        パネルの位置::左,
        子![縦スクロール(
            "重ね合わせの置いたクリップの音の並び",
            子![文字表示("置いたクリップの音"), 縦積み(置いたクリップの並び)]
        )],
    )
    .既定の幅(画素(240.0))
    .into()
}

/// 1つの置いたクリップの名前と、音量のつまみ(0〜1)と、「消音」のチェックボックス。
fn 置いたクリップの音(
    置いたクリップ: &置いたクリップ,
) -> ノード<重ね合わせの作業場の応答> {
    let 音の設定 = 置いたクリップ.音の設定();
    let 音量の識別子 = 置いたクリップ.識別子().clone();
    let 消音の識別子 = 置いたクリップ.識別子().clone();
    縦積み(子![
        文字表示(置いたクリップ.受け継いだ値().名前.文字列()),
        横並び(子![
            スライダー(音の設定.音量.値(), 0.0..=1.0, move |音量| {
                重ね合わせの作業場の応答::操作(
                    重ね合わせの操作::置いたクリップの音量を選ぶ {
                        識別子: 音量の識別子.clone(),
                        音量,
                    },
                )
            })
            .刻み(音量の刻み),
            チェックボックス(
                "消音",
                音の設定.消音しているか,
                move |消音するか| {
                    重ね合わせの作業場の応答::操作(
                        重ね合わせの操作::置いたクリップの消音を設定する {
                            識別子: 消音の識別子.clone(),
                            消音するか,
                        },
                    )
                }
            ),
        ]),
    ])
    .into()
}
