//! 重ね合わせの作業場の左のサイドバー。重ね合わせを開いている間だけ出し、上から、置くクリップの一覧(今のスタックのクリップと「置く」)と、
//! 置いたクリップの一覧と選んでいる置いたクリップの設定と音(`sidebar_placed.rs`・`placed_sound.rs`)を並べる。
//! 置くクリップの一覧は、スタックの動画が重ね合わせの動画と同じときだけ押せ、違うときは一覧の上に理由を出す。参照: _doc/設計/同時再生.md 2-3・2-4

use sengen_egui::{
    ノード, パネル, パネルの位置, ボタン, 付け足せる, 区切り線, 子, 文字表示, 横並び, 無し, 画素,
    縦スクロール, 縦積み,
};

use super::sidebar_placed;
use crate::overlay::command::重ね合わせの作業場の応答;
use crate::overlay::state::placement::{
    動画が違うため置けない文, 動画を開いていないため置けない文, 置くクリップ, 置くクリップの一覧,
    置くクリップの動画,
};
use crate::overlay::state::開いている重ね合わせ;

/// 置くクリップの一覧の見出し。
pub(crate) const 置くクリップの見出し: &str = "置くクリップ(今のスタック)";

/// 左のサイドバーのパネル。置くクリップの一覧が無い(配線が渡さない試験の)ときは、置くクリップの欄を出さない。
pub(super) fn サイドバーのパネル(
    開いている: &開いている重ね合わせ,
    置くクリップ: Option<&置くクリップの一覧>,
) -> ノード<重ね合わせの作業場の応答> {
    let 置くクリップの欄 = 置くクリップ.map_or_else(無し, 置くクリップの一覧の欄);
    パネル(
        "重ね合わせのサイドバー",
        パネルの位置::左,
        子![縦スクロール(
            "重ね合わせのサイドバーの中身",
            子![
                置くクリップの欄,
                区切り線(),
                sidebar_placed::置いたクリップの欄(開いている),
            ]
        )],
    )
    .既定の幅(画素(280.0))
    .into()
}

/// 置くクリップの一覧の欄。今のスタックのクリップをスタックの順に、名前と「置く」で並べる。置けないときは理由を出し、「置く」を押せなくする。
fn 置くクリップの一覧の欄(
    一覧: &置くクリップの一覧,
) -> ノード<重ね合わせの作業場の応答> {
    let 置けない理由 = match 一覧.動画 {
        置くクリップの動画::置ける { .. } => None,
        置くクリップの動画::動画が違う => Some(動画が違うため置けない文),
        置くクリップの動画::動画を開いていない => {
            Some(動画を開いていないため置けない文)
        }
    };
    let 行の並び = 一覧
        .並び
        .iter()
        .map(|クリップ| 置くクリップの行(クリップ, 置けない理由.is_none()))
        .collect();
    縦積み(子![
        文字表示(置くクリップの見出し),
        文字表示(置けない理由.unwrap_or_default()),
        縦積み(行の並び),
    ])
    .into()
}

fn 置くクリップの行(
    クリップ: &置くクリップ,
    置けるか: bool,
) -> ノード<重ね合わせの作業場の応答> {
    横並び(子![
        ボタン(
            "置く",
            重ね合わせの作業場の応答::今のスタックのクリップを置く(
                クリップ.識別子.clone()
            )
        )
        .有効(置けるか)
        .説明("このクリップの写しを、今の再生の位置に、空いている最も手前の行へ置く"),
        文字表示(クリップ.名前.文字列()),
    ])
    .into()
}
