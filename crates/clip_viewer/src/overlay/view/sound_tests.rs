//! 重ね合わせの音の画面の試験。開いている間だけ左のサイドバーを出し、選んでいる置いたクリップの設定に音量のつまみと「消音」を出し、押すと消音を設定する操作を発することと、
//! 再生の操作の行に音量のつまみを、出力の区画の上に2本目の流れを開けなかった理由の音の様子を出すことを、egui に描かせて押して確かめる。
#![allow(clippy::expect_used)]

use super::screen_press_support::{描いたか, 文字を押して集める};
use clip_domain::置いたクリップの音の変更;

use super::placed_sound::置いたクリップの音量の見出し;
use super::sidebar_placed::置いたクリップの見出し;
use crate::overlay::command::{
    置き方の操作, 重ね合わせの作業場の応答, 重ね合わせの操作
};
use crate::overlay::placement_test_support::{
    置いたクリップの識別子を作る, 置き方の操作を当てる
};
use crate::overlay::sound_test_support::装置の無い作業場を作る;
use crate::overlay::state::今のスタックから並べる状況;
use crate::overlay::test_support::五秒の重ね合わせ;

#[test]
fn 選んでいる置いたクリップの設定に音量のつまみと消音を出し_押すと消音を設定する操作を発する() {
    let mut 作業場 = 装置の無い作業場を作る();
    let 押せる = 今のスタックから並べる状況::並べられる;
    assert!(
        !描いたか(&作業場, 押せる, 置いたクリップの見出し),
        "開いていない間はサイドバーを出さない"
    );
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    assert!(描いたか(&作業場, 押せる, 置いたクリップの見出し));
    assert!(
        !描いたか(&作業場, 押せる, "消音"),
        "選んでいない間は置いたクリップの音を出さない"
    );
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを選ぶ(置いたクリップの識別子を作る("置-1")),
    );
    assert!(描いたか(&作業場, 押せる, 置いたクリップの音量の見出し));
    let 押した = 文字を押して集める(&作業場, 押せる, "消音");
    let [重ね合わせの作業場の応答::操作(操作)] = 押した.as_slice() else {
        panic!("消音を設定する操作を1つ発する: {押した:?}");
    };
    assert!(matches!(
        操作,
        重ね合わせの操作::置いたクリップの音を変える {
            変更: 置いたクリップの音の変更::消音を設定する(true),
            ..
        }
    ));
}
#[test]
fn 音量のつまみと音を鳴らせない理由を出す() {
    let 作業場 = 装置の無い作業場を作る();
    let 押せる = 今のスタックから並べる状況::並べられる;
    assert!(描いたか(&作業場, 押せる, "音量"));
    assert!(描いたか(
        &作業場,
        押せる,
        "音: 鳴らせない(音声出力装置が見つからない)"
    ));
}

#[test]
fn 再生の操作の行の全体を消音を押すと全体の消音を切り替える応答を発する() {
    let 作業場 = 装置の無い作業場を作る();
    assert_eq!(
        文字を押して集める(
            &作業場,
            今のスタックから並べる状況::並べられる,
            "全体を消音"
        ),
        [重ね合わせの作業場の応答::全体の消音を切り替える]
    );
}
