//! 選んでいる置いたクリップの音の行。左のサイドバーの選んでいる置いたクリップの設定の中に、その置いたクリップの音量のつまみと「消音」のチェックボックスを出す。
//! 置いたクリップはサイドバーの一覧と重ねる画面の枠で選べるため、音量と消音は選んでいる1つの置いたクリップについて出す。参照: _doc/設計/同時再生.md 2-3・2-6

use clip_domain::{
    置いたクリップ, 置いたクリップの識別子, 置いたクリップの音の変更, 音量
};
use sengen_egui::{
    スライダー, チェックボックス, ノード, 子, 文字表示, 横並び, 縦積み
};

use crate::overlay::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::volume_step::音量のつまみの刻み;

/// 置いたクリップの音の行の見出し。再生の操作の行の「音量」(全体の音量のつまみ)と分けるため、置いたクリップの音量であることを書く。
pub(crate) const 置いたクリップの音量の見出し: &str = "このクリップの音量:";

/// 置いたクリップの音量のつまみ(0〜1)と、「消音」のチェックボックス。つまみの値は境界のここで `音量` へ包む。
pub(super) fn 置いたクリップの音の行(
    置いたクリップ: &置いたクリップ,
) -> ノード<重ね合わせの作業場の応答> {
    let 音の設定 = 置いたクリップ.音の設定();
    let 音量の識別子 = 置いたクリップ.識別子().clone();
    let 消音の識別子 = 置いたクリップ.識別子().clone();
    縦積み(子![
        文字表示(置いたクリップの音量の見出し),
        横並び(子![
            スライダー(音の設定.音量.値(), 0.0..=1.0, move |つまみの値| {
                音を変える応答(
                    &音量の識別子,
                    置いたクリップの音の変更::音量を選ぶ(音量::範囲へ収めて作る(
                        つまみの値,
                    )),
                )
            })
            .刻み(音量のつまみの刻み),
            チェックボックス(
                "消音",
                音の設定.消音しているか,
                move |消音するか| {
                    音を変える応答(
                        &消音の識別子,
                        置いたクリップの音の変更::消音を設定する(消音するか),
                    )
                }
            )
        ]),
    ])
    .into()
}

fn 音を変える応答(
    識別子: &置いたクリップの識別子,
    変更: 置いたクリップの音の変更,
) -> 重ね合わせの作業場の応答 {
    重ね合わせの作業場の応答::操作(
        重ね合わせの操作::置いたクリップの音を変える {
            識別子: 識別子.clone(),
            変更,
        },
    )
}
