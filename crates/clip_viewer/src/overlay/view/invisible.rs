//! 重ね合わせの作業場の見えない部品。ウインドウへ落とされたファイルの受け取りと、入力が無くても画面を進める予約と、キーの表(`keys.rs`)を束ねる。
//! スタックの作業場の見えない部品(`view/invisible.rs`)と同じ役であり、重ね合わせの作業場の層から使えないため別に持つ。

use std::path::PathBuf;
use std::time::Duration;

use sengen_egui::{
    ノード, 子, 描き直しを予約する, 無し, 縦積み, 落とされたファイルをまとめて受け取る,
};

use super::keys;
use crate::overlay::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::overlay::state::重ね合わせの作業場の状態;
use crate::redraw_interval::描き直しの間隔;

pub(super) fn 見えない部品(
    状態: &重ね合わせの作業場の状態,
    スタックの作業場の描き直すまでの時間: Option<Duration>,
) -> ノード<重ね合わせの作業場の応答> {
    縦積み(子![
        落とされたファイルをまとめて受け取る(
            落とされたファイルを開かずに知らせる
        ),
        描き直しの予約(状態, スタックの作業場の描き直すまでの時間),
        keys::キー操作の一覧(),
    ])
    .into()
}

/// 落とされたファイルの受け取りが発する応答。動画と JSON はスタックの作業場で開くため、パスは使わずに知らせだけを頼む。
fn 落とされたファイルを開かずに知らせる(
    _パス一覧: Vec<PathBuf>,
) -> 重ね合わせの作業場の応答 {
    重ね合わせの作業場の応答::操作(重ね合わせの操作::ファイルを落とされた)
}

/// 入力が無くても画面を進めるなら、描き直しを予約する。重ね合わせの作業場の時間と、スタックの作業場の時間の短い方で予約する。
/// 重ね合わせの作業場は、再生している間と、止まっていても区間を溜めているか行のコマを待っている間(開いた直後の最初のコマ等)は描き直す。
fn 描き直しの予約(
    状態: &重ね合わせの作業場の状態,
    スタックの作業場の描き直すまでの時間: Option<Duration>,
) -> ノード<重ね合わせの作業場の応答> {
    let 重ね合わせの描き直すまでの時間 = 状態.画面を進め続けるか().then_some(描き直しの間隔);
    match [
        重ね合わせの描き直すまでの時間,
        スタックの作業場の描き直すまでの時間,
    ]
    .into_iter()
    .flatten()
    .min()
    {
        Some(待つ時間) => 描き直しを予約する(待つ時間).into(),
        None => 無し(),
    }
}
