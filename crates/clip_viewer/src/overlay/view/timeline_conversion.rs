//! 時間の行の並びの操作を、重ね合わせの作業場の応答へ直す境界。部品の値(帯の値・帯の値の差・時間の行の番号・時間の行の差)を、
//! `clip_domain` の型(重ね合わせ上の秒・時刻をずらす量・行の番号・行の差)へ直すのはここ1箇所である。
//! 部品は行を置いた順(最初がいちばん下)で番号を付け、画面は奥の行から置くため、部品の行の番号と差はそのまま重ね合わせの行の番号と差になる。
//! 参照: _doc/設計/同時再生.md 2-6・3-4

use clip_domain::{
    時刻をずらす量, 置いたクリップの識別子, 行の差, 行の番号, 重ね合わせ上の秒
};
use sengen_egui::{
    位置の線の操作, 帯の値, 時間の塊の操作, 時間の塊の移動量, 時間の行の番号
};

use crate::overlay::command::{
    タイムラインの操作, 塊の操作, 置き方の操作, 重ね合わせの作業場の応答,
};
use crate::overlay::state::grab::位置の線の段階;
use crate::overlay::state::timeline::塊のドラッグの動き;

/// 塊の鍵(置いたクリップの識別子)と時間の塊の操作を、塊の操作の応答にする。選んだは、重ねる画面とサイドバーと同じ、置いたクリップを選ぶ操作にする。
pub(super) fn 塊の操作を変換する(
    鍵: 置いたクリップの識別子,
    操作: 時間の塊の操作,
) -> 重ね合わせの作業場の応答 {
    let 塊 = match 操作 {
        時間の塊の操作::選んだ => {
            return 置き方の操作::置いたクリップを選ぶ(鍵).応答にする();
        }
        時間の塊の操作::掴み始めた { .. } => 塊の操作::掴み始めた(鍵),
        時間の塊の操作::動かしている {
            開始点からの移動量
        } => 塊の操作::動かしている(塊の移動量から動きを作る(鍵, 開始点からの移動量)),
        時間の塊の操作::放した {
            開始点からの移動量
        } => 塊の操作::放した(塊の移動量から動きを作る(鍵, 開始点からの移動量)),
        時間の塊の操作::掴んだ塊が無くなった => {
            塊の操作::掴んだ塊が無くなった(鍵)
        }
    };
    タイムラインの操作::塊(塊).応答にする()
}

/// 位置の線の操作を、段階を添えて再生の位置を動かす応答にする。掴み始め・動かしている・放したのどれでも、その値の時刻へ動かし、
/// 状態は段階で、ドラッグの間は流し読みを開き直さず音を黙らせる(画面.md 判断5)。
/// 部品は値を全体の範囲(0秒から)へ収めて渡すため負にならないが、時刻にできない値なら先頭へ動かす。
pub(super) fn 位置の線の操作を変換する(
    操作: 位置の線の操作,
) -> 重ね合わせの作業場の応答 {
    let (段階, 値) = match 操作 {
        位置の線の操作::掴み始めた { 値 } => (位置の線の段階::掴み始めた, 値),
        位置の線の操作::動かしている { 値 } => (位置の線の段階::動かしている, 値),
        位置の線の操作::放した { 値 } => (位置の線の段階::放した, 値),
    };
    let 時刻 =
        重ね合わせ上の秒::作成する(値.倍精度の小数にする()).unwrap_or(重ね合わせ上の秒::先頭);
    タイムラインの操作::再生の位置を動かす(段階, 時刻).応答にする()
}

/// 重ね合わせ上の秒を、時間の行の並びの値(帯の値)にする。塊の始まりと位置の線に使う。
pub(super) fn 秒を帯の値にする(秒: 重ね合わせ上の秒) -> 帯の値 {
    帯の値::倍精度の小数から生成する(秒.秒数())
}

/// 行の何も無い所を押したときに、押した行を選ぶ応答を作る。
pub(super) fn 押した行を選ぶ応答を作る(
    番号: 時間の行の番号,
) -> 重ね合わせの作業場の応答 {
    タイムラインの操作::行を選ぶ(行の番号::番号から作成する(
        番号.置いた順の番号(),
    ))
    .応答にする()
}

/// 部品の移動量を塊のドラッグの動きにする。
/// 注意: 部品は時間の差を、有限の値で作った全体の範囲と正の幅とポインタの有限の移動量から求めるため、有限でない差は届かない。
fn 塊の移動量から動きを作る(
    鍵: 置いたクリップの識別子,
    移動量: 時間の塊の移動量,
) -> 塊のドラッグの動き {
    let ずらす量 = match 時刻をずらす量::符号付きの秒数から作成する(
        移動量.時間.倍精度の小数にする(),
    ) {
        Ok(ずらす量) => ずらす量,
        Err(不正) => panic!("時間の行の並びの時間の差は有限である(到達したらバグ): {不正}"),
    };
    塊のドラッグの動き {
        対象: 鍵,
        ずらす量,
        行の差: 行の差::手前へ動かした行の数から作成する(
            移動量.行.上へ動かした行の数(),
        ),
    }
}
