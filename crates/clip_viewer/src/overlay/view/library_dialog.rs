//! 重ね合わせのダイアログ。名前を付けて登録する・捨てる前に確かめる・保存できないまま続けるかを確かめるダイアログを出す。
//! 捨てる前の確かめは、並べ直すときは並べ直す前の確かめの文(同時再生.md 2-2)で、ほかの操作ではスタックと同じ文と選択肢(画面.md 判断14)で出す。
//! 外側を押すか Escape で閉じようとしたら、ダイアログを閉じる(続ける操作は行わない)。中身の部品はスタックの作業場と共有する `library_common::view` が組む。

use sengen_egui::{ノード, ボタン, モーダル, 子, 文字表示, 横並び, 無し};

use crate::library_common::view::{名前のダイアログ, 確かめるダイアログ};
use crate::overlay::command::{
    一覧とダイアログの操作, 重ね合わせのライブラリの操作, 重ね合わせの作業場の応答,
};
use crate::overlay::state::library::{
    重ね合わせとの関係を終える操作, 重ね合わせのダイアログ
};
use crate::overlay::state::重ね合わせの作業場の状態;
use crate::styles;

/// 並べ直す前に確かめる文。
pub(crate) const 並べ直す前に確かめる文: &str =
    "この重ね合わせは置き方を直してある。今のスタックから並べ直すと、直した置き方は失われる";

/// 並べ直す前の確かめで並べ直すボタンの文。
pub(crate) const 並べ直すボタンの文: &str = "直した置き方を捨てて並べ直す";

/// 未登録の重ね合わせを捨てる前に確かめる文。スタックの「ライブラリに保存していない変更がある」と同じ文である(画面.md 判断14)。
pub(crate) const 捨てる前に確かめる文: &str =
    "ライブラリに保存していない変更がある。続けると失われる";

/// 開いているダイアログ。開いていなければ無い。
pub(super) fn 開いているダイアログ(
    状態: &重ね合わせの作業場の状態,
) -> ノード<重ね合わせの作業場の応答> {
    let 中身 = match 状態.ライブラリ().ダイアログ() {
        重ね合わせのダイアログ::無し => return 無し(),
        重ね合わせのダイアログ::名前を付けて登録(入力, _) => {
            名前のダイアログ(
                "ライブラリに保存する名前",
                入力,
                名前の入力を書き換えた,
                "保存する",
                重ね合わせのライブラリの操作::登録する.応答にする(),
                やめる(),
            )
        }
        重ね合わせのダイアログ::捨てる前の確かめ(
            重ね合わせとの関係を終える操作::今のスタックから並べ直す,
        ) => 確かめるダイアログ(
            並べ直す前に確かめる文.to_string(),
            並べ直すボタンの文,
            捨てて続ける(),
            やめる(),
        ),
        重ね合わせのダイアログ::捨てる前の確かめ(_) => {
            捨てる前の確かめ(状態.ライブラリ().書けるか())
        }
        重ね合わせのダイアログ::保存できずに続ける確認(理由, _) => {
            確かめるダイアログ(
                format!(
                    "開いている重ね合わせを保存できない({理由})。続けると、保存できていない変更が失われる"
                ),
                "変更を捨てて続ける",
                捨てて続ける(),
                やめる(),
            )
        }
    };
    モーダル("重ね合わせのダイアログ", true, 中身)
        .閉じたら(やめる())
        .into()
}

/// 未登録の重ね合わせを捨てる前に確かめる中身。保存は、重ね合わせのライブラリへ書けるときだけ押せる。
fn 捨てる前の確かめ(
    書けるか: bool,
) -> Vec<ノード<重ね合わせの作業場の応答>> {
    子![
        文字表示(捨てる前に確かめる文),
        横並び(子![
            ボタン(
                "ライブラリに保存する",
                重ね合わせのライブラリの操作::登録してから続ける.応答にする()
            )
            .装飾(styles::強調ボタン)
            .有効(書けるか),
            ボタン("変更を捨てて続ける", 捨てて続ける()).装飾(styles::危険ボタン),
            ボタン("やめる", やめる()),
        ]),
    ]
}

fn 捨てて続ける() -> 重ね合わせの作業場の応答 {
    重ね合わせのライブラリの操作::変更を捨てて続ける.応答にする()
}

fn やめる() -> 重ね合わせの作業場の応答 {
    一覧とダイアログの操作::ダイアログを閉じる.応答にする()
}

fn 名前の入力を書き換えた(文字列: String) -> 重ね合わせの作業場の応答 {
    一覧とダイアログの操作::名前の入力を書き換える(文字列).応答にする()
}
