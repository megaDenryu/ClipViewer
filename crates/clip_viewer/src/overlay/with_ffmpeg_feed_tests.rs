//! 重ね合わせの作業場の映像の供給の配線の結合試験。作業場の口(重ね合わせを開く → フレームを進める)から、開いている重ね合わせの映像の供給を通って
//! 行のテクスチャにコマが載ることと、控える前に行ごとの流し読みを閉じ、載せたコマはテクスチャに残すことを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{正規化した動画パス, 行の番号};
use video_source::{バイト数, メモリの上限, 動画の読み手};

use super::feed::重ね合わせの映像の供給を作れたか;
use super::sound_test_support::装置の無い作業場;
use super::test_support::{置き方, 置き方を並べた重ね合わせ};
use super::workspace::重ね合わせの作業場;
use crate::video_feed::with_ffmpeg_support::{
    実行ファイルを探す, 成り立つまで待つ, 試験動画を作る,
};
use clip_domain::音量;

/// 試験動画のファイル。落とすとファイルを消す。
struct 試験動画のファイル(正規化した動画パス);

impl Drop for 試験動画のファイル {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(self.0.文字列());
    }
}

/// 行の番号の行に載ったコマの番号と、その行の流し読みを開いているか。
fn 載せたコマの番号と流し読みを開いているか(
    作業場: &重ね合わせの作業場,
    番号: usize,
) -> (Option<u32>, bool) {
    let 映像 = 作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .映像の供給を作れたか();
    let 重ね合わせの映像の供給を作れたか::作れた(供給) = 映像 else {
        panic!("供給を作れる");
    };
    let 行 = 供給
        .行のコマの載せ先(行の番号::番号から作成する(番号))
        .expect("行の数の上限の内");
    (
        行.テクスチャ()
            .載せたコマ()
            .map(|載せたコマ| 載せたコマ.番号.値()),
        行.流し読みを開いているか(),
    )
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 作業場の口から行のテクスチャにコマが載り_控える前に流し読みを閉じて載せたコマは残す() {
    let 実行ファイル = 実行ファイルを探す();
    let ファイル = 試験動画のファイル(試験動画を作る(&実行ファイル, "作業場の映像の供給"));
    let 重ね合わせ = 置き方を並べた重ね合わせ(
        ファイル.0.clone(),
        4.0,
        &[&[置き方 {
            動画上の区間の開始: 0.5,
            動画上の区間の終了: 1.5,
            始まり: 0.0,
        }]],
    );
    let mut 作業場 = 装置の無い作業場();
    作業場.倉庫の上限で重ね合わせを開く(
        重ね合わせ,
        Some(&動画の読み手::作成する(実行ファイル)),
        メモリの上限::作成する(バイト数::作成する(1)),
    );
    成り立つまで待つ(
        "止まった0秒の位置で0.5秒のコマが流し読みから載ること",
        || {
            作業場.フレームを進める(Instant::now(), 音量::起動したときの音量);
            matches!(
                載せたコマの番号と流し読みを開いているか(&作業場, 0),
                (Some(15), true)
            )
        },
    );
    作業場.控える前に再生を止める();
    assert_eq!(
        載せたコマの番号と流し読みを開いているか(&作業場, 0),
        (Some(15), false),
        "流し読みを閉じ、テクスチャには前のコマが残る"
    );
}
