//! 重ね合わせの作業場の音の結合試験。音付きの試験動画の2つの区間を2つの行に置き、作業場の口(重ね合わせを開く → フレームを進める → 行ごとの再生の指示)から、
//! 行ごとに置いたクリップの区間の音を2本目の流れの周波数で溜めて溜めた音を出どころにし、置いたクリップの音量に全体の鳴らす音量を掛けた音量で、
//! 消音した行は無音で鳴らす指示になり、音量のつまみの値を変えると鳴らす大きさが変わることと、2本目の流れが途中で使えなくなったら行の音を鳴らさないことを確かめる。FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use audio_output::{再生の様子, 行ごとの再生の指示, 音声出力のエラー};
use audio_pcm::サンプリング周波数;
use clip_domain::{動画上の区間, 時刻, 置いたクリップの音の変更, 音量};
use eframe::egui;
use video_source::{メモリの上限, 動画の読み手};

use super::command::重ね合わせの操作;
use super::sound_test_support::{
    溜めた音か, 置いたクリップの識別子を作る, 行の指示を取り出す, 音の出力で作業場を作る,
    音付きの試験動画,
};
use super::state::重ね合わせの音の出力の状況;
use super::test_support::{置き方, 置き方を並べた重ね合わせ};
use crate::video_feed::with_ffmpeg_support::{
    実行ファイルを探す, 成り立つまで待つ
};

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 行ごとに区間の音を溜めて_置いたクリップの音量につまみを掛けた音量で_消音した行は無音で鳴らす() {
    let 動画 = 音付きの試験動画::作る("行ごとの音");
    let 置き方 = |開始, 終了| 置き方 {
        動画上の区間の開始: 開始,
        動画上の区間の終了: 終了,
        始まり: 0.0,
    };
    let 重ね合わせ = 置き方を並べた重ね合わせ(
        動画.0.clone(),
        4.0,
        &[&[置き方(0.5, 1.5)], &[置き方(2.0, 3.5)]],
    );
    let 周波数 = サンプリング周波数::作成する(48_000).expect("周波数");
    let mut 作業場 = 音の出力で作業場を作る(
        egui::Context::default(),
        重ね合わせの音の出力の状況::使える(周波数),
    );
    作業場.倉庫の上限で重ね合わせを開く(
        重ね合わせ,
        Some(&動画の読み手::作成する(実行ファイルを探す())),
        メモリの上限::既定,
    );
    作業場.操作を適用する(重ね合わせの操作::置いたクリップの音を変える {
        識別子: 置いたクリップの識別子を作る("置-1"),
        変更: 置いたクリップの音の変更::音量を選ぶ(音量::範囲へ収めて作る(0.5)),
    });
    作業場.操作を適用する(重ね合わせの操作::置いたクリップの音を変える {
        識別子: 置いたクリップの識別子を作る("置-2"),
        変更: 置いたクリップの音の変更::消音を設定する(true),
    });
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    let つまみ = 音量::範囲へ収めて作る(0.5);
    let mut 指示 = 行ごとの再生の指示::黙る(Instant::now());
    成り立つまで待つ(
        "両方の行が区間の溜めた音を出どころにすること",
        || {
            指示 = 作業場.フレームを進める(Instant::now(), つまみ);
            let 奥 = 行の指示を取り出す(&mut 指示.clone(), 0);
            let 手前 = 行の指示を取り出す(&mut 指示.clone(), 1);
            溜めた音か(&奥) && 溜めた音か(&手前)
        },
    );
    let 奥 = 行の指示を取り出す(&mut 指示, 0);
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    let 奥の区間 = 動画上の区間::作成する(秒(0.5), 秒(1.5)).expect("区間");
    assert_eq!(奥.様子, 再生の様子::再生している);
    assert_eq!(
        奥.区間.as_ref().map(|区間| 区間.範囲),
        Some(周波数.区間の範囲(&奥の区間)),
        "2本目の流れの周波数で区間の範囲を求める"
    );
    assert_eq!(奥.音量, 音量::範囲へ収めて作る(0.25), "0.5 × つまみ 0.5");
    assert_eq!(
        行の指示を取り出す(&mut 指示, 1).音量,
        音量::無音,
        "消音した行は無音"
    );
    assert!(
        行の指示を取り出す(&mut 指示, 2).区間.is_none(),
        "重ね合わせに無い行は黙る"
    );
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    let mut 止めた後 = 作業場.フレームを進める(Instant::now(), 音量::元の大きさ);
    assert_eq!(
        行の指示を取り出す(&mut 止めた後, 0).音量,
        音量::範囲へ収めて作る(0.5),
        "音量のつまみの値を変えると、同じ置いたクリップの音量 0.5 にその値(1)を掛けた大きさになる"
    );
    let mut 全体を消音した = 作業場.フレームを進める(Instant::now(), 音量::無音);
    assert_eq!(
        行の指示を取り出す(&mut 全体を消音した, 0).音量,
        音量::無音,
        "全体を消音した(配線が渡す鳴らす音量が無音の)とき、行の音量は0になる"
    );
    作業場.音の出力が使えなくなったことを知らせる(音声出力のエラー::装置が無い);
    let mut 使えなくなった後 = 作業場.フレームを進める(Instant::now(), 音量::元の大きさ);
    assert!(
        行の指示を取り出す(&mut 使えなくなった後, 0).区間.is_none(),
        "2本目の流れが使えなくなったら、音の倉庫を捨てて行の音を鳴らさない"
    );
}
