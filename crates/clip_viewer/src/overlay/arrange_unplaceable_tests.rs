//! 今のスタックから並べられないときの試験。どのクリップも置けないときは重ね合わせを開かずに報告し、動画を開いていないときは並べないことと、
//! 開いている間に並べ直してどれも置けないときは、開いている重ね合わせを残して報告だけを差し替えることを、作業場のメソッドから確かめる。
#![allow(clippy::expect_used)]

use clip_domain::クリップスタック;

use super::arrange_test_support::{クリップ, 値, 練習の動画};
use super::sound_test_support::装置の無い作業場を作る;
use super::state::今のスタックの値;

#[test]
fn どのクリップも置けないときは重ね合わせを開かずに報告し_動画を開いていないときは並べない() {
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("甲", 0.0, 5.0)]).expect("スタック");
    let パス = 練習の動画();
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.今のスタックから並べる(値(&スタック, &パス, 3.0), None);
    assert!(作業場.状態().開いている重ね合わせ().is_none());
    assert_eq!(
        作業場.状態().置かなかったクリップの報告の文(),
        ["「甲」を置かなかった: 置けない(区間の終わり(5秒)が動画の長さ(3秒)より後ろにある)"]
    );
    作業場.今のスタックから並べる(
        今のスタックの値 {
            開いている動画: None,
            ..値(&スタック, &パス, 3.0)
        },
        None,
    );
    let 知らせ: Vec<String> = 作業場
        .状態()
        .並べる知らせ()
        .iter()
        .map(|通知| format!("{通知:?}"))
        .collect();
    assert_eq!(知らせ.len(), 2, "{知らせ:?}");
    assert!(
        知らせ[0].contains("どれも置けないため、並べられない"),
        "{知らせ:?}"
    );
    assert!(
        知らせ[1].contains("動画を開いていないため、並べられない"),
        "{知らせ:?}"
    );
}

#[test]
fn 開いている間に並べ直してどれも置けないときは_開いている重ね合わせを残して報告だけを差し替える() {
    let 置ける =
        クリップスタック::一覧から作成する(vec![クリップ("甲", 0.0, 1.0)]).expect("スタック");
    let 置けない =
        クリップスタック::一覧から作成する(vec![クリップ("乙", 0.0, 5.0)]).expect("スタック");
    let パス = 練習の動画();
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.今のスタックから並べる(値(&置ける, &パス, 3.0), None);
    let 並べた後の長さ = 作業場.状態().再生の位置と長さ();
    作業場.今のスタックから並べる(値(&置けない, &パス, 3.0), None);
    assert_eq!(作業場.状態().再生の位置と長さ(), 並べた後の長さ);
    assert_eq!(
        作業場.状態().置かなかったクリップの報告の文(),
        ["「乙」を置かなかった: 置けない(区間の終わり(5秒)が動画の長さ(3秒)より後ろにある)"]
    );
}
