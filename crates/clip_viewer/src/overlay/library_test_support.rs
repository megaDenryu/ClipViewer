//! 重ね合わせのライブラリの試験の道具。一時フォルダを置き場所にしたライブラリの錠を試して、書ける(または読むだけの)重ね合わせのライブラリを持つ作業場を作ることと、
//! フォルダにある重ね合わせを読むことを受け持つ。作業場へ操作を当てる道具は `library_test_ops.rs` に置く。利用者の %APPDATA% と %LOCALAPPDATA% の本物のフォルダを使わない。
#![allow(clippy::expect_used)]

use std::path::PathBuf;

use clip_domain::{ライブラリの重ね合わせ, 重ね合わせの識別子};
use clip_library::{
    スタックのライブラリ, ライブラリのフォルダ, 裏で動く重ね合わせのライブラリ,
    重ね合わせのライブラリ, 重ね合わせの一覧の項目, 錠を試したライブラリの組,
    錠を試した重ね合わせのライブラリ,
};
use eframe::egui;
use thumbnail_cache::{
    キャッシュの容量, キャッシュの時計, キャッシュの置き場所, サムネイルのキャッシュ,
};

use super::sound_test_support::装置の無い音の出力を作る;
use super::state::library::重ね合わせのライブラリの状態;
use super::workspace::重ね合わせの作業場;

/// 一時のライブラリとは、試験ごとに重ならない一時フォルダのライブラリのフォルダのことである。落とすとフォルダを消す。
pub(crate) struct 一時のライブラリ {
    フォルダ: PathBuf,
}

impl 一時のライブラリ {
    pub(crate) fn 作る(名前: &str) -> Self {
        let フォルダ = std::env::temp_dir().join(format!(
            "clip_viewer_重ね合わせの保存_{名前}_{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&フォルダ);
        Self { フォルダ }
    }

    fn ライブラリのフォルダ(&self) -> ライブラリのフォルダ {
        ライブラリのフォルダ::作成する(self.フォルダ.join("library"))
    }

    /// スタックのライブラリの錠と `overlays` の錠を試す。先に試した組が錠を持っている間に試すと、読むだけの組になる。
    pub(crate) fn 錠を試す(&self) -> 錠を試したライブラリの組 {
        スタックのライブラリ::作成する(self.ライブラリのフォルダ())
            .錠を試す()
            .重ね合わせの錠も試す()
    }

    /// 錠を試した重ね合わせのライブラリで、重ね合わせを開いていない作業場を作る。サムネイルのキャッシュは使わない。
    /// 組のスタックの側(スタックのライブラリの錠)は、呼び手が試験の間持ち続ける。
    pub(crate) fn 作業場を作る(
        &self,
        重ね合わせ: 錠を試した重ね合わせのライブラリ,
    ) -> 重ね合わせの作業場 {
        let 本体 = egui::Context::default();
        let キャッシュ = サムネイルのキャッシュ::作成する(
            キャッシュの置き場所::使わない,
            キャッシュの容量::既定,
            キャッシュの時計::実時間(),
        );
        let ライブラリ = 重ね合わせのライブラリの状態::作成する(
            Some(
                裏で動く重ね合わせのライブラリ::錠を試した後で起動する(
                    重ね合わせ,
                ),
            ),
            本体.clone(),
            キャッシュ,
        );
        重ね合わせの作業場::開いていない作業場(
            本体,
            装置の無い音の出力を作る(),
            ライブラリ,
        )
    }

    /// 識別子の重ね合わせのファイルのパス。試験でファイルを排他で開き、書き込みを失敗させるために使う。
    pub(crate) fn 重ね合わせのファイルのパス(
        &self,
        識別子: &重ね合わせの識別子,
    ) -> PathBuf {
        self.ライブラリのフォルダ()
            .重ね合わせのフォルダ()
            .パス()
            .join(format!("{識別子}.json"))
    }

    /// フォルダにある重ね合わせを、フォルダを読んだ順に読む。読めないファイルは含めない。
    pub(crate) fn 保存した重ね合わせ(&self) -> Vec<ライブラリの重ね合わせ> {
        重ね合わせのライブラリ::作成する(
            self.ライブラリのフォルダ().重ね合わせのフォルダ(),
        )
        .一覧を作る()
        .expect("一覧を作れる")
        .項目
        .into_iter()
        .filter_map(|項目| match 項目 {
            重ね合わせの一覧の項目::読めた(読めた) => Some(読めた.重ね合わせ),
            重ね合わせの一覧の項目::読めない(_) => None,
        })
        .collect()
    }
}

impl Drop for 一時のライブラリ {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.フォルダ);
    }
}
