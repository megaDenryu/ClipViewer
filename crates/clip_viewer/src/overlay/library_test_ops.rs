//! 重ね合わせのライブラリの試験で、作業場へ操作を当てる道具。ライブラリの操作を借りる値と一緒に当てることと、名前を付けて登録することと、
//! 書き込みと走査を待って知らせを受け取ることを受け持つ。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{アスペクト比設定, 重ねる画面の縦横比};

use super::arrange_test_support::{値, 練習の動画};
use super::command::{
    一覧とダイアログの操作, 置き方の操作, 重ね合わせのライブラリの操作, 重ね合わせの操作,
};
use super::workspace::{
    今のスタックの値と動画の読み手, 重ね合わせの作業場
};

/// 重ね合わせのライブラリの操作を、空のスタックと試験の動画を開いている今のスタックの値を借りて当てる。
pub(crate) fn ライブラリの操作を当てる(
    作業場: &mut 重ね合わせの作業場,
    操作: 重ね合わせのライブラリの操作,
) {
    let スタック = clip_domain::クリップスタック::default();
    let パス = 練習の動画();
    作業場.ライブラリの操作を当てる(
        操作,
        今のスタックの値と動画の読み手 {
            今のスタック: 値(&スタック, &パス, 60.0),
            読み手: None,
        },
    );
}

/// 開いている重ね合わせを、名前を入力して登録する。
pub(crate) fn 名前を付けて登録する(
    作業場: &mut 重ね合わせの作業場, 名前: &str
) {
    for 操作 in [
        一覧とダイアログの操作::登録のダイアログを開く,
        一覧とダイアログの操作::名前の入力を書き換える(名前.to_string()),
    ] {
        ライブラリの操作を当てる(
            作業場,
            重ね合わせのライブラリの操作::一覧とダイアログ(操作),
        );
    }
    ライブラリの操作を当てる(作業場, 重ね合わせのライブラリの操作::登録する);
}

/// 頼んだ書き込みと走査を終えるまで待ってから、その時刻で1フレーム分のライブラリの手順を進め、届いた知らせを当てる。
pub(crate) fn 書き終えるまで待って進める(
    作業場: &mut 重ね合わせの作業場,
    今: Instant,
) {
    作業場.状態().ライブラリ().書き込みと走査を終えるまで待つ();
    作業場.ライブラリとサムネイルを進める(今, None);
}

/// 正方形の重ねる画面の縦横比。
pub(crate) fn 正方形() -> 重ねる画面の縦横比 {
    重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比")
}

/// 重ねる画面の縦横比を正方形に変える(置き方を手で直す)。
pub(crate) fn 縦横比を正方形にする(作業場: &mut 重ね合わせの作業場) {
    作業場.操作を適用する(重ね合わせの操作::置き方(
        置き方の操作::重ねる画面の縦横比を選ぶ(正方形()),
    ));
}
