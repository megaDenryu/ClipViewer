//! 実時間の置いたクリップと重ね合わせの識別子発行元の試験。続けて発行した識別子が重ならないことを確かめる(スタックからの読み替えは同じミリ秒に最大8件を発行する)。

use std::collections::HashSet;

use clip_domain::置いたクリップの識別子の発行元;

use super::placed_id_issuer::実時間の置いたクリップと重ね合わせの識別子発行元;

#[test]
fn 実時間の発行元が同じミリ秒に続けて発行した識別子は重ならない() {
    let mut 発行元 = 実時間の置いたクリップと重ね合わせの識別子発行元::時刻から番号の始まりを取って作る();
    let 識別子の集まり: HashSet<String> = (0..10_000)
        .map(|_| 発行元.新しい識別子を発行する().文字列().to_string())
        .collect();
    assert_eq!(識別子の集まり.len(), 10_000);
}
