//! タイムラインの行を選ぶ試験。行を選ぶと置いたクリップの選びが外れ、置いたクリップを選ぶと行の選びが外れることと、無い行は選ばないことを、
//! 作業場の口から確かめる。選びは重ねる画面の枠・タイムラインの塊・サイドバーで共通である。参照: _doc/設計/同時再生.md 2-6
#![allow(clippy::expect_used)]

use clip_domain::行の番号;

use super::command::{タイムラインの操作, 置き方の操作};
use super::placement_test_support::{
    置いたクリップの識別子を作る, 置き方の操作を当てる
};
use super::timeline_test_support::{
    タイムラインの操作を当てる, 二行を開いた作業場, 選んでいる行
};
use super::workspace::重ね合わせの作業場;

fn 選んでいる置いたクリップ(作業場: &重ね合わせの作業場) -> Option<String> {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .選んでいる置いたクリップ()
        .map(|置いた| 置いた.識別子().文字列().to_string())
}

fn 行(番号: usize) -> 行の番号 {
    行の番号::番号から作成する(番号)
}

fn 選んでいる行の番号(作業場: &重ね合わせの作業場) -> Option<usize> {
    選んでいる行(作業場).map(|様子| 様子.行.番号())
}

#[test]
fn 行を選ぶと置いたクリップの選びが外れ_置いたクリップを選ぶと行の選びが外れる() {
    let mut 作業場 = 二行を開いた作業場();
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを選ぶ(置いたクリップの識別子を作る("置-2")),
    );
    タイムラインの操作を当てる(&mut 作業場, タイムラインの操作::行を選ぶ(行(0)));
    assert_eq!(選んでいる置いたクリップ(&作業場), None);
    assert_eq!(選んでいる行の番号(&作業場), Some(0));
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを選ぶ(置いたクリップの識別子を作る("置-3")),
    );
    assert_eq!(選んでいる行(&作業場), None);
    assert_eq!(選んでいる置いたクリップ(&作業場).as_deref(), Some("置-3"));
    タイムラインの操作を当てる(&mut 作業場, タイムラインの操作::行を選ぶ(行(5)));
    assert_eq!(
        選んでいる置いたクリップ(&作業場).as_deref(),
        Some("置-3"),
        "無い行は選ばない"
    );
}
