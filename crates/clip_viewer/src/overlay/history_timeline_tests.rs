//! タイムラインの編集の取り消しの試験。塊のドラッグの確定と行の追加を取り消すと元の行と始まりの時刻に戻り、重ね合わせの長さが縮んだら
//! 再生の位置を長さへ収めることを、作業場の口から確かめる。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{重ね合わせ上の秒, 音量};

use super::command::{
    タイムラインの操作, 塊の操作, 編集の履歴の操作, 重ね合わせの操作
};
use super::state::grab::位置の線の段階;
use super::timeline_test_support::{
    タイムラインの操作を当てる, 二行を開いた作業場, 塊の動き, 塊の操作を当てる, 塊を掴む,
    置いてある行と始まり,
};
use super::workspace::重ね合わせの作業場;

fn 取り消す(作業場: &mut 重ね合わせの作業場) {
    作業場.操作を適用する(重ね合わせの操作::編集の履歴(
        編集の履歴の操作::編集を取り消す,
    ));
}

fn 一フレーム進める(作業場: &mut 重ね合わせの作業場) {
    let _ = 作業場.フレームを進める(Instant::now(), 音量::範囲へ収めて作る(1.0));
}

fn 位置と長さ(作業場: &重ね合わせの作業場) -> (f64, f64) {
    let (位置, 長さ) = 作業場.状態().再生の位置と長さ().expect("開いている");
    (位置.時刻().秒数(), 長さ.秒数())
}

#[test]
fn 塊のドラッグの確定を取り消すと元の始まりに戻り_縮んだ長さへ再生の位置を収める() {
    let mut 作業場 = 二行を開いた作業場();
    塊を掴む(&mut 作業場, "置-3");
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-3", 4.0, 0)));
    assert_eq!(置いてある行と始まり(&作業場, "置-3"), (1, 7.0));
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::再生の位置を動かす(
            位置の線の段階::放した,
            重ね合わせ上の秒::作成する(7.5).expect("時刻"),
        ),
    );
    一フレーム進める(&mut 作業場);
    assert_eq!(位置と長さ(&作業場), (7.5, 8.0));
    取り消す(&mut 作業場);
    assert_eq!(置いてある行と始まり(&作業場, "置-3"), (1, 3.0));
    assert_eq!(
        位置と長さ(&作業場),
        (4.0, 4.0),
        "長さより後ろの位置は長さで止める"
    );
}

#[test]
fn 行を足したのを取り消すと行の数が戻り_選んでいた足した行の選びは外れる() {
    let mut 作業場 = 二行を開いた作業場();
    タイムラインの操作を当てる(&mut 作業場, タイムラインの操作::空の行を手前に足す);
    let 行の数 = |作業場: &重ね合わせの作業場| {
        作業場
            .状態()
            .開いている重ね合わせ()
            .expect("開いている")
            .重ね合わせ()
            .行の並び()
            .行の数()
    };
    assert_eq!(行の数(&作業場), 3);
    取り消す(&mut 作業場);
    assert_eq!(行の数(&作業場), 2);
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert!(開いている.選んでいる行の番号と空の行かの組().is_none());
}
