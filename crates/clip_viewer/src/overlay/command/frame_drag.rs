//! 映す矩形の枠の操作の語彙と、その状態への適用。重ねる画面の上の枠のドラッグの段階(掴み始めた・動かしている・放した・掴んだ枠が無くなった)を、
//! 開いている重ね合わせの映す矩形のドラッグへ当てる。参照: _doc/設計/同時再生.md 2-4

use clip_domain::{置いたクリップの識別子, 重ね合わせの操作エラー};

use crate::overlay::state::placement::映す矩形のドラッグの動き;
use crate::overlay::state::重ね合わせの作業場の状態;

/// 映す矩形の枠の操作とは、重ねる画面の上の映す矩形の枠のドラッグの段階ごとの操作の区別のことである。移動量は百分率へ直してある。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 映す矩形の枠の操作 {
    掴み始めた(置いたクリップの識別子),
    動かしている(映す矩形のドラッグの動き),
    放した(映す矩形のドラッグの動き),
    掴んだ枠が無くなった(置いたクリップの識別子),
    移動量が数でない,
}

impl 重ね合わせの作業場の状態 {
    /// 映す矩形の枠の操作を、開いている重ね合わせの映す矩形のドラッグへ当てた結果。開いていないときと移動量が数でないときは無い(数でないことは知らせる)。
    pub(super) fn 映す矩形の枠の操作を適用する(
        &mut self,
        操作: 映す矩形の枠の操作,
    ) -> Option<Result<(), 重ね合わせの操作エラー>> {
        if 操作 == 映す矩形の枠の操作::移動量が数でない {
            self.知らせ
                .出す("映す矩形の枠の移動量が数でない(到達したらバグ)");
            return None;
        }
        let 開いている = self.開き方.開いている重ね合わせを書き換える()?;
        Some(match 操作 {
            映す矩形の枠の操作::掴み始めた(識別子) => {
                開いている.映す矩形のドラッグを始める(&識別子);
                Ok(())
            }
            映す矩形の枠の操作::動かしている(動き) => {
                開いている.映す矩形のドラッグを動かす(&動き);
                Ok(())
            }
            映す矩形の枠の操作::放した(動き) => {
                開いている.映す矩形のドラッグを放す(&動き)
            }
            映す矩形の枠の操作::掴んだ枠が無くなった(識別子) => {
                開いている.映す矩形のドラッグを閉じる(&識別子);
                Ok(())
            }
            映す矩形の枠の操作::移動量が数でない => Ok(()),
        })
    }
}
