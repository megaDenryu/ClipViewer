//! タイムラインの操作の語彙と、その状態への適用。塊のドラッグの段階(掴み始めた・動かしている・放した・掴んだ塊が無くなった)と、
//! 行を選ぶ・選んでいる空の行を消す・空の行を手前に足す・時間の軸の位置の線のドラッグで再生の位置を動かす操作を、開いている重ね合わせへ当てる。
//! 塊を選ぶことは置き方の操作の `置いたクリップを選ぶ` を使い、重ねる画面とサイドバーと同じ選びにする。
//! 拒まれたときの知らせの文は、場面ごとに `timeline_notice.rs` が画面と同じ「上から N 番目」の数え方で作る。参照: _doc/設計/同時再生.md 2-6

use clip_domain::{
    置いたクリップの識別子, 行の番号, 重ね合わせの操作エラー, 重ね合わせ上の秒
};

use super::timeline_notice::{塊を動かせない文を作る, 行を消せない文を作る};
use super::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::overlay::state::grab::位置の線の段階;
use crate::overlay::state::timeline::塊のドラッグの動き;
use crate::overlay::state::{重ね合わせの作業場の状態, 開いている重ね合わせ};

/// 塊の操作とは、タイムラインの塊のドラッグの段階ごとの操作の区別のことである。移動量は時刻をずらす量と行の差へ直してある。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 塊の操作 {
    掴み始めた(置いたクリップの識別子),
    動かしている(塊のドラッグの動き),
    放した(塊のドラッグの動き),
    掴んだ塊が無くなった(置いたクリップの識別子),
}

/// タイムラインの操作とは、重ね合わせの作業場の下のタイムラインで、開いている重ね合わせへ当てる操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum タイムラインの操作 {
    塊(塊の操作),
    行を選ぶ(行の番号),
    選んでいる空の行を消す,
    空の行を手前に足す,
    再生の位置を動かす(位置の線の段階, 重ね合わせ上の秒),
}

impl タイムラインの操作 {
    /// このタイムラインの操作を、重ね合わせの作業場の中の操作の応答にする。画面がタイムラインの操作を発するときに使う。
    pub(crate) fn 応答にする(self) -> 重ね合わせの作業場の応答 {
        重ね合わせの作業場の応答::操作(重ね合わせの操作::タイムライン(self))
    }
}

impl 重ね合わせの作業場の状態 {
    /// タイムラインの操作を状態へ適用する。重ね合わせを開いていない間は何もしない。拒まれたら理由を知らせる。
    pub(super) fn タイムラインの操作を適用する(
        &mut self, 操作: タイムラインの操作
    ) {
        let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
        else {
            return;
        };
        let 拒んだ理由の文 = match 操作 {
            タイムラインの操作::塊(塊の操作) => {
                let 結果 = 塊の操作を当てる(開いている, 塊の操作);
                結果.map_err(|理由| {
                    塊を動かせない文を作る(開いている.重ね合わせ().行の並び(), &理由)
                })
            }
            タイムラインの操作::行を選ぶ(行) => {
                開いている.行を選ぶ(行);
                Ok(())
            }
            タイムラインの操作::選んでいる空の行を消す => {
                let 結果 = 開いている.選んでいる空の行を消す();
                結果.map_err(|理由| {
                    行を消せない文を作る(開いている.重ね合わせ().行の並び(), &理由)
                })
            }
            タイムラインの操作::空の行を手前に足す => 開いている
                .空の行を手前に足す()
                .map_err(|理由| 理由.to_string()),
            タイムラインの操作::再生の位置を動かす(段階, 時刻) => {
                開いている.位置の線のドラッグを当てる(段階, 時刻);
                Ok(())
            }
        };
        if let Err(文) = 拒んだ理由の文 {
            self.知らせ.出す(文);
        }
    }
}

// 塊のドラッグの段階を、開いている重ね合わせの塊のドラッグへ当てる。
fn 塊の操作を当てる(
    開いている: &mut 開いている重ね合わせ,
    操作: 塊の操作,
) -> Result<(), 重ね合わせの操作エラー> {
    match 操作 {
        塊の操作::掴み始めた(識別子) => {
            開いている.塊のドラッグを始める(&識別子)
        }
        塊の操作::動かしている(動き) => {
            開いている.塊のドラッグを動かす(&動き)
        }
        塊の操作::放した(動き) => return 開いている.塊のドラッグを放す(&動き),
        塊の操作::掴んだ塊が無くなった(識別子) => {
            開いている.塊のドラッグを閉じる(&識別子)
        }
    }
    Ok(())
}
