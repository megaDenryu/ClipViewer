//! 編集の履歴の操作の語彙と、その状態への適用。開いている重ね合わせの最後の編集を取り消すことと、取り消した編集をやり直すこと。
//! ヘッダーの「取り消す」「やり直す」と、重ね合わせの作業場のキー(Ctrl+Z・Ctrl+Y)が発する。参照: _doc/設計/同時再生.md 2-3・2-6・2-8

use super::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::overlay::state::重ね合わせの作業場の状態;

/// 編集の履歴の操作とは、重ね合わせの作業場の中で、開いている重ね合わせの編集を取り消すかやり直すかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 編集の履歴の操作 {
    編集を取り消す,
    編集をやり直す,
}

impl 編集の履歴の操作 {
    /// この編集の履歴の操作を、重ね合わせの作業場の中の操作の応答にする。画面とキーの表が発するときに使う。
    pub(crate) const fn 応答にする(self) -> 重ね合わせの作業場の応答 {
        重ね合わせの作業場の応答::操作(重ね合わせの操作::編集の履歴(self))
    }
}

impl 重ね合わせの作業場の状態 {
    /// 編集の履歴の操作を状態へ適用する。重ね合わせを開いていない間は何もしない。
    pub(crate) fn 編集の履歴の操作を適用する(
        &mut self, 操作: 編集の履歴の操作
    ) {
        let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
        else {
            return;
        };
        match 操作 {
            編集の履歴の操作::編集を取り消す => 開いている.編集を取り消す(),
            編集の履歴の操作::編集をやり直す => 開いている.編集をやり直す(),
        }
    }
}
