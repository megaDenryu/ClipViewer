//! タイムラインの操作が拒まれたときの知らせの文。塊を動かす場面と空の行を消す場面ごとに、拒んだ理由を場面に合った文へ言い換える。
//! 行を指す理由は、内部の番号(奥から0始まり)でなく、画面と同じ「上から N 番目」(`タイムラインの行の並び::上から数えた順番`)で書く。
//! 参照: _doc/設計/同時再生.md 2-6

use clip_domain::{タイムラインの行の並び, 重ね合わせの操作エラー};

/// 塊を放して動かす操作が拒まれたときの文。
pub(super) fn 塊を動かせない文を作る(
    行の並び: &タイムラインの行の並び,
    理由: &重ね合わせの操作エラー,
) -> String {
    match 理由 {
        重ね合わせの操作エラー::時間が重なる { 行, .. } => {
            match 行の並び.上から数えた順番(*行) {
                Some(順番) => format!(
                    "動かす先の行({順番})で、ほかの置いたクリップと時間が重なるため動かせない"
                ),
                None => "動かす先の行が無いため動かせない".to_string(),
            }
        }
        重ね合わせの操作エラー::行の番号が範囲の外 { .. } => {
            "動かす先の行が無いため動かせない".to_string()
        }
        重ね合わせの操作エラー::置いたクリップが見つからない(_) => {
            "動かそうとした置いたクリップが重ね合わせに無いため動かせない".to_string()
        }
        _ => 理由.to_string(),
    }
}

/// 選んでいる空の行を消す操作が拒まれたときの文。
pub(super) fn 行を消せない文を作る(
    行の並び: &タイムラインの行の並び,
    理由: &重ね合わせの操作エラー,
) -> String {
    match 理由 {
        重ね合わせの操作エラー::行が空でない { 行 } => {
            match 行の並び.上から数えた順番(*行) {
                Some(順番) => format!(
                    "選んでいる行({順番})には置いたクリップがあるため消せない(空の行だけを消せる)"
                ),
                None => "選んでいる行が無い".to_string(),
            }
        }
        重ね合わせの操作エラー::行の番号が範囲の外 { .. } => {
            "選んでいる行が無い".to_string()
        }
        _ => 理由.to_string(),
    }
}
