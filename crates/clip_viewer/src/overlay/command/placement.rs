//! 置き方の編集の操作の語彙と、その状態への適用。置いたクリップを選ぶ・選びを外す・映す矩形の枠のドラッグ・重ねる画面の縦横比を選ぶ・
//! 置いたクリップを取り除く・並べ直す前の確かめを出す・閉じる。重ね合わせの操作が拒まれたら、その理由を知らせる。参照: _doc/設計/同時再生.md 2-2・2-4・2-5

use clip_domain::{
    置いたクリップの識別子, 重ねる画面の縦横比, 重ね合わせの操作エラー
};

use crate::overlay::state::placement::映す矩形のドラッグの動き;
use crate::overlay::state::重ね合わせの作業場の状態;

/// 置き方の操作とは、重ね合わせの作業場の中で、開いている重ね合わせの置き方を選び・直す操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 置き方の操作 {
    置いたクリップを選ぶ(置いたクリップの識別子),
    選びを外す,
    映す矩形の枠(映す矩形の枠の操作),
    重ねる画面の縦横比を選ぶ(重ねる画面の縦横比),
    置いたクリップを取り除く(置いたクリップの識別子),
    並べ直す前の確かめを出す,
    並べ直す前の確かめを閉じる,
}

/// 映す矩形の枠の操作とは、重ねる画面の上の映す矩形の枠のドラッグの段階ごとの操作の区別のことである。移動量は百分率へ直してある。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 映す矩形の枠の操作 {
    掴み始めた(置いたクリップの識別子),
    動かしている(映す矩形のドラッグの動き),
    放した(映す矩形のドラッグの動き),
    掴んだ枠が無くなった(置いたクリップの識別子),
    移動量が数でない,
}

impl 重ね合わせの作業場の状態 {
    /// 置き方の操作を状態へ適用する。重ね合わせを開いていない間の、開いている重ね合わせへの操作は何もしない。
    pub(crate) fn 置き方の操作を適用する(&mut self, 操作: 置き方の操作) {
        let 結果 = match 操作 {
            置き方の操作::並べ直す前の確かめを出す => {
                self.並べ直す前の確かめを出す();
                None
            }
            置き方の操作::並べ直す前の確かめを閉じる => {
                self.並べ直す前の確かめを閉じる();
                None
            }
            置き方の操作::映す矩形の枠(枠の操作) => {
                self.映す矩形の枠の操作を適用する(枠の操作)
            }
            置き方の操作::置いたクリップを選ぶ(識別子) => self
                .開き方
                .開いている重ね合わせを書き換える()
                .map(|開いている| {
                    開いている.置いたクリップを選ぶ(&識別子);
                    Ok(())
                }),
            置き方の操作::選びを外す => self
                .開き方
                .開いている重ね合わせを書き換える()
                .map(|開いている| {
                    開いている.選びを外す();
                    Ok(())
                }),
            置き方の操作::重ねる画面の縦横比を選ぶ(縦横比) => self
                .開き方
                .開いている重ね合わせを書き換える()
                .map(|開いている| {
                    開いている.重ねる画面の縦横比を変える(縦横比);
                    Ok(())
                }),
            置き方の操作::置いたクリップを取り除く(識別子) => self
                .開き方
                .開いている重ね合わせを書き換える()
                .map(|開いている| 開いている.置いたクリップを取り除く(&識別子)),
        };
        self.拒まれたら知らせる(結果);
    }

    fn 映す矩形の枠の操作を適用する(
        &mut self,
        操作: 映す矩形の枠の操作,
    ) -> Option<Result<(), 重ね合わせの操作エラー>> {
        if 操作 == 映す矩形の枠の操作::移動量が数でない {
            self.知らせ
                .出す("映す矩形の枠の移動量が数でない(到達したらバグ)");
            return None;
        }
        let 開いている = self.開き方.開いている重ね合わせを書き換える()?;
        Some(match 操作 {
            映す矩形の枠の操作::掴み始めた(識別子) => {
                開いている.映す矩形のドラッグを始める(&識別子);
                Ok(())
            }
            映す矩形の枠の操作::動かしている(動き) => {
                開いている.映す矩形のドラッグを動かす(&動き);
                Ok(())
            }
            映す矩形の枠の操作::放した(動き) => {
                開いている.映す矩形のドラッグを放す(&動き)
            }
            映す矩形の枠の操作::掴んだ枠が無くなった(識別子) => {
                開いている.映す矩形のドラッグを閉じる(&識別子);
                Ok(())
            }
            映す矩形の枠の操作::移動量が数でない => Ok(()),
        })
    }
}
