//! 置き方の編集の操作の語彙と、その状態への適用。置いたクリップを選ぶ・選びを外す・映す矩形の枠のドラッグ・重ねる画面の縦横比を選ぶ・
//! 置いたクリップを取り除く。重ね合わせの操作が拒まれたら、その理由を知らせる。映す矩形の枠のドラッグの語彙と適用は `frame_drag.rs` に置く。参照: _doc/設計/同時再生.md 2-2・2-4・2-5

use clip_domain::{置いたクリップの識別子, 重ねる画面の縦横比};

use super::frame_drag::映す矩形の枠の操作;
use super::{重ね合わせの作業場の応答, 重ね合わせの操作};
use crate::overlay::state::重ね合わせの作業場の状態;

/// 置き方の操作とは、重ね合わせの作業場の中で、開いている重ね合わせの置き方を選び・直す操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 置き方の操作 {
    置いたクリップを選ぶ(置いたクリップの識別子),
    選びを外す,
    映す矩形の枠(映す矩形の枠の操作),
    重ねる画面の縦横比を選ぶ(重ねる画面の縦横比),
    置いたクリップを取り除く(置いたクリップの識別子),
}

impl 置き方の操作 {
    /// この置き方の操作を、重ね合わせの作業場の中の操作の応答にする。画面が置き方の操作を発するときに使う。
    pub(crate) fn 応答にする(self) -> 重ね合わせの作業場の応答 {
        重ね合わせの作業場の応答::操作(重ね合わせの操作::置き方(self))
    }
}

impl 重ね合わせの作業場の状態 {
    /// 置き方の操作を状態へ適用する。重ね合わせを開いていない間の、開いている重ね合わせへの操作は何もしない。
    pub(crate) fn 置き方の操作を適用する(&mut self, 操作: 置き方の操作) {
        let 結果 = match 操作 {
            置き方の操作::映す矩形の枠(枠の操作) => {
                self.映す矩形の枠の操作を適用する(枠の操作)
            }
            置き方の操作::置いたクリップを選ぶ(識別子) => self
                .開き方
                .開いている重ね合わせを書き換える()
                .map(|開いている| {
                    開いている.置いたクリップを選ぶ(&識別子);
                    Ok(())
                }),
            置き方の操作::選びを外す => self
                .開き方
                .開いている重ね合わせを書き換える()
                .map(|開いている| {
                    開いている.選びを外す();
                    Ok(())
                }),
            置き方の操作::重ねる画面の縦横比を選ぶ(縦横比) => self
                .開き方
                .開いている重ね合わせを書き換える()
                .map(|開いている| {
                    開いている.重ねる画面の縦横比を変える(縦横比);
                    Ok(())
                }),
            置き方の操作::置いたクリップを取り除く(識別子) => self
                .開き方
                .開いている重ね合わせを書き換える()
                .map(|開いている| 開いている.置いたクリップを取り除く(&識別子)),
        };
        self.拒まれたら知らせる(結果);
    }
}
