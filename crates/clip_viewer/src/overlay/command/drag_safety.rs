//! 重ね合わせの作業場のドラッグの安全網。応答を適用した後に主ボタンの様子を受け取り、放したを受け取れずに残った塊のドラッグと
//! 映す矩形のドラッグと時間の軸の位置の線のドラッグを、確定せずに捨てる(位置の線なら、動かした位置は残す)。同じ安全網が、主ボタンを押していないフレームごとに
//! 取り消しのまとめも区切る(つまみのドラッグを放した後の変化を、前のドラッグの変化とまとめないため。スタックの作業場の安全網と同じ)。スタックの作業場の `command/band_commit.rs` の安全網と同じ形であり、重ね合わせの作業場は
//! `crate::command` を使えないため、ここに置く。参照: _doc/設計/同時再生.md 2-6・3-2

use crate::overlay::state::重ね合わせの作業場の状態;
use crate::primary_button::主ボタンの様子;

impl 重ね合わせの作業場の状態 {
    /// 応答を適用した後に呼ぶ安全網。主ボタンを押していないのにドラッグが残っていたら(部品が放したを判定できずにドラッグが終わった等)、
    /// 仮の行き先と仮の矩形を確定せずに捨て、位置の線を掴んだままなら離す(流し読みの開き直しを控えたまま、音を黙らせたままにしない)。時間の行の並びは、放したことを判定できずにドラッグが終わったときに塊の操作を何も知らせないため、
    /// 捨てないとタイムラインの塊が仮の位置に描かれたままになる。放したフレームでは、放したの適用でドラッグが無くなっているので何もしない。
    pub(crate) fn 取り残されたドラッグを捨てる(
        &mut self, 主ボタン: 主ボタンの様子
    ) {
        if 主ボタン == 主ボタンの様子::押している {
            return;
        }
        if let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
        {
            開いている.取り残されたドラッグを捨てる();
            開いている.取り消しのまとめを区切る();
        }
    }
}
