//! 重ね合わせのライブラリの操作の語彙と、スタックの作業場の依存を使わない操作の状態への適用。ヘッダーと一覧とダイアログが発する。
//! 登録する・一覧から開く・重ね合わせを閉じる・確かめるダイアログで続けると決めることは、続ける操作(並べ直す・開く)がスタックの作業場から借りる値を使うため、
//! 重ね合わせの作業場(`overlay/workspace/library.rs`)が当てる。参照: _doc/設計/同時再生.md 2-7

use clip_domain::重ね合わせの識別子;

use super::重ね合わせの作業場の応答;
use crate::library_common::list::{並べ替え方, 見えている行の範囲};
use crate::overlay::state::library::重ね合わせのダイアログ;
use crate::overlay::state::重ね合わせの作業場の状態;

/// 重ね合わせのライブラリの操作とは、重ね合わせのライブラリについて重ね合わせの作業場の画面が発する操作の区別のことである。
/// 一覧とダイアログの操作は状態だけで当て、ほかは開いている重ね合わせとの関係を終えうる(続ける操作がスタックの作業場から借りる値を使う)ため作業場が当てる。
/// 識別子を持たない決定の操作(登録する・変更を捨てて続ける・登録してから続ける)は、開いているダイアログが持つ値を使う。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 重ね合わせのライブラリの操作 {
    一覧とダイアログ(一覧とダイアログの操作),
    登録する,
    開く(重ね合わせの識別子),
    重ね合わせを閉じる,
    変更を捨てて続ける,
    登録してから続ける,
}

/// 一覧とダイアログの操作とは、重ね合わせの一覧の見せ方とダイアログの入力を変える、状態だけで当てられる操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 一覧とダイアログの操作 {
    登録のダイアログを開く,
    名前の入力を書き換える(String),
    ダイアログを閉じる,
    読み直す,
    絞り込みを書き換える(String),
    並べ替えを選ぶ(並べ替え方),
    一覧の見えている行を知らせる(見えている行の範囲),
}

impl 重ね合わせのライブラリの操作 {
    /// この操作を、配線が受け取る応答にする。画面がライブラリの操作を発するときに使う。
    pub(crate) fn 応答にする(self) -> 重ね合わせの作業場の応答 {
        重ね合わせの作業場の応答::ライブラリ(self)
    }
}

impl 一覧とダイアログの操作 {
    /// この操作を、配線が受け取る応答にする。
    pub(crate) fn 応答にする(self) -> 重ね合わせの作業場の応答 {
        重ね合わせのライブラリの操作::一覧とダイアログ(self).応答にする()
    }
}

impl 重ね合わせの作業場の状態 {
    /// 一覧とダイアログの操作を状態へ当てる。
    pub(crate) fn 一覧とダイアログの操作を当てる(
        &mut self,
        操作: 一覧とダイアログの操作,
    ) {
        match 操作 {
            一覧とダイアログの操作::登録のダイアログを開く => {
                self.登録のダイアログを開く()
            }
            一覧とダイアログの操作::名前の入力を書き換える(文字列) => self
                .ライブラリのダイアログを書き換える()
                .名前の入力を書き換える(文字列),
            一覧とダイアログの操作::ダイアログを閉じる => {
                *self.ライブラリのダイアログを書き換える() =
                    重ね合わせのダイアログ::無し
            }
            一覧とダイアログの操作::読み直す => self.重ね合わせの一覧を読み直す(),
            一覧とダイアログの操作::絞り込みを書き換える(文字列) => {
                self.一覧の絞り込みを変える(文字列)
            }
            一覧とダイアログの操作::並べ替えを選ぶ(並べ替え) => {
                self.一覧の並べ替えを変える(並べ替え)
            }
            一覧とダイアログの操作::一覧の見えている行を知らせる(範囲) => {
                self.一覧の見えている行を置く(範囲)
            }
        }
    }
}
