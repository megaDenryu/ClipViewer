//! タイムラインの操作が拒まれたときの知らせの文の試験。どの理由も、内部の番号でなく画面と同じ「上から N 番目」で、場面に合った文にすることを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{行の番号, 重ね合わせの操作エラー};

use super::timeline_notice::{塊を動かせない文を作る, 行を消せない文を作る};
use crate::overlay::placement_test_support::置いたクリップの識別子を作る;
use crate::overlay::timeline_test_support::二行を開いた作業場;

#[test]
fn 拒んだ理由を場面に合った文と上から数えた順番で書く() {
    let 作業場 = 二行を開いた作業場();
    let 行の並び = 作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ね合わせ()
        .行の並び()
        .clone();
    let 行 = 行の番号::番号から作成する;
    let 範囲の外 = 重ね合わせの操作エラー::行の番号が範囲の外 {
        行: 行(5),
        行の数: 2,
    };
    assert_eq!(
        塊を動かせない文を作る(
            &行の並び,
            &重ね合わせの操作エラー::時間が重なる {
                行: 行(1),
                相手: 置いたクリップの識別子を作る("置-2"),
            }
        ),
        "動かす先の行(上から1番目)で、ほかの置いたクリップと時間が重なるため動かせない"
    );
    assert_eq!(
        塊を動かせない文を作る(&行の並び, &範囲の外),
        "動かす先の行が無いため動かせない"
    );
    assert_eq!(
        行を消せない文を作る(
            &行の並び,
            &重ね合わせの操作エラー::行が空でない { 行: 行(0) }
        ),
        "選んでいる行(上から2番目)には置いたクリップがあるため消せない(空の行だけを消せる)"
    );
    assert_eq!(
        行を消せない文を作る(&行の並び, &範囲の外),
        "選んでいる行が無い"
    );
}
