//! 重ね合わせの作業場の応答。重ね合わせの作業場の画面が発する応答の列挙と、重ね合わせの作業場の中の操作の状態への適用を持つ。
//! スタックの作業場の応答の束(`command::応答`)には入れない。スタックの作業場の状態か依存を使う応答(作業場を移る・今のスタックから並べる・今のスタックのクリップを置く・全画面・音量のつまみ)は、
//! 状態へ当てずに配線が受け取る。置き方の編集の操作は `placement.rs` に置く。参照: _doc/設計/同時再生.md 2-4・2-6・2-8・3-2・3-3

mod placement;

pub(crate) use placement::{映す矩形の枠の操作, 置き方の操作};

use clip_domain::{
    クリップ識別子, 置いたクリップの識別子, 置いたクリップの音の変更, 重ね合わせの操作エラー,
};

use super::state::重ね合わせの作業場の状態;

/// 落とされたファイルを開かずに出す知らせの文(同時再生.md 2-8)。重ね合わせの作業場の操作はスタックの作業場の状態を変えないためである。
pub(crate) const 落とされたファイルの知らせ: &str = "動画と JSON は、スタックへ戻ってから落とす";

/// 重ね合わせの作業場の応答とは、重ね合わせの作業場の画面が発する応答の区別のことである。
/// 重ね合わせの作業場の中の操作か、配線が受け取る応答(スタックの作業場へ戻る・今のスタックから並べる・今のスタックのクリップを置く・全画面を切り替える)かを分ける。
/// 今のスタックから並べるのは、スタックの作業場のスタックと、スタックの作業場の動画の開き手が持つ動画の読み手を使うため、配線が受け取る。
/// 全画面を切り替えるのは、ウインドウの状態をスタックの作業場の状態が持つため、配線が受け取る(同時再生.md 3-2 の共有するものの表)。
/// 今のスタックのクリップを置くのは、スタックの作業場のスタックと開いている動画を読むため、配線が受け取る(同時再生.md 2-4)。
/// 音量のつまみの値を選ぶのと全体の消音を切り替えるのは、どちらもスタックの作業場と同じ見る側の設定であるため、配線が受け取る(同時再生.md 2-6)。値はつまみが渡した値である。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 重ね合わせの作業場の応答 {
    操作(重ね合わせの操作),
    スタックの作業場へ戻る,
    今のスタックから並べる,
    今のスタックのクリップを置く(クリップ識別子),
    全画面を切り替える,
    音量のつまみの値を選ぶ(f64),
    全体の消音を切り替える,
}

/// 重ね合わせの操作とは、重ね合わせの作業場の中で状態へ当てる操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 重ね合わせの操作 {
    再生を切り替える,
    全体ループを設定する(bool),
    ファイルを落とされた,
    置き方(置き方の操作),
    置いたクリップの音を変える {
        識別子: 置いたクリップの識別子,
        変更: 置いたクリップの音の変更,
    },
}

impl 重ね合わせの作業場の状態 {
    /// 重ね合わせの操作を状態へ適用する。重ね合わせを開いていない間の再生と全体ループの切り替えと音の設定の変更は何もしない。
    /// 落とされたファイルは開かず、スタックへ戻ってから落とすよう知らせる。音の設定の変更が拒まれたら、その理由を知らせる。
    pub(crate) fn 操作を適用する(&mut self, 操作: 重ね合わせの操作) {
        match 操作 {
            重ね合わせの操作::再生を切り替える => {
                if let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
                {
                    開いている.再生を切り替える();
                }
            }
            重ね合わせの操作::全体ループを設定する(有効) => {
                if let Some(開いている) = self.開き方.開いている重ね合わせを書き換える()
                {
                    開いている.全体ループを設定する(有効);
                }
            }
            重ね合わせの操作::ファイルを落とされた => {
                self.知らせ.出す(落とされたファイルの知らせ)
            }
            重ね合わせの操作::置き方(操作) => {
                self.置き方の操作を適用する(操作)
            }
            重ね合わせの操作::置いたクリップの音を変える {
                識別子, 変更
            } => {
                let 結果 = self
                    .開き方
                    .開いている重ね合わせを書き換える()
                    .map(|開いている| {
                        開いている.置いたクリップの音を変える(&識別子, 変更)
                    });
                self.拒まれたら知らせる(結果);
            }
        }
    }

    /// 開いている重ね合わせへの操作が拒まれたら、その理由を知らせる。開いていなかった(結果が無い)ときは何もしない。
    fn 拒まれたら知らせる(
        &mut self, 結果: Option<Result<(), 重ね合わせの操作エラー>>
    ) {
        if let Some(Err(拒んだ理由)) = 結果 {
            self.知らせ.出す(拒んだ理由.to_string());
        }
    }
}
