//! 重ね合わせの作業場の応答。重ね合わせの作業場の画面が発する応答の列挙と、重ね合わせの作業場の中の操作の状態への適用を持つ。
//! スタックの作業場の応答の束(`command::応答`)には入れない。スタックの作業場の状態か依存を使う応答(作業場を移る・今のスタックから並べる・全画面)は、
//! 状態へ当てずに配線が受け取る。参照: _doc/設計/同時再生.md 2-8・3-2・3-3

use super::state::{重ね合わせの作業場の状態, 重ね合わせの開き方};

/// 落とされたファイルを開かずに出す知らせの文(同時再生.md 2-8)。重ね合わせの作業場の操作はスタックの作業場の状態を変えないためである。
pub(crate) const 落とされたファイルの知らせ: &str = "動画と JSON は、スタックへ戻ってから落とす";

/// 重ね合わせの作業場の応答とは、重ね合わせの作業場の画面が発する応答の区別のことである。
/// 重ね合わせの作業場の中の操作か、配線が受け取る応答(スタックの作業場へ戻る・今のスタックから並べる・全画面を切り替える)かを分ける。
/// 今のスタックから並べるのは、スタックの作業場のスタックと、スタックの作業場の動画の開き手が持つ動画の読み手を使うため、配線が受け取る。
/// 全画面を切り替えるのは、ウインドウの状態をスタックの作業場の状態が持つため、配線が受け取る(同時再生.md 3-2 の共有するものの表)。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 重ね合わせの作業場の応答 {
    操作(重ね合わせの操作),
    スタックの作業場へ戻る,
    今のスタックから並べる,
    全画面を切り替える,
}

/// 重ね合わせの操作とは、重ね合わせの作業場の中で状態へ当てる操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 重ね合わせの操作 {
    再生を切り替える,
    全体ループを設定する(bool),
    ファイルを落とされた,
}

impl 重ね合わせの作業場の状態 {
    /// 重ね合わせの操作を状態へ適用する。重ね合わせを開いていない間の再生と全体ループの切り替えは何もしない。
    /// 落とされたファイルは開かず、スタックへ戻ってから落とすよう知らせる。
    pub(crate) fn 操作を適用する(&mut self, 操作: 重ね合わせの操作) {
        match 操作 {
            重ね合わせの操作::再生を切り替える => {
                if let 重ね合わせの開き方::開いている(開いている) = &mut self.開き方
                {
                    開いている.再生を切り替える();
                }
            }
            重ね合わせの操作::全体ループを設定する(有効) => {
                if let 重ね合わせの開き方::開いている(開いている) = &mut self.開き方
                {
                    開いている.全体ループを設定する(有効);
                }
            }
            重ね合わせの操作::ファイルを落とされた => {
                self.知らせ.出す(落とされたファイルの知らせ)
            }
        }
    }
}
