//! 重ね合わせの作業場の操作。重ね合わせの作業場の画面が発する応答の列挙と、状態への適用を持つ。
//! スタックの作業場の応答の束(`command::応答`)には入れない。作業場を移ることは配線が行うため、適用はその頼みを返すだけにする。
//! 参照: _doc/設計/同時再生.md 3-2・3-3

use super::state::重ね合わせの作業場の状態;

/// 重ね合わせの操作とは、重ね合わせの作業場の画面が発する操作の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 重ね合わせの操作 {
    再生を切り替える,
    スタックの作業場へ戻る,
}

/// 操作の後の作業場とは、操作を適用した後に、重ね合わせの作業場を前に出したままにするか、スタックの作業場を前に出すかの区別のことである。
/// 作業場を持ち替えるのは配線(`app/workspace.rs`)であり、重ね合わせの作業場はスタックの作業場を知らないため、この値で頼む。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 操作の後の作業場 {
    重ね合わせのまま,
    スタックの作業場を前に出す,
}

impl 重ね合わせの作業場の状態 {
    /// 重ね合わせの操作を状態へ適用し、操作の後に前に出す作業場を返す。
    pub(crate) fn 操作を適用する(
        &mut self,
        操作: 重ね合わせの操作,
    ) -> 操作の後の作業場 {
        match 操作 {
            重ね合わせの操作::再生を切り替える => {
                self.再生.再生を切り替える(&self.重ね合わせ);
                操作の後の作業場::重ね合わせのまま
            }
            重ね合わせの操作::スタックの作業場へ戻る => {
                操作の後の作業場::スタックの作業場を前に出す
            }
        }
    }
}
