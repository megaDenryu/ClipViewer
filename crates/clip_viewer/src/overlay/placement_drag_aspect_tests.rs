//! 映す矩形のドラッグの縦横比の試験。動画を開けず絵の縦横比が分からないときに、縦横比を保つ隅のつまみが掴み始めの形を保つことを、作業場の口から確かめる。
#![allow(clippy::expect_used)]

use super::command::映す矩形の枠の操作;
use super::placement_test_support::{
    ドラッグの動きを作る, 右下, 左上の4分の1へ縮める, 映す矩形の枠の操作を当てる,
    置いたクリップの識別子を作る, 置いた矩形, 開いた作業場,
};
use super::state::placement::隅の縦横比の扱い;

#[test]
fn 動画を開けず絵の縦横比が分からないとき_縦横比を保つ隅のつまみは掴み始めの形を保つ() {
    let mut 作業場 = 開いた作業場();
    左上の4分の1へ縮める(&mut 作業場);
    let 広げる =
        ドラッグの動きを作る("置-1", 右下, 20.0, 0.0, 隅の縦横比の扱い::絵の形を保つ);
    映す矩形の枠の操作を当てる(
        &mut 作業場,
        映す矩形の枠の操作::掴み始めた(置いたクリップの識別子を作る("置-1")),
    );
    映す矩形の枠の操作を当てる(&mut 作業場, 映す矩形の枠の操作::放した(広げる));
    assert_eq!(置いた矩形(&作業場, "置-1"), [0.0, 0.0, 70.0, 70.0]);
}
