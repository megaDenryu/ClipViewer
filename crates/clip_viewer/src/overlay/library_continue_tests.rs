//! 関係を終える前の確かめから登録して続ける試験。未登録の重ね合わせを置き方を直したまま閉じるとき(重ね合わせを閉じる・アプリを閉じる)に
//! 「ライブラリに保存する」を選ぶと、登録して書き終えてから元の操作を続けることを確かめる。書けないまま閉じるときは `library_save_failure_tests.rs` が確かめる。
