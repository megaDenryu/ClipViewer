/// 捨てる前の確かめで「ライブラリに保存する」を押し、出た登録のダイアログへ名前を入力して登録する。登録のダイアログが続ける操作を持っていることを確かめる。
fn 確かめから名前を付けて登録する(
    作業場: &mut 重ね合わせの作業場,
    続ける操作: 重ね合わせとの関係を終える操作,
) {
    assert_eq!(
        作業場.状態().ライブラリ().ダイアログ(),
        &重ね合わせのダイアログ::捨てる前の確かめ(続ける操作.clone())
    );
    ライブラリの操作を当てる(作業場, 重ね合わせのライブラリの操作::登録してから続ける);
    assert!(matches!(
        作業場.状態().ライブラリ().ダイアログ(),
        重ね合わせのダイアログ::名前を付けて登録(_, 登録の後にすること::続ける(操作))
            if *操作 == 続ける操作
    ));
    ライブラリの操作を当てる(
        作業場,
        重ね合わせのライブラリの操作::一覧とダイアログ(
            一覧とダイアログの操作::名前の入力を書き換える(
                "ふたり".to_string(),
            ),
        ),
    );
    ライブラリの操作を当てる(作業場, 重ね合わせのライブラリの操作::登録する);
}

#[test]
fn 閉じる前の確かめで登録すると書き終えてから重ね合わせを閉じる() {
    let 一時 = 一時のライブラリ::作る("登録してから閉じる");
    let 組 = 一時.錠を試す();
    let mut 作業場 = 一時.作業場を作る(組.重ね合わせ);
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    縦横比を正方形にする(&mut 作業場);
    ライブラリの操作を当てる(
        &mut 作業場,
        重ね合わせのライブラリの操作::重ね合わせを閉じる,
    );
    確かめから名前を付けて登録する(
        &mut 作業場,
        重ね合わせとの関係を終える操作::重ね合わせを閉じる,
    );
    assert!(
        作業場.状態().開いている重ね合わせ().is_none(),
        "続けて閉じた"
    );
    assert_eq!(一時.保存した重ね合わせ()[0].名前().文字列(), "ふたり");
    assert_eq!(一時.保存した重ね合わせ()[0].重ね合わせ().縦横比(), 正方形());
    drop((作業場, 組.スタック));
}

#[test]
fn アプリを閉じる前の確かめで登録すると書き終えてから閉じてよいと決める() {
    let 一時 = 一時のライブラリ::作る("登録してからアプリを閉じる");
    let 組 = 一時.錠を試す();
    let mut 作業場 = 一時.作業場を作る(組.重ね合わせ);
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    縦横比を正方形にする(&mut 作業場);
    assert_eq!(
        作業場.閉じる要求を確かめる(),
        確かめた結果::確かめるダイアログを出した
    );
    確かめから名前を付けて登録する(
        &mut 作業場,
        重ね合わせとの関係を終える操作::アプリを閉じる,
    );
    assert_eq!(
        作業場.閉じてよいとの決めを取り出す(),
        アプリを閉じてよいとの決め::閉じてよいと決めた
    );
    assert_eq!(一時.保存した重ね合わせ()[0].重ね合わせ().縦横比(), 正方形());
    drop((作業場, 組.スタック));
}
