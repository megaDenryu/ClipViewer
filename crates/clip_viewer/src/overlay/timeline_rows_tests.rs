//! タイムラインの空の行の操作の試験。選んだ空の行だけを消せることと、空の行を最も手前に足して8行で拒むことを、作業場の口から確かめる。
//! 参照: _doc/設計/同時再生.md 2-6
#![allow(clippy::expect_used)]

use clip_domain::行の番号;

use super::command::{タイムラインの操作, 置き方の操作};
use super::placement_test_support::{
    手で直したか, 置いたクリップの識別子を作る, 置き方の操作を当てる,
};
use super::sound_test_support::知らせの文;
use super::state::timeline::選んでいる行の番号と空の行かの組;
use super::timeline_test_support::{
    タイムラインの操作を当てる, 二行を開いた作業場, 行ごとに描く塊, 選んでいる行,
};

fn 行(番号: usize) -> 行の番号 {
    行の番号::番号から作成する(番号)
}

#[test]
fn 選んだ空の行だけを消し_置いたクリップがある行は知らせて消さない() {
    let mut 作業場 = 二行を開いた作業場();
    タイムラインの操作を当てる(&mut 作業場, タイムラインの操作::行を選ぶ(行(1)));
    assert_eq!(
        選んでいる行(&作業場),
        Some(選んでいる行の番号と空の行かの組 {
            行: 行(1),
            空か: false
        })
    );
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::選んでいる空の行を消す,
    );
    assert_eq!(行ごとに描く塊(&作業場).len(), 2);
    assert!(知らせの文(&作業場).iter().any(|文| {
        文.contains(
            "選んでいる行(上から1番目)には置いたクリップがあるため消せない(空の行だけを消せる)",
        )
    }));
    assert!(!手で直したか(&作業場));
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを取り除く(
            置いたクリップの識別子を作る("置-1"),
        ),
    );
    タイムラインの操作を当てる(&mut 作業場, タイムラインの操作::行を選ぶ(行(0)));
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::選んでいる空の行を消す,
    );
    assert_eq!(行ごとに描く塊(&作業場).len(), 1);
    assert_eq!(選んでいる行(&作業場), None, "消した行の選びは外れる");
}

#[test]
fn 行を足すと最も手前に空の行ができて選ばれ_8行で拒んで知らせる() {
    let mut 作業場 = 二行を開いた作業場();
    タイムラインの操作を当てる(&mut 作業場, タイムラインの操作::空の行を手前に足す);
    assert_eq!(
        選んでいる行(&作業場),
        Some(選んでいる行の番号と空の行かの組 {
            行: 行(2),
            空か: true
        })
    );
    assert!(手で直したか(&作業場));
    for _ in 3..8 {
        タイムラインの操作を当てる(
            &mut 作業場,
            タイムラインの操作::空の行を手前に足す,
        );
    }
    assert_eq!(行ごとに描く塊(&作業場).len(), 8);
    assert!(
        !作業場
            .状態()
            .開いている重ね合わせ()
            .expect("開いている")
            .重ね合わせ()
            .行の並び()
            .行を足せるか()
    );
    タイムラインの操作を当てる(&mut 作業場, タイムラインの操作::空の行を手前に足す);
    assert_eq!(行ごとに描く塊(&作業場).len(), 8);
    assert!(
        知らせの文(&作業場)
            .last()
            .is_some_and(|文| 文.contains("新しい行を足せない(行は8つまで)"))
    );
}
