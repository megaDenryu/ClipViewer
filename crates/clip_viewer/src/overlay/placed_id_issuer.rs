//! 実時間の置いたクリップと重ね合わせの識別子の発行元。今の時刻と、発行するたびに1つ進める番号から「placed-<ミリ秒>-<番号>」の置いたクリップの識別子と、
//! 「overlay-<ミリ秒>-<番号>」の重ね合わせの識別子を発行する。時計を読む境界はここ1箇所である。参照: _doc/設計/同時再生.md 4-1・4-2

use std::time::{SystemTime, UNIX_EPOCH};

use clip_domain::{
    発行時刻, 置いたクリップの識別子, 置いたクリップの識別子の発行元, 識別子の乱数,
    重ね合わせの識別子,
};

/// 識別子の番号が取りうる値の数。識別子の乱数(0以上9999以下)と同じ数にする。
const 番号の巡回の周期: u32 = 10_000;

/// 実時間の置いたクリップと重ね合わせの識別子発行元とは、時計を読み、発行するたびに1つ進める番号を添えて置いたクリップの識別子と重ね合わせの識別子を発行するもののことである。
/// 番号は乱数でなく1つずつ進めるため、同じミリ秒に続けて発行しても、1つの発行元が発行した続く10,000件の識別子は重ならない。
/// スタックからの読み替えは最大8件を同じミリ秒に発行するため、乱数を10,000で畳む形では利用者の操作に誤りが無くても識別子が重なりうる。
/// 番号の始まりだけを時刻から取るのは、識別子の見た目をスタックの識別子と揃えるためである。
#[derive(Debug)]
pub(crate) struct 実時間の置いたクリップと重ね合わせの識別子発行元 {
    次の番号: u32,
}

impl 実時間の置いたクリップと重ね合わせの識別子発行元 {
    /// 今の時刻のナノ秒から番号の始まりを取って作る。
    pub(crate) fn 時刻から番号の始まりを取って作る() -> Self {
        Self {
            次の番号: 紀元からの経過().subsec_nanos() % 番号の巡回の周期,
        }
    }

    /// 重ね合わせの識別子を発行する。置いたクリップの識別子と同じ番号を進めるため、続けて発行しても重ならない。
    pub(crate) fn 新しい重ね合わせの識別子を発行する(
        &mut self,
    ) -> 重ね合わせの識別子 {
        let (時刻, 番号) = self.次の時刻と番号();
        重ね合わせの識別子::時刻と乱数から組み立てる(時刻, 番号)
    }

    /// 今の時刻と、番号(発行するたびに1つ進める)。
    fn 次の時刻と番号(&mut self) -> (発行時刻, 識別子の乱数) {
        let ミリ秒 = u64::try_from(紀元からの経過().as_millis()).unwrap_or(u64::MAX);
        let 番号 = 識別子の乱数::乱数を畳んで作成する(self.次の番号);
        self.次の番号 = (self.次の番号 + 1) % 番号の巡回の周期;
        (発行時刻::紀元からのミリ秒で作成する(ミリ秒), 番号)
    }
}

impl 置いたクリップの識別子の発行元
    for 実時間の置いたクリップと重ね合わせの識別子発行元
{
    fn 新しい識別子を発行する(&mut self) -> 置いたクリップの識別子 {
        let (時刻, 番号) = self.次の時刻と番号();
        置いたクリップの識別子::時刻と乱数から組み立てる(時刻, 番号)
    }
}

/// 1970年1月1日(協定世界時)からの経過。時計がそれより前を指していれば0とする。
fn 紀元からの経過() -> std::time::Duration {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
}
