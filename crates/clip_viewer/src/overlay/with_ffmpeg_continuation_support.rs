//! 続く先を止まるにする行の結合試験の道具。3つの行それぞれに隙間なく続く2つの置いたクリップを置いた重ね合わせを開いてコマを載せることと、
//! 行の映像が置いたクリップをどう描くかを文で読むことを受け持つ。FFmpeg が要る。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{正規化した動画パス, 行の番号, 音量};
use video_source::動画の読み手;

use super::feed::{行の描き方, 重ね合わせの映像の供給を作れたか};
use super::placement_test_support::置いたクリップの識別子を作る;
use super::sound_test_support::装置の無い作業場を作る;
use super::test_support::{置き方, 置き方を並べた重ね合わせ};
use super::workspace::重ね合わせの作業場;
use crate::video_feed::with_ffmpeg_support::{
    実行ファイルを探す, 成り立つまで待つ, 試験動画を作る,
};

pub(crate) struct 試験動画のファイル(pub(crate) 正規化した動画パス);

impl Drop for 試験動画のファイル {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(self.0.文字列());
    }
}

/// 動画上の開始から1秒の区間を、重ね合わせ上の始まりに置く置き方。
fn 一秒(開始: f64, 始まり: f64) -> 置き方 {
    置き方 {
        動画上の区間の開始: 開始,
        動画上の区間の終了: 開始 + 1.0,
        始まり,
    }
}

/// 行ごとに、0秒と1秒に隙間なく続く2つの置いたクリップを置いた重ね合わせを開き、3つの行の0秒の置いたクリップのコマが載るまで待つ。
/// 行1の2つは同じ区間にするかを選べる(同じ区間なら、続く先は別の置いたクリップでなく同じ区間になる)。
pub(crate) fn 三行のコマを載せた作業場(
    名前: &str,
    行1を同じ区間にするか: bool,
) -> (重ね合わせの作業場, 試験動画のファイル) {
    let 実行ファイル = 実行ファイルを探す();
    let ファイル = 試験動画のファイル(試験動画を作る(&実行ファイル, 名前));
    let 行1の後ろ = if 行1を同じ区間にするか {
        0.5
    } else {
        2.0
    };
    let 重ね合わせ = 置き方を並べた重ね合わせ(
        ファイル.0.clone(),
        4.0,
        &[
            &[一秒(0.5, 0.0), 一秒(2.0, 1.0)],
            &[一秒(0.5, 0.0), 一秒(行1の後ろ, 1.0)],
            &[一秒(0.5, 0.0), 一秒(2.0, 1.0)],
        ],
    );
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.重ね合わせを開く(重ね合わせ, Some(&動画の読み手::作成する(実行ファイル)));
    成り立つまで待つ(
        "3つの行の0秒の置いたクリップのコマが載ること",
        || {
            作業場.フレームを進める(Instant::now(), 音量::起動したときの音量);
            作業場
                .状態()
                .開いている重ね合わせ()
                .expect("開いている")
                .重ねる画面に描く行の並び()
                .len()
                == 3
        },
    );
    (作業場, ファイル)
}

/// 行の番号の行の映像が、識別子の置いたクリップに対してどう描くか。
pub(crate) fn 描き方(
    作業場: &重ね合わせの作業場, 行: usize, 識別子: &str
) -> String {
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    let 重ね合わせの映像の供給を作れたか::作れた(供給) = 開いている.映像の供給を作れたか()
    else {
        panic!("映像の供給を作れている");
    };
    let 行の映像 = 供給
        .行の映像(行の番号::番号から作成する(行))
        .expect("行の映像");
    match 行の映像.行の描き方を決める(&置いたクリップの識別子を作る(識別子))
    {
        行の描き方::映す置いたクリップのコマ => {
            "映す置いたクリップのコマ".to_string()
        }
        行の描き方::前の置いたクリップのコマ(前) => {
            format!("前の置いたクリップのコマ({})", 前.文字列())
        }
        行の描き方::描かない => "描かない".to_string(),
    }
}
