//! 重ね合わせの取り消しとやり直しの試験。毎フレームの最初に重ね合わせの変化を履歴へ積み、取り消しとやり直しで戻すことと、選んでいるものの扱いと、
//! つまみのドラッグの間の音量の変化を区切りまで1つにまとめることと、映す矩形のドラッグの途中は取り消さないことを、作業場の口から確かめる。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{
    アスペクト比設定, 置いたクリップの音の変更, 重ねる画面の縦横比, 音量
};

use super::command::{
    映す矩形の枠の操作, 編集の履歴の操作, 置き方の操作, 重ね合わせの操作
};
use super::placement_test_support::{
    手で直したか, 映す矩形の枠の操作を当てる, 置いたクリップの識別子を作る, 置き方の操作を当てる,
    開いた作業場,
};
use super::workspace::重ね合わせの作業場;
use crate::primary_button::主ボタンの様子;

/// 1フレーム進める。前のフレームで当てた操作による重ね合わせの変化が、ここで履歴へ積まれる。
fn 一フレーム進める(作業場: &mut 重ね合わせの作業場) {
    let _ = 作業場.フレームを進める(Instant::now(), 音量::範囲へ収めて作る(1.0));
}

fn 履歴の操作を当てる(
    作業場: &mut 重ね合わせの作業場, 操作: 編集の履歴の操作
) {
    作業場.操作を適用する(重ね合わせの操作::編集の履歴(操作));
}

fn 縦横比(作業場: &重ね合わせの作業場) -> 重ねる画面の縦横比 {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ねる画面の縦横比()
}

fn 正方形() -> 重ねる画面の縦横比 {
    重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比")
}

/// 置-1 の音量を選ぶ。
fn 音量を選ぶ(作業場: &mut 重ね合わせの作業場, 値: f64) {
    作業場.操作を適用する(重ね合わせの操作::置いたクリップの音を変える {
        識別子: 置いたクリップの識別子を作る("置-1"),
        変更: 置いたクリップの音の変更::音量を選ぶ(音量::範囲へ収めて作る(値)),
    });
}

fn 置1の音量(作業場: &重ね合わせの作業場) -> f64 {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ね合わせ()
        .識別子で探す(&置いたクリップの識別子を作る("置-1"))
        .expect("置いたクリップ")
        .音の設定()
        .音量
        .値()
}

#[test]
fn 縦横比を変えて取り消すと戻り_やり直すと進み_取り消しても手で直したままである() {
    let mut 作業場 = 開いた作業場();
    assert!(!作業場.状態().取り消せるか());
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::重ねる画面の縦横比を選ぶ(正方形()),
    );
    一フレーム進める(&mut 作業場);
    assert!(作業場.状態().取り消せるか());
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集を取り消す);
    assert_eq!(縦横比(&作業場), 重ねる画面の縦横比::ワイド16対9);
    assert!(手で直したか(&作業場), "取り消しも重ね合わせを変える");
    assert!(作業場.状態().やり直せるか());
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集をやり直す);
    assert_eq!(縦横比(&作業場), 正方形());
    assert!(!作業場.状態().やり直せるか());
}

#[test]
fn 取り除いた置いたクリップは取り消すと戻り_やり直すと選びが外れる() {
    let mut 作業場 = 開いた作業場();
    let 置1 = 置いたクリップの識別子を作る("置-1");
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを取り除く(置1.clone()),
    );
    一フレーム進める(&mut 作業場);
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集を取り消す);
    置き方の操作を当てる(&mut 作業場, 置き方の操作::置いたクリップを選ぶ(置1.clone()));
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert!(開いている.重ね合わせ().識別子で探す(&置1).is_some());
    assert!(
        開いている.選んでいる置いたクリップ().is_some(),
        "戻した置いたクリップを選べる"
    );
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集をやり直す);
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert!(開いている.重ね合わせ().識別子で探す(&置1).is_none());
    assert!(
        開いている.選んでいる置いたクリップ().is_none(),
        "無くなった置いたクリップの選びは外す"
    );
}

#[test]
fn つまみを押している間の音量の変化は区切りまで1つにまとめ_区切りの後は別の変化にする() {
    let mut 作業場 = 開いた作業場();
    for (値, 主ボタン) in [
        (0.9, 主ボタンの様子::押している),
        (0.8, 主ボタンの様子::押している),
        (0.7, 主ボタンの様子::押していない),
    ] {
        音量を選ぶ(&mut 作業場, 値);
        作業場.取り残されたドラッグを捨てる(主ボタン);
        一フレーム進める(&mut 作業場);
    }
    音量を選ぶ(&mut 作業場, 0.5);
    一フレーム進める(&mut 作業場);
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集を取り消す);
    assert_eq!(置1の音量(&作業場), 0.7, "区切りの後の変化は別の変化");
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集を取り消す);
    assert_eq!(置1の音量(&作業場), 1.0, "区切りまでの変化は1つ");
    assert!(!作業場.状態().取り消せるか());
}

#[test]
fn 映す矩形のドラッグの途中は取り消しもやり直しもしない() {
    let mut 作業場 = 開いた作業場();
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::重ねる画面の縦横比を選ぶ(正方形()),
    );
    一フレーム進める(&mut 作業場);
    映す矩形の枠の操作を当てる(
        &mut 作業場,
        映す矩形の枠の操作::掴み始めた(置いたクリップの識別子を作る("置-1")),
    );
    assert!(!作業場.状態().取り消せるか());
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集を取り消す);
    assert_eq!(縦横比(&作業場), 正方形());
    作業場.取り残されたドラッグを捨てる(主ボタンの様子::押していない);
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集を取り消す);
    assert_eq!(縦横比(&作業場), 重ねる画面の縦横比::ワイド16対9);
}
