//! 時間の軸で再生の位置を動かす試験。動かした時刻へ再生の位置を移し、重ね合わせの長さより後ろは長さで止め、再生しているかは変えないことを、
//! 作業場の口から確かめる。動かしたときに前の置いたクリップのコマを描かないことは `with_ffmpeg_seek_tests.rs` が確かめる。参照: _doc/設計/同時再生.md 2-6
#![allow(clippy::expect_used)]

use clip_domain::重ね合わせ上の秒;

use super::command::{タイムラインの操作, 重ね合わせの操作};
use super::timeline_test_support::{
    タイムラインの操作を当てる, 二行を開いた作業場
};
use super::workspace::重ね合わせの作業場;

#[test]
fn 時間の軸で再生の位置を動かし_長さより後ろは長さで止め_再生しているかは変えない() {
    let mut 作業場 = 二行を開いた作業場();
    let 秒 = |値| 重ね合わせ上の秒::作成する(値).expect("時刻");
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::再生の位置を動かす(秒(2.5)),
    );
    assert_eq!(位置と長さ(&作業場), (2.5, 4.0));
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::再生の位置を動かす(秒(9.0)),
    );
    assert_eq!(位置と長さ(&作業場), (4.0, 4.0));
    assert!(作業場.状態().再生しているか());
}

fn 位置と長さ(作業場: &重ね合わせの作業場) -> (f64, f64) {
    let (位置, 長さ) = 作業場.状態().再生の位置と長さ().expect("開いている");
    (位置.時刻().秒数(), 長さ.秒数())
}
