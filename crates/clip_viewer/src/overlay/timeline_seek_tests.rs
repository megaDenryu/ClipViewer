//! 時間の軸で再生の位置を動かす試験。動かした時刻へ再生の位置を移し、重ね合わせの長さより後ろは長さで止め、再生しているかは変えないことと、
//! 位置の線を掴んでいる間は流し読みの開き直しを控え(画面.md 判断5)、放すか安全網が捨てたら開き直してよいに戻ることと、控えるが音の供給まで届くことを、作業場のメソッドから確かめる。
//! 動かしたときに前の置いたクリップのコマを描かないことは `with_ffmpeg_seek_tests.rs` が、掴んでいる間に音を黙らせることは
//! `with_ffmpeg_seek_sound_tests.rs` が、控えるが映像の供給まで届くことは `with_ffmpeg_seek_drag_tests.rs` が確かめる。参照: _doc/設計/同時再生.md 2-6
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{重ね合わせ上の秒, 音量};

use super::command::{タイムラインの操作, 重ね合わせの操作};
use super::state::grab::位置の線の段階;
use super::timeline_test_support::{
    タイムラインの操作を当てる, 二行を開いた作業場
};
use super::workspace::重ね合わせの作業場;
use crate::primary_button::主ボタンの様子;
use crate::stream_rules::流し読みの開き直し;

fn 位置の線を当てる(
    作業場: &mut 重ね合わせの作業場, 段階: 位置の線の段階, 秒: f64
) {
    let 時刻 = 重ね合わせ上の秒::作成する(秒).expect("時刻");
    タイムラインの操作を当てる(
        作業場,
        タイムラインの操作::再生の位置を動かす(段階, 時刻),
    );
}

fn 位置と長さ(作業場: &重ね合わせの作業場) -> (f64, f64) {
    let (位置, 長さ) = 作業場.状態().再生の位置と長さ().expect("開いている");
    (位置.時刻().秒数(), 長さ.秒数())
}

fn 開き直し(作業場: &重ね合わせの作業場) -> 流し読みの開き直し {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .流し読みの開き直し()
}

#[test]
fn 時間の軸で再生の位置を動かし_長さより後ろは長さで止め_再生しているかは変えない() {
    let mut 作業場 = 二行を開いた作業場();
    位置の線を当てる(&mut 作業場, 位置の線の段階::掴み始めた, 2.5);
    位置の線を当てる(&mut 作業場, 位置の線の段階::放した, 2.5);
    assert_eq!(位置と長さ(&作業場), (2.5, 4.0));
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    位置の線を当てる(&mut 作業場, 位置の線の段階::掴み始めた, 9.0);
    位置の線を当てる(&mut 作業場, 位置の線の段階::放した, 9.0);
    assert_eq!(位置と長さ(&作業場), (4.0, 4.0));
    assert!(作業場.状態().再生しているか());
}

#[test]
fn 位置の線を掴んでいる間は流し読みの開き直しを控え_放すと開き直してよいに戻る() {
    let mut 作業場 = 二行を開いた作業場();
    assert_eq!(開き直し(&作業場), 流し読みの開き直し::してよい);
    位置の線を当てる(&mut 作業場, 位置の線の段階::掴み始めた, 1.0);
    位置の線を当てる(&mut 作業場, 位置の線の段階::動かしている, 1.5);
    assert_eq!(位置と長さ(&作業場).0, 1.5, "ドラッグの間も位置は動く");
    assert_eq!(開き直し(&作業場), 流し読みの開き直し::控える);
    位置の線を当てる(&mut 作業場, 位置の線の段階::放した, 2.0);
    assert_eq!(開き直し(&作業場), 流し読みの開き直し::してよい);
    assert_eq!(位置と長さ(&作業場).0, 2.0);
}

#[test]
fn 放したを受け取れずに残った位置の線のドラッグは安全網が捨てて開き直してよいに戻る() {
    let mut 作業場 = 二行を開いた作業場();
    位置の線を当てる(&mut 作業場, 位置の線の段階::掴み始めた, 1.0);
    作業場.取り残されたドラッグを捨てる(主ボタンの様子::押している);
    assert_eq!(開き直し(&作業場), 流し読みの開き直し::控える);
    作業場.取り残されたドラッグを捨てる(主ボタンの様子::押していない);
    assert_eq!(開き直し(&作業場), 流し読みの開き直し::してよい);
    assert_eq!(位置と長さ(&作業場).0, 1.0, "動かした位置は残る");
}

#[test]
fn 位置の線を掴んでいる間の控えるは_音の供給まで届く() {
    let mut 作業場 = 二行を開いた作業場();
    let 音の供給が受け取った = |作業場: &mut 重ね合わせの作業場| {
        作業場.フレームを進める(Instant::now(), 音量::起動したときの音量);
        作業場
            .状態()
            .開いている重ね合わせ()
            .expect("開いている")
            .音()
            .音の供給が最後に受け取った開き直し()
    };
    assert_eq!(
        音の供給が受け取った(&mut 作業場),
        Some(流し読みの開き直し::してよい)
    );
    位置の線を当てる(&mut 作業場, 位置の線の段階::掴み始めた, 1.0);
    assert_eq!(
        音の供給が受け取った(&mut 作業場),
        Some(流し読みの開き直し::控える)
    );
    位置の線を当てる(&mut 作業場, 位置の線の段階::放した, 1.0);
    assert_eq!(
        音の供給が受け取った(&mut 作業場),
        Some(流し読みの開き直し::してよい)
    );
}
