//! 重ね合わせの登録と自動保存の試験。名前を付けて登録すると書き終えてから知らせて保存済みになり、変えると落ち着いてから自動で保存すること、
//! 控えるときとアプリを落とす前は落ち着くのを待たずに保存することを確かめる。
//! 置き場所は一時フォルダである。参照: _doc/設計/同時再生.md 2-2・2-7
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use clip_domain::重ねる画面の縦横比;

use super::command::{置き方の操作, 重ね合わせの操作};
use super::library_test_ops::{
    名前を付けて登録する, 書き終えるまで待って進める, 正方形, 縦横比を正方形にする,
};
use super::library_test_support::一時のライブラリ;
use super::sound_test_support::知らせの文;
use super::state::library::開いている重ね合わせのライブラリの様子;
use super::test_support::五秒の重ね合わせ;
use super::workspace::重ね合わせの作業場;
use crate::library_common::save::保存の段階;

/// 開いている重ね合わせが登録済みで、その保存の段階が保存済みか。
fn 保存済みか(作業場: &重ね合わせの作業場) -> bool {
    matches!(
        作業場.状態().開いている重ね合わせのライブラリの様子(),
        Some(開いている重ね合わせのライブラリの様子::登録済み {
            段階: 保存の段階::保存済み,
            ..
        })
    )
}

#[test]
fn 登録すると書き終えてから知らせて保存済みになり_変えると落ち着いてから自動で保存する() {
    let 一時 = 一時のライブラリ::作る("登録と自動保存");
    let 組 = 一時.錠を試す();
    let mut 作業場 = 一時.作業場を作る(組.重ね合わせ);
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    名前を付けて登録する(&mut 作業場, "ふたり");
    let 始め = Instant::now();
    書き終えるまで待って進める(&mut 作業場, 始め);
    assert!(
        知らせの文(&作業場)
            .iter()
            .any(|文| 文.contains("重ね合わせをライブラリに保存しました: ふたり"))
    );
    assert!(保存済みか(&作業場));
    assert_eq!(一時.保存した重ね合わせ()[0].名前().文字列(), "ふたり");
    縦横比を正方形にする(&mut 作業場);
    作業場.ライブラリとサムネイルを進める(始め + Duration::from_millis(100), None);
    assert!(!保存済みか(&作業場), "落ち着くのを待っている");
    作業場.ライブラリとサムネイルを進める(始め + Duration::from_millis(700), None);
    書き終えるまで待って進める(&mut 作業場, 始め + Duration::from_millis(800));
    assert!(保存済みか(&作業場));
    assert_eq!(一時.保存した重ね合わせ()[0].重ね合わせ().縦横比(), 正方形());
    drop((作業場, 組.スタック));
}

#[test]
fn 控えるときとアプリを落とす前は落ち着くのを待たずに書けていない重ね合わせを保存する() {
    let 一時 = 一時のライブラリ::作る("控えると落とす");
    let 組 = 一時.錠を試す();
    let mut 作業場 = 一時.作業場を作る(組.重ね合わせ);
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    名前を付けて登録する(&mut 作業場, "ふたり");
    書き終えるまで待って進める(&mut 作業場, Instant::now());
    縦横比を正方形にする(&mut 作業場);
    作業場.控える前に再生を止める();
    書き終えるまで待って進める(&mut 作業場, Instant::now());
    assert_eq!(一時.保存した重ね合わせ()[0].重ね合わせ().縦横比(), 正方形());
    作業場.操作を適用する(重ね合わせの操作::置き方(
        置き方の操作::重ねる画面の縦横比を選ぶ(重ねる画面の縦横比::ワイド16対9),
    ));
    作業場.終わる前に保存を頼む();
    drop(作業場);
    assert_eq!(
        一時.保存した重ね合わせ()[0].重ね合わせ().縦横比(),
        重ねる画面の縦横比::ワイド16対9,
        "落とすときは頼んだ書き込みを終えてから閉じる"
    );
    drop(組.スタック);
}
