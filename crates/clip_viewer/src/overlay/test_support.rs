//! 重ね合わせの作業場の試験の道具。決まった識別子の発行元と、試験で開く重ね合わせを作る。
#![allow(clippy::expect_used)]

use clip_domain::{
    アスペクト比設定, クリップ, クリップから受け継いだ値, クリップスタック, クリップ名,
    クリップ識別子, 使う動画の表, 入力された動画パス, 動画の番号, 動画上の区間, 時刻, 時間の長さ,
    正規化した動画パス, 置いたクリップの識別子, 置いたクリップの識別子の発行元, 重ねる画面の縦横比,
    重ね合わせ,
};

/// 「置-1」「置-2」…を順に発行する、試験用の決まった発行元。
#[derive(Default)]
struct 置いた連番の発行元(u32);

impl 置いたクリップの識別子の発行元 for 置いた連番の発行元 {
    fn 新しい識別子を発行する(&mut self) -> 置いたクリップの識別子 {
        self.0 += 1;
        置いたクリップの識別子::文字列から作成する(format!("置-{}", self.0)).expect("空でない")
    }
}

/// 0秒から5秒の区間を1回だけ映すクリップを1つ並べた重ね合わせ(長さ5秒)。
pub(crate) fn 五秒の重ね合わせ() -> 重ね合わせ {
    let クリップ = クリップ::既定値で作成する(
        クリップ識別子::文字列から作成する("甲".to_string()).expect("識別子"),
        クリップ名::作成する("甲".to_string()),
    );
    let スタック = クリップスタック::一覧から作成する(vec![クリップ]).expect("スタック");
    重ね合わせ::スタックから並べる(
        &スタック,
        入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
        時間の長さ::作成する(60.0).expect("長さ"),
        アスペクト比設定::ワイド16対9,
        &mut 置いた連番の発行元::default(),
    )
    .expect("並べられる")
    .重ね合わせ
}

/// 置いたクリップを持たない(長さ0秒の)重ね合わせ。
pub(crate) fn 長さが0秒の重ね合わせ() -> 重ね合わせ {
    重ね合わせ::作成する(
        重ねる画面の縦横比::ワイド16対9,
        使う動画の表::並びから作成する(Vec::new()),
    )
}

/// 置き方とは、試験で置くクリップの区間の開始と終了(動画上の秒)と、重ね合わせ上の始まりの時刻の組のことである。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 置き方 {
    pub(crate) 動画上の区間の開始: f64,
    pub(crate) 動画上の区間の終了: f64,
    pub(crate) 始まり: f64,
}

/// 1本の動画の重ね合わせへ、行ごとの置き方の並びを奥の行から順に置く。各行の最初の置いたクリップは最も手前に新しい行を足して置き、
/// 続く置いたクリップは空いている最も手前の行(今足した行)へ置く。リピート回数は1回、クロップは全体である。
pub(crate) fn 置き方を並べた重ね合わせ(
    動画: 正規化した動画パス,
    動画の長さの秒: f64,
    行ごとの置き方: &[&[置き方]],
) -> 重ね合わせ {
    let mut 重ね合わせ = 重ね合わせ::作成する(
        重ねる画面の縦横比::ワイド16対9,
        使う動画の表::一本の動画から作成する(動画),
    );
    let 動画の長さ = 時間の長さ::作成する(動画の長さの秒).expect("長さ");
    let mut 発行元 = 置いた連番の発行元::default();
    for 置き方の並び in 行ごとの置き方 {
        for (順, 置き方) in 置き方の並び.iter().enumerate() {
            let 秒 = |値| 時刻::作成する(値).expect("時刻");
            let mut 受け継いだ値 =
                クリップから受け継いだ値::クリップから受け継ぐ(
                    &クリップ::既定値で作成する(
                        クリップ識別子::文字列から作成する("置く".to_string()).expect("識別子"),
                        クリップ名::作成する("置く".to_string()),
                    ),
                );
            受け継いだ値.区間 = 動画上の区間::作成する(
                秒(置き方.動画上の区間の開始),
                秒(置き方.動画上の区間の終了),
            )
            .expect("区間");
            let 動画の番号 = 動画の番号::番号から作成する(0);
            let 始まり = 時刻::作成する(置き方.始まり).expect("時刻");
            let 結果 = if 順 == 0 {
                重ね合わせ.手前に新しい行を足して置く(
                    受け継いだ値,
                    動画の番号,
                    始まり,
                    動画の長さ,
                    &mut 発行元,
                )
            } else {
                重ね合わせ.クリップから受け継いだ値を置く(
                    受け継いだ値,
                    動画の番号,
                    始まり,
                    動画の長さ,
                    &mut 発行元,
                )
            };
            結果.expect("置ける");
        }
    }
    重ね合わせ
}
