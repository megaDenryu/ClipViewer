//! 重ね合わせの作業場の試験の道具。決まった識別子の発行元と、試験で開く重ね合わせを作る。
#![allow(clippy::expect_used)]

use clip_domain::{
    アスペクト比設定, クリップ, クリップスタック, クリップ名, クリップ識別子, 使う動画の表,
    入力された動画パス, 時間の長さ, 置いたクリップの識別子, 置いたクリップの識別子の発行元,
    重ねる画面の縦横比, 重ね合わせ,
};

/// 「置-1」「置-2」…を順に発行する、試験用の決まった発行元。
#[derive(Default)]
struct 置いた連番の発行元(u32);

impl 置いたクリップの識別子の発行元 for 置いた連番の発行元 {
    fn 新しい識別子を発行する(&mut self) -> 置いたクリップの識別子 {
        self.0 += 1;
        置いたクリップの識別子::文字列から作成する(format!("置-{}", self.0)).expect("空でない")
    }
}

/// 0秒から5秒の区間を1回だけ映すクリップを1つ並べた重ね合わせ(長さ5秒)。
pub(crate) fn 五秒の重ね合わせ() -> 重ね合わせ {
    let クリップ = クリップ::既定値で作成する(
        クリップ識別子::文字列から作成する("甲".to_string()).expect("識別子"),
        クリップ名::作成する("甲".to_string()),
    );
    let スタック = クリップスタック::一覧から作成する(vec![クリップ]).expect("スタック");
    重ね合わせ::スタックから並べる(
        &スタック,
        入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
        時間の長さ::作成する(60.0).expect("長さ"),
        アスペクト比設定::ワイド16対9,
        &mut 置いた連番の発行元::default(),
    )
    .expect("並べられる")
    .重ね合わせ
}

/// 置いたクリップを持たない(長さ0秒の)重ね合わせ。
pub(crate) fn 長さが0秒の重ね合わせ() -> 重ね合わせ {
    重ね合わせ::作成する(
        重ねる画面の縦横比::ワイド16対9,
        使う動画の表::並びから作成する(Vec::new()),
    )
}
