//! 今のスタックから並べることの試験。並べた重ね合わせを開いて並べた数と置かなかったクリップを知らせることと、
//! 置けるクリップが無いときは開かずに報告し、動画を開いていないときは並べないことと、並べた後に描き直しを頼むことを、作業場の口から確かめる。
//! 動画の読み手を渡さない(FFmpeg が無い)ため、映像の供給は作らない。映像を映す経路は `app/workspace/overlay_with_ffmpeg_tests.rs` が確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{クリップ, クリップスタック};
use eframe::egui;
use sengen_egui::{並べる通知, 通知の回};

use super::arrange_test_support::{クリップ, 値, 練習の動画};
use super::feed::映像の供給を作れない理由;
use super::sound_test_support::{
    装置の無い作業場を作る, 装置の無い音の出力を作る, 音の出力で作業場を作る,
};
use super::state::今のスタックの値;

#[test]
fn 先頭から8つを並べて開き_置けないクリップと行の数の上限で置かなかったクリップを名前と理由で報告する()
 {
    let mut 一覧: Vec<クリップ> = (1..=10)
        .map(|番号| クリップ(&番号.to_string(), 0.0, 1.0))
        .collect();
    一覧.insert(2, クリップ("長い", 50.0, 70.0));
    let スタック = クリップスタック::一覧から作成する(一覧).expect("スタック");
    let パス = 練習の動画();
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.今のスタックから並べる(値(&スタック, &パス, 60.0), None);
    assert!(作業場.状態().開いている重ね合わせ().is_some());
    assert_eq!(
        作業場.状態().置かなかったクリップの報告の文(),
        [
            "「長い」を置かなかった: 置けない(区間の終わり(70秒)が動画の長さ(60秒)より後ろにある)",
            "並べられるのは8つまでのため置かなかったクリップ(2個): 「9」「10」",
        ]
    );
    assert_eq!(
        作業場.状態().並べる知らせ(),
        [
            並べる通知::作成する(
                通知の回::最初(),
                映像の供給を作れない理由::FFmpegが無い.to_string()
            ),
            並べる通知::作成する(
                通知の回::最初().次(),
                "今のスタックから8個のクリップを並べた。3個のクリップは置かなかった(理由は出力の区画の上の端に出す)"
            ),
        ]
    );
}

#[test]
fn どのクリップも置けないときは重ね合わせを開かずに報告し_動画を開いていないときは並べない() {
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("甲", 0.0, 5.0)]).expect("スタック");
    let パス = 練習の動画();
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.今のスタックから並べる(値(&スタック, &パス, 3.0), None);
    assert!(作業場.状態().開いている重ね合わせ().is_none());
    assert_eq!(
        作業場.状態().置かなかったクリップの報告の文(),
        ["「甲」を置かなかった: 置けない(区間の終わり(5秒)が動画の長さ(3秒)より後ろにある)"]
    );
    作業場.今のスタックから並べる(
        今のスタックの値 {
            開いている動画: None,
            ..値(&スタック, &パス, 3.0)
        },
        None,
    );
    let 知らせ: Vec<String> = 作業場
        .状態()
        .並べる知らせ()
        .iter()
        .map(|通知| format!("{通知:?}"))
        .collect();
    assert_eq!(知らせ.len(), 2, "{知らせ:?}");
    assert!(
        知らせ[0].contains("どれも置けないため、並べられない"),
        "{知らせ:?}"
    );
    assert!(
        知らせ[1].contains("動画を開いていないため、並べられない"),
        "{知らせ:?}"
    );
}

#[test]
fn 並べた後は描き直しを頼む() {
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("甲", 0.0, 1.0)]).expect("スタック");
    let パス = 練習の動画();
    let 画面描画の共有状態 = egui::Context::default();
    for _ in 0..2 {
        let _ = 画面描画の共有状態.run(egui::RawInput::default(), |_| {});
    }
    assert!(!画面描画の共有状態.has_requested_repaint());
    let mut 作業場 =
        音の出力で作業場を作る(画面描画の共有状態.clone(), 装置の無い音の出力を作る());
    作業場.今のスタックから並べる(値(&スタック, &パス, 60.0), None);
    assert!(画面描画の共有状態.has_requested_repaint());
}

#[test]
fn 開いている間に並べ直してどれも置けないときは_開いている重ね合わせを残して報告だけを差し替える() {
    let 置ける =
        クリップスタック::一覧から作成する(vec![クリップ("甲", 0.0, 1.0)]).expect("スタック");
    let 置けない =
        クリップスタック::一覧から作成する(vec![クリップ("乙", 0.0, 5.0)]).expect("スタック");
    let パス = 練習の動画();
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.今のスタックから並べる(値(&置ける, &パス, 3.0), None);
    let 並べた後の長さ = 作業場.状態().再生の位置と長さ();
    作業場.今のスタックから並べる(値(&置けない, &パス, 3.0), None);
    assert_eq!(作業場.状態().再生の位置と長さ(), 並べた後の長さ);
    assert_eq!(
        作業場.状態().置かなかったクリップの報告の文(),
        ["「乙」を置かなかった: 置けない(区間の終わり(5秒)が動画の長さ(3秒)より後ろにある)"]
    );
}
