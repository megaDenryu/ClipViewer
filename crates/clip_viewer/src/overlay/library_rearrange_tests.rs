//! 今のスタックから並べ直す前の確かめの試験。手で直した未登録の重ね合わせは捨てる前に確かめ、変更を捨てて続けると並べ直して並べたままになることと、
//! 登録済みの重ね合わせは書けたことを確かめてから(書けていなければ保存してから)確かめずに未登録で並べ直し、元の重ね合わせはライブラリに残ることを確かめる。
//! 置き場所は一時フォルダである。参照: _doc/設計/同時再生.md 2-2・2-7
#![allow(clippy::expect_used)]

use clip_domain::クリップスタック;

use super::arrange_test_support::{クリップ, 値, 練習の動画};
use super::command::重ね合わせのライブラリの操作;
use super::library_test_ops::{
    名前を付けて登録する, 正方形, 縦横比を正方形にする
};
use super::library_test_support::一時のライブラリ;
use super::placement_test_support::{
    左上の4分の1へ縮める, 手で直したか, 開いた作業場
};
use super::state::library::{
    重ね合わせとの関係を終える操作, 重ね合わせのダイアログ, 開いている重ね合わせのライブラリの様子,
};
use super::test_support::五秒の重ね合わせ;
use super::workspace::今のスタックの値と動画の読み手;

#[test]
fn 手で直した未登録の重ね合わせは並べ直す前に確かめ_変更を捨てて続けると並べ直して並べたままになる()
{
    let mut 作業場 = 開いた作業場();
    左上の4分の1へ縮める(&mut 作業場);
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("乙", 10.0, 12.0)]).expect("スタック");
    let パス = 練習の動画();
    作業場.今のスタックから並べる(値(&スタック, &パス, 60.0), None);
    assert_eq!(
        作業場.状態().ライブラリ().ダイアログ(),
        &重ね合わせのダイアログ::捨てる前の確かめ(
            重ね合わせとの関係を終える操作::今のスタックから並べ直す
        )
    );
    assert!(手で直したか(&作業場), "確かめている間は並べ直さない");
    作業場.ライブラリの操作を当てる(
        重ね合わせのライブラリの操作::変更を捨てて続ける,
        今のスタックの値と動画の読み手 {
            今のスタック: 値(&スタック, &パス, 60.0),
            読み手: None,
        },
    );
    assert_eq!(
        作業場.状態().ライブラリ().ダイアログ(),
        &重ね合わせのダイアログ::無し
    );
    assert!(!手で直したか(&作業場));
}

#[test]
fn 登録済みの重ね合わせを並べ直すと確かめずに未登録で並べ直し_元の重ね合わせはライブラリに残る() {
    let 一時 = 一時のライブラリ::作る("登録済みを並べ直す");
    let 組 = 一時.錠を試す();
    let mut 作業場 = 一時.作業場を作る(組.重ね合わせ);
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    名前を付けて登録する(&mut 作業場, "ふたり");
    縦横比を正方形にする(&mut 作業場);
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("乙", 10.0, 12.0)]).expect("スタック");
    let パス = 練習の動画();
    作業場.今のスタックから並べる(値(&スタック, &パス, 60.0), None);
    assert_eq!(
        作業場.状態().ライブラリ().ダイアログ(),
        &重ね合わせのダイアログ::無し
    );
    assert!(matches!(
        作業場.状態().開いている重ね合わせのライブラリの様子(),
        Some(開いている重ね合わせのライブラリの様子::未登録)
    ));
    let 保存した = 一時.保存した重ね合わせ();
    assert_eq!(保存した.len(), 1);
    assert_eq!(
        保存した[0].重ね合わせ().縦横比(),
        正方形(),
        "並べ直す前に書けていない変更を保存した"
    );
    drop((作業場, 組.スタック));
}
