//! 置いたクリップの音量のつまみの取り消しの試験。主ボタンを押している間の音量の変化は操作の区切りまで1つにまとめ、区切りの後の変化は別の変化にすることを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{置いたクリップの音の変更, 音量};

use super::{一フレーム進める, 履歴の操作を当てる};
use crate::overlay::command::{編集の履歴の操作, 重ね合わせの操作};
use crate::overlay::placement_test_support::{
    置いたクリップの識別子を作る, 開いた作業場
};
use crate::overlay::workspace::重ね合わせの作業場;
use crate::primary_button::主ボタンの様子;

/// 置-1 の音量を選ぶ。
fn 音量を選ぶ(作業場: &mut 重ね合わせの作業場, 値: f64) {
    作業場.操作を適用する(重ね合わせの操作::置いたクリップの音を変える {
        識別子: 置いたクリップの識別子を作る("置-1"),
        変更: 置いたクリップの音の変更::音量を選ぶ(音量::範囲へ収めて作る(値)),
    });
}

fn 置1の音量(作業場: &重ね合わせの作業場) -> f64 {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ね合わせ()
        .識別子で探す(&置いたクリップの識別子を作る("置-1"))
        .expect("置いたクリップ")
        .音の設定()
        .音量
        .値()
}

#[test]
fn つまみを押している間の音量の変化は区切りまで1つにまとめ_区切りの後は別の変化にする() {
    let mut 作業場 = 開いた作業場();
    for (値, 主ボタン) in [
        (0.9, 主ボタンの様子::押している),
        (0.8, 主ボタンの様子::押している),
        (0.7, 主ボタンの様子::押していない),
    ] {
        音量を選ぶ(&mut 作業場, 値);
        作業場.取り残されたドラッグを捨てる(主ボタン);
        一フレーム進める(&mut 作業場);
    }
    音量を選ぶ(&mut 作業場, 0.5);
    一フレーム進める(&mut 作業場);
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集を取り消す);
    assert_eq!(置1の音量(&作業場), 0.7, "区切りの後の変化は別の変化");
    履歴の操作を当てる(&mut 作業場, 編集の履歴の操作::編集を取り消す);
    assert_eq!(置1の音量(&作業場), 1.0, "区切りまでの変化は1つ");
    assert!(!作業場.状態().取り消せるか());
}
