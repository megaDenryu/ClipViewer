//! 重ね合わせの取り消しとやり直しの試験。置き方の編集(`placement.rs`)・置いたクリップの音量のつまみ(`volume.rs`)・タイムラインの編集(`timeline.rs`)・
//! 登録した重ね合わせ(`library.rs`)ごとに分け、共に使う道具(1フレーム進めることと、編集の履歴の操作を当てること)をここに置く。

use std::time::Instant;

use clip_domain::音量;

use super::command::{編集の履歴の操作, 重ね合わせの操作};
use super::workspace::重ね合わせの作業場;

mod library;
mod placement;
mod timeline;
mod volume;

/// 1フレーム進める。前のフレームで当てた操作による重ね合わせの変化が、ここで履歴へ積まれる。
fn 一フレーム進める(作業場: &mut 重ね合わせの作業場) {
    let _ = 作業場.フレームを進める(Instant::now(), 音量::範囲へ収めて作る(1.0));
}

/// 編集の履歴の操作を作業場へ当てる。
fn 履歴の操作を当てる(
    作業場: &mut 重ね合わせの作業場, 操作: 編集の履歴の操作
) {
    作業場.操作を適用する(重ね合わせの操作::編集の履歴(操作));
}
