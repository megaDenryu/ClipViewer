//! 止まっている間に置いたときの絵の結合試験。前の置いたクリップのコマが残る行へ置いたとき、新しく置いたクリップのコマが載るまでは
//! その行を描かず、その間は描き直しを続け、コマが載ったら描くことを、作業場の口から確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use clip_domain::{
    クリップスタック, クリップ識別子, 正規化した動画パス, 音量
};
use video_source::{バイト数, メモリの上限, 動画の読み手};

use super::arrange_test_support::{クリップ, 値};
use super::command::重ね合わせの操作;
use super::sound_test_support::装置の無い作業場を作る;
use super::test_support::{置き方, 置き方を並べた重ね合わせ};
use super::workspace::重ね合わせの作業場;
use crate::video_feed::with_ffmpeg_support::{
    実行ファイルを探す, 成り立つまで待つ, 試験動画を作る,
};

/// 試験動画のファイル。落とすとファイルを消す。
struct 試験動画のファイル(正規化した動画パス);

impl Drop for 試験動画のファイル {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(self.0.文字列());
    }
}

fn 描く行の数(作業場: &重ね合わせの作業場) -> usize {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ねる画面に描く行の並び()
        .len()
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 前のコマが残る行へ置くと_コマが載るまで描かずに描き直しを続け_載ったら描く() {
    let 実行ファイル = 実行ファイルを探す();
    let ファイル =
        試験動画のファイル(試験動画を作る(&実行ファイル, "止まっている間に置く"));
    let 重ね合わせ = 置き方を並べた重ね合わせ(
        ファイル.0.clone(),
        4.0,
        &[&[置き方 {
            動画上の区間の開始: 0.5,
            動画上の区間の終了: 1.5,
            始まり: 0.0,
        }]],
    );
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.倉庫の上限で重ね合わせを開く(
        重ね合わせ,
        Some(&動画の読み手::作成する(実行ファイル)),
        メモリの上限::作成する(バイト数::作成する(1)),
    );
    成り立つまで待つ(
        "最初の置いたクリップのコマが載ること",
        || {
            作業場.フレームを進める(Instant::now(), 音量::起動したときの音量);
            描く行の数(&作業場) == 1
        },
    );
    作業場.操作を適用する(重ね合わせの操作::全体ループを設定する(
        false,
    ));
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    let 始め = Instant::now();
    作業場.フレームを進める(始め, 音量::起動したときの音量);
    作業場.フレームを進める(始め + Duration::from_secs(2), 音量::起動したときの音量);
    assert!(!作業場.状態().再生しているか(), "末尾(1秒)で止まる");
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("乙", 2.0, 3.0)]).expect("スタック");
    作業場.今のスタックのクリップを置く(
        &クリップ識別子::文字列から作成する("乙".to_string()).expect("識別子"),
        値(&スタック, &ファイル.0, 4.0),
    );
    assert_eq!(
        描く行の数(&作業場),
        0,
        "前の置いたクリップのコマが残る行を描かない"
    );
    成り立つまで待つ(
        "新しく置いたクリップのコマが載って描くこと",
        || {
            作業場.フレームを進める(Instant::now(), 音量::起動したときの音量);
            let 描く = 描く行の数(&作業場) == 1;
            assert!(
                描く || 作業場.状態().描き直しを続ける必要があるか(),
                "コマを待つ間は描き直しを続ける"
            );
            描く
        },
    );
}
