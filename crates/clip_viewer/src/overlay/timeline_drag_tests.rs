//! 塊のドラッグを確定する試験。動かしている間は重ね合わせを変えずに仮の行き先で描き、放したときに1回だけ確定することと、
//! 行の差を行の数へ収めることと、差0の放したは確定せず手で直したことにならないことを、作業場の口から確かめる。
//! 確定せずに捨てる場合は `timeline_drag_discard_tests.rs` が確かめる。参照: _doc/設計/同時再生.md 2-6
#![allow(clippy::expect_used)]

use super::command::塊の操作;
use super::placement_test_support::手で直したか;
use super::timeline_test_support::{
    二行を開いた作業場, 塊の並び, 塊の動き, 塊の操作を当てる, 塊を掴む, 置いてある行と始まり,
    行ごとに描く塊,
};

#[test]
fn 動かしている間は仮の行き先で描くだけで_放すとぶつかった所で1回だけ確定して手で直したことになる()
{
    let mut 作業場 = 二行を開いた作業場();
    塊を掴む(&mut 作業場, "置-2");
    塊の操作を当てる(
        &mut 作業場,
        塊の操作::動かしている(塊の動き("置-2", 5.0, 0)),
    );
    assert_eq!(
        行ごとに描く塊(&作業場),
        [
            塊の並び(&[("置-1", 0.0)]),
            塊の並び(&[("置-2", 2.0), ("置-3", 3.0)])
        ],
        "置-3 にぶつかった所(2秒)で止まった仮の行き先で描く"
    );
    assert_eq!(置いてある行と始まり(&作業場, "置-2"), (1, 0.0));
    assert!(!手で直したか(&作業場));
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-2", 5.0, 0)));
    assert_eq!(置いてある行と始まり(&作業場, "置-2"), (1, 2.0));
    assert!(手で直したか(&作業場));
}

#[test]
fn 行の差で動かすと行が変わり_行の数の外へは行の数へ収める() {
    let mut 作業場 = 二行を開いた作業場();
    塊を掴む(&mut 作業場, "置-3");
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-3", 0.0, -4)));
    assert_eq!(置いてある行と始まり(&作業場, "置-3"), (0, 3.0));
    塊を掴む(&mut 作業場, "置-3");
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-3", 1.0, 9)));
    assert_eq!(置いてある行と始まり(&作業場, "置-3"), (1, 4.0));
}

#[test]
fn 差0の放したと_ぶつかって動けなかった放したは確定せず手で直したことにならない() {
    let mut 作業場 = 二行を開いた作業場();
    塊を掴む(&mut 作業場, "置-2");
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-2", 0.0, 0)));
    塊を掴む(&mut 作業場, "置-1");
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-1", -3.0, 0)));
    assert_eq!(置いてある行と始まり(&作業場, "置-2"), (1, 0.0));
    assert_eq!(置いてある行と始まり(&作業場, "置-1"), (0, 0.0));
    assert!(!手で直したか(&作業場));
}
