//! 映す矩形のドラッグの試験。動かしている間は仮の矩形だけを変えて放したときに確定し、掴んだ枠が無くなったら確定せずに閉じることと、
//! 押しただけでは手で直したことにならないことと、絵の縦横比が分からないときに隅のつまみが掴み始めの形を保つことを、作業場の口から確かめる。
#![allow(clippy::expect_used)]

use super::command::映す矩形の枠の操作;
use super::placement_test_support::{
    動き, 右下, 左上の4分の1へ縮める, 手で直したか, 枠を当てる, 置いた, 置いた矩形, 重ねる枠,
    開いた作業場,
};
use super::state::placement::隅の縦横比の扱い;
use clip_domain::枠の掴む所;
#[test]
fn 動かしている間は仮の矩形だけが変わり_放すと確定して手で直したことになる() {
    let mut 作業場 = 開いた作業場();
    assert!(!手で直したか(&作業場));
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::掴み始めた(置いた("置-1")));
    let 縮める = 動き("置-1", 右下, -50.0, -50.0, 隅の縦横比の扱い::保たない);
    枠を当てる(
        &mut 作業場,
        映す矩形の枠の操作::動かしている(縮める.clone()),
    );
    assert_eq!(置いた矩形(&作業場, "置-1"), [0.0, 0.0, 100.0, 100.0]);
    assert_eq!(
        重ねる枠(&作業場, "置-1"),
        Some(([0.0, 0.0, 50.0, 50.0], false))
    );
    assert!(!手で直したか(&作業場));
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::放した(縮める));
    assert_eq!(置いた矩形(&作業場, "置-1"), [0.0, 0.0, 50.0, 50.0]);
    assert!(手で直したか(&作業場));
    let 動かす = 動き(
        "置-1",
        枠の掴む所::内側,
        10.0,
        20.0,
        隅の縦横比の扱い::絵の形を保つ,
    );
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::掴み始めた(置いた("置-1")));
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::放した(動かす));
    assert_eq!(置いた矩形(&作業場, "置-1"), [10.0, 20.0, 50.0, 50.0]);
}

#[test]
fn 掴んだ枠が無くなったら確定せずにドラッグを閉じ_押しただけなら手で直したことにならない() {
    let mut 作業場 = 開いた作業場();
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::掴み始めた(置いた("置-1")));
    let 縮める = 動き("置-1", 右下, -50.0, -50.0, 隅の縦横比の扱い::保たない);
    枠を当てる(
        &mut 作業場,
        映す矩形の枠の操作::動かしている(縮める.clone()),
    );
    枠を当てる(
        &mut 作業場,
        映す矩形の枠の操作::掴んだ枠が無くなった(置いた("置-1")),
    );
    assert_eq!(
        重ねる枠(&作業場, "置-1"),
        Some(([0.0, 0.0, 100.0, 100.0], false))
    );
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::放した(縮める));
    assert_eq!(置いた矩形(&作業場, "置-1"), [0.0, 0.0, 100.0, 100.0]);
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::掴み始めた(置いた("置-1")));
    let 動かさない = 動き(
        "置-1",
        枠の掴む所::内側,
        0.0,
        0.0,
        隅の縦横比の扱い::保たない,
    );
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::放した(動かさない));
    assert!(!手で直したか(&作業場));
}

#[test]
fn 動画を開けず絵の縦横比が分からないとき_縦横比を保つ隅のつまみは掴み始めの形を保つ() {
    let mut 作業場 = 開いた作業場();
    左上の4分の1へ縮める(&mut 作業場);
    let 広げる = 動き("置-1", 右下, 20.0, 0.0, 隅の縦横比の扱い::絵の形を保つ);
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::掴み始めた(置いた("置-1")));
    枠を当てる(&mut 作業場, 映す矩形の枠の操作::放した(広げる));
    assert_eq!(置いた矩形(&作業場, "置-1"), [0.0, 0.0, 70.0, 70.0]);
}
