//! タイムラインの編集の試験の道具。2行の重ね合わせを開いた作業場と、タイムラインの操作を作業場へ当てることと、塊のドラッグの動きと、
//! タイムラインに描く塊と置いてある行と始まりの時刻を読むことを受け持つ。
#![allow(clippy::expect_used)]

use clip_domain::{入力された動画パス, 時刻をずらす量, 行の差};

use super::command::{タイムラインの操作, 塊の操作, 重ね合わせの操作};
use super::placement_test_support::置いたクリップの識別子を作る;
use super::sound_test_support::装置の無い作業場を作る;
use super::state::timeline::{塊のドラッグの動き, 選んでいる行の番号と空か};
use super::test_support::{置き方, 置き方を並べた重ね合わせ};
use super::workspace::重ね合わせの作業場;

/// 1回だけ映す区間を、重ね合わせ上の始まりに置く置き方(区間は動画上の0秒からの長さの秒数)。
fn 長さと始まり(長さ: f64, 始まり: f64) -> 置き方 {
    置き方 {
        動画上の区間の開始: 0.0,
        動画上の区間の終了: 長さ,
        始まり,
    }
}

/// 行0に 置-1[0,2)、行1に 置-2[0,1) と 置-3[3,4) を置いた重ね合わせを、読み手を渡さずに開いた作業場(長さ4秒)。
pub(crate) fn 二行を開いた作業場() -> 重ね合わせの作業場 {
    let 動画 = 入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する();
    let 重ね合わせ = 置き方を並べた重ね合わせ(
        動画,
        10.0,
        &[
            &[長さと始まり(2.0, 0.0)],
            &[長さと始まり(1.0, 0.0), 長さと始まり(1.0, 3.0)],
        ],
    );
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.重ね合わせを開く(重ね合わせ, None);
    作業場
}

/// タイムラインの操作を作業場へ当てる。
pub(crate) fn タイムラインの操作を当てる(
    作業場: &mut 重ね合わせの作業場,
    操作: タイムラインの操作,
) {
    作業場.操作を適用する(重ね合わせの操作::タイムライン(操作));
}

/// 塊の操作を作業場へ当てる。
pub(crate) fn 塊の操作を当てる(
    作業場: &mut 重ね合わせの作業場, 操作: 塊の操作
) {
    タイムラインの操作を当てる(作業場, タイムラインの操作::塊(操作));
}

/// 対象の塊を掴み始めから秒数(後ろへが正)と行の数(手前へが正)だけ動かした動き。
pub(crate) fn 塊の動き(対象: &str, 秒: f64, 行の数: i32) -> 塊のドラッグの動き {
    塊のドラッグの動き {
        対象: 置いたクリップの識別子を作る(対象),
        ずらす量: 時刻をずらす量::符号付きの秒数から作成する(秒).expect("有限"),
        行の差: 行の差::手前へ動かした行の数から作成する(行の数),
    }
}

/// 対象の塊を掴み始める。
pub(crate) fn 塊を掴む(作業場: &mut 重ね合わせの作業場, 対象: &str) {
    塊の操作を当てる(
        作業場,
        塊の操作::掴み始めた(置いたクリップの識別子を作る(対象)),
    );
}

/// タイムラインに描く塊を、奥の行から行ごとに、識別子の文字列と始まりの秒数の組で並べる。
pub(crate) fn 行ごとに描く塊(
    作業場: &重ね合わせの作業場
) -> Vec<Vec<(String, f64)>> {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .タイムラインに描く行の並び()
        .into_iter()
        .map(|行| {
            行.into_iter()
                .map(|塊| (塊.識別子.文字列().to_string(), 塊.始まりの時刻.秒数()))
                .collect()
        })
        .collect()
}

/// 開いている重ね合わせの、識別子の置いたクリップを置いてある行の番号と始まりの秒数。
pub(crate) fn 置いてある行と始まり(
    作業場: &重ね合わせの作業場,
    対象: &str,
) -> (usize, f64) {
    let 行き先 = 作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ね合わせ()
        .行の並び()
        .今の行き先(&置いたクリップの識別子を作る(対象))
        .expect("置いてある");
    (行き先.行.番号(), 行き先.始まりの時刻.秒数())
}

/// 開いている重ね合わせの選んでいる行の番号と空か。
pub(crate) fn 選んでいる行(
    作業場: &重ね合わせの作業場,
) -> Option<選んでいる行の番号と空か> {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .選んでいる行の番号と空か()
}

/// 文字列と秒数の組の並びを作る(期待する描く塊の並びを書くため)。
pub(crate) fn 塊の並び(並び: &[(&str, f64)]) -> Vec<(String, f64)> {
    並び
        .iter()
        .map(|(識別子, 秒)| ((*識別子).to_string(), *秒))
        .collect()
}
