//! 置き方の編集の試験の道具。五秒の重ね合わせを開いた作業場と、置き方の操作を作業場へ当てることと、映す矩形のドラッグの動きと、重ねる枠と置いたクリップの映す矩形を読むことを受け持つ。
#![allow(clippy::expect_used)]

use clip_domain::枠の掴む所;
use clip_domain::{
    四隅のつまみ, 映す矩形, 映す矩形の移動量, 百分率, 百分率の差分, 置いたクリップの識別子,
};

use super::command::{映す矩形の枠の操作, 置き方の操作, 重ね合わせの操作};
use super::sound_test_support::装置の無い作業場を作る;
use super::state::placement::{映す矩形のドラッグの動き, 隅の縦横比の扱い};
use super::test_support::五秒の重ね合わせ;
use super::workspace::重ね合わせの作業場;

/// 置き方の操作を作業場へ当てる。
pub(crate) fn 当てる(作業場: &mut 重ね合わせの作業場, 操作: 置き方の操作) {
    作業場.操作を適用する(重ね合わせの操作::置き方(操作));
}

/// 映す矩形の枠の操作を作業場へ当てる。
pub(crate) fn 枠を当てる(
    作業場: &mut 重ね合わせの作業場, 操作: 映す矩形の枠の操作
) {
    当てる(作業場, 置き方の操作::映す矩形の枠(操作));
}

/// 識別子の文字列から置いたクリップの識別子を作る。
pub(crate) fn 置いた(文字列: &str) -> 置いたクリップの識別子 {
    置いたクリップの識別子::文字列から作成する(文字列.to_string()).expect("空でない")
}

/// 対象を掴む所で掴み始めから横と縦(百分率)だけ動かした動き。
pub(crate) fn 動き(
    対象: &str,
    掴む所: 枠の掴む所,
    横: f64,
    縦: f64,
    縦横比: 隅の縦横比の扱い,
) -> 映す矩形のドラッグの動き {
    映す矩形のドラッグの動き {
        対象: 置いた(対象),
        掴む所,
        移動量: 映す矩形の移動量 {
            横: 百分率の差分::作成する(横).expect("有限"),
            縦: 百分率の差分::作成する(縦).expect("有限"),
        },
        縦横比,
    }
}

/// 映す矩形の左端・上端・幅・高さの百分率の数値。
pub(crate) fn 数値の組(矩形: 映す矩形) -> [f64; 4] {
    [矩形.左端(), 矩形.上端(), 矩形.幅(), 矩形.高さ()].map(百分率::数値)
}

/// 開いている重ね合わせの、識別子の置いたクリップの(確定した)映す矩形の数値。
pub(crate) fn 置いた矩形(作業場: &重ね合わせの作業場, 対象: &str) -> [f64; 4] {
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    let 置いたクリップ = 開いている
        .重ね合わせ()
        .識別子で探す(&置いた(対象))
        .expect("置いたクリップ");
    数値の組(置いたクリップ.映す矩形())
}

/// 開いている重ね合わせの重ねる枠の並びの、識別子の枠の矩形の数値と、選んでいるか。
pub(crate) fn 重ねる枠(
    作業場: &重ね合わせの作業場, 対象: &str
) -> Option<([f64; 4], bool)> {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ねる枠の並び()
        .into_iter()
        .find(|枠| 枠.識別子 == 置いた(対象))
        .map(|枠| (数値の組(枠.矩形), 枠.選んでいるか))
}

/// 右下の隅のつまみ。
pub(crate) const 右下: 枠の掴む所 = 枠の掴む所::隅(四隅のつまみ::右下);

/// 五秒の重ね合わせを開いた作業場。
pub(crate) fn 開いた作業場() -> 重ね合わせの作業場 {
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    作業場
}

/// 開いている重ね合わせの置き方を手で直したか。
pub(crate) fn 手で直したか(作業場: &重ね合わせの作業場) -> bool {
    作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .置き方を手で直したか()
}

/// 右下の隅を縦横比を保たずに(-50, -50)動かして、映す矩形を左上の4分の1にして放す。
pub(crate) fn 左上の4分の1へ縮める(作業場: &mut 重ね合わせの作業場) {
    let 縮める = 動き("置-1", 右下, -50.0, -50.0, 隅の縦横比の扱い::保たない);
    枠を当てる(作業場, 映す矩形の枠の操作::掴み始めた(置いた("置-1")));
    枠を当てる(作業場, 映す矩形の枠の操作::放した(縮める));
}
