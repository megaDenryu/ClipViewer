//! 読み取り専用のアプリの重ね合わせの作業場の試験。別のアプリがライブラリの錠を持っているとき、重ね合わせを登録できずにその旨を知らせ、
//! 一覧は読めて開けるが未登録として開き、変えても保存しないことを確かめる。置き場所は一時フォルダである。参照: _doc/設計/同時再生.md 2-7、_doc/設計/ライブラリ.md 判断9
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use clip_domain::{アスペクト比設定, 重ねる画面の縦横比};
use clip_library::重ね合わせの錠を取れない理由;

use super::command::{
    一覧とダイアログの操作, 置き方の操作, 重ね合わせのライブラリの操作, 重ね合わせの操作,
};
use super::library_test_ops::{
    ライブラリの操作を当てる, 名前を付けて登録する, 書き終えるまで待って進める,
};
use super::library_test_support::一時のライブラリ;
use super::sound_test_support::知らせの文;
use super::state::library::{
    重ね合わせのダイアログ, 重ね合わせのライブラリの使える様子,
    開いている重ね合わせのライブラリの様子,
};
use super::test_support::五秒の重ね合わせ;

fn 知らせたか(作業場: &super::workspace::重ね合わせの作業場, 文: &str) -> bool {
    知らせの文(作業場).iter().any(|知らせ| 知らせ.contains(文))
}

#[test]
fn 読み取り専用のアプリは登録できず_一覧から未登録で開き_変えても保存しない() {
    let 一時 = 一時のライブラリ::作る("読み取り専用");
    let 一つ目 = 一時.錠を試す();
    let mut 書ける = 一時.作業場を作る(一つ目.重ね合わせ);
    書ける.重ね合わせを開く(五秒の重ね合わせ(), None);
    名前を付けて登録する(&mut 書ける, "ふたり");
    書き終えるまで待って進める(&mut 書ける, Instant::now());
    let 二つ目 = 一時.錠を試す();
    let mut 読むだけ = 一時.作業場を作る(二つ目.重ね合わせ);
    assert!(matches!(
        読むだけ.状態().ライブラリの使える様子(),
        重ね合わせのライブラリの使える様子::読むだけ(
            _,
            重ね合わせの錠を取れない理由::スタックのライブラリの錠を持っていない
        )
    ));
    読むだけ.重ね合わせを開く(五秒の重ね合わせ(), None);
    ライブラリの操作を当てる(
        &mut 読むだけ,
        重ね合わせのライブラリの操作::一覧とダイアログ(
            一覧とダイアログの操作::登録のダイアログを開く,
        ),
    );
    assert_eq!(
        読むだけ.状態().ライブラリのダイアログ(),
        &重ね合わせのダイアログ::無し
    );
    assert!(知らせたか(
        &読むだけ,
        "重ね合わせのライブラリは読み取り専用である("
    ));
    ライブラリの操作を当てる(
        &mut 読むだけ,
        重ね合わせのライブラリの操作::重ね合わせを閉じる,
    );
    書き終えるまで待って進める(&mut 読むだけ, Instant::now());
    let 識別子 = 一時.保存した重ね合わせ()[0].識別子().clone();
    ライブラリの操作を当てる(&mut 読むだけ, 重ね合わせのライブラリの操作::開く(識別子));
    assert!(matches!(
        読むだけ.状態().開いている重ね合わせのライブラリの様子(),
        Some(開いている重ね合わせのライブラリの様子::未登録)
    ));
    assert!(知らせたか(
        &読むだけ,
        "重ね合わせをライブラリから読み取り専用で開きました: ふたり。変更はライブラリへ保存しない"
    ));
    let 正方形 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    読むだけ.操作を適用する(重ね合わせの操作::置き方(
        置き方の操作::重ねる画面の縦横比を選ぶ(正方形),
    ));
    let 始め = Instant::now();
    読むだけ.ライブラリとサムネイルを進める(始め, None);
    読むだけ.ライブラリとサムネイルを進める(始め + Duration::from_secs(1), None);
    読むだけ.終わる前に保存を頼む();
    書き終えるまで待って進める(&mut 読むだけ, 始め + Duration::from_secs(2));
    assert_eq!(
        一時.保存した重ね合わせ()[0].重ね合わせ().縦横比(),
        重ねる画面の縦横比::ワイド16対9,
        "読み取り専用のアプリは保存しない"
    );
    drop((読むだけ, 二つ目.スタック, 書ける, 一つ目.スタック));
}
