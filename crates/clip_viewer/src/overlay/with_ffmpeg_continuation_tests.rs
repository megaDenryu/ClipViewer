//! 続く先を止まるにする行の結合試験(映像の側)。3つの行それぞれで、隙間なく続く2つの置いたクリップの前の方のコマを載せた後、
//! 塊を確定したときは動かした置いたクリップの元の行と先の行だけ、空の行を消したときは番号が変わる行だけ、続く先を止まるにする
//! (前の置いたクリップのコマを、続く置いたクリップの代わりに描かなくなる)ことを、行の映像の描き方から確かめる。音の側は
//! `timeline_continuation_sound_tests.rs`、再生の位置を動かしたときは `with_ffmpeg_seek_tests.rs` が確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use clip_domain::行の番号;

use super::command::{タイムラインの操作, 塊の操作, 置き方の操作};
use super::placement_test_support::{
    置いたクリップの識別子を作る, 置き方の操作を当てる
};
use super::timeline_test_support::{
    タイムラインの操作を当てる, 塊の動き, 塊の操作を当てる, 塊を掴む,
};
use super::with_ffmpeg_continuation_support::{三行のコマを載せた作業場, 描き方};

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 塊を確定すると_元の行と先の行だけ前の置いたクリップのコマを描かなくなる() {
    let (mut 作業場, _ファイル) = 三行のコマを載せた作業場("塊を確定する", false);
    assert_eq!(描き方(&作業場, 0, "置-2"), "前の置いたクリップのコマ(置-1)");
    // 行1の 置-4(1秒)を行2へ。行2の1秒は 置-6 が塞ぐため、望む2秒(行2の空き)へ置く。
    塊を掴む(&mut 作業場, "置-4");
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-4", 1.0, 1)));
    assert_eq!(
        描き方(&作業場, 0, "置-2"),
        "前の置いたクリップのコマ(置-1)",
        "行0は変えない"
    );
    assert_eq!(描き方(&作業場, 1, "置-4"), "描かない", "元の行");
    assert_eq!(描き方(&作業場, 2, "置-6"), "描かない", "先の行");
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 空の行を消すと_番号が変わる行だけ前の置いたクリップのコマを描かなくなる() {
    let (mut 作業場, _ファイル) = 三行のコマを載せた作業場("空の行を消す", true);
    for 識別子 in ["置-3", "置-4"] {
        置き方の操作を当てる(
            &mut 作業場,
            置き方の操作::置いたクリップを取り除く(置いたクリップの識別子を作る(
                識別子,
            )),
        );
    }
    // 行1の映像には、同じ区間へ続く 置-3 のコマが残る。消した後、行1は 置-5 と 置-6 の行になる。
    assert_eq!(描き方(&作業場, 1, "置-5"), "前の置いたクリップのコマ(置-3)");
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::行を選ぶ(行の番号::番号から作成する(1)),
    );
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::選んでいる空の行を消す,
    );
    assert_eq!(
        描き方(&作業場, 0, "置-2"),
        "前の置いたクリップのコマ(置-1)",
        "行0は変えない"
    );
    assert_eq!(描き方(&作業場, 1, "置-5"), "描かない", "番号が変わった行");
    assert_eq!(描き方(&作業場, 2, "置-6"), "描かない", "番号が変わった行");
}
