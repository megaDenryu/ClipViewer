//! 時間の軸の位置の線を掴んでいる間の音の結合試験。スタックの作業場の再生位置の帯と同じく、再生していても位置の線を掴んでいる間は
//! どの行も止めている指示にして黙らせ、放すと再生している指示に戻ることを、行ごとの再生の指示から確かめる(画面.md 判断10)。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use audio_output::{再生の様子, 行ごとの再生の指示};
use audio_pcm::サンプリング周波数;
use clip_domain::{重ね合わせ上の秒, 音量};
use eframe::egui;
use video_source::{メモリの上限, 動画の読み手};

use super::command::{タイムラインの操作, 重ね合わせの操作};
use super::sound_test_support::{
    溜めた音か, 行の指示を取り出す, 音付きの試験動画
};
use super::state::grab::位置の線の段階;
use super::state::重ね合わせの音の出力の状況;
use super::test_support::{置き方, 置き方を並べた重ね合わせ};
use super::timeline_test_support::タイムラインの操作を当てる;
use super::workspace::重ね合わせの作業場;
use crate::video_feed::with_ffmpeg_support::{
    実行ファイルを探す, 成り立つまで待つ
};

fn 二つの行の様子(指示: &行ごとの再生の指示) -> [再生の様子; 2] {
    [0, 1].map(|番号| 行の指示を取り出す(&mut 指示.clone(), 番号).様子)
}

fn 位置の線を当てる(
    作業場: &mut 重ね合わせの作業場, 段階: 位置の線の段階
) {
    let 時刻 = 重ね合わせ上の秒::作成する(0.5).expect("時刻");
    タイムラインの操作を当てる(
        作業場,
        タイムラインの操作::再生の位置を動かす(段階, 時刻),
    );
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 位置の線を掴んでいる間はどの行も黙り_放すと再生している指示に戻る() {
    let 動画 = 音付きの試験動画::作る("位置の線を掴む");
    let 置き方 = |開始: f64| 置き方 {
        動画上の区間の開始: 開始,
        動画上の区間の終了: 開始 + 2.0,
        始まり: 0.0,
    };
    let 周波数 = サンプリング周波数::作成する(48_000).expect("周波数");
    let mut 作業場 = 重ね合わせの作業場::開いていない作業場(
        egui::Context::default(),
        重ね合わせの音の出力の状況::使える(周波数),
    );
    作業場.倉庫の上限で重ね合わせを開く(
        置き方を並べた重ね合わせ(
            動画.0.clone(),
            4.0,
            &[&[置き方(0.5)], &[置き方(1.5)]],
        ),
        Some(&動画の読み手::作成する(実行ファイルを探す())),
        メモリの上限::既定,
    );
    作業場.操作を適用する(重ね合わせの操作::全体ループを設定する(
        true,
    ));
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    成り立つまで待つ("両方の行が溜めた音で鳴ること", || {
        let 指示 = 作業場.フレームを進める(Instant::now(), 音量::元の大きさ);
        [0, 1]
            .iter()
            .all(|番号| 溜めた音か(&行の指示を取り出す(&mut 指示.clone(), *番号)))
    });
    let 鳴っている = 作業場.フレームを進める(Instant::now(), 音量::元の大きさ);
    assert_eq!(二つの行の様子(&鳴っている), [再生の様子::再生している; 2]);
    位置の線を当てる(&mut 作業場, 位置の線の段階::掴み始めた);
    let 掴んでいる = 作業場.フレームを進める(Instant::now(), 音量::元の大きさ);
    assert_eq!(二つの行の様子(&掴んでいる), [再生の様子::止めている; 2]);
    assert!(作業場.状態().再生しているか(), "再生しているかは変えない");
    位置の線を当てる(&mut 作業場, 位置の線の段階::放した);
    let 放した = 作業場.フレームを進める(Instant::now(), 音量::元の大きさ);
    assert_eq!(二つの行の様子(&放した), [再生の様子::再生している; 2]);
}
