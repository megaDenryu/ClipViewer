//! 今のスタックのクリップを置くことの試験。置くと今の再生の位置の空いている最も手前の行へ置いて選び、手で直したことになることと、
//! スタックの動画が重ね合わせの動画と違うときと置く操作が拒んだときは置かずに理由を知らせることを、作業場の口から確かめる。
#![allow(clippy::expect_used)]

use eframe::egui;

use clip_domain::{クリップスタック, クリップ識別子, 入力された動画パス};
use sengen_egui::{並べる通知, 通知の回};

use super::arrange_test_support::{クリップ, 値, 練習の動画};
use super::state::{動画が違うため置けない文, 置くクリップの動画};
use super::test_support::五秒の重ね合わせ;
use super::workspace::重ね合わせの作業場;

fn 開いた作業場() -> 重ね合わせの作業場 {
    let mut 作業場 =
        重ね合わせの作業場::開いていない作業場(egui::Context::default());
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    作業場
}

fn 乙() -> クリップ識別子 {
    クリップ識別子::文字列から作成する("乙".to_string()).expect("識別子")
}

#[test]
fn 置くと今の位置の空いている最も手前の行へ置いて選び_手で直したことになる() {
    let mut 作業場 = 開いた作業場();
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("乙", 10.0, 12.0)]).expect("スタック");
    let パス = 練習の動画();
    let 今のスタック = 値(&スタック, &パス, 60.0);
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert!(matches!(
        今のスタック.置くクリップの動画(開いている.重ね合わせ().動画の表()),
        置くクリップの動画::置ける { .. }
    ));
    作業場.今のスタックのクリップを置く(&乙(), 今のスタック);
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert_eq!(開いている.重ね合わせ().行の並び().行の数(), 2);
    let 選んでいる = 開いている
        .選んでいる置いたクリップ()
        .expect("置いたクリップを選んでいる");
    assert_eq!(選んでいる.受け継いだ値().名前.文字列(), "乙");
    assert_eq!(選んでいる.始まりの時刻().秒数(), 0.0);
    assert!(開いている.置き方を手で直したか());
}

#[test]
fn 動画が違うときと置く操作が拒んだときは置かずに理由を知らせる() {
    let mut 作業場 = 開いた作業場();
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("乙", 10.0, 70.0)]).expect("スタック");
    let 別の動画 = 入力された動画パス::作成する(r"C:\別.mp4".to_string()).正規化する();
    作業場.今のスタックのクリップを置く(&乙(), 値(&スタック, &別の動画, 60.0));
    let パス = 練習の動画();
    作業場.今のスタックのクリップを置く(&乙(), 値(&スタック, &パス, 60.0));
    // 注意: 読み手を渡さずに開いたため、最初の知らせは FFmpeg が無いことの知らせである。
    let 最初 = 通知の回::default().次();
    assert_eq!(
        作業場.状態().並べる知らせ()[1..],
        [
            並べる通知::作成する(最初, 動画が違うため置けない文),
            並べる通知::作成する(
                最初.次(),
                "「乙」を置けない: 区間の終わり(70秒)が動画の長さ(60秒)より後ろにある",
            ),
        ]
    );
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert_eq!(開いている.奥から手前の順の置いたクリップ().count(), 1);
    assert!(!開いている.置き方を手で直したか());
}
