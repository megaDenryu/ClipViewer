//! 今のスタックから並べることの試験の道具。区間を決めたクリップと、試験で開いている動画と、今のスタックの値を作る。
#![allow(clippy::expect_used)]

use clip_domain::{
    アスペクト比設定, クリップ, クリップスタック, クリップ名, クリップ識別子, 入力された動画パス,
    動画上の区間, 時刻, 時間の長さ, 正規化した動画パス,
};

use super::state::{今のスタックの値, 開いている動画の値};

/// 名前のクリップを、区間を開始から終了(動画上の秒)にして作る。
pub(crate) fn クリップ(名前: &str, 開始: f64, 終了: f64) -> クリップ {
    let mut クリップ = クリップ::既定値で作成する(
        クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子"),
        クリップ名::作成する(名前.to_string()),
    );
    クリップ.区間 = 動画上の区間::作成する(
        時刻::作成する(開始).expect("時刻"),
        時刻::作成する(終了).expect("時刻"),
    )
    .expect("区間");
    クリップ
}

/// 試験で開いている動画のパス。
pub(crate) fn 練習の動画() -> 正規化した動画パス {
    入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する()
}

/// スタックと、長さの秒の動画を開いている、出力のアスペクト比が「クロップ枠に合わせる」の今のスタックの値。
pub(crate) fn 値<'a>(
    スタック: &'a クリップスタック,
    パス: &'a 正規化した動画パス,
    長さの秒: f64,
) -> 今のスタックの値<'a> {
    今のスタックの値 {
        スタック,
        開いている動画: Some(開いている動画の値 {
            パス,
            長さ: 時間の長さ::作成する(長さの秒).expect("長さ"),
        }),
        出力のアスペクト比: アスペクト比設定::クロップ連動,
    }
}
