//! 重ね合わせの作業場の音の出力の知らせの試験。2本目の流れを開けなかったことと、途中で使えなくなったことを1回だけ知らせ、
//! 使えなくなった後は音の様子にその理由を出すことを確かめる。
#![allow(clippy::expect_used)]

use audio_output::音声出力のエラー;
use audio_pcm::サンプリング周波数;
use eframe::egui;

use super::sound_test_support::{知らせの文, 装置の無い作業場};
use super::state::重ね合わせの音の出力の状況;
use super::workspace::重ね合わせの作業場;

#[test]
fn 開けなかったことと途中で使えなくなったことを1回だけ知らせる() {
    let mut 開けない = 装置の無い作業場();
    開けない.開けなかった音の出力を知らせる();
    assert_eq!(知らせの文(&開けない).len(), 1);
    assert!(知らせの文(&開けない)[0].contains(
        "音声出力装置が見つからない。重ね合わせの作業場は音を鳴らさずに映像だけで再生する"
    ));
    let 周波数 = サンプリング周波数::作成する(48_000).expect("周波数");
    let mut 使える = 重ね合わせの作業場::開いていない作業場(
        egui::Context::default(),
        重ね合わせの音の出力の状況::使える(周波数),
    );
    使える.開けなかった音の出力を知らせる();
    assert!(知らせの文(&使える).is_empty(), "開けたなら知らせない");
    使える.音の出力が使えなくなった(音声出力のエラー::装置が無い);
    使える.音の出力が使えなくなった(音声出力のエラー::装置が無い);
    assert_eq!(
        知らせの文(&使える).len(),
        1,
        "使えなくなったことは1回だけ知らせる"
    );
    assert!(
        知らせの文(&使える)[0]
            .contains("音声出力装置が見つからない。重ね合わせの作業場は映像だけで再生を続ける")
    );
    assert_eq!(
        使える.状態().音の様子の文の並び(),
        ["音: 鳴らせない(音声出力装置が見つからない)"]
    );
}
