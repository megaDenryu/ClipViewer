//! 重ね合わせの作業場の試験。開いていない間と長さ0秒の重ね合わせは再生を始めないことと、時計が実時間の経過で進み末尾で全体ループに従うことと、
//! 控える前に再生を止めて位置を残すことと、落とされたファイルを開かずに知らせることと、
//! 動画の読み手を借りられないときは映像の供給を作らずに時計だけ進むことを、作業場の口から確かめる。

use std::time::{Duration, Instant};

use eframe::egui;
use sengen_egui::{並べる通知, 通知の回};

use super::command::{落とされたファイルの知らせ, 重ね合わせの操作};
use super::test_support::{五秒の重ね合わせ, 長さが0秒の重ね合わせ};
use super::workspace::重ね合わせの作業場;
use crate::video_feed::動画を開けない理由;

fn 秒(作業場: &重ね合わせの作業場) -> Option<f64> {
    作業場
        .状態()
        .再生の位置と長さ()
        .map(|(位置, _)| 位置.時刻().秒数())
}

#[test]
fn 重ね合わせを開いていない間は再生を始めず_位置と長さも無い() {
    let mut 作業場 = 重ね合わせの作業場::開いていない作業場();
    assert!(!作業場.状態().再生を始められるか());
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    assert!(!作業場.状態().再生しているか());
    assert_eq!(作業場.状態().再生の位置と長さ(), None);
}

#[test]
fn 長さが0秒の重ね合わせは再生を始めず_0秒に留まる() {
    let mut 作業場 = 重ね合わせの作業場::開いていない作業場();
    作業場.重ね合わせを開く(長さが0秒の重ね合わせ(), None, &egui::Context::default());
    assert!(!作業場.状態().再生を始められるか());
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    assert!(!作業場.状態().再生しているか());
    作業場.フレームを進める(Instant::now() + Duration::from_secs(3));
    assert_eq!(秒(&作業場), Some(0.0));
}

#[test]
fn 再生している間だけ時計が実時間の経過で進み_末尾を越えると全体ループで先頭へ戻る() {
    let mut 作業場 = 重ね合わせの作業場::開いていない作業場();
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None, &egui::Context::default());
    let 始め = Instant::now();
    作業場.フレームを進める(始め + Duration::from_secs(1));
    assert_eq!(秒(&作業場), Some(0.0), "止まっている間は進まない");
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    作業場.フレームを進める(始め);
    作業場.フレームを進める(始め + Duration::from_secs(2));
    assert!(秒(&作業場).is_some_and(|秒| (秒 - 2.0).abs() < 1e-9));
    作業場.フレームを進める(始め + Duration::from_secs(6));
    assert_eq!(秒(&作業場), Some(0.0));
    assert!(作業場.状態().再生しているか());
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    assert!(!作業場.状態().再生しているか());
}

#[test]
fn 控える前に再生を止め_再生の位置は残す() {
    let mut 作業場 = 重ね合わせの作業場::開いていない作業場();
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None, &egui::Context::default());
    let 始め = Instant::now();
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    作業場.フレームを進める(始め);
    作業場.フレームを進める(始め + Duration::from_secs(2));
    作業場.控える前に再生を止める();
    assert!(!作業場.状態().再生しているか());
    assert!(秒(&作業場).is_some_and(|秒| (秒 - 2.0).abs() < 1e-9));
}

#[test]
fn 落とされたファイルは開かずに_スタックへ戻ってから落とすよう知らせる() {
    let mut 作業場 = 重ね合わせの作業場::開いていない作業場();
    作業場.操作を適用する(重ね合わせの操作::ファイルを落とされた);
    assert_eq!(
        作業場.状態().並べる知らせ(),
        [並べる通知::作成する(
            通知の回::最初(),
            落とされたファイルの知らせ
        )]
    );
}

#[test]
fn 読み手を借りられないときは_映像の供給を作らずにffmpegが無いことを持ち_時計は進む() {
    let mut 作業場 = 重ね合わせの作業場::開いていない作業場();
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None, &egui::Context::default());
    let 理由 = 作業場
        .状態()
        .開いている重ね合わせ()
        .and_then(|開いている| 開いている.映像().供給できない理由());
    assert!(matches!(理由, Some(動画を開けない理由::FFmpegが無い)));
    let 始め = Instant::now();
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    作業場.フレームを進める(始め);
    作業場.フレームを進める(始め + Duration::from_secs(1));
    assert!(秒(&作業場).is_some_and(|秒| (秒 - 1.0).abs() < 1e-9));
}
