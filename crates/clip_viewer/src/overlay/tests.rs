//! 重ね合わせの作業場の状態の試験。再生と停止の切り替えと、時計が実時間の経過で進み、末尾で全体ループに従うことと、
//! 「スタックへ戻る」がスタックの作業場を前に出す頼みを返し、状態を変えないことを確かめる。
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use clip_domain::{
    アスペクト比設定, クリップ, クリップスタック, クリップ名, クリップ識別子, 入力された動画パス,
    時間の長さ, 置いたクリップの識別子, 置いたクリップの識別子の発行元, 重ね合わせ,
};

use super::command::{操作の後の作業場, 重ね合わせの操作};
use super::state::重ね合わせの作業場の状態;

/// 「置-1」「置-2」…を順に発行する、試験用の決まった発行元。
#[derive(Default)]
struct 置いた連番の発行元(u32);

impl 置いたクリップの識別子の発行元 for 置いた連番の発行元 {
    fn 新しい識別子を発行する(&mut self) -> 置いたクリップの識別子 {
        self.0 += 1;
        置いたクリップの識別子::文字列から作成する(format!("置-{}", self.0)).expect("空でない")
    }
}

/// 0秒から5秒の区間を1回だけ映すクリップを1つ並べた重ね合わせ(長さ5秒)を持つ状態。
fn 五秒の重ね合わせを持つ状態() -> 重ね合わせの作業場の状態 {
    let クリップ = クリップ::既定値で作成する(
        クリップ識別子::文字列から作成する("甲".to_string()).expect("識別子"),
        クリップ名::作成する("甲".to_string()),
    );
    let スタック = クリップスタック::一覧から作成する(vec![クリップ]).expect("スタック");
    let 並べた結果 = 重ね合わせ::スタックから並べる(
        &スタック,
        入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
        時間の長さ::作成する(60.0).expect("長さ"),
        アスペクト比設定::ワイド16対9,
        &mut 置いた連番の発行元::default(),
    )
    .expect("並べられる");
    let mut 状態 = 重ね合わせの作業場の状態::何も置いていない();
    状態.重ね合わせ = 並べた結果.重ね合わせ;
    状態
}

fn 秒(状態: &重ね合わせの作業場の状態) -> f64 {
    状態.再生.位置().時刻().秒数()
}

#[test]
fn 何も置いていない重ね合わせは再生しても0秒に留まる() {
    let mut 状態 = 重ね合わせの作業場の状態::何も置いていない();
    状態.操作を適用する(重ね合わせの操作::再生を切り替える);
    assert!(状態.再生.再生しているか());
    let 始め = Instant::now();
    状態.時計を進める(始め);
    状態.時計を進める(始め + Duration::from_secs(3));
    assert_eq!(秒(&状態), 0.0);
}

#[test]
fn 再生している間だけ時計が実時間の経過で進み_末尾を越えると全体ループで先頭へ戻る() {
    let mut 状態 = 五秒の重ね合わせを持つ状態();
    let 始め = Instant::now();
    状態.時計を進める(始め + Duration::from_secs(1));
    assert_eq!(秒(&状態), 0.0, "止まっている間は進まない");
    状態.操作を適用する(重ね合わせの操作::再生を切り替える);
    状態.時計を進める(始め);
    状態.時計を進める(始め + Duration::from_secs(2));
    assert!((秒(&状態) - 2.0).abs() < 1e-9, "{}", 秒(&状態));
    状態.時計を進める(始め + Duration::from_secs(6));
    assert_eq!(秒(&状態), 0.0);
    assert!(状態.再生.再生しているか());
    状態.操作を適用する(重ね合わせの操作::再生を切り替える);
    assert!(!状態.再生.再生しているか());
}

#[test]
fn スタックへ戻る操作はスタックの作業場を前に出す頼みを返し_再生の状況を変えない() {
    let mut 状態 = 五秒の重ね合わせを持つ状態();
    状態.操作を適用する(重ね合わせの操作::再生を切り替える);
    assert_eq!(
        状態.操作を適用する(重ね合わせの操作::スタックの作業場へ戻る),
        操作の後の作業場::スタックの作業場を前に出す
    );
    assert!(状態.再生.再生しているか());
}
