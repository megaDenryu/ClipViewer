//! 時間の軸の位置の線を掴んでいる間の映像の結合試験。掴んでいる間は行の流し読みを開き直さない(画面.md 判断5)ことが、映像の供給まで届くことを、
//! 行のテクスチャに載ったコマの番号から確かめる。流し読みは前へしか読めないため、後ろの位置から前の位置へ動かすと、開き直さない限り前のコマは載らない。
//! 音の供給まで届くことは `timeline_seek_tests.rs` が確かめる。FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ流す。
