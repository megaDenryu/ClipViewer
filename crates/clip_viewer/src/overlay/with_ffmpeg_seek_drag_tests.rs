/// 行0のテクスチャに載ったコマの番号(30コマ/秒)。まだ載せていなければ無い。
fn 載せた番号(作業場: &重ね合わせの作業場) -> Option<u32> {
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    let 重ね合わせの映像の供給を作れたか::作れた(供給) = 開いている.映像の供給を作れたか()
    else {
        panic!("映像の供給を作れている");
    };
    供給
        .行のコマの載せ先(行の番号::番号から作成する(0))
        .expect("行0")
        .テクスチャ()
        .載せたコマ()
        .map(|載せたコマ| 載せたコマ.番号.値())
}

fn 位置の線を当てる(
    作業場: &mut 重ね合わせの作業場, 段階: 位置の線の段階, 秒: f64
) {
    let 時刻 = 重ね合わせ上の秒::作成する(秒).expect("時刻");
    タイムラインの操作を当てる(
        作業場,
        タイムラインの操作::再生の位置を動かす(段階, 時刻),
    );
}

fn 進める(作業場: &mut 重ね合わせの作業場) {
    作業場.フレームを進める(Instant::now(), 音量::起動したときの音量);
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 位置の線を掴んでいる間は行の流し読みを開き直さず_放すと開き直す() {
    let 実行ファイル = 実行ファイルを探す();
    let ファイル = 試験動画のファイル(試験動画を作る(&実行ファイル, "位置の線を掴む映像"));
    let 区間の全体 = 置き方 {
        動画上の区間の開始: 0.0,
        動画上の区間の終了: 3.5,
        始まり: 0.0,
    };
    let mut 作業場 = 装置の無い作業場を作る();
    // 倉庫の上限を1バイトにして溜めさせず、流し読みの経路だけを通す。
    作業場.倉庫の上限で重ね合わせを開く(
        置き方を並べた重ね合わせ(ファイル.0.clone(), 4.0, &[&[区間の全体]]),
        Some(&動画の読み手::作成する(実行ファイル)),
        メモリの上限::作成する(バイト数::作成する(1)),
    );
    位置の線を当てる(&mut 作業場, 位置の線の段階::掴み始めた, 2.0);
    位置の線を当てる(&mut 作業場, 位置の線の段階::放した, 2.0);
    成り立つまで待つ("2秒あたりのコマが載ること", || {
        進める(&mut 作業場);
        載せた番号(&作業場).is_some_and(|番号| 番号 >= 55)
    });
    位置の線を当てる(&mut 作業場, 位置の線の段階::掴み始めた, 0.5);
    let 始め = Instant::now();
    while 始め.elapsed() < Duration::from_millis(700) {
        進める(&mut 作業場);
        assert!(
            載せた番号(&作業場).is_some_and(|番号| 番号 >= 55),
            "掴んでいる間は開き直さないため、0.5秒のコマは載らない"
        );
        std::thread::sleep(Duration::from_millis(20));
    }
    位置の線を当てる(&mut 作業場, 位置の線の段階::放した, 0.5);
    成り立つまで待つ(
        "放した後に開き直して0.5秒あたりのコマが載ること",
        || {
            進める(&mut 作業場);
            載せた番号(&作業場).is_some_and(|番号| 番号 <= 20)
        },
    );
}
