/// 行0から行3に 置-1 から 置-4 を1つずつ、どれも0秒から1秒の間に置いた重ね合わせを、読み手を渡さずに開いた作業場。
fn 四行を開いた作業場() -> 重ね合わせの作業場 {
    let 一つ = 置き方 {
        動画上の区間の開始: 0.0,
        動画上の区間の終了: 1.0,
        始まり: 0.0,
    };
    let 動画 = 入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する();
    let mut 作業場 = 装置の無い作業場を作る();
    作業場.重ね合わせを開く(
        置き方を並べた重ね合わせ(動画, 10.0, &[&[一つ], &[一つ], &[一つ], &[一つ]]),
        None,
    );
    作業場
}

/// 1フレーム進めて、行0から行3の位置を飛ばした回数を読む。
fn 四行の回数(
    作業場: &mut 重ね合わせの作業場
) -> [位置を飛ばした回数; 4] {
    let mut 指示 = 作業場.フレームを進める(Instant::now(), 音量::起動したときの音量);
    [0, 1, 2, 3].map(|番号| 行の指示を取り出す(&mut 指示, 番号).飛ばした回数)
}

/// 前と後で回数が変わった行か。
fn 変わったか(
    前: [位置を飛ばした回数; 4], 後: [位置を飛ばした回数; 4]
) -> [bool; 4] {
    [0, 1, 2, 3].map(|番号| 前[番号] != 後[番号])
}

#[test]
fn 塊を確定したときは元の行と先の行だけ位置を飛ばした回数を進める() {
    let mut 作業場 = 四行を開いた作業場();
    let 前 = 四行の回数(&mut 作業場);
    塊を掴む(&mut 作業場, "置-3");
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-3", 1.0, -1)));
    assert_eq!(
        変わったか(前, 四行の回数(&mut 作業場)),
        [false, true, true, false]
    );
}

#[test]
fn 空の行を消したときは番号が変わる行だけ位置を飛ばした回数を進める() {
    let mut 作業場 = 四行を開いた作業場();
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを取り除く(
            置いたクリップの識別子を作る("置-2"),
        ),
    );
    let 前 = 四行の回数(&mut 作業場);
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::行を選ぶ(行の番号::番号から作成する(1)),
    );
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::選んでいる空の行を消す,
    );
    // 行2は、消す前は 置-3、消した後は 置-4 を映し続けるため、映し始めたことでは回数が進まない。番号が変わった行として進めたことが見える。
    let 後 = 四行の回数(&mut 作業場);
    assert_eq!(変わったか(前, 後)[..3], [false, true, true]);
}

#[test]
fn 再生の位置を動かしたときは全部の行の位置を飛ばした回数を進める() {
    let mut 作業場 = 四行を開いた作業場();
    let 前 = 四行の回数(&mut 作業場);
    let 時刻 = 重ね合わせ上の秒::作成する(0.5).expect("時刻");
    タイムラインの操作を当てる(
        &mut 作業場,
        タイムラインの操作::再生の位置を動かす(位置の線の段階::放した, 時刻),
    );
    assert_eq!(
        変わったか(前, 四行の回数(&mut 作業場)),
        [true, true, true, true]
    );
}
