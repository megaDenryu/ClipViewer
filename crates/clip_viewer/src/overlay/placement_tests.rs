//! 置き方の編集の試験。選ぶ・選びを外す・取り除く・縦横比を変えることと、今のスタックから並べ直すと確かめのダイアログを閉じることと、
//! 手で直したかの覚え方を、作業場の口から確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{
    アスペクト比設定, クリップスタック, 置いたクリップの音の変更, 重ねる画面の縦横比, 音量,
};

use super::arrange_test_support::{クリップ, 値, 練習の動画};
use super::command::{置き方の操作, 重ね合わせの操作};
use super::placement_test_support::{
    左上の4分の1へ縮める, 手で直したか, 置いたクリップの識別子を作る, 置き方の操作を当てる,
    重ねる枠, 開いた作業場,
};
#[test]
fn 選ぶと選んでいる枠になり_何も無い所で選びを外し_取り除くと選びも外れる() {
    let mut 作業場 = 開いた作業場();
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを選ぶ(置いたクリップの識別子を作る("置-1")),
    );
    assert_eq!(
        重ねる枠(&作業場, "置-1"),
        Some(([0.0, 0.0, 100.0, 100.0], true))
    );
    置き方の操作を当てる(&mut 作業場, 置き方の操作::選びを外す);
    assert_eq!(
        重ねる枠(&作業場, "置-1"),
        Some(([0.0, 0.0, 100.0, 100.0], false))
    );
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを選ぶ(置いたクリップの識別子を作る("置-1")),
    );
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::置いたクリップを取り除く(
            置いたクリップの識別子を作る("置-1"),
        ),
    );
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert!(開いている.選んでいる置いたクリップ().is_none());
    assert_eq!(開いている.奥から手前の順の置いたクリップ().count(), 0);
    assert!(開いている.置き方を手で直したか());
}

#[test]
fn 縦横比を選ぶと重ねる画面の縦横比が変わり_同じ比を選んでも手で直したことにならない() {
    let mut 作業場 = 開いた作業場();
    置き方の操作を当てる(
        &mut 作業場,
        置き方の操作::重ねる画面の縦横比を選ぶ(重ねる画面の縦横比::ワイド16対9),
    );
    assert!(!手で直したか(&作業場));
    let 正方形 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    置き方の操作を当てる(&mut 作業場, 置き方の操作::重ねる画面の縦横比を選ぶ(正方形));
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いている");
    assert_eq!(開いている.重ねる画面の縦横比(), 正方形);
    assert!(開いている.置き方を手で直したか());
}

#[test]
fn 今のスタックから並べ直すと確かめのダイアログを閉じ_並べ直した重ね合わせは並べたままになる() {
    let mut 作業場 = 開いた作業場();
    左上の4分の1へ縮める(&mut 作業場);
    置き方の操作を当てる(&mut 作業場, 置き方の操作::並べ直す前の確かめを出す);
    assert!(作業場.状態().並べ直す前の確かめを出しているか());
    let スタック =
        クリップスタック::一覧から作成する(vec![クリップ("乙", 10.0, 12.0)]).expect("スタック");
    let パス = 練習の動画();
    作業場.今のスタックから並べる(値(&スタック, &パス, 60.0), None);
    assert!(!作業場.状態().並べ直す前の確かめを出しているか());
    assert!(!手で直したか(&作業場));
}

#[test]
fn 置いたクリップの音量と消音を変えても手で直したことになる() {
    for 変更 in [
        置いたクリップの音の変更::音量を選ぶ(音量::範囲へ収めて作る(0.5)),
        置いたクリップの音の変更::消音を設定する(true),
    ] {
        let mut 作業場 = 開いた作業場();
        作業場.操作を適用する(重ね合わせの操作::置いたクリップの音を変える {
            識別子: 置いたクリップの識別子を作る("置-1"),
            変更,
        });
        assert!(手で直したか(&作業場), "{変更:?}");
    }
}
