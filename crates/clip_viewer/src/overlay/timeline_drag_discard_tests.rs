//! ドラッグを確定せずに捨てる試験。掴んだ塊が無くなったときと、放したを受け取れずにドラッグが残ったとき(安全網)は、
//! 塊のドラッグも映す矩形のドラッグも確定せずに捨てることを、作業場の口から確かめる。参照: _doc/設計/同時再生.md 2-6
#![allow(clippy::expect_used)]

use super::command::{塊の操作, 映す矩形の枠の操作};
use super::placement_test_support::{
    ドラッグの動きを作る, 右下, 手で直したか, 映す矩形の枠の操作を当てる,
    置いたクリップの識別子を作る, 重ねる枠,
};
use super::state::placement::隅の縦横比の扱い;
use super::timeline_test_support::{
    二行を開いた作業場, 塊の並び, 塊の動き, 塊の操作を当てる, 塊を掴む, 置いてある行と始まり,
    行ごとに描く塊,
};
use crate::primary_button::主ボタンの様子;

#[test]
fn 掴んだ塊が無くなったら確定せずにドラッグを閉じる() {
    let mut 作業場 = 二行を開いた作業場();
    塊を掴む(&mut 作業場, "置-2");
    塊の操作を当てる(
        &mut 作業場,
        塊の操作::動かしている(塊の動き("置-2", 1.5, 0)),
    );
    塊の操作を当てる(
        &mut 作業場,
        塊の操作::掴んだ塊が無くなった(置いたクリップの識別子を作る("置-2")),
    );
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-2", 1.5, 0)));
    assert_eq!(置いてある行と始まり(&作業場, "置-2"), (1, 0.0));
    assert!(!手で直したか(&作業場));
}

#[test]
fn 主ボタンを押していないのに残った塊のドラッグは安全網が確定せずに捨てる() {
    let mut 作業場 = 二行を開いた作業場();
    塊を掴む(&mut 作業場, "置-2");
    塊の操作を当てる(
        &mut 作業場,
        塊の操作::動かしている(塊の動き("置-2", 1.5, 0)),
    );
    作業場.取り残されたドラッグを捨てる(主ボタンの様子::押している);
    assert_eq!(
        行ごとに描く塊(&作業場)[1],
        塊の並び(&[("置-2", 1.5), ("置-3", 3.0)]),
        "押している間はドラッグを続ける"
    );
    作業場.取り残されたドラッグを捨てる(主ボタンの様子::押していない);
    assert_eq!(
        行ごとに描く塊(&作業場)[1],
        塊の並び(&[("置-2", 0.0), ("置-3", 3.0)])
    );
    塊の操作を当てる(&mut 作業場, 塊の操作::放した(塊の動き("置-2", 1.5, 0)));
    assert_eq!(置いてある行と始まり(&作業場, "置-2"), (1, 0.0));
    assert!(!手で直したか(&作業場));
}

#[test]
fn 主ボタンを押していないのに残った映す矩形のドラッグも安全網が捨てる() {
    let mut 作業場 = 二行を開いた作業場();
    映す矩形の枠の操作を当てる(
        &mut 作業場,
        映す矩形の枠の操作::掴み始めた(置いたクリップの識別子を作る("置-1")),
    );
    let 縮める = ドラッグの動きを作る(
        "置-1",
        右下,
        -50.0,
        -50.0,
        隅の縦横比の扱い::絵の形を保たない,
    );
    映す矩形の枠の操作を当てる(
        &mut 作業場,
        映す矩形の枠の操作::動かしている(縮める.clone()),
    );
    作業場.取り残されたドラッグを捨てる(主ボタンの様子::押していない);
    assert_eq!(
        重ねる枠(&作業場, "置-1"),
        Some(([0.0, 0.0, 100.0, 100.0], false))
    );
    映す矩形の枠の操作を当てる(&mut 作業場, 映す矩形の枠の操作::放した(縮める));
    assert!(!手で直したか(&作業場));
}
