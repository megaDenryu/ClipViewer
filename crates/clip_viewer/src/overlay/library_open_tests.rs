//! 重ね合わせの一覧と開くことの試験。重ね合わせを閉じると一覧を読み直し、一覧から開くと登録済みとして開くこと、
//! 開いていない間の一覧に、登録した重ね合わせが読めた行として出ることを確かめる。置き場所は一時フォルダである。参照: _doc/設計/同時再生.md 2-7
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::command::重ね合わせのライブラリの操作;
use super::library_test_ops::{
    ライブラリの操作を当てる, 名前を付けて登録する, 書き終えるまで待って進める,
};
use super::library_test_support::一時のライブラリ;
use super::sound_test_support::知らせの文;
use super::state::library::開いている重ね合わせのライブラリの様子;
use super::test_support::五秒の重ね合わせ;
use crate::library_common::list::{並べられる一覧, 最後に読んだ一覧};

#[test]
fn 閉じると一覧を読み直し_一覧から開くと登録済みとして同じ重ね合わせを開く() {
    let 一時 = 一時のライブラリ::作る("閉じて開く");
    let 組 = 一時.錠を試す();
    let mut 作業場 = 一時.作業場を作る(組.重ね合わせ);
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    名前を付けて登録する(&mut 作業場, "ふたり");
    ライブラリの操作を当てる(
        &mut 作業場,
        重ね合わせのライブラリの操作::重ね合わせを閉じる,
    );
    assert!(作業場.状態().開いている重ね合わせ().is_none());
    書き終えるまで待って進める(&mut 作業場, Instant::now());
    let 最後に読んだ一覧::読めた(一覧) = 作業場.状態().重ね合わせの一覧().一覧()
    else {
        panic!("一覧を読めた");
    };
    assert_eq!(一覧.項目の数(), 1);
    let 識別子 = 一時.保存した重ね合わせ()[0].識別子().clone();
    ライブラリの操作を当てる(&mut 作業場, 重ね合わせのライブラリの操作::開く(識別子));
    let 開いている = 作業場.状態().開いている重ね合わせ().expect("開いた");
    assert_eq!(
        開いている.重ね合わせ(),
        &五秒の重ね合わせ(),
        "試験の発行元が識別子を決めるため、何度作っても等しい"
    );
    assert!(matches!(
        作業場.状態().開いている重ね合わせのライブラリの様子(),
        Some(開いている重ね合わせのライブラリの様子::登録済み { 名前, .. }) if 名前.文字列() == "ふたり"
    ));
    assert!(
        知らせの文(&作業場)
            .iter()
            .any(|文| 文.contains("重ね合わせをライブラリから開きました: ふたり"))
    );
    drop((作業場, 組.スタック));
}
