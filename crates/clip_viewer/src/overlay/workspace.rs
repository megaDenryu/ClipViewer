//! 重ね合わせの作業場。重ね合わせの作業場の状態を持ち、1フレームの手順(時計 → 画面 → 応答の適用)の各工程と、控える前に再生を止めることと、
//! 画面が表示する値を読む口を公開する。配線(`app/`)はこの型の口だけを呼び、中の状態・画面・操作を知らない。参照: _doc/設計/同時再生.md 3-2

use std::time::{Duration, Instant};

use clip_domain::{重ね合わせ, 重ね合わせの再生位置, 重ね合わせ上の秒};
use sengen_egui::{ノード, 並べる通知};

use super::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use super::state::重ね合わせの作業場の状態;
use super::view;

/// 重ね合わせの作業場とは、重ね合わせを作り、直し、再生し、保存して開き直すための作業場のことである。
/// スタックの作業場の状態(`アプリの状態`)を持たず、借りもしない。
pub(crate) struct 重ね合わせの作業場 {
    状態: 重ね合わせの作業場の状態,
}

impl 重ね合わせの作業場 {
    /// 初めて重ね合わせの作業場へ移るときに作る。重ね合わせを開いていない。
    pub(crate) fn 開いていない作業場() -> Self {
        Self {
            状態: 重ね合わせの作業場の状態::開いていない(),
        }
    }

    /// 重ね合わせを開き、先頭で止まった再生の状況で始める。
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "第8段階で「今のスタックから並べる」から呼ぶ。それまでは試験からだけ呼ぶ(同時再生.md 6節)"
        )
    )]
    pub(crate) fn 重ね合わせを開く(&mut self, 重ね合わせ: 重ね合わせ) {
        self.状態.重ね合わせを開く(重ね合わせ);
    }

    /// 前に出ている間、画面を組む前に毎フレーム呼ぶ。時計を進める。
    pub(crate) fn フレームを進める(&mut self, 今: Instant) {
        self.状態.時計を進める(今);
    }

    /// 今の状態から1フレーム分の画面を組む。スタックの作業場の描き直すまでの時間は、配線が求めて渡す。
    pub(crate) fn 画面(
        &self,
        スタックの作業場の描き直すまでの時間: Option<Duration>,
    ) -> ノード<重ね合わせの作業場の応答> {
        view::画面(self, スタックの作業場の描き直すまでの時間)
    }

    /// 描画の間に集めた重ね合わせの作業場の中の操作を状態へ適用する。
    pub(crate) fn 操作を適用する(&mut self, 操作: 重ね合わせの操作) {
        self.状態.操作を適用する(操作);
    }

    /// スタックの作業場を前に出すときに呼ぶ。再生を止める。重ね合わせと再生の位置はそのまま残す。
    pub(crate) fn 控える前に再生を止める(&mut self) {
        self.状態.控える前に再生を止める();
    }

    /// 開いている重ね合わせを再生しているか。開いていなければ再生していない。
    pub(crate) fn 再生しているか(&self) -> bool {
        self.状態
            .開いている重ね合わせ()
            .is_some_and(|開いている| 開いている.再生しているか())
    }

    /// 再生を始められるか。重ね合わせを開いていて、長さが0秒でないときだけ始められる。
    pub(crate) fn 再生を始められるか(&self) -> bool {
        self.状態
            .開いている重ね合わせ()
            .is_some_and(|開いている| 開いている.再生を始められるか())
    }

    /// 開いている重ね合わせの再生の位置と長さ。開いていなければ無い。
    pub(crate) fn 再生の位置と長さ(
        &self,
    ) -> Option<(重ね合わせの再生位置, 重ね合わせ上の秒)> {
        self.状態
            .開いている重ね合わせ()
            .map(|開いている| (開いている.再生の位置(), 開いている.重ね合わせの長さ()))
    }

    /// 画面に並べる最近の知らせ(古い順)。
    pub(crate) fn 並べる知らせ(&self) -> Vec<並べる通知> {
        self.状態.知らせ.並べる通知()
    }
}
