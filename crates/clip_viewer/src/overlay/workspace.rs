//! 重ね合わせの作業場。重ね合わせの作業場の状態を持ち、1フレームの手順(時計 → 画面 → 応答の適用)の各工程と、控える前に再生を止めることを公開する。
//! 重ね合わせの作業場の中の配線であり、配線(`app/`)はこの型の口だけを呼び、中の状態・画面・操作を知らない。参照: _doc/設計/同時再生.md 3-2

use std::time::{Duration, Instant};

use sengen_egui::ノード;

use super::command::{操作の後の作業場, 重ね合わせの操作};
use super::state::重ね合わせの作業場の状態;
use super::view;

/// 重ね合わせの作業場とは、重ね合わせを作り、直し、再生し、保存して開き直すための作業場のことである。
/// スタックの作業場の状態(`アプリの状態`)を持たず、借りもしない。
pub(crate) struct 重ね合わせの作業場 {
    状態: 重ね合わせの作業場の状態,
}

impl 重ね合わせの作業場 {
    /// 初めて重ね合わせの作業場へ移るときに作る。何も置いていない重ね合わせの先頭で止まっている。
    pub(crate) fn 何も置いていない作業場() -> Self {
        Self {
            状態: 重ね合わせの作業場の状態::何も置いていない(),
        }
    }

    /// 前に出ている間、画面を組む前に毎フレーム呼ぶ。時計を進める。
    pub(crate) fn フレームを進める(&mut self, 今: Instant) {
        self.状態.時計を進める(今);
    }

    /// 今の状態から1フレーム分の画面を組む。スタックの作業場の描き直すまでの時間は、配線が求めて渡す。
    pub(crate) fn 画面(
        &self,
        スタックの作業場の描き直すまでの時間: Option<Duration>,
    ) -> ノード<重ね合わせの操作> {
        view::画面(&self.状態, スタックの作業場の描き直すまでの時間)
    }

    /// 描画の間に集めた操作を状態へ適用し、操作の後に前に出す作業場を返す。
    pub(crate) fn 操作を適用する(
        &mut self,
        操作: 重ね合わせの操作,
    ) -> 操作の後の作業場 {
        self.状態.操作を適用する(操作)
    }

    /// 試験が重ね合わせの作業場の状態を読む口。
    #[cfg(test)]
    pub(crate) fn 試験のために状態を読む(
        &self,
    ) -> &重ね合わせの作業場の状態 {
        &self.状態
    }

    /// スタックの作業場を前に出すときに呼ぶ。再生を止める。重ね合わせと再生の位置はそのまま残す。
    pub(crate) fn 控える前に再生を止める(&mut self) {
        self.状態.再生.止める();
    }
}
