//! 重ね合わせの作業場。重ね合わせの作業場の状態を持ち、1フレームの手順(時計 → 映像の供給 → 画面 → 応答の適用)の各工程と、控える前に再生を止めることと、
//! 状態を読むことを公開する。配線(`app/`)はこの型の口だけを呼び、中の状態・画面・操作を知らない。参照: _doc/設計/同時再生.md 3-2

use std::time::{Duration, Instant};

use clip_domain::重ね合わせ;
use eframe::egui;
use sengen_egui::ノード;
use video_source::{メモリの上限, 動画の読み手};

use super::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use super::feed::重ね合わせの映像の様子;
use super::state::重ね合わせの作業場の状態;
use super::view;

/// 重ね合わせの作業場とは、重ね合わせを作り、直し、再生し、保存して開き直すための作業場のことである。
/// スタックの作業場の状態(`アプリの状態`)を持たず、借りもしない。
pub(crate) struct 重ね合わせの作業場 {
    状態: 重ね合わせの作業場の状態,
}

impl 重ね合わせの作業場 {
    /// 初めて重ね合わせの作業場へ移るときに作る。重ね合わせを開いていない。
    pub(crate) fn 開いていない作業場() -> Self {
        Self {
            状態: 重ね合わせの作業場の状態::開いていない(),
        }
    }

    /// 重ね合わせを開き、先頭で止まった再生の状況で始める。使う動画の表の動画を、配線がスタックの作業場の `動画の開き手` から借りた読み手
    /// (FFmpeg が見つかっていなければ無い)で開き(ffprobe が終わるまで待つ)、行のテクスチャを登録する。倉庫はスタックの作業場の倉庫と別に既定の上限を持つ。
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "第8段階で「今のスタックから並べる」から呼ぶ。それまでは試験からだけ呼ぶ(同時再生.md 6節)"
        )
    )]
    pub(crate) fn 重ね合わせを開く(
        &mut self,
        重ね合わせ: 重ね合わせ,
        読み手: Option<&動画の読み手>,
        画面描画の共有状態: &egui::Context,
    ) {
        self.倉庫の上限で重ね合わせを開く(
            重ね合わせ,
            読み手,
            メモリの上限::既定,
            画面描画の共有状態,
        );
    }

    /// 倉庫のメモリの上限を指定して重ね合わせを開く。結合試験は、上限を小さくして流し読みの経路を通す。
    pub(crate) fn 倉庫の上限で重ね合わせを開く(
        &mut self,
        重ね合わせ: 重ね合わせ,
        読み手: Option<&動画の読み手>,
        上限: メモリの上限,
        画面描画の共有状態: &egui::Context,
    ) {
        let 映像 = 重ね合わせの映像の様子::開く(
            読み手,
            重ね合わせ.動画の表(),
            上限,
            画面描画の共有状態,
        );
        self.状態.重ね合わせを開く(重ね合わせ, 映像);
    }

    /// 前に出ている間、画面を組む前に毎フレーム呼ぶ。時計を進め、進めた位置に行ごとに映すコマを載せる。
    pub(crate) fn フレームを進める(&mut self, 今: Instant) {
        self.状態.時計を進める(今);
        self.状態.映像を供給する(今);
    }

    /// 今の状態から1フレーム分の画面を組む。スタックの作業場の描き直すまでの時間は、配線が求めて渡す。
    pub(crate) fn 画面(
        &self,
        スタックの作業場の描き直すまでの時間: Option<Duration>,
    ) -> ノード<重ね合わせの作業場の応答> {
        view::画面(self.状態(), スタックの作業場の描き直すまでの時間)
    }

    /// 描画の間に集めた重ね合わせの作業場の中の操作を状態へ適用する。
    pub(crate) fn 操作を適用する(&mut self, 操作: 重ね合わせの操作) {
        self.状態.操作を適用する(操作);
    }

    /// スタックの作業場を前に出すときに呼ぶ。再生を止め、行ごとの流し読みを閉じる。重ね合わせと再生の位置と、行のテクスチャに載せたコマはそのまま残す。
    pub(crate) fn 控える前に再生を止める(&mut self) {
        self.状態.控える前に再生を止める();
    }

    /// 重ね合わせの作業場の状態を読む。画面と、画面が表示する値を確かめる試験が読む。
    pub(crate) fn 状態(&self) -> &重ね合わせの作業場の状態 {
        &self.状態
    }
}
