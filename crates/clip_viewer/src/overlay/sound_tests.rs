//! 重ね合わせの作業場の音の口の試験。置いたクリップの音量と消音の操作が音の設定を変え、無い置いたクリップへの操作は理由を知らせることと、
//! 動画の音を鳴らせない行は止めている指示になり、行の位置を飛ばした回数は映し始めたときに進むことを確かめる。
#![allow(clippy::expect_used)]

use std::time::Instant;

use audio_output::{位置を飛ばした回数, 再生の様子};
use clip_domain::{置いたクリップの音の設定, 音量};

use super::command::重ね合わせの操作;
use super::sound_test_support::{
    知らせの文, 置いた識別子, 行の指示を取り出す, 装置の無い作業場
};
use super::test_support::五秒の重ね合わせ;

#[test]
fn 置いたクリップの音量と消音を別々に変え_無い置いたクリップへの操作は理由を知らせる() {
    let mut 作業場 = 装置の無い作業場();
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    作業場.操作を適用する(重ね合わせの操作::置いたクリップの音量を選ぶ {
        識別子: 置いた識別子("置-1"),
        音量: 0.25,
    });
    作業場.操作を適用する(
        重ね合わせの操作::置いたクリップの消音を設定する {
            識別子: 置いた識別子("置-1"),
            消音するか: true,
        },
    );
    let 音の設定 = 作業場
        .状態()
        .開いている重ね合わせ()
        .expect("開いている")
        .重ね合わせ()
        .識別子で探す(&置いた識別子("置-1"))
        .expect("ある")
        .音の設定();
    assert_eq!(
        音の設定,
        置いたクリップの音の設定 {
            音量: 音量::範囲へ収めて作る(0.25),
            消音しているか: true,
        }
    );
    作業場.操作を適用する(
        重ね合わせの操作::置いたクリップの消音を設定する {
            識別子: 置いた識別子("無い"),
            消音するか: true,
        },
    );
    assert!(
        知らせの文(&作業場)
            .iter()
            .any(|文| 文.contains("識別子「無い」の置いたクリップは存在しない"))
    );
}

#[test]
fn 動画の音を鳴らせない行は止めている指示になり_映し始めた行の飛ばした回数が進む() {
    let mut 作業場 = 装置の無い作業場();
    let つまみ = 音量::元の大きさ;
    let mut 開く前 = 作業場.行ごとの再生の指示(Instant::now(), つまみ);
    assert!(
        行の指示を取り出す(&mut 開く前, 0).区間.is_none(),
        "開いていない間はどの行も黙る"
    );
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
    作業場.フレームを進める(Instant::now());
    let mut 指示 = 作業場.行ごとの再生の指示(Instant::now(), つまみ);
    let 行0 = 行の指示を取り出す(&mut 指示, 0);
    assert_eq!(行0.様子, 再生の様子::止めている, "動画の音を鳴らせない");
    assert!(行0.区間.is_none());
    assert_eq!(行0.飛ばした回数, 位置を飛ばした回数::default().次());
    assert_eq!(
        行の指示を取り出す(&mut 指示, 1).飛ばした回数,
        位置を飛ばした回数::default(),
        "重ね合わせに無い行は進まない"
    );
}
