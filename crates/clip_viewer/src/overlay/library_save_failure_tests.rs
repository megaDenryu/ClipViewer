//! 登録済みの重ね合わせを書けないまま閉じる試験。重ね合わせのファイルを排他で開いて書けなくしたまま閉じようとすると「保存できずに続ける確認」を出し、
//! 確かめる間は閉じず、「変更を捨てて続ける」で閉じることを確かめる(Windows だけで流す)。置き場所は一時フォルダである。参照: _doc/設計/同時再生.md 2-7
#![cfg(windows)]
#![allow(clippy::expect_used)]

use std::os::windows::fs::OpenOptionsExt;
use std::time::Instant;

use super::command::{
    一覧とダイアログの操作, 重ね合わせのライブラリの操作
};
use super::library_test_ops::{
    ライブラリの操作を当てる, 名前を付けて登録する, 書き終えるまで待って進める,
    縦横比を正方形にする,
};
use super::library_test_support::一時のライブラリ;
use super::state::library::{
    重ね合わせとの関係を終える操作, 重ね合わせのダイアログ
};
use super::test_support::五秒の重ね合わせ;

#[test]
fn 登録済みの重ね合わせを書けないまま閉じようとすると確かめ_捨てて続けると閉じる() {
    let 一時 = 一時のライブラリ::作る("書けないまま閉じる");
    let 組 = 一時.錠を試す();
    let mut 作業場 = 一時.作業場を作る(組.重ね合わせ);
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    名前を付けて登録する(&mut 作業場, "ふたり");
    書き終えるまで待って進める(&mut 作業場, Instant::now());
    let 識別子 = 一時.保存した重ね合わせ()[0].識別子().clone();
    let 排他 = std::fs::OpenOptions::new()
        .read(true)
        .share_mode(0)
        .open(一時.重ね合わせのファイルのパス(&識別子))
        .expect("開ける");
    縦横比を正方形にする(&mut 作業場);
    ライブラリの操作を当てる(
        &mut 作業場,
        重ね合わせのライブラリの操作::重ね合わせを閉じる,
    );
    assert!(matches!(
        作業場.状態().ライブラリ().ダイアログ(),
        重ね合わせのダイアログ::保存できずに続ける確認(
            _,
            重ね合わせとの関係を終える操作::重ね合わせを閉じる
        )
    ));
    assert!(
        作業場.状態().開いている重ね合わせ().is_some(),
        "確かめる間は閉じない"
    );
    ライブラリの操作を当てる(
        &mut 作業場,
        重ね合わせのライブラリの操作::変更を捨てて続ける,
    );
    assert!(作業場.状態().開いている重ね合わせ().is_none());
    ライブラリの操作を当てる(
        &mut 作業場,
        重ね合わせのライブラリの操作::一覧とダイアログ(
            一覧とダイアログの操作::ダイアログを閉じる,
        ),
    );
    drop((作業場, 排他, 組.スタック));
}
