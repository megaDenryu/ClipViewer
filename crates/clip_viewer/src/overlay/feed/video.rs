//! 動画ごとの倉庫と台帳。使う動画の表の1本の動画に結び付いた読み手・コマの倉庫・依頼の台帳を持ち、先読みの台帳の手順を倉庫へ行う。
//! 同じ動画の複数の区間を1つの倉庫に溜め、行ごとの流し読みはここから開く。倉庫へ行う手順はスタックの作業場の `読み込んだ動画` と同じだが、
//! `読み込んだ動画` は流し読みとテクスチャを1つずつしか持たないため使わない。参照: _doc/設計/同時再生.md 3-3・5-1

use std::time::Instant;

use clip_domain::{動画上の区間, 動画上の秒, 正規化した動画パス};
use video_source::{
    コマの倉庫, メモリの上限, 保持の優先順, 動画の情報, 動画の読み手, 受付の札, 溜める依頼の結果,
    番号付きのコマ, 長辺の上限,
};

use super::row::開いた流し読み;
use crate::video_feed::{依頼の台帳, 動画を開けない理由, 状況の写し};

/// 動画ごとの倉庫と台帳とは、使う動画の表の1本の動画に結び付いた、動画の読み手と、コマの倉庫と、先読みの依頼の台帳の組のことである。
pub(crate) struct 動画のコマの供給元 {
    読み手: 動画の読み手,
    倉庫: コマの倉庫,
    台帳: 依頼の台帳<受付の札>,
}

impl 動画のコマの供給元 {
    /// 動画の情報を ffprobe で調べ、既定の長辺の上限と渡されたメモリの上限で倉庫を開く。ffprobe が終わるまで待つ。
    pub(super) fn 開く(
        読み手: 動画の読み手,
        パス: &正規化した動画パス,
        上限: メモリの上限,
    ) -> Result<Self, 動画を開けない理由> {
        let 情報 = 読み手.動画の情報を取る(パス)?;
        let 倉庫 = 読み手.コマの倉庫を開く(情報, 長辺の上限::既定, 上限)?;
        Ok(Self {
            読み手,
            倉庫,
            台帳: 依頼の台帳::空(),
        })
    }

    pub(crate) fn 台帳(&self) -> &依頼の台帳<受付の札> {
        &self.台帳
    }

    pub(super) fn 情報(&self) -> &動画の情報 {
        self.倉庫.動画()
    }

    /// 台帳が決めた手順(優先順を渡す → 捨てる → 依頼する)を倉庫へ行い、依頼中の札の状況を台帳へ記録する。
    pub(super) fn 先読みを整える(
        &mut self, 区間の列: &[動画上の区間], 今: Instant
    ) {
        let 手順 = self.台帳.手順を決める(区間の列, 今);
        if let Some(優先順) = 手順.渡す優先順 {
            self.倉庫.保持の優先順を渡す(保持の優先順::作成する(優先順));
        }
        for 区間 in &手順.捨てる区間 {
            self.倉庫.区間の破棄を依頼する(区間);
        }
        for 区間 in 手順.依頼する区間 {
            let 結果 = match self.倉庫.区間を溜める依頼を出す(区間) {
                溜める依頼の結果::受け付けた(札) => Ok(札),
                溜める依頼の結果::受け付けない(理由) => Err(理由),
            };
            self.台帳.依頼の結果を記録する(区間, 結果);
        }
        for 札 in self.台帳.依頼中の札() {
            let 写し = 状況の写し::依頼の状況から写す(
                &self.倉庫.依頼の状況を問い合わせる(札),
            );
            self.台帳.状況を記録する(札, 写し);
        }
    }

    pub(super) fn 溜めたコマを取り出す(
        &mut self,
        区間: &動画上の区間,
        位置: 動画上の秒,
    ) -> Option<番号付きのコマ<'_>> {
        self.倉庫.溜めたコマを取り出す(区間, 位置)
    }

    /// 位置から映像の流し読みを開く。開けなければ、その理由を持った読めない流し読みになる。
    pub(super) fn 流し読みを開く(
        &self,
        位置: 動画上の秒,
        今: Instant,
    ) -> 開いた流し読み {
        開いた流し読み::開いた結果から作る(
            self.読み手
                .流し読みを開く(self.倉庫.動画(), 位置, 長辺の上限::既定),
            位置,
            今,
        )
    }
}
