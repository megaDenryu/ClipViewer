//! 続く先の試験。`clip_domain` の行の映し方から続く先への3つの写し(別の置いたクリップへ進む → その識別子、区間の開始へ戻る → 同じ区間、
//! 末尾で最後のコマを映す → 止まる)を、FFmpeg を使わずに確かめる。参照: _doc/設計/同時再生.md 5-2 の7
#![allow(clippy::expect_used)]

use clip_domain::{時刻, 末尾での振る舞い, 行の映し方, 重ね合わせ};

use super::continuation::続く先;
use crate::overlay::arrange_test_support::練習の動画;
use crate::overlay::placement_test_support::置いたクリップの識別子を作る;
use crate::overlay::test_support::{置き方, 置き方を並べた重ね合わせ};

/// 1つの行に、動画上の区間(開始から1秒)を重ね合わせ上の始まりの時刻に置く置き方。
fn 置く(区間の開始: f64, 始まり: f64) -> 置き方 {
    置き方 {
        動画上の区間の開始: 区間の開始,
        動画上の区間の終了: 区間の開始 + 1.0,
        始まり,
    }
}

/// 重ね合わせの最初の行が、時刻に、全体の末尾で止まる設定で映すもの。
fn 最初の行の映し方(重ね合わせ: &重ね合わせ, 秒: f64) -> 行の映し方<'_> {
    重ね合わせ
        .重ね合わせ上の時刻に映すものを求める(
            時刻::作成する(秒).expect("時刻"),
            末尾での振る舞い::止まる,
        )
        .next()
        .expect("行がある")
        .映し方
}

#[test]
fn 別の置いたクリップへ進む行き先は_その置いたクリップの識別子へ続く() {
    let 重ね合わせ = 置き方を並べた重ね合わせ(
        練習の動画(),
        60.0,
        &[&[置く(0.0, 0.0), 置く(1.0, 1.0)]],
    );
    let 進む先の識別子 = 置いたクリップの識別子を作る("置-2");
    assert_eq!(
        続く先::映し方から求める(最初の行の映し方(&重ね合わせ, 0.5)),
        続く先::別の置いたクリップ(&進む先の識別子)
    );
}

#[test]
fn 区間の開始へ戻る行き先は_同じ区間へ続く() {
    let 重ね合わせ = 置き方を並べた重ね合わせ(
        練習の動画(),
        60.0,
        &[&[置く(0.0, 0.0), 置く(0.0, 1.0)]],
    );
    assert_eq!(
        続く先::映し方から求める(最初の行の映し方(&重ね合わせ, 0.5)),
        続く先::同じ区間
    );
}

#[test]
fn 末尾で最後のコマを映すときと何も映さないときは_止まる() {
    let 重ね合わせ = 置き方を並べた重ね合わせ(練習の動画(), 60.0, &[&[置く(0.0, 0.5)]]);
    let 末尾 = 最初の行の映し方(&重ね合わせ, 1.5);
    assert!(matches!(末尾, 行の映し方::末尾で最後のコマを映す { .. }));
    assert_eq!(続く先::映し方から求める(末尾), 続く先::止まる);
    let 始まりの前 = 最初の行の映し方(&重ね合わせ, 0.2);
    assert!(matches!(始まりの前, 行の映し方::何も映さない));
    assert_eq!(続く先::映し方から求める(始まりの前), 続く先::止まる);
}
