//! 続く先。行が映している置いたクリップの今の周回の区間の終わりから、行の再生が隙間なく続く先を、`clip_domain` の区間の終わりの行き先から写す。
//! 行のテクスチャに前の置いたクリップのコマが残る間、それを描き続けてよいかを決めるために覚える。参照: _doc/設計/同時再生.md 5-2 の7

use clip_domain::{
    置いたクリップの区間の終わりの行き先, 置いたクリップの識別子, 行の映し方
};

/// 続く先とは、行が映している置いたクリップの今の周回の区間の終わりに達したとき、行の再生が隙間なく続く先の区別のことである。
/// 同じ区間とは、同じ置いたクリップの次の周回か、同じ動画の同じ区間を持つ置いたクリップへ続くことである。
/// 識別の型引数は、1フレームの間だけ借りる識別子の参照か、フレームをまたいで覚える識別子である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 続く先<識別> {
    同じ区間,
    別の置いたクリップ(識別),
    止まる,
}

impl<'重ね合わせ> 続く先<&'重ね合わせ 置いたクリップの識別子> {
    /// 行の映し方から求める。末尾で最後のコマを映すときと何も映さないときは、どこへも続かない。
    pub(super) fn 映し方から求める(映し方: 行の映し方<'重ね合わせ>) -> Self {
        let 行の映し方::置いたクリップを映す(中身) = 映し方 else {
            return Self::止まる;
        };
        match 中身.区間の終わりの行き先 {
            置いたクリップの区間の終わりの行き先::区間の開始へ戻る => Self::同じ区間,
            置いたクリップの区間の終わりの行き先::別の置いたクリップへ進む(進む先) => {
                Self::別の置いたクリップ(進む先.識別子())
            }
            置いたクリップの区間の終わりの行き先::止まる => Self::止まる,
        }
    }

    /// フレームをまたいで覚えるための写し。
    pub(super) fn 写しを作る(self) -> 続く先<置いたクリップの識別子> {
        match self {
            Self::同じ区間 => 続く先::同じ区間,
            Self::別の置いたクリップ(識別子) => {
                続く先::別の置いたクリップ(識別子.clone())
            }
            Self::止まる => 続く先::止まる,
        }
    }
}

impl 続く先<置いたクリップの識別子> {
    /// 覚えた続く先を今のフレームの続く先に合わせる。同じなら識別子を複製しない。
    pub(super) fn 今の続く先に合わせる(
        &mut self, 今: 続く先<&置いたクリップの識別子>
    ) {
        let 同じか = match (&*self, 今) {
            (Self::同じ区間, 続く先::同じ区間) | (Self::止まる, 続く先::止まる) => {
                true
            }
            (Self::別の置いたクリップ(覚えた), 続く先::別の置いたクリップ(今の)) => {
                覚えた == 今の
            }
            _ => false,
        };
        if !同じか {
            *self = 今.写しを作る();
        }
    }

    /// 映す置いたクリップへ隙間なく続くか。同じ区間へ続くなら、同じ動画の同じ区間のコマであるため続くとする。
    pub(super) fn 続くか(
        &self, 映す置いたクリップ: &置いたクリップの識別子
    ) -> bool {
        match self {
            Self::同じ区間 => true,
            Self::別の置いたクリップ(識別子) => 識別子 == 映す置いたクリップ,
            Self::止まる => false,
        }
    }
}
