//! 重ね合わせの音の供給への問い合わせ。重ね合わせの状態が行ごとの再生の指示を組み立てるときに、行が映している置いたクリップと、
//! その区間の終わりで進む先の置いたクリップの音の区間(範囲と出どころ)を読み、画面が音の様子の文を読む口。参照: _doc/設計/同時再生.md 5-3

use audio_output::音の区間;
use audio_pcm::サンプリング周波数;
use clip_domain::{動画上の秒, 置いたクリップ, 行の番号};

use super::sound_supply::重ね合わせの音の供給;
use super::sound_video::重ね合わせの動画の音;
use crate::audio_feed::動画の音の供給元;

impl 重ね合わせの音の供給 {
    /// 2本目の流れの周波数。使えなければ無い。
    pub(crate) fn 周波数(&self) -> Option<サンプリング周波数> {
        self.周波数
    }

    /// 行が映している置いたクリップの音の区間。出どころは、区間を溜め終えていれば溜めた音、そうでなければその行の音の流し読みが選ぶ方である。
    /// 置いたクリップの動画の音を鳴らせなければ無い。
    pub(crate) fn 映している音の区間(
        &self,
        行: 行の番号,
        置いたクリップ: &置いたクリップ,
        位置: 動画上の秒,
    ) -> Option<音の区間> {
        let 供給元 = self.置いたクリップの供給元(置いたクリップ)?;
        let 流し読み = self.行ごとの流し読み.get(行.番号())?;
        let 区間 = 置いたクリップ.受け継いだ値().区間;
        Some(音の区間 {
            範囲: 供給元.周波数().区間の範囲(&区間),
            出どころ: 流し読み.鳴らす出どころ(供給元, Some(&区間), 位置),
        })
    }

    /// 区間の終わりで進む先の置いたクリップの音の区間。出どころは、スタックの作業場の行き先と同じく、溜め終えていれば溜めた音だけである。
    /// 置いたクリップの動画の音を鳴らせなければ無い。
    pub(crate) fn 進む先の音の区間(
        &self,
        置いたクリップ: &置いたクリップ,
    ) -> Option<音の区間> {
        let 供給元 = self.置いたクリップの供給元(置いたクリップ)?;
        let 区間 = 置いたクリップ.受け継いだ値().区間;
        Some(音の区間 {
            範囲: 供給元.周波数().区間の範囲(&区間),
            出どころ: 供給元.溜めた音の出どころ(&区間),
        })
    }

    /// 画面の音の様子に出す文の並び(使う動画の表の順)。鳴らせる動画と、映像を開けていない動画の分は出さない。
    pub(crate) fn 様子の文の並び(&self) -> Vec<String> {
        self.動画
            .iter()
            .filter_map(重ね合わせの動画の音::様子の文)
            .collect()
    }

    fn 置いたクリップの供給元(
        &self,
        置いたクリップ: &置いたクリップ,
    ) -> Option<&動画の音の供給元> {
        self.動画.get(置いたクリップ.動画の番号().番号())?.供給元()
    }
}
