//! 載せたコマの置いたクリップの試験(区間の中のコマ)。新しい置いたクリップのコマとみなすのは、その区間の中のコマを載せたときだけであり、
//! それまでは前の置いたクリップのコマを描き続けることを、FFmpeg を使わずに固定する(同時再生.md 5-2 の7)。

use super::continuation::続く先;
use super::loaded_rows::{行の描き方, 載せたコマの置いたクリップ};
use super::loaded_rows_test_support::{毎秒30コマ, 求め, 番号のコマを載せた};
use crate::overlay::placement_test_support::置いたクリップの識別子を作る;
use crate::video_feed::コマを載せたか;

#[test]
fn まだ載せていない行は描かない() {
    let 載せたコマ = 載せたコマの置いたクリップ::載せていない;
    let 甲 = 置いたクリップの識別子を作る("甲");
    assert_eq!(載せたコマ.行の描き方を決める(&甲), 行の描き方::描かない);
}

#[test]
fn 続く先の置いたクリップの区間のコマが載るまで_前の置いたクリップのコマを描く() {
    let (甲, 乙) = (
        置いたクリップの識別子を作る("甲"),
        置いたクリップの識別子を作る("乙"),
    );
    let mut 載せたコマ = 載せたコマの置いたクリップ::載せていない;
    let 甲の求め = 求め(&甲, 0.0, 1.0, 続く先::別の置いたクリップ(&乙));
    載せたコマ.載せた結果を覚える(&甲の求め, 番号のコマを載せた(29), 毎秒30コマ());
    assert_eq!(
        載せたコマ.行の描き方を決める(&甲),
        行の描き方::映す置いたクリップのコマ
    );
    let 乙の求め = 求め(&乙, 1.0, 2.0, 続く先::止まる);
    載せたコマ.載せた結果を覚える(&乙の求め, 番号のコマを載せた(29), 毎秒30コマ());
    assert_eq!(
        載せたコマ.行の描き方を決める(&乙),
        行の描き方::前の置いたクリップのコマ(&甲),
        "開き直さない流し読みがまだ甲の区間のコマ(29番)を出しても、乙のコマとはみなさない"
    );
    載せたコマ.載せた結果を覚える(&乙の求め, 番号のコマを載せた(30), 毎秒30コマ());
    assert_eq!(
        載せたコマ.行の描き方を決める(&乙),
        行の描き方::映す置いたクリップのコマ
    );
}

#[test]
fn 区間の外のコマや載せなかったときは_その置いたクリップのコマとみなさない() {
    let 乙 = 置いたクリップの識別子を作る("乙");
    let mut 載せたコマ = 載せたコマの置いたクリップ::載せていない;
    let 乙の求め = 求め(&乙, 1.0, 2.0, 続く先::止まる);
    載せたコマ.載せた結果を覚える(&乙の求め, 番号のコマを載せた(60), 毎秒30コマ());
    載せたコマ.載せた結果を覚える(&乙の求め, コマを載せたか::載せなかった, 毎秒30コマ());
    assert_eq!(載せたコマ.行の描き方を決める(&乙), 行の描き方::描かない);
}
