//! 行ごとの載せたコマの置いたクリップの試験。行が映す置いたクリップに対してその行に何を描くかを、FFmpeg を使わずに確かめる。
//! 継ぎ目で前の置いたクリップのコマを描き続けるのは、隙間を挟まずに移ったときだけであることを固定する(同時再生.md 5-2 の7)。

use clip_domain::行の番号;

use super::loaded_rows::{行ごとの載せたコマの置いたクリップ, 行の描き方};
use crate::overlay::placement_test_support::置いたクリップの識別子を作る;

fn 番号1の行() -> 行の番号 {
    行の番号::番号から作成する(1)
}

#[test]
fn まだ載せていない行は描かない() {
    let 載せた置いたクリップ =
        行ごとの載せたコマの置いたクリップ::まだ載せていない();
    let 甲 = 置いたクリップの識別子を作る("甲");
    assert_eq!(
        載せた置いたクリップ.行の描き方を決める(番号1の行(), &甲),
        行の描き方::描かない
    );
    assert!(!載せた置いたクリップ.載せた置いたクリップか(番号1の行(), &甲));
}

#[test]
fn 隙間を挟まずに次の置いたクリップへ移ると_そのコマが載るまで前の置いたクリップのコマを描く() {
    let mut 載せた置いたクリップ =
        行ごとの載せたコマの置いたクリップ::まだ載せていない();
    let (甲, 乙) = (
        置いたクリップの識別子を作る("甲"),
        置いたクリップの識別子を作る("乙"),
    );
    載せた置いたクリップ.載せたことを覚える(番号1の行(), &甲);
    assert_eq!(
        載せた置いたクリップ.行の描き方を決める(番号1の行(), &甲),
        行の描き方::映す置いたクリップのコマ
    );
    assert_eq!(
        載せた置いたクリップ.行の描き方を決める(番号1の行(), &乙),
        行の描き方::前の置いたクリップのコマ(&甲)
    );
    assert!(!載せた置いたクリップ.載せた置いたクリップか(番号1の行(), &乙));
    載せた置いたクリップ.載せたことを覚える(番号1の行(), &乙);
    assert_eq!(
        載せた置いたクリップ.行の描き方を決める(番号1の行(), &乙),
        行の描き方::映す置いたクリップのコマ
    );
}

#[test]
fn 隙間を挟んだ後は_前の置いたクリップのコマを別の置いたクリップの代わりに描かない() {
    let mut 載せた置いたクリップ =
        行ごとの載せたコマの置いたクリップ::まだ載せていない();
    let (甲, 乙) = (
        置いたクリップの識別子を作る("甲"),
        置いたクリップの識別子を作る("乙"),
    );
    載せた置いたクリップ.載せたことを覚える(番号1の行(), &甲);
    載せた置いたクリップ.何も映さなかったことを覚える(番号1の行());
    assert_eq!(
        載せた置いたクリップ.行の描き方を決める(番号1の行(), &乙),
        行の描き方::描かない
    );
    assert_eq!(
        載せた置いたクリップ.行の描き方を決める(番号1の行(), &甲),
        行の描き方::映す置いたクリップのコマ,
        "同じ置いたクリップへ戻ったなら、載っているのはその置いたクリップのコマである"
    );
}

#[test]
fn 行ごとに別々に覚える() {
    let mut 載せた置いたクリップ =
        行ごとの載せたコマの置いたクリップ::まだ載せていない();
    let 甲 = 置いたクリップの識別子を作る("甲");
    載せた置いたクリップ.載せたことを覚える(番号1の行(), &甲);
    assert_eq!(
        載せた置いたクリップ.行の描き方を決める(行の番号::番号から作成する(0), &甲),
        行の描き方::描かない
    );
}
