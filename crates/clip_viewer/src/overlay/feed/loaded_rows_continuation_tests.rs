//! 載せたコマの置いたクリップの試験(続く先)。前の置いたクリップのコマを描き続けるのは、前の置いたクリップの続く先が映す置いたクリップか
//! 同じ区間のときだけであり、何も映さない時刻と末尾で止めた後の再生し直しでは描かないことを、FFmpeg を使わずに固定する(同時再生.md 5-2 の7)。

use super::continuation::続く先;
use super::loaded_rows::{行の描き方, 載せたコマの置いたクリップ};
use super::loaded_rows_test_support::{毎秒30コマ, 求め, 番号のコマを載せた};
use crate::overlay::placement_test_support::置いたクリップの識別子を作る;
use crate::video_feed::コマを載せたか;

#[test]
fn 続く先が止まるか何も映さない時刻を挟んだ後は_別の置いたクリップの代わりに描かない() {
    let (甲, 乙) = (
        置いたクリップの識別子を作る("甲"),
        置いたクリップの識別子を作る("乙"),
    );
    let mut 載せたコマ = 載せたコマの置いたクリップ::載せていない;
    載せたコマ.載せた結果を覚える(
        &求め(&甲, 0.0, 1.0, 続く先::別の置いたクリップ(&乙)),
        番号のコマを載せた(10),
        毎秒30コマ(),
    );
    載せたコマ.何も映さなかったことを覚える();
    assert_eq!(載せたコマ.行の描き方を決める(&乙), 行の描き方::描かない);
    assert_eq!(
        載せたコマ.行の描き方を決める(&甲),
        行の描き方::映す置いたクリップのコマ,
        "同じ置いたクリップへ戻ったなら、載っているのはその置いたクリップのコマである"
    );
}

#[test]
fn 末尾で止めた後に先頭から再生し直すと_末尾の置いたクリップのコマを先頭の置いたクリップの代わりに描かない()
 {
    let (甲, 乙) = (
        置いたクリップの識別子を作る("甲"),
        置いたクリップの識別子を作る("乙"),
    );
    let mut 載せたコマ = 載せたコマの置いたクリップ::載せていない;
    載せたコマ.載せた結果を覚える(
        &求め(&乙, 1.0, 2.0, 続く先::別の置いたクリップ(&甲)),
        番号のコマを載せた(40),
        毎秒30コマ(),
    );
    載せたコマ.載せた結果を覚える(
        &求め(&乙, 1.0, 2.0, 続く先::止まる),
        コマを載せたか::載せなかった,
        毎秒30コマ(),
    );
    assert_eq!(
        載せたコマ.行の描き方を決める(&甲),
        行の描き方::描かない,
        "末尾で最後のコマを映したフレームで続く先が止まるに変わり、0秒へ飛んだ先の甲の代わりには描かない"
    );
}

#[test]
fn 同じ区間へ続くなら_別の置いたクリップでも前のコマを描く() {
    let (甲, 乙) = (
        置いたクリップの識別子を作る("甲"),
        置いたクリップの識別子を作る("乙"),
    );
    let mut 載せたコマ = 載せたコマの置いたクリップ::載せていない;
    載せたコマ.載せた結果を覚える(
        &求め(&甲, 0.0, 1.0, 続く先::同じ区間),
        番号のコマを載せた(10),
        毎秒30コマ(),
    );
    assert_eq!(
        載せたコマ.行の描き方を決める(&乙),
        行の描き方::前の置いたクリップのコマ(&甲)
    );
}
