//! 行に載せているコマの出どころ。行が今コマを載せているか、載せているならそのコマの出どころ(溜めたコマか流し読みか)を表す。

use clip_domain::動画上の区間;

/// 行に載せているコマの出どころとは、行が今コマを載せていないか、区間の溜めたコマを載せているか、流し読みのコマを載せているか
/// (求めた位置のコマをまだ待っているか)の区別のことである。待っているかを流し読みの選択肢の中に持つため、
/// 溜めたコマを載せているのに流し読みのコマを待っている、という組は表せない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 載せているコマの出どころ {
    載せていない,
    溜めたコマ(動画上の区間),
    流し読み { コマを待っている: bool },
}
