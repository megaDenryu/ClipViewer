//! 行の映像の試験。重ね合わせの行のコマの載せ先が、流し読みの出したコマのうち求めの区間の中のコマだけを載せる範囲で作られることを、
//! FFmpeg を使わずに確かめる。継ぎ目で2つの区間の間のコマを載せないことは、この範囲に頼る(同時再生.md 5-2 の7)。
#![allow(clippy::expect_used)]

use eframe::egui;

use super::row_video::行の映像;
use crate::video_feed::{テクスチャの名前, 載せるコマの範囲};

#[test]
fn 重ね合わせの行の載せ先は求めの区間の中のコマだけを載せる() {
    let 行 = 行の映像::登録して作る(
        &egui::Context::default(),
        テクスチャの名前::作成する("試験の行の映像"),
    )
    .expect("行のテクスチャを作れる");
    assert_eq!(
        行.載せ先().載せるコマの範囲(),
        載せるコマの範囲::求めの区間の中だけ
    );
}
