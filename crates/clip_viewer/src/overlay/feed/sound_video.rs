//! 重ね合わせの動画の音。使う動画の表の1本の動画の音を、映像を開けていないため鳴らせないか、開いた動画の音(鳴らせない / 音が無い / 鳴らせる)かを持つ。
//! 開いた動画の音の区別と音の様子の文は、スタックの作業場と同じ型(`audio_feed` の `動画の音`)が持つ。

use audio_pcm::サンプリング周波数;
use video_source::{動画の情報, 動画の読み手};

use crate::audio_feed::{動画の音, 動画の音の供給元};

/// 重ね合わせの動画の音とは、使う動画の表の1本の動画の音を、映像を開けていないため鳴らせないか、
/// 開いた動画の音(動画の音の供給元だけを持つ `動画の音`)かの区別のことである。
pub(crate) enum 重ね合わせの動画の音 {
    映像を開けていない,
    開いた(動画の音<動画の音の供給元>),
}

impl 重ね合わせの動画の音 {
    /// 映像を開けた動画(情報を取れた動画)の音を、2本目の流れの周波数(使えなければ無い)で開く。情報が無ければ映像を開けていない。
    pub(super) fn 開く(
        読み手: Option<&動画の読み手>,
        動画: Option<&動画の情報>,
        周波数: Option<サンプリング周波数>,
    ) -> Self {
        match (読み手, 動画) {
            (Some(読み手), Some(動画)) => {
                Self::開いた(動画の音::供給元だけを開く(読み手, 動画, 周波数))
            }
            _ => Self::映像を開けていない,
        }
    }

    /// 鳴らせるなら動画の音の供給元。
    pub(super) fn 供給元(&self) -> Option<&動画の音の供給元> {
        match self {
            Self::開いた(音) => 音.供給(),
            Self::映像を開けていない => None,
        }
    }

    /// 鳴らせるなら、書き換えられる動画の音の供給元。
    pub(super) fn 供給元を書き換える(&mut self) -> Option<&mut 動画の音の供給元> {
        match self {
            Self::開いた(音) => 音.供給を書き換える(),
            Self::映像を開けていない => None,
        }
    }

    /// 画面の音の様子に出す文。鳴らせるとき、映像を開けていないとき(映像の知らせが理由を出す)は無い。
    pub(super) fn 様子の文(&self) -> Option<String> {
        match self {
            Self::開いた(音) => 音.鳴らせないときの様子の文(),
            Self::映像を開けていない => None,
        }
    }
}
