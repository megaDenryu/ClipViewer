//! 重ね合わせの動画の音。使う動画の表の1本の動画の音を、鳴らせるか、鳴らせないなら何故かを持つ。
//! 鳴らせる動画の音の供給元(読み手・情報・音の倉庫)は、スタックの作業場の音の供給と同じ型(`audio_feed` の `動画の音の供給元`)である。

use audio_pcm::サンプリング周波数;
use video_source::{動画の情報, 動画の読み手};

use crate::audio_feed::{動画の音の供給元, 音を鳴らせない理由};

/// 重ね合わせの動画の音とは、使う動画の表の1本の動画の音を、映像を開けていないため鳴らせないか、鳴らせないか(その理由)か、
/// 動画に音が無いか、鳴らせるならその動画の音の供給元かの区別のことである。
pub(crate) enum 重ね合わせの動画の音 {
    映像を開けていない,
    鳴らせない(音を鳴らせない理由),
    音が無い,
    ある(動画の音の供給元),
}

impl 重ね合わせの動画の音 {
    /// 映像を開けた動画(情報を取れた動画)の音を、2本目の流れの周波数(使えなければ無い)で開く。情報が無ければ映像を開けていない。
    pub(super) fn 開く(
        読み手: Option<&動画の読み手>,
        動画: Option<&動画の情報>,
        周波数: Option<サンプリング周波数>,
    ) -> Self {
        let (Some(読み手), Some(動画)) = (読み手, 動画) else {
            return Self::映像を開けていない;
        };
        match 動画の音の供給元::開く(読み手, 動画, 周波数) {
            Ok(Some(供給元)) => Self::ある(供給元),
            Ok(None) => Self::音が無い,
            Err(理由) => Self::鳴らせない(理由),
        }
    }

    /// 鳴らせるなら動画の音の供給元。
    pub(super) fn 供給元(&self) -> Option<&動画の音の供給元> {
        match self {
            Self::ある(供給元) => Some(供給元),
            Self::映像を開けていない | Self::鳴らせない(_) | Self::音が無い => {
                None
            }
        }
    }

    /// 鳴らせるなら、書き換えられる動画の音の供給元。
    pub(super) fn 供給元を書き換える(&mut self) -> Option<&mut 動画の音の供給元> {
        match self {
            Self::ある(供給元) => Some(供給元),
            Self::映像を開けていない | Self::鳴らせない(_) | Self::音が無い => {
                None
            }
        }
    }

    /// 画面の音の様子に出す文。鳴らせるとき、映像を開けていないとき(映像の知らせが理由を出す)は無い。
    pub(super) fn 様子の文(&self) -> Option<String> {
        match self {
            Self::鳴らせない(理由) => Some(format!("音: 鳴らせない({理由})")),
            Self::音が無い => Some("音: この動画には音が無い".to_string()),
            Self::ある(_) | Self::映像を開けていない => None,
        }
    }
}
