//! 重ね合わせの供給の結合試験の道具。試験動画を作って行ごとの置き方で置いた重ね合わせと、その映像の供給を作ること、行に載ったコマの番号を読むこと。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{
    時刻, 末尾での振る舞い, 正規化した動画パス, 行の番号, 重ね合わせ
};
use eframe::egui;
use video_source::{メモリの上限, 動画の読み手};

use super::row::行の映像の供給;
use super::show_condition::映すものを求める条件;
use super::status::重ね合わせの映像の供給を作れたか;
use super::supply::重ね合わせの映像の供給;
use crate::overlay::test_support::{置き方, 置き方を並べた重ね合わせ};
use crate::video_feed::with_ffmpeg_support::{実行ファイルを探す, 試験動画を作る};

/// 奥の行に 0.5〜1.5秒を0秒から、手前の行に 2.0〜3.5秒を0秒から置く置き方(重ね合わせの長さ1.5秒)。
pub(super) const 二つの行の置き方: &[&[置き方]] = &[
    &[置き方 {
        動画上の区間の開始: 0.5,
        動画上の区間の終了: 1.5,
        始まり: 0.0,
    }],
    &[置き方 {
        動画上の区間の開始: 2.0,
        動画上の区間の終了: 3.5,
        始まり: 0.0,
    }],
];

/// 試験の重ね合わせとは、試験動画(4秒、30コマ/秒、320×180)のファイルと、それを使う重ね合わせと、その映像の供給を作れたかの組のことである。
/// 落とすとファイルを消す。
pub(super) struct 試験の重ね合わせ {
    pub(super) 重ね合わせ: 重ね合わせ,
    pub(super) 映像: 重ね合わせの映像の供給を作れたか,
    パス: 正規化した動画パス,
}

impl 試験の重ね合わせ {
    /// 名前ごとに別のファイルへ試験動画を作り、行ごとの置き方で置いて、メモリの上限の倉庫で映像の供給を開く。
    pub(super) fn 作って開く(
        名前: &str,
        上限: メモリの上限,
        行ごとの置き方: &[&[置き方]],
    ) -> Self {
        let 実行ファイル = 実行ファイルを探す();
        let パス = 試験動画を作る(&実行ファイル, 名前);
        let 重ね合わせ = 置き方を並べた重ね合わせ(パス.clone(), 4.0, 行ごとの置き方);
        let 映像 = 重ね合わせの映像の供給を作れたか::開く(
            Some(&動画の読み手::作成する(実行ファイル)),
            重ね合わせ.動画の表(),
            上限,
            &egui::Context::default(),
        );
        Self {
            重ね合わせ,
            映像,
            パス,
        }
    }

    /// 重ね合わせ上の秒の時刻に、全体の末尾で止まる振る舞いで、行ごとに映すコマを載せる。
    pub(super) fn 行ごとのコマを載せる(&mut self, 秒: f64) {
        let 条件 = 映すものを求める条件 {
            時刻: 時刻::作成する(秒).expect("時刻"),
            全体の末尾: 末尾での振る舞い::止まる,
        };
        self.映像
            .行ごとのコマを載せる(&self.重ね合わせ, 条件, Instant::now());
    }

    pub(super) fn 供給(&self) -> &重ね合わせの映像の供給 {
        match &self.映像 {
            重ね合わせの映像の供給を作れたか::作れた(供給) => 供給,
            重ね合わせの映像の供給を作れたか::作れない(理由) => {
                panic!("供給を作れない: {理由}")
            }
        }
    }

    pub(super) fn 行(&self, 番号: usize) -> &行の映像の供給 {
        self.供給()
            .行(行の番号::番号から作成する(番号))
            .expect("行の数の上限の内")
    }

    /// 行のテクスチャに載ったコマの番号。まだ載せていなければ無い。
    pub(super) fn 載せた番号(&self, 番号: usize) -> Option<u32> {
        self.行(番号)
            .テクスチャ()
            .載せたコマの番号と寸法()
            .map(|載せたコマ| 載せたコマ.番号.値())
    }
}

impl Drop for 試験の重ね合わせ {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(self.パス.文字列());
    }
}
