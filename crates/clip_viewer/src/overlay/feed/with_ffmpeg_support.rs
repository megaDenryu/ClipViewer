//! 重ね合わせの供給の結合試験の道具。試験動画を作って2つの行に置いた重ね合わせと、その映像の供給を作ること、行に載ったコマの番号を読むこと。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{
    時刻, 末尾での振る舞い, 正規化した動画パス, 行の番号, 重ね合わせ
};
use eframe::egui;
use video_source::{メモリの上限, 動画の読み手};

use super::row::行の映像の供給;
use super::status::重ね合わせの映像の様子;
use super::supply::重ね合わせの映像の供給;
use crate::overlay::test_support::{置き方, 置き方を並べた重ね合わせ};
use crate::stream_rules::流し読みの開き直し;
use crate::video_feed::with_ffmpeg_support::{実行ファイルを探す, 試験動画を作る};

/// 試験の重ね合わせとは、試験動画(4秒、30コマ/秒、320×180)のファイルと、それを使う重ね合わせと、その映像の様子の組のことである。
/// 重ね合わせは、奥の行に 0.5〜1.5秒を0秒から、手前の行に 2.0〜3.5秒を0秒から置いたもの(長さ1.5秒)である。落とすとファイルを消す。
pub(super) struct 試験の重ね合わせ {
    pub(super) 重ね合わせ: 重ね合わせ,
    pub(super) 映像: 重ね合わせの映像の様子,
    パス: 正規化した動画パス,
}

impl 試験の重ね合わせ {
    /// 名前ごとに別のファイルへ試験動画を作り、メモリの上限の倉庫で映像の供給を開く。
    pub(super) fn 作って開く(名前: &str, 上限: メモリの上限) -> Self {
        let 実行ファイル = 実行ファイルを探す();
        let パス = 試験動画を作る(&実行ファイル, 名前);
        let 重ね合わせ = 置き方を並べた重ね合わせ(
            パス.clone(),
            4.0,
            &[
                &[置き方 {
                    開始: 0.5,
                    終了: 1.5,
                    始まり: 0.0,
                }],
                &[置き方 {
                    開始: 2.0,
                    終了: 3.5,
                    始まり: 0.0,
                }],
            ],
        );
        let 映像 = 重ね合わせの映像の様子::開く(
            Some(&動画の読み手::作成する(実行ファイル)),
            重ね合わせ.動画の表(),
            上限,
            &egui::Context::default(),
        );
        Self {
            重ね合わせ,
            映像,
            パス,
        }
    }

    /// 重ね合わせ上の秒の時刻に、全体の末尾で止まる振る舞いで、行ごとに映すコマを載せる。
    pub(super) fn 供給する(&mut self, 秒: f64) {
        self.映像.供給する(
            &self.重ね合わせ,
            時刻::作成する(秒).expect("時刻"),
            末尾での振る舞い::止まる,
            流し読みの開き直し::してよい,
            Instant::now(),
        );
    }

    pub(super) fn 供給(&self) -> &重ね合わせの映像の供給 {
        match &self.映像 {
            重ね合わせの映像の様子::供給している(供給) => 供給,
            重ね合わせの映像の様子::供給できない(理由) => {
                panic!("供給を作れない: {理由}")
            }
        }
    }

    pub(super) fn 行(&self, 番号: usize) -> &行の映像の供給 {
        self.供給()
            .行(行の番号::番号から作成する(番号))
            .expect("行の数の上限の内")
    }

    /// 行のテクスチャに載ったコマの番号。まだ載せていなければ無い。
    pub(super) fn 載せた番号(&self, 番号: usize) -> Option<u32> {
        self.行(番号)
            .テクスチャ()
            .載せたコマ()
            .map(|載せたコマ| 載せたコマ.番号.値())
    }
}

impl Drop for 試験の重ね合わせ {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(self.パス.文字列());
    }
}
