//! 行の映像。タイムラインの行ごとに1つ持ち、行のコマの載せ先と、行のテクスチャに載っているコマの置いたクリップを一緒に持って、
//! コマを載せることと、載せたコマがどの置いたクリップのコマかを覚えることを1か所で行う。参照: _doc/設計/同時再生.md 5-1・5-2 の7

use std::time::Instant;

use clip_domain::置いたクリップの識別子;
use eframe::egui;
use sengen_egui::{画素の並びの不正, 登録したテクスチャの参照};

use super::loaded_rows::{行の描き方, 載せたコマの置いたクリップ};
use super::row_request::行の表示するコマの求め;
use crate::stream_rules::流し読みの開き直し;
use crate::video_feed::{
    コマの載せ先, テクスチャの名前, 動画のコマの供給元, 載せるコマの範囲
};

/// 行の映像とは、1つの行のコマの載せ先(流し読み・行のテクスチャ・載せたコマの状態)と、行のテクスチャに今載っているコマの置いたクリップの組のことである。
pub(crate) struct 行の映像 {
    載せ先: コマの載せ先,
    載せたコマの置いたクリップ: 載せたコマの置いたクリップ,
}

impl 行の映像 {
    /// 名前を添えて行のテクスチャを登録して作る。まだどの置いたクリップのコマも載せていない。
    pub(super) fn 登録して作る(
        画面描画の共有状態: &egui::Context,
        名前: テクスチャの名前,
    ) -> Result<Self, 画素の並びの不正> {
        Ok(Self {
            載せ先: コマの載せ先::登録して作る(
                画面描画の共有状態,
                名前,
                載せるコマの範囲::求めの区間の中だけ,
            )?,
            載せたコマの置いたクリップ:
                載せたコマの置いたクリップ::載せていない,
        })
    }

    /// 行のコマの載せ先。結合試験で行のテクスチャと載せたコマの状態を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 載せ先(&self) -> &コマの載せ先 {
        &self.載せ先
    }

    /// 行のテクスチャの参照を複製する。重ねる画面がこの行を描くときに使う。
    pub(crate) fn テクスチャの参照を複製する(
        &self,
    ) -> 登録したテクスチャの参照 {
        self.載せ先.テクスチャの参照を複製する()
    }

    /// 行の流し読みで、求めた位置のコマがまだ届いていないか。届くまで描き直しを続けるために読む。
    pub(crate) fn コマを待っているか(&self) -> bool {
        self.載せ先.コマを待っているか()
    }

    /// 行の求めのコマを供給元から載せ、載せた結果からどの置いたクリップのコマが載っているかを覚える。
    pub(super) fn 求めのコマを載せる(
        &mut self,
        供給元: &mut 動画のコマの供給元,
        求め: &行の表示するコマの求め<'_>,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        let 載せたか = self.載せ先.コマを載せる(供給元, &求め.求め, 開き直し, 今);
        self.載せたコマの置いたクリップ.載せた結果を覚える(
            求め,
            載せたか,
            供給元.情報().コマの速さ(),
        );
    }

    /// 行が何も映さない(または映す置いたクリップの動画を開けなかった)フレームに呼ぶ。流し読みを閉じ、何も映さなかったことを覚える。
    pub(super) fn 何も映さない(&mut self) {
        self.載せ先.流し読みを閉じる();
        self.載せたコマの置いたクリップ
            .何も映さなかったことを覚える();
    }

    /// 作業場を控えるときに呼ぶ。流し読みだけを閉じ、行のテクスチャと載せたコマの置いたクリップは残す。
    pub(super) fn 流し読みを閉じる(&mut self) {
        self.載せ先.流し読みを閉じる();
    }

    /// 行のテクスチャに今載っているコマが、その置いたクリップのコマか。
    pub(crate) fn 置いたクリップのコマが載っているか(
        &self,
        置いたクリップ: &置いたクリップの識別子,
    ) -> bool {
        self.行の描き方を決める(置いたクリップ)
            == 行の描き方::映す置いたクリップのコマ
    }

    /// 行が映す置いたクリップに対して、その行をどう描くか(`載せたコマの置いたクリップ::行の描き方を決める`)。
    pub(crate) fn 行の描き方を決める(
        &self,
        映す置いたクリップ: &置いたクリップの識別子,
    ) -> 行の描き方<'_> {
        self.載せたコマの置いたクリップ
            .行の描き方を決める(映す置いたクリップ)
    }
}
