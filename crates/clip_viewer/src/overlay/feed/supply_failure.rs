//! 映像の供給を作れない理由。重ね合わせを開くときに、重ね合わせの映像の供給そのものを作れなかった理由を持つ。
//! 1本の動画を開けない理由(`動画を開けない理由`)とは分ける。動画を開けなくても供給は作り、その動画の行だけが何も映さないためである。

use sengen_egui::画素の並びの不正;

/// 映像の供給を作れない理由とは、重ね合わせの映像の供給を作れなかった理由の区別のことである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 映像の供給を作れない理由 {
    #[error(
        "FFmpeg が見つからないため重ね合わせの動画を開けない。「スタックへ戻る」を押し、画面の上部で FFmpeg の置き場所を設定する"
    )]
    FFmpegが無い,
    #[error("重ね合わせの行のテクスチャを作れない: {0}")]
    行のテクスチャを作れない(#[from] 画素の並びの不正),
}
