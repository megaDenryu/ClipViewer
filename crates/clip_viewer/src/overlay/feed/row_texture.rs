//! 行のテクスチャ。タイムラインの行が映すコマを載せる GPU のテクスチャと、今載っているコマの番号と寸法を持つ。
//! 行の中で置いたクリップが入れ替わっても作り直さず、載せ直すかは載せ直しの鍵(`載せたコマの番号と寸法`)で決める。参照: _doc/設計/同時再生.md 5-1

use eframe::egui;
use sengen_egui::{
    差し替えられるテクスチャ, 拡大縮小の仕方, 画素の並び, 画素の並びの不正, 画素数の寸法,
};
use video_source::{コマ, 動画上のコマ番号};

use crate::video_feed::載せたコマの番号と寸法;

/// 最初のコマが届くまで載せておく1画素の黒。
const 黒の一画素: [u8; 4] = [0, 0, 0, 255];

/// 行のテクスチャとは、タイムラインの行が映すコマを載せるテクスチャと、今載っているコマの番号と寸法(まだ載せていなければ無い)の組のことである。
pub(crate) struct 映像のテクスチャ {
    テクスチャ: 差し替えられるテクスチャ,
    載せたコマ: Option<載せたコマの番号と寸法>,
}

impl 映像のテクスチャ {
    /// 1画素の黒を載せて登録する。動画のコマは写真に近いため、隣の画素と混ぜて拡大縮小する。
    pub(super) fn 登録して作る(
        画面描画の共有状態: &egui::Context,
    ) -> Result<Self, 画素の並びの不正> {
        let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
            画素数の寸法::生成する(1, 1),
            &黒の一画素,
        )?;
        let テクスチャ = 差し替えられるテクスチャ::登録して作る(
            画面描画の共有状態,
            "ClipViewer の重ね合わせの行の映像",
            画素,
            拡大縮小の仕方::隣の画素と混ぜる,
        );
        Ok(Self {
            テクスチャ,
            載せたコマ: None,
        })
    }

    /// 今載っているコマの番号と寸法。まだ動画のコマを1つも載せていなければ無い。試験で、行に載ったコマを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 載せたコマ(&self) -> Option<載せたコマの番号と寸法> {
        self.載せたコマ
    }

    /// コマを載せる。前に載せたコマと番号と寸法が同じなら載せ直さない。
    pub(super) fn コマを載せる(
        &mut self,
        番号: 動画上のコマ番号,
        コマ: &コマ,
    ) -> Result<(), 画素の並びの不正> {
        let 今のコマ = 載せたコマの番号と寸法 {
            番号,
            寸法: コマ.寸法(),
        };
        if !今のコマ.載せ直すか(self.載せたコマ) {
            return Ok(());
        }
        let 寸法 = 画素数の寸法::生成する(コマ.寸法().幅(), コマ.寸法().高さ());
        let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
            寸法,
            コマ.画素の並び(),
        )?;
        self.テクスチャ.差し替える(画素);
        self.載せたコマ = Some(今のコマ);
        Ok(())
    }
}
