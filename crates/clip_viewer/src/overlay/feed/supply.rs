//! 重ね合わせの映像の供給。使う動画の表の動画ごとの動画のコマの供給元と、タイムラインの行ごとのコマの載せ先を持ち、毎フレーム、
//! その時刻に行ごとに映すもの(第2段階の `重ね合わせ上の時刻に映すものを求める`)から、動画ごとの先読みを整えて、行ごとに表示するコマを載せる。
//! 参照: _doc/設計/同時再生.md 5-1・5-2

use std::time::Instant;

use clip_domain::{
    使う動画の表, 動画の番号, 同時に重ねられる行の数, 行の番号
};
use eframe::egui;
use sengen_egui::画素の並びの不正;
use video_source::{メモリの上限, 動画の読み手};

use super::frame_targets::このフレームで映すもの;
use super::loaded_rows::行ごとの載せたコマの置いたクリップ;
use super::row_request::行の表示するコマの求め;
use super::video_status::重ね合わせの動画を開けたか;
use crate::stream_rules::流し読みの開き直し;
use crate::video_feed::{コマの載せ先, コマを載せたか, テクスチャの名前};

const 行の映像のテクスチャの名前: テクスチャの名前 =
    テクスチャの名前::作成する("ClipViewer の重ね合わせの行の映像");

/// 重ね合わせの映像の供給とは、使う動画の表の動画ごとの重ね合わせの動画を開けたか(添字は動画の番号)と、同時に重ねられる行の数だけのコマの載せ先(添字は行の番号)と、
/// 行ごとの載せたコマの置いたクリップ(どの置いたクリップのコマを載せたか)の組のことである。
/// 行のコマの載せ先を行の数の上限だけ先に作るのは、行の中で置いたクリップが入れ替わっても、行が増えても、行のテクスチャを作り直さないためである。
pub(crate) struct 重ね合わせの映像の供給 {
    pub(super) 動画: Vec<重ね合わせの動画を開けたか>,
    pub(super) 行ごとのコマの載せ先: Vec<コマの載せ先>,
    pub(super) 載せたコマの置いたクリップ: 行ごとの載せたコマの置いたクリップ,
}

impl 重ね合わせの映像の供給 {
    /// 使う動画の表の動画を1本ずつ開き(ffprobe が終わるまで待つ)、行のテクスチャを登録する。開けない動画はその理由を持つ。
    pub(super) fn 開く(
        読み手: &動画の読み手,
        動画の表: &使う動画の表,
        上限: メモリの上限,
        画面描画の共有状態: &egui::Context,
    ) -> Result<Self, 画素の並びの不正> {
        let 動画 = 動画の表
            .動画のパスの並び()
            .iter()
            .map(|パス| 重ね合わせの動画を開けたか::開く(読み手, パス, 上限))
            .collect();
        let 行ごとのコマの載せ先 = (0..同時に重ねられる行の数)
            .map(|_| {
                コマの載せ先::登録して作る(
                    画面描画の共有状態,
                    行の映像のテクスチャの名前,
                )
            })
            .collect::<Result<_, _>>()?;
        Ok(Self {
            動画,
            行ごとのコマの載せ先,
            載せたコマの置いたクリップ:
                行ごとの載せたコマの置いたクリップ::まだ載せていない(),
        })
    }

    /// このフレームで映すものから、動画ごとに先読みを整え、行ごとに表示するコマを載せる。何も映さない行(と、映す置いたクリップの動画を開けなかった行)は
    /// 流し読みを閉じ、何も映さなかったことを覚える。コマを実際にテクスチャへ載せた行だけ、その置いたクリップのコマを載せたことを覚える。
    /// 重ね合わせの作業場はまだ再生位置の帯を持たないため、流し読みの開き直しを控えることは無く、いつも開き直してよいとする。
    pub(super) fn 行ごとのコマを載せる(
        &mut self,
        映すもの: &このフレームで映すもの<'_>,
        今: Instant,
    ) {
        for (添字, 開けたか) in self.動画.iter_mut().enumerate() {
            if let Some(動画) = 開けたか.開いた供給元() {
                動画.先読みを整える(
                    映すもの
                        .先読みの並び
                        .区間の列(動画の番号::番号から作成する(添字)),
                    今,
                );
            }
        }
        let 開き直し = 流し読みの開き直し::してよい;
        for (添字, 行) in self.行ごとのコマの載せ先.iter_mut().enumerate() {
            let 行の番号 = 行の番号::番号から作成する(添字);
            let 開いた動画 =
                行の表示するコマの求め::行ごとに映すものから作る(
                    &映すもの.行ごと,
                    行の番号,
                )
                .and_then(|行の求め| {
                    let 動画 = self.動画.get_mut(行の求め.動画.番号())?.開いた供給元()?;
                    Some((動画, 行の求め))
                });
            let Some((動画, 行の求め)) = 開いた動画 else {
                行.流し読みを閉じる();
                self.載せたコマの置いたクリップ
                    .何も映さなかったことを覚える(行の番号);
                continue;
            };
            if let コマを載せたか::載せた(_) =
                行.コマを載せる(動画, &行の求め.求め, 開き直し, 今)
            {
                self.載せたコマの置いたクリップ
                    .載せたことを覚える(行の番号, 行の求め.置いたクリップ);
            }
        }
    }

    /// 全部の行の流し読みを閉じる。行のテクスチャには前に載せたコマが残る。
    pub(super) fn 流し読みを閉じる(&mut self) {
        for 行 in &mut self.行ごとのコマの載せ先 {
            行.流し読みを閉じる();
        }
    }
}
