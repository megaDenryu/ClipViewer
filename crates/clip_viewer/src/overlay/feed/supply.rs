//! 重ね合わせの映像の供給。使う動画の表の動画ごとの供給と、タイムラインの行ごとの供給を持ち、毎フレーム、
//! その時刻に行ごとに映すもの(第2段階の `重ね合わせ上の時刻に映すものを求める`)から、動画ごとの先読みを整えて、行ごとに表示するコマを載せる。
//! 参照: _doc/設計/同時再生.md 5-1・5-2

use std::time::Instant;

use clip_domain::{
    使う動画の表, 動画の番号, 同時に重ねられる行の数, 行の映し方, 行の番号, 重ね合わせ,
};
use eframe::egui;
use sengen_egui::画素の並びの不正;
use video_source::{メモリの上限, 動画の読み手};

use super::prefetch::重ね合わせの先読みの並び;
use super::row::コマの載せ先;
use super::row_request::行の表示するコマの求め;
use super::show_condition::映すものを求める条件;
use super::video_status::重ね合わせの動画を開けたか;

/// 重ね合わせの映像の供給とは、使う動画の表の動画ごとの重ね合わせの動画を開けたか(添字は動画の番号)と、同時に重ねられる行の数だけの行の映像の供給(添字は行の番号)の組のことである。
/// 行の供給を行の数の上限だけ先に作るのは、行の中で置いたクリップが入れ替わっても、行が増えても、行のテクスチャを作り直さないためである。
pub(crate) struct 重ね合わせの映像の供給 {
    動画: Vec<重ね合わせの動画を開けたか>,
    行: Vec<コマの載せ先>,
}

impl 重ね合わせの映像の供給 {
    /// 使う動画の表の動画を1本ずつ開き(ffprobe が終わるまで待つ)、行のテクスチャを登録する。開けない動画はその理由を持つ。
    pub(super) fn 開く(
        読み手: &動画の読み手,
        動画の表: &使う動画の表,
        上限: メモリの上限,
        画面描画の共有状態: &egui::Context,
    ) -> Result<Self, 画素の並びの不正> {
        let 動画 = 動画の表
            .動画のパスの並び()
            .iter()
            .map(|パス| 重ね合わせの動画を開けたか::開く(読み手, パス, 上限))
            .collect();
        let 行 = (0..同時に重ねられる行の数)
            .map(|_| コマの載せ先::登録して作る(画面描画の共有状態))
            .collect::<Result<_, _>>()?;
        Ok(Self { 動画, 行 })
    }

    /// 条件の時刻に映すものを求め、動画ごとに先読みを整え、行ごとに表示するコマを載せる。何も映さない行は流し読みを閉じる。
    pub(super) fn 行ごとのコマを載せる(
        &mut self,
        重ね合わせ: &重ね合わせ,
        条件: 映すものを求める条件,
        今: Instant,
    ) {
        let 映すもの = 条件.行ごとに映すものを求める(重ね合わせ);
        let 並び =
            重ね合わせの先読みの並び::求める(重ね合わせ, 条件.時刻, &映すもの);
        for (添字, 開けたか) in self.動画.iter_mut().enumerate() {
            if let 重ね合わせの動画を開けたか::開いた(動画) = 開けたか {
                動画.先読みを整える(並び.区間の列(動画の番号::番号から作成する(添字)), 今);
            }
        }
        for (添字, 行) in self.行.iter_mut().enumerate() {
            let 映し方 = 映すもの
                .iter()
                .find(|行が映すもの| 行が映すもの.行.番号() == 添字)
                .map_or(行の映し方::何も映さない, |行が映すもの| {
                    行が映すもの.映し方
                });
            let 開いた動画 = 行の表示するコマの求め::映し方から作る(映し方).and_then(|行の求め| {
                match self.動画.get_mut(行の求め.動画.番号()) {
                    Some(重ね合わせの動画を開けたか::開いた(動画)) => {
                        Some((動画, 行の求め.求め))
                    }
                    Some(重ね合わせの動画を開けたか::開けない(_)) | None => None,
                }
            });
            match 開いた動画 {
                Some((動画, 求め)) => 行.コマを載せる(動画, &求め, 今),
                None => 行.映すのをやめる(),
            }
        }
    }

    /// 全部の行の流し読みを閉じる。行のテクスチャには前に載せたコマが残る。
    pub(super) fn 流し読みを閉じる(&mut self) {
        for 行 in &mut self.行 {
            行.映すのをやめる();
        }
    }

    /// 開けなかった動画ごとの理由の文(使う動画の表の順)。
    pub(super) fn 開けなかった動画の理由の文(&self) -> Vec<String> {
        self.動画
            .iter()
            .filter_map(重ね合わせの動画を開けたか::開けない理由)
            .map(ToString::to_string)
            .collect()
    }

    /// 行の番号の行の映像の供給。同時に重ねられる行の数より後ろの番号なら無い。
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "第8段階で重ねる画面に行のテクスチャを描くときに読む(同時再生.md 5-2 の7)。それまでは試験からだけ読む(同時再生.md 6節)"
        )
    )]
    pub(crate) fn 行(&self, 番号: 行の番号) -> Option<&コマの載せ先> {
        self.行.get(番号.番号())
    }

    /// 動画の番号の動画を開けたか。結合試験で、台帳と開けない理由を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 動画を開けたか(
        &self,
        番号: 動画の番号,
    ) -> Option<&重ね合わせの動画を開けたか> {
        self.動画.get(番号.番号())
    }
}
