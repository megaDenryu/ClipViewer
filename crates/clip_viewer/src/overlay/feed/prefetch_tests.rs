//! 重ね合わせの先読みの並びの試験。今映している置いたクリップ → 時刻より後に始まる置いたクリップ → 残りの順に並べ、同じ区間を1つにまとめることを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{
    入力された動画パス, 動画の番号, 動画上の区間, 時刻, 末尾での振る舞い, 重ね合わせ,
};

use super::prefetch::重ね合わせの先読みの並び;
use crate::overlay::test_support::{置き方, 置き方を並べた重ね合わせ};

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}

fn 置き方を作る(開始: f64, 終了: f64, 始まり: f64) -> 置き方 {
    置き方 {
        動画上の区間の開始: 開始,
        動画上の区間の終了: 終了,
        始まり,
    }
}

/// 奥の行: 0〜1秒を0秒から・2〜3秒を2秒から。手前の行: 4〜5秒を1秒から・0〜1秒を3秒から(奥の行の最初と同じ区間)。
fn 二つの行の重ね合わせ() -> 重ね合わせ {
    置き方を並べた重ね合わせ(
        入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
        60.0,
        &[
            &[置き方を作る(0.0, 1.0, 0.0), 置き方を作る(2.0, 3.0, 2.0)],
            &[置き方を作る(4.0, 5.0, 1.0), 置き方を作る(0.0, 1.0, 3.0)],
        ],
    )
}

fn 時刻に求めた区間の列(
    重ね合わせ: &重ね合わせ, 秒: f64
) -> Vec<動画上の区間> {
    let 時刻 = 時刻::作成する(秒).expect("時刻");
    let 映すもの: Vec<_> = 重ね合わせ
        .重ね合わせ上の時刻に映すものを求める(時刻, 末尾での振る舞い::先頭へ戻る)
        .collect();
    重ね合わせの先読みの並び::求める(重ね合わせ, 時刻, &映すもの)
        .区間の列(動画の番号::番号から作成する(0))
        .to_vec()
}

#[test]
fn 今映している置いたクリップを先にし_後に始まるものを始まりの順に続け_同じ区間を1つにする() {
    let 重ね合わせ = 二つの行の重ね合わせ();
    assert_eq!(
        時刻に求めた区間の列(&重ね合わせ, 0.5),
        [区間(0.0, 1.0), 区間(4.0, 5.0), 区間(2.0, 3.0)]
    );
}

#[test]
fn 映しているものの後に_後に始まるものと_残りを始まりの順に並べる() {
    let 重ね合わせ = 二つの行の重ね合わせ();
    assert_eq!(
        時刻に求めた区間の列(&重ね合わせ, 2.5),
        [区間(2.0, 3.0), 区間(0.0, 1.0), 区間(4.0, 5.0)]
    );
}

#[test]
fn 表に無い動画の番号の区間の列は空である() {
    let 重ね合わせ = 二つの行の重ね合わせ();
    let 時刻 = 時刻::先頭;
    let 映すもの: Vec<_> = 重ね合わせ
        .重ね合わせ上の時刻に映すものを求める(時刻, 末尾での振る舞い::先頭へ戻る)
        .collect();
    let 並び = 重ね合わせの先読みの並び::求める(&重ね合わせ, 時刻, &映すもの);
    assert!(並び.区間の列(動画の番号::番号から作成する(1)).is_empty());
}
