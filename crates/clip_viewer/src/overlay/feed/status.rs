//! 重ね合わせの映像の様子と動画の様子。重ね合わせを開いたときに映像の供給を作れたか、使う動画の表の動画ごとに動画を開けたか、
//! 作れなかった・開けなかった理由を持ち、作れたときだけ毎フレーム供給する。
//! 動画の読み手は、スタックの作業場の `動画の開き手` から開くたびに借りる(同時再生.md 3-2 の FFmpeg の読み手の行)。

use std::time::Instant;

use clip_domain::{
    使う動画の表, 末尾での振る舞い, 正規化した動画パス, 重ね合わせ, 重ね合わせ上の秒,
};
use eframe::egui;
use video_source::{メモリの上限, 動画の読み手};

use super::supply::重ね合わせの映像の供給;
use super::video::重ね合わせの動画の供給;
use crate::stream_rules::流し読みの開き直し;
use crate::video_feed::動画を開けない理由;

/// 重ね合わせの映像の様子とは、開いた重ね合わせの映像の供給を作れたか、作れなかったかの区別のことである。
/// 作れないのは、FFmpeg が見つかっていない(読み手を借りられない)ときと、行のテクスチャを作れないときである。
/// 1本の動画を開けないことは、供給の中の動画ごとの様子が持つ。
pub(crate) enum 重ね合わせの映像の様子 {
    供給している(重ね合わせの映像の供給),
    供給できない(動画を開けない理由),
}

impl 重ね合わせの映像の様子 {
    /// 借りた動画の読み手(FFmpeg が見つかっていなければ無い)で、使う動画の表の動画を開いて供給を作る。
    pub(crate) fn 開く(
        読み手: Option<&動画の読み手>,
        動画の表: &使う動画の表,
        上限: メモリの上限,
        画面描画の共有状態: &egui::Context,
    ) -> Self {
        let Some(読み手) = 読み手 else {
            return Self::供給できない(動画を開けない理由::FFmpegが無い);
        };
        match 重ね合わせの映像の供給::開く(読み手, 動画の表, 上限, 画面描画の共有状態)
        {
            Ok(供給) => Self::供給している(供給),
            Err(不正) => Self::供給できない(動画を開けない理由::テクスチャを作れない(不正)),
        }
    }

    /// 供給を作れなかった理由。作れていれば無い。
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "第8段階で重ね合わせの作業場の知らせに出すときに読む。それまでは試験からだけ読む(同時再生.md 6節)"
        )
    )]
    pub(crate) fn 供給できない理由(&self) -> Option<&動画を開けない理由> {
        match self {
            Self::供給している(_) => None,
            Self::供給できない(理由) => Some(理由),
        }
    }

    /// 供給を作れていれば、重ね合わせ上の時刻に行ごとに映すコマを載せる。作れていなければ何もしない。
    pub(crate) fn 供給する(
        &mut self,
        重ね合わせ: &重ね合わせ,
        時刻: 重ね合わせ上の秒,
        全体の末尾: 末尾での振る舞い,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        if let Self::供給している(供給) = self {
            供給.供給する(重ね合わせ, 時刻, 全体の末尾, 開き直し, 今);
        }
    }
}

/// 重ね合わせの動画の様子とは、使う動画の表の1本の動画を、供給のために開けたか、開けなかったか(その理由)の区別のことである。
/// 1本の動画を開けなくても、ほかの動画の行は映す。
#[expect(
    clippy::large_enum_variant,
    reason = "使う動画の表の動画ごとに1つだけ作り、開くときに1回だけ置くため、選択肢の大きさの差は問題にならない"
)]
pub(crate) enum 重ね合わせの動画の様子 {
    開いた(重ね合わせの動画の供給),
    開けない(動画を開けない理由),
}

impl 重ね合わせの動画の様子 {
    /// 借りた読み手の写しで動画を開く。開けなければ、その理由を持つ。
    pub(super) fn 開く(
        読み手: &動画の読み手,
        パス: &正規化した動画パス,
        上限: メモリの上限,
    ) -> Self {
        match 重ね合わせの動画の供給::開く(読み手.clone(), パス, 上限) {
            Ok(供給) => Self::開いた(供給),
            Err(理由) => Self::開けない(理由),
        }
    }

    /// 動画を開けなかった理由。開けていれば無い。
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "第8段階で動画を開けない理由を画面に出すときに読む。それまでは試験からだけ読む(同時再生.md 6節)"
        )
    )]
    pub(crate) fn 開けない理由(&self) -> Option<&動画を開けない理由> {
        match self {
            Self::開いた(_) => None,
            Self::開けない(理由) => Some(理由),
        }
    }
}
