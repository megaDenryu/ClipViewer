//! 重ね合わせの映像の供給を作れたか。重ね合わせを開いたときに映像の供給を作れたか、作れなかったか(その理由)を持ち、作れたときだけ毎フレーム供給する。
//! 動画の読み手は、スタックの作業場の `動画の開き手` から開くたびに借りる(同時再生.md 3-2 の FFmpeg の読み手の行)。

use std::time::Instant;

use clip_domain::{
    使う動画の表, 動画の番号, 置いたクリップの識別子, 行の番号
};
use eframe::egui;
use video_source::{メモリの上限, 動画の情報, 動画の読み手};

use super::frame_targets::このフレームで映すもの;
use super::supply::重ね合わせの映像の供給;
use super::supply_failure::映像の供給を作れない理由;

/// 重ね合わせの映像の供給を作れたかとは、開いた重ね合わせの映像の供給を作れたか、作れなかったか(その理由)の区別のことである。
/// 1本の動画を開けないことは、供給の中の、動画ごとの重ね合わせの動画を開けたかが持つ。
pub(crate) enum 重ね合わせの映像の供給を作れたか {
    作れた(重ね合わせの映像の供給),
    作れない(映像の供給を作れない理由),
}

impl 重ね合わせの映像の供給を作れたか {
    /// 借りた動画の読み手(FFmpeg が見つかっていなければ無い)で、使う動画の表の動画を開いて供給を作る。
    pub(crate) fn 開く(
        読み手: Option<&動画の読み手>,
        動画の表: &使う動画の表,
        上限: メモリの上限,
        画面描画の共有状態: &egui::Context,
    ) -> Self {
        let Some(読み手) = 読み手 else {
            return Self::作れない(映像の供給を作れない理由::FFmpegが無い);
        };
        match 重ね合わせの映像の供給::開く(読み手, 動画の表, 上限, 画面描画の共有状態)
        {
            Ok(供給) => Self::作れた(供給),
            Err(不正) => Self::作れない(不正.into()),
        }
    }

    /// 開いたときに利用者へ知らせる文。供給を作れなかった理由か、開けなかった動画ごとの理由である。全部を開けたなら空である。
    pub(crate) fn 開けなかった知らせの文(&self) -> Vec<String> {
        match self {
            Self::作れた(供給) => 供給.開けなかった動画の理由の文(),
            Self::作れない(理由) => vec![理由.to_string()],
        }
    }

    /// 供給を作れていれば、このフレームで映すものから行ごとに映すコマを載せる。作れていなければ何もしない。
    pub(crate) fn 行ごとのコマを載せる(
        &mut self,
        映すもの: &このフレームで映すもの<'_>,
        今: Instant,
    ) {
        if let Self::作れた(供給) = self {
            供給.行ごとのコマを載せる(映すもの, 今);
        }
    }

    /// 行のテクスチャに今載っているコマが、その置いたクリップのコマか。供給を作れなかったときは、待っても載らないため載っているとみなす。
    pub(crate) fn 行に置いたクリップのコマが載っているか(
        &self,
        行: 行の番号,
        置いたクリップ: &置いたクリップの識別子,
    ) -> bool {
        match self {
            Self::作れた(供給) => {
                供給.行に置いたクリップのコマが載っているか(行, 置いたクリップ)
            }
            Self::作れない(_) => true,
        }
    }

    /// 入力が無くても描き直しを続ける必要があるか。供給を作れていなければ進め続けない。
    pub(crate) fn 描き直しを続ける必要があるか(&self) -> bool {
        match self {
            Self::作れた(供給) => 供給.描き直しを続ける必要があるか(),
            Self::作れない(_) => false,
        }
    }

    /// 動画の番号の動画を開けていれば、その動画の情報。供給を作れていなければ無い。
    pub(crate) fn 開いた動画の情報(
        &self, 番号: 動画の番号
    ) -> Option<&動画の情報> {
        match self {
            Self::作れた(供給) => 供給.開いた動画の情報(番号),
            Self::作れない(_) => None,
        }
    }

    /// 動画の番号の動画の映像の先読みが落ち着いたか。供給を作れていなければ落ち着いたとみなす。
    pub(crate) fn 先読みが落ち着いたか(&self, 番号: 動画の番号) -> bool {
        match self {
            Self::作れた(供給) => 供給.先読みが落ち着いたか(番号),
            Self::作れない(_) => true,
        }
    }

    /// 作業場を控えるときに呼ぶ。全部の行の流し読みを閉じて ffmpeg を止める。行のテクスチャには前に載せたコマが残る。
    pub(crate) fn 流し読みを閉じる(&mut self) {
        if let Self::作れた(供給) = self {
            供給.流し読みを閉じる();
        }
    }
}
