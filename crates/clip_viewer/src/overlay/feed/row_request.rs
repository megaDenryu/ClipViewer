//! 行の表示するコマの求め。その時刻に行が映すもの(第2段階の `行の映し方`)から、どの動画のどの位置のコマを、どの区間から、どう切り出して出すかを求める。

use clip_domain::{
    動画の番号, 置いたクリップの識別子, 行が映すもの, 行の映し方, 行の番号
};

use super::continuation::続く先;
use crate::video_feed::表示するコマの求め;

/// 行の表示するコマの求めとは、行が映す置いたクリップの識別子と、行が映すコマの動画の番号と、その動画の中で表示するコマの求めと、
/// その置いたクリップの続く先の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 行の表示するコマの求め<'重ね合わせ> {
    pub(super) 置いたクリップ: &'重ね合わせ 置いたクリップの識別子,
    pub(super) 動画: 動画の番号,
    pub(super) 求め: 表示するコマの求め,
    pub(super) 続く先: 続く先<&'重ね合わせ 置いたクリップの識別子>,
}

impl<'重ね合わせ> 行の表示するコマの求め<'重ね合わせ> {
    /// 行ごとに映すものの中から、行の番号の行の映し方を探して作る。映すものに無い行は何も映さない。
    pub(super) fn 行ごとに映すものから作る(
        映すもの: &[行が映すもの<'重ね合わせ>],
        行: 行の番号,
    ) -> Option<Self> {
        let 映し方 = 映すもの
            .iter()
            .find(|行が映すもの| 行が映すもの.行.番号() == 行.番号())
            .map_or(行の映し方::何も映さない, |行が映すもの| {
                行が映すもの.映し方
            });
        Self::映し方から作る(映し方)
    }

    /// 行の映し方から作る。何も映さないなら無い。末尾で最後のコマを映すときも区間を添えて求めるため、
    /// 溜めたコマからも流し読みからも、区間の中の最後のコマを映す。
    fn 映し方から作る(映し方: 行の映し方<'重ね合わせ>) -> Option<Self> {
        let (置いたクリップ, 動画上の位置) = match 映し方 {
            行の映し方::置いたクリップを映す(中身) => {
                (中身.置いたクリップ, 中身.動画上の位置)
            }
            行の映し方::末尾で最後のコマを映す {
                置いたクリップ,
                動画上の位置,
            } => (置いたクリップ, 動画上の位置),
            行の映し方::何も映さない => return None,
        };
        let 受け継いだ値 = 置いたクリップ.受け継いだ値();
        Some(Self {
            置いたクリップ: 置いたクリップ.識別子(),
            動画: 置いたクリップ.動画の番号(),
            求め: 表示するコマの求め {
                動画上の位置,
                区間: Some(受け継いだ値.区間),
                クロップ: 受け継いだ値.クロップ,
            },
            続く先: 続く先::映し方から求める(映し方),
        })
    }
}
