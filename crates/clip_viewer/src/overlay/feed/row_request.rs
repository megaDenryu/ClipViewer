//! 行の表示するコマの求め。その時刻に行が映すもの(第2段階の `行の映し方`)から、どの動画のどの位置のコマを、どの区間から、どう切り出して出すかを求める。

use clip_domain::{動画の番号, 行の映し方};

use crate::video_feed::表示するコマの求め;

/// 行の表示するコマの求めとは、行が映すコマの動画の番号と、その動画の中で表示するコマの求めの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) struct 行の表示するコマの求め {
    pub(super) 動画: 動画の番号,
    pub(super) 求め: 表示するコマの求め,
}

impl 行の表示するコマの求め {
    /// 行の映し方から作る。何も映さないなら無い。末尾で最後のコマを映すときも区間を添えて求めるため、
    /// 溜めたコマからも流し読みからも、区間の中の最後のコマを映す。
    pub(super) fn 映し方から作る(映し方: 行の映し方<'_>) -> Option<Self> {
        let (置いたクリップ, 動画上の位置) = match 映し方 {
            行の映し方::置いたクリップを映す(中身) => {
                (中身.置いたクリップ, 中身.動画上の位置)
            }
            行の映し方::末尾で最後のコマを映す {
                置いたクリップ,
                動画上の位置,
            } => (置いたクリップ, 動画上の位置),
            行の映し方::何も映さない => return None,
        };
        let 受け継いだ値 = 置いたクリップ.受け継いだ値();
        Some(Self {
            動画: 置いたクリップ.動画の番号(),
            求め: 表示するコマの求め {
                動画上の位置,
                区間: Some(受け継いだ値.区間),
                クロップ: 受け継いだ値.クロップ,
            },
        })
    }
}
