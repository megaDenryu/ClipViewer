//! 重ね合わせの動画を開けたか。使う動画の表の1本の動画を、供給のために開けたか、開けなかったか(その理由)を持つ。

use clip_domain::正規化した動画パス;
use video_source::{メモリの上限, 動画の読み手};

use super::video::動画ごとの倉庫と台帳;
use crate::video_feed::動画を開けない理由;

/// 重ね合わせの動画を開けたかとは、使う動画の表の1本の動画を、供給のために開けたか、開けなかったか(その理由)の区別のことである。
/// 1本の動画を開けなくても、ほかの動画の行は映す。
#[expect(
    clippy::large_enum_variant,
    reason = "使う動画の表の動画ごとに1つだけ作り、開くときに1回だけ置くため、選択肢の大きさの差は問題にならない"
)]
pub(crate) enum 重ね合わせの動画を開けたか {
    開いた(動画ごとの倉庫と台帳),
    開けない(動画を開けない理由),
}

impl 重ね合わせの動画を開けたか {
    /// 借りた読み手の写しで動画を開く。開けなければ、その理由を持つ。
    pub(super) fn 開く(
        読み手: &動画の読み手,
        パス: &正規化した動画パス,
        上限: メモリの上限,
    ) -> Self {
        match 動画ごとの倉庫と台帳::開く(読み手.clone(), パス, 上限) {
            Ok(供給) => Self::開いた(供給),
            Err(理由) => Self::開けない(理由),
        }
    }

    /// 動画を開けなかった理由。開けていれば無い。
    pub(crate) fn 開けない理由(&self) -> Option<&動画を開けない理由> {
        match self {
            Self::開いた(_) => None,
            Self::開けない(理由) => Some(理由),
        }
    }
}
