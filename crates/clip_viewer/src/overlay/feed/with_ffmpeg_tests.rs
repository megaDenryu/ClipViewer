//! 重ね合わせの供給の結合試験。2つの行に置いた同じ動画の区間を1つの倉庫に溜め終えた後は、行ごとに溜めたコマから載せることと、
//! 置いたクリップの終わった行は何も映さないことと、重ね合わせの末尾では各行がその行の最後の置いたクリップの区間の最後のコマを映すことと、
//! 同じ区間を2つの行に置いても倉庫への依頼は1件であることを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use clip_domain::{動画の番号, 動画上の区間, 時刻};
use video_source::{メモリの上限, 受付の札};

use super::row_showing::行に載せているコマの出どころ;
use super::video_status::重ね合わせの動画を開けたか;
use super::with_ffmpeg_support::{二つの行の置き方, 試験の重ね合わせ};
use crate::overlay::test_support::置き方;
use crate::video_feed::with_ffmpeg_support::成り立つまで待つ;
use crate::video_feed::依頼の台帳;

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}

fn 台帳(試験: &試験の重ね合わせ) -> &依頼の台帳<受付の札> {
    match 試験.供給().動画を開けたか(動画の番号::番号から作成する(0)) {
        Some(重ね合わせの動画を開けたか::開いた(動画)) => 動画.台帳(),
        Some(重ね合わせの動画を開けたか::開けない(理由)) => {
            panic!("動画を開けない: {理由}")
        }
        None => panic!("表に動画が無い"),
    }
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 同じ動画の2つの区間を1つの倉庫に溜め終えた後は_行ごとに溜めたコマから載せ_末尾で各行の最後のコマを映す()
 {
    let mut 試験 = 試験の重ね合わせ::作って開く(
        "重ね合わせの溜めたコマ",
        メモリの上限::既定,
        二つの行の置き方,
    );
    let (奥の区間, 手前の区間) = (区間(0.5, 1.5), 区間(2.0, 3.5));
    成り立つまで待つ("2つの行の区間を溜め終えること", || {
        試験.行ごとのコマを載せる(0.25);
        台帳(&試験).溜め終えたか(&奥の区間) && 台帳(&試験).溜め終えたか(&手前の区間)
    });
    試験.行ごとのコマを載せる(0.25);
    assert_eq!(
        試験.行(0).載せているコマの出どころ(),
        行に載せているコマの出どころ::溜めたコマ(奥の区間)
    );
    assert_eq!(
        試験.行(1).載せているコマの出どころ(),
        行に載せているコマの出どころ::溜めたコマ(手前の区間)
    );
    assert!(matches!(試験.載せた番号(0), Some(22..=23)), "0.75秒のコマ");
    assert!(matches!(試験.載せた番号(1), Some(67..=68)), "2.25秒のコマ");
    assert_eq!(
        試験.行(2).載せているコマの出どころ(),
        行に載せているコマの出どころ::載せていない
    );

    試験.行ごとのコマを載せる(1.2);
    assert_eq!(
        試験.行(0).載せているコマの出どころ(),
        行に載せているコマの出どころ::載せていない,
        "奥の行の置いたクリップは1秒で終わる"
    );
    assert!(matches!(試験.載せた番号(1), Some(96..=97)), "3.2秒のコマ");

    試験.行ごとのコマを載せる(1.5);
    assert_eq!(試験.載せた番号(0), Some(44), "奥の区間の最後のコマ");
    assert_eq!(試験.載せた番号(1), Some(104), "手前の区間の最後のコマ");
    assert!(試験.行(0).映せない理由().is_none());
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 同じ区間を2つの行に置いても倉庫への依頼は1件であり_両方の行が溜めたコマから載せる() {
    let 同じ区間に置く = 置き方 {
        動画上の区間の開始: 1.0,
        動画上の区間の終了: 2.0,
        始まり: 0.0,
    };
    let mut 試験 = 試験の重ね合わせ::作って開く(
        "重ね合わせの同じ区間",
        メモリの上限::既定,
        &[&[同じ区間に置く], &[同じ区間に置く]],
    );
    let 同じ区間 = 区間(1.0, 2.0);
    成り立つまで待つ("区間を溜め終えること", || {
        試験.行ごとのコマを載せる(0.5);
        台帳(&試験).溜め終えたか(&同じ区間)
    });
    assert_eq!(台帳(&試験).行.len(), 1, "同じ区間の依頼は1件");
    試験.行ごとのコマを載せる(0.5);
    for 行 in [0, 1] {
        assert_eq!(
            試験.行(行).載せているコマの出どころ(),
            行に載せているコマの出どころ::溜めたコマ(同じ区間)
        );
        assert!(matches!(試験.載せた番号(行), Some(45..=46)), "1.5秒のコマ");
    }
}
