//! 載せたコマの置いたクリップ。行のテクスチャに今載っているコマがどの置いたクリップのコマかと、その置いたクリップの続く先を覚え、
//! 重ねる画面がその行をどう描くかを決める。行のテクスチャは行の中で置いたクリップが入れ替わっても作り直さないため、
//! 新しく映し始めた置いたクリップのコマが載るまでは、前の置いたクリップのコマが残っている。参照: _doc/設計/同時再生.md 2-4・5-2 の7

use clip_domain::置いたクリップの識別子;
use video_source::コマの速さ;

use super::continuation::続く先;
use super::row_request::行の表示するコマの求め;
use crate::video_feed::コマを載せたか;

/// 行の描き方とは、行が映す置いたクリップに対して、重ねる画面がその行に何を描くかの区別のことである。
/// 前の置いたクリップのコマは、行が隙間なく続けて映していた前の置いたクリップのコマであり、その置いたクリップの映す矩形とクロップで描く。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 行の描き方<'供給> {
    映す置いたクリップのコマ,
    前の置いたクリップのコマ(&'供給 置いたクリップの識別子),
    描かない,
}

/// 載せたコマの置いたクリップとは、行のテクスチャにまだどの置いたクリップのコマも載せていないか、載せたならその置いたクリップの識別子と、
/// 行がその置いたクリップを最後に映したフレームでの続く先の組の区別のことである。
#[derive(Debug, Clone, PartialEq)]
pub(super) enum 載せたコマの置いたクリップ {
    載せていない,
    載せた {
        置いたクリップ: 置いたクリップの識別子,
        続く先: 続く先<置いたクリップの識別子>,
    },
}

impl 載せたコマの置いたクリップ {
    /// 行が求めの置いたクリップを映すフレームで、コマを載せた結果を覚える。載せたコマの置いたクリップが求めの置いたクリップと同じなら、続く先だけを今に合わせる。
    /// 別の置いたクリップのコマとして覚え直すのは、求めの区間の中のコマを載せたときだけである。流し読みを開き直さずに続く継ぎ目では、
    /// 流し読みがまだ前の置いたクリップの区間のコマを出すことがあり、それを新しい置いたクリップのコマとみなさないためである。
    pub(super) fn 載せた結果を覚える(
        &mut self,
        求め: &行の表示するコマの求め<'_>,
        載せたか: コマを載せたか,
        速さ: コマの速さ,
    ) {
        if let Self::載せた {
            置いたクリップ,
            続く先,
        } = self
            && 置いたクリップ == 求め.置いたクリップ
        {
            続く先.今の続く先に合わせる(求め.続く先);
            return;
        }
        if matches!(載せたか, コマを載せたか::載せた(番号) if 求め.求め.区間の中のコマか(番号, 速さ))
        {
            *self = Self::載せた {
                置いたクリップ: 求め.置いたクリップ.clone(),
                続く先: 求め.続く先.写しを作る(),
            };
        }
    }

    /// 行が何も映さなかったことを覚える。これより後は、載っているコマを別の置いたクリップの代わりに描かない。
    pub(super) fn 何も映さなかったことを覚える(&mut self) {
        if let Self::載せた { 続く先, .. } = self {
            *続く先 = 続く先::止まる;
        }
    }

    /// 行が映す置いたクリップに対して、その行をどう描くか。映す置いたクリップのコマが載っていればそれを描く。
    /// 載っていなくても、載っている前の置いたクリップの続く先が映す置いたクリップなら、継ぎ目で行が空になってちらつかないよう、前の置いたクリップのコマを描き続ける。
    pub(super) fn 行の描き方を決める(
        &self,
        映す置いたクリップ: &置いたクリップの識別子,
    ) -> 行の描き方<'_> {
        match self {
            Self::載せた {
                置いたクリップ,
            ..
            } if 置いたクリップ == 映す置いたクリップ => {
                行の描き方::映す置いたクリップのコマ
            }
            Self::載せた {
                置いたクリップ,
                続く先,
            } if 続く先.続くか(映す置いたクリップ) => {
                行の描き方::前の置いたクリップのコマ(置いたクリップ)
            }
            Self::載せた { .. } | Self::載せていない => 行の描き方::描かない,
        }
    }
}
