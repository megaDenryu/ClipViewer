//! 行ごとの載せたコマの置いたクリップ。行のテクスチャに今載っているコマが、どの置いたクリップのコマかと、載せてから行が何も映さない時刻を挟んだかを覚え、
//! 重ねる画面がその行に何を描くかを答える。行のテクスチャは行の中で置いたクリップが入れ替わっても作り直さないため、
//! 新しく映し始めた置いたクリップのコマが載るまでは、前の置いたクリップのコマが残っている。参照: _doc/設計/同時再生.md 2-4・5-2 の7

use clip_domain::{
    同時に重ねられる行の数, 置いたクリップの識別子, 行の番号
};

/// 隙間を挟んだかとは、行のテクスチャにコマを載せてから、その行が何も映さない時刻(置いたクリップの間の隙間など)を挟んだかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 隙間を挟んだか {
    挟んでいない,
    挟んだ,
}

/// 載せたコマの置いたクリップとは、行のテクスチャにまだどの置いたクリップのコマも載せていないか、載せたならその置いたクリップの識別子と、
/// 載せてから隙間を挟んだかの区別のことである。
#[derive(Debug, Clone, PartialEq)]
enum 載せたコマの置いたクリップ {
    載せていない,
    載せた {
        置いたクリップ: 置いたクリップの識別子,
        隙間: 隙間を挟んだか,
    },
}

/// 行の描き方とは、行が映す置いたクリップに対して、重ねる画面がその行に何を描くかの区別のことである。
/// 前の置いたクリップのコマは、行が続けて映していた前の置いたクリップのコマであり、その置いたクリップの映す矩形とクロップで描く。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 行の描き方<'供給> {
    映す置いたクリップのコマ,
    前の置いたクリップのコマ(&'供給 置いたクリップの識別子),
    描かない,
}

/// 行ごとの載せたコマの置いたクリップとは、行の番号ごとの載せたコマの置いたクリップの並びのことである。
pub(super) struct 行ごとの載せたコマの置いたクリップ(
    Vec<載せたコマの置いたクリップ>,
);

impl 行ごとの載せたコマの置いたクリップ {
    /// どの行にもまだ載せていない並び。
    pub(super) fn まだ載せていない() -> Self {
        Self(vec![
            載せたコマの置いたクリップ::載せていない;
            同時に重ねられる行の数
        ])
    }

    /// 行のテクスチャに置いたクリップのコマを載せたことを覚える。
    pub(super) fn 載せたことを覚える(
        &mut self,
        行: 行の番号,
        置いたクリップ: &置いたクリップの識別子,
    ) {
        if let Some(覚えた) = self.0.get_mut(行.番号()) {
            *覚えた = 載せたコマの置いたクリップ::載せた {
                置いたクリップ: 置いたクリップ.clone(),
                隙間: 隙間を挟んだか::挟んでいない,
            };
        }
    }

    /// 行が何も映さなかったことを覚える。これより後は、載っているコマを別の置いたクリップの代わりに描かない。
    pub(super) fn 何も映さなかったことを覚える(&mut self, 行: 行の番号) {
        if let Some(載せたコマの置いたクリップ::載せた { 隙間, .. }) = self.0.get_mut(行.番号())
        {
            *隙間 = 隙間を挟んだか::挟んだ;
        }
    }

    /// 行のテクスチャに載っているコマが、その置いたクリップのコマか。
    pub(super) fn 載せた置いたクリップか(
        &self,
        行: 行の番号,
        置いたクリップ: &置いたクリップの識別子,
    ) -> bool {
        self.行の描き方を決める(行, 置いたクリップ)
            == 行の描き方::映す置いたクリップのコマ
    }

    /// 行が映す置いたクリップに対して、その行に何を描くか。映す置いたクリップのコマが載っていればそれを描く。
    /// 載っていなくても、前の置いたクリップのコマを載せてから隙間を挟まずに映す置いたクリップへ移ったなら、そのコマを描き続ける。
    /// 継ぎ目で新しい置いたクリップのコマが届くまでの間、行が空になってちらつかないためである。
    pub(super) fn 行の描き方を決める(
        &self,
        行: 行の番号,
        映す置いたクリップ: &置いたクリップの識別子,
    ) -> 行の描き方<'_> {
        match self.0.get(行.番号()) {
            Some(載せたコマの置いたクリップ::載せた {
                置いたクリップ,
            ..
            }) if 置いたクリップ == 映す置いたクリップ => {
                行の描き方::映す置いたクリップのコマ
            }
            Some(載せたコマの置いたクリップ::載せた {
                置いたクリップ,
                隙間: 隙間を挟んだか::挟んでいない,
            }) => 行の描き方::前の置いたクリップのコマ(置いたクリップ),
            _ => 行の描き方::描かない,
        }
    }
}
