//! 行ごとに載せた置いたクリップ。行のテクスチャに今載っているコマが、どの置いたクリップのコマかを覚える。
//! 行のテクスチャは行の中で置いたクリップが入れ替わっても作り直さないため、新しく映し始めた置いたクリップのコマが届くまでは、
//! 前の置いたクリップのコマが残っている。重ねる画面はこの記録を読み、映す置いたクリップのコマが載るまでその行を描かない。
//! 参照: _doc/設計/同時再生.md 2-4

use clip_domain::{
    同時に重ねられる行の数, 置いたクリップの識別子, 行の番号
};

/// 行ごとに載せた置いたクリップとは、行の番号ごとの、行のテクスチャに今載っているコマの置いたクリップの識別子(まだ載せていなければ無い)の並びのことである。
pub(super) struct 行ごとに載せた置いたクリップ(Vec<Option<置いたクリップの識別子>>);

impl 行ごとに載せた置いたクリップ {
    /// どの行にもまだ載せていない記録。
    pub(super) fn まだ載せていない() -> Self {
        Self(vec![None; 同時に重ねられる行の数])
    }

    /// 行のテクスチャに置いたクリップのコマを載せたことを覚える。同じ置いたクリップなら書き換えない。
    pub(super) fn 載せたことを覚える(
        &mut self,
        行: 行の番号,
        置いたクリップ: &置いたクリップの識別子,
    ) {
        if let Some(覚えた) = self.0.get_mut(行.番号())
            && 覚えた.as_ref() != Some(置いたクリップ)
        {
            *覚えた = Some(置いたクリップ.clone());
        }
    }

    /// 行のテクスチャに載っているコマが、その置いたクリップのコマか。
    pub(super) fn 載せた置いたクリップか(
        &self,
        行: 行の番号,
        置いたクリップ: &置いたクリップの識別子,
    ) -> bool {
        self.0
            .get(行.番号())
            .is_some_and(|覚えた| 覚えた.as_ref() == Some(置いたクリップ))
    }
}
