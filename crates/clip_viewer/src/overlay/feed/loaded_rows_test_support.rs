//! 載せたコマの置いたクリップの試験の道具。毎秒30コマの速さと、区間と続く先を持つ行の求めと、番号のコマを載せた結果を作る。
#![allow(clippy::expect_used)]

use clip_domain::{
    クロップ範囲, 動画の番号, 動画上の区間, 時刻, 置いたクリップの識別子
};
use video_source::{コマの速さ, 動画上のコマ番号};

use super::continuation::続く先;
use super::row_request::行の表示するコマの求め;
use crate::video_feed::{コマを載せたか, 表示するコマの求め};

pub(super) fn 毎秒30コマ() -> コマの速さ {
    コマの速さ::作成する(30, 1).expect("速さ")
}

/// 動画上の開始から終了までの区間を、続く先へ続けて映す置いたクリップの、開始の位置の求め。
pub(super) fn 求め<'識別子>(
    置いたクリップ: &'識別子 置いたクリップの識別子,
    開始: f64,
    終了: f64,
    続く先: 続く先<&'識別子 置いたクリップの識別子>,
) -> 行の表示するコマの求め<'識別子> {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    行の表示するコマの求め {
        置いたクリップ,
        動画: 動画の番号::番号から作成する(0),
        求め: 表示するコマの求め {
            動画上の位置: 秒(開始),
            区間: Some(動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")),
            クロップ: クロップ範囲::全体,
        },
        続く先,
    }
}

pub(super) fn 番号のコマを載せた(番号: u32) -> コマを載せたか {
    コマを載せたか::載せた(動画上のコマ番号::作成する(番号))
}
