//! 映すものを求める条件。重ね合わせの供給が行ごとに映すものを求めるときの、重ね合わせ上の時刻と全体の末尾での振る舞いの組。
//! 2つは重ね合わせの再生の状況から一緒に取り出すため、1つの値にまとめて渡す。参照: _doc/設計/同時再生.md 5-2

use clip_domain::{
    末尾での振る舞い, 行が映すもの, 重ね合わせ, 重ね合わせ上の秒
};

/// 映すものを求める条件とは、行ごとに映すものを求める重ね合わせ上の時刻と、全体の末尾での振る舞い(区間の終わりの行き先を決める)の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 映すものを求める条件 {
    pub(crate) 時刻: 重ね合わせ上の秒,
    pub(crate) 全体の末尾: 末尾での振る舞い,
}

impl 映すものを求める条件 {
    /// 重ね合わせの行ごとに映すものを、奥の行から手前の行の順に求める(第2段階の `重ね合わせ上の時刻に映すものを求める`)。
    pub(super) fn 行ごとに映すものを求める(
        self,
        重ね合わせ: &重ね合わせ,
    ) -> Vec<行が映すもの<'_>> {
        重ね合わせ
            .重ね合わせ上の時刻に映すものを求める(self.時刻, self.全体の末尾)
            .collect()
    }
}
