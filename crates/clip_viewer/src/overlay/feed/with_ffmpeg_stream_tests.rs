//! 重ね合わせの供給の流し読みの経路の結合試験。倉庫が区間を溜められない(メモリの上限が小さい)とき、行ごとの流し読みからその時刻のコマを載せることと、
//! 重ね合わせの末尾では区間の外のコマを出さずに各行の区間の中の最後のコマを流し読みで載せることを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use video_source::{バイト数, メモリの上限};

use super::row::行の映し具合;
use super::with_ffmpeg_support::試験の重ね合わせ;
use crate::video_feed::with_ffmpeg_support::成り立つまで待つ;
use crate::video_feed::コマの出どころ;

/// 1コマも収まらないメモリの上限。倉庫はどの区間も上限の全体を超えるとして受け付けない。
fn 溜められない上限() -> メモリの上限 {
    メモリの上限::作成する(バイト数::作成する(1))
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 区間を溜められないときは_行ごとの流し読みからその時刻のコマを載せる() {
    let mut 試験 =
        試験の重ね合わせ::作って開く("重ね合わせの流し読み", 溜められない上限());
    成り立つまで待つ("2つの行に流し読みのコマが載ること", || {
        試験.供給する(0.25);
        matches!(試験.載せた番号(0), Some(22..=23)) && matches!(試験.載せた番号(1), Some(67..=68))
    });
    for 行 in [0, 1] {
        assert_eq!(
            試験.行(行).映し具合(),
            行の映し具合::映している(コマの出どころ::流し読み)
        );
        assert!(試験.行(行).映せない理由().is_none());
    }
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 重ね合わせの末尾では_流し読みでも各行の区間の中の最後のコマを載せる() {
    let mut 試験 =
        試験の重ね合わせ::作って開く("重ね合わせの流し読みの末尾", 溜められない上限());
    成り立つまで待つ(
        "2つの行に区間の最後のコマが載ること",
        || {
            試験.供給する(1.5);
            試験.載せた番号(0).is_some()
                && 試験.載せた番号(1).is_some()
                && !試験.行(0).流し読みのコマを待っているか()
                && !試験.行(1).流し読みのコマを待っているか()
        },
    );
    assert_eq!(
        試験.載せた番号(0),
        Some(44),
        "区間の外の45番(1.5秒から表示するコマ)を出さない"
    );
    assert_eq!(
        試験.載せた番号(1),
        Some(104),
        "区間の外の105番(3.5秒から表示するコマ)を出さない"
    );
}
