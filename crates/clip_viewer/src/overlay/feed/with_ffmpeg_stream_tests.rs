//! 重ね合わせの供給の流し読みの経路の結合試験。倉庫が区間を溜められない(メモリの上限が小さい)とき、行ごとの流し読みからその時刻のコマを載せることと、
//! 何も映さない行の流し読みを閉じることと、重ね合わせの末尾では区間の外のコマを出さずに各行の区間の中の最後のコマを流し読みで載せることを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use video_source::{バイト数, メモリの上限};

use super::with_ffmpeg_support::{二つの行の置き方, 試験の重ね合わせ};
use crate::video_feed::with_ffmpeg_support::成り立つまで待つ;
use crate::video_feed::載せているコマの出どころ;

/// 1コマも収まらないメモリの上限。倉庫はどの区間も上限の全体を超えるとして受け付けない。
fn 溜められない上限() -> メモリの上限 {
    メモリの上限::作成する(バイト数::作成する(1))
}

const 載せ終えた流し読み: 載せているコマの出どころ =
    載せているコマの出どころ::流し読み {
        コマを待っている: false,
    };

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 区間を溜められないときは_行ごとの流し読みからその時刻のコマを載せ_何も映さない行は流し読みを閉じる()
 {
    let mut 試験 = 試験の重ね合わせ::作って開く(
        "重ね合わせの流し読み",
        溜められない上限(),
        二つの行の置き方,
    );
    成り立つまで待つ("2つの行に流し読みのコマが載ること", || {
        試験.行ごとのコマを載せる(0.25);
        matches!(試験.載せた番号(0), Some(22..=23)) && matches!(試験.載せた番号(1), Some(67..=68))
    });
    for 行 in [0, 1] {
        assert_eq!(試験.行(行).載せているコマの出どころ(), 載せ終えた流し読み);
        assert!(試験.行(行).流し読みを開いているか());
        assert!(試験.行(行).映せない理由().is_none());
    }
    試験.行ごとのコマを載せる(1.2);
    assert_eq!(
        試験.行(0).載せているコマの出どころ(),
        載せているコマの出どころ::載せていない
    );
    assert!(
        !試験.行(0).流し読みを開いているか(),
        "置いたクリップの終わった行は流し読みを閉じる"
    );
    assert!(
        matches!(試験.載せた番号(0), Some(22..=23)),
        "テクスチャは前のコマのまま"
    );
    assert!(試験.行(1).流し読みを開いているか());
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 重ね合わせの末尾では_流し読みでも各行の区間の中の最後のコマを載せる() {
    let mut 試験 = 試験の重ね合わせ::作って開く(
        "重ね合わせの流し読みの末尾",
        溜められない上限(),
        二つの行の置き方,
    );
    成り立つまで待つ(
        "2つの行に区間の最後のコマが載ること",
        || {
            試験.行ごとのコマを載せる(1.5);
            試験.載せた番号(0).is_some()
                && 試験.載せた番号(1).is_some()
                && 試験.行(0).載せているコマの出どころ() == 載せ終えた流し読み
                && 試験.行(1).載せているコマの出どころ() == 載せ終えた流し読み
        },
    );
    assert_eq!(
        試験.載せた番号(0),
        Some(44),
        "区間の外の45番(1.5秒から表示するコマ)を出さない"
    );
    assert_eq!(
        試験.載せた番号(1),
        Some(104),
        "区間の外の105番(3.5秒から表示するコマ)を出さない"
    );
}
