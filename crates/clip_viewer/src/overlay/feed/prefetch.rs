//! 重ね合わせの先読みの並び。使う動画の表の動画ごとに、倉庫へ溜める依頼を出す順であり、同じ順を保持の優先順として倉庫へ渡す。
//! 映している区間から溜めるため、今映している置いたクリップを先にする。参照: _doc/設計/同時再生.md 5-2・5-4

use std::cmp::Ordering;

use clip_domain::{
    動画の番号, 動画上の区間, 置いたクリップ, 行が映すもの, 行の映し方, 重ね合わせ,
    重ね合わせ上の秒,
};

/// 重ね合わせの先読みの並びとは、使う動画の表の動画ごとに、置いたクリップの区間を「今映している置いたクリップ(奥の行から)
/// → 時刻より後に始まる置いたクリップ(始まりの時刻の順) → 残り(始まりの時刻の順)」の順に並べ、同じ区間を1つにまとめたもののことである。
/// 先頭ほど倉庫に残したい。添字は動画の番号である。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 重ね合わせの先読みの並び(Vec<Vec<動画上の区間>>);

impl 重ね合わせの先読みの並び {
    /// 重ね合わせと、時刻と、その時刻に行ごとに映すものから求める。
    pub(crate) fn 求める(
        重ね合わせ: &重ね合わせ,
        時刻: 重ね合わせ上の秒,
        映すもの: &[行が映すもの<'_>],
    ) -> Self {
        let 映している = 映すもの.iter().filter_map(|行| match 行.映し方 {
            行の映し方::置いたクリップを映す(中身) => Some(中身.置いたクリップ),
            行の映し方::末尾で最後のコマを映す {
                置いたクリップ,
            ..
            } => Some(置いたクリップ),
            行の映し方::何も映さない => None,
        });
        let mut 全部: Vec<&置いたクリップ> = 重ね合わせ
            .行の並び()
            .奥から手前の順の行()
            .iter()
            .flat_map(|行| 行.置いたクリップの並び())
            .collect();
        全部.sort_by(|左, 右| {
            左.始まりの時刻()
                .partial_cmp(&右.始まりの時刻())
                .unwrap_or(Ordering::Equal)
        });
        let (後に始まる, 残り): (Vec<_>, Vec<_>) = 全部
            .into_iter()
            .partition(|置いたクリップ| 置いたクリップ.始まりの時刻() > 時刻);
        let mut 並び = Self(vec![
            Vec::new();
            重ね合わせ.動画の表().動画の数()
        ]);
        for 置いたクリップ in 映している.chain(後に始まる).chain(残り) {
            並び.区間を足す(置いたクリップ);
        }
        並び
    }

    /// 動画の番号の動画の区間の列。表に無い番号なら空である。
    pub(crate) fn 区間の列(&self, 番号: 動画の番号) -> &[動画上の区間] {
        self.0.get(番号.番号()).map_or(&[], Vec::as_slice)
    }

    fn 区間を足す(&mut self, 置いたクリップ: &置いたクリップ) {
        let 区間 = 置いたクリップ.受け継いだ値().区間;
        if let Some(列) = self.0.get_mut(置いたクリップ.動画の番号().番号())
            && !列.contains(&区間)
        {
            列.push(区間);
        }
    }
}
