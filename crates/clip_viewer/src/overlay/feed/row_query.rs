//! 行の映像の供給への問い合わせ。重ね合わせの画面が、行のテクスチャを描くときと、行ごとの映像の様子を出すときと、描き直しを予約するときに読む口。

use super::row::{行の映し具合, 行の映像の供給, 行の流し読み};
use super::row_texture::行のテクスチャ;
use crate::video_feed::コマの出どころ;

#[cfg_attr(
    not(test),
    expect(
        dead_code,
        reason = "第8段階で重ねる画面に行を描くときに読む。それまでは試験からだけ読む(同時再生.md 6節)"
    )
)]
impl 行の映像の供給 {
    pub(crate) fn テクスチャ(&self) -> &行のテクスチャ {
        &self.テクスチャ
    }

    pub(crate) fn 映し具合(&self) -> 行の映し具合 {
        self.映し具合
    }

    /// 流し読みで、求めた位置のコマがまだ届いていないか。画面は、この間は入力が無くても描き直す。
    pub(crate) fn 流し読みのコマを待っているか(&self) -> bool {
        matches!(
            self.映し具合,
            行の映し具合::映している(コマの出どころ::流し読み)
        ) && self.流し読みのコマを待っている
    }

    /// 行の流し読みが読めない理由、またはテクスチャへ載せられなかった理由。
    pub(crate) fn 映せない理由(&self) -> Option<&str> {
        let 流し読みの理由 = match self.映し具合 {
            行の映し具合::映している(コマの出どころ::流し読み) => {
                self.流し読み.as_ref().and_then(行の流し読み::読めない理由)
            }
            行の映し具合::映している(コマの出どころ::溜めたコマ(_))
            | 行の映し具合::映していない => None,
        };
        流し読みの理由.or(self.載せられない理由.as_deref())
    }
}
