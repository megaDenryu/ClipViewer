//! 行の映像の供給への問い合わせ。重ね合わせの画面が、行のテクスチャを描くとき(同時再生.md 5-2 の7)と、行ごとに「溜めたコマ / 流し読み」を
//! 出すとき(5-4 の方針(4))に読む口。映せない理由は、テクスチャへ載せられなかったことを黙って捨てないために読む口を置く。

use super::row::{行の映像の供給, 行の流し読み};
use super::row_showing::行の映し具合;
use super::row_texture::行のテクスチャ;

#[cfg_attr(
    not(test),
    expect(
        dead_code,
        reason = "第8段階で重ねる画面に行を描くときと、行ごとの映像の様子を出すときに読む。それまでは試験からだけ読む(同時再生.md 6節)"
    )
)]
impl 行の映像の供給 {
    pub(crate) fn テクスチャ(&self) -> &行のテクスチャ {
        &self.テクスチャ
    }

    pub(crate) fn 映し具合(&self) -> 行の映し具合 {
        self.映し具合
    }

    /// 行の流し読みが読めない理由、またはテクスチャへ載せられなかった理由。
    pub(crate) fn 映せない理由(&self) -> Option<&str> {
        let 流し読みの理由 = match self.映し具合 {
            行の映し具合::流し読みで映している { .. } => {
                self.流し読み.as_ref().and_then(行の流し読み::読めない理由)
            }
            行の映し具合::溜めたコマを映している(_) | 行の映し具合::映していない => {
                None
            }
        };
        流し読みの理由.or(self.載せられない理由.as_deref())
    }
}
