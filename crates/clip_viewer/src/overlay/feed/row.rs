//! 行の映像の供給。タイムラインの行ごとに1つ持ち、その行が映すコマを、区間を溜め終えていれば倉庫から、そうでなければ行の流し読みから取り出して
//! 行のテクスチャへ載せる。1つの行は同時に高々1つの置いたクリップを映すため、流し読みとテクスチャは行に1つずつで足りる。参照: _doc/設計/同時再生.md 5-1・5-2

use std::time::Instant;

use clip_domain::{動画上の区間, 動画上の秒};
use eframe::egui;
use sengen_egui::画素の並びの不正;
use video_source::流し読み;

use super::row_showing::行に載せているコマの出どころ;
use super::row_texture::行のテクスチャ;
use super::video::動画ごとの倉庫と台帳;
use crate::stream_rules::開き直しを判断できる流し読み;
use crate::video_feed::表示するコマの求め;

/// 行の流し読みとは、タイムラインの行が溜めたコマで映せない間に開く、開き直しを判断できる映像の流し読みのことである。
pub(super) type 行の流し読み = 開き直しを判断できる流し読み<流し読み>;

/// 行の映像の供給とは、1つのタイムラインの行の、流し読み(溜めたコマで映せない間だけ開く)と、行のテクスチャと、載せているコマの出どころと、
/// テクスチャへ載せられなかった理由の組のことである。
pub(crate) struct 行の映像の供給 {
    pub(super) 流し読み: Option<行の流し読み>,
    pub(super) テクスチャ: 行のテクスチャ,
    pub(super) 載せているコマの出どころ: 行に載せているコマの出どころ,
    pub(super) 載せられない理由: Option<String>,
}

impl 行の映像の供給 {
    pub(super) fn 登録して作る(
        画面描画の共有状態: &egui::Context,
    ) -> Result<Self, 画素の並びの不正> {
        Ok(Self {
            流し読み: None,
            テクスチャ: 行のテクスチャ::登録して作る(画面描画の共有状態)?,
            載せているコマの出どころ:
                行に載せているコマの出どころ::載せていない,
            載せられない理由: None,
        })
    }

    /// 行が何も映さない(置いたクリップの間の隙間など)間と、作業場を控えるときは、流し読みを閉じて ffmpeg を止める。
    /// テクスチャは作り直さないため、前に載せたコマが残る。
    pub(super) fn 映すのをやめる(&mut self) {
        self.流し読み = None;
        self.載せているコマの出どころ =
            行に載せているコマの出どころ::載せていない;
    }

    /// 表示するコマを、区間を溜め終えていれば倉庫から、そうでなければ行の流し読みから取り出してテクスチャへ載せる。
    pub(super) fn コマを載せる(
        &mut self,
        動画: &mut 動画ごとの倉庫と台帳,
        求め: &表示するコマの求め,
        今: Instant,
    ) {
        match 求め.区間 {
            Some(区間) if 動画.台帳().溜め終えたか(&区間) => {
                self.流し読み = None;
                self.載せているコマの出どころ =
                    行に載せているコマの出どころ::溜めたコマ(区間);
                self.溜めたコマを載せる(動画, &区間, 求め.動画上の位置);
            }
            _ => self.流し読みのコマを載せる(動画, 求め, 今),
        }
    }

    /// 流し読みを開いているか。結合試験で、何も映さない行と控えた行の流し読みを閉じたことを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 流し読みを開いているか(&self) -> bool {
        self.流し読み.is_some()
    }

    fn 溜めたコマを載せる(
        &mut self,
        動画: &mut 動画ごとの倉庫と台帳,
        区間: &動画上の区間,
        位置: 動画上の秒,
    ) {
        let Some(コマ) = 動画.溜めたコマを取り出す(区間, 位置) else {
            return;
        };
        let 結果 = self.テクスチャ.コマを載せる(コマ.番号(), コマ.コマ());
        self.載せられない理由 = 結果.err().map(|不正| 不正.to_string());
    }
}
