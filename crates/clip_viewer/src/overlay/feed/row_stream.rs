//! 行の流し読みからの供給。行が溜めたコマで映せない間、行の流し読みを必要なときだけ開き直して、その時刻に出すコマを行のテクスチャへ載せる。
//! 開き直しの規則(開き直すかの判断・最短の間隔・控える間)は `stream_rules` を行ごとに当て、8行が同時に ffmpeg を起動し直し続けないようにする。
//! 参照: _doc/設計/同時再生.md 5-4、_doc/設計/画面.md 判断5

use std::time::Instant;

use clip_domain::動画上の秒;
use video_source::{動画の情報, 流し読みの状態};

use super::row::行の映像の供給;
use super::video::重ね合わせの動画の供給;
use crate::stream_rules::{流し読みの開き直し, 開き直しの最短の間隔};
use crate::video_feed::表示するコマの求め;

impl 行の映像の供給 {
    /// 流し読みのコマを載せる。開き直しを控える間は、位置を覚えずに今のコマのままにする(控えを解いた次のフレームで開き直すため)。
    /// 求める位置のコマがまだ届いていない間は、流し読みのコマを待っているとして覚える。
    pub(super) fn 流し読みのコマを載せる(
        &mut self,
        動画: &重ね合わせの動画の供給,
        求め: &表示するコマの求め,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        let 位置 = 求め.流し読みで求める位置(動画.情報().コマの速さ());
        self.流し読みのコマを待っている = false;
        let 開き直すか = self
            .流し読み
            .as_ref()
            .is_none_or(|流し読み| 流し読み.この位置で開き直すか(位置));
        if 開き直すか {
            let 間隔を守ったか = self.流し読み.as_ref().is_none_or(|流し読み| {
                流し読み.開いてからの経過(今) >= 開き直しの最短の間隔
            });
            if 開き直し == 流し読みの開き直し::控える || !間隔を守ったか {
                self.流し読みのコマを待っている =
                    開き直し == 流し読みの開き直し::してよい;
                return;
            }
            self.流し読み = Some(動画.流し読みを開く(位置, 今));
        }
        self.求めた位置のコマを載せる(動画.情報(), 位置);
    }

    fn 求めた位置のコマを載せる(
        &mut self, 情報: &動画の情報, 位置: 動画上の秒
    ) {
        let 目当ての番号 = 情報.コマの速さ().時刻を含むコマ番号(位置);
        let Some(流し読み) = self.流し読み.as_mut().and_then(|開いた| {
            開いた.求めた位置を覚え途中の失敗を写して中身を貸す(位置)
        }) else {
            return;
        };
        let 載せた番号 = match 流し読み.その時刻に出すコマ(位置) {
            Some(コマ) => {
                let 結果 = self.テクスチャ.コマを載せる(コマ.番号(), コマ.コマ());
                self.載せられない理由 = 結果.err().map(|不正| 不正.to_string());
                Some(コマ.番号())
            }
            None => None,
        };
        let 読んでいる = matches!(流し読み.状態(), 流し読みの状態::読んでいる);
        self.流し読みのコマを待っている =
            読んでいる && 載せた番号.is_none_or(|番号| 番号 < 目当ての番号);
    }
}
