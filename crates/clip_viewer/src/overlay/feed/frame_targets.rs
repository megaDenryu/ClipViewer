//! このフレームで映すもの。重ね合わせ上の時刻に行ごとに映すもの(第2段階の `重ね合わせ上の時刻に映すものを求める`)と、それから求めた動画ごとの先読みの並びを、
//! 1フレームに1回だけ求めて、映像の供給・音の供給・行ごとの再生の指示の組み立てが共に読む。参照: _doc/設計/同時再生.md 5-2・5-3

use clip_domain::{行が映すもの, 重ね合わせ};

use super::prefetch::重ね合わせの先読みの並び;
use super::show_condition::映すものを求める条件;

/// このフレームで映すものとは、重ね合わせの行ごとに映すもの(奥の行から手前の行の順)と、動画ごとの先読みの並びの組のことである。
pub(crate) struct このフレームで映すもの<'重ね合わせ> {
    pub(crate) 行ごと: Vec<行が映すもの<'重ね合わせ>>,
    pub(crate) 先読みの並び: 重ね合わせの先読みの並び,
}

impl<'重ね合わせ> このフレームで映すもの<'重ね合わせ> {
    /// 条件の時刻に行ごとに映すものを求め、それから動画ごとの先読みの並びを求める。
    pub(crate) fn 求める(
        重ね合わせ: &'重ね合わせ 重ね合わせ,
        条件: 映すものを求める条件,
    ) -> Self {
        let 行ごと = 条件.行ごとに映すものを求める(重ね合わせ);
        let 先読みの並び =
            重ね合わせの先読みの並び::求める(重ね合わせ, 条件.時刻, &行ごと);
        Self {
            行ごと,
            先読みの並び,
        }
    }
}
