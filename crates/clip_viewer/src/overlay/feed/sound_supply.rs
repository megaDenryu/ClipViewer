//! 重ね合わせの音の供給。使う動画の表の動画ごとの重ね合わせの動画の音と、タイムラインの行ごとの開き直しをまたぐ音の流し読みを持ち、毎フレーム、
//! その時刻に行ごとに映すものから、動画ごとに音の先読みの並びを倉庫へ渡し、行ごとに音の流し読みを整える。
//! 動画ごとと行ごとの型と、溜めた音か流し読みかを選ぶ規則は、スタックの作業場の音の供給(`audio_feed`)と共有する。参照: _doc/設計/同時再生.md 5-1・5-3

use std::time::Instant;

use audio_pcm::サンプリング周波数;
use clip_domain::{動画の番号, 同時に重ねられる行の数, 行の番号};
use video_source::動画の読み手;

use super::frame_targets::このフレームで映すもの;
use super::row_request::行の表示するコマの求め;
use super::sound_video::重ね合わせの動画の音;
use super::status::重ね合わせの映像の供給を作れたか;
use crate::audio_feed::開き直しをまたぐ音の流し読み;
use crate::stream_rules::流し読みの開き直し;

/// 重ね合わせの音の供給とは、2本目の流れの周波数(使えなければ無い)と、使う動画の表の動画ごとの重ね合わせの動画の音(添字は動画の番号)と、
/// 同時に重ねられる行の数だけの開き直しをまたぐ音の流し読み(添字は行の番号)の組のことである。
pub(crate) struct 重ね合わせの音の供給 {
    pub(super) 周波数: Option<サンプリング周波数>,
    pub(super) 動画: Vec<重ね合わせの動画の音>,
    pub(super) 行ごとの流し読み: Vec<開き直しをまたぐ音の流し読み>,
}

impl 重ね合わせの音の供給 {
    /// 映像の供給が開けた動画ごとに、同じ動画の情報と借りた読み手で、2本目の流れの周波数の音の倉庫を開く。
    /// 周波数が無い(2本目の流れを開けない)ときは、どの動画も鳴らせない。
    pub(crate) fn 開く(
        読み手: Option<&動画の読み手>,
        映像: &重ね合わせの映像の供給を作れたか,
        動画の数: usize,
        周波数: Option<サンプリング周波数>,
    ) -> Self {
        let 動画 = (0..動画の数)
            .map(|添字| {
                let 情報 = 映像.開いた動画の情報(動画の番号::番号から作成する(添字));
                重ね合わせの動画の音::開く(読み手, 情報, 周波数)
            })
            .collect();
        Self {
            周波数,
            動画,
            行ごとの流し読み: (0..同時に重ねられる行の数)
                .map(|_| 開き直しをまたぐ音の流し読み::default())
                .collect(),
        }
    }

    /// このフレームで映すものから、動画ごとに音の先読みの並びを(映像の先読みが落ち着いていれば)倉庫へ渡し、
    /// 行ごとに映している置いたクリップの音の流し読みを整える。何も映さない行は音の流し読みを閉じる。
    /// 開き直しは、映像と同じく、時間の軸で再生の位置をドラッグしている間は控え、それ以外はしてよい(画面.md 判断5。呼び手が決めて渡す)。
    pub(crate) fn 行ごとの溜める並びと流し読みを整える(
        &mut self,
        映すもの: &このフレームで映すもの<'_>,
        映像: &重ね合わせの映像の供給を作れたか,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        for (添字, 動画) in self.動画.iter_mut().enumerate() {
            let 番号 = 動画の番号::番号から作成する(添字);
            if let Some(供給元) = 動画.供給元を書き換える() {
                供給元.溜める並びを整える(
                    映すもの.先読みの並び.区間の列(番号),
                    映像.先読みが落ち着いたか(番号),
                );
            }
        }
        for (添字, 流し読み) in self.行ごとの流し読み.iter_mut().enumerate() {
            let 求めと供給元 =
                行の表示するコマの求め::行ごとに映すものから作る(
                    &映すもの.行ごと,
                    行の番号::番号から作成する(添字),
                )
                .and_then(|行の求め| {
                    let 供給元 = self.動画.get(行の求め.動画.番号())?.供給元()?;
                    Some((行の求め.求め, 供給元))
                });
            match 求めと供給元 {
                Some((求め, 供給元)) => {
                    流し読み.整える(供給元, 求め.動画上の位置, 求め.区間.as_ref(), 開き直し, 今)
                }
                None => 流し読み.閉じる(),
            }
        }
    }

    /// 2本目の流れが途中で使えなくなったときに呼ぶ。周波数を無くし、行ごとの音の流し読みを閉じ、動画ごとの音の倉庫を捨てて読み込みを止める。
    /// 音が出ないのに ffmpeg と音の倉庫の裏のスレッドが CPU を使い続けないためである。
    pub(crate) fn 出力が使えないため止める(&mut self) {
        self.周波数 = None;
        self.流し読みを閉じる();
        for 動画 in &mut self.動画 {
            動画.出力が使えないため倉庫を捨てる();
        }
    }

    /// 全部の行の音の流し読みを閉じる。作業場を控えるときに呼び、ffmpeg を止める。
    pub(crate) fn 流し読みを閉じる(&mut self) {
        for 流し読み in &mut self.行ごとの流し読み {
            流し読み.閉じる();
        }
    }
}
