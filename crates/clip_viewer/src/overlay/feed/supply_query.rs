//! 重ね合わせの映像の供給への問い合わせ。重ね合わせの状態が開けなかった動画を知らせへ出すときと、重ねる画面が行のテクスチャを描くとき(同時再生.md 5-2 の7)と、
//! 重ね合わせの音の供給が映像と同じ動画の情報で音を開き先読みの落ち着きを読むときと、結合試験が動画ごとの台帳と開けない理由を確かめるときに読む口。

use clip_domain::{動画の番号, 置いたクリップの識別子, 行の番号};
use video_source::動画の情報;

use super::supply::重ね合わせの映像の供給;
use super::video_status::重ね合わせの動画を開けたか;
use crate::video_feed::{コマの載せ先, 動画のコマの供給元};

impl 重ね合わせの映像の供給 {
    /// 開けなかった動画ごとの理由の文(使う動画の表の順)。
    pub(super) fn 開けなかった動画の理由の文(&self) -> Vec<String> {
        self.動画
            .iter()
            .filter_map(重ね合わせの動画を開けたか::開けない理由)
            .map(ToString::to_string)
            .collect()
    }

    /// 行の番号の行のコマの載せ先。同時に重ねられる行の数より後ろの番号なら無い。重ねる画面が行のテクスチャを描くときに読む。
    pub(crate) fn 行のコマの載せ先(
        &self, 番号: 行の番号
    ) -> Option<&コマの載せ先> {
        self.行ごとのコマの載せ先.get(番号.番号())
    }

    /// 行のテクスチャに今載っているコマが、その置いたクリップのコマか。新しく映し始めた置いたクリップのコマが届くまでは、前の置いたクリップのコマなので違う。
    pub(crate) fn 行に置いたクリップのコマが載っているか(
        &self,
        番号: 行の番号,
        置いたクリップ: &置いたクリップの識別子,
    ) -> bool {
        self.載せた置いたクリップ
            .載せた置いたクリップか(番号, 置いたクリップ)
    }

    /// 動画の番号の動画を開けていれば、その動画の情報。重ね合わせの音の供給が、同じ情報で音の倉庫を開くために読む(ffprobe を2回起動しない)。
    pub(super) fn 開いた動画の情報(
        &self, 番号: 動画の番号
    ) -> Option<&動画の情報> {
        self.動画
            .get(番号.番号())?
            .開いた供給元を読む()
            .map(動画のコマの供給元::情報)
    }

    /// 動画の番号の動画の映像の先読みが落ち着いたか(溜める依頼を出すのを待っていないか)。開けていない動画は落ち着いたとみなす。
    /// 音の倉庫へ並びを渡す時期を映像の依頼の台帳に揃え、区間を続けて変えている間に ffmpeg の起動と停止を繰り返さないために読む。
    pub(super) fn 先読みが落ち着いたか(&self, 番号: 動画の番号) -> bool {
        self.動画
            .get(番号.番号())
            .and_then(重ね合わせの動画を開けたか::開いた供給元を読む)
            .is_none_or(|供給元| !供給元.台帳().依頼を出すのを待っているか())
    }

    /// 入力が無くても描き直しを続ける必要があるか。どれかの動画の倉庫が区間を溜めている途中か、溜める依頼を出すのを待っている間と、
    /// どれかの行が流し読みのコマを待っている間は進め続ける。依頼を出すことと届いたコマを載せることは、毎フレームの手順で行うためである。
    pub(crate) fn 描き直しを続ける必要があるか(&self) -> bool {
        let 倉庫の仕事が残っているか = self.動画.iter().any(|開けたか| {
            開けたか.開いた供給元を読む().is_some_and(|供給元| {
                供給元.台帳().溜めている途中か() || 供給元.台帳().依頼を出すのを待っているか()
            })
        });
        倉庫の仕事が残っているか
            || self
                .行ごとのコマの載せ先
                .iter()
                .any(コマの載せ先::コマを待っているか)
    }

    /// 動画の番号の動画を開けたか。結合試験で、台帳と開けない理由を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 動画を開けたか(
        &self,
        番号: clip_domain::動画の番号,
    ) -> Option<&重ね合わせの動画を開けたか> {
        self.動画.get(番号.番号())
    }
}
