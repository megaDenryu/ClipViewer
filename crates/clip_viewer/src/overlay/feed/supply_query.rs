//! 重ね合わせの映像の供給への問い合わせ。重ね合わせの状態が開けなかった動画を知らせへ出すときと、重ねる画面が行のテクスチャを描くとき(同時再生.md 5-2 の7)と、
//! 結合試験が動画ごとの台帳と開けない理由を確かめるときに読む口。

use clip_domain::{動画の番号, 画素の寸法, 行の番号};

use super::supply::重ね合わせの映像の供給;
use super::video_status::重ね合わせの動画を開けたか;
use crate::video_feed::コマの載せ先;

impl 重ね合わせの映像の供給 {
    /// 開けなかった動画ごとの理由の文(使う動画の表の順)。
    pub(super) fn 開けなかった動画の理由の文(&self) -> Vec<String> {
        self.動画
            .iter()
            .filter_map(重ね合わせの動画を開けたか::開けない理由)
            .map(ToString::to_string)
            .collect()
    }

    /// 行の番号の行のコマの載せ先。同時に重ねられる行の数より後ろの番号なら無い。重ねる画面が行のテクスチャを描くときに読む。
    pub(crate) fn 行のコマの載せ先(
        &self, 番号: 行の番号
    ) -> Option<&コマの載せ先> {
        self.行ごとのコマの載せ先.get(番号.番号())
    }

    /// 動画の番号の動画の元の画素の寸法。開けなかった動画と、表に無い番号なら無い。置き方の編集が絵の縦横比を保つときに読む。
    pub(super) fn 動画の元の寸法(&self, 番号: 動画の番号) -> Option<画素の寸法> {
        self.動画
            .get(番号.番号())?
            .開いた供給元を読む()?
            .情報()
            .元の寸法()
            .画素の寸法へ変換する()
            .ok()
    }

    /// 入力が無くても描き直しを続ける必要があるか。どれかの動画の倉庫が区間を溜めている途中か、溜める依頼を出すのを待っている間と、
    /// どれかの行が流し読みのコマを待っている間は進め続ける。依頼を出すことと届いたコマを載せることは、毎フレームの手順で行うためである。
    pub(crate) fn 描き直しを続ける必要があるか(&self) -> bool {
        let 倉庫の仕事が残っているか = self.動画.iter().any(|開けたか| {
            開けたか.開いた供給元を読む().is_some_and(|供給元| {
                供給元.台帳().溜めている途中か() || 供給元.台帳().依頼を出すのを待っているか()
            })
        });
        倉庫の仕事が残っているか
            || self
                .行ごとのコマの載せ先
                .iter()
                .any(コマの載せ先::コマを待っているか)
    }

    /// 動画の番号の動画を開けたか。結合試験で、台帳と開けない理由を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 動画を開けたか(
        &self,
        番号: clip_domain::動画の番号,
    ) -> Option<&重ね合わせの動画を開けたか> {
        self.動画.get(番号.番号())
    }
}
