//! 今のスタックのクリップを置くこと。サイドバーの「置く」が発した応答を、配線が今のスタックの値と一緒に渡し、作業場が持つ識別子の発行元で置く。
//! 参照: _doc/設計/同時再生.md 2-4

use clip_domain::クリップ識別子;

use super::重ね合わせの作業場;
use crate::overlay::state::今のスタックの値;

impl 重ね合わせの作業場 {
    /// 今のスタックのクリップの写しを、開いている重ね合わせの今の再生の位置に置いて選ぶ。置けないときは理由を知らせる。
    /// 置いたクリップは次のフレームの画面に出るため、最後に描き直しを頼む(止まっている間は予約が無く、頼まないとマウスを動かすまで出ない)。
    pub(crate) fn 今のスタックのクリップを置く(
        &mut self,
        クリップ: &クリップ識別子,
        今のスタック: 今のスタックの値<'_>,
    ) {
        self.状態.今のスタックのクリップを置く(
            クリップ,
            今のスタック,
            &mut self.発行元,
        );
        self.画面描画の共有状態.request_repaint();
    }
}
