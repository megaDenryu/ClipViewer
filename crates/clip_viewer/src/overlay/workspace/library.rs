//! 重ね合わせのライブラリの操作を当てる。一覧とダイアログの操作は状態へ当て、開いている重ね合わせとの関係を終えうるもの(登録してから続ける・一覧から開く・重ね合わせを閉じる・
//! 確かめるダイアログで続けると決める)は、確かめてから続ける操作を行う(`library_continue.rs`)。
//! 続ける操作のうち、並べ直すことは今のスタックの値を、開くことは動画の読み手を、配線がスタックの作業場から借りて渡す。参照: _doc/設計/同時再生.md 2-2・2-7

use video_source::動画の読み手;

use super::重ね合わせの作業場;
use crate::library_common::save::登録の後にすること;
use crate::overlay::command::重ね合わせのライブラリの操作;
use crate::overlay::state::library::重ね合わせとの関係を終える操作;
use crate::overlay::state::今のスタックの値;

/// 今のスタックの値と動画の読み手とは、続ける操作が使う、スタックの作業場の今のスタックの値と、動画の開き手が持つ動画の読み手(FFmpeg が見つかっていなければ無い)の組のことである。
/// 配線が操作を当てるたびに借りて渡す(FFmpeg の置き場所を設定し直すと読み手が変わるため、作業場に持たせない)。
#[derive(Clone, Copy)]
pub(crate) struct 今のスタックの値と動画の読み手<'状態> {
    pub(crate) 今のスタック: 今のスタックの値<'状態>,
    pub(crate) 読み手: Option<&'状態 動画の読み手>,
}

impl 重ね合わせの作業場 {
    /// 重ね合わせのライブラリの操作を当てる。当てた後のフレームは予約が無いことがあるため、最後に描き直しを頼む。
    pub(crate) fn ライブラリの操作を当てる(
        &mut self,
        操作: 重ね合わせのライブラリの操作,
        借りるもの: 今のスタックの値と動画の読み手<'_>,
    ) {
        match 操作 {
            重ね合わせのライブラリの操作::一覧とダイアログ(操作) => {
                self.状態.一覧とダイアログの操作を当てる(操作)
            }
            重ね合わせのライブラリの操作::登録する => {
                let 識別子 = self.発行元.新しい重ね合わせの識別子を発行する();
                if let Some(続ける操作) = self.状態.ダイアログの名前で登録する(識別子)
                {
                    self.確かめてから続ける(続ける操作, 借りるもの);
                }
            }
            重ね合わせのライブラリの操作::開く(識別子) => self
                .確かめてから続ける(
                    重ね合わせとの関係を終える操作::一覧から開く(識別子),
                    借りるもの,
                ),
            重ね合わせのライブラリの操作::重ね合わせを閉じる => self
                .確かめてから続ける(
                    重ね合わせとの関係を終える操作::重ね合わせを閉じる,
                    借りるもの,
                ),
            重ね合わせのライブラリの操作::変更を捨てて続ける => {
                if let Some(続ける操作) = self.状態.ライブラリ.続ける操作を取り出す()
                {
                    self.続ける操作を行う(続ける操作, 借りるもの);
                }
            }
            重ね合わせのライブラリの操作::登録してから続ける => {
                if let Some(続ける操作) = self.状態.ライブラリ.続ける操作を取り出す()
                {
                    self.状態.登録の後にすることと登録のダイアログを開く(
                        登録の後にすること::続ける(続ける操作),
                    );
                }
            }
        }
        self.画面描画の共有状態.request_repaint();
    }
}
