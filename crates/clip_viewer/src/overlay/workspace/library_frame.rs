//! 重ね合わせのライブラリの毎フレームの手順と、アプリを閉じるときの手順。書き込みを進めること(自動保存と知らせの受け取り)と、一覧のサムネイルを進めることと、
//! ウインドウを閉じる要求の確かめと、アプリを落とす前に書けていない重ね合わせの保存を頼むことを、配線(`app/`)へ公開する。
//! 参照: _doc/設計/同時再生.md 2-7・3-2、_doc/設計/ライブラリ.md 判断5

use std::time::{Duration, Instant};

use video_source::動画の読み手;

use super::重ね合わせの作業場;
use crate::library_common::{アプリを閉じてよいとの決め, 確かめた結果};

impl 重ね合わせの作業場 {
    /// 毎フレーム呼ぶ(作業場を控えている間も)。届いた知らせを当て、登録済みの重ね合わせが落ち着いたか、頼み直すときなら保存を頼み、
    /// 一覧のサムネイルの結果を受け取り、一覧を見せていれば仕事を進めさせる。撮る動画の読み手は、配線がスタックの作業場から借りる。
    pub(crate) fn ライブラリとサムネイルを進める(
        &mut self,
        今: Instant,
        読み手: Option<&動画の読み手>,
    ) {
        self.状態.ライブラリの書き込みを進める(今);
        self.状態.ライブラリ.サムネイルの結果を受け取る();
        self.状態.サムネイルの仕事を進める(読み手);
    }

    /// 控えている間、毎フレーム呼ぶ。届いた知らせを当てて頼み直しを進め、サムネイルの結果を受け取る。一覧は見えないため、サムネイルの仕事は進めない。
    pub(crate) fn 控えている間にライブラリを進める(&mut self, 今: Instant) {
        self.状態.ライブラリの書き込みを進める(今);
        self.状態.ライブラリ.サムネイルの結果を受け取る();
    }

    /// 控えている間に、ライブラリの書き込み(頼み直し)とサムネイルの結果の受け取りのために画面を進めるなら、次に描き直すまでの時間。
    /// スタックの作業場が前の間、配線がスタックの作業場の画面へ渡す。
    pub(crate) fn 控えている間に描き直すまでの時間(&self) -> Option<Duration> {
        self.状態.ライブラリ.控えている間に描き直すまでの時間()
    }

    /// 次に重ね合わせを見て保存を頼むまでの時間を置く。試験で、保存の頼み直しを待っている様子を作るために使う。
    #[cfg(test)]
    pub(crate) fn 次に見るまでの時間を置く(&mut self, 時間: Duration) {
        self.状態.ライブラリ.次に見るまでの時間を置く(時間);
    }

    /// 重ね合わせの作業場を前に出すときに呼ぶ。重ね合わせの一覧を読み直す(スタックの作業場がライブラリの構えへ移ったときに読み直すのと同じ)。
    pub(crate) fn 前に出すときに一覧を読み直す(&mut self) {
        self.状態.ライブラリ.一覧を読み直す();
    }

    /// ウインドウを閉じる要求を受けた。開いている重ね合わせを確かめ、書けない・登録していない変更があれば確かめるダイアログを出して、閉じてよくないと答える。
    pub(crate) fn 閉じる要求を確かめる(&mut self) -> 確かめた結果 {
        self.状態.閉じる要求を確かめる()
    }

    /// 利用者が確かめるダイアログでアプリを閉じてよいと決めたかを取り出す。配線の閉じる手順が毎フレーム取り出す。
    pub(crate) fn 閉じてよいとの決めを取り出す(
        &mut self,
    ) -> アプリを閉じてよいとの決め {
        self.状態.ライブラリ.閉じてよいとの決めを取り出す()
    }

    /// アプリを閉じる前の確かめのダイアログを出していれば閉じる。配線が閉じる手順を捨てるときに呼ぶ。
    pub(crate) fn アプリを閉じる前の確かめを閉じる(&mut self) {
        self.状態.ライブラリ.アプリを閉じる前の確かめを閉じる();
    }

    /// アプリを閉じる前の確かめのダイアログを出しているか。出していないなら、利用者が「やめる」を選んだ。
    pub(crate) fn アプリを閉じる前の確かめを出しているか(&self) -> bool {
        self.状態
            .ライブラリ
            .アプリを閉じる前の確かめを出しているか()
    }

    /// アプリを落とす前に呼ぶ。書けていない重ね合わせの保存を頼む。頼んだ書き込みは、重ね合わせのライブラリを落とすときに終えてから閉じる。
    pub(crate) fn 終わる前に保存を頼む(&mut self) {
        self.状態.書けていない重ね合わせの保存を頼む();
    }
}
