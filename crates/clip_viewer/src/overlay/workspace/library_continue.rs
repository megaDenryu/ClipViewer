//! 開いている重ね合わせとの関係を終える操作を続けること。関係を終える前に確かめ、失われる変更が無ければ続ける操作(並べ直す・閉じる・一覧から開く・アプリを閉じてよいと決める)を行う。
//! 一覧から開くときは、書き込みを終えてから読み、ライブラリへ書けるなら登録済みとして、読み取り専用なら未登録として開く。参照: _doc/設計/同時再生.md 2-2・2-7

use clip_domain::重ね合わせの識別子;
use video_source::動画の読み手;

use super::library::スタックの作業場から借りるもの;
use super::重ね合わせの作業場;
use crate::library_common::確かめた結果;
use crate::overlay::state::library::{
    重ね合わせとの関係を終える操作, 重ね合わせとライブラリの関係,
};

impl 重ね合わせの作業場 {
    /// 開いている重ね合わせとの関係を終える前に確かめ、失われる変更が無ければ続ける操作を行う。あれば確かめるダイアログを出す(状態が出す)。
    pub(super) fn 確かめてから続ける(
        &mut self,
        続ける操作: 重ね合わせとの関係を終える操作,
        借りるもの: スタックの作業場から借りるもの<'_>,
    ) {
        if self.状態.関係を終える前に確かめる(続ける操作.clone())
            == 確かめた結果::続けてよい
        {
            self.続ける操作を行う(続ける操作, 借りるもの);
        }
    }

    /// 続ける操作を確かめずに行う。
    pub(super) fn 続ける操作を行う(
        &mut self,
        続ける操作: 重ね合わせとの関係を終える操作,
        借りるもの: スタックの作業場から借りるもの<'_>,
    ) {
        match 続ける操作 {
            重ね合わせとの関係を終える操作::今のスタックから並べ直す => {
                self.並べた結果を当てる(借りるもの.今のスタック, 借りるもの.読み手)
            }
            重ね合わせとの関係を終える操作::重ね合わせを閉じる => {
                self.状態.重ね合わせを閉じる()
            }
            重ね合わせとの関係を終える操作::一覧から開く(識別子) => {
                self.ライブラリの重ね合わせを開く(&識別子, 借りるもの.読み手)
            }
            重ね合わせとの関係を終える操作::アプリを閉じる => {
                self.状態.ライブラリ.アプリを閉じてよいと決める()
            }
        }
    }

    /// 書き込みを終えてから重ね合わせを読んで開く。ライブラリへ書けるなら登録済みとして開き、読み取り専用なら未登録として開く。
    fn ライブラリの重ね合わせを開く(
        &mut self,
        識別子: &重ね合わせの識別子,
        読み手: Option<&動画の読み手>,
    ) {
        let 読んだ = match self
            .状態
            .ライブラリ
            .書き込みを終えてから重ね合わせを読む(識別子)
        {
            Ok(読んだ) => 読んだ,
            Err(理由) => {
                return self
                    .状態
                    .知らせ
                    .出す(format!("重ね合わせをライブラリから開けない: {理由}"));
            }
        };
        let 書けるか = self.状態.ライブラリ.書けるか();
        let 文 = if 書けるか {
            format!("重ね合わせをライブラリから開きました: {}", 読んだ.名前())
        } else {
            format!(
                "重ね合わせをライブラリから読み取り専用で開きました: {}。変更はライブラリへ保存しない",
                読んだ.名前()
            )
        };
        let 重ね合わせ = 読んだ.重ね合わせ().clone();
        let 関係 = if 書けるか {
            重ね合わせとライブラリの関係::ファイルから開いた(読んだ)
        } else {
            重ね合わせとライブラリの関係::未登録
        };
        self.関係と一緒に重ね合わせを開く(重ね合わせ, 関係, 読み手);
        self.状態.知らせ.出す(文);
    }
}
