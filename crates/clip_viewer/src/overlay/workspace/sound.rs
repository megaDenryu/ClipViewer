//! 重ね合わせの作業場の音の口。配線が毎フレーム行ごとの再生の指示を読んで2本目の流れへ渡すことと、2本目の流れを開けなかったことと
//! 途中で使えなくなったことを配線から受け取って知らせることを公開する。参照: _doc/設計/同時再生.md 5-3

use std::time::Instant;

use audio_output::{行ごとの再生の指示, 音声出力のエラー};
use clip_domain::音量;

use super::重ね合わせの作業場;

impl 重ね合わせの作業場 {
    /// 行ごとの再生の指示を組み立てる。音量のつまみの値は、配線がスタックの作業場と共有する見る側の設定から読んで渡す。
    pub(crate) fn 行ごとの再生の指示(
        &self,
        今: Instant,
        つまみの音量: 音量,
    ) -> 行ごとの再生の指示 {
        self.状態.行ごとの再生の指示(今, つまみの音量)
    }

    /// 配線が初めてこの作業場へ移るときに2本目の流れを開き、開けなかったときに1回だけ呼ぶ。その理由を知らせる。
    pub(crate) fn 開けなかった音の出力を知らせる(&mut self) {
        self.状態.開けなかった音の出力を知らせる();
    }

    /// 配線が、2本目の流れが途中で使えなくなったと知ったときに呼ぶ。初めてなら知らせ、以後は映像だけで再生を続ける。
    pub(crate) fn 音の出力が使えなくなった(
        &mut self, 失敗: 音声出力のエラー
    ) {
        self.状態.音の出力が使えなくなった(失敗);
    }
}
