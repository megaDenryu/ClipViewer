//! 重ね合わせの作業場の音の口。2本目の流れを開けなかったことと、途中で使えなくなったことを配線から受け取って知らせることを公開する。
//! 行ごとの再生の指示は、毎フレームの手順(`フレームを進める`)が返す。参照: _doc/設計/同時再生.md 5-3

use audio_output::音声出力のエラー;

use super::重ね合わせの作業場;

impl 重ね合わせの作業場 {
    /// 作業場を作る時点で、2本目の流れを今開けなかったときに1回だけ呼ぶ。その理由を知らせる。
    pub(crate) fn 開けなかった音の出力を知らせる(&mut self) {
        self.状態.開けなかった音の出力を知らせる();
    }

    /// 配線が、2本目の流れが途中で使えなくなったと知ったときに呼ぶ。初めてなら知らせ、以後は映像だけで再生を続ける。
    pub(crate) fn 音の出力が使えなくなった(
        &mut self, 失敗: 音声出力のエラー
    ) {
        self.状態.音の出力が使えなくなった(失敗);
    }
}
