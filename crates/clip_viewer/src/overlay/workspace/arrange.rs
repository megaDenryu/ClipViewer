//! 今のスタックから並べること。スタックの作業場の今のスタックの値から重ね合わせを並べて開き、並べた結果を重ね合わせの作業場の知らせと報告に出す。
//! 重ね合わせを開いている間は並べ直すことになり、開いている重ね合わせを捨てる前に確かめる(`library.rs`)。参照: _doc/設計/同時再生.md 2-2・2-7・4-3

use clip_domain::重ね合わせ;
use video_source::動画の読み手;

use super::library::今のスタックの値と動画の読み手;
use super::重ね合わせの作業場;
use crate::overlay::state::library::重ね合わせとの関係を終える操作;
use crate::overlay::state::今のスタックの値;

impl 重ね合わせの作業場 {
    /// 今のスタックの再生できるクリップを、スタックの順に8つまで格子に並べた重ね合わせを作って開き、並べた結果を知らせる(同時再生.md 2-2)。
    /// 重ね合わせを開いている間は並べ直しであり、捨てる前に確かめる(未登録で置き方を手で直していれば確かめるダイアログを、
    /// 登録済みなら書けたことを確かめ、書けなければ保存できずに続けるかのダイアログを出す)。並べ直すと、新しい重ね合わせは未登録として始まる。
    /// 動画の読み手は、配線がスタックの作業場の `動画の開き手` から借りる(FFmpeg が見つかっていなければ無い)。
    /// 並べた結果と知らせは次のフレームの画面に出るため、最後に描き直しを頼む。頼まないと、利用者がマウスを動かすまで格子の絵も知らせも出ない。
    pub(crate) fn 今のスタックから並べる(
        &mut self,
        値: 今のスタックの値<'_>,
        読み手: Option<&動画の読み手>,
    ) {
        let 借りるもの = 今のスタックの値と動画の読み手 {
            今のスタック: 値,
            読み手,
        };
        self.確かめてから続ける(
            重ね合わせとの関係を終える操作::今のスタックから並べ直す,
            借りるもの,
        );
        self.画面描画の共有状態.request_repaint();
    }

    /// 並べた重ね合わせを開く。置けるクリップが1つも無いときは、開いている重ね合わせを変えずに、置けなかったクリップを知らせる。
    pub(super) fn 並べた結果を当てる(
        &mut self,
        値: 今のスタックの値<'_>,
        読み手: Option<&動画の読み手>,
    ) {
        let Some(動画) = 値.開いている動画 else {
            return self.状態.動画を開いていないため並べられないことを知らせる();
        };
        match 重ね合わせ::スタックから並べる(
            値.スタック,
            動画.パス.clone(),
            動画.長さ,
            値.出力のアスペクト比,
            &mut self.発行元,
        ) {
            Ok(並べた) => {
                // スタックから並べる読み替えは、置いたクリップを1つずつ別の行へ置くため、行の数が並べた数である。
                let 並べた数 = 並べた.重ね合わせ.行の並び().行の数();
                self.重ね合わせを開く(並べた.重ね合わせ, 読み手);
                self.状態
                    .並べた結果を知らせる(並べた数, 並べた.置かなかったクリップの一覧);
            }
            Err(エラー) => self.状態.並べられなかったことを知らせる(エラー),
        }
    }
}
