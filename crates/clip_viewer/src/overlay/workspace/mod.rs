//! 重ね合わせの作業場。重ね合わせの作業場の状態と、行のテクスチャを登録する画面描画の共有状態と、置いたクリップの識別子の発行元を持ち、
//! 1フレームの手順(時計 → 映像と音の供給 → 画面 → 応答の適用)の各工程と、重ね合わせを開くこと(`open.rs`)と、今のスタックから並べること(`arrange.rs`)と、今のスタックのクリップを置くこと(`place.rs`)と、控える前に再生を止めることと、
//! 状態を読むことと、音の口(行ごとの再生の指示と音の出力の知らせ。`sound.rs`)を公開する。配線(`app/`)はこの型の口だけを呼び、中の状態・画面・操作を知らない。参照: _doc/設計/同時再生.md 3-2

use std::time::{Duration, Instant};

use audio_output::行ごとの再生の指示;
use clip_domain::音量;
use eframe::egui;
use sengen_egui::ノード;

mod arrange;
mod open;
mod place;
mod sound;

use super::command::{重ね合わせの作業場の応答, 重ね合わせの操作};
use super::placed_id_issuer::実時間の置いたクリップの識別子発行元;
use super::state::library_status::重ね合わせのライブラリの様子;
use super::state::{
    スタックの保存の観測結果, 今のスタックの値, 重ね合わせの作業場の状態,
    重ね合わせの音の出力の状況,
};
use super::view;
use crate::primary_button::主ボタンの様子;

/// 重ね合わせの作業場とは、重ね合わせを作り、直し、再生し、保存して開き直すための作業場のことである。
/// スタックの作業場の状態(`アプリの状態`)を持たず、借りもしない。スタックの作業場から読む値は、配線が `今のスタックの値` として渡す。
pub(crate) struct 重ね合わせの作業場 {
    状態: 重ね合わせの作業場の状態,
    画面描画の共有状態: egui::Context,
    発行元: 実時間の置いたクリップの識別子発行元,
}

impl 重ね合わせの作業場 {
    /// 初めて重ね合わせの作業場へ移るときに作る。重ね合わせを開いていない。画面描画の共有状態は、重ね合わせを開くときに行のテクスチャを登録するために持つ。
    /// 音の出力の状況は、配線が同じときに2本目の流れを開いた結果であり、重ね合わせを開くときに音の倉庫の周波数を決める。
    pub(crate) fn 開いていない作業場(
        画面描画の共有状態: egui::Context,
        音の出力: 重ね合わせの音の出力の状況,
    ) -> Self {
        Self {
            状態: 重ね合わせの作業場の状態::開いていない(音の出力),
            画面描画の共有状態,
            発行元: 実時間の置いたクリップの識別子発行元::時刻から番号の始まりを取って作る(),
        }
    }

    /// 前に出ている間、画面を組む前に毎フレーム呼ぶ。時計を進め、進めた位置に行ごとに映すコマを載せ、行ごとの音を整え、2本目の流れへ渡す行ごとの再生の指示を返す。
    /// 全体の鳴らす音量は、配線がスタックの作業場と共有する見る側の設定から読んで渡す(音量のつまみの値。全体を消音していれば無音)。
    pub(crate) fn フレームを進める(
        &mut self,
        今: Instant,
        全体の鳴らす音量: 音量,
    ) -> 行ごとの再生の指示 {
        self.状態.フレームを進める(今, 全体の鳴らす音量)
    }

    /// 前に出ている間、毎フレーム呼ぶ。配線が観測したスタックの作業場の開いているスタックの保存を受け取り、新しい失敗なら知らせに写す(同時再生.md 2-8)。
    pub(crate) fn スタックの保存の失敗を知らせる(
        &mut self,
        観測結果: スタックの保存の観測結果,
    ) {
        self.状態.スタックの保存の失敗を知らせる(観測結果);
    }

    /// 今の状態から1フレーム分の画面を組む。今のスタックの値とスタックの作業場の描き直すまでの時間と重ね合わせのライブラリの様子は、配線が求めて渡す。
    pub(crate) fn 画面(
        &self,
        今のスタック: 今のスタックの値<'_>,
        スタックの作業場の描き直すまでの時間: Option<Duration>,
        ライブラリの様子: 重ね合わせのライブラリの様子<'_>,
    ) -> ノード<重ね合わせの作業場の応答> {
        let 置くクリップ = self.状態.置くクリップの一覧(今のスタック);
        view::画面(
            self.状態(),
            今のスタック.並べる状況(),
            置くクリップ.as_ref(),
            今のスタック.全体の音量,
            スタックの作業場の描き直すまでの時間,
            ライブラリの様子,
        )
    }

    /// 描画の間に集めた重ね合わせの作業場の中の操作を状態へ適用する。
    pub(crate) fn 操作を適用する(&mut self, 操作: 重ね合わせの操作) {
        self.状態.操作を適用する(操作);
    }

    /// 描画の間に集めた応答を適用した後に呼ぶ安全網。主ボタンを押していないのに残った塊のドラッグと映す矩形のドラッグを、確定せずに捨てる。
    pub(crate) fn 取り残されたドラッグを捨てる(
        &mut self, 主ボタン: 主ボタンの様子
    ) {
        self.状態.取り残されたドラッグを捨てる(主ボタン);
    }

    /// スタックの作業場を前に出すときに呼ぶ。再生を止め、行ごとの流し読みを閉じる。重ね合わせと再生の位置と、行のテクスチャに載せたコマはそのまま残す。
    pub(crate) fn 控える前に再生を止める(&mut self) {
        self.状態.控える前に再生を止める();
    }

    /// 重ね合わせの作業場の状態を読む。画面と、画面が表示する値を確かめる試験が読む。
    pub(crate) fn 状態(&self) -> &重ね合わせの作業場の状態 {
        &self.状態
    }
}
