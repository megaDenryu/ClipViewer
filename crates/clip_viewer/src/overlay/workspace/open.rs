//! 重ね合わせを開くこと。使う動画の表の動画を借りた読み手で開いて映像の供給を作り、2本目の流れの周波数で音の供給を作り、
//! 重ね合わせとライブラリとの関係と一緒に状態へ渡す。参照: _doc/設計/同時再生.md 3-2・5-1・2-7

use clip_domain::重ね合わせ;
use video_source::{メモリの上限, 動画の読み手};

use super::重ね合わせの作業場;
use crate::overlay::feed::{
    重ね合わせの映像の供給を作れたか, 重ね合わせの音の供給
};
use crate::overlay::state::library::重ね合わせとライブラリの関係;

impl 重ね合わせの作業場 {
    /// ライブラリに登録していない重ね合わせとして開き、先頭で止まった再生の状況で始める。使う動画の表の動画を、配線がスタックの作業場の `動画の開き手` から借りた読み手
    /// (FFmpeg が見つかっていなければ無い)で開き(ffprobe が終わるまで待つ)、行のテクスチャを登録し、開けた動画の音の倉庫を2本目の流れの周波数で開く。
    /// 倉庫はスタックの作業場の倉庫と別に既定の上限を持つ。
    pub(crate) fn 重ね合わせを開く(
        &mut self,
        重ね合わせ: 重ね合わせ,
        読み手: Option<&動画の読み手>,
    ) {
        self.開く(
            重ね合わせ,
            重ね合わせとライブラリの関係::未登録,
            読み手,
            メモリの上限::既定,
        );
    }

    /// ライブラリとの関係(ライブラリから開いたなら登録済み)と一緒に重ね合わせを開く。
    pub(crate) fn 関係と一緒に重ね合わせを開く(
        &mut self,
        重ね合わせ: 重ね合わせ,
        関係: 重ね合わせとライブラリの関係,
        読み手: Option<&動画の読み手>,
    ) {
        self.開く(重ね合わせ, 関係, 読み手, メモリの上限::既定);
    }

    /// 倉庫のメモリの上限を指定して、未登録の重ね合わせとして開く。結合試験は、上限を小さくして流し読みの経路を通す。
    #[cfg(test)]
    pub(crate) fn 倉庫の上限で重ね合わせを開く(
        &mut self,
        重ね合わせ: 重ね合わせ,
        読み手: Option<&動画の読み手>,
        上限: メモリの上限,
    ) {
        self.開く(
            重ね合わせ,
            重ね合わせとライブラリの関係::未登録,
            読み手,
            上限,
        );
    }

    fn 開く(
        &mut self,
        重ね合わせ: 重ね合わせ,
        関係: 重ね合わせとライブラリの関係,
        読み手: Option<&動画の読み手>,
        上限: メモリの上限,
    ) {
        let 映像 = 重ね合わせの映像の供給を作れたか::開く(
            読み手,
            重ね合わせ.動画の表(),
            上限,
            &self.画面描画の共有状態,
        );
        let 音 = 重ね合わせの音の供給::開く(
            読み手,
            &映像,
            重ね合わせ.動画の表().動画の数(),
            self.状態.音の出力の周波数(),
        );
        self.状態.重ね合わせを開く(重ね合わせ, 映像, 音, 関係);
    }
}
