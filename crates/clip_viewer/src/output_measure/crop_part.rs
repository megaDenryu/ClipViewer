//! クロップ範囲を、テクスチャのうち描く部分にする変換。スタックの作業場の出力とプレビュー(`view/`)と、重ね合わせの作業場の重ねる画面
//! (`overlay/view/`)が共有する。2つの作業場の画面はお互いを知らないため、どちらにも属さない置き場にする。参照: _doc/設計/画面.md 判断6

use clip_domain::クロップ範囲;
use sengen_egui::{割合, 割合で表した矩形};

/// クロップ範囲(百分率)を、画像のうち描く部分(割合で表した矩形)にする。右端と下端が100%を超える範囲は画像の端までにする。
pub(crate) fn クロップを描く部分にする(
    クロップ: クロップ範囲,
) -> 割合で表した矩形 {
    let 割合にする = 割合::倍精度の小数から範囲へ丸めて生成する;
    let 左端 = クロップ.左端().割合();
    let 上端 = クロップ.上端().割合();
    let 右端 = 左端 + クロップ.幅().割合();
    let 下端 = 上端 + クロップ.高さ().割合();
    match 割合で表した矩形::生成する(
        割合にする(左端),
        割合にする(上端),
        割合にする(右端),
        割合にする(下端),
    ) {
        Ok(矩形) => 矩形,
        Err(不正) => panic!(
            "クロップ範囲の幅と高さは5%以上なので左端と右端は逆転しない(到達したらバグ): {不正}"
        ),
    }
}
