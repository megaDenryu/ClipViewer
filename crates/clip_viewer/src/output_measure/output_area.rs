//! 出力の欄の余白の内側。出力を描く欄の縁に空ける余白と、欄が小さくても保つ最小の寸法を持ち、使える大きさから余白の内側の寸法を求める。
//! スタックの作業場の出力(`view/output/size.rs`)と、重ね合わせの作業場の重ねる画面(`overlay/view/screen.rs`)が同じ値を使う。
//! 参照: 移植元 Service/動画再生サービス.ts の `_出力寸法を計算する`、_doc/設計/画面.md 判断8

use sengen_egui::縦横の論理画素;

use super::aspect_fit::丸める前の論理画素の寸法;

const 縁の余白: 丸める前の論理画素の寸法 =
    丸める前の論理画素の寸法::生成する(32.0, 32.0); // 出力の欄の縁に空ける余白の幅と高さそれぞれの合計(移植元と同じ)
const 最小の寸法: 丸める前の論理画素の寸法 =
    丸める前の論理画素の寸法::生成する(320.0, 180.0); // 使える大きさが小さくても保つ最小の幅と高さ(移植元と同じ)

impl 丸める前の論理画素の寸法 {
    /// 使える大きさから縁の余白を引いた内側の寸法。内側は最小の幅と高さより小さくしない。
    pub(crate) fn 出力の欄の余白の内側(
        使える大きさ: 縦横の論理画素
    ) -> Self {
        Self::論理画素の組から作る(使える大きさ)
            .差し引く(縁の余白)
            .下限へ揃える(最小の寸法)
    }
}
