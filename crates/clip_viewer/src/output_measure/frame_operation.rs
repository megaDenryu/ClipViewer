//! 範囲枠の操作の値の変換。SengenEgui の範囲枠の部品(範囲枠付き画像と複数の範囲枠)が発する掴んだ部分と割合の差を、
//! `clip_domain` の基準に依らない枠の掴む所と枠の移動量へ直す。スタックの作業場のクロップ枠(`view/conversion.rs`)と、
//! 重ね合わせの作業場の映す矩形の枠(`overlay/view/frame_conversion.rs`)が共に使う。参照: _doc/設計/画面.md 判断6・判断20

use clip_domain::{四隅のつまみ, 枠の掴む所, 枠の移動量, 百分率の差分};
use sengen_egui::{割合の差, 範囲枠の掴んだ部分, 縦横の割合の差};

/// 範囲枠の掴んだ部分を、枠の掴む所にする。
pub(crate) fn 掴んだ部分を掴む所にする(
    部分: 範囲枠の掴んだ部分
) -> 枠の掴む所 {
    match 部分 {
        範囲枠の掴んだ部分::内側 => 枠の掴む所::内側,
        範囲枠の掴んだ部分::左上の隅 => 枠の掴む所::隅(四隅のつまみ::左上),
        範囲枠の掴んだ部分::右上の隅 => 枠の掴む所::隅(四隅のつまみ::右上),
        範囲枠の掴んだ部分::左下の隅 => 枠の掴む所::隅(四隅のつまみ::左下),
        範囲枠の掴んだ部分::右下の隅 => 枠の掴む所::隅(四隅のつまみ::右下),
    }
}

/// 割合の差(基準の幅と高さを1とする)を、百分率の差分(基準の幅と高さを100とする)の枠の移動量にする。有限でなければ無い。
pub(crate) fn 割合の差を枠の移動量にする<基準>(
    差: 縦横の割合の差,
) -> Option<枠の移動量<基準>> {
    let 百分率にする =
        |差: 割合の差| 百分率の差分::作成する(f64::from(差.生の値()) * 100.0).ok();
    Some(枠の移動量 {
        横: 百分率にする(差.横)?,
        縦: 百分率にする(差.縦)?,
    })
}
