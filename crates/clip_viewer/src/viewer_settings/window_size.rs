//! 窓の大きさと、起動のときに作る窓の形。起動の部分(main.rs)が窓を作るときに eframe へ渡し、settings.json が覚える。

use sengen_egui::{画素の組, 縦横の論理画素, 論理画素};

/// 窓の大きさとは、窓の中身(題名の帯と枠を除く部分)の幅と高さを、論理画素(OS の表示の拡大率を掛ける前の画素)で表したもののことである。
/// 幅と高さは有限の正の数である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 窓の大きさ(縦横の論理画素);

/// 画面の大きさとは、窓を置いている画面(モニタ)の幅と高さを論理画素で表したもののことである。egui が起動の後に知らせる。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 画面の大きさ(縦横の論理画素);

impl 窓の大きさ {
    /// 窓の最初の大きさ。窓を作る前の eframe の口では画面の大きさが分からないため、よくある小さめの画面に収まる値に固定する。
    /// 1920x1080 を150%で使う画面の作業領域(論理で約1280x672)と 1366x768 を100%で使う画面に、題名の帯と枠を含めて収まる。
    /// 大きな画面では利用者が最大化するか広げる。
    pub(crate) const 最初: Self = Self(画素の組(1200.0, 620.0));

    /// 窓の最小の大きさ。これより小さくすると、移植元の3区画(サイドバー・出力・再生コントロール)が重なるためである。
    pub(crate) const 最小: Self = Self(画素の組(800.0, 500.0));

    /// 幅と高さの論理画素から作る。どちらかが有限の正の数でなければ無い。egui が知らせた値と settings.json の値を受け取る境界で使う。
    pub(crate) fn 幅と高さから作る(幅: f64, 高さ: f64) -> Option<Self> {
        let 正か = |値: f64| 値.is_finite() && 値 > 0.0;
        (正か(幅) && 正か(高さ)).then(|| {
            Self(縦横の論理画素::生成する(
                論理画素::倍精度の小数から生成する(幅),
                論理画素::倍精度の小数から生成する(高さ),
            ))
        })
    }

    /// 幅と高さの論理画素。settings.json へ書く境界で使う。
    pub(crate) fn 幅と高さ(self) -> (f64, f64) {
        (
            self.0.横.倍精度の小数にする(),
            self.0.縦.倍精度の小数にする(),
        )
    }

    /// 幅と高さの論理画素の組。egui の値へ戻すのは、窓を作る境界(起動の部分)だけである。
    pub(crate) const fn 論理画素の組(self) -> 縦横の論理画素 {
        self.0
    }

    /// 画面に収まり、最小の大きさ以上か。幅と高さの両方で比べる。収まらない大きさ(大きな画面で広げた窓を小さな画面で開いた等)は、
    /// 最初の大きさへ戻す判断に使う。題名の帯と枠の分は数えない(画面の大きさは作業領域でなく画面全体のため、その分の余裕がある)。
    pub(crate) fn 画面に収まるか(self, 画面: 画面の大きさ) -> bool {
        let (幅, 高さ) = self.幅と高さ();
        let (最小の幅, 最小の高さ) = Self::最小.幅と高さ();
        let 画面の幅 = 画面.0.横.倍精度の小数にする();
        let 画面の高さ = 画面.0.縦.倍精度の小数にする();
        (最小の幅..=画面の幅).contains(&幅) && (最小の高さ..=画面の高さ).contains(&高さ)
    }
}

impl 画面の大きさ {
    /// 幅と高さの論理画素から作る。どちらかが有限の正の数でなければ無い。egui が知らせた値を受け取る境界で使う。
    pub(crate) fn 幅と高さから作る(幅: f64, 高さ: f64) -> Option<Self> {
        窓の大きさ::幅と高さから作る(幅, 高さ).map(|大きさ| Self(大きさ.0))
    }
}

/// 最大化の様子とは、窓が最大化しているか、していないかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub(crate) enum 最大化の様子 {
    #[default]
    最大化していない,
    最大化している,
}

/// 窓の記憶とは、最大化していないときの窓の大きさと、最大化しているかの組のことである。
/// 最大化して閉じても、次に最大化を戻したときの大きさを覚えておくため、大きさは最大化していないときのものを持つ。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 窓の記憶 {
    pub(crate) 大きさ: 窓の大きさ,
    pub(crate) 最大化: 最大化の様子,
}

impl 窓の記憶 {
    /// 何も覚えていないときの窓。最初の大きさで、最大化していない。
    pub(crate) const 最初: Self = Self {
        大きさ: 窓の大きさ::最初,
        最大化: 最大化の様子::最大化していない,
    };
}
