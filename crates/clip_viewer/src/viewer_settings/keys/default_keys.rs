//! 既定のキー。操作ごとに、利用者が何も変えていないときのキーの組を決める。「既定に戻す」と、settings.json に
//! キーの割り当てが無いときにこのキーを使う。参照: _doc/設計/画面.md 判断14「キーの割り当て」・判断18

use sengen_egui::{キー, キーの組, 修飾キー};

use super::operation::キーで行う操作;
use super::operation_keys::操作のキー;

/// Ctrl(macOS では Command)と Shift を同時に押す修飾キー。
const コマンドとシフト: 修飾キー = 修飾キー {
    shift: true,
    ..修飾キー::COMMAND
};

const fn 単独(キー: キー) -> 操作のキー {
    操作のキー::一つ(キーの組::単独(キー))
}

const fn シフト(キー: キー) -> 操作のキー {
    操作のキー::一つ(キーの組::生成する(修飾キー::SHIFT, キー))
}

const fn コマンド(キー: キー) -> 操作のキー {
    操作のキー::一つ(キーの組::生成する(修飾キー::COMMAND, キー))
}

impl キーで行う操作 {
    /// 利用者が何も変えていないときのキー。どの2つの操作も同じキーの組を持たない(試験が確かめる)。
    pub(crate) const fn 既定のキー(self) -> 操作のキー {
        match self {
            Self::再生と停止を切り替える => {
                操作のキー::二つ(キーの組::単独(キー::Space), キーの組::単独(キー::K))
            }
            Self::次のクリップへ進めるか知らせる => 単独(キー::Enter),
            Self::前のクリップへ戻る => 単独(キー::PageUp),
            Self::次のクリップへ進める => 単独(キー::PageDown),
            Self::一コマ戻す => 単独(キー::ArrowLeft),
            Self::一コマ進める => 単独(キー::ArrowRight),
            Self::五秒戻す => シフト(キー::ArrowLeft),
            Self::五秒進める => シフト(キー::ArrowRight),
            Self::速度を一段下げる => 単独(キー::OpenBracket),
            Self::速度を一段上げる => 単独(キー::CloseBracket),
            Self::消音を切り替える => 単独(キー::M),
            Self::シアターと編集を切り替える => 単独(キー::T),
            Self::全画面かシアターを抜ける => 単独(キー::Escape),
            Self::全画面を切り替える => 単独(キー::F11),
            Self::ライブラリへ保存する => コマンド(キー::S),
            Self::キーの一覧を開け閉めする => 単独(キー::F1),
            Self::編集を取り消す => コマンド(キー::Z),
            Self::編集をやり直す => 操作のキー::二つ(
                キーの組::生成する(修飾キー::COMMAND, キー::Y),
                キーの組::生成する(コマンドとシフト, キー::Z),
            ),
            Self::開始を今の位置にする => 単独(キー::I),
            Self::終了を今の位置にする => 単独(キー::O),
        }
    }
}
