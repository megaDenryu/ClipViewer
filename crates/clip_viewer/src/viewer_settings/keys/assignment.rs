//! キーの割り当て。すべての操作のキーを持ち、どの2つの操作も同じキーの組を持たないことを保つ。
//! キーを変えることと既定に戻すことは、重なりを確かめてから(overlap.rs)新しい割り当てを返す。保存した変更から作ることは、重なりを起こした変更を捨てて作る(saved_changes.rs)。
//! 参照: _doc/設計/画面.md 判断18

use sengen_egui::キーの組;

use super::operation::{キーで行う操作, 操作の数};
use super::operation_keys::操作のキー;
use super::overlap::キーを変えられない理由;

/// キーの割り当てとは、すべての操作の、その操作に割り当てたキーの組のことである。
/// 不変条件: どの2つの操作も同じキーの組を持たない(キー操作は最初に一致したものだけが押下を受け取るため、重なった後の操作は決して起きない)。
/// どの操作も1つ以上のキーを持つことは `操作のキー` の型が保つ。キー(`キーで行う操作::並びの位置`)の順に並べて持つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct キーの割り当て {
    キー: [操作のキー; 操作の数],
}

impl キーの割り当て {
    /// 利用者が何も変えていない割り当て。どの操作も既定のキーを持つ。
    /// 見る側の設定の既定(定数)から使うため const にする。並べる前の値は、すぐに各操作の既定のキーで上書きする。
    pub(crate) const fn 既定() -> Self {
        let mut キー = [キーで行う操作::すべて[0].既定のキー(); 操作の数];
        let mut 位置 = 0;
        while 位置 < 操作の数 {
            キー[位置] = キーで行う操作::すべて[位置].既定のキー();
            位置 += 1;
        }
        Self { キー }
    }

    /// 既定の割り当てに変更を重ねる。重なりを確かめない(確かめて捨てるのは saved_changes.rs の `保存した変更から作る`)。
    pub(super) fn 確かめずに変更を重ねた<'a>(
        変更: impl IntoIterator<Item = &'a (キーで行う操作, 操作のキー)>,
    ) -> Self {
        let mut 割り当て = Self::既定();
        for (操作, キー) in 変更 {
            割り当て.キー[操作.並びの位置()] = *キー;
        }
        割り当て
    }

    /// その操作のキー。
    pub(crate) fn 操作のキー(&self, 操作: キーで行う操作) -> 操作のキー {
        self.キー[操作.並びの位置()]
    }

    /// すべての操作とそのキーを、キーの一覧のダイアログの行の順に返す。
    pub(crate) fn 並び(
        &self,
    ) -> impl Iterator<Item = (キーで行う操作, 操作のキー)> + '_ {
        キーで行う操作::すべて
            .into_iter()
            .map(|操作| (操作, self.操作のキー(操作)))
    }

    /// 既定と違うキーを持つ操作と、そのキー。settings.json にはこれだけを書く。
    pub(crate) fn 既定と違う操作(
        &self,
    ) -> impl Iterator<Item = (キーで行う操作, 操作のキー)> + '_ {
        self.並び()
            .filter(|(操作, キー)| *キー != 操作.既定のキー())
    }

    /// その操作のキーを1つの組に変えた割り当てを返す。ほかの操作がその組を持つなら変えずに理由を返す。
    /// 自分が既に持つ組なら、その組1つだけにする(2つのキーを持つ操作は、もう1つのキーを外す)。
    pub(crate) fn キーを変えた(
        self,
        操作: キーで行う操作,
        組: キーの組,
    ) -> Result<Self, キーを変えられない理由> {
        self.置き換えた(操作, 操作のキー::一つ(組))
    }

    /// その操作のキーを既定に戻した割り当てを返す。既定のキーをほかの操作が持つなら戻さずに理由を返す。
    pub(crate) fn 既定に戻した(
        self,
        操作: キーで行う操作,
    ) -> Result<Self, キーを変えられない理由> {
        self.置き換えた(操作, 操作.既定のキー())
    }

    /// その操作のキーを置き換えた割り当てを返す。ほかの操作と重なれば置き換えずに理由を返す。
    fn 置き換えた(
        mut self,
        操作: キーで行う操作,
        キー: 操作のキー,
    ) -> Result<Self, キーを変えられない理由> {
        if let Some(理由) = self.ほかの操作との重なり(操作, キー) {
            return Err(理由);
        }
        self.キー[操作.並びの位置()] = キー;
        Ok(self)
    }
}
