//! 保存した変更からキーの割り当てを作る試験。重なりを起こした変更だけを捨ててほかの変更を生かすこと、重なりに関わる変更のうち後に読んだものを捨てること、
//! 入れ替えのように変更どうしでそろって初めて重ならない変更の組を生かすことを確かめる。

use sengen_egui::{キー, キーの組};

use super::{キーで行う操作, キーの割り当て, 操作のキー};

fn 一つ(キー: キー) -> 操作のキー {
    操作のキー::一つ(キーの組::単独(キー))
}

#[test]
fn 変更どうしが重なれば後に読んだ変更だけを捨て_ほかの変更は生かす() {
    let 消音 = キーで行う操作::消音を切り替える;
    let シアター = キーで行う操作::シアターと編集を切り替える;
    let 開始 = キーで行う操作::開始を今の位置にする;
    let 割り当て = キーの割り当て::保存した変更から作る([
        (消音, 一つ(キー::Q)),
        (開始, 一つ(キー::W)),
        (シアター, 一つ(キー::Q)),
    ]);
    assert_eq!(割り当て.操作のキー(消音), 一つ(キー::Q));
    assert_eq!(割り当て.操作のキー(開始), 一つ(キー::W));
    assert_eq!(割り当て.操作のキー(シアター), シアター.既定のキー());
}

#[test]
fn 変えていない操作の既定のキーと重なる変更は捨てる() {
    let 消音 = キーで行う操作::消音を切り替える;
    let 開始 = キーで行う操作::開始を今の位置にする;
    let 割り当て =
        キーの割り当て::保存した変更から作る(
            [(消音, 一つ(キー::Space)), (開始, 一つ(キー::W))],
        );
    assert_eq!(割り当て.操作のキー(消音), 消音.既定のキー());
    assert_eq!(割り当て.操作のキー(開始), 一つ(キー::W));
}

#[test]
fn 入れ替えた2つの変更はそろって重ならないので両方を生かす() {
    let 再生 = キーで行う操作::再生と停止を切り替える;
    let 消音 = キーで行う操作::消音を切り替える;
    let 割り当て =
        キーの割り当て::保存した変更から作る(
            [(消音, 一つ(キー::Space)), (再生, 一つ(キー::M))],
        );
    assert_eq!(割り当て.操作のキー(消音), 一つ(キー::Space));
    assert_eq!(割り当て.操作のキー(再生), 一つ(キー::M));
}
