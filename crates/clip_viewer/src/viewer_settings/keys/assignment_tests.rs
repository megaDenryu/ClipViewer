//! キーの割り当ての試験。既定の割り当てに重なりが無いこと、ほかの操作のキーへ変えると断ること、既定へ戻すこと、
//! 並びの位置が `すべて` の順と一致すること、操作のキーが1つか2つの違う組からだけ作れて既定のキーもその規則を満たすことを確かめる。
#![allow(clippy::expect_used)]

use sengen_egui::{キー, キーの組};

use super::{
    キーで行う操作, キーの割り当て, キーを変えられない理由, 操作のキー
};

const 単独: fn(キー) -> キーの組 = キーの組::単独;

#[test]
fn 並びの位置はすべての順と一致する() {
    for (位置, 操作) in キーで行う操作::すべて.into_iter().enumerate() {
        assert_eq!(操作.並びの位置(), 位置, "{操作:?}");
    }
}

#[test]
fn 既定の割り当ては重ならず_既定と違う操作を持たない() {
    let 既定 = キーの割り当て::既定();
    for 操作 in キーで行う操作::すべて {
        assert_eq!(
            既定.ほかの操作との重なり(操作, 操作.既定のキー()),
            None,
            "{操作:?}"
        );
    }
    assert_eq!(キーの割り当て::既定().既定と違う操作().count(), 0);
}

#[test]
fn ほかの操作が持つキーへは変えずに_持っている操作を返す() {
    let 割り当て = キーの割り当て::既定();
    assert_eq!(
        割り当て.キーを変えた(キーで行う操作::再生と停止を切り替える, 単独(キー::M)),
        Err(キーを変えられない理由::ほかの操作のキーと重なる {
            組: 単独(キー::M),
            持っている操作: キーで行う操作::消音を切り替える,
        })
    );
    assert_eq!(
        割り当て.キーを変えた(キーで行う操作::終了を今の位置にする, 単独(キー::Space)),
        Err(キーを変えられない理由::ほかの操作のキーと重なる {
            組: 単独(キー::Space),
            持っている操作: キーで行う操作::再生と停止を切り替える,
        })
    );
}

#[test]
fn 自分が持つキーへ変えるとその1つだけになり_既定に戻すと2つに戻る() {
    let 操作 = キーで行う操作::再生と停止を切り替える;
    let 変えた = キーの割り当て::既定()
        .キーを変えた(操作, 単独(キー::K))
        .expect("自分のキーへは変えられる");
    assert_eq!(変えた.操作のキー(操作), 操作のキー::一つ(単独(キー::K)));
    assert_eq!(
        変えた.既定と違う操作().collect::<Vec<_>>(),
        [(操作, 操作のキー::一つ(単独(キー::K)))]
    );
    let 戻した = 変えた.既定に戻した(操作).expect("既定へ戻せる");
    assert_eq!(戻した, キーの割り当て::既定());
}

#[test]
fn 既定のキーをほかの操作が持っていれば既定に戻さない() {
    let 再生 = キーで行う操作::再生と停止を切り替える;
    let 消音 = キーで行う操作::消音を切り替える;
    let 割り当て = キーの割り当て::既定()
        .キーを変えた(再生, 単独(キー::P))
        .and_then(|割り当て| 割り当て.キーを変えた(消音, 単独(キー::K)))
        .expect("空いたキーへは変えられる");
    assert_eq!(
        割り当て.既定に戻した(再生),
        Err(キーを変えられない理由::ほかの操作のキーと重なる {
            組: 単独(キー::K),
            持っている操作: 消音,
        })
    );
}

#[test]
fn 操作のキーは1つか2つの異なる組からだけ作る() {
    assert_eq!(操作のキー::組の並びから作る(&[]), None);
    assert_eq!(
        操作のキー::組の並びから作る(&[単独(キー::A), 単独(キー::A)]),
        None
    );
    assert_eq!(
        操作のキー::組の並びから作る(&[単独(キー::A), 単独(キー::B), 単独(キー::C)]),
        None
    );
    assert_eq!(
        操作のキー::組の並びから作る(&[単独(キー::Space), 単独(キー::K)]).map(操作のキー::表記),
        Some("Space・K".to_string())
    );
}

/// 既定のキーは確かめずに作る口で書くため、どの操作の既定のキーも、確かめて作る口で同じ値に作り直せることを確かめる。
#[test]
fn 既定のキーはどれも確かめて作る口で作り直せる() {
    for 操作 in キーで行う操作::すべて {
        let 既定 = 操作.既定のキー();
        assert_eq!(
            操作のキー::組の並びから作る(&既定.組の並び()),
            Some(既定),
            "{操作:?}"
        );
    }
}
