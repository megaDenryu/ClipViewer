//! 保存した変更からキーの割り当てを作ること。settings.json から読んだ変更のうち、ほかの操作とキーが重なる変更を捨て、残りを生かす。
//! 参照: _doc/設計/画面.md 判断18、_doc/設計/ライブラリ.md「keyBindings の読み方」

use super::assignment::キーの割り当て;
use super::operation::キーで行う操作;
use super::operation_keys::操作のキー;

impl キーの割り当て {
    /// 保存した変更(既定と違うキーを持つ操作と、そのキー)を、渡された順に読んだものとして重ねて作る。
    /// 重ねた割り当てでキーが重なるなら、重なりに関わる変更のうち最も後に読んだもの1つを捨て(その操作は既定のキーに戻る)、重なりが無くなるまで繰り返す。
    /// 変更の全体を捨てずに重なりを起こした変更だけを捨てるのは、利用者が変えたほかのキーを黙って既定へ戻さないためである。
    /// 既定の割り当ては重ならない(試験が確かめる)ため、重なりには必ず変更が1つ以上関わり、繰り返しは変更の数の回までで終わる。
    pub(crate) fn 保存した変更から作る(
        変更: impl IntoIterator<Item = (キーで行う操作, 操作のキー)>,
    ) -> Self {
        let mut 生かす変更: Vec<(キーで行う操作, 操作のキー)> = 変更.into_iter().collect();
        loop {
            let 割り当て = Self::確かめずに変更を重ねた(&生かす変更);
            let 重なる変更 = 生かす変更
                .iter()
                .rposition(|(操作, キー)| 割り当て.ほかの操作との重なり(*操作, *キー).is_some());
            match 重なる変更 {
                None => return 割り当て,
                Some(位置) => {
                    生かす変更.remove(位置);
                }
            }
        }
    }
}
