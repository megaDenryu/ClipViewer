//! 操作のキー。1つの操作に割り当てたキーの組の並びであり、空の並びを型で表せないため、操作はキーを失わない。
//! 参照: _doc/設計/画面.md 判断18「閉じ込めの防止」

use sengen_egui::キーの組;

/// 操作のキーとは、1つの操作に割り当てたキーの組の、1つか2つの並びのことである。
/// 既定で2つのキーを持つ操作がある(再生と停止の Space・K)。利用者がキーを変えると1つになる。0個は表せない。
/// 不変条件: 2つのときは2つの組が違う。並びは非公開にし、作る口(`一つ`・`組の並びから作る`・既定のキーだけが使う `既定の二つの組から作る`)が保つ。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 操作のキー(組の並び);

/// 操作のキーの中身。外から2つの同じ組を並べて作れないよう、この型は非公開にする。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 組の並び {
    一つ(キーの組),
    二つ(キーの組, キーの組),
}

impl 操作のキー {
    /// 1つの組だけを持つ操作のキー。1つの並びは不変条件を破れないため、確かめずに作る。
    pub(crate) const fn 一つ(組: キーの組) -> Self {
        Self(組の並び::一つ(組))
    }

    /// キーの組の並びから作る。1つか2つでなければ、または2つが同じ組なら無い。
    pub(crate) fn 組の並びから作る(並び: &[キーの組]) -> Option<Self> {
        match 並び {
            [組] => Some(Self::一つ(*組)),
            [先, 後] if 先 != 後 => Some(Self(組の並び::二つ(*先, *後))),
            _ => None,
        }
    }

    /// 既定のキー(default_keys.rs)で2つの組を持つ操作のキー。既定のキーを const で書くため確かめずに作る。
    /// 注意: 既定のキー以外から使わない。既定の2つの組が違うことは assignment_tests.rs の試験が `組の並びから作る` で確かめる。
    pub(super) const fn 既定の二つの組から作る(
        先: キーの組, 後: キーの組
    ) -> Self {
        Self(組の並び::二つ(先, 後))
    }

    /// キーの組を並びの順に返す。
    pub(crate) fn 組の並び(self) -> Vec<キーの組> {
        match self.0 {
            組の並び::一つ(組) => vec![組],
            組の並び::二つ(先, 後) => vec![先, 後],
        }
    }

    /// その組を含むか。
    pub(crate) fn 含むか(self, 組: キーの組) -> bool {
        match self.0 {
            組の並び::一つ(自分) => 自分 == 組,
            組の並び::二つ(先, 後) => 先 == 組 || 後 == 組,
        }
    }

    /// キーの一覧のダイアログと説明に出す表記。2つなら「・」でつなぐ(「Space・K」)。
    pub(crate) fn 表記(self) -> String {
        self.組の並び()
            .into_iter()
            .map(キーの組::表記)
            .collect::<Vec<_>>()
            .join("・")
    }
}
