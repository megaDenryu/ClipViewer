//! キーで行う操作。キーを割り当てられる操作の閉じた列挙と、その並びを持つ。働きの文は operation_text.rs、既定のキーは default_keys.rs が持つ。
//! 参照: _doc/設計/画面.md 判断18

/// キーで行う操作とは、利用者がキーを割り当てられる操作の区別のことである。キーの組ではなく操作を単位にする
/// (Space と K は「再生と停止を切り替える」の2つのキーである)。並びの順は、キーの一覧のダイアログの行の順である。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub(crate) enum キーで行う操作 {
    再生と停止を切り替える,
    シーケンス再生のときだけ次のクリップへ進める,
    前のクリップへ戻る,
    次のクリップへ進める,
    一コマ戻す,
    一コマ進める,
    五秒戻す,
    五秒進める,
    速度を一段下げる,
    速度を一段上げる,
    消音を切り替える,
    シアターと編集を切り替える,
    全画面を抜けるか全画面でなければシアターを抜ける,
    全画面を切り替える,
    ライブラリへ保存する,
    キーの一覧を開け閉めする,
    編集を取り消す,
    編集をやり直す,
    開始を今の位置にする,
    終了を今の位置にする,
}

/// キーで行う操作の数。
pub(crate) const 操作の数: usize = 20;

impl キーで行う操作 {
    /// すべての操作。キーの一覧のダイアログの行の順に並べる。
    pub(crate) const すべて: [Self; 操作の数] = [
        Self::再生と停止を切り替える,
        Self::シーケンス再生のときだけ次のクリップへ進める,
        Self::前のクリップへ戻る,
        Self::次のクリップへ進める,
        Self::一コマ戻す,
        Self::一コマ進める,
        Self::五秒戻す,
        Self::五秒進める,
        Self::速度を一段下げる,
        Self::速度を一段上げる,
        Self::消音を切り替える,
        Self::シアターと編集を切り替える,
        Self::全画面を抜けるか全画面でなければシアターを抜ける,
        Self::全画面を切り替える,
        Self::ライブラリへ保存する,
        Self::キーの一覧を開け閉めする,
        Self::編集を取り消す,
        Self::編集をやり直す,
        Self::開始を今の位置にする,
        Self::終了を今の位置にする,
    ];

    /// `すべて` の中の位置。キーの割り当てが操作ごとのキーを並べる位置に使う。`すべて` の順と一致することは試験が確かめる。
    pub(crate) const fn 並びの位置(self) -> usize {
        match self {
            Self::再生と停止を切り替える => 0,
            Self::シーケンス再生のときだけ次のクリップへ進める => 1,
            Self::前のクリップへ戻る => 2,
            Self::次のクリップへ進める => 3,
            Self::一コマ戻す => 4,
            Self::一コマ進める => 5,
            Self::五秒戻す => 6,
            Self::五秒進める => 7,
            Self::速度を一段下げる => 8,
            Self::速度を一段上げる => 9,
            Self::消音を切り替える => 10,
            Self::シアターと編集を切り替える => 11,
            Self::全画面を抜けるか全画面でなければシアターを抜ける => 12,
            Self::全画面を切り替える => 13,
            Self::ライブラリへ保存する => 14,
            Self::キーの一覧を開け閉めする => 15,
            Self::編集を取り消す => 16,
            Self::編集をやり直す => 17,
            Self::開始を今の位置にする => 18,
            Self::終了を今の位置にする => 19,
        }
    }
}
