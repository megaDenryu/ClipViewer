//! キーの割り当ての重なりの検査。ある操作のキーをほかの操作も持つかを確かめ、重なれば相手の操作を理由として返す。
//! 参照: _doc/設計/画面.md 判断18

use sengen_egui::キーの組;

use super::assignment::キーの割り当て;
use super::operation::キーで行う操作;
use super::operation_keys::操作のキー;

/// キーを変えられない理由とは、割り当てを変えると、ある操作のキーの組をほかの操作も持つことになる理由のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum キーを変えられない理由 {
    ほかの操作のキーと重なる {
        組: キーの組,
        持っている操作: キーで行う操作,
    },
}

impl キーの割り当て {
    /// その操作のキーを置き換えたとき、ほかの操作のキーと重なるなら、重なる組と相手の操作を理由として返す。
    /// 渡したキーとほかの操作の今のキーだけを比べる(割り当てのほかの操作どうしの重なりは見ない)。
    pub(super) fn ほかの操作との重なり(
        &self,
        操作: キーで行う操作,
        キー: 操作のキー,
    ) -> Option<キーを変えられない理由> {
        self.並び()
            .filter(|(ほかの操作, _)| *ほかの操作 != 操作)
            .find_map(|(ほかの操作, ほかのキー)| {
                キー
                    .組の並び()
                    .into_iter()
                    .find(|組| ほかのキー.含むか(*組))
                    .map(|組| {
                        キーを変えられない理由::ほかの操作のキーと重なる {
                            組,
                            持っている操作: ほかの操作,
                        }
                    })
            })
    }
}
