//! 再生の操作の行。-5s・コマ送り・再生・+5s のボタンと、速度と音量のつまみと、消音と全体ループのチェックボックスを並べる。
//! ボタンとつまみの説明に、同じ操作のキーを出す(キーの割り当ては view/keys/table.rs)。

use clip_domain::末尾での振る舞い;
use sengen_egui::{
    スライダー, チェックボックス, ノード, ボタン, 付け足せる, 子, 文字表示, 横並び
};

use super::再生;
use crate::command::{再生の操作, 応答, 送る向き};
use crate::state::{
    アプリの状態, 消音の様子, 速度のつまみの刻み, 速度のつまみの範囲
};
use crate::view::styles;

pub(super) fn 操作の行(状態: &アプリの状態) -> ノード<応答> {
    let 再生の文字 = if 状態.再生.再生しているか() {
        "停止"
    } else {
        "再生"
    };
    let 全体ループ = 状態.再生.全体の末尾 == 末尾での振る舞い::先頭へ戻る;
    let 消している = 状態.再生.音量.消音の様子() == 消音の様子::消している;
    横並び(子![
        ボタン("-5s", 再生(再生の操作::五秒ずらす(送る向き::戻す))).説明("Shift+←"),
        ボタン("< F", 再生(再生の操作::コマ送り(送る向き::戻す))).説明("←"),
        ボタン(再生の文字, 再生(再生の操作::再生を切り替える))
            .装飾(styles::強調ボタン)
            .説明("Space・K"),
        ボタン("F >", 再生(再生の操作::コマ送り(送る向き::進める))).説明("→"),
        ボタン("+5s", 再生(再生の操作::五秒ずらす(送る向き::進める))).説明("Shift+→"),
        文字表示("速度").装飾(styles::補足),
        スライダー(
            状態.再生.速度.倍率(),
            速度のつまみの範囲,
            |倍率| 再生(再生の操作::速度を選ぶ(倍率))
        )
        .刻み(速度のつまみの刻み)
        .説明("[ と ] で0.25倍ごとに変える"),
        文字表示("音量").装飾(styles::補足),
        スライダー(
            状態.再生.音量.選んだ音量().値(),
            0.0..=1.0,
            |値| 再生(再生の操作::音量を選ぶ(値))
        )
        .刻み(0.05)
        .説明("0で無音。速度を変えると音の高さも変わる"),
        チェックボックス("消音", 消している, |_| 再生(
            再生の操作::消音を切り替える
        ))
        .説明("M"),
        チェックボックス("全体ループ", 全体ループ, |有効| 再生(
            再生の操作::全体ループを切り替える(有効)
        )),
    ])
    .into()
}
