//! 音の様子の表示。音声出力装置が使えるか、動画に音があるか、今の区間の音を溜めた音と流し読みのどちらで鳴らしているかを出す。

use sengen_egui::{ノード, 文字表示, 無し};

use crate::audio_feed::{
    動画の音, 音が無い様子の文, 音の鳴らし方, 鳴らせない様子の文
};
use crate::command::応答;
use crate::state::{アプリの状態, 音の出力の状況};
use crate::view::styles;

/// 音の様子の行。動画が無く、出力装置も使えるなら何も出さない。
pub(crate) fn 音の様子(状態: &アプリの状態) -> ノード<応答> {
    let 出す文 = match (&状態.音の出力, &状態.動画) {
        (音の出力の状況::使えない(理由), _) => 鳴らせない様子の文(理由),
        (音の出力の状況::使える(_), None) => return 無し(),
        (音の出力の状況::使える(_), Some(動画)) => match &動画.音 {
            動画の音::鳴らせない(理由) => 鳴らせない様子の文(理由),
            動画の音::音が無い => 音が無い様子の文.to_string(),
            動画の音::ある(供給) => {
                let 区間 = 状態.表示するコマの求め().and_then(|求め| 求め.区間);
                match 供給.鳴らし方(区間.as_ref()) {
                    音の鳴らし方::溜めた音 => {
                        "音: 溜めた音で鳴らしている(区間の継ぎ目で途切れない)".to_string()
                    }
                    音の鳴らし方::流し読み => "音: 流し読みで鳴らしている".to_string(),
                    音の鳴らし方::読めない(理由) => {
                        format!("音: 流し読みで読めない({理由})")
                    }
                }
            }
        },
    };
    文字表示(出す文).装飾(styles::補足).into()
}
