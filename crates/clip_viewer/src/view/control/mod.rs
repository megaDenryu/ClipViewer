//! 再生コントロール。ステータスと時刻の行、再生位置の帯、再生の操作と速度・音量・全体ループの行、映像の供給の様子、音の様子を並べる。

mod operation_row;
mod sound_status;
mod supply_status;

use clip_domain::再生位置;
use sengen_egui::{スライダー, ノード, 子, 文字表示, 横並び, 縦積み};

use crate::command::{再生の操作, 応答};
use crate::state::アプリの状態;
use crate::styles;
use crate::view::text;

fn 再生(操作: 再生の操作) -> 応答 {
    応答::再生(操作)
}

pub(crate) fn 再生コントロール(状態: &アプリの状態) -> ノード<応答> {
    縦積み(子![
        時刻の行(状態),
        再生位置の帯(状態),
        operation_row::操作の行(状態),
        supply_status::供給の様子(状態),
        sound_status::音の様子(状態),
    ])
    .into()
}

fn 時刻の行(状態: &アプリの状態) -> ノード<応答> {
    let ステータス = match 状態.再生.位置() {
        再生位置::シーケンス再生(_) => 状態.シーケンスの再生の様子().map_or_else(
            || "待機中".to_string(),
            |再生の中身| text::シーケンスのステータス(&再生の中身),
        ),
        再生位置::単独クリップ再生(_) => 状態.並び.選択中のクリップ().map_or_else(
            || "待機中".to_string(),
            |クリップ| format!("{} [Solo]", クリップ.名前.文字列()),
        ),
        再生位置::元動画再生(_) => "元動画全体を再生中".to_string(),
    };
    let 現在 = text::時刻の表示(状態.再生.位置().位置の秒数());
    let 合計 = text::時刻の表示(状態.合計の長さ().秒数());
    横並び(子![
        文字表示(format!("構成パス: {ステータス}")),
        文字表示(format!("{現在} / {合計}")),
        文字表示(元動画の時刻(状態)).装飾(styles::補足),
    ])
    .into()
}

/// 元動画の上の「区間の開始 / 表示しているコマの位置 / 区間の終わり」。元動画再生は動画の全体を区間とする。
fn 元動画の時刻(状態: &アプリの状態) -> String {
    let Some(求め) = 状態.表示するコマの求め().filter(|_| 状態.動画.is_some())
    else {
        return "元動画 --:--.- / --:--.- / --:--.-".to_string();
    };
    let (開始, 終了) = 求め.区間.map_or((0.0, 状態.動画の長さ().秒数()), |区間| {
        (区間.開始().秒数(), 区間.終了().秒数())
    });
    let 位置 = 求め.動画上の位置.秒数();
    format!(
        "元動画 {} / {} / {}",
        text::時刻の表示(開始),
        text::時刻の表示(位置),
        text::時刻の表示(終了)
    )
}

/// 再生位置の帯。ドラッグの間は位置だけを動かし、放したとき(矢印キーで変えたときも)に位置を決める。
fn 再生位置の帯(状態: &アプリの状態) -> ノード<応答> {
    let 合計 = 状態.合計の長さ().秒数();
    スライダー(
        状態.再生.位置().位置の秒数(),
        0.0..=合計,
        |秒| 再生(再生の操作::位置を動かしている(秒)),
    )
    .幅いっぱい()
    .数値を隠す()
    .操作を終えたら発する(|秒| 再生(再生の操作::位置を決めた(秒)))
    .into()
}
