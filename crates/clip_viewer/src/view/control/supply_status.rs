//! 映像の供給の様子の表示。表示しているコマが溜めたコマか流し読みか、溜めている途中の進み具合、溜められない理由を出す。

use clip_domain::動画上の区間;
use sengen_egui::{ノード, 割合, 子, 文字表示, 横並び, 無し, 画素, 進捗バー};
use video_source::{バイト数, 受け付けない理由};

use crate::command::応答;
use crate::state::アプリの状態;
use crate::styles;
use crate::video_feed::{
    コマの出どころ, 依頼の結末, 依頼の進み具合, 行の状態, 読み込んだ動画
};

/// 映像の供給の様子の行。動画が無ければ何も出さない。
pub(crate) fn 供給の様子(状態: &アプリの状態) -> ノード<応答> {
    let Some(動画) = &状態.動画 else {
        return 無し();
    };
    if let Some(理由) = 動画.映せない理由() {
        return 文字表示(format!("映せない: {理由}"))
            .装飾(styles::不備の文)
            .into();
    }
    match 動画.出どころ() {
        コマの出どころ::溜めたコマ(_) => {
            文字表示("溜めたコマで再生中(区間の継ぎ目で途切れない)").into()
        }
        コマの出どころ::流し読み => {
            let 区間 = 状態.表示するコマの求め().and_then(|求め| 求め.区間);
            流し読みの様子(動画, 区間)
        }
    }
}

fn 流し読みの様子(
    動画: &読み込んだ動画, 区間: Option<動画上の区間>
) -> ノード<応答> {
    let Some(区間) = 区間 else {
        return 文字表示("元動画を流し読みで再生中").into();
    };
    let 出す文 = match 動画.台帳().行の状態(&区間) {
        None => "区間を溜める依頼を待っている".to_string(),
        Some(行の状態::依頼中 { 進み具合, .. }) => match 進み具合 {
            依頼の進み具合::処理を待っている => {
                "区間を溜める順番を待っている".to_string()
            }
            依頼の進み具合::溜めている {
                溜めたコマ数,
                見込みのコマ数,
            } => {
                let 途中の文面 = format!(
                    "区間を溜めている {}/{}コマ(流し読みで再生中)",
                    溜めたコマ数.値(),
                    見込みのコマ数.値()
                );
                let 進み = f64::from(溜めたコマ数.値()) / f64::from(見込みのコマ数.値().max(1));
                let 棒 =
                    進捗バー(割合::倍精度の小数から範囲へ丸めて生成する(進み)).幅(画素(160.0));
                return 横並び(子![文字表示(途中の文面), 棒]).into();
            }
            依頼の進み具合::溜め終えた(_) => "区間を溜め終えた".to_string(),
        },
        Some(行の状態::終わった(結末)) => {
            format!("区間を溜められない: {}", 結末の文(結末))
        }
    };
    文字表示(format!("{出す文}(流し読みで再生中)")).into()
}

fn 結末の文(結末: &依頼の結末) -> String {
    match 結末 {
        依頼の結末::断られた(理由) => 受け付けない理由の文(理由),
        依頼の結末::倉庫が捨てた => "優先順の高い区間のために捨てた".to_string(),
        依頼の結末::取り消された => "依頼を取り消した".to_string(),
        依頼の結末::倉庫が覚えていない => "倉庫が依頼を覚えていない".to_string(),
        依頼の結末::失敗した(理由) => format!("デコードに失敗した: {理由}"),
    }
}

fn 受け付けない理由の文(理由: &受け付けない理由) -> String {
    let メガバイト = |大きさ: バイト数| 大きさ.値() / 1_000_000;
    match 理由 {
        受け付けない理由::区間にコマが無い => "区間にコマが無い".to_string(),
        受け付けない理由::上限の全体を超える {
            見積もり, 上限
        } => format!(
            "区間が大きすぎる(約{}MB。上限は約{}MB)",
            メガバイト(*見積もり),
            メガバイト(上限.大きさ())
        ),
        受け付けない理由::優先順の高い区間で埋まっている { .. } => {
            "優先順の高い区間でメモリが埋まっている".to_string()
        }
        受け付けない理由::裏のスレッドが止まっている => {
            "デコードの裏のスレッドが止まっている".to_string()
        }
    }
}
