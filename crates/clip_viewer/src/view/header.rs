//! ヘッダー。編集とシアターとライブラリの切り替えと、設定ファイルの読込と保存のボタンと、キーの一覧のダイアログを開く「キー設定」のボタン(F1 のキーを変えて忘れても開ける入口)と、
//! 編集の構えでは編集の取り消しとやり直しのボタンと、今のスタックのライブラリへの登録の様子と、最後に重ね合わせの作業場へ移る「同時再生」のボタン
//! (同時再生.md 2-1)を並べる。アプリの題名の文字は置かない(オーナーの裁定)。
//! 切り替えのボタンは、選ばれている方を移植元のモードボタンと同じ琥珀色の地と暗い文字で示す。
//! SengenEgui の選択ボタンは選ばれた面を強調色で塗り文字を明るい色で描くため、琥珀色の地では文字が読めない。

use sengen_egui::{
    スタイル, ノード, ボタン, ボタン型, 付け足せる, 子, 条件付き表示, 横並び
};

use crate::command::{クリップの操作, ファイルの操作, 出力の操作, 応答};
use crate::state::{アプリの状態, 画面の構え};
use crate::view::{keys, library, styles};
use crate::viewer_settings::キーで行う操作;

/// 構えを切り替えるボタン。今の構えと同じ構えのボタンを、選ばれた見た目にする。
fn 構えを切り替えるボタン(
    名前: &str,
    構え: 画面の構え,
    今の構え: 画面の構え,
) -> ボタン型<応答> {
    let 装飾 = if 構え == 今の構え {
        styles::強調ボタン
    } else {
        スタイル::無指定
    };
    ボタン(名前, 応答::出力(出力の操作::構えを選ぶ(構え))).装飾(装飾)
}

pub(crate) fn ヘッダー(状態: &アプリの状態) -> ノード<応答> {
    let 今の構え = 状態.出力.構え;
    横並び(子![
        構えを切り替えるボタン("編集", 画面の構え::編集, 今の構え),
        構えを切り替えるボタン("シアター", 画面の構え::シアター, 今の構え),
        構えを切り替えるボタン("ライブラリ", 画面の構え::ライブラリ, 今の構え),
        ボタン(
            "JSON読込",
            応答::ファイル(ファイルの操作::設定ファイルを読み込む)
        ),
        ボタン(
            "JSON保存",
            応答::ファイル(ファイルの操作::設定ファイルを保存する)
        )
        .装飾(styles::強調ボタン),
        ボタン("キー設定", 応答::出力(出力の操作::キーの一覧を開く)).説明(
            keys::操作のキーの表記(状態, キーで行う操作::キーの一覧を開け閉めする)
        ),
        条件付き表示(今の構え == 画面の構え::編集, || {
            取り消しとやり直し(状態)
        }),
        library::ヘッダーのライブラリの様子(状態),
        // 注意: 「同時再生」は後から足したボタンなので最後に置く。間に挟むと、前からある部品(取り消す・やり直す・ライブラリの様子)が右へずれ、
        // 狭いウインドウで右端の部品がはみ出す範囲が広がるためである(view/header_width_tests.rs)。
        ボタン("同時再生", 応答::重ね合わせの作業場へ移る)
            .説明("今のスタックのクリップを並べて同時に再生する作業場へ移る"),
    ])
    .into()
}

/// 編集の取り消しとやり直しのボタン。取り消せる・やり直せる編集が無ければ押せない。キーの割り当ては説明に出す。
fn 取り消しとやり直し(状態: &アプリの状態) -> ノード<応答> {
    横並び(子![
        ボタン("取り消す", 応答::クリップ(クリップの操作::編集を取り消す))
            .有効(状態.取り消せるか())
            .説明(keys::操作のキーの表記(
                状態,
                キーで行う操作::編集を取り消す
            )),
        ボタン("やり直す", 応答::クリップ(クリップの操作::編集をやり直す))
            .有効(状態.やり直せるか())
            .説明(keys::操作のキーの表記(
                状態,
                キーで行う操作::編集をやり直す
            )),
    ])
    .into()
}
