//! ヘッダーの「キー設定」と「同時再生」のボタンの試験。「キー設定」は編集の構えとライブラリの構えのヘッダーに出て、押すとキーの一覧を開く応答を発し、
//! その応答はキーの一覧のダイアログを開くことを確かめる(F1 のキーを変えて忘れても、マウスでダイアログを開ける入口である)。
//! 「同時再生」は同じ2つの構えのヘッダーに出て、押すと重ね合わせの作業場へ移る応答を発することを確かめる
//! (その応答を配線が受け取って作業場を移すことは `app/workspace/overlay_tests.rs` が確かめる。同時再生.md 3-2)。

use eframe::egui;

use super::header::ヘッダー;
use super::test_support::{
    動画の無い状態, 大きさを決めて描く, 押して集める, 描いた文字の範囲
};
use crate::command::{出力の操作, 応答};
use crate::state::画面の構え;

const 画面の大きさ: egui::Vec2 = egui::vec2(1200.0, 620.0);

#[test]
fn 編集とライブラリの構えのキー設定のボタンを押すとキーの一覧が開く() {
    for 構え in [画面の構え::編集, 画面の構え::ライブラリ] {
        let mut 状態 = 動画の無い状態(構え);
        let 画面描画の共有状態 = egui::Context::default();
        let 木 = || ヘッダー(&状態);
        let (_, 出力) =
            大きさを決めて描く(&画面描画の共有状態, 画面の大きさ, Vec::new(), &木);
        let 位置 = 描いた文字の範囲(&出力, "キー設定").center();
        let 集めた = 押して集める(&画面描画の共有状態, 画面の大きさ, 位置, &木);
        let 開く = 応答::出力(出力の操作::キーの一覧を開く);
        assert_eq!(集めた, std::slice::from_ref(&開く), "{構え:?}");
        状態.出力の操作を適用する(出力の操作::キーの一覧を開く);
        assert!(状態.キーの一覧.開いているか(), "{構え:?}");
        状態.出力の操作を適用する(出力の操作::キーの一覧を開く);
        assert!(
            状態.キーの一覧.開いているか(),
            "開いているときに押しても閉じない"
        );
    }
}

#[test]
fn 編集とライブラリの構えの同時再生のボタンは重ね合わせの作業場へ移る応答を発する() {
    for 構え in [画面の構え::編集, 画面の構え::ライブラリ] {
        let 状態 = 動画の無い状態(構え);
        let 画面描画の共有状態 = egui::Context::default();
        let 木 = || ヘッダー(&状態);
        let (_, 出力) =
            大きさを決めて描く(&画面描画の共有状態, 画面の大きさ, Vec::new(), &木);
        let 位置 = 描いた文字の範囲(&出力, "同時再生").center();
        let 集めた = 押して集める(&画面描画の共有状態, 画面の大きさ, 位置, &木);
        assert_eq!(集めた, [応答::重ね合わせの作業場へ移る], "{構え:?}");
    }
}
