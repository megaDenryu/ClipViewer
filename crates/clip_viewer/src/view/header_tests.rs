//! ヘッダーの「キー設定」のボタンの試験。編集の構えとライブラリの構えのヘッダーに出て、押すとキーの一覧を開く応答を発し、
//! その応答はキーの一覧のダイアログを開くことを確かめる(F1 のキーを変えて忘れても、マウスでダイアログを開ける入口である)。

use eframe::egui;

use super::header::ヘッダー;
use super::test_support::{
    動画の無い状態, 大きさを決めて描く, 押して集める, 描いた文字の範囲
};
use crate::command::{出力の操作, 応答};
use crate::state::画面の構え;

const 画面の大きさ: egui::Vec2 = egui::vec2(1200.0, 620.0);

#[test]
fn 編集とライブラリの構えのキー設定のボタンを押すとキーの一覧が開く() {
    for 構え in [画面の構え::編集, 画面の構え::ライブラリ] {
        let mut 状態 = 動画の無い状態(構え);
        let eguiの本体 = egui::Context::default();
        let 木 = || ヘッダー(&状態);
        let (_, 出力) = 大きさを決めて描く(&eguiの本体, 画面の大きさ, Vec::new(), &木);
        let 位置 = 描いた文字の範囲(&出力, "キー設定").center();
        let 集めた = 押して集める(&eguiの本体, 画面の大きさ, 位置, &木);
        let 開く = 応答::出力(出力の操作::キーの一覧を開く);
        assert_eq!(集めた, std::slice::from_ref(&開く), "{構え:?}");
        状態.出力の操作を適用する(出力の操作::キーの一覧を開く);
        assert!(状態.キーの一覧.開いているか(), "{構え:?}");
        状態.出力の操作を適用する(出力の操作::キーの一覧を開く);
        assert!(
            状態.キーの一覧.開いているか(),
            "開いているときに押しても閉じない"
        );
    }
}
