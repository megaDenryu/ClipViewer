use sengen_egui::{
    ノード, パネル, パネルの位置, 一定時間で消える通知の並び, 子, 条件付き表示, 画素, 積み型,
    縦積み,
};

use crate::command::応答;
use crate::state::{アプリの状態, 画面の構え};

pub(crate) use invisible::描き直すまでの時間;

pub(crate) fn 画面(状態: &アプリの状態) -> ノード<応答> {
    let 構え = 状態.出力.構え;
    let 区画 = match 構え {
        画面の構え::ライブラリ => {
            縦積み(子![ヘッダーの区画(状態), library::ライブラリの区画(状態)])
        }
        画面の構え::編集 | 画面の構え::シアター => 再生の区画(状態, 構え),
    };
    縦積み(子![
        invisible::見えない部品(状態),
        区画,
        library::開いているダイアログ(状態),
        keys::キーの一覧を出すダイアログ(状態),
        一定時間で消える通知の並び("通知", 状態.通知.並べる通知()),
    ])
    .into()
}

/// 編集とシアターの構えの区画。編集の構えでは上にヘッダー、下に再生コントロール、左にサイドバー、中央に出力を置く。
/// シアターでは出力だけを置き、出力がウインドウ全体を使う。
fn 再生の区画(状態: &アプリの状態, 構え: 画面の構え) -> 積み型<応答> {
    let 編集の構えか = 構え == 画面の構え::編集;
    縦積み(子![
        条件付き表示(編集の構えか, || ヘッダーの区画(状態)),
        条件付き表示(編集の構えか, || パネル(
            "再生コントロール",
            パネルの位置::下,
            子![control::再生コントロール(状態)]
        )
        .装飾(styles::再生コントロールの地)),
        条件付き表示(編集の構えか, || 左サイドバーの区画(状態)),
        output::出力の区画(状態),
    ])
}

fn ヘッダーの区画(状態: &アプリの状態) -> ノード<応答> {
    パネル(
        "ヘッダー",
        パネルの位置::上,
        子![
            header::ヘッダー(状態),
            ffmpeg_setup::ffmpegの置き場所の欄(状態)
        ],
    )
    .装飾(styles::ヘッダーの地)
    .into()
}

/// 左サイドバーは、移植元の最小幅と同じ480論理画素で始め、縁のドラッグで移植元の幅の範囲(480〜610論理画素)の中で変えられる。
/// 移植元のウインドウの幅の42%に合わせる規則は、幅を人がドラッグで決めるため写さない。
/// プレビューはその時の幅に合わせて大きさを決める(sidebar/preview.rs)。
fn 左サイドバーの区画(状態: &アプリの状態) -> ノード<応答> {
    左サイドバーのパネル(sidebar::左サイドバー(状態))
}

/// 左サイドバーのパネル。中身を包み、幅の既定と範囲と地を決める。サイドバーの幅の試験も同じパネルで描く。
fn 左サイドバーのパネル(中身: ノード<応答>) -> ノード<応答> {
    パネル("左サイドバー", パネルの位置::左, 子![中身])
        .既定の幅(画素(480.0))
        .幅の範囲(画素(480.0), 画素(610.0))
        .大きさを変えられる(true)
        .装飾(styles::左サイドバーの地)
        .into()
}
