//! トリガー待ちの案内の文の試験。既定のキーでは説明書5.9節の文になり、キーを変えると、進めるキーの表記が今のキーになり、
//! 再生と停止が Space を持たなければ「Space は再生と停止に使う」の補足を出さないことを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::トリガー;
use sengen_egui::{キー, キーの組};

use super::text::トリガー待ちの案内;
use crate::viewer_settings::{キーで行う操作, キーの割り当て};

#[test]
fn 既定のキーでは説明書の案内の文になる() {
    let 既定 = キーの割り当て::既定();
    assert_eq!(
        トリガー待ちの案内(トリガー::Enterキー待ち, &既定),
        "Enterキーを押すか、Nextボタンで進めてください"
    );
    assert_eq!(
        トリガー待ちの案内(トリガー::Spaceキー待ち, &既定),
        "Space待ちは Enterキーで進む(Space は再生と停止に使う)。Enterキーを押すか、Nextボタンで進めてください"
    );
}

#[test]
fn キーを変えると今のキーで案内し_再生と停止がspaceでなければ補足を出さない() {
    let 割り当て = キーの割り当て::既定()
        .キーを変えた(
            キーで行う操作::シーケンス再生のときだけ次のクリップへ進める,
            キーの組::単独(キー::F2),
        )
        .and_then(|割り当て| {
            割り当て.キーを変えた(
                キーで行う操作::再生と停止を切り替える,
                キーの組::単独(キー::K),
            )
        })
        .expect("空いたキーへは変えられる");
    assert_eq!(
        トリガー待ちの案内(トリガー::Enterキー待ち, &割り当て),
        "F2キーを押すか、Nextボタンで進めてください"
    );
    assert_eq!(
        トリガー待ちの案内(トリガー::Spaceキー待ち, &割り当て),
        "Space待ちは F2キーで進む。F2キーを押すか、Nextボタンで進めてください"
    );
}
