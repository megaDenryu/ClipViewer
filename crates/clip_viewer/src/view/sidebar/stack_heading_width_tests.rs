//! スタックの欄の見出しの行の幅の試験。見出しの行には「Modifier Stack」と「新規Clipを追加」と「新しいスタックを始める」が並ぶ。
//! 画面と同じ左サイドバーのパネル(既定の幅480論理画素)に左サイドバーの全体を描き、見出しの行がはみ出してパネルを広げないことを確かめる。
//! 参照: 日本語フォントを当てる理由は `view/test_support.rs` の `日本語フォントとテーマを当てた本体を作る`

use eframe::egui;

use super::左サイドバー;
use crate::state::画面の構え;
use crate::view::test_support::{
    サイドバーのパネルの幅, 動画の無い状態, 日本語フォントとテーマを当てた本体を作る,
};
use crate::view::左サイドバーのパネル;

#[test]
fn スタックの欄の見出しの行は最小の幅のサイドバーに収まる() {
    let 画面描画の共有状態 = 日本語フォントとテーマを当てた本体を作る();
    let 状態 = 動画の無い状態(画面の構え::編集);
    for 回 in 0..2 {
        let _ = 画面描画の共有状態.run(egui::RawInput::default(), |画面描画の共有状態| {
            egui::CentralPanel::default().show(画面描画の共有状態, |ui| {
                let _ = 左サイドバーのパネル(左サイドバー(&状態)).描画して集める(ui);
            });
        });
        assert_eq!(
            サイドバーのパネルの幅(&画面描画の共有状態),
            480.0,
            "{回}回目"
        );
    }
}
