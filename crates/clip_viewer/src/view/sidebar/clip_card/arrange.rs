//! クリップカードの並べ替えと今の位置の行。並びの中で前へ・後ろへ動かすボタンと複製のボタンと、
//! 区間の開始か終了を今見ている位置に合わせるボタンを1行に並べる。参照: _doc/設計/画面.md 判断14

use clip_domain::クリップ識別子;
use sengen_egui::{ノード, ボタン, 付け足せる, 子, 横並び};

use super::カードの様子;
use crate::command::{クリップの操作, 動かす向き, 区間の端, 応答};

fn クリップ(操作: クリップの操作) -> 応答 {
    応答::クリップ(操作)
}

/// 前へ(↑)・後ろへ(↓)・複製・開始を今の位置に・終了を今の位置にの行。先頭は前へ、末尾は後ろへ動かせない。
pub(super) fn 並べ替えと今の位置の行(
    識別子: &クリップ識別子,
    様子: &カードの様子,
) -> ノード<応答> {
    let 動かす = |向き| {
        クリップ(クリップの操作::並びで動かす(
            識別子.clone(),
            向き,
        ))
    };
    let 今の位置へ = |端| {
        クリップ(クリップの操作::区間の端を今の位置にする(
            識別子.clone(),
            端,
        ))
    };
    横並び(子![
        ボタン("↑", 動かす(動かす向き::前へ))
            .小さい()
            .有効(様子.前へ動かせるか)
            .説明("並びの1つ前へ動かす"),
        ボタン("↓", 動かす(動かす向き::後ろへ))
            .小さい()
            .有効(様子.後ろへ動かせるか)
            .説明("並びの1つ後ろへ動かす"),
        ボタン("複製", クリップ(クリップの操作::複製する(識別子.clone()))).小さい(),
        ボタン("開始を今の位置に", 今の位置へ(区間の端::開始))
            .小さい()
            .説明("今見ている位置を区間の開始にする(選択中のクリップは I キー)"),
        ボタン("終了を今の位置に", 今の位置へ(区間の端::終了))
            .小さい()
            .説明("今見ている位置を区間の終了にする(選択中のクリップは O キー)"),
    ])
    .into()
}
