//! 区間の数値の行の幅の試験。開始の行と終了の行を描き、サイドバーの最小の幅(480論理画素)からカードの縁と余白を引いた幅に収まることを確かめる。
//! 注意: 試験の egui は日本語のフォントを持たないため、「開始:」の3文字は代わりの字の幅で測る。ボタンと数値は英数字なので本物の幅である。

use clip_domain::{クリップ識別子, 動画上の区間, 動画上の秒};
use eframe::egui;

use super::span::区間の調整の行;

/// カードの中身に使える幅の上限。サイドバーの最小の幅480論理画素から、パネルとカードの縁と余白、縦のスクロールバーの分として80論理画素を引いた。
const カードの中身に使える幅: f32 = 400.0;

fn 描いた幅(開始: f64, 終了: f64) -> f32 {
    let 識別子 = クリップ識別子::文字列から作成する("甲".to_string())
        .unwrap_or_else(|不正| panic!("識別子が不正: {不正}"));
    let 秒 = |値| 動画上の秒::作成する(値).unwrap_or_else(|不正| panic!("秒が不正: {不正}"));
    let 区間 = 動画上の区間::作成する(秒(開始), 秒(終了))
        .unwrap_or_else(|不正| panic!("区間が不正: {不正}"));
    let eguiの本体 = egui::Context::default();
    let mut 幅 = 0.0;
    let _ = eguiの本体.run(egui::RawInput::default(), |eguiの本体| {
        egui::SidePanel::left("試験").show(eguiの本体, |ui| {
            let 始め = ui.cursor().min.x;
            let _ = 区間の調整の行(&識別子, 区間).描画して集める(ui);
            幅 = ui.min_rect().max.x - 始め;
        });
    });
    幅
}

#[test]
fn 開始と終了の行はサイドバーの最小の幅に収まる() {
    let 幅 = 描いた幅(3599.95, 3600.0);
    assert!(幅 <= カードの中身に使える幅, "描いた幅: {幅}");
}
