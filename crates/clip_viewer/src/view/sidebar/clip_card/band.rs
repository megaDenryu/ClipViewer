//! クリップカードの区間の帯。全体の帯と拡大の帯を縦に並べる。操作を応答へ写すのは `band_response.rs` である。
//! 帯の値の単位は動画上の秒である。参照: _doc/設計/画面.md 判断11

use clip_domain::{クリップ識別子, 動画上の区間, 動画上の秒};
use sengen_egui::{
    ノード, 区間の帯, 子, 帯の値, 帯の全体の範囲, 文字表示, 条件付き表示, 縦積み
};

use super::band_response::区間の帯の操作から応答を作る;
use crate::command::応答;
use crate::state::{カードの区間の帯に描く値, 区間の帯の種類};
use crate::styles;

fn 帯の値へ写す(秒: 動画上の秒) -> 帯の値 {
    帯の値::倍精度の小数から生成する(秒.秒数())
}

/// 範囲を全体とする1本の区間の帯を組む。範囲が帯にできない(長さ0)ときは、その理由を出す。
fn 区間の帯を組む(
    識別子: &クリップ識別子,
    帯: 区間の帯の種類,
    範囲: 動画上の区間,
    区間: 動画上の区間,
    位置: Option<動画上の秒>,
) -> ノード<応答> {
    let 全体 = match 帯の全体の範囲::生成する(
        帯の値へ写す(範囲.開始()),
        帯の値へ写す(範囲.終了()),
    ) {
        Ok(全体) => 全体,
        Err(不正) => {
            return 文字表示(format!("区間の帯を描けない: {不正}"))
                .装飾(styles::不備の文)
                .into();
        }
    };
    let 識別子 = 識別子.clone();
    let 組んだ区間の帯 = 区間の帯(
        全体,
        帯の値へ写す(区間.開始()),
        帯の値へ写す(区間.終了()),
        move |操作| 区間の帯の操作から応答を作る(&識別子, 帯, 操作),
    )
    .装飾(styles::区間の帯);
    match 位置 {
        Some(位置) => 組んだ区間の帯.位置(帯の値へ写す(位置)).into(),
        None => 組んだ区間の帯.into(),
    }
}

/// 全体の帯と、拡大の帯(範囲が全体と違うときだけ。上に範囲の秒数を添える)を縦に並べる。
pub(super) fn 区間の帯の欄(
    識別子: &クリップ識別子,
    値: &カードの区間の帯に描く値,
) -> ノード<応答> {
    let 拡大 = 値.拡大の範囲;
    let 全体 = 値.全体の範囲;
    縦積み(子![
        条件付き表示(値.区間が動画の外にあるか, || {
            文字表示(format!(
                "区間({:.2}〜{:.2}秒)が動画の終わり({:.2}秒)より後ろまである。区間の帯の端の三角は範囲の外を指す。区間を動画の中へ収める",
                値.区間.開始().秒数(),
                値.区間.終了().秒数(),
                全体.終了().秒数()
            ))
            .装飾(styles::不備の文)
        }),
        区間の帯を組む(識別子, 区間の帯の種類::全体の帯, 全体, 値.区間, 値.位置),
        条件付き表示(値.拡大の帯を出すか(), || {
            縦積み(子![
                文字表示(format!(
                    "拡大 {:.2}〜{:.2}秒",
                    拡大.開始().秒数(),
                    拡大.終了().秒数()
                ))
                .装飾(styles::補足),
                区間の帯を組む(
                    識別子,
                    区間の帯の種類::拡大の帯,
                    拡大,
                    値.区間,
                    値.拡大の帯の位置(),
                ),
            ])
        }),
    ])
    .into()
}
