//! 区間の帯の操作の写し。SengenEgui の区間の帯が発する操作(部品の語彙)を、クリップの操作の応答(操作コマンドの語彙)へ写す。
//! 値は動画上の秒の倍精度の小数のまま運び、収め方は状態の側(`区間の編集の決まり`)が持つ。
//! 位置を渡していない区間の帯(選ばれていないカード)の区間の外を押したときは、値を捨てて段階だけを運ぶ。

use clip_domain::クリップ識別子;
use sengen_egui::{区間の帯の掴んだもの, 区間の帯の操作};

use crate::command::{
    クリップの区間の帯の操作, クリップの操作, 区間の帯の段階, 応答
};
use crate::state::{区間の帯で掴んだもの, 区間の帯の種類};

/// 区間の帯の操作を、そのクリップの区間の帯の操作の応答へ写す。
pub(super) fn 区間の帯の操作から応答を作る(
    識別子: &クリップ識別子,
    帯: 区間の帯の種類,
    操作: 区間の帯の操作,
) -> 応答 {
    let (段階, 掴んだもの, 値) = match 操作 {
        区間の帯の操作::掴み始めた {
            掴んだもの, 値
        } => (区間の帯の段階::掴み始めた, 掴んだもの, 値),
        区間の帯の操作::動かしている {
            掴んだもの, 値
        } => (区間の帯の段階::動かしている, 掴んだもの, 値),
        区間の帯の操作::放した {
            掴んだもの, 値
        } => (区間の帯の段階::放した, 掴んだもの, 値),
    };
    let 掴んだもの = match 掴んだもの {
        区間の帯の掴んだもの::開始のつまみ => {
            区間の帯で掴んだもの::開始のつまみ
        }
        区間の帯の掴んだもの::終了のつまみ => {
            区間の帯で掴んだもの::終了のつまみ
        }
        区間の帯の掴んだもの::区間の内側 => {
            区間の帯で掴んだもの::区間の内側
        }
        区間の帯の掴んだもの::位置の印 => {
            区間の帯で掴んだもの::位置の印
        }
        区間の帯の掴んだもの::区間の外 => {
            let 押した =
                クリップの操作::区間の帯の区間の外を押す(識別子.clone(), 段階);
            return 応答::クリップ(押した);
        }
    };
    let 操作 = クリップの区間の帯の操作 {
        帯,
        段階,
        掴んだもの,
        秒: 値.倍精度の小数にする(),
    };
    応答::クリップ(クリップの操作::区間の帯を操作する(
        識別子.clone(),
        操作,
    ))
}
