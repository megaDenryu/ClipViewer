/// このクリップへの編集の応答。
fn 編集の応答(識別子: &クリップ識別子, 編集: クリップの編集) -> 応答 {
    応答::クリップ(クリップの操作::編集する(識別子.clone(), 編集))
}

/// 部品が渡す値から、このクリップへの編集の応答を作る手続き。部品の閉包へ所有させるため識別子を写して持つ。
fn 編集の写像<値: 'static>(
    識別子: &クリップ識別子,
    編集を作る: fn(値) -> クリップの編集,
) -> impl Fn(値) -> 応答 + 'static {
    let 識別子 = 識別子.clone();
    move |値| 編集の応答(&識別子, 編集を作る(値))
}

/// カードの様子とは、カードを組むときに状態から受け取る、選ばれているか・区間の帯に描く値・単独で再生しているか・
/// 並びの中で前と後ろへ動かせるかの組のことである。
pub(crate) struct カードの様子 {
    pub(crate) 選ばれているか: bool,
    pub(crate) 区間の帯に描く値: カードの区間の帯に描く値,
    pub(crate) 単独で再生しているか: bool,
    pub(crate) 前へ動かせるか: bool,
    pub(crate) 後ろへ動かせるか: bool,
}

/// カードを組む。
pub(crate) fn クリップカード(
    クリップ: &クリップ, 様子: &カードの様子
) -> ノード<応答> {
    let 装飾 = if 様子.選ばれているか {
        styles::選ばれた札
    } else {
        styles::札
    };
    let 識別子 = クリップ.識別子();
    let 選ぶ = 応答::クリップ(クリップの操作::選ぶ(識別子.clone()));
    縦積み(子![
        見出しの行(クリップ, 様子.単独で再生しているか),
        arrange::並べ替えと今の位置の行(識別子, 様子),
        band::区間の帯の欄(識別子, &様子.区間の帯に描く値),
        span::区間の調整の行(識別子, 様子.区間の帯に描く値.区間),
        repeat::繰り返しとトリガーの行(クリップ),
    ])
    .装飾(装飾)
    .押されたら発する(選ぶ)
}

/// 名前の欄の枠の内側の幅の下限(オーナーの決定)。サイドバーが最小の幅(480論理画素)でも、見出しの行はこの下限でサイドバーに収まる(`card_width_tests.rs`)。
const 名前の欄の最小幅: 論理画素 = 画素(120.0);

/// 有効・名前・「このクリップを再生」(再生中は「単独再生を止める」)・「先頭へ」・削除の行。
fn 見出しの行(
    クリップ: &クリップ, 単独で再生しているか: bool
) -> ノード<応答> {
    let 識別子 = クリップ.識別子();
    let 開始へ移る = 応答::クリップ(クリップの操作::開始へ移る(識別子.clone()));
    let 削除する = 応答::クリップ(クリップの操作::削除する(識別子.clone()));
    let 単独再生 = 応答::クリップ(クリップの操作::単独再生を切り替える(
        識別子.clone(),
    ));
    let 単独再生のボタン = if 単独で再生しているか {
        ボタン("単独再生を止める", 単独再生).装飾(styles::強調ボタン)
    } else {
        ボタン("このクリップを再生", 単独再生)
    };
    // 名前の欄(1番目の子)に、後ろの3つのボタンを置いた残りの幅を渡す。子は左から右へ描くため、Tab キーの順も見えている並びと同じになる。
    横並び(子![
        チェックボックス(
            "有効",
            クリップ.有効か,
            編集の写像(識別子, クリップの編集::有効を切り替える)
        ),
        一行テキスト入力(
            クリップ.名前.文字列(),
            編集の写像(識別子, クリップの編集::名前を変える)
        )
        .確定時のみ発行(format!("クリップの名前_{識別子}"))
        .幅いっぱい()
        .最小幅(名前の欄の最小幅),
        単独再生のボタン,
        ボタン("先頭へ", 開始へ移る).小さい(),
        ボタン("削除", 削除する).装飾(styles::危険ボタン),
    ])
    .残りの幅を渡す(1)
    .into()
}
