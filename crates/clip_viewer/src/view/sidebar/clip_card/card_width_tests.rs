//! カードの幅の試験。日本語フォントと画面のテーマを当てたカードを描き、サイドバーの最小の幅(480論理画素)から
//! サイドバーの内余白(左右12論理画素ずつ)を引いた幅に収まることを確かめる。
//! 注意: OS に日本語フォントが無いと日本語の字が幅0で描かれ、試験は実際より狭く測る。開発機と CI の Windows には游ゴシックかメイリオがある。

use clip_domain::{
    クリップ, クリップ名, クリップ識別子, 動画上の区間, 動画上の秒
};
use eframe::egui;
use sengen_egui::日本語フォントの候補;

use super::{カードの様子, クリップカード};
use crate::state::カードの区間の帯に描く値;
use crate::view::styles;

/// サイドバーの中身に使える幅(480 - 12 × 2)。
const サイドバーの中身の幅: f32 = 456.0;

/// 日本語フォントとテーマを当て、カードを描いた幅を測る。フォントは次のフレームから効くため2回描く。
fn カードを描いた幅(クリップ: &クリップ, 様子: &カードの様子) -> f32 {
    let eguiの本体 = egui::Context::default();
    let _ = 日本語フォントの候補::標準で入っている候補()
        .最初に読めたものを設定する(&eguiの本体);
    styles::画面のテーマ.適用する(&eguiの本体);
    let mut 幅 = 0.0;
    for _ in 0..2 {
        let _ = eguiの本体.run(egui::RawInput::default(), |eguiの本体| {
            egui::SidePanel::left("試験").show(eguiの本体, |ui| {
                let 始め = ui.cursor().min.x;
                let _ = クリップカード(クリップ, 様子).描画して集める(ui);
                幅 = ui.min_rect().max.x - 始め;
            });
        });
    }
    幅
}

fn 長い数値の区間() -> 動画上の区間 {
    let 秒 = |値| 動画上の秒::作成する(値).unwrap_or_else(|不正| panic!("秒が不正: {不正}"));
    動画上の区間::作成する(秒(3599.95), 秒(3600.0))
        .unwrap_or_else(|不正| panic!("区間が不正: {不正}"))
}

#[test]
fn カードはどの行もサイドバーの最小の幅に収まる() {
    let 識別子 = クリップ識別子::文字列から作成する("甲".to_string())
        .unwrap_or_else(|不正| panic!("識別子が不正: {不正}"));
    let 名前 = クリップ名::作成する("Clip Mod 12 のコピー".to_string());
    let クリップ = クリップ::既定値で作成する(識別子, 名前);
    let 区間 = 長い数値の区間();
    for 単独で再生しているか in [false, true] {
        let 様子 = カードの様子 {
            選ばれているか: true,
            区間の帯に描く値: カードの区間の帯に描く値 {
                全体の範囲: 区間,
                拡大の範囲: 区間,
                区間,
                位置: None,
                区間が動画の外にあるか: false,
            },
            単独で再生しているか,
            前へ動かせるか: true,
            後ろへ動かせるか: true,
        };
        let 幅 = カードを描いた幅(&クリップ, &様子);
        assert!(幅 <= サイドバーの中身の幅, "描いた幅: {幅}");
    }
}
