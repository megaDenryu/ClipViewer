//! カードの幅の試験。日本語フォントと画面のテーマを当てたカードを、サイドバーの中身に使える幅(サイドバーの幅から
//! 内余白の左右12論理画素ずつを引いた幅)の中に描き、次のことを確かめる。サイドバーが最小の幅(480論理画素)のとき、
//! カードはどの行もその幅に収まり、見出しの行の部品は重ならず、名前の欄は枠の内側が120論理画素以上ある。
//! サイドバーを最大の幅(610論理画素)へ広げると、名前の欄は広げた幅の分だけ広がる。
//! 見出しの行の部品は左から右の順に記録される(egui は記録した順に Tab キーでフォーカスを移すため、Tab の順が見えている並びと同じになる)。
//! 注意: 日本語フォントが無いと日本語の字が幅0で描かれ、実際より狭く測って通ってしまうため、OS の日本語フォントを読めなければ試験を失敗させる。

use clip_domain::{動画上の区間, 動画上の秒};

use super::card_measure::{
    カードを描いて測る, 内余白の左右, 名前の欄の余白の左右
};
use super::カードの様子;
use crate::state::カードの区間の帯に描く値;

fn 様子(単独で再生しているか: bool) -> カードの様子 {
    let 秒 = |値| 動画上の秒::作成する(値).unwrap_or_else(|不正| panic!("秒が不正: {不正}"));
    let 区間 = 動画上の区間::作成する(秒(3599.95), 秒(3600.0))
        .unwrap_or_else(|不正| panic!("区間が不正: {不正}"));
    カードの様子 {
        選ばれているか: true,
        区間の帯に描く値: カードの区間の帯に描く値 {
            全体の範囲: 区間,
            拡大の範囲: 区間,
            区間,
            位置: None,
            区間が動画の外にあるか: false,
        },
        単独で再生しているか,
        前へ動かせるか: true,
        後ろへ動かせるか: true,
    }
}

#[test]
fn サイドバーが最小の幅のときカードは収まり見出しの行の部品は重ならず名前の欄は120論理画素以上ある()
{
    for 単独で再生しているか in [false, true] {
        let 描いた = カードを描いて測る(480.0, &様子(単独で再生しているか));
        assert!(描いた.幅 <= 480.0 - 内余白の左右, "描いた幅: {}", 描いた.幅);
        assert_eq!(
            描いた.見出しの行の部品.len(),
            5,
            "{:?}",
            描いた.見出しの行の部品
        );
        for 隣 in 描いた.見出しの行の部品.windows(2) {
            assert!(隣[0].right() <= 隣[1].left(), "重なっている: {隣:?}");
        }
        assert!(
            描いた.名前の欄.width() - 名前の欄の余白の左右 >= 120.0,
            "{:?}",
            描いた.名前の欄
        );
    }
}

#[test]
fn サイドバーを広げると名前の欄は広げた幅の分だけ広がる() {
    for 単独で再生しているか in [false, true] {
        let 最小 = カードを描いて測る(480.0, &様子(単独で再生しているか))
            .名前の欄
            .width();
        let 最大 = カードを描いて測る(610.0, &様子(単独で再生しているか))
            .名前の欄
            .width();
        assert!(
            (最大 - 最小 - 130.0).abs() < 0.5,
            "最小: {最小} 最大: {最大}"
        );
    }
}

#[test]
fn 見出しの行の部品は左から右の順に記録されtabの順が見えている並びと同じになる() {
    let 描いた = カードを描いて測る(480.0, &様子(false));
    let 左端: Vec<f32> = 描いた
        .見出しの行の部品
        .iter()
        .map(|矩形| 矩形.left())
        .collect();
    assert!(左端.windows(2).all(|隣| 隣[0] < 隣[1]), "{左端:?}");
}
