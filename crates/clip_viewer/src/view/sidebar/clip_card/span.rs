//! クリップカードの区間の数値の行。開始と終了のそれぞれに、端の名前・前へずらすボタン・秒の数値入力・後ろへずらすボタンの行を組み、
//! 区間の帯の下に開始の行、終了の行の順に置く。8つのボタンと2つの数値入力を1行に並べるとサイドバーの最小の幅(480論理画素)に収まらないため、端ごとに1行へ分ける。

use clip_domain::{クリップ識別子, 動画上の区間};
use sengen_egui::{
    ノード, ボタン, 付け足せる, 子, 数値入力, 文字表示, 横並び, 縦積み
};

use super::{編集の写像, 編集の応答};
use crate::command::{
    クリップの操作, クリップの編集, 区間の端, 応答, 端のずらし方
};

/// 数値入力の刻み(移植元と同じ0.05秒)。
const 秒の刻み: f64 = 0.05;

fn 開始を決める(秒: f64) -> クリップの編集 {
    クリップの編集::区間の端を決める(区間の端::開始, 秒)
}

fn 終了を決める(秒: f64) -> クリップの編集 {
    クリップの編集::区間の端を決める(区間の端::終了, 秒)
}

/// 数値入力のドラッグを放したか直接入力を確定した。編集の履歴が、ドラッグや打鍵の間の変化を1つにまとめる区切りにする。
fn 操作を終えた(_秒: f64) -> 応答 {
    応答::クリップ(クリップの操作::続けて変える操作を終えた)
}

/// 開始の行と終了の行を縦に並べる。
/// 秒は帯に描く区間(区間の帯のドラッグの間は仮の区間)で出し、帯と数値が同じ値を示すようにする。
pub(super) fn 区間の調整の行(
    識別子: &クリップ識別子,
    区間: 動画上の区間,
) -> ノード<応答> {
    縦積み(子![
        端の調整の行(識別子, 区間の端::開始, 区間.開始().秒数()),
        端の調整の行(識別子, 区間の端::終了, 区間.終了().秒数()),
    ])
    .into()
}

/// 1つの端の行。端の名前、前へずらす2つのボタン、秒の数値入力、後ろへずらす2つのボタンを並べる。
fn 端の調整の行(
    識別子: &クリップ識別子, 端: 区間の端, 秒: f64
) -> ノード<応答> {
    let (端の名前, 秒を決める): (&str, fn(f64) -> クリップの編集) = match 端 {
        区間の端::開始 => ("開始", 開始を決める),
        区間の端::終了 => ("終了", 終了を決める),
    };
    let ずらすボタン = |文字: &str, ずらし方, 説明: &str| {
        ボタン(
            文字,
            編集の応答(識別子, クリップの編集::区間の端をずらす(端, ずらし方)),
        )
        .小さい()
        .説明(format!("{端の名前}を{説明}"))
    };
    横並び(子![
        文字表示(format!("{端の名前}:")),
        ずらすボタン("-0.5s", 端のずらし方::半秒戻す, "0.5秒前へ"),
        ずらすボタン("< F", 端のずらし方::一コマ戻す, "1コマ前へ"),
        数値入力(秒, 0.0..=f64::MAX, 編集の写像(識別子, 秒を決める))
            .刻み(秒の刻み)
            .小数点以下の桁数(2)
            .操作を終えたら発する(操作を終えた),
        ずらすボタン("F >", 端のずらし方::一コマ進める, "1コマ後ろへ"),
        ずらすボタン("+0.5s", 端のずらし方::半秒進める, "0.5秒後ろへ"),
    ])
    .into()
}
