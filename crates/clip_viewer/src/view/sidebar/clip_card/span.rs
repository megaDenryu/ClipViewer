//! クリップカードの区間の数値の行。ずらすボタンと秒の数値入力を1行に並べ、区間の帯の下に置く。

use clip_domain::{クリップ識別子, 動画上の区間};
use sengen_egui::{ノード, ボタン, 子, 数値入力, 文字表示, 横並び};

use super::{編集の写像, 編集の応答};
use crate::command::{
    クリップの操作, クリップの編集, 区間の端, 応答, 端のずらし方
};

/// 数値入力の刻み(移植元と同じ0.05秒)。
const 秒の刻み: f64 = 0.05;

fn 開始を決める(秒: f64) -> クリップの編集 {
    クリップの編集::区間の端を決める(区間の端::開始, 秒)
}

fn 終了を決める(秒: f64) -> クリップの編集 {
    クリップの編集::区間の端を決める(区間の端::終了, 秒)
}

/// 数値入力のドラッグを放したか直接入力を確定した。編集の履歴が、ドラッグや打鍵の間の変化を1つにまとめる区切りにする。
fn 操作を終えた(_秒: f64) -> 応答 {
    応答::クリップ(クリップの操作::続けて変える操作を終えた)
}

/// 開始を戻すボタン・開始と終了の数値入力・終了を進めるボタンの行(移植元と同じ並び)。
/// 秒は帯に描く区間(区間の帯のドラッグの間は仮の区間)で出し、帯と数値が同じ値を示すようにする。
pub(super) fn 区間の調整の行(
    識別子: &クリップ識別子,
    区間: 動画上の区間,
) -> ノード<応答> {
    let ずらす =
        |端, ずらし方| 編集の応答(識別子, クリップの編集::区間の端をずらす(端, ずらし方));
    let 開始 = 区間.開始().秒数();
    let 終了 = 区間.終了().秒数();
    横並び(子![
        ボタン("-0.5s", ずらす(区間の端::開始, 端のずらし方::半秒戻す)).小さい(),
        ボタン("< F", ずらす(区間の端::開始, 端のずらし方::一コマ戻す)).小さい(),
        数値入力(開始, 0.0..=f64::MAX, 編集の写像(識別子, 開始を決める))
            .刻み(秒の刻み)
            .小数点以下の桁数(2)
            .操作を終えたら発する(操作を終えた),
        文字表示("〜"),
        数値入力(終了, 0.0..=f64::MAX, 編集の写像(識別子, 終了を決める))
            .刻み(秒の刻み)
            .小数点以下の桁数(2)
            .操作を終えたら発する(操作を終えた),
        ボタン("F >", ずらす(区間の端::終了, 端のずらし方::一コマ進める)).小さい(),
        ボタン("+0.5s", ずらす(区間の端::終了, 端のずらし方::半秒進める)).小さい(),
    ])
    .into()
}
