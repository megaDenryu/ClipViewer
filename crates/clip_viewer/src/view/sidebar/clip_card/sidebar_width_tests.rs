//! サイドバーの幅の試験。画面と同じ左サイドバーのパネル(既定の幅480論理画素・利用者が変えられる範囲480〜610論理画素)の中の
//! 縦スクロールにカードを並べて描き、利用者が縁を動かさない限りパネルの幅が480論理画素のままであることを確かめる。
//! パネルは中身がはみ出した幅を覚えて広がるため、名前の欄を広げる見出しの行が、最初の回・カードを足した回・
//! 1枚だけ単独再生にした回のどれでも、パネルの幅を超えて描かれないことを、この幅で確かめる。
//! 注意: 日本語フォントが無いと日本語の字が幅0で描かれて通ってしまうため、OS の日本語フォントを読めなければ試験を失敗させる。

use clip_domain::{
    クリップ, クリップ名, クリップ識別子, 動画上の区間, 動画上の秒
};
use eframe::egui;
use sengen_egui::{ノード, 縦スクロール};

use super::{カードの様子, クリップカード};
use crate::command::応答;
use crate::state::カードの区間の帯に描く値;
use crate::view::test_support::{
    サイドバーのパネルの幅, 日本語フォントとテーマを当てた本体を作る
};
use crate::view::左サイドバーのパネル;

fn カード(番号: usize, 単独で再生しているか: bool) -> ノード<応答> {
    let 識別子 = クリップ識別子::文字列から作成する(format!("クリップ{番号}"))
        .unwrap_or_else(|不正| panic!("識別子が不正: {不正}"));
    let クリップ = クリップ::既定値で作成する(
        識別子,
        クリップ名::作成する(format!("Clip Mod {番号}")),
    );
    let 秒 = |値| 動画上の秒::作成する(値).unwrap_or_else(|不正| panic!("秒が不正: {不正}"));
    let 区間 = 動画上の区間::作成する(秒(3599.95), 秒(3600.0))
        .unwrap_or_else(|不正| panic!("区間が不正: {不正}"));
    let 様子 = カードの様子 {
        選ばれているか: 番号 == 0,
        区間の帯に描く値: カードの区間の帯に描く値 {
            全体の範囲: 区間,
            拡大の範囲: 区間,
            区間,
            位置: None,
            区間が動画の外にあるか: false,
        },
        単独で再生しているか,
        前へ動かせるか: 番号 > 0,
        後ろへ動かせるか: true,
    };
    クリップカード(&クリップ, &様子)
}

/// カードを数だけ並べたサイドバーを1回描き、パネルが覚えた幅を返す。単独再生の番号のカードだけ「単独再生を止める」にする。
fn 描いてパネルの幅を測る(
    画面描画の共有状態: &egui::Context,
    数: usize,
    単独再生の番号: Option<usize>,
) -> f32 {
    let _ = 画面描画の共有状態.run(egui::RawInput::default(), |画面描画の共有状態| {
        egui::CentralPanel::default().show(画面描画の共有状態, |ui| {
            let カード一覧 = (0..数)
                .map(|番号| カード(番号, Some(番号) == 単独再生の番号))
                .collect();
            let _ = 左サイドバーのパネル(縦スクロール("左サイドバー", カード一覧).into())
                .描画して集める(ui);
        });
    });
    サイドバーのパネルの幅(画面描画の共有状態)
}

#[test]
fn 最初の回もカードを足した回も1枚だけ単独再生にした回もサイドバーの幅は変わらない() {
    let 画面描画の共有状態 = 日本語フォントとテーマを当てた本体を作る();
    let 最初の回 = 描いてパネルの幅を測る(&画面描画の共有状態, 1, None);
    assert_eq!(最初の回, 480.0, "最初の回");
    let 足した回 = 描いてパネルの幅を測る(&画面描画の共有状態, 3, None);
    assert_eq!(足した回, 480.0, "カードを足した回");
    let 単独再生の回 = 描いてパネルの幅を測る(&画面描画の共有状態, 3, Some(1));
    assert_eq!(単独再生の回, 480.0, "1枚だけ単独再生にした回");
    let 戻した回 = 描いてパネルの幅を測る(&画面描画の共有状態, 3, None);
    assert_eq!(戻した回, 480.0, "単独再生を止めた回");
}
