//! クリップカードの繰り返しとトリガーの部品。回数の増減・無限ループ・トリガーの選択欄を並べる。

use clip_domain::{クリップ, トリガー, リピート設定};
use sengen_egui::{
    チェックボックス, ノード, ボタン, 子, 文字表示, 横並び, 選択欄, 選択肢
};

use super::{編集の写像, 編集の応答};
use crate::command::{クリップの編集, 応答};
use crate::styles;
use crate::view::text;

const トリガーの一覧: [トリガー; 4] = [
    トリガー::自動進行,
    トリガー::Enterキー待ち,
    トリガー::Spaceキー待ち,
    トリガー::クリック待ち,
];

pub(super) fn 繰り返しとトリガーの行(クリップ: &クリップ) -> ノード<応答> {
    let 識別子 = クリップ.識別子();
    let (回数の表示, 無限か) = match クリップ.リピート {
        リピート設定::回数指定(回数) => (format!("{}x", 回数.回数()), false),
        リピート設定::無限ループ => ("無限".to_string(), true),
    };
    let トリガーの選択肢 = トリガーの一覧
        .into_iter()
        .map(|トリガー| {
            let 応答 = 編集の応答(識別子, クリップの編集::トリガーを選ぶ(トリガー));
            選択肢(text::トリガーの選択肢の名前(トリガー), 応答)
        })
        .collect();
    let 選んでいるトリガー = text::トリガーの選択肢の名前(クリップ.トリガー);
    横並び(子![
        ボタン("-", 編集の応答(識別子, クリップの編集::リピートを減らす)).小さい(),
        文字表示(回数の表示),
        ボタン("+", 編集の応答(識別子, クリップの編集::リピートを増やす)).小さい(),
        チェックボックス(
            "無限",
            無限か,
            編集の写像(識別子, クリップの編集::無限ループを切り替える)
        ),
        文字表示("トリガー").装飾(styles::補足),
        選択欄(
            format!("トリガー_{識別子}"),
            選んでいるトリガー,
            トリガーの選択肢
        ),
    ])
    .into()
}
