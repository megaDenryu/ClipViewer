//! プレビューの寸法の試験。期待値は手で計算した値である。

use clip_domain::{画素の寸法, 縦横比};
use sengen_egui::画素の組;

use super::preview::プレビューの寸法を求める;

fn 縦横比にする(幅: f64, 高さ: f64) -> Option<縦横比> {
    画素の寸法::作成する(幅, 高さ)
        .ok()
        .and_then(|寸法| 寸法.縦横比())
}

#[test]
fn プレビューは幅に合わせ_高さの上限を超えるなら高さに合わせる() {
    let 横長 =
        プレビューの寸法を求める(画素の組(456.0, 264.0), 縦横比にする(16.0, 9.0));
    assert_eq!(横長, 画素の組(456.0, 256.0));
    let 縦長 =
        プレビューの寸法を求める(画素の組(456.0, 264.0), 縦横比にする(9.0, 16.0));
    assert_eq!(縦長, 画素の組(148.0, 264.0));
}

#[test]
fn 最大が負なら大きさ0に収める() {
    let 負 = プレビューの寸法を求める(画素の組(-8.0, 264.0), 縦横比にする(16.0, 9.0));
    assert_eq!(負, 画素の組(0.0, 0.0));
}
