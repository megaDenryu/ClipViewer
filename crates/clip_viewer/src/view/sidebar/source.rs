//! 動画の欄。読み込んだ動画の名前と解除のボタン、PC内の絶対パスのメモと検証の文、動画を開くボタンを並べる。

use clip_domain::動画パスの検証結果;
use sengen_egui::{
    ノード, ボタン, 一行テキスト入力, 子, 文字表示, 横並び, 無し, 画素, 縦積み
};

use crate::command::{ファイルの操作, 応答, 手がかりの操作};
use crate::state::アプリの状態;
use crate::view::styles;

pub(crate) fn 動画の欄(状態: &アプリの状態) -> ノード<応答> {
    縦積み(子![
        文字表示("Video Source File").装飾(styles::見出し),
        動画の名前の行(状態),
        横並び(子![
            文字表示("PC内絶対パス:").装飾(styles::補足),
            一行テキスト入力(状態.手がかり.パスのメモ().文字列(), |入力| {
                応答::手がかり(手がかりの操作::パスのメモを書き換える(
                    入力,
                ))
            })
            .案内文("C:/path/to/your/video.mp4")
            .幅(画素(280.0)),
        ]),
        パスの検証の文(状態),
        ボタン(
            "動画を開く",
            応答::ファイル(ファイルの操作::動画を選んで開く)
        )
        .装飾(styles::強調ボタン),
        文字表示("ウインドウのどこかへ動画をドラッグ＆ドロップしても開ける").装飾(styles::補足),
    ])
    .into()
}

fn 動画の名前の行(状態: &アプリの状態) -> ノード<応答> {
    let Some(動画) = &状態.動画 else {
        return 文字表示("未ロード").装飾(styles::補足).into();
    };
    let 名前 = 動画.情報().パス().ファイル名().map_or_else(
        || 動画.情報().パス().文字列().to_string(),
        |名前| 名前.文字列().to_string(),
    );
    横並び(子![
        文字表示(名前).装飾(styles::動画の名前),
        ボタン("解除", 応答::ファイル(ファイルの操作::動画を解除する)).装飾(styles::危険ボタン),
    ])
    .into()
}

/// パスのメモを期待する動画で検証した結果の文。検証を通ったか、何も分かっていなければ出さない。
fn パスの検証の文(状態: &アプリの状態) -> ノード<応答> {
    match 状態.手がかり.検証する() {
        Some(動画パスの検証結果::不正 { 不備, .. }) => {
            文字表示(不備.to_string()).装飾(styles::不備の文).into()
        }
        Some(動画パスの検証結果::有効(_)) | None => 無し(),
    }
}
