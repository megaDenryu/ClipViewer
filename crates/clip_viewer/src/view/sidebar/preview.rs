//! プレビューの欄。表示しているコマの全体を出し、その上に選択中のクリップのクロップ枠を重ねてドラッグで動かせるようにする。
//! 出力と同じテクスチャを使うため、プレビューは出力が切り出す前のコマそのものである。
//! 大きさはサイドバーの使える幅に合わせ、縦横比は動画の元の寸法に合わせる。高さは移植元のプレビューの枠と同じ上限で止める。

use clip_domain::{クロップ範囲, 縦横比};
use sengen_egui::{
    ノード, 使える大きさから組む, 子, 文字表示, 横並び, 画像, 画素, 登録したテクスチャの参照,
    範囲枠付き画像, 範囲枠付き画像の周りの余白, 縦横の論理画素, 縦積み, 論理画素,
};

use crate::command::応答;
use crate::state::アプリの状態;
use crate::view::aspect_fit::{丸める前の論理画素の寸法, 描く縦横比};
use crate::view::conversion::{
    クロップを描く部分にする, 範囲枠の操作を変換する
};
use crate::view::styles;

/// プレビューの高さの上限。移植元のプレビューの枠(高さ280・内余白8)の内側の高さである。
const プレビューの高さの上限: 論理画素 = 画素(264.0);

/// 使える幅が余白より狭いときに負になった最大を、大きさ0へ揃えるための下限。
const 負を除く下限: 丸める前の論理画素の寸法 =
    丸める前の論理画素の寸法::生成する(0.0, 0.0);

pub(crate) fn プレビューの欄(状態: &アプリの状態) -> ノード<応答> {
    縦積み(子![
        横並び(子![
            文字表示("オリジナル動画 (クロップ調整対象)").装飾(styles::見出し),
            文字表示(解像度の文(状態)).装飾(styles::補足),
        ]),
        プレビュー(状態),
    ])
    .into()
}

fn 解像度の文(状態: &アプリの状態) -> String {
    状態.動画.as_ref().map_or_else(
        || "0 x 0".to_string(),
        |動画| {
            let 寸法 = 動画.情報().元の寸法();
            format!("{} x {}", 寸法.幅(), 寸法.高さ())
        },
    )
}

fn プレビュー(状態: &アプリの状態) -> ノード<応答> {
    let Some(動画) = &状態.動画 else {
        return 文字表示("動画未ロード").装飾(styles::補足).into();
    };
    let 材料 = プレビューの材料 {
        映像: 動画.映像().テクスチャ().参照を複製する(),
        縦横比: 動画
            .情報()
            .元の寸法()
            .画素の寸法へ変換する()
            .ok()
            .and_then(|寸法| 寸法.縦横比()),
        クロップ: 状態
            .並び
            .選択中のクリップ()
            .map(|クリップ| クリップ.クロップ),
    };
    使える大きさから組む(move |大きさ| 材料.組む(大きさ)).into()
}

/// プレビューの材料とは、使える幅が分かってからプレビューを組むために、状態から先に取り出しておく値の組のことである。
/// クロップは選択中のクリップのクロップ範囲であり、クリップを選んでいなければ枠を出さない。
struct プレビューの材料 {
    映像: 登録したテクスチャの参照,
    縦横比: Option<縦横比>,
    クロップ: Option<クロップ範囲>,
}

impl プレビューの材料 {
    /// 範囲枠付き画像は画像の周りに余白を取るため、その分を除いた幅と高さの中へ動画の縦横比で収める。
    fn 組む(&self, 使える大きさ: 縦横の論理画素) -> ノード<応答> {
        let 余白の合計 = 範囲枠付き画像の周りの余白 * 2.0;
        let 最大 = 縦横の論理画素::生成する(
            使える大きさ.横 - 余白の合計,
            プレビューの高さの上限,
        );
        let 寸法 = プレビューの寸法を求める(最大, self.縦横比);
        match self.クロップ {
            Some(クロップ) => 範囲枠付き画像(
                &self.映像,
                寸法,
                クロップを描く部分にする(クロップ),
                |操作| 応答::クロップ枠(範囲枠の操作を変換する(操作)),
            )
            .into(),
            None => 画像(&self.映像).表示寸法(寸法).into(),
        }
    }
}

/// 最大の大きさの中へ、動画の縦横比を保って収まる最も大きい寸法を、論理画素の整数へ切り捨てて求める。
/// 最大の幅か高さが負なら0とみなし、縦横比が無いか0以下なら16:9とみなす。
pub(super) fn プレビューの寸法を求める(
    最大: 縦横の論理画素,
    縦横比: Option<縦横比>,
) -> 縦横の論理画素 {
    丸める前の論理画素の寸法::論理画素の組から作る(最大)
        .下限へ揃える(負を除く下限)
        .縦横比を保って収める(描く縦横比::求める(縦横比))
        .切り捨てて論理画素の組にする()
}
