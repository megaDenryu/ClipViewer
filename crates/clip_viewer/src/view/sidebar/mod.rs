//! 左サイドバー。動画の欄・プレビューの欄・クリップスタックの欄を上から並べ、全体を縦にスクロールさせる。

mod clip_card;
mod preview;
mod source;

#[cfg(test)]
mod preview_tests;

use sengen_egui::{
    ノード, ボタン, 余白, 区切り線, 子, 文字表示, 横並び, 画素, 縦スクロール, 縦積み,
};

use crate::command::{クリップの操作, 応答};
use crate::state::アプリの状態;
use crate::view::styles;

pub(crate) fn 左サイドバー(状態: &アプリの状態) -> ノード<応答> {
    縦スクロール(
        "左サイドバー",
        子![
            source::動画の欄(状態),
            区切り線(),
            preview::プレビューの欄(状態),
            区切り線(),
            スタックの欄(状態),
            余白(画素(12.0)),
        ],
    )
    .into()
}

/// クリップスタックの欄。見出しと追加のボタンの下に、クリップカードを並び順に並べる。
fn スタックの欄(状態: &アプリの状態) -> ノード<応答> {
    let 見出し = 横並び(子![
        文字表示("Modifier Stack").装飾(styles::見出し),
        ボタン("新規Clipを追加", 応答::クリップ(クリップの操作::追加する))
            .装飾(styles::強調ボタン),
    ]);
    let 選択中 = 状態
        .並び
        .選択中のクリップ()
        .map(|クリップ| クリップ.識別子().clone());
    let 数 = 状態.並び.一覧().len();
    let カード: Vec<ノード<応答>> = 状態
        .並び
        .一覧()
        .iter()
        .enumerate()
        .map(|(番号, クリップ)| {
            let 選ばれているか = 選択中.as_ref() == Some(クリップ.識別子());
            let 様子 = clip_card::カードの様子 {
                選ばれているか,
                区間の帯に描く値: 状態
                    .カードの区間の帯に描く値(クリップ, 選ばれているか),
                単独で再生しているか: 状態
                    .単独で再生しているか(クリップ.識別子()),
                前へ動かせるか: 番号 > 0,
                後ろへ動かせるか: 番号 + 1 < 数,
            };
            clip_card::クリップカード(クリップ, &様子)
        })
        .collect();
    if カード.is_empty() {
        return 縦積み(子![
            見出し,
            文字表示("クリップスタックが登録されていません"),
            文字表示("動画をロード、または新規Clipを追加してください。").装飾(styles::補足),
        ])
        .into();
    }
    let mut 子一覧 = vec![見出し.into()];
    子一覧.extend(カード);
    縦積み(子一覧).into()
}
