//! 割合と百分率の変換の境界。ドメインは百分率(0〜100)と f64 で持ち、SengenEgui は割合(0〜1)と f32 で受け取るため、
//! その間の変換をここ1箇所に置く。掴んだ部分と割合の差の変換は、重ね合わせの作業場の映す矩形の枠と共有するため `output_measure/frame_operation.rs` に置く。クロップ範囲を描く部分にする変換は、重ね合わせの作業場の画面と共有するため `output_measure/crop_part.rs` に置く。参照: _doc/設計/画面.md 判断6・_doc/設計/アーキテクチャ.md 判断5

use sengen_egui::範囲枠の操作;

use crate::command::クロップ枠の操作;
use crate::output_measure::{
    割合の差を枠の移動量にする, 掴んだ部分を掴む所にする
};

/// 範囲枠の操作を、百分率へ直したクロップ枠の操作にする。
pub(crate) fn 範囲枠の操作を変換する(
    操作: 範囲枠の操作
) -> クロップ枠の操作 {
    match 操作 {
        範囲枠の操作::掴み始めた { .. } => クロップ枠の操作::掴み始めた,
        範囲枠の操作::動かしている {
            掴んだ部分,
            開始点からの移動量,
        } => match 割合の差を枠の移動量にする(開始点からの移動量) {
            Some(移動量) => クロップ枠の操作::動かしている {
                掴む所: 掴んだ部分を掴む所にする(掴んだ部分),
                移動量,
            },
            None => クロップ枠の操作::移動量が数でない,
        },
        範囲枠の操作::放した {
            掴んだ部分,
            開始点からの移動量,
        } => match 割合の差を枠の移動量にする(開始点からの移動量) {
            Some(移動量) => クロップ枠の操作::放した {
                掴む所: 掴んだ部分を掴む所にする(掴んだ部分),
                移動量,
            },
            None => クロップ枠の操作::移動量が数でない,
        },
    }
}
