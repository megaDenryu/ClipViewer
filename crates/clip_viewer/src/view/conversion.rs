//! 割合と百分率の変換の境界。ドメインは百分率(0〜100)と f64 で持ち、SengenEgui は割合(0〜1)と f32 で受け取るため、
//! その間の変換をここ1箇所に置く。参照: _doc/設計/画面.md 判断6・_doc/設計/アーキテクチャ.md 判断5

use clip_domain::{
    クロップの移動量, クロップ範囲, 四隅のつまみ, 百分率の差分
};
use sengen_egui::{
    割合, 割合で表した矩形, 割合の差, 範囲枠の掴んだ部分, 範囲枠の操作, 縦横の割合の差,
};

use crate::command::{クロップ枠の掴む所, クロップ枠の操作};

/// クロップ範囲(百分率)を、画像のうち描く部分(割合で表した矩形)にする。右端と下端が100%を超える範囲は画像の端までにする。
pub(crate) fn クロップを描く部分にする(
    クロップ: クロップ範囲,
) -> 割合で表した矩形 {
    let 割合にする = 割合::倍精度の小数から範囲へ丸めて生成する;
    let 左端 = クロップ.左端().割合();
    let 上端 = クロップ.上端().割合();
    let 右端 = 左端 + クロップ.幅().割合();
    let 下端 = 上端 + クロップ.高さ().割合();
    match 割合で表した矩形::生成する(
        割合にする(左端),
        割合にする(上端),
        割合にする(右端),
        割合にする(下端),
    ) {
        Ok(矩形) => 矩形,
        Err(不正) => panic!(
            "クロップ範囲の幅と高さは5%以上なので左端と右端は逆転しない(到達したらバグ): {不正}"
        ),
    }
}

/// 範囲枠の操作を、百分率へ直したクロップ枠の操作にする。
pub(crate) fn 範囲枠の操作を変換する(
    操作: 範囲枠の操作
) -> クロップ枠の操作 {
    match 操作 {
        範囲枠の操作::掴み始めた { .. } => クロップ枠の操作::掴み始めた,
        範囲枠の操作::動かしている {
            掴んだ部分,
            開始点からの移動量,
        } => match 移動量を変換する(開始点からの移動量) {
            Some(移動量) => クロップ枠の操作::動かしている {
                掴む所: 掴む所にする(掴んだ部分),
                移動量,
            },
            None => クロップ枠の操作::移動量が数でない,
        },
        範囲枠の操作::放した {
            掴んだ部分,
            開始点からの移動量,
        } => match 移動量を変換する(開始点からの移動量) {
            Some(移動量) => クロップ枠の操作::放した {
                掴む所: 掴む所にする(掴んだ部分),
                移動量,
            },
            None => クロップ枠の操作::移動量が数でない,
        },
    }
}

fn 掴む所にする(部分: 範囲枠の掴んだ部分) -> クロップ枠の掴む所 {
    match 部分 {
        範囲枠の掴んだ部分::内側 => クロップ枠の掴む所::内側,
        範囲枠の掴んだ部分::左上の隅 => {
            クロップ枠の掴む所::隅(四隅のつまみ::左上)
        }
        範囲枠の掴んだ部分::右上の隅 => {
            クロップ枠の掴む所::隅(四隅のつまみ::右上)
        }
        範囲枠の掴んだ部分::左下の隅 => {
            クロップ枠の掴む所::隅(四隅のつまみ::左下)
        }
        範囲枠の掴んだ部分::右下の隅 => {
            クロップ枠の掴む所::隅(四隅のつまみ::右下)
        }
    }
}

/// 割合の差(画像の幅と高さを1とする)を、百分率の差分(画像の幅と高さを100とする)にする。有限でなければ無い。
fn 移動量を変換する(差: 縦横の割合の差) -> Option<クロップの移動量> {
    let 百分率にする =
        |差: 割合の差| 百分率の差分::作成する(f64::from(差.生の値()) * 100.0).ok();
    Some(クロップの移動量 {
        横: 百分率にする(差.横)?,
        縦: 百分率にする(差.縦)?,
    })
}
