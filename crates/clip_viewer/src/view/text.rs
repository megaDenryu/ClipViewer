//! 表示の文字列。ドメインは文字列を組み立てないため(アーキテクチャ.md 判断7)、画面に出す文はここで組み立てる。

use clip_domain::{
    アスペクト比設定, タイムライン上の位置の再生の中身, トリガー, 再生モード, 周回の状況,
};

use crate::state::表示サイズ;

/// 秒を「分:秒.十分の一秒」(例 01:05.3)にする。負と非数は 00:00.0 にする(移植元と同じ)。
pub(crate) fn 時刻の表示(秒: f64) -> String {
    if !秒.is_finite() || 秒 < 0.0 {
        return "00:00.0".to_string();
    }
    let 分 = (秒 / 60.0).floor();
    let 秒の部分 = (秒 % 60.0).floor();
    let 十分の一 = ((秒 % 1.0) * 10.0).floor();
    format!("{分:02}:{秒の部分:02}.{十分の一}")
}

/// シーケンス再生のステータス(移植元の「クリップ名 (2/3) [Trigger: Enterキー待ち]」と同じ形)。
pub(crate) fn シーケンスのステータス(
    再生の中身: &タイムライン上の位置の再生の中身<'_>,
) -> String {
    let クリップ = 再生の中身.対象クリップ;
    let 周回 = match 再生の中身.周回の状況() {
        周回の状況::無限ループ中 => "(Loop)".to_string(),
        周回の状況::回数指定中 { 何周目, 回数 } => {
            format!("({何周目}/{})", 回数.回数())
        }
    };
    let トリガーの表示 = match クリップ.トリガー {
        トリガー::自動進行 => String::new(),
        その他 => format!(" [Trigger: {}]", トリガーの名前(その他)),
    };
    format!("{} {周回}{トリガーの表示}", クリップ.名前.文字列())
}

/// トリガーの名前(移植元の kind と同じ表記)。Space待ちは Enter で進むため、そのことを添える(Space は再生と停止に使う)。
fn トリガーの名前(トリガー: トリガー) -> &'static str {
    match トリガー {
        トリガー::自動進行 => "自動進行",
        トリガー::Enterキー待ち => "Enterキー待ち",
        トリガー::Spaceキー待ち => "Spaceキー待ち(Enterで進む)",
        トリガー::クリック待ち => "クリック待ち",
    }
}

/// カードの選択欄に出すトリガーの名前(移植元の選択肢と同じ。Space待ちには Enter で進むことを添える)。
pub(crate) fn トリガーの選択肢の名前(トリガー: トリガー) -> &'static str {
    match トリガー {
        トリガー::自動進行 => "自動進行",
        トリガー::Enterキー待ち => "Enter待ち",
        トリガー::Spaceキー待ち => "Space待ち(Enterで進む)",
        トリガー::クリック待ち => "Click待ち",
    }
}

/// 待っているクリップの案内の文。自動進行の無限ループは次へボタンでだけ進む。
pub(crate) fn トリガー待ちの案内(トリガー: トリガー) -> &'static str {
    match トリガー {
        トリガー::自動進行 => "無限ループ中です。Nextボタンで進めてください",
        トリガー::Enterキー待ち => "Enterキーを押すか、Nextボタンで進めてください",
        トリガー::Spaceキー待ち => {
            "Space待ちは Enterキーで進む(Space は再生と停止に使う)。Enterキーを押すか、Nextボタンで進めてください"
        }
        トリガー::クリック待ち => "出力映像をクリックするか、Nextボタンで進めてください",
    }
}

