//! 出力の寸法。使える大きさと縦横比と表示サイズから、出力を描く幅と高さを移植元と同じ式で求める。
//! 縦横比を保って収める・覆う計算と出力の欄の余白の内側は、プレビューと重ね合わせの作業場と共有する output_measure が持つ。
//! シアターだけは移植元の高さ基準を写さず、ウインドウ全体の使える大きさへ縦横比を保って収める(_doc/設計/画面.md 判断12)。
//! 参照: 移植元 Service/動画再生サービス.ts の `_出力寸法を計算する`、_doc/設計/画面.md 判断8

use clip_domain::縦横比;
use sengen_egui::縦横の論理画素;

use crate::output_measure::{丸める前の論理画素の寸法, 描く縦横比};
use crate::state::表示サイズ;

const シアターの最小の寸法: 丸める前の論理画素の寸法 =
    丸める前の論理画素の寸法::生成する(1.0, 1.0); // ウインドウを極端に縮めても0で割らないための下限
const 標準の比: f64 = 0.84; // 標準の表示サイズが使える大きさに対して占める比(移植元と同じ)

/// 出力の描き方とは、編集の構えで表示サイズに従って描くか、シアターでウインドウ全体の使える大きさへ収めて描くかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 出力の描き方 {
    表示サイズで(表示サイズ),
    シアター,
}

impl 出力の描き方 {
    /// 出力の幅と高さを求める。縦横比が無いか0以下なら16:9とみなす(`描く縦横比::求める`)。
    pub(crate) fn 寸法を求める(
        self,
        使える大きさ: 縦横の論理画素,
        縦横比: Option<縦横比>,
    ) -> 縦横の論理画素 {
        let 比 = 描く縦横比::求める(縦横比);
        let 使える =
            丸める前の論理画素の寸法::論理画素の組から作る(使える大きさ);
        let 最大 =
            丸める前の論理画素の寸法::出力の欄の余白の内側(使える大きさ);
        let 寸法 = match self {
            Self::表示サイズで(表示サイズ::標準) => {
                最大.比を掛ける(標準の比).縦横比を保って収める(比)
            }
            Self::表示サイズで(表示サイズ::大きめ) => {
                最大.縦横比を保って収める(比)
            }
            Self::表示サイズで(表示サイズ::横幅優先) => 最大.幅に合わせる(比),
            Self::表示サイズで(表示サイズ::余白なし) => {
                最大.縦横比を保って覆う(比)
            }
            Self::シアター => 使える
                .下限へ揃える(シアターの最小の寸法)
                .縦横比を保って収める(比),
        };
        寸法.四捨五入して論理画素の組にする()
    }
}
