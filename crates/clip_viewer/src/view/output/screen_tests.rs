//! 出力の画面の左右の向きの試験。左右を反転すると、編集の構えの出力でもシアターでも、映像の uv の左端と右端が入れ替わる。
//! 描く部分(クロップ)を指定しているときは、その部分の中で入れ替わる。

use eframe::egui;
use sengen_egui::{
    割合, 割合で表した矩形, 差し替えられるテクスチャ, 拡大縮小の仕方, 画素の並び, 画素の組,
    画素数の寸法,
};

use super::screen::出力の画面の材料;
use super::size::出力の描き方;
use super::theater_controls::操作の欄の出し方;
use crate::state::{左右の向き, 画面の構え, 表示サイズ};

/// 左端0.25・右端0.5の描く部分で、構えと左右の向きの材料を組んで1フレーム描き、映像の uv を返す。
fn 描いた映像のuv(構え: 画面の構え, 左右: 左右の向き) -> egui::Rect {
    let eguiの本体 = egui::Context::default();
    let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
        画素数の寸法::生成する(2, 1),
        &[0; 8],
    )
    .unwrap_or_else(|不正| panic!("画素の並びが不正: {不正}"));
    let テクスチャ = 差し替えられるテクスチャ::登録して作る(
        &eguiの本体,
        "試験",
        画素,
        拡大縮小の仕方::隣の画素と混ぜる,
    );
    let 割合にする = 割合::範囲へ丸めて生成する;
    let 描く部分 = 割合で表した矩形::生成する(
        割合にする(0.25),
        割合にする(0.0),
        割合にする(0.5),
        割合にする(1.0),
    )
    .unwrap_or_else(|不正| panic!("矩形が不正: {不正}"));
    let 材料 = 出力の画面の材料 {
        映像: テクスチャ.参照を複製する(),
        描く部分,
        左右,
        縦横比: None,
        描き方: 出力の描き方::表示サイズで(表示サイズ::大きめ),
        待ちの案内: None,
        次へを出すか: false,
        構え,
        操作の出し入れ: 操作の欄の出し方(),
    };
    let 出力 = eguiの本体.run(egui::RawInput::default(), |eguiの本体| {
        egui::CentralPanel::default().show(eguiの本体, |ui| {
            let _ = 材料.組む(画素の組(800.0, 600.0)).描画して集める(ui);
        });
    });
    出力
        .shapes
        .iter()
        .find_map(|切り抜いた形| match &切り抜いた形.shape {
            egui::Shape::Rect(矩形) => 矩形.brush.as_ref().map(|塗り方| 塗り方.uv),
            _ => None,
        })
        .unwrap_or_else(|| panic!("映像を貼った矩形が無い"))
}

#[test]
fn 左右を反転すると編集の構えでもシアターでも描く部分の中で左右を入れ替える() {
    for 構え in [画面の構え::編集, 画面の構え::シアター] {
        let そのまま = 描いた映像のuv(構え, 左右の向き::そのまま);
        assert_eq!((そのまま.min.x, そのまま.max.x), (0.25, 0.5), "{構え:?}");
        let 反転 = 描いた映像のuv(構え, 左右の向き::反転);
        assert_eq!((反転.min.x, 反転.max.x), (0.5, 0.25), "{構え:?}");
    }
}
