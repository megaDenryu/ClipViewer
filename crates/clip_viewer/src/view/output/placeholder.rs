//! 動画を開いていないときの出力の欄の案内。設定ファイルが期待する動画があれば、そのファイル名とパスを出す。
//! シアターの構えでは、動画が無いと出力の画面の「編集へ戻る」も出ないため、この案内に「編集へ戻る」と Escape の説明を足す。

use sengen_egui::{ノード, ボタン, 子, 文字表示, 条件付き表示, 縦積み};

use crate::command::{出力の操作, 応答};
use crate::state::{アプリの状態, 画面の構え};
use crate::view::styles;

/// 動画を開いていないときの案内。設定ファイルが期待する動画があれば、そのファイル名とパスを出す(移植元の警告の札)。
pub(super) fn 動画の無い案内(状態: &アプリの状態) -> ノード<応答> {
    let 期待する動画 = 状態
        .手がかり
        .期待する動画()
        .map(|名前| 名前.文字列().to_string());
    let パス = 状態.手がかり.パスのメモ().文字列().to_string();
    縦積み(子![
        文字表示("Smart Video Modifier Stack").装飾(styles::動画の名前),
        文字表示(
            "左の「動画を開く」か、ウインドウへ動画をドラッグ＆ドロップして、シーケンス再生を開始します。"
        )
        .装飾(styles::補足),
        条件付き表示(
            状態.出力.構え == 画面の構え::シアター,
            シアターから編集へ戻る案内
        ),
        条件付き表示(期待する動画.is_some(), move || {
            縦積み(子![
                文字表示("対応する元動画が見つかりません").装飾(styles::見出し),
                文字表示("インポートされた設定で期待されている動画ファイルは以下です。")
                    .装飾(styles::補足),
                文字表示(format!("ファイル名: {}", 期待する動画.unwrap_or_default())),
                文字表示(format!(
                    "保存時パス: {}",
                    if パス.is_empty() {
                        "未指定".to_string()
                    } else {
                        パス
                    }
                )),
            ])
            .装飾(styles::警告の札)
        }),
    ])
    .中央寄せ()
    .into()
}

/// シアターの構えで動画が無いときの、編集の構えへ戻る案内。戻り方の文と「編集へ戻る」のボタンを並べる。
pub(super) fn シアターから編集へ戻る案内() -> ノード<応答> {
    縦積み(子![
        文字表示("「編集へ戻る」を押すか Escape キーを押すと、編集の構えへ戻ります。")
            .装飾(styles::補足),
        ボタン(
            "編集へ戻る",
            応答::出力(出力の操作::構えを選ぶ(画面の構え::編集))
        ),
    ])
    .into()
}
