//! シアターの操作の欄。シアターでは再生コントロールを下のパネルに置かず、出力の画面の下端に半透明の地で重ねる。
//! 欄は、動画サイトの再生画面に揃え、出力の上でマウスを実際に動かすか押したときと、左右キーを押している間だけ出し、
//! 止まってから2.5秒で隠す。欄の上にマウスがあっても、一時停止していても隠す。欄の中で押し始めたドラッグの間だけは隠さない。
//! マウスがウインドウの外へ出たらすぐ隠す。隠している間はマウスのカーソルも隠す(規則は SengenEgui の `ポインタが止まると隠す指定`)。
//! 欄と「編集へ戻る」とトリガー待ちの札(screen.rs)は同じ組で出し入れするため、指定は出力の区画が1つ作って両方の画面へ渡す。
//! 参照: _doc/設計/画面.md 判断12

use std::time::Duration;

use clip_domain::再生位置;
use sengen_egui::{
    キー, ノード, ポインタが止まると隠す指定, ポインタが止まると隠す組, 子, 条件付き表示, 横並び,
    画素, 縦積み, 重ねる, 重ねる位置,
};

use super::screen;
use crate::command::応答;
use crate::state::アプリの状態;
use crate::view::{control, styles};

/// 出力の上でマウスを止めてから操作の欄を隠すまでの時間。
const 隠すまでの時間: Duration = Duration::from_millis(2500);

/// 押している間は操作の欄を出すキー。コマ送りの左右キーであり、送った先の再生位置を欄の帯で見せる。
const 欄を出すキー: &[キー] = &[キー::ArrowLeft, キー::ArrowRight];

/// 操作の欄と「編集へ戻る」とトリガー待ちの札を一緒に出し入れする組の名。
const 操作の組の名: &str = "シアターの操作";

/// 出力の画面の下端へ、シアターの操作の欄を重ねる。欄は出力の画面の幅いっぱいに、端から間を空けずに置く。
pub(super) fn 操作の欄を重ねる(
    状態: &アプリの状態,
    出力の画面: ノード<応答>,
    出し入れ: ポインタが止まると隠す指定,
) -> ノード<応答> {
    重ねる("シアターの操作の欄", 出力の画面)
        .端からの間隔(画素(0.0))
        .ポインタが止まると隠して上に置く(重ねる位置::下, 出し入れ, 操作の欄(状態))
        .into()
}

/// 操作の欄と「編集へ戻る」とトリガー待ちの札の出し入れの指定。再生していても一時停止していても、マウスを止めると隠す。
/// 3つを同じ組にするのは、組のどれかの上で押し始めたドラッグの間に全部を出したままにし、隠すときは一緒に隠すためである(画面.md 判断12)。
pub(super) fn 操作の欄の出し方() -> ポインタが止まると隠す指定 {
    ポインタが止まると隠す指定::作成する(隠すまでの時間)
        .隠している間はカーソルも隠す()
        .キーを押している間は出す(欄を出すキー)
        .組にする(ポインタが止まると隠す組::作成する(
            操作の組の名,
        ))
}

/// 操作の欄。シーケンス再生では右端に前へと Next Clip を置き、その下に編集の構えと同じ再生コントロールを並べる。
fn 操作の欄(状態: &アプリの状態) -> ノード<応答> {
    let 次へを出すか = matches!(状態.再生.位置(), 再生位置::シーケンス再生(_));
    縦積み(子![
        条件付き表示(次へを出すか, || {
            横並び(子![screen::前へと次への行()]).右寄せ()
        }),
        control::再生コントロール(状態),
    ])
    .装飾(styles::シアターの操作の欄の地)
    .into()
}
