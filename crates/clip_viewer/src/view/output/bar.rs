//! 出力の帯。出力の欄の上に、再生モード・シアター化・全画面・アスペクト比・表示サイズの選択と左右反転を並べる(編集の構えのときだけ出す)。

use clip_domain::{アスペクト比設定, 再生モード};
use sengen_egui::{
    チェックボックス, ノード, ボタン, 付け足せる, 子, 文字表示, 横並び, 選択欄, 選択肢,
};

use crate::command::{出力の操作, 応答};
use crate::state::{アプリの状態, 左右の向き, 画面の構え, 表示サイズ};
use crate::styles;
use crate::view::{keys, text};
use crate::viewer_settings::キーで行う操作;

fn 出力(操作: 出力の操作) -> 応答 {
    応答::出力(操作)
}

const 再生モードの一覧: [再生モード; 3] = [
    再生モード::シーケンス再生,
    再生モード::単独クリップ再生,
    再生モード::元動画再生,
];

const アスペクト比の一覧: [アスペクト比設定; 5] = [
    アスペクト比設定::クロップ連動,
    アスペクト比設定::ワイド16対9,
    アスペクト比設定::スタンダード4対3,
    アスペクト比設定::正方形,
    アスペクト比設定::縦型9対16,
];

const 表示サイズの一覧: [表示サイズ; 4] = [
    表示サイズ::標準,
    表示サイズ::大きめ,
    表示サイズ::横幅優先,
    表示サイズ::余白なし,
];

pub(crate) fn 出力の帯(状態: &アプリの状態) -> ノード<応答> {
    let モード = 状態.再生.位置().モード();
    let キー = |操作| keys::操作のキーの表記(状態, 操作);
    横並び(子![
        文字表示("再生モード:").装飾(styles::見出し),
        選択欄(
            "再生モード",
            text::再生モードの名前(モード),
            再生モードの一覧
                .map(|モード| 選択肢(
                    text::再生モードの名前(モード),
                    出力(出力の操作::再生モードを選ぶ(モード))
                ))
                .into_iter()
                .collect(),
        ),
        ボタン(
            "シアターで見る",
            出力(出力の操作::構えを選ぶ(画面の構え::シアター))
        )
        .説明(format!(
            "{} でもシアターへ入る・編集へ戻る",
            キー(キーで行う操作::シアターと編集を切り替える)
        )),
        ボタン("全画面", 出力(出力の操作::全画面を切り替える)).説明(format!(
            "{} で全画面にする・抜ける。{} でも抜ける",
            キー(キーで行う操作::全画面を切り替える),
            キー(キーで行う操作::全画面を抜けるか全画面でなければシアターを抜ける)
        )),
        文字表示("出力アスペクト比:").装飾(styles::補足),
        選択欄(
            "出力アスペクト比",
            text::アスペクト比の名前(状態.出力.アスペクト比),
            アスペクト比の一覧
                .map(|比| 選択肢(
                    text::アスペクト比の名前(比),
                    出力(出力の操作::アスペクト比を選ぶ(比))
                ))
                .into_iter()
                .collect(),
        ),
        文字表示("表示サイズ:").装飾(styles::補足),
        選択欄(
            "表示サイズ",
            text::表示サイズの名前(状態.出力.表示サイズ),
            表示サイズの一覧
                .map(|サイズ| 選択肢(
                    text::表示サイズの名前(サイズ),
                    出力(出力の操作::表示サイズを選ぶ(サイズ))
                ))
                .into_iter()
                .collect(),
        ),
        左右反転のチェックボックス(状態.出力.左右),
    ])
    .into()
}

/// 出力の画面とシアターの映像を左右反転するかのチェックボックス。プレビューとクロップ枠は元の向きのまま描く。
fn 左右反転のチェックボックス(向き: 左右の向き) -> ノード<応答> {
    チェックボックス(
        "左右反転",
        向き == 左右の向き::反転,
        |反転する| {
            出力(出力の操作::左右の向きを選ぶ(if 反転する {
                左右の向き::反転
            } else {
                左右の向き::そのまま
            }))
        },
    )
    .説明("出力とシアターの映像を鏡のように映す。プレビューとクロップ枠は元の動画の向きのまま")
}
