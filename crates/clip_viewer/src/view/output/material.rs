//! 出力の画面の材料を状態から集める。クロップ・縦横比・描き方・トリガー待ちの案内・次へを出すかを、
//! 使える大きさが分かる前に状態から取り出し、状態を借りない値にする。

use clip_domain::{クロップ範囲, 再生位置};
use sengen_egui::ポインタが止まると隠す指定;

use super::screen::出力の画面の材料;
use super::size::出力の描き方;
use crate::output_measure::クロップを描く部分にする;
use crate::state::{アプリの状態, 画面の構え};
use crate::video_feed::読み込んだ動画;
use crate::view::text;

impl 出力の画面の材料 {
    /// 状態と読み込んだ動画から、クロップ・縦横比・描き方・トリガー待ちの案内などを取り出して材料にする。
    pub(super) fn 状態から集める(
        状態: &アプリの状態,
        動画: &読み込んだ動画,
        操作の出し入れ: ポインタが止まると隠す指定,
    ) -> Self {
        let クロップ = 状態
            .表示するコマの求め()
            .map_or(クロップ範囲::全体, |求め| 求め.クロップ);
        // 注意: 元の寸法は1以上の整数なので画素の寸法への変換は失敗しない。失敗したら縦横比を求めず16:9で描く。
        let 縦横比 = 動画
            .情報()
            .元の寸法()
            .画素の寸法へ変換する()
            .ok()
            .map(|元の寸法| {
                状態
                    .出力
                    .アスペクト比
                    .縦横比を求める(クロップ.切り出し後の寸法(元の寸法))
            });
        let 描き方 = match 状態.出力.構え {
            画面の構え::編集 | 画面の構え::ライブラリ => {
                出力の描き方::表示サイズで(状態.出力.表示サイズ)
            }
            画面の構え::シアター => 出力の描き方::シアター,
        };
        let 待ちの案内 = 状態
            .シーケンスの再生の様子()
            .filter(|再生の中身| 再生の中身.待っているか)
            .map(|再生の中身| {
                text::トリガー待ちの案内(
                    再生の中身.対象クリップ.トリガー,
                    &状態.キーの割り当て,
                )
            });
        Self {
            映像: 動画.映像().テクスチャ().参照を複製する(),
            描く部分: クロップを描く部分にする(クロップ),
            左右: 状態.出力.左右,
            縦横比,
            描き方,
            待ちの案内,
            次へを出すか: matches!(状態.再生.位置(), 再生位置::シーケンス再生(_)),
            構え: 状態.出力.構え,
            操作の出し入れ,
        }
    }
}
