use sengen_egui::{
    スタイル, ノード, パネル, パネルの位置, 使える大きさから組む, 子, 条件付き表示
};

use crate::command::応答;
use crate::state::{アプリの状態, 画面の構え};
use crate::view::styles;
use screen::出力の画面の材料;

pub(crate) fn 出力の区画(状態: &アプリの状態) -> ノード<応答> {
    let 編集の構えか = 状態.出力.構え == 画面の構え::編集;
    let 地 = 出力の地(状態.出力.構え);
    パネル(
        "出力",
        パネルの位置::中央,
        子![
            条件付き表示(編集の構えか, || パネル(
                "出力の帯",
                パネルの位置::上,
                子![bar::出力の帯(状態)]
            )
            .装飾(styles::出力の帯の地)),
            パネル("出力の画面", パネルの位置::中央, 子![出力の画面(状態)]).装飾(地),
        ],
    )
    .装飾(地)
    .into()
}

fn 出力の地(構え: 画面の構え) -> スタイル {
    match 構え {
        画面の構え::編集 | 画面の構え::ライブラリ => styles::出力の地,
        画面の構え::シアター => styles::シアターの出力の地,
    }
}

fn 出力の画面(状態: &アプリの状態) -> ノード<応答> {
    match &状態.動画 {
        Some(動画) => {
            // 操作の欄と「編集へ戻る」は同じ組の子なので、同じ指定を1つ作って両方へ渡す。
            let 操作の出し入れ = theater_controls::操作の欄の出し方();
            let 材料 = 出力の画面の材料::状態から集める(状態, 動画, 操作の出し入れ);
            let 画面 = 使える大きさから組む(move |大きさ| 材料.組む(大きさ)).into();
            match 状態.出力.構え {
                画面の構え::編集 | 画面の構え::ライブラリ => 画面,
                画面の構え::シアター => {
                    theater_controls::操作の欄を重ねる(状態, 画面, 操作の出し入れ)
                }
            }
        }
        None => placeholder::動画の無い案内(状態),
    }
}
