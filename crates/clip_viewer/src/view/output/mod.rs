//! 出力の区画。編集の構えでは出力の帯を上の縁に出し、残りの大きさいっぱいに出力の画面を描く。
//! シアターでは出力の画面の下端へ操作の欄を重ねる(theater_controls.rs)。
//! 出力の帯を区画の幅いっぱいに塗るため、出力の帯と画面はそれぞれ出力の区画の中のパネルにする。

