//! 出力の寸法の試験。期待値は移植元の式を手で計算した値である。

use clip_domain::{画素の寸法, 縦横比};
use sengen_egui::{画素の組, 縦横の論理画素};

use super::size::出力の描き方;
use crate::state::表示サイズ;

const 十六対九: (f64, f64) = (16.0, 9.0);

fn 求める(
    描き方: 出力の描き方, 幅: f32, 高さ: f32, 比: (f64, f64)
) -> 縦横の論理画素 {
    描き方.寸法を求める(画素の組(幅, 高さ), 縦横比にする(比))
}

fn 縦横比にする((幅, 高さ): (f64, f64)) -> Option<縦横比> {
    画素の寸法::作成する(幅, 高さ)
        .ok()
        .and_then(|寸法| 寸法.縦横比())
}

#[test]
fn 大きめは縁の余白を除いた中へ縦横比を保って収める() {
    let 寸法 = 求める(
        出力の描き方::表示サイズで(表示サイズ::大きめ),
        1032.0,
        632.0,
        十六対九,
    );
    assert_eq!(寸法, 画素の組(1000.0, 563.0));
    let 寸法 = 求める(
        出力の描き方::表示サイズで(表示サイズ::大きめ),
        1032.0,
        432.0,
        十六対九,
    );
    assert_eq!(寸法, 画素の組(711.0, 400.0));
}

#[test]
fn 標準は大きめの0点84倍の中へ収める() {
    let 寸法 = 求める(
        出力の描き方::表示サイズで(表示サイズ::標準),
        1032.0,
        632.0,
        十六対九,
    );
    assert_eq!(寸法, 画素の組(840.0, 473.0));
}

#[test]
fn 横幅優先は幅いっぱいにし_余白なしは覆う() {
    let 横幅優先 = 求める(
        出力の描き方::表示サイズで(表示サイズ::横幅優先),
        1032.0,
        432.0,
        十六対九,
    );
    assert_eq!(横幅優先, 画素の組(1000.0, 563.0));
    let 余白なし = 求める(
        出力の描き方::表示サイズで(表示サイズ::余白なし),
        1032.0,
        632.0,
        (1.0, 1.0),
    );
    assert_eq!(余白なし, 画素の組(1000.0, 1000.0));
}

#[test]
fn 小さい欄でも最小の320と180を保つ() {
    let 寸法 = 求める(
        出力の描き方::表示サイズで(表示サイズ::大きめ),
        100.0,
        100.0,
        十六対九,
    );
    assert_eq!(寸法, 画素の組(320.0, 180.0));
}

#[test]
fn シアターは縁の余白を置かずウインドウ全体の使える大きさへ縦横比を保って収める() {
    let 横に余るウインドウ = 求める(出力の描き方::シアター, 1920.0, 900.0, (4.0, 3.0));
    assert_eq!(横に余るウインドウ, 画素の組(1200.0, 900.0));
    let 縦に余るウインドウ = 求める(出力の描き方::シアター, 1440.0, 900.0, 十六対九);
    assert_eq!(縦に余るウインドウ, 画素の組(1440.0, 810.0));
    let 同じ比のウインドウ = 求める(出力の描き方::シアター, 1600.0, 900.0, 十六対九);
    assert_eq!(同じ比のウインドウ, 画素の組(1600.0, 900.0));
}

#[test]
fn 縦横比が0なら16対9とみなす() {
    let 寸法 = 求める(
        出力の描き方::表示サイズで(表示サイズ::大きめ),
        1032.0,
        632.0,
        (0.0, 9.0),
    );
    assert_eq!(寸法, 画素の組(1000.0, 563.0));
}

#[test]
fn 縦横比が無ければ16対9とみなす() {
    let 寸法 = 出力の描き方::表示サイズで(表示サイズ::大きめ)
        .寸法を求める(画素の組(1032.0, 632.0), None);
    assert_eq!(寸法, 画素の組(1000.0, 563.0));
}
