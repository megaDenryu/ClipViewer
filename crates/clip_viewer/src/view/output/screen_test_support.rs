//! 出力の画面の試験の道具。2×1画素の映像を登録し、左端0.25・右端0.5の描く部分で、構えと左右の向きと待ちの案内を決めた材料を作る。

use eframe::egui;
use sengen_egui::{
    割合, 割合で表した矩形, 差し替えられるテクスチャ, 拡大縮小の仕方, 画素の並び, 画素数の寸法,
};

use super::screen::出力の画面の材料;
use super::size::出力の描き方;
use super::theater_controls::操作の欄の出し方;
use crate::state::{左右の向き, 画面の構え, 表示サイズ};

/// 試験の材料の選び方とは、試験ごとに変える、出力の画面の材料の値の組のことである。
pub(super) struct 試験の材料の選び方 {
    pub(super) 構え: 画面の構え,
    pub(super) 左右: 左右の向き,
    pub(super) 待ちの案内: Option<String>,
}

impl 試験の材料の選び方 {
    /// 映像を画面描画の共有状態へ登録し、選んだ値で出力の画面の材料を作る。出し入れの指定はアプリと同じものを使う。
    pub(super) fn 材料を作る(
        self,
        画面描画の共有状態: &egui::Context,
    ) -> 出力の画面の材料 {
        let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
            画素数の寸法::生成する(2, 1),
            &[0; 8],
        )
        .unwrap_or_else(|不正| panic!("画素の並びが不正: {不正}"));
        let テクスチャ = 差し替えられるテクスチャ::登録して作る(
            画面描画の共有状態,
            "試験",
            画素,
            拡大縮小の仕方::隣の画素と混ぜる,
        );
        let 割合にする = 割合::範囲へ丸めて生成する;
        let 描く部分 = 割合で表した矩形::生成する(
            割合にする(0.25),
            割合にする(0.0),
            割合にする(0.5),
            割合にする(1.0),
        )
        .unwrap_or_else(|不正| panic!("矩形が不正: {不正}"));
        出力の画面の材料 {
            映像: テクスチャ.参照を複製する(),
            描く部分,
            左右: self.左右,
            縦横比: None,
            描き方: 出力の描き方::表示サイズで(表示サイズ::大きめ),
            待ちの案内: self.待ちの案内,
            次へを出すか: false,
            構え: self.構え,
            操作の出し入れ: 操作の欄の出し方(),
        }
    }
}
