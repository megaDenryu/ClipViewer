//! シアターの操作の欄の出し入れの指定の試験。時刻・マウスの動き・欄の上・ドラッグの間・窓の外へ出た回の規則そのものは、
//! SengenEgui の tests/overlay_idle*.rs が確かめる。ここでは、指定が再生しているかに依らず一時停止中も隠すことと、
//! 左右キーで出すことと、「編集へ戻る」と同じ組に入ることだけを確かめる。

use std::time::Duration;

use sengen_egui::{
    キー, ポインタが止まると隠す指定, ポインタが止まると隠す組
};

use super::theater_controls::操作の欄の出し方;

#[test]
fn 一時停止中も含めてマウスを止めてから2秒半で隠しカーソルも隠し_左右キーで出す() {
    let 期待 = ポインタが止まると隠す指定::作成する(Duration::from_millis(2500))
        .隠している間はカーソルも隠す()
        .キーを押している間は出す(&[キー::ArrowLeft, キー::ArrowRight])
        .組にする(ポインタが止まると隠す組::作成する(
            "シアターの操作",
        ));
    assert_eq!(操作の欄の出し方(), 期待);
}

#[test]
fn 一時停止中も出したままにしない() {
    assert_ne!(
        操作の欄の出し方(),
        操作の欄の出し方().出したままにする(true)
    );
}
