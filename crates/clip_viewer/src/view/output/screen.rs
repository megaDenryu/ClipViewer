//! 出力の画面。使える大きさから出力の寸法を求め、クロップを描く部分として切り出して引き伸ばし、
//! 前へと Next のボタン・トリガー待ちの案内・シアターの「編集へ戻る」を上に重ねる。
//! 「編集へ戻る」はシアターで右上に出し、操作の欄と同じ組で出し入れする(マウスを動かしたときだけ出し、止めて2.5秒で隠す)。
//! シアターでは下端に操作の欄を重ねるため(theater_controls.rs)、Next ボタンは操作の欄の中へ移し、トリガー待ちの札は上の辺へ置く。

use clip_domain::{縦横比, 進める操作};
use sengen_egui::{
    ノード, ボタン, ポインタが止まると隠す指定, 余白, 割合で表した矩形, 大きさを決めた領域, 子,
    文字表示, 横並び, 画像, 登録したテクスチャの参照, 縦横の論理画素, 縦積み, 論理画素, 重ねる,
    重ねる位置,
};

use super::size::出力の描き方;
use crate::command::{出力の操作, 応答};
use crate::state::{左右の向き, 画面の構え};
use crate::view::styles;

fn 出力(操作: 出力の操作) -> 応答 {
    応答::出力(操作)
}

/// 出力の画面の材料とは、使える大きさが分かってから出力の画面を組むために、状態から先に取り出しておく値の組のことである。
/// 描く時点で使える大きさを測る部品へ所有させて渡すため、状態を借りずに持つ。
#[derive(Clone)]
pub(crate) struct 出力の画面の材料 {
    pub(crate) 映像: 登録したテクスチャの参照,
    pub(crate) 描く部分: 割合で表した矩形,
    pub(crate) 左右: 左右の向き,
    pub(crate) 縦横比: Option<縦横比>,
    pub(crate) 描き方: 出力の描き方,
    pub(crate) 待ちの案内: Option<String>,
    pub(crate) 次へを出すか: bool,
    pub(crate) 構え: 画面の構え,
    pub(crate) 操作の出し入れ: ポインタが止まると隠す指定, // シアターの「編集へ戻る」を操作の欄と同じ組で出し入れする
}

impl 出力の画面の材料 {
    /// 使える大きさの欄の中央へ出力を描き、上に重ねるものを置く。
    pub(crate) fn 組む(&self, 使える大きさ: 縦横の論理画素) -> ノード<応答> {
        let 寸法 = self.描き方.寸法を求める(使える大きさ, self.縦横比);
        let 上の余白 = ((使える大きさ.縦 - 寸法.縦) * 0.5).大きい方(論理画素::ゼロ);
        let 映像 = 画像(&self.映像)
            .描く部分(self.描く部分)
            .表示寸法へ引き伸ばす(寸法);
        let 映像 = match self.左右 {
            左右の向き::そのまま => 映像,
            左右の向き::反転 => 映像.左右を反転する(),
        }
        .押されたら発する(出力(出力の操作::次へ進める(
            進める操作::出力のクリック,
        )));
        let 欄 = 大きさを決めた領域(使える大きさ, 子![余白(上の余白), 映像]).中央寄せ();
        let mut 重ね = 重ねる("出力の画面", 欄);
        // 注意: 重ねる子の大きさの記憶の識別子は、寄せる位置と、同じ位置の中での番号の組である。下の3つは位置が別なので、
        // 出入りしても互いの識別子を変えない。同じ位置へ子を足すときは、出入りする子をその位置の後ろに置く。
        let シアターか = self.構え == 画面の構え::シアター;
        if self.次へを出すか && !シアターか {
            重ね = 重ね.上に置く(重ねる位置::右下, 前へと次への行());
        }
        if let Some(案内) = &self.待ちの案内 {
            let 札の位置 = if シアターか {
                重ねる位置::上
            } else {
                重ねる位置::下
            };
            重ね = 重ね.上に置く(札の位置, トリガー待ちの札(案内));
        }
        if シアターか {
            let 戻る = ボタン("編集へ戻る", 出力(出力の操作::構えを選ぶ(画面の構え::編集)));
            重ね = 重ね.ポインタが止まると隠して上に置く(
                重ねる位置::右上,
                self.操作の出し入れ,
                戻る,
            );
        }
        重ね.into()
    }
}

/// 前へと Next Clip のボタンの行。前へは前の再生できるクリップの開始へ戻る(先頭のクリップではその開始へ)。
pub(super) fn 前へと次への行() -> ノード<応答> {
    横並び(子![
        ボタン("前へ", 出力(出力の操作::前のクリップへ戻る)),
        ボタン(
            "Next Clip",
            出力(出力の操作::次へ進める(
                進める操作::トリガーを待たずに進める
            ))
        )
        .装飾(styles::強調ボタン),
    ])
    .into()
}

/// トリガー待ちの札。移植元の覆いと違い出力の全体を覆わず、下に置いて出力を押せるままにする(クリック待ちのため)。
fn トリガー待ちの札(案内: &str) -> ノード<応答> {
    縦積み(子![
        文字表示("トリガー待機中").装飾(styles::見出し),
        文字表示(案内),
        ボタン(
            "Next Clip",
            出力(出力の操作::次へ進める(
                進める操作::トリガーを待たずに進める
            ))
        )
        .装飾(styles::強調ボタン),
    ])
    .装飾(styles::トリガー待ちの札)
    .into()
}
