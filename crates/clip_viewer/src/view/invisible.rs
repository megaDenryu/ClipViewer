//! 見えない部品。キーの割り当て、ウインドウへ落とされたファイルの受け取り、入力が無くても画面を進める予約を束ねる。

use std::time::Duration;

use sengen_egui::{
    ノード, 子, 描き直しを予約する, 無し, 縦積み, 落とされたファイルをまとめて受け取る,
};

use super::keys;
use crate::command::{ファイルの操作, 一度に落としたファイル, 応答};
use crate::redraw_interval::{サムネイルの返事を待つ間隔, 描き直しの間隔};
use crate::state::{アプリの状態, 画面の構え};

pub(super) fn 見えない部品(
    状態: &アプリの状態,
    重ね合わせの作業場の描き直すまでの時間: Option<Duration>,
) -> ノード<応答> {
    縦積み(子![
        keys::キー操作の一覧(状態),
        落とされたファイルをまとめて受け取る(落としたファイルを開く),
        描き直しの予約(状態, 重ね合わせの作業場の描き直すまでの時間),
    ])
    .into()
}

/// 1回にウインドウへ落とされたファイルをまとめて開く応答。動画か設定ファイルかは、適用するときに拡張子で見分ける。
fn 落としたファイルを開く(パス一覧: Vec<std::path::PathBuf>) -> 応答 {
    応答::ファイル(ファイルの操作::落としたファイルを開く(
        一度に落としたファイル::作成する(パス一覧),
    ))
}

/// 入力が無くても画面を進めるなら、描き直しを予約する。スタックの作業場の時間と、控えている重ね合わせの作業場の時間の短いほうで予約する。
fn 描き直しの予約(
    状態: &アプリの状態,
    重ね合わせの作業場の描き直すまでの時間: Option<Duration>,
) -> ノード<応答> {
    match 描き直すまでの時間(状態)
        .into_iter()
        .chain(重ね合わせの作業場の描き直すまでの時間)
        .min()
    {
        Some(待つ時間) => 描き直しを予約する(待つ時間).into(),
        None => 無し(),
    }
}

/// 入力が無くても画面を進めるなら、次に描き直すまでの時間。再生中、溜めている途中、最初のコマや流し読みのコマを待っている間と、
/// ライブラリの裏のスレッドの返事を待っている間は、描き直しの間隔で進める。サムネイルは `サムネイルのために描き直すまでの時間` が決める。登録済みのスタックの並びが書けるのを待っている間
/// (落ち着き待ちと、保存に失敗した後の頼み直し)は、並びを次に見る時刻に合わせて進める。保存できない間に毎フレーム描き直さないためである。
/// 見る側の設定(ウインドウの大きさ・音量等)が変わって落ち着くのを待っている間も、保存する時刻に合わせて進める(画面.md 判断17)。
pub(crate) fn 描き直すまでの時間(状態: &アプリの状態) -> Option<Duration> {
    let 続けて進めるか = 状態.ライブラリ.接続.返事を待っているか()
        || 状態.動画.as_ref().is_some_and(|動画| {
            状態.再生.再生しているか()
                || 動画.台帳().溜めている途中か()
                || 動画.映像().まだ映していないか()
                || 動画.流し読みのコマを待っているか()
                || 動画.台帳().依頼を出すのを待っているか()
        });
    if 続けて進めるか {
        return Some(描き直しの間隔);
    }
    let 並びを見るまで = 状態
        .ライブラリ
        .次に並びを見るまでの時間
        .map(|残り| 残り.max(描き直しの間隔));
    let 見る側の設定を保存するまで = 状態
        .見る側の設定を保存するまでの時間
        .map(|残り| 残り.max(描き直しの間隔));
    [
        並びを見るまで,
        見る側の設定を保存するまで,
        サムネイルのために描き直すまでの時間(状態),
    ]
    .into_iter()
    .flatten()
    .min()
}

/// サムネイルのために描き直すまでの時間。ライブラリの構えで、見せる行(絞り込みの後の行)にキャッシュを見る前の行が残っている間は、
/// 描き直しの間隔で進める。絞り込みで隠れた行はキャッシュを見る仕事が回らないため、数えると描き直しが止まらない。
/// キャッシュを見る仕事はフレームごとに頼むため、0.1秒ごとでは400件の一覧を見終えるのに約5秒かかる。
/// それ以外で裏のスレッドの返事を待っている間は、0.1秒ごとに受け取る。
fn サムネイルのために描き直すまでの時間(
    状態: &アプリの状態
) -> Option<Duration> {
    if 状態.出力.構え == 画面の構え::ライブラリ && 状態.見せる行にキャッシュを見る前の行があるか()
    {
        return Some(描き直しの間隔);
    }
    状態
        .ライブラリ
        .サムネイル
        .返事を待っているか()
        .then_some(サムネイルの返事を待つ間隔)
}
