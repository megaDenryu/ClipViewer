//! 割合と百分率の変換の試験。
#![allow(clippy::expect_used)]

use clip_domain::{クロップ範囲, 四隅のつまみ};
use sengen_egui::{
    割合の差, 範囲枠の掴んだ部分, 範囲枠の操作, 縦横の割合の差
};

use super::conversion::範囲枠の操作を変換する;
use crate::command::{クロップ枠の掴む所, クロップ枠の操作};
use crate::output_measure::クロップを描く部分にする;

fn 近い(左: f32, 右: f32) -> bool {
    (左 - 右).abs() < 1e-6
}

#[test]
fn クロップ範囲の百分率を割合の矩形にし_はみ出す右端は1に収める() {
    let 矩形 = クロップを描く部分にする(
        クロップ範囲::各値を範囲へ収めて作成する(10.0, 20.0, 50.0, 30.0),
    );
    assert!(近い(矩形.左端().eguiへ渡す値(), 0.1));
    assert!(近い(矩形.上端().eguiへ渡す値(), 0.2));
    assert!(近い(矩形.右端().eguiへ渡す値(), 0.6));
    assert!(近い(矩形.下端().eguiへ渡す値(), 0.5));
    let はみ出す = クロップを描く部分にする(
        クロップ範囲::各値を範囲へ収めて作成する(80.0, 0.0, 50.0, 100.0),
    );
    assert!(近い(はみ出す.右端().eguiへ渡す値(), 1.0));
}

#[test]
fn 範囲枠の移動量の割合の差を百分率の差分にし_隅を四隅のつまみにする() {
    let 移動量 =
        縦横の割合の差::生成する(割合の差::生成する(0.25), 割合の差::生成する(-0.5));
    let 操作 = 範囲枠の操作::放した {
        掴んだ部分: 範囲枠の掴んだ部分::右上の隅,
        開始点からの移動量: 移動量,
    };
    let クロップ枠の操作::放した {
        掴む所, 移動量
    } = 範囲枠の操作を変換する(操作)
    else {
        panic!("放したへ変換されない");
    };
    assert_eq!(掴む所, クロップ枠の掴む所::隅(四隅のつまみ::右上));
    let 動かした =
        クロップ範囲::各値を範囲へ収めて作成する(0.0, 60.0, 50.0, 40.0).移動する(移動量);
    assert!((動かした.左端().数値() - 25.0).abs() < 1e-6);
    assert!((動かした.上端().数値() - 10.0).abs() < 1e-6);
}

#[test]
fn 数でない移動量は移動量が数でない操作にする() {
    let 移動量 = 縦横の割合の差::生成する(割合の差::生成する(f32::NAN), 割合の差::ゼロ);
    let 操作 = 範囲枠の操作::動かしている {
        掴んだ部分: 範囲枠の掴んだ部分::内側,
        開始点からの移動量: 移動量,
    };
    assert_eq!(
        範囲枠の操作を変換する(操作),
        クロップ枠の操作::移動量が数でない
    );
}
