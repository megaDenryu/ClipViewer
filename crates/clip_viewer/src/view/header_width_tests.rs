//! ヘッダーの幅の試験。最初のウインドウの幅(1200論理画素)で、最後に置いた「同時再生」までのヘッダーの部品がウインドウの中に収まることを、
//! 未登録で「ライブラリに保存」を出す状態と、登録済みで保存に失敗した状態で確かめる。
//! 注意: 最小の幅(800論理画素)では、この2つの状態のライブラリの様子は「同時再生」を足す前から右端がはみ出す(「ライブラリに保存」の右端は約850、
//! 保存に失敗の文の右端は約1110)。「同時再生」を最後に置いたため、前からある部品の位置は足す前と変わらない。
#![allow(clippy::expect_used)]

use clip_domain::{
    スタックの名前, スタックの識別子, ライブラリのスタック, ライブラリの日時, 入力された動画パス,
};
use clip_library::{スタックのライブラリ, ライブラリのフォルダ};
use eframe::egui;

use super::header::ヘッダー;
use super::test_support::{
    動画の無い状態, 大きさを決めて描く, 描いた文字の範囲
};
use crate::state::library::{
    ライブラリの接続, ライブラリを使えない理由, 登録済みのスタック, 開いているスタック,
};
use crate::state::{アプリの状態, 画面の構え};

const 最初の大きさの画面: egui::Vec2 = egui::vec2(1200.0, 620.0);

/// 一時フォルダのライブラリへ書ける、編集の構えの状態。試験ごとに名前で一時フォルダを分ける。
fn 書けるライブラリの状態(名前: &str) -> アプリの状態 {
    let フォルダ = std::env::temp_dir().join(format!(
        "clip_viewer_ヘッダーの幅_{名前}_{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&フォルダ);
    std::fs::create_dir_all(&フォルダ).expect("フォルダを作れる");
    let mut 状態 = 動画の無い状態(画面の構え::編集);
    状態.ライブラリ.接続 =
        ライブラリの接続::錠を試したライブラリから起動する(Some(
            スタックのライブラリ::作成する(ライブラリのフォルダ::作成する(フォルダ)).錠を試す(),
        ));
    状態
}

fn 右端が画面に収まるか(状態: &アプリの状態, 右端の文字: &str) -> bool {
    let 画面描画の共有状態 =
        super::test_support::日本語フォントとテーマを当てた本体を作る();
    let 木 = || ヘッダー(状態);
    let (_, 出力) =
        大きさを決めて描く(&画面描画の共有状態, 最初の大きさの画面, Vec::new(), &木);
    描いた文字の範囲(&出力, 右端の文字).right() <= 最初の大きさの画面.x
}

#[test]
fn 未登録で_ライブラリに保存を出す状態でも_最初の幅のヘッダーの同時再生まで画面に収まる() {
    let 状態 = 書けるライブラリの状態("未登録");
    assert!(右端が画面に収まるか(&状態, "ライブラリに保存"));
    assert!(右端が画面に収まるか(&状態, "同時再生"));
}

#[test]
fn 登録済みで保存に失敗した状態でも_最初の幅のヘッダーの同時再生まで画面に収まる() {
    let mut 状態 = 書けるライブラリの状態("保存に失敗");
    let mut 登録済み =
        登録済みのスタック::ファイルから開いた(ライブラリのスタック::新しく作る(
            スタックの識別子::文字列から作成する("stack-1-1".to_string()).expect("識別子"),
            スタックの名前::作成する("練習".to_string()).expect("名前"),
            入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
            状態.並び.clone(),
            ライブラリの日時::紀元からのミリ秒で作成する(1_000).expect("日時"),
        ));
    登録済み.保存を頼めなかった(ライブラリを使えない理由::置き場所が無い);
    状態.ライブラリ.開いている = 開いているスタック::登録済み(登録済み);
    let 文 = format!("保存に失敗: {}", ライブラリを使えない理由::置き場所が無い);
    assert!(右端が画面に収まるか(&状態, &文));
    assert!(右端が画面に収まるか(&状態, "同時再生"));
}
