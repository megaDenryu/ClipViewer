//! ヘッダーの幅の試験。最初のウインドウの幅(1200論理画素)で、実際のヘッダーの区画(内余白10)に描いたとき、最後に置いた「同時再生」までの部品が
//! ウインドウの中に収まることを、未登録で「ライブラリに保存」を出す状態と、登録済みで短い理由(ライブラリの置き場所が無い)で保存に失敗した状態で確かめる。
//! 注意: 保存に失敗した理由が長いとき(「<パス> を読み書きできない: <原因>」等)は、1200でもライブラリの様子が「同時再生」を右の外へ押し出す。
//! 最小の幅(800論理画素)では、この2つの状態のライブラリの様子は「同時再生」を足す前から右端がはみ出す。説明書 15.2 に書いた。
#![allow(clippy::expect_used)]

use std::path::PathBuf;

use clip_domain::{
    スタックの名前, スタックの識別子, ライブラリのスタック, ライブラリの日時, 入力された動画パス,
};
use clip_library::{スタックのライブラリ, ライブラリのフォルダ};
use eframe::egui;

use super::test_support::{
    動画の無い状態, 大きさを決めて描く, 描いた文字の範囲, 日本語フォントとテーマを当てた本体を作る,
};
use crate::library_common::save::ライブラリを使えない理由;
use crate::state::library::{
    ライブラリの接続, 登録済みのスタック, 開いているスタック
};
use crate::state::{アプリの状態, 画面の構え};

const 最初の大きさの画面: egui::Vec2 = egui::vec2(1200.0, 620.0);

/// 試験の一時フォルダとは、試験ごとに名前で分けたライブラリの置き場所のことである。落とすとフォルダを消す。
struct 試験の一時フォルダ(PathBuf);

impl 試験の一時フォルダ {
    fn 作る(名前: &str) -> Self {
        let フォルダ = std::env::temp_dir().join(format!(
            "clip_viewer_ヘッダーの幅_{名前}_{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&フォルダ);
        std::fs::create_dir_all(&フォルダ).expect("フォルダを作れる");
        Self(フォルダ)
    }

    /// このフォルダのライブラリへ書ける、編集の構えの状態。
    fn 書けるライブラリの状態(&self) -> アプリの状態 {
        let mut 状態 = 動画の無い状態(画面の構え::編集);
        状態.ライブラリ.接続 =
            ライブラリの接続::錠を試したライブラリから起動する(Some(
                スタックのライブラリ::作成する(ライブラリのフォルダ::作成する(
                    self.0.clone(),
                ))
                .錠を試す(),
            ));
        状態
    }
}

impl Drop for 試験の一時フォルダ {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

/// 実際のヘッダーの区画(ヘッダーの地の内余白を含む)を最初の大きさの画面に描き、その文字の右端が画面の中にあるか。
fn 右端が画面に収まるか(状態: &アプリの状態, 文字: &str) -> bool {
    let 画面描画の共有状態 = 日本語フォントとテーマを当てた本体を作る();
    let 木 = || super::ヘッダーの区画(状態);
    let (_, 出力) =
        大きさを決めて描く(&画面描画の共有状態, 最初の大きさの画面, Vec::new(), &木);
    描いた文字の範囲(&出力, 文字).right() <= 最初の大きさの画面.x
}

#[test]
fn 未登録で_ライブラリに保存を出す状態では_最初の幅のヘッダーの同時再生まで画面に収まる() {
    let フォルダ = 試験の一時フォルダ::作る("未登録");
    let 状態 = フォルダ.書けるライブラリの状態();
    assert!(右端が画面に収まるか(&状態, "ライブラリに保存"));
    assert!(右端が画面に収まるか(&状態, "同時再生"));
    drop(状態);
}

#[test]
fn 登録済みで短い理由で保存に失敗した状態では_最初の幅のヘッダーの同時再生まで画面に収まる() {
    let フォルダ = 試験の一時フォルダ::作る("短い理由");
    let mut 状態 = フォルダ.書けるライブラリの状態();
    let mut 登録済み =
        登録済みのスタック::ファイルから開いた(ライブラリのスタック::新しく作る(
            スタックの識別子::文字列から作成する("stack-1-1".to_string()).expect("識別子"),
            スタックの名前::作成する("練習".to_string()).expect("名前"),
            入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
            状態.並び.clone(),
            ライブラリの日時::紀元からのミリ秒で作成する(1_000).expect("日時"),
        ));
    登録済み
        .保存を頼めなかったことを覚える(ライブラリを使えない理由::置き場所が無い);
    状態.ライブラリ.開いている = 開いているスタック::登録済み(登録済み);
    let 文 = format!("保存に失敗: {}", ライブラリを使えない理由::置き場所が無い);
    assert!(右端が画面に収まるか(&状態, &文));
    assert!(右端が画面に収まるか(&状態, "同時再生"));
    drop(状態);
}
