//! スタックのライブラリの画面。ライブラリの構えで、ヘッダーの下を一覧の区画にする。ヘッダーに出す登録の様子と、ダイアログもここに置く。
//! 参照: _doc/設計/ライブラリ.md 判断8

mod dialog;
mod discard_dialog;
mod row;
mod row_source;
mod rows;
mod status;
mod toolbar;

pub(crate) use dialog::開いているダイアログ;
pub(crate) use status::ヘッダーのライブラリの様子;

use sengen_egui::{ノード, パネル, パネルの位置, 子, 縦積み};

use crate::command::応答;
use crate::library_common::view::{
    一覧の文言, 一覧の本体の出し方, 読み取り専用の理由の出し方
};
use crate::state::アプリの状態;
use crate::styles;

pub(crate) fn ライブラリの区画(状態: &アプリの状態) -> ノード<応答> {
    パネル(
        "ライブラリ",
        パネルの位置::中央,
        子![縦積み(子![
            toolbar::道具の帯(状態),
            一覧の文言.置き場所の文(状態.ライブラリ.接続.使える様子()),
            一覧の本体(状態),
        ])],
    )
    .装飾(styles::左サイドバーの地)
    .into()
}

/// スタックの一覧の文言。ヘッダーの登録の様子(`status.rs`)も使う。
pub(super) const 一覧の文言: 一覧の文言 = 一覧の文言 {
    ライブラリの呼び名: "ライブラリ",
    フォルダの呼び名: "ライブラリのフォルダ",
    読み取り専用でできないこと: "登録・保存・名前の変更・複製・削除・取り込み",
    置き場所が無いときにできないこと: "保存も一覧もできない",
    空のときの文: "ライブラリにスタックがありません",
    空のときの案内: "編集の構えで動画を開いてクリップを作り、ヘッダーの「ライブラリに保存」で登録する",
    読み取り専用の理由: 読み取り専用の理由の出し方::一覧の画面へ回す,
};

/// 一覧の本体。置き場所が無いときは何も出さず、読めた一覧が空でなければ行を並べる。
fn 一覧の本体(状態: &アプリの状態) -> ノード<応答> {
    match 一覧の文言.一覧の本体の出し方(
        状態.ライブラリ.接続.使える様子(),
        状態.ライブラリ.一覧.一覧(),
    ) {
        一覧の本体の出し方::文を出す(文) => 文,
        一覧の本体の出し方::行を並べる(一覧) => {
            rows::一覧の行の並び(状態, &一覧)
        }
    }
}
