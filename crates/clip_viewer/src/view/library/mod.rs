//! スタックのライブラリの画面。ライブラリの構えで、ヘッダーの下を一覧の区画にする。ヘッダーに出す登録の様子と、窓もここに置く。
//! 参照: _doc/設計/ライブラリ.md 判断8

mod dialog;
mod discard_dialog;
mod row;
mod row_source;
mod rows;
mod status;
mod thumbnail;
mod toolbar;

pub(crate) use dialog::開いている窓;
pub(crate) use status::ヘッダーのライブラリの様子;

use sengen_egui::{ノード, パネル, パネルの位置, 子, 文字表示, 縦積み};

use crate::command::応答;
use crate::state::library::{ライブラリの使える様子, 最後に読んだ一覧};
use crate::state::アプリの状態;
use crate::view::styles;

pub(crate) fn ライブラリの区画(状態: &アプリの状態) -> ノード<応答> {
    パネル(
        "ライブラリ",
        パネルの位置::中央,
        子![縦積み(子![
            toolbar::道具の帯(状態),
            置き場所の文(状態),
            一覧の本体(状態),
        ])],
    )
    .装飾(styles::左サイドバーの地)
    .into()
}

fn 置き場所の文(状態: &アプリの状態) -> ノード<応答> {
    match 状態.ライブラリ.接続.使える様子() {
        ライブラリの使える様子::書ける(フォルダ) => {
            文字表示(format!("置き場所: {}", フォルダ.パス().display())).装飾(styles::補足).into()
        }
        ライブラリの使える様子::読むだけ(フォルダ, 理由) => 文字表示(format!(
            "読み取り専用: {理由}。開くことはできるが、登録・保存・名前の変更・複製・削除・取り込みはできない(置き場所: {})",
            フォルダ.パス().display()
        ))
        .装飾(styles::不備の文)
        .into(),
        ライブラリの使える様子::置き場所が無い => {
            文字表示("ライブラリの置き場所が無い(環境変数 APPDATA が無い)ため、保存も一覧もできない")
                .装飾(styles::不備の文)
                .into()
        }
    }
}

/// 一覧の本体。置き場所が無いときは一覧を読まないため、置き場所の文だけにして「一覧を読んでいる」を出さない。
fn 一覧の本体(状態: &アプリの状態) -> ノード<応答> {
    if let ライブラリの使える様子::置き場所が無い = 状態.ライブラリ.接続.使える様子()
    {
        return sengen_egui::無し();
    }
    match 状態.ライブラリ.一覧.一覧() {
        最後に読んだ一覧::まだ無い => {
            文字表示("一覧を読んでいる").装飾(styles::補足).into()
        }
        最後に読んだ一覧::読めない(理由) => {
            文字表示(format!("ライブラリのフォルダを読めない: {理由}"))
                .装飾(styles::不備の文)
                .into()
        }
        最後に読んだ一覧::読めた(一覧) if 一覧.項目.is_empty() => 縦積み(子![
            文字表示("ライブラリにスタックがありません"),
            文字表示(
                "編集の構えで動画を開いてクリップを作り、ヘッダーの「ライブラリに保存」で登録する"
            )
            .装飾(styles::補足),
        ])
        .into(),
        最後に読んだ一覧::読めた(一覧) => rows::一覧の行の並び(状態, 一覧),
    }
}
