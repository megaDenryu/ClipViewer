//! ライブラリの一覧の道具の帯。件数・名前の絞り込み・並べ替え・読み直す・ブラウザ版の設定の取り込みを横に並べる。

use sengen_egui::{ノード, ボタン, 子, 文字表示, 横並び};

use crate::command::{ライブラリの操作, 応答};
use crate::library_common::list::並べ替え方;
use crate::library_common::view::{件数の文, 絞り込みと並べ替えの材料};
use crate::state::アプリの状態;
use crate::styles;

fn ライブラリ(操作: ライブラリの操作) -> 応答 {
    応答::ライブラリ(操作)
}

fn 絞り込みを書き換えた(文字列: String) -> 応答 {
    ライブラリ(ライブラリの操作::絞り込みを書き換える(
        文字列,
    ))
}

fn 並べ替えを選んだ(並べ替え: 並べ替え方) -> 応答 {
    ライブラリ(ライブラリの操作::並べ替えを選ぶ(並べ替え))
}

pub(super) fn 道具の帯(状態: &アプリの状態) -> ノード<応答> {
    let 件数 = 件数の文(状態.ライブラリ.一覧.一覧());
    let 見せ方 = 状態.ライブラリ.一覧.見せ方();
    let 絞り込みと並べ替え = 絞り込みと並べ替えの材料 {
        絞り込みの文字列: 見せ方.絞り込み.文字列(),
        並べ替え: 見せ方.並べ替え,
        並べ替えの識別子: "ライブラリの並べ替え",
        絞り込みを書き換えた,
        並べ替えを選んだ,
    };
    横並び(
        子![
            文字表示("ライブラリ").装飾(styles::見出し),
            文字表示(件数).装飾(styles::補足),
        ]
        .into_iter()
        .chain(絞り込みと並べ替え.部品の並び())
        .chain(子![
            ボタン("読み直す", ライブラリ(ライブラリの操作::読み直す)),
            ボタン(
                "v4.0 JSON を取り込む",
                ライブラリ(ライブラリの操作::取り込む)
            )
            .有効(状態.ライブラリ.接続.書けるか()),
        ])
        .collect(),
    )
    .into()
}
