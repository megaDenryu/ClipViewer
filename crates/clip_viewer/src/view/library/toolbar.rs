//! ライブラリの一覧の道具の帯。件数・名前の絞り込み・並べ替え・読み直す・ブラウザ版の設定の取り込みを横に並べる。

use sengen_egui::{
    ノード, ボタン, 一行テキスト入力, 子, 文字表示, 横並び, 画素, 選択欄, 選択肢
};

use crate::command::{ライブラリの操作, 応答};
use crate::state::library::{並べ替え方, 最後に読んだ一覧};
use crate::state::アプリの状態;
use crate::view::styles;

fn ライブラリ(操作: ライブラリの操作) -> 応答 {
    応答::ライブラリ(操作)
}

fn 並べ替え方の名前(並べ替え: 並べ替え方) -> &'static str {
    match 並べ替え {
        並べ替え方::更新日時の新しい順 => "更新日時の新しい順",
        並べ替え方::更新日時の古い順 => "更新日時の古い順",
        並べ替え方::名前順 => "名前順",
        並べ替え方::作った日時の新しい順 => "作った日時の新しい順",
    }
}

pub(super) fn 道具の帯(状態: &アプリの状態) -> ノード<応答> {
    let 件数 = match 状態.ライブラリ.一覧.一覧() {
        最後に読んだ一覧::読めた(一覧) => format!("{}件", 一覧.項目.len()),
        最後に読んだ一覧::まだ無い | 最後に読んだ一覧::読めない(_) => {
            String::new()
        }
    };
    let 見せ方 = 状態.ライブラリ.一覧.見せ方();
    横並び(子![
        文字表示("ライブラリ").装飾(styles::見出し),
        文字表示(件数).装飾(styles::補足),
        一行テキスト入力(見せ方.絞り込み.文字列(), |文字列| {
            ライブラリ(ライブラリの操作::絞り込みを書き換える(
                文字列,
            ))
        })
        .案内文("名前で絞り込む")
        .幅(画素(200.0)),
        選択欄(
            "ライブラリの並べ替え",
            並べ替え方の名前(見せ方.並べ替え),
            並べ替え方::一覧
                .map(|並べ替え| 選択肢(
                    並べ替え方の名前(並べ替え),
                    ライブラリ(ライブラリの操作::並べ替えを選ぶ(並べ替え))
                ))
                .into_iter()
                .collect(),
        ),
        ボタン("読み直す", ライブラリ(ライブラリの操作::読み直す)),
        ボタン(
            "v4.0 JSON を取り込む",
            ライブラリ(ライブラリの操作::取り込む)
        )
        .有効(状態.ライブラリ.接続.書けるか()),
    ])
    .into()
}
