//! ライブラリのダイアログ。名前を付けて登録する・名前を変える・削除を確かめる・未登録の並びを捨てて続けるかを確かめる(`discard_dialog.rs`)・
//! 保存できないまま続けるかを確かめる。外側を押すか Escape で閉じようとしたら、ダイアログを閉じる操作を発する。

use sengen_egui::{
    ノード, ボタン, モーダル, 一行テキスト入力, 子, 文字表示, 横並び, 無し, 画素
};

use crate::command::{ライブラリの操作, 応答};
use crate::state::library::{ライブラリのダイアログ, 入力中の名前};
use crate::state::アプリの状態;
use crate::view::styles;

fn ライブラリ(操作: ライブラリの操作) -> 応答 {
    応答::ライブラリ(操作)
}

pub(crate) fn 開いているダイアログ(状態: &アプリの状態) -> ノード<応答> {
    let 中身: Vec<ノード<応答>> = match &状態.ライブラリ.ダイアログ {
        ライブラリのダイアログ::無し => return 無し(),
        ライブラリのダイアログ::名前を付けて登録(入力, _) => {
            名前のダイアログ(
                "ライブラリに保存する名前",
                入力,
                "保存する",
                ライブラリの操作::登録する,
            )
        }
        ライブラリのダイアログ::名前を変える(_, 入力) => {
            名前のダイアログ(
                "新しい名前",
                入力,
                "名前を変える",
                ライブラリの操作::名前を変える,
            )
        }
        ライブラリのダイアログ::削除の確認(_, 名前) => {
            確かめるダイアログ(
                format!(
                    "「{名前}」をライブラリから削除しますか。削除すると元に戻せない(動画は消えない)"
                ),
                "削除する",
                ライブラリの操作::削除する,
            )
        }
        ライブラリのダイアログ::保存できずに続ける確認(理由, _) => {
            確かめるダイアログ(
                format!(
                    "開いているスタックを保存できない({理由})。続けると、保存できていない変更が失われる"
                ),
                "変更を捨てて続ける",
                ライブラリの操作::変更を捨てて続ける,
            )
        }
        ライブラリのダイアログ::並びを捨てる確認(理由, _) => {
            super::discard_dialog::並びを捨てる確認のダイアログ(状態, *理由)
        }
    };
    モーダル("ライブラリのダイアログ", true, 中身)
        .閉じたら(ライブラリ(ライブラリの操作::ダイアログを閉じる))
        .into()
}

fn 名前のダイアログ(
    題: &str,
    入力: &入力中の名前,
    決定の名前: &str,
    決定: ライブラリの操作,
) -> Vec<ノード<応答>> {
    子![
        文字表示(題).装飾(styles::見出し),
        一行テキスト入力(入力.文字列(), |文字列| {
            ライブラリ(ライブラリの操作::名前の入力を書き換える(
                文字列,
            ))
        })
        .幅(画素(320.0)),
        決定とやめるの行(決定の名前, 決定),
    ]
}

fn 確かめるダイアログ(
    確かめる文: String,
    決定の名前: &str,
    決定: ライブラリの操作,
) -> Vec<ノード<応答>> {
    子![文字表示(確かめる文), 決定とやめるの行(決定の名前, 決定)]
}

fn 決定とやめるの行(
    決定の名前: &str, 決定: ライブラリの操作
) -> ノード<応答> {
    横並び(子![
        ボタン(決定の名前, ライブラリ(決定)).装飾(styles::強調ボタン),
        ボタン("やめる", ライブラリ(ライブラリの操作::ダイアログを閉じる)),
    ])
    .into()
}
