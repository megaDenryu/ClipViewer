//! ライブラリの一覧の1行。行の形(サムネイルの枠・名前と印・説明と操作のボタン・区切り線)は2つの作業場の画面が共有する `library_common::view` が組み、
//! ここはスタックの行の印(開いている・動画が見つからない)と操作のボタンを決める。読めないファイルはファイル名と理由を出す。

use clip_domain::スタックの識別子;
use sengen_egui::{ノード, ボタン, 子, 条件付き表示, 横並び};

use crate::command::{ライブラリの操作, 応答};
use crate::library_common::view::{行の印, 読めた行, 読めない行};
use crate::styles;
use crate::thumbnail_feed::サムネイルの見せ方;

/// 一覧の行とは、一覧の1行に出す値の組のことである。行を組む閉包へ所有させるため、画面の状態を借りない値で持つ。
pub(super) enum 一覧の行 {
    スタック {
        識別子: スタックの識別子,
        名前: String,
        説明: String,
        開いているか: bool,
        動画が見つからないか: bool,
        サムネイル: Option<サムネイルの見せ方>,
    },
    読めない {
        ファイル名: String, 理由: String
    },
}

fn ライブラリ(操作: ライブラリの操作) -> 応答 {
    応答::ライブラリ(操作)
}

impl 一覧の行 {
    /// 行を組む。ライブラリへ書けないとき(読み取り専用・置き場所が無い)は、開く以外のボタンを押せなくする。
    pub(super) fn 組む(&self, 書けるか: bool) -> ノード<応答> {
        match self {
            Self::スタック {
                識別子,
                名前,
                説明,
                開いているか,
                動画が見つからないか,
                サムネイル,
            } => 読めた行(
                サムネイル.as_ref(),
                名前.clone(),
                &[
                    行の印 {
                        文: "開いている",
                        出すか: *開いているか,
                        不備か: false,
                    },
                    行の印 {
                        文: "動画が見つからない",
                        出すか: *動画が見つからないか,
                        不備か: true,
                    },
                ],
                説明.clone(),
                操作のボタン(識別子, *動画が見つからないか, 書けるか),
            ),
            Self::読めない {
                ファイル名, 理由
            } => 読めない行(ファイル名, 理由),
        }
    }
}

fn 操作のボタン(
    識別子: &スタックの識別子,
    動画が見つからないか: bool,
    書けるか: bool,
) -> ノード<応答> {
    let 操作 = |操作を作る: fn(スタックの識別子) -> ライブラリの操作| {
        ライブラリ(操作を作る(識別子.clone()))
    };
    横並び(子![
        ボタン("開く", 操作(ライブラリの操作::開く)).装飾(styles::強調ボタン),
        ボタン(
            "名前を変える",
            操作(ライブラリの操作::名前を変えるダイアログを開く)
        )
        .有効(書けるか),
        ボタン("複製する", 操作(ライブラリの操作::複製する)).有効(書けるか),
        ボタン("削除する", 操作(ライブラリの操作::削除の確認を開く))
            .装飾(styles::危険ボタン)
            .有効(書けるか),
        条件付き表示(動画が見つからないか, || ボタン(
            "動画の場所を指定し直す",
            操作(ライブラリの操作::動画の場所を指定し直す)
        )
        .有効(書けるか)),
    ])
    .into()
}
