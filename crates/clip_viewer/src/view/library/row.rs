//! ライブラリの一覧の1行。左にサムネイルの枠、右に名前と印の行と説明と操作のボタンの行を並べ、下に区切り線を引く。
//! 読めないファイルはファイル名と理由を出す。

use clip_domain::スタックの識別子;
use sengen_egui::{
    ノード, ボタン, 区切り線, 子, 文字表示, 条件付き表示, 横並び, 縦積み
};

use super::thumbnail::サムネイルの枠;
use crate::command::{ライブラリの操作, 応答};
use crate::thumbnail_feed::サムネイルの見せ方;
use crate::view::styles;

/// 一覧の行とは、一覧の1行に出す値の組のことである。行を組む閉包へ所有させるため、画面の状態を借りない値で持つ。
pub(super) enum 一覧の行 {
    スタック {
        識別子: スタックの識別子,
        名前: String,
        説明: String,
        開いているか: bool,
        動画が見つからないか: bool,
        サムネイル: Option<サムネイルの見せ方>,
    },
    読めない {
        ファイル名: String, 理由: String
    },
}

fn ライブラリ(操作: ライブラリの操作) -> 応答 {
    応答::ライブラリ(操作)
}

impl 一覧の行 {
    /// 行を組む。ライブラリへ書けないとき(読み取り専用・置き場所が無い)は、開く以外のボタンを押せなくする。
    pub(super) fn 組む(&self, 書けるか: bool) -> ノード<応答> {
        match self {
            Self::スタック {
                識別子,
                名前,
                説明,
                開いているか,
                動画が見つからないか,
                サムネイル,
            } => 縦積み(子![
                横並び(子![
                    サムネイルの枠(サムネイル.as_ref()),
                    縦積み(子![
                        横並び(子![
                            文字表示(名前.clone()).装飾(styles::見出し),
                            条件付き表示(*開いているか, || 文字表示("開いている")
                                .装飾(styles::動画の名前)),
                            条件付き表示(*動画が見つからないか, || {
                                文字表示("動画が見つからない").装飾(styles::不備の文)
                            }),
                        ]),
                        横並び(子![
                            文字表示(説明.clone()).装飾(styles::補足),
                            操作のボタン(識別子, *動画が見つからないか, 書けるか),
                        ]),
                    ]),
                ]),
                区切り線(),
            ])
            .into(),
            Self::読めない {
                ファイル名, 理由
            } => 縦積み(子![
                文字表示(format!("読めない: {ファイル名}")).装飾(styles::不備の文),
                文字表示(理由.clone()).装飾(styles::補足),
                区切り線(),
            ])
            .into(),
        }
    }
}

fn 操作のボタン(
    識別子: &スタックの識別子,
    動画が見つからないか: bool,
    書けるか: bool,
) -> ノード<応答> {
    let 操作 = |操作を作る: fn(スタックの識別子) -> ライブラリの操作| {
        ライブラリ(操作を作る(識別子.clone()))
    };
    横並び(子![
        ボタン("開く", 操作(ライブラリの操作::開く)).装飾(styles::強調ボタン),
        ボタン(
            "名前を変える",
            操作(ライブラリの操作::名前を変えるダイアログを開く)
        )
        .有効(書けるか),
        ボタン("複製する", 操作(ライブラリの操作::複製する)).有効(書けるか),
        ボタン("削除する", 操作(ライブラリの操作::削除の確認を開く))
            .装飾(styles::危険ボタン)
            .有効(書けるか),
        条件付き表示(動画が見つからないか, || ボタン(
            "動画の場所を指定し直す",
            操作(ライブラリの操作::動画の場所を指定し直す)
        )
        .有効(書けるか)),
    ])
    .into()
}
