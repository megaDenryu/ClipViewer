//! 行の材料。見えている行を組む閉包が所有する材料と、そこから1行分の値(名前・説明・印・サムネイル)を作ること。
//! 行の文(説明・日時)は見えている行を組むときだけ作る。参照: _doc/設計/ライブラリ.md 判断8・判断10

use std::rc::Rc;

use clip_domain::スタックの識別子;
use clip_library::{
    ライブラリの一覧, 一覧の項目, 動画の有無, 読めたスタック
};
use sengen_egui::ノード;

use super::row::一覧の行;
use crate::command::応答;
use crate::library_common::view::{一覧の行の材料, 日時の表示};
use crate::state::library::見せる行;
use crate::state::アプリの状態;
use crate::thumbnail_feed::{サムネイルの見せ方, サムネイルの項目の表};
use crate::view::text;

/// 行の材料とは、見えている行を組む閉包が所有する、読んだ一覧と見せる行の順と、開いているスタックの識別子と書けるかと、
/// サムネイルの項目の表の組のことである。一覧と順と表は状態と共有し、行の文(説明・日時)は見えている行を組むときだけ作る。
pub(super) struct 行の材料 {
    一覧: Rc<ライブラリの一覧>,
    見せる行の順: Rc<Vec<見せる行>>,
    開いている: Option<スタックの識別子>,
    書けるか: bool,
    サムネイル: サムネイルの項目の表<スタックの識別子>,
}

impl 行の材料 {
    /// 状態と読んだ一覧から作る。一覧と順と表は状態と共有し、写さない。
    pub(super) fn 状態から作る(
        状態: &アプリの状態, 一覧: &Rc<ライブラリの一覧>
    ) -> Self {
        Self {
            一覧: Rc::clone(一覧),
            見せる行の順: 状態.ライブラリ.一覧.見せる行の順(),
            開いている: 状態.ライブラリ.開いている.識別子().cloned(),
            書けるか: 状態.ライブラリ.接続.書けるか(),
            サムネイル: 状態.ライブラリ.サムネイル.項目の表(),
        }
    }
}

impl 一覧の行の材料<応答> for 行の材料 {
    /// 見せる行の数。
    fn 行の数(&self) -> usize {
        self.見せる行の順.len()
    }

    /// 番号の行を組む。
    fn 行を組む(&self, 番号: usize) -> Option<ノード<応答>> {
        let 行 = match (*self.見せる行の順.get(番号)?, &self.一覧.項目) {
            (見せる行::読めた(位置), 項目) => match 項目.get(位置)? {
                一覧の項目::読めた(読めた) => スタックの行(
                    読めた,
                    self.開いている.as_ref() == Some(読めた.スタック.識別子()),
                    self.サムネイル
                        .get(読めた.スタック.識別子())
                        .map(|項目| 項目.見せ方()),
                ),
                一覧の項目::読めない(_) => return None,
            },
            (見せる行::読めない(位置), 項目) => match 項目.get(位置)? {
                一覧の項目::読めない(ファイル) => 一覧の行::読めない {
                    ファイル名: ファイル.ファイル名.文字列().to_string(),
                    理由: ファイル.理由.clone(),
                },
                一覧の項目::読めた(_) => return None,
            },
        };
        Some(行.組む(self.書けるか))
    }
}

fn スタックの行(
    読めた: &読めたスタック,
    開いているか: bool,
    サムネイル: Option<サムネイルの見せ方>,
) -> 一覧の行 {
    let スタック = &読めた.スタック;
    let 動画 = スタック.動画のパス().ファイル名().map_or_else(
        || "(動画のパスが空)".to_string(),
        |名前| 名前.文字列().to_string(),
    );
    let 説明 = format!(
        "{動画} ・ {}クリップ ・ 合計 {} ・ 更新 {}",
        スタック.並び().一覧().len(),
        text::時刻の表示(スタック.区間の長さの合計().秒数()),
        日時の表示(スタック.更新した日時()),
    );
    一覧の行::スタック {
        識別子: スタック.識別子().clone(),
        名前: スタック.名前().文字列().to_string(),
        説明,
        開いているか,
        動画が見つからないか: 読めた.動画 == 動画の有無::見つからない,
        サムネイル,
    }
}
