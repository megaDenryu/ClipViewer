//! 一覧の行の左に出すサムネイルの枠。見せられるサムネイルは縦横比を保って枠へ収め、読んでいる・撮る順番を待っている・撮っている・
//! 撮らない・撮れないは空の枠に短い文で示す(撮れない理由は長くなるため、枠に乗せたときの説明に出す)。
//! 途中の行は、入力が無くても描き直しを予約する(見えている行のサムネイルを出すまで、仕事を進めて結果を受け取るため)。
//! 参照: _doc/設計/ライブラリ.md 判断10

use std::time::Duration;

use clip_domain::画素の寸法;
use sengen_egui::{
    ノード, 付け足せる, 大きさを決めた領域, 子, 描き直しを予約する, 文字表示, 画像, 画素,
    縦横の論理画素, 縦積み,
};

use crate::command::応答;
use crate::thumbnail_feed::{サムネイルの見せ方, 途中の段階};
use crate::view::aspect_fit::{丸める前の論理画素の寸法, 描く縦横比};
use crate::view::styles;

/// サムネイルの枠の大きさ。16:9 の顔がちょうど収まり、行の高さに入る大きさにする。
const サムネイルの枠の大きさ: 縦横の論理画素 =
    縦横の論理画素::生成する(画素(96.0), 画素(54.0));

/// 見えている行のサムネイルがまだ出せない間に描き直す間隔(約60回/秒)。
const 途中の描き直しの間隔: Duration = Duration::from_millis(16);

pub(super) fn サムネイルの枠(
    見せ方: Option<&サムネイルの見せ方>
) -> ノード<応答> {
    let 中身: ノード<応答> = match 見せ方 {
        Some(サムネイルの見せ方::見せられる(テクスチャ)) => {
            画像(テクスチャ.参照を複製する())
                .表示寸法(収める寸法(
                    テクスチャ.寸法().幅(),
                    テクスチャ.寸法().高さ(),
                ))
                .into()
        }
        Some(サムネイルの見せ方::途中(段階)) => 途中の文(*段階),
        None => 途中の文(途中の段階::読んでいる),
        Some(サムネイルの見せ方::撮らない(理由)) => 短い文(&理由.to_string()),
        Some(サムネイルの見せ方::出せない(理由)) => 文字表示("撮れない")
            .装飾(styles::不備の文)
            .説明(理由.to_string()),
    };
    大きさを決めた領域(サムネイルの枠の大きさ, 子![中身])
        .中央寄せ()
        .装飾(styles::出力の地)
        .into()
}

/// 途中の段階の短い文と、描き直しの予約。
fn 途中の文(段階: 途中の段階) -> ノード<応答> {
    let 文面 = match 段階 {
        途中の段階::読んでいる => "読んでいる",
        途中の段階::撮る順番を待っている => "撮る順番を待っている",
        途中の段階::撮っている => "撮っている",
    };
    縦積み(子![短い文(文面), 描き直しを予約する(途中の描き直しの間隔)]).into()
}

fn 短い文(文面: &str) -> ノード<応答> {
    文字表示(文面.to_string()).装飾(styles::補足).into()
}

/// テクスチャの画素の寸法から、縦横比を保って枠に収まる表示寸法を求める。
fn 収める寸法(幅: u32, 高さ: u32) -> 縦横の論理画素 {
    let 比 = 画素の寸法::作成する(f64::from(幅), f64::from(高さ))
        .ok()
        .and_then(|寸法| 寸法.縦横比());
    丸める前の論理画素の寸法::論理画素の組から作る(サムネイルの枠の大きさ)
        .縦横比を保って収める(描く縦横比::求める(比))
        .切り捨てて論理画素の組にする()
}
