//! 未登録の並びを捨てて続けるかを確かめるダイアログ。ライブラリに保存するか、捨てて続けるか、やめるかを選ぶ。参照: _doc/設計/画面.md 判断14

use sengen_egui::{ノード, ボタン, 子, 文字表示, 横並び};

use crate::command::{ライブラリの操作, 応答};
use crate::state::library::並びを捨てる理由;
use crate::state::アプリの状態;
use crate::styles;

fn ライブラリ(操作: ライブラリの操作) -> 応答 {
    応答::ライブラリ(操作)
}

/// ダイアログの中身。保存は、ライブラリへ書けて動画を開いているときだけ押せる(登録の条件と同じ)。
pub(super) fn 並びを捨てる確認のダイアログ(
    状態: &アプリの状態,
    理由: 並びを捨てる理由,
) -> Vec<ノード<応答>> {
    let 登録できるか = 状態.ライブラリ.接続.書けるか() && 状態.動画.is_some();
    let (文, 捨てるボタンの名前) = match 理由 {
        並びを捨てる理由::登録していない変更がある => (
            "ライブラリに保存していない変更がある。続けると失われる",
            "変更を捨てて続ける",
        ),
        並びを捨てる理由::読み込んだ並びを名前の違う動画で捨てる => (
            "読み込んだ並びは、名前の違う動画を開くと捨てて、最初のクリップだけの並びで始める。続けると今の並びは失われる",
            "並びを捨てて続ける",
        ),
    };
    子![
        文字表示(文),
        横並び(子![
            ボタン(
                "ライブラリに保存する",
                ライブラリ(ライブラリの操作::登録してから続ける)
            )
            .装飾(styles::強調ボタン)
            .有効(登録できるか),
            ボタン(
                捨てるボタンの名前,
                ライブラリ(ライブラリの操作::変更を捨てて続ける)
            )
            .装飾(styles::危険ボタン),
            ボタン("やめる", ライブラリ(ライブラリの操作::ダイアログを閉じる)),
        ]),
    ]
}
