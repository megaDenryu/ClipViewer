//! ヘッダーに出す、今のスタックのライブラリへの登録の様子。未登録なら「ライブラリに保存」のボタンを出す。

use sengen_egui::{ノード, ボタン, 子, 文字表示, 横並び};

use crate::command::{ライブラリの操作, 応答};
use crate::library_common::view::保存の段階の文字;
use crate::state::アプリの状態;
use crate::styles;

pub(crate) fn ヘッダーのライブラリの様子(
    状態: &アプリの状態
) -> ノード<応答> {
    if let Some(文) = super::一覧の文言.書けないことの文(状態.ライブラリ.接続.使える様子())
    {
        return 文字表示(文).装飾(styles::不備の文).into();
    }
    match 状態.開いている登録済みのスタックと保存の段階() {
        None => 横並び(子![
            文字表示("ライブラリ: 未登録").装飾(styles::補足),
            ボタン(
                "ライブラリに保存",
                応答::ライブラリ(ライブラリの操作::登録のダイアログを開く)
            )
            .有効(状態.動画.is_some() && !状態.並び.一覧().is_empty()),
        ])
        .into(),
        Some((登録済み, 段階)) => 横並び(子![
            文字表示(format!("ライブラリ: {}", 登録済み.名前())).装飾(styles::動画の名前),
            保存の段階の文字(段階),
        ])
        .into(),
    }
}
