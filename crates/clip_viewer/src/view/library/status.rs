//! ヘッダーに出す、今のスタックのライブラリへの登録の様子。未登録なら「ライブラリに保存」のボタンを出す。

use sengen_egui::{ノード, ボタン, 子, 文字表示, 横並び};

use crate::command::{ライブラリの操作, 応答};
use crate::state::library::{ライブラリの使える様子, 保存の段階};
use crate::state::アプリの状態;
use crate::view::styles;

pub(crate) fn ヘッダーのライブラリの様子(
    状態: &アプリの状態
) -> ノード<応答> {
    match 状態.ライブラリ.接続.使える様子() {
        ライブラリの使える様子::書ける(_) => {}
        ライブラリの使える様子::読むだけ(..) => {
            return 文字表示(
                "ライブラリ: 読み取り専用(別の ClipViewer が開いている等。一覧の画面に理由を出す)",
            )
            .装飾(styles::不備の文)
            .into();
        }
        ライブラリの使える様子::置き場所が無い => {
            return 文字表示("ライブラリ: 使えない(置き場所が無い)")
                .装飾(styles::不備の文)
                .into();
        }
    }
    match 状態.開いている登録済みのスタックと保存の段階() {
        None => 横並び(子![
            文字表示("ライブラリ: 未登録").装飾(styles::補足),
            ボタン(
                "ライブラリに保存",
                応答::ライブラリ(ライブラリの操作::登録のダイアログを開く)
            )
            .有効(状態.動画.is_some() && !状態.並び.一覧().is_empty()),
        ])
        .into(),
        Some((登録済み, 段階)) => 横並び(子![
            文字表示(format!("ライブラリ: {}", 登録済み.名前())).装飾(styles::動画の名前),
            保存の段階の文字(段階),
        ])
        .into(),
    }
}

/// 開いている登録済みのスタックの保存の段階の文字。
fn 保存の段階の文字(段階: 保存の段階<'_>) -> ノード<応答> {
    let (段階, 装飾) = match 段階 {
        保存の段階::保存済み => ("保存済み".to_string(), styles::補足),
        保存の段階::変更を保存待ち => ("変更を保存待ち".to_string(), styles::補足),
        保存の段階::保存中 => ("保存中".to_string(), styles::補足),
        保存の段階::保存に失敗(理由) => {
            (format!("保存に失敗: {理由}"), styles::不備の文)
        }
    };
    文字表示(段階).装飾(装飾).into()
}
