//! ライブラリの一覧の行の並び。状態が一覧か見せ方が変わったときだけ作る見せる行の順に従い、仮想縦スクロールで見えている行だけ組む。
//! 行を組む閉包は画面の状態を借りられないため、一覧と順を `Rc` で状態と共有して閉包へ所有させる(毎フレーム写さないため)。
//! 組んだ行の範囲は仮想縦スクロールが応答として発し、応答の適用が状態へ置いて、次のフレームで見えている行のサムネイルを先に撮らせる。

use std::rc::Rc;

use clip_library::ライブラリの一覧;
use sengen_egui::{
    ノード, 仮想縦スクロール, 使える大きさから組む, 大きさを決めた領域, 子, 無し, 画素,
    縦横の論理画素,
};

use super::row_source::行の材料;
use crate::command::{ライブラリの操作, 応答};
use crate::state::library::見えている行の範囲;
use crate::state::アプリの状態;

/// 1行の高さ(論理画素)。左のサムネイルの枠と、区切り線が収まる高さにする。
const 行の高さ: f32 = 70.0;

pub(super) fn 一覧の行の並び(
    状態: &アプリの状態,
    一覧: &Rc<ライブラリの一覧>,
) -> ノード<応答> {
    let 材料 = Rc::new(行の材料::状態から作る(状態, 一覧));
    使える大きさから組む(move |大きさ| {
        let 材料 = Rc::clone(&材料);
        let 寸法 = 縦横の論理画素::生成する(大きさ.横, 画素(行の高さ));
        仮想縦スクロール(
            "ライブラリの一覧",
            画素(行の高さ),
            材料.行の数(),
            move |番号| {
                材料
                    .行を組む(番号)
                    .map_or_else(無し, |一行| 大きさを決めた領域(寸法, 子![一行]).into())
            },
        )
        .見えている行を発する(見えている行を知らせる)
        .into()
    })
    .into()
}

fn 見えている行を知らせる(範囲: sengen_egui::見えている行の範囲) -> 応答 {
    応答::ライブラリ(
        ライブラリの操作::一覧の見えている行を知らせる(
            見えている行の範囲::両端の行番号から作る(範囲.最初(), 範囲.最後()),
        ),
    )
}
