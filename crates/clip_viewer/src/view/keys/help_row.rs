//! キーの一覧のダイアログの格子。見出しの行と、操作1つにつき1行の、働き・今のキー・効く構え・「変更」・「既定に戻す」の5列を並べる。
//! キーを待っている操作の行は、今のキーの代わりに待っていることを出し、「変更」の代わりに「やめる」を出す。参照: _doc/設計/画面.md 判断18

use sengen_egui::{ノード, ボタン, 文字表示, 格子};

use super::table;
use crate::command::{キーの設定の操作, 応答};
use crate::state::アプリの状態;
use crate::view::styles;
use crate::viewer_settings::{キーで行う操作, 操作のキー};

/// 格子の列の数。
const 列の数: usize = 5;

/// 見出しの行と、操作1つにつき1行の格子。
pub(super) fn 割り当ての格子(状態: &アプリの状態) -> ノード<応答> {
    let 見出し = ["働き", "今のキー", "効く構え", "", ""]
        .into_iter()
        .map(|名前| 文字表示(名前).装飾(styles::補足).into());
    let 待っている操作 = 状態.キーの一覧.待っている操作();
    let 行 = 状態
        .キーの割り当て
        .並び()
        .flat_map(|(操作, キー)| 操作の行(操作, キー, 待っている操作 == Some(操作)));
    格子("キーの一覧の格子", 列の数, 見出し.chain(行).collect())
        .縞模様()
        .into()
}

/// 1つの操作の行の5つの升目。
fn 操作の行(
    操作: キーで行う操作,
    キー: 操作のキー,
    待っているか: bool,
) -> [ノード<応答>; 列の数] {
    let 設定 = 応答::キーの設定;
    let (今のキー, 変更) = if 待っているか {
        (
            文字表示("キーを押してください").装飾(styles::見出し).into(),
            ボタン("やめる", 設定(キーの設定の操作::変更の待ちをやめる)).into(),
        )
    } else {
        (
            文字表示(キー.表記()).into(),
            ボタン("変更", 設定(キーの設定の操作::変更を待ち始める(操作))).into(),
        )
    };
    [
        文字表示(操作.働き()).into(),
        今のキー,
        文字表示(table::キー操作の決まり(操作).効く範囲.説明()).into(),
        変更,
        ボタン("既定に戻す", 設定(キーの設定の操作::既定に戻す(操作)))
            .有効(キー != 操作.既定のキー())
            .into(),
    ]
}
