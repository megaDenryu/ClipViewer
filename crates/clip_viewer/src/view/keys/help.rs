//! キーの一覧のダイアログ。F1 かヘッダーの「キー設定」で開き、今の割り当ての全操作を、働き・今のキー・効く構えと、「変更」「既定に戻す」のボタンの行で並べる。
//! 「変更」を押すと、その操作の新しいキーを待ち、ダイアログの先頭に置いた受け取りが次に押されたキーの組を受け取る。
//! もう一度 F1 を押すか、Escape(待っていないとき)・ダイアログの外を押す・閉じるボタンで閉じる。ダイアログはウインドウに収め、
//! 収まらない行は縦にスクロールさせる(格子の働きの文は列の最大幅で折り返す。help_row.rs)。参照: _doc/設計/画面.md 判断14・判断18

use sengen_egui::{
    ノード, ボタン, モーダル, 子, 文字表示, 条件付き表示, 横並び, 次に押されたキーの組を受け取る,
    無し, 画素, 論理画素,
};

use super::help_row;
use crate::command::{キーの設定の操作, 出力の操作, 応答};
use crate::state::アプリの状態;
use crate::styles;
use crate::viewer_settings::キーの割り当て;

/// キーの変え方を知らせる文。
const 変え方の案内: &str = "「変更」を押してから、割り当てるキーを押す(Ctrl・Alt・Shift と一緒に押してもよい)。Escape を押すと変更をやめる";

/// ダイアログの枠とウインドウの4辺との間。ダイアログはこの間を空けてウインドウに収め、収まらない行は縦にスクロールさせる。
const 画面の端との間: 論理画素 = 画素(16.0);

/// 入力欄との関係の規則を、表の下に1行で知らせる文。
const 入力欄の注意: &str = "入力欄に文字を打っている間は、Ctrl か Alt を含むキーだけが効く(取り消し・やり直し・選択中のクリップの開始と終了を今の位置にするキーは入力欄に任せる)";

pub(crate) fn キーの一覧を出すダイアログ(
    状態: &アプリの状態
) -> ノード<応答> {
    if !状態.キーの一覧.開いているか() {
        return 無し();
    }
    let 待っているか = 状態.キーの一覧.待っている操作().is_some();
    let 閉じる = 応答::出力(出力の操作::キーの一覧を閉じる);
    let 設定 = 応答::キーの設定;
    モーダル(
        "キーの一覧",
        true,
        子![
            条件付き表示(待っているか, || {
                次に押されたキーの組を受け取る(|組| {
                    応答::キーの設定(キーの設定の操作::押されたキーを受け取る(
                        組,
                    ))
                })
            }),
            文字表示("キーの一覧").装飾(styles::見出し),
            文字表示(変え方の案内).装飾(styles::補足),
            help_row::割り当ての格子(状態),
            文字表示(入力欄の注意).装飾(styles::補足),
            横並び(子![
                ボタン("すべて既定に戻す", 設定(キーの設定の操作::すべて既定に戻す))
                    .有効(状態.キーの割り当て != キーの割り当て::既定()),
                ボタン("閉じる", 閉じる.clone()),
            ]),
        ],
    )
    .閉じたら(閉じる)
    .画面に収める(画面の端との間)
    .into()
}
