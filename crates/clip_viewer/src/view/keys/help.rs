//! キーの一覧の窓。F1 で開き、割り当ての表(table.rs)の全行を、キー・働き・効く構えの3列で並べる。
//! もう一度 F1 を押すか、Escape・窓の外を押す・閉じるボタンで閉じる。参照: _doc/設計/画面.md 判断14「キーの割り当て」

use sengen_egui::{ノード, ボタン, モーダル, 子, 文字表示, 格子, 無し};

use super::table;
use crate::command::{出力の操作, 応答};
use crate::state::{アプリの状態, キーの一覧の窓};
use crate::view::styles;

/// 入力欄との関係の規則を、表の下に1行で知らせる文。
const 入力欄の注意: &str = "入力欄に文字を打っている間は、Ctrl+S 以外のキーは入力欄に任せる";

pub(crate) fn キーの一覧を出す窓(状態: &アプリの状態) -> ノード<応答> {
    if 状態.キーの一覧 == キーの一覧の窓::閉じている {
        return 無し();
    }
    let 閉じる = 応答::出力(出力の操作::キーの一覧を閉じる);
    モーダル(
        "キーの一覧",
        true,
        子![
            文字表示("キーの一覧").装飾(styles::見出し),
            割り当ての格子(),
            文字表示(入力欄の注意).装飾(styles::補足),
            ボタン("閉じる", 閉じる.clone()),
        ],
    )
    .閉じたら(閉じる)
    .into()
}

/// 見出しの行と、割り当て1つにつき1行の、キー・働き・効く構えの3列の格子。
fn 割り当ての格子() -> ノード<応答> {
    let 見出し = ["キー", "働き", "効く構え"]
        .into_iter()
        .map(|名前| 文字表示(名前).装飾(styles::補足).into());
    let 行 = table::キーの割り当ての一覧()
        .into_iter()
        .flat_map(|割り当て| {
            [
                文字表示(割り当て.表記).into(),
                文字表示(割り当て.働き).into(),
                文字表示(割り当て.効く範囲.説明()).into(),
            ]
        });
    格子("キーの一覧の格子", 3, 見出し.chain(行).collect())
        .縞模様()
        .into()
}
