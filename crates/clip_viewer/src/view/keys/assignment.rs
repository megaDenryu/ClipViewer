//! キーの割り当ての型。1つのキーの組の表記・働き・効く範囲・発する応答と、効く範囲の判定を持つ。
//! 割り当ての表そのものは table.rs に置く。参照: _doc/設計/画面.md 判断14「キーの割り当て」

use sengen_egui::キーの組;

use crate::command::{クリップの操作, 応答};
use crate::state::library::ライブラリの窓;
use crate::state::{アプリの状態, キーの一覧の窓, 画面の構え};

/// キーの効く範囲とは、そのキーを見張る構えと窓の様子の区別のことである。
/// 窓とは、画面を覆うライブラリの窓とキーの一覧の窓のことであり、開いている間は窓がキーを扱う(Escape で閉じる等)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum キーの効く範囲 {
    いつでも,
    ライブラリの窓が無い間,
    窓が無い間,
    再生の構えで窓が無い間,
    編集の構えで窓が無い間,
}

impl キーの効く範囲 {
    pub(super) fn 今効くか(self, 状態: &アプリの状態) -> bool {
        let ライブラリの窓が無い = 状態.ライブラリ.窓 == ライブラリの窓::無し;
        let 窓が無い =
            ライブラリの窓が無い && 状態.キーの一覧 == キーの一覧の窓::閉じている;
        match self {
            Self::いつでも => true,
            Self::ライブラリの窓が無い間 => ライブラリの窓が無い,
            Self::窓が無い間 => 窓が無い,
            Self::再生の構えで窓が無い間 => {
                窓が無い && 状態.出力.構え != 画面の構え::ライブラリ
            }
            Self::編集の構えで窓が無い間 => {
                窓が無い && 状態.出力.構え == 画面の構え::編集
            }
        }
    }

    /// キーの一覧の窓に出す、効く範囲の説明。
    pub(super) fn 説明(self) -> &'static str {
        match self {
            Self::いつでも => "いつでも(窓を開いている間も)",
            Self::ライブラリの窓が無い間 => "どの構えでも",
            Self::窓が無い間 => "どの構えでも(窓を開いている間は窓を閉じる)",
            Self::再生の構えで窓が無い間 => "編集・シアター",
            Self::編集の構えで窓が無い間 => "編集",
        }
    }
}

/// 入力欄との関係とは、入力欄にフォーカスがある間に、修飾キーを含む組を入力欄から奪うか、入力欄に任せるかの区別のことである。
/// 修飾キーを含まない組は、どちらでも入力欄に任せる(SengenEgui のキー操作の規則)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 入力欄との関係 {
    修飾キーの組なら奪う,
    入力欄に任せる,
}

/// キーの割り当てとは、1つのキーの組と、その表記・働き・効く範囲・発する応答・入力欄との関係の組のことである。
pub(super) struct キーの割り当て {
    pub(super) 組: キーの組,
    pub(super) 表記: &'static str,
    pub(super) 働き: &'static str,
    pub(super) 効く範囲: キーの効く範囲,
    pub(super) 応答: 応答,
    pub(super) 入力欄: 入力欄との関係,
}

/// 修飾キーを含む組を入力欄から奪う割り当てを作る。
pub(super) fn 割り当て(
    組: キーの組,
    表記: &'static str,
    働き: &'static str,
    効く範囲: キーの効く範囲,
    応答: 応答,
) -> キーの割り当て {
    キーの割り当て {
        組,
        表記,
        働き,
        効く範囲,
        応答,
        入力欄: 入力欄との関係::修飾キーの組なら奪う,
    }
}

/// 編集の構えだけで効き、入力欄にフォーカスがある間は入力欄に任せる割り当てを作る。Ctrl+Z は入力欄の文字の取り消しに使うためである。
pub(super) fn 編集の割り当て(
    組: キーの組,
    表記: &'static str,
    働き: &'static str,
    操作: クリップの操作,
) -> キーの割り当て {
    キーの割り当て {
        入力欄: 入力欄との関係::入力欄に任せる,
        ..割り当て(
            組,
            表記,
            働き,
            キーの効く範囲::編集の構えで窓が無い間,
            応答::クリップ(操作),
        )
    }
}
