//! キーの割り当て。割り当ての表(table.rs)のうち、今の構えとウインドウの様子で効く行を、見えないキー操作の部品にする。
//! 入力欄に文字を打っている間は、修飾キーの無いキーは発しない(SengenEgui のキー操作の規則)。Ctrl+Z 等の編集のキーも入力欄に任せる
//! (入力欄が自分の取り消しに使うため)。F1 で開くキーの一覧のダイアログ(help.rs)も同じ表から作る。参照: _doc/設計/画面.md 判断14

mod assignment;
mod help;
mod table;

#[cfg(test)]
mod table_tests;

pub(crate) use help::キーの一覧を出すダイアログ;

use sengen_egui::{キー操作, ノード, 縦積み};

use crate::command::応答;
use crate::state::アプリの状態;
use assignment::{キーの割り当て, 入力欄との関係};

pub(crate) fn キー操作の一覧(状態: &アプリの状態) -> ノード<応答> {
    縦積み(
        table::キーの割り当ての一覧()
            .into_iter()
            .filter(|割り当て| 割り当て.効く範囲.今効くか(状態))
            .map(キー操作の部品にする)
            .collect(),
    )
    .into()
}

/// 割り当てを、見えないキー操作の部品にする。
fn キー操作の部品にする(割り当て: キーの割り当て) -> ノード<応答> {
    let 部品 = キー操作(割り当て.組, 割り当て.応答);
    match 割り当て.入力欄 {
        入力欄との関係::修飾キーの組なら奪う => 部品.into(),
        入力欄との関係::入力欄に任せる => {
            部品.入力欄にフォーカスがある間は発しない().into()
        }
    }
}
