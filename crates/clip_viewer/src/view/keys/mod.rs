//! キーの割り当て。今の割り当て(状態の `キーの割り当て`)の各操作のうち、今の構えとウインドウの様子で効く操作のキーを、見えないキー操作の部品にする。
//! 入力欄に文字を打っている間は、修飾キーの無いキーは発しない(SengenEgui のキー操作の規則)。Ctrl+Z 等の編集のキーも入力欄に任せる
//! (入力欄が自分の取り消しに使うため)。キーの一覧のダイアログでキーの変更を待っている間は、どのキー操作も置かない(押したキーを新しいキーとして受け取るため)。
//! F1 で開くキーの一覧のダイアログ(help.rs)も同じ割り当てと表(table.rs)から作る。参照: _doc/設計/画面.md 判断14・判断18

mod help;
mod help_row;
mod rule;
mod table;

pub(crate) use help::キーの一覧を出すダイアログ;

use sengen_egui::{キーの組, キー操作, ノード, 無し, 縦積み};

use crate::command::応答;
use crate::state::アプリの状態;
use crate::viewer_settings::キーで行う操作;
use rule::入力欄との関係;

pub(crate) fn キー操作の一覧(状態: &アプリの状態) -> ノード<応答> {
    if 状態.キーの一覧.待っている操作().is_some() {
        return 無し();
    }
    縦積み(
        状態
            .キーの割り当て
            .並び()
            .flat_map(|(操作, キー)| キー.組の並び().into_iter().map(move |組| (操作, 組)))
            .filter(|(操作, _)| table::キー操作の決まり(*操作).効く範囲.今効くか(状態))
            .map(|(操作, 組)| キー操作の部品にする(操作, 組))
            .collect(),
    )
    .into()
}

/// 今の割り当てで、その操作に割り当てたキーの表記(「Space・K」の形)。ボタンの説明と案内の文に出す。
pub(crate) fn 操作のキーの表記(
    状態: &アプリの状態, 操作: キーで行う操作
) -> String {
    状態.キーの割り当て.操作のキー(操作).表記()
}

/// 操作の1つのキーの組を、見えないキー操作の部品にする。
fn キー操作の部品にする(
    操作: キーで行う操作, 組: キーの組
) -> ノード<応答> {
    let 決まり = table::キー操作の決まり(操作);
    let 部品 = キー操作(組, 決まり.応答);
    match 決まり.入力欄 {
        入力欄との関係::修飾キーの組なら奪う => 部品.into(),
        入力欄との関係::入力欄に任せる => {
            部品.入力欄にフォーカスがある間は発しない().into()
        }
    }
}
