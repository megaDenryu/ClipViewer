//! キーの一覧のダイアログの大きさの試験。日本語フォントとテーマを当てた egui に、最小のウインドウ(800×500)と最初のウインドウ(1200×620)の
//! 大きさでダイアログを描かせ、ダイアログの枠がウインドウの中に収まることを確かめる(行が多いため縦にスクロールし、働きの文は列の最大幅で折り返す)。
//! キーを待っている行(今のキーの升目に見出しの装飾の文を出す)を含めて確かめる。

use eframe::egui;
use sengen_egui::日本語フォントの候補;

use super::help::キーの一覧を出すダイアログ;
use crate::command::{キーの設定の操作, 出力の操作};
use crate::state::{アプリの状態, 画面の構え};
use crate::view::styles;
use crate::view::test_support::{動画の無い状態, 大きさを決めて描く};
use crate::viewer_settings::キーで行う操作;

/// 日本語フォントとテーマを当てた egui の本体。フォントは次の回から効くため、何も描かない回を1回進めておく。
fn 本体を作る() -> egui::Context {
    let eguiの本体 = egui::Context::default();
    日本語フォントの候補::標準で入っている候補()
        .最初に読めたものを設定する(&eguiの本体)
        .unwrap_or_else(|失敗| panic!("日本語フォントを読めないため、大きさを測れない: {失敗}"));
    styles::画面のテーマ.適用する(&eguiの本体);
    let _ = eguiの本体.run(egui::RawInput::default(), |_| {});
    eguiの本体
}

/// その大きさのウインドウにダイアログを数回描き(最初の回は egui が大きさだけを測る)、ダイアログの枠の範囲と最後の回の出力を返す。
fn 描いた枠(
    状態: &アプリの状態, 画面の大きさ: egui::Vec2
) -> (egui::Rect, egui::FullOutput) {
    let eguiの本体 = 本体を作る();
    let 木 = || キーの一覧を出すダイアログ(状態);
    let mut 出力 = 大きさを決めて描く(&eguiの本体, 画面の大きさ, Vec::new(), &木).1;
    for _ in 0..3 {
        出力 = 大きさを決めて描く(&eguiの本体, 画面の大きさ, Vec::new(), &木).1;
    }
    let 枠 = eguiの本体
        .memory(|記憶| 記憶.area_rect(egui::Id::new("キーの一覧")))
        .unwrap_or_else(|| panic!("ダイアログの枠の範囲を記憶していない"));
    (枠, 出力)
}

/// 描いた文字のうち、その文字をそのまま描いたものの行の数の並び。
fn 描いた文字の行の数(出力: &egui::FullOutput, 文字: &str) -> Vec<usize> {
    出力
        .shapes
        .iter()
        .filter_map(|切り抜いた形| match &切り抜いた形.shape {
            egui::Shape::Text(文字の形) if 文字の形.galley.text() == 文字 => {
                Some(文字の形.galley.rows.len())
            }
            _ => None,
        })
        .collect()
}

/// キーの一覧のダイアログを開いた状態。待つ操作を渡せば、その操作の新しいキーを待っている状態にする。
fn ダイアログを開いた状態(
    待つ操作: Option<キーで行う操作>
) -> アプリの状態 {
    let mut 状態 = 動画の無い状態(画面の構え::編集);
    状態.出力の操作を適用する(出力の操作::キーの一覧を開く);
    if let Some(操作) = 待つ操作 {
        状態.キーの設定の操作を適用する(キーの設定の操作::変更を待ち始める(操作));
    }
    状態
}

/// 枠がウインドウに収まり、最後の列のボタン(「既定に戻す」)が狭い列へ押し込まれて折り返していないことと、
/// 最も長い働きの文が列の最大幅で折り返していること(行が2つ以上)を確かめる。
#[test]
fn 最小と最初のウインドウの大きさでダイアログはウインドウに収まり_働きの文は折り返す() {
    let 状態の並び = [
        ダイアログを開いた状態(None),
        ダイアログを開いた状態(Some(キーで行う操作::編集をやり直す)),
    ];
    let 最も長い働き = キーで行う操作::次のクリップへ進めるか知らせる.働き();
    for 画面の大きさ in [egui::vec2(800.0, 500.0), egui::vec2(1200.0, 620.0)] {
        let 画面 = egui::Rect::from_min_size(egui::Pos2::ZERO, 画面の大きさ);
        for 状態 in &状態の並び {
            let (枠, 出力) = 描いた枠(状態, 画面の大きさ);
            assert!(
                画面.contains_rect(枠),
                "枠 {枠:?} がウインドウ {画面:?} からはみ出す"
            );
            let ボタンの行 = 描いた文字の行の数(&出力, "既定に戻す");
            assert!(
                !ボタンの行.is_empty() && ボタンの行.iter().all(|数| *数 == 1),
                "{ボタンの行:?}"
            );
            let 働きの行 = 描いた文字の行の数(&出力, 最も長い働き);
            assert!(
                !働きの行.is_empty() && 働きの行.iter().all(|数| *数 >= 2),
                "{働きの行:?}"
            );
        }
    }
}
