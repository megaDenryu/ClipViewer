//! キー操作の決まりの型。キーで行う操作ごとの、効く範囲・発する応答・入力欄との関係と、効く範囲の判定を持つ。
//! 操作ごとの決まりの表は table.rs、操作に割り当てたキーは状態の `キーの割り当て` が持つ。参照: _doc/設計/画面.md 判断14「キーの割り当て」・判断18

use crate::command::応答;
use crate::state::library::ライブラリのダイアログ;
use crate::state::{アプリの状態, 画面の構え};

/// キーの効く範囲とは、そのキーを見張る構えとウインドウの様子の区別のことである。
/// ダイアログとは、画面を覆うライブラリのダイアログとキーの一覧のダイアログのことであり、開いている間はダイアログがキーを扱う(Escape で閉じる等)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum キーの効く範囲 {
    いつでも,
    ライブラリのダイアログが無い間,
    ダイアログが無い間,
    再生の構えでダイアログが無い間,
    編集の構えでダイアログが無い間,
}

impl キーの効く範囲 {
    pub(super) fn 今効くか(self, 状態: &アプリの状態) -> bool {
        let ライブラリのダイアログが無い =
            状態.ライブラリ.ダイアログ == ライブラリのダイアログ::無し;
        let ダイアログが無い = ライブラリのダイアログが無い && !状態.キーの一覧.開いているか();
        match self {
            Self::いつでも => true,
            Self::ライブラリのダイアログが無い間 => {
                ライブラリのダイアログが無い
            }
            Self::ダイアログが無い間 => ダイアログが無い,
            Self::再生の構えでダイアログが無い間 => {
                ダイアログが無い && 状態.出力.構え != 画面の構え::ライブラリ
            }
            Self::編集の構えでダイアログが無い間 => {
                ダイアログが無い && 状態.出力.構え == 画面の構え::編集
            }
        }
    }

    /// キーの一覧のダイアログに出す、効く範囲の説明。範囲だけを述べ、割り当てたキーで決まること(Escape でダイアログが閉じる等)を書かない。
    /// 利用者がキーを変えても説明が嘘にならないためである。
    pub(super) fn 説明(self) -> &'static str {
        match self {
            Self::いつでも => "いつでも(ダイアログを開いている間も)",
            Self::ライブラリのダイアログが無い間 => {
                "どの構えでも(キーの一覧のダイアログを開いている間も効く)"
            }
            Self::ダイアログが無い間 => "どの構えでも(ダイアログを開いている間は効かない)",
            Self::再生の構えでダイアログが無い間 => "編集・シアター",
            Self::編集の構えでダイアログが無い間 => "編集",
        }
    }
}

/// 入力欄との関係とは、入力欄にフォーカスがある間に、修飾キーを含む組を入力欄から奪うか、入力欄に任せるかの区別のことである。
/// 修飾キーを含まない組は、どちらでも入力欄に任せる(SengenEgui のキー操作の規則)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum 入力欄との関係 {
    修飾キーの組なら奪う,
    入力欄に任せる,
}

/// キー操作の決まりとは、キーで行う操作の、効く範囲と発する応答と入力欄との関係の組のことである。
pub(super) struct キー操作の決まり {
    pub(super) 効く範囲: キーの効く範囲,
    pub(super) 応答: 応答,
    pub(super) 入力欄: 入力欄との関係,
}
