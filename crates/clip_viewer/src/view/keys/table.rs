//! キー操作の決まりの表。キーで行う操作ごとに、効く範囲・発する応答・入力欄との関係を決める。操作を網羅する match で書くため、
//! 操作を足すと表の書き忘れがコンパイルエラーになる。キーの組は表に書かず、状態の `キーの割り当て`(既定は viewer_settings/keys/default_keys.rs)から取る。
//! キー操作の部品(mod.rs)と F1 のキーの一覧のダイアログ(help.rs)の両方が、この表と今の割り当てから作る。参照: _doc/設計/画面.md 判断14「キーの割り当て」・判断18

use clip_domain::進める操作;

use super::rule::{キーの効く範囲, キー操作の決まり, 入力欄との関係};
use crate::command::{
    クリップの操作, ライブラリの操作, 再生の操作, 出力の操作, 区間の端, 応答, 送る向き,
};
use crate::state::速度を変える向き;
use crate::viewer_settings::キーで行う操作;

/// 操作の決まり。1行に1つの操作を置く表の形を保つため、rustfmt に整形させない。
#[rustfmt::skip]
pub(super) fn キー操作の決まり(操作: キーで行う操作) -> キー操作の決まり {
    use キーの効く範囲::{いつでも, ライブラリのダイアログが無い間, ダイアログが無い間, 再生の構えでダイアログが無い間};
    let 再生 = |操作| 奪う(再生の構えでダイアログが無い間, 応答::再生(操作));
    let 出力 = |範囲, 操作| 奪う(範囲, 応答::出力(操作));
    let 編集 = |操作| 編集の構えで入力欄に任せる(応答::クリップ(操作));
    match 操作 {
        キーで行う操作::再生と停止を切り替える => 再生(再生の操作::再生を切り替える),
        キーで行う操作::シーケンス再生のときだけ次のクリップへ進める => 出力(再生の構えでダイアログが無い間, 出力の操作::エンターキーの押下で次へ進める),
        キーで行う操作::前のクリップへ戻る => 出力(再生の構えでダイアログが無い間, 出力の操作::前のクリップへ戻る),
        キーで行う操作::次のクリップへ進める => 出力(再生の構えでダイアログが無い間, 出力の操作::次へ進める(進める操作::トリガーを待たずに進める)),
        キーで行う操作::一コマ戻す => 再生(再生の操作::コマ送り(送る向き::戻す)),
        キーで行う操作::一コマ進める => 再生(再生の操作::コマ送り(送る向き::進める)),
        キーで行う操作::五秒戻す => 再生(再生の操作::五秒ずらす(送る向き::戻す)),
        キーで行う操作::五秒進める => 再生(再生の操作::五秒ずらす(送る向き::進める)),
        キーで行う操作::速度を一段下げる => 再生(再生の操作::速度を一段変える(速度を変える向き::下げる)),
        キーで行う操作::速度を一段上げる => 再生(再生の操作::速度を一段変える(速度を変える向き::上げる)),
        キーで行う操作::消音を切り替える => 再生(再生の操作::消音を切り替える),
        キーで行う操作::シアターと編集を切り替える => 出力(再生の構えでダイアログが無い間, 出力の操作::シアターと編集を切り替える),
        キーで行う操作::全画面を抜けるか全画面でなければシアターを抜ける => 出力(ダイアログが無い間, 出力の操作::全画面かシアターを抜ける),
        キーで行う操作::全画面を切り替える => 出力(いつでも, 出力の操作::全画面を切り替える),
        キーで行う操作::ライブラリへ保存する => 奪う(再生の構えでダイアログが無い間, 応答::ライブラリ(ライブラリの操作::今すぐ保存する)),
        キーで行う操作::キーの一覧を開け閉めする => 出力(ライブラリのダイアログが無い間, 出力の操作::キーの一覧を切り替える),
        キーで行う操作::編集を取り消す => 編集(クリップの操作::編集を取り消す),
        キーで行う操作::編集をやり直す => 編集(クリップの操作::編集をやり直す),
        キーで行う操作::開始を今の位置にする => 編集(クリップの操作::選択中の区間の端を今の位置にする(区間の端::開始)),
        キーで行う操作::終了を今の位置にする => 編集(クリップの操作::選択中の区間の端を今の位置にする(区間の端::終了)),
    }
}

/// 修飾キーを含む組を入力欄から奪う決まり。
fn 奪う(効く範囲: キーの効く範囲, 応答: 応答) -> キー操作の決まり {
    キー操作の決まり {
        効く範囲,
        応答,
        入力欄: 入力欄との関係::修飾キーの組なら奪う,
    }
}

/// 編集の構えだけで効き、入力欄にフォーカスがある間は入力欄に任せる決まり。Ctrl+Z は入力欄の文字の取り消しに使うためである。
fn 編集の構えで入力欄に任せる(応答: 応答) -> キー操作の決まり {
    キー操作の決まり {
        効く範囲: キーの効く範囲::編集の構えでダイアログが無い間,
        応答,
        入力欄: 入力欄との関係::入力欄に任せる,
    }
}
