//! 縦横比を保った寸法の計算の試験。期待値は手で計算した値である。出力の寸法の試験は output/size_tests.rs、プレビューの寸法の試験は sidebar/preview_tests.rs にある。

use clip_domain::{画素の寸法, 縦横比};

use super::aspect_fit::{丸める前の論理画素の寸法, 描く縦横比};

fn 縦横比にする(幅: f64, 高さ: f64) -> Option<縦横比> {
    画素の寸法::作成する(幅, 高さ)
        .ok()
        .and_then(|寸法| 寸法.縦横比())
}

const 四百と三百: 丸める前の論理画素の寸法 =
    丸める前の論理画素の寸法::生成する(400.0, 300.0);

#[test]
fn 収めるは内側に収まる最も大きい寸法で_覆うは外側を覆う最も小さい寸法である() {
    let 横長 = 描く縦横比::求める(縦横比にする(2.0, 1.0));
    let 収めた = 四百と三百.縦横比を保って収める(横長);
    assert_eq!(収めた, 丸める前の論理画素の寸法::生成する(400.0, 200.0));
    let 覆った = 四百と三百.縦横比を保って覆う(横長);
    assert_eq!(覆った, 丸める前の論理画素の寸法::生成する(600.0, 300.0));
}

#[test]
fn 縦横比が無いか0なら16対9とみなす() {
    let 無い = 四百と三百.幅に合わせる(描く縦横比::求める(None));
    assert_eq!(無い, 丸める前の論理画素の寸法::生成する(400.0, 225.0));
    let 零 = 四百と三百.幅に合わせる(描く縦横比::求める(縦横比にする(0.0, 9.0)));
    assert_eq!(零, 無い);
}
