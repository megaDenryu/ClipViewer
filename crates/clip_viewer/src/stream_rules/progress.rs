//! 流し読みの進み。流し読みは前へしか読めないため、求める位置が戻ったか遠くへ飛んだかで開き直すかを決める。
//! 参照: _doc/設計/画面.md 判断5

use clip_domain::動画上の秒;

/// 開き直さずに読み進めてよい先の秒数。これより先へ飛んだら、途中のコマを読むより開き直す方が早い。
const 読み進めてよい秒数: f64 = 2.0;

/// 流し読みの進みとは、流し読みに最後に求めた動画上の位置のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 流し読みの進み {
    最後に求めた位置: 動画上の秒,
}

impl 流し読みの進み {
    /// 開いた位置から始める。
    pub(crate) fn 開いた位置から(位置: 動画上の秒) -> Self {
        Self {
            最後に求めた位置: 位置,
        }
    }

    /// その位置を求めるのに開き直すか。最後に求めた位置より前へ戻ったとき、または読み進めてよい先を越えたときに開き直す。
    pub(crate) fn この位置で開き直すか(&self, 求める位置: 動画上の秒) -> bool {
        let 戻ったか = 求める位置 < self.最後に求めた位置;
        let 進んだ長さ = 求める位置.起点から経過した長さ(self.最後に求めた位置);
        戻ったか || 進んだ長さ.秒数() > 読み進めてよい秒数
    }

    /// 求めた位置を覚える。
    pub(crate) fn 求めた位置を覚える(&mut self, 位置: 動画上の秒) {
        self.最後に求めた位置 = 位置;
    }
}
