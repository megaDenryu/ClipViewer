//! 開き直しを判断できる流し読み。映像と音の流し読みが共有する外殻であり、中身(読んでいるか読めないか)と、最後に求めた位置と、
//! 開いた時刻を持ち、開き直すかの判断と、読む途中の失敗を読めない中身へ写すことを受け持つ。

use std::fmt::Display;
use std::time::{Duration, Instant};

use clip_domain::動画上の秒;

use super::progress::流し読みの進み;

/// 流し読みの中身とは、開き直しを判断できる流し読みに入れる、読む途中で失敗したかを問い合わせられる流し読みのことである。
pub(crate) trait 流し読みの中身 {
    /// 読む途中で失敗していれば、その理由の文。
    fn 途中の失敗(&mut self) -> Option<String>;

    /// 動画の終わりまで読み終えたか。
    fn 終わりまで読んだか(&mut self) -> bool;
}

/// 読めるかの区別とは、流し読みを読んでいるか、開けなかったか読む途中で失敗したかの区別のことである。
/// 読めない理由は画面に出す文だけを残す(失敗の値は流し読みが持っていて、流し読みごと捨てるため)。
enum 読めるかの区別<中身> {
    読んでいる(中身),
    読めない(String),
}

/// 開き直しを判断できる流し読みとは、ある位置で開いた流し読みの中身と、最後に求めた位置と、開いた時刻の組のことである。
/// 読めなかったときも同じ位置の規則で扱い、毎フレーム開き直さない。
pub(crate) struct 開き直しを判断できる流し読み<中身> {
    中身: 読めるかの区別<中身>,
    進み: 流し読みの進み,
    開いた時刻: Instant,
}

impl<中身: 流し読みの中身> 開き直しを判断できる流し読み<中身> {
    /// 位置で開いた結果から作る。開けなければ、その理由を持った読めない流し読みになる。
    pub(crate) fn 開いた結果から作る(
        結果: Result<中身, impl Display>,
        位置: 動画上の秒,
        今: Instant,
    ) -> Self {
        let 中身 = match 結果 {
            Ok(中身) => 読めるかの区別::読んでいる(中身),
            Err(失敗) => 読めるかの区別::読めない(失敗.to_string()),
        };
        Self {
            中身,
            進み: 流し読みの進み::開いた位置から(位置),
            開いた時刻: 今,
        }
    }

    pub(crate) fn この位置で開き直すか(&self, 位置: 動画上の秒) -> bool {
        self.進み.この位置で開き直すか(位置)
    }

    /// 開いてから今までの経過。開き直しの最短の間隔を守るために使う。
    pub(crate) fn 開いてからの経過(&self, 今: Instant) -> Duration {
        今.saturating_duration_since(self.開いた時刻)
    }

    /// 読めない理由。読んでいる間は無い。
    pub(crate) fn 読めない理由(&self) -> Option<&str> {
        match &self.中身 {
            読めるかの区別::読んでいる(_) => None,
            読めるかの区別::読めない(理由) => Some(理由),
        }
    }

    /// 読んでいる中身が動画の終わりまで読み終えたか。読めなければ偽である。
    pub(crate) fn 中身が終わりまで読んだか(&mut self) -> bool {
        match &mut self.中身 {
            読めるかの区別::読んでいる(中身) => 中身.終わりまで読んだか(),
            読めるかの区別::読めない(_) => false,
        }
    }

    /// 読んでいる中身。読めなければ無い。失敗は写さない(毎フレームの `求めた位置を覚え途中の失敗を写して中身を貸す` が写す)。
    pub(crate) fn 読んでいる中身(&self) -> Option<&中身> {
        match &self.中身 {
            読めるかの区別::読んでいる(中身) => Some(中身),
            読めるかの区別::読めない(_) => None,
        }
    }

    /// 位置を求めたことを覚え、読む途中で失敗していれば読めない流し読みへ移り、読んでいればその中身を貸す。
    /// 映像も音も、毎フレームこれを呼んで失敗を写す。
    pub(crate) fn 求めた位置を覚え途中の失敗を写して中身を貸す(
        &mut self,
        位置: 動画上の秒,
    ) -> Option<&mut 中身> {
        self.進み.求めた位置を覚える(位置);
        if let 読めるかの区別::読んでいる(中身) = &mut self.中身
            && let Some(理由) = 中身.途中の失敗()
        {
            self.中身 = 読めるかの区別::読めない(理由);
        }
        match &mut self.中身 {
            読めるかの区別::読んでいる(中身) => Some(中身),
            読めるかの区別::読めない(_) => None,
        }
    }
}
