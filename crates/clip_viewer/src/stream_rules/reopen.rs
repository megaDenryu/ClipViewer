//! 流し読みを開き直してよいかの区別と、開き直しの最短の間隔。

use std::time::Duration;

/// 流し読みを開き直す最短の間隔。求める位置が毎フレーム戻っても、ffmpeg をフレームの頻度で起動し直さない。
pub(crate) const 開き直しの最短の間隔: Duration = Duration::from_millis(250);

/// 流し読みの開き直しとは、このフレームで流し読みを開き直してよいかの区別のことである。
/// 再生位置の帯をドラッグしている間は、映像も音も開き直さない。カードの区間の帯をドラッグしている間は、映像は掴んだものの
/// 位置のコマを映すため開き直してよく、音は黙っているため開き直さない。参照: _doc/設計/画面.md 判断5
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 流し読みの開き直し {
    してよい,
    控える,
}
