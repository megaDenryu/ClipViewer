//! キャッシュを使わない一覧のサムネイルの作り方。サムネイルを確かめない試験で、%LOCALAPPDATA% の本物のフォルダを使わないために使う。

use eframe::egui;
use thumbnail_cache::{
    キャッシュの容量, キャッシュの時計, キャッシュの置き場所, サムネイルのキャッシュ,
};

use super::shelf::一覧のサムネイル;

impl 一覧のサムネイル {
    /// キャッシュの置き場所を使わない一覧のサムネイル。何を置いても持たず、読むと常に無い。
    pub(crate) fn キャッシュを使わずに作る(eguiの本体: egui::Context) -> Self {
        let キャッシュ = サムネイルのキャッシュ::作成する(
            キャッシュの置き場所::使わない,
            キャッシュの容量::既定,
            キャッシュの時計::実時間(),
        );
        Self::作成する(eguiの本体, キャッシュ)
    }
}
