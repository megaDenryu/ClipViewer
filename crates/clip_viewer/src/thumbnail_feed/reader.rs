//! キャッシュを見て画素へ戻す処理。キャッシュに撮り方のサムネイルがあるかを見ることと、持っている JPEG を画素へ戻すことを行う。
//! キャッシュから読んだ JPEG が画素へ戻せなければ、壊れたキャッシュとして消す(撮り直させるため)。

use std::marker::PhantomData;

use clip_domain::{サムネイルの撮り方, サムネイルの画像};
use thumbnail_cache::サムネイルのキャッシュ;

use super::pixels::{戻した画素, 画素へ戻せない理由};
use super::rows::一覧の行の識別子;
use super::status::画像の出どころ;
use super::worker::裏のスレッドで仕事を行う処理;

/// 読む仕事とは、読む裏のスレッドへ頼む仕事の区別のことである。
pub(super) enum 読む仕事<識別子> {
    キャッシュを見る {
        識別子: 識別子,
        撮り方: サムネイルの撮り方,
    },
    画素へ戻す {
        識別子: 識別子,
        撮り方: サムネイルの撮り方,
        画像: サムネイルの画像,
        出どころ: 画像の出どころ,
    },
}

/// 読んだ結果とは、読む仕事の結果の区別のことである。どちらも識別子と撮り方を持ち、今の撮り方の結果かを確かめられる。
pub(super) enum 読んだ結果<識別子> {
    キャッシュを見た {
        識別子: 識別子,
        撮り方: サムネイルの撮り方,
        画像: Option<サムネイルの画像>,
    },
    画素へ戻した {
        識別子: 識別子,
        撮り方: サムネイルの撮り方,
        画素: Result<戻した画素, 画素へ戻せない理由>,
    },
}

/// キャッシュを見て画素へ戻す処理とは、サムネイルのキャッシュを保持して、読む仕事を行うもののことである。仕事と結果が持つ識別子の型を引数に取る。
pub(super) struct キャッシュを見て画素へ戻す処理<識別子> {
    キャッシュ: サムネイルのキャッシュ,
    識別子の型: PhantomData<fn() -> 識別子>,
}

impl<識別子> キャッシュを見て画素へ戻す処理<識別子> {
    /// 読むキャッシュから作る。
    pub(super) fn 作成する(キャッシュ: サムネイルのキャッシュ) -> Self {
        Self {
            キャッシュ,
            識別子の型: PhantomData,
        }
    }
}

impl<識別子: 一覧の行の識別子> 裏のスレッドで仕事を行う処理
    for キャッシュを見て画素へ戻す処理<識別子>
{
    type 仕事 = 読む仕事<識別子>;
    type 結果 = 読んだ結果<識別子>;

    fn 行う(&mut self, 仕事: 読む仕事<識別子>) -> 読んだ結果<識別子> {
        match 仕事 {
            読む仕事::キャッシュを見る {
                識別子, 撮り方
            } => {
                // キャッシュを読めないときは無いとして撮りに行く。キャッシュは捨ててよいデータであり、撮れば見せられるためである。
                let 画像 = self.キャッシュ.読む(&撮り方).ok().flatten();
                読んだ結果::キャッシュを見た {
                    識別子,
                    撮り方,
                    画像,
                }
            }
            読む仕事::画素へ戻す {
                識別子,
                撮り方,
                画像,
                出どころ,
            } => {
                let 画素 = 戻した画素::サムネイルの画像から戻す(&画像);
                if 画素.is_err() && 出どころ == 画像の出どころ::キャッシュ {
                    let _ = self.キャッシュ.捨てる(&撮り方);
                }
                読んだ結果::画素へ戻した {
                    識別子,
                    撮り方,
                    画素,
                }
            }
        }
    }
}
