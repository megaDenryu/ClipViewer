//! 重ね合わせの一覧を読んだことを当てる試験。顔の置いたクリップがある重ね合わせは顔の撮り方と顔の動画の有無で、置いたクリップが無い重ね合わせは撮らない項目にする。
//! 参照: _doc/設計/ライブラリ.md 判断11
#![allow(clippy::expect_used)]

use clip_domain::{
    ライブラリの日時, ライブラリの重ね合わせ, 重ね合わせ, 重ね合わせの名前, 重ね合わせの識別子,
};
use clip_library::{
    動画の有無, 読めた重ね合わせ, 重ね合わせの一覧, 重ね合わせの一覧の項目
};
use eframe::egui;

use super::item::サムネイルの項目;
use super::list_sync::一覧のサムネイルの大きさ;
use super::shelf::一覧のサムネイル;
use crate::overlay::test_support::{五秒の重ね合わせ, 長さが0秒の重ね合わせ};

fn 識別子(番号: u32) -> 重ね合わせの識別子 {
    重ね合わせの識別子::文字列から作成する(format!("overlay-{番号}-0")).expect("識別子")
}

fn 読めた(
    番号: u32,
    重ね合わせ: 重ね合わせ,
    動画: 動画の有無,
) -> 重ね合わせの一覧の項目 {
    重ね合わせの一覧の項目::読めた(読めた重ね合わせ {
        動画の有無の並び: vec![動画; 重ね合わせ.動画の表().動画の数()],
        重ね合わせ: ライブラリの重ね合わせ::新しく作る(
            識別子(番号),
            重ね合わせの名前::作成する("重ね".into()).expect("名前"),
            重ね合わせ,
            ライブラリの日時::紀元,
        ),
    })
}

#[test]
fn 顔のある重ね合わせは顔の撮り方と動画の有無で_置いたクリップの無い重ね合わせは撮らない項目にする()
{
    let mut サムネイル =
        一覧のサムネイル::<重ね合わせの識別子>::キャッシュを使わずに作る(egui::Context::default());
    let 一覧 = 重ね合わせの一覧 {
        項目: vec![
            読めた(1, 五秒の重ね合わせ(), 動画の有無::見つからない),
            読めた(2, 長さが0秒の重ね合わせ(), 動画の有無::ある),
        ],
    };
    サムネイル.重ね合わせの一覧を読んだ(&一覧);
    let 表 = サムネイル.項目の表();
    let 重ね合わせの一覧の項目::読めた(一つ目) = &一覧.項目[0] else {
        panic!("読めた");
    };
    assert!(matches!(
        表.get(&識別子(1)),
        Some(サムネイルの項目::撮り方がある { 撮り方, 動画: 動画の有無::見つからない, .. })
            if Some(撮り方) == 一つ目.重ね合わせ.サムネイルの撮り方(一覧のサムネイルの大きさ).as_ref()
    ));
    assert!(matches!(
        表.get(&識別子(2)),
        Some(サムネイルの項目::撮り方が無い)
    ));
}
