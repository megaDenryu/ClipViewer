//! 撮る順番。撮る裏のスレッドが空くたびに、見えている行から先に撮る順番を待っている行を選び、見えている行に無ければ見せる順の最初の行を選んで
//! 撮る仕事を頼む。1件ずつ選び直すため、スクロールした先の行や登録したばかりの行が、先に選んだ行の後ろで待たない。

use std::collections::HashMap;

use super::item::サムネイルの項目;
use super::means::撮る手立て;
use super::rows::{一覧の行の識別子, 行の並び};
use super::shelf::一覧のサムネイル;
use super::shooter::撮る仕事;
use super::status::{サムネイルの様子, サムネイルを撮らない理由};

impl<識別子: 一覧の行の識別子> 一覧のサムネイル<識別子> {
    /// 撮る裏のスレッドが空いていれば、次に撮る行を1つ選んで撮る仕事にする。FFmpeg が無ければ撮らない。
    pub(super) fn 撮る仕事を頼む(
        &mut self,
        並び: &行の並び<'_, 識別子>,
        手立て: &撮る手立て,
    ) {
        if self.撮る裏のスレッド.返事を待っている数() > 0 {
            return;
        }
        let 読み手 = match 手立て {
            撮る手立て::撮れる(読み手) => 読み手,
            撮る手立て::FFmpegが無い => {
                return self.待っている行をすべて撮らないにする(
                    サムネイルを撮らない理由::FFmpegが無い,
                );
            }
        };
        self.ffmpegが無くて撮らなかった行を撮る順番へ戻す();
        let Some(識別子) = 次に撮る行(self.表を読む(), 並び).cloned() else {
            return;
        };
        let Some(サムネイルの項目::撮り方がある { 撮り方, .. }) = self.表を読む().get(&識別子)
        else {
            return;
        };
        let 仕事 = 撮る仕事 {
            識別子: 識別子.clone(),
            撮り方: 撮り方.clone(),
            読み手: 読み手.clone(),
        };
        let 様子 = match self.撮る裏のスレッド.頼む(仕事) {
            Ok(()) => サムネイルの様子::撮っている,
            Err(止まっている) => サムネイルの様子::出せない(止まっている.into()),
        };
        self.様子を置く(&識別子, 様子);
    }
}

/// 撮る順番を待っている行のうち、見えている行から順に並べて最初のものを選ぶ。無ければ無い。
pub(super) fn 次に撮る行<'並び, 識別子: 一覧の行の識別子>(
    表: &HashMap<識別子, サムネイルの項目>,
    並び: &'並び 行の並び<'並び, 識別子>,
) -> Option<&'並び 識別子> {
    並び.見えている行を先にした全部の行().find(|識別子| {
        matches!(
            表.get(*識別子),
            Some(サムネイルの項目::撮り方がある {
                様子: サムネイルの様子::撮る順番を待っている,
                ..
            })
        )
    })
}
