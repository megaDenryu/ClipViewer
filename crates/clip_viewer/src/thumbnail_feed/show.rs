//! サムネイルの見せ方。サムネイルの項目の様子から、一覧の行の枠にテクスチャを出すか、途中の段階を出すか、
//! 撮らない・出せない理由を出すかを決める。

use std::rc::Rc;

use sengen_egui::差し替えられるテクスチャ;

use super::item::サムネイルの項目;
use super::status::{
    サムネイルの様子, サムネイルを出せない理由, サムネイルを撮らない理由, 表示の段階,
};

/// 途中の段階とは、サムネイルをまだ見せられず、裏の仕事を待っている段階の区別のことである。一覧の枠に短い文で出す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 途中の段階 {
    読んでいる,
    撮る順番を待っている,
    撮っている,
}

/// サムネイルの見せ方とは、一覧の行の枠に、テクスチャを出すか、途中の段階を出すか、撮らない・出せない理由を出すかの区別のことである。
#[derive(Clone)]
pub(crate) enum サムネイルの見せ方 {
    見せられる(Rc<差し替えられるテクスチャ>),
    途中(途中の段階),
    撮らない(サムネイルを撮らない理由),
    出せない(サムネイルを出せない理由),
}

impl サムネイルの項目 {
    /// 一覧の行の枠に出す見せ方。
    pub(crate) fn 見せ方(&self) -> サムネイルの見せ方 {
        let Self::撮り方がある { 様子, .. } = self else {
            return サムネイルの見せ方::撮らない(
                サムネイルを撮らない理由::再生できるクリップが無い,
            );
        };
        let 途中 = サムネイルの見せ方::途中;
        match 様子 {
            サムネイルの様子::持っている {
                表示:
                    表示の段階::載せた {
                        テクスチャ, ..
                    },
                ..
            } => サムネイルの見せ方::見せられる(Rc::clone(テクスチャ)),
            サムネイルの様子::キャッシュを見る前
            | サムネイルの様子::キャッシュを見ている
            | サムネイルの様子::持っている { .. } => 途中(途中の段階::読んでいる),
            サムネイルの様子::撮る順番を待っている => {
                途中(途中の段階::撮る順番を待っている)
            }
            サムネイルの様子::撮っている => 途中(途中の段階::撮っている),
            サムネイルの様子::撮らない(理由) => {
                サムネイルの見せ方::撮らない(*理由)
            }
            サムネイルの様子::出せない(理由) => {
                サムネイルの見せ方::出せない(理由.clone())
            }
        }
    }
}
