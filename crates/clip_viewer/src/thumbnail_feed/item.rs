//! サムネイルの項目。1つのスタックの撮り方と動画の有無と様子を持ち、様子を問い合わせる・書き換える口を持つ。
//! 一覧の行に出す見せ方は show.rs が決める。

use clip_domain::サムネイルの撮り方;
use clip_library::動画の有無;

use super::status::サムネイルの様子;

/// サムネイルの項目とは、1つのスタックのサムネイルについて、撮り方が無いか、撮り方と動画の有無と様子があるかの区別のことである。
/// 撮り方が等しい間は様子を引き継ぎ、撮り方が変わったらキャッシュを見る前からやり直す。
#[derive(Clone)]
pub(crate) enum サムネイルの項目 {
    撮り方が無い,
    撮り方がある {
        撮り方: サムネイルの撮り方,
        動画: 動画の有無,
        様子: サムネイルの様子,
    },
}

impl サムネイルの項目 {
    /// 撮り方と動画の有無から、キャッシュを見る前の項目を作る。撮り方が無ければ撮らない。
    pub(super) fn 撮り方から作る(
        撮り方: Option<サムネイルの撮り方>,
        動画: 動画の有無,
    ) -> Self {
        match 撮り方 {
            None => Self::撮り方が無い,
            Some(撮り方) => Self::撮り方がある {
                撮り方,
                動画,
                様子: サムネイルの様子::キャッシュを見る前,
            },
        }
    }

    /// キャッシュを見る前か。
    pub(super) fn キャッシュを見る前か(&self) -> bool {
        matches!(
            self,
            Self::撮り方がある {
                様子: サムネイルの様子::キャッシュを見る前,
                ..
            }
        )
    }

    /// 撮り方が等しく、JPEG を持っているか。
    pub(super) fn 同じ撮り方で画像を持っているか(
        &self,
        撮り方: &サムネイルの撮り方,
    ) -> bool {
        matches!(
            self,
            Self::撮り方がある {
                撮り方: 今の撮り方,
                様子: サムネイルの様子::持っている { .. },
                ..
            } if 今の撮り方 == 撮り方
        )
    }

    /// 撮り方が等しいときだけ、様子を借りて書き換える。届いた結果が今の撮り方のものかを確かめるために使う。
    pub(super) fn 同じ撮り方の様子(
        &mut self,
        撮り方: &サムネイルの撮り方,
    ) -> Option<(&mut サムネイルの様子, 動画の有無)> {
        match self {
            Self::撮り方がある {
                撮り方: 今の撮り方,
                動画,
                様子,
            } if 今の撮り方 == 撮り方 => Some((様子, *動画)),
            _ => None,
        }
    }
}
