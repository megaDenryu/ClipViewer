//! テクスチャの棚。画素へ戻したサムネイルを egui へ登録して載せ、仕事を進めた回を数え、見えている行のテクスチャに
//! 見えた回の印を付け、テクスチャが上限を超えたら、見えていないものを最後に見えた回の古い順に捨てる
//! (JPEG のバイト列は残し、また見えたら画素へ戻し直す)。GPU のメモリを件数に比例させないためである。
//! 参照: _doc/設計/ライブラリ.md 判断10(GPU)

use std::collections::HashMap;
use std::rc::Rc;

use clip_domain::スタックの識別子;
use eframe::egui;
use sengen_egui::画素の並びの不正;

use super::item::サムネイルの項目;
use super::pixels::戻した画素;
use super::rows::{行の並び, 見えた回};
use super::status::{サムネイルの様子, 表示の段階};

/// テクスチャを持つ数の上限。1枚は 192×108×4 = 約83KB なので、48枚で約4MB である。見えている行はこれを超えても捨てない。
pub(super) const テクスチャを持つ上限: usize = 48;

/// テクスチャの棚とは、サムネイルのテクスチャの登録に使う egui の本体と、一覧のサムネイルが仕事を進めた今の回の組のことである。
/// 載せたテクスチャそのものは項目の表の各項目が持ち、棚は載せることと、回の印と、上限を超えた分を捨てることを受け持つ。
pub(super) struct テクスチャの棚 {
    画面描画の共有状態: egui::Context,
    今の回: 見えた回,
}

impl テクスチャの棚 {
    /// egui の本体から作る。回は最初の回から数える。
    pub(super) fn 作成する(画面描画の共有状態: egui::Context) -> Self {
        Self {
            画面描画の共有状態,
            今の回: 見えた回::default(),
        }
    }

    /// 仕事を進める回を1つ進める。
    pub(super) fn 回を進める(&mut self) {
        self.今の回 = self.今の回.次();
    }

    /// 戻した画素を egui へ登録し、今の回に見えたものとして載せた表示の段階にする。
    pub(super) fn 載せる(
        &self,
        識別子: &スタックの識別子,
        戻した: &戻した画素,
    ) -> Result<表示の段階, 画素の並びの不正> {
        let 名前 = format!("ライブラリのサムネイル {識別子}");
        let テクスチャ = 戻した.テクスチャにする(&self.画面描画の共有状態, 名前)?;
        Ok(表示の段階::載せた {
            テクスチャ: Rc::new(テクスチャ),
            最後に見えた回: self.今の回,
        })
    }

    /// 見えている行の載せたテクスチャに、今の回を最後に見えた回として付ける。
    pub(super) fn 見えている行に印を付ける(
        &self,
        表: &mut HashMap<スタックの識別子, サムネイルの項目>,
        並び: &行の並び,
    ) {
        for 識別子 in &並び.見えている {
            if let Some(最後に見えた回) =
                載せたテクスチャの見えた回(表.get_mut(*識別子))
            {
                *最後に見えた回 = self.今の回;
            }
        }
    }

    /// 載せたテクスチャが上限を超えていれば、今の回に見えていないものを、最後に見えた回の古い順に捨てる。
    pub(super) fn 見えていないテクスチャを捨てる(
        &self,
        表: &mut HashMap<スタックの識別子, サムネイルの項目>,
    ) {
        let mut 載せた: Vec<(見えた回, スタックの識別子)> = 表
            .iter_mut()
            .filter_map(|(識別子, 項目)| {
                載せたテクスチャの見えた回(Some(項目)).map(|回| (*回, 識別子.clone()))
            })
            .collect();
        let Some(捨てる数) = 載せた.len().checked_sub(テクスチャを持つ上限) else {
            return;
        };
        載せた.sort();
        for (回, 識別子) in 載せた.into_iter().take(捨てる数) {
            if 回 == self.今の回 {
                break;
            }
            if let Some(サムネイルの項目::撮り方がある {
                様子: サムネイルの様子::持っている { 表示, .. },
                ..
            }) = 表.get_mut(&識別子)
            {
                *表示 = 表示の段階::載せていない;
            }
        }
    }
}

/// 項目がテクスチャを載せていれば、その最後に見えた回を借りる。
fn 載せたテクスチャの見えた回(
    項目: Option<&mut サムネイルの項目>,
) -> Option<&mut 見えた回> {
    match 項目? {
        サムネイルの項目::撮り方がある {
            様子:
                サムネイルの様子::持っている {
                    表示:
                        表示の段階::載せた {
                            最後に見えた回,
                        ..
                        },
                    ..
                },
            ..
        } => Some(最後に見えた回),
        _ => None,
    }
}
