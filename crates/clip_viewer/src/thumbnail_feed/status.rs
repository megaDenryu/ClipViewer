//! サムネイルの様子。一覧の1行のサムネイルが、キャッシュを見る前から見せられるまでのどこにいるかと、撮らない・出せない理由を持つ。
//! 参照: _doc/設計/ライブラリ.md 判断10

use std::rc::Rc;

use clip_domain::サムネイルの画像;
use clip_library::動画の有無;
use sengen_egui::{差し替えられるテクスチャ, 画素の並びの不正};
use video_source::サムネイルの撮影の失敗;

use super::pixels::画素へ戻せない理由;
use super::rows::見えた回;
use super::worker::裏のスレッドが止まっている;

/// サムネイルを撮らない理由とは、キャッシュに無いサムネイルを撮りに行かない理由の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub(crate) enum サムネイルを撮らない理由 {
    #[error("動画が無い")]
    動画が見つからない,
    #[error("再生できるクリップが無い")]
    再生できるクリップが無い,
    #[error("FFmpeg が無い")]
    FFmpegが無い,
}

/// サムネイルを出せない理由とは、撮りに行ったのにサムネイルを見せられなかった理由の区別のことである。
/// 見えている行を組む閉包と共有するため、複製できない失敗は `Rc` で持つ。文字列にするのは表示の直前だけである。
#[derive(Debug, Clone, thiserror::Error)]
pub(crate) enum サムネイルを出せない理由 {
    #[error("{0}")]
    撮れない(Rc<サムネイルの撮影の失敗>),
    #[error("{0}")]
    画素へ戻せない(Rc<画素へ戻せない理由>),
    #[error("テクスチャにできない: {0}")]
    テクスチャにできない(画素の並びの不正),
    #[error("{0}")]
    裏のスレッドが止まっている(#[from] 裏のスレッドが止まっている),
}

/// 画像の出どころとは、持っている JPEG をキャッシュから読んだか、今撮ったかの区別のことである。
/// キャッシュから読んだものが画素へ戻せなければ壊れたキャッシュとして撮り直し、撮ったものが戻せなければ撮れないとする。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 画像の出どころ {
    キャッシュ,
    撮った,
}

/// 表示の段階とは、持っている JPEG をテクスチャにしていないか、画素へ戻している途中か、テクスチャに載せたかの区別のことである。
/// 載せたテクスチャは、最後に見えた回とともに持つ(見えなくなったものを古い順に捨てるため)。
#[derive(Clone)]
pub(crate) enum 表示の段階 {
    載せていない,
    画素へ戻している,
    載せた {
        テクスチャ: Rc<差し替えられるテクスチャ>,
        最後に見えた回: 見えた回,
    },
}

/// サムネイルの様子とは、撮り方のある1つのスタックのサムネイルが、キャッシュを見る前から見せられるまでのどこにいるか、
/// または撮らない・出せないかの区別のことである。持っている間は JPEG のバイト列(数KB)を RAM に持つ。
#[derive(Clone)]
pub(crate) enum サムネイルの様子 {
    キャッシュを見る前,
    キャッシュを見ている,
    撮る順番を待っている,
    撮っている,
    持っている {
        画像: サムネイルの画像,
        出どころ: 画像の出どころ,
        表示: 表示の段階,
    },
    撮らない(サムネイルを撮らない理由),
    出せない(サムネイルを出せない理由),
}

impl サムネイルの様子 {
    /// JPEG を持ち、まだテクスチャにしていない様子。
    pub(super) fn 画像を持った(
        画像: サムネイルの画像, 出どころ: 画像の出どころ
    ) -> Self {
        Self::持っている {
            画像,
            出どころ,
            表示: 表示の段階::載せていない,
        }
    }

    /// キャッシュに無い(壊れていた)ときの様子。動画があれば撮る順番を待ち、無ければ撮らない。
    pub(super) fn キャッシュに無いとき(動画: 動画の有無) -> Self {
        match 動画 {
            動画の有無::ある => Self::撮る順番を待っている,
            動画の有無::見つからない => {
                Self::撮らない(サムネイルを撮らない理由::動画が見つからない)
            }
        }
    }
}
