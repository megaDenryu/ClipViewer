//! 様子をまとめて変える。裏のスレッドが止まったとき、FFmpeg が無いとき・見つかったときに、該当する行の様子を一度に変える。

use clip_domain::スタックの識別子;

use super::item::サムネイルの項目;
use super::shelf::一覧のサムネイル;
use super::status::{
    サムネイルの様子, サムネイルを出せない理由, サムネイルを撮らない理由, 表示の段階,
};
use super::worker::裏のスレッドが止まっている;

impl 一覧のサムネイル {
    /// 識別子の行に様子を置く。撮り方の無い行と一覧に無い行には置かない。
    pub(super) fn 様子を置く(
        &mut self,
        識別子: &スタックの識別子,
        新しい様子: サムネイルの様子,
    ) {
        if let Some(サムネイルの項目::撮り方がある { 様子, .. }) = self.表を変える().get_mut(識別子)
        {
            *様子 = 新しい様子;
        }
    }

    /// 識別子の行を出せないにする。
    pub(super) fn 出せないにする(
        &mut self,
        識別子: &スタックの識別子,
        理由: サムネイルを出せない理由,
    ) {
        self.様子を置く(識別子, サムネイルの様子::出せない(理由));
    }

    /// 裏のスレッドが異常終了していたら、その返事を待っていた行を出せないにする。もう届かない返事を待ち続けて、
    /// 描き直しを永久に続けないためである。
    pub(super) fn 止まった裏のスレッドの仕事を諦める(&mut self) {
        let (撮るほうが止まった, 読むほうが止まった) = (
            self.撮る裏のスレッド.止まったか(),
            self.読む裏のスレッド.止まったか(),
        );
        if !撮るほうが止まった && !読むほうが止まった {
            return;
        }
        for 項目 in self.表を変える().values_mut() {
            let サムネイルの項目::撮り方がある { 様子, .. } = 項目 else {
                continue;
            };
            let 返事を待っていたか = match 様子 {
                サムネイルの様子::撮っている => 撮るほうが止まった,
                サムネイルの様子::キャッシュを見ている
                | サムネイルの様子::持っている {
                    表示: 表示の段階::画素へ戻している,
                    ..
                } => 読むほうが止まった,
                _ => false,
            };
            if 返事を待っていたか {
                *様子 = サムネイルの様子::出せない(裏のスレッドが止まっている.into());
            }
        }
    }

    /// 撮る順番を待っている行をすべて撮らないにする(FFmpeg が無いとき)。
    pub(super) fn 待っている行をすべて撮らないにする(
        &mut self,
        理由: サムネイルを撮らない理由,
    ) {
        for 項目 in self.表を変える().values_mut() {
            if let サムネイルの項目::撮り方がある {
                様子: 様子 @ サムネイルの様子::撮る順番を待っている,
                ..
            } = 項目
            {
                *様子 = サムネイルの様子::撮らない(理由);
            }
        }
    }

    /// FFmpeg が無いので撮らなかった行を、撮る順番へ戻す(利用者が FFmpeg の場所を指定し直したとき)。
    pub(super) fn ffmpegが無くて撮らなかった行を撮る順番へ戻す(&mut self) {
        for 項目 in self.表を変える().values_mut() {
            if let サムネイルの項目::撮り方がある {
                様子:
                    様子 @ サムネイルの様子::撮らない(
                        サムネイルを撮らない理由::FFmpegが無い,
                    ),
                ..
            } = 項目
            {
                *様子 = サムネイルの様子::撮る順番を待っている;
            }
        }
    }
}
