//! 一覧のサムネイル。ライブラリの一覧の各スタックのサムネイルの項目を持ち、キャッシュを見る・撮る・画素へ戻すを裏のスレッドへ頼み、
//! 届いた結果をテクスチャにする。何をいつ撮るか・読むかの判断はここに閉じ、状態は一覧を読んだことと見えている行を知らせるだけにする。
//! 参照: _doc/設計/ライブラリ.md 判断10

use std::collections::HashMap;
use std::rc::Rc;

use clip_domain::スタックの識別子;
use eframe::egui;
use sengen_egui::画素の並びの不正;
use thumbnail_cache::サムネイルのキャッシュ;
use video_source::{取り消しの合図, 撮影に使う動画の情報の覚え};

use super::item::サムネイルの項目;
use super::pixels::戻した画素;
use super::reader::キャッシュを見て画素へ戻す処理;
use super::rows::行の並び;
use super::shooter::サムネイルを撮ってキャッシュへ置く処理;
use super::status::表示の段階;
use super::textures::テクスチャの棚;
use super::worker::仕事を順に行う裏のスレッド;

/// 項目の表とは、スタックの識別子ごとのサムネイルの項目のことである。見えている行を組む閉包と共有するため `Rc` で持つ。
pub(crate) type サムネイルの項目の表 = Rc<HashMap<スタックの識別子, サムネイルの項目>>;

/// 一覧のサムネイルとは、テクスチャの棚と、スタックごとのサムネイルの項目の表と、撮る裏のスレッドと読む裏のスレッドと、
/// 撮影を取り消す合図の組のことである。項目の表とテクスチャの棚は私有にし、ほかのファイルはこの型のメソッドを通して触る。
/// 撮る(FFmpeg を起動する)ことと読むことを別のスレッドにするのは、撮っている間(1枚あたり ffprobe と ffmpeg の2回の起動)も、キャッシュにあるサムネイルを待たずに出すためである。
pub(crate) struct 一覧のサムネイル {
    テクスチャ: テクスチャの棚,
    項目の表: サムネイルの項目の表,
    pub(super) 撮る裏のスレッド:
        仕事を順に行う裏のスレッド<サムネイルを撮ってキャッシュへ置く処理>,
    pub(super) 読む裏のスレッド:
        仕事を順に行う裏のスレッド<キャッシュを見て画素へ戻す処理>,
    合図: 取り消しの合図,
}

impl 一覧のサムネイル {
    /// egui の本体とサムネイルのキャッシュから作り、撮る裏のスレッドと読む裏のスレッドを起こす。
    pub(crate) fn 作成する(
        画面描画の共有状態: egui::Context,
        キャッシュ: サムネイルのキャッシュ,
    ) -> Self {
        let 合図 = 取り消しの合図::default();
        Self {
            テクスチャ: テクスチャの棚::作成する(画面描画の共有状態),
            項目の表: Rc::default(),
            撮る裏のスレッド: 仕事を順に行う裏のスレッド::起こす(
                サムネイルを撮ってキャッシュへ置く処理 {
                    キャッシュ: キャッシュ.clone(),
                    合図: 合図.clone(),
                    動画の情報の覚え: 撮影に使う動画の情報の覚え::default(),
                },
            ),
            読む裏のスレッド: 仕事を順に行う裏のスレッド::起こす(
                キャッシュを見て画素へ戻す処理 { キャッシュ },
            ),
            合図,
        }
    }

    /// 項目の表。見えている行を組む閉包へ持ち込む。
    pub(crate) fn 項目の表(&self) -> サムネイルの項目の表 {
        Rc::clone(&self.項目の表)
    }

    /// 撮るか読むかの結果をまだ受け取っていないか。待っている間は、入力が無くても画面を進めて結果を受け取る。
    pub(crate) fn 返事を待っているか(&self) -> bool {
        self.撮る裏のスレッド.返事を待っている数() > 0
            || self.読む裏のスレッド.返事を待っている数() > 0
    }

    /// 行の並びの見せる順(絞り込みの後の行)に、キャッシュを見る前の行が残っているか。残っている間は、画面が描き直しを早めて
    /// キャッシュを見る仕事を続けて頼ませる。仕事は見せる順の行にしか回らないため、絞り込みで隠れた行は数えない
    /// (数えると、隠れた行が残る限り描き直しが止まらない)。
    pub(crate) fn キャッシュを見る前の行があるか(
        &self, 並び: &行の並び
    ) -> bool {
        並び.見せる順.iter().any(|識別子| {
            self.項目の表
                .get(*識別子)
                .is_some_and(サムネイルの項目::キャッシュを見る前か)
        })
    }

    /// 項目の表を読むために借りる。
    pub(super) fn 表を読む(
        &self,
    ) -> &HashMap<スタックの識別子, サムネイルの項目> {
        &self.項目の表
    }

    /// 回を進め、見えている行の載せたテクスチャに今の回の印を付ける。
    pub(super) fn 回を進めて見えている行に印を付ける(
        &mut self, 並び: &行の並び
    ) {
        self.テクスチャ.回を進める();
        let 表 = Rc::make_mut(&mut self.項目の表);
        self.テクスチャ.見えている行に印を付ける(表, 並び);
    }

    /// 載せたテクスチャが上限を超えていれば、見えていないものを古い順に捨てる。
    pub(super) fn 見えていないテクスチャを捨てる(&mut self) {
        let 表 = Rc::make_mut(&mut self.項目の表);
        self.テクスチャ.見えていないテクスチャを捨てる(表);
    }

    /// 戻した画素をテクスチャの棚へ載せ、載せた表示の段階を返す。
    pub(super) fn テクスチャに載せる(
        &self,
        識別子: &スタックの識別子,
        戻した: &戻した画素,
    ) -> Result<表示の段階, 画素の並びの不正> {
        self.テクスチャ.載せる(識別子, 戻した)
    }

    /// 項目の表を書き換えるために借りる。見えている行を組む閉包と共有していれば、表を写してから借りる
    /// (閉包は描画の間だけ生きるため、フレームを進める間に写すことは起きない)。
    pub(super) fn 表を変える(
        &mut self,
    ) -> &mut HashMap<スタックの識別子, サムネイルの項目> {
        Rc::make_mut(&mut self.項目の表)
    }
}

impl Drop for 一覧のサムネイル {
    /// 撮っている途中の ffmpeg を止めさせてから、裏のスレッドを閉じる(フィールドはこの後に落ちる)。
    /// アプリを閉じるときに撮影の終わりを待たないためである。
    fn drop(&mut self) {
        self.合図.取り消す();
    }
}
