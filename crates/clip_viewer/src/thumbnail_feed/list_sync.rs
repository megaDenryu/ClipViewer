//! 一覧を読んだことを当てる。走査した一覧の各スタックの撮り方と動画の有無を項目の表へ写し、撮り方が変わらない項目は様子を引き継ぐ。
//! 参照: _doc/設計/ライブラリ.md 判断10(古いサムネイルが出ない理由・撮るとき)

use std::collections::HashSet;

use clip_domain::サムネイルの大きさ;
use clip_library::{ライブラリの一覧, 一覧の項目, 動画の有無};

use super::item::サムネイルの項目;
use super::shelf::一覧のサムネイル;
use super::status::{サムネイルの様子, サムネイルを撮らない理由};

/// 一覧に出すサムネイルの大きさ。一覧の行の枠(96×54 論理画素)の2倍にし、表示倍率が2倍でも粗く見せない。
pub(crate) const 一覧のサムネイルの大きさ: サムネイルの大きさ =
    match サムネイルの大きさ::作成する(192, 108) {
        Some(大きさ) => 大きさ,
        None => panic!("一覧のサムネイルの大きさは0でない"),
    };

impl 一覧のサムネイル {
    /// 一覧を読んだ。撮り方が変わっていない項目は様子を引き継ぎ、変わった項目と新しい項目はキャッシュを見る前からにする。
    /// ここでは撮りも読みもしない(起動しただけでは撮らないため。仕事はライブラリの構えで `仕事を進める` が頼む)。
    /// 一覧に無くなったスタックの項目は捨てる(テクスチャも解放される)。
    pub(crate) fn 一覧を読んだ(&mut self, 一覧: &ライブラリの一覧) {
        let mut 一覧にある = HashSet::new();
        let 表 = self.表を変える();
        for 項目 in &一覧.項目 {
            let 一覧の項目::読めた(読めた) = 項目 else {
                continue;
            };
            let 識別子 = 読めた.スタック.識別子();
            一覧にある.insert(識別子.clone());
            let 新しい = サムネイルの項目::撮り方から作る(
                読めた.スタック.サムネイルの撮り方(一覧のサムネイルの大きさ),
                読めた.動画,
            );
            match (表.get_mut(識別子), 新しい) {
                (
                    Some(サムネイルの項目::撮り方がある {
                        撮り方, 動画, 様子
                    }),
                    サムネイルの項目::撮り方がある {
                        撮り方: 新しい撮り方,
                        動画: 新しい動画,
                        ..
                    },
                ) if *撮り方 == 新しい撮り方 => {
                    *動画 = 新しい動画;
                    if let Some(変わった様子) = 動画の有無で変わる様子(様子, 新しい動画)
                    {
                        *様子 = 変わった様子;
                    }
                }
                (_, 新しい) => {
                    表.insert(識別子.clone(), 新しい);
                }
            }
        }
        表.retain(|識別子, _| 一覧にある.contains(識別子));
    }
}

/// 動画の有無を読み直したことで変わる様子。動画が見つかったので撮らなかった行はキャッシュを見る前へ戻し、
/// 動画が見つからなくなった撮る順番の行は撮らないにする(ffmpeg に無い動画を渡さないため)。変わらなければ無い。
fn 動画の有無で変わる様子(
    様子: &サムネイルの様子,
    動画: 動画の有無,
) -> Option<サムネイルの様子> {
    match (様子, 動画) {
        (
            サムネイルの様子::撮らない(サムネイルを撮らない理由::動画が見つからない),
            動画の有無::ある,
        ) => Some(サムネイルの様子::キャッシュを見る前),
        (サムネイルの様子::撮る順番を待っている, 動画の有無::見つからない) => {
            Some(サムネイルの様子::撮らない(
                サムネイルを撮らない理由::動画が見つからない,
            ))
        }
        _ => None,
    }
}
