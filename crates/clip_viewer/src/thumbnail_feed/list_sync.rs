//! 一覧を読んだことを当てる。走査した一覧の各行(スタックか重ね合わせ)の撮り方と動画の有無を項目の表へ写し、撮り方が変わらない項目は様子を引き継ぐ。
//! 参照: _doc/設計/ライブラリ.md 判断10(古いサムネイルが出ない理由・撮るとき)・判断11

use std::collections::HashSet;

use clip_domain::{サムネイルの大きさ, サムネイルの撮り方};
use clip_library::動画の有無;

use super::item::サムネイルの項目;
use super::rows::一覧の行の識別子;
use super::shelf::一覧のサムネイル;
use super::status::{サムネイルの様子, サムネイルを撮らない理由};

/// 一覧に出すサムネイルの大きさ。一覧の行の枠(96×54 論理画素)の2倍にし、表示倍率が2倍でも粗く見せない。
pub(crate) const 一覧のサムネイルの大きさ: サムネイルの大きさ =
    match サムネイルの大きさ::作成する(192, 108) {
        Some(大きさ) => 大きさ,
        None => panic!("一覧のサムネイルの大きさは0でない"),
    };

/// 撮る行とは、走査した一覧の読めた行1つの、識別子と、顔の撮り方(撮らないなら無い)と、顔の動画の有無の組のことである。
pub(crate) struct 撮る行<識別子> {
    pub(crate) 識別子: 識別子,
    pub(crate) 撮り方: Option<サムネイルの撮り方>,
    pub(crate) 動画: 動画の有無,
}

impl<識別子: 一覧の行の識別子> 一覧のサムネイル<識別子> {
    /// 一覧を読んだ。撮り方が変わっていない項目は様子を引き継ぎ、変わった項目と新しい項目はキャッシュを見る前からにする。
    /// ここでは撮りも読みもしない(起動しただけでは撮らないため。仕事は一覧を見せている間に `仕事を進める` が頼む)。
    /// 一覧に無くなった行の項目は捨てる(テクスチャも解放される)。
    pub(crate) fn 撮る行の並びを読んだ(
        &mut self,
        並び: impl IntoIterator<Item = 撮る行<識別子>>,
    ) {
        let mut 一覧にある = HashSet::new();
        let 表 = self.表を変える();
        for 行 in 並び {
            let 新しい = サムネイルの項目::撮り方から作る(行.撮り方, 行.動画);
            match (表.get_mut(&行.識別子), 新しい) {
                (
                    Some(サムネイルの項目::撮り方がある {
                        撮り方, 動画, 様子
                    }),
                    サムネイルの項目::撮り方がある {
                        撮り方: 新しい撮り方,
                        動画: 新しい動画,
                        ..
                    },
                ) if *撮り方 == 新しい撮り方 => {
                    *動画 = 新しい動画;
                    if let Some(変わった様子) = 動画の有無で変わる様子(様子, 新しい動画)
                    {
                        *様子 = 変わった様子;
                    }
                }
                (_, 新しい) => {
                    表.insert(行.識別子.clone(), 新しい);
                }
            }
            一覧にある.insert(行.識別子);
        }
        表.retain(|識別子, _| 一覧にある.contains(識別子));
    }
}

/// 動画の有無を読み直したことで変わる様子。動画が見つかったので撮らなかった行はキャッシュを見る前へ戻し、
/// 動画が見つからなくなった撮る順番の行は撮らないにする(ffmpeg に無い動画を渡さないため)。変わらなければ無い。
fn 動画の有無で変わる様子(
    様子: &サムネイルの様子,
    動画: 動画の有無,
) -> Option<サムネイルの様子> {
    match (様子, 動画) {
        (
            サムネイルの様子::撮らない(サムネイルを撮らない理由::動画が見つからない),
            動画の有無::ある,
        ) => Some(サムネイルの様子::キャッシュを見る前),
        (サムネイルの様子::撮る順番を待っている, 動画の有無::見つからない) => {
            Some(サムネイルの様子::撮らない(
                サムネイルを撮らない理由::動画が見つからない,
            ))
        }
        _ => None,
    }
}
