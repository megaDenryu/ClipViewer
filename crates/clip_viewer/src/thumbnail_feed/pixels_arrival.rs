//! 画素へ戻した結果をテクスチャにする。戻せた画素は egui へ登録して見えている行のテクスチャにする。
//! キャッシュから読んで画素へ戻せなかった(壊れた)画像は撮り直し(読む処理がファイルを消している)、撮った画像が戻せなければ
//! 出せないとする(撮り直しを繰り返さないため)。参照: _doc/設計/ライブラリ.md 判断10(壊れたキャッシュ)

use std::rc::Rc;

use clip_domain::サムネイルの撮り方;

use super::pixels::{戻した画素, 画素へ戻せない理由};
use super::rows::一覧の行の識別子;
use super::shelf::一覧のサムネイル;
use super::status::{
    サムネイルの様子, サムネイルを出せない理由, 画像の出どころ
};

impl<識別子: 一覧の行の識別子> 一覧のサムネイル<識別子> {
    pub(super) fn 画素へ戻した結果を当てる(
        &mut self,
        識別子: &識別子,
        撮り方: &サムネイルの撮り方,
        画素: Result<戻した画素, 画素へ戻せない理由>,
    ) {
        // 注意: 撮り方が変わった後に届いた古い結果を egui へ登録しないため、今の撮り方で JPEG を持っている行かを先に確かめる。
        let 今の結果か = self
            .表を読む()
            .get(識別子)
            .is_some_and(|項目| 項目.同じ撮り方で画像を持っているか(撮り方));
        if !今の結果か {
            return;
        }
        let 載せた = 画素.map(|戻した| self.テクスチャに載せる(識別子, &戻した));
        let Some((様子, 動画)) = self.今の撮り方の様子(識別子, 撮り方) else {
            return;
        };
        let サムネイルの様子::持っている {
            出どころ, 表示,
        ..
        } = 様子
        else {
            return;
        };
        let 出どころ = *出どころ;
        match 載せた {
            Ok(Ok(載せた表示)) => *表示 = 載せた表示,
            Ok(Err(不正)) => {
                *様子 = サムネイルの様子::出せない(
                    サムネイルを出せない理由::テクスチャにできない(不正),
                )
            }
            Err(_) if 出どころ == 画像の出どころ::キャッシュ => {
                *様子 = サムネイルの様子::キャッシュに無いとき(動画)
            }
            Err(理由) => {
                *様子 = サムネイルの様子::出せない(
                    サムネイルを出せない理由::画素へ戻せない(Rc::new(理由)),
                )
            }
        }
    }
}
