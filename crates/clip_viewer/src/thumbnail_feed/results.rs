//! 一覧のサムネイルへ届いた結果を当てる。キャッシュにあれば持ち、無ければ撮る順番へ回し、撮れたら持つ(画素へ戻した結果は pixels_arrival.rs)。
//! 結果は撮り方を持ち、今の撮り方と同じ行にだけ当てる(一覧を読み直して撮り方が変わった後に届いた古い結果を捨てるため)。

use std::rc::Rc;

use clip_domain::{サムネイルの撮り方, サムネイルの画像};
use clip_library::動画の有無;
use video_source::サムネイルの撮影の失敗;

use super::reader::読んだ結果;
use super::rows::一覧の行の識別子;
use super::shelf::一覧のサムネイル;
use super::shooter::撮った結果;
use super::status::{
    サムネイルの様子, サムネイルを出せない理由, 画像の出どころ
};

impl<識別子: 一覧の行の識別子> 一覧のサムネイル<識別子> {
    /// 毎フレーム呼ぶ。届いた結果をすべて当てる。ライブラリの構えを開いていない間も、頼んだ仕事の結果は受け取る。
    pub(crate) fn 結果を受け取る(&mut self) {
        for 読んだ in self.読む裏のスレッド.届いた結果を受け取る() {
            match 読んだ {
                読んだ結果::キャッシュを見た {
                    識別子,
                    撮り方,
                    画像,
                } => self.キャッシュを見た結果を当てる(&識別子, &撮り方, 画像),
                読んだ結果::画素へ戻した {
                    識別子,
                    撮り方,
                    画素,
                } => self.画素へ戻した結果を当てる(&識別子, &撮り方, 画素),
            }
        }
        for 撮った結果 {
            識別子,
            撮り方,
            画像,
        } in self.撮る裏のスレッド.届いた結果を受け取る()
        {
            self.撮った結果を当てる(&識別子, &撮り方, 画像);
        }
    }

    fn キャッシュを見た結果を当てる(
        &mut self,
        識別子: &識別子,
        撮り方: &サムネイルの撮り方,
        画像: Option<サムネイルの画像>,
    ) {
        let Some((様子, 動画)) = self.今の撮り方の様子(識別子, 撮り方) else {
            return;
        };
        *様子 = match 画像 {
            Some(画像) => {
                サムネイルの様子::画像を持った(画像, 画像の出どころ::キャッシュ)
            }
            None => サムネイルの様子::キャッシュに無いとき(動画),
        };
    }

    fn 撮った結果を当てる(
        &mut self,
        識別子: &識別子,
        撮り方: &サムネイルの撮り方,
        画像: Result<サムネイルの画像, サムネイルの撮影の失敗>,
    ) {
        let Some((様子, _)) = self.今の撮り方の様子(識別子, 撮り方) else {
            return;
        };
        *様子 = match 画像 {
            Ok(画像) => {
                サムネイルの様子::画像を持った(画像, 画像の出どころ::撮った)
            }
            Err(失敗) => サムネイルの様子::出せない(
                サムネイルを出せない理由::撮れない(Rc::new(失敗)),
            ),
        };
    }

    /// 識別子の行が同じ撮り方なら、その様子と動画の有無を借りる。
    pub(super) fn 今の撮り方の様子(
        &mut self,
        識別子: &識別子,
        撮り方: &サムネイルの撮り方,
    ) -> Option<(&mut サムネイルの様子, 動画の有無)> {
        self.表を変える().get_mut(識別子)?.同じ撮り方の様子(撮り方)
    }
}
