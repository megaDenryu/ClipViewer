//! 一覧の種類ごとの撮る行の並び。スタックの一覧はスタックの顔とその動画の有無を、重ね合わせの一覧は重ね合わせの顔とその顔の動画の有無を、
//! 撮る行にして一覧のサムネイルへ渡す。参照: _doc/設計/ライブラリ.md 判断10・判断11

use clip_domain::{スタックの識別子, 重ね合わせの識別子};
use clip_library::{
    ライブラリの一覧, 一覧の項目, 動画の有無, 読めた重ね合わせ, 重ね合わせの一覧,
    重ね合わせの一覧の項目,
};

use super::list_sync::{一覧のサムネイルの大きさ, 撮る行};
use super::shelf::一覧のサムネイル;

impl 一覧のサムネイル<スタックの識別子> {
    /// スタックの一覧を読んだ。各スタックの顔の撮り方と動画の有無を撮る行にする。
    pub(crate) fn 一覧から撮る行を当てる(&mut self, 一覧: &ライブラリの一覧) {
        self.撮る行の並びを当てる(一覧.項目.iter().filter_map(|項目| match 項目 {
            一覧の項目::読めた(読めた) => Some(撮る行 {
                識別子: 読めた.スタック.識別子().clone(),
                撮り方: 読めた.スタック.サムネイルの撮り方(一覧のサムネイルの大きさ),
                動画: 読めた.動画,
            }),
            一覧の項目::読めない(_) => None,
        }));
    }
}

impl 一覧のサムネイル<重ね合わせの識別子> {
    /// 重ね合わせの一覧から撮る行を当てる。各重ね合わせの顔の撮り方と、顔の置いたクリップの動画の有無を撮る行にする。
    pub(crate) fn 重ね合わせの一覧から撮る行を当てる(
        &mut self,
        一覧: &重ね合わせの一覧,
    ) {
        self.撮る行の並びを当てる(一覧.項目.iter().filter_map(|項目| {
            match 項目 {
                重ね合わせの一覧の項目::読めた(読めた) => Some(撮る行 {
                    識別子: 読めた.重ね合わせ.識別子().clone(),
                    撮り方: 読めた
                        .重ね合わせ
                        .サムネイルの撮り方(一覧のサムネイルの大きさ),
                    動画: 顔の動画の有無(読めた),
                }),
                重ね合わせの一覧の項目::読めない(_) => None,
            }
        }));
    }
}

/// 顔の置いたクリップの動画の有無。顔が無ければ撮らないため、有無はどちらでもよく、あるとする。
fn 顔の動画の有無(読めた: &読めた重ね合わせ) -> 動画の有無 {
    読めた
        .重ね合わせ
        .重ね合わせ()
        .顔の置いたクリップ()
        .and_then(|顔| 読めた.動画の有無の並び.get(顔.動画の番号().番号()))
        .copied()
        .unwrap_or(動画の有無::ある)
}
