//! サムネイルを撮ってキャッシュへ置く処理。撮り方のコマを FFmpeg で JPEG にして、キャッシュへ置いてから返す。
//! 1枚は、動画の情報を調べる ffprobe と撮る ffmpeg の2回の起動でできる(動画の情報は動画ごとに覚えて使い回す)。
//! 固まった ffprobe は30秒、ffmpeg は10秒の期限で止まる(video_source)。閉じるときは取り消しの合図で子プロセスを止める。

use std::marker::PhantomData;

use clip_domain::{サムネイルの撮り方, サムネイルの画像};
use thumbnail_cache::サムネイルのキャッシュ;
use video_source::{
    サムネイルの撮影の失敗, 動画の読み手, 取り消しの合図, 撮影に使う動画の情報の覚え,
};

use super::rows::一覧の行の識別子;
use super::worker::裏のスレッドで仕事を行う処理;

/// 撮る仕事とは、識別子の行の顔を、撮り方に従って動画の読み手で撮ることの頼みのことである。
/// 動画の読み手は FFmpeg の場所を変えると変わるため、処理に持たせず仕事ごとに渡す。
pub(super) struct 撮る仕事<識別子> {
    pub(super) 識別子: 識別子,
    pub(super) 撮り方: サムネイルの撮り方,
    pub(super) 読み手: 動画の読み手,
}

/// 撮った結果とは、撮る仕事の識別子と撮り方と、撮れた画像か撮れなかった理由の組のことである。
pub(super) struct 撮った結果<識別子> {
    pub(super) 識別子: 識別子,
    pub(super) 撮り方: サムネイルの撮り方,
    pub(super) 画像: Result<サムネイルの画像, サムネイルの撮影の失敗>,
}

/// サムネイルを撮ってキャッシュへ置く処理とは、撮った画像を置くキャッシュと、撮影を取り消す合図と、撮影に使う動画の情報の覚えを
/// 保持して、撮る仕事を行うもののことである。仕事と結果が持つ識別子の型を引数に取る。
pub(super) struct サムネイルを撮ってキャッシュへ置く処理<識別子> {
    キャッシュ: サムネイルのキャッシュ,
    合図: 取り消しの合図,
    動画の情報の覚え: 撮影に使う動画の情報の覚え,
    識別子の型: PhantomData<fn() -> 識別子>,
}

impl<識別子> サムネイルを撮ってキャッシュへ置く処理<識別子> {
    /// 置くキャッシュと取り消しの合図から作る。動画の情報の覚えは空で始める。
    pub(super) fn 作成する(
        キャッシュ: サムネイルのキャッシュ, 合図: 取り消しの合図
    ) -> Self {
        Self {
            キャッシュ,
            合図,
            動画の情報の覚え: 撮影に使う動画の情報の覚え::default(),
            識別子の型: PhantomData,
        }
    }
}

impl<識別子: 一覧の行の識別子> 裏のスレッドで仕事を行う処理
    for サムネイルを撮ってキャッシュへ置く処理<識別子>
{
    type 仕事 = 撮る仕事<識別子>;
    type 結果 = 撮った結果<識別子>;

    /// 撮ってキャッシュへ置く。キャッシュへ置けなくても撮った画像は返して見せる(キャッシュは捨ててよいデータであり、
    /// 置けないことで見せる結果は変わらないため、画面に出さない。参照: _doc/設計/ライブラリ.md 判断10)。
    fn 行う(&mut self, 仕事: 撮る仕事<識別子>) -> 撮った結果<識別子> {
        let 画像 =
            self.動画の情報の覚え
                .サムネイルを作る(&仕事.読み手, &仕事.撮り方, &self.合図);
        if let Ok(撮れた) = &画像 {
            let _ = self.キャッシュ.置く(&仕事.撮り方, 撮れた);
        }
        撮った結果 {
            識別子: 仕事.識別子,
            撮り方: 仕事.撮り方,
            画像,
        }
    }
}
