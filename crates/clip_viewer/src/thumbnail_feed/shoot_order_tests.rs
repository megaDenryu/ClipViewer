//! 次に撮る行の選び方の試験。見えている行から先に選び、見えている行に撮る順番の行が無ければ見せる順の最初の行を選ぶ。
#![allow(clippy::expect_used)]

use std::collections::HashMap;

use clip_domain::{
    クリップ, クリップスタック, クリップ名, クリップ識別子, サムネイルの撮り方, スタックの名前,
    スタックの識別子, ライブラリのスタック, ライブラリの日時, 入力された動画パス,
};
use clip_library::動画の有無;

use super::item::サムネイルの項目;
use super::list_sync::一覧のサムネイルの大きさ;
use super::rows::行の並び;
use super::shoot_order::次に撮る行;
use super::status::サムネイルの様子;

fn 識別子(番号: u32) -> スタックの識別子 {
    スタックの識別子::文字列から作成する(format!("stack-{番号}-0")).expect("識別子")
}

fn 撮り方() -> サムネイルの撮り方 {
    let 識別子 = クリップ識別子::文字列から作成する("a".into()).expect("識別子");
    let クリップ =
        クリップ::既定値で作成する(識別子, クリップ名::作成する("一".into()));
    ライブラリのスタック::新しく作る(
        スタックの識別子::文字列から作成する("stack-1-1".into()).expect("識別子"),
        スタックの名前::作成する("甲".into()).expect("名前"),
        入力された動画パス::作成する(r"D:\a.mp4".into()).正規化する(),
        クリップスタック::一覧から作成する(vec![クリップ]).expect("並び"),
        ライブラリの日時::紀元,
    )
    .サムネイルの撮り方(一覧のサムネイルの大きさ)
    .expect("撮り方")
}

fn 項目(様子: サムネイルの様子) -> サムネイルの項目 {
    サムネイルの項目::撮り方がある {
        撮り方: 撮り方(),
        動画: 動画の有無::ある,
        様子,
    }
}

#[test]
fn 見えている行の撮る順番の行を先に選び_無ければ見せる順の最初を選ぶ() {
    let 全部: Vec<スタックの識別子> = (0..5).map(識別子).collect();
    let mut 表 = HashMap::new();
    for 一つ in &全部 {
        表.insert(一つ.clone(), 項目(サムネイルの様子::撮る順番を待っている));
    }
    表.insert(全部[3].clone(), 項目(サムネイルの様子::撮っている));
    let 見せる順: Vec<&スタックの識別子> = 全部.iter().collect();
    let 見えている行が後ろ = 行の並び {
        見えている: vec![&全部[3], &全部[4]],
        見せる順: 見せる順.clone(),
    };
    assert_eq!(
        次に撮る行(&表, &見えている行が後ろ),
        Some(&全部[4]),
        "見せる順で前にある行より、見えている行を先に撮る"
    );
    表.insert(全部[4].clone(), 項目(サムネイルの様子::撮っている));
    assert_eq!(
        次に撮る行(&表, &見えている行が後ろ),
        Some(&全部[0]),
        "見えている行に撮る順番の行が無ければ、見せる順の最初を撮る"
    );
    for 一つ in &全部 {
        表.insert(一つ.clone(), 項目(サムネイルの様子::撮っている));
    }
    assert_eq!(次に撮る行(&表, &見えている行が後ろ), None);
}
