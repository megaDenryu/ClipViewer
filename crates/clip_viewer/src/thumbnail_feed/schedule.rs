//! 一覧のサムネイルの仕事を進める。ライブラリの構えを開いている間だけ毎フレーム呼ばれ、見えている行から先に、
//! キャッシュを見る・画素へ戻す仕事を読む裏のスレッドへ、撮る仕事を撮る裏のスレッドへ頼む。
//! 撮る仕事は1件ずつ頼み、次に撮るものはそのたびに選び直すため、スクロールした先の行が待ち行列の後ろで待たない。
//! 参照: _doc/設計/ライブラリ.md 判断10(撮るとき・読むとき)

use super::item::サムネイルの項目;
use super::means::撮る手立て;
use super::reader::読む仕事;
use super::rows::{一覧の行の識別子, 行の並び};
use super::shelf::一覧のサムネイル;
use super::status::{サムネイルの様子, 表示の段階};

/// 読む裏のスレッドへ同時に頼む仕事の数。キャッシュを見る仕事は1件1ミリ秒ほどなので、フレームごとに8件ずつ進めれば足りる
/// (キャッシュを見る前の行が残っている間は、画面が約60回/秒で描き直す。view/invisible.rs)。
/// 数を絞るのは、見えている行がスクロールで変わったときに、先に頼んだ見えていない行の仕事の後ろで待たないためである。
const 同時に頼む読む仕事の数: usize = 8;

impl<識別子: 一覧の行の識別子> 一覧のサムネイル<識別子> {
    /// 回を進め、見えている行のテクスチャに印を付け、仕事を頼み、見えていないテクスチャを上限まで捨てる。
    pub(crate) fn 仕事を進める(
        &mut self, 並び: &行の並び<'_, 識別子>, 手立て: &撮る手立て
    ) {
        self.回を進めて見えている行に印を付ける(並び);
        self.止まった裏のスレッドの仕事を諦める();
        self.画素へ戻す仕事を頼む(並び);
        self.キャッシュを見る仕事を頼む(並び);
        self.撮る仕事を頼む(並び, 手立て);
        self.見えていないテクスチャを捨てる();
    }

    /// 見えている行で、JPEG を持っているのにテクスチャにしていないものを、画素へ戻す仕事にする。
    fn 画素へ戻す仕事を頼む(&mut self, 並び: &行の並び<'_, 識別子>) {
        for 識別子 in &並び.見えている {
            if self.読む空きが無いか() {
                return;
            }
            let Some(サムネイルの項目::撮り方がある {
                撮り方, 様子, ..
            }) = self.表を変える().get_mut(*識別子)
            else {
                continue;
            };
            let サムネイルの様子::持っている {
                画像,
                出どころ,
                表示: 表示 @ 表示の段階::載せていない,
            } = 様子
            else {
                continue;
            };
            let 仕事 = 読む仕事::画素へ戻す {
                識別子: (*識別子).clone(),
                撮り方: 撮り方.clone(),
                画像: 画像.clone(),
                出どころ: *出どころ,
            };
            *表示 = 表示の段階::画素へ戻している;
            self.読む仕事を送る(識別子, 仕事);
        }
    }

    /// キャッシュを見る前の行を、見えている行を先にした全部の行、キャッシュを見る仕事にする。
    fn キャッシュを見る仕事を頼む(&mut self, 並び: &行の並び<'_, 識別子>) {
        for 識別子 in 並び.見えている行を先にした全部の行() {
            if self.読む空きが無いか() {
                return;
            }
            let Some(サムネイルの項目::撮り方がある {
                撮り方, 様子, ..
            }) = self.表を変える().get_mut(識別子)
            else {
                continue;
            };
            if !matches!(様子, サムネイルの様子::キャッシュを見る前) {
                continue;
            }
            let 仕事 = 読む仕事::キャッシュを見る {
                識別子: 識別子.clone(),
                撮り方: 撮り方.clone(),
            };
            *様子 = サムネイルの様子::キャッシュを見ている;
            self.読む仕事を送る(識別子, 仕事);
        }
    }

    fn 読む空きが無いか(&self) -> bool {
        self.読む裏のスレッド.返事を待っている数() >= 同時に頼む読む仕事の数
    }

    /// 読む仕事を送る。送れなければ(裏のスレッドが止まっていれば)、その行を出せないにする。
    fn 読む仕事を送る(&mut self, 識別子: &識別子, 仕事: 読む仕事<識別子>) {
        if let Err(止まっている) = self.読む裏のスレッド.頼む(仕事) {
            self.出せないにする(識別子, 止まっている.into());
        }
    }
}
