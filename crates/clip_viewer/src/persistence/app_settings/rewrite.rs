//! settings.json の書き直し。保存の前に今のファイルを読み直した結果と、保存したことを利用者へどう知らせるかの区別を持つ。

use std::fmt;
use std::path::PathBuf;

use super::error::アプリの設定のエラー;
use super::settings::アプリの設定;

/// 壊れた設定の移し先とは、壊れていて読めなかった settings.json を、書き直す前に移したファイルのパスのことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct 壊れた設定の移し先(PathBuf);

impl 壊れた設定の移し先 {
    pub(super) fn 作成する(パス: PathBuf) -> Self {
        Self(パス)
    }
}

impl fmt::Display for 壊れた設定の移し先 {
    fn fmt(&self, 書き手: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(書き手, "{}", self.0.display())
    }
}

/// 読み直した設定とは、保存の前に settings.json を読み直した結果の区別のことである。
/// 読めたアプリの設定は見る側の設定(キーの割り当てを含めて約270バイト)を持ち、壊れたときの移し先(パス1つ)より大きいため箱に入れる。
/// 箱を作るのは保存のたびに1回だけである(保存は値が1秒落ち着いたときと閉じるときだけ起きる)。
pub(super) enum 読み直した設定 {
    読めた(Box<アプリの設定>),
    壊れていたので移した(壊れた設定の移し先),
}

/// アプリの設定の保存の結果とは、settings.json を書き直せたときに、何をしたかを利用者へ知らせるための区別のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum アプリの設定の保存の結果 {
    書き直した,
    壊れたファイルを移して書いた(壊れた設定の移し先),
}

impl 読み直した設定 {
    /// 変える前の設定と、書けたときの保存の結果に分ける。壊れていたときは、何も設定していない設定から書き直す。
    pub(super) fn 変える前の設定と保存の結果に分ける(
        self,
    ) -> (アプリの設定, アプリの設定の保存の結果) {
        match self {
            Self::読めた(設定) => (*設定, アプリの設定の保存の結果::書き直した),
            Self::壊れていたので移した(移し先) => (
                アプリの設定::何も無い(),
                アプリの設定の保存の結果::壊れたファイルを移して書いた(
                    移し先,
                ),
            ),
        }
    }
}

impl アプリの設定の保存の結果 {
    /// 書けなかったときのエラーにする。壊れたファイルを移した後なら、移し先のパスを理由の文に入れる(利用者が写しを探せるように)。
    /// 移したファイルが残る場所を失敗の文から消さないため、元のエラーは箱に入れて保つ(エラーの型が自分を含むため箱が要る)。
    pub(super) fn 書けなかったときのエラーにする(
        &self,
        エラー: アプリの設定のエラー,
    ) -> アプリの設定のエラー {
        match self {
            Self::書き直した => エラー,
            Self::壊れたファイルを移して書いた(移し先) => {
                アプリの設定のエラー::移した後で書けない {
                    移し先: 移し先.to_string(),
                    理由: Box::new(エラー),
                }
            }
        }
    }
}
