//! settings.json のキーの割り当て(keyBindings)の試験。保存して読み戻すと同じ割り当てになること、キーの割り当ての無い古いファイルを既定で読むこと、
//! 既定のままなら項目を書かないこと、知らない操作の名前・読めない表記の行だけを既定にし、重なる行があれば全体を既定にすること、
//! 項目の形が違うファイルは壊れているとみなすこと、操作の名前が重ならないことを確かめる。
#![allow(clippy::expect_used)]

use std::collections::HashSet;

use sengen_egui::{キー, キーの組};

use super::format::設定のファイルの本文;
use super::test_support::{
    ファイルを置く, 一時の保管場所, 後片付け, 読み直す
};
use super::text_tests::第1版の見本;
use super::v1_keys::名前にする;
use crate::viewer_settings::{
    キーで行う操作, キーの割り当て, 操作のキー, 見る側の設定
};

fn 本文から読んだ割り当て(本文: &str) -> キーの割り当て {
    設定のファイルの本文::作成する(本文.to_string())
        .最新の設定として読む()
        .expect("壊れたとみなさない")
        .見る側の設定()
        .キー
}

fn キーの割り当ての本文(項目: &str) -> String {
    format!(r#"{{"format":"ClipViewer.settings","version":1,"keyBindings":{項目}}}"#)
}

#[test]
fn 変えたキーの割り当てを保存して読み戻すと同じ割り当てになる() {
    let (保管場所, パス) = 一時の保管場所("キーの往復");
    let 割り当て = キーの割り当て::既定()
        .キーを変えた(キーで行う操作::消音を切り替える, キーの組::単独(キー::Q))
        .expect("空いたキーへは変えられる");
    let 設定 = 見る側の設定 {
        キー: 割り当て,
        ..見る側の設定::既定
    };
    保管場所.見る側の設定を保存する(設定).expect("書ける");
    assert_eq!(
        読み直す(&パス)["keyBindings"],
        serde_json::json!({"toggleMute": ["Q"]})
    );
    assert_eq!(保管場所.見る側の設定を読む().expect("読める"), 設定);
    後片付け(&パス);
}

#[test]
fn キーの割り当ての無い古いファイルは既定のキーで読み_既定のままなら項目を書かない() {
    assert_eq!(本文から読んだ割り当て(第1版の見本), キーの割り当て::既定());
    let (保管場所, パス) = 一時の保管場所("キーの既定");
    ファイルを置く(&パス, r#"{"ffmpegFolder":"D:/ff"}"#);
    保管場所
        .見る側の設定を保存する(見る側の設定::既定)
        .expect("書ける");
    assert!(読み直す(&パス).get("keyBindings").is_none());
    後片付け(&パス);
}

#[test]
fn 知らない操作の名前と読めない表記の行はその行だけ既定にする() {
    let 本文 = キーの割り当ての本文(
        r#"{"futureOperation":["F2"],"toggleMute":["無いキー"],"undo":["F3","F4","F5"],"toggleTheater":["Shift+Y"]}"#,
    );
    let 期待 = キーの割り当て::既定()
        .キーを変えた(
            キーで行う操作::シアターと編集を切り替える,
            キーの組::表記から読む("Shift+Y").expect("表記"),
        )
        .expect("空いたキーへは変えられる");
    assert_eq!(本文から読んだ割り当て(&本文), 期待);
}

#[test]
fn 読んだ行どうしでキーが重なれば全体を既定にする() {
    let 本文 = キーの割り当ての本文(r#"{"toggleMute":["Space"],"toggleTheater":["Y"]}"#);
    assert_eq!(本文から読んだ割り当て(&本文), キーの割り当て::既定());
}

#[test]
fn 項目の形が違うファイルは壊れているとみなす() {
    for 項目 in [r#""T""#, r#"{"toggleMute":"Q"}"#] {
        let 結果 =
            設定のファイルの本文::作成する(キーの割り当ての本文(項目)).最新の設定として読む();
        assert!(結果.is_err(), "{項目}");
    }
}

#[test]
fn 操作の名前は重ならず_既定のキーの表記は読み戻せる() {
    let 名前: HashSet<&str> = キーで行う操作::すべて.into_iter().map(名前にする).collect();
    assert_eq!(名前.len(), キーで行う操作::すべて.len());
    for 操作 in キーで行う操作::すべて {
        let 並び: Vec<キーの組> = 操作
            .既定のキー()
            .組の並び()
            .into_iter()
            .map(|組| キーの組::表記から読む(&組.表記()).expect("読み戻せる"))
            .collect();
        assert_eq!(操作のキー::組の並びから作る(&並び), Some(操作.既定のキー()));
    }
}
