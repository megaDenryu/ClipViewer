//! 見る側の設定の読み書き。settings.json の見る側の項目だけを読み、変えて書く。書くときは今のファイルを読み直してほかの項目を消さない。
//! 壊れたファイルと、このアプリが書き換えてはならないファイルには書かない(壊れたファイルを移すのは、利用者が FFmpeg の置き場所を保存したときだけである)。
//! 参照: _doc/設計/ライブラリ.md「settings.json の形式」、_doc/設計/画面.md 判断17

use super::{アプリの設定のエラー, アプリの設定の保管場所};
use crate::viewer_settings::見る側の設定;

impl アプリの設定の保管場所 {
    /// 覚えている見る側の設定を読む。保管場所かファイルが無いか、見る側の項目が1つも無ければ既定の設定である。
    pub(crate) fn 見る側の設定を読む(
        &self,
    ) -> Result<見る側の設定, アプリの設定のエラー> {
        match self.設定のファイル() {
            Some(ファイル) => Ok(ファイル.読む()?.見る側の設定()),
            None => Ok(見る側の設定::既定),
        }
    }

    /// 見る側の設定を保存する。今のファイルを読み直して見る側の項目だけを変え、一時ファイルへ書き切ってから置き換える。
    /// 今のファイルが壊れているか、新しすぎる版・別の形式なら書かずに理由を返す。
    pub(crate) fn 見る側の設定を保存する(
        &self,
        設定: 見る側の設定,
    ) -> Result<(), アプリの設定のエラー> {
        let ファイル = self
            .設定のファイル()
            .ok_or(アプリの設定のエラー::保管場所が無い)?;
        let 今の設定 = ファイル.読む()?;
        ファイル.書き切って置き換える(今の設定.見る側の設定を変えた(設定))
    }
}
