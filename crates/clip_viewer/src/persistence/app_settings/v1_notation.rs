//! settings.json 第1版の文字列の項目の表記。アスペクト比と表示サイズを、ファイルに書く英数字の表記と相互に変換する。
//! 表記はファイル形式が決めており、名前を変えない(変えると古いアプリが読めない値になる)。

use clip_domain::アスペクト比設定;

use crate::viewer_settings::表示サイズ;

/// アスペクト比の表記。移植元の選択肢の文字と同じにする。
pub(super) const アスペクト比の表記: [(アスペクト比設定, &str); 5] = [
    (アスペクト比設定::クロップ連動, "crop"),
    (アスペクト比設定::ワイド16対9, "16:9"),
    (アスペクト比設定::スタンダード4対3, "4:3"),
    (アスペクト比設定::正方形, "1:1"),
    (アスペクト比設定::縦型9対16, "9:16"),
];

/// 表示サイズの表記。
pub(super) const 表示サイズの表記: [(表示サイズ, &str); 4] = [
    (表示サイズ::標準, "standard"),
    (表示サイズ::大きめ, "large"),
    (表示サイズ::横幅優先, "widthFirst"),
    (表示サイズ::余白なし, "noMargin"),
];

/// 表記の表から、値に当たる表記を探す。
pub(super) fn 表記にする<値: PartialEq + Copy>(
    表: &[(値, &'static str)], 値: 値
) -> String {
    表.iter()
        .find(|(候補, _)| *候補 == 値)
        .map_or_else(String::new, |(_, 表記)| (*表記).to_string())
}

/// 表記の表から、表記に当たる値を探す。知らない表記なら無い。
pub(super) fn 表記から読む<値: Copy>(
    表: &[(値, &'static str)], 表記: &str
) -> Option<値> {
    表.iter().find(|(_, 候補)| *候補 == 表記).map(|(値, _)| *値)
}
