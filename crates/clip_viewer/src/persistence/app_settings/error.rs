//! アプリの設定を読めない・保存できない理由。本文の中身の理由と、ファイルの読み書きの理由を分けて持つ。
//! 本文の中身の理由は、壊れている(次の保存で別の名前へ移して書き直す)か、書き換えてはならない(新しい版・別の形式)かに分かれる。

use std::io;

/// 書き換えない理由とは、settings.json を読めず、しかもこのアプリが書き換えてはならない理由のことである。
/// どれも、このアプリの知らない書き手が書いたファイルであり、書き換えるとその書き手の設定を消すためである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 書き換えない理由 {
    #[error("ClipViewer の設定のファイルでない(format が {0:?})")]
    形式の名前が違う(Option<String>),
    #[error(
        "このアプリより新しい ClipViewer で保存された(version が {0})。ClipViewer を更新すれば読める"
    )]
    版が新しすぎる(u64),
    #[error("このアプリが読めない版である(version が {0:?})")]
    対応していない版(Option<u64>),
}

/// 設定の本文のエラーとは、settings.json の本文を最新のアプリの設定にできない理由のことである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 設定の本文のエラー {
    #[error("JSON として読めないか、形が不正: {0}")]
    壊れている(#[from] serde_json::Error),
    #[error("{0}")]
    書き換えない(#[from] 書き換えない理由),
}

/// アプリの設定のエラーとは、アプリの設定を読めなかった、または保存できなかった理由のことである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum アプリの設定のエラー {
    #[error("アプリの設定の保管場所が無い(環境変数 APPDATA が無い)")]
    保管場所が無い,
    #[error("アプリの設定 {パス} を読み書きできない: {原因}")]
    読み書きできない { パス: String, 原因: io::Error },
    #[error(
        "アプリの設定 {パス} が壊れていて読めない。このファイルを消すか直せば、次の起動から読める。FFmpeg の置き場所を保存するときには、このファイルを別の名前へ移して書き直す: {原因}"
    )]
    壊れている {
        パス: String,
        原因: serde_json::Error,
    },
    #[error("アプリの設定 {パス} を読めないため、このファイルを書き換えない: {理由}")]
    書き換えない {
        パス: String,
        理由: 書き換えない理由,
    },
    #[error("壊れていたアプリの設定を {移し先} へ移したが、新しい設定を書けない: {理由}")]
    移した後で書けない {
        移し先: String,
        理由: Box<アプリの設定のエラー>,
    },
    #[error("アプリの設定 {パス} へ書き出せない: {原因}")]
    書き出せない {
        パス: String,
        原因: serde_json::Error,
    },
}

impl アプリの設定のエラー {
    /// io のエラーを、どのパスで起きたかと組にする。
    pub(super) fn 読み書きできないときのエラーを作る(
        パス: &std::path::Path,
        原因: io::Error,
    ) -> Self {
        Self::読み書きできない {
            パス: パス.display().to_string(),
            原因,
        }
    }
}
