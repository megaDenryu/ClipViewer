//! サムネイルのキャッシュの置き場所の決め方。ローカルのアプリのデータのフォルダ(Windows の %LOCALAPPDATA%)の下の
//! `ClipViewer\thumbnails` にする。ライブラリ(%APPDATA%)と分けるのは、キャッシュが消えても撮り直せる、この計算機だけのデータだからである。
//! 参照: _doc/設計/ライブラリ.md 判断10

use std::path::PathBuf;

use thumbnail_cache::{
    キャッシュのフォルダ, キャッシュの容量, キャッシュの時計, キャッシュの置き場所,
    サムネイルのキャッシュ,
};

/// サムネイルのキャッシュのフォルダ名。ライブラリのフォルダ名(library)と揃えて ASCII にする。
const キャッシュのフォルダ名: &str = "thumbnails";

/// ローカルのアプリのデータのフォルダ(無ければ無い)から、実時間の時計と既定の容量の上限を持つサムネイルのキャッシュを作る。
/// フォルダが無ければキャッシュを使わない(撮った画像を RAM に持って見せる)。
pub(crate) fn サムネイルのキャッシュを決める(
    ローカルのアプリのデータのフォルダ: Option<PathBuf>,
) -> サムネイルのキャッシュ {
    let 置き場所 = ローカルのアプリのデータのフォルダ.map_or(
        キャッシュの置き場所::使わない,
        |フォルダ| {
            キャッシュの置き場所::フォルダ(キャッシュのフォルダ::作成する(
                フォルダ.join("ClipViewer").join(キャッシュのフォルダ名),
            ))
        },
    );
    サムネイルのキャッシュ::作成する(
        置き場所,
        キャッシュの容量::既定,
        キャッシュの時計::実時間(),
    )
}
