//! 見る側の設定の変化の見張り。毎フレーム今の設定を受け取り、最後に書いた設定から変わって少し落ち着いたら、保存すると答える。
//! 純粋な判断であり、ファイルに触らない(書くのは `viewer_settings_save.rs` の保存係)。参照: _doc/設計/画面.md 判断17

use std::time::{Duration, Instant};

use crate::viewer_settings::見る側の設定;

/// 設定が変わってから保存するまで待つ時間。つまみやウインドウの縁をドラッグしている間に、フレームごとに書かないためである。
pub(super) const 落ち着くまでの時間: Duration = Duration::from_secs(1);

/// 見た結果とは、今の設定を見て、保存するか、まだしないかの区別のことである。
#[expect(
    clippy::large_enum_variant,
    reason = "見る側の設定はキーの割り当てを含めて約270バイトの値であり、保存の見張りと読み書きで1フレームに数回写すだけである。箱に入れると毎フレームの比較のたびに確保が起きる"
)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub(super) enum 見た結果 {
    まだ保存しない,
    保存する(見る側の設定),
}

/// 変わりかけの設定とは、最後に書いた設定と違う今の設定と、その値になった時刻の組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
struct 変わりかけの設定 {
    設定: 見る側の設定,
    変わった時刻: Instant,
}

/// 設定の変化の見張りとは、最後に書いた(または読んだ)設定と、それと違う変わりかけの設定の組のことである。
#[derive(Debug, Clone)]
pub(super) struct 設定の変化の見張り {
    書いた設定: 見る側の設定,
    変わりかけ: Option<変わりかけの設定>,
}

impl 設定の変化の見張り {
    /// 起動したときに読んだ設定を、最後に書いた設定として見張り始める。
    pub(super) fn 読んだ設定から始める(読んだ設定: 見る側の設定) -> Self {
        Self {
            書いた設定: 読んだ設定,
            変わりかけ: None,
        }
    }

    /// 今の設定を見る。書いた設定と同じなら何もしない。違う値になった時刻から落ち着くまでの時間が過ぎたら、保存すると答える。
    /// 保存すると答えた設定は、書けたかに関わらず書いた設定として覚える(書けなかったときに毎フレーム書き直さないため)。
    pub(super) fn 見る(
        &mut self, 今の設定: 見る側の設定, 今: Instant
    ) -> 見た結果 {
        if 今の設定 == self.書いた設定 {
            self.変わりかけ = None;
            return 見た結果::まだ保存しない;
        }
        let 変わりかけ = match self.変わりかけ {
            Some(変わりかけ) if 変わりかけ.設定 == 今の設定 => 変わりかけ,
            _ => 変わりかけの設定 {
                設定: 今の設定,
                変わった時刻: 今,
            },
        };
        if 今.saturating_duration_since(変わりかけ.変わった時刻) < 落ち着くまでの時間
        {
            self.変わりかけ = Some(変わりかけ);
            return 見た結果::まだ保存しない;
        }
        self.書いたことにする(今の設定);
        見た結果::保存する(今の設定)
    }

    /// 変わりかけの設定を保存するまでの残り時間。変わりかけが無ければ無い。入力が無くてもその時刻に画面を進めて保存させるため、画面が描き直しの予約に使う。
    pub(super) fn 保存するまでの残り時間(&self, 今: Instant) -> Option<Duration> {
        self.変わりかけ.map(|変わりかけ| {
            落ち着くまでの時間.saturating_sub(今.saturating_duration_since(変わりかけ.変わった時刻))
        })
    }

    /// 終わる前に、書いた設定と違えば落ち着くのを待たずに保存すると答える。
    pub(super) fn 終わる前に見る(
        &mut self, 今の設定: 見る側の設定
    ) -> 見た結果 {
        if 今の設定 == self.書いた設定 {
            return 見た結果::まだ保存しない;
        }
        self.書いたことにする(今の設定);
        見た結果::保存する(今の設定)
    }

    fn 書いたことにする(&mut self, 設定: 見る側の設定) {
        self.書いた設定 = 設定;
        self.変わりかけ = None;
    }
}
