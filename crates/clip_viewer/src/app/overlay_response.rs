//! 重ね合わせの作業場の応答の振り分け。スタックの作業場へ戻ること・全画面・音量のつまみ・全体の消音は前に出ているかに関わらず当て、
//! 今のスタックから並べること・今のスタックのクリップを置くこと・ライブラリの操作・作業場の中の操作は、重ね合わせが前のときだけ重ね合わせの側へ当てる。
//! 参照: _doc/設計/同時再生.md 3-2

use std::time::Instant;

use super::stack_values::今のスタックの値を借りる;
use super::クリップビューアー;
use crate::command::再生の操作;
use crate::overlay::重ね合わせの作業場の応答;

impl クリップビューアー {
    /// 重ね合わせの作業場の応答を適用する。スタックの作業場へ戻ることと全画面の切り替えと音量のつまみと全体の消音は前に出ているかに関わらず当て、
    /// 音量のつまみと全体の消音は、スタックの作業場の今の操作(`再生の操作::音量を選ぶ`・`再生の操作::消音を切り替える`)をそのまま当てる(同時再生.md 3-2 の共有するものの表)。
    /// 今のスタックから並べることと今のスタックのクリップを置くことと重ね合わせの作業場の中の操作は、重ね合わせが前のときだけ、重ね合わせの側へ当てる。
    /// 並べることと置くことには、スタックの作業場の状態から借りた今のスタックの値を渡す(読むだけで変えない)。
    pub(super) fn 重ね合わせの作業場の応答を適用する(
        &mut self,
        応答: 重ね合わせの作業場の応答,
        今: Instant,
    ) {
        let 前の重ね合わせ = self.前に出ている作業場.前の重ね合わせを書き換える();
        match 応答 {
            重ね合わせの作業場の応答::スタックの作業場へ戻る => {
                self.スタックの作業場を前に出す(今)
            }
            重ね合わせの作業場の応答::全画面を切り替える => {
                self.状態.ウインドウ.全画面を切り替える()
            }
            重ね合わせの作業場の応答::音量のつまみの値を選ぶ(値) => {
                self.状態.再生の操作を適用する(再生の操作::音量を選ぶ(値))
            }
            重ね合わせの作業場の応答::全体の消音を切り替える => {
                self.状態.再生の操作を適用する(再生の操作::消音を切り替える)
            }
            重ね合わせの作業場の応答::今のスタックから並べる => {
                if let Some(側) = 前の重ね合わせ {
                    側.今のスタックから並べる(
                        今のスタックの値を借りる(&self.状態),
                        self.適用係.動画の読み手(),
                    );
                }
            }
            重ね合わせの作業場の応答::今のスタックのクリップを置く(
                クリップ,
            ) => {
                if let Some(側) = 前の重ね合わせ {
                    側.今のスタックのクリップを置く(
                        &クリップ,
                        今のスタックの値を借りる(&self.状態),
                    );
                }
            }
            重ね合わせの作業場の応答::操作(操作) => {
                if let Some(側) = 前の重ね合わせ {
                    側.操作を当てる(操作);
                }
            }
            重ね合わせの作業場の応答::ライブラリ(操作) => {
                if let Some(側) = 前の重ね合わせ {
                    側.ライブラリの操作を当てる(
                        操作,
                        &self.状態,
                        self.適用係.動画の読み手(),
                    );
                }
            }
        }
    }
}
