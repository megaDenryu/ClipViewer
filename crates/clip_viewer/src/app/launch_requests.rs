//! 起動の頼みの適用。起動の引数の頼みと、起動の受け口に届いた2つ目のアプリからの頼みを、動画を開く操作として状態へ当てる。
//! 描画の後に当てるため、描画の途中で状態を書き換えない。参照: _doc/設計/画面.md 判断13

use std::time::Instant;

use eframe::egui;

use super::クリップビューアー;
use crate::launch::{起動の受け口, 起動の頼み, 開かなかった動画の数};
use crate::state::library::開いたときの添え書き;

/// 起動の頼みの届き方とは、1フレームの間に起動の受け口へ頼みが届いたかの区別のことである。
/// 届いたなら、ウインドウへの指示でウインドウを前に出す(最小化していれば戻す)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 起動の頼みの届き方 {
    届いた,
    届いていない,
}

impl クリップビューアー {
    /// 起動の受け口(1つ目のアプリだけが持つ)で裏のスレッドに受け取り始めさせ、起動の引数の頼みを当てる。
    /// 受け取り始められなくても起動は止めず、知らせに足す。
    pub(super) fn 起動の受け口で受け取り始めて頼みを当てる(
        &mut self,
        受け口: Option<起動の受け口>,
        画面描画の共有状態: egui::Context,
        頼み: 起動の頼み,
        mut 知らせ: Vec<String>,
    ) {
        self.起動の受け口 = match 受け口
            .map(|受け口| 受け口.受け取り始める(画面描画の共有状態))
        {
            Some(Ok(受け取っている)) => Some(受け取っている),
            Some(Err(原因)) => {
                知らせ.push(format!("起動の受け口で受け取り始められない: {原因}"));
                None
            }
            None => None,
        };
        self.起動の頼みを適用する(頼み, 知らせ);
    }

    /// 起動の受け口に届いた頼みをすべて当てる。頼みが届いたら、重ね合わせが前でもスタックの作業場を前に出してから当てる
    /// (頼みはスタックの作業場で動画を開くため。参照: _doc/設計/同時再生.md 2-8)。
    pub(super) fn 届いた起動の頼みを適用する(
        &mut self,
        今: Instant,
    ) -> 起動の頼みの届き方 {
        let 届いた頼み = self
            .起動の受け口
            .as_ref()
            .map(|受け口| 受け口.届いた頼みを受け取る())
            .unwrap_or_default();
        if 届いた頼み.is_empty() {
            return 起動の頼みの届き方::届いていない;
        }
        self.スタックの作業場を前に出す(今);
        for 頼み in 届いた頼み {
            self.起動の頼みを適用する(頼み, Vec::new());
        }
        起動の頼みの届き方::届いた
    }

    /// 頼みが動画を開くなら、ウインドウへ落とした動画と同じく確かめてから開く(開いているスタックとの関係を終える前の確かめも同じに通る)。
    /// 開かなかった動画があったことは、開いたときだけ開いた結果の通知へ書き足す(確かめるダイアログを経て開いたときも書き足す)。
    /// ダイアログ(ライブラリのダイアログとキーの一覧のダイアログ)を開いている間は開かずに、ダイアログを閉じてから開き直すよう知らせる(開いているダイアログを上書きしないため)。
    /// 起動の途中の知らせは、開いたかにかかわらず書き足す。
    fn 起動の頼みを適用する(
        &mut self, 頼み: 起動の頼み, mut 知らせ: Vec<String>
    ) {
        let 前の回 = self.状態.通知.最新().map(|(回, _)| 回);
        if let 起動の頼み::動画を開く {
            動画,
            開かなかった数,
        } = 頼み
        {
            if self.状態.ダイアログを開いているか() {
                知らせ.push(format!(
                    "開いているダイアログを閉じてから、もう一度開いてください({})",
                    動画.文字列()
                ));
            } else {
                let 添え書き = 開かなかった数の添え書き(開かなかった数);
                self.適用係
                    .確かめてから動画を開く(&mut self.状態, &動画, 添え書き);
            }
        }
        self.状態.通知.この回の後に書き足す(前の回, 知らせ);
    }
}

/// 開かなかった動画の数を知らせる添え書き。開かなかった動画が無ければ無し。
fn 開かなかった数の添え書き(
    数: 開かなかった動画の数,
) -> 開いたときの添え書き {
    if 数.無いか() {
        return 開いたときの添え書き::無し;
    }
    開いたときの添え書き::書き足す(format!(
        "複数の動画が渡されたため、最初の1つだけを開いた(ほかの{}個は開いていない)",
        数.数()
    ))
}
