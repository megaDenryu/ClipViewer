//! 重ね合わせの側の、重ね合わせのライブラリに関わる口。ライブラリの操作を、スタックの作業場から借りた値と一緒に作業場へ当てることと、
//! 閉じる要求の確かめと、アプリを落とす前の保存を、前に出ている作業場(`front_workspace.rs`)へ公開する。参照: _doc/設計/同時再生.md 2-7・3-2

use video_source::動画の読み手;

use super::overlay_side::重ね合わせの側;
use super::stack_values::今のスタックの値を借りる;
use crate::overlay::{
    スタックの作業場から借りるもの, 重ね合わせのライブラリの操作
};
use crate::state::アプリの状態;

impl 重ね合わせの側 {
    /// 重ね合わせのライブラリの操作を当てる。続ける操作が使う今のスタックの値と動画の読み手は、スタックの作業場から借りる(読むだけで変えない)。
    pub(super) fn ライブラリの操作を当てる(
        &mut self,
        操作: 重ね合わせのライブラリの操作,
        状態: &アプリの状態,
        読み手: Option<&動画の読み手>,
    ) {
        let 借りるもの = スタックの作業場から借りるもの {
            今のスタック: 今のスタックの値を借りる(状態),
            読み手,
        };
        self.作業場.ライブラリの操作を当てる(操作, 借りるもの);
    }

    /// 重ね合わせの作業場を前に出すときに呼ぶ。重ね合わせの一覧を読み直す。
    pub(super) fn 前に出すときに一覧を読み直す(&mut self) {
        self.作業場.前に出すときに一覧を読み直す();
    }

    /// ウインドウを閉じる要求を受けた。開いている重ね合わせを確かめ、閉じてよいかを答える(よくなければ確かめるダイアログを出している)。
    pub(super) fn 閉じてよいかを確かめる(&mut self) -> bool {
        self.作業場.閉じてよいかを確かめる()
    }

    /// 利用者が重ね合わせの確かめるダイアログで変更を捨てて閉じると決めたか。
    pub(super) fn 閉じると決めたか(&self) -> bool {
        self.作業場.閉じると決めたか()
    }

    /// アプリを落とす前に、書けていない重ね合わせの保存を頼む。頼んだ書き込みは、作業場が持つ重ね合わせのライブラリを落とすときに終えてから閉じる。
    pub(super) fn 終わる前に保存を頼む(&mut self) {
        self.作業場.終わる前に保存を頼む();
    }
}
