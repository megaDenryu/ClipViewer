//! スタックの作業場を前に出す経路の試験。重ね合わせが前のとき、閉じる要求でスタックの確かめがダイアログを出すとスタックの作業場が前に出ることと、
//! 起動の受け口に頼みが届くとスタックの作業場が前に出てから動画を開こうとすることを確かめる。参照: _doc/設計/同時再生.md 2-8・3-2
#![allow(clippy::expect_used)]

use std::ffi::OsString;
use std::time::Duration;

use eframe::egui;

use super::launch_requests::起動の頼みの届き方;
use super::launch_requests_test_support::{試験のビューアー, 通知の文};
use super::workspace::前に出ている作業場;
use super::workspace_test_support::スタックの作業場の値を既定から変えて再生しているビューアー;
use super::クリップビューアー;
use crate::launch::{
    受け口の案内ファイル, 起動の受け口, 起動の頼み, 起動の頼みの送り手
};
use crate::state::library::ライブラリのダイアログ;
use crate::state::閉じる要求への答え;

fn 重ね合わせが前か(ビューアー: &クリップビューアー) -> bool {
    matches!(
        ビューアー.前に出ている作業場,
        前に出ている作業場::重ね合わせが前(_)
    )
}

#[test]
fn 重ね合わせが前でスタックだけが登録していない変更を持つとき_閉じる要求でスタックの作業場が前に出てダイアログが出る()
 {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    ビューアー.重ね合わせの作業場へ移る();
    assert_eq!(
        ビューアー.閉じる要求を確かめる(),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(!重ね合わせが前か(&ビューアー));
    assert!(matches!(
        ビューアー.状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(..)
    ));
}

#[test]
fn 重ね合わせが前でスタックに失う変更が無ければ_閉じてよく重ね合わせの作業場は前のままである() {
    let mut ビューアー = 試験のビューアー();
    ビューアー.重ね合わせの作業場へ移る();
    assert_eq!(
        ビューアー.閉じる要求を確かめる(),
        閉じる要求への答え::閉じてよい
    );
    assert!(重ね合わせが前か(&ビューアー));
}

#[test]
fn 重ね合わせが前のときに起動の頼みが届くと_スタックの作業場が前に出て動画を開こうとする() {
    let フォルダ = std::env::temp_dir().join(format!(
        "clip_viewer_作業場と起動の頼み_{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&フォルダ);
    let 案内ファイル = 受け口の案内ファイル::作成する(フォルダ.join("launch.json"));
    let mut ビューアー = 試験のビューアー();
    let 受け口 = 起動の受け口::開く(&案内ファイル).expect("待ち始められる");
    ビューアー.起動の受け口で受け取り始めて頼みを当てる(
        Some(受け口),
        egui::Context::default(),
        起動の頼み::前に出る,
        Vec::new(),
    );
    ビューアー.重ね合わせの作業場へ移る();
    assert_eq!(
        ビューアー.届いた起動の頼みを適用する(),
        起動の頼みの届き方::届いていない
    );
    assert!(重ね合わせが前か(&ビューアー), "頼みが届くまでは前のまま");
    let 頼み = 起動の頼み::引数から読む([OsString::from(r"C:\届いた.mp4")]);
    起動の頼みの送り手::作成する(案内ファイル, Duration::from_secs(3))
        .送る(&頼み)
        .expect("渡せる");
    assert_eq!(
        ビューアー.届いた起動の頼みを適用する(),
        起動の頼みの届き方::届いた
    );
    assert!(!重ね合わせが前か(&ビューアー));
    let 文面 = 通知の文(&ビューアー);
    assert!(
        文面.starts_with("FFmpeg が見つからないため動画を開けない"),
        "{文面}"
    );
    drop(ビューアー);
    let _ = std::fs::remove_dir_all(&フォルダ);
}
