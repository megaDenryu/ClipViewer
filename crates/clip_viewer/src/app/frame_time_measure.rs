//! 1フレームの時間の計測の手順。`cargo xtask frame-time` が起動したアプリで、画面の殻が毎フレーム呼ぶ。起動の引数の動画が開くのを待ち、
//! 重ね合わせの作業場で8行に並べて再生を始め(`frame_time_setup.rs`)、落ち着くまで待ってから決まった長さだけフレームの時間を溜め、
//! まとめの文を結果のファイルへ書いてウインドウを閉じさせる。頼みが無い普段の起動では、画面の殻はこの型を持たない。参照: _doc/設計/同時再生.md 5-4

use std::time::{Duration, Instant};

use super::クリップビューアー;
use crate::frame_time::{
    フレームの時間を測る頼み, 動画を待つ上限, 測ったフレームの時間, 測る前に待つ時間, 測る長さ,
};

/// 計測の段階とは、フレームの時間の計測がどこまで進んだかの区別のことである。
enum 計測の段階 {
    動画を待つ {
        始めた: Option<Instant>,
    },
    落ち着くのを待つ {
        始めた: Instant,
    },
    測っている {
        始めた: Instant,
        前の時刻: Instant,
        測った: 測ったフレームの時間,
    },
    終えた,
}

/// 計測の続きとは、このフレームの後に画面の殻がウインドウを閉じさせるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 計測の続き {
    続ける,
    ウインドウを閉じる,
}

/// フレームの時間の計測とは、フレームの時間を測る頼みと、計測の段階の組のことである。
pub(crate) struct フレームの時間の計測 {
    頼み: フレームの時間を測る頼み,
    段階: 計測の段階,
}

impl フレームの時間の計測 {
    pub(crate) fn 頼みから始める(頼み: フレームの時間を測る頼み) -> Self {
        Self {
            頼み,
            段階: 計測の段階::動画を待つ { 始めた: None },
        }
    }

    /// 毎フレーム、配線の手順の後に呼ぶ。前のフレームの秒数は eframe が知らせた値(まだ知らせていなければ無い)であり、時間へ直すのはここ1箇所である。
    pub(crate) fn フレームを数える(
        &mut self,
        ビューアー: &mut クリップビューアー,
        今: Instant,
        前のフレームの秒数: Option<f32>,
    ) -> 計測の続き {
        let 前のフレームの時間 =
            前のフレームの秒数.and_then(|秒| Duration::try_from_secs_f32(秒).ok());
        match &mut self.段階 {
            計測の段階::動画を待つ { 始めた } => {
                let 待ち始め = *始めた.get_or_insert(今);
                if ビューアー.状態.動画.is_some() {
                    return match ビューアー.計測のために八行を並べて再生する(今)
                    {
                        Ok(()) => self
                            .進める(計測の段階::落ち着くのを待つ { 始めた: 今 }),
                        Err(理由) => self.書いて終える(&format!("測れなかった: {理由}")),
                    };
                }
                if 今.duration_since(待ち始め) > 動画を待つ上限 {
                    return self.書いて終える("測れなかった: 起動の引数の動画が開かなかった");
                }
            }
            計測の段階::落ち着くのを待つ { 始めた }
                if 今.duration_since(*始めた) >= 測る前に待つ時間 =>
            {
                return self.進める(計測の段階::測っている {
                    始めた: 今,
                    前の時刻: 今,
                    測った: 測ったフレームの時間::default(),
                });
            }
            計測の段階::測っている {
                始めた,
                前の時刻,
                測った,
            } => {
                測った.足す(前のフレームの時間, 今.duration_since(*前の時刻));
                *前の時刻 = 今;
                if 今.duration_since(*始めた) >= 測る長さ {
                    let 文 = format!(
                        "重ね合わせの8行を再生している間の{}秒\n{}",
                        測る長さ.as_secs(),
                        測った.まとめの文()
                    );
                    return self.書いて終える(&文);
                }
            }
            計測の段階::落ち着くのを待つ { .. } | 計測の段階::終えた => {}
        }
        計測の続き::続ける
    }

    fn 進める(&mut self, 次: 計測の段階) -> 計測の続き {
        self.段階 = 次;
        計測の続き::続ける
    }

    fn 書いて終える(&mut self, 文: &str) -> 計測の続き {
        self.頼み.結果を書く(文);
        self.段階 = 計測の段階::終えた;
        計測の続き::ウインドウを閉じる
    }
}
