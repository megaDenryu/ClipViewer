//! 窓への指示の並びの試験。閉じる要求への答えと、変更を捨てて閉じると決めたかと、起動の頼みが届いたかと、全画面の頼みから、
//! 起動の部分が窓へ送る指示の並びを決める。

use super::close::窓への指示;
use super::launch_requests::起動の頼みの届き方::{届いた, 届いていない};
use crate::state::{全画面の様子, 窓への頼み, 閉じる要求への答え};
use crate::viewer_settings::窓の大きさ;

fn 頼み無し() -> 窓への頼み {
    窓への頼み::default()
}

fn 全画面の頼み(様子: 全画面の様子) -> 窓への頼み {
    窓への頼み {
        全画面: Some(様子),
        大きさ: None,
    }
}

#[test]
fn 要求を受けなければ何も送らない() {
    assert!(窓への指示::並びを決める(None, false, 届いていない, 頼み無し()).is_empty());
}

#[test]
fn 閉じてよいと答えたら何も送らず_窓はそのまま閉じる() {
    let 答え = Some(閉じる要求への答え::閉じてよい);
    assert!(窓への指示::並びを決める(答え, false, 届いていない, 頼み無し()).is_empty());
}

#[test]
fn 閉じるのをやめると答えたら要求を取り消す() {
    let 答え = Some(閉じる要求への答え::閉じるのをやめる);
    assert_eq!(
        窓への指示::並びを決める(答え, false, 届いていない, 頼み無し()),
        [窓への指示::閉じるのを取り消す]
    );
}

#[test]
fn 変更を捨てて閉じると決めたら閉じる指示だけを送る() {
    assert_eq!(
        窓への指示::並びを決める(None, true, 届いた, 全画面の頼み(全画面の様子::全画面)),
        [窓への指示::閉じる]
    );
}

#[test]
fn 起動の頼みが届いたら前に出す() {
    assert_eq!(
        窓への指示::並びを決める(None, false, 届いた, 頼み無し()),
        [窓への指示::前に出す]
    );
    assert_eq!(
        窓への指示::並びを決める(
            Some(閉じる要求への答え::閉じてよい),
            false,
            届いた,
            頼み無し()
        ),
        [窓への指示::前に出す]
    );
}

#[test]
fn 同じフレームの指示は_取り消し_全画面_大きさ_前に出すの順に全部送る() {
    let 答え = Some(閉じる要求への答え::閉じるのをやめる);
    let 頼み = 窓への頼み {
        全画面: Some(全画面の様子::全画面でない),
        大きさ: Some(窓の大きさ::最初),
    };
    assert_eq!(
        窓への指示::並びを決める(答え, false, 届いた, 頼み),
        [
            窓への指示::閉じるのを取り消す,
            窓への指示::全画面にする(全画面の様子::全画面でない),
            窓への指示::大きさを変える(窓の大きさ::最初),
            窓への指示::前に出す,
        ]
    );
}
