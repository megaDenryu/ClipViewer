//! 前に出ている作業場。スタックの作業場と重ね合わせの作業場のどちらが前かと、控えた重ね合わせの側と、重ね合わせの側の作り方を持ち、
//! 前に出す作業場を持ち替え、重ね合わせの側を毎フレーム進める。重ね合わせの側へ触れる口はここに集める。参照: _doc/設計/同時再生.md 3-2

use std::time::Instant;

use super::overlay_side::{重ね合わせの側, 重ね合わせの側の作り方};
use crate::state::アプリの状態;

/// どちらが前かとは、スタックの作業場と重ね合わせの作業場のどちらを利用者に見せているかの区別のことである。
/// 一度作った重ね合わせの側は、スタックの作業場が前の間も控えておき、再び移ったときに同じ重ね合わせを同じ再生の位置で出す。
enum どちらが前 {
    スタックが前 {
        控えた重ね合わせ: Option<重ね合わせの側>,
    },
    重ね合わせが前(重ね合わせの側),
}

/// 前に出ている作業場とは、どちらが前かと、初めて重ね合わせの作業場へ移るときに重ね合わせの側を作る作り方の組のことである。
/// スタックの作業場の状態は `クリップビューアー` が常に持つ。
pub(crate) struct 前に出ている作業場 {
    前: どちらが前,
    作り方: 重ね合わせの側の作り方,
}

impl 前に出ている作業場 {
    /// 起動したときの値。スタックの作業場が前で、重ね合わせの側はまだ作っていない。
    pub(crate) fn 起動時(作り方: 重ね合わせの側の作り方) -> Self {
        let 前 = どちらが前::スタックが前 {
            控えた重ね合わせ: None,
        };
        Self { 前, 作り方 }
    }

    /// 重ね合わせが前か。
    pub(crate) fn 重ね合わせが前か(&self) -> bool {
        matches!(self.前, どちらが前::重ね合わせが前(_))
    }

    /// 前に出ている重ね合わせの側。スタックの作業場が前なら無い。
    pub(crate) fn 前の重ね合わせ(&self) -> Option<&重ね合わせの側> {
        match &self.前 {
            どちらが前::重ね合わせが前(側) => Some(側),
            どちらが前::スタックが前 { .. } => None,
        }
    }

    /// 書き換えられる、前に出ている重ね合わせの側。スタックの作業場が前なら無い。
    pub(crate) fn 前の重ね合わせを書き換える(
        &mut self,
    ) -> Option<&mut 重ね合わせの側> {
        match &mut self.前 {
            どちらが前::重ね合わせが前(側) => Some(側),
            どちらが前::スタックが前 { .. } => None,
        }
    }

    /// 控えている重ね合わせの側。まだ作っていないか、重ね合わせが前なら無い。試験で控えた後の様子を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 控えた重ね合わせ(&self) -> Option<&重ね合わせの側> {
        match &self.前 {
            どちらが前::スタックが前 {
                控えた重ね合わせ
            } => 控えた重ね合わせ.as_ref(),
            どちらが前::重ね合わせが前(_) => None,
        }
    }

    /// 重ね合わせの作業場を前に出す。控えた重ね合わせの側があればそれを、無ければ作り方で作って(2本目の流れを開いて)前に出す。
    pub(super) fn 重ね合わせを前に出す(&mut self) {
        if let どちらが前::スタックが前 {
            控えた重ね合わせ
        } = &mut self.前
        {
            let 側 = 控えた重ね合わせ
                .take()
                .unwrap_or_else(|| 重ね合わせの側::作る(&self.作り方));
            self.前 = どちらが前::重ね合わせが前(側);
        }
    }

    /// スタックの作業場を前に出す。重ね合わせの側は再生を止めて控える。
    pub(super) fn スタックを前に出す(&mut self) {
        // 注意: 前に出ていた重ね合わせの側を値として取り出すため、取り出す間だけ控えの無いスタックの作業場を置き、すぐに書き戻す。
        let 控えの無いスタックが前 = どちらが前::スタックが前 {
            控えた重ね合わせ: None,
        };
        self.前 = match std::mem::replace(&mut self.前, 控えの無いスタックが前) {
            どちらが前::重ね合わせが前(mut 側) => {
                側.控える();
                どちらが前::スタックが前 {
                    控えた重ね合わせ: Some(側),
                }
            }
            スタックが前 @ どちらが前::スタックが前 { .. } => スタックが前,
        };
    }

    /// 毎フレーム呼ぶ。重ね合わせが前ならその側のフレームを進め、控えているならどの行も黙る指示を渡す。まだ作っていなければ何もしない。
    pub(super) fn 重ね合わせの側のフレームを進める(
        &mut self,
        今: Instant,
        状態: &アプリの状態,
    ) {
        match &mut self.前 {
            どちらが前::重ね合わせが前(側) => {
                側.前に出ている間のフレームを進める(今, 状態)
            }
            どちらが前::スタックが前 {
                控えた重ね合わせ: Some(側),
            } => 側.控えている間に黙らせる(今),
            どちらが前::スタックが前 {
                控えた重ね合わせ: None,
            } => {}
        }
    }
}
