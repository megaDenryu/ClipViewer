//! 前に出ている作業場。スタックの作業場と重ね合わせの作業場のどちらが前かと、控えた重ね合わせの作業場を持ち、前に出す作業場を持ち替える。
//! 参照: _doc/設計/同時再生.md 3-2

use eframe::egui;

use crate::overlay::{重ね合わせの作業場, 重ね合わせの音の出力の状況};

/// 前に出ている作業場とは、スタックの作業場と重ね合わせの作業場のどちらを利用者に見せているかの区別のことである。スタックの作業場の状態は `クリップビューアー` が常に持つ。
/// 一度作った重ね合わせの作業場は、スタックの作業場が前の間も控えておき、再び移ったときに同じ重ね合わせを同じ再生の位置で出す。
pub(crate) enum 前に出ている作業場 {
    スタックが前 {
        控えた重ね合わせ: Option<重ね合わせの作業場>,
    },
    重ね合わせが前(重ね合わせの作業場),
}

impl 前に出ている作業場 {
    /// 起動したときの値。スタックの作業場が前で、重ね合わせの作業場はまだ作っていない。
    pub(crate) fn 起動時() -> Self {
        Self::スタックが前 {
            控えた重ね合わせ: None,
        }
    }

    /// 重ね合わせの作業場を前に出す。控えていればそれを、無ければ重ね合わせを開いていない作業場を、画面描画の共有状態と2本目の流れの音の出力の状況を渡して作って前に出す。
    pub(super) fn 重ね合わせを前に出す(
        &mut self,
        画面描画の共有状態: &egui::Context,
        音の出力: 重ね合わせの音の出力の状況,
    ) {
        if let Self::スタックが前 {
            控えた重ね合わせ
        } = self
        {
            let 作業場 = 控えた重ね合わせ.take().unwrap_or_else(|| {
                重ね合わせの作業場::開いていない作業場(
                    画面描画の共有状態.clone(),
                    音の出力,
                )
            });
            *self = Self::重ね合わせが前(作業場);
        }
    }

    /// スタックの作業場を前に出す。重ね合わせの作業場は再生を止めて控える。
    pub(super) fn スタックを前に出す(&mut self) {
        // 注意: 前に出ていた重ね合わせの作業場を値として取り出すため、取り出す間だけ控えの無いスタックの作業場を置き、すぐに書き戻す。
        let 控えの無いスタックが前 = Self::スタックが前 {
            控えた重ね合わせ: None,
        };
        *self = match std::mem::replace(self, 控えの無いスタックが前) {
            Self::重ね合わせが前(mut 作業場) => {
                作業場.控える前に再生を止める();
                Self::スタックが前 {
                    控えた重ね合わせ: Some(作業場),
                }
            }
            スタックが前 @ Self::スタックが前 { .. } => スタックが前,
        };
    }
}
