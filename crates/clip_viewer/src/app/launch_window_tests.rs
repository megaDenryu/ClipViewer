//! ライブラリのダイアログを開いている間に届いた起動の頼みの試験。開いているダイアログを上書きせず、動画を開かずに、ダイアログを閉じてから開き直すよう知らせる。

use std::ffi::OsString;

use eframe::egui;

use super::launch_requests_test_support::{試験のビューアー, 通知の文};
use crate::launch::起動の頼み;
use crate::state::library::{
    ライブラリのダイアログ, 並びを捨てる理由, 関係を終える操作
};

#[test]
fn ダイアログを開いている間に届いた動画は開かず_ダイアログをそのままにして閉じてから開き直すよう知らせる()
 {
    let mut ビューアー = 試験のビューアー();
    let 開いているダイアログ = ライブラリのダイアログ::並びを捨てる確認(
        並びを捨てる理由::登録していない変更がある,
        関係を終える操作::アプリを閉じる,
    );
    ビューアー.状態.ライブラリ.ダイアログ = 開いているダイアログ.clone();
    ビューアー.起動の受け口で受け取り始めて頼みを当てる(
        None,
        egui::Context::default(),
        起動の頼み::引数から読む([OsString::from(r"C:\届いた.mp4")]),
        Vec::new(),
    );
    assert_eq!(ビューアー.状態.ライブラリ.ダイアログ, 開いているダイアログ);
    let 文 = 通知の文(&ビューアー);
    assert!(
        文.contains("開いているダイアログを閉じてから、もう一度開いてください"),
        "{文}"
    );
    assert!(!文.contains("FFmpeg"), "開こうとしない: {文}");
}
