//! 作業場を移す時点で音の流れへ渡す指示の試験。渡した指示を覚える受け口に差し替え、「同時再生」へ移る時点で1本目の流れへ止める指示を1回渡すことと、
//! 「スタックへ戻る」で控える時点で2本目の流れへどの行も黙る指示を1回渡すことを、装置を開かずに確かめる。参照: _doc/設計/同時再生.md 3-2・5-3
#![allow(clippy::expect_used)]

use std::time::Instant;

use audio_output::{再生の指示, 再生の様子, 行ごとの再生の指示};
use clip_domain::行の番号;

use super::super::sound_sender::音の送り手;
use super::super::workspace_response::作業場の応答;
use super::instruction_receiver_test_support::{控えへ開く, 渡した指示の控え};
use super::launch_requests_test_support::試験のビューアーを二本目の流れの手立てで作る;
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生させる,
    スタックの作業場の値を既定から変えて再生しているビューアー,
};
use crate::overlay::重ね合わせの作業場の応答;

/// 行の番号の行の指示を、黙る指示と入れ替えて取り出す。
fn 行の指示を取り出す(
    指示: &mut 行ごとの再生の指示, 番号: usize
) -> 再生の指示 {
    指示
        .行の指示を置き換える(
            行の番号::番号から作成する(番号),
            再生の指示::黙る(Instant::now()),
        )
        .expect("行の数の上限の内")
}

#[test]
fn 同時再生へ移る時点で_止めたスタックの作業場の指示を1本目の流れへ1回渡す() {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    let 一本目 = 渡した指示の控え::<再生の指示>::空();
    ビューアー.音の送り手 = 音の送り手::装置あり(Box::new(一本目.clone()));
    assert!(
        ビューアー.状態.再生.再生しているか(),
        "試験の前提: 再生している"
    );
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    let 渡された = 一本目.渡された指示の並び();
    assert_eq!(渡された.len(), 1, "次の描き直しを待たずに1回渡す");
    assert_eq!(渡された[0].様子, 再生の様子::止めている);
}

#[test]
fn スタックへ戻る時点で_2本目の流れへどの行も黙る指示を1回渡す() {
    let 二本目 = 渡した指示の控え::<行ごとの再生の指示>::空();
    let mut ビューアー = スタックの作業場の値を既定から変えて再生させる(
        試験のビューアーを二本目の流れの手立てで作る(
            Box::new(控えへ開く(二本目.clone())),
        ),
    );
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    assert!(
        二本目.渡された指示の並び().is_empty(),
        "移っただけでは渡さない"
    );
    ビューアー.作業場の応答を適用する(
        作業場の応答::重ね合わせの応答(
            重ね合わせの作業場の応答::スタックの作業場へ戻る,
        ),
        Instant::now(),
    );
    let mut 渡された = 二本目.渡された指示の並び();
    assert_eq!(渡された.len(), 1, "控える時点で1回渡す");
    let 行 = 行の指示を取り出す(&mut 渡された[0], 0);
    assert_eq!(行.様子, 再生の様子::止めている);
    assert!(行.区間.is_none(), "黙る指示");
}
