//! 回帰試験(b)の手順。スタックの作業場の今のキーの割り当てから、キーで行う操作の全部のキーの組を押す入力を作り、
//! 重ね合わせの作業場が前のときに1つずつ押して、スタックの作業場の写しが変わらないことを確かめる。動画を開いていない試験と開いた試験が共有する。
#![allow(clippy::expect_used)]

use eframe::egui;
use sengen_egui::キーの組;

use super::super::launch_requests::起動の頼みの届き方;
use super::super::クリップビューアー;
use super::workspace_test_frames::{
    キーを押して適用する, 何も押さずに一フレーム進める
};
use super::workspace_test_snapshot::スタックの作業場の写し;
use crate::overlay::重ね合わせの作業場が受け取るキーの組;

/// キーの組を押す入力のキーと修飾キー。キーの組は修飾キーを外へ見せないため、候補の修飾キーで組を作り直して等しいものを選ぶ。
/// どの候補とも等しくなければ、押せないキーの組を黙って外さずに失敗させる。
fn キーの組を押す入力(組: キーの組) -> (egui::Key, egui::Modifiers) {
    let 候補 = [
        egui::Modifiers::NONE,
        egui::Modifiers::SHIFT,
        egui::Modifiers::COMMAND,
        egui::Modifiers::COMMAND | egui::Modifiers::SHIFT,
        egui::Modifiers::ALT,
        egui::Modifiers::ALT | egui::Modifiers::SHIFT,
        egui::Modifiers::COMMAND | egui::Modifiers::ALT,
    ];
    let 修飾キー = 候補
        .into_iter()
        .find(|修飾キー| キーの組::生成する(*修飾キー, 組.キー()) == 組)
        .unwrap_or_else(|| panic!("{} の修飾キーを候補から決められない", 組.表記()));
    (組.キー(), 修飾キー)
}

/// 今のキーの割り当てで、キーで行う操作の全部に割り当てたキーの組を押す入力の並び。重ね合わせの作業場が受け取るキー(F11)と重なる組は除く。
/// 重ね合わせの作業場の F11 は、設計どおり2つの作業場で共有する全画面を切り替えるため(同時再生.md 2-8)、`app/workspace/overlay_tests.rs` で別に確かめる。
fn 今の割り当ての全部のキー(
    ビューアー: &クリップビューアー,
) -> Vec<(egui::Key, egui::Modifiers)> {
    ビューアー
        .状態
        .キーの割り当て
        .並び()
        .flat_map(|(_, キー)| キー.組の並び())
        .filter(|組| !重ね合わせの作業場が受け取るキーの組().any(|受け取る| 受け取る == *組))
        .map(キーの組を押す入力)
        .collect()
}

/// 重ね合わせの作業場へ移り、今の割り当ての全部のキーを1つずつ押して、そのたびにスタックの作業場の写しが移った直後と同じで、
/// 再生していないことを確かめる。最後に、ウインドウへの指示(全画面の頼み等)が並んでいないことを確かめる。
pub(in crate::app) fn 重ね合わせが前のときに全部のキーを押してもスタックの作業場が変わらないことを確かめる(
    ビューアー: &mut クリップビューアー,
) {
    let キーの並び = 今の割り当ての全部のキー(ビューアー);
    assert!(キーの並び.len() >= 20, "{キーの並び:?}");
    ビューアー.重ね合わせの作業場へ移る();
    何も押さずに一フレーム進める(ビューアー);
    let 移った後 = スタックの作業場の写し::写しを取る(ビューアー);
    for (キー, 修飾キー) in キーの並び {
        キーを押して適用する(ビューアー, キー, 修飾キー);
        assert_eq!(
            スタックの作業場の写し::写しを取る(ビューアー),
            移った後,
            "{キー:?} {修飾キー:?}"
        );
        assert!(
            !ビューアー.状態.再生.再生しているか(),
            "{キー:?} {修飾キー:?}"
        );
    }
    assert!(
        ビューアー
            .ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない)
            .is_empty()
    );
}
