//! 重ね合わせの側をまだ作っていないときのアプリを閉じる手順の試験。ファイルの中身と並びが違い、ライブラリの接続が無いため書けない登録済みのスタックを閉じようとして確かめ、スタックのダイアログで
//! 変更を捨てて続けると決めると、同じフレームで開いているスタックとの関係を終え、閉じる指示を並べることを確かめる。参照: _doc/設計/同時再生.md 2-7
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{
    スタックの名前, スタックの識別子, ライブラリのスタック, ライブラリの日時, 入力された動画パス,
};

use super::super::close::ウインドウへの指示;
use super::super::launch_requests::起動の頼みの届き方;
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生しているビューアー, スタックの応答を適用する,
};
use crate::command::{ライブラリの操作, 応答};
use crate::state::library::{
    ライブラリのダイアログ, 登録済みのスタック, 開いているスタック, 関係を終える操作,
};
use crate::state::閉じる要求への答え;

#[test]
fn 重ね合わせの側が無いときにスタックのダイアログで捨てると_同じフレームで関係を終えて閉じる指示を並べる()
 {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    let 登録済み =
        登録済みのスタック::ファイルから開いた(ライブラリのスタック::新しく作る(
            スタックの識別子::文字列から作成する("stack-1-1".to_string()).expect("識別子"),
            スタックの名前::作成する("練習".to_string()).expect("名前"),
            入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
            clip_domain::クリップスタック::default(),
            ライブラリの日時::紀元からのミリ秒で作成する(1_000).expect("日時"),
        ));
    ビューアー.状態.ライブラリ.開いている = 開いているスタック::登録済み(登録済み);
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(matches!(
        &ビューアー.状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::保存できずに続ける確認(
            _,
            関係を終える操作::アプリを閉じる
        )
    ));
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::ライブラリ(
            ライブラリの操作::変更を捨てて続ける,
        )],
    );
    assert!(matches!(
        ビューアー.状態.ライブラリ.開いている,
        開いているスタック::未登録
    ));
    assert_eq!(
        ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない),
        [ウインドウへの指示::閉じる]
    );
}
