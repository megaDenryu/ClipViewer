//! アプリを閉じる手順の試験の道具。重ね合わせを開いて置き方を手で直すことと、重ね合わせのライブラリの操作を画面と同じ経路で当てることと、
//! スタックの作業場が閉じる前の確かめを出しているかを読むことと、重ね合わせの決めを待つところまで閉じる手順を進めることを受け持つ。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::{アスペクト比設定, 重ねる画面の縦横比};

use super::super::workspace_response::作業場の応答;
use super::super::クリップビューアー;
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生しているビューアー, スタックの応答を適用する,
    前の重ね合わせの作業場,
};
use crate::command::{ライブラリの操作, 応答};
use crate::overlay::test_support::五秒の重ね合わせ;
use crate::overlay::{
    置き方の操作, 重ね合わせのライブラリの操作, 重ね合わせの作業場の応答, 重ね合わせの操作,
};
use crate::primary_button::主ボタンの様子;
use crate::state::library::{ライブラリのダイアログ, 関係を終える操作};

/// 重ね合わせの作業場へ移り、五秒の重ね合わせを開いて、縦横比を正方形に変える(置き方を手で直す)。
pub(in crate::app) fn 重ね合わせを開いて縦横比を変える(
    ビューアー: &mut クリップビューアー,
) {
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    let 作業場 = 前の重ね合わせの作業場(ビューアー).expect("重ね合わせが前");
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    let 正方形 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    作業場.操作を適用する(重ね合わせの操作::置き方(
        置き方の操作::重ねる画面の縦横比を選ぶ(正方形),
    ));
}

/// 重ね合わせの作業場の応答のライブラリの操作を、画面が発したときと同じ経路で当てる。
pub(in crate::app) fn 重ね合わせのライブラリの操作を当てる(
    ビューアー: &mut クリップビューアー,
    操作: 重ね合わせのライブラリの操作,
) {
    let _ = ビューアー.応答を適用する(
        vec![作業場の応答::重ね合わせの応答(
            重ね合わせの作業場の応答::ライブラリ(操作),
        )],
        主ボタンの様子::押していない,
        Instant::now(),
    );
}

/// スタックの作業場が、続けるとアプリを閉じる並びを捨てる確認を出しているか。
pub(in crate::app) fn スタックが閉じる前の確かめを出しているか(
    ビューアー: &クリップビューアー,
) -> bool {
    matches!(
        &ビューアー.状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(
            _,
            関係を終える操作::アプリを閉じる
        )
    )
}

/// スタックと重ね合わせの両方が登録していない変更を持つビューアーで閉じようとし、スタックの確かめで変更を捨てて続けると決め、
/// 重ね合わせの確かめのダイアログが出て重ね合わせの決めを待っているところまで進める。
pub(in crate::app) fn 重ね合わせの決めを待つまで進めたビューアー() -> クリップビューアー {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    重ね合わせを開いて縦横比を変える(&mut ビューアー);
    ビューアー.スタックの作業場を前に出す(Instant::now());
    let _ = ビューアー.閉じる要求を確かめる(Instant::now());
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::ライブラリ(
            ライブラリの操作::変更を捨てて続ける,
        )],
    );
    ビューアー
}
