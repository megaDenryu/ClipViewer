fn 識別子(名前: &str) -> クリップ識別子 {
    クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子")
}

/// スタックの作業場の応答を、画面が発したときと同じ経路で適用する。
pub(in crate::app) fn スタックの応答を適用する(
    ビューアー: &mut クリップビューアー,
    応答一覧: Vec<応答>,
) {
    let _ = ビューアー.応答を適用する(
        応答一覧
            .into_iter()
            .map(作業場の応答::スタックの応答)
            .collect(),
        主ボタンの様子::押していない,
        Instant::now(),
    );
}

/// スタックの作業場に手を加えたクリップビューアー。甲と乙の並びで甲の名前を変えた編集を履歴に積み、乙を選び、シアターの構えにし、
/// 音量とキーの割り当てを既定から変え、再生の位置を1.5秒へ移して再生している。並びは未登録で、登録していない変更がある。
pub(in crate::app) fn スタックの作業場の値を既定から変えて再生しているビューアー()
-> クリップビューアー {
    スタックの作業場の値を既定から変えて再生させる(試験のビューアー())
}

/// 渡したクリップビューアーのスタックの作業場の値を、`スタックの作業場の値を既定から変えて再生しているビューアー` と同じに変えて再生させる。
pub(in crate::app) fn スタックの作業場の値を既定から変えて再生させる(
    mut ビューアー: クリップビューアー,
) -> クリップビューアー {
    let 並び = クリップスタック::一覧から作成する(vec![
        クリップ::既定値で作成する(
            識別子("甲"),
            クリップ名::作成する("甲".to_string()),
        ),
        クリップ::既定値で作成する(
            識別子("乙"),
            クリップ名::作成する("乙".to_string()),
        ),
    ])
    .expect("スタック");
    ビューアー
        .状態
        .並びを置き換える(並び, 並びの出どころ::新しく作った);
    スタックの応答を適用する(
        &mut ビューアー,
        vec![
            応答::クリップ(クリップの操作::編集する(
                識別子("甲"),
                クリップの編集::名前を変える("甲の新しい名前".to_string()),
            )),
            応答::クリップ(クリップの操作::選ぶ(識別子("乙"))),
            応答::出力(出力の操作::構えを選ぶ(画面の構え::シアター)),
            応答::再生(再生の操作::音量を選ぶ(0.3)),
        ],
    );
    ビューアー.フレームを進める(Instant::now());
    let 状態 = &mut ビューアー.状態;
    状態.キーの割り当て = 状態
        .キーの割り当て
        .キーを変えた(
            キーで行う操作::キーの一覧を開け閉めする,
            キーの組::単独(キー::Y),
        )
        .expect("Y は空いている");
    状態.再生.位置を移す(再生位置::シーケンス再生(
        時刻::作成する(1.5).expect("時刻"),
    ));
    状態.再生.再生を始める();
    ビューアー
}

/// 前に出ている重ね合わせの作業場。スタックの作業場が前なら無い。
pub(in crate::app) fn 前の重ね合わせの作業場(
    ビューアー: &mut クリップビューアー,
) -> Option<&mut 重ね合わせの作業場> {
    ビューアー
        .前に出ている作業場
        .前の重ね合わせを書き換える()
        .map(重ね合わせの側::作業場を書き換える)
}
