//! アプリを閉じる手順を捨てる試験。スタックと重ね合わせの両方が登録していない変更を持つとき、スタックの確かめで変更を捨てて続けると決めても、
//! 重ね合わせの確かめで「やめる」を選べば何も当てずに手順を捨てることと、その後にスタックを編集して閉じようとすると、スタックの確かめがもう一度出ることを確かめる。
//! 両方で決めたときは `workspace_close_both_tests.rs` が確かめる。参照: _doc/設計/同時再生.md 2-7、_doc/使い方.md 11.3・15.9・15.10
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::super::close::ウインドウへの指示;
use super::super::launch_requests::起動の頼みの届き方;
use super::workspace_close_test_support::{
    スタックが閉じる前の確かめを出しているか, 重ね合わせのライブラリの操作を当てる,
    重ね合わせを開いて縦横比を変える,
};
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生しているビューアー, スタックの応答を適用する,
};
use clip_domain::クリップ識別子;

use super::super::close_procedure::{アプリを閉じる手順, スタックの決め方};
use crate::command::{
    クリップの操作, クリップの編集, ライブラリの操作, 応答
};
use crate::overlay::{
    一覧とダイアログの操作, 重ね合わせのライブラリの操作
};
use crate::state::閉じる要求への答え;

#[test]
fn スタックで変更を捨てると決めても_重ね合わせでやめると手順を捨て_編集して閉じるとスタックの確かめがもう一度出る()
 {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    重ね合わせを開いて縦横比を変える(&mut ビューアー);
    ビューアー.スタックの作業場を前に出す(Instant::now());
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(スタックが閉じる前の確かめを出しているか(
        &ビューアー
    ));
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::ライブラリ(
            ライブラリの操作::変更を捨てて続ける,
        )],
    );
    assert!(ビューアー.前に出ている作業場.重ね合わせが前か());
    assert_eq!(
        ビューアー.閉じる手順,
        アプリを閉じる手順::重ね合わせの決めを待つ(
            スタックの決め方::利用者が閉じてよいと決めた
        )
    );
    重ね合わせのライブラリの操作を当てる(
        &mut ビューアー,
        重ね合わせのライブラリの操作::一覧とダイアログ(
            一覧とダイアログの操作::ダイアログを閉じる,
        ),
    );
    assert_eq!(
        ビューアー.閉じる手順,
        アプリを閉じる手順::閉じようとしていない
    );
    assert!(
        ビューアー
            .ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない)
            .iter()
            .all(|指示| *指示 != ウインドウへの指示::閉じる)
    );
    ビューアー.スタックの作業場を前に出す(Instant::now());
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::クリップ(クリップの操作::編集する(
            クリップ識別子::文字列から作成する("乙".to_string()).expect("識別子"),
            クリップの編集::名前を変える("乙の新しい名前".to_string()),
        ))],
    );
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(スタックが閉じる前の確かめを出しているか(
        &ビューアー
    ));
    assert!(!ビューアー.前に出ている作業場.重ね合わせが前か());
}
