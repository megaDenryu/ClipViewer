//! アプリを閉じる手順の試験。スタックと重ね合わせの両方が登録していない変更を持つとき、スタックの確かめで変更を捨てて続けると決めても、
//! 重ね合わせの確かめで「やめる」を選べば何も当てずに手順を捨てることと、その後にスタックを編集して閉じようとすると、スタックの確かめがもう一度出ることと、
//! 両方で変更を捨てて続けると決めたときにだけ閉じると決めることを確かめる。
//! 参照: _doc/設計/同時再生.md 2-7、_doc/使い方.md 14.1・15.10
#![allow(clippy::expect_used)]

