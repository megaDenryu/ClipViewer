fn 重ね合わせのライブラリの操作を当てる(
    ビューアー: &mut クリップビューアー,
    操作: 重ね合わせのライブラリの操作,
) {
    let _ = ビューアー.応答を適用する(
        vec![作業場の応答::重ね合わせの応答(
            重ね合わせの作業場の応答::ライブラリ(操作),
        )],
        主ボタンの様子::押していない,
        Instant::now(),
    );
}

fn スタックが閉じる前の確かめを出しているか(
    ビューアー: &クリップビューアー,
) -> bool {
    matches!(
        &ビューアー.状態.ライブラリ.ダイアログ,
        ライブラリのダイアログ::並びを捨てる確認(
            _,
            関係を終える操作::アプリを閉じる
        )
    )
}

#[test]
fn スタックで変更を捨てると決めても_重ね合わせでやめると手順を捨て_編集して閉じるとスタックの確かめがもう一度出る()
 {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    重ね合わせを開いて縦横比を変える(&mut ビューアー);
    ビューアー.スタックの作業場を前に出す(Instant::now());
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(スタックが閉じる前の確かめを出しているか(
        &ビューアー
    ));
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::ライブラリ(
            ライブラリの操作::変更を捨てて続ける,
        )],
    );
    assert!(ビューアー.前に出ている作業場.重ね合わせが前か());
    assert_eq!(
        ビューアー.閉じる手順,
        アプリを閉じる手順::重ね合わせの決めを待つ(
            スタックの決め方::利用者が閉じてよいと決めた
        )
    );
    重ね合わせのライブラリの操作を当てる(
        &mut ビューアー,
        重ね合わせのライブラリの操作::一覧とダイアログ(
            一覧とダイアログの操作::ダイアログを閉じる,
        ),
    );
    assert_eq!(
        ビューアー.閉じる手順,
        アプリを閉じる手順::閉じようとしていない
    );
    assert!(
        ビューアー
            .ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない)
            .iter()
            .all(|指示| *指示 != ウインドウへの指示::閉じる)
    );
    ビューアー.スタックの作業場を前に出す(Instant::now());
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::クリップ(クリップの操作::編集する(
            クリップ識別子::文字列から作成する("乙".to_string()).expect("識別子"),
            クリップの編集::名前を変える("乙の新しい名前".to_string()),
        ))],
    );
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(スタックが閉じる前の確かめを出しているか(
        &ビューアー
    ));
    assert!(!ビューアー.前に出ている作業場.重ね合わせが前か());
}

#[test]
fn スタックと重ね合わせの両方で変更を捨てると決めたときにだけ閉じると決める() {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    重ね合わせを開いて縦横比を変える(&mut ビューアー);
    ビューアー.スタックの作業場を前に出す(Instant::now());
    let _ = ビューアー.閉じる要求を確かめる(Instant::now());
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::ライブラリ(
            ライブラリの操作::変更を捨てて続ける,
        )],
    );
    assert!(!ビューアー.閉じる手順.閉じると決めたか());
    重ね合わせのライブラリの操作を当てる(
        &mut ビューアー,
        重ね合わせのライブラリの操作::変更を捨てて続ける,
    );
    assert!(ビューアー.閉じる手順.閉じると決めたか());
    assert_eq!(
        ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない),
        [ウインドウへの指示::閉じる]
    );
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じてよい
    );
}
