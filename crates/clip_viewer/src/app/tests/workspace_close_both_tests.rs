//! アプリを閉じる手順の試験。スタックと重ね合わせの両方が登録していない変更を持つとき、両方の確かめで変更を捨てて続けると決めたときにだけ閉じると決め、
//! 以後は閉じる指示を並べ、閉じる要求を確かめずに通すことを確かめる。参照: _doc/設計/同時再生.md 2-7、_doc/使い方.md 11.3・15.9
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::super::close::ウインドウへの指示;
use super::super::launch_requests::起動の頼みの届き方;
use super::workspace_close_test_support::{
    重ね合わせのライブラリの操作を当てる, 重ね合わせを開いて縦横比を変える,
};
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生しているビューアー, スタックの応答を適用する,
};
use crate::command::{ライブラリの操作, 応答};
use crate::overlay::重ね合わせのライブラリの操作;
use crate::state::閉じる要求への答え;

#[test]
fn スタックと重ね合わせの両方で変更を捨てると決めたときにだけ閉じると決める() {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    重ね合わせを開いて縦横比を変える(&mut ビューアー);
    ビューアー.スタックの作業場を前に出す(Instant::now());
    let _ = ビューアー.閉じる要求を確かめる(Instant::now());
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::ライブラリ(
            ライブラリの操作::変更を捨てて続ける,
        )],
    );
    assert!(!ビューアー.閉じる手順.閉じると決めたか());
    重ね合わせのライブラリの操作を当てる(
        &mut ビューアー,
        重ね合わせのライブラリの操作::変更を捨てて続ける,
    );
    assert!(ビューアー.閉じる手順.閉じると決めたか());
    assert_eq!(
        ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない),
        [ウインドウへの指示::閉じる]
    );
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じてよい
    );
}
