//! 重ね合わせの作業場の入口と、2つの作業場が共有するウインドウの試験。スタックの作業場のヘッダーの「同時再生」の応答で重ね合わせの作業場へ移り、
//! スタックの作業場の値は再生が止まるだけであることと、その応答が操作の適用係へ届いたら到達したらバグとして止まることと、重ね合わせの作業場の F11 がスタックの作業場の値を変えずに全画面の頼みだけを置くことを確かめる。
//! 参照: _doc/設計/同時再生.md 2-1・2-8・3-2

use eframe::egui;

use super::super::close::ウインドウへの指示;
use super::super::launch_requests::起動の頼みの届き方;
use super::launch_requests_test_support::試験のビューアー;
use super::workspace_test_frames::{
    キーを押して適用する, 何も押さずに一フレーム進める
};
use super::workspace_test_snapshot::スタックの作業場の写し;
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生しているビューアー, スタックの応答を適用する,
    前の重ね合わせの作業場,
};
use crate::command::応答;
use crate::state::全画面の様子;

#[test]
fn ヘッダーの同時再生の応答で重ね合わせの作業場へ移り_スタックの作業場の値は再生が止まるだけである()
{
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    // 注意: 応答を適用する手順は、編集の履歴の区切りを毎回そろえる。比べる前に1回通して、区切りの差を写しから除く。
    スタックの応答を適用する(&mut ビューアー, Vec::new());
    let 移る前 = スタックの作業場の写し::写しを取る(&ビューアー);
    スタックの応答を適用する(&mut ビューアー, vec![応答::重ね合わせの作業場へ移る]);
    assert!(前の重ね合わせの作業場(&mut ビューアー).is_some());
    assert!(!ビューアー.状態.再生.再生しているか());
    assert_eq!(スタックの作業場の写し::写しを取る(&ビューアー), 移る前);
}

#[test]
fn 重ね合わせの作業場のf11はスタックの作業場の値を変えずに全画面の頼みを置く() {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    ビューアー.重ね合わせの作業場へ移る();
    何も押さずに一フレーム進める(&mut ビューアー);
    let 移った後 = スタックの作業場の写し::写しを取る(&ビューアー);
    キーを押して適用する(&mut ビューアー, egui::Key::F11, egui::Modifiers::NONE);
    assert_eq!(スタックの作業場の写し::写しを取る(&ビューアー), 移った後);
    assert_eq!(
        ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない),
        [ウインドウへの指示::全画面にする(
            全画面の様子::全画面
        )]
    );
}

#[test]
#[should_panic(expected = "到達したらバグ")]
fn 重ね合わせの作業場へ移る応答は配線が受け取り_操作の適用係へ届いたら止まる() {
    let mut ビューアー = 試験のビューアー();
    ビューアー
        .適用係
        .適用する(&mut ビューアー.状態, 応答::重ね合わせの作業場へ移る);
}
