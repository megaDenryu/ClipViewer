//! 2つの作業場が共有する音量の試験。重ね合わせの作業場の音量のつまみと「全体を消音」が、スタックの作業場の音量のつまみと消音と同じ設定を変え、
//! 重ね合わせへ渡す鳴らす音量に消音を掛けることと、消音中につまみを動かすと消音をやめることを確かめる。参照: _doc/設計/同時再生.md 2-6・3-2

use std::time::Instant;

use audio_pcm::音量;

use super::super::stack_values::今のスタックの値を借りる;
use super::super::workspace_response::作業場の応答;
use super::super::クリップビューアー;
use super::launch_requests_test_support::試験のビューアー;
use crate::command::再生の操作;
use crate::overlay::重ね合わせの作業場の応答;

#[test]
fn 重ね合わせの作業場で音量のつまみを動かすと_スタックの作業場へ戻ったときのつまみが同じ値である() {
    let mut ビューアー = 試験のビューアー();
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    ビューアー.作業場の応答を適用する(
        作業場の応答::重ね合わせの応答(
            重ね合わせの作業場の応答::音量のつまみの値を選ぶ(0.3),
        ),
        Instant::now(),
    );
    ビューアー.作業場の応答を適用する(
        作業場の応答::重ね合わせの応答(
            重ね合わせの作業場の応答::スタックの作業場へ戻る,
        ),
        Instant::now(),
    );
    assert_eq!(
        ビューアー.状態.再生.音量.選んだ音量(),
        音量::範囲へ収めて作る(0.3)
    );
}

/// 重ね合わせの作業場の応答を、画面と同じ経路で配線へ当てる。
fn 重ね合わせの応答を当てる(
    ビューアー: &mut クリップビューアー,
    応答: 重ね合わせの作業場の応答,
) {
    ビューアー
        .作業場の応答を適用する(作業場の応答::重ね合わせの応答(応答), Instant::now());
}

#[test]
fn 全体を消音するとスタックの作業場の消音になり_重ね合わせへ渡す鳴らす音量が無音になる() {
    let mut ビューアー = 試験のビューアー();
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    重ね合わせの応答を当てる(
        &mut ビューアー,
        重ね合わせの作業場の応答::音量のつまみの値を選ぶ(0.4),
    );
    重ね合わせの応答を当てる(
        &mut ビューアー,
        重ね合わせの作業場の応答::全体の消音を切り替える,
    );
    let 全体 = 今のスタックの値を借りる(&ビューアー.状態).全体の音量;
    assert!(全体.消音しているか, "スタックの作業場の消音と同じ設定");
    assert_eq!(
        全体.つまみの値,
        音量::範囲へ収めて作る(0.4),
        "つまみは消す前の値を覚える"
    );
    assert_eq!(
        全体.鳴らす音量,
        音量::無音,
        "重ね合わせの行に掛ける音量は無音"
    );
}

#[test]
fn スタックの作業場で消音しても重ね合わせの鳴らす音量は無音になり_消音中につまみを動かすと消音をやめる()
 {
    let mut ビューアー = 試験のビューアー();
    ビューアー
        .状態
        .再生の操作を適用する(再生の操作::消音を切り替える);
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    assert_eq!(
        今のスタックの値を借りる(&ビューアー.状態)
            .全体の音量
            .鳴らす音量,
        音量::無音
    );
    重ね合わせの応答を当てる(
        &mut ビューアー,
        重ね合わせの作業場の応答::音量のつまみの値を選ぶ(0.3),
    );
    let 全体 = 今のスタックの値を借りる(&ビューアー.状態).全体の音量;
    assert!(
        !全体.消音しているか,
        "消音中につまみを動かすと消音をやめる(説明書 6.6節)"
    );
    assert_eq!(全体.鳴らす音量, 音量::範囲へ収めて作る(0.3));
}
