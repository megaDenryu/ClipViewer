//! アプリを閉じる手順が作業場の決めを待っている間の試験。待っている間に届いた起動の頼み(動画を開く)は断って作業場を移さないことと、
//! 手順を捨てたときに、もう一方の作業場に残っていた「アプリを閉じる」の確かめるダイアログも閉じることを確かめる。
//! 参照: _doc/設計/同時再生.md 2-7・2-8
#![allow(clippy::expect_used)]

use std::ffi::OsString;
use std::time::Instant;

use eframe::egui;

use super::super::close_procedure::{アプリを閉じる手順, スタックの決め方};
use super::launch_requests_test_support::通知の文;
use super::workspace_close_test_support::{
    スタックが閉じる前の確かめを出しているか, 重ね合わせの決めを待つまで進めたビューアー,
};
use super::workspace_test_support::スタックの応答を適用する;
use crate::command::{ライブラリの操作, 応答};
use crate::launch::起動の頼み;
use crate::state::閉じる要求への答え;

#[test]
fn 重ね合わせの決めを待っている間に届いた動画は開かずに断り_重ね合わせの作業場を前に出したままにする()
 {
    let mut ビューアー = 重ね合わせの決めを待つまで進めたビューアー();
    let 待っている手順 = アプリを閉じる手順::重ね合わせの決めを待つ(
        スタックの決め方::利用者が閉じてよいと決めた,
    );
    assert_eq!(ビューアー.閉じる手順, 待っている手順);
    let 並びの数 = ビューアー.状態.並び.一覧().len();
    ビューアー.起動の受け口で受け取り始めて頼みを当てる(
        None,
        egui::Context::default(),
        起動の頼み::引数から読む([OsString::from(r"C:\届いた.mp4")]),
        Vec::new(),
    );
    let 文面 = 通知の文(&ビューアー);
    assert!(文面.contains("開いているダイアログを閉じてから"), "{文面}");
    assert!(
        !文面.contains("FFmpeg が見つからない"),
        "開こうとしない: {文面}"
    );
    assert_eq!(
        ビューアー.状態.並び.一覧().len(),
        並びの数,
        "並びを捨てない"
    );
    assert!(!スタックが閉じる前の確かめを出しているか(&ビューアー));
    assert_eq!(ビューアー.閉じる手順, 待っている手順);
}

#[test]
fn 手順を捨てたら_もう一方の作業場に残っていたアプリを閉じる確かめのダイアログも閉じる() {
    let mut ビューアー = 重ね合わせの決めを待つまで進めたビューアー();
    ビューアー.スタックの作業場を前に出す(Instant::now());
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(スタックが閉じる前の確かめを出しているか(
        &ビューアー
    ));
    スタックの応答を適用する(
        &mut ビューアー,
        vec![応答::ライブラリ(
            ライブラリの操作::ダイアログを閉じる,
        )],
    );
    assert_eq!(
        ビューアー.閉じる手順,
        アプリを閉じる手順::閉じようとしていない
    );
    let 重ね合わせ = ビューアー
        .前に出ている作業場
        .重ね合わせの作業場を書き換える()
        .expect("重ね合わせの作業場を作ってある");
    assert!(!重ね合わせ.アプリを閉じる前の確かめを出しているか());
}
