//! ウインドウへの指示の並びの試験。閉じる要求への答えと、変更を捨てて閉じると決めたかと、起動の頼みが届いたかと、全画面の頼みから、
//! 起動の部分がウインドウへ送る指示の並びを決める。

use super::super::close::ウインドウへの指示;
use super::super::launch_requests::起動の頼みの届き方::{届いた, 届いていない};
use crate::state::{ウインドウへの頼み, 全画面の様子, 閉じる要求への答え};
use crate::viewer_settings::ウインドウの大きさ;

fn 頼み無し() -> ウインドウへの頼み {
    ウインドウへの頼み::default()
}

fn 全画面の頼み(様子: 全画面の様子) -> ウインドウへの頼み {
    ウインドウへの頼み {
        全画面: Some(様子),
        大きさ: None,
    }
}

#[test]
fn 要求を受けなければ何も送らない() {
    assert!(ウインドウへの指示::並びを決める(None, false, 届いていない, 頼み無し()).is_empty());
}

#[test]
fn 閉じてよいと答えたら何も送らず_ウインドウはそのまま閉じる() {
    let 答え = Some(閉じる要求への答え::閉じてよい);
    assert!(ウインドウへの指示::並びを決める(答え, false, 届いていない, 頼み無し()).is_empty());
}

#[test]
fn 閉じるのをやめると答えたら要求を取り消す() {
    let 答え = Some(閉じる要求への答え::閉じるのをやめる);
    assert_eq!(
        ウインドウへの指示::並びを決める(答え, false, 届いていない, 頼み無し()),
        [ウインドウへの指示::閉じるのを取り消す]
    );
}

#[test]
fn 変更を捨てて閉じると決めたら閉じる指示だけを送る() {
    assert_eq!(
        ウインドウへの指示::並びを決める(
            None,
            true,
            届いた,
            全画面の頼み(全画面の様子::全画面)
        ),
        [ウインドウへの指示::閉じる]
    );
}

#[test]
fn 起動の頼みが届いたら前に出す() {
    assert_eq!(
        ウインドウへの指示::並びを決める(None, false, 届いた, 頼み無し()),
        [ウインドウへの指示::前に出す]
    );
    assert_eq!(
        ウインドウへの指示::並びを決める(
            Some(閉じる要求への答え::閉じてよい),
            false,
            届いた,
            頼み無し()
        ),
        [ウインドウへの指示::前に出す]
    );
}

#[test]
fn 同じフレームの指示は_取り消し_全画面_大きさ_前に出すの順に全部送る() {
    let 答え = Some(閉じる要求への答え::閉じるのをやめる);
    let 頼み = ウインドウへの頼み {
        全画面: Some(全画面の様子::全画面でない),
        大きさ: Some(ウインドウの大きさ::最初),
    };
    assert_eq!(
        ウインドウへの指示::並びを決める(答え, false, 届いた, 頼み),
        [
            ウインドウへの指示::閉じるのを取り消す,
            ウインドウへの指示::全画面にする(全画面の様子::全画面でない),
            ウインドウへの指示::大きさを変える(ウインドウの大きさ::最初),
            ウインドウへの指示::前に出す,
        ]
    );
}
