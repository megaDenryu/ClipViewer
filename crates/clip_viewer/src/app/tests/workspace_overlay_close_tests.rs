/// 重ね合わせの作業場へ移り、五秒の重ね合わせを開いて、縦横比を正方形に変える(置き方を手で直す)。
pub(in crate::app) fn 重ね合わせを開いて縦横比を変える(
    ビューアー: &mut クリップビューアー,
) {
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    let 作業場 = 前の重ね合わせの作業場(ビューアー).expect("重ね合わせが前");
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    let 正方形 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    作業場.操作を適用する(重ね合わせの操作::置き方(
        置き方の操作::重ねる画面の縦横比を選ぶ(正方形),
    ));
}

fn 指示の並び(
    ビューアー: &mut クリップビューアー
) -> Vec<ウインドウへの指示> {
    ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない)
}

#[test]
fn 重ね合わせだけが登録していない変更を持つとき_閉じる要求で重ね合わせを前に出して確かめ_捨てると閉じる指示を毎フレーム並べる()
 {
    let mut ビューアー = 試験のビューアー();
    重ね合わせを開いて縦横比を変える(&mut ビューアー);
    ビューアー.スタックの作業場を前に出す(Instant::now());
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じるのをやめる
    );
    assert!(ビューアー.前に出ている作業場.重ね合わせが前か());
    assert!(指示の並び(&mut ビューアー).is_empty());
    ビューアー.応答を適用する(
        vec![作業場の応答::重ね合わせの応答(
            重ね合わせの作業場の応答::ライブラリ(
                重ね合わせのライブラリの操作::変更を捨てて続ける,
            ),
        )],
        主ボタンの様子::押していない,
        Instant::now(),
    );
    assert_eq!(指示の並び(&mut ビューアー), [ウインドウへの指示::閉じる]);
    assert_eq!(
        指示の並び(&mut ビューアー),
        [ウインドウへの指示::閉じる],
        "閉じると決めた後は毎フレーム並べる"
    );
    assert_eq!(
        ビューアー.閉じる要求を確かめる(Instant::now()),
        閉じる要求への答え::閉じてよい
    );
}

#[test]
fn アプリを落とすときに登録済みの重ね合わせの書けていない変更を保存する() {
    let 一時 = 一時のライブラリ::作る("落とすときの保存");
    let 組 = 一時.錠を試す();
    let mut ビューアー = 試験のビューアー();
    ビューアー
        .前に出ている作業場
        .重ね合わせのライブラリを持たせる(
            裏で動く重ね合わせのライブラリ::錠を試した後で起動する(
                組.重ね合わせ,
            ),
        );
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    let 作業場 = 前の重ね合わせの作業場(&mut ビューアー).expect("重ね合わせが前");
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    名前を付けて登録する(作業場, "ふたり");
    書き終えるまで待って進める(作業場, Instant::now());
    let 正方形 = 重ねる画面の縦横比::作成する(アスペクト比設定::正方形).expect("固定の比");
    作業場.操作を適用する(重ね合わせの操作::置き方(
        置き方の操作::重ねる画面の縦横比を選ぶ(正方形),
    ));
    drop(ビューアー);
    assert_eq!(一時.保存した重ね合わせ()[0].重ね合わせ().縦横比(), 正方形);
    drop(組.スタック);
}
