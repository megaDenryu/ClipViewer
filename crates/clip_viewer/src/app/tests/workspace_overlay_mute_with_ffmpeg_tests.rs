//! 全体の消音の結合試験。スタックの作業場で音付きの動画を開いて「同時再生」から並べて再生し、2本目の流れへ渡した行の指示の音量が、
//! スタックの作業場で消音すると0になることを、配線の経路(重ね合わせの側が全体の鳴らす音量を選んで渡すこと)を一続きに通して確かめる。
//! 2本目の流れは渡した指示を覚える受け口に差し替え、装置は開かない。FFmpeg が要るため `#[ignore]` にしてある。
