/// 最後に渡された行ごとの指示の、奥の行の指示。まだ渡されていなければ無い。
fn 最後の奥の行の指示(
    控え: &渡した指示の控え<行ごとの再生の指示>,
) -> Option<再生の指示> {
    let mut 最後 = 控え.渡された指示の並び().pop()?;
    最後
        .行の指示を置き換える(
            行の番号::番号から作成する(0),
            再生の指示::黙る(Instant::now()),
        )
        .ok()
}

fn 当てる(
    ビューアー: &mut super::super::クリップビューアー, 応答一覧: Vec<作業場の応答>
) {
    let _ =
        ビューアー.応答を適用する(応答一覧, 主ボタンの様子::押していない, Instant::now());
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn スタックの作業場で消音すると_重ね合わせの行へ渡す音量が0になる() {
    let 実行ファイル = 実行ファイルを探す();
    let フォルダ = 実行ファイル
        .変換のパス()
        .parent()
        .expect("フォルダ")
        .to_path_buf();
    let 二本目 = 渡した指示の控え::<行ごとの再生の指示>::空();
    let mut ビューアー = 試験のビューアーを二本目の流れの手立てで作る(
        Box::new(控えへ開く(二本目.clone())),
    );
    ビューアー.状態.ffmpegの状況 =
        ビューアー
            .適用係
            .ffmpegを探す(&FFmpegの置き場所の設定::設定済み(
                FFmpegを置いたフォルダ::作成する(フォルダ),
            ));
    let 動画 = 音付きの試験動画::作る("全体の消音");
    ビューアー.適用係.確かめてから動画を開く(
        &mut ビューアー.状態,
        &入力された動画パス::作成する(動画.0.文字列().to_string()),
        開いたときの添え書き::無し,
    );
    let mut クリップ = クリップ::既定値で作成する(
        クリップ識別子::文字列から作成する("甲".to_string()).expect("識別子"),
        クリップ名::作成する("甲".to_string()),
    );
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    クリップ.区間 = 動画上の区間::作成する(秒(0.5), 秒(1.5)).expect("区間");
    let 並び = クリップスタック::一覧から作成する(vec![クリップ]).expect("スタック");
    ビューアー
        .状態
        .並びを置き換える(並び, 並びの出どころ::新しく作った);
    当てる(
        &mut ビューアー,
        vec![作業場の応答::スタックの応答(
            応答::重ね合わせの作業場へ移る,
        )],
    );
    当てる(
        &mut ビューアー,
        vec![
            作業場の応答::重ね合わせの応答(
                重ね合わせの作業場の応答::今のスタックから並べる,
            ),
            作業場の応答::重ね合わせの応答(重ね合わせの作業場の応答::操作(
                重ね合わせの操作::再生を切り替える,
            )),
        ],
    );
    let 期限 = Instant::now() + Duration::from_secs(20);
    let 鳴らしている = loop {
        ビューアー.フレームを進める(Instant::now());
        let 奥 = 最後の奥の行の指示(&二本目).filter(|指示| 指示.区間.is_some());
        if 奥.is_some() || Instant::now() > 期限 {
            break 奥.expect("奥の行の音の区間を渡す");
        }
        std::thread::sleep(Duration::from_millis(20));
    };
    let 鳴らす音量 = ビューアー.状態.再生.音量.鳴らす音量();
    assert_ne!(鳴らす音量, 音量::無音, "試験の前提: 消音していない");
    assert_eq!(
        鳴らしている.音量, 鳴らす音量,
        "置いたクリップの音量1に全体の鳴らす音量を掛ける"
    );
    ビューアー
        .状態
        .再生の操作を適用する(再生の操作::消音を切り替える);
    ビューアー.フレームを進める(Instant::now());
    let 消した後 = 最後の奥の行の指示(&二本目).expect("渡した");
    assert_eq!(
        消した後.音量,
        音量::無音,
        "スタックの作業場の消音(M キーと同じ操作)で行の音量は0になる"
    );
}
