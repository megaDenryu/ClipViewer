//! 作業場の FFmpeg の結合試験の道具。クリップビューアーに FFmpeg を見つけさせてスタックの作業場で動画を開くことと、区間を決めたクリップを作ること。
#![allow(clippy::expect_used)]

use clip_domain::{
    クリップ, クリップ名, クリップ識別子, 入力された動画パス, 動画上の区間, 時刻,
    正規化した動画パス,
};
use video_source::{FFmpegの置き場所の設定, FFmpegを置いたフォルダ};

use super::super::クリップビューアー;
use crate::state::library::開いたときの添え書き;
use crate::video_feed::with_ffmpeg_support::実行ファイルを探す;

/// クリップビューアーに、試験の FFmpeg を置いたフォルダを探させ、スタックの作業場でその動画を開かせる。
pub(in crate::app) fn 試験のffmpegを見つけて動画を開く(
    ビューアー: &mut クリップビューアー,
    動画: &正規化した動画パス,
) {
    let 実行ファイル = 実行ファイルを探す();
    let フォルダ = 実行ファイル
        .変換のパス()
        .parent()
        .expect("フォルダ")
        .to_path_buf();
    ビューアー.状態.ffmpegの状況 =
        ビューアー
            .適用係
            .ffmpegを探す(&FFmpegの置き場所の設定::設定済み(
                FFmpegを置いたフォルダ::作成する(フォルダ),
            ));
    ビューアー.適用係.確かめてから動画を開く(
        &mut ビューアー.状態,
        &入力された動画パス::作成する(動画.文字列().to_string()),
        開いたときの添え書き::無し,
    );
}

/// 名前のクリップを、区間を開始から終了(動画上の秒)にして作る。
pub(in crate::app) fn 区間を決めたクリップを作る(
    名前: &str,
    開始: f64,
    終了: f64,
) -> クリップ {
    let mut クリップ = クリップ::既定値で作成する(
        クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子"),
        クリップ名::作成する(名前.to_string()),
    );
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    クリップ.区間 = 動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間");
    クリップ
}
