//! 配線が重ね合わせの作業場の知らせへ出すものの試験。作業場を移る前に頼んだスタックの保存の失敗を重ね合わせの作業場の知らせに一度だけ写すことと、
//! 動画を開いていないときに「今のスタックから並べる」が重ね合わせを開かずに知らせることを確かめる。参照: _doc/設計/同時再生.md 2-2・2-8
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use clip_domain::{
    スタックの名前, スタックの識別子, ライブラリのスタック, ライブラリの日時, 入力された動画パス,
};

use super::super::workspace_response::作業場の応答;
use super::super::クリップビューアー;
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生しているビューアー, 前の重ね合わせの作業場,
};
use crate::command::主ボタンの様子;
use crate::overlay::重ね合わせの作業場の応答;
use crate::state::library::{
    ライブラリを使えない理由, 登録済みのスタック, 開いているスタック
};

fn 重ね合わせの知らせの文(
    ビューアー: &mut クリップビューアー
) -> Vec<String> {
    前の重ね合わせの作業場(ビューアー)
        .expect("重ね合わせが前")
        .状態()
        .並べる知らせ()
        .iter()
        .map(|通知| format!("{通知:?}"))
        .collect()
}

#[test]
fn 重ね合わせが前の間に失敗したスタックの保存は_重ね合わせの作業場の知らせに一度だけ写す() {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    let mut 登録済み =
        登録済みのスタック::ファイルから開いた(ライブラリのスタック::新しく作る(
            スタックの識別子::文字列から作成する("stack-1-1".to_string()).expect("識別子"),
            スタックの名前::作成する("練習".to_string()).expect("名前"),
            入力された動画パス::作成する(r"C:\練習.mp4".to_string()).正規化する(),
            ビューアー.状態.並び.clone(),
            ライブラリの日時::紀元からのミリ秒で作成する(1_000).expect("日時"),
        ));
    登録済み.保存を頼めなかった(ライブラリを使えない理由::置き場所が無い);
    ビューアー.状態.ライブラリ.開いている = 開いているスタック::登録済み(登録済み);
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    let 始め = Instant::now();
    for 秒 in 0..3 {
        ビューアー.フレームを進める(始め + Duration::from_secs(秒));
    }
    let 知らせ = 重ね合わせの知らせの文(&mut ビューアー);
    assert_eq!(知らせ.len(), 2, "{知らせ:?}");
    assert!(
        知らせ[0].contains(
            "音声出力装置が見つからない。重ね合わせの作業場は音を鳴らさずに映像だけで再生する"
        ),
        "初めて移ったときの知らせ: {知らせ:?}"
    );
    assert!(
        知らせ[1].contains(&format!(
            "スタックをライブラリへ保存できない: {}",
            ライブラリを使えない理由::置き場所が無い
        )),
        "{知らせ:?}"
    );
}

#[test]
fn 動画を開いていないときの今のスタックから並べるは_重ね合わせを開かずに知らせる() {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    let _ = ビューアー.応答を適用する(
        vec![作業場の応答::重ね合わせの応答(
            重ね合わせの作業場の応答::今のスタックから並べる,
        )],
        主ボタンの様子::押していない,
        Instant::now(),
    );
    let 知らせ = 重ね合わせの知らせの文(&mut ビューアー);
    assert!(
        前の重ね合わせの作業場(&mut ビューアー)
            .expect("重ね合わせが前")
            .状態()
            .開いている重ね合わせ()
            .is_none()
    );
    assert_eq!(知らせ.len(), 2, "{知らせ:?}");
    assert!(
        知らせ[0].contains(
            "音声出力装置が見つからない。重ね合わせの作業場は音を鳴らさずに映像だけで再生する"
        ),
        "初めて移ったときの知らせ: {知らせ:?}"
    );
    assert!(
        知らせ[1].contains("動画を開いていないため、並べられない"),
        "{知らせ:?}"
    );
}
