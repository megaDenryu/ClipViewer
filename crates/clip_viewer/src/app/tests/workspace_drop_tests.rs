//! 重ね合わせが前のときに落としたファイルの試験。ファイルを開かず、重ね合わせの作業場の知らせで「スタックへ戻ってから落とす」と知らせ、
//! スタックの作業場の値(通知を含む)を変えないことを確かめる。参照: _doc/設計/同時再生.md 2-8
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::workspace_test_frames::{
    ファイルを落として一フレーム進める, 何も押さずに一フレーム進める,
};
use super::workspace_test_snapshot::スタックの作業場の写し;
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生しているビューアー, 前の重ね合わせの作業場,
};
use crate::overlay::落とされたファイルの知らせ;

#[test]
fn 重ね合わせが前のときに落としたファイルは開かず_重ね合わせの作業場で知らせて_スタックの作業場は変わらない()
 {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    ビューアー.重ね合わせの作業場へ移る(Instant::now());
    何も押さずに一フレーム進める(&mut ビューアー);
    let 落とす前 = スタックの作業場の写し::写しを取る(&ビューアー);
    ファイルを落として一フレーム進める(&mut ビューアー, r"C:\落とした.mp4".into());
    assert_eq!(スタックの作業場の写し::写しを取る(&ビューアー), 落とす前);
    let 作業場 = 前の重ね合わせの作業場(&mut ビューアー).expect("重ね合わせが前");
    let 知らせ = format!("{:?}", 作業場.状態().並べる知らせ());
    assert_eq!(
        作業場.状態().並べる知らせ().len(),
        2,
        "初めて移ったときの2本目の流れを開けなかった知らせと、落としたファイルの知らせ"
    );
    assert!(知らせ.contains(
        "音声出力装置が見つからない。重ね合わせの作業場は音を鳴らさずに映像だけで再生する"
    ));
    assert!(知らせ.contains(落とされたファイルの知らせ));
}
