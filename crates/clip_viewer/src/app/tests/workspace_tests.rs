//! 作業場を移すことの試験。回帰試験(a)(作業場を行き来してもスタックの作業場の値が変わらず、再生は止まるだけであること)と、
//! 重ね合わせの作業場を控えて同じ再生の位置で出し直すことと、重ね合わせの作業場の中の操作を前に出ているときだけ当てることを確かめる。
//! 参照: _doc/設計/同時再生.md 3-2
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use super::super::launch_requests::起動の頼みの届き方;
use super::super::workspace_response::作業場の応答;
use super::super::クリップビューアー;
use super::workspace_test_snapshot::スタックの作業場の写し;
use super::workspace_test_support::{
    スタックの作業場の値を既定から変えて再生しているビューアー, 前の重ね合わせの作業場,
};
use crate::command::主ボタンの様子;
use crate::overlay::test_support::五秒の重ね合わせ;
use crate::overlay::{重ね合わせの作業場の応答, 重ね合わせの操作};
use clip_domain::音量;

fn 重ね合わせの応答を適用する(
    ビューアー: &mut クリップビューアー,
    応答: 重ね合わせの作業場の応答,
) {
    let _ = ビューアー.応答を適用する(
        vec![作業場の応答::重ね合わせの応答(応答)],
        主ボタンの様子::押していない,
    );
}

#[test]
fn 回帰試験a_作業場を行き来してもスタックの作業場の値は変わらず_再生は止まるだけである() {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    assert!(ビューアー.状態.再生.再生しているか());
    let 移る前 = スタックの作業場の写し::写しを取る(&ビューアー);
    let 行き来しない指示 =
        ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない);

    ビューアー.重ね合わせの作業場へ移る();
    assert!(前の重ね合わせの作業場(&mut ビューアー).is_some());
    ビューアー.フレームを進める(Instant::now());
    重ね合わせの応答を適用する(
        &mut ビューアー,
        重ね合わせの作業場の応答::スタックの作業場へ戻る,
    );
    assert!(前の重ね合わせの作業場(&mut ビューアー).is_none());
    ビューアー.フレームを進める(Instant::now());

    assert!(!ビューアー.状態.再生.再生しているか());
    assert_eq!(スタックの作業場の写し::写しを取る(&ビューアー), 移る前);
    assert_eq!(
        ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない),
        行き来しない指示
    );
}

#[test]
fn 重ね合わせの作業場は控えておき_再び移ると同じ重ね合わせを同じ再生の位置で止まって出す() {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    ビューアー.重ね合わせの作業場へ移る();
    let 作業場 = 前の重ね合わせの作業場(&mut ビューアー).expect("重ね合わせが前");
    作業場.重ね合わせを開く(五秒の重ね合わせ(), None);
    重ね合わせの応答を適用する(
        &mut ビューアー,
        重ね合わせの作業場の応答::操作(重ね合わせの操作::再生を切り替える),
    );
    let 始め = Instant::now();
    let 作業場 = 前の重ね合わせの作業場(&mut ビューアー).expect("重ね合わせが前");
    作業場.フレームを進める(始め, 音量::起動したときの音量);
    作業場.フレームを進める(始め + Duration::from_secs(2), 音量::起動したときの音量);
    assert!(作業場.状態().再生しているか());
    let 控える前の位置と長さ = 作業場.状態().再生の位置と長さ();

    ビューアー.スタックの作業場を前に出す();
    let 控えた = ビューアー
        .前に出ている作業場
        .控えた重ね合わせ()
        .expect("重ね合わせの作業場を控えているはず");
    assert!(!控えた.作業場().状態().再生しているか());

    ビューアー.重ね合わせの作業場へ移る();
    let 作業場 = 前の重ね合わせの作業場(&mut ビューアー).expect("重ね合わせが前");
    assert!(!作業場.状態().再生しているか());
    assert_eq!(作業場.状態().再生の位置と長さ(), 控える前の位置と長さ);
}

#[test]
fn 重ね合わせの作業場の中の操作はスタックの作業場が前のときに届いても当てず_重ね合わせの作業場を作らない()
 {
    let mut ビューアー =
        スタックの作業場の値を既定から変えて再生しているビューアー();
    重ね合わせの応答を適用する(
        &mut ビューアー,
        重ね合わせの作業場の応答::操作(重ね合わせの操作::再生を切り替える),
    );
    assert!(!ビューアー.前に出ている作業場.重ね合わせが前か());
    assert!(ビューアー.前に出ている作業場.控えた重ね合わせ().is_none());
}
