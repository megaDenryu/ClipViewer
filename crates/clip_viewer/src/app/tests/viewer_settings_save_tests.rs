//! 見る側の設定の保存係の試験。書く係は変えてから落ち着いたときと終わる前に settings.json へ書き、書かない係(読み取り専用で起動したアプリ)は書かない。
//! 一時フォルダを置き場所にし、%APPDATA% の本物のフォルダを使わない。
#![allow(clippy::expect_used)]

use std::path::PathBuf;
use std::time::Instant;

use super::super::settings_watch::落ち着くまでの時間;
use super::super::viewer_settings_save::{見る側の設定の保存係, 設定の書き方};
use super::launch_requests_test_support::試験のビューアー;
use crate::command::再生の操作;
use crate::persistence::アプリの設定の保管場所;
use crate::viewer_settings::見る側の設定;

/// 試験ごとに重ならない一時フォルダの保管場所と、その settings.json のパス。前の実行の残りを消してから使う。
fn 一時の保管場所(名前: &str) -> (アプリの設定の保管場所, PathBuf, PathBuf) {
    let 一時フォルダ = std::env::temp_dir().join(format!(
        "clip_viewer_見る側の保存_{名前}_{}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&一時フォルダ);
    let 保管場所 =
        アプリの設定の保管場所::アプリのデータのフォルダから決める(
            Some(一時フォルダ.clone()),
        );
    let パス = 一時フォルダ.join("ClipViewer").join("settings.json");
    (保管場所, パス, 一時フォルダ)
}

#[test]
fn 書く係は変えてから落ち着いたら書き_書かない係は書かない() {
    for (名前, 書き方) in [
        ("書く", 設定の書き方::書く),
        ("書かない", 設定の書き方::書かない),
    ] {
        let (保管場所, パス, 一時フォルダ) = 一時の保管場所(名前);
        let mut 係 = 見る側の設定の保存係::作成する(
            保管場所.clone(),
            書き方,
            見る側の設定::既定,
        );
        let mut ビューアー = 試験のビューアー();
        let 状態 = &mut ビューアー.状態;
        状態.再生の操作を適用する(再生の操作::音量を選ぶ(0.8));
        let 始め = Instant::now();
        係.進める(状態, 始め);
        assert!(!パス.exists(), "落ち着く前は書かない");
        係.進める(状態, 始め + 落ち着くまでの時間);
        match 書き方 {
            設定の書き方::書く => {
                let 読んだ = 保管場所.見る側の設定を読む().expect("読める");
                assert_eq!(読んだ.音量, 状態.見る側の設定().音量);
            }
            設定の書き方::書かない => {
                assert!(!パス.exists(), "読み取り専用のアプリは書かない")
            }
        }
        let _ = std::fs::remove_dir_all(一時フォルダ);
    }
}

#[test]
fn 終わる前は落ち着くのを待たずに書く() {
    let (保管場所, _, 一時フォルダ) = 一時の保管場所("終わる前");
    let mut 係 = 見る側の設定の保存係::作成する(
        保管場所.clone(),
        設定の書き方::書く,
        見る側の設定::既定,
    );
    let mut ビューアー = 試験のビューアー();
    ビューアー
        .状態
        .再生の操作を適用する(再生の操作::速度を選ぶ(1.5));
    係.終わる前に書く(&mut ビューアー.状態);
    let 読んだ = 保管場所.見る側の設定を読む().expect("読める");
    assert_eq!(読んだ.速度.倍率(), 1.5);
    let _ = std::fs::remove_dir_all(一時フォルダ);
}

#[test]
fn 起動したときの状態の見る側の設定は既定と同じで_当てた設定はそのまま組み直せる() {
    let mut ビューアー = 試験のビューアー();
    assert_eq!(ビューアー.状態.見る側の設定(), 見る側の設定::既定);
    let 当てる設定 = 見る側の設定 {
        音量: crate::state::音量::範囲へ収めて作る(0.1),
        左右: crate::viewer_settings::左右の向き::反転,
        表示サイズ: crate::viewer_settings::表示サイズ::標準,
        ..見る側の設定::既定
    };
    ビューアー.状態.見る側の設定を当てる(当てる設定);
    assert_eq!(ビューアー.状態.見る側の設定(), 当てる設定);
}

#[test]
fn 書く係は変わりかけの間に保存するまでの時間を状態へ置き_書いたら消す() {
    let (保管場所, _, 一時フォルダ) = 一時の保管場所("残り時間");
    let mut 係 = 見る側の設定の保存係::作成する(
        保管場所,
        設定の書き方::書く,
        見る側の設定::既定,
    );
    let mut ビューアー = 試験のビューアー();
    ビューアー
        .状態
        .再生の操作を適用する(再生の操作::音量を選ぶ(0.8));
    let 始め = Instant::now();
    係.進める(&mut ビューアー.状態, 始め);
    assert_eq!(
        ビューアー.状態.見る側の設定を保存するまでの時間,
        Some(落ち着くまでの時間)
    );
    係.進める(&mut ビューアー.状態, 始め + 落ち着くまでの時間);
    assert_eq!(ビューアー.状態.見る側の設定を保存するまでの時間, None);
    let _ = std::fs::remove_dir_all(一時フォルダ);
}
