//! 起動の決着と起動の準備。起動の手順(`launch_plan.rs`)が決めた結果であり、起動の部分(main.rs)が窓を作るかを選び、
//! 組み立て(`assemble.rs`)が準備からクリップビューアーを組み立てる。参照: _doc/設計/画面.md 判断13

use clip_library::錠を試したライブラリ;

use super::environment::起動時の環境;
use crate::launch::{起動の受け口, 起動の頼み};
use crate::persistence::アプリの設定の保管場所;
use crate::viewer_settings::{窓の記憶, 見る側の設定};

/// 起動の決着とは、起動の手順を決めた結果の区別のことである。
pub(crate) enum 起動の決着 {
    /// 頼みを1つ目のアプリへ渡し終えた。このアプリは窓を作らずに終わる。
    一つ目へ渡した,
    /// 窓を作って起動する。準備は大きく、起動に1回だけ作るため箱に入れて列挙の大きさを揃える。
    起動する(Box<起動の準備>),
}

/// 起動の準備とは、窓を作って組み立てるときに使う、起動時の環境・settings.json から読んだ見る側の設定・アプリの設定の保管場所・錠を試したライブラリ(置き場所が無ければ無い)・
/// 開いた起動の受け口(1つ目でなければ無い)・起動の頼み・起動の途中で利用者へ知らせる文の組のことである。
pub(crate) struct 起動の準備 {
    pub(super) 環境: 起動時の環境,
    pub(super) 見る側: 見る側の設定,
    pub(super) 保管場所: アプリの設定の保管場所,
    pub(super) ライブラリ: Option<錠を試したライブラリ>,
    pub(super) 受け口: Option<起動の受け口>,
    pub(super) 頼み: 起動の頼み,
    pub(super) 知らせ: Vec<String>,
}

impl 起動の準備 {
    /// 窓を作るときの大きさと最大化。settings.json が覚えていなければ最初の大きさである。
    pub(crate) fn 窓の記憶(&self) -> 窓の記憶 {
        self.見る側.窓
    }

    /// ライブラリの錠を持つ(1つ目の)アプリか。受け渡しに失敗して読み取り専用で起動したアプリと、錠を試せなかった
    /// (ライブラリの置き場所が無い)アプリは持たない。警告の記録は、錠を持つアプリだけが取り付ける。
    pub(crate) fn ライブラリの錠を持つか(&self) -> bool {
        self.ライブラリ
            .as_ref()
            .is_some_and(錠を試したライブラリ::書けるか)
    }
}
