//! 起動の手順。窓を作る前に、ライブラリの錠を試して1つ目のアプリかを決める。1つ目なら起動の受け口を開き、
//! 2つ目なら開きたい動画(無ければ前に出ること)を1つ目へ渡して終わる。期限までに渡せなければ錠を取り直し、
//! 取れなければ読み取り専用で普通に起動する。参照: _doc/設計/画面.md 判断13

use std::time::Duration;

use clip_library::{スタックのライブラリ, 錠を試したライブラリ};

use super::environment::起動時の環境;
use super::launch_preparation::{起動の決着, 起動の準備};
use crate::launch::{
    受け口の案内ファイル, 起動の受け口, 起動の頼み, 起動の頼みの送り手
};
use crate::persistence::アプリの設定の保管場所;
use crate::viewer_settings::見る側の設定;

/// 2つ目のアプリが1つ目のアプリへ頼みを渡し終えるまで待つ期限。1つ目が固まっていても、2つ目がこれより長く待たないようにする。
const 渡す期限: Duration = Duration::from_secs(3);

/// 起動の手順とは、起動時の環境と、そこから決めたアプリの設定の保管場所と、起動の引数から読んだ頼みの組のことである。
pub(crate) struct 起動の手順 {
    環境: 起動時の環境,
    保管場所: アプリの設定の保管場所,
    頼み: 起動の頼み,
}

impl 起動の手順 {
    pub(crate) fn 作成する(環境: 起動時の環境) -> Self {
        Self {
            保管場所: アプリの設定の保管場所::アプリのデータのフォルダから決める(
                環境.アプリのデータのフォルダ.clone(),
            ),
            頼み: 起動の頼み::引数から読む(環境.起動の引数.iter().cloned()),
            環境,
        }
    }

    /// 錠を試し、別のアプリが持っていれば頼みを渡しに行く。それ以外は普通に起動する準備をする。
    pub(crate) fn 決める(self) -> 起動の決着 {
        let ライブラリ = self
            .保管場所
            .ライブラリのフォルダ()
            .map(|フォルダ| スタックのライブラリ::作成する(フォルダ).錠を試す());
        let 案内ファイル = self.保管場所.起動の受け口の案内ファイル();
        match (ライブラリ, 案内ファイル) {
            (Some(試した), Some(案内ファイル)) if 試した.別のアプリが持っているか() => {
                self.一つ目へ渡す(試した, 案内ファイル)
            }
            (ライブラリ, 案内ファイル) => {
                self.起動する(ライブラリ, 案内ファイル, Vec::new())
            }
        }
    }

    /// 頼みを1つ目へ渡す。渡せなければ錠を取り直して起動する(1つ目が落ちた直後なら1つ目になり、生きていれば読み取り専用になる)。
    fn 一つ目へ渡す(
        self,
        試した: 錠を試したライブラリ,
        案内ファイル: 受け口の案内ファイル,
    ) -> 起動の決着 {
        let 送り手 = 起動の頼みの送り手::作成する(案内ファイル.clone(), 渡す期限);
        let 理由 = match 送り手.送る(&self.頼み) {
            Ok(()) => return 起動の決着::一つ目へ渡した,
            Err(理由) => 理由,
        };
        let 試した = 試した.錠を取り直す();
        let mut 知らせ = Vec::new();
        if !試した.書けるか() {
            知らせ.push(format!(
                "起動中の ClipViewer へ動画を渡せなかったため、ライブラリを読み取り専用で開いた({理由})"
            ));
        }
        self.起動する(Some(試した), Some(案内ファイル), 知らせ)
    }

    /// 錠を取れていれば起動の受け口を開き、起動の準備をまとめる。受け口を開けなくても起動は止めず、知らせに足す。
    fn 起動する(
        self,
        ライブラリ: Option<錠を試したライブラリ>,
        案内ファイル: Option<受け口の案内ファイル>,
        mut 知らせ: Vec<String>,
    ) -> 起動の決着 {
        let 受け口 = match 案内ファイル
            .filter(|_| {
                ライブラリ
                    .as_ref()
                    .is_some_and(錠を試したライブラリ::書けるか)
            })
            .map(|案内| 起動の受け口::開く(&案内))
        {
            Some(Ok(受け口)) => Some(受け口),
            Some(Err(原因)) => {
                知らせ.push(format!(
                    "起動の受け口を開けない(エクスプローラーから開いた動画を、起動中のこのアプリへ渡せない): {原因}"
                ));
                None
            }
            None => None,
        };
        // 読めないときは既定の設定で起動する。読めない理由は、組み立てで FFmpeg の置き場所を読むときに通知で知らせる(同じ理由を2回出さない)。
        let 見る側 = self
            .保管場所
            .見る側の設定を読む()
            .unwrap_or(見る側の設定::既定);
        起動の決着::起動する(Box::new(起動の準備 {
            環境: self.環境,
            見る側,
            保管場所: self.保管場所,
            ライブラリ,
            受け口,
            頼み: self.頼み,
            知らせ,
        }))
    }
}
