//! 再生の指示の受け口。配線が組み立てた再生の指示を渡す相手(1本目と2本目の音声出力装置の流れ)の口と、2本目の流れを開く手立てを持つ。
//! 装置の流れ(`audio_output` の `音声出力`・`行を混ぜる音声出力`)がこれを満たす。試験は、渡した指示を覚える受け口と、開けなかったものとして開く手立てに
//! 差し替え、配線が渡した指示と開けなかったときの知らせを、装置を開かずに観測する。参照: _doc/設計/同時再生.md 3-2・5-3

use audio_output::{
    再生の指示, 行ごとの再生の指示, 行を混ぜる音声出力, 音声出力, 音声出力のエラー,
};
use audio_pcm::サンプリング周波数;

/// 再生の指示の受け口とは、スタックの作業場の再生の指示を受け取って鳴らすもの(1本目の流れ)の口のことである。
pub(crate) trait 再生の指示の受け口 {
    /// 再生の指示を置き換える。
    fn 指示を渡す(&self, 指示: 再生の指示);
    /// 途中で使えなくなった理由。使えていれば無い。
    fn 使えなくなった理由(&self) -> Option<音声出力のエラー>;
}

impl 再生の指示の受け口 for 音声出力 {
    fn 指示を渡す(&self, 指示: 再生の指示) {
        音声出力::指示を渡す(self, 指示);
    }

    fn 使えなくなった理由(&self) -> Option<音声出力のエラー> {
        音声出力::使えなくなった理由(self)
    }
}

/// 行ごとの再生の指示の受け口とは、重ね合わせの作業場の行ごとの再生の指示を受け取って鳴らすもの(2本目の流れ)の口のことである。
pub(crate) trait 行ごとの再生の指示の受け口 {
    /// 行ごとの再生の指示を置き換える。
    fn 指示を渡す(&self, 指示: 行ごとの再生の指示);
    /// 途中で使えなくなった理由。使えていれば無い。
    fn 使えなくなった理由(&self) -> Option<音声出力のエラー>;
    /// 鳴らす周波数。重ね合わせの音の倉庫は、この周波数で FFmpeg に音を出させる。
    fn 周波数(&self) -> サンプリング周波数;
}

impl 行ごとの再生の指示の受け口 for 行を混ぜる音声出力 {
    fn 指示を渡す(&self, 指示: 行ごとの再生の指示) {
        行を混ぜる音声出力::指示を渡す(self, 指示);
    }

    fn 使えなくなった理由(&self) -> Option<音声出力のエラー> {
        行を混ぜる音声出力::使えなくなった理由(self)
    }

    fn 周波数(&self) -> サンプリング周波数 {
        行を混ぜる音声出力::周波数(self)
    }
}

/// 2本目の流れを開く手立てとは、初めて重ね合わせの作業場へ移るときに、2本目の流れを開いて行ごとの再生の指示の受け口を返す操作のことである。
/// 開く時期を決めるのは前に出ている作業場なので、組み立ての側がこの操作を渡す。
pub(crate) trait 二本目の流れを開く手立て {
    /// 2本目の流れを開く。開けなければ、その理由を返す。
    fn 開く(
        &self,
    ) -> Result<Box<dyn 行ごとの再生の指示の受け口>, 音声出力のエラー>;
}

/// 既定の装置に2本目の流れを開く手立てとは、スタックの作業場の音声出力と同じ既定の装置へ `行を混ぜる音声出力` を開く手立てのことである。
/// 画面のスレッドで開くため、装置を開く時間(開発機で約5ミリ秒)だけ画面が止まる。初めて重ね合わせの作業場へ移るときの1回だけである。
pub(crate) struct 既定の装置に二本目の流れを開く;

impl 二本目の流れを開く手立て for 既定の装置に二本目の流れを開く {
    fn 開く(
        &self,
    ) -> Result<Box<dyn 行ごとの再生の指示の受け口>, 音声出力のエラー> {
        let 出力 = 行を混ぜる音声出力::既定の装置を開く()?;
        Ok(Box::new(出力))
    }
}
