//! 作業場の切り替えの試験。回帰試験(a)(作業場を行き来してもスタックの作業場の値が変わらず、再生は止まるだけであること)と、
//! 重ね合わせの作業場を控えて同じ再生の位置で出し直すことと、重ね合わせの操作を前の作業場へだけ当てることを確かめる。
//! 参照: _doc/設計/同時再生.md 3-2
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::launch_requests::起動の頼みの届き方;
use super::workspace::{作業場の切り替え, 作業場の応答};
use super::workspace_test_snapshot::スタックの作業場の写し;
use super::workspace_test_support::手を加えたビューアー;
use super::クリップビューアー;
use crate::command::主ボタンの様子;
use crate::overlay::重ね合わせの操作;

fn 重ね合わせが前か(ビューアー: &クリップビューアー) -> bool {
    matches!(ビューアー.作業場, 作業場の切り替え::重ね合わせが前(_))
}

fn 重ね合わせの操作を適用する(
    ビューアー: &mut クリップビューアー,
    操作: 重ね合わせの操作,
) {
    let _ = ビューアー.応答を適用する(
        vec![作業場の応答::重ね合わせ(操作)],
        主ボタンの様子::押していない,
    );
}

#[test]
fn 回帰試験a_作業場を行き来してもスタックの作業場の値は変わらず_再生は止まるだけである() {
    let mut ビューアー = 手を加えたビューアー();
    assert!(ビューアー.状態.再生.再生しているか());
    let 移る前 = スタックの作業場の写し::写す(&ビューアー);
    let 行き来しない指示 =
        ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない);

    ビューアー.重ね合わせの作業場へ移る();
    assert!(重ね合わせが前か(&ビューアー));
    ビューアー.フレームを進める(Instant::now());
    重ね合わせの操作を適用する(
        &mut ビューアー,
        重ね合わせの操作::スタックの作業場へ戻る,
    );
    assert!(!重ね合わせが前か(&ビューアー));
    ビューアー.フレームを進める(Instant::now());

    assert!(!ビューアー.状態.再生.再生しているか());
    assert_eq!(スタックの作業場の写し::写す(&ビューアー), 移る前);
    assert_eq!(
        ビューアー.ウインドウへの指示の並び(None, 起動の頼みの届き方::届いていない),
        行き来しない指示
    );
}

#[test]
fn 重ね合わせの作業場は控えておき_再び移ると同じ再生の位置で止まって出る() {
    let mut ビューアー = 手を加えたビューアー();
    ビューアー.重ね合わせの作業場へ移る();
    重ね合わせの操作を適用する(&mut ビューアー, 重ね合わせの操作::再生を切り替える);
    let 作業場の切り替え::重ね合わせが前(作業場) = &ビューアー.作業場
    else {
        panic!("重ね合わせが前のはず");
    };
    assert!(作業場.試験のために状態を読む().再生.再生しているか());

    ビューアー.スタックの作業場を前に出す();
    let 作業場の切り替え::スタックが前 {
        控えた重ね合わせ: Some(控えた),
    } = &ビューアー.作業場
    else {
        panic!("重ね合わせの作業場を控えているはず");
    };
    assert!(!控えた.試験のために状態を読む().再生.再生しているか());
    let 控えた位置 = 控えた.試験のために状態を読む().再生.位置();

    ビューアー.重ね合わせの作業場へ移る();
    let 作業場の切り替え::重ね合わせが前(作業場) = &ビューアー.作業場
    else {
        panic!("重ね合わせが前のはず");
    };
    assert_eq!(作業場.試験のために状態を読む().再生.位置(), 控えた位置);
}

#[test]
fn 重ね合わせの操作はスタックの作業場が前のときに届いても当てず_重ね合わせの作業場を作らない() {
    let mut ビューアー = 手を加えたビューアー();
    重ね合わせの操作を適用する(&mut ビューアー, 重ね合わせの操作::再生を切り替える);
    assert!(!重ね合わせが前か(&ビューアー));
    assert!(matches!(
        ビューアー.作業場,
        作業場の切り替え::スタックが前 {
            控えた重ね合わせ: None
        }
    ));
}
