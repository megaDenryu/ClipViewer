//! 見る側の設定の変化の見張りの試験。変わってから1秒落ち着いたら保存すると答え、その間に値が変わると待ち直し、
//! 元の値へ戻ったら保存しない。終わる前は、書いた設定と違えば待たずに保存すると答える。

use std::time::{Duration, Instant};

use super::settings_watch::{落ち着くまでの時間, 設定の変化の見張り};
use crate::state::音量;
use crate::viewer_settings::見る側の設定;

fn 音量を変えた(値: f64) -> 見る側の設定 {
    見る側の設定 {
        音量: 音量::範囲へ収めて作る(値),
        ..見る側の設定::既定
    }
}

#[test]
fn 変わってから落ち着くまで保存せず_落ち着いたら1回だけ保存する() {
    let mut 見張り =
        設定の変化の見張り::読んだ設定から始める(見る側の設定::既定);
    let 始め = Instant::now();
    let 変えた = 音量を変えた(0.8);
    assert_eq!(見張り.見る(変えた, 始め), None);
    let 少し後 = 始め + Duration::from_millis(500);
    assert_eq!(見張り.見る(変えた, 少し後), None);
    let 落ち着いた = 始め + 落ち着くまでの時間;
    assert_eq!(見張り.見る(変えた, 落ち着いた), Some(変えた));
    let もっと後 = 落ち着いた + Duration::from_secs(5);
    assert_eq!(見張り.見る(変えた, もっと後), None);
}

#[test]
fn 待っている間に値が変わると待ち直し_元へ戻ると保存しない() {
    let mut 見張り =
        設定の変化の見張り::読んだ設定から始める(見る側の設定::既定);
    let 始め = Instant::now();
    let _ = 見張り.見る(音量を変えた(0.8), 始め);
    let 次 = 始め + Duration::from_millis(900);
    assert_eq!(見張り.見る(音量を変えた(0.7), 次), None);
    let 最初から1秒 = 始め + 落ち着くまでの時間;
    assert_eq!(見張り.見る(音量を変えた(0.7), 最初から1秒), None);
    let 戻した = 次 + 落ち着くまでの時間;
    assert_eq!(見張り.見る(見る側の設定::既定, 戻した), None);
}

#[test]
fn 終わる前は書いた設定と違えば待たずに保存すると答える() {
    let mut 見張り =
        設定の変化の見張り::読んだ設定から始める(見る側の設定::既定);
    assert_eq!(見張り.終わる前に見る(見る側の設定::既定), None);
    let 変えた = 音量を変えた(0.2);
    assert_eq!(見張り.終わる前に見る(変えた), Some(変えた));
}

#[test]
fn 変わりかけの間は保存するまでの残り時間を返し_保存したら返さない() {
    let mut 見張り =
        設定の変化の見張り::読んだ設定から始める(見る側の設定::既定);
    let 始め = Instant::now();
    assert_eq!(見張り.保存するまでの残り時間(始め), None);
    let _ = 見張り.見る(音量を変えた(0.8), 始め);
    let 少し後 = 始め + Duration::from_millis(300);
    assert_eq!(
        見張り.保存するまでの残り時間(少し後),
        Some(落ち着くまでの時間 - Duration::from_millis(300))
    );
    let _ = 見張り.見る(音量を変えた(0.8), 始め + 落ち着くまでの時間);
    assert_eq!(
        見張り.保存するまでの残り時間(始め + 落ち着くまでの時間),
        None
    );
}
