//! 閉じる決めの見張り。2つの作業場(スタック・重ね合わせ)のどちらかが、確かめるダイアログで変更を捨てて閉じると新しく決めたかを見る。
//! 新しく決めたフレームでだけウインドウへ閉じる指示を送り、閉じる要求の確かめ(`close.rs`)で、まだ確かめていないもう一方の作業場を確かめさせる。
//! 決めたままの間に毎フレーム閉じる指示を送ると、もう一方の作業場が確かめるダイアログを出している間、閉じる要求と取り消しを繰り返すためである。
//! 参照: _doc/設計/同時再生.md 3-2(触れる所の表の閉じる前の確かめの行)

/// 閉じる決めの見張りとは、最後に見たときに、スタックの作業場と重ね合わせの作業場がそれぞれ変更を捨てて閉じると決めていたかの組のことである。
#[derive(Debug, Default)]
pub(super) struct 閉じる決めの見張り {
    スタックが決めていたか: bool,
    重ね合わせが決めていたか: bool,
}

impl 閉じる決めの見張り {
    /// 今の決めを見て、前に見たときから新しく決めた作業場があるか。見た決めを覚える。
    pub(super) fn 新しく決めたかを見る(
        &mut self,
        スタックが決めたか: bool,
        重ね合わせが決めたか: bool,
    ) -> bool {
        let 新しく決めたか = (スタックが決めたか && !self.スタックが決めていたか)
            || (重ね合わせが決めたか && !self.重ね合わせが決めていたか);
        self.スタックが決めていたか = スタックが決めたか;
        self.重ね合わせが決めていたか = 重ね合わせが決めたか;
        新しく決めたか
    }
}
