//! 1フレームの時間を測るための並べ方。スタックの作業場で開いた動画から、別々の5秒の区間を持つ8つのクリップのスタックを測るためだけに作り、
//! 重ね合わせの作業場へ移って「今のスタックから並べる」と同じ経路で8行に並べ、再生を始める。スタックの作業場のスタックは変えない。
//! `cargo xtask frame-time` が起動したアプリだけが呼ぶ。参照: _doc/設計/同時再生.md 5-4

use std::time::Instant;

use clip_domain::{
    アスペクト比設定, クリップ, クリップスタック, クリップ名, クリップ識別子, 動画上の区間,
    同時に重ねられる行の数, 時刻, 時間の長さ,
};

use super::stack_values::今のスタックの値を借りる;
use super::クリップビューアー;
use crate::overlay::{
    今のスタックの値, 重ね合わせの操作, 開いている動画の値
};

/// 測るクリップ1つの区間の長さ(秒)。行ごとに別の区間を流し読みさせるため、区間を重ねずに並べる。
const 区間の秒数: f64 = 5.0;

impl クリップビューアー {
    /// 開いている動画の別々の区間から8つのクリップを作り、重ね合わせの作業場で8行に並べて再生を始める。
    /// 動画を開いていないか、動画が8区間分(40秒)より短いか、8行に並ばなかったら、理由を返す。
    pub(super) fn 計測のために八行を並べて再生する(
        &mut self,
        今: Instant,
    ) -> Result<(), String> {
        let 動画 = self.状態.動画.as_ref().ok_or("動画を開いていない")?;
        let パス = 動画.情報().パス().clone();
        let 長さ = 動画.情報().長さ();
        let スタック = 測るスタックを作る(長さ)?;
        self.重ね合わせの作業場へ移る(今);
        let 値 = 今のスタックの値 {
            スタック: &スタック,
            開いている動画: Some(開いている動画の値 {
                パス: &パス, 長さ
            }),
            出力のアスペクト比: アスペクト比設定::ワイド16対9,
            ..今のスタックの値を借りる(&self.状態)
        };
        let 読み手 = self.適用係.動画の読み手();
        let 作業場 = self
            .前に出ている作業場
            .前の重ね合わせの作業場を書き換える()
            .ok_or("重ね合わせの作業場が前に出ない")?;
        作業場.今のスタックから並べる(値, 読み手);
        作業場.操作を適用する(重ね合わせの操作::再生を切り替える);
        let 行の数 = 作業場
            .状態()
            .開いている重ね合わせ()
            .map_or(0, |開いている| 開いている.重ね合わせ().行の並び().行の数());
        if 行の数 != 同時に重ねられる行の数 || !作業場.状態().再生しているか()
        {
            return Err(format!(
                "8行に並べて再生できなかった(並んだ行の数 {行の数})"
            ));
        }
        Ok(())
    }
}

/// 動画の先頭から5秒ずつ重ならない区間を8つ持つスタック。
fn 測るスタックを作る(
    動画の長さ: 時間の長さ
) -> Result<クリップスタック, String> {
    let 一覧 = (0..同時に重ねられる行の数)
        .map(|番号| 測るクリップを作る(番号, 動画の長さ))
        .collect::<Result<Vec<_>, String>>()?;
    クリップスタック::一覧から作成する(一覧).map_err(|原因| 原因.to_string())
}

fn 測るクリップを作る(
    番号: usize,
    動画の長さ: 時間の長さ,
) -> Result<クリップ, String> {
    let 開始の秒 =
        f64::from(u32::try_from(番号).map_err(|原因| 原因.to_string())?) * 区間の秒数;
    let 終了の秒 = 開始の秒 + 区間の秒数;
    if 終了の秒 > 動画の長さ.秒数() {
        return Err(format!(
            "動画が短い({:.1}秒)。8つの区間を並べるには{}秒以上の動画が要る",
            動画の長さ.秒数(),
            区間の秒数 * 8.0
        ));
    }
    let 名前 = format!("計測{}", 番号 + 1);
    let mut クリップ = クリップ::既定値で作成する(
        クリップ識別子::文字列から作成する(名前.clone()).map_err(|原因| 原因.to_string())?,
        クリップ名::作成する(名前),
    );
    クリップ.区間 = 動画上の区間::作成する(
        時刻::作成する(開始の秒).map_err(|原因| 原因.to_string())?,
        時刻::作成する(終了の秒).map_err(|原因| 原因.to_string())?,
    )
    .map_err(|原因| 原因.to_string())?;
    Ok(クリップ)
}
