//! 前に出ている作業場。重ね合わせの側をまだ作っていないか(作り方を持つ)、作ったか(側とどちらが前かを持つ)を区別して持ち、
//! 前に出す作業場を持ち替え、重ね合わせの側を毎フレーム進める。重ね合わせの作業場を配線へ貸すことは `side_access.rs` に置く。参照: _doc/設計/同時再生.md 3-2

use std::time::Instant;

use video_source::動画の読み手;

mod side_access;

use super::overlay_side::重ね合わせの側;
use super::overlay_side_recipe::重ね合わせの側の作り方;
use crate::state::アプリの状態;

/// どちらが前とは、重ね合わせの側を作った後に、スタックの作業場と重ね合わせの作業場のどちらを利用者に見せているかの区別のことである。
/// 一度作った重ね合わせの側は、スタックの作業場が前の間も控えておき、再び移ったときに同じ重ね合わせを同じ再生の位置で出す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum どちらが前 {
    スタックが前,
    重ね合わせが前,
}

/// 重ね合わせの側の様子とは、重ね合わせの側をまだ作っていないか、作ったか、アプリを落とすときに放したかの区別のことである。
/// 作っていない間はスタックの作業場が前である(重ね合わせが前なら必ず側を作っている)。
/// アプリに1つしか無く、選択肢の大きさの差は使う記憶の量に効かないため、作成済みの側を箱に入れない。
#[allow(clippy::large_enum_variant)]
enum 重ね合わせの側の様子 {
    未作成(重ね合わせの側の作り方),
    作成済み {
        側: 重ね合わせの側,
        前: どちらが前,
    },
    放した,
}

/// 前に出ている作業場とは、重ね合わせの側の様子のことである。スタックの作業場の状態は `クリップビューアー` が常に持つ。
pub(crate) struct 前に出ている作業場 {
    様子: 重ね合わせの側の様子,
}

impl 前に出ている作業場 {
    /// 起動したときの値。スタックの作業場が前で、重ね合わせの側はまだ作っていない。
    pub(crate) fn 起動時(作り方: 重ね合わせの側の作り方) -> Self {
        Self {
            様子: 重ね合わせの側の様子::未作成(作り方),
        }
    }

    /// 重ね合わせの作業場を前に出す。作った側があればそれを(重ね合わせの一覧を読み直して)、無ければ作り方を消費して作って(2本目の流れを開いて)前に出す。
    pub(super) fn 重ね合わせを前に出す(&mut self) {
        match &mut self.様子 {
            重ね合わせの側の様子::作成済み { 側, 前 } => {
                if *前 == どちらが前::スタックが前 {
                    側.作業場.前に出すときに一覧を読み直す();
                    *前 = どちらが前::重ね合わせが前;
                }
            }
            重ね合わせの側の様子::未作成(_) => {
                // 注意: 作り方を値として取り出すため、取り出す間だけ放した様子を置き、すぐに作成済みを書き込む。
                if let 重ね合わせの側の様子::未作成(作り方) =
                    std::mem::replace(&mut self.様子, 重ね合わせの側の様子::放した)
                {
                    self.様子 = 重ね合わせの側の様子::作成済み {
                        側: 作り方.作る(),
                        前: どちらが前::重ね合わせが前,
                    };
                }
            }
            重ね合わせの側の様子::放した => {}
        }
    }

    /// スタックの作業場を前に出す。重ね合わせの側は、再生を止めて黙る指示を1回渡してから控える。スタックの作業場が前なら何もしない。
    pub(super) fn スタックを前に出す(&mut self, 今: Instant) {
        if let 重ね合わせの側の様子::作成済み { 側, 前 } = &mut self.様子
            && *前 == どちらが前::重ね合わせが前
        {
            側.控える(今);
            *前 = どちらが前::スタックが前;
        }
    }

    /// 毎フレーム呼ぶ。重ね合わせが前ならその側のフレームを進め、控えているならどの行も黙る指示を渡してライブラリの書き込みを進める。まだ作っていなければ何もしない。
    pub(super) fn 重ね合わせの側のフレームを進める(
        &mut self,
        今: Instant,
        状態: &アプリの状態,
        読み手: Option<&動画の読み手>,
    ) {
        if let 重ね合わせの側の様子::作成済み { 側, 前 } = &mut self.様子 {
            match 前 {
                どちらが前::重ね合わせが前 => {
                    側.前に出ている間のフレームを進める(今, 状態, 読み手)
                }
                どちらが前::スタックが前 => 側.控えている間に黙らせる(今),
            }
        }
    }

    /// 重ね合わせの側(作ったもの)か作り方(まだ作っていないもの)を落として、重ね合わせのライブラリを放す。`overlays` の錠が放れる。
    /// アプリを落とすときに、スタックのライブラリの錠より先に呼ぶ。
    pub(in crate::app) fn 重ね合わせの側を放す(&mut self) {
        self.様子 = 重ね合わせの側の様子::放した;
    }
}
