//! 前に出ている作業場のうち、前に出ているか控えているかに関わらず重ね合わせの側に触れる口。閉じる要求の確かめとアプリを落とす前の保存が使う
//! 重ね合わせの側を借りることと、アプリを落とすときに重ね合わせの側と重ね合わせのライブラリを落とすことと、試験の口を置く。参照: _doc/設計/同時再生.md 3-2

use super::{どちらが前, 前に出ている作業場};
use crate::app::overlay_side::重ね合わせの側;

impl 前に出ている作業場 {
    /// 前に出ているか控えている重ね合わせの側。まだ作っていなければ無い。閉じる要求の確かめとアプリを落とす前の保存で使う。
    pub(in crate::app) fn 重ね合わせの側を書き換える(
        &mut self,
    ) -> Option<&mut 重ね合わせの側> {
        match &mut self.前 {
            どちらが前::重ね合わせが前(側)
            | どちらが前::スタックが前 {
                控えた重ね合わせ: Some(側),
            } => Some(側),
            どちらが前::スタックが前 {
                控えた重ね合わせ: None,
            } => None,
        }
    }

    /// 重ね合わせの側を落として、重ね合わせのライブラリ(作業場が持つものか、まだ作り方が持つもの)を放す。`overlays` の錠が放れる。
    /// アプリを落とすときに、スタックのライブラリの錠より先に呼ぶ。以後はスタックの作業場が前で、重ね合わせの側は無い。
    pub(in crate::app) fn 重ね合わせの側を落としてライブラリを放す(&mut self) {
        self.前 = どちらが前::スタックが前 {
            控えた重ね合わせ: None,
        };
        self.作り方.重ね合わせのライブラリを放す();
    }

    /// 作業場へ渡す前の重ね合わせのライブラリを置き換える。試験で、一時フォルダの錠を試した重ね合わせのライブラリを持たせるために使う。
    #[cfg(test)]
    pub(crate) fn 重ね合わせのライブラリを持たせる(
        &mut self,
        ライブラリ: clip_library::裏で動く重ね合わせのライブラリ,
    ) {
        self.作り方.重ね合わせのライブラリ = Some(ライブラリ);
    }

    /// 控えている重ね合わせの側。まだ作っていないか、重ね合わせが前なら無い。試験で控えた後の様子を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 控えた重ね合わせ(&self) -> Option<&重ね合わせの側> {
        match &self.前 {
            どちらが前::スタックが前 {
                控えた重ね合わせ
            } => 控えた重ね合わせ.as_ref(),
            どちらが前::重ね合わせが前(_) => None,
        }
    }
}
