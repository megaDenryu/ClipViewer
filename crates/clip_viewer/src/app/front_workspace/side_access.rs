//! 前に出ている作業場が、重ね合わせの側と重ね合わせの作業場を配線へ貸すこと。前に出ているときだけ貸すものと、前に出ているか控えているかに関わらず貸すもの
//! (閉じる手順とアプリを落とす前の保存が使う)と、試験の口を置く。参照: _doc/設計/同時再生.md 3-2

use super::{どちらが前, 前に出ている作業場, 重ね合わせの側の様子};
use crate::app::overlay_side::重ね合わせの側;
use crate::overlay::重ね合わせの作業場;

impl 前に出ている作業場 {
    /// 重ね合わせが前か。
    pub(crate) fn 重ね合わせが前か(&self) -> bool {
        self.前の重ね合わせ().is_some()
    }

    /// 前に出ている重ね合わせの側。スタックの作業場が前なら無い。
    pub(crate) fn 前の重ね合わせ(&self) -> Option<&重ね合わせの側> {
        match &self.様子 {
            重ね合わせの側の様子::作成済み {
                側,
                前: どちらが前::重ね合わせが前,
            } => Some(側),
            _ => None,
        }
    }

    /// 前に出ている重ね合わせの作業場。スタックの作業場が前なら無い。応答の適用が使う。
    pub(crate) fn 前の重ね合わせの作業場を書き換える(
        &mut self,
    ) -> Option<&mut 重ね合わせの作業場> {
        match &mut self.様子 {
            重ね合わせの側の様子::作成済み {
                側,
                前: どちらが前::重ね合わせが前,
            } => Some(&mut 側.作業場),
            _ => None,
        }
    }

    /// 前に出ているか控えている重ね合わせの作業場。まだ作っていなければ無い。閉じる手順とアプリを落とす前の保存が使う。
    pub(crate) fn 重ね合わせの作業場を書き換える(
        &mut self,
    ) -> Option<&mut 重ね合わせの作業場> {
        match &mut self.様子 {
            重ね合わせの側の様子::作成済み { 側, .. } => Some(&mut 側.作業場),
            _ => None,
        }
    }

    /// まだ作っていない重ね合わせの側の作り方へ、重ね合わせのライブラリを持たせる。試験で、一時フォルダの錠を試した重ね合わせのライブラリを持たせるために使う。
    #[cfg(test)]
    pub(crate) fn 重ね合わせのライブラリを持たせる(
        &mut self,
        ライブラリ: clip_library::裏で動く重ね合わせのライブラリ,
    ) {
        if let 重ね合わせの側の様子::未作成(作り方) = &mut self.様子 {
            作り方.重ね合わせのライブラリ = Some(ライブラリ);
        }
    }

    /// 控えている重ね合わせの側。まだ作っていないか、重ね合わせが前なら無い。試験で控えた後の様子を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 控えた重ね合わせ(&self) -> Option<&重ね合わせの側> {
        match &self.様子 {
            重ね合わせの側の様子::作成済み {
                側,
                前: どちらが前::スタックが前,
            } => Some(側),
            _ => None,
        }
    }
}
