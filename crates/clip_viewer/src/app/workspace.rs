//! 作業場を移すこと。前に出ている作業場(スタックの作業場か重ね合わせの作業場)を持ち替え、作業場ごとの応答を振り分け、
//! 前に出ている作業場の画面の木だけを組む。スタックの作業場の型と経路(`アプリの状態`・画面の構え・キーの表・閉じる前の確かめ)は変えない。
//! 参照: _doc/設計/同時再生.md 3-2

use std::time::Instant;

use sengen_egui::ノード;

use super::stack_values::今のスタックの値を借りる;
use super::workspace_response::作業場の応答;
use super::クリップビューアー;
use crate::command::応答;
use crate::view;

impl クリップビューアー {
    /// 重ね合わせの作業場へ移る。スタックの作業場は再生を止め、書けていない並びの保存をすぐに頼み、止めている指示を1本目の流れへすぐに渡してから控える。
    /// 初めて移るときは、重ね合わせの側を作る(同じ既定の装置へ2本目の流れを開く。同時再生.md 5-3)。
    /// スタックの作業場のヘッダーの「同時再生」が発する応答を、配線が受け取って呼ぶ。
    pub(crate) fn 重ね合わせの作業場へ移る(&mut self, 今: Instant) {
        if self.前に出ている作業場.重ね合わせが前か() {
            return;
        }
        self.状態.控える前に再生を止めて並びの保存を頼む();
        self.音の送り手.指示を送る(&mut self.状態, 今);
        self.前に出ている作業場.重ね合わせを前に出す();
    }

    /// スタックの作業場を前に出す。重ね合わせの作業場の再生を止め、2本目の流れへ黙る指示をすぐに渡して控える。スタックの作業場が前なら何もしない。
    pub(super) fn スタックの作業場を前に出す(&mut self, 今: Instant) {
        self.前に出ている作業場.スタックを前に出す(今);
    }

    /// 前に出ている作業場の画面の木だけを組む。重ね合わせが前のフレームでは、スタックの作業場の画面の木(画面の構えの分岐とキーの表)を通らない。
    pub(super) fn 前に出ている作業場の画面を組む(
        &self,
    ) -> ノード<作業場の応答> {
        match self.前に出ている作業場.前の重ね合わせ() {
            None => view::画面(
                &self.状態,
                self.前に出ている作業場
                    .控えた重ね合わせの作業場()
                    .and_then(|作業場| 作業場.控えている間に描き直すまでの時間()),
            )
            .写す(作業場の応答::スタックの応答),
            Some(側) => 側
                .作業場()
                .画面(
                    今のスタックの値を借りる(&self.状態),
                    view::描き直すまでの時間(&self.状態),
                )
                .写す(作業場の応答::重ね合わせの応答),
        }
    }

    /// 作業場の応答を、その作業場へ振り分けて適用する。重ね合わせの作業場の中の操作は、重ね合わせが前のときだけ当てる。
    /// スタックの作業場のヘッダーの「同時再生」は、スタックの作業場の状態へ当てずに、作業場を移す。
    pub(super) fn 作業場の応答を適用する(
        &mut self, 応答: 作業場の応答, 今: Instant
    ) {
        match 応答 {
            作業場の応答::スタックの応答(応答::重ね合わせの作業場へ移る) => {
                self.重ね合わせの作業場へ移る(今)
            }
            作業場の応答::スタックの応答(応答) => {
                self.適用係.適用する(&mut self.状態, 応答)
            }
            作業場の応答::重ね合わせの応答(応答) => {
                self.重ね合わせの作業場の応答を適用する(応答, 今)
            }
        }
    }
}
