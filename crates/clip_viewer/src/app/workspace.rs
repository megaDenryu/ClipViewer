//! 作業場を移すこと。前に出ている作業場(スタックの作業場か重ね合わせの作業場)を持ち替え、作業場ごとの応答を振り分け、
//! 前に出ている作業場の画面の木だけを組む。スタックの作業場の型と経路(`アプリの状態`・画面の構え・キーの表・閉じる前の確かめ)は変えない。
//! 参照: _doc/設計/同時再生.md 3-2

use std::time::Instant;

use sengen_egui::ノード;

use super::stack_values::今のスタックの値を借りる;
use super::workspace_response::作業場の応答;
use super::クリップビューアー;
use crate::command::{再生の操作, 応答};
use crate::overlay::重ね合わせの作業場の応答;
use crate::view;

impl クリップビューアー {
    /// 重ね合わせの作業場へ移る。スタックの作業場は再生を止め、書けていない並びの保存をすぐに頼み、止めている指示を1本目の流れへすぐに渡してから控える。
    /// 初めて移るときは、重ね合わせの側を作る(同じ既定の装置へ2本目の流れを開く。同時再生.md 5-3)。
    /// スタックの作業場のヘッダーの「同時再生」が発する応答を、配線が受け取って呼ぶ。
    /// 注意: 応答の適用は時刻を受け取らないため、止めている指示の時刻はここで読む(止めている指示は時刻からの経過で位置を進めない)。
    pub(crate) fn 重ね合わせの作業場へ移る(&mut self) {
        if self.前に出ている作業場.重ね合わせが前か() {
            return;
        }
        self.状態.控える前に再生を止めて並びの保存を頼む();
        self.音の送り手.指示を送る(&mut self.状態, Instant::now());
        self.前に出ている作業場.重ね合わせを前に出す();
    }

    /// スタックの作業場を前に出す。重ね合わせの作業場の再生を止め、2本目の流れへ黙る指示をすぐに渡して控える。スタックの作業場が前なら何もしない。
    /// 注意: 時刻を読む理由は `重ね合わせの作業場へ移る` と同じである。
    pub(super) fn スタックの作業場を前に出す(&mut self) {
        self.前に出ている作業場.スタックを前に出す(Instant::now());
    }

    /// 前に出ている作業場の画面の木だけを組む。重ね合わせが前のフレームでは、スタックの作業場の画面の木(画面の構えの分岐とキーの表)を通らない。
    pub(super) fn 前に出ている作業場の画面を組む(
        &self,
    ) -> ノード<作業場の応答> {
        match self.前に出ている作業場.前の重ね合わせ() {
            None => view::画面(&self.状態).写す(作業場の応答::スタックの応答),
            Some(側) => 側
                .作業場()
                .画面(
                    今のスタックの値を借りる(&self.状態),
                    view::描き直すまでの時間(&self.状態),
                )
                .写す(作業場の応答::重ね合わせの応答),
        }
    }

    /// 作業場の応答を、その作業場へ振り分けて適用する。重ね合わせの作業場の中の操作は、重ね合わせが前のときだけ当てる。
    /// スタックの作業場のヘッダーの「同時再生」は、スタックの作業場の状態へ当てずに、作業場を移す。
    pub(super) fn 作業場の応答を適用する(&mut self, 応答: 作業場の応答) {
        match 応答 {
            作業場の応答::スタックの応答(応答::重ね合わせの作業場へ移る) => {
                self.重ね合わせの作業場へ移る()
            }
            作業場の応答::スタックの応答(応答) => {
                self.適用係.適用する(&mut self.状態, 応答)
            }
            作業場の応答::重ね合わせの応答(応答) => {
                self.重ね合わせの作業場の応答を適用する(応答)
            }
        }
    }

    /// 重ね合わせの作業場の応答を適用する。スタックの作業場へ戻ることと全画面の切り替えと音量のつまみと全体の消音は前に出ているかに関わらず当て、
    /// 音量のつまみと全体の消音は、スタックの作業場の今の操作(`再生の操作::音量を選ぶ`・`再生の操作::消音を切り替える`)をそのまま当てる(同時再生.md 3-2 の共有するものの表)。
    /// 今のスタックから並べることと重ね合わせの作業場の中の操作は、重ね合わせが前のときだけ、重ね合わせの側へ当てる。
    fn 重ね合わせの作業場の応答を適用する(
        &mut self,
        応答: 重ね合わせの作業場の応答,
    ) {
        let 前の重ね合わせ = self.前に出ている作業場.前の重ね合わせを書き換える();
        match 応答 {
            重ね合わせの作業場の応答::スタックの作業場へ戻る => {
                self.スタックの作業場を前に出す()
            }
            重ね合わせの作業場の応答::全画面を切り替える => {
                self.状態.ウインドウ.全画面を切り替える()
            }
            重ね合わせの作業場の応答::音量のつまみの値を選ぶ(値) => {
                self.状態.再生の操作を適用する(再生の操作::音量を選ぶ(値))
            }
            重ね合わせの作業場の応答::全体の消音を切り替える => {
                self.状態.再生の操作を適用する(再生の操作::消音を切り替える)
            }
            重ね合わせの作業場の応答::今のスタックから並べる => {
                if let Some(側) = 前の重ね合わせ {
                    側.今のスタックから並べる(
                        今のスタックの値を借りる(&self.状態),
                        self.適用係.動画の読み手(),
                    );
                }
            }
            重ね合わせの作業場の応答::操作(操作) => {
                if let Some(側) = 前の重ね合わせ {
                    側.操作を当てる(操作);
                }
            }
        }
    }
}
