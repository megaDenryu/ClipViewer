/// 作業場の応答とは、前に出ている作業場の画面が発した応答を、どちらの作業場の画面が発したかで分けたもののことである。
/// スタックの応答はスタックの作業場の画面が発する `command::応答`、重ね合わせの応答は重ね合わせの作業場の画面が発する `重ね合わせの作業場の応答` である。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 作業場の応答 {
    スタックの応答(応答),
    重ね合わせの応答(重ね合わせの作業場の応答),
}

impl クリップビューアー {
    /// 重ね合わせの作業場へ移る。スタックの作業場は再生を止め、書けていない並びの保存をすぐに頼んでから控える。
    /// スタックの作業場のヘッダーの「同時再生」が発する応答を、配線が受け取って呼ぶ。
    pub(crate) fn 重ね合わせの作業場へ移る(&mut self) {
        if let 前に出ている作業場::重ね合わせが前(_) = self.前に出ている作業場
        {
            return;
        }
        self.状態.控える前に再生を止めて並びの保存を頼む();
        self.前に出ている作業場
            .重ね合わせを前に出す(&self.画面描画の共有状態);
    }

    /// スタックの作業場を前に出す。重ね合わせの作業場の再生を止めて控える。スタックの作業場が前なら何もしない。
    pub(super) fn スタックの作業場を前に出す(&mut self) {
        self.前に出ている作業場.スタックを前に出す();
    }

    /// 重ね合わせが前なら、作業場を移る前に頼んだスタックの保存の失敗を重ね合わせの作業場の知らせへ出し、重ね合わせの作業場の時計を進める。
    /// スタックの作業場の1フレームの手順は、どちらが前でも配線が今のまま呼ぶ。
    pub(super) fn 前に出ている重ね合わせの作業場のフレームを進める(
        &mut self,
        今: Instant,
    ) {
        if let 前に出ている作業場::重ね合わせが前(作業場) = &mut self.前に出ている作業場
        {
            作業場.スタックの保存の失敗を知らせる(スタックの保存の観測結果を求める(
                &self.状態,
            ));
            作業場.フレームを進める(今);
        }
    }

    /// 前に出ている作業場の画面の木だけを組む。重ね合わせが前のフレームでは、スタックの作業場の画面の木(画面の構えの分岐とキーの表)を通らない。
    pub(super) fn 前に出ている作業場の画面を組む(
        &self,
    ) -> ノード<作業場の応答> {
        match &self.前に出ている作業場 {
            前に出ている作業場::スタックが前 { .. } => {
                view::画面(&self.状態).写す(作業場の応答::スタックの応答)
            }
            前に出ている作業場::重ね合わせが前(作業場) => 作業場
                .画面(
                    今のスタックの値を借りる(&self.状態),
                    view::描き直すまでの時間(&self.状態),
                )
                .写す(作業場の応答::重ね合わせの応答),
        }
    }

    /// 作業場の応答を、その作業場へ振り分けて適用する。重ね合わせの作業場の中の操作は、重ね合わせが前のときだけ当てる。
    /// スタックの作業場のヘッダーの「同時再生」は、スタックの作業場の状態へ当てずに、作業場を移す。
    pub(super) fn 作業場の応答を適用する(&mut self, 応答: 作業場の応答) {
        match 応答 {
            作業場の応答::スタックの応答(応答::重ね合わせの作業場へ移る) => {
                self.重ね合わせの作業場へ移る()
            }
            作業場の応答::スタックの応答(応答) => {
                self.適用係.適用する(&mut self.状態, 応答)
            }
            作業場の応答::重ね合わせの応答(応答) => {
                self.重ね合わせの作業場の応答を適用する(応答)
            }
        }
    }

    /// 重ね合わせの作業場の応答を適用する。スタックの作業場へ戻ることと全画面の切り替えは前に出ているかに関わらず当て、
    /// 今のスタックから並べることと重ね合わせの作業場の中の操作は、重ね合わせが前のときだけ当てる。
    fn 重ね合わせの作業場の応答を適用する(
        &mut self,
        応答: 重ね合わせの作業場の応答,
    ) {
        match 応答 {
            重ね合わせの作業場の応答::スタックの作業場へ戻る => {
                self.スタックの作業場を前に出す()
            }
            重ね合わせの作業場の応答::全画面を切り替える => {
                self.状態.ウインドウ.全画面を切り替える()
            }
            重ね合わせの作業場の応答::今のスタックから並べる => {
                if let 前に出ている作業場::重ね合わせが前(作業場) = &mut self.前に出ている作業場
                {
                    作業場.今のスタックから並べる(
                        今のスタックの値を借りる(&self.状態),
                        self.適用係.動画の読み手(),
                    );
                }
            }
            重ね合わせの作業場の応答::操作(操作) => {
                if let 前に出ている作業場::重ね合わせが前(作業場) = &mut self.前に出ている作業場
                {
                    作業場.操作を適用する(操作);
                }
            }
        }
    }
}
