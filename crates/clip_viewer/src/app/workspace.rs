//! 作業場を移すこと。前に出ている作業場(スタックの作業場か重ね合わせの作業場)を持ち替え、作業場ごとの応答を振り分け、
//! 前に出ている作業場の画面の木だけを組む。スタックの作業場の型と経路(`アプリの状態`・画面の構え・キーの表・閉じる前の確かめ)は変えない。
//! 参照: _doc/設計/同時再生.md 3-2

use std::time::Instant;

use sengen_egui::ノード;

use super::クリップビューアー;
use crate::command::応答;
use crate::overlay::{
    操作の後の作業場, 重ね合わせの作業場, 重ね合わせの操作
};
use crate::view;

/// 作業場の応答とは、前に出ている作業場の画面が発した応答を、どちらの作業場のものかで分けたもののことである。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 作業場の応答 {
    スタックの応答(応答),
    重ね合わせの応答(重ね合わせの操作),
}

/// 前に出ている作業場とは、スタックの作業場と重ね合わせの作業場のどちらを利用者に見せているかの区別のことである。スタックの作業場の状態は `クリップビューアー` が常に持つ。
/// 一度作った重ね合わせの作業場は、スタックの作業場が前の間も控えておき、再び移ったときに同じ重ね合わせを同じ再生の位置で出す。
pub(crate) enum 前に出ている作業場 {
    スタックが前 {
        控えた重ね合わせ: Option<重ね合わせの作業場>,
    },
    重ね合わせが前(重ね合わせの作業場),
}

impl 前に出ている作業場 {
    /// 起動したときの切り替え。スタックの作業場が前で、重ね合わせの作業場はまだ作っていない。
    pub(crate) fn 起動時() -> Self {
        Self::スタックが前 {
            控えた重ね合わせ: None,
        }
    }

    /// 重ね合わせの作業場を前に出す。控えていればそれを、無ければ何も置いていない作業場を前に出す。
    fn 重ね合わせを前に出す(&mut self) {
        *self = match std::mem::replace(self, Self::起動時()) {
            Self::スタックが前 {
                控えた重ね合わせ
            } => Self::重ね合わせが前(
                控えた重ね合わせ.unwrap_or_else(重ね合わせの作業場::何も置いていない作業場),
            ),
            重ね合わせが前 @ Self::重ね合わせが前(_) => 重ね合わせが前,
        };
    }

    /// スタックの作業場を前に出す。重ね合わせの作業場は再生を止めて控える。
    fn スタックを前に出す(&mut self) {
        *self = match std::mem::replace(self, Self::起動時()) {
            Self::重ね合わせが前(mut 作業場) => {
                作業場.控える前に再生を止める();
                Self::スタックが前 {
                    控えた重ね合わせ: Some(作業場),
                }
            }
            スタックが前 @ Self::スタックが前 { .. } => スタックが前,
        };
    }
}

impl クリップビューアー {
    /// 重ね合わせの作業場へ移る。スタックの作業場の再生を止め、登録済みのスタックなら落ち着くのを待っている並びの保存をすぐに頼む
    /// (Ctrl+S の登録済みのときと同じ。後ろへ下げている間に変更が失われないようにするため)。
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "第8段階でスタックの作業場のヘッダーの「同時再生」から呼ぶ。それまでは試験からだけ呼ぶ(同時再生.md 6節)"
        )
    )]
    pub(crate) fn 重ね合わせの作業場へ移る(&mut self) {
        if let 前に出ている作業場::重ね合わせが前(_) = self.前に出ている作業場
        {
            return;
        }
        self.状態.再生.止める();
        self.状態.書けていない並びの保存を頼む();
        self.前に出ている作業場.重ね合わせを前に出す();
    }

    /// スタックの作業場を前に出す。重ね合わせの作業場の再生を止めて控える。スタックの作業場が前なら何もしない。
    pub(super) fn スタックの作業場を前に出す(&mut self) {
        self.前に出ている作業場.スタックを前に出す();
    }

    /// 前に出ている作業場の時計を進める。スタックの作業場の1フレームの手順は、どちらが前でも配線が今のまま呼ぶ。
    pub(super) fn 前に出ている重ね合わせの作業場のフレームを進める(
        &mut self,
        今: Instant,
    ) {
        if let 前に出ている作業場::重ね合わせが前(作業場) = &mut self.前に出ている作業場
        {
            作業場.フレームを進める(今);
        }
    }

    /// 前に出ている作業場の画面の木だけを組む。重ね合わせが前のフレームでは、スタックの作業場の画面の木(画面の構えの分岐とキーの表)を通らない。
    pub(super) fn 前に出ている作業場の画面を組む(
        &self,
    ) -> ノード<作業場の応答> {
        match &self.前に出ている作業場 {
            前に出ている作業場::スタックが前 { .. } => {
                view::画面(&self.状態).写す(作業場の応答::スタックの応答)
            }
            前に出ている作業場::重ね合わせが前(作業場) => 作業場
                .画面(view::描き直すまでの時間(&self.状態))
                .写す(作業場の応答::重ね合わせの応答),
        }
    }

    /// 作業場の応答を、その作業場へ振り分けて適用する。重ね合わせの応答は、重ね合わせが前のときだけ当てる。
    pub(super) fn 作業場の応答を適用する(&mut self, 応答: 作業場の応答) {
        match 応答 {
            作業場の応答::スタックの応答(応答) => {
                self.適用係.適用する(&mut self.状態, 応答)
            }
            作業場の応答::重ね合わせの応答(操作) => {
                let 前に出ている作業場::重ね合わせが前(作業場) = &mut self.前に出ている作業場
                else {
                    return;
                };
                if 作業場.操作を適用する(操作)
                    == 操作の後の作業場::スタックの作業場を前に出す
                {
                    self.スタックの作業場を前に出す();
                }
            }
        }
    }
}
