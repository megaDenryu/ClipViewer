//! 作業場を移すこと。前に出ている作業場(スタックの作業場か重ね合わせの作業場)を持ち替え、作業場ごとの応答を振り分け、
//! 前に出ている作業場の画面の木だけを組む。スタックの作業場の型と経路(`アプリの状態`・画面の構え・キーの表・閉じる前の確かめ)は変えない。
//! 参照: _doc/設計/同時再生.md 3-2

use std::time::Instant;

use sengen_egui::ノード;

use super::front_workspace::前に出ている作業場;
use super::クリップビューアー;
use crate::command::応答;
use crate::overlay::重ね合わせの作業場の応答;
use crate::view;

/// 作業場の応答とは、前に出ている作業場の画面が発した応答を、どちらの作業場の画面が発したかで分けたもののことである。
/// スタックの応答はスタックの作業場の画面が発する `command::応答`、重ね合わせの応答は重ね合わせの作業場の画面が発する `重ね合わせの作業場の応答` である。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 作業場の応答 {
    スタックの応答(応答),
    重ね合わせの応答(重ね合わせの作業場の応答),
}

impl クリップビューアー {
    /// 重ね合わせの作業場へ移る。スタックの作業場は再生を止め、書けていない並びの保存をすぐに頼んでから控える。
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "第8段階でスタックの作業場のヘッダーの「同時再生」から呼ぶ。それまでは試験からだけ呼ぶ(同時再生.md 6節)"
        )
    )]
    pub(crate) fn 重ね合わせの作業場へ移る(&mut self) {
        if let 前に出ている作業場::重ね合わせが前(_) = self.前に出ている作業場
        {
            return;
        }
        self.状態.控える前に再生を止めて並びの保存を頼む();
        self.前に出ている作業場.重ね合わせを前に出す();
    }

    /// スタックの作業場を前に出す。重ね合わせの作業場の再生を止めて控える。スタックの作業場が前なら何もしない。
    pub(super) fn スタックの作業場を前に出す(&mut self) {
        self.前に出ている作業場.スタックを前に出す();
    }

    /// 重ね合わせが前なら、重ね合わせの作業場の時計を進める。スタックの作業場の1フレームの手順は、どちらが前でも配線が今のまま呼ぶ。
    pub(super) fn 前に出ている重ね合わせの作業場のフレームを進める(
        &mut self,
        今: Instant,
    ) {
        if let 前に出ている作業場::重ね合わせが前(作業場) = &mut self.前に出ている作業場
        {
            作業場.フレームを進める(今);
        }
    }

    /// 前に出ている作業場の画面の木だけを組む。重ね合わせが前のフレームでは、スタックの作業場の画面の木(画面の構えの分岐とキーの表)を通らない。
    pub(super) fn 前に出ている作業場の画面を組む(
        &self,
    ) -> ノード<作業場の応答> {
        match &self.前に出ている作業場 {
            前に出ている作業場::スタックが前 { .. } => {
                view::画面(&self.状態).写す(作業場の応答::スタックの応答)
            }
            前に出ている作業場::重ね合わせが前(作業場) => 作業場
                .画面(view::描き直すまでの時間(&self.状態))
                .写す(作業場の応答::重ね合わせの応答),
        }
    }

    /// 作業場の応答を、その作業場へ振り分けて適用する。重ね合わせの作業場の中の操作は、重ね合わせが前のときだけ当てる。
    pub(super) fn 作業場の応答を適用する(&mut self, 応答: 作業場の応答) {
        match 応答 {
            作業場の応答::スタックの応答(応答) => {
                self.適用係.適用する(&mut self.状態, 応答)
            }
            作業場の応答::重ね合わせの応答(
                重ね合わせの作業場の応答::スタックの作業場へ戻る,
            ) => self.スタックの作業場を前に出す(),
            作業場の応答::重ね合わせの応答(重ね合わせの作業場の応答::操作(操作)) => {
                if let 前に出ている作業場::重ね合わせが前(作業場) = &mut self.前に出ている作業場
                {
                    作業場.操作を適用する(操作);
                }
            }
        }
    }
}
