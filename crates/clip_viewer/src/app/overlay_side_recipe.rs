//! 重ね合わせの側の作り方。初めて重ね合わせの作業場へ移るときに重ね合わせの側を作る材料(画面描画の共有状態・2本目の流れを開く手立て・
//! 起動のときに錠を試した重ね合わせのライブラリ・サムネイルのキャッシュ)を持ち、重ね合わせの作業場を作る。
//! 参照: _doc/設計/同時再生.md 3-2(起動の手順の行・作業場をまたいで共有するもののサムネイルの行)

use clip_library::裏で動く重ね合わせのライブラリ;
use eframe::egui;
use thumbnail_cache::サムネイルのキャッシュ;

use super::instruction_receiver::二本目の流れを開く手立て;
use crate::overlay::{
    重ね合わせのライブラリの状態, 重ね合わせの作業場, 重ね合わせの音の出力の状況,
};

/// 重ね合わせの側の作り方とは、重ね合わせの作業場が行のテクスチャとサムネイルを登録する画面描画の共有状態と、2本目の流れを開く手立てと、
/// 重ね合わせの作業場へ渡すまで持つ裏で動く重ね合わせのライブラリ(置き場所が無ければ無い)と、サムネイルのキャッシュの組のことである。
/// 手立ては組み立ての側が渡す(本番は既定の装置に開く手立て、試験は開けなかったものとして開く手立てなど)。
/// キャッシュはスタックの一覧のサムネイルと同じ値から複製する(同じプロセスの書き込みを錠で1つずつ行うため。ライブラリ.md 判断11)。
/// 注意: 重ね合わせのライブラリは `overlays` の錠を持つため、作業場へ渡すまでここで持ち、アプリを落とすときはスタックのライブラリより先に放す(`前に出ている作業場`)。
pub(crate) struct 重ね合わせの側の作り方 {
    pub(crate) 画面描画の共有状態: egui::Context,
    pub(crate) 流れを開く手立て: Box<dyn 二本目の流れを開く手立て>,
    pub(crate) 重ね合わせのライブラリ: Option<裏で動く重ね合わせのライブラリ>,
    pub(crate) サムネイルのキャッシュ: サムネイルのキャッシュ,
}

impl 重ね合わせの側の作り方 {
    /// 重ね合わせを開いていない作業場を、渡した音の出力の状況で作る。重ね合わせのライブラリは作業場へ渡す(作り方には残らない)。
    /// 重ね合わせの側を作るのは1回だけであり(`前に出ている作業場` が控えた側を使い回す)、2回目に作るときはライブラリを持たない。
    pub(super) fn 作業場を作る(
        &mut self,
        音の出力: 重ね合わせの音の出力の状況,
    ) -> 重ね合わせの作業場 {
        let ライブラリ = 重ね合わせのライブラリの状態::作成する(
            self.重ね合わせのライブラリ.take(),
            self.画面描画の共有状態.clone(),
            self.サムネイルのキャッシュ.clone(),
        );
        重ね合わせの作業場::開いていない作業場(
            self.画面描画の共有状態.clone(),
            音の出力,
            ライブラリ,
        )
    }

    /// 作業場へ渡す前の重ね合わせのライブラリを放す(`overlays` の錠を放す)。アプリを落とすときに、スタックのライブラリの錠より先に呼ぶ。
    pub(super) fn 重ね合わせのライブラリを放す(&mut self) {
        drop(self.重ね合わせのライブラリ.take());
    }
}
