//! 見る側の設定の保存係。変化の見張り(`settings_watch.rs`)が保存すると答えたら settings.json へ書く。書くのは、変えてから1秒落ち着いた時点と、
//! アプリを閉じるときである。ライブラリの錠を持たない(読み取り専用で起動した)アプリは書かない。参照: _doc/設計/画面.md 判断17

use std::time::Instant;

use super::settings_watch::{見た結果, 設定の変化の見張り};
use crate::persistence::アプリの設定の保管場所;
use crate::state::アプリの状態;
use crate::viewer_settings::見る側の設定;

/// 設定の書き方とは、見る側の設定を settings.json へ書くか、書かないかの区別のことである。
/// ライブラリの錠を持たないアプリ(2つ目に起動して読み取り専用になったアプリと、置き場所の無いアプリ)は書かない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 設定の書き方 {
    書く,
    書かない,
}

/// 失敗の知らせとは、書けなかったことを通知で知らせたかの区別のことである。同じ起動の間に同じ失敗を何度も知らせないため、最初の1回だけ知らせる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 失敗の知らせ {
    まだ,
    知らせた,
}

/// 見る側の設定の保存係とは、アプリの設定の保管場所と、書き方と、変化の見張りと、失敗を知らせたかを持ち、見る側の設定を書くもののことである。
pub(crate) struct 見る側の設定の保存係 {
    保管場所: アプリの設定の保管場所,
    書き方: 設定の書き方,
    見張り: 設定の変化の見張り,
    知らせ: 失敗の知らせ,
}

impl 見る側の設定の保存係 {
    /// 起動したときに読んだ設定を、最後に書いた設定として作る。
    pub(crate) fn 作成する(
        保管場所: アプリの設定の保管場所,
        書き方: 設定の書き方,
        読んだ設定: 見る側の設定,
    ) -> Self {
        Self {
            保管場所,
            書き方,
            見張り: 設定の変化の見張り::読んだ設定から始める(読んだ設定),
            知らせ: 失敗の知らせ::まだ,
        }
    }

    /// 毎フレーム呼ぶ。今の設定が変わって落ち着いたら書き、書けなければ最初の1回だけ通知で知らせる。
    /// 最後に、保存するまでの残り時間を状態へ置く(入力が無くてもその時刻に画面を進めるため。画面が描き直しの予約に使う)。
    pub(crate) fn 進める(&mut self, 状態: &mut アプリの状態, 今: Instant) {
        if self.書き方 == 設定の書き方::書かない {
            return;
        }
        if let 見た結果::保存する(設定) = self.見張り.見る(状態.見る側の設定(), 今)
        {
            self.書く(状態, 設定);
        }
        状態.見る側の設定を保存するまでの時間 = self.見張り.保存するまでの残り時間(今);
    }

    /// アプリを閉じるときに呼ぶ。書いた設定と違えば、落ち着くのを待たずに書く。
    pub(crate) fn 終わる前に書く(&mut self, 状態: &mut アプリの状態) {
        if self.書き方 == 設定の書き方::書かない {
            return;
        }
        if let 見た結果::保存する(設定) = self.見張り.終わる前に見る(状態.見る側の設定())
        {
            self.書く(状態, 設定);
        }
    }

    fn 書く(&mut self, 状態: &mut アプリの状態, 設定: 見る側の設定) {
        let Err(理由) = self.保管場所.見る側の設定を保存する(設定) else {
            return;
        };
        if self.知らせ == 失敗の知らせ::まだ {
            self.知らせ = 失敗の知らせ::知らせた;
            状態.通知.出す(format!(
                "ウインドウの大きさ・音量などの見る側の設定を保存できない(同じ起動の間は、この知らせを繰り返さない): {理由}"
            ));
        }
    }
}
