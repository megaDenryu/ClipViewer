//! 組み立て。起動の準備から、保存した設定を読み、FFmpeg を探し、音声出力装置とライブラリとサムネイルのキャッシュをつないで
//! クリップビューアーを組み立てる(コンポジションルート)。起動の受け口と起動の頼みの扱いは `launch_requests.rs` に置く。

use eframe::egui;
use video_source::{FFmpegの置き場所の設定, FFmpegを置いたフォルダ};

use super::launch_preparation::起動の準備;
use super::sound_sender::音の送り手;
use super::viewer_settings_save::{見る側の設定の保存係, 設定の書き方};
use super::クリップビューアー;
use crate::command::操作の適用係;
use crate::persistence::{
    FFmpegの置き場所の候補, サムネイルのキャッシュを決める
};
use crate::state::library::ライブラリの接続;
use crate::state::{アプリの状態, 音の出力の状況};
use crate::thumbnail_feed::一覧のサムネイル;

impl クリップビューアー {
    /// 保存した設定を読み、FFmpeg を探して組み立て、起動の受け口で受け取り始め、起動の頼みを当てる。
    /// 設定を読めなくても起動は止めず、通知で知らせる。
    pub(crate) fn 組み立てる(eguiの本体: egui::Context, 準備: 起動の準備) -> Self {
        let 書き方 = if 準備.ライブラリの錠を持つか() {
            設定の書き方::書く
        } else {
            設定の書き方::書かない
        };
        let 環境 = 準備.環境;
        let 保管場所 = 準備.保管場所;
        let 設定の保存係 =
            見る側の設定の保存係::作成する(保管場所.clone(), 書き方, 準備.見る側);
        let (保存した置き場所, 読めない理由) = match 保管場所.ffmpegの置き場所を読む() {
            Ok(置き場所) => (置き場所, None),
            Err(理由) => (FFmpegの置き場所の設定::未設定, Some(理由.to_string())),
        };
        let 候補 = FFmpegの置き場所の候補 {
            環境変数のフォルダ: 環境
                .ffmpegのフォルダ
                .map(FFmpegを置いたフォルダ::作成する),
            保存した置き場所,
        };
        let (音の送り手, 音の出力) = 音の送り手::既定の装置を開く();
        let 接続 = ライブラリの接続::錠を試したライブラリから起動する(
            準備.ライブラリ,
        );
        let キャッシュ =
            サムネイルのキャッシュを決める(環境.ローカルのアプリのデータのフォルダ);
        let サムネイル = 一覧のサムネイル::作成する(eguiの本体.clone(), キャッシュ);
        let mut 適用係 =
            操作の適用係::作成する(保管場所, 環境.検索パス, eguiの本体.clone());
        let ffmpegの状況 = 適用係.ffmpegを探す(&候補.使う置き場所());
        let mut 状態 = アプリの状態::起動時(ffmpegの状況, 音の出力.clone(), サムネイル);
        状態.ライブラリ.接続 = 接続;
        状態.見る側の設定を当てる(準備.見る側);
        状態.一覧を読み直す();
        if let Some(理由) = 読めない理由 {
            状態.通知.出す(format!("アプリの設定を読めない: {理由}"));
        }
        if let 音の出力の状況::使えない(理由) = 音の出力 {
            状態
                .通知
                .出す(format!("{理由}。音を鳴らさずに映像だけで再生する"));
        }
        let mut ビューアー = Self {
            状態,
            適用係,
            音の送り手,
            起動の受け口: None,
            設定の保存係,
        };
        ビューアー.起動の受け口で受け取り始めて頼みを当てる(
            準備.受け口,
            eguiの本体,
            準備.頼み,
            準備.知らせ,
        );
        ビューアー
    }
}
