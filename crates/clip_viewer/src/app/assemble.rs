//! 組み立て。起動の準備から、保存した設定を読み、FFmpeg を探し、音声出力装置とライブラリとサムネイルのキャッシュをつないで
//! クリップビューアーを組み立てる(コンポジションルート)。起動の受け口と起動の頼みの扱いは `launch_requests.rs` に置く。
//! 起動の準備から読むこと(設定の書き方・FFmpeg の置き場所の候補)は起動の準備のメソッドに、重ね合わせの側の作り方は作り方の型に置き、
//! スタックの作業場(状態と操作の適用係)を組む工程は、このファイルの私有の関数に分ける。

use clip_library::錠を試したライブラリ;
use eframe::egui;
use thumbnail_cache::サムネイルのキャッシュ;

use super::close_procedure::アプリを閉じる手順;
use super::front_workspace::前に出ている作業場;
use super::launch_preparation::起動の準備;
use super::overlay_side_recipe::重ね合わせの側の作り方;
use super::sound_sender::音の送り手;
use super::viewer_settings_save::見る側の設定の保存係;
use super::クリップビューアー;
use crate::command::操作の適用係;
use crate::persistence::サムネイルのキャッシュを決める;
use crate::state::library::ライブラリの接続;
use crate::state::{アプリの状態, 音の出力の状況};
use crate::thumbnail_feed::一覧のサムネイル;

impl クリップビューアー {
    /// 保存した設定を読み、FFmpeg を探して組み立て、起動の受け口で受け取り始め、起動の頼みを当てる。
    /// 設定を読めなくても起動は止めず、通知で知らせる。
    pub(crate) fn 組み立てる(
        画面描画の共有状態: egui::Context, mut 準備: 起動の準備
    ) -> Self {
        let 書き方 = 準備.設定の書き方();
        let 設定の保存係 = 見る側の設定の保存係::作成する(
            準備.保管場所.clone(),
            書き方,
            準備.見る側,
        );
        let (音の送り手, 音の出力) = 音の送り手::既定の装置を開く();
        let (重ね合わせのライブラリ, スタックのライブラリ) = 準備
            .ライブラリ
            .take()
            .map(|組| (組.重ね合わせ, 組.スタック))
            .unzip();
        let キャッシュ = サムネイルのキャッシュを決める(
            準備.環境.ローカルのアプリのデータのフォルダ.clone(),
        );
        let (状態, 適用係) = スタックの作業場を組む(
            &画面描画の共有状態,
            &準備,
            音の出力,
            スタックのライブラリ,
            &キャッシュ,
        );
        let 作り方 = 重ね合わせの側の作り方::起動のときに作る(
            画面描画の共有状態.clone(),
            重ね合わせのライブラリ,
            キャッシュ,
        );
        let mut ビューアー = Self {
            状態,
            適用係,
            音の送り手,
            起動の受け口: None,
            設定の保存係,
            前に出ている作業場: 前に出ている作業場::起動時(作り方),
            閉じる手順: アプリを閉じる手順::default(),
        };
        ビューアー.起動の受け口で受け取り始めて頼みを当てる(
            準備.受け口,
            画面描画の共有状態,
            準備.頼み,
            準備.知らせ,
        );
        ビューアー
    }
}

/// スタックの作業場(アプリの状態と操作の適用係)を組む。FFmpeg を探し、見る側の設定を当て、スタックのライブラリへつないで一覧を読み直す。
/// 設定を読めなかったときと、音を鳴らせないときは、その旨を通知に出す。
fn スタックの作業場を組む(
    画面描画の共有状態: &egui::Context,
    準備: &起動の準備,
    音の出力: 音の出力の状況,
    スタックのライブラリ: Option<錠を試したライブラリ>,
    キャッシュ: &サムネイルのキャッシュ,
) -> (アプリの状態, 操作の適用係) {
    let (候補, 読めない理由) = 準備.ffmpegの置き場所の候補を読む();
    let mut 適用係 = 操作の適用係::作成する(
        準備.保管場所.clone(),
        準備.環境.検索パス.clone(),
        画面描画の共有状態.clone(),
    );
    let サムネイル =
        一覧のサムネイル::作成する(画面描画の共有状態.clone(), キャッシュ.clone());
    let ffmpegの状況 = 適用係.ffmpegを探す(&候補.使う置き場所());
    let mut 状態 = アプリの状態::起動時(ffmpegの状況, 音の出力.clone(), サムネイル);
    状態.見る側の設定を当てる(準備.見る側);
    状態.ライブラリ.接続 =
        ライブラリの接続::錠を試したライブラリから起動する(
            スタックのライブラリ,
        );
    状態.一覧を読み直す();
    if let Some(理由) = 読めない理由 {
        状態.通知.出す(format!("アプリの設定を読めない: {理由}"));
    }
    if let 音の出力の状況::使えない(理由) = 音の出力 {
        状態
            .通知
            .出す(format!("{理由}。音を鳴らさずに映像だけで再生する"));
    }
    (状態, 適用係)
}
