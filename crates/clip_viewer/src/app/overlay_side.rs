//! 重ね合わせの側。重ね合わせの作業場と、その音を鳴らす2本目の流れの送り手を、初めて重ね合わせの作業場へ移るときに一緒に作って一緒に持つ。
//! 「重ね合わせの作業場があるのに送り手が無い」状態を型で表せなくするため、2つを1つの型にまとめる。参照: _doc/設計/同時再生.md 3-2・5-3

use std::time::Instant;

use clip_domain::クリップ識別子;
use video_source::動画の読み手;

use super::overlay_side_recipe::重ね合わせの側の作り方;
use super::overlay_sound_sender::重ね合わせの音の送り手;
use super::stack_values::{
    スタックの保存の観測結果を求める, 今のスタックの値を借りる
};
use crate::overlay::{
    今のスタックの値, 重ね合わせの作業場, 重ね合わせの操作
};
use crate::primary_button::主ボタンの様子;
use crate::state::アプリの状態;

/// 重ね合わせの側とは、重ね合わせの作業場と、その音を鳴らす重ね合わせの音の送り手の組のことである。
pub(crate) struct 重ね合わせの側 {
    pub(super) 作業場: 重ね合わせの作業場,
    送り手: 重ね合わせの音の送り手,
}

impl 重ね合わせの側 {
    /// 2本目の流れを開き、その音の出力の状況で重ね合わせを開いていない作業場を作る。開けなかったら、作る時点で作業場の知らせに出す。
    pub(super) fn 作る(作り方: &mut 重ね合わせの側の作り方) -> Self {
        let 送り手 =
            重ね合わせの音の送り手::手立てで開く(作り方.流れを開く手立て.as_ref());
        let mut 作業場 = 作り方.作業場を作る(送り手.出力の状況());
        作業場.開けなかった音の出力を知らせる();
        Self {
            作業場, 送り手
        }
    }

    /// 重ね合わせの作業場を読む。画面を組むときと、試験が状態を確かめるときに読む。
    pub(crate) fn 作業場(&self) -> &重ね合わせの作業場 {
        &self.作業場
    }

    /// 書き換えられる重ね合わせの作業場。試験で、作業場の口を直接呼ぶために使う。
    #[cfg(test)]
    pub(crate) fn 作業場を書き換える(&mut self) -> &mut 重ね合わせの作業場 {
        &mut self.作業場
    }

    /// 前に出ている間、毎フレーム呼ぶ。スタックの保存の失敗を知らせに写し、重ね合わせのライブラリの書き込みと一覧のサムネイルを進め、
    /// 作業場の時計と供給を進め、組み立てた行ごとの再生の指示を2本目の流れへ渡す。サムネイルを撮る読み手は、配線がスタックの作業場から借りる。
    /// 掛ける音量は、スタックの作業場と共有する見る側の設定の鳴らす音量である(全体を消音していれば無音。オーナーの決定。同時再生.md 2-6)。
    pub(super) fn 前に出ている間のフレームを進める(
        &mut self,
        今: Instant,
        状態: &アプリの状態,
        読み手: Option<&動画の読み手>,
    ) {
        self.作業場
            .スタックの保存の失敗を知らせる(スタックの保存の観測結果を求める(状態));
        self.作業場.ライブラリとサムネイルを進める(今, 読み手);
        let 全体の鳴らす音量 = 今のスタックの値を借りる(状態).全体の音量.鳴らす音量;
        let 指示 = self.作業場.フレームを進める(今, 全体の鳴らす音量);
        self.送り手.指示を送る(指示, &mut self.作業場);
    }

    /// 控えている間、毎フレーム呼ぶ。どの行も黙る指示を渡し、重ね合わせのライブラリの書き込み(頼み直しと知らせの受け取り)と、サムネイルの結果の受け取りを進める。
    pub(super) fn 控えている間に黙らせる(&mut self, 今: Instant) {
        self.送り手.黙る指示を送る(今);
        self.作業場.控えている間にライブラリを進める(今);
    }

    /// スタックの作業場を前に出す時点で呼ぶ。再生を止めて行ごとの流し読みを閉じ、次の描き直しを待たずに黙る指示を1回渡す。
    pub(super) fn 控える(&mut self, 今: Instant) {
        self.作業場.控える前に再生を止める();
        self.送り手.黙る指示を送る(今);
    }

    /// 今のスタックの値から重ね合わせを並べて開く。読み手は配線がスタックの作業場の動画の開き手から借りる。
    pub(super) fn 今のスタックから並べる(
        &mut self,
        値: 今のスタックの値<'_>,
        読み手: Option<&動画の読み手>,
    ) {
        self.作業場.今のスタックから並べる(値, 読み手);
    }

    /// 今のスタックのクリップの写しを、開いている重ね合わせの今の再生の位置に置く(サイドバーの「置く」。同時再生.md 2-4)。
    pub(super) fn 今のスタックのクリップを置く(
        &mut self,
        クリップ: &クリップ識別子,
        値: 今のスタックの値<'_>,
    ) {
        self.作業場.今のスタックのクリップを置く(クリップ, 値);
    }

    /// 応答を適用した後に呼ぶ。主ボタンを押していないのに残った重ね合わせの作業場のドラッグを捨てる。
    pub(super) fn 取り残されたドラッグを捨てる(
        &mut self, 主ボタン: 主ボタンの様子
    ) {
        self.作業場.取り残されたドラッグを捨てる(主ボタン);
    }

    /// 重ね合わせの作業場の中の操作を当てる。
    pub(super) fn 操作を当てる(&mut self, 操作: 重ね合わせの操作) {
        self.作業場.操作を適用する(操作);
    }
}
