//! アプリを閉じる手順の型。ウインドウを閉じる要求を受けてから、2つの作業場(スタック・重ね合わせ)の決めを集めるまでの途中の様子を持つ。
//! 手順を進めること(両方が閉じてよいと決まったときにだけ当てること・「やめる」で何も当てずに捨てること)は `close_flow.rs` が行う。
//! 参照: _doc/設計/同時再生.md 2-7・2-8、_doc/設計/ライブラリ.md 判断5

/// スタックの決め方とは、閉じる手順の中で、スタックの作業場が閉じてよいと決まった経路の区別のことである。
/// 利用者が確かめるダイアログで決めたときだけ、閉じると決めた時点で開いているスタックとの関係を終える(アプリを落とすときに捨てた変更を保存しないため)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum スタックの決め方 {
    確かめて閉じてよかった,
    利用者が閉じてよいと決めた,
}

/// アプリを閉じる手順とは、ウインドウを閉じる要求を受けてから閉じると決めるまでの途中の様子のことである。
/// スタックの作業場を先に確かめ、閉じてよいと決まってから重ね合わせの作業場を確かめる。
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(super) enum アプリを閉じる手順 {
    #[default]
    閉じようとしていない,
    スタックの決めを待つ,
    重ね合わせの決めを待つ(スタックの決め方),
    閉じると決めた,
}

impl アプリを閉じる手順 {
    /// 閉じると決めたか。決めた後は、ウインドウへ閉じる指示を毎フレーム送り、閉じる要求を確かめずに通す。
    pub(super) fn 閉じると決めたか(self) -> bool {
        self == Self::閉じると決めた
    }

    /// 作業場の確かめるダイアログで利用者の決めを待っている途中か。途中の間は、起動の頼み(動画を開く)を断る(開くと確かめた変更が失われるため)。
    pub(super) fn 決めを待っている途中か(self) -> bool {
        matches!(
            self,
            Self::スタックの決めを待つ | Self::重ね合わせの決めを待つ(_)
        )
    }
}
