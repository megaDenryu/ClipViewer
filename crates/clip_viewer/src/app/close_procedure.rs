//! アプリを閉じる手順。ウインドウを閉じる要求を受けてから、2つの作業場(スタック・重ね合わせ)の決めを集め、両方が閉じてよいと決まったときにだけ、
//! スタックとの関係を終えることと、確かめずに閉じることを当てる。どちらかの確かめるダイアログで利用者が「やめる」を選んだら、何も当てずに手順を捨てる。
//! 参照: _doc/設計/同時再生.md 2-7・2-8、_doc/設計/ライブラリ.md 判断5

use std::time::Instant;

use super::クリップビューアー;
use crate::library_common::確かめた結果;
use crate::state::閉じる要求への答え;

/// スタックの決め方とは、閉じる手順の中で、スタックの作業場が閉じてよいと決まった経路の区別のことである。
/// 利用者が確かめるダイアログで決めたときだけ、閉じると決めた時点で開いているスタックとの関係を終える(アプリを落とすときに捨てた変更を保存しないため)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum スタックの決め方 {
    確かめて閉じてよかった,
    利用者が閉じてよいと決めた,
}

/// アプリを閉じる手順とは、ウインドウを閉じる要求を受けてから閉じると決めるまでの途中の様子のことである。
/// スタックの作業場を先に確かめ、閉じてよいと決まってから重ね合わせの作業場を確かめる。
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(super) enum アプリを閉じる手順 {
    #[default]
    閉じようとしていない,
    スタックの決めを待つ,
    重ね合わせの決めを待つ(スタックの決め方),
    閉じると決めた,
}

impl アプリを閉じる手順 {
    /// 閉じると決めたか。決めた後は、ウインドウへ閉じる指示を毎フレーム送り、閉じる要求を確かめずに通す。
    pub(super) fn 閉じると決めたか(self) -> bool {
        self == Self::閉じると決めた
    }
}

impl クリップビューアー {
    /// ウインドウを閉じる要求を受けた。閉じる手順が閉じると決めていれば閉じてよい。そうでなければ手順を始め直し、開いているスタックの保存を確かめる。
    /// 書けなければ確かめるダイアログを出してスタックの作業場を前に出し(重ね合わせが前でも)、閉じるのをやめる。
    /// スタックが閉じてよいと分かってから重ね合わせの作業場(前に出ているか控えている)を確かめる(参照: _doc/設計/同時再生.md 2-7・2-8)。
    pub(crate) fn 閉じる要求を確かめる(
        &mut self,
        今: Instant,
    ) -> 閉じる要求への答え {
        if self.閉じる手順.閉じると決めたか() {
            return 閉じる要求への答え::閉じてよい;
        }
        if self.状態.閉じる要求を確かめる() == 閉じる要求への答え::閉じるのをやめる
        {
            self.閉じる手順 = アプリを閉じる手順::スタックの決めを待つ;
            self.スタックの作業場を前に出す(今);
            return 閉じる要求への答え::閉じるのをやめる;
        }
        self.重ね合わせを確かめる(スタックの決め方::確かめて閉じてよかった, 今)
    }

    /// スタックが閉じてよいと決まった後に、重ね合わせの作業場を確かめる。確かめるダイアログを出したら重ね合わせの作業場を前に出して決めを待ち、
    /// 出さなければ(まだ作っていなければ)閉じると決める。
    fn 重ね合わせを確かめる(
        &mut self,
        スタック: スタックの決め方,
        今: Instant,
    ) -> 閉じる要求への答え {
        let ダイアログを出したか = self
            .前に出ている作業場
            .重ね合わせの作業場を書き換える()
            .is_some_and(|作業場| {
                作業場.閉じる要求を確かめる()
                    == 確かめた結果::確かめるダイアログを出した
            });
        if !ダイアログを出したか {
            self.閉じると決める(スタック);
            return 閉じる要求への答え::閉じてよい;
        }
        self.閉じる手順 = アプリを閉じる手順::重ね合わせの決めを待つ(スタック);
        self.重ね合わせの作業場へ移る(今);
        閉じる要求への答え::閉じるのをやめる
    }

    /// 2つの作業場がどちらも閉じてよいと決まった。利用者がスタックの確かめるダイアログで決めていたなら、ここで開いているスタックとの関係を終える。
    fn 閉じると決める(&mut self, スタック: スタックの決め方) {
        if スタック == スタックの決め方::利用者が閉じてよいと決めた {
            self.状態.開いているスタックとの関係を終える();
        }
        self.閉じる手順 = アプリを閉じる手順::閉じると決めた;
    }

    /// 応答を適用した後に毎フレーム呼ぶ。2つの作業場から閉じてよいとの決めを取り出し、待っている作業場が決めていれば手順を進める。
    /// 待っている作業場が確かめるダイアログを出していなければ(利用者が「やめる」を選んだ)、何も当てずに手順を捨てる。
    pub(super) fn 閉じる手順を進める(&mut self, 今: Instant) {
        let スタックが決めたか = self
            .状態
            .閉じてよいとの決めを取り出す()
            .閉じてよいと決めたか();
        let 重ね合わせ = self.前に出ている作業場.重ね合わせの作業場を書き換える();
        let 重ね合わせが待っているか = 重ね合わせ
            .as_ref()
            .is_some_and(|作業場| 作業場.アプリを閉じる前の確かめを出しているか());
        let 重ね合わせが決めたか = 重ね合わせ
            .is_some_and(|作業場| 作業場.閉じてよいとの決めを取り出す().閉じてよいと決めたか());
        use アプリを閉じる手順::{
            スタックの決めを待つ, 重ね合わせの決めを待つ
        };
        let 捨てた手順 = アプリを閉じる手順::閉じようとしていない;
        match self.閉じる手順 {
            スタックの決めを待つ if スタックが決めたか => {
                let 利用者が決めた =
                    スタックの決め方::利用者が閉じてよいと決めた;
                self.重ね合わせを確かめる(利用者が決めた, 今);
            }
            スタックの決めを待つ if !self.状態.アプリを閉じる前の確かめを出しているか() => {
                self.閉じる手順 = 捨てた手順
            }
            重ね合わせの決めを待つ(スタック) if 重ね合わせが決めたか => {
                self.閉じると決める(スタック)
            }
            重ね合わせの決めを待つ(_) if !重ね合わせが待っているか => {
                self.閉じる手順 = 捨てた手順
            }
            _ => {}
        }
    }
}
