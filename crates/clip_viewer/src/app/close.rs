//! 窓への指示の決め方。1フレームで受けた閉じる要求への答えと、利用者が変更を捨てて閉じると決めたかと、起動の受け口に頼みが届いたかと、
//! 状態が頼んだ全画面の出入りから、起動の部分が窓へ送る指示の並びを決める。閉じることの判断は状態(`state/app_close.rs`)が行い、egui の窓への指示の送り出しは起動の部分が行う。
//! 参照: _doc/設計/ライブラリ.md 判断5、_doc/設計/画面.md 判断13・判断16

use super::launch_requests::起動の頼みの届き方;
use super::クリップビューアー;
use crate::state::{
    全画面の様子, 窓の様子, 窓への頼み, 閉じる要求への答え
};
use crate::viewer_settings::窓の大きさ;

/// 窓への指示とは、1フレームの終わりに起動の部分が窓へ送る指示(閉じること・前に出すこと・全画面の出入り・大きさの変更)の区別のことである。
/// 1フレームに複数の指示を送りうるため、配線は指示の並びを決める(`窓への指示::並びを決める`)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 窓への指示 {
    閉じるのを取り消す,
    閉じる,
    /// 2つ目のアプリから頼みが届いたので、最小化を戻して窓を前に出す。
    前に出す,
    全画面にする(全画面の様子),
    大きさを変える(窓の大きさ),
}

impl 窓への指示 {
    /// 閉じる要求への答え(要求を受けなかったフレームでは無い)と、利用者が変更を捨てて閉じると決めたかと、起動の頼みの届き方と、
    /// 状態が頼んだ全画面の出入りと大きさの変更から、このフレームで送る指示の並びを決める。
    /// 閉じると決めたなら、閉じる指示だけにする(閉じる窓へほかの指示を送っても意味が無いため)。
    /// 要求を受けて閉じるのをやめると答えたなら、要求の取り消しを最初に置く(取り消さないと窓が閉じる)。続けて全画面の出入り、大きさの変更、最後に前に出す。
    /// 前に出すのを最後にするのは、全画面を変えた後の窓を前に出すためである。
    pub(crate) fn 並びを決める(
        答え: Option<閉じる要求への答え>,
        閉じると決めたか: bool,
        届き方: 起動の頼みの届き方,
        頼み: 窓への頼み,
    ) -> Vec<Self> {
        if 閉じると決めたか {
            return vec![Self::閉じる];
        }
        let 取り消し = (答え == Some(閉じる要求への答え::閉じるのをやめる))
            .then_some(Self::閉じるのを取り消す);
        let 前に出す = (届き方 == 起動の頼みの届き方::届いた).then_some(Self::前に出す);
        [
            取り消し,
            頼み.全画面.map(Self::全画面にする),
            頼み.大きさ.map(Self::大きさを変える),
            前に出す,
        ]
        .into_iter()
        .flatten()
        .collect()
    }
}

impl クリップビューアー {
    /// 窓を閉じる要求を受けた。開いているスタックの保存を確かめ、書けなければ確かめる窓を出して閉じるのをやめる。
    pub(crate) fn 閉じる要求を確かめる(&mut self) -> 閉じる要求への答え {
        self.状態.閉じる要求を確かめる()
    }

    /// 1フレームの手順を終えた後に、窓へ送る指示の並びを決める。届き方は、このフレームで `応答を適用する` が返したものである。
    /// 状態が頼んだ全画面の出入りと大きさの変更は、ここで取り出して並びに入れる。
    pub(crate) fn 窓への指示の並び(
        &mut self,
        答え: Option<閉じる要求への答え>,
        届き方: 起動の頼みの届き方,
    ) -> Vec<窓への指示> {
        let 頼み = self.状態.窓.頼みを取り出す();
        窓への指示::並びを決める(答え, self.状態.閉じると決めたか(), 届き方, 頼み)
    }

    /// 起動の部分が egui から読んだ窓の様子を状態へ知らせる。毎フレーム、状態を進める前に呼ぶ。
    pub(crate) fn 窓の様子を知らせる(&mut self, 様子: 窓の様子) {
        self.状態.窓.様子を知らせる(様子);
    }
}
