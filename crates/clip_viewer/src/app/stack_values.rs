//! スタックの作業場から重ね合わせの作業場へ渡す値。重ね合わせの作業場の層は `アプリの状態` を知らないため、配線が `アプリの状態` から読んで値にする。
//! 渡すのは、今のスタックの値(「今のスタックから並べる」が読むもの)と、見たスタックの保存(作業場を移る前に頼んだ保存の失敗を写すもの)である。
//! 参照: _doc/設計/同時再生.md 2-2・2-8・3-3

use super::クリップビューアー;
use crate::overlay::{
    今のスタックの値, 見たスタックの保存, 開いている動画の値
};
use crate::state::library::{保存の段階, 開いているスタック};
use crate::state::アプリの状態;

/// スタックの作業場の状態から、今のスタックと、開いている動画のパスと長さと、出力のアスペクト比を借りる。
/// 配線が重ね合わせの作業場を可変で借りている間にも読めるよう、`クリップビューアー` でなくアプリの状態だけを借りる。
pub(super) fn 今のスタックの値を借りる(
    状態: &アプリの状態,
) -> 今のスタックの値<'_> {
    今のスタックの値 {
        スタック: &状態.並び,
        開いている動画: 状態.動画.as_ref().map(|動画| 開いている動画の値 {
            パス: 動画.情報().パス(),
            長さ: 動画.情報().長さ(),
        }),
        出力のアスペクト比: 状態.出力.アスペクト比,
    }
}

impl クリップビューアー {
    /// スタックの作業場の開いているスタックの保存の様子を見る。登録していないスタックは保存しないため、失敗していないとする。
    pub(super) fn スタックの保存を見る(&self) -> 見たスタックの保存 {
        let 開いているスタック::登録済み(登録済み) = &self.状態.ライブラリ.開いている
        else {
            return 見たスタックの保存::失敗していない;
        };
        match 登録済み.保存の様子().段階(self.状態.並び.一覧()) {
            保存の段階::保存に失敗(失敗) => 見たスタックの保存::失敗した {
                理由: 失敗.to_string(),
            },
            保存の段階::保存中 => 見たスタックの保存::結果を待っている,
            保存の段階::保存済み | 保存の段階::変更を保存待ち => {
                見たスタックの保存::失敗していない
            }
        }
    }
}
