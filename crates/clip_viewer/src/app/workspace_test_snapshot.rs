//! 作業場を移すことの試験の道具のうち、スタックの作業場の写し。作業場を行き来する前と後、キーを押す前と後で比べる。

use super::クリップビューアー;
use crate::state::画面の構え;

/// スタックの作業場の写しとは、作業場を行き来しても変わってはならないスタックの作業場の値を、比べられる形で写したもののことである。
/// 型が等しさを持たない値(並び・編集の履歴・再生の状況の各項目)は、Debug の表記で写す。再生しているかは含めない(作業場を移ると止まるため)。
/// 見る側の設定の音量は消音を写さないため、音量の設定(消音の様子を含む)を別に写す。
#[derive(Debug, PartialEq)]
pub(super) struct スタックの作業場の写し {
    並び: String,
    履歴: String,
    取り消せるか: bool,
    やり直せるか: bool,
    再生の位置: String,
    位置を飛ばした回数: String,
    音量の設定: String,
    シーク: String,
    全体の末尾: String,
    構え: 画面の構え,
    見る側の設定: String,
    ライブラリのダイアログ: String,
    キーの一覧: String,
    最新の通知: String,
}

impl スタックの作業場の写し {
    pub(super) fn 写しを取る(ビューアー: &クリップビューアー) -> Self {
        let 状態 = &ビューアー.状態;
        Self {
            並び: format!("{:?}", 状態.並び),
            履歴: format!("{:?}", 状態.履歴),
            取り消せるか: 状態.取り消せるか(),
            やり直せるか: 状態.やり直せるか(),
            再生の位置: format!("{:?}", 状態.再生.位置()),
            位置を飛ばした回数: format!("{:?}", 状態.再生.飛ばした回数()),
            音量の設定: format!("{:?}", 状態.再生.音量),
            シーク: format!("{:?}", 状態.再生.シーク),
            全体の末尾: format!("{:?}", 状態.再生.全体の末尾),
            構え: 状態.出力.構え,
            見る側の設定: format!("{:?}", 状態.見る側の設定()),
            ライブラリのダイアログ: format!("{:?}", 状態.ライブラリ.ダイアログ),
            キーの一覧: format!("{:?}", 状態.キーの一覧),
            最新の通知: format!("{:?}", 状態.通知.最新()),
        }
    }
}
