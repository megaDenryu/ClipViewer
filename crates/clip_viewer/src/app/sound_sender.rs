//! 音の送り手。起動時に音声出力装置を開き、毎フレーム状態から組み立てた再生の指示を音声のスレッドへ渡す。

use std::time::Instant;

use audio_output::音声出力;

use super::instruction_receiver::再生の指示の受け口;
use crate::state::{アプリの状態, 音の出力の状況};

/// 音の送り手とは、開いた音声出力(再生の指示の受け口)か、装置を開けなかったことの区別のことである。
/// 装置を開けなかったときも同じ型で持ち、送る操作は何もしない(映像だけで再生を続ける)。
/// 受け口を口として持つのは、試験が渡した指示を覚える受け口に差し替えて、配線が渡した指示を観測するためである。
pub(crate) enum 音の送り手 {
    装置あり(Box<dyn 再生の指示の受け口>),
    装置なし,
}

impl 音の送り手 {
    /// 既定の音声出力装置を開く。開けなければ、その理由を持った音の出力の状況と、送る操作が何もしない送り手を返す。
    pub(crate) fn 既定の装置を開く() -> (Self, 音の出力の状況) {
        match 音声出力::既定の装置を開く() {
            Ok(出力) => {
                let 周波数 = 出力.周波数();
                (
                    Self::装置あり(Box::new(出力)),
                    音の出力の状況::使える(周波数),
                )
            }
            Err(失敗) => (Self::装置なし, 音の出力の状況::使えない(失敗)),
        }
    }

    /// 状態から再生の指示を組み立てて渡す。装置が途中で使えなくなっていたら、状態の音の出力の状況へ写して通知を出す。
    pub(crate) fn 指示を送る(&self, 状態: &mut アプリの状態, 今: Instant) {
        let Self::装置あり(出力) = self else {
            return;
        };
        出力.指示を渡す(状態.音の再生の指示(今));
        let Some(失敗) = 出力.使えなくなった理由() else {
            return;
        };
        if let 音の出力の状況::使える(_) = 状態.音の出力 {
            状態.通知.出す(format!("{失敗}。映像だけで再生を続ける"));
            状態.音の出力 = 音の出力の状況::使えない(失敗);
        }
    }
}
