//! 重ね合わせの音の送り手。スタックの作業場の音声出力と同じ既定の装置へ開いた2本目の流れ(行を混ぜる音声出力)を持ち、
//! 重ね合わせの作業場が組み立てた行ごとの再生の指示か、どの行も黙る指示を渡す。重ね合わせの側(`overlay_side.rs`)が作業場と一緒に持つ。
//! 参照: _doc/設計/同時再生.md 5-3

use std::time::Instant;

use audio_output::{
    行ごとの再生の指示, 行を混ぜる音声出力, 音声出力のエラー
};

use crate::overlay::{重ね合わせの作業場, 重ね合わせの音の出力の状況};

/// 重ね合わせの音の送り手とは、開いた2本目の流れか、開けなかったこと(その理由)の区別のことである。
/// 開けなかったときも同じ型で持ち、送る操作は何もしない(重ね合わせの作業場は映像だけで再生する)。スタックの作業場の音の送り手とは別に持つ。
/// 試験では装置を開かず、開けなかったことも知らせない送り手を使う。
pub(crate) enum 重ね合わせの音の送り手 {
    装置あり(行を混ぜる音声出力),
    開けなかった(音声出力のエラー),
    #[cfg(test)]
    試験では開いていない,
}

impl 重ね合わせの音の送り手 {
    /// 既定の音声出力装置に2本目の流れを開く。開けなければ、その理由を持った送り手を返す。
    /// 画面のスレッドで開くため、装置を開く時間(開発機で約5ミリ秒)だけ画面が止まる。初めて重ね合わせの作業場へ移るときの1回だけである。
    pub(super) fn 既定の装置を開く() -> Self {
        match 行を混ぜる音声出力::既定の装置を開く() {
            Ok(出力) => Self::装置あり(出力),
            Err(失敗) => Self::開けなかった(失敗),
        }
    }

    /// 重ね合わせの作業場へ渡す音の出力の状況。
    pub(super) fn 出力の状況(&self) -> 重ね合わせの音の出力の状況 {
        match self {
            Self::装置あり(出力) => {
                重ね合わせの音の出力の状況::使える(出力.周波数())
            }
            Self::開けなかった(理由) => {
                重ね合わせの音の出力の状況::使えない(理由.clone())
            }
            #[cfg(test)]
            Self::試験では開いていない => {
                重ね合わせの音の出力の状況::使えない(音声出力のエラー::装置が無い)
            }
        }
    }

    /// 装置を開こうとして開けなかったか。開けなかったときだけ、作業場を作る時点で知らせる。
    pub(super) fn 開けなかったか(&self) -> bool {
        matches!(self, Self::開けなかった(_))
    }

    /// 行ごとの再生の指示を渡す。装置が途中で使えなくなっていたら、重ね合わせの作業場へ知らせる。
    pub(super) fn 指示を送る(
        &self,
        指示: 行ごとの再生の指示,
        作業場: &mut 重ね合わせの作業場,
    ) {
        let Self::装置あり(出力) = self else {
            return;
        };
        出力.指示を渡す(指示);
        if let Some(失敗) = 出力.使えなくなった理由() {
            作業場.音の出力が使えなくなったことを知らせる(失敗);
        }
    }

    /// どの行も黙る指示を渡す。スタックの作業場が前の間は毎フレーム、作業場を控える時点では1回呼ぶ。
    /// 控えている間も渡し続けるのは、音声のスレッドが行ごとに手放した出どころ(溜めた音と流れてくる音)を、指示を渡すたびに画面のスレッドで捨てるためである。
    pub(super) fn 黙る指示を送る(&self, 今: Instant) {
        if let Self::装置あり(出力) = self {
            出力.指示を渡す(行ごとの再生の指示::黙る(今));
        }
    }
}
