//! 重ね合わせの音の送り手。2本目の流れ(行ごとの再生の指示の受け口)を持ち、重ね合わせの作業場が組み立てた行ごとの再生の指示か、
//! どの行も黙る指示を渡す。重ね合わせの側(`overlay_side.rs`)が作業場と一緒に持つ。参照: _doc/設計/同時再生.md 5-3

use std::time::Instant;

use audio_output::{行ごとの再生の指示, 音声出力のエラー};

use super::instruction_receiver::{
    二本目の流れを開く手立て, 行ごとの再生の指示の受け口
};
use crate::overlay::{重ね合わせの作業場, 重ね合わせの音の出力の状況};

/// 重ね合わせの音の送り手とは、開いた2本目の流れ(行ごとの再生の指示の受け口)か、開けなかったこと(その理由)の区別のことである。
/// 開けなかったときも同じ型で持ち、送る操作は何もしない(重ね合わせの作業場は映像だけで再生する)。スタックの作業場の音の送り手とは別に持つ。
pub(crate) enum 重ね合わせの音の送り手 {
    装置あり(Box<dyn 行ごとの再生の指示の受け口>),
    開けなかった(音声出力のエラー),
}

impl 重ね合わせの音の送り手 {
    /// 手立てで2本目の流れを開く。開けなければ、その理由を持った送り手を返す。
    pub(super) fn 手立てで開く(手立て: &dyn 二本目の流れを開く手立て) -> Self {
        match 手立て.開く() {
            Ok(受け口) => Self::装置あり(受け口),
            Err(失敗) => Self::開けなかった(失敗),
        }
    }

    /// 重ね合わせの作業場へ渡す音の出力の状況。
    pub(super) fn 出力の状況(&self) -> 重ね合わせの音の出力の状況 {
        match self {
            Self::装置あり(受け口) => {
                重ね合わせの音の出力の状況::使える(受け口.周波数())
            }
            Self::開けなかった(理由) => {
                重ね合わせの音の出力の状況::使えない(理由.clone())
            }
        }
    }

    /// 行ごとの再生の指示を渡す。装置が途中で使えなくなっていたら、重ね合わせの作業場へ知らせる。
    pub(super) fn 指示を送る(
        &self,
        指示: 行ごとの再生の指示,
        作業場: &mut 重ね合わせの作業場,
    ) {
        let Self::装置あり(受け口) = self else {
            return;
        };
        受け口.指示を渡す(指示);
        if let Some(失敗) = 受け口.使えなくなった理由() {
            作業場.音の出力が使えなくなったことを知らせる(失敗);
        }
    }

    /// どの行も黙る指示を渡す。スタックの作業場が前の間は毎フレーム、作業場を控える時点では1回呼ぶ。
    /// 控えている間も渡し続けるのは、音声のスレッドが行ごとに手放した出どころ(溜めた音と流れてくる音)を、指示を渡すたびに画面のスレッドで捨てるためである。
    pub(super) fn 黙る指示を送る(&self, 今: Instant) {
        if let Self::装置あり(受け口) = self {
            受け口.指示を渡す(行ごとの再生の指示::黙る(今));
        }
    }
}
