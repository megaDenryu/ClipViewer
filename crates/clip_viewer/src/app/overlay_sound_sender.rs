//! 重ね合わせの音の送り手。初めて重ね合わせの作業場へ移ったときに、スタックの作業場の音声出力と同じ既定の装置へ2本目の流れ(行を混ぜる音声出力)を開き、
//! 毎フレーム、重ね合わせが前なら重ね合わせの作業場が組み立てた行ごとの再生の指示を、スタックの作業場が前の間はどの行も黙る指示を渡す。
//! 控えている間も黙る指示を渡し続けるのは、音声のスレッドが行ごとに手放した出どころ(溜めた音と流れてくる音)を、指示を渡すたびに画面のスレッドで捨てるためである。
//! 1回だけ渡すと、その指示を音声のスレッドが取り込んだ後に手放した出どころが、次に移るまで置き場に残る。参照: _doc/設計/同時再生.md 5-3

use std::time::Instant;

use audio_output::{
    行ごとの再生の指示, 行を混ぜる音声出力, 音声出力のエラー
};
use clip_domain::音量;

use super::front_workspace::前に出ている作業場;
use super::クリップビューアー;
use crate::overlay::{重ね合わせの作業場, 重ね合わせの音の出力の状況};

/// 重ね合わせの音の送り手とは、開いた2本目の流れか、開けなかったこと(その理由)の区別のことである。
/// 開けなかったときも同じ型で持ち、送る操作は何もしない(重ね合わせの作業場は映像だけで再生する)。スタックの作業場の音の送り手とは別に持つ。
pub(crate) enum 重ね合わせの音の送り手 {
    装置あり(行を混ぜる音声出力),
    装置なし(音声出力のエラー),
}

impl 重ね合わせの音の送り手 {
    /// 既定の音声出力装置に2本目の流れを開く。開けなければ、その理由を持った送り手を返す。
    /// 画面のスレッドで開くため、装置を開く時間だけ画面が止まる(初めて重ね合わせの作業場へ移るときの1回だけである)。
    pub(super) fn 既定の装置を開く() -> Self {
        match 行を混ぜる音声出力::既定の装置を開く() {
            Ok(出力) => Self::装置あり(出力),
            Err(失敗) => Self::装置なし(失敗),
        }
    }

    /// 重ね合わせの作業場へ渡す音の出力の状況。
    pub(super) fn 出力の状況(&self) -> 重ね合わせの音の出力の状況 {
        match self {
            Self::装置あり(出力) => {
                重ね合わせの音の出力の状況::使える(出力.周波数())
            }
            Self::装置なし(理由) => {
                重ね合わせの音の出力の状況::使えない(理由.clone())
            }
        }
    }

    /// 重ね合わせの作業場から行ごとの再生の指示を組み立てて渡す。装置が途中で使えなくなっていたら、重ね合わせの作業場へ知らせる。
    fn 重ね合わせの指示を送る(
        &self,
        作業場: &mut 重ね合わせの作業場,
        今: Instant,
        つまみの音量: 音量,
    ) {
        let Self::装置あり(出力) = self else {
            return;
        };
        出力.指示を渡す(作業場.行ごとの再生の指示(今, つまみの音量));
        if let Some(失敗) = 出力.使えなくなった理由() {
            作業場.音の出力が使えなくなった(失敗);
        }
    }

    /// どの行も黙る指示を渡す。スタックの作業場が前の間に呼ぶ。
    fn 黙る指示を送る(&self, 今: Instant) {
        if let Self::装置あり(出力) = self {
            出力.指示を渡す(行ごとの再生の指示::黙る(今));
        }
    }
}

impl クリップビューアー {
    /// 重ね合わせの作業場を前に出す。初めて移るときは、2本目の流れを開いてから、その音の出力の状況で重ね合わせの作業場を作り、
    /// 開けなかったら重ね合わせの作業場の知らせに出す。2回目からは、開いた送り手と控えた作業場をそのまま使う。
    pub(super) fn 音の流れを開いてから重ね合わせの作業場を前に出す(
        &mut self,
    ) {
        let 今開いたか = self.重ね合わせの音の送り手.is_none();
        let 音の出力 = self
            .重ね合わせの音の送り手
            .get_or_insert_with(重ね合わせの音の送り手::既定の装置を開く)
            .出力の状況();
        self.前に出ている作業場
            .重ね合わせを前に出す(&self.画面描画の共有状態, 音の出力);
        if 今開いたか
            && let 前に出ている作業場::重ね合わせが前(作業場) = &mut self.前に出ている作業場
        {
            作業場.開けなかった音の出力を知らせる();
        }
    }

    /// 2本目の流れを開いていれば、毎フレーム指示を渡す。重ね合わせが前なら重ね合わせの作業場の行ごとの指示を、スタックの作業場が前なら黙る指示を渡す。
    /// 音量のつまみの値は、スタックの作業場と共有する見る側の設定の、つまみで選んだ音量である。
    pub(super) fn 重ね合わせの音を送る(&mut self, 今: Instant) {
        let Some(送り手) = &self.重ね合わせの音の送り手 else {
            return;
        };
        match &mut self.前に出ている作業場 {
            前に出ている作業場::重ね合わせが前(作業場) => {
                送り手.重ね合わせの指示を送る(
                    作業場,
                    今,
                    self.状態.再生.音量.選んだ音量(),
                );
            }
            前に出ている作業場::スタックが前 { .. } => {
                送り手.黙る指示を送る(今)
            }
        }
    }
}
