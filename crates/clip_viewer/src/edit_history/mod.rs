//! 取り消しの履歴の共有の置き場。編集する値が変わるたびに変わる前の値を積み、取り消しとやり直しで値を戻す仕組みを、
//! スタックの作業場の編集の履歴(`state/history/`。値はクリップスタック)と重ね合わせの作業場の編集の履歴(`overlay/state/history.rs`。値は重ね合わせ)が共に使う。
//! 値を見て積むのは作業場ごとに毎フレームの1箇所であり、操作ごとに積む呼び出しを足さない(自動保存と同じ理由)。
//! 注意: この下では `crate::state`・`crate::command`・`crate::view`・`crate::overlay`・`crate::app` を使わない(`cargo xtask check-overlay-deps` が検査する)。
//! 参照: _doc/設計/画面.md 判断14、同時再生.md 2-6

use std::collections::VecDeque;

mod merge;

use merge::続けて変えた変化のまとめ;

/// 取り消せる値の数の上限。10クリップの並びは約2KB、8行に置いた重ね合わせも数KBなので、上限まで積んでも1MBに届かない。
const 取り消せる数の上限: usize = 100;

/// 履歴に積む値とは、取り消しの履歴が積んで戻す値の型が満たす約束のことである。
/// 編集として同じかは、取り消しの単位に数えない違い(スタックなら選択だけの違い)を除いて比べた結果である。
pub(crate) trait 履歴に積む値: Clone {
    /// 2つの値が、編集として同じか。違えば変化として積む。
    fn 編集として同じか(&self, 他: &Self) -> bool;
}

/// 取り消しの履歴とは、最後に見た値と、取り消せる値とやり直せる値と、続けて変えた変化のまとめの組のことである。
/// 型の引数の値は積む値の型、区別は続けて変える値の区別の型である。
/// 不変条件: 最後に見た値は、履歴を最後に進めたときの今の値である。取り消しとやり直しはこれを戻した値へ進める。
#[derive(Debug, Clone)]
pub(crate) struct 取り消しの履歴<値, 区別> {
    最後に見た: 値,
    取り消せる: VecDeque<値>,
    やり直せる: Vec<値>,
    まとめ: 続けて変えた変化のまとめ<区別>,
}

impl<値: 履歴に積む値, 区別: PartialEq> 取り消しの履歴<値, 区別> {
    /// 今の値から、取り消せるものもやり直せるものも無い履歴を始める。
    pub(crate) fn 今の値から始める(今の値: &値) -> Self {
        Self {
            最後に見た: 今の値.clone(),
            取り消せる: VecDeque::new(),
            やり直せる: Vec::new(),
            まとめ: 続けて変えた変化のまとめ::何もまとめていない(),
        }
    }

    /// 次に見る変化が、続けて変える値の変化であることを覚える。値を変える操作を当てるときに呼ぶ。
    pub(crate) fn 次の変化の値を覚える(&mut self, 変える値: 区別) {
        self.まとめ.次の変化の値を覚える(変える値);
    }

    /// 操作の区切りが来たことを覚える。
    pub(crate) fn 操作の区切りを覚える(&mut self) {
        self.まとめ.操作の区切りを覚える();
    }

    /// 今の値を見る。最後に見た値と編集として違えば、変わる前の値を積む。
    /// 同じ値を操作の区切りまで続けて変えている間は、前の変化とまとめる。
    pub(crate) fn 値を見る(&mut self, 今の値: &値) {
        let 区別 = self.まとめ.次の変化の値を取り出す();
        if !今の値.編集として同じか(&self.最後に見た) {
            let 前 = std::mem::replace(&mut self.最後に見た, 今の値.clone());
            if !self.まとめ.まとめるか(区別) {
                self.積む(前);
            }
        }
        self.まとめ.区切りを当てる();
    }

    /// 最後の変化を取り消した値。まだ見ていない変化があれば、先にそれを積んでから取り消す。取り消せなければ無い。
    pub(crate) fn 取り消す(&mut self, 今の値: &値) -> Option<値> {
        self.見ていない変化を積む(今の値);
        let 戻す値 = self.取り消せる.pop_back()?;
        let 今 = std::mem::replace(&mut self.最後に見た, 戻す値.clone());
        self.やり直せる.push(今);
        self.まとめ.直前を忘れる();
        Some(戻す値)
    }

    /// 取り消した変化をやり直した値。取り消した後に値を変えていれば、やり直せない(変えたことを積む)。
    pub(crate) fn やり直す(&mut self, 今の値: &値) -> Option<値> {
        if self.見ていない変化を積む(今の値) {
            return None;
        }
        let 進める値 = self.やり直せる.pop()?;
        let 今 = std::mem::replace(&mut self.最後に見た, 進める値.clone());
        self.取り消せる.push_back(今);
        self.まとめ.直前を忘れる();
        Some(進める値)
    }

    /// 取り消せる変化があるか。
    pub(crate) fn 取り消せるか(&self, 今の値: &値) -> bool {
        !self.取り消せる.is_empty() || !今の値.編集として同じか(&self.最後に見た)
    }

    /// やり直せる変化があるか。
    pub(crate) fn やり直せるか(&self, 今の値: &値) -> bool {
        !self.やり直せる.is_empty() && 今の値.編集として同じか(&self.最後に見た)
    }

    /// 最後に見た値から変わっていれば、変わる前の値を積んで今の値を最後に見た値にする。積んだかを返す。
    fn 見ていない変化を積む(&mut self, 今の値: &値) -> bool {
        if 今の値.編集として同じか(&self.最後に見た) {
            return false;
        }
        let 前 = std::mem::replace(&mut self.最後に見た, 今の値.clone());
        self.積む(前);
        true
    }

    /// 変わる前の値を積み、やり直せる値を捨てる。上限を超えたら古いものから捨てる。
    fn 積む(&mut self, 前: 値) {
        self.取り消せる.push_back(前);
        if self.取り消せる.len() > 取り消せる数の上限 {
            self.取り消せる.pop_front();
        }
        self.やり直せる.clear();
    }
}
