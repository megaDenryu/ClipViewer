//! アスペクト比設定の画面に出す名前。スタックの作業場の出力アスペクト比の選択欄(`view/text.rs` が再公開する)と、
//! 重ね合わせの作業場の縦横比の選択欄(`overlay/view/header.rs`)が共有する。2つの作業場の画面はお互いを知らないため、どちらにも属さない置き場にする。

use clip_domain::アスペクト比設定;

/// アスペクト比設定の選択欄に出す名前。
pub(crate) fn アスペクト比の名前(比: アスペクト比設定) -> &'static str {
    match 比 {
        アスペクト比設定::クロップ連動 => "クロップ枠に合わせる",
        アスペクト比設定::ワイド16対9 => "16:9",
        アスペクト比設定::スタンダード4対3 => "4:3",
        アスペクト比設定::正方形 => "1:1",
        アスペクト比設定::縦型9対16 => "9:16",
    }
}
