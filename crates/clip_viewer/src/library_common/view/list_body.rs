//! 一覧の本体の出し方と、道具の帯の件数の文。一覧の本体に、読んでいる・読めない・空の文を出すか、読めた一覧の行を並べるかを、
//! スタックの一覧と重ね合わせの一覧が、一覧の文言だけを替えて同じ分岐で決める。参照: _doc/設計/ライブラリ.md 判断8・判断11

use std::rc::Rc;

use clip_library::裏で行うライブラリ;
use sengen_egui::{ノード, 子, 文字表示, 縦積み};

use super::list_texts::一覧の文言;
use crate::library_common::list::{並べられる一覧, 最後に読んだ一覧};
use crate::library_common::save::保存物のライブラリの使える様子;
use crate::styles;

/// 一覧の本体の出し方とは、一覧の本体に文だけを出すか(置き場所が無いときは何も出さない)、読めた一覧の行を並べるかの区別のことである。
pub(crate) enum 一覧の本体の出し方<応答, 一覧> {
    文を出す(ノード<応答>),
    行を並べる(Rc<一覧>),
}

impl 一覧の文言 {
    /// 一覧の本体の出し方。置き場所が無いときは一覧を読まないため何も出さず(「一覧を読んでいる」を出さない)、読めた一覧が空でなければ行を並べる。
    pub(crate) fn 一覧の本体の出し方<
        ライブラリ: 裏で行うライブラリ,
        応答: 'static,
        一覧: 並べられる一覧,
    >(
        &self,
        様子: 保存物のライブラリの使える様子<'_, ライブラリ>,
        最後に読んだ: &最後に読んだ一覧<一覧>,
    ) -> 一覧の本体の出し方<応答, 一覧> {
        let 文 = match (様子, 最後に読んだ) {
            (保存物のライブラリの使える様子::置き場所が無い, _) => {
                sengen_egui::無し()
            }
            (_, 最後に読んだ一覧::まだ無い) => {
                文字表示("一覧を読んでいる").装飾(styles::補足).into()
            }
            (_, 最後に読んだ一覧::読めない(理由)) => {
                文字表示(format!("{}を読めない: {理由}", self.フォルダの呼び名))
                    .装飾(styles::不備の文)
                    .into()
            }
            (_, 最後に読んだ一覧::読めた(一覧)) if 一覧.項目の数() == 0 => {
                縦積み(子![
                    文字表示(self.空のときの文),
                    文字表示(self.空のときの案内).装飾(styles::補足),
                ])
                .into()
            }
            (_, 最後に読んだ一覧::読めた(一覧)) => {
                return 一覧の本体の出し方::行を並べる(Rc::clone(一覧));
            }
        };
        一覧の本体の出し方::文を出す(文)
    }
}

/// 道具の帯に出す件数の文。読めた一覧なら「3件」の形(読めないファイルも数える)、まだ読んでいないか読めないなら空である。
pub(crate) fn 件数の文<一覧: 並べられる一覧>(
    最後に読んだ: &最後に読んだ一覧<一覧>,
) -> String {
    match 最後に読んだ {
        最後に読んだ一覧::読めた(一覧) => format!("{}件", 一覧.項目の数()),
        最後に読んだ一覧::まだ無い | 最後に読んだ一覧::読めない(_) => {
            String::new()
        }
    }
}
