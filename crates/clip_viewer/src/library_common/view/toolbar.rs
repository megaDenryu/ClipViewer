//! 一覧の絞り込みと並べ替えの部品。「名前で絞り込む」の欄と並べ替えの選択欄を、スタックの一覧と重ね合わせの一覧が、応答の型だけを替えて共に使う。

use sengen_egui::{ノード, 一行テキスト入力, 子, 画素, 選択欄, 選択肢};

use crate::library_common::list::並べ替え方;

/// 並べ替えの選択欄に出す名前。
fn 並べ替え方の名前(並べ替え: 並べ替え方) -> &'static str {
    match 並べ替え {
        並べ替え方::更新日時の新しい順 => "更新日時の新しい順",
        並べ替え方::更新日時の古い順 => "更新日時の古い順",
        並べ替え方::名前順 => "名前順",
        並べ替え方::作った日時の新しい順 => "作った日時の新しい順",
    }
}

/// 一覧の絞り込みと並べ替えの部品の材料とは、今の絞り込みの語の文字列と今の並べ替え方と、選択欄の識別子と、2つの部品が発する応答の作り方の組のことである。
pub(crate) struct 絞り込みと並べ替えの材料<'語, 応答> {
    pub(crate) 絞り込みの文字列: &'語 str,
    pub(crate) 並べ替え: 並べ替え方,
    pub(crate) 並べ替えの識別子: &'static str,
    pub(crate) 絞り込みを書き換えた: fn(String) -> 応答,
    pub(crate) 並べ替えを選んだ: fn(並べ替え方) -> 応答,
}

impl<応答: Clone + 'static> 絞り込みと並べ替えの材料<'_, 応答> {
    /// 「名前で絞り込む」の欄と並べ替えの選択欄を、横に並べる順に返す。
    pub(crate) fn 部品の並び(&self) -> Vec<ノード<応答>> {
        let 選んだ = self.並べ替えを選んだ;
        子![
            一行テキスト入力(self.絞り込みの文字列, self.絞り込みを書き換えた)
                .案内文("名前で絞り込む")
                .幅(画素(200.0)),
            選択欄(
                self.並べ替えの識別子,
                並べ替え方の名前(self.並べ替え),
                並べ替え方::一覧
                    .map(|並べ替え| 選択肢(並べ替え方の名前(並べ替え), 選んだ(並べ替え)))
                    .into_iter()
                    .collect(),
            ),
        ]
    }
}
