//! ライブラリのダイアログの中身。名前を入力して決めるダイアログと、文を読んで決めるダイアログと、決定とやめるのボタンの行を、
//! スタックのライブラリと重ね合わせのライブラリが、応答の型だけを替えて共に使う。モーダルで包むことと、外側を押したときの応答は呼び手が決める。

use sengen_egui::{
    ノード, ボタン, 一行テキスト入力, 子, 文字表示, 横並び, 画素
};

use crate::library_common::save::入力中の名前;
use crate::styles;

/// 名前のダイアログの中身。題と、入力欄(書き換えるたびに `書き換えた` が作る応答を発する)と、決定とやめるのボタンの行を縦に並べる。
pub(crate) fn 名前のダイアログ<応答: Clone + 'static>(
    題: &str,
    入力: &入力中の名前,
    書き換えた: fn(String) -> 応答,
    決定の名前: &str,
    決定: 応答,
    やめる: 応答,
) -> Vec<ノード<応答>> {
    子![
        文字表示(題).装飾(styles::見出し),
        一行テキスト入力(入力.文字列(), 書き換えた).幅(画素(320.0)),
        決定とやめるの行(決定の名前, 決定, やめる),
    ]
}

/// 確かめるダイアログの中身。確かめる文と、決定とやめるのボタンの行を縦に並べる。
pub(crate) fn 確かめるダイアログ<応答: Clone + 'static>(
    確かめる文: String,
    決定の名前: &str,
    決定: 応答,
    やめる: 応答,
) -> Vec<ノード<応答>> {
    子![
        文字表示(確かめる文),
        決定とやめるの行(決定の名前, 決定, やめる)
    ]
}

/// 決定(強調したボタン)とやめるのボタンの行。
fn 決定とやめるの行<応答: Clone + 'static>(
    決定の名前: &str,
    決定: 応答,
    やめる: 応答,
) -> ノード<応答> {
    横並び(子![
        ボタン(決定の名前, 決定).装飾(styles::強調ボタン),
        ボタン("やめる", やめる),
    ])
    .into()
}
