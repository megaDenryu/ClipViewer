//! 一覧の文言と、それで組む置き場所の文とヘッダーの書けないことの文。スタックの一覧と重ね合わせの一覧が、文言だけを替えて同じ分岐で組む。
//! 一覧の本体と件数の文は `list_body.rs` が組む。参照: _doc/設計/ライブラリ.md 判断8・判断11

use std::fmt;
use std::path::Path;

use clip_library::{
    ライブラリのフォルダ, 裏で行うライブラリ, 重ね合わせのフォルダ
};
use sengen_egui::{ノード, 文字表示};

use crate::library_common::save::保存物のライブラリの使える様子;
use crate::styles;

/// パスで示すフォルダとは、置き場所の文にパスを出せるライブラリのフォルダの性質のことである。
pub(crate) trait パスで示すフォルダ {
    fn パス(&self) -> &Path;
}

impl パスで示すフォルダ for ライブラリのフォルダ {
    fn パス(&self) -> &Path {
        ライブラリのフォルダ::パス(self)
    }
}

impl パスで示すフォルダ for 重ね合わせのフォルダ {
    fn パス(&self) -> &Path {
        重ね合わせのフォルダ::パス(self)
    }
}

/// 読み取り専用の理由の出し方とは、ヘッダーの読み取り専用の文に錠を取れない理由をその場で出すか、一覧の画面へ回すかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 読み取り専用の理由の出し方 {
    その場で出す,
    一覧の画面へ回す,
}

/// 一覧の文言とは、スタックの一覧と重ね合わせの一覧で違う文の組のことである。
pub(crate) struct 一覧の文言 {
    pub(crate) ライブラリの呼び名: &'static str,
    pub(crate) フォルダの呼び名: &'static str,
    pub(crate) 読み取り専用でできないこと: &'static str,
    pub(crate) 置き場所が無いときにできないこと: &'static str,
    pub(crate) 空のときの文: &'static str,
    pub(crate) 空のときの案内: &'static str,
    pub(crate) 読み取り専用の理由: 読み取り専用の理由の出し方,
}

impl 一覧の文言 {
    /// 一覧の上に出す置き場所の文。書けるときはフォルダのパス、読むだけのときは理由とできないこと、置き場所が無いときはその旨を出す。
    pub(crate) fn 置き場所の文<ライブラリ: 裏で行うライブラリ, 応答: 'static>(
        &self,
        様子: 保存物のライブラリの使える様子<'_, ライブラリ>,
    ) -> ノード<応答>
    where
        ライブラリ::フォルダ: パスで示すフォルダ,
        ライブラリ::錠を取れない理由: fmt::Display,
    {
        match 様子 {
            保存物のライブラリの使える様子::書ける(フォルダ) => {
                文字表示(format!("置き場所: {}", フォルダ.パス().display()))
                    .装飾(styles::補足)
                    .into()
            }
            保存物のライブラリの使える様子::読むだけ(フォルダ, 理由) => {
                文字表示(format!(
                    "読み取り専用: {理由}。開くことはできるが、{}はできない(置き場所: {})",
                    self.読み取り専用でできないこと,
                    フォルダ.パス().display()
                ))
                .装飾(styles::不備の文)
                .into()
            }
            保存物のライブラリの使える様子::置き場所が無い => {
                文字表示(format!(
                    "ライブラリの置き場所が無い(環境変数 APPDATA が無い)ため、{}",
                    self.置き場所が無いときにできないこと
                ))
                .装飾(styles::不備の文)
                .into()
            }
        }
    }

    /// ヘッダーに出す、ライブラリへ書けないことの文。書けるときは無い。
    pub(crate) fn 書けないことの文<ライブラリ: 裏で行うライブラリ>(
        &self,
        様子: 保存物のライブラリの使える様子<'_, ライブラリ>,
    ) -> Option<String>
    where
        ライブラリ::錠を取れない理由: fmt::Display,
    {
        let 呼び名 = self.ライブラリの呼び名;
        match (様子, self.読み取り専用の理由) {
            (保存物のライブラリの使える様子::書ける(_), _) => None,
            (
                保存物のライブラリの使える様子::読むだけ(_, 理由),
                読み取り専用の理由の出し方::その場で出す,
            ) => Some(format!("{呼び名}: 読み取り専用({理由})")),
            (
                保存物のライブラリの使える様子::読むだけ(..),
                読み取り専用の理由の出し方::一覧の画面へ回す,
            ) => Some(format!(
                "{呼び名}: 読み取り専用(別の ClipViewer が開いている等。一覧の画面に理由を出す)"
            )),
            (保存物のライブラリの使える様子::置き場所が無い, _) => {
                Some(format!("{呼び名}: 使えない(置き場所が無い)"))
            }
        }
    }
}
