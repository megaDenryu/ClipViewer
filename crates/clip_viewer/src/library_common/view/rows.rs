//! 一覧の行の並び。状態が一覧か見せ方が変わったときだけ作る見せる行の順に従い、仮想縦スクロールで見えている行だけ組む。
//! 行を組む閉包は画面の状態を借りられないため、行の材料(一覧と順を `Rc` で状態と共有したもの)を閉包へ所有させる(毎フレーム写さないため)。
//! 組んだ行の範囲は仮想縦スクロールが応答として発し、応答の適用が状態へ置いて、次のフレームで見えている行のサムネイルを先に撮らせる。
//! スタックの一覧と重ね合わせの一覧が、行の材料と応答の型だけを替えて共に使う。

use std::rc::Rc;

use sengen_egui::{
    ノード, 仮想縦スクロール, 使える大きさから組む, 大きさを決めた領域, 子, 無し, 画素,
    縦横の論理画素,
};

use crate::library_common::list::見えている行の範囲;

/// 1行の高さ(論理画素)。左のサムネイルの枠と、区切り線が収まる高さにする。
const 行の高さ: f32 = 70.0;

/// 一覧の行の材料とは、見えている行を組む閉包が所有し、見せる行の数と、番号の行の画面の木を答えるもののことである。
pub(crate) trait 一覧の行の材料<応答> {
    fn 行の数(&self) -> usize;
    fn 行を組む(&self, 番号: usize) -> Option<ノード<応答>>;
}

/// 行の並び。仮想縦スクロールの識別子と、行の材料と、見えている行の範囲を知らせる応答の作り方を受け取る。
pub(crate) fn 一覧の行の並び<応答: 'static, 材料: 一覧の行の材料<応答> + 'static>(
    識別子: &'static str,
    材料: 材料,
    見えている行を知らせる: fn(見えている行の範囲) -> 応答,
) -> ノード<応答> {
    let 材料 = Rc::new(材料);
    使える大きさから組む(move |大きさ| {
        let 材料 = Rc::clone(&材料);
        let 寸法 = 縦横の論理画素::生成する(大きさ.横, 画素(行の高さ));
        仮想縦スクロール(
            識別子,
            画素(行の高さ),
            材料.行の数(),
            move |番号| {
                材料
                    .行を組む(番号)
                    .map_or_else(無し, |一行| 大きさを決めた領域(寸法, 子![一行]).into())
            },
        )
        .見えている行を発する(move |範囲: sengen_egui::見えている行の範囲| {
            見えている行を知らせる(見えている行の範囲::両端の行番号から作る(
                範囲.最初(),
                範囲.最後(),
            ))
        })
        .into()
    })
    .into()
}
