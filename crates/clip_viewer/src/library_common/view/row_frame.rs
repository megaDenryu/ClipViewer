//! 一覧の1行の形。左にサムネイルの枠、右に名前と印の行と、説明と操作のボタンの行を並べ、下に区切り線を引く。
//! 読めないファイルの行はファイル名と理由を出す。スタックの一覧と重ね合わせの一覧が、印と操作のボタンだけを替えて共に使う。

use sengen_egui::{
    ノード, 区切り線, 子, 文字表示, 条件付き表示, 横並び, 縦積み
};

use super::thumbnail::サムネイルの枠;
use crate::styles;
use crate::thumbnail_feed::サムネイルの見せ方;

/// 行の印とは、名前の右に並べる短い文(「開いている」「動画が見つからない」)と、それを出すか・不備として装飾するかの組のことである。
pub(crate) struct 行の印 {
    pub(crate) 文: &'static str,
    pub(crate) 出すか: bool,
    pub(crate) 不備か: bool,
}

/// 読めた保存物の行。サムネイルの枠と、名前と印の並びと、説明と操作のボタンを組む。
pub(crate) fn 読めた行<応答: 'static>(
    サムネイル: Option<&サムネイルの見せ方>,
    名前: String,
    印の並び: &[行の印],
    説明: String,
    操作のボタン: ノード<応答>,
) -> ノード<応答> {
    let 名前と印 = std::iter::once(文字表示(名前).装飾(styles::見出し).into())
        .chain(印の並び.iter().map(印を組む))
        .collect();
    縦積み(子![
        横並び(子![
            サムネイルの枠(サムネイル),
            縦積み(子![
                横並び(名前と印),
                横並び(子![文字表示(説明).装飾(styles::補足), 操作のボタン]),
            ]),
        ]),
        区切り線(),
    ])
    .into()
}

fn 印を組む<応答: 'static>(印: &行の印) -> ノード<応答> {
    let 装飾 = if 印.不備か {
        styles::不備の文
    } else {
        styles::動画の名前
    };
    条件付き表示(印.出すか, || 文字表示(印.文).装飾(装飾))
}

/// 読めないファイルの行。ファイル名と理由を出す。
pub(crate) fn 読めない行<応答: 'static>(
    ファイル名: &str, 理由: &str
) -> ノード<応答> {
    縦積み(子![
        文字表示(format!("読めない: {ファイル名}")).装飾(styles::不備の文),
        文字表示(理由.to_string()).装飾(styles::補足),
        区切り線(),
    ])
    .into()
}
