//! アプリを閉じてよいとの決め。ウインドウを閉じる要求を受けて作業場(スタック・重ね合わせ)が出した確かめるダイアログで、利用者が閉じてよいと決めたことを、
//! 配線(`app/close_procedure.rs`)が取り出すまで、2つの作業場がそれぞれ持つ。決めを受け取ってから関係を終えるかを決めるのは配線である
//! (もう一方の作業場で利用者が「やめる」を選んだら、何も当てずに閉じる手順を捨てるため)。参照: _doc/設計/同時再生.md 2-7

/// アプリを閉じてよいとの決めとは、作業場の確かめるダイアログで、利用者がアプリを閉じてよいと決めたかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub(crate) enum アプリを閉じてよいとの決め {
    #[default]
    決めていない,
    閉じてよいと決めた,
}

impl アプリを閉じてよいとの決め {
    /// 利用者が閉じてよいと決めたことを覚える。
    pub(crate) fn 閉じてよいと決める(&mut self) {
        *self = Self::閉じてよいと決めた;
    }

    /// 決めを取り出して、決めていない様子へ戻す。配線が毎フレーム取り出す。
    pub(crate) fn 取り出す(&mut self) -> Self {
        std::mem::take(self)
    }
}
