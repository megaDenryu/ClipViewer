//! 続ける操作を持つダイアログ。スタックのライブラリのダイアログと重ね合わせのダイアログが、確かめるダイアログから続ける操作を取り出すことと、
//! 名前の入力欄を書き換えることを同じ手順で行う。2つのダイアログで違うのは、どの選択肢が確かめるダイアログか・名前の入力欄を持つかだけである。
//! 参照: _doc/設計/ライブラリ.md 判断5、_doc/設計/同時再生.md 2-7

use super::save::入力中の名前;

/// 続ける操作を持つダイアログとは、利用者が続けると決めたときに行う操作を持つ確かめるダイアログと、名前の入力欄のあるダイアログを選択肢に持つ、
/// 作業場のダイアログの性質のことである。既定の値はダイアログを開いていない様子である。
pub(crate) trait 続ける操作を持つダイアログ: Default {
    type 操作;

    /// 確かめるダイアログなら、持っている続ける操作を返す。ほかのダイアログなら自分をそのまま返す。
    fn 確かめるダイアログを操作へ分ける(self) -> Result<Self::操作, Self>;

    /// 確かめるダイアログか、登録の後に続けると決めた名前を付けて登録するダイアログなら、続けて行う操作。
    fn 続ける操作(&self) -> Option<&Self::操作>;

    /// 名前の入力欄のあるダイアログなら、その入力。
    fn 名前の入力欄(&mut self) -> Option<&mut 入力中の名前>;

    /// 確かめるダイアログなら、利用者が続けると決めたときに行う操作を取り出してダイアログを閉じる。確かめるダイアログでなければ何もしない。
    fn 続ける操作を取り出す(&mut self) -> Option<Self::操作> {
        match std::mem::take(self).確かめるダイアログを操作へ分ける() {
            Ok(操作) => Some(操作),
            Err(ほかのダイアログ) => {
                *self = ほかのダイアログ;
                None
            }
        }
    }

    /// 名前の入力欄のあるダイアログなら、その入力を書き換える。
    fn 名前の入力を書き換える(&mut self, 文字列: String) {
        if let Some(入力) = self.名前の入力欄() {
            *入力 = 入力中の名前::作成する(文字列);
        }
    }
}
