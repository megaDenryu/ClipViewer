//! 保存を頼めるライブラリ。裏で動くライブラリへ送る保存の頼みと一覧を作る頼みを、ライブラリの種類(スタックのライブラリ・重ね合わせのライブラリ)ごとに作る。
//! ライブラリの接続(`connection.rs`)は、この性質だけを使って2つの種類を同じ手順で扱う。

use clip_domain::{
    スタックの識別子, ライブラリのスタック, ライブラリの重ね合わせ, 重ね合わせの識別子,
};
use clip_library::{
    スタックのライブラリ, ライブラリのフォルダ, ライブラリへの頼み, 保存の番号, 裏で行うライブラリ,
    重ね合わせのフォルダ, 重ね合わせのライブラリ, 重ね合わせのライブラリへの頼み,
};

use super::content::登録できる保存物;

/// 保存を頼めるライブラリとは、裏で動くライブラリへ、登録できる保存物の保存と、一覧を作ることを頼め、フォルダから保存物を1つ読めるライブラリの性質のことである。
pub(crate) trait 保存を頼めるライブラリ: 裏で行うライブラリ {
    type 保存物: 登録できる保存物;
    fn 保存の頼み(保存物: Self::保存物, 番号: 保存の番号) -> Self::頼み;
    fn 一覧を作る頼み() -> Self::頼み;
    /// フォルダの識別子の保存物を読む。読めなければ理由の文を返す。一覧から開くときに画面のスレッドで読む。
    fn フォルダから読む(
        フォルダ: &Self::フォルダ,
        識別子: &<Self::保存物 as 登録できる保存物>::識別子,
    ) -> Result<Self::保存物, String>;
}

impl 保存を頼めるライブラリ for スタックのライブラリ {
    type 保存物 = ライブラリのスタック;

    fn 保存の頼み(
        保存物: ライブラリのスタック,
        番号: 保存の番号,
    ) -> ライブラリへの頼み {
        ライブラリへの頼み::保存する(保存物, 番号)
    }

    fn 一覧を作る頼み() -> ライブラリへの頼み {
        ライブラリへの頼み::一覧を作る
    }

    fn フォルダから読む(
        フォルダ: &ライブラリのフォルダ,
        識別子: &スタックの識別子,
    ) -> Result<ライブラリのスタック, String> {
        スタックのライブラリ::作成する(フォルダ.clone())
            .読む(識別子)
            .map_err(|エラー| エラー.to_string())
    }
}

impl 保存を頼めるライブラリ for 重ね合わせのライブラリ {
    type 保存物 = ライブラリの重ね合わせ;

    fn 保存の頼み(
        保存物: ライブラリの重ね合わせ,
        番号: 保存の番号,
    ) -> 重ね合わせのライブラリへの頼み {
        重ね合わせのライブラリへの頼み::保存する(保存物, 番号)
    }

    fn 一覧を作る頼み() -> 重ね合わせのライブラリへの頼み {
        重ね合わせのライブラリへの頼み::一覧を作る
    }

    fn フォルダから読む(
        フォルダ: &重ね合わせのフォルダ,
        識別子: &重ね合わせの識別子,
    ) -> Result<ライブラリの重ね合わせ, String> {
        重ね合わせのライブラリ::作成する(フォルダ.clone())
            .読む(識別子)
            .map_err(|エラー| エラー.to_string())
    }
}
