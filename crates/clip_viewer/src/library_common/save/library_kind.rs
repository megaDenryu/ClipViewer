//! 保存を頼めるライブラリ。裏で動くライブラリへ送る保存の頼みと一覧を作る頼みを、ライブラリの種類(スタックのライブラリ・重ね合わせのライブラリ)ごとに作る。
//! ライブラリの接続(`connection.rs`)は、この性質だけを使って2つの種類を同じ手順で扱う。

use clip_domain::{ライブラリのスタック, ライブラリの重ね合わせ};
use clip_library::{
    スタックのライブラリ, ライブラリへの頼み, 保存の番号, 保存物を読めるライブラリ,
    重ね合わせのライブラリ, 重ね合わせのライブラリへの頼み,
};

use super::content::登録できる保存物;

/// 保存を頼めるライブラリとは、保存物を1つ読めるライブラリのうち、裏で動くライブラリへ、登録できる保存物の保存と、一覧を作ることを頼めるものの性質のことである。
pub(crate) trait 保存を頼めるライブラリ:
    保存物を読めるライブラリ<保存物: 登録できる保存物>
{
    fn 保存の頼み(保存物: Self::保存物, 番号: 保存の番号) -> Self::頼み;
    fn 一覧を作る頼み() -> Self::頼み;
}

impl 保存を頼めるライブラリ for スタックのライブラリ {
    fn 保存の頼み(
        保存物: ライブラリのスタック,
        番号: 保存の番号,
    ) -> ライブラリへの頼み {
        ライブラリへの頼み::保存する(保存物, 番号)
    }

    fn 一覧を作る頼み() -> ライブラリへの頼み {
        ライブラリへの頼み::一覧を作る
    }
}

impl 保存を頼めるライブラリ for 重ね合わせのライブラリ {
    fn 保存の頼み(
        保存物: ライブラリの重ね合わせ,
        番号: 保存の番号,
    ) -> 重ね合わせのライブラリへの頼み {
        重ね合わせのライブラリへの頼み::保存する(保存物, 番号)
    }

    fn 一覧を作る頼み() -> 重ね合わせのライブラリへの頼み {
        重ね合わせのライブラリへの頼み::一覧を作る
    }
}
