//! 保存の様子を読むメソッド。今の値がファイルに書けていないかと、書けたことの確かめと、ヘッダーに出す保存の段階を返す。参照: _doc/設計/ライブラリ.md 判断5

use super::保存の様子;
use crate::library_common::save::content::登録できる保存物;
use crate::library_common::save::failure::{保存の失敗, 書けていない理由};

/// 保存の段階とは、開いている登録済みの保存物が保存についてどの段階にあるかの区別のことである。ヘッダーに出す。
#[derive(Debug)]
pub(crate) enum 保存の段階<'様子, 操作エラー: std::fmt::Display + std::fmt::Debug> {
    保存済み,
    変更を保存待ち,
    保存中,
    保存に失敗(&'様子 保存の失敗<操作エラー>),
}

impl<保存物: 登録できる保存物> 保存の様子<保存物> {
    /// 今の値がファイルに書けていないか。
    pub(crate) fn 保存されていないか(&self, 今の値: &保存物::比べる値) -> bool {
        self.ファイルにある中身.as_ref().map(保存物::比べる値) != Some(今の値)
    }

    /// 今の値がファイルに書けていて、待っている保存も無いことを確かめる。書けていなければ理由を返す。
    pub(crate) fn 書けたことを確かめる(
        &self,
        今の値: &保存物::比べる値,
    ) -> Result<(), 書けていない理由<'_, 保存物::操作エラー>> {
        if !self.保存されていないか(今の値) && self.頼んでいる.is_empty() {
            return Ok(());
        }
        Err(self.最後の失敗.as_ref().map_or(
            書けていない理由::保存を終えていない,
            書けていない理由::失敗した,
        ))
    }

    /// 保存の段階。失敗は、次の保存が成功するまで出し続ける。失敗の後に変えた値も保存できていないためである。
    pub(crate) fn 段階(
        &self,
        今の値: &保存物::比べる値,
    ) -> 保存の段階<'_, 保存物::操作エラー> {
        if !self.頼んでいる.is_empty() {
            return 保存の段階::保存中;
        }
        match (&self.最後の失敗, self.保存されていないか(今の値)) {
            (Some(失敗), _) => 保存の段階::保存に失敗(失敗),
            (None, true) => 保存の段階::変更を保存待ち,
            (None, false) => 保存の段階::保存済み,
        }
    }
}
