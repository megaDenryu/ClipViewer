//! 保存の様子。開いている登録済みの保存物について、ファイルに書けたと分かっている中身と、頼んでいて結果を待っている保存と、
//! 最後の保存の失敗と、頼み直しを持つ。書けたか・保存の段階を読むメソッドは `read.rs` に置く。参照: _doc/設計/ライブラリ.md 判断5・判断11

use std::time::{Duration, Instant};

use clip_library::保存の番号;

mod read;

pub(crate) use read::保存の段階;

use super::content::登録できる保存物;
use super::failure::{ライブラリを使えない理由, 保存の失敗};
use super::retry::頼み直し;

/// 保存の様子とは、ファイルに書けたと分かっている中身(登録を頼んだだけでまだ書けていなければ無い)と、頼んで結果を待っている保存
/// (番号と中身)と、最後に終えた保存が失敗したならその理由と、頼み直しの組のことである。
/// ファイルにある中身は、保存が成功したと知らせを受けたときだけ進める。書けていない中身を書けたものとして扱わないためである。
#[derive(Debug)]
pub(crate) struct 保存の様子<保存物: 登録できる保存物> {
    ファイルにある中身: Option<保存物::中身>,
    頼んでいる: Vec<(保存の番号, 保存物::中身)>,
    最後の失敗: Option<保存の失敗<保存物::操作エラー>>,
    頼み直し: 頼み直し,
}

impl<保存物: 登録できる保存物> 保存の様子<保存物> {
    /// ファイルから読んだ中身で始める。
    pub(crate) fn ファイルから開いた(中身: 保存物::中身) -> Self {
        Self::始める(Some(中身), Vec::new())
    }

    /// 登録の保存を頼んだところから始める。書けたと分かるまでファイルにある中身は無い。
    pub(crate) fn 登録を頼んだ(番号: 保存の番号, 中身: 保存物::中身) -> Self {
        Self::始める(None, vec![(番号, 中身)])
    }

    fn 始める(
        ファイルにある中身: Option<保存物::中身>,
        頼んでいる: Vec<(保存の番号, 保存物::中身)>,
    ) -> Self {
        Self {
            ファイルにある中身,
            頼んでいる,
            最後の失敗: None,
            頼み直し: 頼み直し::default(),
        }
    }

    /// 保存を頼んだ。
    pub(crate) fn 頼んだ(&mut self, 番号: 保存の番号, 中身: 保存物::中身) {
        self.頼んでいる.push((番号, 中身));
        self.頼み直し = 頼み直し::無し;
    }

    /// 保存を終えた知らせを受けた。成功ならファイルにある中身を進める。
    /// 失敗して待っている保存がもう無ければ、頼み直すことにする(失敗した中身を黙って捨てないため)。
    pub(crate) fn 終えた(
        &mut self, 番号: 保存の番号, 結果: Result<(), 保存物::操作エラー>
    ) {
        let Some(位置) = self
            .頼んでいる
            .iter()
            .position(|(頼んだ, _)| *頼んだ == 番号)
        else {
            return;
        };
        let 書いた中身 = self.頼んでいる.drain(..=位置).next_back();
        match 結果 {
            Ok(()) => {
                self.最後の失敗 = None;
                self.ファイルにある中身 = 書いた中身.map(|(_, 中身)| 中身);
            }
            Err(エラー) => self.失敗を覚える(保存の失敗::書けなかった(エラー)),
        }
    }

    /// 保存を頼めなかった。
    pub(crate) fn 頼めなかった(&mut self, 理由: ライブラリを使えない理由) {
        self.失敗を覚える(保存の失敗::頼めなかった(理由));
    }

    /// 失敗を覚え、待っている保存が無ければ頼み直すことにする。
    fn 失敗を覚える(&mut self, 失敗: 保存の失敗<保存物::操作エラー>) {
        self.最後の失敗 = Some(失敗);
        if self.頼んでいる.is_empty() {
            self.頼み直し = 頼み直し::時刻を決める前;
        }
    }

    /// 今、頼み直すときか。失敗を受けて最初に見たときに、頼み直す時刻を決める。
    pub(crate) fn 頼み直すときか(&mut self, 今: Instant) -> bool {
        self.頼み直し.頼み直すときか(今)
    }

    /// 頼み直すまでの残りの時間。頼み直さないなら無い。
    pub(crate) fn 頼み直すまでの時間(&self, 今: Instant) -> Option<Duration> {
        self.頼み直し.頼み直すまでの時間(今)
    }
}
