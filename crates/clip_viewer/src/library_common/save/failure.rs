//! 保存の失敗。ライブラリへ頼みを送れない理由と、開いている登録済みの保存物の保存を頼めなかったか、頼んだが書けなかったかを、理由の型のまま持つ。
//! 参照: _doc/設計/ライブラリ.md 判断5

use clip_library::頼めない理由;

/// ライブラリを使えない理由とは、ライブラリ(スタックか重ね合わせ)へ頼みを送れない理由の区別のことである。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub(crate) enum ライブラリを使えない理由 {
    #[error("ライブラリの置き場所が無い(環境変数 APPDATA が無い)")]
    置き場所が無い,
    #[error("{0}")]
    頼めない(#[from] 頼めない理由),
}

/// 保存の失敗とは、開いている登録済みの保存物の保存を、頼めなかったか、頼んだが書けなかったかの区別と、その理由のことである。
/// 書けなかった理由の型は、保存物の種類ごとの操作エラーである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 保存の失敗<操作エラー: std::fmt::Display + std::fmt::Debug> {
    #[error("{0}")]
    頼めなかった(ライブラリを使えない理由),
    #[error("{0}")]
    書けなかった(操作エラー),
}

/// 書けていない理由とは、今の値がファイルに書けたと確かめられなかった理由の区別のことである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 書けていない理由<'様子, 操作エラー: std::fmt::Display + std::fmt::Debug> {
    #[error("保存を終えていない")]
    保存を終えていない,
    #[error("{0}")]
    失敗した(&'様子 保存の失敗<操作エラー>),
}
