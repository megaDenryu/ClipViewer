//! ライブラリの使える様子と、書き込みを終えるまで待つこと。接続が、ライブラリへ書けるか、錠を取れずに読むだけか、置き場所が無くて使えないかを答え、
//! 裏のスレッドが頼まれた書き込みを終えるまで待つ。待つのは画面のスレッドを止めるため、使う場所を一覧から開く前と関係を終える前の保存の確かめ(と試験)に限る。

use clip_library::{裏で行うライブラリ, 錠による書き込みの許し};

use super::connection::保存物のライブラリの接続;
use super::library_kind::保存を頼めるライブラリ;
use super::purpose::保存の目的の区別;

/// ライブラリの使える様子とは、ライブラリへ書けるか、読むだけか、置き場所が無くて使えないかの区別のことである。画面が出し分けに使う。
pub(crate) enum 保存物のライブラリの使える様子<'接続, ライブラリ: 裏で行うライブラリ> {
    書ける(&'接続 ライブラリ::フォルダ),
    読むだけ(
        &'接続 ライブラリ::フォルダ,
        &'接続 ライブラリ::錠を取れない理由,
    ),
    置き場所が無い,
}

impl<ライブラリ: 保存を頼めるライブラリ, 目的: 保存の目的の区別>
    保存物のライブラリの接続<ライブラリ, 目的>
{
    pub(crate) fn 使える様子(
        &self,
    ) -> 保存物のライブラリの使える様子<'_, ライブラリ> {
        let Ok(裏で動くライブラリ) = self.裏で動くライブラリ() else {
            return 保存物のライブラリの使える様子::置き場所が無い;
        };
        match 裏で動くライブラリ.許し() {
            錠による書き込みの許し::書ける(_) => {
                保存物のライブラリの使える様子::書ける(
                    裏で動くライブラリ.フォルダ(),
                )
            }
            錠による書き込みの許し::読むだけ(理由) => {
                保存物のライブラリの使える様子::読むだけ(
                    裏で動くライブラリ.フォルダ(),
                    理由,
                )
            }
        }
    }

    /// ライブラリへ書けるか。
    pub(crate) fn 書けるか(&self) -> bool {
        matches!(self.使える様子(), 保存物のライブラリの使える様子::書ける(_))
    }

    /// 頼んだ書き込みを終えるまで待つ。一覧の走査は待たない(遅いドライブの走査で画面のスレッドを止めないため)。
    pub(crate) fn 書き込みを終えるまで待つ(&self) {
        if let Ok(裏で動くライブラリ) = self.裏で動くライブラリ() {
            裏で動くライブラリ.書き込みを終えるまで待つ();
        }
    }

    /// 頼んだ書き込みを終えてから、識別子の保存物を読む。名前の変更の直後に開いても、変更の前の中身を読まないためである。
    pub(crate) fn 書き込みを終えてから読む(
        &self,
        識別子: &ライブラリ::保存物の識別子,
    ) -> Result<ライブラリ::保存物, String> {
        let 裏で動くライブラリ = self.裏で動くライブラリ().map_err(|理由| 理由.to_string())?;
        裏で動くライブラリ.書き込みを終えるまで待つ();
        裏で動くライブラリ
            .読む(識別子)
            .map_err(|理由| 理由.to_string())
    }

    /// 書き込みと走査を終えるまで待つ。試験で知らせがそろうのを待つために使う。
    #[cfg(test)]
    pub(crate) fn 走査も終えるまで待つ(&self) {
        if let Ok(裏で動くライブラリ) = self.裏で動くライブラリ() {
            裏で動くライブラリ.走査も終えるまで待つ();
        }
    }
}
