//! 登録済みの保存物。最後に保存を頼んだ保存物と、保存の様子と、変更の見張りを持つ。スタックと重ね合わせが、保存物の型だけを替えて同じ型を使う。
//! スタックだけが持つ変え方(名前の変更と動画の場所の変更)は `state/library/registered_stack.rs` に置く。
//! 参照: _doc/設計/ライブラリ.md 判断5・判断11

use std::time::{Duration, Instant};

use clip_library::保存の番号;

use super::change_watch::{変更の見張り, 見た結果};
use super::content::登録できる保存物;
use super::failure::ライブラリを使えない理由;
use super::status::保存の様子;

/// 登録済みの保存物とは、最後に保存を頼んだ保存物と、保存の様子(ファイルに書けたと分かっている中身を含む)と、変更の見張りの組のことである。
#[derive(Debug)]
pub(crate) struct 登録済みの保存物<保存物: 登録できる保存物> {
    保存物: 保存物,
    保存: 保存の様子<保存物>,
    見張り: 変更の見張り<保存物::比べる値>,
}

impl<保存物: 登録できる保存物> 登録済みの保存物<保存物> {
    /// ファイルから読んで開いた保存物。
    pub(crate) fn ファイルから開いた(保存物: 保存物) -> Self {
        Self {
            保存: 保存の様子::ファイルから開いた(保存物.中身().clone()),
            保存物,
            見張り: 変更の見張り::default(),
        }
    }

    /// 登録の保存を頼んだ保存物。書けたと分かるまでファイルにある中身は無い。
    pub(crate) fn 登録を頼んだ(保存物: 保存物, 番号: 保存の番号) -> Self {
        Self {
            保存: 保存の様子::登録を頼んだ(番号, 保存物.中身().clone()),
            保存物,
            見張り: 変更の見張り::default(),
        }
    }

    /// 最後に保存を頼んだ保存物。
    pub(crate) fn 中身(&self) -> &保存物 {
        &self.保存物
    }

    pub(crate) fn 識別子(&self) -> &保存物::識別子 {
        self.保存物.識別子()
    }

    pub(crate) fn 名前(&self) -> &保存物::名前 {
        self.保存物.名前()
    }

    /// 保存の様子。ファイルに書けたか・保存の段階を読むために貸す。変えるのはこの型のメソッドだけである。
    pub(crate) fn 保存の様子(&self) -> &保存の様子<保存物> {
        &self.保存
    }

    /// 今の値を見て、保存を頼むかを判定する。保存に失敗した後は間隔を置いて頼み直し、それ以外は値が落ち着いたら頼む。
    pub(crate) fn 並びを見る(
        &mut self,
        今の値: &保存物::比べる値,
        今: Instant,
    ) -> 見た結果 {
        if self.保存.頼み直すときか(今) {
            return 見た結果::保存する;
        }
        let 頼んだ値 = 保存物::比べる値(self.保存物.中身());
        self.見張り.見る(今の値, 頼んだ値, 今)
    }

    /// 次に値を見て保存を頼むかもしれない時刻までの残り。落ち着き待ちと頼み直しの早い方であり、どちらも無ければ無い。
    pub(crate) fn 次に並びを見るまでの時間(&self, 今: Instant) -> Option<Duration> {
        [
            self.保存.頼み直すまでの時間(今),
            self.見張り.落ち着くまでの残り(今),
        ]
        .into_iter()
        .flatten()
        .min()
    }

    /// 保存を頼んだ。保存物を頼んだものに置き換える。
    pub(crate) fn 保存を頼んだ(&mut self, 保存物: 保存物, 番号: 保存の番号) {
        self.保存.頼んだ(番号, 保存物.中身().clone());
        self.保存物 = 保存物;
        self.見張り = 変更の見張り::default();
    }

    /// 保存を頼まずに、保存物だけを置き換える。ファイルへ別に頼んだ変更(スタックの名前の変更等)を中身へも当て、後の自動保存が古い値で上書きしないために使う。
    pub(crate) fn 保存物を置き換える(&mut self, 保存物: 保存物) {
        self.保存物 = 保存物;
    }

    /// 保存を頼めなかった。
    pub(crate) fn 保存を頼めなかった(
        &mut self, 理由: ライブラリを使えない理由
    ) {
        self.保存.頼めなかった(理由);
    }

    /// 保存を終えた知らせを受けた。書けたならファイルにある中身を進める。
    pub(crate) fn 保存を終えた(
        &mut self,
        番号: 保存の番号,
        結果: Result<(), 保存物::操作エラー>,
    ) {
        self.保存.終えた(番号, 結果);
    }
}
