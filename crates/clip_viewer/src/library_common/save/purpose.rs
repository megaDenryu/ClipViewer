//! 知らせる保存の目的の覚え。登録と取り込みのように結果を利用者へ知らせる保存の目的を、書き込みを終えた知らせを受けるまで覚えておく。
//! 目的の型はスタック(`state/library/save_purpose.rs`)と重ね合わせ(`overlay/state/library/purpose.rs`)が別に持つ。

use clip_library::保存の番号;

/// 保存の目的の区別とは、保存を頼んだ理由の型(スタックの保存の目的・重ね合わせの保存の目的)が、自動保存かを答えられる性質のことである。
/// 自動保存の結果は利用者へ知らせない(開いている保存物の失敗はヘッダーで知らせる)ため、覚えない。
pub(crate) trait 保存の目的の区別 {
    fn 自動保存() -> Self;
    fn 自動保存か(&self) -> bool;
}

/// 知らせる保存の目的の覚えとは、結果を利用者へ知らせる保存(自動保存以外)の番号と目的を、結果が届くまで覚えておくもののことである。
#[derive(Debug)]
pub(crate) struct 知らせる保存の目的の覚え<目的>(Vec<(保存の番号, 目的)>);

impl<目的> Default for 知らせる保存の目的の覚え<目的> {
    fn default() -> Self {
        Self(Vec::new())
    }
}

impl<目的: 保存の目的の区別> 知らせる保存の目的の覚え<目的> {
    /// 自動保存でなければ、番号と目的を覚える。
    pub(crate) fn 覚える(&mut self, 番号: 保存の番号, 目的: 目的) {
        if !目的.自動保存か() {
            self.0.push((番号, 目的));
        }
    }

    /// 番号の目的を取り出す。覚えていなければ自動保存である。
    pub(crate) fn 取り出す(&mut self, 番号: 保存の番号) -> 目的 {
        match self.0.iter().position(|(覚えた, _)| *覚えた == 番号) {
            Some(位置) => self.0.remove(位置).1,
            None => 目的::自動保存(),
        }
    }
}
