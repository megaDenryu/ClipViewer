//! 登録できる保存物。ライブラリへ名前を付けて登録し、編集のたびに自動で保存する保存物(ライブラリのスタックとライブラリの重ね合わせ)の性質と、
//! その2つの型の実装を置く。保存の追跡(`status.rs`・`registered.rs`)は、この性質だけを使って2つの型を同じ手順で扱う。

use std::fmt;

use clip_domain::{
    クリップ, クリップスタック, スタックの名前, スタックの識別子, ライブラリのスタック,
    ライブラリの重ね合わせ, 重ね合わせ, 重ね合わせの名前, 重ね合わせの識別子,
};
use clip_library::{
    ライブラリの操作エラー, 重ね合わせのライブラリの操作エラー
};

/// 登録できる保存物とは、ライブラリへ登録して編集のたびに自動で保存する保存物の性質のことである。
/// 中身とは、保存物のうち利用者が編集するもの(スタックはクリップの並び、重ね合わせは重ね合わせ)のことであり、
/// 比べる値とは、中身のうち保存したかを比べる値(スタックは選んでいるクリップを除いたクリップの一覧、重ね合わせは重ね合わせ全体)のことである。
pub(crate) trait 登録できる保存物: Clone + fmt::Debug {
    type 識別子: PartialEq + Clone;
    type 名前: Clone + fmt::Display;
    type 中身: Clone + fmt::Debug;
    type 比べる値: ?Sized + PartialEq + ToOwned;
    type 操作エラー: fmt::Display + fmt::Debug;
    fn 識別子(&self) -> &Self::識別子;
    fn 名前(&self) -> &Self::名前;
    fn 中身(&self) -> &Self::中身;
    fn 比べる値(中身: &Self::中身) -> &Self::比べる値;
}

impl 登録できる保存物 for ライブラリのスタック {
    type 識別子 = スタックの識別子;
    type 名前 = スタックの名前;
    type 中身 = クリップスタック;
    type 比べる値 = [クリップ];
    type 操作エラー = ライブラリの操作エラー;

    fn 識別子(&self) -> &スタックの識別子 {
        ライブラリのスタック::識別子(self)
    }

    fn 名前(&self) -> &スタックの名前 {
        ライブラリのスタック::名前(self)
    }

    fn 中身(&self) -> &クリップスタック {
        self.並び()
    }

    fn 比べる値(中身: &クリップスタック) -> &[クリップ] {
        中身.一覧()
    }
}

impl 登録できる保存物 for ライブラリの重ね合わせ {
    type 識別子 = 重ね合わせの識別子;
    type 名前 = 重ね合わせの名前;
    type 中身 = 重ね合わせ;
    type 比べる値 = 重ね合わせ;
    type 操作エラー = 重ね合わせのライブラリの操作エラー;

    fn 識別子(&self) -> &重ね合わせの識別子 {
        ライブラリの重ね合わせ::識別子(self)
    }

    fn 名前(&self) -> &重ね合わせの名前 {
        ライブラリの重ね合わせ::名前(self)
    }

    fn 中身(&self) -> &重ね合わせ {
        self.重ね合わせ()
    }

    fn 比べる値(中身: &重ね合わせ) -> &重ね合わせ {
        中身
    }
}
