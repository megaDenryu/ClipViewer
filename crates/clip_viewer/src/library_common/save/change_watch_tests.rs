//! 変更の見張りの試験。並びが変わってから落ち着くまで保存を頼まず、落ち着いたら1回だけ保存すると判定する。
#![allow(clippy::expect_used)]

use std::time::{Duration, Instant};

use clip_domain::{クリップ, クリップ名, クリップ識別子};

use super::change_watch::{
    保存するかの判定, 変更の見張り, 落ち着くまでの時間
};

fn クリップ(名前: &str) -> クリップ {
    let 識別子 = クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子");
    クリップ::既定値で作成する(識別子, クリップ名::作成する(名前.to_string()))
}

#[test]
fn 並びが保存を頼んだ並びと同じなら保存しない() {
    let mut 見張り = 変更の見張り::default();
    let 並び = vec![クリップ("甲")];
    assert_eq!(
        見張り.変更を見る(&並び, &並び, Instant::now()),
        保存するかの判定::保存しない
    );
}

#[test]
fn 変わってから落ち着くまでの時間がたつと1回だけ保存する() {
    let mut 見張り = 変更の見張り::default();
    let 頼んだ = vec![クリップ("甲")];
    let 今の並び = vec![クリップ("甲"), クリップ("乙")];
    let 始め = Instant::now();
    let 少し後 = 始め + Duration::from_millis(100);
    assert_eq!(
        見張り.変更を見る(&今の並び, &頼んだ, 始め),
        保存するかの判定::保存しない
    );
    assert_eq!(
        見張り.変更を見る(&今の並び, &頼んだ, 少し後),
        保存するかの判定::保存しない
    );
    assert_eq!(
        見張り.落ち着くまでの残り(少し後),
        Some(Duration::from_millis(400)),
        "最初に変わったのを見た時刻から数える"
    );
    let 落ち着いた = 始め + 落ち着くまでの時間;
    assert_eq!(
        見張り.変更を見る(&今の並び, &頼んだ, 落ち着いた),
        保存するかの判定::保存する
    );
    assert_eq!(見張り.落ち着くまでの残り(落ち着いた), None);
    assert_eq!(
        見張り.変更を見る(&今の並び, &頼んだ, 落ち着いた + Duration::from_millis(1)),
        保存するかの判定::保存しない,
        "保存すると判定した後は、次に変わるまで保存しない"
    );
}

#[test]
fn 続けて変えている間は待ち直す() {
    let mut 見張り = 変更の見張り::default();
    let 頼んだ = vec![クリップ("甲")];
    let 始め = Instant::now();
    let 一回目 = vec![クリップ("乙")];
    let 二回目 = vec![クリップ("丙")];
    assert_eq!(
        見張り.変更を見る(&一回目, &頼んだ, 始め),
        保存するかの判定::保存しない
    );
    let 途中 = 始め + Duration::from_millis(400);
    assert_eq!(
        見張り.変更を見る(&二回目, &頼んだ, 途中),
        保存するかの判定::保存しない
    );
    let 始めから数えて落ち着いた = 始め + 落ち着くまでの時間;
    assert_eq!(
        見張り.変更を見る(&二回目, &頼んだ, 始めから数えて落ち着いた),
        保存するかの判定::保存しない
    );
    assert_eq!(
        見張り.変更を見る(&二回目, &頼んだ, 途中 + 落ち着くまでの時間),
        保存するかの判定::保存する
    );
}
