//! ライブラリの接続。裏で動くライブラリ(スタックか重ね合わせ)を持ち、頼みを送り、返事を待っている頼みを数え、知らせを受け取る。
//! 読み込んだ動画と同じく、アプリが生きている間の資源として持つ。置き場所の有無と書けるかの正本はこの型だけである。
//! ライブラリの日時を得るために時計を読む境界もここ1箇所である。スタックと重ね合わせが、ライブラリと目的の型だけを替えて同じ型を使う。

use std::time::SystemTime;

use clip_domain::ライブラリの日時;
use clip_library::{
    保存の番号, 裏で動く保存物のライブラリ, 錠を試した保存物のライブラリ
};

use super::failure::ライブラリを使えない理由;
use super::library_kind::保存を頼めるライブラリ;
use super::purpose::{保存の目的の区別, 知らせる保存の控え};

/// ライブラリの接続とは、裏で動くライブラリ(置き場所が無ければ無い)と、最後に頼んだ保存の番号と、
/// 返事を待っている頼みの数と、結果を利用者へ知らせる保存の目的の組のことである。
pub(crate) struct 保存物のライブラリの接続
<ライブラリ: 保存を頼めるライブラリ, 目的> {
    裏で動くライブラリ: Option<裏で動く保存物のライブラリ<ライブラリ>>,
    最後の保存の番号: 保存の番号,
    返事を待っている頼みの数: usize,
    知らせる保存: 知らせる保存の控え<目的>,
}

impl<ライブラリ: 保存を頼めるライブラリ, 目的: 保存の目的の区別>
    保存物のライブラリの接続<ライブラリ, 目的>
{
    /// 錠を試したライブラリがあれば、裏のスレッドを起こす(錠を取れていなければ読むだけ)。無ければ置き場所が無い接続にする。
    /// 錠は起動の部分が先に試す。取れなかったときに、錠を持つアプリへ動画を渡して終わるかを決めるためである(画面.md 判断13)。
    pub(crate) fn 錠を試したライブラリから起動する(
        試した: Option<錠を試した保存物のライブラリ<ライブラリ>>,
    ) -> Self {
        Self::裏で動くライブラリから作る(
            試した.map(裏で動く保存物のライブラリ::錠を試した後で起動する),
        )
    }

    /// 起動した裏で動くライブラリ(置き場所が無ければ無い)から作る。
    pub(crate) fn 裏で動くライブラリから作る(
        裏で動くライブラリ: Option<裏で動く保存物のライブラリ<ライブラリ>>,
    ) -> Self {
        Self {
            裏で動くライブラリ,
            最後の保存の番号: 保存の番号::default(),
            返事を待っている頼みの数: 0,
            知らせる保存: 知らせる保存の控え::default(),
        }
    }

    /// 裏で動くライブラリ。置き場所が無ければ、使えない理由(置き場所が無い)を返す。
    pub(crate) fn 裏で動くライブラリ(
        &self,
    ) -> Result<&裏で動く保存物のライブラリ<ライブラリ>, ライブラリを使えない理由> {
        self.裏で動くライブラリ
            .as_ref()
            .ok_or(ライブラリを使えない理由::置き場所が無い)
    }

    /// 頼みを送る。待たない。送れたら、返事を待っている頼みとして数える。
    pub(crate) fn 頼む(
        &mut self,
        頼み: ライブラリ::頼み,
    ) -> Result<(), ライブラリを使えない理由> {
        self.裏で動くライブラリ()?.頼む(頼み)?;
        self.返事を待っている頼みの数 += 1;
        Ok(())
    }

    /// 一覧を作ることを頼む。
    pub(crate) fn 一覧を作ることを頼む(
        &mut self,
    ) -> Result<(), ライブラリを使えない理由> {
        self.頼む(ライブラリ::一覧を作る頼み())
    }

    /// 次の保存の番号を付けて、保存物の保存を頼む。自動保存でなければ、結果を知らせるために目的を覚える。
    pub(crate) fn 保存を頼む(
        &mut self,
        保存物: ライブラリ::保存物,
        目的: 目的,
    ) -> Result<保存の番号, ライブラリを使えない理由> {
        let 番号 = self.最後の保存の番号.次();
        self.頼む(ライブラリ::保存の頼み(保存物, 番号))?;
        self.最後の保存の番号 = 番号;
        self.知らせる保存.控える(番号, 目的);
        Ok(番号)
    }

    /// 番号の保存の目的を取り出す。覚えていなければ自動保存である。
    pub(crate) fn 保存の目的を取り出す(&mut self, 番号: 保存の番号) -> 目的 {
        self.知らせる保存.取り出す(番号)
    }

    /// 届いている知らせをすべて受け取り、その数だけ返事を待っている頼みを減らす。
    pub(crate) fn 届いた知らせを受け取る(&mut self) -> Vec<ライブラリ::知らせ> {
        let 知らせ = self
            .裏で動くライブラリ()
            .map(裏で動く保存物のライブラリ::届いた知らせを受け取る)
            .unwrap_or_default();
        self.返事を待っている頼みの数 = self.返事を待っている頼みの数.saturating_sub(知らせ.len());
        知らせ
    }

    /// 裏のスレッドの返事を待っているか。待っている間は、入力が無くても画面を進めて知らせを受け取る。
    pub(crate) fn 返事を待っているか(&self) -> bool {
        self.返事を待っている頼みの数 > 0
    }

    /// 今のライブラリの日時。時計が1970年より前か9999年より後を指す壊れた状態では、1970年1月1日にする(日時は並べ替えと表示にだけ使うため)。
    pub(crate) fn 今の日時(&self) -> ライブラリの日時 {
        ライブラリの日時::時刻から作成する(SystemTime::now()).unwrap_or(ライブラリの日時::紀元)
    }
}
