//! 並べた一覧。最後に読んだ一覧と一覧の見せ方と、そこから作った見せる行の順を1つに持ち、一覧か見せ方が変わったときだけ順を作り直す。
//! 毎フレーム全件を絞り込み・並べ替えないためである。画面は見えている行だけを組む(参照: _doc/設計/ライブラリ.md 判断8・判断11)。

use std::rc::Rc;

use super::listing::{一覧の項目の参照, 並べられる一覧, 並べられる保存物};
use super::view::{一覧の見せ方, 並べ替え方, 絞り込みの語, 見せる行};

/// 最後に読んだ一覧とは、一覧をまだ読んでいないか、読めたか、フォルダを読めなかったかの区別のことである。
/// 読めた一覧は、見えている行を組む閉包と共有するため `Rc` で持つ。
#[derive(Debug, Default)]
pub(crate) enum 最後に読んだ一覧<一覧> {
    #[default]
    まだ無い,
    読めた(Rc<一覧>),
    読めない(String),
}

impl<一覧> Clone for 最後に読んだ一覧<一覧> {
    fn clone(&self) -> Self {
        match self {
            Self::まだ無い => Self::まだ無い,
            Self::読めた(一覧) => Self::読めた(Rc::clone(一覧)),
            Self::読めない(理由) => Self::読めない(理由.clone()),
        }
    }
}

/// 並べた一覧とは、最後に読んだ一覧と、一覧の見せ方と、そこから作った見せる行の順の組のことである。
/// 不変条件: 見せる行の順は、今の一覧と見せ方から作ったものである(変える口がすべて作り直す)。
#[derive(Debug)]
pub(crate) struct 並べた一覧<一覧> {
    一覧: 最後に読んだ一覧<一覧>,
    見せ方: 一覧の見せ方,
    見せる行の順: Rc<Vec<見せる行>>,
}

impl<一覧> Default for 並べた一覧<一覧> {
    fn default() -> Self {
        Self {
            一覧: 最後に読んだ一覧::default(),
            見せ方: 一覧の見せ方::default(),
            見せる行の順: Rc::default(),
        }
    }
}

impl<一覧: 並べられる一覧> 並べた一覧<一覧> {
    pub(crate) fn 一覧(&self) -> &最後に読んだ一覧<一覧> {
        &self.一覧
    }

    pub(crate) fn 見せ方(&self) -> &一覧の見せ方 {
        &self.見せ方
    }

    /// 見せる行の順。見えている行を組む閉包と共有する。
    pub(crate) fn 見せる行の順(&self) -> Rc<Vec<見せる行>> {
        Rc::clone(&self.見せる行の順)
    }

    /// 見せる行の順を借りる。
    pub(super) fn 見せる行の順を借りる(&self) -> &[見せる行] {
        &self.見せる行の順
    }

    pub(crate) fn 一覧を置き換える(&mut self, 一覧: 最後に読んだ一覧<一覧>) {
        self.一覧 = 一覧;
        self.見せる行の順を作り直す();
    }

    pub(crate) fn 絞り込みを変える(&mut self, 語: 絞り込みの語) {
        self.見せ方.絞り込み = 語;
        self.見せる行の順を作り直す();
    }

    pub(crate) fn 並べ替えを変える(&mut self, 並べ替え: 並べ替え方) {
        self.見せ方.並べ替え = 並べ替え;
        self.見せる行の順を作り直す();
    }

    fn 見せる行の順を作り直す(&mut self) {
        self.見せる行の順 = Rc::new(match &self.一覧 {
            最後に読んだ一覧::読めた(一覧) => {
                self.見せ方.見せる順に並べる(一覧.as_ref())
            }
            最後に読んだ一覧::まだ無い | 最後に読んだ一覧::読めない(_) => {
                Vec::new()
            }
        });
    }

    /// 識別子の保存物の名前。最後に読んだ一覧に無ければ無い。
    pub(crate) fn 名前(
        &self,
        識別子: &<一覧::読めた as 並べられる保存物>::識別子,
    ) -> Option<<一覧::読めた as 並べられる保存物>::名前> {
        let 最後に読んだ一覧::読めた(一覧) = &self.一覧 else {
            return None;
        };
        (0..一覧.項目の数()).find_map(|位置| match 一覧.項目(位置)? {
            一覧の項目の参照::読めた(読めた) if 読めた.識別子() == 識別子 => {
                Some(読めた.名前().clone())
            }
            _ => None,
        })
    }
}
