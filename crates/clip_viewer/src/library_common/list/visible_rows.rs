//! 見えている行の範囲。一覧の仮想縦スクロールが描画のたびに応答として発した範囲を、応答の適用で状態へ置き、
//! 次のフレームで状態が取り出して、見えている行のサムネイルを先に撮る・読むために使う。
//! スタックと重ね合わせの一覧が共に使う。参照: _doc/設計/ライブラリ.md 判断10(撮るとき)・判断11

use std::ops::RangeInclusive;

/// 見えている行の範囲とは、一覧の見せる行の順の中で、あるフレームに組んだ行の最初と最後の番号の組のことである。最初は最後以下である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 見えている行の範囲 {
    最初: usize,
    最後: usize,
}

impl 見えている行の範囲 {
    /// 両端の行番号から作る。小さい方を最初、大きい方を最後にする。
    pub(crate) fn 両端の行番号から作る(一方: usize, 他方: usize) -> Self {
        Self {
            最初: 一方.min(他方),
            最後: 一方.max(他方),
        }
    }

    /// 範囲の番号。
    pub(crate) fn 番号(self) -> RangeInclusive<usize> {
        self.最初..=self.最後
    }
}
