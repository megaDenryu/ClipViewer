//! 並べられる一覧。ライブラリの一覧(スタック)と重ね合わせの一覧を、絞り込み・並べ替え・見せる行の順(`view.rs`・`shown.rs`)が同じ手順で扱えるようにする。

use clip_domain::{
    スタックの名前, スタックの識別子, ライブラリの日時, 重ね合わせの名前, 重ね合わせの識別子,
};
use clip_library::{
    ライブラリの一覧, 一覧の項目, 読めたスタック, 読めた重ね合わせ, 読めないファイル,
    重ね合わせの一覧, 重ね合わせの一覧の項目,
};

/// 一覧の項目の参照とは、並べられる一覧の項目1つを、読めた保存物か読めないファイルかに分けて借りたもののことである。
pub(crate) enum 一覧の項目の参照<'一覧, 読めた> {
    読めた(&'一覧 読めた),
    読めない(&'一覧 読めないファイル),
}

/// 並べられる保存物とは、一覧の読めた行が、絞り込み(名前)と並べ替え(名前・作った日時・更新した日時)と識別子での検索に答える性質のことである。
pub(crate) trait 並べられる保存物 {
    type 識別子: PartialEq;
    type 名前: Clone;
    fn 識別子(&self) -> &Self::識別子;
    fn 名前(&self) -> &Self::名前;
    fn 名前の文字列(&self) -> &str;
    fn 作った日時(&self) -> ライブラリの日時;
    fn 更新した日時(&self) -> ライブラリの日時;
}

/// 並べられる一覧とは、フォルダを読んだ順の項目を、位置で読めた保存物か読めないファイルとして貸せる一覧の性質のことである。
pub(crate) trait 並べられる一覧 {
    type 読めた: 並べられる保存物;
    fn 項目の数(&self) -> usize;
    fn 項目(&self, 位置: usize) -> Option<一覧の項目の参照<'_, Self::読めた>>;
}

impl 並べられる保存物 for 読めたスタック {
    type 識別子 = スタックの識別子;
    type 名前 = スタックの名前;
    fn 識別子(&self) -> &スタックの識別子 {
        self.スタック.識別子()
    }
    fn 名前(&self) -> &スタックの名前 {
        self.スタック.名前()
    }
    fn 名前の文字列(&self) -> &str {
        self.スタック.名前().文字列()
    }
    fn 作った日時(&self) -> ライブラリの日時 {
        self.スタック.作った日時()
    }
    fn 更新した日時(&self) -> ライブラリの日時 {
        self.スタック.更新した日時()
    }
}

impl 並べられる保存物 for 読めた重ね合わせ {
    type 識別子 = 重ね合わせの識別子;
    type 名前 = 重ね合わせの名前;
    fn 識別子(&self) -> &重ね合わせの識別子 {
        self.重ね合わせ.識別子()
    }
    fn 名前(&self) -> &重ね合わせの名前 {
        self.重ね合わせ.名前()
    }
    fn 名前の文字列(&self) -> &str {
        self.重ね合わせ.名前().文字列()
    }
    fn 作った日時(&self) -> ライブラリの日時 {
        self.重ね合わせ.作った日時()
    }
    fn 更新した日時(&self) -> ライブラリの日時 {
        self.重ね合わせ.更新した日時()
    }
}

impl 並べられる一覧 for ライブラリの一覧 {
    type 読めた = 読めたスタック;
    fn 項目の数(&self) -> usize {
        self.項目.len()
    }
    fn 項目(&self, 位置: usize) -> Option<一覧の項目の参照<'_, 読めたスタック>> {
        Some(match self.項目.get(位置)? {
            一覧の項目::読めた(読めた) => 一覧の項目の参照::読めた(読めた),
            一覧の項目::読めない(読めない) => {
                一覧の項目の参照::読めない(読めない)
            }
        })
    }
}

impl 並べられる一覧 for 重ね合わせの一覧 {
    type 読めた = 読めた重ね合わせ;
    fn 項目の数(&self) -> usize {
        self.項目.len()
    }
    fn 項目(
        &self,
        位置: usize,
    ) -> Option<一覧の項目の参照<'_, 読めた重ね合わせ>> {
        Some(match self.項目.get(位置)? {
            重ね合わせの一覧の項目::読めた(読めた) => {
                一覧の項目の参照::読めた(読めた)
            }
            重ね合わせの一覧の項目::読めない(読めない) => {
                一覧の項目の参照::読めない(読めない)
            }
        })
    }
}
