//! 並べた一覧から行の並びを作る。見えている行の範囲と見せる行の順から、読めた保存物の識別子を並べ、サムネイルの仕事の順にする。

use super::listing::{一覧の項目の参照, 並べられる一覧, 並べられる保存物};
use super::shown::{並べた一覧, 最後に読んだ一覧};
use super::view::見せる行;
use super::visible_rows::見えている行の範囲;
use crate::thumbnail_feed::行の並び;

/// 一覧の行の識別子の型。並べられる一覧の読めた保存物の識別子である。
type 識別子の型<一覧> =
    <<一覧 as 並べられる一覧>::読めた as 並べられる保存物>::識別子;

impl<一覧: 並べられる一覧> 並べた一覧<一覧> {
    /// 見えている行の範囲(無ければ見えている行は無い)と見せる行の順から、行の並びを作る。読めないファイルの行は含めない。
    pub(crate) fn 行の並び(
        &self,
        見えている: Option<見えている行の範囲>,
    ) -> 行の並び<'_, 識別子の型<一覧>> {
        let 見せる順 = self.見せる行の順を借りる();
        let 見えている行 = 見えている
            .and_then(|範囲| 見せる順.get(範囲.番号()))
            .unwrap_or_default();
        行の並び {
            見えている: 見えている行
                .iter()
                .filter_map(|行| self.読めた識別子(行))
                .collect(),
            見せる順: 見せる順
                .iter()
                .filter_map(|行| self.読めた識別子(行))
                .collect(),
        }
    }

    fn 読めた識別子(&self, 行: &見せる行) -> Option<&識別子の型<一覧>> {
        let (見せる行::読めた(位置), 最後に読んだ一覧::読めた(一覧)) = (行, self.一覧())
        else {
            return None;
        };
        match 一覧.項目(*位置)? {
            一覧の項目の参照::読めた(読めた) => Some(読めた.識別子()),
            一覧の項目の参照::読めない(_) => None,
        }
    }
}
