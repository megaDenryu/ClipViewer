//! 一覧の見せ方の試験。名前で絞り込み、並べ替え、読めないファイルは絞り込まずに最後へ出す。
#![allow(clippy::expect_used)]

use clip_domain::{
    クリップスタック, スタックの名前, スタックの識別子, ライブラリのスタック, ライブラリの日時,
    入力された動画パス,
};
use clip_library::{
    ライブラリの一覧, 一覧の項目, 動画の有無, 読めたスタック
};

use super::view::{一覧の見せ方, 並べ替え方, 絞り込みの語, 見せる行};

fn 読めた(番号: u64, 名前: &str, 作った: u64, 更新: u64) -> 一覧の項目 {
    let スタック = ライブラリのスタック::新しく作る(
        スタックの識別子::文字列から作成する(format!("stack-{番号}")).expect("識別子"),
        スタックの名前::作成する(名前.to_string()).expect("名前"),
        入力された動画パス::作成する("C:/a.mp4".into()).正規化する(),
        クリップスタック::default(),
        ライブラリの日時::紀元からのミリ秒で作成する(作った).expect("日時"),
    )
    .名前を変えた(
        スタックの名前::作成する(名前.to_string()).expect("名前"),
        ライブラリの日時::紀元からのミリ秒で作成する(更新).expect("日時"),
    );
    一覧の項目::読めた(読めたスタック {
        スタック,
        動画: 動画の有無::ある,
    })
}

fn 試験の一覧() -> ライブラリの一覧 {
    ライブラリの一覧 {
        項目: vec![
            読めた(1, "Beta", 10, 300),
            一覧の項目::読めない(clip_library::読めないファイル {
                ファイル名: 読めないファイル名(),
                理由: "壊れた".into(),
            }),
            読めた(2, "alpha", 30, 100),
            読めた(3, "gamma", 20, 200),
        ],
    }
}

fn 読めないファイル名() -> clip_library::ライブラリのファイル名 {
    clip_library::ライブラリのファイル名::作成する("stack-9.json".into())
}

fn 名前の順(見せ方: &一覧の見せ方) -> Vec<String> {
    let 一覧 = 試験の一覧();
    let 順 = 見せ方.見せる順に並べる(&一覧);
    assert_eq!(
        順.last(),
        Some(&見せる行::読めない(1)),
        "読めないファイルは絞り込まずに最後に出す"
    );
    順.iter()
        .filter_map(|行| match 行 {
            見せる行::読めた(位置) => match &一覧.項目[*位置] {
                一覧の項目::読めた(読めた) => {
                    Some(読めた.スタック.名前().文字列().to_string())
                }
                一覧の項目::読めない(_) => None,
            },
            見せる行::読めない(_) => None,
        })
        .collect()
}

#[test]
fn 既定は更新日時の新しい順で_ほかの並べ替えも選べる() {
    let mut 見せ方 = 一覧の見せ方::default();
    assert_eq!(名前の順(&見せ方), ["Beta", "gamma", "alpha"]);
    見せ方.並べ替え = 並べ替え方::更新日時の古い順;
    assert_eq!(名前の順(&見せ方), ["alpha", "gamma", "Beta"]);
    見せ方.並べ替え = 並べ替え方::名前順;
    assert_eq!(名前の順(&見せ方), ["alpha", "Beta", "gamma"]);
    見せ方.並べ替え = 並べ替え方::作った日時の新しい順;
    assert_eq!(名前の順(&見せ方), ["alpha", "gamma", "Beta"]);
}

#[test]
fn 名前の一部で大文字と小文字を区別せずに絞り込む() {
    let 見せ方 = 一覧の見せ方 {
        絞り込み: 絞り込みの語::作成する(" A ".into()),
        並べ替え: 並べ替え方::名前順,
    };
    assert_eq!(名前の順(&見せ方), ["alpha", "Beta", "gamma"]);
    let 見せ方 = 一覧の見せ方 {
        絞り込み: 絞り込みの語::作成する("MM".into()),
        並べ替え: 並べ替え方::名前順,
    };
    assert_eq!(名前の順(&見せ方), ["gamma"]);
}
