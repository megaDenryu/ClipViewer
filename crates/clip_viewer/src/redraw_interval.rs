//! 描き直しの間隔。スタックの作業場の画面(`view/invisible.rs`)と重ね合わせの作業場の画面(`overlay/view/`)が共有する、
//! 入力が無くても画面を進める間に描き直す間隔を1か所に置く。2つの作業場の画面はお互いを知らないため、どちらにも属さない置き場にする。

use std::time::Duration;

/// 再生中と、溜めている途中と、最初のコマを待っている間に描き直す間隔(約60回/秒)。描き直しを予約する最短の間隔も兼ねる。
pub(crate) const 描き直しの間隔: Duration = Duration::from_millis(16);

/// 一覧のサムネイルの裏のスレッドの返事を待つ間に描き直す間隔。見えていない行を撮っておく間に、毎フレーム描き直さないためである
/// (見えている行がまだ出せない間は、行の枠が約60回/秒で予約する。キャッシュを見る前の行が残っている間も約60回/秒にする)。
/// スタックの一覧と重ね合わせの一覧が共に使う。
pub(crate) const サムネイルの返事を待つ間隔: Duration = Duration::from_millis(100);
