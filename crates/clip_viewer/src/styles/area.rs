//! 区画の地。ヘッダー・左サイドバー・出力・出力の帯・再生コントロールの各パネルへ付ける背景色と内余白である。
//! 出力は、シアターでは移植元どおり黒の地にする。シアターの操作の欄は出力の下端に重ねるため、半透明の黒の地にする。
//! 出力の区画は内余白を置かない。
//! 縁の余白は出力の寸法の計算(output_measure/output_area.rs の `縁の余白`)が持つためである。

use sengen_egui::{スタイル, 余白画素};

use super::palette;

pub(crate) const ヘッダーの地: スタイル = スタイル {
    背景色: Some(palette::札の地),
    内余白: Some(余白画素(10)),
    ..スタイル::無指定
};

pub(crate) const 左サイドバーの地: スタイル = スタイル {
    背景色: Some(palette::左ペインの地),
    内余白: Some(余白画素(12)),
    ..スタイル::無指定
};

pub(crate) const 出力の帯の地: スタイル = スタイル {
    背景色: Some(palette::出力の帯の地),
    内余白: Some(余白画素(8)),
    ..スタイル::無指定
};

pub(crate) const 出力の地: スタイル = スタイル {
    背景色: Some(palette::最も濃い地),
    内余白: Some(余白画素(0)),
    ..スタイル::無指定
};

pub(crate) const シアターの出力の地: スタイル = スタイル {
    背景色: Some(palette::黒),
    ..出力の地
};

pub(crate) const 再生コントロールの地: スタイル = スタイル {
    背景色: Some(palette::札の地),
    内余白: Some(余白画素(12)),
    ..スタイル::無指定
};

pub(crate) const シアターの操作の欄の地: スタイル = スタイル {
    背景色: Some(palette::半透明の黒),
    内余白: Some(余白画素(14)),
    ..スタイル::無指定
};
