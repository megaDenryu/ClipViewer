//! 音量の設定。つまみで選んだ音量と、M のキーで音を消しているかを持ち、音声のスレッドへ渡す音量を決める。
//! 参照: _doc/設計/画面.md 判断14「キーの割り当て」

use audio_pcm::音量;

/// 消音の様子とは、つまみで選んだ音量のまま鳴らすか、音を消しているかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 消音の様子 {
    鳴らす,
    消している,
}

/// 音量の設定とは、つまみで選んだ音量と消音の様子の組のことである。
/// 音を消している間もつまみの音量を覚え、戻したときにその音量で鳴らす。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 音量の設定 {
    選んだ音量: 音量,
    消音: 消音の様子,
}

impl 音量の設定 {
    /// 起動したときの設定。起動したときの音量で鳴らす。
    pub(crate) const 起動時: Self = Self {
        選んだ音量: 音量::起動したときの音量,
        消音: 消音の様子::鳴らす,
    };

    /// つまみで選んだ音量。音を消している間も、つまみはこの音量を指す。
    pub(crate) fn 選んだ音量(self) -> 音量 {
        self.選んだ音量
    }

    pub(crate) fn 消音の様子(self) -> 消音の様子 {
        self.消音
    }

    /// 音声のスレッドへ渡す音量。音を消している間は無音である。
    pub(crate) fn 鳴らす音量(self) -> 音量 {
        match self.消音 {
            消音の様子::鳴らす => self.選んだ音量,
            消音の様子::消している => 音量::無音,
        }
    }

    /// つまみで音量を選ぶ。音を消していたら戻す(つまみを動かした人は音を聞きたいため。動画サイトの再生画面と同じ)。
    pub(crate) fn 音量を選ぶ(&mut self, 選んだ音量: 音量) {
        self.選んだ音量 = 選んだ音量;
        self.消音 = 消音の様子::鳴らす;
    }

    /// 音を消すか、消していれば戻す。
    pub(crate) fn 消音を切り替える(&mut self) {
        self.消音 = match self.消音 {
            消音の様子::鳴らす => 消音の様子::消している,
            消音の様子::消している => 消音の様子::鳴らす,
        };
    }
}
