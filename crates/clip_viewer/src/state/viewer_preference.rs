//! 見る側の設定と状態の受け渡し。起動したときに settings.json から読んだ設定を状態へ当て、毎フレーム状態から今の設定を組む。
//! 参照: _doc/設計/画面.md 判断17

use super::{アプリの状態, 窓の状態};
use crate::viewer_settings::見る側の設定;

impl アプリの状態 {
    /// 今の見る側の設定。窓の記憶と、つまみで選んだ音量(音を消していても消す前の音量)と、速度と、出力の見せ方である。
    pub(crate) fn 見る側の設定(&self) -> 見る側の設定 {
        見る側の設定 {
            窓: self.窓.記憶(),
            音量: self.再生.音量.選んだ音量(),
            速度: self.再生.速度,
            左右: self.出力.左右,
            アスペクト比: self.出力.アスペクト比,
            表示サイズ: self.出力.表示サイズ,
        }
    }

    /// 起動したときに、settings.json から読んだ見る側の設定を当てる。窓の記憶は、窓を作るときに渡したものと同じである。
    pub(crate) fn 見る側の設定を当てる(&mut self, 設定: 見る側の設定) {
        let 見る側の設定 {
            窓,
            音量,
            速度,
            左右,
            アスペクト比,
            表示サイズ,
        } = 設定;
        self.窓 = 窓の状態::起動時(窓);
        self.再生.音量.音量を選ぶ(音量);
        self.再生.速度 = 速度;
        self.出力.左右 = 左右;
        self.出力.アスペクト比 = アスペクト比;
        self.出力.表示サイズ = 表示サイズ;
    }
}
