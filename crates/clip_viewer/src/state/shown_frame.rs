//! 表示するコマの求めを状態から選ぶ。カードの区間の帯をドラッグしている間は、掴んだものの位置のコマ(プレビュー)を求め、
//! それ以外は再生位置のコマを求める。流し読みを開き直してよいかも、区間の帯のドラッグの間と再生位置の帯のドラッグの間で分ける。
//! 参照: _doc/設計/画面.md 判断5・判断11

use super::band_vocabulary::区間の帯で掴んだもの;
use super::{アプリの状態, シークの様子};
use crate::stream_rules::流し読みの開き直し;
use crate::video_feed::表示するコマの求め;

/// 流し読みの開き直し方とは、映像の流し読みと音の流し読みのそれぞれを、このフレームで開き直してよいかの組のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 流し読みの開き直し方 {
    pub(crate) 映像: 流し読みの開き直し,
    pub(crate) 音: 流し読みの開き直し,
}

impl アプリの状態 {
    /// 画面とテクスチャへ映すコマの求め。区間の帯のドラッグの間はプレビューの求め、それ以外は再生位置の求めである。
    pub(crate) fn 表示するコマの求め(&self) -> Option<表示するコマの求め> {
        self.区間の帯のドラッグのプレビューの求め()
            .or_else(|| self.再生位置の求め())
    }

    /// 再生位置のコマの求め。区間の帯のドラッグのプレビューに置き換える前の求めであり、位置の印はこの位置に描く。
    pub(crate) fn 再生位置の求め(&self) -> Option<表示するコマの求め> {
        表示するコマの求め::求める(&self.並び, self.再生.位置())
    }

    /// 区間の帯のドラッグのプレビューの求め。開始のつまみと区間の内側は新しい開始のコマを、終了のつまみは新しい終了を
    /// 区間の中の最後のコマとして(流し読みも溜めたコマも、区間の終了ちょうどは区間の中の最後のコマを出す)、
    /// 位置の印は区間を持たずにその位置のコマを求める。位置の印の位置は再生モードの写し方で収めてあり、元動画再生では区間の外にもある。
    fn 区間の帯のドラッグのプレビューの求め(
        &self,
    ) -> Option<表示するコマの求め> {
        let ドラッグ = self.区間の帯のドラッグ.as_ref()?;
        let クリップ = self.並び.識別子で探す(ドラッグ.クリップ())?;
        let 仮の区間 = ドラッグ.仮の値().区間;
        let (動画上の位置, 区間) = match ドラッグ.掴んだもの() {
            区間の帯で掴んだもの::開始のつまみ | 区間の帯で掴んだもの::区間の内側 => {
                (仮の区間.開始(), Some(仮の区間))
            }
            区間の帯で掴んだもの::終了のつまみ => (仮の区間.終了(), Some(仮の区間)),
            区間の帯で掴んだもの::位置の印 => (ドラッグ.仮の値().位置, None),
        };
        Some(表示するコマの求め {
            動画上の位置,
            区間,
            クロップ: クリップ.クロップ,
        })
    }

    /// このフレームで流し読みを開き直してよいか。区間の帯のドラッグの間は、映像は掴んだものの位置のコマを映すため開き直してよく、
    /// 音は黙っているため開き直さない。再生位置の帯のドラッグの間はどちらも開き直さない。
    pub(crate) fn 流し読みの開き直し方(&self) -> 流し読みの開き直し方 {
        let シークに従う = match self.再生.シーク {
            シークの様子::していない => 流し読みの開き直し::してよい,
            シークの様子::ドラッグしている => 流し読みの開き直し::控える,
        };
        match self.区間の帯のドラッグ {
            Some(_) => 流し読みの開き直し方 {
                映像: 流し読みの開き直し::してよい,
                音: 流し読みの開き直し::控える,
            },
            None => 流し読みの開き直し方 {
                映像: シークに従う,
                音: シークに従う,
            },
        }
    }
}
