//! 画面の構えを移す。構えを変える経路(利用者の選択・Escape でシアターを抜ける・動画を開いたとき・ライブラリから開いたとき)は、
//! すべてこの1つのメソッドを通し、構えと一緒に変えなければならない再生の状況を揃える。

use super::{アプリの状態, シークの様子, 画面の構え};

impl アプリの状態 {
    /// 構えを移す。変わらなければ何もしない。構えが変わると再生位置の帯は別の部品に描き直されて放したを受け取れないため、
    /// 帯のドラッグの様子を終える(残ると、ドラッグの間は音を黙らせるため音が黙ったままになる)。ライブラリの一覧へ移るときは、
    /// 映像が見えないまま音が鳴り続けないよう再生を止める(参照: _doc/設計/ライブラリ.md 判断8)。変わったかを返す。
    pub(crate) fn 構えを移す(&mut self, 構え: 画面の構え) -> bool {
        if self.出力.構え == 構え {
            return false;
        }
        self.出力.構え = 構え;
        self.再生.シーク = シークの様子::していない;
        if 構え == 画面の構え::ライブラリ {
            self.再生.止める();
        }
        true
    }

    /// ライブラリの構えなら編集の構えへ移る。動画を開いたときと設定を読み込んだときに、開いたものが見えないまま再生しないためである。
    pub(crate) fn ライブラリの構えなら編集へ移る(&mut self) {
        if self.出力.構え == 画面の構え::ライブラリ {
            self.構えを移す(画面の構え::編集);
        }
    }
}
