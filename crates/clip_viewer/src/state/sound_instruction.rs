//! 状態から音の再生の指示を組み立てる。映している区間とその行き先を、溜めた音か流し読みの出どころと組にして渡す。
//! 参照: _doc/設計/アーキテクチャ.md 判断8-5、_doc/設計/画面.md 判断10

use std::time::Instant;

use audio_output::{再生の指示, 再生の様子, 終わりで続く音, 音の区間};
use clip_domain::{
    動画上の区間, 区間の終わりの行き先, 時刻, 時計を進める条件
};

use super::{アプリの状態, シークの様子};
use crate::audio_feed::音の供給;

impl アプリの状態 {
    /// 音声のスレッドへ渡す再生の指示を組み立てる。今は、この指示の位置を求めた時刻である。
    /// 音量は、音を消している間は無音にする。再生位置の帯をドラッグしている間は止めている指示にして黙らせる。音を鳴らせない動画では区間の無い指示にする。
    pub(crate) fn 音の再生の指示(&self, 今: Instant) -> 再生の指示 {
        let mut 指示 = 再生の指示::黙る(今);
        指示.速度 = self.再生.速度;
        指示.音量 = self.再生.音量.鳴らす音量();
        指示.飛ばした回数 = self.再生.飛ばした回数();
        let ドラッグしている = self.再生.シーク == シークの様子::ドラッグしている;
        if self.再生.再生しているか() && !ドラッグしている {
            指示.様子 = 再生の様子::再生している;
        }
        let 供給 = self.動画.as_ref().and_then(|動画| 動画.音.供給());
        let (Some(供給), Some(求め)) = (供給, self.表示するコマの求め()) else {
            return 指示;
        };
        let 周波数 = 供給.周波数();
        let 区間 = 求め.区間.unwrap_or_else(|| self.動画の全体());
        指示.位置 = 周波数.時刻の小数の位置(求め.動画上の位置);
        指示.区間 = Some(音の区間 {
            範囲: 周波数.区間の範囲(&区間),
            出どころ: 供給.鳴らす出どころ(求め.区間.as_ref(), 求め.動画上の位置),
        });
        指示.行き先 = self.区間の終わりで続く音(供給);
        指示
    }

    /// 元動画再生で区間として扱う、動画の全体。
    fn 動画の全体(&self) -> 動画上の区間 {
        動画上の区間::開始と長さから作る(時刻::先頭, self.動画の長さ())
    }

    fn 区間の終わりで続く音(&self, 供給: &音の供給) -> 終わりで続く音 {
        let 条件 = 時計を進める条件 {
            スタック: &self.並び,
            動画の長さ: self.動画の長さ(),
            速度: self.再生.速度,
            全体の末尾: self.再生.全体の末尾,
        };
        match self.再生.位置().区間の終わりの行き先(&条件) {
            区間の終わりの行き先::区間の開始へ戻る => {
                終わりで続く音::開始へ戻る
            }
            区間の終わりの行き先::止まる => 終わりで続く音::止まる,
            区間の終わりの行き先::別の区間へ進む(次) => {
                終わりで続く音::別の区間へ進む(音の区間 {
                    範囲: 供給.周波数().区間の範囲(&次),
                    出どころ: 供給.溜めた音の出どころ(&次),
                })
            }
        }
    }
}
