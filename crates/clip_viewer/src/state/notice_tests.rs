//! 通知の試験。続けて出した通知を置き換えずに最近のものから並べ、書き足すときは最新の通知を新しい回の1つの文に置き換える。
#![allow(clippy::expect_used)]

use super::notice::通知;

fn 並べる数(通知: &通知) -> usize {
    通知.並べる通知().len()
}

#[test]
fn 続けて出した通知は置き換えずに並べ_上限を超えたら古いものから外す() {
    let mut 通知 = 通知::default();
    通知.出す("設定を読めない");
    通知.出す("音を鳴らせない");
    assert_eq!(
        並べる数(&通知),
        2,
        "起動の途中の知らせが前の知らせを消さない"
    );
    for 番号 in 0..5 {
        通知.出す(format!("知らせ{番号}"));
    }
    assert_eq!(並べる数(&通知), 4);
    assert_eq!(
        通知.最新().map(|(_, 文面)| 文面.to_string()),
        Some("知らせ4".into())
    );
}

#[test]
fn 前の回の後に出た通知へ書き足すと新しい回の1つの文にする() {
    let mut 通知 = 通知::default();
    通知.出す("起動した");
    let 前の回 = 通知.最新().map(|(通知の回, _)| 通知の回);
    通知.出す("動画を読み込みました");
    let 書き足す前の回 = 通知.最新().map(|(通知の回, _)| 通知の回);
    通知.この回の後に書き足す(前の回, vec!["ほかの動画は開いていない".into()]);
    assert_eq!(並べる数(&通知), 2);
    let (通知の回, 文面) = 通知.最新().expect("ある");
    assert_eq!(文面, "動画を読み込みました。ほかの動画は開いていない");
    assert_ne!(
        Some(通知の回),
        書き足す前の回,
        "書き足した通知は新しい回として表示し直す"
    );
}
