//! 並びの変化を編集の履歴へ積むことと、取り消しとやり直しで並びを戻すこと。
//! 積むのは毎フレームの最初の1箇所であり、クロップ枠をドラッグしている間は積まない(放した時点で1つの変化として積む)。
//! 区間の帯のドラッグの間はクリップスタックを変えないため、放した時点で1つの変化になる(画面.md 判断11)。
//! 参照: _doc/設計/画面.md 判断14

use clip_domain::クリップスタック;

use super::アプリの状態;

impl アプリの状態 {
    /// 毎フレームの最初に呼ぶ。クロップ枠をドラッグしていなければ、並びの変化を履歴へ積む。
    pub(crate) fn 並びの変化を履歴へ積む(&mut self) {
        if self.掴み始め.is_none() {
            self.履歴.並びを見る(&self.並び);
        }
    }

    /// 最後の編集を取り消す。ドラッグの途中と、取り消せる編集が無いときは何もしない。
    pub(crate) fn 編集を取り消す(&mut self) {
        if self.ドラッグしているか() {
            return;
        }
        if let Some(戻す並び) = self.履歴.取り消す(&self.並び) {
            self.履歴から並びを戻す(戻す並び);
        }
    }

    /// 取り消した編集をやり直す。ドラッグの途中と、やり直せる編集が無いときは何もしない。
    pub(crate) fn 編集をやり直す(&mut self) {
        if self.ドラッグしているか() {
            return;
        }
        if let Some(進める並び) = self.履歴.やり直す(&self.並び) {
            self.履歴から並びを戻す(進める並び);
        }
    }

    /// 取り消しのボタンを押せるか。
    pub(crate) fn 取り消せるか(&self) -> bool {
        !self.ドラッグしているか() && self.履歴.取り消せるか(&self.並び)
    }

    /// やり直しのボタンを押せるか。
    pub(crate) fn やり直せるか(&self) -> bool {
        !self.ドラッグしているか() && self.履歴.やり直せるか(&self.並び)
    }

    fn ドラッグしているか(&self) -> bool {
        self.掴み始め.is_some() || self.区間の帯のドラッグ.is_some()
    }

    /// 履歴の並びへ戻す。選択は履歴に積んだときのものでなく今のものを保つ(選択の変化は編集として積まないため)。
    /// 今選んでいるクリップが戻した並びに無ければ、戻した並びの選択を使う。
    fn 履歴から並びを戻す(&mut self, mut 並び: クリップスタック) {
        if let Some(選択中) = self
            .並び
            .選択中のクリップ()
            .map(|クリップ| クリップ.識別子().clone())
        {
            let _ = 並び.選択する(&選択中);
        }
        self.並び = 並び;
        self.選んだクリップへ再生位置を合わせる();
    }
}
