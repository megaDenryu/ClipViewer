//! 関係を終える前の確かめ。開いているスタックとの関係を終える操作(多くは今の並びを捨てる)の前に、失われる変更が無いかを確かめる。
//! 登録済みなら、今の並びがファイルに書けたことを確かめ、書けていなければ保存を頼み直して書き込みを終えるまで待ち、それでも書けなければ窓を出す。
//! 未登録なら、並びを捨てる操作で、並びを置き換えたときから変えたクリップがあるか、ファイルから読んだ並びを名前の違う動画で捨てるときに窓を出す
//! (自動保存の対象でなく、黙って捨てると失われるため)。同じ動画を開き直すときは並びと関係を残すため確かめない。
//! 参照: _doc/設計/ライブラリ.md 判断5・判断7

use clip_domain::正規化した動画パス;

use super::library::{
    ライブラリの窓, 並びを捨てる理由, 開いているスタック, 関係を終える操作
};
use super::アプリの状態;

/// 確かめた結果とは、関係を終える前に確かめて、操作を続けてよいか、確かめる窓を出したので止めるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 確かめた結果 {
    続けてよい,
    確かめる窓を出した,
}

impl アプリの状態 {
    /// 関係を終える前に、失われる変更が無いことを確かめる。あれば、理由と続ける操作を持った確かめる窓を出す。
    pub(crate) fn 関係を終える前に確かめる(
        &mut self,
        続ける操作: 関係を終える操作,
    ) -> 確かめた結果 {
        if self.並びを残す操作か(&続ける操作) {
            return 確かめた結果::続けてよい;
        }
        let 窓 = match &self.ライブラリ.開いている {
            開いているスタック::未登録 => match self
                .未登録の並びを捨てる理由(&続ける操作)
            {
                Some(理由) => ライブラリの窓::並びを捨てる確認(理由, 続ける操作),
                None => return 確かめた結果::続けてよい,
            },
            開いているスタック::登録済み(_) => match self.保存を確かめる() {
                Ok(()) => return 確かめた結果::続けてよい,
                Err(理由) => {
                    ライブラリの窓::保存できずに続ける確認(理由, 続ける操作)
                }
            },
        };
        self.ライブラリ.窓 = 窓;
        確かめた結果::確かめる窓を出した
    }

    /// 動画を開くときに、今の並びを残してよいか。並びが空でなく、並びを作った動画(設定ファイルが期待する動画か、最後に開いた動画)の
    /// ファイル名が開く動画と同じとき(大文字と小文字は区別しない)と、期待する動画が分からないとき(動画の名前を持たない設定ファイルを読んだ後)に残す。
    /// 別の動画の区間を新しい動画のパスでライブラリへ登録しないため、それ以外は新しい並びで始める。
    pub(crate) fn 並びを残して動画を開けるか(
        &self,
        パス: &正規化した動画パス,
    ) -> bool {
        if self.並び.一覧().is_empty() {
            return false;
        }
        match (self.手がかり.期待する動画(), パス.ファイル名()) {
            (None, _) => true,
            (Some(期待する), Some(開く)) => {
                期待する.大文字小文字を区別せず等しいか(&開く)
            }
            (Some(_), None) => false,
        }
    }

    /// 続ける操作が、並びも開いているスタックとの関係も残すか。残すなら確かめることが無い。登録済みのスタックとの関係を残すのは、
    /// 動画のパス全体が同じときだけである(`関係を保って開き直せるか`)。
    fn 並びを残す操作か(&self, 続ける操作: &関係を終える操作) -> bool {
        matches!(続ける操作, 関係を終える操作::動画を開く(入力, _)
            if self.並びを残して動画を開けるか(&入力.正規化する())
                && self.関係を保って開き直せるか(&入力.正規化する()))
    }

    /// 未登録の並びを、続ける操作が捨てるときに確かめる理由。並びを置き換えたときからクリップを変えていれば、登録していない変更がある。
    /// 変えていなくても、ファイルから読んだ並びを名前の違う動画を開いて捨てるときは確かめる(読み込んだ並びを使うつもりで動画を開くことが多いため)。
    /// 並びが空か、失うものが無ければ無い。
    fn 未登録の並びを捨てる理由(
        &self,
        続ける操作: &関係を終える操作,
    ) -> Option<並びを捨てる理由> {
        let 起点 = &self.履歴.起点;
        if self.並び.一覧().is_empty() {
            return None;
        }
        if 起点.変わったか(&self.並び) {
            return Some(並びを捨てる理由::登録していない変更がある);
        }
        (matches!(続ける操作, 関係を終える操作::動画を開く(..)) && 起点.ファイルから読んだか())
            .then_some(並びを捨てる理由::読み込んだ並びを名前の違う動画で捨てる)
    }

    fn 保存を確かめる(&mut self) -> Result<(), String> {
        let 開いているスタック::登録済み(登録済み) = &self.ライブラリ.開いている
        else {
            return Ok(());
        };
        if 登録済み
            .保存の様子()
            .書けたことを確かめる(self.並び.一覧())
            .is_ok()
        {
            return Ok(());
        }
        if 登録済み.保存の様子().保存されていないか(self.並び.一覧()) {
            self.今の並びの保存を頼む();
        }
        self.ライブラリ.接続.書き込みを終えるまで待つ();
        self.ライブラリの知らせを受け取る();
        match &self.ライブラリ.開いている {
            開いているスタック::登録済み(登録済み) => 登録済み
                .保存の様子()
                .書けたことを確かめる(self.並び.一覧())
                .map_err(|理由| 理由.to_string()),
            開いているスタック::未登録 => Ok(()),
        }
    }
}
