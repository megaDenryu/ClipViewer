//! 動画の手がかり。設定ファイルが期待する動画のファイル名と、利用者が書き留めた動画のパス(パスのメモ)を持つ。

use clip_domain::{
    入力された動画パス, 動画パスの検証結果, 動画ファイル名, 正規化した動画パス
};

/// 動画の手がかりとは、スタックを作った動画のファイル名と、その動画のPC内の絶対パスのメモの組のことである。
/// 設定ファイルの書き出しは、パスのメモをこのファイル名で検証してから行う。
#[derive(Debug, Clone)]
pub(crate) struct 動画の手がかり {
    期待する動画: Option<動画ファイル名>,
    パスのメモ: 入力された動画パス,
}

impl 動画の手がかり {
    /// 何も分かっていない手がかり。
    pub(crate) fn 空() -> Self {
        Self {
            期待する動画: None,
            パスのメモ: 入力された動画パス::作成する(String::new()),
        }
    }

    pub(crate) fn 期待する動画(&self) -> Option<&動画ファイル名> {
        self.期待する動画.as_ref()
    }

    pub(crate) fn パスのメモ(&self) -> &入力された動画パス {
        &self.パスのメモ
    }

    pub(crate) fn パスのメモを書き換える(&mut self, 入力: String) {
        self.パスのメモ = 入力された動画パス::作成する(入力);
    }

    /// 動画を開いたとき、その動画のファイル名とパスを手がかりにする(移植元と同じ)。
    pub(crate) fn 開いた動画に合わせる(&mut self, パス: &正規化した動画パス) {
        self.期待する動画 = パス.ファイル名();
        self.パスのメモ = 入力された動画パス::作成する(パス.文字列().to_string());
    }

    /// 設定ファイルを読み込んだとき、ファイルに書かれた手がかりにする。パスが無ければメモを空にする。
    pub(crate) fn 設定ファイルに合わせる(
        &mut self,
        期待する動画: Option<動画ファイル名>,
        期待する動画のパス: Option<&正規化した動画パス>,
    ) {
        self.期待する動画 = 期待する動画;
        let 文字列 = 期待する動画のパス.map_or(String::new(), |パス| パス.文字列().to_string());
        self.パスのメモ = 入力された動画パス::作成する(文字列);
    }

    /// パスのメモを期待する動画で検証する。ファイル名もメモも無いときは検証しない(移植元と同じ)。
    pub(crate) fn 検証する(&self) -> Option<動画パスの検証結果> {
        let 何も無い = self.期待する動画.is_none() && self.パスのメモ.正規化する().空か();
        (!何も無い).then(|| self.パスのメモ.検証する(self.期待する動画.as_ref()))
    }
}
