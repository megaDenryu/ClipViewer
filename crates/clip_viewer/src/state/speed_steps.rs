//! 速度の選択肢。[ と ] のキーで速度を1段ずつ変える規則を持つ。
//! 選択肢とは別に、つまみは範囲(`viewer_settings::速度のつまみの範囲`)の中を0.05倍刻みで選べる。参照: _doc/設計/画面.md 判断14「キーの割り当て」

use clip_domain::再生速度;

use super::再生の状況;

/// 速度の選択肢とは、[ と ] のキーで選べる倍率の並びのことであり、つまみの範囲を0.25倍ごとに区切ったものである。
/// 動画サイトの再生画面の速度の選択肢と同じ幅にし、等倍を選択肢に含める。
const 速度の選択肢: [f64; 8] = [0.25, 0.5, 0.75, 1.0, 1.25, 1.5, 1.75, 2.0];

/// 今の倍率が選択肢の上にあるとみなす許し。つまみの刻みで選んだ値を、小数の誤差で選択肢の外と判定しないためである。
const 選択肢の上とみなす許し: f64 = 1e-6;

/// 速度を変える向きとは、[ のキーで1段下げるか、] のキーで1段上げるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 速度を変える向き {
    下げる,
    上げる,
}

impl 再生の状況 {
    /// 速度を1段変える。選択肢の間の倍率(つまみで1.1倍を選んだ等)からは、その向きで最も近い選択肢へ移る。
    /// 最も遅い選択肢より下と、最も速い選択肢より上へは動かない。
    pub(crate) fn 速度を一段変える(&mut self, 向き: 速度を変える向き) {
        let 今 = self.速度.倍率();
        let 選択肢 = 速度の選択肢.into_iter();
        let 次の倍率 = match 向き {
            速度を変える向き::上げる => 選択肢
                .filter(|倍率| *倍率 > 今 + 選択肢の上とみなす許し)
                .reduce(f64::min),
            速度を変える向き::下げる => 選択肢
                .filter(|倍率| *倍率 < 今 - 選択肢の上とみなす許し)
                .reduce(f64::max),
        };
        if let Some(速度) = 次の倍率.and_then(|倍率| 再生速度::作成する(倍率).ok())
        {
            self.速度 = 速度;
        }
    }
}
