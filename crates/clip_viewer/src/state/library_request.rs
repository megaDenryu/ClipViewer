//! ライブラリへ頼みを送ること。送れなければ理由を通知する。変更の後には一覧を読み直すことも頼む。

use clip_library::ライブラリへの頼み;

use super::library::最後に読んだ一覧;
use super::アプリの状態;
use crate::library_common::save::ライブラリを使えない理由;

/// 頼んだ結果とは、ライブラリへ頼みを送れたか、送れずに理由を通知したかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 頼んだ結果 {
    送れた,
    送れなかった,
}

impl アプリの状態 {
    /// 頼みを送る。送れなければ理由を通知する。
    pub(crate) fn ライブラリへ頼む(
        &mut self, 頼み: ライブラリへの頼み
    ) -> 頼んだ結果 {
        match self.ライブラリ.接続.頼む(頼み) {
            Ok(()) => 頼んだ結果::送れた,
            Err(理由) => {
                self.通知.出す(format!("ライブラリへ書き込めない: {理由}"));
                頼んだ結果::送れなかった
            }
        }
    }

    /// 変更を頼み、続けて一覧を読み直すことも頼む。一覧を作る頼みは書き込みの後ろに並ぶので、一覧は変更の後の中身になる。
    pub(crate) fn 変更を頼んで一覧を読み直す(
        &mut self, 頼み: ライブラリへの頼み
    ) {
        if self.ライブラリへ頼む(頼み) == 頼んだ結果::送れた {
            self.一覧を読み直す();
        }
    }

    /// 一覧を読み直すことを頼む。置き場所が無ければ、置き場所の文で知らせているので黙る。
    /// 裏のスレッドが止まっていて頼めなければ、一覧を読めないとして理由を一覧の画面に出す(黙って古い一覧を見せ続けないため)。
    pub(crate) fn 一覧を読み直す(&mut self) {
        match self.ライブラリ.接続.頼む(ライブラリへの頼み::一覧を作る) {
            Ok(()) | Err(ライブラリを使えない理由::置き場所が無い) => {}
            Err(理由 @ ライブラリを使えない理由::頼めない(_)) => self
                .ライブラリ
                .一覧
                .一覧を置き換える(最後に読んだ一覧::読めない(理由.to_string())),
        }
    }
}
