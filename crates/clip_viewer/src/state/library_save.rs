//! ライブラリの自動保存。登録済みのスタックの並びが変わって落ち着いたら保存を頼み、失敗したら間隔を置いて頼み直す。
//! 関係を終える前の確かめは `relation_check.rs` が行う。参照: _doc/設計/ライブラリ.md 判断5

use std::time::Instant;

use super::library::{
    保存の段階, 保存の目的, 登録済みのスタック, 開いているスタック
};
use super::アプリの状態;
use crate::library_common::save::見た結果;

impl アプリの状態 {
    /// 毎フレーム呼ぶ。届いた知らせを当て、登録済みのスタックの並びが落ち着いたか、頼み直すときなら保存を頼む。
    /// 最後に、次に並びを見るまでの時間を決める(入力が無くてもその時刻に画面を進めるため)。
    pub(crate) fn ライブラリの書き込みを進める(&mut self, 今: Instant) {
        self.ライブラリの知らせを受け取る();
        if let 開いているスタック::登録済み(登録済み) = &mut self.ライブラリ.開いている
            && 登録済み.並びを見る(self.並び.一覧(), 今) == 見た結果::保存する
        {
            self.今の並びの保存を頼む();
        }
        self.ライブラリ.次に並びを見るまでの時間 = match &self.ライブラリ.開いている {
            開いているスタック::登録済み(登録済み) => {
                登録済み.次に並びを見るまでの時間(今)
            }
            開いているスタック::未登録 => None,
        };
    }

    /// 開いている登録済みのスタックと、その今の並びでの保存の段階。未登録なら無い。ヘッダーの保存の様子が読む。
    pub(crate) fn 開いている登録済みのスタックと保存の段階(
        &self,
    ) -> Option<(&登録済みのスタック, 保存の段階<'_>)> {
        match &self.ライブラリ.開いている {
            開いているスタック::登録済み(登録済み) => {
                Some((登録済み, 登録済み.保存の様子().段階(self.並び.一覧())))
            }
            開いているスタック::未登録 => None,
        }
    }

    /// 開いている登録済みのスタックの、今の並びでの保存の段階。未登録なら無い。重ね合わせが前の間に保存の失敗を重ね合わせの作業場の知らせへ出す
    /// 配線(`app/stack_values.rs`)と、ライブラリの試験が読む。
    pub(crate) fn 開いているスタックの保存の段階(
        &self,
    ) -> Option<保存の段階<'_>> {
        self.開いている登録済みのスタックと保存の段階()
            .map(|(_, 段階)| 段階)
    }

    /// 開いているスタックとの関係を終えて未登録へ戻す。保存は呼ぶ前に `関係を終える前に確かめる` で確かめておく。
    pub(crate) fn 開いているスタックとの関係を終える(&mut self) {
        self.ライブラリ.開いている = 開いているスタック::未登録;
    }

    /// アプリを閉じるときに、書けていない並びがあれば保存を頼む。頼んだ書き込みは、接続が落とされるときに終えてから閉じる。
    pub(crate) fn 書けていない並びの保存を頼む(&mut self) {
        if self.ライブラリ.保存されていないか(self.並び.一覧()) {
            self.今の並びの保存を頼む();
        }
    }

    /// 今の並びで中身を差し替えて保存を頼む。頼めなければ失敗として覚え、間隔を置いて頼み直す。
    pub(crate) fn 今の並びの保存を頼む(&mut self) {
        let 開いているスタック::登録済み(登録済み) = &mut self.ライブラリ.開いている
        else {
            return;
        };
        let 今の日時 = self.ライブラリ.接続.今の日時();
        let 中身 = 登録済み
            .中身()
            .clone()
            .並びを差し替えた(self.並び.clone(), 今の日時);
        match self
            .ライブラリ
            .接続
            .保存を頼む(中身.clone(), 保存の目的::自動保存)
        {
            Ok(番号) => 登録済み.保存を頼んだ(中身, 番号),
            Err(理由) => 登録済み.保存を頼めなかった(理由),
        }
    }
}
