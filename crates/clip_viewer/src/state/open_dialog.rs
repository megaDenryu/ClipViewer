//! 開いているダイアログ。画面を覆うダイアログ(ライブラリのダイアログとキーの一覧のダイアログ)のどれかを開いているかを判定する。
//! 開いている間は、ウインドウへ落としたファイルも、2つ目のアプリから届いた動画も開かない。判定はこの1か所に置く。

use super::{アプリの状態, キーの一覧のダイアログ};

impl アプリの状態 {
    /// ライブラリのダイアログかキーの一覧のダイアログを開いているか。
    pub(crate) fn ダイアログを開いているか(&self) -> bool {
        self.ライブラリ.ダイアログ.開いているか()
            || self.キーの一覧 == キーの一覧のダイアログ::開いている
    }
}
