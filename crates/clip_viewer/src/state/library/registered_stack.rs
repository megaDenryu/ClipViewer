//! 登録済みのスタックだけが持つ変え方。名前の変更と動画の場所の変更は、ファイルへの頼みと同時に中身へも当てる。後から頼む自動保存が古い値で上書きしないためである。
//! 保存の追跡は2つの作業場が共有する `library_common::save::登録済みの保存物` が持つ。参照: _doc/設計/ライブラリ.md 判断5

use clip_domain::{
    スタックの名前, ライブラリのスタック, ライブラリの日時, 正規化した動画パス
};

use crate::library_common::save::登録済みの保存物;

/// 登録済みのスタックとは、ライブラリのスタックを保存物にした登録済みの保存物のことである。
pub(crate) type 登録済みのスタック = 登録済みの保存物<ライブラリのスタック>;

impl 登録済みのスタック {
    /// ファイルへ頼んだ名前の変更を、中身へも当てる。
    pub(crate) fn 名前を変えた(
        &mut self, 名前: スタックの名前, 今: ライブラリの日時
    ) {
        self.保存物を置き換える(self.保存物().clone().名前を変えた(名前, 今));
    }

    /// ファイルへ頼んだ動画の場所の変更を、中身へも当てる。
    pub(crate) fn 動画の場所を変えた(
        &mut self,
        パス: 正規化した動画パス,
        今: ライブラリの日時,
    ) {
        self.保存物を置き換える(self.保存物().clone().動画の場所を変えた(パス, 今));
    }
}
