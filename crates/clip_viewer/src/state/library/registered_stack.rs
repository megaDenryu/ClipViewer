//! 登録済みのスタック。最後に保存を頼んだ中身と、保存の様子と、変更の見張りを持つ。
//! 参照: _doc/設計/ライブラリ.md 判断5

use std::time::{Duration, Instant};

use clip_domain::{
    クリップ, スタックの名前, スタックの識別子, ライブラリのスタック, ライブラリの日時,
    正規化した動画パス,
};
use clip_library::{ライブラリの操作エラー, 保存の番号};

use super::change_watch::{変更の見張り, 見た結果};
use super::connection::ライブラリを使えない理由;
use super::save_status::保存の様子;

/// 登録済みのスタックとは、最後に保存を頼んだ中身と、保存の様子(ファイルに書けたと分かっている並びを含む)と、変更の見張りの組のことである。
/// 名前の変更と動画の場所の変更は、ファイルへの頼みと同時に中身へも当てる。後から頼む自動保存が古い名前で上書きしないためである。
#[derive(Debug)]
pub(crate) struct 登録済みのスタック {
    中身: ライブラリのスタック,
    保存: 保存の様子,
    見張り: 変更の見張り,
}

impl 登録済みのスタック {
    /// ファイルから読んで開いたスタック。
    pub(crate) fn ファイルから開いた(中身: ライブラリのスタック) -> Self {
        Self {
            保存: 保存の様子::ファイルから開いた(中身.並び().clone()),
            中身,
            見張り: 変更の見張り::default(),
        }
    }

    /// 登録の保存を頼んだスタック。書けたと分かるまでファイルにある並びは無い。
    pub(crate) fn 登録を頼んだ(
        中身: ライブラリのスタック, 番号: 保存の番号
    ) -> Self {
        Self {
            保存: 保存の様子::登録を頼んだ(番号, 中身.並び().clone()),
            中身,
            見張り: 変更の見張り::default(),
        }
    }

    pub(crate) fn 中身(&self) -> &ライブラリのスタック {
        &self.中身
    }

    pub(crate) fn 識別子(&self) -> &スタックの識別子 {
        self.中身.識別子()
    }

    pub(crate) fn 名前(&self) -> &スタックの名前 {
        self.中身.名前()
    }

    /// 保存の様子。ファイルに書けたか・保存の段階を読むために貸す。変えるのはこの型のメソッドだけである。
    pub(crate) fn 保存の様子(&self) -> &保存の様子 {
        &self.保存
    }

    /// 今の並びを見て、保存を頼むかを判定する。保存に失敗した後は間隔を置いて頼み直し、それ以外は並びが落ち着いたら頼む。
    pub(crate) fn 並びを見る(
        &mut self, 今の並び: &[クリップ], 今: Instant
    ) -> 見た結果 {
        if self.保存.頼み直すときか(今) {
            return 見た結果::保存する;
        }
        self.見張り.見る(今の並び, self.中身.並び().一覧(), 今)
    }

    /// 次に並びを見て保存を頼むかもしれない時刻までの残り。落ち着き待ちと頼み直しの早い方であり、どちらも無ければ無い。
    pub(crate) fn 次に並びを見るまでの時間(&self, 今: Instant) -> Option<Duration> {
        [
            self.保存.頼み直すまでの時間(今),
            self.見張り.落ち着くまでの残り(今),
        ]
        .into_iter()
        .flatten()
        .min()
    }

    /// 保存を頼んだ。中身を頼んだものに置き換える。
    pub(crate) fn 保存を頼んだ(
        &mut self, 中身: ライブラリのスタック, 番号: 保存の番号
    ) {
        self.保存.頼んだ(番号, 中身.並び().clone());
        self.中身 = 中身;
        self.見張り = 変更の見張り::default();
    }

    /// 保存を頼めなかった。
    pub(crate) fn 保存を頼めなかった(
        &mut self, 理由: ライブラリを使えない理由
    ) {
        self.保存.頼めなかった(理由);
    }

    /// 保存を終えた知らせを受けた。書けたならファイルにある並びを進める。
    pub(crate) fn 保存を終えた(
        &mut self,
        番号: 保存の番号,
        結果: Result<(), ライブラリの操作エラー>,
    ) {
        self.保存.終えた(番号, 結果);
    }

    /// ファイルへ頼んだ名前の変更を、中身へも当てる。
    pub(crate) fn 名前を変えた(
        &mut self, 名前: スタックの名前, 今: ライブラリの日時
    ) {
        self.中身 = self.中身.clone().名前を変えた(名前, 今);
    }

    /// ファイルへ頼んだ動画の場所の変更を、中身へも当てる。
    pub(crate) fn 動画の場所を変えた(
        &mut self,
        パス: 正規化した動画パス,
        今: ライブラリの日時,
    ) {
        self.中身 = self.中身.clone().動画の場所を変えた(パス, 今);
    }
}
