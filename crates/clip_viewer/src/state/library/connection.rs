//! ライブラリの接続。スタックのライブラリの裏のスレッドを持ち、頼みを送り、返事を待っている頼みを数え、知らせを受け取る。
//! 読み込んだ動画と同じく、アプリが生きている間の資源として状態に置く。置き場所の有無と書けるかの正本はこの型だけである。
//! ライブラリの日時を得るために時計を読む境界もここ1箇所である。

use std::time::SystemTime;

use clip_domain::{ライブラリのスタック, ライブラリの日時};
use clip_library::{
    ライブラリからの知らせ, ライブラリへの頼み, 保存の番号, 裏で動くライブラリ,
    錠を試したライブラリ, 頼めない理由,
};

use super::save_purpose::{保存の目的, 知らせる保存の控え};

/// ライブラリを使えない理由とは、スタックのライブラリへ頼みを送れない理由の区別のことである。
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub(crate) enum ライブラリを使えない理由 {
    #[error("ライブラリの置き場所が無い(環境変数 APPDATA が無い)")]
    置き場所が無い,
    #[error("{0}")]
    頼めない(#[from] 頼めない理由),
}

/// ライブラリの接続とは、裏で動くライブラリ(置き場所が無ければ無い)と、最後に頼んだ保存の番号と、
/// 返事を待っている頼みの数と、結果を利用者へ知らせる保存の目的の組のことである。
pub(crate) struct ライブラリの接続 {
    pub(super) 裏で動くライブラリ: Option<裏で動くライブラリ>,
    最後の保存の番号: 保存の番号,
    返事を待っている頼みの数: usize,
    知らせる保存: 知らせる保存の控え,
}

impl ライブラリの接続 {
    /// 錠を試したライブラリがあれば、裏のスレッドを起こす(錠を取れていなければ読むだけ)。無ければ置き場所が無い接続にする。
    /// 錠は起動の部分が先に試す。取れなかったときに、錠を持つアプリへ動画を渡して終わるかを決めるためである(画面.md 判断13)。
    pub(crate) fn 錠を試したライブラリから起動する(
        試した: Option<錠を試したライブラリ>,
    ) -> Self {
        Self {
            裏で動くライブラリ: 試した.map(裏で動くライブラリ::錠を試した後で起動する),
            最後の保存の番号: 保存の番号::default(),
            返事を待っている頼みの数: 0,
            知らせる保存: 知らせる保存の控え::default(),
        }
    }

    /// 裏で動くライブラリ。置き場所が無ければ、使えない理由(置き場所が無い)を返す。
    pub(super) fn 裏で動くライブラリ(
        &self,
    ) -> Result<&裏で動くライブラリ, ライブラリを使えない理由> {
        self.裏で動くライブラリ
            .as_ref()
            .ok_or(ライブラリを使えない理由::置き場所が無い)
    }

    /// 頼みを送る。待たない。送れたら、返事を待っている頼みとして数える。
    pub(crate) fn 頼む(
        &mut self,
        頼み: ライブラリへの頼み,
    ) -> Result<(), ライブラリを使えない理由> {
        self.裏で動くライブラリ()?.頼む(頼み)?;
        self.返事を待っている頼みの数 += 1;
        Ok(())
    }

    /// 次の保存の番号を付けて、スタックの保存を頼む。自動保存でなければ、結果を知らせるために目的を覚える。
    pub(crate) fn 保存を頼む(
        &mut self,
        スタック: ライブラリのスタック,
        目的: 保存の目的,
    ) -> Result<保存の番号, ライブラリを使えない理由> {
        let 番号 = self.最後の保存の番号.次();
        self.頼む(ライブラリへの頼み::保存する(スタック, 番号))?;
        self.最後の保存の番号 = 番号;
        self.知らせる保存.控える(番号, 目的);
        Ok(番号)
    }

    /// 番号の保存の目的を取り出す。覚えていなければ自動保存である。
    pub(crate) fn 保存の目的を取り出す(
        &mut self, 番号: 保存の番号
    ) -> 保存の目的 {
        self.知らせる保存.取り出す(番号)
    }

    /// 届いている知らせをすべて受け取り、その数だけ返事を待っている頼みを減らす。
    pub(crate) fn 届いた知らせを受け取る(
        &mut self,
    ) -> Vec<ライブラリからの知らせ> {
        let 知らせ = self
            .裏で動くライブラリ()
            .map(裏で動くライブラリ::届いた知らせを受け取る)
            .unwrap_or_default();
        self.返事を待っている頼みの数 = self.返事を待っている頼みの数.saturating_sub(知らせ.len());
        知らせ
    }

    /// 裏のスレッドの返事を待っているか。待っている間は、入力が無くても画面を進めて知らせを受け取る。
    pub(crate) fn 返事を待っているか(&self) -> bool {
        self.返事を待っている頼みの数 > 0
    }

    /// 今のライブラリの日時。時計が1970年より前か9999年より後を指す壊れた状態では、1970年1月1日にする(日時は並べ替えと表示にだけ使うため)。
    pub(crate) fn 今の日時(&self) -> ライブラリの日時 {
        ライブラリの日時::時刻から作成する(SystemTime::now()).unwrap_or(ライブラリの日時::紀元)
    }
}
