//! 保存の様子。開いている登録済みのスタックについて、ファイルに書けたと分かっている並びと、頼んでいて結果を待っている保存と、
//! 最後の保存の失敗と、頼み直しを持つ。
//! 参照: _doc/設計/ライブラリ.md 判断5

use std::time::{Duration, Instant};

use clip_domain::{クリップ, クリップスタック};
use clip_library::{ライブラリの操作エラー, 保存の番号};

use super::connection::ライブラリを使えない理由;
use super::save_failure::{保存の失敗, 書けていない理由};
use super::save_retry::頼み直し;

/// 保存の様子とは、ファイルに書けたと分かっている並び(登録を頼んだだけでまだ書けていなければ無い)と、頼んで結果を待っている保存
/// (番号と並び)と、最後に終えた保存が失敗したならその理由と、頼み直しの組のことである。
/// ファイルにある並びは、保存が成功したと知らせを受けたときだけ進める。書けていない並びを書けたものとして扱わないためである。
#[derive(Debug, Default)]
pub(crate) struct 保存の様子 {
    ファイルにある並び: Option<クリップスタック>,
    頼んでいる: Vec<(保存の番号, クリップスタック)>,
    最後の失敗: Option<保存の失敗>,
    頼み直し: 頼み直し,
}

/// 保存の段階とは、開いている登録済みのスタックが保存についてどの段階にあるかの区別のことである。ヘッダーに出す。
#[derive(Debug)]
pub(crate) enum 保存の段階<'様子> {
    保存済み,
    変更を保存待ち,
    保存中,
    保存に失敗(&'様子 保存の失敗),
}

impl 保存の様子 {
    /// ファイルから読んだ並びで始める。
    pub(crate) fn ファイルから開いた(並び: クリップスタック) -> Self {
        Self {
            ファイルにある並び: Some(並び),
            ..Self::default()
        }
    }

    /// 登録の保存を頼んだところから始める。書けたと分かるまでファイルにある並びは無い。
    pub(crate) fn 登録を頼んだ(
        番号: 保存の番号, 並び: クリップスタック
    ) -> Self {
        Self {
            頼んでいる: vec![(番号, 並び)],
            ..Self::default()
        }
    }

    /// 保存を頼んだ。
    pub(crate) fn 頼んだ(&mut self, 番号: 保存の番号, 並び: クリップスタック) {
        self.頼んでいる.push((番号, 並び));
        self.頼み直し = 頼み直し::無し;
    }

    /// 保存を終えた知らせを受けた。成功ならファイルにある並びを進める。
    /// 失敗して待っている保存がもう無ければ、頼み直すことにする(失敗した並びを黙って捨てないため)。
    pub(crate) fn 終えた(
        &mut self, 番号: 保存の番号, 結果: Result<(), ライブラリの操作エラー>
    ) {
        let Some(位置) = self
            .頼んでいる
            .iter()
            .position(|(頼んだ, _)| *頼んだ == 番号)
        else {
            return;
        };
        let 書いた並び = self.頼んでいる.drain(..=位置).next_back();
        match 結果 {
            Ok(()) => {
                self.最後の失敗 = None;
                self.ファイルにある並び = 書いた並び.map(|(_, 並び)| 並び);
            }
            Err(エラー) => self.失敗を覚える(保存の失敗::書けなかった(エラー)),
        }
    }

    /// 保存を頼めなかった。
    pub(crate) fn 頼めなかった(&mut self, 理由: ライブラリを使えない理由) {
        self.失敗を覚える(保存の失敗::頼めなかった(理由));
    }

    /// 失敗を覚え、待っている保存が無ければ頼み直すことにする。
    fn 失敗を覚える(&mut self, 失敗: 保存の失敗) {
        self.最後の失敗 = Some(失敗);
        if self.頼んでいる.is_empty() {
            self.頼み直し = 頼み直し::時刻を決める前;
        }
    }

    /// 今、頼み直すときか。失敗を受けて最初に見たときに、頼み直す時刻を決める。
    pub(crate) fn 頼み直すときか(&mut self, 今: Instant) -> bool {
        self.頼み直し.頼み直すときか(今)
    }

    /// 頼み直すまでの残りの時間。頼み直さないなら無い。
    pub(crate) fn 頼み直すまでの時間(&self, 今: Instant) -> Option<Duration> {
        self.頼み直し.頼み直すまでの時間(今)
    }

    /// 今の並びがファイルに書けていないか。
    pub(crate) fn 保存されていないか(&self, 今の並び: &[クリップ]) -> bool {
        self.ファイルにある並び.as_ref().map(クリップスタック::一覧) != Some(今の並び)
    }

    /// 今の並びがファイルに書けていて、待っている保存も無いことを確かめる。書けていなければ理由を返す。
    pub(crate) fn 書けたことを確かめる(
        &self,
        今の並び: &[クリップ],
    ) -> Result<(), 書けていない理由<'_>> {
        if !self.保存されていないか(今の並び) && self.頼んでいる.is_empty() {
            return Ok(());
        }
        Err(self.最後の失敗.as_ref().map_or(
            書けていない理由::保存を終えていない,
            書けていない理由::失敗した,
        ))
    }

    /// 保存の段階。失敗は、次の保存が成功するまで出し続ける。失敗の後に変えた並びも保存できていないためである。
    pub(crate) fn 段階(&self, 今の並び: &[クリップ]) -> 保存の段階<'_> {
        if !self.頼んでいる.is_empty() {
            return 保存の段階::保存中;
        }
        match (&self.最後の失敗, self.保存されていないか(今の並び)) {
            (Some(失敗), _) => 保存の段階::保存に失敗(失敗),
            (None, true) => 保存の段階::変更を保存待ち,
            (None, false) => 保存の段階::保存済み,
        }
    }
}
