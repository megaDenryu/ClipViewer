//! 保存の目的と、結果を利用者へ知らせる保存の控え。登録と取り込みは、書き込みを終えた知らせを受けてから通知するために覚えておく。

use clip_domain::スタックの名前;
use clip_library::保存の番号;

/// 保存の目的とは、保存を頼んだ理由の区別のことである。登録と取り込みは、書き込みを終えた知らせを受けてから利用者へ知らせる。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 保存の目的 {
    自動保存,
    登録(スタックの名前),
    取り込み(スタックの名前),
}

/// 知らせる保存の控えとは、結果を利用者へ知らせる保存(自動保存以外)の番号と目的を、結果が届くまで覚えておくもののことである。
#[derive(Debug, Default)]
pub(crate) struct 知らせる保存の控え(Vec<(保存の番号, 保存の目的)>);

impl 知らせる保存の控え {
    /// 自動保存でなければ、番号と目的を控える。
    pub(crate) fn 控える(&mut self, 番号: 保存の番号, 目的: 保存の目的) {
        if 目的 != 保存の目的::自動保存 {
            self.0.push((番号, 目的));
        }
    }

    /// 番号の目的を取り出す。控えていなければ自動保存である。
    pub(crate) fn 取り出す(&mut self, 番号: 保存の番号) -> 保存の目的 {
        match self.0.iter().position(|(控えた, _)| *控えた == 番号) {
            Some(位置) => self.0.remove(位置).1,
            None => 保存の目的::自動保存,
        }
    }
}
