//! ライブラリの窓。名前を付けて登録する・名前を変える・削除を確かめる・未登録の並びを捨てて続けるかを確かめる・
//! 保存できないまま続けるかを確かめる窓の状態を持つ。

use clip_domain::{
    スタックの名前, スタックの識別子, スタック設定, 入力された動画パス
};

/// 入力中の名前とは、窓の名前の入力欄に今書かれている文字列のことである。決定したときにスタックの名前として検査する。
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub(crate) struct 入力中の名前(String);

impl 入力中の名前 {
    pub(crate) fn 作成する(文字列: String) -> Self {
        Self(文字列)
    }

    /// 入力欄へ出す文字列。
    pub(crate) fn 文字列(&self) -> &str {
        &self.0
    }

    /// スタックの名前として読む。前後の空白だけなら無い。
    pub(crate) fn 名前として読む(&self) -> Option<スタックの名前> {
        スタックの名前::作成する(self.0.clone()).ok()
    }
}

/// 関係を終える操作とは、開いているスタックとの関係を終え、多くは今の並びを捨てる操作の区別のことである。
/// 確かめる窓が、利用者が続けると決めたときに行う操作として持つ。ファイルを選ぶダイアログは確かめる前に済ませ、
/// 選んだ動画と読んだ設定を持つ(ダイアログを取り消したときに確かめる窓を出さないため)。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 関係を終える操作 {
    一覧から開く(スタックの識別子),
    動画を開く(入力された動画パス, 開いたときの添え書き),
    動画を解除する,
    設定を当てる(スタック設定),
    アプリを閉じる,
}

/// 開いたときの添え書きとは、動画を開けたときだけ、開いた結果の通知へ書き足す文があるかの区別のことである。
/// 起動の引数に複数の動画があったときの「最初の1つだけを開いた」に使う。確かめる窓を経て開いたときも書き足すため、続ける操作が持つ。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 開いたときの添え書き {
    無し,
    書き足す(String),
}

/// 並びを捨てる理由とは、未登録の並びを捨てる前に確かめる窓を出す理由の区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 並びを捨てる理由 {
    登録していない変更がある,
    読み込んだ並びを名前の違う動画で捨てる,
}

/// 登録の後にすることとは、名前を付けて登録する窓で登録したら、続けて関係を終える操作を行うかの区別のことである。
/// 並びを捨てるかを確かめる窓で「ライブラリに保存する」を選んだときに、元の操作を続けるために持つ。
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum 登録の後にすること {
    何もしない,
    続ける(関係を終える操作),
}

/// ライブラリの窓とは、画面を覆って開いているライブラリの窓の区別のことである。同時に開く窓は1つである。
#[derive(Debug, Clone, Default, PartialEq)]
pub(crate) enum ライブラリの窓 {
    #[default]
    無し,
    名前を付けて登録(入力中の名前, 登録の後にすること),
    名前を変える(スタックの識別子, 入力中の名前),
    削除の確認(スタックの識別子, スタックの名前),
    並びを捨てる確認(並びを捨てる理由, 関係を終える操作),
    保存できずに続ける確認(String, 関係を終える操作),
}

impl ライブラリの窓 {
    /// 名前の入力欄のある窓なら、その入力を書き換える。
    pub(crate) fn 名前の入力を書き換える(&mut self, 文字列: String) {
        match self {
            Self::名前を付けて登録(入力, _) | Self::名前を変える(_, 入力) => {
                *入力 = 入力中の名前::作成する(文字列)
            }
            Self::無し
            | Self::削除の確認(..)
            | Self::並びを捨てる確認(..)
            | Self::保存できずに続ける確認(..) => {}
        }
    }

    /// 窓を開いているか。開いている間は、2つ目のアプリから届いた動画を開かない(開いている窓を上書きしないため)。
    pub(crate) fn 開いているか(&self) -> bool {
        !matches!(self, Self::無し)
    }

    /// 確かめる窓なら、利用者が続けると決めたときに行う操作を取り出して窓を閉じる。確かめる窓でなければ何もしない。
    pub(crate) fn 続ける操作を取り出す(&mut self) -> Option<関係を終える操作> {
        match std::mem::take(self) {
            Self::並びを捨てる確認(_, 操作) | Self::保存できずに続ける確認(_, 操作) => {
                Some(操作)
            }
            ほかの窓 => {
                *self = ほかの窓;
                None
            }
        }
    }
}
