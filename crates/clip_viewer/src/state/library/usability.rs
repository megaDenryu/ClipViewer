//! ライブラリの使える様子。接続が、ライブラリへ書けるか、錠を取れずに読むだけか、置き場所が無くて使えないかを答える。

use clip_library::{
    ライブラリのフォルダ, 書き込みの許し, 錠を取れない理由
};

use super::connection::ライブラリの接続;

/// ライブラリの使える様子とは、ライブラリへ書けるか、読むだけか、置き場所が無くて使えないかの区別のことである。画面が出し分けに使う。
pub(crate) enum ライブラリの使える様子<'接続> {
    書ける(&'接続 ライブラリのフォルダ),
    読むだけ(&'接続 ライブラリのフォルダ, &'接続 錠を取れない理由),
    置き場所が無い,
}

impl ライブラリの接続 {
    pub(crate) fn 使える様子(&self) -> ライブラリの使える様子<'_> {
        match &self.裏で動くライブラリ {
            None => ライブラリの使える様子::置き場所が無い,
            Some(裏で動くライブラリ) => match 裏で動くライブラリ.許し() {
                書き込みの許し::書ける(_) => {
                    ライブラリの使える様子::書ける(裏で動くライブラリ.フォルダ())
                }
                書き込みの許し::読むだけ(理由) => {
                    ライブラリの使える様子::読むだけ(
                        裏で動くライブラリ.フォルダ(),
                        理由,
                    )
                }
            },
        }
    }

    /// ライブラリへ書けるか。
    pub(crate) fn 書けるか(&self) -> bool {
        matches!(self.使える様子(), ライブラリの使える様子::書ける(_))
    }
}
