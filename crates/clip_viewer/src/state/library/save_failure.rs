//! 保存の失敗。開いている登録済みのスタックの保存を頼めなかったか、頼んだが書けなかったかを、理由の型のまま持つ。
//! 参照: _doc/設計/ライブラリ.md 判断5

use clip_library::ライブラリの操作エラー;

use super::connection::ライブラリを使えない理由;

/// 保存の失敗とは、開いている登録済みのスタックの保存を、頼めなかったか、頼んだが書けなかったかの区別と、その理由のことである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 保存の失敗 {
    #[error("{0}")]
    頼めなかった(ライブラリを使えない理由),
    #[error("{0}")]
    書けなかった(ライブラリの操作エラー),
}

/// 書けていない理由とは、今の並びがファイルに書けたと確かめられなかった理由の区別のことである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 書けていない理由<'様子> {
    #[error("保存を終えていない")]
    保存を終えていない,
    #[error("{0}")]
    失敗した(&'様子 保存の失敗),
}
