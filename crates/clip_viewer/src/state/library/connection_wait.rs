//! スタックのライブラリの接続と使える様子。接続そのもの(一覧から開く前に書き込みを終えてから読むことを含む)は、
//! 2つの作業場が共有する `library_common::save::保存物のライブラリの接続` である。

use clip_library::スタックのライブラリ;

use super::save_purpose::保存の目的;
use crate::library_common::save::{
    保存物のライブラリの使える様子, 保存物のライブラリの接続
};

/// ライブラリの接続とは、スタックのライブラリへのライブラリの接続のことである。
pub(crate) type ライブラリの接続 =
    保存物のライブラリの接続<スタックのライブラリ, 保存の目的>;

/// ライブラリの使える様子とは、スタックのライブラリの使える様子のことである。
pub(crate) type ライブラリの使える様子<'接続> =
    保存物のライブラリの使える様子<'接続, スタックのライブラリ>;
