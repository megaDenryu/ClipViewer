//! ライブラリの接続で、裏のスレッドが頼まれた書き込みを終えるのを待つこと。画面のスレッドを止めるため、使う場所を
//! 一覧から開く前と、関係を終える前の保存の確かめ(と試験)に限る。一覧の走査は待たない(遅いドライブで固まらないため)。

use clip_domain::{スタックの識別子, ライブラリのスタック};
use clip_library::スタックのライブラリ;

use super::connection::ライブラリの接続;

impl ライブラリの接続 {
    /// 頼んだ書き込みを終えるまで待つ。一覧の走査は待たない(遅いドライブの走査で画面のスレッドを止めないため)。
    pub(crate) fn 書き込みを終えるまで待つ(&self) {
        if let Ok(裏で動くライブラリ) = self.裏で動くライブラリ() {
            裏で動くライブラリ.書き込みを終えるまで待つ();
        }
    }

    /// 頼んだ書き込みを終えてから、識別子のスタックを読む。名前の変更の直後に開いても、変更の前の中身を読まないためである。
    pub(crate) fn 書き込みを終えてから読む(
        &self,
        識別子: &スタックの識別子,
    ) -> Result<ライブラリのスタック, String> {
        let 裏で動くライブラリ = self.裏で動くライブラリ().map_err(|理由| 理由.to_string())?;
        裏で動くライブラリ.書き込みを終えるまで待つ();
        スタックのライブラリ::作成する(裏で動くライブラリ.フォルダ().clone())
            .読む(識別子)
            .map_err(|エラー| エラー.to_string())
    }

    /// 書き込みと走査を終えるまで待つ。試験で知らせがそろうのを待つために使う。
    #[cfg(test)]
    pub(crate) fn 走査も終えるまで待つ(&self) {
        if let Ok(裏で動くライブラリ) = self.裏で動くライブラリ() {
            裏で動くライブラリ.走査も終えるまで待つ();
        }
    }
}
