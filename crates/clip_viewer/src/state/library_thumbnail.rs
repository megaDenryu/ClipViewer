//! ライブラリの一覧のサムネイルを、状態の側から動かす。一覧を読んだことを知らせ、毎フレーム結果を受け取り、
//! ライブラリの構えを開いている間だけ、見えている行と見せる順と撮る手立て(FFmpeg があるか)を渡して仕事を進めさせる。
//! 何をいつ撮るかの判断は `一覧のサムネイル` が持つ。参照: _doc/設計/ライブラリ.md 判断10

use clip_library::ライブラリの一覧;
use video_source::動画の読み手;

use super::{FFmpegの状況, アプリの状態, 画面の構え};
use crate::thumbnail_feed::撮る手立て;

impl アプリの状態 {
    /// 一覧を読んだので、各スタックの撮り方を一覧のサムネイルへ知らせる。ここでは撮りも読みもしない(起動しただけでは撮らないため)。
    pub(crate) fn 一覧のサムネイルをそろえる(
        &mut self, 一覧: &ライブラリの一覧
    ) {
        self.ライブラリ.サムネイル.一覧を読んだ(一覧);
    }

    /// 見せる行(絞り込みの後の行)に、キャッシュを見る前の行が残っているか。画面が描き直しを早めるかを決めるのに使う。
    pub(crate) fn 見せる行にキャッシュを見る前の行があるか(&self) -> bool {
        let 並び = self.ライブラリ.一覧.行の並び(None);
        self.ライブラリ
            .サムネイル
            .キャッシュを見る前の行があるか(&並び)
    }

    /// 毎フレーム呼ぶ。届いた結果を当て、ライブラリの構えを開いていれば、前のフレームで見えていた行から先に仕事を進めさせる。
    pub(crate) fn サムネイルを進める(&mut self) {
        let 見えている = self.ライブラリ.見えている行.take();
        self.ライブラリ.サムネイル.結果を受け取る();
        if self.出力.構え != 画面の構え::ライブラリ {
            return;
        }
        let 手立て = match &self.ffmpegの状況 {
            FFmpegの状況::見つかった(実行ファイル) => {
                撮る手立て::撮れる(動画の読み手::作成する(実行ファイル.clone()))
            }
            FFmpegの状況::見つからない { .. } => 撮る手立て::FFmpegが無い,
        };
        let ライブラリ = &mut self.ライブラリ;
        let 並び = ライブラリ.一覧.行の並び(見えている);
        ライブラリ.サムネイル.仕事を進める(&並び, &手立て);
    }
}
