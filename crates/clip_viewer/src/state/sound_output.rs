//! 音の出力の状況。音声出力装置を開けたか、開けなかったか途中で使えなくなったかを、画面に出すために持つ。

use audio_output::音声出力のエラー;
use audio_pcm::サンプリング周波数;

/// 音の出力の状況とは、音声出力装置を開いて鳴らしているか、使えないかの区別のことである。使えない間も映像は再生を続ける。
#[derive(Debug, Clone)]
pub(crate) enum 音の出力の状況 {
    使える(サンプリング周波数),
    使えない(音声出力のエラー),
}

impl 音の出力の状況 {
    /// 使えるなら出力装置の周波数。
    pub(crate) fn 周波数(&self) -> Option<サンプリング周波数> {
        match self {
            Self::使える(周波数) => Some(*周波数),
            Self::使えない(_) => None,
        }
    }
}
