//! キーの一覧のダイアログ。F1 かヘッダーの「キー設定」で開き、もう一度 F1 か Escape で閉じる。開いている間は、操作の行の「変更」を押すと
//! その操作の新しいキーを待つ。参照: _doc/設計/画面.md 判断14「キーの割り当て」・判断18

use crate::viewer_settings::キーで行う操作;

/// キーの一覧のダイアログとは、キーの割り当ての一覧と設定を出すダイアログを開いているかと、開いているならキーの変更を待っているかの区別のことである。
/// 待っている間は、画面のキー操作をすべて止め、押されたキーの組をその操作の新しいキーとして受け取る。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub(crate) enum キーの一覧のダイアログ {
    #[default]
    閉じている,
    開いている,
    キーを待っている(キーで行う操作),
}

impl キーの一覧のダイアログ {
    /// 閉じていれば開き、開いていれば(待っていても)閉じる。
    pub(crate) fn 切り替える(&mut self) {
        *self = match self {
            Self::閉じている => Self::開いている,
            Self::開いている | Self::キーを待っている(_) => Self::閉じている,
        };
    }

    /// 閉じていれば開く。開いていれば(待っていても)何もしない。ヘッダーの「キー設定」のボタンが使う。
    pub(crate) fn 開く(&mut self) {
        if *self == Self::閉じている {
            *self = Self::開いている;
        }
    }

    /// 開いているか(キーを待っている間も開いている)。
    pub(crate) fn 開いているか(self) -> bool {
        self != Self::閉じている
    }

    /// キーの変更を待っている操作。待っていなければ無い。
    pub(crate) fn 待っている操作(self) -> Option<キーで行う操作> {
        match self {
            Self::キーを待っている(操作) => Some(操作),
            Self::閉じている | Self::開いている => None,
        }
    }
}
