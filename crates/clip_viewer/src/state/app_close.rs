//! アプリを閉じる要求の判断。開いているスタックの保存を確かめ、書けなければ確かめるダイアログを出して閉じるのをやめる。
//! 利用者が確かめるダイアログで閉じてよいと決めたら、その決めを配線が取り出すまで覚える。関係を終えることと、確かめずに閉じることは、
//! 2つの作業場がどちらも閉じてよいと決まったときに配線の閉じる手順(`app/close_procedure.rs`)が当てる。egui を知らない。
//! 参照: _doc/設計/ライブラリ.md 判断5、_doc/設計/同時再生.md 2-7

use super::library::関係を終える操作;
use super::アプリの状態;
use crate::library_common::続ける操作を持つダイアログ;
use crate::library_common::{アプリを閉じてよいとの決め, 確かめた結果};

/// 閉じる要求への答えとは、ウインドウを閉じる要求を受けて、閉じてよいか、確かめるダイアログを出したので閉じるのをやめるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 閉じる要求への答え {
    閉じてよい,
    閉じるのをやめる,
}

impl アプリの状態 {
    /// ウインドウを閉じる要求を受けた。開いているスタックの保存を確かめ、書けなければ確かめるダイアログを出して閉じるのをやめる。
    /// 利用者が前に閉じてよいと決めたかは見ない(決めを受け取って閉じるかを決めるのは配線の閉じる手順である)。
    pub(crate) fn 閉じる要求を確かめる(&mut self) -> 閉じる要求への答え {
        match self.関係を終える前に確かめる(関係を終える操作::アプリを閉じる)
        {
            確かめた結果::続けてよい => 閉じる要求への答え::閉じてよい,
            確かめた結果::確かめるダイアログを出した => {
                閉じる要求への答え::閉じるのをやめる
            }
        }
    }

    /// 利用者が確かめるダイアログでアプリを閉じてよいと決めたか。取り出さずに読む。試験が読む。
    #[cfg(test)]
    pub(crate) fn 閉じてよいと決めたか(&self) -> bool {
        self.ライブラリ.閉じる決め.閉じてよいと決めたか()
    }

    /// 利用者がアプリを閉じてよいと決めたかを取り出す。取り出した後は、決めていない様子へ戻る。
    pub(crate) fn 閉じてよいとの決めを取り出す(
        &mut self,
    ) -> アプリを閉じてよいとの決め {
        self.ライブラリ.閉じる決め.取り出す()
    }

    /// アプリを閉じる前の確かめのダイアログ(続けるとアプリを閉じるもの。名前を付けて登録してから閉じるものを含む)を出しているか。
    pub(crate) fn アプリを閉じる前の確かめを出しているか(&self) -> bool {
        self.ライブラリ.ダイアログ.続ける操作() == Some(&関係を終える操作::アプリを閉じる)
    }
}
