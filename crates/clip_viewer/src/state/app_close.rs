//! アプリを閉じる要求の判断。開いているスタックの保存を確かめ、書けなければ確かめる窓を出して閉じるのをやめる。
//! 利用者が変更を捨てると決めたら、確かめずに閉じる。egui を知らない(窓への指示は起動の部分が送る)。
//! 参照: _doc/設計/ライブラリ.md 判断5

use super::library::{アプリの閉じ方, 関係を終える操作};
use super::relation_check::確かめた結果;
use super::アプリの状態;

/// 閉じる要求への答えとは、窓を閉じる要求を受けて、閉じてよいか、確かめる窓を出したので閉じるのをやめるかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 閉じる要求への答え {
    閉じてよい,
    閉じるのをやめる,
}

impl アプリの状態 {
    /// 窓を閉じる要求を受けた。利用者が既に変更を捨てると決めていれば閉じてよい。そうでなければ開いているスタックの保存を確かめ、
    /// 書けなければ確かめる窓を出して閉じるのをやめる。
    pub(crate) fn 閉じる要求を確かめる(&mut self) -> 閉じる要求への答え {
        if self.閉じると決めたか() {
            return 閉じる要求への答え::閉じてよい;
        }
        match self.関係を終える前に確かめる(関係を終える操作::アプリを閉じる)
        {
            確かめた結果::続けてよい => 閉じる要求への答え::閉じてよい,
            確かめた結果::確かめる窓を出した => {
                閉じる要求への答え::閉じるのをやめる
            }
        }
    }

    /// 利用者が変更を捨てて閉じると決めたか。
    pub(crate) fn 閉じると決めたか(&self) -> bool {
        self.ライブラリ.閉じ方 == アプリの閉じ方::確かめずに閉じる
    }
}
