//! スタックの作業場を控える前の手順。重ね合わせの作業場へ移るとき、配線(`app/workspace.rs`)が呼ぶ。参照: _doc/設計/同時再生.md 3-2

use super::アプリの状態;

impl アプリの状態 {
    /// スタックの作業場を控える前に、再生を止め、書けていない並びがあれば保存をすぐに頼む
    /// (Ctrl+S の登録済みのときと同じ。控えている間に変更が失われないようにするため)。
    pub(crate) fn 控える前に再生を止めて並びの保存を頼む(&mut self) {
        self.再生.止める();
        self.書けていない並びの保存を頼む();
    }
}
