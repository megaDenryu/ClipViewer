//! クロップ枠の掴み始め。範囲枠の部品は掴み始めからの累積の移動量を発するため、掴み始めのクロップを覚えておく。

use clip_domain::{クリップ識別子, クロップ範囲};

/// クロップ枠の掴み始めとは、ドラッグを始めたときに対象だったクリップと、そのときのクロップ範囲の組のことである。
/// ドラッグの間は、移動量をこのクロップ範囲へ当てて毎回計算し直す。
#[derive(Debug, Clone)]
pub(crate) struct クロップ枠の掴み始め {
    pub(crate) 対象: クリップ識別子,
    pub(crate) クロップ: クロップ範囲,
}
