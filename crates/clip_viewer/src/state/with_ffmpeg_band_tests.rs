//! 区間の帯のドラッグと「このクリップを再生」の結合試験。帯のつまみを動かしている間、テクスチャにつまみの位置のコマ
//! (開始のつまみはその位置のコマ、終了のつまみは区間の中の最後のコマ)が載ることを、試験動画のコマ番号(30コマ/秒)で確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use audio_output::再生の様子;
use clip_domain::{クリップ識別子, 再生位置};

use super::with_ffmpeg_sound_support::{
    二つのクリップの状態, 試験動画を作る, 開く
};
use super::{アプリの状態, 区間の帯で掴んだもの, 区間の帯の種類};
use crate::command::{
    クリップの区間の帯の操作, クリップの操作, 区間の帯の段階
};
use crate::video_feed::with_ffmpeg_support::成り立つまで待つ;

fn 識別子(名前: &str) -> クリップ識別子 {
    クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子")
}

fn 区間の帯を操作する(
    状態: &mut アプリの状態,
    段階: 区間の帯の段階,
    掴んだもの: 区間の帯で掴んだもの,
    秒: f64,
) {
    let 操作 = クリップの区間の帯の操作 {
        帯: 区間の帯の種類::全体の帯,
        段階,
        掴んだもの,
        秒,
    };
    状態.クリップの操作を適用する(クリップの操作::区間の帯を操作する(
        識別子("A"),
        操作,
    ));
}

fn 載せた番号(状態: &アプリの状態) -> Option<u32> {
    状態
        .動画
        .as_ref()
        .and_then(|動画| 動画.映像().載せたコマ())
        .map(|載せたコマ| 載せたコマ.番号.値())
}

/// フレームを進めながら、テクスチャに番号のコマが載るまで待つ。
fn 番号のコマが載るまで待つ(
    状態: &mut アプリの状態, 説明: &str, 番号: u32
) {
    成り立つまで待つ(説明, || {
        状態.フレームを進める(Instant::now());
        載せた番号(状態) == Some(番号)
    });
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 区間の帯のつまみを動かしている間はつまみの位置のコマが載り_音は黙る() {
    let パス = 試験動画を作る("区間の帯のドラッグ", false);
    let mut 状態 = 二つのクリップの状態(開く(&パス, None));
    状態.再生.再生を始める();
    let 開始 = 区間の帯で掴んだもの::開始のつまみ;
    区間の帯を操作する(&mut 状態, 区間の帯の段階::掴み始めた, 開始, 1.0);
    区間の帯を操作する(&mut 状態, 区間の帯の段階::動かしている, 開始, 0.5);
    番号のコマが載るまで待つ(&mut 状態, "0.5秒から表示する15番のコマが載ること", 15);
    let 指示 = 状態.音の再生の指示(Instant::now());
    assert_eq!(
        指示.様子,
        再生の様子::止めている,
        "ドラッグの間は音を黙らせる"
    );
    区間の帯を操作する(&mut 状態, 区間の帯の段階::放した, 開始, 0.5);
    assert!(状態.再生.再生しているか(), "放すと再生を戻す");
    状態.再生.止める();
    let 終了 = 区間の帯で掴んだもの::終了のつまみ;
    区間の帯を操作する(&mut 状態, 区間の帯の段階::掴み始めた, 終了, 2.0);
    区間の帯を操作する(&mut 状態, 区間の帯の段階::動かしている, 終了, 3.0);
    番号のコマが載るまで待つ(
        &mut 状態,
        "区間[0.5,3.0)の中の最後の89番のコマが載ること",
        89,
    );
    区間の帯を操作する(&mut 状態, 区間の帯の段階::放した, 終了, 3.0);
    drop(状態);
    let _ = std::fs::remove_file(パス);
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn このクリップを再生で単独クリップ再生を開始から始め_もう一度押すと止める() {
    let パス = 試験動画を作る("単独再生", false);
    let mut 状態 = 二つのクリップの状態(開く(&パス, None));
    let 単独再生 = クリップの操作::単独再生を切り替える(識別子("B"));
    状態.クリップの操作を適用する(単独再生.clone());
    assert!(状態.単独で再生しているか(&識別子("B")));
    assert!(matches!(状態.再生.位置(), 再生位置::単独クリップ再生(経過) if 経過.ゼロか()));
    番号のコマが載るまで待つ(&mut 状態, "Bの開始の90番のコマが載ること", 90);
    状態.クリップの操作を適用する(単独再生);
    assert!(!状態.再生.再生しているか());
    assert!(
        matches!(状態.再生.位置(), 再生位置::単独クリップ再生(_)),
        "止めてもモードは変えない"
    );
    drop(状態);
    let _ = std::fs::remove_file(パス);
}
