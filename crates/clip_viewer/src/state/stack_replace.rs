//! クリップの並びを丸ごと置き換える。動画を開く(並びを残さないとき)・動画を解除する・設定ファイルを読み込む・ライブラリから開くが、この1つのメソッドを通す。
//! 並びと一緒に変えなければならない項目(開いているスタックとの関係・ドラッグの状態・編集の履歴・再生位置)を、ここで必ず揃える。
//! 同じ動画を開き直して並びを残すときは、並びと履歴を引き継ぎ、ドラッグと再生位置だけを戻す(関係は動画のパス全体が同じときだけ保つ)。

use clip_domain::{クリップスタック, 再生位置, 正規化した動画パス};

use super::history::{並びの出どころ, 並びの起点, 編集の履歴};
use super::library::開いているスタック;
use super::アプリの状態;

impl アプリの状態 {
    /// 並びを置き換える。開いているスタックとの関係を終え(保存は呼ぶ前に確かめておく)、クロップ枠と区間の帯のドラッグを捨て、
    /// 編集の履歴を新しい並びから始め直し、再生位置を今の再生モードの先頭へ戻す。再生を始めるか止めるかは呼ぶ側が決める。
    /// 出どころは、新しい並びをこの場で作ったか、ファイルから読んだかである(並びを捨てる前の確かめに使う)。
    pub(crate) fn 並びを置き換える(
        &mut self,
        並び: クリップスタック,
        出どころ: 並びの出どころ,
    ) {
        self.開いているスタックとの関係を終える();
        self.履歴 = 編集の履歴::起点から始める(&並び, 出どころ);
        self.並び = 並び;
        self.ドラッグを捨てて再生位置を先頭へ戻す();
    }

    /// 同じ動画を開き直したときに、並びと編集の履歴を引き継いだまま、先頭のクリップを選び、ドラッグを捨てて再生位置を今の再生モードの先頭へ戻す。
    /// 起点を今の並びにすると、閉じるときの確かめが編集を見落とすためである。取り消しのまとめは区切る(開き直しの前後の変化をまとめないため)。
    /// 開いているスタックとの関係は、関係を保って開き直せるときだけ保つ。保てないときは関係を終え(保存は呼ぶ前に確かめておく)、
    /// 今の並びはライブラリのファイルに書けているので、起点を今の並び(ファイルから読んだ並び)に置き直す。
    pub(crate) fn 並びを残して動画を開き直す(
        &mut self, パス: &正規化した動画パス
    ) {
        if !self.関係を保って開き直せるか(パス) {
            self.開いているスタックとの関係を終える();
            self.履歴.起点 = 並びの起点::作成する(
                self.並び.clone(),
                並びの出どころ::ファイルから読んだ,
            );
        }
        self.履歴.操作の区切りを覚える();
        self.並び = std::mem::take(&mut self.並び).先頭を選ぶ();
        self.ドラッグを捨てて再生位置を先頭へ戻す();
    }

    /// 動画を開き直しても、開いているスタックとの関係を保てるか。未登録なら保つ(関係が無い)。登録済みなら、スタックの動画のパス全体が
    /// 開く動画のパスと同じときだけ保つ。ファイル名が同じでもフォルダが違えば別の動画かもしれず、合わせて直した区間で古いパスのスタックを
    /// 上書きしないためである。スタックのパスを書き換えないのは、別の動画だったときにスタックを壊すためである。
    pub(crate) fn 関係を保って開き直せるか(
        &self, パス: &正規化した動画パス
    ) -> bool {
        match &self.ライブラリ.開いている {
            開いているスタック::未登録 => true,
            開いているスタック::登録済み(登録済み) => {
                登録済み.中身().動画のパス() == パス
            }
        }
    }

    /// 開いているスタックをライブラリから削除した。関係を終え、並びはファイルにも残っていないので起点を空の並びに置き直す
    /// (並びが空でなければ、捨てる前に確かめるダイアログが出る)。
    pub(crate) fn 削除したスタックとの関係を終える(&mut self) {
        self.開いているスタックとの関係を終える();
        self.履歴.起点 = 並びの起点::作成する(
            クリップスタック::default(),
            並びの出どころ::新しく作った,
        );
    }

    fn ドラッグを捨てて再生位置を先頭へ戻す(&mut self) {
        self.掴み始め = None;
        self.区間の帯のドラッグ = None;
        self.再生
            .位置を移す(再生位置::モードの先頭(self.再生.位置().モード()));
    }
}
