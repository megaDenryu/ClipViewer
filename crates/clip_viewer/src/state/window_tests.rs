//! 窓の状態の試験。全画面でない普通の窓の大きさと最大化を覚え、全画面と最小化の間は覚え直さない。
//! 最初に画面の大きさを知らされた回に、覚えていた大きさが画面に収まらなければ最初の大きさへ戻す(最大化しているなら窓へは頼まない)。

use super::{全画面の様子, 窓の形, 窓の様子, 窓の状態};
use crate::viewer_settings::{
    最大化の様子, 画面の大きさ, 窓の大きさ, 窓の記憶
};

fn 大きさ(幅: f64, 高さ: f64) -> 窓の大きさ {
    窓の大きさ::幅と高さから作る(幅, 高さ).unwrap_or_else(|| panic!("大きさが不正"))
}

fn 画面(幅: f64, 高さ: f64) -> Option<画面の大きさ> {
    画面の大きさ::幅と高さから作る(幅, 高さ)
}

fn 様子(全画面か: 全画面の様子, 形: 窓の形) -> 窓の様子 {
    窓の様子 {
        全画面: 全画面か,
        形,
        画面: None,
    }
}

#[test]
fn 普通の窓の大きさと最大化を覚え_全画面と最小化の間は覚え直さない() {
    let mut 窓 = 窓の状態::起動時(窓の記憶::最初);
    let 広げた = 大きさ(1300.0, 700.0);
    窓.様子を知らせる(様子(
        全画面の様子::全画面でない,
        窓の形::普通(Some(広げた)),
    ));
    assert_eq!(窓.記憶().大きさ, 広げた);
    窓.様子を知らせる(様子(全画面の様子::全画面でない, 窓の形::最大化している));
    assert_eq!(窓.記憶().最大化, 最大化の様子::最大化している);
    assert_eq!(
        窓.記憶().大きさ,
        広げた,
        "最大化の間も普通の大きさを覚えておく"
    );
    窓.様子を知らせる(様子(
        全画面の様子::全画面,
        窓の形::普通(Some(大きさ(1920.0, 1080.0))),
    ));
    窓.様子を知らせる(様子(全画面の様子::全画面でない, 窓の形::最小化している));
    assert_eq!(窓.記憶().大きさ, 広げた);
    assert_eq!(窓.記憶().最大化, 最大化の様子::最大化している);
}

#[test]
fn 画面に収まらない大きさは最初に画面を知らされた回に最初の大きさへ戻して窓へ頼む() {
    let 大きすぎる = 窓の記憶 {
        大きさ: 大きさ(2400.0, 1300.0),
        最大化: 最大化の様子::最大化していない,
    };
    let mut 窓 = 窓の状態::起動時(大きすぎる);
    窓.様子を知らせる(窓の様子 {
        画面: 画面(1366.0, 768.0),
        ..様子(全画面の様子::全画面でない, 窓の形::普通(None))
    });
    assert_eq!(窓.記憶().大きさ, 窓の大きさ::最初);
    assert_eq!(窓.頼みを取り出す().大きさ, Some(窓の大きさ::最初));
    窓.様子を知らせる(窓の様子 {
        画面: 画面(800.0, 600.0),
        ..様子(全画面の様子::全画面でない, 窓の形::普通(None))
    });
    assert_eq!(
        窓.頼みを取り出す().大きさ,
        None,
        "確かめるのは最初の1回だけ"
    );
}

#[test]
fn 最大化して起動したときは収まらない大きさを覚え直すだけで窓へは頼まない() {
    let mut 窓 = 窓の状態::起動時(窓の記憶 {
        大きさ: 大きさ(2400.0, 1300.0),
        最大化: 最大化の様子::最大化している,
    });
    窓.様子を知らせる(窓の様子 {
        画面: 画面(1366.0, 768.0),
        ..様子(全画面の様子::全画面でない, 窓の形::最大化している)
    });
    assert_eq!(窓.記憶().大きさ, 窓の大きさ::最初);
    assert_eq!(窓.頼みを取り出す().大きさ, None);
}

#[test]
fn 画面に収まる大きさは変えない() {
    let 収まる = 窓の記憶 {
        大きさ: 大きさ(1300.0, 700.0),
        最大化: 最大化の様子::最大化していない,
    };
    let mut 窓 = 窓の状態::起動時(収まる);
    窓.様子を知らせる(窓の様子 {
        画面: 画面(1920.0, 1080.0),
        ..様子(全画面の様子::全画面でない, 窓の形::普通(None))
    });
    assert_eq!(窓.記憶(), 収まる);
    assert_eq!(窓.頼みを取り出す().大きさ, None);
}
