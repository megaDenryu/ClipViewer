//! 通知。操作の結果を利用者へ知らせる一時的な文を、最近のものから数個だけ持つ。
//! 画面は最近の通知を並べて出し、通知ごとに一定時間で消す。続けて出た通知(起動の途中の知らせと動画を読み込んだこと等)が、
//! 前の通知を読む前に置き換えないためである。

use std::collections::VecDeque;

use sengen_egui::{並べる通知, 通知の回};

/// 並べて出す通知の数の上限。これより古い通知は、画面に出ている途中でも並びから外す。
const 並べる数の上限: usize = 4;

/// 通知とは、最近出した通知の文と、それぞれが何番目の通知かの組の並び(古い順)と、次に出す通知の回の組のことである。
/// 画面は回ごとに表示の時間を数えるため、同じ文を続けて出しても新しい通知として表示し直される。
#[derive(Debug, Default)]
pub(crate) struct 通知 {
    最近: VecDeque<(通知の回, String)>,
    次の回: 通知の回,
}

impl 通知 {
    /// 新しい通知を出す。同じ文を続けて出しても、回を進めるので表示し直される。
    pub(crate) fn 出す(&mut self, 文面: impl Into<String>) {
        let 通知の回 = self.次の回;
        self.次の回 = 通知の回.次();
        self.最近.push_back((通知の回, 文面.into()));
        if self.最近.len() > 並べる数の上限 {
            self.最近.pop_front();
        }
    }

    /// 最後に出した通知。まだ出していなければ無い。
    pub(crate) fn 最新(&self) -> Option<(通知の回, &str)> {
        self.最近
            .back()
            .map(|(通知の回, 文面)| (*通知の回, 文面.as_str()))
    }

    /// 画面に並べる最近の通知(古い順)。
    pub(crate) fn 並べる通知(&self) -> Vec<並べる通知> {
        self.最近
            .iter()
            .map(|(通知の回, 文面)| 並べる通知::作成する(*通知の回, 文面.clone()))
            .collect()
    }

    /// 文の並びを通知へ書き足す。前の回より後に新しい通知が出ていれば、その文の後ろへ続けて新しい回の通知に置き換え、
    /// 出ていなければ新しい通知として出す。1つの操作の中で出した通知(動画を読み込んだ等)と、続けて出す知らせを1つの文にするためである。
    pub(crate) fn この回の後に書き足す(
        &mut self,
        前の回: Option<通知の回>,
        文の並び: Vec<String>,
    ) {
        if 文の並び.is_empty() {
            return;
        }
        let 足す文面 = 文の並び.join("。");
        let 文面 = match self.最新() {
            Some((通知の回, 最新の文面)) if Some(通知の回) != 前の回 => {
                let 続けた文面 = format!("{最新の文面}。{足す文面}");
                self.最近.pop_back();
                続けた文面
            }
            _ => 足す文面,
        };
        self.出す(文面);
    }
}
