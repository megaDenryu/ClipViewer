//! ライブラリからの知らせを状態へ当てる。開いているスタックの保存なら保存の様子へ、登録と取り込みは結果を受けてから通知し、
//! 変更の成功と失敗は通知へ出し、一覧を作ったら並べた一覧を置き換えて、一覧のサムネイルへ各スタックの撮り方を知らせる。
//! 開いているスタックの自動保存の失敗は、頼み直すたびに通知を繰り返さないよう、ヘッダーの保存の段階だけで知らせる。

use clip_domain::スタックの識別子;
use clip_library::{
    ライブラリからの知らせ, ライブラリの操作エラー, 保存の番号, 変更の種類
};

use super::library::{保存の目的, 最後に読んだ一覧};
use super::アプリの状態;

impl アプリの状態 {
    /// 届いた知らせをすべて状態へ当てる。
    pub(crate) fn ライブラリの知らせを受け取る(&mut self) {
        for 知らせ in self.ライブラリ.接続.届いた知らせを受け取る() {
            self.ライブラリの知らせを当てる(知らせ);
        }
    }

    fn ライブラリの知らせを当てる(
        &mut self, 知らせ: ライブラリからの知らせ
    ) {
        match 知らせ {
            ライブラリからの知らせ::保存した(識別子, 番号, 結果) => {
                self.保存の知らせを当てる(&識別子, 番号, 結果)
            }
            ライブラリからの知らせ::変えた(種類, _, Ok(_)) => {
                self.通知.出す(match 種類 {
                    変更の種類::名前を変えた => "名前を変えました",
                    変更の種類::複製した => "複製しました",
                    変更の種類::動画の場所を変えた => "動画の場所を指定し直しました",
                    変更の種類::削除した => "削除しました",
                })
            }
            ライブラリからの知らせ::変えた(_, 識別子, Err(エラー)) => {
                self.通知.出す(format!(
                    "ライブラリのスタック {識別子} を変えられない: {エラー}"
                ))
            }
            ライブラリからの知らせ::一覧を作った(Ok(一覧)) => {
                self.一覧のサムネイルをそろえる(&一覧);
                self.ライブラリ
                    .一覧
                    .一覧を置き換える(最後に読んだ一覧::読めた(一覧.into()));
            }
            ライブラリからの知らせ::一覧を作った(Err(エラー)) => self
                .ライブラリ
                .一覧
                .一覧を置き換える(最後に読んだ一覧::読めない(エラー.to_string())),
        }
    }

    fn 保存の知らせを当てる(
        &mut self,
        識別子: &スタックの識別子,
        番号: 保存の番号,
        結果: Result<(), ライブラリの操作エラー>,
    ) {
        let 失敗 = 結果.as_ref().err().map(ToString::to_string);
        let 開いているか = match self.ライブラリ.開いている.識別子が同じなら(識別子)
        {
            Some(登録済み) => {
                登録済み.保存の結果を当てる(番号, 結果);
                true
            }
            None => false,
        };
        match (self.ライブラリ.接続.保存の目的を取り出す(番号), 失敗) {
            (保存の目的::登録(名前), None) => {
                self.通知.出す(format!("ライブラリに保存しました: {名前}"))
            }
            (保存の目的::取り込み(名前), None) => self
                .通知
                .出す(format!("ライブラリへ取り込みました: {名前}")),
            (保存の目的::自動保存, None) => {}
            (保存の目的::自動保存, Some(_)) if 開いているか => {}
            (保存の目的::取り込み(名前), Some(理由)) => {
                self.通知.出す(format!("「{名前}」を取り込めない: {理由}"))
            }
            (保存の目的::登録(_) | 保存の目的::自動保存, Some(理由)) => {
                self.通知.出す(format!("ライブラリへ保存できない: {理由}"))
            }
        }
    }
}
