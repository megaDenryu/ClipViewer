//! 区間の帯のドラッグ。カードの区間の帯を掴んでから放すまでの間だけ、区間と位置の仮の値を持つ。
//! ドラッグの間はクリップスタックを書き換えず、プレビューには仮の値の位置のコマを映す。参照: _doc/設計/画面.md 判断11

use clip_domain::{
    クリップ識別子, 動画上の区間, 動画上の秒, 区間の編集の決まり, 時間の長さ
};

use super::band_vocabulary::{
    区間の帯で掴んだもの, 区間の帯に置いた値, 区間の帯のドラッグの結末, 区間の帯の種類,
};

/// 区間の帯から受け取る秒を丸める幅。カードの秒の数値入力が小数点以下2桁で出すため、丸めないと表示と値が食い違う。
const 区間の帯の秒の丸めの幅: 時間の長さ = 時間の長さ::定数の秒数から作る(0.01);

/// 区間の帯のドラッグとは、掴んだクリップ・掴んだ帯(全体の帯か拡大の帯か)・掴んだもの・掴んだときの値・仮の値・拡大の帯の範囲・区間を動かす決まり・
/// 掴む前に再生していたかの組のことである。拡大の帯の範囲と決まりは掴み始めに決め、放すまで変えない。
/// 区間の帯から受け取った秒は0.01秒の倍数へ丸め、上限を超えるなら上限以下で最大の0.01秒の倍数にする。右端まで動かした端も
/// 数値入力の小数2桁の表示と一致する。決まりの上限そのものは丸めないため、動かさなかった端は変えない。
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 区間の帯のドラッグ {
    クリップ: クリップ識別子,
    帯: 区間の帯の種類,
    掴んだもの: 区間の帯で掴んだもの,
    掴んだときの値: 区間の帯に置いた値,
    仮の値: 区間の帯に置いた値,
    拡大の範囲: 動画上の区間,
    決まり: 区間の編集の決まり,
    再生していたか: bool,
}

impl 区間の帯のドラッグ {
    /// 掴み始める。仮の値は掴んだときの値で始める。
    pub(crate) fn 掴み始める(
        クリップ: クリップ識別子,
        帯: 区間の帯の種類,
        掴んだもの: 区間の帯で掴んだもの,
        値: 区間の帯に置いた値,
        拡大の範囲: 動画上の区間,
        決まり: 区間の編集の決まり,
        再生していたか: bool,
    ) -> Self {
        Self {
            クリップ,
            帯,
            掴んだもの,
            掴んだときの値: 値,
            仮の値: 値,
            拡大の範囲,
            決まり,
            再生していたか,
        }
    }

    pub(crate) fn クリップ(&self) -> &クリップ識別子 {
        &self.クリップ
    }

    /// このドラッグが、そのクリップのその区間の帯のものか。別のカードや別の区間の帯の応答で今のドラッグを動かさないために使う。
    pub(crate) fn そのクリップのその区間の帯のものか(
        &self,
        クリップ: &クリップ識別子,
        帯: 区間の帯の種類,
    ) -> bool {
        &self.クリップ == クリップ && self.帯 == 帯
    }

    pub(crate) fn 掴んだもの(&self) -> 区間の帯で掴んだもの {
        self.掴んだもの
    }

    pub(crate) fn 仮の値(&self) -> 区間の帯に置いた値 {
        self.仮の値
    }

    pub(crate) fn 掴む前に再生していたか(&self) -> bool {
        self.再生していたか
    }

    pub(crate) fn 拡大の範囲(&self) -> 動画上の区間 {
        self.拡大の範囲
    }

    /// 掴んだつまみか区間の内側を、区間の帯の秒へ動かした仮の区間にする。秒は0.01秒の倍数へ丸めてから決まりで収める。
    pub(crate) fn 区間を動かす(&mut self, 秒: f64) {
        let 丸めた秒 = self
            .決まり
            .刻みへ丸めて上限の内側へ収める(秒, 区間の帯の秒の丸めの幅);
        let 元 = self.掴んだときの値.区間;
        self.仮の値.区間 = match self.掴んだもの {
            区間の帯で掴んだもの::開始のつまみ => {
                self.決まり.開始を動かす(元, 丸めた秒)
            }
            区間の帯で掴んだもの::終了のつまみ => {
                self.決まり.終了を動かす(元, 丸めた秒)
            }
            区間の帯で掴んだもの::区間の内側 => {
                self.決まり.長さを保って動かす(元, 丸めた秒)
            }
            区間の帯で掴んだもの::位置の印 => 元,
        };
    }

    /// 位置の印の仮の位置を置く。位置は呼び出し側が再生モードの写し方で収めた位置である。
    pub(crate) fn 位置を置く(&mut self, 位置: 動画上の秒) {
        self.仮の値.位置 = 位置;
    }

    /// 放す。掴んだときから値が変わっていなければ何も決めない。部品が掴んだだけで放したときにも値を発するが、
    /// その値で区間を書き換えないためである。
    pub(crate) fn 放す(self) -> 区間の帯のドラッグの結末 {
        let 仮の値 = self.仮の値;
        match self.掴んだもの {
            _ if 仮の値 == self.掴んだときの値 => {
                区間の帯のドラッグの結末::何も決めない
            }
            区間の帯で掴んだもの::位置の印 => {
                区間の帯のドラッグの結末::位置を決める(仮の値.位置)
            }
            _ => 区間の帯のドラッグの結末::区間を決める(仮の値.区間),
        }
    }
}
