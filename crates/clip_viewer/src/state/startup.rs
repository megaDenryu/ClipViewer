//! 起動したときのアプリの状態。クリップも動画も無く、シーケンス再生の先頭で止まっている状態を組む。

use clip_domain::クリップスタック;

use super::{
    FFmpegの状況, library, アプリの状態, キーの一覧の窓, 並びの出どころ, 再生の状況, 出力の設定,
    動画の手がかり, 窓の状態, 編集の履歴, 通知, 音の出力の状況,
};
use crate::thumbnail_feed::一覧のサムネイル;
use crate::viewer_settings::窓の記憶;

impl アプリの状態 {
    /// 起動したときの状態。クリップも動画も無く、シーケンス再生の先頭で止まっている。
    /// 一覧のサムネイルは、テクスチャを登録する egui の本体を持つため、配線が作って渡す。
    pub(crate) fn 起動時(
        ffmpegの状況: FFmpegの状況,
        音の出力: 音の出力の状況,
        サムネイル: 一覧のサムネイル,
    ) -> Self {
        Self {
            並び: クリップスタック::default(),
            再生: 再生の状況::起動時(),
            出力: 出力の設定::default(),
            手がかり: 動画の手がかり::空(),
            動画: None,
            通知: 通知::default(),
            掴み始め: None,
            区間の帯のドラッグ: None,
            履歴: 編集の履歴::起点から始める(
                &クリップスタック::default(),
                並びの出どころ::新しく作った,
            ),
            ffmpegの状況,
            音の出力,
            ライブラリ: library::ライブラリの状態::接続から作る(
                library::ライブラリの接続::錠を試したライブラリから起動する(
                    None,
                ),
                サムネイル,
            ),
            キーの一覧: キーの一覧の窓::閉じている,
            窓: 窓の状態::起動時(窓の記憶::最初),
            見る側の設定を保存するまでの時間: None,
        }
    }
}
