//! 再生の状況。再生位置・再生しているか・速度・末尾での振る舞い・音量の設定・位置を飛ばした回数を持ち、実時間の経過で時計を進める。

use std::time::Instant;

use clip_domain::{
    クリップスタック, 再生モード, 再生位置, 再生速度, 時計を進めた結果, 時計を進める条件,
    時間の長さ, 末尾での振る舞い,
};

use audio_output::位置を飛ばした回数;

use super::volume::音量の設定;

/// 進み方とは、時計を進めているか止めているかの区別のことである。進めている間は前回に進めた時刻を覚える。
#[derive(Debug, Clone, Copy, PartialEq)]
enum 進み方 {
    止まっている,
    進んでいる { 前回の時刻: Option<Instant> },
}

/// シークの様子とは、利用者が再生位置の帯をドラッグしている途中かの区別のことである。
/// カードの区間の帯のドラッグは、この様子でなく `アプリの状態` の区間の帯のドラッグで表す。
/// ドラッグの間は流し読みを開き直さない(開き直しは放して値を決めたときに行う)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum シークの様子 {
    していない,
    ドラッグしている,
}

/// 再生の状況とは、再生位置と、時計の進み方と、時計の進め方の設定(速度・末尾での振る舞い)と音量の設定と、位置を飛ばした回数の組のことである。
/// 位置を飛ばした回数は、位置を移す操作(シーク・クリップの選択・モードの切り替え)のたびに進み、音の再生器はそれを見て即座に合わせる。
#[derive(Debug, Clone)]
pub(crate) struct 再生の状況 {
    位置: 再生位置,
    進み方: 進み方,
    pub(crate) シーク: シークの様子,
    pub(crate) 速度: 再生速度,
    pub(crate) 全体の末尾: 末尾での振る舞い,
    pub(crate) 音量: 音量の設定,
    飛ばした回数: 位置を飛ばした回数,
}

impl 再生の状況 {
    /// 起動したときの状況。シーケンス再生の先頭で止まり、等倍・全体ループ有効(移植元と同じ)。
    pub(crate) fn 起動時() -> Self {
        Self {
            位置: 再生位置::モードの先頭(再生モード::シーケンス再生),
            進み方: 進み方::止まっている,
            シーク: シークの様子::していない,
            速度: 再生速度::等倍,
            全体の末尾: 末尾での振る舞い::先頭へ戻る,
            音量: 音量の設定::起動時,
            飛ばした回数: 位置を飛ばした回数::default(),
        }
    }

    pub(crate) fn 位置(&self) -> 再生位置 {
        self.位置
    }

    /// 位置を移し、位置を飛ばした回数を進める。時計が進める連続した移動は `時計を進める` が行い、回数を進めない。
    pub(crate) fn 位置を移す(&mut self, 位置: 再生位置) {
        self.位置 = 位置;
        self.飛ばした回数 = self.飛ばした回数.次();
    }

    pub(crate) fn 飛ばした回数(&self) -> 位置を飛ばした回数 {
        self.飛ばした回数
    }

    pub(crate) fn 再生しているか(&self) -> bool {
        matches!(self.進み方, 進み方::進んでいる { .. })
    }

    /// 再生を始める。最初のフレームの経過は0秒として数える。
    pub(crate) fn 再生を始める(&mut self) {
        if !self.再生しているか() {
            self.進み方 = 進み方::進んでいる {
                前回の時刻: None
            };
        }
    }

    pub(crate) fn 止める(&mut self) {
        self.進み方 = 進み方::止まっている;
    }

    pub(crate) fn 再生を切り替える(&mut self) {
        if self.再生しているか() {
            self.止める();
        } else {
            self.再生を始める();
        }
    }

    /// 再生している間だけ、前回からの実時間の経過で時計を進める。末尾で止まったら再生を止める。
    pub(crate) fn 時計を進める(
        &mut self,
        今: Instant,
        並び: &クリップスタック,
        動画の長さ: 時間の長さ,
    ) {
        let 進み方::進んでいる { 前回の時刻 } = self.進み方 else {
            return;
        };
        self.進み方 = 進み方::進んでいる {
            前回の時刻: Some(今),
        };
        // 注意: Duration は常に有限で非負のため、時間の長さへの変換は失敗しない。
        let 経過 = 前回の時刻.map_or(時間の長さ::ゼロ, |前回| {
            時間の長さ::作成する(今.duration_since(前回).as_secs_f64()).unwrap_or(時間の長さ::ゼロ)
        });
        let 条件 = 時計を進める条件 {
            スタック: 並び,
            動画の長さ,
            速度: self.速度,
            全体の末尾: self.全体の末尾,
        };
        match self.位置.再生で進める(経過, &条件) {
            時計を進めた結果::続ける(位置) => self.位置 = 位置,
            時計を進めた結果::末尾で止まる(位置) => {
                self.位置 = 位置;
                self.止める();
            }
        }
    }
}
