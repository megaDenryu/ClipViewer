//! 状態から導く値。再生モードごとの合計の長さ、映しているクリップ、先読みの並び、区間の上限、単独で再生しているかを求める。

use clip_domain::{
    クリップ, クリップ識別子, タイムライン上の位置で再生するもの, タイムライン上の位置の再生の中身,
    再生位置, 動画上の区間, 動画上の秒, 時刻, 時間の長さ,
};

use super::アプリの状態;
use crate::video_feed::先読みの並び;

/// 動画が無いときの区間の上限の最小の長さ(移植元と同じ1秒)。
const 動画が無いときの上限の最小: 時間の長さ = 時間の長さ::定数の秒数から作る(1.0);

impl アプリの状態 {
    /// 読み込んだ動画の長さ。動画が無ければ0秒。
    pub(crate) fn 動画の長さ(&self) -> 時間の長さ {
        self.動画
            .as_ref()
            .map_or(時間の長さ::ゼロ, |動画| 動画.情報().長さ())
    }

    /// 今の再生モードの合計の長さ。シーケンス再生はスタックの長さ、単独クリップ再生は選択中の区間の長さ、元動画再生は動画の長さ。
    pub(crate) fn 合計の長さ(&self) -> 時間の長さ {
        match self.再生.位置() {
            再生位置::シーケンス再生(_) => self.並び.合計の占有時間(),
            再生位置::単独クリップ再生(_) => self
                .並び
                .選択中のクリップ()
                .map_or(時間の長さ::ゼロ, |クリップ| クリップ.区間.長さ()),
            再生位置::元動画再生(_) => self.動画の長さ(),
        }
    }

    /// 映しているクリップ。シーケンス再生では再生位置に当たるクリップ(末尾以降は最後の再生できるクリップ)、それ以外では選択中のクリップ。
    pub(crate) fn 映しているクリップ(&self) -> Option<&クリップ> {
        match self.再生.位置() {
            再生位置::シーケンス再生(位置) => self
                .並び
                .表示するコマを求める(位置)
                .map(|コマ| コマ.クリップ),
            再生位置::単独クリップ再生(_) | 再生位置::元動画再生(_) => {
                self.並び.選択中のクリップ()
            }
        }
    }

    /// シーケンス再生のタイムライン上の位置の再生の中身。シーケンス再生でないか、当たるクリップが無ければ無い。
    pub(crate) fn シーケンスの再生の様子(
        &self,
    ) -> Option<タイムライン上の位置の再生の中身<'_>> {
        let 再生位置::シーケンス再生(位置) = self.再生.位置() else {
            return None;
        };
        match self.並び.タイムライン上の位置で再生するものを求める(位置) {
            タイムライン上の位置で再生するもの::クリップがある(
                再生の中身,
            ) => Some(再生の中身),
            タイムライン上の位置で再生するもの::クリップが無い => None,
        }
    }

    /// 映しているクリップを起点にした先読みの並び。
    pub(crate) fn 先読みの並び(&self) -> 先読みの並び {
        let 起点 = self.映しているクリップ().map(クリップ::識別子);
        先読みの並び::スタックから求める(&self.並び, 起点)
    }

    /// 区間の端を動かせる上限。動画があればその長さであり、1秒より短い動画でも区間は動画の終わりを越えない。
    /// 動画が無ければ区間の終了であり、1秒より短ければ1秒にする。動画が無いときは収める先の動画の終わりが無く、
    /// 0秒から始まる長さ0の区間でも区間の帯の範囲を描けるようにするためである。
    pub(crate) fn 区間の上限(&self, 区間: &動画上の区間) -> 時間の長さ {
        match &self.動画 {
            Some(_) => self.動画の長さ(),
            None => {
                let 終了まで = 区間.終了().起点から経過した長さ(時刻::先頭);
                if 終了まで < 動画が無いときの上限の最小 {
                    動画が無いときの上限の最小
                } else {
                    終了まで
                }
            }
        }
    }

    /// 今見ている動画上の位置。再生位置のコマの位置(区間の帯のドラッグのプレビューに置き換える前の位置)であり、
    /// 再生位置に当たるクリップが無ければ動画の先頭である。新しいクリップの開始と、区間の端を今の位置に合わせる操作が使う。
    pub(crate) fn 今見ている動画上の位置(&self) -> 動画上の秒 {
        self.再生位置の求め()
            .map_or(時刻::先頭, |求め| 求め.動画上の位置)
    }

    /// そのクリップを単独クリップ再生で再生しているか。カードの「このクリップを再生」を止めるボタンに変えるために使う。
    pub(crate) fn 単独で再生しているか(&self, 識別子: &クリップ識別子) -> bool {
        matches!(self.再生.位置(), 再生位置::単独クリップ再生(_))
            && self.再生.再生しているか()
            && self.並び.選択中のクリップ().map(クリップ::識別子) == Some(識別子)
    }
}
