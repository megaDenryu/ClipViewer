//! カードの区間の帯に描く値。全体の帯と拡大の帯の範囲、区間(ドラッグの間は仮の区間)、位置の印の位置を状態から求める。
//! 参照: _doc/設計/画面.md 判断11

use clip_domain::{クリップ, 動画上の区間, 動画上の秒, 時刻, 時間の長さ};

use super::band_vocabulary::区間の帯で掴んだもの;
use super::アプリの状態;

/// 拡大の帯で区間の前後に足す余白の最小の秒数。短い区間でも、前後の様子が見える幅を残す。
const 拡大の余白の最小の秒数: f64 = 2.0;

/// カードの区間の帯に描く値とは、全体の帯の範囲・拡大の帯の範囲・帯に描く区間・位置の印の位置(描かないなら無い)と、
/// 区間の終了が全体の帯の範囲(動画の終わり)より後ろにあるかの組のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct カードの区間の帯に描く値 {
    pub(crate) 全体の範囲: 動画上の区間,
    pub(crate) 拡大の範囲: 動画上の区間,
    pub(crate) 区間: 動画上の区間,
    pub(crate) 位置: Option<動画上の秒>,
    pub(crate) 区間が動画の外にあるか: bool,
}

impl カードの区間の帯に描く値 {
    /// 拡大の帯を出すか。範囲が全体の帯と同じなら、同じ帯が2本並ぶだけなので出さない。区間が動画の外にあるときは、
    /// 拡大しても区間の端を範囲の中に描けないため出さない。
    pub(crate) fn 拡大の帯を出すか(&self) -> bool {
        !self.区間が動画の外にあるか && self.拡大の範囲 != self.全体の範囲
    }

    /// 拡大の帯に描く位置の印。範囲の外の位置を渡すと部品が範囲の端に描き、そこにあるように見えるため、内側のときだけ描く。
    pub(crate) fn 拡大の帯の位置(&self) -> Option<動画上の秒> {
        let 範囲 = self.拡大の範囲;
        self.位置
            .filter(|位置| *位置 >= 範囲.開始() && *位置 <= 範囲.終了())
    }
}

/// 区間の終了が上限を超えたとみなす超過の秒数。小数の計算で終了が上限を1ulp超えても、動画の外とみなさないためである。
const 動画の外とみなす超過の秒数: f64 = 1e-6;

/// 区間の終了が上限(動画の終わり)を、許す誤差より多く超えるか。
pub(crate) fn 終了が上限を超えるか(
    区間: &動画上の区間, 上限: 時間の長さ
) -> bool {
    区間.終了().秒数() > 上限.秒数() + 動画の外とみなす超過の秒数
}

/// 拡大の帯の範囲。区間の前後に、区間の長さの半分と最小の余白の大きい方を足し、0秒から上限の間へ収める。
/// 区間の終了が上限より後ろにある(別の動画の設定ファイルを読み込んだ等)ときは、全体の帯と同じ範囲にする。
pub(crate) fn 拡大の帯の範囲を求める(
    区間: &動画上の区間,
    上限: 時間の長さ,
) -> 動画上の区間 {
    let 余白 = (区間.長さ().秒数() / 2.0).max(拡大の余白の最小の秒数);
    let 余白 = 時間の長さ::作成する(余白).unwrap_or(時間の長さ::ゼロ);
    let 終わり = 時刻::先頭.進める(上限);
    let 後ろ = 区間.終了().進める(余白);
    let 後ろ = if 後ろ < 終わり {
        後ろ
    } else {
        終わり
    };
    let 全体 = 動画上の区間::開始と長さから作る(時刻::先頭, 上限);
    if 終了が上限を超えるか(区間, 上限) {
        return 全体;
    }
    動画上の区間::作成する(区間.開始().戻す(余白), 後ろ).unwrap_or(全体)
}

impl アプリの状態 {
    /// 区間に対する拡大の帯の範囲。上限は区間の端を動かせる上限である。
    pub(crate) fn 拡大の帯の範囲(&self, 区間: &動画上の区間) -> 動画上の区間 {
        拡大の帯の範囲を求める(区間, self.区間の上限(区間))
    }

    /// カードの区間の帯に描く値。このクリップを帯でドラッグしている間は、仮の区間と、掴んだときに決めた拡大の範囲を描く。
    /// 位置の印は選ばれているカードにだけ描き、位置の印をドラッグしている間は仮の位置、それ以外は再生の今の動画上の位置である。
    pub(crate) fn カードの区間の帯に描く値(
        &self,
        クリップ: &クリップ,
        選ばれているか: bool,
    ) -> カードの区間の帯に描く値 {
        let 上限 = self.区間の上限(&クリップ.区間);
        let 全体の範囲 = 動画上の区間::開始と長さから作る(時刻::先頭, 上限);
        let ドラッグ = self
            .区間の帯のドラッグ
            .as_ref()
            .filter(|ドラッグ| ドラッグ.クリップ() == クリップ.識別子());
        let 位置 = match ドラッグ {
            Some(ドラッグ)
                if ドラッグ.掴んだもの() == 区間の帯で掴んだもの::位置の印 =>
            {
                Some(ドラッグ.仮の値().位置)
            }
            _ => self.再生位置の求め().map(|求め| 求め.動画上の位置),
        };
        カードの区間の帯に描く値 {
            全体の範囲,
            拡大の範囲: ドラッグ.map_or_else(
                || 拡大の帯の範囲を求める(&クリップ.区間, 上限),
                |ドラッグ| ドラッグ.拡大の範囲(),
            ),
            区間: ドラッグ.map_or(クリップ.区間, |ドラッグ| ドラッグ.仮の値().区間),
            位置: 位置.filter(|_| 選ばれているか),
            区間が動画の外にあるか: 終了が上限を超えるか(&クリップ.区間, 上限),
        }
    }
}
