//! OS のウインドウの状態。起動の部分が毎フレーム知らせるウインドウの様子(全画面か・最大化か・大きさ・画面の大きさ)から、次に起動したときへ持ち越すウインドウの記憶を作り、
//! 状態の操作(F11・Escape)と起動の後の大きさの確かめが決めたウインドウへの頼みを持つ。頼みは配線が1フレームの終わりに取り出し、
//! ウインドウへの指示の並びに入れる。egui を知らない。参照: _doc/設計/画面.md 判断16・判断17

use super::window_vocabulary::{
    ウインドウの形, ウインドウの様子, ウインドウへの頼み, 全画面の様子,
};
use crate::viewer_settings::{
    ウインドウの大きさ, ウインドウの記憶, 最大化の様子, 画面の大きさ
};

/// 大きさの確かめとは、起動したウインドウの大きさが画面に収まるかを、egui が画面の大きさを知らせた最初の回にだけ確かめるための区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 大きさの確かめ {
    確かめ待ち,
    確かめた,
}

/// ウインドウの状態とは、知らせられた全画面の様子と、持ち越すウインドウの記憶と、起動の後の大きさの確かめと、まだ送っていないウインドウへの頼みの組のことである。
/// 全画面の頼みは最後に頼んだものだけを持つ。同じフレームで F11 を2回押したときに、2回目は1回目の頼みの結果から切り替えるためである。
#[derive(Debug, Clone)]
pub(crate) struct ウインドウの状態 {
    知らされた全画面: 全画面の様子,
    記憶: ウインドウの記憶,
    確かめ: 大きさの確かめ,
    頼み: ウインドウへの頼み,
}

impl ウインドウの状態 {
    /// 起動したときの状態。記憶は、ウインドウを作るときに渡した大きさと最大化である。
    pub(crate) fn 起動時(記憶: ウインドウの記憶) -> Self {
        Self {
            知らされた全画面: 全画面の様子::全画面でない,
            記憶,
            確かめ: 大きさの確かめ::確かめ待ち,
            頼み: ウインドウへの頼み::default(),
        }
    }

    /// 起動の部分が egui から読んだウインドウの様子を知らせる。毎フレーム、状態を進める前に呼ぶ。
    /// 全画面でない間だけウインドウの記憶を更新する(全画面の大きさを、次に起動したときのウインドウの大きさにしないため)。最小化している間は更新しない。
    pub(crate) fn 様子を知らせる(&mut self, 様子: ウインドウの様子) {
        self.知らされた全画面 = 様子.全画面;
        if let Some(画面) = 様子.画面 {
            self.起動した大きさを確かめる(画面);
        }
        if 様子.全画面 == 全画面の様子::全画面 {
            return;
        }
        match 様子.形 {
            ウインドウの形::最小化している => {}
            ウインドウの形::最大化している => {
                self.記憶.最大化 = 最大化の様子::最大化している
            }
            ウインドウの形::普通(大きさ) => {
                self.記憶.最大化 = 最大化の様子::最大化していない;
                if let Some(大きさ) = 大きさ {
                    self.記憶.大きさ = 大きさ;
                }
            }
        }
    }

    /// 最初に画面の大きさを知らされた回にだけ、覚えていた大きさが画面に収まるかを確かめる。収まらなければ最初の大きさへ戻す
    /// (大きな画面で広げたウインドウを、小さな画面で開いた等)。最大化しているときは、最大化を解かないようウインドウへは頼まず、覚える大きさだけを戻す。
    fn 起動した大きさを確かめる(&mut self, 画面: 画面の大きさ) {
        if self.確かめ == 大きさの確かめ::確かめた {
            return;
        }
        self.確かめ = 大きさの確かめ::確かめた;
        if self.記憶.大きさ.画面に収まるか(画面) {
            return;
        }
        self.記憶.大きさ = ウインドウの大きさ::最初;
        if self.記憶.最大化 == 最大化の様子::最大化していない {
            self.頼み.大きさ = Some(ウインドウの大きさ::最初);
        }
    }

    /// 次に起動したときへ持ち越すウインドウの記憶。
    pub(crate) fn 記憶(&self) -> ウインドウの記憶 {
        self.記憶
    }

    /// 今の全画面の様子。まだ送っていない頼みがあれば、頼んだ様子を今とみなす。
    pub(crate) fn 全画面の様子(&self) -> 全画面の様子 {
        self.頼み.全画面.unwrap_or(self.知らされた全画面)
    }

    /// 全画面なら抜け、そうでなければ全画面にするよう頼む。
    pub(crate) fn 全画面を切り替える(&mut self) {
        self.頼み.全画面 = Some(self.全画面の様子().逆());
    }

    /// 全画面なら抜けるよう頼み、頼んだかを返す。全画面でなければ何もしない。
    pub(crate) fn 全画面なら抜ける(&mut self) -> bool {
        if self.全画面の様子() == 全画面の様子::全画面でない {
            return false;
        }
        self.頼み.全画面 = Some(全画面の様子::全画面でない);
        true
    }

    /// まだウインドウへ送っていない頼みを取り出す。取り出すと頼みは空になる。
    pub(crate) fn 頼みを取り出す(&mut self) -> ウインドウへの頼み {
        std::mem::take(&mut self.頼み)
    }
}
