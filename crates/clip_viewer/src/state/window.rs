//! OS の窓の状態。起動の部分が毎フレーム知らせる窓の様子(全画面か・最大化か・大きさ・画面の大きさ)から、次に起動したときへ持ち越す窓の記憶を作り、
//! 状態の操作(F11・Escape)と起動の後の大きさの確かめが決めた窓への頼みを持つ。頼みは配線が1フレームの終わりに取り出し、
//! 窓への指示の並びに入れる。egui を知らない。参照: _doc/設計/画面.md 判断16・判断17

use super::window_vocabulary::{全画面の様子, 窓の形, 窓の様子, 窓への頼み};
use crate::viewer_settings::{
    最大化の様子, 画面の大きさ, 窓の大きさ, 窓の記憶
};

/// 大きさの確かめとは、起動した窓の大きさが画面に収まるかを、egui が画面の大きさを知らせた最初の回にだけ確かめるための区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum 大きさの確かめ {
    確かめ待ち,
    確かめた,
}

/// 窓の状態とは、知らせられた全画面の様子と、持ち越す窓の記憶と、起動の後の大きさの確かめと、まだ送っていない窓への頼みの組のことである。
/// 全画面の頼みは最後に頼んだものだけを持つ。同じフレームで F11 を2回押したときに、2回目は1回目の頼みの結果から切り替えるためである。
#[derive(Debug, Clone)]
pub(crate) struct 窓の状態 {
    知らされた全画面: 全画面の様子,
    記憶: 窓の記憶,
    確かめ: 大きさの確かめ,
    頼み: 窓への頼み,
}

impl 窓の状態 {
    /// 起動したときの状態。記憶は、窓を作るときに渡した大きさと最大化である。
    pub(crate) fn 起動時(記憶: 窓の記憶) -> Self {
        Self {
            知らされた全画面: 全画面の様子::全画面でない,
            記憶,
            確かめ: 大きさの確かめ::確かめ待ち,
            頼み: 窓への頼み::default(),
        }
    }

    /// 起動の部分が egui から読んだ窓の様子を知らせる。毎フレーム、状態を進める前に呼ぶ。
    /// 全画面でない間だけ窓の記憶を更新する(全画面の大きさを、次に起動したときの窓の大きさにしないため)。最小化している間は更新しない。
    pub(crate) fn 様子を知らせる(&mut self, 様子: 窓の様子) {
        self.知らされた全画面 = 様子.全画面;
        if let Some(画面) = 様子.画面 {
            self.起動した大きさを確かめる(画面);
        }
        if 様子.全画面 == 全画面の様子::全画面 {
            return;
        }
        match 様子.形 {
            窓の形::最小化している => {}
            窓の形::最大化している => {
                self.記憶.最大化 = 最大化の様子::最大化している
            }
            窓の形::普通(大きさ) => {
                self.記憶.最大化 = 最大化の様子::最大化していない;
                if let Some(大きさ) = 大きさ {
                    self.記憶.大きさ = 大きさ;
                }
            }
        }
    }

    /// 最初に画面の大きさを知らされた回にだけ、覚えていた大きさが画面に収まるかを確かめる。収まらなければ最初の大きさへ戻す
    /// (大きな画面で広げた窓を、小さな画面で開いた等)。最大化しているときは、最大化を解かないよう窓へは頼まず、覚える大きさだけを戻す。
    fn 起動した大きさを確かめる(&mut self, 画面: 画面の大きさ) {
        if self.確かめ == 大きさの確かめ::確かめた {
            return;
        }
        self.確かめ = 大きさの確かめ::確かめた;
        if self.記憶.大きさ.画面に収まるか(画面) {
            return;
        }
        self.記憶.大きさ = 窓の大きさ::最初;
        if self.記憶.最大化 == 最大化の様子::最大化していない {
            self.頼み.大きさ = Some(窓の大きさ::最初);
        }
    }

    /// 次に起動したときへ持ち越す窓の記憶。
    pub(crate) fn 記憶(&self) -> 窓の記憶 {
        self.記憶
    }

    /// 今の全画面の様子。まだ送っていない頼みがあれば、頼んだ様子を今とみなす。
    pub(crate) fn 全画面の様子(&self) -> 全画面の様子 {
        self.頼み.全画面.unwrap_or(self.知らされた全画面)
    }

    /// 全画面なら抜け、そうでなければ全画面にするよう頼む。
    pub(crate) fn 全画面を切り替える(&mut self) {
        self.頼み.全画面 = Some(self.全画面の様子().逆());
    }

    /// 全画面なら抜けるよう頼み、頼んだかを返す。全画面でなければ何もしない。
    pub(crate) fn 全画面なら抜ける(&mut self) -> bool {
        if self.全画面の様子() == 全画面の様子::全画面でない {
            return false;
        }
        self.頼み.全画面 = Some(全画面の様子::全画面でない);
        true
    }

    /// まだ窓へ送っていない頼みを取り出す。取り出すと頼みは空になる。
    pub(crate) fn 頼みを取り出す(&mut self) -> 窓への頼み {
        std::mem::take(&mut self.頼み)
    }
}
