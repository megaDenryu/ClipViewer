//! 拡大の帯の範囲の試験。区間の前後に余白を足し、0秒から上限の間へ収めることと、全体と同じ範囲になるときを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{動画上の区間, 時刻, 時間の長さ};

use super::band_values::{拡大の帯の範囲を求める, 終了が上限を超えるか};

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}

fn 長さ(秒: f64) -> 時間の長さ {
    時間の長さ::作成する(秒).expect("長さ")
}

#[test]
fn 短い区間は前後に2秒の余白を足す() {
    let 三十分 = 長さ(1800.0);
    assert_eq!(
        拡大の帯の範囲を求める(&区間(600.0, 601.0), 三十分),
        区間(598.0, 603.0)
    );
}

#[test]
fn 長い区間は前後に区間の長さの半分を足し_動画の範囲へ収める() {
    assert_eq!(
        拡大の帯の範囲を求める(&区間(10.0, 20.0), 長さ(1800.0)),
        区間(5.0, 25.0)
    );
    assert_eq!(
        拡大の帯の範囲を求める(&区間(0.5, 1.0), 長さ(2.0)),
        区間(0.0, 2.0)
    );
}

#[test]
fn 区間の終了が上限より後ろなら全体と同じ範囲にする() {
    assert_eq!(
        拡大の帯の範囲を求める(&区間(25.0, 31.0), 長さ(30.0)),
        区間(0.0, 30.0)
    );
    assert_eq!(
        拡大の帯の範囲を求める(&区間(50.0, 60.0), 長さ(30.0)),
        区間(0.0, 30.0)
    );
}

#[test]
fn 終了が上限を1ulp超えても動画の外とみなさず_拡大の帯を出す() {
    let 上限 = 長さ(100.0);
    let 少し超えた終了 = 区間(90.0, 100.00000000000001);
    assert!(!終了が上限を超えるか(&少し超えた終了, 上限));
    assert_eq!(
        拡大の帯の範囲を求める(&少し超えた終了, 上限),
        区間(85.0, 100.0)
    );
    assert!(終了が上限を超えるか(&区間(90.0, 100.1), 上限));
}
