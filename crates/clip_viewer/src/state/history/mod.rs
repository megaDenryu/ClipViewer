//! 編集の履歴。クリップの並びが変わるたびに変わる前の並びを積み、取り消しとやり直しで並びを戻す。
//! 並びを見て積むのは毎フレームの1箇所(`stack_history.rs`)であり、操作ごとに積む呼び出しを足さない(自動保存と同じ理由)。
//! 参照: _doc/設計/画面.md 判断14

use std::collections::VecDeque;

use clip_domain::クリップスタック;

mod merge;
mod origin;

#[cfg(test)]
mod merge_tests;
#[cfg(test)]
mod tests;

pub(crate) use merge::続けて変える値;
pub(crate) use origin::{並びの出どころ, 並びの起点};

use merge::続けて変えた変化のまとめ;

/// 取り消せる並びの数の上限。10クリップの並びは約2KBなので、上限まで積んでも約200KBである。
const 取り消せる数の上限: usize = 100;

/// 編集の履歴とは、並びを置き換えたときの並び(起点)と、最後に見た並びと、取り消せる並びとやり直せる並びの組のことである。
/// 不変条件: 最後に見た並びは、履歴を最後に進めたときの今の並びである。取り消しとやり直しはこれを戻した並びへ進める。
/// 起点はほかの項目と関係を持たないため、関係を終えて並びの保存先が変わったときに、型の外から取り消しの履歴を残したまま置き直してよい。
#[derive(Debug, Clone)]
pub(crate) struct 編集の履歴 {
    pub(crate) 起点: 並びの起点,
    最後に見た: クリップスタック,
    取り消せる: VecDeque<クリップスタック>,
    やり直せる: Vec<クリップスタック>,
    まとめ: 続けて変えた変化のまとめ,
}

impl 編集の履歴 {
    /// 並びを置き換えたときの並びと出どころを起点にして、空の履歴を始める。
    pub(crate) fn 起点から始める(
        並び: &クリップスタック, 出どころ: 並びの出どころ
    ) -> Self {
        Self {
            起点: 並びの起点::作成する(並び.clone(), 出どころ),
            最後に見た: 並び.clone(),
            取り消せる: VecDeque::new(),
            やり直せる: Vec::new(),
            まとめ: 続けて変えた変化のまとめ::default(),
        }
    }

    /// 次に見る変化が、続けて変える値の変化であることを覚える。値を変える操作を当てるときに呼ぶ。
    pub(crate) fn 次の変化の値を覚える(&mut self, 値: 続けて変える値) {
        self.まとめ.次の変化の値を覚える(値);
    }

    /// 操作の区切り(数値入力のドラッグを放した・直接入力を確定した)が来たことを覚える。
    pub(crate) fn 操作の区切りを覚える(&mut self) {
        self.まとめ.操作の区切りを覚える();
    }

    /// 今の並びを見る。最後に見た並びとクリップが違えば、変わる前の並びを積む(選択だけの変化は積まない)。
    /// 同じ値を操作の区切りまで続けて変えている間は、前の変化とまとめる。
    pub(crate) fn 並びを見る(&mut self, 今の並び: &クリップスタック) {
        let 値 = self.まとめ.次の変化の値を取り出す();
        if 今の並び.一覧() != self.最後に見た.一覧() {
            let 前 = std::mem::replace(&mut self.最後に見た, 今の並び.clone());
            if !self.まとめ.まとめるか(値) {
                self.積む(前);
            }
        }
        self.まとめ.区切りを当てる();
    }

    /// 最後の変化を取り消した並び。まだ見ていない変化があれば、先にそれを積んでから取り消す。取り消せなければ無い。
    pub(crate) fn 取り消す(
        &mut self,
        今の並び: &クリップスタック,
    ) -> Option<クリップスタック> {
        self.見ていない変化を積む(今の並び);
        let 戻す並び = self.取り消せる.pop_back()?;
        let 今 = std::mem::replace(&mut self.最後に見た, 戻す並び.clone());
        self.やり直せる.push(今);
        self.まとめ.直前を忘れる();
        Some(戻す並び)
    }

    /// 取り消した変化をやり直した並び。取り消した後に並びを変えていれば、やり直せない(変えたことを積む)。
    pub(crate) fn やり直す(
        &mut self,
        今の並び: &クリップスタック,
    ) -> Option<クリップスタック> {
        if self.見ていない変化を積む(今の並び) {
            return None;
        }
        let 進める並び = self.やり直せる.pop()?;
        let 今 = std::mem::replace(&mut self.最後に見た, 進める並び.clone());
        self.取り消せる.push_back(今);
        self.まとめ.直前を忘れる();
        Some(進める並び)
    }

    /// 取り消せる変化があるか。
    pub(crate) fn 取り消せるか(&self, 今の並び: &クリップスタック) -> bool {
        !self.取り消せる.is_empty() || 今の並び.一覧() != self.最後に見た.一覧()
    }

    /// やり直せる変化があるか。
    pub(crate) fn やり直せるか(&self, 今の並び: &クリップスタック) -> bool {
        !self.やり直せる.is_empty() && 今の並び.一覧() == self.最後に見た.一覧()
    }

    /// 最後に見た並びから変わっていれば、変わる前の並びを積んで今の並びを最後に見た並びにする。積んだかを返す。
    fn 見ていない変化を積む(&mut self, 今の並び: &クリップスタック) -> bool {
        if 今の並び.一覧() == self.最後に見た.一覧() {
            return false;
        }
        let 前 = std::mem::replace(&mut self.最後に見た, 今の並び.clone());
        self.積む(前);
        true
    }

    /// 変わる前の並びを積み、やり直せる並びを捨てる。上限を超えたら古いものから捨てる。
    fn 積む(&mut self, 前: クリップスタック) {
        self.取り消せる.push_back(前);
        if self.取り消せる.len() > 取り消せる数の上限 {
            self.取り消せる.pop_front();
        }
        self.やり直せる.clear();
    }
}
