//! スタックの作業場の編集の履歴。クリップの並びが変わるたびに変わる前の並びを積み、取り消しとやり直しで並びを戻す。
//! 積んで戻す仕組みは2つの作業場が共有する取り消しの履歴(`edit_history/`)であり、ここはクリップスタックを積む値にすることと、並びの起点を持つことだけを足す。
//! 並びを見て積むのは毎フレームの1箇所(`stack_history.rs`)であり、操作ごとに積む呼び出しを足さない(自動保存と同じ理由)。
//! 参照: _doc/設計/画面.md 判断14

use clip_domain::クリップスタック;

use crate::edit_history::{取り消しの履歴, 履歴に積む値};

mod merge;
mod origin;

#[cfg(test)]
mod merge_tests;
#[cfg(test)]
mod tests;

pub(crate) use merge::続けて変える値;
pub(crate) use origin::{並びの出どころ, 並びの起点};

/// クリップスタックは、選択だけの違いを編集に数えない(クリップの一覧で比べる)。
impl 履歴に積む値 for クリップスタック {
    fn 編集として同じか(&self, 他: &Self) -> bool {
        self.一覧() == 他.一覧()
    }
}

/// 編集の履歴とは、並びを置き換えたときの並び(起点)と、クリップスタックを積む取り消しの履歴の組のことである。
/// 起点は取り消しの履歴と関係を持たないため、関係を終えて並びの保存先が変わったときに、型の外から取り消しの履歴を残したまま置き直してよい。
#[derive(Debug, Clone)]
pub(crate) struct 編集の履歴 {
    pub(crate) 起点: 並びの起点,
    履歴: 取り消しの履歴<クリップスタック, 続けて変える値>,
}

impl 編集の履歴 {
    /// 並びを置き換えたときの並びと出どころを起点にして、空の履歴を始める。
    pub(crate) fn 起点から始める(
        並び: &クリップスタック, 出どころ: 並びの出どころ
    ) -> Self {
        Self {
            起点: 並びの起点::作成する(並び.clone(), 出どころ),
            履歴: 取り消しの履歴::今の値から始める(並び),
        }
    }

    /// 次に見る変化が、続けて変える値の変化であることを覚える。値を変える操作を当てるときに呼ぶ。
    pub(crate) fn 次の変化の値を覚える(&mut self, 値: 続けて変える値) {
        self.履歴.次の変化の値を覚える(値);
    }

    /// 操作の区切り(数値入力のドラッグを放した・直接入力を確定した)が来たことを覚える。
    pub(crate) fn 操作の区切りを覚える(&mut self) {
        self.履歴.操作の区切りを覚える();
    }

    /// 今の並びを見る。最後に見た並びとクリップが違えば、変わる前の並びを積む(選択だけの変化は積まない)。
    /// 同じ値を操作の区切りまで続けて変えている間は、前の変化とまとめる。
    pub(crate) fn 並びを見る(&mut self, 今の並び: &クリップスタック) {
        self.履歴.値を見る(今の並び);
    }

    /// 最後の変化を取り消した並び。まだ見ていない変化があれば、先にそれを積んでから取り消す。取り消せなければ無い。
    pub(crate) fn 取り消す(
        &mut self,
        今の並び: &クリップスタック,
    ) -> Option<クリップスタック> {
        self.履歴.取り消す(今の並び)
    }

    /// 取り消した変化をやり直した並び。取り消した後に並びを変えていれば、やり直せない(変えたことを積む)。
    pub(crate) fn やり直す(
        &mut self,
        今の並び: &クリップスタック,
    ) -> Option<クリップスタック> {
        self.履歴.やり直す(今の並び)
    }

    /// 取り消せる変化があるか。
    pub(crate) fn 取り消せるか(&self, 今の並び: &クリップスタック) -> bool {
        self.履歴.取り消せるか(今の並び)
    }

    /// やり直せる変化があるか。
    pub(crate) fn やり直せるか(&self, 今の並び: &クリップスタック) -> bool {
        self.履歴.やり直せるか(今の並び)
    }
}
