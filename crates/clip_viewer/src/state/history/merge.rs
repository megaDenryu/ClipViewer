//! スタックの作業場の続けて変える値。数値入力のドラッグや打鍵のように、1つの操作の間に同じ値が何度も変わるとき、
//! どの値の変化かを取り消しの履歴(`edit_history/`)へ知らせる区別である。まとめる規則は取り消しの履歴が持つ。
//! 操作の区切りは、数値入力が操作を終えたときに発する応答で知る(ドラッグを放した・直接入力を確定した)。参照: _doc/設計/画面.md 判断14

use clip_domain::クリップ識別子;

/// 続けて変える値とは、数値入力のドラッグや打鍵のように、1つの操作の間に何度も変わる並びの中の値の区別のことである。
/// 同じ値の変化が操作の区切りまで続く間は、履歴には1つの変化として積む。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 続けて変える値 {
    区間の開始(クリップ識別子),
    区間の終了(クリップ識別子),
}
