//! 続けて変えた変化のまとめ。数値入力のドラッグや打鍵のように、1つの操作の間に同じ値が何度も変わるとき、履歴に1つの変化として積むかを決める。
//! 操作の区切りは、数値入力が操作を終えたときに発する応答で知る(ドラッグを放した・直接入力を確定した)。クロップ枠のドラッグを
//! 放した時点で1つの変化にするのと同じ方針である。参照: _doc/設計/画面.md 判断14

use clip_domain::クリップ識別子;

/// 続けて変える値とは、数値入力のドラッグや打鍵のように、1つの操作の間に何度も変わる並びの中の値の区別のことである。
/// 同じ値の変化が操作の区切りまで続く間は、履歴には1つの変化として積む。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 続けて変える値 {
    区間の開始(クリップ識別子),
    区間の終了(クリップ識別子),
}

/// 直前の変化とは、最後に見た変化が、区切りの来ていない続けて変える値の変化かの区別のことである。
#[derive(Debug, Clone, Default)]
enum 直前の変化 {
    #[default]
    まとめない,
    続けて変えている(続けて変える値),
}

/// 続けて変えた変化のまとめとは、直前の変化と、次に見る変化がどの値の変化かと、操作の区切りが来たかの組のことである。
/// 区切りは次に並びを見た後で当てる。区切りと同じフレームに届いた最後の変化を、その前の変化とまとめるためである。
#[derive(Debug, Clone, Default)]
pub(super) struct 続けて変えた変化のまとめ {
    直前: 直前の変化,
    次の変化の値: Option<続けて変える値>,
    区切りが来たか: bool,
}

impl 続けて変えた変化のまとめ {
    /// 次に見る変化が、続けて変える値の変化であることを覚える。
    pub(super) fn 次の変化の値を覚える(&mut self, 値: 続けて変える値) {
        self.次の変化の値 = Some(値);
    }

    /// 操作の区切りが来たことを覚える。次に並びを見た後から、同じ値の変化も別の変化として積む。
    pub(super) fn 操作の区切りを覚える(&mut self) {
        self.区切りが来たか = true;
    }

    /// 次の変化の値を取り出す。並びを見るたびに取り出し、変化が無くても忘れる。
    pub(super) fn 次の変化の値を取り出す(&mut self) -> Option<続けて変える値> {
        self.次の変化の値.take()
    }

    /// 今見た変化を直前の変化とまとめるか。同じ値の変化が区切りの前から続いていればまとめる。今見た変化を直前の変化として覚える。
    pub(super) fn まとめるか(&mut self, 値: Option<続けて変える値>) -> bool {
        let まとめる = matches!(
            (&self.直前, &値),
            (直前の変化::続けて変えている(前の値), Some(値)) if 前の値 == 値
        );
        self.直前 = 値.map_or(直前の変化::まとめない, 直前の変化::続けて変えている);
        まとめる
    }

    /// 来ていた区切りを当てる。並びを見るたびに最後に呼ぶ。
    pub(super) fn 区切りを当てる(&mut self) {
        if std::mem::take(&mut self.区切りが来たか) {
            self.直前 = 直前の変化::まとめない;
        }
    }

    /// 直前の変化を忘れる。取り消しとやり直しの後は、次の変化を前の変化とまとめないためである。
    pub(super) fn 直前を忘れる(&mut self) {
        self.直前 = 直前の変化::まとめない;
    }
}
