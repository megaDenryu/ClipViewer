//! 並びの起点。並びを置き換えたときの並びと、それをこの場で作ったかファイルから読んだかを持ち、並びを捨てる前の確かめに答える。
//! 参照: _doc/設計/画面.md 判断14

use clip_domain::クリップスタック;

/// 並びの出どころとは、並びを置き換えたときの並びが、この場で新しく作ったものか、ファイル(設定ファイルかライブラリ)から読んだものかの区別のことである。
/// ファイルから読んだ並びは、変えていなくても、名前の違う動画を開いて捨てる前に確かめる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 並びの出どころ {
    新しく作った,
    ファイルから読んだ,
}

/// 並びの起点とは、並びを置き換えたときの並びと、その出どころの組のことである。
#[derive(Debug, Clone)]
pub(crate) struct 並びの起点 {
    並び: クリップスタック,
    出どころ: 並びの出どころ,
}

impl 並びの起点 {
    pub(crate) fn 作成する(
        並び: クリップスタック, 出どころ: 並びの出どころ
    ) -> Self {
        Self {
            並び, 出どころ
        }
    }

    /// 今の並びが、起点からクリップを変えているか(選択だけの違いは変えたことに数えない)。
    pub(crate) fn 変わったか(&self, 今の並び: &クリップスタック) -> bool {
        今の並び.一覧() != self.並び.一覧()
    }

    /// 起点の並びをファイルから読んだか。
    pub(crate) fn ファイルから読んだか(&self) -> bool {
        self.出どころ == 並びの出どころ::ファイルから読んだ
    }
}
