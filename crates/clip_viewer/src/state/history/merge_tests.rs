//! 続けて変えた変化のまとめの試験。同じ値を続けて変えた変化は操作の区切りまで履歴に1つとして積み、
//! 区切りと同じフレームに届いた最後の変化もまとめ、区切りの後の変化は別の変化にする。
#![allow(clippy::expect_used)]

use super::tests::{名前, 名前の並び, 新しく作った履歴, 識別子};
use super::続けて変える値;

#[test]
fn 同じ値を続けて変えた変化は区切りまで1つにまとめ_区切りの後は別の変化にする() {
    let mut 履歴 = 新しく作った履歴(&["甲"]);
    let 値 = || 続けて変える値::区間の開始(識別子("甲"));
    for 名前 in ["乙", "丙", "丁"] {
        履歴.次の変化の値を覚える(値());
        if 名前 == "丁" {
            履歴.操作の区切りを覚える();
        }
        履歴.並びを見る(&名前の並び(&["甲", 名前]));
    }
    履歴.次の変化の値を覚える(値());
    履歴.並びを見る(&名前の並び(&["甲", "戊"]));
    let 最後 = 名前の並び(&["甲", "戊"]);
    let 戻した = 履歴.取り消す(&最後).expect("取り消せる");
    assert_eq!(名前(&戻した), ["甲", "丁"], "区切りの後の変化は別の変化");
    assert_eq!(
        名前(&履歴.取り消す(&戻した).expect("取り消せる")),
        ["甲"],
        "区切りと同じフレームの変化までが1つになっている"
    );
}

#[test]
fn 別の値の変化はまとめない() {
    let mut 履歴 = 新しく作った履歴(&["甲"]);
    履歴.次の変化の値を覚える(続けて変える値::区間の開始(識別子("甲")));
    履歴.並びを見る(&名前の並び(&["甲", "乙"]));
    履歴.次の変化の値を覚える(続けて変える値::区間の終了(識別子("甲")));
    履歴.並びを見る(&名前の並び(&["甲", "丙"]));
    let 戻した = 履歴
        .取り消す(&名前の並び(&["甲", "丙"]))
        .expect("取り消せる");
    assert_eq!(名前(&戻した), ["甲", "乙"]);
}
