//! 編集の履歴の試験。並びの変化を積み、取り消しとやり直しで戻すことと、選択だけの変化を積まないことと、
//! 上限を超えたら古いものから捨てることを確かめる。続けて変えた値のまとめは `edit_merge_tests.rs` が確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{クリップ, クリップスタック, クリップ名, クリップ識別子};

use super::{並びの出どころ, 編集の履歴};

pub(super) fn 識別子(名前: &str) -> クリップ識別子 {
    クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子")
}

pub(super) fn 名前の並び(名前: &[&str]) -> クリップスタック {
    let 一覧 = 名前
        .iter()
        .map(|名前| {
            クリップ::既定値で作成する(
                識別子(名前),
                クリップ名::作成する(名前.to_string()),
            )
        })
        .collect();
    クリップスタック::一覧から作成する(一覧).expect("並び")
}

/// 名前の並びを起点にした、新しく作った並びの空の履歴。
pub(super) fn 新しく作った履歴(名前: &[&str]) -> 編集の履歴 {
    編集の履歴::起点から始める(&名前の並び(名前), 並びの出どころ::新しく作った)
}

pub(super) fn 名前(並び: &クリップスタック) -> Vec<String> {
    並び
        .一覧()
        .iter()
        .map(|クリップ| クリップ.識別子().文字列().to_string())
        .collect()
}

#[test]
fn 変化を積んで取り消しとやり直しで戻し_取り消した後に変えるとやり直せない() {
    let 起点 = 名前の並び(&["甲"]);
    let mut 履歴 = 編集の履歴::起点から始める(&起点, 並びの出どころ::新しく作った);
    let 二つ = 名前の並び(&["甲", "乙"]);
    履歴.並びを見る(&二つ);
    let 三つ = 名前の並び(&["甲", "乙", "丙"]);
    履歴.並びを見る(&三つ);
    let 戻した = 履歴.取り消す(&三つ).expect("取り消せる");
    assert_eq!(名前(&戻した), ["甲", "乙"]);
    let 進めた = 履歴.やり直す(&戻した).expect("やり直せる");
    assert_eq!(名前(&進めた), ["甲", "乙", "丙"]);
    let 戻した = 履歴.取り消す(&進めた).expect("取り消せる");
    let 別の並び = 名前の並び(&["甲", "乙", "丁"]);
    assert!(
        履歴.やり直す(&別の並び).is_none(),
        "取り消した後に変えたらやり直せない"
    );
    assert!(!履歴.やり直せるか(&別の並び));
    assert_eq!(
        名前(&履歴.取り消す(&別の並び).expect("取り消せる")),
        名前(&戻した)
    );
}

#[test]
fn 選択だけの変化は積まず_起点から変わったかはクリップだけで決める() {
    let 起点 = 名前の並び(&["甲", "乙"]);
    let mut 履歴 = 編集の履歴::起点から始める(&起点, 並びの出どころ::新しく作った);
    let mut 選び直した = 起点.clone();
    選び直した.選択する(&識別子("乙")).expect("選べる");
    履歴.並びを見る(&選び直した);
    assert!(!履歴.取り消せるか(&選び直した));
    assert!(!履歴.起点.変わったか(&選び直した));
    assert!(履歴.起点.変わったか(&名前の並び(&["甲"])));
}

#[test]
fn 取り消せる数は100までで古いものから捨てる() {
    let mut 履歴 = 編集の履歴::起点から始める(
        &名前の並び(&["起点"]),
        並びの出どころ::新しく作った,
    );
    let mut 最後 = 名前の並び(&["起点"]);
    for 番号 in 0..101 {
        最後 = 名前の並び(&[&format!("変化{番号}")]);
        履歴.並びを見る(&最後);
    }
    let mut 取り消した数 = 0;
    while let Some(戻した) = 履歴.取り消す(&最後) {
        最後 = 戻した;
        取り消した数 += 1;
    }
    assert_eq!(取り消した数, 100);
    assert_eq!(名前(&最後), ["変化0"]);
}
