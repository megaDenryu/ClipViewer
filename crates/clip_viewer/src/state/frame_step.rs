//! 1フレームの状態の進め方。時計を進め、再生中なら映しているクリップを選び、先読みを整えて表示するコマを載せ、音の先読みと流し読みを整える。

use std::time::Instant;

use super::アプリの状態;

impl アプリの状態 {
    /// 画面を組む前に毎フレーム呼ぶ。前のフレームで当てた応答による並びの変化を編集の履歴へ積み、
    /// 動画があれば時計と供給を進める(動画が無ければ何もしない。移植元と同じ)。
    pub(crate) fn フレームを進める(&mut self, 今: Instant) {
        self.並びの変化を履歴へ積む();
        if self.動画.is_none() {
            return;
        }
        let 動画の長さ = self.動画の長さ();
        self.再生.時計を進める(今, &self.並び, 動画の長さ);
        if self.再生.再生しているか() {
            self.映しているクリップを選ぶ();
        }
        let 並び = self.先読みの並び();
        let 求め = self.表示するコマの求め();
        let 開き直し方 = self.流し読みの開き直し方();
        if let Some(動画) = self.動画.as_mut() {
            動画.先読みを整える(&並び, 今);
            if let Some(求め) = &求め {
                動画.コマを載せる(求め, 開き直し方.映像, 今);
            }
            let 落ち着いたか = !動画.台帳().依頼を出すのを待っているか();
            if let Some(供給) = 動画.音.供給を書き換える() {
                供給.溜める並びを整える(並び.区間の列(), 落ち着いたか);
                if let Some(求め) = &求め {
                    供給.流し読みを整える(
                        求め.動画上の位置,
                        求め.区間.as_ref(),
                        開き直し方.音,
                        今,
                    );
                }
            }
        }
    }

    /// 映しているクリップを選択中にする。再生中にカードの表示が映しているクリップへ付いてくるようにする。
    fn 映しているクリップを選ぶ(&mut self) {
        let Some(識別子) = self
            .映しているクリップ()
            .map(|クリップ| クリップ.識別子().clone())
        else {
            return;
        };
        if self
            .並び
            .選択中のクリップ()
            .map(|クリップ| クリップ.識別子())
            != Some(&識別子)
        {
            // 注意: 識別子は並びから取ったばかりなので、選択は失敗しない。
            let _ = self.並び.選択する(&識別子);
        }
    }
}
