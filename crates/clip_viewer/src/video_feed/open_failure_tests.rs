//! 動画を開けなかったときの案内の文の試験。

use std::time::Duration;

use video_source::動画の情報の取得エラー;

use super::open_failure::{動画を開く経路, 動画を開けない理由};

fn 時間切れ() -> 動画を開けない理由 {
    動画を開けない理由::情報を取れない(動画の情報の取得エラー::時間切れ {
        期限: Duration::from_secs(30),
    })
}

#[test]
fn 時間切れはどの経路でも少し待ってからもう一度開くよう案内する() {
    for 経路 in [
        動画を開く経路::ライブラリの一覧から,
        動画を開く経路::パスを指定して,
    ] {
        let 文 = 時間切れ().案内を添えた文(経路);
        assert!(文.ends_with("少し待ってからもう一度開く"), "{文}");
        assert!(!文.contains("動画の場所を指定し直す"), "{文}");
    }
}

#[test]
fn 案内の決まらない理由は理由だけを出す() {
    let 理由 = 動画を開けない理由::FFmpegが無い;
    assert_eq!(
        理由.案内を添えた文(動画を開く経路::パスを指定して),
        理由.to_string()
    );
}
