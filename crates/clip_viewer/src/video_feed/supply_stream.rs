//! 流し読みからの供給。溜めたコマで映せない間、流し読みを必要なときだけ開き直して、その時刻に出すコマをテクスチャへ載せる。
//! 参照: _doc/設計/画面.md 判断5

use std::time::Instant;

use clip_domain::動画上の秒;
use video_source::{流し読みの状態, 長辺の上限};

use super::frame_request::表示するコマの求め;
use super::loaded_video::読み込んだ動画;
use super::stream_slot::開いた流し読み;
use crate::stream_rules::{流し読みの開き直し, 開き直しの最短の間隔};

impl 読み込んだ動画 {
    /// 流し読みのコマを載せる。開き直しを控える間は、位置を覚えずに今のコマのままにする(控えを解いた次のフレームで開き直すため)。
    /// 求める位置のコマがまだ届いていない間は、流し読みのコマを待っているとして覚える。
    pub(super) fn 流し読みのコマを載せる(
        &mut self,
        求め: &表示するコマの求め,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        let 位置 = 求め.流し読みで求める位置(self.倉庫.動画().コマの速さ());
        self.流し読みのコマを待っている = false;
        let 開き直すか = self
            .流し読み
            .as_ref()
            .is_none_or(|流し読み| 流し読み.この位置で開き直すか(位置));
        if 開き直すか {
            let 間隔を守ったか = self.流し読み.as_ref().is_none_or(|流し読み| {
                流し読み.開いてからの経過(今) >= 開き直しの最短の間隔
            });
            if 開き直し == 流し読みの開き直し::控える || !間隔を守ったか {
                self.流し読みのコマを待っている =
                    開き直し == 流し読みの開き直し::してよい;
                return;
            }
            let 動画 = self.倉庫.動画();
            self.流し読み = Some(開いた流し読み::開く(
                &self.読み手,
                動画,
                位置,
                長辺の上限::既定,
                今,
            ));
        }
        self.求めた位置のコマを載せる(位置);
    }

    fn 求めた位置のコマを載せる(&mut self, 位置: 動画上の秒) {
        let 目当ての番号 = self.倉庫.動画().コマの速さ().時刻を含むコマ番号(位置);
        let Some(流し読み) = self.流し読み.as_mut().and_then(|開いた| {
            開いた.求めた位置を覚え途中の失敗を写して中身を貸す(位置)
        }) else {
            return;
        };
        let 載せた番号 = match 流し読み.その時刻に出すコマ(位置) {
            Some(コマ) => {
                let 結果 = self.映像.コマを載せる(コマ.番号(), コマ.コマ());
                self.載せられない理由 = 結果.err().map(|不正| 不正.to_string());
                Some(コマ.番号())
            }
            None => None,
        };
        let 読んでいる = matches!(流し読み.状態(), 流し読みの状態::読んでいる);
        self.流し読みのコマを待っている =
            読んでいる && 載せた番号.is_none_or(|番号| 番号 < 目当ての番号);
    }
}
