//! コマを載せたかの結合試験。コマの載せ先が「載せた」と返すのは、求めた動画のコマを実際にテクスチャへ載せたときだけであることを確かめる。
//! 重ね合わせの供給は、この返り値で行のテクスチャに載っている置いたクリップのコマを覚える(同時再生.md 5-2 の7)。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use super::frame_loaded::コマを載せたか;
use super::load_range::載せるコマの範囲;
use super::with_ffmpeg_loaded_support::試験動画の供給元と載せ先;
use super::with_ffmpeg_support::成り立つまで待つ;

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 出すコマが無いまま流し読みが終わっても_載せたとは返さない() {
    let mut 試験 = 試験動画の供給元と載せ先::試験動画を作って開く(
        "出すコマが無い",
        載せるコマの範囲::どのコマも,
    );
    成り立つまで待つ(
        "動画の終わりより後ろで開いた流し読みが読めなくなること",
        || {
            assert_eq!(試験.位置のコマを載せる(10.0), コマを載せたか::載せなかった);
            試験.載せ先.映せない理由().is_some()
        },
    );
    assert!(!試験.載せ先.コマを待っているか());
    assert!(試験.載せ先.テクスチャ().まだ映していないか());
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 流し読みのコマをテクスチャへ載せたら載せたと返す() {
    let mut 試験 = 試験動画の供給元と載せ先::試験動画を作って開く(
        "載せたと返す",
        載せるコマの範囲::どのコマも,
    );
    成り立つまで待つ("1秒のコマを載せたと返すこと", || {
        matches!(試験.位置のコマを載せる(1.0), コマを載せたか::載せた(_))
    });
    assert!(!試験.載せ先.テクスチャ().まだ映していないか());
}
