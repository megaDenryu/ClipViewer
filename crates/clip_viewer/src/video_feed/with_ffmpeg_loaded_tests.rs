//! コマを載せたかの結合試験。コマの載せ先が「載せた」と返すのは、求めた動画のコマを実際にテクスチャへ載せたときだけであることを確かめる。
//! 重ね合わせの供給は、この返り値で行のテクスチャに載っている置いたクリップのコマを覚える(同時再生.md 5-2 の7)。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::正規化した動画パス;
use eframe::egui;
use video_source::{メモリの上限, 動画の読み手};

use super::frame_source::動画のコマの供給元;
use super::frame_target::コマの載せ先;
use super::loaded_frame_state::コマを載せたか;
use super::video_texture::テクスチャの名前;
use super::with_ffmpeg_support::{
    実行ファイルを探す, 成り立つまで待つ, 求め, 試験動画を作る
};
use crate::stream_rules::流し読みの開き直し;

/// 試験の載せ先とは、試験動画(4秒、30コマ/秒)の動画のコマの供給元と、コマの載せ先と、動画ファイルのパスの組のことである。落とすとファイルを消す。
struct 試験の載せ先 {
    供給元: 動画のコマの供給元,
    載せ先: コマの載せ先,
    パス: 正規化した動画パス,
}

impl 試験の載せ先 {
    fn 作って開く(名前: &str) -> Self {
        let 実行ファイル = 実行ファイルを探す();
        let パス = 試験動画を作る(&実行ファイル, 名前);
        let 供給元 = 動画のコマの供給元::動画の情報を取って作る(
            動画の読み手::作成する(実行ファイル),
            &パス,
            メモリの上限::既定,
        )
        .expect("動画を開ける");
        let 載せ先 = コマの載せ先::登録して作る(
            &egui::Context::default(),
            テクスチャの名前::作成する("試験の映像"),
        )
        .expect("テクスチャを作れる");
        Self {
            供給元,
            載せ先,
            パス,
        }
    }

    /// 区間を持たない求めで、位置のコマを流し読みから載せる。
    fn 位置のコマを載せる(&mut self, 位置: f64) -> コマを載せたか {
        self.載せ先.コマを載せる(
            &mut self.供給元,
            &求め(位置, None),
            流し読みの開き直し::してよい,
            Instant::now(),
        )
    }
}

impl Drop for 試験の載せ先 {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(self.パス.文字列());
    }
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 出すコマが無いまま流し読みが終わっても_載せたとは返さない() {
    let mut 試験 = 試験の載せ先::作って開く("出すコマが無い");
    成り立つまで待つ(
        "動画の終わりより後ろで開いた流し読みが読めなくなること",
        || {
            assert_eq!(試験.位置のコマを載せる(10.0), コマを載せたか::載せなかった);
            試験.載せ先.映せない理由().is_some()
        },
    );
    assert!(!試験.載せ先.コマを待っているか());
    assert!(試験.載せ先.テクスチャ().まだ映していないか());
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 流し読みのコマをテクスチャへ載せたら載せたと返す() {
    let mut 試験 = 試験の載せ先::作って開く("載せたと返す");
    成り立つまで待つ("1秒のコマを載せたと返すこと", || {
        試験.位置のコマを載せる(1.0) == コマを載せたか::載せた
    });
    assert!(!試験.載せ先.テクスチャ().まだ映していないか());
}
