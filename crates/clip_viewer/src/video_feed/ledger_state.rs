//! 依頼の台帳の行の状態。倉庫へ出した依頼が今どうなっているかを、画面が表示し、台帳が依頼し直すかを決めるために持つ。

use video_source::{コマ数, 依頼の状況, 受け付けない理由, 溜め終えた内訳};

/// 依頼の進み具合とは、倉庫が受け付けた依頼の、処理待ち・溜めている途中・溜め終えたの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 依頼の進み具合 {
    処理を待っている,
    溜めている {
        溜めたコマ数: コマ数,
        見込みのコマ数: コマ数,
    },
    溜め終えた(溜め終えた内訳),
}

/// 依頼の結末とは、区間を溜めなかった理由、または溜める途中で外れた理由の区別のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 依頼の結末 {
    断られた(受け付けない理由),
    倉庫が捨てた,
    取り消された,
    倉庫が覚えていない,
    失敗した(String),
}

impl 依頼の結末 {
    /// 並びの順が変わったときに依頼し直すか。優先順で決まる結末だけを依頼し直し、区間そのものに原因がある結末は依頼し直さない。
    pub(crate) fn 順が変わったら依頼し直すか(&self) -> bool {
        matches!(
            self,
            Self::断られた(受け付けない理由::優先順の高い区間で埋まっている { .. })
                | Self::倉庫が捨てた
                | Self::取り消された
                | Self::倉庫が覚えていない
        )
    }
}

/// 状況の写しとは、倉庫の依頼の状況を、台帳が持つ進み具合か結末へ写したもののことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 状況の写し {
    進んでいる(依頼の進み具合),
    終わった(依頼の結末),
}

impl 状況の写し {
    /// 倉庫の依頼の状況を写す。失敗は理由の文にして持つ(倉庫の失敗の値は倉庫から借りたものであるため)。
    pub(crate) fn 依頼の状況から写す(状況: &依頼の状況<'_>) -> Self {
        match 状況 {
            依頼の状況::処理待ち => {
                Self::進んでいる(依頼の進み具合::処理を待っている)
            }
            依頼の状況::処理中 {
                溜めたコマ数,
                見込みのコマ数,
            } => Self::進んでいる(依頼の進み具合::溜めている {
                溜めたコマ数: *溜めたコマ数,
                見込みのコマ数: *見込みのコマ数,
            }),
            依頼の状況::完了(内訳) => {
                Self::進んでいる(依頼の進み具合::溜め終えた(*内訳))
            }
            依頼の状況::失敗(失敗) => {
                Self::終わった(依頼の結末::失敗した(失敗.to_string()))
            }
            依頼の状況::取り消した => Self::終わった(依頼の結末::取り消された),
            依頼の状況::捨てた => Self::終わった(依頼の結末::倉庫が捨てた),
            依頼の状況::知らない札 => Self::終わった(依頼の結末::倉庫が覚えていない),
        }
    }
}

/// 行の状態とは、台帳の1つの区間について、倉庫に依頼中か、依頼が終わったかの区別のことである。
/// 札の型は倉庫の受付の札であり、試験では倉庫を使わずに台帳の判断を確かめるため型引数にしている。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum 行の状態<札> {
    依頼中 {
        札: 札,
        進み具合: 依頼の進み具合,
    },
    終わった(依頼の結末),
}

impl<札> 行の状態<札> {
    /// 並びの順が変わったときに、この行を外して依頼し直すか。終わった行のうち、結末が依頼し直せるものだけである。
    pub(crate) fn 順が変わったら依頼し直すか(&self) -> bool {
        matches!(self, Self::終わった(結末) if 結末.順が変わったら依頼し直すか())
    }
}
