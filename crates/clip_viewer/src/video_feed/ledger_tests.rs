//! 依頼の台帳の判断の試験。倉庫を使わず、札の代わりに数を使う。
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::ledger::依頼の台帳;
use super::ledger_state::{依頼の進み具合, 状況の写し};
use super::ledger_test_support::{区間, 落ち着いた後};

#[test]
fn 最初の並びは優先順をすぐ渡し_依頼は落ち着いてから出す() {
    let mut 台帳 = 依頼の台帳::<u32>::空();
    let 並び = [区間(0.0, 1.0), 区間(2.0, 3.0)];
    let 始め = Instant::now();
    let 手順 = 台帳.手順を決める(&並び, 始め);
    assert_eq!(手順.渡す優先順, Some(並び.to_vec()));
    assert!(手順.依頼する区間.is_empty());
    assert!(台帳.依頼を出すのを待っているか());
    let 手順 = 台帳.手順を決める(&並び, 落ち着いた後(始め));
    assert_eq!(手順.渡す優先順, None);
    assert_eq!(手順.依頼する区間, 並び.to_vec());
    assert!(!台帳.依頼を出すのを待っているか());
}

#[test]
fn 依頼した区間は依頼し直さない() {
    let mut 台帳 = 依頼の台帳::<u32>::空();
    let 並び = [区間(0.0, 1.0)];
    let 始め = Instant::now();
    台帳.手順を決める(&並び, 始め);
    台帳.依頼の結果を記録する(並び[0], Ok(7));
    let 手順 = 台帳.手順を決める(&並び, 落ち着いた後(始め));
    assert!(手順.依頼する区間.is_empty());
    assert_eq!(台帳.依頼中の札(), vec![7]);
}

#[test]
fn 並びから消えた依頼中の区間は捨て_新しい区間は落ち着いてから依頼する() {
    let mut 台帳 = 依頼の台帳::<u32>::空();
    let (古い, 新しい) = (区間(0.0, 1.0), 区間(0.0, 1.5));
    let 始め = Instant::now();
    台帳.手順を決める(&[古い], 始め);
    台帳.依頼の結果を記録する(古い, Ok(1));
    let 編集した時刻 = 落ち着いた後(始め);
    let 手順 = 台帳.手順を決める(&[新しい], 編集した時刻);
    assert_eq!(手順.捨てる区間, vec![古い]);
    assert!(手順.依頼する区間.is_empty());
    assert!(台帳.依頼中の札().is_empty());
    let 手順 = 台帳.手順を決める(&[新しい], 落ち着いた後(編集した時刻));
    assert_eq!(手順.依頼する区間, vec![新しい]);
}

#[test]
fn 溜め終えた区間だけを溜め終えたとみなす() {
    let mut 台帳 = 依頼の台帳::<u32>::空();
    let 甲 = 区間(0.0, 1.0);
    台帳.依頼の結果を記録する(甲, Ok(1));
    assert!(!台帳.溜め終えたか(&甲));
    let 途中 = 依頼の進み具合::処理を待っている;
    台帳.状況を記録する(1, 状況の写し::進んでいる(途中));
    assert!(!台帳.溜め終えたか(&甲));
    let 内訳 = video_source::溜め終えた内訳 {
        溜めたコマ数: video_source::コマ数::作成する(3),
        見込みのコマ数: video_source::コマ数::作成する(3),
    };
    台帳.状況を記録する(1, 状況の写し::進んでいる(依頼の進み具合::溜め終えた(内訳)));
    assert!(台帳.溜め終えたか(&甲));
}
