//! 先読みの並び。倉庫へ溜める依頼を出す順であり、同じ順を保持の優先順として倉庫へ渡す。

use clip_domain::{クリップスタック, クリップ識別子, 動画上の区間};

/// 先読みの並びとは、再生できるクリップの区間を、再生中のクリップ → 次のクリップ → 残りの順に並べ、同じ区間を1つにまとめたもののことである。
/// 先頭ほど倉庫に残したい。参照: _doc/設計/アーキテクチャ.md 判断1-5
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct 先読みの並び(Vec<動画上の区間>);

impl 先読みの並び {
    /// 起点のクリップから並び順に一巡して求める。起点が無ければ先頭から並べる。起点が再生できなくても、並びの位置は起点から数える。
    pub(crate) fn スタックから求める(
        並び: &クリップスタック,
        起点: Option<&クリップ識別子>,
    ) -> Self {
        let 一覧 = 並び.一覧();
        let 起点の位置 = 起点
            .and_then(|識別子| 一覧.iter().position(|クリップ| クリップ.識別子() == 識別子))
            .unwrap_or(0);
        let (前, 後) = 一覧.split_at(起点の位置);
        let mut 区間の列: Vec<動画上の区間> = Vec::new();
        for クリップ in 後
            .iter()
            .chain(前)
            .filter(|クリップ| クリップ.再生できるか())
        {
            if !区間の列.contains(&クリップ.区間) {
                区間の列.push(クリップ.区間);
            }
        }
        Self(区間の列)
    }

    /// 区間の列から直接作る。結合試験で、スタックを組まずに先読みの並びを渡すために使う。
    #[cfg(test)]
    pub(crate) fn 区間の列から作る(区間の列: Vec<動画上の区間>) -> Self {
        Self(区間の列)
    }

    pub(crate) fn 区間の列(&self) -> &[動画上の区間] {
        &self.0
    }
}
