//! 読み込んだ動画。動画を開いたときに一緒に作り、解除したときに一緒に捨てるもの(コマの供給元・コマの載せ先・動画の音)の組と、
//! 毎フレーム先読みの台帳の手順を倉庫へ行い、表示するコマを溜めたコマか流し読みから取り出してテクスチャへ載せる手順。
//! 参照: _doc/設計/画面.md 判断2

use std::time::Instant;

use audio_pcm::サンプリング周波数;
use eframe::egui;
use video_source::{メモリの上限, 動画の情報, 動画の読み手, 受付の札};

use clip_domain::正規化した動画パス;

use super::frame_request::{コマの出どころ, 表示するコマの求め};
use super::frame_source::動画のコマの供給元;
use super::frame_target::コマの載せ先;
use super::ledger::依頼の台帳;
use super::open_failure::動画を開けない理由;
use super::prefetch_order::先読みの並び;
use super::video_texture::{テクスチャの名前, 映像のテクスチャ};
use crate::audio_feed::動画の音;
use crate::stream_rules::流し読みの開き直し;

const スタックの映像のテクスチャの名前: テクスチャの名前 =
    テクスチャの名前::作成する("ClipViewer の映像");

/// 読み込んだ動画とは、1つの動画に結び付いた、動画のコマの供給元(読み手・倉庫・依頼の台帳)と、コマの載せ先(流し読み・映像のテクスチャ)と、
/// 動画の音の組のことである。動画の音は音の供給(`audio_feed`)が扱う。
pub(crate) struct 読み込んだ動画 {
    供給元: 動画のコマの供給元,
    載せ先: コマの載せ先,
    pub(crate) 音: 動画の音,
}

impl 読み込んだ動画 {
    /// 動画の情報を ffprobe で調べ、音を開き、既定の長辺の上限とメモリの上限で倉庫を開き、映像のテクスチャを登録する(この順に行う)。
    /// 音は出力装置の周波数があれば開く。音を鳴らせなくても動画は開く。
    pub(crate) fn 開く(
        読み手: 動画の読み手,
        パス: &正規化した動画パス,
        画面描画の共有状態: &egui::Context,
        周波数: Option<サンプリング周波数>,
    ) -> Result<Self, 動画を開けない理由> {
        let 情報 = 読み手.動画の情報を取る(パス)?;
        let 音 = 動画の音::開く(&読み手, &情報, 周波数);
        let 供給元 = 動画のコマの供給元::倉庫を開いて作る(
            読み手,
            情報,
            メモリの上限::既定,
        )?;
        let 載せ先 = コマの載せ先::登録して作る(
            画面描画の共有状態,
            スタックの映像のテクスチャの名前,
        )?;
        Ok(Self {
            供給元, 載せ先, 音
        })
    }

    pub(crate) fn 情報(&self) -> &動画の情報 {
        self.供給元.情報()
    }

    pub(crate) fn 映像(&self) -> &映像のテクスチャ {
        self.載せ先.テクスチャ()
    }

    pub(crate) fn 台帳(&self) -> &依頼の台帳<受付の札> {
        self.供給元.台帳()
    }

    /// 流し読みで、求めた位置のコマがまだ届いていないか。画面は、この間は入力が無くても描き直す。
    pub(crate) fn 流し読みのコマを待っているか(&self) -> bool {
        self.載せ先.コマを待っているか()
    }

    /// 最後に表示したコマの出どころ。
    pub(crate) fn 出どころ(&self) -> コマの出どころ {
        self.載せ先
            .載せているコマの出どころ()
            .コマの出どころへ写す()
    }

    /// 流し読みを開いているか。結合試験で、溜めたコマで載せる間は流し読みを開かないことを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 流し読みを開いているか(&self) -> bool {
        self.載せ先.流し読みを開いているか()
    }

    /// 流し読みが読めない理由、またはテクスチャへ載せられなかった理由。
    pub(crate) fn 映せない理由(&self) -> Option<&str> {
        self.載せ先.映せない理由()
    }

    /// 台帳が決めた手順(優先順を渡す → 捨てる → 依頼する)を倉庫へ行い、依頼中の札の状況を台帳へ書き込む。
    pub(crate) fn 先読みを整える(&mut self, 並び: &先読みの並び, 今: Instant) {
        self.供給元.先読みを整える(並び.区間の列(), 今);
    }

    /// 表示するコマを、区間を溜め終えていれば倉庫から、そうでなければ流し読みから取り出してテクスチャへ載せる。
    pub(crate) fn コマを載せる(
        &mut self,
        求め: &表示するコマの求め,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        self.載せ先
            .コマを載せる(&mut self.供給元, 求め, 開き直し, 今);
    }
}
