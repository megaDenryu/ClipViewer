//! 先読みの並びの試験。
#![allow(clippy::expect_used)]

use clip_domain::{
    クリップ, クリップスタック, クリップ名, クリップ識別子, 動画上の区間, 時刻
};

use super::prefetch_order::先読みの並び;

fn クリップを作る(名前: &str, 開始: f64, 終了: f64) -> クリップ {
    let 識別子 = クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子");
    let mut クリップ =
        クリップ::既定値で作成する(識別子, クリップ名::作成する(名前.to_string()));
    クリップ.区間 = 区間(開始, 終了);
    クリップ
}

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}

fn 識別子(名前: &str) -> クリップ識別子 {
    クリップ識別子::文字列から作成する(名前.to_string()).expect("識別子")
}

#[test]
fn 再生中のクリップから一巡し_再生できないクリップを飛ばす() {
    let mut 無効 = クリップを作る("乙", 2.0, 3.0);
    無効.有効か = false;
    let 並び = クリップスタック::一覧から作成する(vec![
        クリップを作る("甲", 0.0, 1.0),
        無効,
        クリップを作る("丙", 4.0, 5.0),
        クリップを作る("丁", 6.0, 7.0),
    ])
    .expect("スタック");
    let 求めた = 先読みの並び::スタックから求める(&並び, Some(&識別子("丙")));
    assert_eq!(
        求めた.区間の列(),
        [区間(4.0, 5.0), 区間(6.0, 7.0), 区間(0.0, 1.0)]
    );
}

#[test]
fn 同じ区間は1つにまとめ_起点が無ければ先頭から並べる() {
    let 並び = クリップスタック::一覧から作成する(vec![
        クリップを作る("甲", 0.0, 1.0),
        クリップを作る("乙", 0.0, 1.0),
        クリップを作る("丙", 1.0, 1.0),
    ])
    .expect("スタック");
    let 求めた = 先読みの並び::スタックから求める(&並び, None);
    assert_eq!(求めた.区間の列(), [区間(0.0, 1.0)]);
}
