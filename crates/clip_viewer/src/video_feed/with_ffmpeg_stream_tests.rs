//! 流し読みの経路の結合試験。再生位置の帯のドラッグの間は開き直さず放すと後ろの位置のコマが載ることと、
//! 区間の終わりちょうど(末尾で止めたとき)は区間の中の最後のコマを載せることを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::動画上の区間;

use super::loaded_video::読み込んだ動画;
use super::with_ffmpeg_support::{成り立つまで待つ, 求め, 秒, 試験の動画};
use crate::stream_rules::流し読みの開き直し;

fn 載せた番号(動画: &読み込んだ動画) -> Option<u32> {
    動画
        .映像()
        .載せたコマ()
        .map(|載せたコマ| 載せたコマ.番号.値())
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 再生位置の帯のドラッグの間は開き直さず_放すと後ろの位置のコマが載る() {
    let mut 試験 = 試験の動画::作って開く("ドラッグ");
    let 動画 = &mut 試験.動画;
    成り立つまで待つ("3秒のコマが載ること", || {
        動画.コマを載せる(
            &求め(3.0, None),
            流し読みの開き直し::してよい,
            Instant::now(),
        );
        matches!(載せた番号(動画), Some(88..=90))
    });
    let ドラッグ前 = 載せた番号(動画);
    for 位置 in [2.0, 1.0, 0.5] {
        動画.コマを載せる(
            &求め(位置, None),
            流し読みの開き直し::控える,
            Instant::now(),
        );
        assert_eq!(
            載せた番号(動画),
            ドラッグ前,
            "ドラッグの間は開き直さず今のコマのままにする"
        );
    }
    成り立つまで待つ("放した後に0.5秒のコマが載ること", || {
        動画.コマを載せる(
            &求め(0.5, None),
            流し読みの開き直し::してよい,
            Instant::now(),
        );
        matches!(載せた番号(動画), Some(14..=15))
    });
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 区間の終わりちょうどは区間の中の最後のコマを流し読みで載せる() {
    let mut 試験 = 試験の動画::作って開く("末尾");
    let 動画 = &mut 試験.動画;
    let 区間 = 動画上の区間::作成する(秒(1.0), 秒(2.0)).expect("区間");
    成り立つまで待つ("区間の最後のコマが載ること", || {
        動画.コマを載せる(
            &求め(2.0, Some(区間)),
            流し読みの開き直し::してよい,
            Instant::now(),
        );
        載せた番号(動画).is_some()
    });
    assert_eq!(
        載せた番号(動画),
        Some(59),
        "区間の外の60番(2.0秒から表示するコマ)を出さない"
    );
}
