//! 映像の供給の手順。毎フレーム、先読みの台帳の手順を倉庫へ行い、表示するコマを溜めたコマか流し読みから取り出してテクスチャへ載せる。

use std::time::Instant;

use clip_domain::{動画上の区間, 動画上の秒};
use video_source::{保持の優先順, 溜める依頼の結果};

use super::frame_request::{コマの出どころ, 表示するコマの求め};
use super::ledger_state::状況の写し;
use super::loaded_video::読み込んだ動画;
use super::prefetch_order::先読みの並び;
use crate::stream_rules::流し読みの開き直し;

impl 読み込んだ動画 {
    /// 台帳が決めた手順(優先順を渡す → 捨てる → 依頼する)を倉庫へ行い、依頼中の札の状況を台帳へ記録する。
    pub(crate) fn 先読みを整える(&mut self, 並び: &先読みの並び, 今: Instant) {
        let 手順 = self.台帳.手順を決める(並び.区間の列(), 今);
        if let Some(優先順) = 手順.渡す優先順 {
            self.倉庫.保持の優先順を渡す(保持の優先順::作成する(優先順));
        }
        for 区間 in &手順.捨てる区間 {
            self.倉庫.区間の破棄を依頼する(区間);
        }
        for 区間 in 手順.依頼する区間 {
            let 結果 = match self.倉庫.区間を溜める依頼を出す(区間) {
                溜める依頼の結果::受け付けた(札) => Ok(札),
                溜める依頼の結果::受け付けない(理由) => Err(理由),
            };
            self.台帳.依頼の結果を記録する(区間, 結果);
        }
        for 札 in self.台帳.依頼中の札() {
            let 写し = 状況の写し::依頼の状況から写す(
                &self.倉庫.依頼の状況を問い合わせる(札),
            );
            self.台帳.状況を記録する(札, 写し);
        }
    }

    /// 表示するコマを、区間を溜め終えていれば倉庫から、そうでなければ流し読みから取り出してテクスチャへ載せる。
    pub(crate) fn コマを載せる(
        &mut self,
        求め: &表示するコマの求め,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        self.出どころ = match 求め.区間 {
            Some(区間) if self.台帳.溜め終えたか(&区間) => {
                コマの出どころ::溜めたコマ(区間)
            }
            _ => コマの出どころ::流し読み,
        };
        match self.出どころ {
            コマの出どころ::溜めたコマ(区間) => {
                self.流し読み = None;
                self.溜めたコマを載せる(&区間, 求め.動画上の位置);
            }
            コマの出どころ::流し読み => {
                self.流し読みのコマを載せる(求め, 開き直し, 今)
            }
        }
    }

    fn 溜めたコマを載せる(
        &mut self, 区間: &動画上の区間, 位置: 動画上の秒
    ) {
        let Some(コマ) = self.倉庫.溜めたコマを取り出す(区間, 位置) else {
            return;
        };
        let 結果 = self.映像.コマを載せる(コマ.番号(), コマ.コマ());
        self.載せられない理由 = 結果.err().map(|不正| 不正.to_string());
    }
}
