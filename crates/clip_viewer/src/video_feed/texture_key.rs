//! テクスチャに載せたコマの番号と寸法。同じコマを毎フレーム GPU へ送り直さないために、前に載せたコマと比べる。
//! 参照: _doc/設計/画面.md 判断3

use video_source::{コマの寸法, 動画上のコマ番号};

/// 載せたコマの番号と寸法とは、テクスチャに今載っているコマの動画上のコマ番号と寸法の組のことである。
/// 動画を読み込み直したことの区別は、これを持つ `読み込んだ動画` ごと作り直すことで表す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct 載せたコマの番号と寸法 {
    pub(crate) 番号: 動画上のコマ番号,
    pub(crate) 寸法: コマの寸法,
}

impl 載せたコマの番号と寸法 {
    /// 前に載せたコマ(無ければ無い)から見て、このコマを載せ直すか。
    pub(crate) fn 載せ直すか(self, 前に載せたコマ: Option<Self>) -> bool {
        前に載せたコマ != Some(self)
    }
}
