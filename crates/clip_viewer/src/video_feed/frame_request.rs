//! 表示するコマの求め。再生位置とクリップスタックから、動画のどの位置のコマを、どの区間から、どう切り出して出すかを求める。

use clip_domain::{
    クリップスタック, クロップ範囲, 再生位置, 動画上の区間, 動画上の秒, 時間の長さ
};
use video_source::{コマの速さ, コマ数, 動画上のコマ番号};

/// 表示するコマの求めとは、画面に出すコマの動画上の位置と、そのコマを含むクリップの区間と、出力へ切り出すクロップの組のことである。
/// 元動画再生はクリップに属さないため、区間を持たずクロップは全体である。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct 表示するコマの求め {
    pub(crate) 動画上の位置: 動画上の秒,
    pub(crate) 区間: Option<動画上の区間>,
    pub(crate) クロップ: クロップ範囲,
}

impl 表示するコマの求め {
    /// 再生位置から求める。シーケンス再生で当たるクリップが無い、または単独クリップ再生で選択中のクリップが無いなら無い。
    /// シーケンス再生の末尾以降は、最後の再生できるクリップの区間の終わりを求める(`クリップスタック::表示するコマを求める`)。
    pub(crate) fn 求める(
        並び: &クリップスタック, 位置: 再生位置
    ) -> Option<Self> {
        match 位置 {
            再生位置::シーケンス再生(位置) => {
                並び.表示するコマを求める(位置).map(|コマ| Self {
                    動画上の位置: コマ.動画上の位置,
                    区間: Some(コマ.クリップ.区間),
                    クロップ: コマ.クリップ.クロップ,
                })
            }
            再生位置::単独クリップ再生(経過) => {
                並び.選択中のクリップ().map(|クリップ| Self {
                    動画上の位置: クリップ.単独再生での動画上の位置(経過),
                    区間: Some(クリップ.区間),
                    クロップ: クリップ.クロップ,
                })
            }
            再生位置::元動画再生(位置) => Some(Self {
                動画上の位置: 位置,
                区間: None,
                クロップ: クロップ範囲::全体,
            }),
        }
    }
}

impl 表示するコマの求め {
    /// 流し読みに求める位置。区間の終わりちょうどやそれより後ろ(末尾で止めたとき)は、区間の外のコマを出さないよう、
    /// 区間の中の最後のコマの真ん中を求める。スタックの作業場と重ね合わせの作業場の流し読みが共に使う。
    pub(crate) fn 流し読みで求める位置(
        &self, 速さ: コマの速さ
    ) -> 動画上の秒 {
        let Some(区間) = self
            .区間
            .filter(|区間| self.動画上の位置 >= 区間.終了() && !区間.長さ().ゼロか())
        else {
            return self.動画上の位置;
        };
        let 次の番号 = 速さ.時刻より前に始まるコマの次の番号(区間.終了());
        let 最後の番号 = 動画上のコマ番号::作成する(次の番号.値().saturating_sub(1));
        let 半コマ = 速さ.コマ数の長さ(コマ数::作成する(1)).秒数() / 2.0;
        let 真ん中 = 速さ
            .コマの始まる時刻(最後の番号)
            .進める(時間の長さ::作成する(半コマ).unwrap_or(時間の長さ::ゼロ));
        区間.位置を区間の中へ収める(真ん中)
    }
}

/// コマの出どころとは、表示するコマを倉庫の溜めたコマから取り出すか、流し読みから取り出すかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum コマの出どころ {
    溜めたコマ(動画上の区間),
    流し読み,
}
