//! 依頼の台帳への記録。倉庫へ依頼した結果と、問い合わせた状況を行へ書く。

use clip_domain::動画上の区間;
use video_source::受け付けない理由;

use super::ledger::{依頼の台帳, 台帳の行};
use super::ledger_state::{依頼の結末, 依頼の進み具合, 状況の写し, 行の状態};

impl<札: Copy + PartialEq> 依頼の台帳<札> {
    /// 区間を溜める依頼の結果を記録する。受け付けたなら札で依頼中の行を、断られたなら終わった行を足す。
    pub(crate) fn 依頼の結果を記録する(
        &mut self,
        区間: 動画上の区間,
        結果: Result<札, 受け付けない理由>,
    ) {
        let 状態 = match 結果 {
            Ok(札) => 行の状態::依頼中 {
                札,
                進み具合: 依頼の進み具合::処理を待っている,
            },
            Err(理由) => 行の状態::終わった(依頼の結末::断られた(理由)),
        };
        match self.行の位置(&区間) {
            Some(位置) => self.行[位置].状態 = 状態,
            None => self.行.push(台帳の行 { 区間, 状態 }),
        }
    }

    /// 依頼中の行の札の一覧。倉庫へ状況を問い合わせるために使う。
    pub(crate) fn 依頼中の札(&self) -> Vec<札> {
        self.行
            .iter()
            .filter_map(|行| match 行.状態 {
                行の状態::依頼中 { 札, .. } => Some(札),
                行の状態::終わった(_) => None,
            })
            .collect()
    }

    /// 札の依頼の状況を記録する。台帳に無い札なら何もしない。
    pub(crate) fn 状況を記録する(&mut self, 対象の札: 札, 写し: 状況の写し) {
        let 行 = self
            .行
            .iter_mut()
            .find(|行| matches!(行.状態, 行の状態::依頼中 { 札, .. } if 札 == 対象の札));
        let Some(行) = 行 else {
            return;
        };
        行.状態 = match 写し {
            状況の写し::進んでいる(進み具合) => 行の状態::依頼中 {
                札: 対象の札,
                進み具合,
            },
            状況の写し::終わった(結末) => 行の状態::終わった(結末),
        };
    }
}
