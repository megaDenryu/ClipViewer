//! 映像の供給の小さな判断(流し読みを開き直すか・テクスチャを載せ直すか・表示するコマの求め・状況の写し)の試験。
#![allow(clippy::expect_used)]

use clip_domain::{
    クリップ, クリップスタック, クリップ名, クリップ識別子, クロップ範囲, 再生位置, 時刻,
    時間の長さ,
};
use video_source::{コマの寸法, 依頼の状況, 動画上のコマ番号};

use super::frame_request::表示するコマの求め;
use super::ledger_state::{依頼の結末, 状況の写し};
use super::texture_key::載せたコマの番号と寸法;
use crate::stream_rules::流し読みの進み;

fn 秒(値: f64) -> clip_domain::動画上の秒 {
    時刻::作成する(値).expect("時刻")
}

#[test]
fn 流し読みは戻ったときと2秒より先へ飛んだときに開き直す() {
    let 進み = 流し読みの進み::開いた位置から(秒(10.0));
    assert!(!進み.この位置で開き直すか(秒(10.0)));
    assert!(!進み.この位置で開き直すか(秒(11.9)));
    assert!(進み.この位置で開き直すか(秒(9.99)));
    assert!(進み.この位置で開き直すか(秒(12.5)));
}

#[test]
fn テクスチャは番号か寸法が変わったときと最初だけ載せ直す() {
    let 寸法 = コマの寸法::作成する(4, 2).expect("寸法");
    let 別の寸法 = コマの寸法::作成する(2, 4).expect("寸法");
    let コマ = |番号, 寸法| 載せたコマの番号と寸法 {
        番号: 動画上のコマ番号::作成する(番号),
        寸法,
    };
    assert!(コマ(3, 寸法).載せ直すか(None));
    assert!(!コマ(3, 寸法).載せ直すか(Some(コマ(3, 寸法))));
    assert!(コマ(4, 寸法).載せ直すか(Some(コマ(3, 寸法))));
    assert!(コマ(3, 別の寸法).載せ直すか(Some(コマ(3, 寸法))));
}

#[test]
fn 単独クリップ再生は選択中のクリップの区間とクロップで求め_元動画再生は区間を持たない() {
    let 識別子 = クリップ識別子::文字列から作成する("甲".into()).expect("識別子");
    let mut クリップ =
        クリップ::既定値で作成する(識別子, クリップ名::作成する("甲".into()));
    クリップ.区間 = clip_domain::動画上の区間::作成する(秒(2.0), 秒(4.0)).expect("区間");
    クリップ.クロップ =
        クロップ範囲::各値を範囲へ収めて作成する(10.0, 10.0, 50.0, 50.0);
    let 並び = クリップスタック::一覧から作成する(vec![クリップ.clone()]).expect("スタック");
    let 経過 = 時間の長さ::作成する(1.5).expect("長さ");
    let 求め = 表示するコマの求め::求める(&並び, 再生位置::単独クリップ再生(経過)).expect("求め");
    assert_eq!(求め.動画上の位置, 秒(3.5));
    assert_eq!(求め.区間, Some(クリップ.区間));
    assert_eq!(求め.クロップ, クリップ.クロップ);
    let 元動画 = 表示するコマの求め::求める(&並び, 再生位置::元動画再生(秒(7.0))).expect("求め");
    assert_eq!(元動画.区間, None);
    assert_eq!(元動画.クロップ, クロップ範囲::全体);
}

#[test]
fn 倉庫の知らない札と捨てたは依頼し直せる結末へ写す() {
    let 写し = 状況の写し::依頼の状況から写す(&依頼の状況::知らない札);
    assert_eq!(写し, 状況の写し::終わった(依頼の結末::倉庫が覚えていない));
    let 写し = 状況の写し::依頼の状況から写す(&依頼の状況::捨てた);
    assert!(matches!(写し, 状況の写し::終わった(結末) if 結末.順が変わったら依頼し直すか()));
}
