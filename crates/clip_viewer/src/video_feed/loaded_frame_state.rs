//! 載せたコマの状態。コマの載せ先が今コマを載せているか、載せているならそのコマの出どころ(溜めたコマか流し読みか)を表す。
//! あわせて、コマの載せ先へ1回コマを求めた結果としてテクスチャへ載せたか(`コマを載せたか`)を表す。

use clip_domain::動画上の区間;
use sengen_egui::画素の並びの不正;

use super::frame_request::コマの出どころ;

/// 載せたコマの状態とは、コマの載せ先が今コマを載せていないか、区間の溜めたコマを載せているか、流し読みのコマを載せているか
/// (求めた位置のコマをまだ待っているか)の区別のことである。待っているかを流し読みの選択肢の中に持つため、
/// 溜めたコマを載せているのに流し読みのコマを待っている、という組は表せない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 載せたコマの状態 {
    載せていない,
    溜めたコマ(動画上の区間),
    流し読み { コマを待っている: bool },
}

impl 載せたコマの状態 {
    /// スタックの作業場の画面が出す、倉庫の溜めたコマか流し読みかの区別へ写す。載せていない(開いた直後と `コマの載せ先::流し読みを閉じる` の後)は、
    /// 最初のコマを流し読みで待つため流し読みとして写す。前提: スタックの作業場は `コマの載せ先::流し読みを閉じる` を呼ばないため、載せていないのは開いた直後だけである。
    pub(crate) fn コマの出どころへ写す(self) -> コマの出どころ {
        match self {
            Self::溜めたコマ(区間) => コマの出どころ::溜めたコマ(区間),
            Self::流し読み { .. } | Self::載せていない => {
                コマの出どころ::流し読み
            }
        }
    }
}

/// コマを載せたかとは、コマの載せ先へ1回コマを求めたときに、求めた動画のコマをテクスチャへ載せたか、載せなかったかの区別のことである。
/// 前に載せたコマと番号と寸法が同じで載せ直さなかったときも、テクスチャにはそのコマが載っているため載せたとする。
/// 重ね合わせの供給が、行のテクスチャに今載っているコマがどの置いたクリップのコマかを覚えるために使う。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum コマを載せたか {
    載せた,
    載せなかった,
}

impl コマを載せたか {
    /// テクスチャへ載せた結果から求める。載せられなかったときは載せなかったとする。
    pub(super) fn テクスチャへ載せた結果から(
        結果: &Result<(), 画素の並びの不正>,
    ) -> Self {
        match 結果 {
            Ok(()) => Self::載せた,
            Err(_) => Self::載せなかった,
        }
    }
}
