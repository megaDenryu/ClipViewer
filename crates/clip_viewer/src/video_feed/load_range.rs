//! 載せるコマの範囲。コマの載せ先が、流し読みの出したコマのうちどれをテクスチャへ載せるかを決める。参照: _doc/設計/同時再生.md 5-2 の7

use video_source::{コマの速さ, 動画上のコマ番号};

use super::frame_request::表示するコマの求め;

/// 載せるコマの範囲とは、コマの載せ先が流し読みの出したコマをどれでも載せるか、求めの区間の中のコマだけを載せるかの区別のことである。
/// スタックの作業場はどのコマも載せる(区間の継ぎ目で読み進める間のコマも映す今の振る舞い)。重ね合わせの行は求めの区間の中だけを載せる。
/// 流し読みを開き直さずに次の置いたクリップへ続く継ぎ目で、2つの区間の間にあるどちらの区間にも入らないコマを載せず、
/// 前の置いたクリップの最後のコマを残すためである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 載せるコマの範囲 {
    どのコマも,
    求めの区間の中だけ,
}

impl 載せるコマの範囲 {
    /// 求めに対して番号のコマをテクスチャへ載せてよいか。
    pub(super) fn 載せてよいか(
        self,
        求め: &表示するコマの求め,
        番号: 動画上のコマ番号,
        速さ: コマの速さ,
    ) -> bool {
        match self {
            Self::どのコマも => true,
            Self::求めの区間の中だけ => 求め.区間の中のコマか(番号, 速さ),
        }
    }
}
