//! コマを載せたか。コマの載せ先へ1回コマを求めた結果として、テクスチャへコマを載せたかを表す。

use video_source::動画上のコマ番号;

/// コマを載せたかとは、コマの載せ先へ1回コマを求めたときに、テクスチャへコマを載せたならその番号、載せなかったならそのことの区別のことである。
/// 前に載せたコマと番号と寸法が同じで載せ直さなかったときも、テクスチャにはそのコマが載っているため載せたとする。
/// 重ね合わせの供給が、行のテクスチャに今載っているコマがどの置いたクリップのコマかを覚えるために使う。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum コマを載せたか {
    載せた(動画上のコマ番号),
    載せなかった,
}
