//! 溜めたコマの経路の区間の終わりの結合試験。区間を溜め終えた後、区間の終わりちょうど(末尾で止めたとき)とそれより後ろの位置でも、
//! 流し読みを開かずに、溜めたコマから区間の中の最後のコマを載せることを確かめる。流し読みの経路の同じ規則は `with_ffmpeg_stream_tests.rs` が確かめる。
//! 後ろの位置は、テクスチャに前のコマが残って通ってしまわないよう、区間の中の別の位置を載せて番号が変わったのを見てから載せる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::動画上の区間;

use super::frame_request::コマの出どころ;
use super::prefetch_order::先読みの並び;
use super::with_ffmpeg_support::{成り立つまで待つ, 求め, 秒, 試験の動画};
use crate::stream_rules::流し読みの開き直し;

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 溜め終えた区間の終わりちょうどとそれより後ろは_溜めたコマから区間の中の最後のコマを載せる() {
    let mut 試験 = 試験の動画::作って開く("溜めたコマの末尾");
    let 動画 = &mut 試験.動画;
    let 区間 = 動画上の区間::作成する(秒(1.0), 秒(2.0)).expect("区間");
    let 並び = 先読みの並び::区間の列から作る(vec![区間]);
    成り立つまで待つ("区間を溜め終えること", || {
        動画.先読みを整える(&並び, Instant::now());
        動画.台帳().溜め終えたか(&区間)
    });
    let mut 溜めたコマで載せる = |位置: f64| {
        動画.コマを載せる(
            &求め(位置, Some(区間)),
            流し読みの開き直し::してよい,
            Instant::now(),
        );
        assert_eq!(動画.出どころ(), コマの出どころ::溜めたコマ(区間));
        assert!(
            !動画.流し読みを開いているか(),
            "溜めたコマで載せる間は流し読みを開かない"
        );
        動画
            .映像()
            .載せたコマ()
            .map(|載せたコマ| 載せたコマ.番号.値())
    };
    assert_eq!(
        溜めたコマで載せる(2.0),
        Some(59),
        "区間の終わりちょうどで、区間の外の60番(2.0秒から表示するコマ)を出さない"
    );
    assert!(
        matches!(溜めたコマで載せる(1.5), Some(44..=45)),
        "区間の中の別の位置では番号が変わる"
    );
    assert_eq!(
        溜めたコマで載せる(2.5),
        Some(59),
        "区間の終わりより後ろでも、取り出した最後のコマを載せ直す"
    );
    assert!(動画.映せない理由().is_none());
}
