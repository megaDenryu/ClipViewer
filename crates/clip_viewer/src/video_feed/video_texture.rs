//! 映像のテクスチャ。表示するコマを載せる GPU のテクスチャと、今載っているコマの番号と寸法と、最後に載せられなかった理由を持つ。
//! スタックの作業場の読み込んだ動画と、重ね合わせの作業場の行ごとのコマの載せ先が、テクスチャの名前だけを変えて共に使う。

use eframe::egui;
use sengen_egui::{
    差し替えられるテクスチャ, 拡大縮小の仕方, 画素の並び, 画素の並びの不正, 画素数の寸法,
};
use video_source::{コマ, 動画上のコマ番号};

use super::frame_loaded::コマを載せたか;
use super::texture_key::載せたコマの番号と寸法;

/// 最初のコマが届くまで載せておく1画素の黒。
const 黒の一画素: [u8; 4] = [0, 0, 0, 255];

/// テクスチャの名前とは、egui へテクスチャを登録するときに添える、どの画面のテクスチャかを見分けるための名前のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub(crate) struct テクスチャの名前(&'static str);

impl テクスチャの名前 {
    pub(crate) const fn 作成する(名前: &'static str) -> Self {
        Self(名前)
    }
}

/// 映像のテクスチャとは、表示するコマを載せるテクスチャと、今載っているコマの番号と寸法(まだ載せていなければ無い)と、
/// 最後にコマを載せようとして載せられなかった理由(載せられたなら無い)の組のことである。
pub(crate) struct 映像のテクスチャ {
    テクスチャ: 差し替えられるテクスチャ,
    載せたコマ: Option<載せたコマの番号と寸法>,
    載せられない理由: Option<String>,
}

impl 映像のテクスチャ {
    /// 1画素の黒を載せて、名前を添えて登録する。動画のコマは写真に近いため、隣の画素と混ぜて拡大縮小する。
    pub(crate) fn 登録して作る(
        画面描画の共有状態: &egui::Context,
        名前: テクスチャの名前,
    ) -> Result<Self, 画素の並びの不正> {
        let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
            画素数の寸法::生成する(1, 1),
            &黒の一画素,
        )?;
        let テクスチャ = 差し替えられるテクスチャ::登録して作る(
            画面描画の共有状態,
            名前.0,
            画素,
            拡大縮小の仕方::隣の画素と混ぜる,
        );
        Ok(Self {
            テクスチャ,
            載せたコマ: None,
            載せられない理由: None,
        })
    }

    pub(crate) fn テクスチャ(&self) -> &差し替えられるテクスチャ {
        &self.テクスチャ
    }

    /// まだ動画のコマを1つも載せていないか。
    pub(crate) fn まだ映していないか(&self) -> bool {
        self.載せたコマ.is_none()
    }

    /// 今載っているコマの番号と寸法。結合試験で、流し読みのコマが載ったことを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 載せたコマ(&self) -> Option<載せたコマの番号と寸法> {
        self.載せたコマ
    }

    /// 最後にコマを載せようとして載せられなかった理由。黙って捨てないため、画面が映せない理由として出す。
    pub(crate) fn 載せられない理由(&self) -> Option<&str> {
        self.載せられない理由.as_deref()
    }

    /// コマを載せ、載せたか(載せたならその番号)を返す。載せられなければ、その理由を覚えて載せなかったと返す。
    /// 前に載せたコマと番号と寸法が同じなら載せ直さないが、そのコマは載っているため載せたと返す。
    pub(crate) fn コマを載せる(
        &mut self,
        番号: 動画上のコマ番号,
        コマ: &コマ,
    ) -> コマを載せたか {
        match self.画素を差し替える(番号, コマ) {
            Ok(()) => {
                self.載せられない理由 = None;
                コマを載せたか::載せた(番号)
            }
            Err(不正) => {
                self.載せられない理由 = Some(不正.to_string());
                コマを載せたか::載せなかった
            }
        }
    }

    fn 画素を差し替える(
        &mut self,
        番号: 動画上のコマ番号,
        コマ: &コマ,
    ) -> Result<(), 画素の並びの不正> {
        let 今のコマ = 載せたコマの番号と寸法 {
            番号,
            寸法: コマ.寸法(),
        };
        if !今のコマ.載せ直すか(self.載せたコマ) {
            return Ok(());
        }
        let 寸法 = 画素数の寸法::生成する(コマ.寸法().幅(), コマ.寸法().高さ());
        let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
            寸法,
            コマ.画素の並び(),
        )?;
        self.テクスチャ.差し替える(画素);
        self.載せたコマ = Some(今のコマ);
        Ok(())
    }
}
