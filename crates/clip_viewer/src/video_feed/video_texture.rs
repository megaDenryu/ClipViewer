//! 映像のテクスチャ。表示するコマを載せる GPU のテクスチャと、今載っているコマの番号と寸法を持つ。

use eframe::egui;
use sengen_egui::{
    差し替えられるテクスチャ, 拡大縮小の仕方, 画素の並び, 画素の並びの不正, 画素数の寸法,
};
use video_source::{コマ, 動画上のコマ番号};

use super::texture_key::載せたコマの番号と寸法;

/// 最初のコマが届くまで載せておく1画素の黒。
const 黒の一画素: [u8; 4] = [0, 0, 0, 255];

/// 映像のテクスチャとは、表示するコマを載せるテクスチャと、今載っているコマの番号と寸法(まだ載せていなければ無い)の組のことである。
pub(crate) struct 映像のテクスチャ {
    テクスチャ: 差し替えられるテクスチャ,
    載せたコマ: Option<載せたコマの番号と寸法>,
}

impl 映像のテクスチャ {
    /// 1画素の黒を載せて登録する。動画のコマは写真に近いため、隣の画素と混ぜて拡大縮小する。
    pub(crate) fn 登録して作る(
        eguiの本体: &egui::Context,
    ) -> Result<Self, 画素の並びの不正> {
        let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
            画素数の寸法::生成する(1, 1),
            &黒の一画素,
        )?;
        let テクスチャ = 差し替えられるテクスチャ::登録して作る(
            eguiの本体,
            "ClipViewer の映像",
            画素,
            拡大縮小の仕方::隣の画素と混ぜる,
        );
        Ok(Self {
            テクスチャ,
            載せたコマ: None,
        })
    }

    pub(crate) fn テクスチャ(&self) -> &差し替えられるテクスチャ {
        &self.テクスチャ
    }

    /// まだ動画のコマを1つも載せていないか。
    pub(crate) fn まだ映していないか(&self) -> bool {
        self.載せたコマ.is_none()
    }

    /// 今載っているコマの番号と寸法。結合試験で、流し読みのコマが載ったことを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 載せたコマ(&self) -> Option<載せたコマの番号と寸法> {
        self.載せたコマ
    }

    /// コマを載せる。前に載せたコマと番号と寸法が同じなら載せ直さない。
    pub(crate) fn コマを載せる(
        &mut self,
        番号: 動画上のコマ番号,
        コマ: &コマ,
    ) -> Result<(), 画素の並びの不正> {
        let 今のコマ = 載せたコマの番号と寸法 {
            番号,
            寸法: コマ.寸法(),
        };
        if !今のコマ.載せ直すか(self.載せたコマ) {
            return Ok(());
        }
        let 寸法 = 画素数の寸法::生成する(コマ.寸法().幅(), コマ.寸法().高さ());
        let 画素 = 画素の並び::赤緑青と不透明度のバイト列から作る(
            寸法,
            コマ.画素の並び(),
        )?;
        self.テクスチャ.差し替える(画素);
        self.載せたコマ = Some(今のコマ);
        Ok(())
    }
}
