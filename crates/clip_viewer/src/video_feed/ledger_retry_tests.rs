//! 依頼の台帳が、終わった依頼を並びの順が変わったときに依頼し直すかの試験。
#![allow(clippy::expect_used)]

use std::time::Instant;

use super::ledger::依頼の台帳;
use super::ledger_test_support::{区間, 落ち着いた後};
use video_source::{バイト数, メモリの上限, 受け付けない理由};

use super::ledger_state::{依頼の結末, 状況の写し};

#[test]
fn 失敗と上限を超える区間は順が変わっても依頼し直さない() {
    let mut 台帳 = 依頼の台帳::<u32>::空();
    let (甲, 乙) = (区間(0.0, 1.0), 区間(2.0, 3.0));
    let 始め = Instant::now();
    台帳.手順を決める(&[甲, 乙], 始め);
    台帳.依頼の結果を記録する(甲, Ok(1));
    台帳.状況を記録する(
        1,
        状況の写し::終わった(依頼の結末::失敗した("壊れた".into())),
    );
    let 上限 = 受け付けない理由::上限の全体を超える {
        見積もり: バイト数::作成する(10),
        上限: メモリの上限::作成する(バイト数::作成する(1)),
    };
    台帳.依頼の結果を記録する(乙, Err(上限));
    let 手順 = 台帳.手順を決める(&[乙, 甲], 落ち着いた後(始め));
    assert!(手順.渡す優先順.is_some());
    assert!(手順.依頼する区間.is_empty());
}

#[test]
fn 埋まっていた区間と倉庫が捨てた区間は順が変わると依頼し直す() {
    let mut 台帳 = 依頼の台帳::<u32>::空();
    let (甲, 乙) = (区間(0.0, 1.0), 区間(2.0, 3.0));
    let 始め = Instant::now();
    台帳.手順を決める(&[甲, 乙], 始め);
    let 埋まっている = 受け付けない理由::優先順の高い区間で埋まっている {
        見積もり: バイト数::作成する(10),
        作れる空き: バイト数::作成する(1),
    };
    台帳.依頼の結果を記録する(乙, Err(埋まっている));
    台帳.依頼の結果を記録する(甲, Ok(1));
    台帳.状況を記録する(1, 状況の写し::終わった(依頼の結末::倉庫が捨てた));
    let 同じ順 = 台帳.手順を決める(&[甲, 乙], 落ち着いた後(始め));
    assert!(同じ順.依頼する区間.is_empty());
    let 変えた順 = 台帳.手順を決める(&[乙, 甲], 落ち着いた後(始め));
    assert_eq!(変えた順.依頼する区間, vec![乙, 甲]);
}
