//! 流し読みを開き直さない継ぎ目の結合試験。区間の甲(0秒〜1秒)の0.9秒を載せた後、同じ流し読みのまま区間の乙(1.5秒〜2.5秒)の始まりを求めると、
//! 流し読みは2つの区間の間にあるどちらの区間にも入らないコマ(28番〜44番)を順に出す。求めの区間の中だけを載せる載せ先(重ね合わせの行)は
//! それを載せず、甲の最後のコマを残すことと、どのコマも載せる載せ先(スタックの作業場)は今のとおり載せることを確かめる(同時再生.md 5-2 の7)。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use clip_domain::動画上の区間;

use super::load_range::載せるコマの範囲;
use super::with_ffmpeg_loaded_support::試験動画の供給元と載せ先;
use super::with_ffmpeg_support::{成り立つまで待つ, 秒};

/// 乙の始まりの45番より前に載ったコマの番号のうち、甲の0.9秒のコマより後ろのもの(2つの区間の間のコマ)の並び。
fn 継ぎ目で載った間のコマの番号(
    範囲: 載せるコマの範囲, 名前: &str
) -> Vec<u32> {
    let mut 試験 = 試験動画の供給元と載せ先::試験動画を作って開く(名前, 範囲);
    let 甲 = 動画上の区間::作成する(秒(0.0), 秒(1.0)).expect("区間");
    let 乙 = 動画上の区間::作成する(秒(1.5), 秒(2.5)).expect("区間");
    let 載せた番号 = |試験: &試験動画の供給元と載せ先| {
        試験
            .載せ先
            .テクスチャ()
            .載せたコマ()
            .map(|載せたコマ| 載せたコマ.番号.値())
    };
    成り立つまで待つ("甲の0.9秒のコマが載ること", || {
        試験.区間の位置のコマを載せる(0.9, Some(甲));
        載せた番号(&試験).is_some_and(|番号| (25..=27).contains(&番号))
    });
    let 甲の番号 = 載せた番号(&試験).expect("甲のコマ");
    let mut 間のコマ = Vec::new();
    成り立つまで待つ("乙の始まりのコマが載ること", || {
        試験.区間の位置のコマを載せる(1.5, Some(乙));
        let 番号 = 載せた番号(&試験).expect("載っている");
        if 番号 > 甲の番号 && 番号 < 45 {
            間のコマ.push(番号);
        }
        番号 >= 45
    });
    間のコマ
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 求めの区間の中だけを載せる載せ先は_継ぎ目で2つの区間の間のコマを載せず甲の最後のコマを残す() {
    assert_eq!(
        継ぎ目で載った間のコマの番号(
            載せるコマの範囲::求めの区間の中だけ,
            "継ぎ目_区間の中"
        ),
        Vec::<u32>::new()
    );
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn どのコマも載せる載せ先は_継ぎ目で2つの区間の間のコマも載せる() {
    assert!(
        !継ぎ目で載った間のコマの番号(
            載せるコマの範囲::どのコマも,
            "継ぎ目_どのコマも"
        )
        .is_empty(),
        "流し読みの通り道は4コマ分しか先に読まないため、乙を求めた最初のフレームで間のコマを出す"
    );
}
