//! 流し読みを開き直さない継ぎ目の結合試験。区間の甲(0秒〜1秒)の0.9秒を載せた後、同じ流し読みのまま区間の乙(1.5秒〜2.5秒)を、
//! 甲の0.9秒のコマの次のコマから乙の始まりのコマ(45番)まで1コマずつ求める。1コマずつ求め、流し読みがその位置のコマを出すまで待つため、
//! 裏のスレッドの速さによらず、流し読みは2つの区間の間にあるどちらの区間にも入らないコマを必ず1つずつ出す。求めの区間の中だけを
//! 載せる載せ先(重ね合わせの行)はそれを載せず、甲の最後のコマを残すことと、どのコマも載せる載せ先(スタックの作業場)は今のとおり
//! 載せることを確かめる(同時再生.md 5-2 の7)。FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ流す。
#![allow(clippy::expect_used)]

use clip_domain::動画上の区間;

use super::load_range::載せるコマの範囲;
use super::with_ffmpeg_loaded_support::試験動画の供給元と載せ先;
use super::with_ffmpeg_support::{成り立つまで待つ, 秒};

/// 乙の始まりのコマの番号(1.5秒、30コマ/秒)。
const 乙の始まりのコマ: u32 = 45;

fn 載せた番号(試験: &試験動画の供給元と載せ先) -> u32 {
    試験
        .載せ先
        .テクスチャ()
        .載せたコマ()
        .map(|載せたコマ| 載せたコマ.番号.値())
        .expect("載っている")
}

/// 甲の0.9秒のコマを載せた後、乙の区間の求めで、次のコマから乙の始まりのコマまで1コマずつ求め、求めたコマの番号と、
/// そのとき行のテクスチャに載っていたコマの番号の組を並べる。
fn 継ぎ目で載ったコマの並び(
    範囲: 載せるコマの範囲, 名前: &str
) -> Vec<(u32, u32)> {
    let mut 試験 = 試験動画の供給元と載せ先::試験動画を作って開く(名前, 範囲);
    let 甲 = 動画上の区間::作成する(秒(0.0), 秒(1.0)).expect("区間");
    let 乙 = 動画上の区間::作成する(秒(1.5), 秒(2.5)).expect("区間");
    成り立つまで待つ("甲の0.9秒のコマが載ること", || {
        試験.区間の位置のコマを載せる(0.9, Some(甲));
        !試験.載せ先.コマを待っているか()
    });
    let 甲の番号 = 載せた番号(&試験);
    ((甲の番号 + 1)..=乙の始まりのコマ)
        .map(|求めたコマ| {
            let 真ん中 = (f64::from(求めたコマ) + 0.5) / 30.0;
            成り立つまで待つ("求めたコマを流し読みが出すこと", || {
                試験.区間の位置のコマを載せる(真ん中, Some(乙));
                !試験.載せ先.コマを待っているか()
            });
            (求めたコマ, 載せた番号(&試験))
        })
        .collect()
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 求めの区間の中だけを載せる載せ先は_継ぎ目で2つの区間の間のコマを載せず甲の最後のコマを残す() {
    let 並び = 継ぎ目で載ったコマの並び(
        載せるコマの範囲::求めの区間の中だけ,
        "継ぎ目_区間の中",
    );
    let (甲の次, _) = *並び.first().expect("間のコマがある");
    for (求めたコマ, 載っていたコマ) in 並び {
        let 期待 = if 求めたコマ < 乙の始まりのコマ {
            甲の次 - 1
        } else {
            乙の始まりのコマ
        };
        assert_eq!(載っていたコマ, 期待, "{求めたコマ}番を求めたとき");
    }
}

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn どのコマも載せる載せ先は_継ぎ目で2つの区間の間のコマも載せる() {
    for (求めたコマ, 載っていたコマ) in
        継ぎ目で載ったコマの並び(載せるコマの範囲::どのコマも, "継ぎ目_どのコマも")
    {
        assert_eq!(載っていたコマ, 求めたコマ);
    }
}
