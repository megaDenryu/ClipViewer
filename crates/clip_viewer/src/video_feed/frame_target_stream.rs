//! 流し読みからの載せ方。コマの載せ先が溜めたコマで映せない間、流し読みを必要なときだけ開き直して、その時刻に出すコマをテクスチャへ載せる。
//! 開き直しの規則(開き直すかの判断・最短の間隔)は `stream_rules` を載せ先ごとに当て、重ね合わせの8行が同時に ffmpeg を起動し直し続けないようにする。
//! 参照: _doc/設計/画面.md 判断5、_doc/設計/同時再生.md 5-4

use std::time::Instant;

use clip_domain::動画上の秒;
use video_source::{動画の情報, 流し読みの状態};

use super::frame_loaded::コマを載せたか;
use super::frame_request::表示するコマの求め;
use super::frame_source::動画のコマの供給元;
use super::frame_target::コマの載せ先;
use super::loaded_frame_state::載せたコマの状態;
use crate::stream_rules::{流し読みの開き直し, 開き直しの最短の間隔};

impl コマの載せ先 {
    /// 流し読みのコマを載せ、載せたかを返す。開き直しを控える間は、位置を覚えずに今のコマのままにする(控えを解いた次のフレームで開き直すため)。
    /// 開き直してよいのに最短の間隔を守れない間と、求める位置のコマがまだ届いていない間は、コマを待っているとする。
    pub(super) fn 流し読みのコマを載せる(
        &mut self,
        供給元: &動画のコマの供給元,
        求め: &表示するコマの求め,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) -> コマを載せたか {
        let 位置 = 求め.流し読みで求める位置(供給元.情報().コマの速さ());
        let 開き直すか = self
            .流し読み
            .as_ref()
            .is_none_or(|流し読み| 流し読み.この位置で開き直すか(位置));
        if 開き直すか {
            let 間隔を守ったか = self.流し読み.as_ref().is_none_or(|流し読み| {
                流し読み.開いてからの経過(今) >= 開き直しの最短の間隔
            });
            if 開き直し == 流し読みの開き直し::控える || !間隔を守ったか {
                self.載せたコマの状態 = 載せたコマの状態::流し読み {
                    コマを待っている: 開き直し == 流し読みの開き直し::してよい,
                };
                return コマを載せたか::載せなかった;
            }
            self.流し読み = Some(供給元.流し読みを開く(位置, 今));
        }
        let 載せた結果 = self.求めた位置のコマを載せる(供給元.情報(), 位置);
        self.載せたコマの状態 = 載せたコマの状態::流し読み {
            コマを待っている: 載せた結果.コマを待っている,
        };
        載せた結果.載せたか
    }

    /// 求めた位置のコマを載せ、載せたかと、求める位置のコマがまだ届いていないか(読んでいる間だけ)を返す。読めない流し読みなら待たない。
    /// 読み終えるか失敗して出すコマが無いときも待たないが、テクスチャには何も載せていないため載せなかったと返す。
    fn 求めた位置のコマを載せる(
        &mut self,
        情報: &動画の情報,
        位置: 動画上の秒,
    ) -> 流し読みから載せた結果 {
        let 目当ての番号 = 情報.コマの速さ().時刻を含むコマ番号(位置);
        let Some(流し読み) = self.流し読み.as_mut().and_then(|開いた| {
            開いた.求めた位置を覚え途中の失敗を写して中身を貸す(位置)
        }) else {
            return 流し読みから載せた結果 {
                載せたか: コマを載せたか::載せなかった,
                コマを待っている: false,
            };
        };
        let (出した番号, 載せたか) = match 流し読み.その時刻に出すコマ(位置) {
            Some(コマ) => (
                Some(コマ.番号()),
                self.テクスチャ.コマを載せる(コマ.番号(), コマ.コマ()),
            ),
            None => (None, コマを載せたか::載せなかった),
        };
        let 読んでいる = matches!(流し読み.状態(), 流し読みの状態::読んでいる);
        流し読みから載せた結果 {
            載せたか,
            コマを待っている: 読んでいる
                && 出した番号.is_none_or(|番号| 番号 < 目当ての番号),
        }
    }
}

/// 流し読みから載せた結果とは、流し読みのコマをテクスチャへ載せたかと、求める位置のコマがまだ届いていないかの組のことである。
struct 流し読みから載せた結果 {
    載せたか: コマを載せたか,
    コマを待っている: bool,
}
