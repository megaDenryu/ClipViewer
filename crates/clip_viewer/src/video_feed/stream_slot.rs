//! 映像の開いた流し読み。流し読みの規則の開き直しを判断できる流し読みに、映像の流し読みを入れたものであり、開く口と、途中の失敗の問い合わせ方を持つ。

use std::time::Instant;

use clip_domain::動画上の秒;
use video_source::{
    動画の情報, 動画の読み手, 流し読み, 流し読みの状態, 長辺の上限
};

use crate::stream_rules::{流し読みの中身, 開き直しを判断できる流し読み};

/// 開いた流し読みとは、ある位置で開いた、開き直しを判断できる映像の流し読みのことである。
pub(crate) type 開いた流し読み = 開き直しを判断できる流し読み<流し読み>;

impl 流し読みの中身 for 流し読み {
    fn 途中の失敗(&mut self) -> Option<String> {
        match self.状態() {
            流し読みの状態::失敗(失敗) => Some(失敗.to_string()),
            流し読みの状態::読んでいる | 流し読みの状態::終わりまで読んだ => {
                None
            }
        }
    }

    fn 終わりまで読んだか(&mut self) -> bool {
        matches!(self.状態(), 流し読みの状態::終わりまで読んだ)
    }
}

impl 開いた流し読み {
    /// 位置から映像の流し読みを開く。開けなければ、その理由を持った読めない流し読みになる。
    pub(crate) fn 開く(
        読み手: &動画の読み手,
        動画: &動画の情報,
        位置: 動画上の秒,
        上限: 長辺の上限,
        今: Instant,
    ) -> Self {
        Self::開いた結果から作る(読み手.流し読みを開く(動画, 位置, 上限), 位置, 今)
    }
}
