//! 映像の開いた流し読み。流し読みの規則の開き直しを判断できる流し読みに、映像の流し読みを入れたものであり、途中の失敗の問い合わせ方を持つ。
//! 開く口は、読み手と動画の情報を持つ動画のコマの供給元(`動画のコマの供給元::流し読みを開く`)が持つ。

use video_source::{流し読み, 流し読みの状態};

use crate::stream_rules::{流し読みの中身, 開き直しを判断できる流し読み};

/// 開いた流し読みとは、ある位置で開いた、開き直しを判断できる映像の流し読みのことである。
pub(crate) type 開いた流し読み = 開き直しを判断できる流し読み<流し読み>;

impl 流し読みの中身 for 流し読み {
    fn 途中の失敗(&mut self) -> Option<String> {
        match self.状態() {
            流し読みの状態::失敗(失敗) => Some(失敗.to_string()),
            流し読みの状態::読んでいる | 流し読みの状態::終わりまで読んだ => {
                None
            }
        }
    }

    fn 終わりまで読んだか(&mut self) -> bool {
        matches!(self.状態(), 流し読みの状態::終わりまで読んだ)
    }
}
