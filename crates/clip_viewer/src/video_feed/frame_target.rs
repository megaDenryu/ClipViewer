//! コマの載せ先。表示するコマを、区間を溜め終えていれば動画のコマの供給元の倉庫から、そうでなければ載せ先の流し読みから取り出して
//! 映像のテクスチャへ載せる。スタックの作業場の読み込んだ動画が1つ持ち、重ね合わせの作業場はタイムラインの行ごとに1つ持つ
//! (1つの行は同時に高々1つの置いたクリップを映すため)。参照: _doc/設計/画面.md 判断2〜判断5、_doc/設計/同時再生.md 3-3・5-1・5-2

use std::time::Instant;

use clip_domain::{動画上の区間, 動画上の秒};
use eframe::egui;
use sengen_egui::画素の並びの不正;

use super::frame_loaded::コマを載せたか;
use super::frame_request::表示するコマの求め;
use super::frame_source::動画のコマの供給元;
use super::loaded_frame_state::載せたコマの状態;
use super::stream_slot::開いた流し読み;
use super::video_texture::{テクスチャの名前, 映像のテクスチャ};
use crate::stream_rules::流し読みの開き直し;

/// コマの載せ先とは、表示するコマを載せる映像のテクスチャと、溜めたコマで映せない間だけ開く流し読みと、載せたコマの状態の組のことである。
/// どの動画のコマを載せるかは持たず、載せるたびに動画のコマの供給元を渡される。
pub(crate) struct コマの載せ先 {
    pub(super) 流し読み: Option<開いた流し読み>,
    pub(super) テクスチャ: 映像のテクスチャ,
    pub(super) 載せたコマの状態: 載せたコマの状態,
}

impl コマの載せ先 {
    /// 名前を添えてテクスチャを登録して作る。まだコマを載せていない。
    pub(crate) fn 登録して作る(
        画面描画の共有状態: &egui::Context,
        名前: テクスチャの名前,
    ) -> Result<Self, 画素の並びの不正> {
        Ok(Self {
            流し読み: None,
            テクスチャ: 映像のテクスチャ::登録して作る(
                画面描画の共有状態,
                名前,
            )?,
            載せたコマの状態: 載せたコマの状態::載せていない,
        })
    }

    /// 何も映さない間(重ね合わせの置いたクリップの間の隙間など)と、作業場を控えるときは、流し読みを閉じて ffmpeg を止め、載せたコマの状態を
    /// 載せていないへ戻す。テクスチャは作り直さないため、前に載せたコマが残る。
    pub(crate) fn 流し読みを閉じる(&mut self) {
        self.流し読み = None;
        self.載せたコマの状態 = 載せたコマの状態::載せていない;
    }

    /// 表示するコマを、区間を溜め終えていれば供給元の倉庫から、そうでなければ流し読みから取り出してテクスチャへ載せ、載せたかを返す。
    pub(crate) fn コマを載せる(
        &mut self,
        供給元: &mut 動画のコマの供給元,
        求め: &表示するコマの求め,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) -> コマを載せたか {
        match 求め.区間 {
            Some(区間) if 供給元.台帳().溜め終えたか(&区間) => {
                self.流し読み = None;
                self.載せたコマの状態 = 載せたコマの状態::溜めたコマ(区間);
                self.溜めたコマを載せる(供給元, &区間, 求め.動画上の位置)
            }
            _ => self.流し読みのコマを載せる(供給元, 求め, 開き直し, 今),
        }
    }

    /// 流し読みを開いているか。結合試験で、溜めたコマで載せる間と、何も映さない間と控えた間に流し読みを閉じたことを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 流し読みを開いているか(&self) -> bool {
        self.流し読み.is_some()
    }

    /// 溜めたコマを載せる。台帳が溜め終えたとする区間は、このフレームの `先読みを整える` の終わりに倉庫へ問い合わせた状況であり、
    /// 倉庫は溜めた区間を画面のスレッドの操作(破棄・取り消し・空きを作る)でしか外さず、溜めた区間は1つ以上のコマを持つため、
    /// 取り出しが無いことは起きない。起きたときも載せなかったと返し、前のコマを載せたことにはしない。
    fn 溜めたコマを載せる(
        &mut self,
        供給元: &mut 動画のコマの供給元,
        区間: &動画上の区間,
        位置: 動画上の秒,
    ) -> コマを載せたか {
        match 供給元.溜めたコマを取り出す(区間, 位置) {
            Some(コマ) => self.テクスチャ.コマを載せる(コマ.番号(), コマ.コマ()),
            None => コマを載せたか::載せなかった,
        }
    }
}
