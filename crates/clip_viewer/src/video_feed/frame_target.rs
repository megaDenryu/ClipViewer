//! コマの載せ先。表示するコマを、区間を溜め終えていれば動画のコマの供給元の倉庫から、そうでなければ載せ先の流し読みから取り出して
//! 映像のテクスチャへ載せる。スタックの作業場の読み込んだ動画が1つ持ち、重ね合わせの作業場はタイムラインの行ごとに1つ持つ
//! (1つの行は同時に高々1つの置いたクリップを映すため)。参照: _doc/設計/画面.md 判断2〜判断5、_doc/設計/同時再生.md 3-3・5-1・5-2

use std::time::Instant;

use clip_domain::{動画上の区間, 動画上の秒};
use eframe::egui;
use sengen_egui::画素の並びの不正;

use super::frame_request::表示するコマの求め;
use super::frame_source::動画のコマの供給元;
use super::loaded_frame_source::載せているコマの出どころ;
use super::stream_slot::開いた流し読み;
use super::video_texture::{テクスチャの名前, 映像のテクスチャ};
use crate::stream_rules::流し読みの開き直し;

/// コマの載せ先とは、表示するコマを載せる映像のテクスチャと、溜めたコマで映せない間だけ開く流し読みと、載せているコマの出どころと、
/// テクスチャへ載せられなかった理由の組のことである。どの動画のコマを載せるかは持たず、載せるたびに動画のコマの供給元を渡される。
pub(crate) struct コマの載せ先 {
    pub(super) 流し読み: Option<開いた流し読み>,
    pub(super) テクスチャ: 映像のテクスチャ,
    pub(super) 載せているコマの出どころ: 載せているコマの出どころ,
    pub(super) 載せられない理由: Option<String>,
}

impl コマの載せ先 {
    /// 名前を添えてテクスチャを登録して作る。まだコマを載せていない。
    pub(crate) fn 登録して作る(
        画面描画の共有状態: &egui::Context,
        名前: テクスチャの名前,
    ) -> Result<Self, 画素の並びの不正> {
        Ok(Self {
            流し読み: None,
            テクスチャ: 映像のテクスチャ::登録して作る(
                画面描画の共有状態,
                名前,
            )?,
            載せているコマの出どころ:
                載せているコマの出どころ::載せていない,
            載せられない理由: None,
        })
    }

    /// 何も映さない間(重ね合わせの置いたクリップの間の隙間など)と、作業場を控えるときは、流し読みを閉じて ffmpeg を止める。
    /// テクスチャは作り直さないため、前に載せたコマが残る。
    pub(crate) fn 映すのをやめる(&mut self) {
        self.流し読み = None;
        self.載せているコマの出どころ = 載せているコマの出どころ::載せていない;
    }

    /// 表示するコマを、区間を溜め終えていれば供給元の倉庫から、そうでなければ流し読みから取り出してテクスチャへ載せる。
    pub(crate) fn コマを載せる(
        &mut self,
        供給元: &mut 動画のコマの供給元,
        求め: &表示するコマの求め,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        match 求め.区間 {
            Some(区間) if 供給元.台帳().溜め終えたか(&区間) => {
                self.流し読み = None;
                self.載せているコマの出どころ =
                    載せているコマの出どころ::溜めたコマ(区間);
                self.溜めたコマを載せる(供給元, &区間, 求め.動画上の位置);
            }
            _ => self.流し読みのコマを載せる(供給元, 求め, 開き直し, 今),
        }
    }

    /// 流し読みを開いているか。結合試験で、溜めたコマで載せる間と、何も映さない間と控えた間に流し読みを閉じたことを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 流し読みを開いているか(&self) -> bool {
        self.流し読み.is_some()
    }

    fn 溜めたコマを載せる(
        &mut self,
        供給元: &mut 動画のコマの供給元,
        区間: &動画上の区間,
        位置: 動画上の秒,
    ) {
        let Some(コマ) = 供給元.溜めたコマを取り出す(区間, 位置) else {
            return;
        };
        let 結果 = self.テクスチャ.コマを載せる(コマ.番号(), コマ.コマ());
        self.載せられない理由 = 結果.err().map(|不正| 不正.to_string());
    }
}
