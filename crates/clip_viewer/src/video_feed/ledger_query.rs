//! 依頼の台帳への問い合わせ。画面と映像の供給が、区間を溜め終えたかや、溜めている途中の依頼があるかを尋ねる口。

use clip_domain::動画上の区間;

use super::ledger::依頼の台帳;
use super::ledger_state::{依頼の進み具合, 行の状態};

impl<札> 依頼の台帳<札> {
    /// 区間を溜め終えたか。
    pub(crate) fn 溜め終えたか(&self, 区間: &動画上の区間) -> bool {
        self.行の状態(区間).is_some_and(|状態| {
            matches!(
                状態,
                行の状態::依頼中 {
                    進み具合: 依頼の進み具合::溜め終えた(_),
                    ..
                }
            )
        })
    }

    /// 処理を待っているか溜めている途中の依頼があるか。画面は、この間は入力が無くても描き直して進み具合を出す。
    pub(crate) fn 溜めている途中か(&self) -> bool {
        self.行.iter().any(|行| {
            matches!(
                行.状態,
                行の状態::依頼中 {
                    進み具合: 依頼の進み具合::処理を待っている
                        | 依頼の進み具合::溜めている { .. },
                    ..
                }
            )
        })
    }

    /// 区間の行の状態。台帳に無ければ無い。
    pub(crate) fn 行の状態(&self, 区間: &動画上の区間) -> Option<&行の状態<札>> {
        self.行
            .iter()
            .find(|行| 行.区間 == *区間)
            .map(|行| &行.状態)
    }

    pub(crate) fn 行の位置(&self, 区間: &動画上の区間) -> Option<usize> {
        self.行.iter().position(|行| 行.区間 == *区間)
    }

    /// 区間の集まりが落ち着くのを待って、まだ依頼を出していない区間があるか。
    /// 画面は、この間も入力が無くても描き直して、落ち着いた後の依頼を出す。
    pub(crate) fn 依頼を出すのを待っているか(&self) -> bool {
        self.依頼を待っている
    }
}
