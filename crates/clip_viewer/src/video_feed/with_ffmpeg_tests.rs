//! 映像の供給の結合試験。先読みで区間を溜め終えた後は、区間の繰り返しの継ぎ目でも溜めたコマから載せる
//! (流し読みを開き直さない)ことと、区間の無い位置は流し読みで載せることを確かめる。
//! FFmpeg が要るため `#[ignore]` にしてあり、`cargo xtask verify` が FFmpeg を見つけたときだけ `--ignored` で流す。
#![allow(clippy::expect_used)]

use std::time::Instant;

use clip_domain::動画上の区間;

use super::frame_request::コマの出どころ;
use super::prefetch_order::先読みの並び;
use super::with_ffmpeg_support::{成り立つまで待つ, 求め, 秒, 試験の動画};
use crate::stream_rules::流し読みの開き直し;

#[test]
#[ignore = "FFmpeg が要る。cargo xtask verify が FFmpeg を見つけたときだけ流す"]
fn 溜め終えた区間は継ぎ目でも溜めたコマから載せ_区間の無い位置は流し読みで載せる() {
    let mut 試験 = 試験の動画::作って開く("溜めたコマ");
    let 動画 = &mut 試験.動画;
    let 区間 = 動画上の区間::作成する(秒(1.0), 秒(2.0)).expect("区間");
    let 並び = 先読みの並び::区間の列から作る(vec![区間]);
    成り立つまで待つ("区間を溜め終えること", || {
        動画.先読みを整える(&並び, Instant::now());
        動画.台帳().溜め終えたか(&区間)
    });
    for 位置 in [1.0, 1.5, 1.97, 1.0, 1.03] {
        let 開き直し = 流し読みの開き直し::してよい;
        動画.コマを載せる(&求め(位置, Some(区間)), 開き直し, Instant::now());
        assert_eq!(動画.出どころ(), コマの出どころ::溜めたコマ(区間));
        assert!(
            動画.流し読み.is_none(),
            "溜めたコマで載せる間は流し読みを開かない"
        );
    }
    assert!(!動画.映像().まだ映していないか());
    let 寸法 = 動画.映像().テクスチャ().寸法();
    assert_eq!((寸法.幅(), 寸法.高さ()), (320, 180));
    成り立つまで待つ("流し読みのコマが載ること", || {
        動画.コマを載せる(
            &求め(3.0, None),
            流し読みの開き直し::してよい,
            Instant::now(),
        );
        let 番号 = 動画
            .映像()
            .載せたコマ()
            .map(|載せたコマ| 載せたコマ.番号.値());
        動画.出どころ() == コマの出どころ::流し読み && matches!(番号, Some(88..=90))
    });
    assert!(動画.映せない理由().is_none());
}
