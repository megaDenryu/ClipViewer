//! 載せているコマの出どころ。コマの載せ先が今コマを載せているか、載せているならそのコマの出どころ(溜めたコマか流し読みか)を表す。

use clip_domain::動画上の区間;

use super::frame_request::コマの出どころ;

/// 載せているコマの出どころとは、コマの載せ先が今コマを載せていないか、区間の溜めたコマを載せているか、流し読みのコマを載せているか
/// (求めた位置のコマをまだ待っているか)の区別のことである。待っているかを流し読みの選択肢の中に持つため、
/// 溜めたコマを載せているのに流し読みのコマを待っている、という組は表せない。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum 載せているコマの出どころ {
    載せていない,
    溜めたコマ(動画上の区間),
    流し読み { コマを待っている: bool },
}

impl 載せているコマの出どころ {
    /// スタックの作業場の画面が出す、倉庫の溜めたコマか流し読みかの区別へ写す。載せていない(開いた直後と `映すのをやめる` の後)は、
    /// 最初のコマを流し読みで待つため流し読みとして写す。前提: スタックの作業場は `映すのをやめる` を呼ばないため、載せていないのは開いた直後だけである。
    pub(crate) fn コマの出どころへ写す(self) -> コマの出どころ {
        match self {
            Self::溜めたコマ(区間) => コマの出どころ::溜めたコマ(区間),
            Self::流し読み { .. } | Self::載せていない => {
                コマの出どころ::流し読み
            }
        }
    }
}
