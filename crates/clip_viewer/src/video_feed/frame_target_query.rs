//! コマの載せ先への問い合わせ。画面が、テクスチャを描くときと、「溜めたコマ / 流し読み」と映せない理由を出すときに読む口。
//! 映せない理由は、テクスチャへ載せられなかったことを黙って捨てないために読む口を置く。

use sengen_egui::登録したテクスチャの参照;

use super::frame_target::コマの載せ先;
use super::loaded_frame_state::載せたコマの状態;
use super::stream_slot::開いた流し読み;
use super::video_texture::映像のテクスチャ;

impl コマの載せ先 {
    pub(crate) fn テクスチャ(&self) -> &映像のテクスチャ {
        &self.テクスチャ
    }

    /// 映像のテクスチャの参照を複製する。重ねる画面が行のテクスチャを描くときに使う。
    pub(crate) fn テクスチャの参照を複製する(
        &self,
    ) -> 登録したテクスチャの参照 {
        self.テクスチャ.テクスチャ().参照を複製する()
    }

    /// 載せるコマの範囲。試験で、重ね合わせの行が求めの区間の中だけを載せることを確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 載せるコマの範囲(&self) -> super::load_range::載せるコマの範囲 {
        self.載せるコマの範囲
    }

    pub(crate) fn 載せたコマの状態(&self) -> 載せたコマの状態 {
        self.載せたコマの状態
    }

    /// 流し読みで、求めた位置のコマがまだ届いていないか。
    pub(crate) fn コマを待っているか(&self) -> bool {
        self.載せたコマの状態
            == 載せたコマの状態::流し読み {
                コマを待っている: true,
            }
    }

    /// 流し読みが読めない理由、またはテクスチャへ載せられなかった理由。
    pub(crate) fn 映せない理由(&self) -> Option<&str> {
        let 流し読みの理由 = match self.載せたコマの状態 {
            載せたコマの状態::流し読み { .. } => self
                .流し読み
                .as_ref()
                .and_then(開いた流し読み::読めない理由),
            載せたコマの状態::溜めたコマ(_) | 載せたコマの状態::載せていない => {
                None
            }
        };
        流し読みの理由.or(self.テクスチャ.載せられない理由())
    }
}
