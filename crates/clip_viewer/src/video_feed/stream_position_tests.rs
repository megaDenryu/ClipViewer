//! 流し読みで求める位置の試験。区間の中ではそのままの位置を、区間の終わりちょうどと終わりより後ろでは、区間の中の最後のコマの真ん中を求めることを確かめる。
#![allow(clippy::expect_used)]

use clip_domain::{クロップ範囲, 動画上の区間, 時刻};
use video_source::コマの速さ;

use super::frame_request::表示するコマの求め;

fn 秒(値: f64) -> clip_domain::動画上の秒 {
    時刻::作成する(値).expect("時刻")
}

fn 求めた位置の秒(位置: f64, 区間: Option<動画上の区間>) -> f64 {
    let 求め = 表示するコマの求め {
        動画上の位置: 秒(位置),
        区間,
        クロップ: クロップ範囲::全体,
    };
    let 三十コマ毎秒 = コマの速さ::作成する(30, 1).expect("コマの速さ");
    求め.流し読みで求める位置(三十コマ毎秒).秒数()
}

#[test]
fn 区間の中と区間の無い求めは_位置をそのまま求める() {
    let 区間 = 動画上の区間::作成する(秒(1.0), 秒(1.5)).expect("区間");
    assert_eq!(求めた位置の秒(1.2, Some(区間)), 1.2);
    assert_eq!(求めた位置の秒(3.0, None), 3.0);
}

#[test]
fn 区間の終わりちょうどと終わりより後ろは_区間の中の最後のコマの真ん中を求める() {
    let 区間 = 動画上の区間::作成する(秒(1.0), 秒(1.5)).expect("区間");
    let 最後のコマの真ん中 = (44.0 + 0.5) / 30.0;
    for 位置 in [1.5, 2.0] {
        let 求めた = 求めた位置の秒(位置, Some(区間));
        assert!(
            (求めた - 最後のコマの真ん中).abs() < 1e-9,
            "{位置}秒は44番のコマの真ん中を求める: {求めた}"
        );
    }
}
