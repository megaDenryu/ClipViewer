//! 動画を開けない理由と、開けなかったときに利用者へ出す案内。案内の文は、動画を開こうとした経路(一覧から・パスを指定して)に合わせる。

use video_source::{倉庫を開くエラー, 動画の情報の取得エラー};

/// 動画を開けない理由とは、動画を読み込んだ動画にできなかった理由の区別のことである。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 動画を開けない理由 {
    #[error("FFmpeg が見つからないため動画を開けない。画面の上部で FFmpeg の置き場所を設定する")]
    FFmpegが無い,
    #[error("動画の情報を取れない: {0}")]
    情報を取れない(#[from] 動画の情報の取得エラー),
    #[error("コマの倉庫を開けない: {0}")]
    倉庫を開けない(#[from] 倉庫を開くエラー),
    #[error("映像のテクスチャを作れない: {0}")]
    テクスチャを作れない(#[from] sengen_egui::画素の並びの不正),
}

/// 動画を開く経路とは、利用者がどこから動画を開こうとしたかの区別のことである。開けなかったときの案内の文を経路に合わせる。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 動画を開く経路 {
    ライブラリの一覧から,
    パスを指定して,
}

impl 動画を開けない理由 {
    /// 開けなかった理由に、利用者が次にすることの案内を添えた文。理由から次にすることが決まらないときは理由だけである。
    pub(crate) fn 案内を添えた文(&self, 経路: 動画を開く経路) -> String {
        match self.次にすることの案内(経路) {
            Some(案内) => format!("{self}。{案内}"),
            None => self.to_string(),
        }
    }

    fn 次にすることの案内(&self, 経路: 動画を開く経路) -> Option<&'static str> {
        match (self, 経路) {
            (
                Self::情報を取れない(動画の情報の取得エラー::異常終了 { .. }),
                動画を開く経路::ライブラリの一覧から,
            ) => Some("動画を移動したなら、一覧の「動画の場所を指定し直す」で指定する"),
            (
                Self::情報を取れない(動画の情報の取得エラー::異常終了 { .. }),
                動画を開く経路::パスを指定して,
            ) => Some("ファイルがその場所にあり、動画のファイルであるかを確かめる"),
            (Self::情報を取れない(動画の情報の取得エラー::時間切れ { .. }), _) => {
                Some("動画のあるドライブかネットワークの応答が遅い。少し待ってからもう一度開く")
            }
            (
                Self::情報を取れない(_)
                | Self::FFmpegが無い
                | Self::倉庫を開けない(_)
                | Self::テクスチャを作れない(_),
                _,
            ) => None,
        }
    }
}
