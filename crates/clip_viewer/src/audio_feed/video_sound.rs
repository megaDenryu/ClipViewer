//! 動画の音。動画を開いたときに、音声出力装置の有無と動画の音の有無から、音を鳴らせるかを決めて音の倉庫を開く。

use audio_pcm::サンプリング周波数;
use video_source::{動画の情報, 動画の読み手};

use super::source::動画の音の供給元;
use super::supply::音の供給;

/// 音を鳴らせない理由とは、動画に音があっても鳴らせない理由の区別のことである。映像は再生を続ける。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 音を鳴らせない理由 {
    #[error("音声出力装置が使えない")]
    出力装置が無い,
    #[error("音の倉庫を開けない: {0}")]
    倉庫を開けない(#[from] std::io::Error),
}

/// 動画の音とは、読み込んだ動画の音を鳴らせるか、音が無いか、鳴らせるならその音の供給の区別のことである。
/// 読み込んだ動画と一緒に作り、一緒に捨てる。
#[expect(
    clippy::large_enum_variant,
    reason = "読み込んだ動画1つにつき1つしか持たないため、選択肢の大きさの差は問題にならない"
)]
pub(crate) enum 動画の音 {
    鳴らせない(音を鳴らせない理由),
    音が無い,
    ある(音の供給),
}

impl 動画の音 {
    /// 出力装置の周波数が無ければ鳴らせない。動画に音があれば、その周波数で溜める音の倉庫を開く。音の有無は動画の情報が持つ。
    pub(crate) fn 開く(
        読み手: &動画の読み手,
        動画: &動画の情報,
        周波数: Option<サンプリング周波数>,
    ) -> Self {
        match 動画の音の供給元::開く(読み手, 動画, 周波数) {
            Ok(Some(供給元)) => Self::ある(音の供給::作成する(供給元)),
            Ok(None) => Self::音が無い,
            Err(理由) => Self::鳴らせない(理由),
        }
    }

    /// 鳴らせるなら音の供給。
    pub(crate) fn 供給(&self) -> Option<&音の供給> {
        match self {
            Self::ある(供給) => Some(供給),
            Self::鳴らせない(_) | Self::音が無い => None,
        }
    }

    /// 鳴らせるなら、書き換えられる音の供給。
    pub(crate) fn 供給を書き換える(&mut self) -> Option<&mut 音の供給> {
        match self {
            Self::ある(供給) => Some(供給),
            Self::鳴らせない(_) | Self::音が無い => None,
        }
    }
}
