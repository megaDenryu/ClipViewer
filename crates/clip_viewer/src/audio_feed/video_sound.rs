//! 動画の音。動画を開いたときに、音声出力装置の有無と動画の音の有無から、音を鳴らせるかを決めて音の倉庫を開く。
//! 鳴らせない / 音が無い / ある の区別と、画面の音の様子に出す文は、スタックの作業場と重ね合わせの作業場が共に使う。

use std::fmt::Display;

use audio_pcm::サンプリング周波数;
use video_source::{動画の情報, 動画の読み手};

use super::source::動画の音の供給元;
use super::supply::音の供給;

/// 動画に音が無いときに、画面の音の様子に出す文。
pub(crate) const 音が無い様子の文: &str = "音: この動画には音が無い";

/// 音を鳴らせない理由を、画面の音の様子に出す文にする。
pub(crate) fn 鳴らせない様子の文(理由: &impl Display) -> String {
    format!("音: 鳴らせない({理由})")
}

/// 音を鳴らせない理由とは、動画に音があっても鳴らせない理由の区別のことである。映像は再生を続ける。
#[derive(Debug, thiserror::Error)]
pub(crate) enum 音を鳴らせない理由 {
    #[error("音声出力装置が使えない")]
    出力装置が無い,
    #[error("音の倉庫を開けない: {0}")]
    倉庫を開けない(#[from] std::io::Error),
}

/// 動画の音とは、動画の音を鳴らせるか、音が無いか、鳴らせるならその音の供給の区別のことである。
/// スタックの作業場は音の供給(動画の音の供給元と流し読み)を持ち、読み込んだ動画と一緒に作って一緒に捨てる。
/// 重ね合わせの作業場は、使う動画の表の動画ごとに動画の音の供給元だけを持つ(流し読みは行ごとに持つ)。
pub(crate) enum 動画の音<供給 = 音の供給> {
    鳴らせない(音を鳴らせない理由),
    音が無い,
    ある(供給),
}

impl 動画の音 {
    /// 出力装置の周波数が無ければ鳴らせない。動画に音があれば、その周波数で溜める音の倉庫を開く。音の有無は動画の情報が持つ。
    pub(crate) fn 開く(
        読み手: &動画の読み手,
        動画: &動画の情報,
        周波数: Option<サンプリング周波数>,
    ) -> Self {
        Self::開いた結果から作る(
            動画の音の供給元::開く(読み手, 動画, 周波数)
                .map(|供給元| 供給元.map(音の供給::作成する)),
        )
    }
}

impl 動画の音<動画の音の供給元> {
    /// 動画の音の供給元だけを開く。重ね合わせの作業場が使う動画の表の動画ごとに使う。
    pub(crate) fn 供給元だけを開く(
        読み手: &動画の読み手,
        動画: &動画の情報,
        周波数: Option<サンプリング周波数>,
    ) -> Self {
        Self::開いた結果から作る(動画の音の供給元::開く(読み手, 動画, 周波数))
    }
}

impl<供給> 動画の音<供給> {
    fn 開いた結果から作る(
        結果: Result<Option<供給>, 音を鳴らせない理由>
    ) -> Self {
        match 結果 {
            Ok(Some(供給)) => Self::ある(供給),
            Ok(None) => Self::音が無い,
            Err(理由) => Self::鳴らせない(理由),
        }
    }

    /// 鳴らせるなら音の供給。
    pub(crate) fn 供給(&self) -> Option<&供給> {
        match self {
            Self::ある(供給) => Some(供給),
            Self::鳴らせない(_) | Self::音が無い => None,
        }
    }

    /// 鳴らせるなら、書き換えられる音の供給。
    pub(crate) fn 供給を書き換える(&mut self) -> Option<&mut 供給> {
        match self {
            Self::ある(供給) => Some(供給),
            Self::鳴らせない(_) | Self::音が無い => None,
        }
    }

    /// 鳴らせないときと音が無いときに画面の音の様子に出す文。鳴らせるなら無い。
    pub(crate) fn 鳴らせないときの様子の文(&self) -> Option<String> {
        match self {
            Self::鳴らせない(理由) => Some(鳴らせない様子の文(理由)),
            Self::音が無い => Some(音が無い様子の文.to_string()),
            Self::ある(_) => None,
        }
    }
}
