//! 音の開いた流し読み。流し読みの規則の開き直しを判断できる流し読みに、音の流し読みを入れたものであり、開く口と、出どころの渡し方を持つ。

use std::sync::Arc;
use std::time::Instant;

use audio_pcm::{サンプリング周波数, 動画上の標本位置, 音の出どころ};
use clip_domain::{動画上の秒, 時間の長さ};
use video_source::{
    動画の情報, 動画の読み手, 音の流し読み, 音の流し読みの状態
};

use crate::stream_rules::{流し読みの中身, 開き直しを判断できる流し読み};

/// 求める位置より前から開く長さ(秒)。音の再生器が映像より少し遅れていても、その位置の音が入れ物にあるようにする。
const 手前から開く秒数: f64 = 0.1;

/// 開いた音の流し読みとは、ある位置で開いた、開き直しを判断できる音の流し読みのことである。
pub(super) type 開いた音の流し読み = 開き直しを判断できる流し読み<音の流し読み>;

impl 流し読みの中身 for 音の流し読み {
    fn 途中の失敗(&mut self) -> Option<String> {
        match self.状態() {
            音の流し読みの状態::失敗(失敗) => Some(失敗.to_string()),
            音の流し読みの状態::読んでいる | 音の流し読みの状態::終わりまで読んだ => {
                None
            }
        }
    }

    fn 終わりまで読んだか(&mut self) -> bool {
        matches!(self.状態(), 音の流し読みの状態::終わりまで読んだ)
    }
}

impl 開いた音の流し読み {
    /// 位置の少し前から開く。開けなければ、その理由を持った読めない流し読みになる。
    pub(super) fn 開く(
        読み手: &動画の読み手,
        動画: &動画の情報,
        位置: 動画上の秒,
        周波数: サンプリング周波数,
        今: Instant,
    ) -> Self {
        let 手前 = 時間の長さ::作成する(手前から開く秒数).unwrap_or(時間の長さ::ゼロ);
        let 結果 = 読み手.音の流し読みを開く(動画, 位置.戻す(手前), 周波数);
        Self::開いた結果から作る(結果, 位置, 今)
    }

    /// 音声のスレッドへ渡す出どころ。読めなければ無い。
    pub(super) fn 出どころ(&self) -> Option<音の出どころ> {
        self.読んでいる中身()
            .map(|流し読み| 音の出どころ::流れてくる音(Arc::clone(流し読み.音())))
    }

    /// その位置の標本が、もう入れ物に届いているか。
    pub(super) fn 標本が届いているか(&self, 位置: 動画上の標本位置) -> bool {
        self.読んでいる中身()
            .is_some_and(|流し読み| 流し読み.音().標本(位置).is_some())
    }
}
