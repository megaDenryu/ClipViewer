//! 動画の音の供給元から音を出す流し読みの扱い。区間を溜め終える前と元動画再生の間、映像の流し読みと同じ規則で音の流し読みを開き直し、
//! 鳴らす出どころを溜めた音か流し読みから選ぶ。スタックの作業場の音の供給と、重ね合わせの作業場の行ごとの流し読みが共に使う。

use std::time::Instant;

use audio_pcm::音の出どころ;
use clip_domain::{動画上の区間, 動画上の秒};

use super::source::動画の音の供給元;
use super::stream_pair::開き直しをまたぐ音の流し読み;
use crate::stream_rules::流し読みの開き直し;

/// 音の鳴らし方とは、今の区間の音を溜めた音から鳴らしているか、流し読みから鳴らしているか、流し読みで読めないかの区別のことである。
/// 画面は再生コントロールに出す。
pub(crate) enum 音の鳴らし方<'理由> {
    溜めた音,
    流し読み,
    読めない(&'理由 str),
}

impl 開き直しをまたぐ音の流し読み {
    /// 今の区間の音の鳴らし方。
    pub(crate) fn 鳴らし方(
        &self,
        供給元: &動画の音の供給元,
        区間: Option<&動画上の区間>,
    ) -> 音の鳴らし方<'_> {
        if 区間.is_some_and(|区間| 供給元.溜めた音の出どころ(区間).is_some()) {
            return 音の鳴らし方::溜めた音;
        }
        match self.読めない理由() {
            Some(理由) => 音の鳴らし方::読めない(理由),
            None => 音の鳴らし方::流し読み,
        }
    }

    /// 区間の音を鳴らす出どころ。溜め終えていれば溜めた音、そうでなければ開き直しをまたぐ音の流し読みが選ぶ方。
    pub(crate) fn 鳴らす出どころ(
        &self,
        供給元: &動画の音の供給元,
        区間: Option<&動画上の区間>,
        位置: 動画上の秒,
    ) -> Option<音の出どころ> {
        if let Some(溜めた音) = 区間.and_then(|区間| 供給元.溜めた音の出どころ(区間))
        {
            return Some(溜めた音);
        }
        self.届いている方の出どころ(供給元.周波数().時刻を含む標本位置(位置))
    }

    /// 今の区間(元動画再生では無い)を溜め終えていれば流し読みを閉じ、そうでなければ映像の流し読みと同じ規則で、
    /// 映している動画上の位置から音の流し読みを開き直す。
    pub(crate) fn 整える(
        &mut self,
        供給元: &動画の音の供給元,
        位置: 動画上の秒,
        区間: Option<&動画上の区間>,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        if 区間.is_some_and(|区間| 供給元.溜めた音の出どころ(区間).is_some()) {
            self.閉じる();
            return;
        }
        if !self.開き直すか(位置) {
            self.求めた位置を覚える(位置);
        } else if 開き直し == 流し読みの開き直し::してよい
            && self.開き直しの間隔を守ったか(今)
        {
            self.開き直す(供給元.流し読みを開く(位置, 今));
        }
        let 標本位置 = 供給元.周波数().時刻を含む標本位置(位置);
        self.片付ける(標本位置);
    }
}
