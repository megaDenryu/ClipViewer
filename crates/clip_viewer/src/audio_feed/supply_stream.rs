//! 音の流し読みからの供給。今の区間を溜め終える前と元動画再生の間、映像の流し読みと同じ規則で音の流し読みを開き直す。

use std::time::Instant;

use clip_domain::{動画上の区間, 動画上の秒};

use super::stream_slot::開いた音の流し読み;
use super::supply::音の供給;
use crate::stream_rules::流し読みの開き直し;

/// 音の鳴らし方とは、今の区間の音を溜めた音から鳴らしているか、流し読みから鳴らしているか、流し読みで読めないかの区別のことである。
/// 画面は再生コントロールに出す。
pub(crate) enum 音の鳴らし方<'理由> {
    溜めた音,
    流し読み,
    読めない(&'理由 str),
}

impl 音の供給 {
    /// 今の区間の音の鳴らし方。
    pub(crate) fn 鳴らし方(
        &self, 区間: Option<&動画上の区間>
    ) -> 音の鳴らし方<'_> {
        if 区間.is_some_and(|区間| self.溜めた音の出どころ(区間).is_some()) {
            return 音の鳴らし方::溜めた音;
        }
        match self.流し読み.読めない理由() {
            Some(理由) => 音の鳴らし方::読めない(理由),
            None => 音の鳴らし方::流し読み,
        }
    }

    /// 今の区間(元動画再生では無い)を溜め終えていれば流し読みを閉じ、そうでなければ映像の流し読みと同じ規則で、
    /// 映している動画上の位置から音の流し読みを開き直す。
    pub(crate) fn 流し読みを整える(
        &mut self,
        位置: 動画上の秒,
        区間: Option<&動画上の区間>,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        if 区間.is_some_and(|区間| self.溜めた音の出どころ(区間).is_some()) {
            self.流し読み.閉じる();
            return;
        }
        if !self.流し読み.開き直すか(位置) {
            self.流し読み.求めた位置を覚える(位置);
        } else if 開き直し == 流し読みの開き直し::してよい
            && self.流し読み.開き直しの間隔を守ったか(今)
        {
            let 周波数 = self.周波数();
            let 新しい方 =
                開いた音の流し読み::開く(&self.読み手, &self.動画, 位置, 周波数, 今);
            self.流し読み.開き直す(新しい方);
        }
        let 標本位置 = self.周波数().時刻を含む標本位置(位置);
        self.流し読み.片付ける(標本位置);
    }
}
