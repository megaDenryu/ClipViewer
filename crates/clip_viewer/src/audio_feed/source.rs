//! 動画の音の供給元。1本の動画に結び付いた読み手・動画の情報・音の倉庫と、最後に倉庫へ渡した並びを持ち、先読みの並びを倉庫へ渡し、
//! 溜めた音の出どころを出し、音の流し読みを開く。スタックの作業場の音の供給が1つ持ち、重ね合わせの作業場は使う動画の表の動画ごとに1つ持つ。
//! 参照: _doc/設計/同時再生.md 3-3・5-3

use std::time::Instant;

use audio_pcm::{サンプリング周波数, 音の出どころ};
use clip_domain::{動画上の区間, 動画上の秒, 時間の長さ};
use video_source::{
    動画の情報, 動画の読み手, 音のメモリの上限, 音の倉庫, 音の有無, 音の溜め方
};

use super::stream_slot::開いた音の流し読み;
use super::video_sound::音を鳴らせない理由;

/// 区間の開始より前に溜める長さ(秒)。音の再生器が区間の終わりで重ねる長さ(8ミリ秒)より長くする。
const 開始の前の余白の秒数: f64 = 0.01;

/// 動画の音の供給元とは、音を鳴らせる1本の動画の、動画の読み手と情報と音の倉庫と、最後に倉庫へ渡した並びの組のことである。
pub(crate) struct 動画の音の供給元 {
    読み手: 動画の読み手,
    動画: 動画の情報,
    倉庫: 音の倉庫,
    渡した並び: Vec<動画上の区間>,
}

impl 動画の音の供給元 {
    /// 出力装置の周波数が無ければ鳴らせない。動画に音が無ければ無い。音があれば、その周波数で溜める音の倉庫を開く。
    pub(crate) fn 開く(
        読み手: &動画の読み手,
        動画: &動画の情報,
        周波数: Option<サンプリング周波数>,
    ) -> Result<Option<Self>, 音を鳴らせない理由> {
        let 周波数 = 周波数.ok_or(音を鳴らせない理由::出力装置が無い)?;
        if 動画.音の有無() == 音の有無::無い {
            return Ok(None);
        }
        let 溜め方 = 音の溜め方 {
            周波数,
            開始の前の余白: 時間の長さ::作成する(開始の前の余白の秒数)
                .unwrap_or(時間の長さ::ゼロ),
            上限: 音のメモリの上限::既定,
        };
        let 倉庫 = 読み手.音の倉庫を開く(動画, 溜め方)?;
        Ok(Some(Self {
            読み手: 読み手.clone(),
            動画: 動画.clone(),
            倉庫,
            渡した並び: Vec::new(),
        }))
    }

    /// 音を出させる周波数(出力装置の周波数)。
    pub(crate) fn 周波数(&self) -> サンプリング周波数 {
        self.倉庫.溜め方().周波数
    }

    /// 区間の集まりが落ち着いていて、並びが前に渡したものと違うときだけ、倉庫へ渡す。
    /// 映像の依頼の台帳と同じく、区間の数値を続けて変えている間に ffmpeg の起動と停止を繰り返さないためである。
    pub(crate) fn 溜める並びを整える(
        &mut self,
        区間の列: &[動画上の区間],
        落ち着いたか: bool,
    ) {
        if 落ち着いたか && 区間の列 != self.渡した並び.as_slice() {
            self.渡した並び = 区間の列.to_vec();
            self.倉庫.溜める区間の並びを渡す(&self.渡した並び);
        }
    }

    /// 区間を溜め終えていれば、その溜めた音の出どころ。
    pub(crate) fn 溜めた音の出どころ(
        &self,
        区間: &動画上の区間,
    ) -> Option<音の出どころ> {
        self.倉庫
            .区間の状況(区間)
            .溜めた音()
            .map(|音| 音の出どころ::溜めた音(音.clone()))
    }

    /// 位置の少し前から音の流し読みを開く。開けなければ、その理由を持った読めない流し読みになる。
    pub(super) fn 流し読みを開く(
        &self,
        位置: 動画上の秒,
        今: Instant,
    ) -> 開いた音の流し読み {
        開いた音の流し読み::開く(&self.読み手, &self.動画, 位置, self.周波数(), 今)
    }
}
