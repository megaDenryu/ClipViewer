//! 音の供給。音の倉庫へ先読みの並びを渡し、今の区間の音を溜めた音から、溜め終える前と元動画再生では流し読み(`supply_stream.rs`)から出す。

use audio_pcm::{サンプリング周波数, 音の出どころ};
use clip_domain::{動画上の区間, 動画上の秒};
use video_source::{動画の情報, 動画の読み手, 音の倉庫};

use super::stream_pair::開き直しをまたぐ音の流し読み;

/// 音の供給とは、音を鳴らせる動画の、動画の読み手と情報と音の倉庫と、開き直しをまたぐ音の流し読みと、最後に倉庫へ渡した並びの組のことである。
pub(crate) struct 音の供給 {
    pub(super) 読み手: 動画の読み手,
    pub(super) 動画: 動画の情報,
    倉庫: 音の倉庫,
    pub(super) 流し読み: 開き直しをまたぐ音の流し読み,
    渡した並び: Vec<動画上の区間>,
}

impl 音の供給 {
    pub(super) fn 作成する(
        読み手: 動画の読み手, 動画: 動画の情報, 倉庫: 音の倉庫
    ) -> Self {
        Self {
            読み手,
            動画,
            倉庫,
            流し読み: 開き直しをまたぐ音の流し読み::default(),
            渡した並び: Vec::new(),
        }
    }

    /// 音を出させる周波数(出力装置の周波数)。
    pub(crate) fn 周波数(&self) -> サンプリング周波数 {
        self.倉庫.溜め方().周波数
    }

    /// 区間の集まりが落ち着いていて、並びが前に渡したものと違うときだけ、倉庫へ渡す。
    /// 映像の依頼の台帳と同じく、区間の数値を続けて変えている間に ffmpeg の起動と停止を繰り返さないためである。
    pub(crate) fn 溜める並びを整える(
        &mut self,
        区間の列: &[動画上の区間],
        落ち着いたか: bool,
    ) {
        if 落ち着いたか && 区間の列 != self.渡した並び.as_slice() {
            self.渡した並び = 区間の列.to_vec();
            self.倉庫.溜める区間の並びを渡す(&self.渡した並び);
        }
    }

    /// 区間を溜め終えていれば、その溜めた音の出どころ。
    pub(crate) fn 溜めた音の出どころ(
        &self,
        区間: &動画上の区間,
    ) -> Option<音の出どころ> {
        self.倉庫
            .区間の状況(区間)
            .溜めた音()
            .map(|音| 音の出どころ::溜めた音(音.clone()))
    }

    /// 区間の音を鳴らす出どころ。溜め終えていれば溜めた音、そうでなければ開き直しをまたぐ音の流し読みが選ぶ方。
    pub(crate) fn 鳴らす出どころ(
        &self,
        区間: Option<&動画上の区間>,
        位置: 動画上の秒,
    ) -> Option<音の出どころ> {
        if let Some(溜めた音) = 区間.and_then(|区間| self.溜めた音の出どころ(区間))
        {
            return Some(溜めた音);
        }
        self.流し読み
            .鳴らす出どころ(self.周波数().時刻を含む標本位置(位置))
    }

    /// 今の音の流し読みに、その位置の標本が届いているか。試験で、開き直した直後の前提を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 今の流し読みに届いているか(&self, 位置: 動画上の秒) -> bool {
        self.流し読み
            .今の方に届いているか(self.周波数().時刻を含む標本位置(位置))
    }
}
