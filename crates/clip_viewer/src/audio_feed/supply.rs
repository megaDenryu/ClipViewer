//! 音の供給。スタックの作業場の読み込んだ動画の音であり、動画の音の供給元(`source.rs`)と開き直しをまたぐ音の流し読みを1つずつ持って委ねる。
//! 今の区間の音を溜めた音から、溜め終える前と元動画再生では流し読み(`supply_stream.rs`)から出す。

use std::time::Instant;

use audio_pcm::{サンプリング周波数, 音の出どころ};
use clip_domain::{動画上の区間, 動画上の秒};

use super::source::動画の音の供給元;
use super::stream_pair::開き直しをまたぐ音の流し読み;
use super::supply_stream::音の鳴らし方;
use crate::stream_rules::流し読みの開き直し;

/// 音の供給とは、音を鳴らせる動画の、動画の音の供給元と、開き直しをまたぐ音の流し読みの組のことである。
pub(crate) struct 音の供給 {
    供給元: 動画の音の供給元,
    流し読み: 開き直しをまたぐ音の流し読み,
}

impl 音の供給 {
    pub(super) fn 作成する(供給元: 動画の音の供給元) -> Self {
        Self {
            供給元,
            流し読み: 開き直しをまたぐ音の流し読み::default(),
        }
    }

    /// 音を出させる周波数(出力装置の周波数)。
    pub(crate) fn 周波数(&self) -> サンプリング周波数 {
        self.供給元.周波数()
    }

    /// 区間の集まりが落ち着いていて、並びが前に渡したものと違うときだけ、倉庫へ渡す。
    pub(crate) fn 溜める並びを整える(
        &mut self,
        区間の列: &[動画上の区間],
        落ち着いたか: bool,
    ) {
        self.供給元.溜める並びを整える(区間の列, 落ち着いたか);
    }

    /// 区間を溜め終えていれば、その溜めた音の出どころ。
    pub(crate) fn 溜めた音の出どころ(
        &self,
        区間: &動画上の区間,
    ) -> Option<音の出どころ> {
        self.供給元.溜めた音の出どころ(区間)
    }

    /// 区間の音を鳴らす出どころ。溜め終えていれば溜めた音、そうでなければ開き直しをまたぐ音の流し読みが選ぶ方。
    pub(crate) fn 鳴らす出どころ(
        &self,
        区間: Option<&動画上の区間>,
        位置: 動画上の秒,
    ) -> Option<音の出どころ> {
        self.流し読み.鳴らす出どころ(&self.供給元, 区間, 位置)
    }

    /// 今の区間の音の鳴らし方。
    pub(crate) fn 鳴らし方(
        &self, 区間: Option<&動画上の区間>
    ) -> 音の鳴らし方<'_> {
        self.流し読み.鳴らし方(&self.供給元, 区間)
    }

    /// 今の区間(元動画再生では無い)を溜め終えていれば流し読みを閉じ、そうでなければ映像の流し読みと同じ規則で開き直す。
    pub(crate) fn 流し読みを整える(
        &mut self,
        位置: 動画上の秒,
        区間: Option<&動画上の区間>,
        開き直し: 流し読みの開き直し,
        今: Instant,
    ) {
        self.流し読み.整える(&self.供給元, 位置, 区間, 開き直し, 今);
    }

    /// 今の音の流し読みに、その位置の標本が届いているか。試験で、開き直した直後の前提を確かめるために使う。
    #[cfg(test)]
    pub(crate) fn 今の流し読みに届いているか(&self, 位置: 動画上の秒) -> bool {
        self.流し読み
            .今の方に届いているか(self.周波数().時刻を含む標本位置(位置))
    }
}
