//! 開き直しをまたぐ音の流し読み。今の流し読みと、開き直す前の流し読みの組であり、開き直すこと・鳴らす出どころを選ぶこと・
//! 開き直す前の流し読みを片付けることを受け持つ。

use std::time::Instant;

use audio_pcm::{動画上の標本位置, 音の出どころ};
use clip_domain::動画上の秒;

use super::stream_slot::開いた音の流し読み;
use crate::stream_rules::開き直しの最短の間隔;

/// 開き直しをまたぐ音の流し読みとは、今の流し読みと、開き直す前の流し読みの組のことである。
/// 開き直した直後は新しい入れ物がまだ空なので、今の方に求める位置の標本が届くまで、前の方を鳴らし続ける。
/// 前の方は、今の方に標本が届いたとき・今の方が読めないか終わりまで読んだとき・前の方がその位置の標本を持たないときに閉じる。
#[derive(Default)]
pub(crate) struct 開き直しをまたぐ音の流し読み {
    今の方: Option<開いた音の流し読み>,
    前の方: Option<開いた音の流し読み>,
}

impl 開き直しをまたぐ音の流し読み {
    /// 両方を閉じる。今の区間を溜め終えたときと、重ね合わせの行が何も映さないときに使う。
    pub(crate) fn 閉じる(&mut self) {
        self.今の方 = None;
        self.前の方 = None;
    }

    /// その位置を求めるのに開き直すか。今の方が無ければ開き直す。
    pub(super) fn 開き直すか(&self, 位置: 動画上の秒) -> bool {
        self.今の方
            .as_ref()
            .is_none_or(|開いた| 開いた.この位置で開き直すか(位置))
    }

    /// 今の方を開いてから開き直しの最短の間隔が過ぎたか。今の方が無ければ過ぎたとみなす。
    pub(super) fn 開き直しの間隔を守ったか(&self, 今: Instant) -> bool {
        self.今の方
            .as_ref()
            .is_none_or(|開いた| 開いた.開いてからの経過(今) >= 開き直しの最短の間隔)
    }

    /// 新しく開いた流し読みを今の方にし、今までの今の方を前の方へ移す。
    pub(super) fn 開き直す(&mut self, 新しい方: 開いた音の流し読み) {
        self.前の方 = self.今の方.replace(新しい方);
    }

    /// 今の方に、求めた位置を覚えさせ、途中の失敗を写させる。
    pub(super) fn 求めた位置を覚える(&mut self, 位置: 動画上の秒) {
        if let Some(開いた) = self.今の方.as_mut() {
            開いた.求めた位置を覚え途中の失敗を写して中身を貸す(位置);
        }
    }

    /// 前の方を閉じてよいなら閉じる。
    pub(super) fn 片付ける(&mut self, 位置: 動画上の標本位置) {
        let 前の方に届いているか = self
            .前の方
            .as_ref()
            .is_some_and(|開いた| 開いた.標本が届いているか(位置));
        let 今の方を待つか = self.今の方.as_mut().is_some_and(|開いた| {
            !開いた.標本が届いているか(位置)
                && 開いた.読めない理由().is_none()
                && !開いた.中身が終わりまで読んだか()
        });
        if !(今の方を待つか && 前の方に届いているか) {
            self.前の方 = None;
        }
    }

    /// 鳴らす出どころ。今の方に位置の標本がまだ届いておらず前の方には届いているなら前の方、そうでなければ今の方。
    pub(super) fn 届いている方の出どころ(
        &self,
        位置: 動画上の標本位置,
    ) -> Option<音の出どころ> {
        let 届いているか = |開いた: &Option<開いた音の流し読み>| {
            開いた
                .as_ref()
                .is_some_and(|開いた| 開いた.標本が届いているか(位置))
        };
        let 使う方 = if !届いているか(&self.今の方) && 届いているか(&self.前の方)
        {
            &self.前の方
        } else {
            &self.今の方
        };
        使う方.as_ref().and_then(開いた音の流し読み::出どころ)
    }

    /// 今の方に位置の標本が届いているか。試験で、開き直した直後の前提を確かめるために使う。
    #[cfg(test)]
    pub(super) fn 今の方に届いているか(&self, 位置: 動画上の標本位置) -> bool {
        self.今の方
            .as_ref()
            .is_some_and(|開いた| 開いた.標本が届いているか(位置))
    }

    /// 今の方が読めない理由。
    pub(super) fn 読めない理由(&self) -> Option<&str> {
        self.今の方
            .as_ref()
            .and_then(開いた音の流し読み::読めない理由)
    }
}
