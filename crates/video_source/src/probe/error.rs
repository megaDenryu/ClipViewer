//! 動画の情報を取れないときのエラー。

use std::io;
use std::process::ExitStatus;
use std::time::Duration;

use crate::process::{期限付きの待ちの失敗, 標準エラーの末尾};

/// 読めない項目とは、ffprobe の出力に無いか値として成立しない、動画の情報の項目のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 読めない項目 {
    /// 映像の幅と高さ。
    寸法,
    /// コマの速さ(avg_frame_rate と r_frame_rate)。
    コマの速さ,
    /// 動画の長さ(映像の duration と入れ物の duration)。
    長さ,
    /// 映像の流れの番号(index)。
    流れの番号,
}

/// 動画の情報の取得エラーとは、ffprobe で動画の長さ・寸法・コマの速さ・流れを取れなかった理由のことである。
#[derive(Debug, thiserror::Error)]
pub enum 動画の情報の取得エラー {
    /// ffprobe を起動できなかった。
    #[error("ffprobe を起動できない: {0}")]
    起動できない(#[source] io::Error),
    /// ffprobe の終わりを確かめられなかった。
    #[error("ffprobe の終わりを確かめられない: {0}")]
    待てない(#[source] io::Error),
    /// ffprobe の出力を読めなかった。
    #[error("ffprobe の出力を読めない: {0}")]
    出力を読めない(#[source] io::Error),
    /// ffprobe が期限までに終わらなかったので止めた。ファイルがネットワークの先で応答しない等。
    #[error("ffprobe が{}秒の期限までに終わらなかったので止めた", .期限.as_secs())]
    時間切れ {
        /// 過ぎた期限。
        期限: Duration,
    },
    /// ffprobe が失敗の終了状態で終わった。ファイルが無い・動画でない等。
    #[error("ffprobe が異常終了した({終了状態})。{標準エラーの末尾}")]
    異常終了 {
        /// ffprobe の終了状態。
        終了状態: ExitStatus,
        /// ffprobe の標準エラーの末尾。
        標準エラーの末尾: 標準エラーの末尾,
    },
    /// ffprobe の出力を JSON として解釈できなかった。
    #[error("ffprobe の出力を解釈できない: {理由}")]
    出力を解釈できない {
        /// 解釈に失敗した理由。
        理由: String,
    },
    /// ファイルに映像が無い。
    #[error("ファイルに映像が無い")]
    映像が無い,
    /// 必要な項目を読めなかった。
    #[error("動画の{0:?}を読めない")]
    項目を読めない(読めない項目),
}

impl 動画の情報の取得エラー {
    /// 期限付きの待ちの失敗から作る。時間切れには過ぎた期限を添える。
    pub(crate) fn 待ちの失敗から作る(
        失敗: 期限付きの待ちの失敗, 期限: Duration
    ) -> Self {
        match 失敗 {
            期限付きの待ちの失敗::起動できない(原因) => {
                Self::起動できない(原因)
            }
            期限付きの待ちの失敗::待てない(原因) => Self::待てない(原因),
            期限付きの待ちの失敗::出力を読めない(原因) => {
                Self::出力を読めない(原因)
            }
            期限付きの待ちの失敗::時間切れ => Self::時間切れ { 期限 },
            // 注意: 動画の情報を取る口は取り消しの合図を誰にも渡さないため、ここへは来ない。来たら終わりを確かめられなかったとして返す。
            期限付きの待ちの失敗::取り消した => {
                Self::待てない(io::Error::other("ffprobe の待ちが取り消された"))
            }
        }
    }
}

/// 調査の失敗とは、期限付きで動画の情報を調べられなかった理由を、ffprobe を待てなかったか、ffprobe の結果を動画の情報にできなかったかで
/// 分けたもののことである。呼び出し側が、待ちの失敗(時間切れ・取り消し)を自分の失敗の型へ写せるようにするために分ける。
#[derive(Debug)]
pub(crate) enum 調査の失敗 {
    待てなかった(期限付きの待ちの失敗),
    読めなかった(動画の情報の取得エラー),
}
