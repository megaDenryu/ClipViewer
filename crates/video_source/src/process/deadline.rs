//! 期限付きの子プロセス。起動した子プロセスの終わりを、期限と取り消しの合図を見回りながら待ち、過ぎたら止める。
//! 動画の情報を調べる ffprobe(30秒)とサムネイルを撮る ffprobe と ffmpeg(10秒)が、固まったときに呼び出し側を止め続けないために使う。
//! 参照: _doc/設計/アーキテクチャ.md 1-7(動画の情報を取る)、_doc/設計/ライブラリ.md 判断10(FFmpeg の期限)

use std::io::{self, Read};
use std::process::{ChildStdout, Command};
use std::time::{Duration, Instant};

use super::cancel::取り消しの合図;
use super::child::起動した子プロセス;
use super::deadline_outcome::{期限付きの待ちの失敗, 集めた出力};
use super::stderr_tail::標準エラーの収集;
use super::thread::終わりを待つスレッド;

/// 終わったかを見回る間隔。取り消してから子プロセスを止めるまでの遅れもこの長さで決まる。
const 見回りの間隔: Duration = Duration::from_millis(10);

/// 期限付きの子プロセスとは、起動した子プロセスと、その標準出力と標準エラー出力を読み続ける裏のスレッドの組のことである。
/// 読み続けるのは、パイプが詰まって子プロセスが止まることを防ぐためである。
pub(crate) struct 期限付きの子プロセス {
    子プロセス: 起動した子プロセス,
    標準出力: 終わりを待つスレッド<io::Result<Vec<u8>>>,
    標準エラー: 標準エラーの収集,
}

impl 期限付きの子プロセス {
    /// 命令を起動する。標準入力は閉じ、標準出力と標準エラー出力はパイプで受け取る。
    pub(crate) fn 起動する(
        mut 命令: Command
    ) -> Result<Self, 期限付きの待ちの失敗> {
        let (mut 子プロセス, パイプ) =
            起動した子プロセス::起動する(&mut 命令).map_err(期限付きの待ちの失敗::起動できない)?;
        let 標準出力 =
            終わりを待つスレッド::起動する("子プロセスの標準出力を読む", move || {
                全部読む(パイプ.標準出力)
            })
            .map_err(期限付きの待ちの失敗::起動できない)?;
        match 標準エラーの収集::起動する(パイプ.標準エラー) {
            Ok(標準エラー) => Ok(Self {
                子プロセス,
                標準出力,
                標準エラー,
            }),
            Err(原因) => {
                // 注意: 標準出力を読むスレッドは、落とすときに終わりを待つ。先に子プロセスを止めて出力を閉じないと待ち続ける。
                子プロセス.止めて終わりを待つ();
                Err(期限付きの待ちの失敗::起動できない(原因))
            }
        }
    }

    /// 子プロセスが終わるまで待ち、出力を集める。期限を過ぎるか取り消されたら、子プロセスを止めて失敗を返す。
    pub(crate) fn 終わるまで待つ(
        mut self,
        期限: Duration,
        合図: &取り消しの合図,
    ) -> Result<集めた出力, 期限付きの待ちの失敗> {
        let 始め = Instant::now();
        let 終了状態 = loop {
            match self.子プロセス.終わったかを確かめる() {
                Ok(Some(終了状態)) => break 終了状態,
                Ok(None) => {}
                Err(原因) => return Err(self.止めて返す(期限付きの待ちの失敗::待てない(原因))),
            }
            if 合図.取り消されたか() {
                return Err(self.止めて返す(期限付きの待ちの失敗::取り消した));
            }
            if 始め.elapsed() >= 期限 {
                return Err(self.止めて返す(期限付きの待ちの失敗::時間切れ));
            }
            std::thread::sleep(見回りの間隔);
        };
        let 標準エラーの末尾 = self.標準エラー.読み終えるまで待つ();
        let 標準出力 = self
            .標準出力
            .終わるまで待つ()
            .unwrap_or_else(|| Err(io::Error::other("標準出力を読むスレッドが異常終了した")))
            .map_err(期限付きの待ちの失敗::出力を読めない)?;
        Ok(集めた出力 {
            終了状態,
            標準出力,
            標準エラーの末尾,
        })
    }

    /// 子プロセスを止めて終わりを待ち、渡された失敗を返す。パイプが閉じるため、読むスレッドも終わる。
    fn 止めて返す(
        &mut self, 失敗: 期限付きの待ちの失敗
    ) -> 期限付きの待ちの失敗 {
        self.子プロセス.止めて終わりを待つ();
        失敗
    }
}

fn 全部読む(mut 出力: ChildStdout) -> io::Result<Vec<u8>> {
    let mut 中身 = Vec::new();
    出力.read_to_end(&mut 中身)?;
    Ok(中身)
}
