//! ffmpeg の起動と、その出力を読む仕組みの組み立て。

use super::child::起動した子プロセス;
use super::error::デコードの失敗;
use super::frame_reader::コマの読み手;
use super::spec::デコードの指定;
use super::stderr_tail::標準エラーの収集;
use crate::locate::FFmpegの実行ファイル;

/// 起動したデコードとは、起動した ffmpeg の子プロセスと、その出力を読む仕組みの組のことである。
/// 受け取った側は子プロセスを止める時機を決める。落とせば止まる。
pub(crate) struct 起動したデコード {
    pub(crate) 子プロセス: 起動した子プロセス,
    pub(crate) 読み手: コマの読み手,
    pub(crate) 標準エラー: 標準エラーの収集,
}

impl 起動したデコード {
    /// 指定のとおりに ffmpeg を起動する。標準出力と標準エラー出力はパイプで受け取る。
    /// 読む仕組みを作れなければ、起動した ffmpeg は落とされて止まる。
    pub(crate) fn 起動する(
        指定: &デコードの指定,
        実行ファイル: &FFmpegの実行ファイル,
    ) -> Result<Self, デコードの失敗> {
        let mut 命令 = 実行ファイル.変換の命令();
        命令.args(指定.引数を並べる());
        let (子プロセス, パイプ) =
            起動した子プロセス::起動する(&mut 命令).map_err(デコードの失敗::起動できない)?;
        let 読み手 = コマの読み手::作成する(パイプ.標準出力, 指定.出力の寸法)
            .map_err(デコードの失敗::起動できない)?;
        let 標準エラー =
            標準エラーの収集::起動する(パイプ.標準エラー).map_err(デコードの失敗::起動できない)?;
        Ok(Self {
            子プロセス,
            読み手,
            標準エラー,
        })
    }
}
