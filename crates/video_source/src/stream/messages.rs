//! 流し読みの裏のスレッドが送る知らせと、受け取ったコマの型。

use clip_domain::動画上の秒;

use crate::frame::コマ;
use crate::frame_number::動画上のコマ番号;
use crate::process::標準エラーの末尾;

/// 流し読みのコマとは、流し読みで受け取ったコマと、その動画上のコマ番号と、表示が始まる動画上の時刻の組のことである。
#[derive(Debug)]
pub struct 流し読みのコマ {
    番号: 動画上のコマ番号,
    時刻: 動画上の秒,
    コマ: コマ,
}

impl 流し読みのコマ {
    pub(crate) fn 作成する(
        番号: 動画上のコマ番号, 時刻: 動画上の秒, コマ: コマ
    ) -> Self {
        Self {
            番号, 時刻, コマ
        }
    }

    /// 動画上のコマ番号。画面は前のフレームと比べ、同じコマなら GPU へ載せ直さずに済ませる。
    /// 前提: 番号が同じなら同じ画像であるのは、同じ動画を同じ長辺の上限で読んだときだけである(`番号付きのコマ` と同じ)。
    pub fn 番号(&self) -> 動画上のコマ番号 {
        self.番号
    }

    /// このコマの表示が始まる動画上の時刻。
    pub fn 時刻(&self) -> 動画上の秒 {
        self.時刻
    }

    /// コマ。
    pub fn コマ(&self) -> &コマ {
        &self.コマ
    }
}

/// 流し読みの知らせとは、裏のスレッドが通り道へ送る、コマか読み終わりの区別のことである。
pub(crate) enum 流し読みの知らせ {
    コマ(流し読みのコマ),
    出力が閉じた(標準エラーの末尾),
    読めない {
        原因: std::io::Error,
        標準エラーの末尾: 標準エラーの末尾,
    },
}
