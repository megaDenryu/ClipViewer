//! 流し読みの公開の口。

use clip_domain::動画上の秒;

use super::ending::{流し読みの状態, 読み取りの状況};
use super::messages::{流し読みのコマ, 流し読みの知らせ};
use super::reader_thread::{流し読みの読み取り, 起動した流し読み};
use crate::locate::FFmpegの実行ファイル;
use crate::long_side::長辺の上限;
use crate::process::{デコードの失敗, デコードの指定, 起動したデコード};
use crate::video_info::動画の情報;

/// 流し読みとは、開始の時刻から動画の終わりまでを裏のスレッドで順にデコードし、画面が時刻に合うコマを取り出すもののことである。
/// シークするときは、これを落として新しく開く。落とすと ffmpeg を止め、裏のスレッドの終わりを待つ。
pub struct 流し読み {
    起動した流し読み: 起動した流し読み,
    今のコマ: Option<流し読みのコマ>,
    次のコマ: Option<流し読みのコマ>,
    読み取りの状況: 読み取りの状況,
}

impl 流し読み {
    pub(crate) fn 開く(
        実行ファイル: &FFmpegの実行ファイル,
        動画: &動画の情報,
        開始: 動画上の秒,
        上限: 長辺の上限,
    ) -> Result<Self, デコードの失敗> {
        let 指定 = デコードの指定::終わりまで流し読む(動画, 開始, 上限);
        let 起動したデコード {
            子プロセス,
            読み手,
            標準エラー,
        } = 起動したデコード::起動する(&指定, 実行ファイル)?;
        let (先頭のコマ, コマの速さ) = (指定.先頭のコマ, 指定.コマの速さ);
        let 読み取り = 流し読みの読み取り {
            読み手,
            標準エラー,
            先頭のコマ,
            コマの速さ,
        };
        let 起動した流し読み = 起動した流し読み::読み始める(子プロセス, 読み取り)
            .map_err(デコードの失敗::起動できない)?;
        let (今のコマ, 次のコマ) = (None, None);
        Ok(Self {
            起動した流し読み,
            今のコマ,
            次のコマ,
            読み取りの状況: 読み取りの状況::読んでいる,
        })
    }

    /// その時刻に出すコマを取り出す。待たずに返る。届いたコマのうち、表示の始まりがその時刻以前の最後のコマである。
    /// 最初のコマがまだ届いていなければ `None` である。時刻を戻しても前のコマには戻らない(戻すときは開き直す)。
    pub fn その時刻に出すコマ(
        &mut self,
        位置: 動画上の秒,
    ) -> Option<&流し読みのコマ> {
        loop {
            if self.次のコマ.is_none() {
                self.次のコマ = self.知らせを一つ受け取る();
            }
            match &self.次のコマ {
                Some(次) if 次.時刻() <= 位置 => self.今のコマ = self.次のコマ.take(),
                _ => break,
            }
        }
        self.今のコマ.as_ref()
    }

    /// 読み終わったかを問い合わせる。待たずに返る。
    pub fn 状態(&mut self) -> 流し読みの状態<'_> {
        if self.次のコマ.is_none() {
            self.次のコマ = self.知らせを一つ受け取る();
        }
        self.読み取りの状況.状態()
    }

    /// 知らせを1つ受け取り、コマならそれを返す。出力が閉じたか読めない知らせなら、読み取りの状況を記録する。
    /// 注意: 次のコマが空のときだけ呼ぶこと。出力が閉じた後の判定は、それまでのコマが今のコマへ移っている前提で行う。
    fn 知らせを一つ受け取る(&mut self) -> Option<流し読みのコマ> {
        let 標準エラーの末尾 = match self.起動した流し読み.知らせを受け取る()? {
            流し読みの知らせ::コマ(コマ) => return Some(コマ),
            流し読みの知らせ::読めない {
                原因,
                標準エラーの末尾,
            } => {
                let 失敗 = デコードの失敗::出力を読めない {
                    原因,
                    標準エラーの末尾,
                };
                self.読み取りの状況 = 読み取りの状況::失敗(失敗);
                return None;
            }
            流し読みの知らせ::出力が閉じた(末尾) => 末尾,
        };
        let 終了状態 = self.起動した流し読み.終わりを待つ();
        let コマを受け取ったか = self.今のコマ.is_some();
        self.読み取りの状況 = 読み取りの状況::出力が閉じた後に決める(
            終了状態,
            標準エラーの末尾,
            コマを受け取ったか,
        );
        None
    }
}
