//! 流し読みの裏のスレッド。ffmpeg の出力を1コマずつ読み、時刻を付けて上限付きの通り道へ送る。

use std::io;
use std::process::ExitStatus;
use std::sync::mpsc::{self, Receiver, SyncSender};

use super::messages::{流し読みのコマ, 流し読みの知らせ};
use crate::frame_number::{コマ数, 動画上のコマ番号};
use crate::frame_rate::コマの速さ;
use crate::process::{
    コマの読み手, 標準エラーの収集, 終わりを待つスレッド, 起動した子プロセス
};

/// 通り道に溜めてよいコマの数。これを超えると裏のスレッドは送る所で待ち、ffmpeg も出力のパイプで止まる。
const 通り道の容量: usize = 4;

/// 起動した流し読みとは、流し読みの ffmpeg の子プロセスと、その出力を読む裏のスレッドと、そこから知らせを受け取る口の組のことである。
/// 落とすと、ffmpeg を止め、送り口が閉じるまで知らせを受け取って捨て、スレッドの終わりを待つ。
pub(crate) struct 起動した流し読み {
    子プロセス: 起動した子プロセス,
    受け口: Receiver<流し読みの知らせ>,
    スレッド: 終わりを待つスレッド<()>,
}

/// 流し読みの読み取りとは、裏のスレッドで ffmpeg の出力を読み、時刻を付けて通り道へ送る仕事のことである。
pub(crate) struct 流し読みの読み取り {
    pub(crate) 読み手: コマの読み手,
    pub(crate) 標準エラー: 標準エラーの収集,
    pub(crate) 先頭のコマ: 動画上のコマ番号,
    pub(crate) コマの速さ: コマの速さ,
}

impl 起動した流し読み {
    /// 読み取りを裏のスレッドで始める。スレッドを起動できなければ、読む者がいない ffmpeg を置き去りにせず止める。
    pub(crate) fn 読み始める(
        mut 子プロセス: 起動した子プロセス,
        読み取り: 流し読みの読み取り,
    ) -> io::Result<Self> {
        let (送り口, 受け口) = mpsc::sync_channel(通り道の容量);
        match 終わりを待つスレッド::起動する("流し読み", move || {
            読み取り.読み続ける(送り口)
        }) {
            Ok(スレッド) => Ok(Self {
                子プロセス,
                受け口,
                スレッド,
            }),
            Err(原因) => {
                子プロセス.止めて終わりを待つ();
                Err(原因)
            }
        }
    }

    /// 出力が閉じた後に、ffmpeg が終わるのを待って終了状態を受け取る。
    pub(crate) fn 終わりを待つ(&mut self) -> io::Result<ExitStatus> {
        self.子プロセス.終わりを待つ()
    }

    /// 届いている知らせを1つ、待たずに受け取る。
    pub(crate) fn 知らせを受け取る(&self) -> Option<流し読みの知らせ> {
        self.受け口.try_recv().ok()
    }
}

impl Drop for 起動した流し読み {
    fn drop(&mut self) {
        self.子プロセス.止めて終わりを待つ();
        // 通り道が詰まって送る所で待っている裏のスレッドを通すため、送り口が落とされるまで受け取って捨てる。
        for _ in self.受け口.iter() {}
        self.スレッド.終わるまで待つ();
    }
}

impl 流し読みの読み取り {
    /// 出力が閉じるか、受け口が落とされるまで読み続ける。通り道が詰まっている間は送る所で待つ。
    fn 読み続ける(mut self, 送り口: SyncSender<流し読みの知らせ>) {
        let mut 読んだコマ数 = コマ数::ゼロ;
        loop {
            let 知らせ = match self.読み手.次のコマを読む() {
                Ok(Some(コマ)) => {
                    let 番号 = self.先頭のコマ.進める(読んだコマ数);
                    読んだコマ数 = 読んだコマ数.一つ増やす();
                    let 時刻 = self.コマの速さ.コマの始まる時刻(番号);
                    流し読みの知らせ::コマ(流し読みのコマ::作成する(番号, 時刻, コマ))
                }
                Ok(None) => 流し読みの知らせ::出力が閉じた(
                    self.標準エラー.読み終えるまで待つ(),
                ),
                Err(原因) => {
                    let 標準エラーの末尾 = self.標準エラー.読み終えるまで待つ();
                    流し読みの知らせ::読めない {
                        原因,
                        標準エラーの末尾,
                    }
                }
            };
            let 最後か = !matches!(知らせ, 流し読みの知らせ::コマ(_));
            // 送れないのは流し読みが閉じられた後なので、受け取る者はいない。子プロセスは閉じる側が止める。
            if 送り口.send(知らせ).is_err() || 最後か {
                return;
            }
        }
    }
}
