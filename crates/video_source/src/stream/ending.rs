//! 流し読みが読み終わったかの判定と、その公開の状態。

use std::io;
use std::process::ExitStatus;

use crate::process::{デコードの失敗, 標準エラーの末尾};

/// 流し読みの状態とは、流し読みが動画の終わりまで読んだか、失敗したかの区別のことである。
#[derive(Debug)]
pub enum 流し読みの状態<'流し読み> {
    /// まだ読んでいる。
    読んでいる,
    /// 動画の終わりまで読んだ。最後のコマを出し続ける。
    終わりまで読んだ,
    /// デコードに失敗した。
    失敗(&'流し読み デコードの失敗),
}

/// 読み取りの状況とは、流し読みの ffmpeg の出力をまだ読んでいるか、終わりまで読んだか、失敗したかの区別のことである。
pub(crate) enum 読み取りの状況 {
    読んでいる,
    終わりまで読んだ,
    失敗(デコードの失敗),
}

impl 読み取りの状況 {
    /// 出力が閉じた後の ffmpeg の終了状態から、終わりまで読んだか失敗したかを決める。
    pub(crate) fn 出力が閉じた後に決める(
        終了状態: io::Result<ExitStatus>,
        標準エラーの末尾: 標準エラーの末尾,
        コマを受け取ったか: bool,
    ) -> Self {
        let 失敗 = match 終了状態 {
            Err(原因) => デコードの失敗::出力を読めない {
                原因,
                標準エラーの末尾,
            },
            Ok(終了状態) if !終了状態.success() => デコードの失敗::異常終了 {
                終了状態,
                標準エラーの末尾,
            },
            Ok(_) if !コマを受け取ったか => デコードの失敗::コマが無い {
                標準エラーの末尾,
            },
            Ok(_) => return Self::終わりまで読んだ,
        };
        Self::失敗(失敗)
    }

    pub(crate) fn 状態(&self) -> 流し読みの状態<'_> {
        match self {
            Self::読んでいる => 流し読みの状態::読んでいる,
            Self::終わりまで読んだ => 流し読みの状態::終わりまで読んだ,
            Self::失敗(失敗) => 流し読みの状態::失敗(失敗),
        }
    }
}
