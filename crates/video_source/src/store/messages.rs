//! 裏のスレッドがコマの倉庫へ送る報告の型。

use std::io;
use std::process::ExitStatus;

use crate::frame::コマ;
use crate::frame_number::コマ数;
use crate::process::{デコードの失敗, 標準エラーの末尾};

use super::ticket::受付の札;

/// 倉庫への報告とは、裏のスレッドがコマの倉庫へ送る、依頼の進み具合と結果の区別のことである。
pub(crate) enum 倉庫への報告 {
    進んだ {
        札: 受付の札,
        溜めたコマ数: コマ数,
    },
    溜め終えた {
        札: 受付の札,
        コマの並び: Vec<コマ>,
    },
    失敗した {
        札: 受付の札,
        失敗: デコードの失敗,
    },
    取り消された(受付の札),
}

impl 倉庫への報告 {
    /// 読み終えた結果と ffmpeg の終了状態から、溜め終えたか失敗したかの報告を作る。取り消されていないことを確かめた後に使う。
    pub(crate) fn 読み終えた結果から作る(
        札: 受付の札,
        読んだ結果: io::Result<Vec<コマ>>,
        終了状態: Option<io::Result<ExitStatus>>,
        標準エラーの末尾: 標準エラーの末尾,
    ) -> Self {
        let 失敗 = match (読んだ結果, 終了状態) {
            (Err(原因), _) | (Ok(_), Some(Err(原因))) => {
                デコードの失敗::出力を読めない {
                    原因,
                    標準エラーの末尾,
                }
            }
            (Ok(_), Some(Ok(終了状態))) if !終了状態.success() => {
                デコードの失敗::異常終了 {
                    終了状態,
                    標準エラーの末尾,
                }
            }
            (Ok(コマの並び), _) if コマの並び.is_empty() => {
                デコードの失敗::コマが無い {
                    標準エラーの末尾
                }
            }
            (Ok(コマの並び), _) => {
                return Self::溜め終えた {
                    札, コマの並び
                };
            }
        };
        Self::失敗した { 札, 失敗 }
    }
}
