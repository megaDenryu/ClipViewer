//! コマの倉庫が依頼に返す結果と、依頼の状況の型。

use crate::bytes::{バイト数, メモリの上限};
use crate::frame_number::コマ数;
use crate::process::デコードの失敗;

use super::ticket::受付の札;

/// 溜める依頼の結果とは、区間を溜める依頼を受け付けたか、受け付けなかったかの区別のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 溜める依頼の結果 {
    /// 受け付けた。同じ区間の依頼が既にあれば、その札を返す。
    受け付けた(受付の札),
    /// 受け付けなかった。画面はこの区間を流し読みで表示する。
    受け付けない(受け付けない理由),
}

/// 受け付けない理由とは、コマの倉庫が区間を溜める依頼を受け付けなかった理由のことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 受け付けない理由 {
    /// 区間の中で表示が始まるコマが無い(長さ0の区間や、動画の終わりより後ろの区間)。
    区間にコマが無い,
    /// 見積もりがメモリの上限の全体を超える。
    上限の全体を超える {
        /// 区間を溜めるのに必要な大きさ。
        見積もり: バイト数,
        /// メモリの上限。
        上限: メモリの上限,
    },
    /// 保持の優先順がこの区間より高い区間を捨てないと、空きを作れない。
    優先順の高い区間で埋まっている {
        /// 区間を溜めるのに必要な大きさ。
        見積もり: バイト数,
        /// 優先順の低い区間をすべて捨てたときの空きの大きさ。
        作れる空き: バイト数,
    },
    /// デコードする裏のスレッドが止まっている。スレッドが異常終了したときに起きる。
    裏のスレッドが止まっている,
}

/// 依頼の状況とは、受付の札が指す依頼が今どうなっているかの区別のことである。
#[derive(Debug)]
pub enum 依頼の状況<'倉庫> {
    /// 順番を待っている。
    処理待ち,
    /// デコードしている。
    処理中 {
        /// 読み終えたコマの数。
        溜めたコマ数: コマ数,
        /// 読む予定のコマの数。
        見込みのコマ数: コマ数,
    },
    /// 溜め終えた。溜めたコマを取り出せる。
    完了(溜め終えた内訳),
    /// デコードに失敗した。
    失敗(&'倉庫 デコードの失敗),
    /// 札で取り消された。
    取り消した,
    /// 空きを作るため、または区間の破棄の依頼で捨てられた。
    捨てた,
    /// この倉庫が発行していない札である。
    知らない札,
}

/// 溜め終えた内訳とは、溜め終えた依頼の、実際に溜めたコマ数と見積もりのコマ数の組のことである。
/// ffmpeg は区間の終わりが動画の終わりに近いとき等に、見積もりより少ないコマしか出さないことがある。
/// 少なくても失敗にはせず、取り出す口は溜めたコマの最後を返す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 溜め終えた内訳 {
    /// 実際に溜めたコマの数。
    pub 溜めたコマ数: コマ数,
    /// 見積もりのコマの数。
    pub 見込みのコマ数: コマ数,
}

impl 溜め終えた内訳 {
    /// 見積もりより少ないコマしか溜められなかったか。
    pub fn 見積もりより少なかったか(&self) -> bool {
        self.溜めたコマ数 < self.見込みのコマ数
    }
}

/// 倉庫を開くエラーとは、コマの倉庫を開けなかった理由のことである。
#[derive(Debug, thiserror::Error)]
pub enum 倉庫を開くエラー {
    /// デコードする裏のスレッドを起動できなかった。
    #[error("コマの倉庫のスレッドを起動できない: {0}")]
    スレッドを起動できない(#[source] std::io::Error),
}
