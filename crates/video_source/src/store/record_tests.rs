//! 依頼の記録の試験。処理待ちの取り消しと区間の破棄による予約の解放と結末を、FFmpeg を使わずに確かめる。

use super::outcome::依頼の状況;
use super::results::終わった依頼の結末;
use super::test_support::{一秒分, 区間, 受け付ける, 受付と記録, 新しい札};
use crate::bytes::バイト数;

#[test]
fn 処理待ちの取り消しと区間の破棄は予約を解放し_結末を残す() {
    let (mut 受付, mut 記録) = 受付と記録(10);
    let 取り消す札 = 新しい札(受け付ける(&mut 受付, &mut 記録, 0.0));
    let 捨てる札 = 新しい札(受け付ける(&mut 受付, &mut 記録, 5.0));
    assert_eq!(記録.予約の合計(), バイト数::作成する(一秒分 * 2));
    let 外した状態 = 記録.項目を外す(取り消す札, 終わった依頼の結末::取り消した);
    assert!(外した状態.is_some_and(|状態| 状態.溜め終えていないか()));
    assert_eq!(記録.区間の札(&区間(5.0)), Some(捨てる札));
    記録.項目を外す(捨てる札, 終わった依頼の結末::捨てた);
    assert_eq!(記録.予約の合計(), バイト数::ゼロ);
    assert!(matches!(記録.状況(取り消す札), 依頼の状況::取り消した));
    assert!(matches!(記録.状況(捨てる札), 依頼の状況::捨てた));
}
