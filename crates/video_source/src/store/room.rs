//! 保持の規則。新しい区間を溜める空きを作るために、どの項目を捨てるかを決める。

use clip_domain::動画上の区間;

use crate::bytes::{バイト数, メモリの上限};

use super::entry::倉庫の項目;
use super::outcome::受け付けない理由;
use super::priority::{保持の優先順, 保持の順位};
use super::ticket::受付の札;

/// 保持の規則とは、保持の優先順とメモリの上限の組のことであり、空きを作るために捨てる項目を決める。
pub(crate) struct 保持の規則 {
    優先順: 保持の優先順,
    上限: メモリの上限,
}

/// 捨てる候補とは、捨てる札を選ぶ計算に渡す、倉庫の項目の札・順位・予約の大きさの組のことである。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 捨てる候補 {
    pub(crate) 札: 受付の札,
    pub(crate) 順位: 保持の順位,
    pub(crate) 大きさ: バイト数,
}

impl 保持の規則 {
    pub(crate) fn 作成する(上限: メモリの上限) -> Self {
        Self {
            優先順: 保持の優先順::default(),
            上限,
        }
    }

    pub(crate) fn 優先順を置き換える(&mut self, 優先順: 保持の優先順) {
        self.優先順 = 優先順;
    }

    /// 新しい区間を溜める空きを作るために捨てる札を、捨てる順に求める。項目の並びは受け付けた順で渡すこと。
    pub(crate) fn 空きを作るために捨てる札(
        &self,
        項目の並び: &[倉庫の項目],
        区間: &動画上の区間,
        見積もり: バイト数,
    ) -> Result<Vec<受付の札>, 受け付けない理由> {
        let 候補にする = |項目: &倉庫の項目| 捨てる候補 {
            札: 項目.札,
            順位: self.優先順.順位(&項目.区間),
            大きさ: 項目.見積もり.バイト数(),
        };
        let 候補の並び: Vec<捨てる候補> = 項目の並び.iter().map(候補にする).collect();
        捨てる札を選ぶ(&候補の並び, self.優先順.順位(区間), 見積もり, self.上限)
    }
}

/// 捨ててよいのは新しい区間より順位の低い項目だけであり、低いものから捨てる(同じ順位なら先に並んだものから)。
pub(crate) fn 捨てる札を選ぶ(
    候補の並び: &[捨てる候補],
    新しい順位: 保持の順位,
    見積もり: バイト数,
    上限: メモリの上限,
) -> Result<Vec<受付の札>, 受け付けない理由> {
    if !上限.収まるか(見積もり) {
        return Err(受け付けない理由::上限の全体を超える {
            見積もり, 上限
        });
    }
    let 予約の合計 = 候補の並び
        .iter()
        .fold(バイト数::ゼロ, |合計, 候補| 合計.足す(候補.大きさ));
    let mut 空き = 上限.大きさ().差し引く(予約の合計);
    let mut 捨てられる: Vec<&捨てる候補> = 候補の並び
        .iter()
        .filter(|候補| 候補.順位 < 新しい順位)
        .collect();
    捨てられる.sort_by_key(|候補| 候補.順位);
    let mut 捨てる札 = Vec::new();
    for 候補 in 捨てられる {
        if 見積もり <= 空き {
            break;
        }
        空き = 空き.足す(候補.大きさ);
        捨てる札.push(候補.札);
    }
    if 見積もり <= 空き {
        Ok(捨てる札)
    } else {
        Err(受け付けない理由::優先順の高い区間で埋まっている {
            見積もり,
            作れる空き: 空き,
        })
    }
}
