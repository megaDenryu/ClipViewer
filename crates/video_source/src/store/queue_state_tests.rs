//! 待ち行列の中身の状態の移り変わりの試験。FFmpeg を使わない。

use super::priority::保持の優先順;
use super::queue_state::{処理待ちの依頼, 待ち行列の中身};
use super::test_support::{動画, 区間};
use super::ticket::{受付の札, 札の発行元};
use crate::long_side::長辺の上限;
use crate::process::デコードの指定;

/// 開始の秒の区間の処理待ちの依頼を、新しい札で作る。
fn 依頼(発行元: &mut 札の発行元, 開始: f64) -> 処理待ちの依頼 {
    let 動画 = 動画();
    let 見積もり = 動画.区間を見積もる(&区間(開始), 長辺の上限::既定);
    let 指定 = デコードの指定::区間を読む(&動画, &見積もり);
    処理待ちの依頼 {
        札: 発行元.発行する(),
        区間: 区間(開始),
        指定,
    }
}

/// 開始の秒の区間を1つずつ積んだ中身と、積んだ順の札を作る。
fn 積んだ中身(開始の並び: &[f64]) -> (待ち行列の中身, Vec<受付の札>) {
    let mut 発行元 = 札の発行元::default();
    let mut 中身 = 待ち行列の中身::default();
    let mut 札 = Vec::new();
    for 開始 in 開始の並び {
        let 一つ = 依頼(&mut 発行元, *開始);
        札.push(一つ.札);
        中身.積む(一つ);
    }
    (中身, 札)
}

#[test]
fn 取り出した後に取り消すと_終えるときに取り消されていたと返す() {
    let (mut 中身, 札) = 積んだ中身(&[0.0]);
    assert!(
        中身
            .次の依頼を取り出す()
            .is_some_and(|依頼| 依頼.札 == 札[0])
    );
    中身.取り消す(札[0]);
    assert!(中身.実行を終えて取り消されていたかを返す());
}

#[test]
fn 他の札の取り消しでは実行中の依頼は取り消されない() {
    let (mut 中身, 札) = 積んだ中身(&[0.0, 5.0]);
    assert!(
        中身
            .次の依頼を取り出す()
            .is_some_and(|依頼| 依頼.札 == 札[0])
    );
    中身.取り消す(札[1]);
    assert!(!中身.実行を終えて取り消されていたかを返す());
}

#[test]
fn 処理待ちの取り消しで待ち行列から外れる() {
    let (mut 中身, 札) = 積んだ中身(&[0.0, 5.0, 9.0]);
    中身.取り消す(札[1]);
    let 取り出した札: Vec<受付の札> = std::iter::from_fn(|| {
        let 依頼 = 中身.次の依頼を取り出す()?;
        中身.実行を終えて取り消されていたかを返す();
        Some(依頼.札)
    })
    .collect();
    assert_eq!(取り出した札, vec![札[0], 札[2]]);
}

#[test]
fn すべて止めた後は止めるかが真になり_処理待ちを取り出さない() {
    let (mut 中身, _) = 積んだ中身(&[0.0, 5.0]);
    assert!(!中身.止めるか());
    中身.すべて止める();
    assert!(中身.止めるか());
    assert!(中身.次の依頼を取り出す().is_none());
}

#[test]
fn 優先順を置き換えると次に取り出す依頼が変わる() {
    let (mut 中身, 札) = 積んだ中身(&[0.0, 5.0]);
    中身.優先順を置き換える(保持の優先順::作成する(vec![区間(5.0)]));
    assert!(
        中身
            .次の依頼を取り出す()
            .is_some_and(|依頼| 依頼.札 == 札[1])
    );
}
