//! 依頼の受付と依頼の記録の試験で共通に使う道具。FFmpeg を使わない。

use clip_domain::{入力された動画パス, 動画上の区間, 時刻};

use super::intake::{依頼の受付, 受け付けた依頼};
use super::outcome::受け付けない理由;
use super::record::依頼の記録;
use super::ticket::受付の札;
use crate::bytes::{バイト数, メモリの上限};
use crate::long_side::長辺の上限;
use crate::video_info::動画の情報;

/// 10×10画素・10コマ/秒の動画の1秒の区間は、10コマ×400バイト = 4,000バイトである。
pub(super) const 一秒分: u64 = 4_000;

pub(super) fn 動画() -> 動画の情報 {
    let パス = 入力された動画パス::作成する("C:/動画/試験.mp4".to_string()).正規化する();
    let 本文 = r#"{"streams":[{"index":0,"codec_type":"video","width":10,"height":10,"avg_frame_rate":"10/1","duration":"100"}]}"#;
    let Ok(情報) = 動画の情報::調査の出力から作る(パス, 本文) else {
        panic!("動画の情報を作れない")
    };
    情報
}

pub(super) fn 区間(開始: f64) -> 動画上の区間 {
    let (Ok(開始), Ok(終了)) = (時刻::作成する(開始), 時刻::作成する(開始 + 1.0))
    else {
        panic!("時刻を作れない")
    };
    let Ok(区間) = 動画上の区間::作成する(開始, 終了) else {
        panic!("区間を作れない")
    };
    区間
}

/// 上限が指定の秒数分の受付と、空の記録を作る。
pub(super) fn 受付と記録(秒数分: u64) -> (依頼の受付, 依頼の記録) {
    (
        依頼の受付::作成する(メモリの上限::作成する(バイト数::作成する(
            一秒分 * 秒数分,
        ))),
        依頼の記録::default(),
    )
}

pub(super) fn 受け付ける(
    受付: &mut 依頼の受付,
    記録: &mut 依頼の記録,
    開始: f64,
) -> Result<受け付けた依頼, 受け付けない理由> {
    受付.受け付ける(
        記録,
        区間(開始),
        動画().区間を見積もる(&区間(開始), 長辺の上限::既定),
    )
}

pub(super) fn 新しい札(
    結果: Result<受け付けた依頼, 受け付けない理由>
) -> 受付の札 {
    let Ok(受け付けた依頼::新しく加えた { 札, .. }) = 結果 else {
        panic!("新しく受け付けられなかった")
    };
    札
}
