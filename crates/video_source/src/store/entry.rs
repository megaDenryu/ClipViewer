//! 倉庫の項目の型。

use clip_domain::動画上の区間;

use crate::estimate::区間の見積もり;
use crate::frame_number::コマ数;

use super::outcome::{依頼の状況, 溜め終えた内訳};
use super::stored::溜めた区間;
use super::ticket::受付の札;

/// 倉庫の項目とは、受け付けて、まだ取り消されも捨てられもしていない1つの依頼のことである。
/// 項目は溜め終える前から見積もりの大きさをメモリの予約として数える。
#[derive(Debug)]
pub(crate) struct 倉庫の項目 {
    pub(crate) 札: 受付の札,
    pub(crate) 区間: 動画上の区間,
    pub(crate) 見積もり: 区間の見積もり,
    pub(crate) 状態: 項目の状態,
}

/// 項目の状態とは、倉庫の項目のデコードの進み具合の区別のことである。
#[derive(Debug)]
pub(crate) enum 項目の状態 {
    処理待ち,
    処理中 { 溜めたコマ数: コマ数 },
    溜めた(溜めた区間),
}

impl 倉庫の項目 {
    pub(crate) fn 処理待ちで作る(
        札: 受付の札,
        区間: 動画上の区間,
        見積もり: 区間の見積もり,
    ) -> Self {
        Self {
            札,
            区間,
            見積もり,
            状態: 項目の状態::処理待ち,
        }
    }

    pub(crate) fn 状況(&self) -> 依頼の状況<'_> {
        match &self.状態 {
            項目の状態::処理待ち => 依頼の状況::処理待ち,
            項目の状態::処理中 { 溜めたコマ数 } => 依頼の状況::処理中 {
                溜めたコマ数: *溜めたコマ数,
                見込みのコマ数: self.見積もり.コマ数(),
            },
            項目の状態::溜めた(溜めた区間) => {
                依頼の状況::完了(溜め終えた内訳 {
                    溜めたコマ数: 溜めた区間.コマ数(),
                    見込みのコマ数: self.見積もり.コマ数(),
                })
            }
        }
    }
}

impl 項目の状態 {
    /// 溜め終えていないか。溜め終えていない依頼は、外すときに裏のスレッドで止める必要がある。
    pub(crate) fn 溜め終えていないか(&self) -> bool {
        !matches!(self, Self::溜めた(_))
    }
}
