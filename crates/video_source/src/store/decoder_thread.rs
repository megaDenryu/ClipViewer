//! コマの倉庫が持つ、区間をデコードする裏のスレッドと、それとの連絡の口。

use std::io;
use std::sync::mpsc::{self, Receiver};

use clip_domain::動画上の区間;

use crate::locate::FFmpegの実行ファイル;
use crate::process::{デコードの指定, 終わりを待つスレッド};

use super::intake::受け付けた依頼;
use super::messages::倉庫への報告;
use super::outcome::{受け付けない理由, 溜める依頼の結果};
use super::priority::保持の優先順;
use super::queue::依頼の待ち行列;
use super::queue_state::処理待ちの依頼;
use super::record::依頼の記録;
use super::results::終わった依頼の結末;
use super::ticket::受付の札;
use super::worker::区間を溜める作業;

/// 区間をデコードする裏のスレッドとは、依頼の待ち行列から保持の優先順で依頼を取り出して ffmpeg で区間を読む裏のスレッドと、
/// 待ち行列・報告を受ける口の組のことである。
/// 落とすと、実行中の ffmpeg を止め、処理を待つ依頼を捨て、スレッドの終わりを待つ。
pub(crate) struct 区間をデコードする裏のスレッド {
    待ち行列: 依頼の待ち行列,
    報告の受け口: Receiver<倉庫への報告>,
    スレッド: 終わりを待つスレッド<()>,
}

impl 区間をデコードする裏のスレッド {
    /// 裏のスレッドを起動する。
    pub(crate) fn 起動する(
        実行ファイル: FFmpegの実行ファイル
    ) -> io::Result<Self> {
        let (報告の送り口, 報告の受け口) = mpsc::channel();
        let 待ち行列 = 依頼の待ち行列::default();
        let 作業 = 区間を溜める作業 {
            実行ファイル,
            待ち行列: 待ち行列.clone(),
            報告の送り口,
        };
        let スレッド =
            終わりを待つスレッド::起動する("コマの倉庫のデコード", move || {
                作業.依頼を待ち続ける()
            })?;
        Ok(Self {
            待ち行列,
            報告の受け口,
            スレッド,
        })
    }

    /// 裏のスレッドが次の依頼を選ぶときに使う保持の優先順を置き換える。
    pub(crate) fn 優先順を置き換える(&self, 優先順: 保持の優先順) {
        self.待ち行列.優先順を置き換える(優先順);
    }

    /// 新しく受け付けた依頼を待ち行列へ積み、空きを作るために捨てた依頼を止める。既にあった依頼は積み直さない。
    /// スレッドが異常終了していれば、項目を記録から外して受け付けない。
    pub(crate) fn 受け付けた依頼を送る(
        &self,
        記録: &mut 依頼の記録,
        受付: 受け付けた依頼,
        区間: 動画上の区間,
        指定: デコードの指定,
    ) -> 溜める依頼の結果 {
        let (札, 止める札) = match 受付 {
            受け付けた依頼::既にある(札) => {
                return 溜める依頼の結果::受け付けた(札);
            }
            受け付けた依頼::新しく加えた { 札, 止める札 } => (札, 止める札),
        };
        for 止める in 止める札 {
            self.待ち行列.取り消す(止める);
        }
        if self.スレッド.終わったか() {
            記録.項目を外す(札, 終わった依頼の結末::取り消した);
            return 溜める依頼の結果::受け付けない(
                受け付けない理由::裏のスレッドが止まっている,
            );
        }
        self.待ち行列.積む(処理待ちの依頼 {
            札, 区間, 指定
        });
        溜める依頼の結果::受け付けた(札)
    }

    /// 届いている報告を、待たずにすべて記録へ反映する。
    pub(crate) fn 報告を記録へ反映する(&self, 記録: &mut 依頼の記録) {
        for 報告 in self.報告の受け口.try_iter() {
            記録.報告を反映する(報告);
        }
    }

    /// 札の項目を記録から外し、溜め終えていない依頼なら待ち行列から外すか ffmpeg を止める。
    pub(crate) fn 項目を外して止める(
        &self,
        記録: &mut 依頼の記録,
        札: 受付の札,
        結末: 終わった依頼の結末,
    ) {
        if let Some(状態) = 記録.項目を外す(札, 結末)
            && 状態.溜め終えていないか()
        {
            self.待ち行列.取り消す(札);
        }
    }
}

impl Drop for 区間をデコードする裏のスレッド {
    fn drop(&mut self) {
        self.待ち行列.すべて止める();
        self.スレッド.終わるまで待つ();
    }
}
