//! 依頼の記録。受け付けた依頼の項目と、外れた依頼の結末を記録する。裏のスレッドにも ffmpeg にも触らない。

use clip_domain::{動画上の区間, 動画上の秒};

use crate::bytes::バイト数;
use crate::frame::番号付きのコマ;
use crate::frame_rate::コマの速さ;

use super::entry::{倉庫の項目, 項目の状態};
use super::messages::倉庫への報告;
use super::outcome::依頼の状況;
use super::results::{終わった依頼の結末, 結末の記録};
use super::stored::溜めた区間;
use super::ticket::受付の札;

/// 依頼の記録とは、受け付けた順の倉庫の項目の並びと、外れた依頼の結末の記録の組のことである。
#[derive(Default)]
pub(crate) struct 依頼の記録 {
    項目の並び: Vec<倉庫の項目>,
    結末: 結末の記録,
}

impl 依頼の記録 {
    pub(crate) fn 項目の並び(&self) -> &[倉庫の項目] {
        &self.項目の並び
    }

    pub(crate) fn 加える(&mut self, 項目: 倉庫の項目) {
        self.項目の並び.push(項目);
    }

    pub(crate) fn 区間の札(&self, 区間: &動画上の区間) -> Option<受付の札> {
        self.項目の並び
            .iter()
            .find(|項目| &項目.区間 == 区間)
            .map(|項目| 項目.札)
    }

    /// 区間の溜めたコマから、その時刻に出すコマを返す。溜め終えていなければ `None` である。
    pub(crate) fn 溜めたコマ(
        &self,
        区間: &動画上の区間,
        位置: 動画上の秒,
        速さ: コマの速さ,
    ) -> Option<番号付きのコマ<'_>> {
        match &self.項目の並び.iter().find(|項目| &項目.区間 == 区間)?.状態 {
            項目の状態::溜めた(溜めた区間) => 溜めた区間.時刻のコマ(位置, 速さ),
            項目の状態::処理待ち | 項目の状態::処理中 { .. } => None,
        }
    }

    /// 予約しているメモリの合計。溜め終えた項目もまだの項目も見積もりの大きさで数える。
    pub(crate) fn 予約の合計(&self) -> バイト数 {
        let 足す = |合計: バイト数, 項目: &倉庫の項目| 合計.足す(項目.見積もり.バイト数());
        self.項目の並び.iter().fold(バイト数::ゼロ, 足す)
    }

    pub(crate) fn 状況(&self, 札: 受付の札) -> 依頼の状況<'_> {
        let 項目 = self.項目の並び.iter().find(|項目| 項目.札 == 札);
        項目.map_or_else(|| self.結末.状況(札), 倉庫の項目::状況)
    }

    /// 札の項目を外し、結末を記録する。外した項目の状態を返す。
    pub(crate) fn 項目を外す(
        &mut self,
        札: 受付の札,
        結末: 終わった依頼の結末,
    ) -> Option<項目の状態> {
        let 位置 = self.項目の並び.iter().position(|項目| 項目.札 == 札)?;
        self.結末.記録する(札, 結末);
        Some(self.項目の並び.remove(位置).状態)
    }

    /// 裏のスレッドからの報告を反映する。既に外した項目への報告は捨てる。
    pub(crate) fn 報告を反映する(&mut self, 報告: 倉庫への報告) {
        match 報告 {
            倉庫への報告::進んだ {
                札, 溜めたコマ数
            } => {
                if let Some(項目) = self.札の項目(札) {
                    項目.状態 = 項目の状態::処理中 { 溜めたコマ数 };
                }
            }
            倉庫への報告::溜め終えた {
                札, コマの並び
            } => {
                if let Some(項目) = self.札の項目(札) {
                    let 先頭のコマ = 項目.見積もり.先頭のコマ();
                    項目.状態 =
                        項目の状態::溜めた(溜めた区間::作成する(先頭のコマ, コマの並び));
                }
            }
            倉庫への報告::失敗した { 札, 失敗 } => {
                self.項目を外す(札, 終わった依頼の結末::失敗(失敗));
            }
            倉庫への報告::取り消された(札) => {
                self.項目を外す(札, 終わった依頼の結末::取り消した);
            }
        }
    }

    fn 札の項目(&mut self, 札: 受付の札) -> Option<&mut 倉庫の項目> {
        self.項目の並び.iter_mut().find(|項目| 項目.札 == 札)
    }
}
