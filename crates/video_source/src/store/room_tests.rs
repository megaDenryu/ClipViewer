//! 捨てる札を選ぶ計算の試験。

use super::outcome::受け付けない理由;
use super::priority::保持の順位;
use super::room::{捨てる候補, 捨てる札を選ぶ};
use super::ticket::{受付の札, 札の発行元};
use crate::bytes::{バイト数, メモリの上限};

fn 上限(大きさ: u64) -> メモリの上限 {
    メモリの上限::作成する(バイト数::作成する(大きさ))
}

/// 大きさ10の候補を、順位の並びのとおりに作る。
fn 候補を並べる(
    順位の並び: &[保持の順位]
) -> (Vec<捨てる候補>, Vec<受付の札>) {
    let mut 発行元 = 札の発行元::default();
    let 候補: Vec<捨てる候補> = 順位の並び
        .iter()
        .map(|順位| 捨てる候補 {
            札: 発行元.発行する(),
            順位: *順位,
            大きさ: バイト数::作成する(10),
        })
        .collect();
    let 札 = 候補.iter().map(|候補| 候補.札).collect();
    (候補, 札)
}

#[test]
fn 空きがあれば何も捨てない() {
    let (候補, _) = 候補を並べる(&[保持の順位::並びの位置(0)]);
    let 結果 = 捨てる札を選ぶ(
        &候補,
        保持の順位::並びの位置(1),
        バイト数::作成する(10),
        上限(20),
    );
    assert_eq!(結果, Ok(vec![]));
}

#[test]
fn 並びに無い区間から_次に並びの後ろの区間から捨てる() {
    let 順位の並び = [
        保持の順位::並びの位置(1),
        保持の順位::優先順に無い,
        保持の順位::並びの位置(2),
    ];
    let (候補, 札) = 候補を並べる(&順位の並び);
    let 結果 = 捨てる札を選ぶ(
        &候補,
        保持の順位::並びの位置(0),
        バイト数::作成する(20),
        上限(30),
    );
    assert_eq!(結果, Ok(vec![札[1], 札[2]]));
}

#[test]
fn 順位の高い区間を捨てないと空かないなら受け付けない() {
    let (候補, _) = 候補を並べる(&[保持の順位::並びの位置(0), 保持の順位::並びの位置(2)]);
    let 結果 = 捨てる札を選ぶ(
        &候補,
        保持の順位::並びの位置(1),
        バイト数::作成する(20),
        上限(20),
    );
    let 期待 = 受け付けない理由::優先順の高い区間で埋まっている {
        見積もり: バイト数::作成する(20),
        作れる空き: バイト数::作成する(10),
    };
    assert_eq!(結果, Err(期待));
}

#[test]
fn 見積もりが上限の全体を超えるなら何も捨てずに受け付けない() {
    let (候補, _) = 候補を並べる(&[保持の順位::優先順に無い]);
    let 結果 = 捨てる札を選ぶ(
        &候補,
        保持の順位::並びの位置(0),
        バイト数::作成する(21),
        上限(20),
    );
    let 期待 = 受け付けない理由::上限の全体を超える {
        見積もり: バイト数::作成する(21),
        上限: 上限(20),
    };
    assert_eq!(結果, Err(期待));
}

#[test]
fn 同じ順位の区間は捨てない() {
    let (候補, _) = 候補を並べる(&[保持の順位::優先順に無い]);
    let 結果 = 捨てる札を選ぶ(
        &候補,
        保持の順位::優先順に無い,
        バイト数::作成する(10),
        上限(10),
    );
    assert!(結果.is_err());
}
