//! 依頼の受付。保持の規則に従って空きを作り、依頼の記録へ処理待ちの項目として加える。

use clip_domain::動画上の区間;

use crate::bytes::メモリの上限;
use crate::estimate::区間の見積もり;

use super::entry::倉庫の項目;
use super::outcome::受け付けない理由;
use super::priority::保持の優先順;
use super::record::依頼の記録;
use super::results::終わった依頼の結末;
use super::room::保持の規則;
use super::ticket::{受付の札, 札の発行元};

/// 依頼の受付とは、保持の規則と札の発行元の組のことであり、区間を溜める依頼を受け付けるかを決める。
pub(crate) struct 依頼の受付 {
    規則: 保持の規則,
    札の発行元: 札の発行元,
}

/// 受け付けた依頼とは、依頼の受付が受け付けた依頼が、既にあった依頼か、新しく記録へ加えた依頼かの区別のことである。
pub(crate) enum 受け付けた依頼 {
    /// 同じ区間の依頼が記録に既にあった。裏のスレッドへ積み直さない。
    既にある(受付の札),
    /// 新しく記録へ加えた。止める札は、空きを作るために捨てた項目のうち溜め終えていなかったものの札である。
    新しく加えた {
        札: 受付の札,
        止める札: Vec<受付の札>,
    },
}

impl 依頼の受付 {
    pub(crate) fn 作成する(上限: メモリの上限) -> Self {
        let 規則 = 保持の規則::作成する(上限);
        Self {
            規則,
            札の発行元: 札の発行元::default(),
        }
    }

    pub(crate) fn 優先順を置き換える(&mut self, 優先順: 保持の優先順) {
        self.規則.優先順を置き換える(優先順);
    }

    /// 同じ区間の依頼が記録にあればその札を返す。無ければ、保持の優先順がこの区間より低い項目を記録から捨てて空きを作り、
    /// 処理待ちの項目として記録へ加える。
    pub(crate) fn 受け付ける(
        &mut self,
        記録: &mut 依頼の記録,
        区間: 動画上の区間,
        見積もり: 区間の見積もり,
    ) -> Result<受け付けた依頼, 受け付けない理由> {
        if let Some(札) = 記録.区間の札(&区間) {
            return Ok(受け付けた依頼::既にある(札));
        }
        if 見積もり.コマ数().ゼロか() {
            return Err(受け付けない理由::区間にコマが無い);
        }
        let 捨てる札 = self.規則.空きを作るために捨てる札(
            記録.項目の並び(),
            &区間,
            見積もり.バイト数(),
        )?;
        let mut 止める札 = Vec::new();
        for 札 in 捨てる札 {
            let 外した状態 = 記録.項目を外す(札, 終わった依頼の結末::捨てた);
            if 外した状態.is_some_and(|状態| 状態.溜め終えていないか()) {
                止める札.push(札);
            }
        }
        let 札 = self.札の発行元.発行する();
        記録.加える(倉庫の項目::処理待ちで作る(札, 区間, 見積もり));
        Ok(受け付けた依頼::新しく加えた { 札, 止める札 })
    }
}
