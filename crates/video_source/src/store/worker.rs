//! 区間を溜める依頼を、保持の優先順で最も上位のものから処理する、裏のスレッドの本体。

use std::io;
use std::sync::mpsc::Sender;

use crate::frame::コマ;
use crate::frame_number::コマ数;
use crate::locate::FFmpegの実行ファイル;
use crate::process::{コマの読み手, 起動したデコード};

use super::messages::倉庫への報告;
use super::queue::依頼の待ち行列;
use super::queue_state::処理待ちの依頼;
use super::ticket::受付の札;

/// 区間を溜める作業とは、裏のスレッドで、待ち行列から依頼を取り出しては ffmpeg を起動してコマを読み切る仕事のことである。
pub(crate) struct 区間を溜める作業 {
    pub(crate) 実行ファイル: FFmpegの実行ファイル,
    pub(crate) 待ち行列: 依頼の待ち行列,
    pub(crate) 報告の送り口: Sender<倉庫への報告>,
}

impl 区間を溜める作業 {
    /// 倉庫が落とされるまで、待ち行列から依頼を取り出して処理する。
    pub(crate) fn 依頼を待ち続ける(self) {
        while let Some(依頼) = self.待ち行列.次の依頼を待つ() {
            let 結果 = self.依頼を処理する(依頼);
            self.報告する(結果);
        }
    }

    fn 依頼を処理する(&self, 依頼: 処理待ちの依頼) -> 倉庫への報告 {
        let 札 = 依頼.札;
        let 起動 = match 起動したデコード::起動する(&依頼.指定, &self.実行ファイル)
        {
            Ok(起動) => 起動,
            Err(失敗) => {
                self.待ち行列.実行を終えて取り消されていたかを返す();
                return 倉庫への報告::失敗した { 札, 失敗 };
            }
        };
        let 起動したデコード {
            子プロセス,
            mut 読み手,
            mut 標準エラー,
        } = 起動;
        self.待ち行列.子プロセスを預ける(子プロセス);
        self.報告する(倉庫への報告::進んだ {
            札,
            溜めたコマ数: コマ数::ゼロ,
        });
        let 読んだ結果 = self.コマを読み切る(札, &mut 読み手);
        drop(読み手);
        let 終了状態 = self.待ち行列.引き取って終わりを待つ();
        let 標準エラーの末尾 = 標準エラー.読み終えるまで待つ();
        if self.待ち行列.実行を終えて取り消されていたかを返す() {
            return 倉庫への報告::取り消された(札);
        }
        倉庫への報告::読み終えた結果から作る(
            札,
            読んだ結果,
            終了状態,
            標準エラーの末尾,
        )
    }

    fn コマを読み切る(
        &self,
        札: 受付の札,
        読み手: &mut コマの読み手,
    ) -> io::Result<Vec<コマ>> {
        let mut コマの並び = Vec::new();
        let mut 溜めたコマ数 = コマ数::ゼロ;
        while let Some(コマ) = 読み手.次のコマを読む()? {
            コマの並び.push(コマ);
            溜めたコマ数 = 溜めたコマ数.一つ増やす();
            self.報告する(倉庫への報告::進んだ {
                札, 溜めたコマ数
            });
        }
        Ok(コマの並び)
    }

    fn 報告する(&self, 報告: 倉庫への報告) {
        // 倉庫が落とされて受け口が無いなら、報告を受け取る者はいないため捨てる。
        let _ = self.報告の送り口.send(報告);
    }
}
