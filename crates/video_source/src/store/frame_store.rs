//! コマの倉庫の公開の口。

use clip_domain::{動画上の区間, 動画上の秒};

use crate::bytes::{バイト数, メモリの上限};
use crate::frame::番号付きのコマ;
use crate::locate::FFmpegの実行ファイル;
use crate::long_side::長辺の上限;
use crate::process::デコードの指定;
use crate::video_info::動画の情報;

use super::decoder_thread::区間をデコードする裏のスレッド;
use super::intake::依頼の受付;
use super::outcome::{依頼の状況, 倉庫を開くエラー, 溜める依頼の結果};
use super::priority::保持の優先順;
use super::record::依頼の記録;
use super::results::終わった依頼の結末;
use super::ticket::受付の札;

/// コマの倉庫とは、1つの動画について、区間のコマを裏のスレッドでデコードして RAM に溜め、取り出させるもののことである。
/// 別の動画を読み込んだら作り直す。落とすと、実行中の ffmpeg を止め、裏のスレッドの終わりを待つ。
/// 操作はすべて画面のスレッドから呼び、待たずに返る。裏のスレッドからの報告は、各操作の最初に記録へ反映する。
pub struct コマの倉庫 {
    動画: 動画の情報,
    長辺の上限: 長辺の上限,
    記録: 依頼の記録,
    受付: 依頼の受付,
    裏のスレッド: 区間をデコードする裏のスレッド,
}

impl コマの倉庫 {
    pub(crate) fn 開く(
        実行ファイル: FFmpegの実行ファイル,
        動画: 動画の情報,
        長辺の上限: 長辺の上限,
        メモリの上限: メモリの上限,
    ) -> Result<Self, 倉庫を開くエラー> {
        let 裏のスレッド =
            区間をデコードする裏のスレッド::起動する(実行ファイル)
                .map_err(倉庫を開くエラー::スレッドを起動できない)?;
        let (記録, 受付) = (依頼の記録::default(), 依頼の受付::作成する(メモリの上限));
        Ok(Self {
            動画,
            長辺の上限,
            記録,
            受付,
            裏のスレッド,
        })
    }

    /// この倉庫が結び付いた動画の情報。
    pub fn 動画(&self) -> &動画の情報 {
        &self.動画
    }

    /// 保持の優先順を渡す。以降、空きを作るときに捨てる順と、裏のスレッドが次に処理する依頼をこの並びで決める。
    pub fn 保持の優先順を渡す(&mut self, 優先順: 保持の優先順) {
        self.裏のスレッド.優先順を置き換える(優先順.clone());
        self.受付.優先順を置き換える(優先順);
    }

    /// 予約しているメモリの合計。溜め終えた区間も、処理を待つ区間も見積もりの大きさで数える。
    pub fn 予約している大きさ(&self) -> バイト数 {
        self.記録.予約の合計()
    }

    /// 区間を溜める依頼を出す。同じ区間の依頼が既にあればその札を返す。
    /// 空きが足りなければ、保持の優先順がこの区間より低い区間を捨ててから受け付ける。
    pub fn 区間を溜める依頼を出す(
        &mut self,
        区間: 動画上の区間,
    ) -> 溜める依頼の結果 {
        self.裏のスレッド.報告を記録へ反映する(&mut self.記録);
        let 見積もり = self.動画.区間を見積もる(&区間, self.長辺の上限);
        let 受付 = match self.受付.受け付ける(&mut self.記録, 区間, 見積もり) {
            Ok(受付) => 受付,
            Err(理由) => return 溜める依頼の結果::受け付けない(理由),
        };
        let 指定 = デコードの指定::区間を読む(&self.動画, &見積もり);
        self.裏のスレッド
            .受け付けた依頼を送る(&mut self.記録, 受付, 区間, 指定)
    }

    /// 札の依頼の状況を問い合わせる。
    pub fn 依頼の状況を問い合わせる(
        &mut self, 札: 受付の札
    ) -> 依頼の状況<'_> {
        self.裏のスレッド.報告を記録へ反映する(&mut self.記録);
        self.記録.状況(札)
    }

    /// 札の依頼を取り消す。デコード中なら ffmpeg を止め、溜め終えていれば溜めたコマを捨てる。
    pub fn 依頼を取り消す(&mut self, 札: 受付の札) {
        self.裏のスレッド.報告を記録へ反映する(&mut self.記録);
        self.裏のスレッド.項目を外して止める(
            &mut self.記録,
            札,
            終わった依頼の結末::取り消した,
        );
    }

    /// 区間の溜めたコマから、その時刻に出すコマを取り出す。溜め終えていなければ `None` である。
    /// 区間の開始より前の時刻なら最初のコマ、区間の終わりちょうどやそれより後ろなら最後のコマを返す。
    pub fn 溜めたコマを取り出す(
        &mut self,
        区間: &動画上の区間,
        位置: 動画上の秒,
    ) -> Option<番号付きのコマ<'_>> {
        self.裏のスレッド.報告を記録へ反映する(&mut self.記録);
        self.記録.溜めたコマ(区間, 位置, self.動画.コマの速さ())
    }

    /// 区間の破棄を依頼する。溜めたコマを捨て、処理を待つかデコード中の依頼は止める。
    pub fn 区間の破棄を依頼する(&mut self, 区間: &動画上の区間) {
        self.裏のスレッド.報告を記録へ反映する(&mut self.記録);
        if let Some(札) = self.記録.区間の札(区間) {
            self.裏のスレッド.項目を外して止める(
                &mut self.記録,
                札,
                終わった依頼の結末::捨てた,
            );
        }
    }
}
