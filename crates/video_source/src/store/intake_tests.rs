//! 依頼の受付の試験。同じ区間の再依頼と、空きを作るときに捨てる項目を FFmpeg を使わずに確かめる。

use super::intake::受け付けた依頼;
use super::messages::倉庫への報告;
use super::outcome::依頼の状況;
use super::priority::保持の優先順;
use super::test_support::{一秒分, 区間, 受け付ける, 受付と記録, 新しい札};
use crate::bytes::バイト数;
use crate::frame::コマ;
use crate::frame_number::コマ数;
use crate::frame_size::コマの寸法;

#[test]
fn 同じ区間の再依頼は既にある札を返し_予約を重ねない() {
    let (mut 受付, mut 記録) = 受付と記録(10);
    let 札 = 新しい札(受け付ける(&mut 受付, &mut 記録, 0.0));
    let Ok(受け付けた依頼::既にある(再依頼の札)) = 受け付ける(&mut 受付, &mut 記録, 0.0)
    else {
        panic!("既にあるはずである")
    };
    assert_eq!(再依頼の札, 札);
    assert_eq!(記録.予約の合計(), バイト数::作成する(一秒分));
}

#[test]
fn 溜め終えても予約は見積もりのまま数え_空きを作るときに捨てる() {
    let (mut 受付, mut 記録) = 受付と記録(1);
    let 先の札 = 新しい札(受け付ける(&mut 受付, &mut 記録, 0.0));
    let Some(寸法) = コマの寸法::作成する(10, 10) else {
        panic!("寸法を作れない")
    };
    let コマ = コマ::読み取った画素から作る(寸法, vec![0; 400]);
    記録.報告を反映する(倉庫への報告::溜め終えた {
        札: 先の札,
        コマの並び: vec![コマ],
    });
    let Some(依頼の状況::完了(内訳)) = Some(記録.状況(先の札)) else {
        panic!("完了のはずである")
    };
    assert_eq!(
        (内訳.溜めたコマ数, 内訳.見込みのコマ数),
        (コマ数::作成する(1), コマ数::作成する(10))
    );
    assert!(内訳.見積もりより少なかったか());
    assert_eq!(記録.予約の合計(), バイト数::作成する(一秒分));
    受付.優先順を置き換える(保持の優先順::作成する(vec![区間(5.0)]));
    let Ok(受け付けた依頼::新しく加えた { 止める札, .. }) =
        受け付ける(&mut 受付, &mut 記録, 5.0)
    else {
        panic!("受け付けられなかった")
    };
    assert!(
        止める札.is_empty(),
        "溜め終えた項目は裏のスレッドで止める必要が無い"
    );
    assert!(matches!(記録.状況(先の札), 依頼の状況::捨てた));
}
