//! 溜め終えた区間のコマの並び。

use clip_domain::動画上の秒;

use crate::frame::{コマ, 番号付きのコマ};
use crate::frame_number::{コマ数, 動画上のコマ番号};
use crate::frame_rate::コマの速さ;

/// 溜めた区間とは、区間の先頭のコマから順にデコードして RAM に置いたコマの並びのことである。
/// 不変条件: コマの並びは1つ以上である(デコードが1コマも出さなければ失敗として扱い、溜めた区間を作らない)。
#[derive(Debug)]
pub(crate) struct 溜めた区間 {
    先頭のコマ: 動画上のコマ番号,
    コマの並び: Vec<コマ>,
}

impl 溜めた区間 {
    /// 先頭のコマの番号と、読んだコマの並びから作る。
    pub(crate) fn 作成する(
        先頭のコマ: 動画上のコマ番号, コマの並び: Vec<コマ>
    ) -> Self {
        Self {
            先頭のコマ,
            コマの並び,
        }
    }

    /// 溜めたコマの数。
    pub(crate) fn コマ数(&self) -> コマ数 {
        コマ数::作成する(u32::try_from(self.コマの並び.len()).unwrap_or(u32::MAX))
    }

    /// その時刻に出すコマを番号付きで返す。区間の開始より前なら最初のコマ、区間の終わりちょうどやそれより後ろなら最後のコマである。
    pub(crate) fn 時刻のコマ(
        &self,
        位置: 動画上の秒,
        速さ: コマの速さ,
    ) -> Option<番号付きのコマ<'_>> {
        let 最後の添字 = self.コマの並び.len().checked_sub(1)?;
        let 進んだ = 速さ
            .時刻を含むコマ番号(位置)
            .起点から進んだコマ数(self.先頭のコマ);
        let 添字 = usize::try_from(進んだ.値())
            .unwrap_or(usize::MAX)
            .min(最後の添字);
        let 添字のコマ数 = コマ数::作成する(u32::try_from(添字).unwrap_or(u32::MAX));
        let コマ = self.コマの並び.get(添字)?;
        Some(番号付きのコマ::作成する(
            self.先頭のコマ.進める(添字のコマ数),
            コマ,
        ))
    }
}

#[cfg(test)]
mod tests {
    use clip_domain::時刻;

    use super::*;
    use crate::frame_size::コマの寸法;

    fn 印のコマ(印: u8) -> コマ {
        let Some(寸法) = コマの寸法::作成する(1, 1) else {
            panic!("寸法を作れない")
        };
        コマ::読み取った画素から作る(寸法, vec![印, 0, 0, 255])
    }

    /// その時刻に出すコマの番号と印を返す。
    fn 印(溜め: &溜めた区間, 秒: f64) -> Option<(u32, u8)> {
        let (Ok(位置), Some(速さ)) = (時刻::作成する(秒), コマの速さ::作成する(10, 1))
        else {
            panic!("値を作れない")
        };
        溜め
            .時刻のコマ(位置, 速さ)
            .map(|取り出した| (取り出した.番号().値(), 取り出した.コマ().画素の並び()[0]))
    }

    #[test]
    fn 時刻を含むコマを返し_区間の外は端のコマを返す() {
        let 溜め = 溜めた区間::作成する(
            動画上のコマ番号::作成する(10),
            vec![印のコマ(0), 印のコマ(1), 印のコマ(2)],
        );
        assert_eq!(印(&溜め, 1.0), Some((10, 0)));
        assert_eq!(印(&溜め, 1.15), Some((11, 1)));
        assert_eq!(印(&溜め, 1.29), Some((12, 2)));
        assert_eq!(印(&溜め, 1.3), Some((12, 2)));
        assert_eq!(印(&溜め, 99.0), Some((12, 2)));
        assert_eq!(印(&溜め, 0.2), Some((10, 0)));
    }
}
