//! 区間を溜めるときの見積もりの型。

use crate::bytes::バイト数;
use crate::frame_number::{コマ数, 動画上のコマ番号};
use crate::frame_size::コマの寸法;

/// 区間の見積もりとは、区間を溜めるときに読む先頭のコマ・コマ数・縮めた寸法の組のことである。
/// 必要なバイト数は コマ数 × 幅 × 高さ × 4 であり、組から求めるので食い違わない。
/// 作れるのは `動画の情報::区間を見積もる` だけである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 区間の見積もり {
    先頭のコマ: 動画上のコマ番号,
    コマ数: コマ数,
    寸法: コマの寸法,
}

impl 区間の見積もり {
    pub(crate) fn 作成する(
        先頭のコマ: 動画上のコマ番号,
        コマ数: コマ数,
        寸法: コマの寸法,
    ) -> Self {
        Self {
            先頭のコマ,
            コマ数,
            寸法,
        }
    }

    /// 区間の開始を含むコマ。
    pub fn 先頭のコマ(&self) -> 動画上のコマ番号 {
        self.先頭のコマ
    }

    /// 区間の中で表示が始まるコマの数。動画の終わりより後ろは数えない。
    pub fn コマ数(&self) -> コマ数 {
        self.コマ数
    }

    /// 長辺の上限へ縮めたコマの寸法。
    pub fn 寸法(&self) -> コマの寸法 {
        self.寸法
    }

    /// 溜めるのに必要なメモリの大きさ。
    pub fn バイト数(&self) -> バイト数 {
        self.寸法.一コマのバイト数().コマ数倍にする(self.コマ数)
    }
}
