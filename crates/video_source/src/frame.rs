//! デコードしたコマの型。

use crate::bytes::バイト数;
use crate::frame_number::動画上のコマ番号;
use crate::frame_size::コマの寸法;

/// コマとは、動画の1枚の画像を、RGBA8(1画素4バイト、左上から行ごと)の画素の並びで表したもののことである。
/// 不変条件: 画素の並びの長さは 幅×高さ×4 バイトである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct コマ {
    寸法: コマの寸法,
    画素: Vec<u8>,
}

impl コマ {
    /// 読み取った画素の並びから作る。
    /// 注意: 長さが 幅×高さ×4 バイトであることは、読み取り側が1コマ分ずつ読むことで保証する。
    pub(crate) fn 読み取った画素から作る(
        寸法: コマの寸法, 画素: Vec<u8>
    ) -> Self {
        Self { 寸法, 画素 }
    }

    /// コマの寸法。
    pub fn 寸法(&self) -> コマの寸法 {
        self.寸法
    }

    /// RGBA8 の画素の並び。画像を GPU へ送る境界で使う。
    pub fn 画素の並び(&self) -> &[u8] {
        &self.画素
    }

    /// このコマが占めるメモリの大きさ。
    pub fn バイト数(&self) -> バイト数 {
        self.寸法.一コマのバイト数()
    }
}

/// 番号付きのコマとは、コマの倉庫から取り出したコマと、その動画上のコマ番号の組のことである。
/// 画面は番号を前のフレームと比べ、同じコマなら GPU へ載せ直さずに済ませる。
/// 前提: 番号が同じなら同じ画像であるのは、同じ動画を同じ長辺の上限で読んだときだけである。
/// 画面は比べるときに使う値に、番号に加えてコマの寸法と、動画を読み込み直したことの区別を含める。
#[derive(Debug, Clone, Copy)]
pub struct 番号付きのコマ<'コマ> {
    番号: 動画上のコマ番号,
    コマ: &'コマ コマ,
}

impl<'コマ> 番号付きのコマ<'コマ> {
    pub(crate) fn 作成する(番号: 動画上のコマ番号, コマ: &'コマ コマ) -> Self {
        Self { 番号, コマ }
    }

    /// 動画上のコマ番号。
    pub fn 番号(&self) -> 動画上のコマ番号 {
        self.番号
    }

    /// コマ。
    pub fn コマ(&self) -> &'コマ コマ {
        self.コマ
    }
}
