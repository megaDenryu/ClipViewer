//! 動画の読み手。見つけた FFmpeg を保持し、動画の情報の取得・流し読み・コマの倉庫を開く。外の層はこの型だけを通して FFmpeg を使う。

use std::time::Duration;

use clip_domain::{動画上の秒, 正規化した動画パス};

use crate::bytes::メモリの上限;
use crate::locate::FFmpegの実行ファイル;
use crate::long_side::長辺の上限;
use crate::probe::{動画の情報の取得エラー, 調査の失敗};
use crate::process::{
    デコードの失敗, 取り消しの合図, 期限付きの子プロセス
};
use crate::store::{コマの倉庫, 倉庫を開くエラー};
use crate::stream::流し読み;
use crate::video_info::動画の情報;

/// 動画の情報を調べる ffprobe の期限。ffprobe は通常0.1秒ほどで終わるが、眠っていたハードディスクやネットワークドライブ、
/// 末尾に索引のある長い mp4 では数秒から十数秒かかることがある。30秒を過ぎたものは固まったとみなし、画面を止め続けないようにする。
pub(crate) const 調査の期限: Duration = Duration::from_secs(30);

/// 動画の読み手とは、見つけた FFmpeg の実行ファイルを保持し、それで動画を調べ・読む操作を持つもののことである。
/// 画面のコンポジションルートが1つ作って持つ。同じ実行ファイルの組から作った読み手は等しい。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 動画の読み手 {
    実行ファイル: FFmpegの実行ファイル,
}

impl 動画の読み手 {
    /// 見つけた FFmpeg の実行ファイルから作成する。
    pub fn 作成する(実行ファイル: FFmpegの実行ファイル) -> Self {
        Self { 実行ファイル }
    }

    pub(crate) fn 実行ファイル(&self) -> &FFmpegの実行ファイル {
        &self.実行ファイル
    }

    /// ffprobe で動画の長さ・元の寸法・コマの速さ・映像の流れ・音の有無を1回で調べる。ffprobe が終わるまで待つ。
    /// 30秒の期限を過ぎたら ffprobe を止めて失敗を返す。
    pub fn 動画の情報を取る(
        &self,
        パス: &正規化した動画パス,
    ) -> Result<動画の情報, 動画の情報の取得エラー> {
        // 注意: この合図は誰にも渡さないため、取り消されることはない。
        let 取り消さない合図 = 取り消しの合図::default();
        self.期限付きで動画の情報を取る(パス, 調査の期限, &取り消さない合図)
            .map_err(|失敗| match 失敗 {
                調査の失敗::待てなかった(失敗) => {
                    動画の情報の取得エラー::待ちの失敗から作る(失敗, 調査の期限)
                }
                調査の失敗::読めなかった(エラー) => エラー,
            })
    }

    /// 期限と取り消しの合図を見回りながら ffprobe で動画の情報を調べる。サムネイルを撮るときにも使う。
    pub(crate) fn 期限付きで動画の情報を取る(
        &self,
        パス: &正規化した動画パス,
        期限: Duration,
        合図: &取り消しの合図,
    ) -> Result<動画の情報, 調査の失敗> {
        let mut 命令 = self.実行ファイル.調査の命令();
        命令
            .args([
                "-v",
                "error",
                "-show_streams",
                "-show_format",
                "-of",
                "json",
            ])
            .arg(パス.文字列());
        let 出力 = 期限付きの子プロセス::起動する(命令)
            .and_then(|子プロセス| 子プロセス.終わるまで待つ(期限, 合図))
            .map_err(調査の失敗::待てなかった)?;
        if !出力.終了状態.success() {
            return Err(調査の失敗::読めなかった(
                動画の情報の取得エラー::異常終了 {
                    終了状態: 出力.終了状態,
                    標準エラーの末尾: 出力.標準エラーの末尾,
                },
            ));
        }
        let 本文 = String::from_utf8_lossy(&出力.標準出力);
        動画の情報::調査の出力から作る(パス.clone(), &本文).map_err(調査の失敗::読めなかった)
    }

    /// 開始の時刻から動画の終わりまでの流し読みを開く。ffmpeg を起動して待たずに返る。
    pub fn 流し読みを開く(
        &self,
        動画: &動画の情報,
        開始: 動画上の秒,
        上限: 長辺の上限,
    ) -> Result<流し読み, デコードの失敗> {
        流し読み::開く(&self.実行ファイル, 動画, 開始, 上限)
    }

    /// 1つの動画に結び付いたコマの倉庫を開く。裏のスレッドを起動して待たずに返る。
    pub fn コマの倉庫を開く(
        &self,
        動画: 動画の情報,
        上限: 長辺の上限,
        メモリの上限: メモリの上限,
    ) -> Result<コマの倉庫, 倉庫を開くエラー> {
        コマの倉庫::開く(self.実行ファイル.clone(), 動画, 上限, メモリの上限)
    }
}
