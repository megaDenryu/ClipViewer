//! 区間の見積もりの試験。

use clip_domain::{入力された動画パス, 動画上の区間, 時刻};

use crate::bytes::バイト数;
use crate::long_side::長辺の上限;
use crate::video_info::動画の情報;

fn 動画(幅: u32, 高さ: u32, 長さ: f64) -> 動画の情報 {
    let パス = 入力された動画パス::作成する("C:/動画/試験.mp4".to_string()).正規化する();
    let 本文 = format!(
        r#"{{"streams":[{{"index":0,"codec_type":"video","width":{幅},"height":{高さ},"avg_frame_rate":"30/1","duration":"{長さ}"}}]}}"#
    );
    let Ok(情報) = 動画の情報::調査の出力から作る(パス, &本文) else {
        panic!("動画の情報を作れない")
    };
    情報
}

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let (Ok(開始), Ok(終了)) = (時刻::作成する(開始), 時刻::作成する(終了))
    else {
        panic!("時刻を作れない")
    };
    let Ok(区間) = 動画上の区間::作成する(開始, 終了) else {
        panic!("区間を作れない")
    };
    区間
}

#[test]
fn 見積もりはコマ数と縮めた寸法と4バイトの積である() {
    let 見積もり = 動画(1920, 1080, 60.0).区間を見積もる(&区間(1.0, 3.0), 長辺の上限::既定);
    assert_eq!(見積もり.先頭のコマ().値(), 30);
    assert_eq!(見積もり.コマ数().値(), 60);
    assert_eq!((見積もり.寸法().幅(), 見積もり.寸法().高さ()), (1280, 720));
    assert_eq!(見積もり.バイト数(), バイト数::作成する(60 * 1280 * 720 * 4));
}

#[test]
fn 開始がコマの途中ならそのコマから数え_終わりがコマの途中ならそのコマまで数える() {
    let 見積もり = 動画(640, 360, 60.0).区間を見積もる(&区間(1.01, 1.05), 長辺の上限::既定);
    assert_eq!(見積もり.先頭のコマ().値(), 30);
    assert_eq!(見積もり.コマ数().値(), 2);
}

#[test]
fn 動画の終わりより後ろは数えない() {
    let 動画 = 動画(640, 360, 3.0);
    assert_eq!(
        動画
            .区間を見積もる(&区間(2.0, 10.0), 長辺の上限::既定)
            .コマ数()
            .値(),
        30
    );
    assert!(
        動画
            .区間を見積もる(&区間(5.0, 10.0), 長辺の上限::既定)
            .コマ数()
            .ゼロか()
    );
}

#[test]
fn 長さ0の区間はコマが無い() {
    assert!(
        動画(640, 360, 3.0)
            .区間を見積もる(&区間(1.0, 1.0), 長辺の上限::既定)
            .コマ数()
            .ゼロか()
    );
}
