//! 音を溜める作業が ffmpeg の出力を読むのをやめた理由と、その理由に応じた ffmpeg の終わらせ方。

use std::io;

use super::launch::起動した音のデコード;
use crate::process::{
    デコードの失敗, 標準エラーの収集, 起動した子プロセス
};

/// 読むのをやめた理由とは、音を溜める作業が ffmpeg の出力を読むのをやめた理由の区別のことである。
pub(super) enum 読むのをやめた理由 {
    要らなくなった,
    数に届いた,
    出力が閉じた,
    読めない(io::Error),
}

/// 区間の読み取りの結末とは、ffmpeg を終わらせた後に決まる、区間の音を溜めるか、捨てるか、失敗にするかの区別のことである。
pub(super) enum 区間の読み取りの結末 {
    要らなくなった,
    読み終えた,
    失敗(デコードの失敗),
}

impl 読むのをやめた理由 {
    /// 理由に応じて ffmpeg を終わらせ、結末を決める。出力が閉じたときだけ ffmpeg の終わりを待って終了状態を確かめ、
    /// それ以外は止めてから終わりを待つ。
    pub(super) fn ffmpegを終わらせる(
        self,
        子プロセス: &mut 起動した子プロセス,
        mut 標準エラー: 標準エラーの収集,
    ) -> 区間の読み取りの結末 {
        if !matches!(self, Self::出力が閉じた) {
            子プロセス.止めて終わりを待つ();
        }
        let 失敗 = match self {
            Self::要らなくなった => {
                return 区間の読み取りの結末::要らなくなった;
            }
            Self::数に届いた => None,
            Self::出力が閉じた => 起動した音のデコード::失敗かを決める(
                子プロセス.終わりを待つ(),
                標準エラー.読み終えるまで待つ(),
            ),
            Self::読めない(原因) => Some(デコードの失敗::出力を読めない {
                原因,
                標準エラーの末尾: 標準エラー.読み終えるまで待つ(),
            }),
        };
        match 失敗 {
            Some(失敗) => 区間の読み取りの結末::失敗(失敗),
            None => 区間の読み取りの結末::読み終えた,
        }
    }
}
