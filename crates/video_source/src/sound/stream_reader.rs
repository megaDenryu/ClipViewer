//! 音の流し読みの裏のスレッドの仕事。ffmpeg の出力を読み、流れてくる音へ書き足し続ける。

use std::process::ChildStdout;

use audio_pcm::{書き足した結果, 流れてくる音};

use super::pcm_reader::{左右の値の読み手, 読んだ結果};
use crate::process::{標準エラーの収集, 標準エラーの末尾};

/// 読み取りの終わりとは、音の流し読みの裏のスレッドが、なぜ読むのをやめたかの区別のことである。
pub(super) enum 読み取りの終わり {
    終わりまで読んだ(標準エラーの末尾),
    閉じられた,
    読めない(std::io::Error, 標準エラーの末尾),
}

/// 出力が閉じるか、入れ物が閉じられるまで読み、流れてくる音へ書き足し続ける。裏のスレッドの本体である。
pub(super) fn 読み続ける(
    mut 読み手: 左右の値の読み手<ChildStdout>,
    mut 標準エラー: 標準エラーの収集,
    音: &流れてくる音,
) -> 読み取りの終わり {
    let mut 塊 = Vec::new();
    loop {
        塊.clear();
        match 読み手.次の塊を読む(&mut 塊) {
            Ok(読んだ結果::読んだ) => {
                if 音.書き足す(&塊) == 書き足した結果::閉じられた {
                    return 読み取りの終わり::閉じられた;
                }
            }
            Ok(読んだ結果::終わった) => {
                return 読み取りの終わり::終わりまで読んだ(
                    標準エラー.読み終えるまで待つ(),
                );
            }
            Err(原因) => {
                return 読み取りの終わり::読めない(
                    原因,
                    標準エラー.読み終えるまで待つ(),
                );
            }
        }
    }
}
