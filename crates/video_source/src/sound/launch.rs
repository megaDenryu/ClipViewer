//! 音を読む ffmpeg の起動と、その出力を読む仕組みの組み立て。

use std::io;
use std::process::{ChildStdout, ExitStatus};

use super::pcm_reader::左右の値の読み手;
use super::spec::音のデコードの指定;
use crate::locate::FFmpegの実行ファイル;
use crate::process::{
    デコードの失敗, 標準エラーの収集, 標準エラーの末尾, 起動した子プロセス
};

/// 起動した音のデコードとは、音を読む ffmpeg の子プロセスと、その出力を読む仕組みと、標準エラーを読み続ける仕組みの組のことである。
/// 受け取った側は `分ける` で子プロセスと読む仕組みに分け、子プロセスを止める時機を決める。落とせば止まる。
pub(crate) struct 起動した音のデコード {
    子プロセス: 起動した子プロセス,
    読み手: 左右の値の読み手<ChildStdout>,
    標準エラー: 標準エラーの収集,
}

impl 起動した音のデコード {
    /// 指定のとおりに ffmpeg を起動する。標準出力と標準エラー出力はパイプで受け取る。
    /// 読む仕組みを作れなければ、起動した ffmpeg は落とされて止まる。
    pub(crate) fn 起動する(
        指定: &音のデコードの指定,
        実行ファイル: &FFmpegの実行ファイル,
    ) -> Result<Self, デコードの失敗> {
        let mut 命令 = 実行ファイル.変換の命令();
        命令.args(指定.引数を並べる());
        let (子プロセス, パイプ) =
            起動した子プロセス::起動する(&mut 命令).map_err(デコードの失敗::起動できない)?;
        let 標準エラー =
            標準エラーの収集::起動する(パイプ.標準エラー).map_err(デコードの失敗::起動できない)?;
        Ok(Self {
            子プロセス,
            読み手: 左右の値の読み手::作成する(パイプ.標準出力),
            標準エラー,
        })
    }

    /// 子プロセスと、出力の読み手と、標準エラーの収集に分ける。読む仕事を別のスレッドへ渡し、子プロセスは手元に残すときに使う。
    pub(crate) fn 分ける(
        self,
    ) -> (
        起動した子プロセス,
        左右の値の読み手<ChildStdout>,
        標準エラーの収集,
    ) {
        (self.子プロセス, self.読み手, self.標準エラー)
    }

    /// 終了状態と標準エラーの末尾から、失敗かを決める。
    pub(crate) fn 失敗かを決める(
        終了状態: io::Result<ExitStatus>,
        標準エラーの末尾: 標準エラーの末尾,
    ) -> Option<デコードの失敗> {
        match 終了状態 {
            Err(原因) => Some(デコードの失敗::出力を読めない {
                原因,
                標準エラーの末尾,
            }),
            Ok(状態) if !状態.success() => Some(デコードの失敗::異常終了 {
                終了状態: 状態,
                標準エラーの末尾,
            }),
            Ok(_) => None,
        }
    }
}
