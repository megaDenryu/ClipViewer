//! 音の溜め方。区間の音をどの周波数で、開始のどれだけ前から溜め、どれだけのメモリまで使うかを持ち、見積もりを求める。

use audio_pcm::{
    サンプリング周波数, 動画上の標本位置, 左右の値のバイト数, 標本数
};
use clip_domain::{動画上の区間, 時間の長さ};

use crate::bytes::バイト数;

/// 音のメモリの上限とは、音の倉庫が溜める音に使ってよいメモリの大きさの上限のことである。映像の倉庫の上限とは別に数える。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(transparent)]
pub struct 音のメモリの上限(バイト数);

impl 音のメモリの上限 {
    /// 既定の上限(256,000,000バイト)。48kHz なら約11分が収まる。
    pub const 既定: Self = Self(バイト数::作成する(256_000_000));

    /// 大きさから作成する。
    pub fn 作成する(大きさ: バイト数) -> Self {
        Self(大きさ)
    }

    /// 上限の大きさ。
    pub fn 大きさ(self) -> バイト数 {
        self.0
    }

    /// その大きさが上限に収まるか。
    pub fn 収まるか(self, 大きさ: バイト数) -> bool {
        大きさ <= self.0
    }
}

/// 音の溜め方とは、音を出させるサンプリング周波数と、区間の開始より前に余分に溜める長さと、音のメモリの上限の組のことである。
/// 開始より前を溜めるのは、鳴らす側が区間の終わりで開始の手前の音と重ねて交差させるためである。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 音の溜め方 {
    /// FFmpeg に出させる周波数(出力装置の周波数)。
    pub 周波数: サンプリング周波数,
    /// 区間の開始より前に余分に溜める長さ。
    pub 開始の前の余白: 時間の長さ,
    /// 音のメモリの上限。
    pub 上限: 音のメモリの上限,
}

impl 音の溜め方 {
    /// 区間を溜めるときに読む最初の標本の位置と標本数。開始の前の余白は動画の先頭より前へは伸ばさない。
    pub(crate) fn 読む範囲(
        &self,
        区間: &動画上の区間,
    ) -> (動画上の標本位置, 標本数) {
        let 開始 = self.周波数.時刻を含む標本位置(区間.開始());
        let 先頭 = 開始.戻す(self.周波数.長さの標本数(self.開始の前の余白));
        let 終了 = self.周波数.時刻を含む標本位置(区間.終了());
        (先頭, 終了.起点からの標本数(先頭))
    }

    /// 区間を溜めるのに要るメモリの見積もり。
    pub(crate) fn 見積もる(&self, 区間: &動画上の区間) -> バイト数 {
        let (_, 数) = self.読む範囲(区間);
        let 一標本のバイト数 = u64::try_from(左右の値のバイト数).unwrap_or(u64::MAX);
        バイト数::作成する(u64::from(数.値()).saturating_mul(一標本のバイト数))
    }
}
