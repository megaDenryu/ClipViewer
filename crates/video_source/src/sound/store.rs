//! 音の倉庫の公開の口。

use std::io;
use std::sync::Arc;

use clip_domain::{動画上の区間, 正規化した動画パス};

use super::plan::音の溜め方;
use super::status::音の区間の状況;
use super::store_shared::倉庫の共有;
use super::store_worker::音を溜める作業;
use crate::locate::FFmpegの実行ファイル;
use crate::process::終わりを待つスレッド;

/// 音の倉庫とは、1つの動画について、画面から渡された区間の並びの音を裏のスレッドで読んで溜め、取り出させるもののことである。
/// 別の動画を読み込んだら作り直す。落とすと、読んでいる ffmpeg を止め、裏のスレッドに止まるよう求めて終わりを待つ。
pub struct 音の倉庫 {
    共有: Arc<倉庫の共有>,
    _スレッド: 終わりを待つスレッド<()>,
}

impl 音の倉庫 {
    pub(crate) fn 開く(
        実行ファイル: FFmpegの実行ファイル,
        動画: 正規化した動画パス,
        溜め方: 音の溜め方,
    ) -> io::Result<Self> {
        let 共有 = Arc::new(倉庫の共有::空(溜め方));
        let 作業 = 音を溜める作業 {
            共有: Arc::clone(&共有),
            実行ファイル,
            動画,
        };
        let スレッド =
            終わりを待つスレッド::起動する("音の倉庫の読み出し", move || {
                作業.依頼を待ち続ける()
            })?;
        Ok(Self {
            共有,
            _スレッド: スレッド,
        })
    }

    /// 音の溜め方。
    pub fn 溜め方(&self) -> 音の溜め方 {
        self.共有.錠を取る().行.溜め方()
    }

    /// 溜める区間の並び(先頭ほど先に読み、残したい)を渡す。並びに無い区間はすぐに捨て、上限に収まらない区間は溜めない。
    pub fn 溜める区間の並びを渡す(&self, 並び: &[動画上の区間]) {
        self.共有.並びを置き換える(並び);
    }

    /// 区間の状況。溜め終えていれば溜めた音を持つ。
    pub fn 区間の状況(&self, 区間: &動画上の区間) -> 音の区間の状況 {
        self.共有.錠を取る().行.状況(区間)
    }
}

impl Drop for 音の倉庫 {
    fn drop(&mut self) {
        self.共有.止めるよう求める();
    }
}
