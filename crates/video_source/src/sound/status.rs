//! 音の倉庫の区間の状況。

use std::sync::Arc;

use audio_pcm::溜めた音;

use crate::process::デコードの失敗;

/// 音の区間の状況とは、音の倉庫がある区間の音をどこまで溜めたかの区別のことである。
#[derive(Debug, Clone)]
pub enum 音の区間の状況 {
    /// 渡された並びに無い区間である。
    並びに無い,
    /// 読む順番を待っている。
    処理を待っている,
    /// ffmpeg で読んでいる。
    読んでいる,
    /// 溜め終えた。
    溜め終えた(Arc<溜めた音>),
    /// 並びの前の区間で上限が埋まり、溜めない。流し読みで鳴らす。
    上限に収まらない,
    /// 読めなかった。
    失敗(Arc<デコードの失敗>),
}

impl 音の区間の状況 {
    /// 溜め終えた音。溜め終えていなければ無い。
    pub fn 溜めた音(&self) -> Option<&Arc<溜めた音>> {
        match self {
            Self::溜め終えた(音) => Some(音),
            Self::並びに無い
            | Self::処理を待っている
            | Self::読んでいる
            | Self::上限に収まらない
            | Self::失敗(_) => None,
        }
    }
}
