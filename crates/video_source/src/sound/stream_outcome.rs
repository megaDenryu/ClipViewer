//! 音の流し読みが読み終わったかの判定と、その公開の状態。

use super::launch::起動した音のデコード;
use super::stream_reader::読み取りの終わり;
use crate::process::{
    デコードの失敗, 標準エラーの末尾, 起動した子プロセス
};

/// 音の流し読みの状態とは、音の流し読みがまだ読んでいるか、動画の終わりまで読んだか、失敗したかの区別のことである。
#[derive(Debug)]
pub enum 音の流し読みの状態<'流し読み> {
    /// まだ読んでいる。
    読んでいる,
    /// 動画の終わりまで読んだ。
    終わりまで読んだ,
    /// 読めなかった。
    失敗(&'流し読み デコードの失敗),
}

/// 流し読みの結末とは、裏のスレッドが終わった後に決まった、終わりまで読んだか失敗したかの記録のことである。
pub(super) enum 流し読みの結末 {
    まだ,
    終わりまで読んだ,
    失敗(デコードの失敗),
}

impl 流し読みの結末 {
    pub(super) fn まだか(&self) -> bool {
        matches!(self, Self::まだ)
    }

    /// 裏のスレッドの終わりと ffmpeg の終了状態から結末を決める。スレッドが異常終了していれば `None` を受け取る。
    pub(super) fn 終わりから決める(
        終わり: Option<読み取りの終わり>,
        子プロセス: &mut 起動した子プロセス,
    ) -> Self {
        match 終わり {
            Some(読み取りの終わり::終わりまで読んだ(末尾)) => {
                match 起動した音のデコード::失敗かを決める(
                    子プロセス.終わりを待つ(),
                    末尾,
                ) {
                    Some(失敗) => Self::失敗(失敗),
                    None => Self::終わりまで読んだ,
                }
            }
            Some(読み取りの終わり::読めない(原因, 標準エラーの末尾)) => {
                Self::失敗(デコードの失敗::出力を読めない {
                    原因,
                    標準エラーの末尾,
                })
            }
            Some(読み取りの終わり::閉じられた) | None => {
                Self::失敗(デコードの失敗::出力を読めない {
                    原因: std::io::Error::other("音の流し読みの裏のスレッドが途中で止まった"),
                    標準エラーの末尾: 標準エラーの末尾::default(),
                })
            }
        }
    }

    pub(super) fn 状態(&self) -> 音の流し読みの状態<'_> {
        match self {
            Self::まだ => 音の流し読みの状態::読んでいる,
            Self::終わりまで読んだ => 音の流し読みの状態::終わりまで読んだ,
            Self::失敗(失敗) => 音の流し読みの状態::失敗(失敗),
        }
    }
}
