//! 動画の読み手の、音についての口。音の倉庫・音の流し読みを開く口を持つ。音があるかは `動画の情報::音の有無` が持つ。

use audio_pcm::サンプリング周波数;
use clip_domain::動画上の秒;

use super::plan::音の溜め方;
use super::store::音の倉庫;
use super::stream::音の流し読み;
use crate::process::デコードの失敗;
use crate::reader::動画の読み手;
use crate::video_info::動画の情報;

impl 動画の読み手 {
    /// 1つの動画に結び付いた音の倉庫を開く。裏のスレッドを起動して待たずに返る。
    pub fn 音の倉庫を開く(
        &self,
        動画: &動画の情報,
        溜め方: 音の溜め方,
    ) -> std::io::Result<音の倉庫> {
        音の倉庫::開く(self.実行ファイル().clone(), 動画.パス().clone(), 溜め方)
    }

    /// 開始の時刻から動画の終わりまでの音の流し読みを開く。ffmpeg を起動して待たずに返る。
    pub fn 音の流し読みを開く(
        &self,
        動画: &動画の情報,
        開始: 動画上の秒,
        周波数: サンプリング周波数,
    ) -> Result<音の流し読み, デコードの失敗> {
        音の流し読み::開く(self.実行ファイル(), 動画.パス(), 開始, 周波数)
    }
}
