//! 音の倉庫の行の並び。渡された区間の並びと上限から、どの区間を溜めるかと、次に読む区間を決める純粋な判断。

use std::sync::Arc;

use audio_pcm::溜めた音;
use clip_domain::動画上の区間;

use super::plan::音の溜め方;
use super::status::音の区間の状況;
use crate::bytes::バイト数;
use crate::process::デコードの失敗;

/// 音の行とは、溜める区間の1つと、その区間の状況の組のことである。
struct 音の行 {
    区間: 動画上の区間,
    状況: 音の区間の状況,
}

/// 音の行の並びとは、画面から渡された順の区間の行のことである。先頭ほど先に読み、上限の内に残す。
/// 並びの状況は `並びに無い` にならない。並びから外れた区間は行ごと消す。
pub(crate) struct 音の行の並び {
    溜め方: 音の溜め方,
    行: Vec<音の行>,
}

impl 音の行の並び {
    pub(crate) fn 空(溜め方: 音の溜め方) -> Self {
        Self {
            溜め方,
            行: Vec::new(),
        }
    }

    /// 区間の並びへ置き換える。並びに残った区間は状況を引き継ぎ、無くなった区間は溜めた音ごと捨てる。
    /// 並びの順に見積もりを足し、上限を超えた区間から後ろは溜めない(溜めていたら捨てる)。同じ区間の2つ目は無視する。
    pub(crate) fn 並びを置き換える(&mut self, 区間の並び: &[動画上の区間]) {
        let mut 前の行 = std::mem::take(&mut self.行);
        let mut 合計 = バイト数::ゼロ;
        for 区間 in 区間の並び {
            if self.行.iter().any(|行| 行.区間 == *区間) {
                continue;
            }
            合計 = 合計.足す(self.溜め方.見積もる(区間));
            let 引き継ぐ状況 = 前の行
                .iter()
                .position(|行| 行.区間 == *区間)
                .map(|位置| 前の行.swap_remove(位置).状況);
            let 状況 = if !self.溜め方.上限.収まるか(合計) {
                音の区間の状況::上限に収まらない
            } else {
                match 引き継ぐ状況 {
                    None | Some(音の区間の状況::上限に収まらない | 音の区間の状況::並びに無い) => {
                        音の区間の状況::処理を待っている
                    }
                    Some(状況) => 状況,
                }
            };
            self.行.push(音の行 {
                区間: *区間, 状況
            });
        }
    }

    /// 並びの順で最初の処理を待っている区間を、読んでいるにして返す。
    pub(crate) fn 次に読む区間(&mut self) -> Option<動画上の区間> {
        let 行 = self
            .行
            .iter_mut()
            .find(|行| matches!(行.状況, 音の区間の状況::処理を待っている))?;
        行.状況 = 音の区間の状況::読んでいる;
        Some(行.区間)
    }

    /// 区間をまだ読んでいるか(並びから外されていないか)。
    pub(crate) fn まだ読むか(&self, 区間: &動画上の区間) -> bool {
        self.行
            .iter()
            .any(|行| 行.区間 == *区間 && matches!(行.状況, 音の区間の状況::読んでいる))
    }

    /// 読み終えた結果を置く。区間がまだ読んでいる行であるときだけ置く。
    pub(crate) fn 読み終えた結果を置く(
        &mut self,
        区間: &動画上の区間,
        結果: Result<溜めた音, デコードの失敗>,
    ) {
        let Some(行) = self
            .行
            .iter_mut()
            .find(|行| 行.区間 == *区間 && matches!(行.状況, 音の区間の状況::読んでいる))
        else {
            return;
        };
        行.状況 = match 結果 {
            Ok(音) => 音の区間の状況::溜め終えた(Arc::new(音)),
            Err(失敗) => 音の区間の状況::失敗(Arc::new(失敗)),
        };
    }

    /// 区間の状況。並びに無ければ `並びに無い` である。
    pub(crate) fn 状況(&self, 区間: &動画上の区間) -> 音の区間の状況 {
        self.行
            .iter()
            .find(|行| 行.区間 == *区間)
            .map_or(音の区間の状況::並びに無い, |行| 行.状況.clone())
    }

    pub(crate) fn 溜め方(&self) -> 音の溜め方 {
        self.溜め方
    }
}
