//! 音の倉庫の裏のスレッドの本体。並びの順に処理を待っている区間を1つずつ ffmpeg で読み切る。

use std::process::ChildStdout;
use std::sync::Arc;

use audio_pcm::{左右の値, 標本数, 溜めた音};
use clip_domain::{動画上の区間, 正規化した動画パス};

use super::launch::起動した音のデコード;
use super::pcm_reader::{
    一回に足す標本数の上限, 左右の値の読み手, 読んだ結果
};
use super::read_stop::{区間の読み取りの結末, 読むのをやめた理由};
use super::spec::{読む標本数, 音のデコードの指定};
use super::store_shared::倉庫の共有;
use crate::locate::FFmpegの実行ファイル;
use crate::process::デコードの失敗;

/// 音を溜める作業とは、裏のスレッドで、倉庫の共有から次に読む区間を受け取っては ffmpeg で読み切る仕事のことである。
pub(super) struct 音を溜める作業 {
    pub(super) 共有: Arc<倉庫の共有>,
    pub(super) 実行ファイル: FFmpegの実行ファイル,
    pub(super) 動画: 正規化した動画パス,
}

impl 音を溜める作業 {
    /// 倉庫が落とされるまで、次に読む区間を待っては読み、結果を置く。
    pub(super) fn 依頼を待ち続ける(self) {
        while let Some(区間) = self.共有.次に読む区間を待つ() {
            if let Some(結果) = self.区間を読む(&区間) {
                self.共有.錠を取る().行.読み終えた結果を置く(&区間, 結果);
            }
        }
    }

    /// 区間を読む。途中で要らなくなったら ffmpeg を止めて `None` を返す。
    fn 区間を読む(
        &self,
        区間: &動画上の区間,
    ) -> Option<Result<溜めた音, デコードの失敗>> {
        let 溜め方 = self.共有.錠を取る().行.溜め方();
        let (先頭, 数) = 溜め方.読む範囲(区間);
        let 指定 = 音のデコードの指定 {
            動画: self.動画.clone(),
            先頭,
            読む数: 読む標本数::数(数),
            周波数: 溜め方.周波数,
        };
        let 結果 = match 起動した音のデコード::起動する(&指定, &self.実行ファイル)
        {
            Ok(起動) => self.読み切る(区間, 起動, 数)?,
            Err(失敗) => Err(失敗),
        };
        Some(結果.map(|値の並び| 溜めた音::作成する(先頭, 値の並び)))
    }

    /// 起動した ffmpeg の出力を、数だけ読むか出力が閉じるまで読む。途中で要らなくなったら止めて `None` を返す。
    /// ffmpeg は読む間だけ倉庫の共有へ預け、倉庫を落とす側が止められるようにする。
    fn 読み切る(
        &self,
        区間: &動画上の区間,
        起動: 起動した音のデコード,
        数: 標本数,
    ) -> Option<Result<Vec<左右の値>, デコードの失敗>> {
        let (子プロセス, mut 読み手, 標準エラー) = 起動.分ける();
        if !self.共有.子プロセスを預ける(子プロセス) {
            return None;
        }
        // 注意: 数に届いた塊で読むのをやめるため、最後の塊の分だけ数を超える。その分を先に確保し、途中で確保し直さない。
        let mut 値の並び = Vec::with_capacity(数.並びの長さ() + 一回に足す標本数の上限);
        let 理由 = self.やめるまで読む(区間, &mut 読み手, &mut 値の並び, 数);
        drop(読み手);
        let mut 子プロセス = self.共有.子プロセスを引き取る()?;
        match 理由.ffmpegを終わらせる(&mut 子プロセス, 標準エラー) {
            区間の読み取りの結末::要らなくなった => None,
            区間の読み取りの結末::失敗(失敗) => Some(Err(失敗)),
            区間の読み取りの結末::読み終えた => {
                値の並び.truncate(数.並びの長さ());
                Some(Ok(値の並び))
            }
        }
    }

    /// 数だけ読むか、出力が閉じるか、読めないか、区間が要らなくなるまで読み、やめた理由を返す。
    fn やめるまで読む(
        &self,
        区間: &動画上の区間,
        読み手: &mut 左右の値の読み手<ChildStdout>,
        値の並び: &mut Vec<左右の値>,
        数: 標本数,
    ) -> 読むのをやめた理由 {
        loop {
            let 結果 = 読み手.次の塊を読む(値の並び);
            if !self.共有.まだ要るか(区間) {
                return 読むのをやめた理由::要らなくなった;
            }
            match 結果 {
                Ok(読んだ結果::読んだ) if 値の並び.len() < 数.並びの長さ() => {}
                Ok(読んだ結果::読んだ) => {
                    return 読むのをやめた理由::数に届いた;
                }
                Ok(読んだ結果::終わった) => {
                    return 読むのをやめた理由::出力が閉じた;
                }
                Err(原因) => return 読むのをやめた理由::読めない(原因),
            }
        }
    }
}
