//! 音の流し読み。開始の時刻から動画の終わりまでの音を裏のスレッドで読み、流れてくる音へ書き足す。

use std::sync::Arc;

use audio_pcm::{サンプリング周波数, 流れてくる音};
use clip_domain::{動画上の秒, 時間の長さ, 正規化した動画パス};

use super::launch::起動した音のデコード;
use super::spec::{読む標本数, 音のデコードの指定};
use super::stream_outcome::{流し読みの結末, 音の流し読みの状態};
use super::stream_reader::{読み取りの終わり, 読み続ける};
use crate::locate::FFmpegの実行ファイル;
use crate::process::{
    デコードの失敗, 終わりを待つスレッド, 起動した子プロセス
};

/// 流れてくる音の容量(秒)。書き手はこれより先へ読み進めず、鳴らす側が進むのを待つ。
const 容量の秒数: f64 = 4.0;

/// 鳴らしている位置より前に残す長さ(秒)。鳴らす側が少し戻って読み直せるようにする。
const 残す秒数: f64 = 0.5;

/// 音の流し読みとは、開始の時刻から動画の終わりまでの音を裏のスレッドで読み、流れてくる音へ書き足すもののことである。
/// 位置を戻すときは、これを落として新しく開く。落とすと、入れ物を閉じ、ffmpeg を止め、裏のスレッドの終わりを待つ。
pub struct 音の流し読み {
    音: Arc<流れてくる音>,
    子プロセス: 起動した子プロセス,
    スレッド: 終わりを待つスレッド<読み取りの終わり>,
    結末: 流し読みの結末,
}

impl 音の流し読み {
    pub(crate) fn 開く(
        実行ファイル: &FFmpegの実行ファイル,
        動画: &正規化した動画パス,
        開始: 動画上の秒,
        周波数: サンプリング周波数,
    ) -> Result<Self, デコードの失敗> {
        let 指定 = 音のデコードの指定 {
            動画: 動画.clone(),
            先頭: 周波数.時刻を含む標本位置(開始),
            読む数: 読む標本数::終わりまで,
            周波数,
        };
        let (子プロセス, 読み手, 標準エラー) =
            起動した音のデコード::起動する(&指定, 実行ファイル)?.分ける();
        let 秒 = |秒数| {
            周波数.長さの標本数(時間の長さ::作成する(秒数).unwrap_or(時間の長さ::ゼロ))
        };
        let 音 = Arc::new(流れてくる音::作成する(
            指定.先頭,
            秒(容量の秒数),
            秒(残す秒数),
        ));
        let 書き手の音 = Arc::clone(&音);
        let スレッド = 終わりを待つスレッド::起動する("音の流し読み", move || {
            読み続ける(読み手, 標準エラー, &書き手の音)
        })
        .map_err(デコードの失敗::起動できない)?;
        Ok(Self {
            音,
            子プロセス,
            スレッド,
            結末: 流し読みの結末::まだ,
        })
    }

    /// 流れてくる音。鳴らす側へ渡す。
    pub fn 音(&self) -> &Arc<流れてくる音> {
        &self.音
    }

    /// 読み終わったかを問い合わせる。待たずに返る。
    pub fn 状態(&mut self) -> 音の流し読みの状態<'_> {
        if self.結末.まだか() && self.スレッド.終わったか() {
            let 終わり = self.スレッド.終わるまで待つ();
            self.結末 =
                流し読みの結末::終わりから決める(終わり, &mut self.子プロセス);
        }
        self.結末.状態()
    }
}

impl Drop for 音の流し読み {
    fn drop(&mut self) {
        self.音.閉じる();
        self.子プロセス.止めて終わりを待つ();
    }
}
