//! 音の倉庫の行の並びの試験。並びの順に上限まで溜め、並びから外れた区間を捨て、読み終えた結果を置く。

#![allow(clippy::expect_used)]

use audio_pcm::{サンプリング周波数, 動画上の標本位置, 溜めた音};
use clip_domain::{動画上の区間, 時刻, 時間の長さ};

use super::plan::{音のメモリの上限, 音の溜め方};
use super::rows::音の行の並び;
use super::status::音の区間の状況;
use crate::bytes::バイト数;

fn 区間(開始: f64, 終了: f64) -> 動画上の区間 {
    let 秒 = |値| 時刻::作成する(値).expect("時刻");
    動画上の区間::作成する(秒(開始), 秒(終了)).expect("区間")
}

/// 1000Hz・余白0.01秒(10標本)・上限160バイト(20標本)の溜め方。1秒の区間は1010標本で上限を超える。
fn 溜め方(上限のバイト数: u64) -> 音の溜め方 {
    音の溜め方 {
        周波数: サンプリング周波数::作成する(1000).expect("周波数"),
        開始の前の余白: 時間の長さ::作成する(0.01).expect("長さ"),
        上限: 音のメモリの上限::作成する(バイト数::作成する(上限のバイト数)),
    }
}

#[test]
fn 読む範囲は開始の余白を含み動画の先頭より前へ伸ばさない() {
    let 溜め方 = 溜め方(1_000_000);
    let (先頭, 数) = 溜め方.読む範囲(&区間(1.0, 1.5));
    assert_eq!((先頭.値(), 数.値()), (990, 510));
    let (先頭, 数) = 溜め方.読む範囲(&区間(0.0, 0.5));
    assert_eq!((先頭.値(), 数.値()), (0, 500));
    assert_eq!(溜め方.見積もる(&区間(1.0, 1.5)).値(), 510 * 8);
}

#[test]
fn 並びの順に上限まで溜め残りは上限に収まらない() {
    let mut 並び = 音の行の並び::空(溜め方(510 * 8 + 100));
    let 前 = 区間(1.0, 1.5);
    let 後 = 区間(3.0, 3.5);
    並び.並びを置き換える(&[前, 後]);
    assert!(matches!(並び.状況(&前), 音の区間の状況::処理を待っている));
    assert!(matches!(並び.状況(&後), 音の区間の状況::上限に収まらない));
    assert_eq!(並び.次に読む区間(), Some(前));
    assert_eq!(並び.次に読む区間(), None);
    並び.並びを置き換える(&[後, 前]);
    assert!(matches!(並び.状況(&前), 音の区間の状況::上限に収まらない));
    assert!(!並び.まだ読むか(&前), "上限から外れた区間は読むのをやめる");
    assert_eq!(並び.次に読む区間(), Some(後));
}

#[test]
fn 読み終えた結果は並びに残る区間にだけ置く() {
    let mut 並び = 音の行の並び::空(溜め方(1_000_000));
    let 前 = 区間(1.0, 1.5);
    並び.並びを置き換える(&[前]);
    assert_eq!(並び.次に読む区間(), Some(前));
    let 音 = 溜めた音::作成する(動画上の標本位置::作成する(990), vec![[0.5, 0.5]; 510]);
    並び.読み終えた結果を置く(&前, Ok(音.clone()));
    assert!(並び.状況(&前).溜めた音().is_some());
    並び.並びを置き換える(&[]);
    assert!(matches!(並び.状況(&前), 音の区間の状況::並びに無い));
    並び.読み終えた結果を置く(&前, Ok(音));
    assert!(matches!(並び.状況(&前), 音の区間の状況::並びに無い));
}
