//! 撮影に使う動画の情報の覚え。同じ動画から作ったスタックのサムネイルを続けて撮るとき、動画の情報を動画ごとに1回だけ調べる。

use std::collections::HashMap;
use std::time::SystemTime;

use clip_domain::{
    サムネイルの撮り方, サムネイルの画像, 正規化した動画パス
};

use super::failure::サムネイルの撮影の失敗;
use crate::process::取り消しの合図;
use crate::reader::動画の読み手;
use crate::video_info::動画の情報;

/// ファイルの印とは、動画のファイルの大きさと最後に書き換えた日時の組のことである。どちらかが変われば、動画を調べ直す。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct ファイルの印 {
    大きさ: u64,
    書き換えた日時: SystemTime,
}

impl ファイルの印 {
    /// ファイルの情報から調べる。調べられない(ファイルでない入力や見つからないファイル)なら無い。
    fn 調べる(パス: &正規化した動画パス) -> Option<Self> {
        let 情報 = std::fs::metadata(パス.文字列()).ok()?;
        Some(Self {
            大きさ: 情報.len(),
            書き換えた日時: 情報.modified().ok()?,
        })
    }
}

/// 撮影に使う動画の情報の覚えとは、動画のパスごとに、調べたときのファイルの印と動画の情報を覚えたもののことである。
/// サムネイルを撮る裏のスレッドが1つ持つ。ファイルの印を調べられない入力は覚えず、毎回調べる。
#[derive(Debug, Default)]
pub struct 撮影に使う動画の情報の覚え(
    HashMap<正規化した動画パス, (ファイルの印, 動画の情報)>,
);

impl 撮影に使う動画の情報の覚え {
    /// 撮り方のコマを JPEG にして返す。動画の情報は、ファイルの大きさと最後に書き換えた日時が覚えたときと同じなら使い回す。
    /// 失敗の扱いは `動画の読み手::サムネイルを作る` と同じである。
    pub fn サムネイルを作る(
        &mut self,
        読み手: &動画の読み手,
        撮り方: &サムネイルの撮り方,
        合図: &取り消しの合図,
    ) -> Result<サムネイルの画像, サムネイルの撮影の失敗> {
        let 動画 = self.動画の情報を取る(読み手, 撮り方.動画のパス(), 合図)?;
        読み手.調べた情報でサムネイルを作る(撮り方, &動画, 合図)
    }

    fn 動画の情報を取る(
        &mut self,
        読み手: &動画の読み手,
        パス: &正規化した動画パス,
        合図: &取り消しの合図,
    ) -> Result<動画の情報, サムネイルの撮影の失敗> {
        let 印 = ファイルの印::調べる(パス);
        if let (Some(印), Some((覚えた印, 覚えた情報))) = (印, self.0.get(パス))
            && 印 == *覚えた印
        {
            return Ok(覚えた情報.clone());
        }
        self.0.remove(パス);
        let 情報 = 読み手.撮る動画の情報を取る(パス, 合図)?;
        if let Some(印) = 印 {
            self.0.insert(パス.clone(), (印, 情報.clone()));
        }
        Ok(情報)
    }
}
