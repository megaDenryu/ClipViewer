//! サムネイルを撮る口。撮り方の時刻のコマを1枚だけデコードし、クロップを掛け、撮り方の大きさへ収めた JPEG を ffmpeg に作らせる。
//! ffmpeg が JPEG を標準出力へ書き、画素を RGBA で受け取らないため、1枚の受け渡しは数KBで済む。
//! 固まった ffmpeg が撮影の全体を止めないよう、期限を過ぎたら止める。参照: _doc/設計/ライブラリ.md 判断10

mod arguments;
mod failure;
mod memo;

#[cfg(test)]
mod arguments_tests;

pub use failure::サムネイルの撮影の失敗;
pub use memo::撮影に使う動画の情報の覚え;

use std::time::Duration;

use clip_domain::{
    サムネイルの撮り方, サムネイルの画像, 正規化した動画パス
};

use crate::process::{取り消しの合図, 期限付きの子プロセス};
use crate::reader::{動画の読み手, 調査の期限};
use crate::video_info::動画の情報;

/// サムネイルを撮る ffmpeg の期限。1枚は通常0.1〜0.25秒ほどで撮れるため、10秒を過ぎたものは固まったとみなす。
/// 撮る前に動画の情報を調べる ffprobe の期限は、動画を開くときと同じ30秒である(撮る処理は裏のスレッドで行うため、長くても画面は止まらない)。
const 撮影の期限: Duration = Duration::from_secs(10);

impl 動画の読み手 {
    /// 撮り方のコマを JPEG にして返す。ffprobe で動画の情報を調べてから、再生と同じ規則(`コマを読む位置`)で撮り方の時刻に
    /// 映っているコマを ffmpeg に撮らせ、終わるまで待つ(画面のスレッドからは呼ばない)。同じ動画から続けて撮るなら、
    /// 動画の情報を使い回す `撮影に使う動画の情報の覚え` を使う。
    /// 撮り方の時刻が動画の終わりより後ろにあるときは、コマが無いとして失敗する。期限を過ぎるか、合図で取り消されたら、
    /// 子プロセスを止めて失敗する。
    pub fn サムネイルを作る(
        &self,
        撮り方: &サムネイルの撮り方,
        合図: &取り消しの合図,
    ) -> Result<サムネイルの画像, サムネイルの撮影の失敗> {
        let 動画 = self.撮る動画の情報を取る(撮り方.動画のパス(), 合図)?;
        self.調べた情報でサムネイルを作る(撮り方, &動画, 合図)
    }

    /// 撮る前に ffprobe で動画の情報を調べる。期限は動画を開くときと同じである。
    pub(crate) fn 撮る動画の情報を取る(
        &self,
        パス: &正規化した動画パス,
        合図: &取り消しの合図,
    ) -> Result<動画の情報, サムネイルの撮影の失敗> {
        self.期限付きで動画の情報を取る(パス, 調査の期限, 合図)
            .map_err(|失敗| {
                サムネイルの撮影の失敗::調査の失敗から作る(失敗, 調査の期限)
            })
    }

    /// 調べた動画の情報を使って、撮り方のコマを ffmpeg に JPEG にさせる。
    pub(crate) fn 調べた情報でサムネイルを作る(
        &self,
        撮り方: &サムネイルの撮り方,
        動画: &動画の情報,
        合図: &取り消しの合図,
    ) -> Result<サムネイルの画像, サムネイルの撮影の失敗> {
        let mut 命令 = self.実行ファイル().変換の命令();
        命令.args(arguments::サムネイルの引数を並べる(
            撮り方, 動画,
        ));
        let 出力 = 期限付きの子プロセス::起動する(命令)
            .and_then(|子プロセス| 子プロセス.終わるまで待つ(撮影の期限, 合図))
            .map_err(|失敗| {
                サムネイルの撮影の失敗::待ちの失敗から作る(失敗, 撮影の期限)
            })?;
        if !出力.終了状態.success() {
            return Err(サムネイルの撮影の失敗::異常終了 {
                終了状態: 出力.終了状態,
                標準エラーの末尾: 出力.標準エラーの末尾,
            });
        }
        if 出力.標準出力.is_empty() {
            return Err(サムネイルの撮影の失敗::コマが無い {
                標準エラーの末尾: 出力.標準エラーの末尾,
            });
        }
        Ok(サムネイルの画像::作成する(出力.標準出力))
    }
}
