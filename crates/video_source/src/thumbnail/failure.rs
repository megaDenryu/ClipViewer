//! サムネイルの撮影の失敗の型。

use std::io;
use std::process::ExitStatus;
use std::time::Duration;

use crate::probe::{動画の情報の取得エラー, 調査の失敗};
use crate::process::{期限付きの待ちの失敗, 標準エラーの末尾};

/// サムネイルの撮影の失敗とは、ffmpeg でサムネイルの JPEG を作れなかった理由の区別のことである。
#[derive(Debug, thiserror::Error)]
pub enum サムネイルの撮影の失敗 {
    /// 撮る前に ffprobe で動画の情報(コマの速さ・読む映像の流れ)を取れなかった。
    #[error("動画の情報を取れない: {0}")]
    動画の情報を取れない(#[source] 動画の情報の取得エラー),
    /// ffmpeg を起動できなかった。
    #[error("ffmpeg を起動できない: {0}")]
    起動できない(#[source] io::Error),
    /// ffmpeg の終わりを確かめられなかった。
    #[error("ffmpeg の終わりを確かめられない: {0}")]
    待てない(#[source] io::Error),
    /// ffmpeg の出力を読めなかった。
    #[error("ffmpeg の出力を読めない: {0}")]
    出力を読めない(#[source] io::Error),
    /// ffmpeg が失敗の終了状態で終わった。
    #[error("ffmpeg が異常終了した({終了状態})。{標準エラーの末尾}")]
    異常終了 {
        /// ffmpeg の終了状態。
        終了状態: ExitStatus,
        /// ffmpeg の標準エラーの末尾。
        標準エラーの末尾: 標準エラーの末尾,
    },
    /// ffmpeg が正常に終わったが、コマを1つも出さなかった。時刻が動画の終わりより後ろにある等。
    #[error("ffmpeg がコマを1つも出さなかった。{標準エラーの末尾}")]
    コマが無い {
        /// ffmpeg の標準エラーの末尾。
        標準エラーの末尾: 標準エラーの末尾,
    },
    /// ffmpeg が期限までに終わらなかったので止めた。
    #[error("ffmpeg が{}秒の期限までに終わらなかったので止めた", .期限.as_secs())]
    時間切れ {
        /// 過ぎた期限。
        期限: Duration,
    },
    /// 撮影を取り消したので ffmpeg を止めた。
    #[error("撮影を取り消した")]
    取り消した,
}

impl サムネイルの撮影の失敗 {
    /// 期限付きの待ちの失敗から作る。時間切れには過ぎた期限を添える。
    pub(crate) fn 待ちの失敗から作る(
        失敗: 期限付きの待ちの失敗, 期限: Duration
    ) -> Self {
        match 失敗 {
            期限付きの待ちの失敗::起動できない(原因) => {
                Self::起動できない(原因)
            }
            期限付きの待ちの失敗::待てない(原因) => Self::待てない(原因),
            期限付きの待ちの失敗::出力を読めない(原因) => {
                Self::出力を読めない(原因)
            }
            期限付きの待ちの失敗::時間切れ => Self::時間切れ { 期限 },
            期限付きの待ちの失敗::取り消した => Self::取り消した,
        }
    }

    /// 調査の失敗から作る。待てなかったときは撮影の待ちの失敗と同じに扱う。
    pub(crate) fn 調査の失敗から作る(失敗: 調査の失敗, 期限: Duration) -> Self {
        match 失敗 {
            調査の失敗::待てなかった(失敗) => {
                Self::待ちの失敗から作る(失敗, 期限)
            }
            調査の失敗::読めなかった(エラー) => {
                Self::動画の情報を取れない(エラー)
            }
        }
    }
}
