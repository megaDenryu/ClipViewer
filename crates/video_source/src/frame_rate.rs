//! コマの速さの型と、時刻とコマ番号の対応。

use clip_domain::{
    動画上の秒, 境目を許容して切り上げた整数, 境目を許容して切り捨てた整数, 時刻, 時間の長さ,
};

use crate::frame_number::{コマ数, 動画上のコマ番号};

/// コマの速さとは、1秒あたりに表示するコマの枚数を、分子÷分母の分数で表したもののことである。
/// 分数で持つのは、29.97コマ/秒が 30000/1001 のように小数では割り切れないためである。
/// 不変条件: 分子と分母はどちらも1以上である。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct コマの速さ {
    分子: u32,
    分母: u32,
}

impl コマの速さ {
    /// 分子と分母から作成する。どちらかが0なら作らない。
    pub fn 作成する(分子: u32, 分母: u32) -> Option<Self> {
        (分子 > 0 && 分母 > 0).then_some(Self { 分子, 分母 })
    }

    /// 「30000/1001」または「30」の表記から読む。FFmpeg の出力を受け取る境界で使う。
    pub(crate) fn 分数の表記から読む(表記: &str) -> Option<Self> {
        let (分子, 分母) = 表記.split_once('/').unwrap_or((表記, "1"));
        Self::作成する(分子.trim().parse().ok()?, 分母.trim().parse().ok()?)
    }

    /// FFmpeg の引数へ渡す「分子/分母」の表記。
    pub(crate) fn 分数の表記(self) -> String {
        format!("{}/{}", self.分子, self.分母)
    }

    /// 1秒あたりのコマの枚数を小数で返す。表示の境界で使う。
    pub fn 一秒あたりのコマ数(self) -> f64 {
        f64::from(self.分子) / f64::from(self.分母)
    }

    /// その時刻に表示されているコマの番号を求める。
    pub fn 時刻を含むコマ番号(self, 位置: 動画上の秒) -> 動画上のコマ番号 {
        let コマ単位 = 位置.秒数() * self.一秒あたりのコマ数();
        動画上のコマ番号::作成する(境目を許容して切り捨てた整数(コマ単位))
    }

    /// 時刻より前に表示が始まるコマのうち、最後のコマの次の番号を求める。区間の終わりのコマの数え方に使う。
    /// 時刻がコマの始まりちょうどなら、そのコマは含まない。
    pub fn 時刻より前に始まるコマの次の番号(
        self,
        位置: 動画上の秒,
    ) -> 動画上のコマ番号 {
        let コマ単位 = 位置.秒数() * self.一秒あたりのコマ数();
        動画上のコマ番号::作成する(境目を許容して切り上げた整数(コマ単位))
    }

    /// そのコマの表示が始まる時刻を求める。
    pub fn コマの始まる時刻(self, 番号: 動画上のコマ番号) -> 動画上の秒 {
        let 秒 = f64::from(番号.値()) * f64::from(self.分母) / f64::from(self.分子);
        時刻::作成する(秒).unwrap_or(時刻::先頭)
    }

    /// 指定のコマ数を表示し終えるまでの長さを求める。
    pub fn コマ数の長さ(self, 枚数: コマ数) -> 時間の長さ {
        let 秒 = f64::from(枚数.値()) * f64::from(self.分母) / f64::from(self.分子);
        時間の長さ::作成する(秒).unwrap_or(時間の長さ::ゼロ)
    }
}
