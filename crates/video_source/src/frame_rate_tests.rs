//! コマの速さと、時刻とコマ番号の対応の試験。
use clip_domain::{動画上の秒, 時刻};

use crate::frame_rate::コマの速さ;

fn 秒(値: f64) -> 動画上の秒 {
    時刻::作成する(値).unwrap_or(時刻::先頭)
}

#[test]
fn 表記から分数を読む() {
    assert_eq!(
        コマの速さ::分数の表記から読む("30000/1001"),
        コマの速さ::作成する(30000, 1001)
    );
    assert_eq!(
        コマの速さ::分数の表記から読む("25"),
        コマの速さ::作成する(25, 1)
    );
    assert_eq!(コマの速さ::分数の表記から読む("0/0"), None);
    assert_eq!(コマの速さ::分数の表記から読む("abc"), None);
}

#[test]
fn 時刻からコマ番号を求める() {
    let Some(速さ) = コマの速さ::作成する(30, 1) else {
        panic!("速さを作れない")
    };
    assert_eq!(速さ.時刻を含むコマ番号(秒(0.0)).値(), 0);
    assert_eq!(速さ.時刻を含むコマ番号(秒(1.0)).値(), 30);
    assert_eq!(速さ.時刻を含むコマ番号(秒(29.0 / 30.0)).値(), 29);
    assert_eq!(速さ.時刻を含むコマ番号(秒(1.0 - 1e-3)).値(), 29);
}

#[test]
fn 区間の終わりはコマの始まりちょうどならそのコマを含まない() {
    let Some(速さ) = コマの速さ::作成する(30, 1) else {
        panic!("速さを作れない")
    };
    assert_eq!(速さ.時刻より前に始まるコマの次の番号(秒(2.0)).値(), 60);
    assert_eq!(速さ.時刻より前に始まるコマの次の番号(秒(2.01)).値(), 61);
    assert_eq!(速さ.時刻より前に始まるコマの次の番号(秒(0.0)).値(), 0);
}
