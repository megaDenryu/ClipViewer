//! 動画の情報と、区間を溜めるときの見積もり。

use clip_domain::{
    動画上の区間, 動画上の秒, 時刻, 時間の長さ, 正規化した動画パス
};

use crate::estimate::区間の見積もり;
use crate::frame_rate::コマの速さ;
use crate::frame_size::コマの寸法;
use crate::long_side::長辺の上限;
use crate::probe::{
    動画の情報の取得エラー, 流れの番号, 調査の出力を読む, 音の有無
};

/// 動画の情報とは、動画のパスと、ffprobe で調べた動画の長さ・元の寸法・コマの速さ・読む映像の流れ・音の有無の組のことである。
/// 元の寸法は、回転の情報に従って表示される向きの寸法である。映像を読む ffmpeg には、調べた映像の流れを番号で指定する。
#[derive(Debug, Clone, PartialEq)]
pub struct 動画の情報 {
    パス: 正規化した動画パス,
    長さ: 時間の長さ,
    元の寸法: コマの寸法,
    コマの速さ: コマの速さ,
    映像の流れ: 流れの番号,
    音の有無: 音の有無,
}

impl 動画の情報 {
    /// ffprobe の出力の本文から作る。
    pub(crate) fn 調査の出力から作る(
        パス: 正規化した動画パス,
        本文: &str,
    ) -> Result<Self, 動画の情報の取得エラー> {
        let 値 = 調査の出力を読む(本文)?;
        Ok(Self {
            パス,
            長さ: 値.長さ,
            元の寸法: 値.元の寸法,
            コマの速さ: 値.コマの速さ,
            映像の流れ: 値.映像の流れ,
            音の有無: 値.音の有無,
        })
    }

    /// 動画のパス。
    pub fn パス(&self) -> &正規化した動画パス {
        &self.パス
    }

    /// 動画の長さ。
    pub fn 長さ(&self) -> 時間の長さ {
        self.長さ
    }

    /// 表示される向きの元の寸法。
    pub fn 元の寸法(&self) -> コマの寸法 {
        self.元の寸法
    }

    /// コマの速さ。可変フレームレートの動画では、平均のコマの速さである。
    pub fn コマの速さ(&self) -> コマの速さ {
        self.コマの速さ
    }

    /// 読む映像の流れ。添付の画像を除いた最初の映像の流れである。
    pub(crate) fn 映像の流れ(&self) -> 流れの番号 {
        self.映像の流れ
    }

    /// 動画に音の流れがあるか。
    pub fn 音の有無(&self) -> 音の有無 {
        self.音の有無
    }

    /// 動画の終わりの時刻。
    pub fn 終わりの時刻(&self) -> 動画上の秒 {
        時刻::先頭.進める(self.長さ)
    }

    /// 区間を長辺の上限へ縮めて溜めるときの、コマ数と必要なバイト数を見積もる。動画の終わりより後ろは数えない。
    pub fn 区間を見積もる(
        &self,
        区間: &動画上の区間,
        上限: 長辺の上限,
    ) -> 区間の見積もり {
        let 先頭のコマ = self.コマの速さ.時刻を含むコマ番号(区間.開始());
        let 動画の終わり = self.終わりの時刻();
        let 終わり = if 区間.終了() < 動画の終わり {
            区間.終了()
        } else {
            動画の終わり
        };
        let 終わりの次 = self.コマの速さ.時刻より前に始まるコマの次の番号(終わり);
        let コマ数 = 終わりの次.起点から進んだコマ数(先頭のコマ);
        let 寸法 = self.元の寸法.長辺の上限へ縮める(上限);
        区間の見積もり::作成する(先頭のコマ, コマ数, 寸法)
    }
}
