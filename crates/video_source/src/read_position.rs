//! 先頭のコマを確実に読むための ffmpeg のシーク位置と、コマの速さをそろえる fps フィルタの指定。
//! 区間を溜めるデコード・流し読み・サムネイルが同じ規則でコマを選ぶよう、この型が ffmpeg の書き方を1か所に持つ。

use clip_domain::{動画上の秒, 時間の長さ};

use crate::frame_number::{コマ数, 動画上のコマ番号};
use crate::frame_rate::コマの速さ;

/// コマを読む位置とは、ffmpeg に先頭のコマから読ませるためのシーク位置と、fps フィルタへ入る前にコマの時刻へ足す補正と、
/// そろえるコマの速さの組のことである。
/// 2つを合わせると、先頭のコマの時刻は出力の始まりのちょうど半コマ後ろになる。fps フィルタを切り捨て(round=down)で使えば、
/// 出力のi番目は先頭のコマ+i になる。丸めの境目がどのコマの時刻からも半コマ離れるためである。
/// 注意: mkv・webm はコマの時刻をミリ秒で持ち、元のコマの時刻が理想の時刻から前後にずれる。丸めの境目をコマの時刻に置くと
/// (半コマ手前へシークして四捨五入する形)、丸めの向きがコマごとに変わってコマが重複・欠落する。
/// 注意: fps フィルタには出力の始まりを0秒と教える(start_time=0)。動画の種類によらず、シーク位置の直後にコマの無い時間が
/// あっても(可変フレームレートの隙間・入れ物の始まりより遅れて始まる映像)、出力の0番目をシーク位置の枠に保つためである。
/// 読み始めが隙間の中なら、隙間の枠は隙間の後ろの最初のコマで埋まる。読み始めが隙間より前なら、隙間の枠は隙間の前の最後の
/// コマで埋まる(fps フィルタが直前のコマを出し続けるため)。
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) struct コマを読む位置 {
    シーク位置: 動画上の秒,
    時刻の補正: 時間の長さ,
    速さ: コマの速さ,
}

impl コマを読む位置 {
    /// 先頭のコマを読む位置を求める。シーク位置は先頭のコマの始まりの半コマ手前であり、動画の先頭より前へ出る分は
    /// シークせずに時刻の補正で足す。
    pub(crate) fn 求める(速さ: コマの速さ, 先頭: 動画上のコマ番号) -> Self {
        let 半コマ =
            時間の長さ::作成する(速さ.コマ数の長さ(コマ数::作成する(1)).秒数() / 2.0)
                .unwrap_or(時間の長さ::ゼロ);
        let 始まり = 速さ.コマの始まる時刻(先頭);
        let シーク位置 = 始まり.戻す(半コマ);
        let 時刻の補正 = 半コマ.差し引く(始まり.起点から経過した長さ(シーク位置));
        Self {
            シーク位置,
            時刻の補正,
            速さ,
        }
    }

    /// ffmpeg の -ss へ渡すシーク位置の表記。
    pub(crate) fn シーク位置の表記(self) -> String {
        format!("{:.6}", self.シーク位置.秒数())
    }

    /// 時刻を補正してからコマの速さをそろえるフィルタの表記。-vf のフィルタの列の先頭に置く。
    pub(crate) fn コマをそろえるフィルタ(self) -> String {
        format!(
            "setpts=PTS+{:.6}/TB,fps={}:round=down:start_time=0",
            self.時刻の補正.秒数(),
            self.速さ.分数の表記()
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn 三十コマ毎秒() -> コマの速さ {
        コマの速さ::作成する(30, 1).unwrap_or_else(|| panic!("速さを作れない"))
    }

    #[test]
    fn シーク位置は半コマ手前で補正は無い() {
        let 位置 = コマを読む位置::求める(三十コマ毎秒(), 動画上のコマ番号::作成する(30));
        assert_eq!(位置.シーク位置の表記(), "0.983333");
        assert_eq!(
            位置.コマをそろえるフィルタ(),
            "setpts=PTS+0.000000/TB,fps=30/1:round=down:start_time=0"
        );
    }

    #[test]
    fn 先頭のコマはシークせず半コマを補正で足す() {
        let 位置 = コマを読む位置::求める(三十コマ毎秒(), 動画上のコマ番号::先頭);
        assert_eq!(位置.シーク位置の表記(), "0.000000");
        assert_eq!(
            位置.コマをそろえるフィルタ(),
            "setpts=PTS+0.016667/TB,fps=30/1:round=down:start_time=0"
        );
    }
}
