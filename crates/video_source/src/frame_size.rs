//! コマの寸法と長辺の上限の型。溜めるコマを表示用に縮めた寸法の計算を持つ。

use clip_domain::{画素の寸法, 画素の寸法エラー};

use crate::bytes::バイト数;
use crate::long_side::長辺の上限;

/// RGBA8 の1画素のバイト数。
const 一画素のバイト数: u32 = 4;

/// コマの寸法とは、デコードしたコマの幅と高さを画素の数(1以上の整数)で表したもののことである。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct コマの寸法 {
    幅: u32,
    高さ: u32,
}

impl コマの寸法 {
    /// 幅と高さから作成する。どちらかが0なら作らない。
    pub fn 作成する(幅: u32, 高さ: u32) -> Option<Self> {
        (幅 > 0 && 高さ > 0).then_some(Self { 幅, 高さ })
    }

    /// 幅の画素数。
    pub fn 幅(self) -> u32 {
        self.幅
    }

    /// 高さの画素数。
    pub fn 高さ(self) -> u32 {
        self.高さ
    }

    /// 幅と高さを入れ替えた寸法。縦向きに回転して表示する動画の寸法を求めるときに使う。
    pub(crate) fn 縦横を入れ替える(self) -> Self {
        Self {
            幅: self.高さ,
            高さ: self.幅,
        }
    }

    /// 縦横比を保ったまま、長辺が上限に収まるよう縮めた寸法を求める。上限に収まっていれば拡大せずそのまま返す。
    /// 短辺は四捨五入し、1画素を下回らない。RGBA の生データで受け取るため偶数へそろえる必要は無い。
    pub fn 長辺の上限へ縮める(self, 上限: 長辺の上限) -> Self {
        let 長辺 = self.幅.max(self.高さ);
        if 長辺 <= 上限.画素数() {
            return self;
        }
        let 縮める = |辺: u32| {
            let 分子 = u64::from(辺) * u64::from(上限.画素数()) * 2 + u64::from(長辺);
            let 縮めた辺 = 分子 / (u64::from(長辺) * 2);
            u32::try_from(縮めた辺).unwrap_or(上限.画素数()).max(1)
        };
        Self {
            幅: 縮める(self.幅),
            高さ: 縮める(self.高さ),
        }
    }

    /// RGBA8 の1コマのバイト数。
    pub fn 一コマのバイト数(self) -> バイト数 {
        バイト数::作成する(
            u64::from(self.幅) * u64::from(self.高さ) * u64::from(一画素のバイト数),
        )
    }

    /// ドメイン層の画素の寸法へ変換する。
    pub fn 画素の寸法へ変換する(
        self,
    ) -> Result<画素の寸法, 画素の寸法エラー> {
        画素の寸法::作成する(f64::from(self.幅), f64::from(self.高さ))
    }

    /// FFmpeg の scale フィルタへ渡す「幅:高さ」の指定。
    pub(crate) fn 拡大縮小の指定(self) -> String {
        format!("{}:{}", self.幅, self.高さ)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn 寸法(幅: u32, 高さ: u32) -> コマの寸法 {
        コマの寸法::作成する(幅, 高さ).unwrap_or(コマの寸法 { 幅: 1, 高さ: 1 })
    }

    #[test]
    fn 長辺が上限を超えるなら縦横比を保って縮める() {
        assert_eq!(
            寸法(1920, 1080).長辺の上限へ縮める(長辺の上限::既定),
            寸法(1280, 720)
        );
        assert_eq!(
            寸法(1080, 1920).長辺の上限へ縮める(長辺の上限::既定),
            寸法(720, 1280)
        );
        assert_eq!(
            寸法(1000, 333)
                .長辺の上限へ縮める(長辺の上限::作成する(500).unwrap_or(長辺の上限::既定)),
            寸法(500, 167)
        );
    }

    #[test]
    fn 上限に収まるなら拡大しない() {
        assert_eq!(
            寸法(640, 360).長辺の上限へ縮める(長辺の上限::既定),
            寸法(640, 360)
        );
    }

    #[test]
    fn 極端に細長い動画でも短辺は1画素を下回らない() {
        assert_eq!(
            寸法(10000, 1)
                .長辺の上限へ縮める(長辺の上限::作成する(100).unwrap_or(長辺の上限::既定)),
            寸法(100, 1)
        );
    }

    #[test]
    fn 一コマのバイト数は幅と高さと4の積である() {
        assert_eq!(
            寸法(1280, 720).一コマのバイト数(),
            バイト数::作成する(3_686_400)
        );
    }
}
