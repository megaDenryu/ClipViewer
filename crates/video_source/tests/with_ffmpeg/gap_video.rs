//! 可変フレームレートの試験動画。30コマ/秒の mkv から40番から49番のコマを抜き、残りのコマの時刻をそのまま残したもの。
//! 隙間の枠にどのコマが描かれているべきかの規則も持つ。

use std::ops::Range;

use video_source::動画の情報;

use crate::common::読み手;
use crate::numbered_videos::番号を描くフィルタ;
use crate::test_videos::動画を作る;

/// 抜いたコマの番号の範囲。
const 隙間: Range<u32> = 40..50;
/// 読み始めるコマ。隙間の前・隙間の中・隙間の後ろを含める。
pub const 読み始めるコマの一覧: [u32; 5] = [36, 40, 43, 49, 50];
pub const 確かめるコマ数: u32 = 16;

pub fn 隙間のある動画を開く(名前: &str) -> 動画の情報 {
    let 入力 = format!(
        r"color=c=black:s=320x180:r=30:d=4,format=yuv420p,{番号を描くフィルタ},select='not(between(n\,{}\,{}))'",
        隙間.start,
        隙間.end - 1
    );
    let 引数 = [
        "-f", "lavfi", "-i", &入力, "-vsync", "0", "-c:v", "libx264", "-crf", "5", "-g", "300",
    ];
    let 情報 = 読み手()
        .動画の情報を取る(&動画を作る(名前, &引数))
        .expect("動画の情報を取れない");
    assert_eq!(
        情報.コマの速さ().一秒あたりのコマ数(),
        30.0,
        "試験の前提: 平均のコマの速さが30である"
    );
    情報
}

pub fn 秒数(番号: u32) -> f64 {
    f64::from(番号) / 30.0
}

/// 先頭のコマから読んだときに、番号の枠に描かれているべき番号。隙間の枠は、読み始めが隙間の中なら隙間の後ろの最初のコマで
/// 埋まり(fps フィルタが出力の始まりを埋める)、読み始めが隙間より前なら隙間の前の最後のコマで埋まる(直前のコマを出し続ける)。
fn 描かれるべき番号(先頭: u32, 番号: u32) -> u32 {
    match (隙間.contains(&番号), 隙間.contains(&先頭)) {
        (false, _) => 番号,
        (true, true) => 隙間.end,
        (true, false) => 隙間.start - 1,
    }
}

/// 付けた番号と描かれた番号が合っているか。
pub fn 合っているか(
    先頭: u32, 番号: u32, 付けた番号: u32, 描かれた: u32
) -> bool {
    付けた番号 == 番号 && 描かれた == 描かれるべき番号(先頭, 番号)
}
