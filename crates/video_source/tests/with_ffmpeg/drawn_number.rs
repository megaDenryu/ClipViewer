//! 試験動画のコマに描いたコマ番号を、デコードしたコマや JPEG の画素から読み戻す。描き方は numbered_videos.rs の `番号を描くフィルタ` である。

use video_source::コマ;

/// 番号を描く帯の数。コマ番号の下位8ビットを、左から1ビットずつ白黒の縦の帯で描く。
const 帯の数: usize = 8;

/// コマに描かれたコマ番号の下位8ビットを読む。
pub fn 描かれた番号(読んだ: &コマ) -> u32 {
    画素から描かれた番号を読む(
        読んだ.寸法().幅(),
        読んだ.寸法().高さ(),
        読んだ.画素の並び(),
    )
}

/// RGBA の画素の並びから、描かれたコマ番号の下位8ビットを読む。各帯の真ん中の行の中央の画素の赤の強さで白黒を決める。
pub fn 画素から描かれた番号を読む(
    幅: u32, 高さ: u32, 画素の並び: &[u8]
) -> u32 {
    let 並びの長さ = |値: u32| usize::try_from(値).expect("寸法が並びの長さに収まらない");
    let (幅, 高さ) = (並びの長さ(幅), 並びの長さ(高さ));
    let 帯の幅 = 幅 / 帯の数;
    (0..帯の数)
        .filter(|帯| 画素の並び[(高さ / 2 * 幅 + 帯 * 帯の幅 + 帯の幅 / 2) * 4] > 128)
        .map(|帯| 1_u32 << 帯)
        .sum()
}
