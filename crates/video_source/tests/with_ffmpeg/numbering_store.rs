//! 時刻をミリ秒で持つ入れ物(mkv・webm)で、溜めた区間のコマが1つずつ連続して並び、
//! 付けたコマ番号とコマに描かれた番号が合うかの結合試験。

use video_source::{コマの倉庫, メモリの上限};

use crate::common::{区間, 秒, 読み手};
use crate::drawn_number::描かれた番号;
use crate::numbered_videos::{
    入れ物の一覧, 番号を描いた動画を開く, 試験の長辺, 速さの一覧
};
use crate::store_support::{受け付けた札, 完了まで待つ};

/// 溜める区間の先頭のコマ。動画の先頭・キーフレームから離れた位置・秒の境目の前後を含める。
const 区間の先頭の一覧: [u32; 11] = [0, 1, 2, 7, 29, 30, 31, 44, 59, 61, 83];
const 確かめるコマ数: u32 = 12;

#[test]
#[ignore = "FFmpeg が要る"]
fn 溜めた区間のコマは番号が1つずつ連続し描かれた番号と合う() {
    let mut 食い違い = Vec::new();
    for 速さ in 速さの一覧 {
        for 入れ物 in 入れ物の一覧 {
            let 情報 = 番号を描いた動画を開く("溜める", 速さ, 入れ物);
            let mut 倉庫 = 読み手()
                .コマの倉庫を開く(情報, 試験の長辺(), メモリの上限::既定)
                .expect("倉庫を開けない");
            for 先頭 in 区間の先頭の一覧 {
                let 終わり = 先頭 + 確かめるコマ数;
                let 溜める区間 = 区間(速さ.コマの始まり(先頭), 速さ.コマの始まり(終わり));
                let 札 = 受け付けた札(倉庫.区間を溜める依頼を出す(溜める区間));
                完了まで待つ(&mut 倉庫, 札);
                for 番号 in 先頭..終わり {
                    let 読めた = 番号を読む(&mut 倉庫, 溜める区間, 速さ.コマの真ん中(番号));
                    if 読めた != (番号, 番号 % 256) {
                        食い違い.push(format!(
                            "{速さ:?} {入れ物:?} 区間の先頭{先頭}: 期待{番号} 付けた番号と描かれた番号{読めた:?}"
                        ));
                    }
                }
            }
        }
    }
    assert!(
        食い違い.is_empty(),
        "コマが重複か欠落した:\n{}",
        食い違い.join("\n")
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 動画の終わりに届く区間は最後のコマまで溜める() {
    let mut 食い違い = Vec::new();
    for 速さ in 速さの一覧 {
        for 入れ物 in 入れ物の一覧 {
            let 情報 = 番号を描いた動画を開く("終わりまで溜める", 速さ, 入れ物);
            let mut 倉庫 = 読み手()
                .コマの倉庫を開く(情報, 試験の長辺(), メモリの上限::既定)
                .expect("倉庫を開けない");
            let (先頭, 終わり) = (速さ.動画のコマ数() - 確かめるコマ数, 速さ.動画のコマ数());
            let 溜める区間 = 区間(速さ.コマの始まり(先頭), 速さ.コマの始まり(終わり) + 1.0);
            let 札 = 受け付けた札(倉庫.区間を溜める依頼を出す(溜める区間));
            let 内訳 = 完了まで待つ(&mut 倉庫, 札);
            if 内訳.見積もりより少なかったか() {
                食い違い.push(format!("{速さ:?} {入れ物:?}: 見積もりより少ない {内訳:?}"));
            }
            for 番号 in 先頭..終わり {
                let 読めた = 番号を読む(&mut 倉庫, 溜める区間, 速さ.コマの真ん中(番号));
                if 読めた != (番号, 番号 % 256) {
                    食い違い.push(format!("{速さ:?} {入れ物:?}: 期待{番号} 読めた{読めた:?}"));
                }
            }
        }
    }
    assert!(
        食い違い.is_empty(),
        "終わりのコマが欠けた:
{}",
        食い違い.join(
            "
"
        )
    );
}

/// 溜めた区間から時刻のコマを取り出し、付けたコマ番号と描かれた番号を返す。
fn 番号を読む(
    倉庫: &mut コマの倉庫,
    溜めた区間: clip_domain::動画上の区間,
    位置: f64,
) -> (u32, u32) {
    let 取り出した = 倉庫
        .溜めたコマを取り出す(&溜めた区間, 秒(位置))
        .expect("コマを取り出せない");
    (取り出した.番号().値(), 描かれた番号(取り出した.コマ()))
}
