//! 音の読み出しの結合試験の共通の道具。440Hz の正弦波の音を付けた試験動画を作り、読んだ音が正弦波と合うかを測る。

use audio_pcm::{
    サンプリング周波数, 動画上の標本位置, 標本の範囲, 溜めた音
};
use video_source::動画の情報;

use crate::common::読み手;
use crate::test_videos::動画を作る;

/// 試験で使う出力装置の周波数。試験動画の音(44.1kHz)と違う値にして、FFmpeg が変換することも確かめる。
pub const 周波数の値: u32 = 48_000;

pub fn 周波数() -> サンプリング周波数 {
    サンプリング周波数::作成する(周波数の値).expect("周波数")
}

/// 映像(testsrc2)と 440Hz の正弦波(44.1kHz)の音を持つ3秒の試験動画を作り、情報を取る。
pub fn 音のある動画(名前: &str) -> 動画の情報 {
    let パス = 動画を作る(
        名前,
        &[
            "-f",
            "lavfi",
            "-i",
            "testsrc2=size=320x180:rate=30:duration=3",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=440:sample_rate=44100:duration=3",
            "-c:v",
            "libx264",
            "-preset",
            "ultrafast",
            "-pix_fmt",
            "yuv420p",
            "-c:a",
            "aac",
            "-shortest",
        ],
    );
    読み手()
        .動画の情報を取る(&パス)
        .expect("動画の情報を取れない")
}

/// 範囲の標本の左の値が0をまたいだ回数。440Hz なら1秒あたり約880回である。
pub fn 零をまたいだ回数(音: &溜めた音, 範囲: 標本の範囲) -> usize {
    let 値: Vec<f64> = (範囲.開始().値()..範囲.終了().値())
        .filter_map(|番号| 音.標本(動画上の標本位置::作成する(番号)))
        .map(|標本| 標本.左)
        .collect();
    値.windows(2)
        .filter(|組| (組[0] < 0.0) != (組[1] < 0.0))
        .count()
}

/// 標本の左の値と、動画の先頭から鳴る 440Hz の正弦波との相関(-1〜1)。位置がずれていなければ1に近い。
pub fn 正弦波との相関(
    音: impl Fn(動画上の標本位置) -> Option<f64>,
    範囲: 標本の範囲,
) -> f64 {
    let (mut 積, mut 実際の二乗, mut 期待の二乗) = (0.0, 0.0, 0.0);
    for 番号 in 範囲.開始().値()..範囲.終了().値() {
        let Some(実際) = 音(動画上の標本位置::作成する(番号)) else {
            continue;
        };
        let 期待 = (std::f64::consts::TAU * 440.0 * f64::from(番号) / f64::from(周波数の値)).sin();
        積 += 実際 * 期待;
        実際の二乗 += 実際 * 実際;
        期待の二乗 += 期待 * 期待;
    }
    積 / (実際の二乗 * 期待の二乗).sqrt()
}
