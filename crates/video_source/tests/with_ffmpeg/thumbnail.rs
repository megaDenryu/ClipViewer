//! サムネイルを作る口の結合試験。撮り方の時刻のコマにクロップを掛け、撮り方の大きさへ収めた JPEG ができることを確かめる。
//! JPEG として読めることと寸法と色は、jpeg_check.rs の道具で確かめる。

use std::path::PathBuf;

use clip_domain::{
    クロップ範囲, サムネイルの大きさ, サムネイルの撮り方, 正規化した動画パス
};
use video_source::{サムネイルの撮影の失敗, 取り消しの合図};

use crate::common::{最も強い色, 秒, 読み手};
use crate::jpeg_check::{寸法を調べる, 最初の画素};
use crate::test_videos::色を並べた動画を作る;

pub fn 撮り方(
    動画: 正規化した動画パス,
    時刻: f64,
    クロップ: クロップ範囲,
) -> サムネイルの撮り方 {
    let 大きさ = サムネイルの大きさ::作成する(192, 108).expect("大きさ");
    サムネイルの撮り方::作成する(動画, 秒(時刻), クロップ, 大きさ).expect("撮り方")
}

pub fn 合図() -> 取り消しの合図 {
    取り消しの合図::default()
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 撮り方の時刻のコマをクロップして大きさへ収めた画像にする() {
    let 動画 = 色を並べた動画を作る("サムネイル.mp4");
    let 左半分 = クロップ範囲::各値を範囲へ収めて作成する(0.0, 0.0, 50.0, 100.0);
    let 画像 = 読み手()
        .サムネイルを作る(&撮り方(動画, 1.5, 左半分), &合図())
        .expect("作れる");
    let バイト列 = 画像.バイト列();
    assert_eq!(&バイト列[..2], [0xFF, 0xD8], "JPEG の始まりの印");
    println!("サムネイルの大きさ: {}バイト", バイト列.len());
    let パス = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join("サムネイル.jpg");
    std::fs::write(&パス, バイト列).expect("書ける");
    assert_eq!(
        寸法を調べる(&パス),
        (96, 108),
        "160x180 を 192x108 の枠へ縮めて収める"
    );
    assert_eq!(最も強い色(&最初の画素(&パス)), 1, "1.5秒は緑のコマ");
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 動画の終わりより後ろの時刻はコマが無いとして失敗する() {
    let 動画 = 色を並べた動画を作る("サムネイル_終わりの後.mp4");
    let 結果 = 読み手().サムネイルを作る(&撮り方(動画, 10.0, クロップ範囲::全体), &合図());
    assert!(
        matches!(結果, Err(サムネイルの撮影の失敗::コマが無い { .. })),
        "{結果:?}"
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 小さいクロップは大きさの枠に接するまで拡大する() {
    let 動画 = 色を並べた動画を作る("サムネイル_小さいクロップ.mp4");
    let 小さい = クロップ範囲::各値を範囲へ収めて作成する(0.0, 0.0, 10.0, 10.0);
    let 画像 = 読み手()
        .サムネイルを作る(&撮り方(動画, 0.5, 小さい), &合図())
        .expect("作れる");
    let パス = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join("サムネイル_小さいクロップ.jpg");
    std::fs::write(&パス, 画像.バイト列()).expect("書ける");
    assert_eq!(
        寸法を調べる(&パス),
        (192, 108),
        "32x18 を 192x108 の枠へ拡大する"
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 取り消した撮影は止めて取り消したにする() {
    let 動画 = 色を並べた動画を作る("サムネイル_取り消し.mp4");
    let 取り消した合図 = 合図();
    取り消した合図.取り消す();
    let 結果 =
        読み手().サムネイルを作る(&撮り方(動画, 0.5, クロップ範囲::全体), &取り消した合図);
    assert!(
        matches!(結果, Err(サムネイルの撮影の失敗::取り消した)),
        "{結果:?}"
    );
}
