//! 映像の流れが入れ物の始まりより遅れて始まる動画(音が先に始まるもの)で、溜めた区間と流し読みのコマ番号が、
//! 入れ物の始まりから数えた時刻と合うかの結合試験。映像が始まる前の枠は最初のコマで埋まる。
//! 注意: ffmpeg 4.4.1 では、fps フィルタの start_time=0 を外してもこの試験は通った(ffmpeg の出力側の同期が始まりを埋める)。
//! この試験は start_time の有無を見分けず、映像が遅れて始まる動画で番号と時刻が合うことだけを確かめる。

use video_source::メモリの上限;

use crate::common::{区間, 成り立つまで待つ, 秒, 読み手};
use crate::drawn_number::描かれた番号;
use crate::late_video::{合っているか, 映像の遅れた動画を開く};
use crate::numbered_videos::試験の長辺;
use crate::store_support::{受け付けた札, 完了まで待つ};

/// 読み始めるコマ。映像が始まる前と後を含める。
const 読み始めるコマの一覧: [u32; 3] = [0, 5, 30];
const 確かめるコマ数: u32 = 30;

#[test]
#[ignore = "FFmpeg が要る"]
fn 映像が遅れて始まる動画でも溜めた区間と流し読みの番号が時刻と合う() {
    let (情報, 始まり) = 映像の遅れた動画を開く("映像が遅れる.mkv");
    let mut 倉庫 = 読み手()
        .コマの倉庫を開く(情報.clone(), 試験の長辺(), メモリの上限::既定)
        .expect("倉庫を開けない");
    let mut 食い違い = Vec::new();
    for 先頭 in 読み始めるコマの一覧 {
        let 秒数 = |番号: u32| f64::from(番号) / 30.0;
        let 溜める区間 = 区間(秒数(先頭), 秒数(先頭 + 確かめるコマ数));
        let 札 = 受け付けた札(倉庫.区間を溜める依頼を出す(溜める区間));
        完了まで待つ(&mut 倉庫, 札);
        let mut 流し読み = 読み手()
            .流し読みを開く(&情報, 秒(秒数(先頭)), 試験の長辺())
            .expect("流し読みを開けない");
        for 番号 in 先頭..先頭 + 確かめるコマ数 {
            let 位置 = 秒((f64::from(番号) + 0.5) / 30.0);
            let 溜めた = 倉庫
                .溜めたコマを取り出す(&溜める区間, 位置)
                .expect("コマが無い");
            let 溜めた組 = (溜めた.番号().値(), 描かれた番号(溜めた.コマ()));
            成り立つまで待つ("時刻のコマが届くこと", || {
                流し読み
                    .その時刻に出すコマ(位置)
                    .is_some_and(|コマ| コマ.番号().値() >= 番号)
            });
            let 流れた = 流し読み.その時刻に出すコマ(位置).expect("コマが無い");
            let 流れた組 = (流れた.番号().値(), 描かれた番号(流れた.コマ()));
            for (出どころ, (付けた, 描かれた)) in [("溜めた", 溜めた組), ("流し読み", 流れた組)]
            {
                if 付けた != 番号 || !合っているか(番号, 描かれた, 始まり) {
                    食い違い.push(format!(
                        "{出どころ} 先頭{先頭}: 期待{番号} 付けた{付けた} 描かれた{描かれた}"
                    ));
                }
            }
        }
    }
    assert!(
        食い違い.is_empty(),
        "番号が時刻と合わない:\n{}",
        食い違い.join("\n")
    );
}
