//! コマの倉庫のメモリの上限と保持の優先順の結合試験。

use video_source::{
    バイト数, メモリの上限, 依頼の状況, 保持の優先順, 受け付けない理由, 溜める依頼の結果,
};

use crate::common::{区間, 秒};
use crate::store_support::{倉庫を開く, 受け付けた札, 完了まで待つ};

#[test]
#[ignore = "FFmpeg が要る"]
fn 上限の全体を超える区間と_優先順の高い区間で埋まっているときは受け付けない() {
    let 一秒分 = 30 * 160 * 90 * 4;
    let mut 倉庫 = 倉庫を開く(
        "上限.mp4",
        メモリの上限::作成する(バイト数::作成する(一秒分 * 3 / 2)),
    );
    let 結果 = 倉庫.区間を溜める依頼を出す(区間(0.0, 2.0));
    assert!(matches!(
        結果,
        溜める依頼の結果::受け付けない(受け付けない理由::上限の全体を超える { .. })
    ));
    倉庫.保持の優先順を渡す(保持の優先順::作成する(
        vec![区間(0.0, 1.0), 区間(1.0, 2.0)],
    ));
    let 先の札 = 受け付けた札(倉庫.区間を溜める依頼を出す(区間(0.0, 1.0)));
    let 結果 = 倉庫.区間を溜める依頼を出す(区間(1.0, 2.0));
    assert!(matches!(
        結果,
        溜める依頼の結果::受け付けない(
            受け付けない理由::優先順の高い区間で埋まっている { .. }
        )
    ));
    倉庫.保持の優先順を渡す(保持の優先順::作成する(
        vec![区間(1.0, 2.0), 区間(0.0, 1.0)],
    ));
    let 後の札 = 受け付けた札(倉庫.区間を溜める依頼を出す(区間(1.0, 2.0)));
    assert!(matches!(
        倉庫.依頼の状況を問い合わせる(先の札),
        依頼の状況::捨てた
    ));
    完了まで待つ(&mut 倉庫, 後の札);
    assert!(
        倉庫
            .溜めたコマを取り出す(&区間(0.0, 1.0), 秒(0.5))
            .is_none()
    );
}
