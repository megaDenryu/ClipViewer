//! 動画の情報を取る口の結合試験。

use clip_domain::入力された動画パス;
use video_source::動画の情報の取得エラー;

use crate::common::読み手;
use crate::test_videos::色を並べた動画を作る;

#[test]
#[ignore = "FFmpeg が要る"]
fn 動画の長さと寸法とコマの速さを取る() {
    let パス = 色を並べた動画を作る("情報を取る.mp4");
    let 情報 = 読み手()
        .動画の情報を取る(&パス)
        .expect("動画の情報を取れない");
    assert!((情報.長さ().秒数() - 3.0).abs() < 0.05);
    assert_eq!((情報.元の寸法().幅(), 情報.元の寸法().高さ()), (320, 180));
    assert_eq!(情報.コマの速さ().一秒あたりのコマ数(), 30.0);
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 無いファイルは標準エラーの末尾を載せた異常終了になる() {
    let パス = 入力された動画パス::作成する(format!(
        "{}/無い動画.mp4",
        env!("CARGO_TARGET_TMPDIR")
    ))
    .正規化する();
    let 結果 = 読み手().動画の情報を取る(&パス);
    let Err(動画の情報の取得エラー::異常終了 {
        標準エラーの末尾,
    ..
    }) = 結果
    else {
        panic!("異常終了になるはずである")
    };
    assert!(!標準エラーの末尾.文字列().is_empty());
}
