//! コマの倉庫が処理待ちの依頼を保持の優先順で選ぶことの結合試験。
//! 塞ぎ役の区間がデコード中の間に、優先順が上の短い区間と下の長い区間を積み、短い区間が先に溜め終わることを確かめる。
//! 短い区間を後に積む組で受付順(先入れ先出し)の実装と、先に積む組で後入れ先出しの実装と区別する。

use video_source::{
    コマの倉庫, メモリの上限, 依頼の状況, 保持の優先順, 長辺の上限
};

use crate::common::{区間, 成り立つまで待つ, 読み手};
use crate::store_support::受け付けた札;
use crate::test_videos::長い動画を作る;

#[test]
#[ignore = "FFmpeg が要る"]
fn 後から積んだ区間でも優先順が上なら先に溜め終える() {
    優先順が上の短い区間が先に溜め終わる("処理の順_後に積む.mp4", false);
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 先に積んだ区間が優先順で上なら後から積んだ区間より先に溜め終える() {
    優先順が上の短い区間が先に溜め終わる("処理の順_先に積む.mp4", true);
}

fn 倉庫を開く(名前: &str) -> コマの倉庫 {
    let 読み手 = 読み手();
    let 情報 = 読み手
        .動画の情報を取る(&長い動画を作る(名前))
        .expect("動画の情報を取れない");
    let 長辺 = 長辺の上限::作成する(320).expect("長辺の上限を作れない");
    読み手
        .コマの倉庫を開く(情報, 長辺, メモリの上限::既定)
        .expect("倉庫を開けない")
}

fn 優先順が上の短い区間が先に溜め終わる(
    名前: &str, 短い区間を先に積むか: bool
) {
    let mut 倉庫 = 倉庫を開く(名前);
    let (塞ぎ役, 長い区間, 短い区間) = (区間(0.0, 5.0), 区間(5.0, 20.0), 区間(1.0, 1.2));
    倉庫.保持の優先順を渡す(保持の優先順::作成する(
        vec![短い区間, 長い区間, 塞ぎ役],
    ));
    let 塞ぎ役の札 = 受け付けた札(倉庫.区間を溜める依頼を出す(塞ぎ役));
    成り立つまで待つ("塞ぎ役のデコードが始まること", || {
        matches!(
            倉庫.依頼の状況を問い合わせる(塞ぎ役の札),
            依頼の状況::処理中 { .. }
        )
    });
    let 積む順 = if 短い区間を先に積むか {
        [短い区間, 長い区間]
    } else {
        [長い区間, 短い区間]
    };
    let 札 = 積む順.map(|区間| 受け付けた札(倉庫.区間を溜める依頼を出す(区間)));
    let (短い札, 長い札) = if 短い区間を先に積むか {
        (札[0], 札[1])
    } else {
        (札[1], 札[0])
    };
    成り立つまで待つ("短い区間を溜め終えること", || {
        matches!(倉庫.依頼の状況を問い合わせる(短い札), 依頼の状況::完了(_))
    });
    assert!(
        !matches!(倉庫.依頼の状況を問い合わせる(長い札), 依頼の状況::完了(_)),
        "優先順が下の長い区間が、優先順が上の短い区間より先に溜め終わった"
    );
}
