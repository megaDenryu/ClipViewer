//! 撮影に使う動画の情報の覚えの結合試験。同じパスのファイルを書き換えたら、覚えた動画の情報を使わずに調べ直すことを確かめる。

use clip_domain::クロップ範囲;
use video_source::撮影に使う動画の情報の覚え;

use crate::common::読み手;
use crate::test_videos::動画を作る;
use crate::thumbnail::{合図, 撮り方};

#[test]
#[ignore = "FFmpeg が要る"]
fn 動画のファイルを書き換えたら動画の情報を調べ直して撮る() {
    let 名前 = "覚えを書き換える.mkv";
    let 映像だけ = [
        "-f",
        "lavfi",
        "-i",
        "color=c=red:s=320x180:r=30:d=2",
        "-c:v",
        "libx264",
    ];
    let パス = 動画を作る(名前, &映像だけ);
    let 読み手 = 読み手();
    let mut 覚え = 撮影に使う動画の情報の覚え::default();
    let 撮る = |覚え: &mut 撮影に使う動画の情報の覚え| {
        覚え.サムネイルを作る(
            &読み手,
            &撮り方(パス.clone(), 0.5, クロップ範囲::全体),
            &合図(),
        )
    };
    撮る(&mut 覚え).expect("映像だけの動画を撮れない");
    // 書き換えた後の動画は、音の流れを先に置き、映像の流れを1番にする。覚えた情報(映像は0番)を使い回すと、音の流れを読んで撮れない。
    let 音が先 = [
        "-f",
        "lavfi",
        "-i",
        "sine=d=3",
        "-f",
        "lavfi",
        "-i",
        "color=c=blue:s=320x180:r=30:d=3",
        "-map",
        "0",
        "-map",
        "1",
        "-c:v",
        "libx264",
        "-c:a",
        "aac",
    ];
    動画を作る(名前, &音が先);
    撮る(&mut 覚え).expect("書き換えた動画を撮れない(覚えた動画の情報を使い回した)");
}
