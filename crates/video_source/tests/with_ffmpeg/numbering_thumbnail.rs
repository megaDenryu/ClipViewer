//! サムネイルが、再生と同じコマ(撮り方の時刻を含むコマ)を撮るかの結合試験。コマの始まりの時刻とコマの途中の時刻で確かめる。
//! 時刻をミリ秒で持つ入れ物(mkv・webm)では、コマの始まりの時刻がコマの時刻の丸めの境目に当たる。

use std::path::PathBuf;

use clip_domain::{クロップ範囲, 正規化した動画パス};

use crate::common::読み手;
use crate::drawn_number::画素から描かれた番号を読む;
use crate::jpeg_check::{全体の画素, 寸法を調べる};
use crate::numbered_videos::{
    入れ物の一覧, 番号を描いた動画を開く, 速さの一覧
};
use crate::thumbnail::{合図, 撮り方};

/// 撮るコマ。動画の先頭・キーフレームから離れた位置・秒の境目の前後を含める。
const 撮るコマの一覧: [u32; 6] = [0, 1, 29, 31, 44, 83];

#[test]
#[ignore = "FFmpeg が要る"]
fn サムネイルは撮り方の時刻を含むコマを撮る() {
    let mut 食い違い = Vec::new();
    for 速さ in 速さの一覧 {
        for 入れ物 in 入れ物の一覧 {
            let 情報 = 番号を描いた動画を開く("サムネイル", 速さ, 入れ物);
            for 番号 in 撮るコマの一覧 {
                for 時刻 in [速さ.コマの始まり(番号), 速さ.コマの真ん中(番号)]
                {
                    let 撮れた = 撮ったコマの番号(情報.パス(), 時刻);
                    if 撮れた != 番号 {
                        食い違い.push(format!(
                            "{速さ:?} {入れ物:?} {時刻}秒: 期待{番号} 撮れた{撮れた}"
                        ));
                    }
                }
            }
        }
    }
    assert!(
        食い違い.is_empty(),
        "再生と違うコマを撮った:\n{}",
        食い違い.join("\n")
    );
}

fn 撮ったコマの番号(動画: &正規化した動画パス, 時刻: f64) -> u32 {
    let 画像 = 読み手()
        .サムネイルを作る(&撮り方(動画.clone(), 時刻, クロップ範囲::全体), &合図())
        .expect("撮れない");
    let パス = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join("番号のサムネイル.jpg");
    std::fs::write(&パス, 画像.バイト列()).expect("書ける");
    let (幅, 高さ) = 寸法を調べる(&パス);
    画素から描かれた番号を読む(幅, 高さ, &全体の画素(&パス))
}
