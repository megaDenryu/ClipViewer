//! 可変フレームレートの動画で、シーク位置の直後にコマの無い隙間があっても、溜めた区間と流し読みのコマ番号がずれないかの結合試験。
//! 試験動画と、隙間の枠に描かれているべき番号の規則は gap_video.rs が持つ。

use video_source::メモリの上限;

use crate::common::{区間, 成り立つまで待つ, 秒, 読み手};
use crate::drawn_number::描かれた番号;
use crate::gap_video::{
    合っているか, 確かめるコマ数, 秒数, 読み始めるコマの一覧, 隙間のある動画を開く,
};
use crate::numbered_videos::試験の長辺;
use crate::store_support::{受け付けた札, 完了まで待つ};

#[test]
#[ignore = "FFmpeg が要る"]
fn 隙間の手前や中から溜めても区間の番号がずれない() {
    let mut 倉庫 = 読み手()
        .コマの倉庫を開く(
            隙間のある動画を開く("隙間_溜める.mkv"),
            試験の長辺(),
            メモリの上限::既定,
        )
        .expect("倉庫を開けない");
    let mut 食い違い = Vec::new();
    for 先頭 in 読み始めるコマの一覧 {
        let 溜める区間 = 区間(秒数(先頭), 秒数(先頭 + 確かめるコマ数));
        let 札 = 受け付けた札(倉庫.区間を溜める依頼を出す(溜める区間));
        完了まで待つ(&mut 倉庫, 札);
        for 番号 in 先頭..先頭 + 確かめるコマ数 {
            let 取り出した = 倉庫
                .溜めたコマを取り出す(&溜める区間, 秒(秒数(番号) + 0.5 / 30.0))
                .expect("コマを取り出せない");
            let (付けた, 描かれた) = (取り出した.番号().値(), 描かれた番号(取り出した.コマ()));
            if !合っているか(先頭, 番号, 付けた, 描かれた) {
                食い違い.push(format!(
                    "区間の先頭{先頭}: 期待{番号} 付けた{付けた} 描かれた{描かれた}"
                ));
            }
        }
    }
    assert!(
        食い違い.is_empty(),
        "番号がずれた:\n{}",
        食い違い.join("\n")
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 隙間の手前や中から流し読んでも番号がずれない() {
    let 情報 = 隙間のある動画を開く("隙間_流し読み.mkv");
    let mut 食い違い = Vec::new();
    for 先頭 in 読み始めるコマの一覧 {
        let mut 流し読み = 読み手()
            .流し読みを開く(&情報, 秒(秒数(先頭)), 試験の長辺())
            .expect("流し読みを開けない");
        for 番号 in 先頭..先頭 + 確かめるコマ数 {
            let 位置 = 秒(秒数(番号) + 0.5 / 30.0);
            成り立つまで待つ("時刻のコマが届くこと", || {
                流し読み
                    .その時刻に出すコマ(位置)
                    .is_some_and(|コマ| コマ.番号().値() >= 番号)
            });
            let コマ = 流し読み.その時刻に出すコマ(位置).expect("コマが無い");
            let (付けた, 描かれた) = (コマ.番号().値(), 描かれた番号(コマ.コマ()));
            if !合っているか(先頭, 番号, 付けた, 描かれた) {
                食い違い.push(format!(
                    "流し読みの先頭{先頭}: 期待{番号} 付けた{付けた} 描かれた{描かれた}"
                ));
            }
        }
    }
    assert!(
        食い違い.is_empty(),
        "番号がずれた:\n{}",
        食い違い.join("\n")
    );
}
