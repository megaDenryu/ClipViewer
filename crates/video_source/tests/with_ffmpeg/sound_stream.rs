//! 音の流し読みの結合試験。

use audio_pcm::{動画上の標本位置, 標本の範囲};
use video_source::音の流し読みの状態;

use crate::common::{成り立つまで待つ, 秒, 読み手};
use crate::sound_support::{周波数, 正弦波との相関, 音のある動画};

#[test]
#[ignore = "FFmpeg が要る"]
fn 流し読みは開始の位置から動画の終わりまで書き足す() {
    let 情報 = 音のある動画("音の流し読み.mp4");
    let mut 流し読み = 読み手()
        .音の流し読みを開く(&情報, 秒(1.0), 周波数())
        .expect("音の流し読みを開けない");
    成り立つまで待つ("終わりまで読むこと", || {
        !matches!(流し読み.状態(), 音の流し読みの状態::読んでいる)
    });
    assert!(matches!(
        流し読み.状態(),
        音の流し読みの状態::終わりまで読んだ
    ));
    let 範囲 = 流し読み.音().範囲();
    assert_eq!(範囲.開始().値(), 48_000);
    let 長さ = 範囲.長さ().値();
    assert!(
        (95_000..=97_000).contains(&長さ),
        "1秒から3秒までの約2秒分でない: {長さ}"
    );
    let 真ん中 = 流し読み.音().標本(動画上の標本位置::作成する(72_000));
    assert!(真ん中.is_some(), "真ん中の標本が無い");
    let 一部 = 標本の範囲::作成する(
        動画上の標本位置::作成する(60_000),
        動画上の標本位置::作成する(84_000),
    )
    .expect("範囲");
    let 相関 = 正弦波との相関(|位置| 流し読み.音().標本(位置).map(|標本| 標本.左), 一部);
    assert!(
        相関 > 0.9,
        "流し読みの音の位置が動画の時刻とずれている(相関 {相関})"
    );
}
