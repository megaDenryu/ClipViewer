//! 流し読みの結合試験。

use std::time::{Duration, Instant};

use clip_domain::入力された動画パス;
use video_source::{デコードの失敗, 流し読み, 流し読みの状態, 長辺の上限};

use crate::common::{成り立つまで待つ, 最も強い色, 秒, 読み手};
use crate::test_videos::{色を並べた動画を作る, 長い動画を作る};

fn 開く(名前: &str, 開始: f64) -> 流し読み {
    let 読み手 = 読み手();
    let 情報 = 読み手
        .動画の情報を取る(&色を並べた動画を作る(名前))
        .expect("動画の情報を取れない");
    読み手
        .流し読みを開く(&情報, 秒(開始), 長辺の上限::既定)
        .expect("流し読みを開けない")
}

/// その時刻に出すコマが、表示の始まりが期待の時刻のコマになるまで待ち、そのコマの色を返す。
fn 時刻のコマの色(
    流し読み: &mut 流し読み, 位置: f64, 期待する始まり: f64
) -> usize {
    成り立つまで待つ("時刻のコマが届くこと", || {
        流し読み
            .その時刻に出すコマ(秒(位置))
            .is_some_and(|コマ| (コマ.時刻().秒数() - 期待する始まり).abs() < 1e-6)
    });
    let コマ = 流し読み.その時刻に出すコマ(秒(位置)).expect("コマが無い");
    assert_eq!(
        f64::from(コマ.番号().値()),
        期待する始まり * 30.0,
        "コマ番号が表示の始まりと合わない"
    );
    最も強い色(コマ.コマ().画素の並び())
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 開始の時刻を含むコマから読み_時刻を進めると追いつく() {
    let mut 流し読み = 開く("流し読み.mp4", 1.0);
    assert_eq!(時刻のコマの色(&mut 流し読み, 1.0, 1.0), 1);
    assert_eq!(時刻のコマの色(&mut 流し読み, 2.02, 2.0), 2);
    let コマ = 流し読み.その時刻に出すコマ(秒(2.02)).expect("コマが無い");
    assert_eq!(
        (コマ.コマ().寸法().幅(), コマ.コマ().寸法().高さ()),
        (320, 180)
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 動画の終わりまで読むと最後のコマを出し続ける() {
    let mut 流し読み = 開く("終わりまで.mp4", 2.5);
    成り立つまで待つ("終わりまで読むこと", || {
        流し読み.その時刻に出すコマ(秒(100.0));
        matches!(流し読み.状態(), 流し読みの状態::終わりまで読んだ)
    });
    let コマ = 流し読み.その時刻に出すコマ(秒(100.0)).expect("コマが無い");
    assert!((コマ.時刻().秒数() - 89.0 / 30.0).abs() < 1e-6);
    assert_eq!(最も強い色(コマ.コマ().画素の並び()), 2);
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 読んでいる途中で閉じても待たされない() {
    let 読み手 = 読み手();
    let 情報 = 読み手
        .動画の情報を取る(&長い動画を作る("流し読みを閉じる.mp4"))
        .expect("動画の情報を取れない");
    let mut 流し読み = 読み手
        .流し読みを開く(&情報, 秒(0.0), 長辺の上限::既定)
        .expect("流し読みを開けない");
    成り立つまで待つ("最初のコマが届くこと", || {
        流し読み.その時刻に出すコマ(秒(0.0)).is_some()
    });
    std::thread::sleep(Duration::from_millis(200));
    let 始め = Instant::now();
    drop(流し読み);
    assert!(
        始め.elapsed() < Duration::from_secs(2),
        "流し読みを閉じるのに時間がかかりすぎる"
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 読めない動画は異常終了の失敗になる() {
    let 読み手 = 読み手();
    let 情報 = 読み手
        .動画の情報を取る(&色を並べた動画を作る("消える動画.mp4"))
        .expect("動画の情報を取れない");
    let 消した後 = 入力された動画パス::作成する(情報.パス().文字列().to_string()).正規化する();
    std::fs::remove_file(消した後.文字列()).expect("試験動画を消せない");
    let mut 流し読み = 読み手
        .流し読みを開く(&情報, 秒(0.0), 長辺の上限::既定)
        .expect("流し読みを開けない");
    成り立つまで待つ("失敗が分かること", || {
        !matches!(流し読み.状態(), 流し読みの状態::読んでいる)
    });
    assert!(matches!(
        流し読み.状態(),
        流し読みの状態::失敗(デコードの失敗::異常終了 { .. })
    ));
}
