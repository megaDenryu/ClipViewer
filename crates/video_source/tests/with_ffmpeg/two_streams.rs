//! 映像の流れが2つある動画で、動画の情報・溜めたコマ・流し読み・サムネイルが同じ流れを読むかの結合試験。
//! 2つ目の流れは大きく、既定の印を付ける。流れを指定しない ffmpeg はこちらを選ぶため、指定の抜けを検出できる。

use std::path::PathBuf;

use clip_domain::クロップ範囲;
use video_source::{メモリの上限, 動画の情報, 長辺の上限};

use crate::common::{区間, 成り立つまで待つ, 最も強い色, 秒, 読み手};
use crate::jpeg_check::最初の画素;
use crate::store_support::{受け付けた札, 完了まで待つ};
use crate::test_videos::動画を作る;
use crate::thumbnail::{合図, 撮り方};

/// 赤の成分の位置は0であり、1つ目の流れの色(赤)を読んだかを確かめるのに使う。
const 赤の成分の位置: usize = 0;

fn 流れが2つある動画を開く(名前: &str) -> 動画の情報 {
    let パス = 動画を作る(
        名前,
        &[
            "-f",
            "lavfi",
            "-i",
            "color=c=red:s=160x90:r=30:d=2",
            "-f",
            "lavfi",
            "-i",
            "color=c=blue:s=320x180:r=30:d=2",
            "-map",
            "0",
            "-map",
            "1",
            "-c:v",
            "libx264",
            "-disposition:v:0",
            "0",
            "-disposition:v:1",
            "default",
        ],
    );
    読み手()
        .動画の情報を取る(&パス)
        .expect("動画の情報を取れない")
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 溜めたコマと流し読みは動画の情報が調べた1つ目の流れを読む() {
    let 情報 = 流れが2つある動画を開く("流れが2つ_読む.mkv");
    assert_eq!((情報.元の寸法().幅(), 情報.元の寸法().高さ()), (160, 90));
    let 長辺 = 長辺の上限::既定;
    let mut 流し読み = 読み手()
        .流し読みを開く(&情報, 秒(0.5), 長辺)
        .expect("流し読みを開けない");
    let mut 倉庫 = 読み手()
        .コマの倉庫を開く(情報, 長辺, メモリの上限::既定)
        .expect("倉庫を開けない");
    let 札 = 受け付けた札(倉庫.区間を溜める依頼を出す(区間(0.5, 0.7)));
    完了まで待つ(&mut 倉庫, 札);
    let 溜めた = 倉庫
        .溜めたコマを取り出す(&区間(0.5, 0.7), 秒(0.6))
        .expect("コマが無い");
    assert_eq!(最も強い色(溜めた.コマ().画素の並び()), 赤の成分の位置);
    成り立つまで待つ("流し読みのコマが届くこと", || {
        流し読み.その時刻に出すコマ(秒(0.6)).is_some()
    });
    let 流れてきた = 流し読み.その時刻に出すコマ(秒(0.6)).expect("コマが無い");
    assert_eq!(最も強い色(流れてきた.コマ().画素の並び()), 赤の成分の位置);
}

#[test]
#[ignore = "FFmpeg が要る"]
fn サムネイルは添付の画像を除いた最初の流れを撮る() {
    let 情報 = 流れが2つある動画を開く("流れが2つ_サムネイル.mkv");
    let 画像 = 読み手()
        .サムネイルを作る(
            &撮り方(情報.パス().clone(), 0.5, クロップ範囲::全体),
            &合図(),
        )
        .expect("撮れない");
    let パス = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join("流れが2つ_サムネイル.jpg");
    std::fs::write(&パス, 画像.バイト列()).expect("書ける");
    assert_eq!(最も強い色(&最初の画素(&パス)), 赤の成分の位置);
}
