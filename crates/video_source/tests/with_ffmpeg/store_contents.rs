//! コマの倉庫が溜めたコマの内容と、時刻から取り出すコマの結合試験。

use video_source::{バイト数, メモリの上限};

use crate::common::区間;
use crate::store_support::{倉庫を開く, 受け付けた札, 完了まで待つ, 番号と色};

#[test]
#[ignore = "FFmpeg が要る"]
fn 溜めた区間の先頭のコマは区間の開始を含むコマで_端では端のコマを返す() {
    let mut 倉庫 = 倉庫を開く("区間を溜める.mp4", メモリの上限::既定);
    let 札 = 受け付けた札(倉庫.区間を溜める依頼を出す(区間(29.0 / 30.0, 2.0 + 1.0 / 60.0)));
    完了まで待つ(&mut 倉庫, 札);
    assert_eq!(
        番号と色(&mut 倉庫, 29.0 / 30.0, 2.0 + 1.0 / 60.0, 0.0),
        (29, 0)
    );
    assert_eq!(
        番号と色(&mut 倉庫, 29.0 / 30.0, 2.0 + 1.0 / 60.0, 1.0),
        (30, 1)
    );
    assert_eq!(
        番号と色(&mut 倉庫, 29.0 / 30.0, 2.0 + 1.0 / 60.0, 1.999),
        (59, 1)
    );
    assert_eq!(
        番号と色(&mut 倉庫, 29.0 / 30.0, 2.0 + 1.0 / 60.0, 2.0),
        (60, 2)
    );
    assert_eq!(
        番号と色(&mut 倉庫, 29.0 / 30.0, 2.0 + 1.0 / 60.0, 9.0),
        (60, 2)
    );
    assert_eq!(
        倉庫.予約している大きさ(),
        バイト数::作成する(32 * 160 * 90 * 4)
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 区間の先頭がキーフレームから離れていても先頭のコマがずれない() {
    let mut 倉庫 = 倉庫を開く("先頭のコマ.mp4", メモリの上限::既定);
    for (開始, 期待する色) in [(1.0, 1), (2.0, 2), (59.0 / 30.0, 1), (1.0 + 0.5 / 30.0, 1)] {
        let 札 = 受け付けた札(倉庫.区間を溜める依頼を出す(区間(開始, 開始 + 0.2)));
        完了まで待つ(&mut 倉庫, 札);
        assert_eq!(
            番号と色(&mut 倉庫, 開始, 開始 + 0.2, 開始).1,
            期待する色,
            "開始 {開始}秒"
        );
    }
}
