//! 動画の情報が持つ音の有無と、音の倉庫の結合試験。

use clip_domain::時間の長さ;
use video_source::{
    音のメモリの上限, 音の区間の状況, 音の有無, 音の溜め方
};

use crate::common::{区間, 成り立つまで待つ, 読み手};
use crate::sound_support::{
    周波数, 正弦波との相関, 零をまたいだ回数, 音のある動画
};
use crate::test_videos::色を並べた動画を作る;

#[test]
#[ignore = "FFmpeg が要る"]
fn 動画の情報が音の有無を持つ() {
    assert_eq!(音のある動画("音の有無.mp4").音の有無(), 音の有無::ある);
    let 無音 = 読み手()
        .動画の情報を取る(&色を並べた動画を作る("音の無い動画.mp4"))
        .expect("動画の情報を取れない");
    assert_eq!(無音.音の有無(), 音の有無::無い);
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 区間の音を開始の余白を含めて出力装置の周波数で溜める() {
    let 情報 = 音のある動画("音の倉庫.mp4");
    let 溜め方 = 音の溜め方 {
        周波数: 周波数(),
        開始の前の余白: 時間の長さ::作成する(0.01).expect("長さ"),
        上限: 音のメモリの上限::既定,
    };
    let 倉庫 = 読み手()
        .音の倉庫を開く(&情報, 溜め方)
        .expect("音の倉庫を開けない");
    let 目当て = 区間(1.0, 1.5);
    倉庫.溜める区間の並びを渡す(&[目当て]);
    成り立つまで待つ("区間の音を溜め終えること", || {
        !matches!(
            倉庫.区間の状況(&目当て),
            音の区間の状況::処理を待っている | 音の区間の状況::読んでいる
        )
    });
    let 状況 = 倉庫.区間の状況(&目当て);
    let 音 = 状況
        .溜めた音()
        .unwrap_or_else(|| panic!("溜め終えていない: {状況:?}"));
    assert_eq!(音.先頭().値(), 47_520, "開始の10ミリ秒前から溜める");
    assert_eq!(
        音.標本数().値(),
        24_480,
        "0.5秒と余白の10ミリ秒を 48kHz で数えた数"
    );
    let またいだ回数 = 零をまたいだ回数(音, 音.範囲());
    assert!(
        (400..=500).contains(&またいだ回数),
        "440Hz の正弦波でない: {またいだ回数}"
    );
    let 相関 = 正弦波との相関(|位置| 音.標本(位置).map(|標本| 標本.左), 音.範囲());
    assert!(
        相関 > 0.9,
        "溜めた音の位置が動画の時刻とずれている(相関 {相関})"
    );
    倉庫.溜める区間の並びを渡す(&[]);
    assert!(matches!(
        倉庫.区間の状況(&目当て),
        音の区間の状況::並びに無い
    ));
}
