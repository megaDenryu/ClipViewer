//! コマごとに自分のコマ番号を描いた試験動画を作り、デコードしたコマから番号を読み戻す。
//! 入れ物の時刻の刻みで丸めの向きがコマごとに変わり、コマが重複・欠落しないかを確かめるために使う。

use video_source::{動画の情報, 長辺の上限};

use crate::common::読み手;
use crate::test_videos::動画を作る;

/// 試験動画の長さ(秒)。
const 動画の秒数: u32 = 4;

/// コマ番号の下位8ビットを、左から1ビットずつ白黒の縦の帯で描く lavfi のフィルタ。
pub const 番号を描くフィルタ: &str =
    r"geq=lum='if(bitand(N\,pow(2\,floor(X*8/W)))\,235\,16)':cb=128:cr=128";

/// 試験の速さとは、試験動画のコマの速さの、ffmpeg の表記と分子と分母の組のことである。
#[derive(Debug, Clone, Copy)]
pub struct 試験の速さ {
    表記: &'static str,
    分子: u32,
    分母: u32,
}

/// 確かめる速さ。30・60コマ/秒と、小数で割り切れない29.97コマ/秒。
pub const 速さの一覧: [試験の速さ; 3] = [
    試験の速さ {
        表記: "30",
        分子: 30,
        分母: 1,
    },
    試験の速さ {
        表記: "60",
        分子: 60,
        分母: 1,
    },
    試験の速さ {
        表記: "30000/1001",
        分子: 30000,
        分母: 1001,
    },
];

impl 試験の速さ {
    /// 番号のコマの表示が始まる時刻(秒)。
    pub fn コマの始まり(self, 番号: u32) -> f64 {
        f64::from(番号) * f64::from(self.分母) / f64::from(self.分子)
    }

    /// 番号のコマの表示が始まってから次のコマまでの真ん中の時刻(秒)。
    pub fn コマの真ん中(self, 番号: u32) -> f64 {
        (self.コマの始まり(番号) + self.コマの始まり(番号 + 1)) / 2.0
    }

    /// 試験動画(長さ4秒)のコマの数。lavfi は4秒より前に始まるコマをすべて出す。
    pub fn 動画のコマ数(self) -> u32 {
        (動画の秒数 * self.分子).div_ceil(self.分母)
    }
}

/// 試験の入れ物とは、動画の入れ物の形式と、その中の映像の符号化方式の組のことである。どちらも時刻をミリ秒で持つ。
#[derive(Debug, Clone, Copy)]
pub enum 試験の入れ物 {
    /// mkv に H.264 で入れる。
    Mkvの中のH264,
    /// webm に VP9 で入れる。OBS の既定の保存形式の1つである。
    Webmの中のVP9,
}

/// 確かめる入れ物。
pub const 入れ物の一覧: [試験の入れ物; 2] =
    [試験の入れ物::Mkvの中のH264, 試験の入れ物::Webmの中のVP9];

impl 試験の入れ物 {
    fn 拡張子(self) -> &'static str {
        match self {
            Self::Mkvの中のH264 => "mkv",
            Self::Webmの中のVP9 => "webm",
        }
    }

    fn 符号化の引数(self) -> [&'static str; 6] {
        match self {
            Self::Mkvの中のH264 => ["-c:v", "libx264", "-crf", "5", "-sc_threshold", "0"],
            Self::Webmの中のVP9 => ["-c:v", "libvpx-vp9", "-crf", "10", "-b:v", "0"],
        }
    }
}

/// 320×180・4秒の、各コマが自分のコマ番号を描いた動画を作って調べる。キーフレームは先頭だけにし、区間の途中への
/// シークがキーフレームからのデコードを伴うようにする。名前の頭は試験ごとに変え、並行に走る試験が同じファイルを
/// 作り直している間に読まないようにする。
pub fn 番号を描いた動画を開く(
    名前の頭: &str,
    速さ: 試験の速さ,
    入れ物: 試験の入れ物,
) -> 動画の情報 {
    let 名前 = format!(
        "{名前の頭}_{}.{}",
        速さ.表記.replace('/', "_"),
        入れ物.拡張子()
    );
    let 入力 = format!(
        "color=c=black:s=320x180:r={}:d={動画の秒数},format=yuv420p,{番号を描くフィルタ}",
        速さ.表記
    );
    let mut 引数 = vec!["-f", "lavfi", "-i", 入力.as_str(), "-g", "300"];
    引数.extend(入れ物.符号化の引数());
    読み手()
        .動画の情報を取る(&動画を作る(&名前, &引数))
        .expect("動画の情報を取れない")
}

/// 試験で読むコマの長辺の上限。
pub fn 試験の長辺() -> 長辺の上限 {
    長辺の上限::作成する(160).expect("長辺の上限を作れない")
}
