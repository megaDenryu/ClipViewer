//! コマの倉庫の取り消しと後始末の結合試験。実行中の ffmpeg が止まることを、待たされる時間で確かめる。

use std::time::{Duration, Instant};

use video_source::{メモリの上限, 依頼の状況, 長辺の上限};

use crate::common::{区間, 成り立つまで待つ, 読み手};
use crate::store_support::{受け付けた札, 完了まで待つ};
use crate::test_videos::長い動画を作る;

#[test]
#[ignore = "FFmpeg が要る"]
fn デコード中の依頼を取り消すと_次の依頼がすぐに処理される() {
    let 読み手 = 読み手();
    let 情報 = 読み手
        .動画の情報を取る(&長い動画を作る("取り消し.mp4"))
        .expect("動画の情報を取れない");
    let mut 倉庫 = 読み手
        .コマの倉庫を開く(情報, 長辺の上限::既定, メモリの上限::既定)
        .expect("倉庫を開けない");
    let 長い札 = 受け付けた札(倉庫.区間を溜める依頼を出す(区間(0.0, 20.0)));
    成り立つまで待つ(
        "デコードが始まること",
        || matches!(倉庫.依頼の状況を問い合わせる(長い札), 依頼の状況::処理中 { 溜めたコマ数, .. } if !溜めたコマ数.ゼロか()),
    );
    倉庫.依頼を取り消す(長い札);
    assert!(matches!(
        倉庫.依頼の状況を問い合わせる(長い札),
        依頼の状況::取り消した
    ));
    let 短い札 = 受け付けた札(倉庫.区間を溜める依頼を出す(区間(5.0, 5.2)));
    let 始め = Instant::now();
    完了まで待つ(&mut 倉庫, 短い札);
    assert!(
        始め.elapsed() < Duration::from_secs(3),
        "取り消した ffmpeg が止まっていない"
    );
    assert_eq!(
        倉庫.予約している大きさ(),
        倉庫
            .動画()
            .区間を見積もる(&区間(5.0, 5.2), 長辺の上限::既定)
            .バイト数()
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn デコード中に倉庫を落としても待たされない() {
    let 読み手 = 読み手();
    let 情報 = 読み手
        .動画の情報を取る(&長い動画を作る("倉庫を落とす.mp4"))
        .expect("動画の情報を取れない");
    let mut 倉庫 = 読み手
        .コマの倉庫を開く(情報, 長辺の上限::既定, メモリの上限::既定)
        .expect("倉庫を開けない");
    let 札 = 受け付けた札(倉庫.区間を溜める依頼を出す(区間(0.0, 20.0)));
    受け付けた札(倉庫.区間を溜める依頼を出す(区間(0.0, 10.0)));
    成り立つまで待つ(
        "デコードが始まること",
        || matches!(倉庫.依頼の状況を問い合わせる(札), 依頼の状況::処理中 { 溜めたコマ数, .. } if !溜めたコマ数.ゼロか()),
    );
    let 始め = Instant::now();
    drop(倉庫);
    assert!(
        始め.elapsed() < Duration::from_secs(2),
        "倉庫を落とすのに時間がかかりすぎる"
    );
}
