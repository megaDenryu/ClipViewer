//! 時刻をミリ秒で持つ入れ物(mkv・webm)で、流し読みのコマのコマ番号と表示の始まりの時刻と、
//! コマに描かれた番号が合うかの結合試験。

use video_source::{流し読み, 流し読みの状態};

use crate::common::{成り立つまで待つ, 秒, 読み手};
use crate::drawn_number::描かれた番号;
use crate::numbered_videos::{
    入れ物の一覧, 番号を描いた動画を開く, 試験の速さ, 試験の長辺, 速さの一覧,
};

/// 流し読みを開くコマ。動画の先頭・キーフレームから離れた位置・秒の境目の手前を含める。
const 開くコマの一覧: [u32; 4] = [0, 7, 31, 59];
const 確かめるコマ数: u32 = 12;

#[test]
#[ignore = "FFmpeg が要る"]
fn 流し読みのコマは番号と時刻と描かれた番号が合う() {
    let mut 食い違い = Vec::new();
    for 速さ in 速さの一覧 {
        for 入れ物 in 入れ物の一覧 {
            let 情報 = 番号を描いた動画を開く("流し読み", 速さ, 入れ物);
            for 先頭 in 開くコマの一覧 {
                let mut 流し読み = 読み手()
                    .流し読みを開く(&情報, 秒(速さ.コマの始まり(先頭)), 試験の長辺())
                    .expect("流し読みを開けない");
                for 番号 in 先頭..先頭 + 確かめるコマ数 {
                    let 読めた = 番号を読む(&mut 流し読み, 速さ, 番号);
                    if 読めた != (番号, 番号 % 256, true) {
                        食い違い.push(format!(
                            "{速さ:?} {入れ物:?} 流し読みの先頭{先頭}: 期待{番号} 付けた番号と描かれた番号と時刻が合うか{読めた:?}"
                        ));
                    }
                }
            }
        }
    }
    assert!(
        食い違い.is_empty(),
        "コマが重複か欠落した:\n{}",
        食い違い.join("\n")
    );
}

#[test]
#[ignore = "FFmpeg が要る"]
fn 動画の終わりまで流し読むと最後のコマまで出す() {
    let mut 食い違い = Vec::new();
    for 速さ in 速さの一覧 {
        for 入れ物 in 入れ物の一覧 {
            let 情報 = 番号を描いた動画を開く("終わりまで流し読む", 速さ, 入れ物);
            let 先頭 = 速さ.動画のコマ数() - 確かめるコマ数;
            let mut 流し読み = 読み手()
                .流し読みを開く(&情報, 秒(速さ.コマの始まり(先頭)), 試験の長辺())
                .expect("流し読みを開けない");
            for 番号 in 先頭..速さ.動画のコマ数() {
                let 読めた = 番号を読む(&mut 流し読み, 速さ, 番号);
                if 読めた != (番号, 番号 % 256, true) {
                    食い違い.push(format!("{速さ:?} {入れ物:?}: 期待{番号} 読めた{読めた:?}"));
                }
            }
            成り立つまで待つ("終わりまで読むこと", || {
                matches!(流し読み.状態(), 流し読みの状態::終わりまで読んだ)
            });
        }
    }
    assert!(
        食い違い.is_empty(),
        "終わりのコマが欠けた:
{}",
        食い違い.join(
            "
"
        )
    );
}

/// 番号のコマの真ん中の時刻に出すコマが、期待の番号以上のコマになるまで待ち、付けたコマ番号と描かれた番号と、
/// 表示の始まりの時刻が付けたコマ番号の始まりと合うかを返す。
fn 番号を読む(
    流し読み: &mut 流し読み,
    速さ: 試験の速さ,
    期待する番号: u32,
) -> (u32, u32, bool) {
    let 位置 = 秒(速さ.コマの真ん中(期待する番号));
    成り立つまで待つ("時刻のコマが届くこと", || {
        流し読み
            .その時刻に出すコマ(位置)
            .is_some_and(|コマ| コマ.番号().値() >= 期待する番号)
    });
    let コマ = 流し読み.その時刻に出すコマ(位置).expect("コマが無い");
    let 付けた番号 = コマ.番号().値();
    let 時刻が合うか = (コマ.時刻().秒数() - 速さ.コマの始まり(付けた番号)).abs() < 1e-6;
    (付けた番号, 描かれた番号(コマ.コマ()), 時刻が合うか)
}
