//! コマの倉庫の結合試験で共通に使う道具。

use video_source::{
    コマの倉庫, メモリの上限, 依頼の状況, 受付の札, 溜める依頼の結果, 溜め終えた内訳, 長辺の上限,
};

use crate::common::{区間, 成り立つまで待つ, 最も強い色, 秒, 読み手};
use crate::test_videos::色を並べた動画を作る;

pub fn 倉庫を開く(名前: &str, 上限: メモリの上限) -> コマの倉庫 {
    let 読み手 = 読み手();
    let 情報 = 読み手
        .動画の情報を取る(&色を並べた動画を作る(名前))
        .expect("動画の情報を取れない");
    let 長辺 = 長辺の上限::作成する(160).expect("長辺の上限を作れない");
    読み手
        .コマの倉庫を開く(情報, 長辺, 上限)
        .expect("倉庫を開けない")
}

pub fn 受け付けた札(結果: 溜める依頼の結果) -> 受付の札 {
    let 溜める依頼の結果::受け付けた(札) = 結果 else {
        panic!("受け付けられなかった: {結果:?}")
    };
    札
}

/// 札の依頼が溜め終わるまで待ち、溜め終えた内訳を返す。
pub fn 完了まで待つ(
    倉庫: &mut コマの倉庫, 札: 受付の札
) -> 溜め終えた内訳 {
    let mut 内訳 = None;
    成り立つまで待つ("区間を溜め終えること", || {
        match 倉庫.依頼の状況を問い合わせる(札) {
            依頼の状況::完了(溜め終えた) => 内訳 = Some(溜め終えた),
            依頼の状況::処理待ち | 依頼の状況::処理中 { .. } => {}
            他 => panic!("完了しなかった: {他:?}"),
        }
        内訳.is_some()
    });
    内訳.expect("完了の内訳が無い")
}

/// 区間の溜めたコマから時刻のコマを取り出し、その動画上のコマ番号と最も強い色を返す。
pub fn 番号と色(
    倉庫: &mut コマの倉庫, 開始: f64, 終了: f64, 位置: f64
) -> (u32, usize) {
    let 取り出した = 倉庫
        .溜めたコマを取り出す(&区間(開始, 終了), 秒(位置))
        .expect("コマを取り出せない");
    let コマ = 取り出した.コマ();
    assert_eq!((コマ.寸法().幅(), コマ.寸法().高さ()), (160, 90));
    (取り出した.番号().値(), 最も強い色(コマ.画素の並び()))
}
