//! 文字の読み手のうち、コメント・文字列・生の文字列・文字を読み飛ばすこと。
//! 閉じていないものは、黙って終わりまで読み飛ばさずに解析できない理由として返す。

use super::文字の読み手;
use crate::overlay_deps::tokens::解析できない理由;

impl 文字の読み手 {
    /// 入れ子のブロックコメントを、開きの `/*` を読んだ後から閉じまで読み飛ばす。
    pub fn ブロックコメントを読み飛ばす(
        &mut self,
    ) -> Result<(), 解析できない理由> {
        let 始めの行 = self.行;
        let mut 深さ = 1;
        while 深さ > 0 {
            match (self.進める(), self.見る(0)) {
                (Some('/'), Some('*')) => {
                    self.位置 += 1;
                    深さ += 1;
                }
                (Some('*'), Some('/')) => {
                    self.位置 += 1;
                    深さ -= 1;
                }
                (Some(_), _) => {}
                (None, _) => {
                    return Err(解析できない理由::作成する(
                        始めの行,
                        "ブロックコメントが閉じていない",
                    ));
                }
            }
        }
        Ok(())
    }

    /// 文字列を、開きの `"` を読んだ後から閉じの `"` まで、エスケープを含めて読み飛ばす。
    pub fn 文字列を読み飛ばす(&mut self) -> Result<(), 解析できない理由> {
        let 始めの行 = self.行;
        loop {
            match self.進める() {
                Some('\\') => {
                    let _ = self.進める();
                }
                Some('"') => return Ok(()),
                Some(_) => {}
                None => {
                    return Err(解析できない理由::作成する(
                        始めの行,
                        "文字列が閉じていない",
                    ));
                }
            }
        }
    }

    /// 生の文字列を、`r` の後の `#` の数を数えたところから、閉じの `"` と同じ数の `#` まで読み飛ばす。
    pub fn 生の文字列を読み飛ばす(
        &mut self,
        井桁の数: usize,
    ) -> Result<(), 解析できない理由> {
        let 始めの行 = self.行;
        while let Some(文字) = self.進める() {
            if 文字 == '"' && (0..井桁の数).all(|ずれ| self.見る(ずれ) == Some('#')) {
                self.位置 += 井桁の数;
                return Ok(());
            }
        }
        Err(解析できない理由::作成する(
            始めの行,
            "生の文字列が閉じていない",
        ))
    }

    /// `'` を読んだ後に呼ぶ。文字(`'a'`・`'\n'`)なら閉じの `'` まで読み飛ばす。寿命の名前(`'a`)なら何も読まない。
    pub fn 文字なら読み飛ばす(&mut self) -> Result<(), 解析できない理由> {
        let 始めの行 = self.行;
        if self.見る(0) == Some('\\') {
            // 注意: エスケープされた文字が `'` のこと(`'\''`)があるため、`\` とその次の1文字は閉じの印として見ない。
            self.位置 += 2;
            while let Some(文字) = self.進める() {
                if 文字 == '\'' {
                    return Ok(());
                }
            }
            return Err(解析できない理由::作成する(
                始めの行,
                "文字が閉じていない",
            ));
        }
        if self.見る(1) == Some('\'') {
            self.位置 += 2;
        }
        Ok(())
    }
}
