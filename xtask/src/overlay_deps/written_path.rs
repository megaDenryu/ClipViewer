//! ソースに書かれたパス。`use` の木を展開した1本のパスの、行と名前の並びと終わり方。

/// パスの終わり方とは、ソースに書かれたパスが名前で終わるか、`*` で全部を取り込むか、`as` で別名を付けるかの区別のことである。
/// クレートルートを全部取り込む書き方と、クレートルートに別名を付ける書き方は、禁じたモジュールを名指さずに使えてしまうため見分ける。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum パスの終わり方 {
    名前で終わる,
    全部を取り込む,
    別名を付ける(String),
}

/// ソースに書かれたパスとは、ソースに書かれたパスの行と、`::` で区切った名前の並び(`use` の波括弧は展開したもの)と、終わり方の組のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ソースに書かれたパス {
    pub 行: usize,
    pub 名前の並び: Vec<String>,
    pub 終わり方: パスの終わり方,
}

impl ソースに書かれたパス {
    pub fn 作成する(
        行: usize, 名前の並び: Vec<String>, 終わり方: パスの終わり方
    ) -> Self {
        Self {
            行,
            名前の並び,
            終わり方,
        }
    }
}
