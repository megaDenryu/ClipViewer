//! 字句。依存の向きの検査が見分ける字句(名前・`::`・波括弧・コンマ・`*`)の種類と、それが始まる行の組。

/// 字句の種類とは、依存の向きの検査が見分ける字句の区別のことである。ほかの記号と数はすべて `その他` にまとめる。
/// 星印は `use 前置き::*` の全部を取り込む印であり、クレートルートを全部取り込む書き方を見つけるために分ける。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 字句の種類 {
    名前(String),
    二重コロン,
    開き波括弧,
    閉じ波括弧,
    コンマ,
    星印,
    その他,
}

/// 字句とは、ソースの1つの字句の種類と、それが始まる行(1から数える)の組のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 字句 {
    pub 種類: 字句の種類,
    pub 行: usize,
}

impl 字句の種類 {
    /// 名前・`::`・コメント・文字列のどれでもない1文字の記号の字句の種類。
    pub fn 記号から決める(文字: char) -> Self {
        match 文字 {
            '{' => Self::開き波括弧,
            '}' => Self::閉じ波括弧,
            ',' => Self::コンマ,
            '*' => Self::星印,
            _ => Self::その他,
        }
    }
}

impl 字句 {
    /// 字句の並びの位置の字句の種類。並びの終わりを越えれば無い。
    pub fn 並びの位置の種類(並び: &[字句], 位置: usize) -> Option<&字句の種類> {
        並び.get(位置).map(|字句| &字句.種類)
    }
}
