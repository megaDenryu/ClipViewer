//! 禁じた参照。重ね合わせの作業場の層のファイルに書かれた、スタックの作業場のモジュールを使える書き方。

/// 禁じた理由とは、禁じた参照がなぜ禁じられるかの区別のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 禁じた理由 {
    禁じたモジュールを指す,
    クレートルートの全部を取り込む,
    クレートルートに別名を付ける,
}

/// 禁じた参照とは、禁じた書き方をした行と、クレートルートからのパスへ直した書き方と、禁じた理由の組のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 禁じた参照 {
    pub 行: usize,
    pub クレートルートからのパス: String,
    pub 理由: 禁じた理由,
}

impl 禁じた参照 {
    /// 利用者へ見せる説明の文。
    pub fn 説明(&self) -> String {
        let パス = &self.クレートルートからのパス;
        match self.理由 {
            禁じた理由::禁じたモジュールを指す => {
                format!("スタックの作業場の {パス} を使っている")
            }
            禁じた理由::クレートルートの全部を取り込む => {
                format!(
                    "{パス} で クレートルートを全部取り込んでいる(スタックの作業場のモジュールを含む)"
                )
            }
            禁じた理由::クレートルートに別名を付ける => {
                format!(
                    "{パス} で クレートルートに別名を付けている(別名からスタックの作業場のモジュールを使える)"
                )
            }
        }
    }
}
