//! コメントと文字列の読み飛ばし。文字の読み手の公開の口だけを使い、コメント・文字列・生の文字列・文字を読み飛ばす。
//! 閉じていないものは、黙って終わりまで読み飛ばさずに解析できない理由として返す。

use super::reader::文字の読み手;
use super::reason::解析できない理由;

/// コメントと文字列の読み飛ばしとは、字句分けの間だけ文字の読み手を借りて、字句にしない範囲を読み飛ばすもののことである。
pub struct コメントと文字列の読み飛ばし<'読み手> {
    読み手: &'読み手 mut 文字の読み手,
}

impl<'読み手> コメントと文字列の読み飛ばし<'読み手> {
    pub fn 作成する(読み手: &'読み手 mut 文字の読み手) -> Self {
        Self { 読み手 }
    }

    /// 入れ子のブロックコメントを、開きの `/*` を読んだ後から閉じまで読み飛ばす。
    pub fn ブロックコメントを読み飛ばす(
        &mut self,
    ) -> Result<(), 解析できない理由> {
        let 始めの行 = self.読み手.今の行();
        let mut 深さ = 1;
        while 深さ > 0 {
            match (
                self.読み手.一文字読み進める(),
                self.読み手.先の文字を見る(0),
            ) {
                (Some('/'), Some('*')) => {
                    self.読み手.文字を読み進める(1);
                    深さ += 1;
                }
                (Some('*'), Some('/')) => {
                    self.読み手.文字を読み進める(1);
                    深さ -= 1;
                }
                (Some(_), _) => {}
                (None, _) => {
                    return Err(解析できない理由::作成する(
                        始めの行,
                        "ブロックコメントが閉じていない",
                    ));
                }
            }
        }
        Ok(())
    }

    /// 文字列を、開きの `"` を読んだ後から閉じの `"` まで、エスケープを含めて読み飛ばす。
    pub fn 文字列を読み飛ばす(&mut self) -> Result<(), 解析できない理由> {
        let 始めの行 = self.読み手.今の行();
        loop {
            match self.読み手.一文字読み進める() {
                Some('\\') => self.読み手.文字を読み進める(1),
                Some('"') => return Ok(()),
                Some(_) => {}
                None => {
                    return Err(解析できない理由::作成する(
                        始めの行,
                        "文字列が閉じていない",
                    ));
                }
            }
        }
    }

    /// 生の文字列を、開きの `"` を読んだ後から、閉じの `"` と同じ数の `#` まで読み飛ばす。
    pub fn 生の文字列を読み飛ばす(
        &mut self,
        井桁の数: usize,
    ) -> Result<(), 解析できない理由> {
        let 始めの行 = self.読み手.今の行();
        while let Some(文字) = self.読み手.一文字読み進める() {
            if 文字 == '"'
                && (0..井桁の数).all(|ずれ| self.読み手.先の文字を見る(ずれ) == Some('#'))
            {
                self.読み手.文字を読み進める(井桁の数);
                return Ok(());
            }
        }
        Err(解析できない理由::作成する(
            始めの行,
            "生の文字列が閉じていない",
        ))
    }

    /// `'` を読んだ後に呼ぶ。文字(`'a'`・`'\n'`)なら閉じの `'` まで読み飛ばす。寿命の名前(`'a`)なら何も読まない。
    pub fn 文字なら読み飛ばす(&mut self) -> Result<(), 解析できない理由> {
        let 始めの行 = self.読み手.今の行();
        if self.読み手.先の文字を見る(0) == Some('\\') {
            // 注意: エスケープされた文字が `'` のこと(`'\''`)があるため、`\` とその次の1文字は閉じの印として見ない。
            self.読み手.文字を読み進める(2);
            while let Some(文字) = self.読み手.一文字読み進める() {
                if 文字 == '\'' {
                    return Ok(());
                }
            }
            return Err(解析できない理由::作成する(
                始めの行,
                "文字が閉じていない",
            ));
        }
        if self.読み手.先の文字を見る(1) == Some('\'') {
            self.読み手.文字を読み進める(2);
        }
        Ok(())
    }
}
