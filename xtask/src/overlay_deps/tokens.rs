//! Rust のソースの字句分け。依存の向きの検査が要る字句(名前・`::`・波括弧・コンマ)だけを取り出し、コメントと文字列と文字は読み飛ばす。
//! 閉じていないコメント・文字列・文字は、黙って読み飛ばさずに解析できない理由として返す。

use super::reader::文字の読み手;

/// 字句の種類とは、依存の向きの検査が見分ける字句の区別のことである。ほかの記号と数はすべて `その他` にまとめる。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 字句の種類 {
    名前(String),
    二重コロン,
    開き波括弧,
    閉じ波括弧,
    コンマ,
    その他,
}

/// 字句とは、ソースの1つの字句の種類と、それが始まる行(1から数える)の組のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 字句 {
    pub 種類: 字句の種類,
    pub 行: usize,
}

/// 解析できない理由とは、ソースを字句に分けられなかった、またはパスを読めなかった行と説明の組のことである。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 解析できない理由 {
    pub 行: usize,
    pub 説明: String,
}

impl 解析できない理由 {
    pub fn 作成する(行: usize, 説明: &str) -> Self {
        Self {
            行,
            説明: 説明.to_string(),
        }
    }
}

/// ソースを字句の並びに分ける。コメント・文字列・生の文字列・文字は字句にしない。寿命の名前(`'a`)は `その他` と名前に分ける。
pub fn 字句に分ける(本文: &str) -> Result<Vec<字句>, 解析できない理由> {
    let mut 読み手 = 文字の読み手::作成する(本文);
    let mut 並び = Vec::new();
    while let Some(文字) = 読み手.先の文字を見る(0) {
        let 行 = 読み手.行;
        let 種類 = match (文字, 読み手.先の文字を見る(1)) {
            (文字, _) if 文字.is_whitespace() => {
                let _ = 読み手.一文字読み進める();
                continue;
            }
            ('/', Some('/')) => {
                読み手.行の終わりまで読み飛ばす();
                continue;
            }
            ('/', Some('*')) => {
                let _ = (読み手.一文字読み進める(), 読み手.一文字読み進める());
                読み手.ブロックコメントを読み飛ばす()?;
                continue;
            }
            ('"', _) => {
                let _ = 読み手.一文字読み進める();
                読み手.文字列を読み飛ばす()?;
                continue;
            }
            ('\'', _) => {
                let _ = 読み手.一文字読み進める();
                読み手.文字なら読み飛ばす()?;
                字句の種類::その他
            }
            (':', Some(':')) => {
                let _ = (読み手.一文字読み進める(), 読み手.一文字読み進める());
                字句の種類::二重コロン
            }
            (文字, _) if 文字.is_alphanumeric() || 文字 == '_' => {
                match 読み手.名前か文字列の前置きを読む()? {
                    Some(名前) => 字句の種類::名前(名前),
                    None => continue,
                }
            }
            (文字, _) => {
                let _ = 読み手.一文字読み進める();
                match 文字 {
                    '{' => 字句の種類::開き波括弧,
                    '}' => 字句の種類::閉じ波括弧,
                    ',' => 字句の種類::コンマ,
                    _ => 字句の種類::その他,
                }
            }
        };
        並び.push(字句 { 種類, 行 });
    }
    Ok(並び)
}
