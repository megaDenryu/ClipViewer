//! Rust のソースの字句分け。依存の向きの検査が要る字句だけを取り出し、コメントと文字列と文字は読み飛ばす(`skipping.rs`)。

use super::reader::文字の読み手;
use super::reason::解析できない理由;
use super::skipping::コメントと文字列の読み飛ばし;
use super::token::{字句, 字句の種類};

/// ソースを字句の並びに分ける。コメント・文字列・生の文字列・文字は字句にしない。寿命の名前(`'a`)は `その他` と名前に分ける。
pub fn 字句に分ける(本文: &str) -> Result<Vec<字句>, 解析できない理由> {
    let mut 読み手 = 文字の読み手::作成する(本文);
    let mut 並び = Vec::new();
    while let Some(文字) = 読み手.先の文字を見る(0) {
        let 行 = 読み手.今の行();
        let 種類 = match (文字, 読み手.先の文字を見る(1)) {
            (文字, _) if 文字.is_whitespace() => {
                読み手.文字を読み進める(1);
                continue;
            }
            ('/', Some('/')) => {
                読み手.行の終わりまで読み飛ばす();
                continue;
            }
            ('/', Some('*')) => {
                読み手.文字を読み進める(2);
                コメントと文字列の読み飛ばし::作成する(&mut 読み手)
                    .ブロックコメントを読み飛ばす()?;
                continue;
            }
            ('"', _) => {
                読み手.文字を読み進める(1);
                コメントと文字列の読み飛ばし::作成する(&mut 読み手).文字列を読み飛ばす()?;
                continue;
            }
            ('\'', _) => {
                読み手.文字を読み進める(1);
                コメントと文字列の読み飛ばし::作成する(&mut 読み手).文字なら読み飛ばす()?;
                字句の種類::その他
            }
            (':', Some(':')) => {
                読み手.文字を読み進める(2);
                字句の種類::二重コロン
            }
            (文字, _) if 文字.is_alphanumeric() || 文字 == '_' => {
                match 読み手.名前か文字列の前置きを読む()? {
                    Some(名前) => 字句の種類::名前(名前),
                    None => continue,
                }
            }
            (文字, _) => {
                読み手.文字を読み進める(1);
                字句の種類::記号から決める(文字)
            }
        };
        並び.push(字句 { 種類, 行 });
    }
    Ok(並び)
}
