//! 検査する層。依存の向きを検査する `clip_viewer` の中のフォルダと、その下のファイルが使ってはならないモジュールの組を並べる。
//! 参照: _doc/設計/同時再生.md 3-2「依存の向きの検査」、_doc/設計/ライブラリ.md 判断11

/// 検査する層とは、`src` の直下のフォルダの名前と、利用者へ見せる呼び名と、その下のファイルが使ってはならないクレートルートの直下のモジュールの組のことである。
pub struct 検査する層 {
    pub フォルダの名前: &'static str,
    pub 呼び名: &'static str,
    pub 禁じたモジュール: &'static [&'static str],
}

/// 重ね合わせの作業場の層。スタックの作業場の状態・応答・画面を使わない。
pub const 重ね合わせの作業場の層: 検査する層 = 検査する層 {
    フォルダの名前: "overlay",
    呼び名: "重ね合わせの作業場の層",
    禁じたモジュール: &["state", "command", "view"],
};

/// ライブラリの部品の共有の置き場。2つの作業場が共に使うため、どちらの作業場も配線も知らない。
pub const ライブラリの部品の共有の置き場: 検査する層 = 検査する層 {
    フォルダの名前: "library_common",
    呼び名: "ライブラリの部品の共有の置き場",
    禁じたモジュール: &["state", "command", "view", "overlay", "app"],
};

/// 検査する層の並び。この順に検査して表示する。
pub const 検査する層の並び: [&検査する層; 2] =
    [&重ね合わせの作業場の層, &ライブラリの部品の共有の置き場];
