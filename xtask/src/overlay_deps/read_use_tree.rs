//! 読んだuseの木。useの木を読み終えた次の字句の位置と、読んだソースに書かれたパスの並び。

use super::written_path::ソースに書かれたパス;

/// 読んだuseの木とは、パスを読み終えた次の字句の位置と、読んだソースに書かれたパスの並びの組のことである。
pub struct 読んだuseの木 {
    pub 次の位置: usize,
    pub パスの並び: Vec<ソースに書かれたパス>,
}

impl 読んだuseの木 {
    /// 1本のパスだけを読んだ結果。
    pub fn 一本のパス(次の位置: usize, パス: ソースに書かれたパス) -> Self {
        Self {
            次の位置,
            パスの並び: vec![パス],
        }
    }
}
