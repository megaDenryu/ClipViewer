//! パスの読み方。字句の並びの1つの位置から、`use` の木(`a::b`・`a::{b, c::d}`・`a::*`)か、式や型に書いた `a::b::c` を読み、
//! 波括弧を展開した書かれたパスの並びにする。式のパスの後ろの `::<型>`(ターボフィッシュ)は、その手前でパスを終える。

use super::module_path::ソースに書かれたパス;
use super::tokens::{字句, 字句の種類, 解析できない理由};

/// 読んだuseの木とは、パスを読み終えた次の字句の位置と、読んだ書かれたパスの並びの組のことである。
pub struct 読んだuseの木 {
    pub 次の位置: usize,
    pub パスの並び: Vec<ソースに書かれたパス>,
}

fn 字句の種類を読む(並び: &[字句], 位置: usize) -> Option<&字句の種類> {
    並び.get(位置).map(|字句| &字句.種類)
}

/// 位置から1本の木を読む。前置きは、外側の波括弧の手前までに読んだ名前の並びである。
pub fn useの木を読む(
    並び: &[字句],
    位置: usize,
    前置き: Vec<String>,
) -> Result<読んだuseの木, 解析できない理由> {
    let 行 = 並び.get(位置).map_or(0, |字句| 字句.行);
    let 名前 = match 字句の種類を読む(並び, 位置) {
        Some(字句の種類::開き波括弧) => {
            return 波括弧の中身を読む(並び, 位置 + 1, 前置き);
        }
        Some(字句の種類::名前(名前)) => 名前,
        _ => {
            return Err(解析できない理由::作成する(
                行,
                "use の波括弧の中を読めない",
            ));
        }
    };
    let mut 名前の並び = 前置き;
    名前の並び.push(名前.clone());
    let mut 次の位置 = 位置 + 1;
    while 字句の種類を読む(並び, 次の位置) == Some(&字句の種類::二重コロン)
    {
        match 字句の種類を読む(並び, 次の位置 + 1) {
            Some(字句の種類::名前(続き)) => {
                名前の並び.push(続き.clone());
                次の位置 += 2;
            }
            Some(字句の種類::開き波括弧) => {
                return 波括弧の中身を読む(並び, 次の位置 + 2, 名前の並び);
            }
            _ => break,
        }
    }
    Ok(読んだuseの木 {
        次の位置,
        パスの並び: vec![ソースに書かれたパス {
            行, 名前の並び
        }],
    })
}

/// `{` の次の位置から、コンマで区切った木を閉じの `}` まで読む。`*` は名前を足さないため読み飛ばす。
fn 波括弧の中身を読む(
    並び: &[字句],
    mut 位置: usize,
    前置き: Vec<String>,
) -> Result<読んだuseの木, 解析できない理由> {
    let mut パスの並び = Vec::new();
    loop {
        match 字句の種類を読む(並び, 位置) {
            Some(字句の種類::閉じ波括弧) => {
                return Ok(読んだuseの木 {
                    次の位置: 位置 + 1,
                    パスの並び,
                });
            }
            Some(字句の種類::コンマ | 字句の種類::その他) => 位置 += 1,
            Some(_) => {
                let 読んだ = useの木を読む(並び, 位置, 前置き.clone())?;
                パスの並び.extend(読んだ.パスの並び);
                位置 = 読んだ.次の位置;
            }
            None => {
                let 行 = 並び.last().map_or(0, |字句| 字句.行);
                return Err(解析できない理由::作成する(
                    行,
                    "use の波括弧が閉じていない",
                ));
            }
        }
    }
}
