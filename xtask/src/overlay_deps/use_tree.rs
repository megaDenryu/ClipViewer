//! パスの読み方。字句の並びの1つの位置から、`use` の木(`a::b`・`a::{b, c::d}`・`a::*`・`a as 別名`)か、式や型に書いた `a::b::c` を読み、
//! 波括弧を展開したソースに書かれたパスの並びにする。式のパスの後ろの `::<型>`(ターボフィッシュ)は、その手前でパスを終える。

use super::read_use_tree::読んだuseの木;
use super::reason::解析できない理由;
use super::token::{字句, 字句の種類};
use super::written_path::{ソースに書かれたパス, パスの終わり方};

/// 位置から1本のuseの木を読む。前置きは、外側の波括弧の手前までに読んだ名前の並びである。
pub fn useの木を読む(
    並び: &[字句],
    位置: usize,
    前置き: Vec<String>,
) -> Result<読んだuseの木, 解析できない理由> {
    let 行 = 並び.get(位置).map_or(0, |字句| 字句.行);
    let 名前 = match 字句::並びの位置の種類(並び, 位置) {
        Some(字句の種類::開き波括弧) => {
            return 波括弧の中身を読む(並び, 位置 + 1, 前置き);
        }
        Some(字句の種類::名前(名前)) => 名前,
        _ => {
            return Err(解析できない理由::作成する(
                行,
                "use の波括弧の中を読めない",
            ));
        }
    };
    let mut 名前の並び = 前置き;
    名前の並び.push(名前.clone());
    let mut 次の位置 = 位置 + 1;
    let mut 終わり方 = パスの終わり方::名前で終わる;
    while 字句::並びの位置の種類(並び, 次の位置) == Some(&字句の種類::二重コロン)
    {
        match 字句::並びの位置の種類(並び, 次の位置 + 1) {
            Some(字句の種類::名前(続き)) => 名前の並び.push(続き.clone()),
            Some(字句の種類::開き波括弧) => {
                return 波括弧の中身を読む(並び, 次の位置 + 2, 名前の並び);
            }
            Some(字句の種類::星印) => {
                終わり方 = パスの終わり方::全部を取り込む
            }
            _ => break,
        }
        次の位置 += 2;
    }
    if let (パスの終わり方::名前で終わる, Some(字句の種類::名前(印)), Some(字句の種類::名前(別名))) = (
        &終わり方,
        字句::並びの位置の種類(並び, 次の位置),
        字句::並びの位置の種類(並び, 次の位置 + 1),
    ) && 印 == "as"
    {
        終わり方 = パスの終わり方::別名を付ける(別名.clone());
        次の位置 += 2;
    }
    Ok(読んだuseの木::一本のパス(
        次の位置,
        ソースに書かれたパス::作成する(行, 名前の並び, 終わり方),
    ))
}

/// `{` の次の位置から、コンマで区切ったuseの木を閉じの `}` まで読む。中の `*` は前置きの全部を取り込むパスにする。
fn 波括弧の中身を読む(
    並び: &[字句],
    mut 位置: usize,
    前置き: Vec<String>,
) -> Result<読んだuseの木, 解析できない理由> {
    let mut パスの並び = Vec::new();
    loop {
        let 行 = 並び.get(位置).map_or(0, |字句| 字句.行);
        match 字句::並びの位置の種類(並び, 位置) {
            Some(字句の種類::閉じ波括弧) => {
                return Ok(読んだuseの木 {
                    次の位置: 位置 + 1,
                    パスの並び,
                });
            }
            Some(字句の種類::星印) => {
                パスの並び.push(ソースに書かれたパス::作成する(
                    行,
                    前置き.clone(),
                    パスの終わり方::全部を取り込む,
                ));
                位置 += 1;
            }
            Some(字句の種類::コンマ | 字句の種類::その他) => 位置 += 1,
            Some(_) => {
                let 読んだ = useの木を読む(並び, 位置, 前置き.clone())?;
                パスの並び.extend(読んだ.パスの並び);
                位置 = 読んだ.次の位置;
            }
            None => {
                let 行 = 並び.last().map_or(0, |字句| 字句.行);
                return Err(解析できない理由::作成する(
                    行,
                    "use の波括弧が閉じていない",
                ));
            }
        }
    }
}
