//! 禁じた参照を探すこと。字句の並びを頭から読み、パスの始まりごとにパスを読み(`use_tree.rs`)、モジュールパスから直して(`module_path.rs`)、
//! 検査する層が使ってはならないモジュールを指すものを集める。ファイルの中の `mod 名前 { … }` の間は、モジュールパスにその名前を足して直す。

use super::extern_crate::extern宣言を読む;
use super::forbidden_reference::禁じた参照;
use super::module_path::モジュールパス;
use super::reason::解析できない理由;
use super::token::{字句, 字句の種類};
use super::use_tree::useの木を読む;

/// 字句の並びの中のパスをすべて読み、禁じた参照を集める。`::` の直後の名前はパスの続きなので、パスの始まりとして読まない。
/// 閉じの波括弧が開きより多いときと、走査の終わりで開きの波括弧が閉じていないときは、中のモジュールの出入りを決められないため解析できない理由を返す。
pub fn 禁じた参照を探す(
    並び: &[字句],
    ファイルのモジュールパス: &モジュールパス,
    禁じたモジュール: &[&str],
) -> Result<Vec<禁じた参照>, 解析できない理由> {
    let mut 見つけたもの = Vec::new();
    let mut 今のモジュールパス = ファイルのモジュールパス.clone();
    let mut 波括弧の深さ: usize = 0;
    let mut 中のモジュールの深さ: Vec<usize> = Vec::new();
    let mut 位置 = 0;
    while let Some(今) = 並び.get(位置) {
        let 前 = 位置
            .checked_sub(1)
            .and_then(|前| 並び.get(前))
            .map(|字句| &字句.種類);
        match (&今.種類, 中のモジュールの名前(並び, 位置)) {
            (_, Some(名前)) => {
                今のモジュールパス.中のモジュールへ入る(名前);
                波括弧の深さ += 1;
                中のモジュールの深さ.push(波括弧の深さ);
                位置 += 3;
            }
            (字句の種類::名前(印), None) if 印 == "extern" => {
                let 読んだ = extern宣言を読む(並び, 位置);
                見つけたもの.extend(読んだ.禁じた参照);
                位置 = 読んだ.次の位置;
            }
            (字句の種類::名前(_), None) if 前 != Some(&字句の種類::二重コロン) => {
                let 読んだ = useの木を読む(並び, 位置, Vec::new())?;
                for パス in &読んだ.パスの並び {
                    見つけたもの.extend(
                        今のモジュールパス.禁じた参照なら返す(パス, 禁じたモジュール)?,
                    );
                }
                位置 = 読んだ.次の位置;
            }
            (字句の種類::開き波括弧, None) => {
                波括弧の深さ += 1;
                位置 += 1;
            }
            (字句の種類::閉じ波括弧, None) => {
                if 中のモジュールの深さ.last() == Some(&波括弧の深さ) {
                    中のモジュールの深さ.pop();
                    今のモジュールパス.中のモジュールから出る();
                }
                波括弧の深さ = 波括弧の深さ.checked_sub(1).ok_or_else(|| {
                    解析できない理由::作成する(今.行, "閉じの波括弧が開きより多い")
                })?;
                位置 += 1;
            }
            _ => 位置 += 1,
        }
    }
    if 波括弧の深さ != 0 {
        let 行 = 並び.last().map_or(0, |字句| 字句.行);
        return Err(解析できない理由::作成する(
            行,
            "開きの波括弧が閉じていない",
        ));
    }
    Ok(見つけたもの)
}

/// 位置から `mod 名前 {` が始まるなら、その名前。
fn 中のモジュールの名前(並び: &[字句], 位置: usize) -> Option<String> {
    let 種類 = |ずれ: usize| 並び.get(位置 + ずれ).map(|字句| &字句.種類);
    match (種類(0), 種類(1), 種類(2)) {
        (
            Some(字句の種類::名前(印)),
            Some(字句の種類::名前(名前)),
            Some(字句の種類::開き波括弧),
        ) if 印 == "mod" => Some(名前.clone()),
        _ => None,
    }
}
