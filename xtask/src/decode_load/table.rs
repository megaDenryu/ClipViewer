//! 測定の並びを、設計文書 5-4 の表と同じ列の Markdown の表に書く。

use super::frame_rate::コマの速さ;
use super::measurement::一回の測定;

/// 負荷の表とは、ffmpegの数ごとの測定の並びと、倍率の基準にする動画の再生の速さの組のことである。
pub struct 負荷の表<'a> {
    測定の並び: &'a [一回の測定],
    再生の速さ: コマの速さ,
}

impl<'a> 負荷の表<'a> {
    /// 測定の並びと再生の速さから組み立てる。
    pub fn 組み立てる(
        測定の並び: &'a [一回の測定], 再生の速さ: コマの速さ
    ) -> Self {
        Self {
            測定の並び,
            再生の速さ,
        }
    }

    /// 見出しと区切りとffmpegの数ごとの行を、行末に改行を付けて書く。設計文書へそのまま貼れる形である。
    pub fn markdownの表として書く(&self) -> String {
        let 再生の速さ = self.再生の速さ.一秒あたりのコマ数の表記();
        let mut 表 = format!(
            "| 同時に読む本数 | 読み切る時間 | 合計の速さ | 1本あたりの速さ | 再生の速さ({再生の速さ}コマ/秒)に対する倍率 |\n|---|---|---|---|---|\n"
        );
        for 測定 in self.測定の並び {
            表.push_str(&format!(
                "| {} | {} | {} | {} | {} |\n",
                測定.ffmpegの数(),
                測定.読み切る時間(),
                測定.合計の速さ(),
                測定.一本あたりの速さ(),
                測定
                    .一本あたりの速さ()
                    .再生の速さに対する倍率(self.再生の速さ),
            ));
        }
        表
    }
}
