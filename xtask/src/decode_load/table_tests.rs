//! 測定の結果から速さを求めることと、設計文書 5-4 と同じ列の表に書くことの試験。
#![allow(clippy::expect_used)]

use std::time::Duration;

use super::measurement::一回の測定;
use super::stream_count::同時に読む本数;
use super::table::負荷の表;
use super::video_shape::コマの速さ;

fn 三十コマ毎秒() -> コマの速さ {
    コマの速さ {
        分子: 30, 分母: 1
    }
}

fn 測定(本数: u32, ミリ秒: u64, コマ数: u32) -> 一回の測定 {
    let 本数 = 同時に読む本数::並びを表記から読む(&本数.to_string()).expect("読める")[0];
    一回の測定::作る(本数, Duration::from_millis(ミリ秒), コマ数).expect("作れる")
}

#[test]
fn 合計と1本あたりの速さと倍率を求める() {
    let 四本 = 測定(4, 8_000, 900);
    assert!((四本.合計の速さ().値() - 450.0).abs() < 1e-9);
    assert!((四本.一本あたりの速さ().値() - 112.5).abs() < 1e-9);
    let 倍率 = 四本
        .一本あたりの速さ()
        .再生の速さに対する倍率(三十コマ毎秒());
    assert!((倍率 - 3.75).abs() < 1e-9);
}

#[test]
fn 時間かコマ数が0の測定は作らない() {
    let 本数 = 測定(2, 1, 1).本数();
    assert!(一回の測定::作る(本数, Duration::ZERO, 900).is_err());
    assert!(一回の測定::作る(本数, Duration::from_secs(1), 0).is_err());
}

#[test]
fn 設計文書と同じ列の表に書く() {
    let 並び = [測定(1, 3_000, 900), 測定(8, 20_000, 900)];
    let 表 = 負荷の表::組み立てる(&並び, 三十コマ毎秒()).markdownの表として書く();
    assert_eq!(
        表,
        "| 同時に読む本数 | 読み切る時間 | 合計の速さ | 1本あたりの速さ | 再生の速さ(30コマ/秒)に対する倍率 |\n\
         |---|---|---|---|---|\n\
         | 1 | 3.0秒 | 約300コマ/秒 | 約300コマ/秒 | 約10.0倍 |\n\
         | 8 | 20.0秒 | 約360コマ/秒 | 約45コマ/秒 | 約1.5倍 |\n"
    );
}

#[test]
fn 割り切れない再生の速さは小数2桁で見出しに書く() {
    let 並び = [測定(1, 1_000, 30)];
    let 速さ = コマの速さ {
        分子: 30_000,
        分母: 1_001,
    };
    let 表 = 負荷の表::組み立てる(&並び, 速さ).markdownの表として書く();
    assert!(表.starts_with(
        "| 同時に読む本数 | 読み切る時間 | 合計の速さ | 1本あたりの速さ | 再生の速さ(29.97コマ/秒)"
    ));
}
