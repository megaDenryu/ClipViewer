//! 測定の並びを、設計文書 5-4 と同じ列の表に書くことの試験。
#![allow(clippy::expect_used)]

use std::time::Duration;

use super::elapsed::読み切る時間;
use super::frame_count::コマ数;
use super::frame_rate::コマの速さ;
use super::measurement::一回の測定;
use super::stream_count::同時に起動するffmpegの数;
use super::table::負荷の表;

fn 一回の測定を作る(
    ffmpegの数: u32, ミリ秒: u64, コマの枚数: u32
) -> 一回の測定 {
    一回の測定::作成する(
        同時に起動するffmpegの数::作成する(ffmpegの数).expect("作れる"),
        読み切る時間::作成する(Duration::from_millis(ミリ秒)).expect("作れる"),
        コマ数::作成する(コマの枚数).expect("作れる"),
    )
}

#[test]
fn 設計文書と同じ列の表に書く() {
    let 並び = [
        一回の測定を作る(1, 3_000, 900),
        一回の測定を作る(8, 20_000, 900),
    ];
    let 再生の速さ = コマの速さ::作成する(30, 1).expect("作れる");
    let 表 = 負荷の表::組み立てる(&並び, 再生の速さ).markdownの表として書く();
    assert_eq!(
        表,
        "| 同時に読む本数 | 読み切る時間 | 合計の速さ | 1本あたりの速さ | 再生の速さ(30コマ/秒)に対する倍率 |\n\
         |---|---|---|---|---|\n\
         | 1 | 3.0秒 | 約300コマ/秒 | 約300コマ/秒 | 約10.0倍 |\n\
         | 8 | 20.0秒 | 約360コマ/秒 | 約45コマ/秒 | 約1.5倍 |\n"
    );
}

#[test]
fn 割り切れない再生の速さは小数2桁で見出しに書く() {
    let 並び = [一回の測定を作る(1, 1_000, 30)];
    let 再生の速さ = コマの速さ::作成する(30_000, 1_001).expect("作れる");
    let 表 = 負荷の表::組み立てる(&並び, 再生の速さ).markdownの表として書く();
    assert!(表.contains("再生の速さ(29.97コマ/秒)に対する倍率"));
}
