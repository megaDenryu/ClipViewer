//! 同時に読んだ全部の結果のまとめ方の試験。自分で失敗した1本の理由を、止めた残りより先に返すことを確かめる。

use super::byte_count::バイト数;
use super::stream_failure::一本の読み出しの失敗;

#[test]
fn 全部読めたらバイト数の並びを返す() {
    let 一コマ分 = バイト数::ゼロ.読んだ分を足す(16);
    let 結果 = 一本の読み出しの失敗::結果の並びをまとめる(
        vec![Ok(一コマ分), Ok(一コマ分)],
    );
    assert_eq!(結果, Ok(vec![一コマ分, 一コマ分]));
}

#[test]
fn 止めたものより自分で失敗したものの理由を返す() {
    let 結果 = 一本の読み出しの失敗::結果の並びをまとめる(vec![
        Err(一本の読み出しの失敗::ほかの失敗を受けて止めた),
        Ok(バイト数::ゼロ),
        Err(一本の読み出しの失敗::失敗した(
            "ffmpeg が失敗した".to_owned(),
        )),
    ]);
    assert_eq!(結果, Err("ffmpeg が失敗した".to_owned()));
}

#[test]
fn 止めたものだけが残ったときも失敗にする() {
    let 結果 = 一本の読み出しの失敗::結果の並びをまとめる(vec![Err(
        一本の読み出しの失敗::ほかの失敗を受けて止めた,
    )]);
    assert!(結果.is_err());
}
