//! 画素の寸法の試験。読み出すコマの寸法がアプリ(video_source)の丸めと同じになることを確かめる。
#![allow(clippy::expect_used)]

use super::frame_size::画素の寸法;

fn 画素の寸法を作る(幅: u32, 高さ: u32) -> 画素の寸法 {
    画素の寸法::作成する(幅, 高さ).expect("作れる")
}

#[test]
fn 幅か高さが0の寸法は作らない() {
    assert!(画素の寸法::作成する(0, 1080).is_none());
    assert!(画素の寸法::作成する(1920, 0).is_none());
}

#[test]
fn 長辺が上限を超えるときだけアプリと同じ丸めで縮める() {
    assert_eq!(
        画素の寸法を作る(1920, 1080).長辺を上限へ縮める(),
        画素の寸法を作る(1280, 720)
    );
    assert_eq!(
        画素の寸法を作る(3840, 2160).長辺を上限へ縮める(),
        画素の寸法を作る(1280, 720)
    );
    assert_eq!(
        画素の寸法を作る(1080, 1920).長辺を上限へ縮める(),
        画素の寸法を作る(720, 1280)
    );
    assert_eq!(
        画素の寸法を作る(2000, 999).長辺を上限へ縮める(),
        画素の寸法を作る(1280, 639)
    );
    assert_eq!(
        画素の寸法を作る(640, 360).長辺を上限へ縮める(),
        画素の寸法を作る(640, 360)
    );
}

#[test]
fn 一コマのバイト数と拡大縮小の指定() {
    let 寸法 = 画素の寸法を作る(1280, 720);
    assert_eq!(寸法.一コマのバイト数().to_string(), "3686400バイト");
    assert_eq!(寸法.拡大縮小の指定(), "1280:720");
    assert_eq!(寸法.縦横を入れ替える().to_string(), "720x1280");
}
