//! 動画の形の試験。ffprobe の出力の読み方と、読み出すコマの寸法がアプリ(video_source)の丸めと同じになることを確かめる。
#![allow(clippy::expect_used)]

use super::video_shape::{動画の形, 画素の寸法};

fn 寸法(幅: u32, 高さ: u32) -> 画素の寸法 {
    画素の寸法 { 幅, 高さ }
}

#[test]
fn ffprobeの出力から寸法とコマの速さを読む() {
    let 形 = 動画の形::ffprobeの出力から読む("1920,1080,30000/1001\r\n").expect("読める");
    assert_eq!(形.元の寸法, 寸法(1920, 1080));
    assert_eq!(形.コマの速さ.分数の表記(), "30000/1001");
    assert!((形.コマの速さ.毎秒のコマ数() - 29.97).abs() < 0.001);
}

#[test]
fn 読めない出力は理由を付けて失敗にする() {
    for 出力 in [
        "",
        "1920,1080",
        "1920,1080,0/0",
        "1920,1080,30",
        "1920,横,30/1",
        "0,1080,30/1",
    ] {
        let 理由 = 動画の形::ffprobeの出力から読む(出力).expect_err("失敗する");
        assert!(理由.contains("読めない"), "{出力}: {理由}");
    }
}

#[test]
fn 長辺が上限を超えるときだけアプリと同じ丸めで縮める() {
    assert_eq!(寸法(1920, 1080).長辺を上限へ縮める(), 寸法(1280, 720));
    assert_eq!(寸法(3840, 2160).長辺を上限へ縮める(), 寸法(1280, 720));
    assert_eq!(寸法(1080, 1920).長辺を上限へ縮める(), 寸法(720, 1280));
    assert_eq!(寸法(2000, 999).長辺を上限へ縮める(), 寸法(1280, 639));
    assert_eq!(寸法(640, 360).長辺を上限へ縮める(), 寸法(640, 360));
    assert_eq!(寸法(1280, 720).一コマのバイト数(), 3_686_400);
}
